{{ config(
        alias = 'OPTIONSET_METADATA',
        materialized='tel_incremental',
        incremental_strategy = 'insert_overwrite',
        transiet = 'false'
) }}

with source_data as (
    SELECT
        ENTITYNAME AS ENTITYNAME,
        OPTIONSETNAME AS OPTIONSETNAME,
        OPTION AS OPTION,
        ISUSERLOCALIZEDLABEL AS ISUSERLOCALIZEDLABEL,
        LOCALIZEDLABELLANGUAGECODE AS LOCALIZEDLABELLANGUAGECODE,
        LOCALIZEDLABEL AS LOCALIZEDLABEL,
        'GLOBAL' AS SOURCE_FLAG
    FROM {{ ref('BRONZE__TEA_STRATEGIC_BUSINESS_OPERATIONS__CRM_FILE_GLOBALOPTIONSETMETADATA') }}
    UNION ALL
    SELECT
        ENTITYNAME AS ENTITYNAME,
        OPTIONSETNAME AS OPTIONSETNAME,
        OPTION AS OPTION,
        ISUSERLOCALIZEDLABEL AS ISUSERLOCALIZEDLABEL,
        LOCALIZEDLABELLANGUAGECODE AS LOCALIZEDLABELLANGUAGECODE,
        LOCALIZEDLABEL AS LOCALIZEDLABEL,
        'LOCAL' AS SOURCE_FLAG
    FROM {{ ref('BRONZE__TEA_STRATEGIC_BUSINESS_OPERATIONS__CRM_FILE_OPTIONSETMETADATA') }}
),

transform_data as (
    SELECT
        ENTITYNAME,
        OPTIONSETNAME,
        OPTION,
        ISUSERLOCALIZEDLABEL,
        LOCALIZEDLABELLANGUAGECODE,
        LOCALIZEDLABEL,
        SOURCE_FLAG,
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
	FROM source_data
),

type_data as (
    SELECT
        _AUDIT_LOG_ID AS _AUDIT_LOG_ID,
        _ROW_HASH AS _ROW_HASH,
        ENTITYNAME AS ENTITYNAME,
        OPTIONSETNAME AS OPTIONSETNAME,
        OPTION AS OPTION,
        ISUSERLOCALIZEDLABEL AS ISUSERLOCALIZEDLABEL,
        LOCALIZEDLABELLANGUAGECODE AS LOCALIZEDLABELLANGUAGECODE,
        LOCALIZEDLABEL AS LOCALIZEDLABEL,
        SOURCE_FLAG AS SOURCE_FLAG
    FROM transform_data
)

SELECT * FROM type_data
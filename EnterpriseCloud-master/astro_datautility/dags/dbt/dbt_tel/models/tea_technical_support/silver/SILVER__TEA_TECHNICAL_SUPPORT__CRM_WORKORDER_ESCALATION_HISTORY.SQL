get_history as (
    SELECT
        esc.*,
        hist.LEVELFROM, 
        hist.LEVELTO,
        hist.levelto_startdate, 
        hist.LEVELCHANGEDESCRIPTION, 
        hist.MODIFIEDON_HIST,
        lead(hist.levelto_startdate) over (partition by esc.issue_no order by hist.MODIFIEDON_HIST asc ) as levelto_enddate, 
        datediff(day,levelto_startdate,levelto_enddate) as leveldays
	FROM wo_escalation esc  
    left join escalation_hist hist
    on esc.ISSUE_NO = hist.ISSUE_NO

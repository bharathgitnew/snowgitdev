                THEN  NULL
		        ELSE 'No' 
		END AS Day90Flag,
        base_table.SECURITY_REGION,
        base_table.COMPLETION_COMPLETION_REPORT_ROOT_CAUSE_CODE AS COM_ROOT_CAUSE_CODE 
    FROM {{ ref('SILVER__TEA_TECHNICAL_SUPPORT__TIRS_ACCIDENTREPORTSFORUS_NOLOCK') }} base_table
        LEFT OUTER JOIN 
        (
            SELECT   
                accidentreport.TIRS_No,

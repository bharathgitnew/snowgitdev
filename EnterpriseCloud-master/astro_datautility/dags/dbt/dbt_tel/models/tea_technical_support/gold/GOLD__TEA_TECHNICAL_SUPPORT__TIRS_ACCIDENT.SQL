            FROM {{ ref('SILVER__TEA_TECHNICAL_SUPPORT__TIRS_ACCIDENTREPORTSFORUS_NOLOCK') }} accidentreport
                LEFT OUTER JOIN {{ ref('SILVER__TEA_TECHNICAL_SUPPORT__TIRS_ACCIDENTWORKFLOWPROGRESSFORUS_NOLOCK') }} accidentworkflow 
            ON accidentreport.TIRS_No=accidentworkflow.TIRS_No
            WHERE accidentreport.Status_En LIKE '%Closed'

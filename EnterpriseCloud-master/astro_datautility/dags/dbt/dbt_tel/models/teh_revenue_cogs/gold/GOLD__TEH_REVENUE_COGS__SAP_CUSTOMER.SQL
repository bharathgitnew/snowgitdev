WITH BPGD AS (
    SELECT * FROM {{ ref('SILVER__TEH_REVENUE_COGS__BUSINESS_PARTNERS_GENERAL_DATA') }}
)

, DISTINCTBP AS (
    SELECT DISTINCT
        CORPORATION AS BUSINESS_PARTNER_NUMBER
        , CORPORATION
    FROM BPGD
    WHERE 1=1
        AND LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B'
        AND EXTENDED_TO_COMPANY_3200  = 'Y'

    UNION

    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
        , CORPORATION
    FROM BPGD
    WHERE EXTENDED_TO_COMPANY_3200  = 'Y'
)

,BPGENERAL AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
        , NAME_1_OF_ORGANIZATION
        , CASE
            WHEN LEN(SEARCH_TERM_2_FOR_BUSINESS_PARTNER) < 1 THEN NULL
            ELSE SEARCH_TERM_2_FOR_BUSINESS_PARTNER
        END AS SEARCH_TERM_2
        , NAME_1_OF_ORGANIZATION AS CORPORATION_NAME
        , STREET_AND_HOUSE_NUMBER
        , CITY
        , REGION
        , POSTAL_CODE
        , IDENTIFICATION_NUMBER
        , EXTENDED_TO_COMPANY_3200
        , SEARCH_TERM_1_FOR_BUSINESS_PARTNER AS SEARCH_TERM_1
        , NAME_1
        , COUNTRY_KEY AS COUNTRY
        , CUSTOMER_FLAG
        , VENDOR_FLAG
        , SORT_FIELD
    FROM BPGD
    WHERE IDENTIFICATION_TYPE = '1100'
)

,STANDARDNAME AS (
    SELECT
        NAME_1_OF_ORGANIZATION AS CORPORATION_NAME
        , CORPORATION
        , RECORDCOUNT
        , ROW_NUMBER() OVER(Partition by CORPORATION ORDER BY RECORDCOUNT DESC) AS RN
    FROM(
        SELECT
            NAME_1_OF_ORGANIZATION
            , CORPORATION
            , COUNT(*) AS RECORDCOUNT
        FROM BPGD
        WHERE EXTENDED_TO_COMPANY_3200  = 'Y'
        GROUP BY
            NAME_1_OF_ORGANIZATION
            , CORPORATION
        )
)

,ACODE_ID AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
        , IDENTIFICATION_NUMBER AS CORPORATION_ID
    FROM BPGD
    WHERE 1=1
        AND IDENTIFICATION_TYPE = '1100'
        AND LEFT(BUSINESS_PARTNER_NUMBER,1) = 'A'
),
CGM AS (
SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('BRONZE__TEH_REVENUE_COGS__SHAREPOINT_CUSTOMER_GROUP_MAPPING') }}
)
, SOURCE_DATA AS (
    SELECT
        DISTINCTBP.CORPORATION
        , CGM.CUSTOMER_GROUP AS CUSTOMER_GROUP
        , CGM.CUSTOMER_GROUP2 AS CUSTOMER_GROUP2
        , BPGENERAL.CORPORATION_NAME AS BP_CORP_NAME
        , DISTINCTBP.BUSINESS_PARTNER_NUMBER
        , STANDARDNAME.CORPORATION_NAME AS STANDARD_CORP_NAME
        , ACODE_ID.CORPORATION_ID
        , BPGENERAL.SEARCH_TERM_1
        , BPGENERAL.SEARCH_TERM_2
        , BPGENERAL.NAME_1_OF_ORGANIZATION
        , BPGENERAL.STREET_AND_HOUSE_NUMBER
        , BPGENERAL.CITY
        , BPGENERAL.REGION
        , BPGENERAL.POSTAL_CODE
        , BPGENERAL.COUNTRY
        , BPGENERAL.SORT_FIELD
        , BPGENERAL.IDENTIFICATION_NUMBER
        , BPGENERAL.CUSTOMER_FLAG
        , BPGENERAL.VENDOR_FLAG
        , BPGENERAL.EXTENDED_TO_COMPANY_3200
    FROM DISTINCTBP
    INNER JOIN BPGENERAL
        ON DISTINCTBP.BUSINESS_PARTNER_NUMBER = BPGENERAL.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN STANDARDNAME
        ON DISTINCTBP.CORPORATION = STANDARDNAME.CORPORATION
        AND STANDARDNAME.RN = 1
    LEFT OUTER JOIN ACODE_ID
        ON DISTINCTBP.CORPORATION = ACODE_ID.BUSINESS_PARTNER_NUMBER
    LEFT JOIN CGM
        ON CGM.ACCOUNT_NUMBER = DISTINCTBP.CORPORATION
)

, TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') as _ROW_HASH
        , CUSTOMER_GROUP
        , CUSTOMER_GROUP2
        , LEFT(BUSINESS_PARTNER_NUMBER ,1) AS BUSINESS_PARTNER_SERIES
        , BUSINESS_PARTNER_NUMBER
        , STANDARD_CORP_NAME AS CORPORATION_NAME
        , CORPORATION
        , CORPORATION_ID
        , SEARCH_TERM_1
        , SEARCH_TERM_2
        , NAME_1_OF_ORGANIZATION
        , STREET_AND_HOUSE_NUMBER
        , CITY
        , CASE
            WHEN COUNTRY = 'US' THEN REGION
            ELSE NULL
        END AS US_STATE
        , POSTAL_CODE
        , COUNTRY
        , REGION
        , SORT_FIELD
        , IDENTIFICATION_NUMBER
        , CUSTOMER_FLAG
        , VENDOR_FLAG
        , EXTENDED_TO_COMPANY_3200
        , 'Y' AS EXTENDED_TO_COMPANY_3200_ADJ

    FROM SOURCE_DATA
)

,TYPE_DATA AS (
    SELECT
          CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        , CUSTOMER_GROUP
        , CUSTOMER_GROUP2
        , BUSINESS_PARTNER_SERIES
        , BUSINESS_PARTNER_NUMBER
        , CORPORATION_NAME
        , CORPORATION
        , CORPORATION_ID
        , SEARCH_TERM_1
        , SEARCH_TERM_2
        , NAME_1_OF_ORGANIZATION
        , STREET_AND_HOUSE_NUMBER
        , CITY
        , US_STATE
        , POSTAL_CODE
        , COUNTRY
        , REGION
        , SORT_FIELD
        , IDENTIFICATION_NUMBER
        , CUSTOMER_FLAG
        , VENDOR_FLAG
        , EXTENDED_TO_COMPANY_3200
        , EXTENDED_TO_COMPANY_3200_ADJ
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
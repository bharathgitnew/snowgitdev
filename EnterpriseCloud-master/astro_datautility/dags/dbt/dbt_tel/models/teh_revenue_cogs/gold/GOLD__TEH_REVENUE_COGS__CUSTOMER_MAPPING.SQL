    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='CUSTOMER_MAPPING',
    unique_key = ['CUSTOMER_CODE']
) }}

WITH customer_all AS
(
    SELECT
        DISTINCT BUSINESS_PARTNER_NUMBER AS CUSTOMER_CODE
    FROM {{ ref('GOLD__TEH_REVENUE_COGS__SAP_CUSTOMER') }}
    UNION
    SELECT
        DISTINCT CUSTOMER_CODE
    FROM {{ source('STATIC_OBJECTS', 'LEGACY_FSTR_FST_BUDGET_ACTUAL_FORECAST_LEGACY') }}
    UNION
    SELECT
        DISTINCT LEFT(REPLACE(DIMENSION_5,'C',''),5)
    FROM {{ source('STATIC_OBJECTS', 'LEGACY_TELR_BAANV_TEA_FINALIZED_TRANSACTIONS') }}
    WHERE LEN(DIMENSION_5) > 1
    AND LEFT (LEDGER_ACC,1) IN ('4','5')
    AND LEFT(REPLACE(DIMENSION_5,'C',''),1) NOT IN ('6','7','9')
    UNION
    SELECT
        DISTINCT CUSTOMER_CODE_B
    FROM {{ ref('GOLD__TEH_REVENUE_COGS__US_MACHINES') }}
    WHERE LEN(CUSTOMER_CODE_B)> 1
    UNION
    SELECT
        DISTINCT CUSTOMER_CODE_D
    FROM {{ ref('GOLD__TEH_REVENUE_COGS__US_MACHINES') }}
    WHERE LEN(CUSTOMER_CODE_D)> 1
    UNION
    SELECT
        DISTINCT ACTIVITYLEVEL2NAMECUSTOMER
    FROM {{ ref('BRONZE__TEH_REVENUE_COGS__KRONOS_ACTIVITIESTOTAL') }}
    WHERE LEFT(ACTIVITYLEVEL2NAMECUSTOMER,1) IN ('B','D')
    UNION
    SELECT
        DISTINCT END_USER
    FROM {{ ref('GOLD__TEH_REVENUE_COGS__REVENUE_COGS_DAILY_REPORT') }}
    WHERE LEN(END_USER)> 1
),
sap_customer AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
        ,CORPORATION
        ,CORPORATION_NAME AS SAP_CORPORATION_NAME
        ,CORPORATION_ID AS SAP_CORPORATION_ID
        ,CORPORATION AS CORPORATION_CODE
        ,SEARCH_TERM_1 AS SEARCH_NAME1
        ,SEARCH_TERM_2 AS SEARCH_NAME2
    FROM {{ ref('GOLD__TEH_REVENUE_COGS__SAP_CUSTOMER') }}
),
customer_map AS (
    SELECT
        CUSTOMER_CODE
        ,CUSTOMER_NAME_COMMON
        ,CUSTOMER_NAME_SOURCE
        ,CUSTOMER_SHORT_NAME
        ,SAP_CORPORATION_CODE
        ,CUSTOMER_SOURCE
        ,CUSTOMER_FLAG
        ,CUSTOMER_FLAG2
    FROM {{ ref('BRONZE__TEH_REVENUE_COGS__SHAREPOINT_SERVICE_CUSTOMER_MAPPING') }}
),
crm AS (
    SELECT
        ACCT.ACCOUNTNUMBER
        ,ACCT.PARENTACCOUNTIDNAME
        ,ACCT.COM_COMPANY_NAME
        ,ACCT.COM_LEAGAL_COMPANY_E_NAME AS CRM_CORPORATION_NAME
        ,ACCT.NAME AS SEARCH_NAME_CRM
        ,ACCT.COM_OFFICE_SHORT_E_NAME
        ,ACCT.TEL_COM_NAME_3_EN
        ,ACCT.COM_REGIONNAME
        ,ACCT.COM_NIS_REGION
        ,ACCT.COM_COUNTRY_NAMENAME
        ,ACCT.TEL_COM_OLD_CUSTOMER_CODE AS CRM_LEGACY_CODE
        ,CASE
            WHEN
                LEFT(ACCT.ACCOUNTNUMBER,1) = 'A' THEN ACCT.ACCOUNTNUMBER
            ELSE PARENT.ACCOUNTNUMBER
            END AS PARENT
        ,CASE
            WHEN
                LEFT(ACCT.ACCOUNTNUMBER,1) = 'A' THEN ACCT.ACCOUNTNUMBER
            WHEN
                LEFT(ACCT.ACCOUNTNUMBER,1) = 'B' THEN PARENT.ACCOUNTNUMBER
            WHEN
                LEFT(ACCT.ACCOUNTNUMBER,1) IN ('C','D') THEN GRANDPARENT.ACCOUNTNUMBER
            ELSE NULL
            END AS CORPORATION
        ,CASE
            WHEN
                LEFT(ACCT.ACCOUNTNUMBER,1) = 'A' THEN ACCT.PARENTACCOUNTIDNAME
            WHEN
                LEFT(ACCT.ACCOUNTNUMBER,1) IN ('C','D') THEN PARENT.TEL_COM_CUSTOMER_GROUP_1NAME
            ELSE ACCT.TEL_COM_CUSTOMER_GROUP_1NAME
            END AS CRM_GROUP
    FROM {{ ref('BRONZE__TEH_REVENUE_COGS__CRM_FILE_ACCOUNT') }} ACCT
    LEFT OUTER JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__CRM_FILE_ACCOUNT') }} PARENT
    ON PARENT.ID = ACCT.PARENTACCOUNTID
    LEFT OUTER JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__CRM_FILE_ACCOUNT') }} GRANDPARENT
    ON GRANDPARENT.ID = PARENT.PARENTACCOUNTID
),
customer_group AS
(
    SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('BRONZE__TEH_REVENUE_COGS__SHAREPOINT_CUSTOMER_GROUP_MAPPING') }}
),
baan AS
(
    SELECT DISTINCT
        LEFT(CUSTOMER_CODE,5) AS CUSTOMER_CODE
        ,LTRIM(RTRIM(CUSTOMER)) AS CUSTOMER_NAME_BAAN
        ,CRM_CORPORATION_NAME
        ,crm.CORPORATION
        ,crm.CRM_GROUP
        ,crm.SEARCH_NAME_CRM
    FROM {{ ref('BRONZE__TEH_REVENUE_COGS__TEA93TEL_REPORTING_BAANV_TEA_CUSTOMERS') }} BAANV_TEA_CUSTOMERS
    LEFT OUTER JOIN crm
    ON LEFT(BAANV_TEA_CUSTOMERS.CUSTOMER_CODE,5) = crm.CRM_LEGACY_CODE
),
combined AS
(
    SELECT
        customer_all.CUSTOMER_CODE
        ,CASE
            WHEN
                LEFT(customer_all.CUSTOMER_CODE,1) IN ('A','B','C','D','E') AND customer_map.CUSTOMER_NAME_COMMON IS NOT NULL THEN customer_map.CUSTOMER_NAME_COMMON  --Updated 8/29/24
            ELSE COALESCE(sap_customer.SAP_CORPORATION_NAME,customer_map.CUSTOMER_NAME_COMMON)
            END AS CUSTOMER_NAME
        ,COALESCE(sap_customer.CORPORATION_CODE,customer_map.SAP_CORPORATION_CODE) AS SAP_CORPORATION
        ,COALESCE(baan.CUSTOMER_CODE, crm.CRM_LEGACY_CODE) AS CUSTOMER_CODE_OLD
        ,COALESCE(sap_customer.SAP_CORPORATION_NAME,PARENTSAP.SAP_CORPORATION_NAME) AS SAP_CUSTOMER_NAME
        ,COALESCE(crm.CRM_CORPORATION_NAME, baan.CRM_CORPORATION_NAME) AS CUSTOMER_NAME_CRM
        ,COALESCE(crm.SEARCH_NAME_CRM, baan.SEARCH_NAME_CRM) AS SEARCH_NAME_CRM
        ,baan.CUSTOMER_NAME_BAAN
        ,sap_customer.SEARCH_NAME1
        ,sap_customer.SEARCH_NAME2
        ,CASE
            WHEN
                LEFT(customer_all.CUSTOMER_CODE,1) = 'A' THEN customer_all.CUSTOMER_CODE
            WHEN
                customer_map.SAP_CORPORATION_CODE IS NOT NULL THEN customer_map.SAP_CORPORATION_CODE
            WHEN PARENT IS NOT NULL THEN PARENT  --Updated Logic LK 10/9
            ELSE customer_all.CUSTOMER_CODE  --Updated Logic LK 10/9
            END AS SAP_PARENT_CODE
        ,COALESCE(crm.CRM_GROUP, baan.CRM_GROUP) AS CUSTOMER_GROUP_CRM
        ,COALESCE(customer_map.CUSTOMER_SHORT_NAME,sap_customer.SAP_CORPORATION_NAME) AS CUSTOMER_SHORT_NAME
        ,customer_map.CUSTOMER_FLAG
        ,customer_map.CUSTOMER_FLAG2
        ,CASE
            WHEN
                LEFT(customer_all.CUSTOMER_CODE,1) IN ('A','B', 'C','D','E') THEN 'SAP/CRM'
            ELSE 'BAAN/Other'
            END AS SOURCESYSTEM
    FROM customer_all
    LEFT OUTER JOIN customer_map
    ON customer_all.CUSTOMER_CODE = customer_map.CUSTOMER_CODE
    LEFT OUTER JOIN crm
    ON customer_all.CUSTOMER_CODE = crm.ACCOUNTNUMBER
    LEFT OUTER JOIN baan
    ON customer_all.CUSTOMER_CODE =baan.CUSTOMER_CODE
    LEFT OUTER JOIN sap_customer PARENTSAP
    ON PARENTSAP.BUSINESS_PARTNER_NUMBER = baan.CORPORATION
    LEFT OUTER JOIN sap_customer
    ON sap_customer.BUSINESS_PARTNER_NUMBER = customer_all.CUSTOMER_CODE
),
transform_data AS
(
    SELECT
        combined.CUSTOMER_CODE
        ,combined.CUSTOMER_NAME
        ,customer_group.CUSTOMER_GROUP --Updated Logic LK 10/9 from COALESCE(customer_group.CUSTOMER_GROUP,CGSAP.CUSTOMER_GROUP) AS CUSTOMER_GROUP
        ,customer_group.CUSTOMER_GROUP2  --Updated Logic LK 10/9 from COALESCE(customer_group.CUSTOMER_GROUP2,CGSAP.CUSTOMER_GROUP2) AS CUSTOMER_GROUP2
        ,combined.SAP_CORPORATION
        ,combined.CUSTOMER_CODE_OLD
        ,combined.CUSTOMER_SHORT_NAME
        ,combined.SAP_CUSTOMER_NAME
        ,combined.CUSTOMER_NAME_CRM
        ,combined.SEARCH_NAME_CRM
        ,combined.CUSTOMER_NAME_BAAN
        ,combined.SEARCH_NAME1
        ,combined.SEARCH_NAME2
        ,combined.SAP_PARENT_CODE
        ,combined.CUSTOMER_GROUP_CRM
        ,combined.CUSTOMER_FLAG
        ,combined.CUSTOMER_FLAG2
        ,combined.SOURCESYSTEM
        ,'{{ invocation_id }}' AS _AUDIT_LOG_ID
        ,SHA2('hash_me') as _ROW_HASH
    FROM combined
    -- LEFT OUTER JOIN customer_group CGSAP  --REMOVE JOIN LK 10/9
    -- ON CGSAP.ACCOUNT_NUMBER = combined.SAP_PARENT_CODE AND combined.SOURCESYSTEM = 'SAP/CRM'  --REMOVE JOIN LK 10/9
    LEFT OUTER JOIN customer_group
    ON customer_group.ACCOUNT_NUMBER = combined.SAP_PARENT_CODE -- UPDATE JOIN CONDITION 10/9 removed combined.SOURCESYSTEM = 'BAAN/Other'
    QUALIFY row_number() over ( partition by combined.CUSTOMER_CODE order by combined.CUSTOMER_CODE ) = 1
),
type_data AS
(
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) AS _AUDIT_LOG_ID
        ,CAST(_ROW_HASH as VARCHAR(128)) AS _ROW_HASH
        ,CAST(CUSTOMER_CODE AS VARCHAR(16777216)) AS CUSTOMER_CODE
        ,CAST(CUSTOMER_NAME AS VARCHAR(16777216)) AS CUSTOMER_NAME
        ,CAST(CUSTOMER_GROUP AS VARCHAR(16777216)) AS CUSTOMER_GROUP
        ,CAST(CUSTOMER_GROUP2 AS VARCHAR(16777216)) AS CUSTOMER_GROUP2
        ,CAST(CUSTOMER_GROUP_CRM AS VARCHAR(16777216)) AS CUSTOMER_GROUP_CRM
        ,CAST(SAP_CORPORATION AS VARCHAR(16777216)) AS SAP_CORPORATION
        ,CAST(SAP_PARENT_CODE AS VARCHAR(16777216)) AS SAP_PARENT_CODE
        ,CAST(CUSTOMER_CODE_OLD AS VARCHAR(16777216)) AS CUSTOMER_CODE_OLD
        ,CAST(SOURCESYSTEM AS VARCHAR(16777216)) AS SOURCESYSTEM
        ,CAST(CUSTOMER_SHORT_NAME AS VARCHAR(16777216)) AS CUSTOMER_SHORT_NAME
        ,CAST(SAP_CUSTOMER_NAME AS VARCHAR(16777216)) AS SAP_CUSTOMER_NAME
        ,CAST(CUSTOMER_NAME_CRM AS VARCHAR(16777216)) AS CUSTOMER_NAME_CRM
        ,CAST(SEARCH_NAME_CRM AS VARCHAR(16777216)) AS SEARCH_NAME_CRM
        ,CAST(CUSTOMER_NAME_BAAN AS VARCHAR(16777216)) AS CUSTOMER_NAME_BAAN
        ,CAST(SEARCH_NAME1 AS VARCHAR(16777216)) AS SEARCH_NAME1
        ,CAST(SEARCH_NAME2 AS VARCHAR(16777216)) AS SEARCH_NAME2
        ,CAST(CUSTOMER_FLAG AS VARCHAR(16777216)) AS CUSTOMER_FLAG
        ,CAST(CUSTOMER_FLAG2 AS VARCHAR(16777216)) AS CUSTOMER_FLAG2
    FROM transform_data)
SELECT * FROM type_data
with vbap_cte as (
    select * from {{ ref('SILVER__TEH_REVENUE_COGS__ZCDV_T_CMTU010_VBAP') }}
    where IS_DELETED = 'No'
),

universal_pl_data as
(
        SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        OBJECT_NUMBER,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        PARTNER_OBJECT
    FROM {{ ref('GOLD__TEH_REVENUE_COGS__UNIVERSAL_PL_ACCOUNT_TYPE') }} -- General Ledger
    WHERE ACDOCA_BUSINESS_TRANSACTION_TYPE = 'KOAO'
),

OR_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        vbap.zzorty AS SALES_CATEGORY,
        vbap.VBELN AS SALES_DOCUMENT,
        vbap.POSNR AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU090_AUFK') }}  AUFK
            ON universal_pl_data.OBJECT_NUMBER = AUFK.OBJNR
        JOIN vbap_cte  VBAP
            ON AUFK.KDAUF = VBAP.VBELN
            and AUFK.KDPOS = VBAP.POSNR
    WHERE OBJECT_NUMBER like 'OR%'

),

OV_object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        vbap.zzorty AS SALES_CATEGORY,
        vbap.VBELN AS SALES_DOCUMENT,
        vbap.POSNR AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU089_AFVC') }}  AFVC
            ON universal_pl_data.OBJECT_NUMBER = AFVC.OBJNR
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU119_AFKO') }}  AFKO
            ON AFVC.AUFPL = AFKO.AUFPL
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU090_AUFK') }}  AUFK
            ON AFKO.AUFNR = AUFK.AUFNR
        JOIN vbap_cte  VBAP
            ON AUFK.KDAUF = VBAP.VBELN and AUFK.KDPOS = VBAP.POSNR
    WHERE OBJECT_NUMBER like 'OV%'
),

PR_OR_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        vbap.zzorty AS SALES_CATEGORY,
        vbap.VBELN AS SALES_DOCUMENT,
        vbap.POSNR AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU090_AUFK') }}  AUFK
            ON universal_pl_data.PARTNER_OBJECT = AUFK.OBJNR
        JOIN vbap_cte  VBAP
            ON AUFK.KDAUF = VBAP.VBELN and AUFK.KDPOS = VBAP.POSNR
    WHERE OBJECT_NUMBER like 'PR%' and PARTNER_OBJECT LIKE 'OR%'
),
PR_OV_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        vbap.zzorty AS SALES_CATEGORY,
        vbap.VBELN AS SALES_DOCUMENT,
        vbap.POSNR AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU089_AFVC') }}  AFVC
            ON universal_pl_data.PARTNER_OBJECT = AFVC.OBJNR
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU119_AFKO') }}  AFKO
            ON AFVC.AUFPL = AFKO.AUFPL
        JOIN {{ ref('BRONZE__TEH_REVENUE_COGS__SAPAPI_ZCDV_T_CMTU090_AUFK') }}  AUFK
            ON AFKO.AUFNR = AUFK.AUFNR
        JOIN vbap_cte  VBAP
            ON AUFK.KDAUF = VBAP.VBELN and AUFK.KDPOS = VBAP.POSNR
    WHERE OBJECT_NUMBER like 'PR%' and PARTNER_OBJECT LIKE 'OV%'
),
source_data as
(
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,

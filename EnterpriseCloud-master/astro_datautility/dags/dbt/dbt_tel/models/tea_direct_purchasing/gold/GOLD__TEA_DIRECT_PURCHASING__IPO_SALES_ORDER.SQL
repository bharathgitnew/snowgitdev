        incremental_strategy='insert_overwrite',
        alias='IPO_SALES_ORDER',
        transient=false,
        enabled=true
) }}

WITH MAX_GTM_FIELD AS
( 
    SELECT 
         ZZDVONO
        ,ZZDVOINO
        ,MAX(ZZGCST) AS ZZGCST
        ,MAX(ZZGRSZ) AS ZZGRSZ
    FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU187_ZSDT0165') }}
    GROUP BY ZZDVONO, ZZDVOINO
), 
VBFA AS (
    SELECT 
        VBELN, 
        POSNN, 
        VBELV, 
        POSNV, 
        VBTYP_N  
    FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU064_VBFA') }}
    WHERE VBTYP_N = 'V'
) ,

VBPA_INFO AS (
    SELECT 
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_THE_SD_DOCUMENT,
        CUSTOMER_NUMBER,
        PARTNER_FUNCTION
    FROM {{ ref('SILVER__TEA_DIRECT_PURCHASING__BUSINESS_PARTNERS') }}
    WHERE PARTNER_FUNCTION='SP'
),

SHIP_TO AS (   
    SELECT 
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_THE_SD_DOCUMENT,
        CUSTOMER_NUMBER,
        PARTNER_FUNCTION
    FROM {{ ref('SILVER__TEA_DIRECT_PURCHASING__BUSINESS_PARTNERS') }}
    WHERE PARTNER_FUNCTION='SH'
),

EKES AS ( 
  SELECT 
    EBELN, 
    EBELP, 
    MAX(EINDT) AS EINDT
  FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU050_EKES') }}
  WHERE EBTYP = 'AB'
  GROUP BY EBELN, EBELP
),

business_partners_general_data as (
    select distinct
        SEARCH_TERM_1_FOR_BUSINESS_PARTNER,
        BUSINESS_PARTNER_NUMBER
    from {{ ref('SILVER__TEA_DIRECT_PURCHASING__BUSINESS_PARTNERS_GENERAL_DATA') }}
),

schedule_lines as (
    select 
        VBEP_SALES_DOCUMENT,
        VBEP_SALES_DOCUMENT_ITEM,
        SCHEDULE_LINE_NUMBER,
        SCHEDULE_LINE_DATE_EDATU
    from {{ ref('SILVER__TEA_DIRECT_PURCHASING__SALES_ORDER_SCHEDULE_LINE') }}
    qualify row_number() over(partition by VBEP_SALES_DOCUMENT, VBEP_SALES_DOCUMENT_ITEM order by SCHEDULE_LINE_NUMBER) = 1
),

Sales_to_delivery as ( 
      SELECT 
        VBAK_SALES_DOCUMENT 
        ,SALES_DOCUMENT_ITEM_POSNR 
        ,VBAK_DELIVERY_CREATE_DATE 
        ,VBAK_SALES_DOCUMENT_TYPE 
        ,CUSTOMER_REFERENCE 
        ,REQUESTED_DELIVERY_DATE 
        ,MATERIAL_NUMBER
        ,VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM 
        ,CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS 
        ,VBAP_BASE_UNIT_OF_MEASURE 
        ,CUSTOMER_REFERENCE_DATE 
        ,VBAP_SHIP_DATE 
        ,UPDATE_DATE_VBAP 
        ,ACTUAL_GOODS_MOVEMENT_DATE
        ,STORAGE_LOCATION_VBAP 
        ,LIPS_DELIVERY
        ,DELIVERY_ITEM_POSNR 
        ,LIPS_DELIVERY_CREATE_DATE 
        ,LIKP_OVERALL_GOODS_MOVEMENT_STATUS
        ,ACTUAL_QUANTITY_DELIVERED 
        ,REASON_FOR_REJECTION_OF_SALES_DOCUMENTS 
        ,NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY 
        ,zeroifnull(NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY/nullifzero(CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS)) AS SO_PART_PRICE
        ,sum(ACTUAL_QUANTITY_DELIVERED) over ( partition by VBAK_SALES_DOCUMENT,SALES_DOCUMENT_ITEM_POSNR order by LIPS_DELIVERY,DELIVERY_ITEM_POSNR 
ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING )
        AS OVER_ALL_DEL_QTY
  FROM {{ ref('SILVER__TEA_DIRECT_PURCHASING__SALES_ORDER_DELIVERY_LINE') }}
  WHERE VBAK_SALES_DOCUMENT_TYPE = 'ZT10' 
),

SOURCE_DATA AS 
(   
    SELECT DISTINCT
        SD.VBAK_SALES_DOCUMENT AS SO_NUMBER
        ,SD.SALES_DOCUMENT_ITEM_POSNR AS SO_LINE
        ,SD.VBAK_DELIVERY_CREATE_DATE AS SO_CREATE_DT
        ,SD.VBAK_SALES_DOCUMENT_TYPE AS ORDER_TYPE
        ,VBPA_INFO.CUSTOMER_NUMBER AS SOLD_TO
        ,BP.SEARCH_TERM_1_FOR_BUSINESS_PARTNER AS SOLD_TO_NAME
        ,SHIP_TO.CUSTOMER_NUMBER AS SHIP_TO
        ,BP2.SEARCH_TERM_1_FOR_BUSINESS_PARTNER AS SHIP_TO_NAME
        ,SD.CUSTOMER_REFERENCE AS CUST_PO_NUMBER
        ,SD.REQUESTED_DELIVERY_DATE AS CUST_REQ_DT
        ,schedule_lines.SCHEDULE_LINE_DATE_EDATU AS FIRST_DATE
        ,VBFA.VBELN AS OUR_PO_NUMBER
        ,VBFA.POSNN AS PO_LINE
        ,EK.LIFNR AS VENDOR_ID
        ,BP4.SEARCH_TERM_1_FOR_BUSINESS_PARTNER AS VENDOR_NAME
        ,SD.MATERIAL_NUMBER AS ITEM
        ,SD.VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM AS DESCRIPTION
        ,SD.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS AS QTY
        ,SD.VBAP_BASE_UNIT_OF_MEASURE AS UOM
        ,SD.CUSTOMER_REFERENCE_DATE AS CUST_PO_DT
        ,SD.VBAP_SHIP_DATE AS PLAN_SHIP_DT
        ,SD.UPDATE_DATE_VBAP AS UPDATE_DT
        ,EKES.EINDT AS CONFIRM_DT
        ,SD.ACTUAL_GOODS_MOVEMENT_DATE
        ,SD.STORAGE_LOCATION_VBAP AS SLOC
        ,T001L.LGOBE AS SLOC_DESC
        ,EKPO.EBELN
        ,EKPO.EBELP
        ,MAX_GTM_FIELD.ZZGCST AS GTM_CHECK_STATUS
        ,MAX_GTM_FIELD.ZZGRSZ AS GTM_RETURN_STATUS
        ,SD.LIPS_DELIVERY AS OBDO_NUMBER
        ,SD.DELIVERY_ITEM_POSNR AS DO_LINE
        ,SD.LIPS_DELIVERY_CREATE_DATE AS DO_CREATE_DT
        ,SD.ACTUAL_QUANTITY_DELIVERED AS DO_QTY
        ,SD.REASON_FOR_REJECTION_OF_SALES_DOCUMENTS AS REJECTION_STATUS
        ,SD.NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY AS SO_LINE_PRICE
        ,zeroifnull(SO_LINE_PRICE/nullifzero(QTY)) AS SO_PART_PRICE
    FROM Sales_to_delivery SD
    LEFT JOIN VBPA_INFO ON SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER=SD.VBAK_SALES_DOCUMENT 
    LEFT JOIN SHIP_TO ON SHIP_TO.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER=SD.VBAK_SALES_DOCUMENT 
    LEFT JOIN MAX_GTM_FIELD  ON SD.LIPS_DELIVERY = MAX_GTM_FIELD.ZZDVONO AND SD.DELIVERY_ITEM_POSNR = TRY_TO_NUMBER(MAX_GTM_FIELD.ZZDVOINO)
    LEFT JOIN (SELECT VBELN, POSNN, VBELV, POSNV, VBTYP_N  FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU064_VBFA')}}  WHERE VBTYP_N = 'V') AS VBFA ON SD.VBAK_SALES_DOCUMENT = VBFA.VBELV AND SD.SALES_DOCUMENT_ITEM_POSNR = TRY_TO_NUMBER(VBFA.POSNV)  
    LEFT JOIN {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU028_EKPO')}} EKPO ON EKPO.EBELN = VBFA.VBELN AND TRY_TO_NUMBER(EKPO.EBELP) = TRY_TO_NUMBER(VBFA.POSNN)
    LEFT JOIN EKES ON EKPO.EBELN = EKES.EBELN AND TRY_TO_NUMBER(EKPO.EBELP) = TRY_TO_NUMBER(EKES.EBELP)
    LEFT JOIN {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU027_EKKO')}} EK ON VBFA.VBELN = EK.EBELN AND VBFA.POSNN = TRY_TO_NUMBER(EKPO.EBELP)
    LEFT JOIN business_partners_general_data BP ON VBPA_INFO.CUSTOMER_NUMBER = BP.BUSINESS_PARTNER_NUMBER
    LEFT JOIN business_partners_general_data BP2 ON SHIP_TO.CUSTOMER_NUMBER = BP2.BUSINESS_PARTNER_NUMBER
    LEFT JOIN business_partners_general_data BP4 ON EK.LIFNR = BP4.BUSINESS_PARTNER_NUMBER
    LEFT JOIN {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU080_T001L')}} T001L ON T001L.LGORT = SD.STORAGE_LOCATION_VBAP
    LEFT JOIN schedule_lines on try_to_number(schedule_lines.VBEP_SALES_DOCUMENT) = try_to_number(SD.VBAK_SALES_DOCUMENT) and try_to_number(schedule_lines.VBEP_SALES_DOCUMENT_ITEM) = try_to_number(SD.SALES_DOCUMENT_ITEM_POSNR)
    WHERE 1=1
    --AND ORDER_TYPE = 'ZT10' 
    AND (TRIM(EKPO.LOEKZ)='' OR EKPO.LOEKZ IS NULL) -- LOEKZ is the deletion indicator in EKPO table, any non null or non blank value in this field means the record/PO line is deleted
    --AND LIKP_OVERALL_GOODS_MOVEMENT_STATUS != 'C' Commented out this and replaced it with below logic as requested in #CAS-169903-M0S7K0
    --AND ((OBDO_NUMBER IS NULL) OR (OBDO_NUMBER IS NOT NULL AND LIKP_OVERALL_GOODS_MOVEMENT_STATUS!='C' and DO_QTY>0))
    AND ((OBDO_NUMBER IS NULL) OR (OBDO_NUMBER IS NOT NULL AND 
    (LIKP_OVERALL_GOODS_MOVEMENT_STATUS!='C' OR (CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS - OVER_ALL_DEL_QTY) > 0 )
    AND DO_QTY > 0 ))
    AND nullif(trim(REJECTION_STATUS),'') is null
),

	TRANSFORM_DATA AS (
    SELECT
		'{{ invocation_id }}' as _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		SO_NUMBER,
		SO_LINE,
		SO_CREATE_DT,
		ORDER_TYPE,
		SOLD_TO,
		SOLD_TO_NAME,
		SHIP_TO,
		SHIP_TO_NAME,
		CUST_PO_NUMBER,
		CUST_REQ_DT,
		FIRST_DATE,
		OUR_PO_NUMBER,
		PO_LINE,
		VENDOR_ID,
		VENDOR_NAME,
		ITEM,
		DESCRIPTION,
		QTY,
		UOM,
		CUST_PO_DT,
		PLAN_SHIP_DT,
		UPDATE_DT,
		CONFIRM_DT,
		SO_PART_PRICE,
		SO_LINE_PRICE,
		ACTUAL_GOODS_MOVEMENT_DATE,
		SLOC,
		SLOC_DESC,
		EBELN,
		EBELP,
		GTM_CHECK_STATUS,
		GTM_RETURN_STATUS,
		OBDO_NUMBER,
		DO_LINE,
		DO_CREATE_DT,
		DO_QTY,
		REJECTION_STATUS 
    FROM SOURCE_DATA
),

	TYPE_DATA AS (
    SELECT
		cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		CAST(SO_NUMBER AS VARCHAR(16777216)) AS SO_NUMBER,
		CAST(SO_LINE AS VARCHAR(16777216)) AS SO_LINE,
		TRY_TO_DATE(SO_CREATE_DT,'YYYYMMDD') AS SO_CREATE_DT,
		CAST(ORDER_TYPE AS VARCHAR(16777216)) AS ORDER_TYPE,
		CAST(SOLD_TO AS VARCHAR(16777216)) AS SOLD_TO,
		CAST(SOLD_TO_NAME AS VARCHAR(16777216)) AS SOLD_TO_NAME,
		CAST(SHIP_TO AS VARCHAR(16777216)) AS SHIP_TO,
		CAST(SHIP_TO_NAME AS VARCHAR(16777216)) AS SHIP_TO_NAME,
		CAST(CUST_PO_NUMBER AS VARCHAR(16777216)) AS CUST_PO_NUMBER,
		TRY_TO_DATE(CUST_REQ_DT,'YYYYMMDD') AS CUST_REQ_DT,
		TRY_TO_DATE(FIRST_DATE,'YYYYMMDD') AS FIRST_DATE,
		CAST(OUR_PO_NUMBER AS VARCHAR(16777216)) AS OUR_PO_NUMBER,
		CAST(PO_LINE AS VARCHAR(16777216)) AS PO_LINE,
		CAST(VENDOR_ID AS VARCHAR(16777216)) AS VENDOR_ID,
		CAST(VENDOR_NAME AS VARCHAR(16777216)) AS VENDOR_NAME,
		CAST(ITEM AS VARCHAR(16777216)) AS ITEM,
		CAST(DESCRIPTION AS VARCHAR(16777216)) AS DESCRIPTION,
		CAST(QTY AS NUMBER(38,0)) AS QTY,
		CAST(UOM AS VARCHAR(16777216)) AS UOM,
		TRY_TO_DATE(CUST_PO_DT,'YYYYMMDD') AS CUST_PO_DT,
		TRY_TO_DATE(PLAN_SHIP_DT,'YYYYMMDD') AS PLAN_SHIP_DT,
		TRY_TO_DATE(UPDATE_DT,'YYYYMMDD') AS UPDATE_DT,
		TRY_TO_DATE(CONFIRM_DT,'YYYYMMDD') AS CONFIRM_DT,
		CAST(SO_PART_PRICE AS VARCHAR(16777216)) AS SO_PART_PRICE,
		CAST(SO_LINE_PRICE AS VARCHAR(16777216)) AS SO_LINE_PRICE,
		TRY_TO_DATE(ACTUAL_GOODS_MOVEMENT_DATE,'YYYYMMDD') AS ACTUAL_GOODS_MOVEMENT_DATE,
		CAST(SLOC AS VARCHAR(16777216)) AS SLOC,
		CAST(SLOC_DESC AS VARCHAR(16777216)) AS SLOC_DESC,
		CAST(EBELN AS VARCHAR(16777216)) AS EBELN,
		CAST(EBELP AS VARCHAR(16777216)) AS EBELP,
		CAST(GTM_CHECK_STATUS AS VARCHAR(16777216)) AS GTM_CHECK_STATUS,
		CAST(GTM_RETURN_STATUS AS VARCHAR(16777216)) AS GTM_RETURN_STATUS,
		CAST(OBDO_NUMBER AS VARCHAR(16777216)) AS OBDO_NUMBER,
		CAST(DO_LINE AS VARCHAR(16777216)) AS DO_LINE,
		TRY_TO_DATE(DO_CREATE_DT,'YYYYMMDD') AS DO_CREATE_DT,
		CAST(DO_QTY AS NUMBER(38,0)) AS DO_QTY,
		CAST(REJECTION_STATUS AS VARCHAR(16777216)) AS REJECTION_STATUS
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
WITH PURCHASE_ORDER AS (
	SELECT 
		DISTINCT
		EKPO_PURCHASING_DOCUMENT_NUMBER AS PURCHASE_ORDER,
		ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP AS PO_LINE,
		PURCHASING_DOCUMENT_TYPE AS PO_TYPE,
		PURCHASING_DOCUMENT_DATE AS PO_DATE,
		CASH_DISCOUNT_DAYS_ZBD1T AS PAYTERM,
		EKKO_VENDOR_S_ACCOUNT_NUMBER AS VENDOR,
		MATERIAL_NUMBER_MATNR AS MATERIAL,
		SHORT_TEXT AS MATERIAL_DESCRIPTION,
		CREATED_BY_EMPLOYEE_NO AS BUYER,
		PURCHASE_ORDER_QUANTITY AS PO_QTY,
		NET_PRICE_IN_PURCHASING_DOCUMENT*PURCHASE_ORDER_QUANTITY AS PO_VALUE,
		NUMBER_OF_PURCHASING_INFO_RECORD AS PIR
	FROM  {{ ref('GOLD__TEA_DIRECT_PURCHASING__PURCHASE_ORDER_DELIVERY_LINE') }} 
		WHERE EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT <>'L'
		AND SUBSTR(EKPO_PURCHASING_DOCUMENT_NUMBER,0,1) = '4'
		AND EKPO_PURCHASING_DOCUMENT_CATEGORY = 'F'
		AND PURCHASING_DOCUMENT_TYPE NOT IN ('ZP25','ZP26')
),
LFA1 AS ( 
	SELECT 
		LIFNR AS VENDOR ,
		NAME1 AS VENDOR_NAME 
	FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU061_LFA1') }} 
),
PO_TYPE AS (
	SELECT
		BSART AS PO_TYPE,
		BATXT AS PO_TYPE_TEXT
	FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU129_T161T') }}
		WHERE BSTYP = 'F'
),
PIR AS (
	SELECT 
		INFNR AS PIR,
		EKORG AS PURCHASE_ORG,
		WERKS AS PLANT,
		NETPR AS PRICE
    FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU073_EINE') }} 
        WHERE  EKORG IN ('3200','3300')
),
MATDOC AS (
	SELECT
		MJAHR,
		MBLNR,
		ZEILE,
		RECORD_TYPE,
		CANCELLED,
		EBELN,
		EBELP,
		BWART,
		BUDAT,
		SHKZG,
		BSTMG
	FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU025_MATDOC') }}
		WHERE RECORD_TYPE = 'MDOC'
		AND BWART IN ('101','102','105','106')
		QUALIFY(ROW_NUMBER() OVER(PARTITION BY MJAHR,MBLNR,ZEILE,BWART ORDER BY MJAHR,MBLNR,ZEILE,BWART)) = 1
),
GR_DATE AS (
	SELECT
		EBELN AS PURCHASE_ORDER,
		EBELP AS PO_LINE,
		MAX(BUDAT) OVER (PARTITION BY EBELN,EBELP ORDER BY EBELN,EBELP,BUDAT DESC )  AS GR_DATE,
		SUM(CASE WHEN SHKZG = 'S' THEN BSTMG ELSE BSTMG * -1 END) AS GR_QUANTITY,
		SUM(GR_QUANTITY) OVER (PARTITION BY EBELN,EBELP ORDER BY  EBELN,EBELP ) AS GR_QTY
	FROM MATDOC WHERE
		EBELN <> ''
		GROUP BY EBELN,EBELP,BUDAT
),
GR AS ( 
	SELECT 
		PURCHASE_ORDER,
		PO_LINE,
		MAX(GR_DATE) AS GR_DATE,
		TO_NUMBER(SUM(GR_QUANTITY)) AS GR_QTY
	FROM GR_DATE  
		GROUP BY PURCHASE_ORDER,PO_LINE,GR_DATE
),
INVOICE_DATE AS (
	select 
		RSEG.EBELN AS PURCHASE_ORDER,
		RSEG.EBELP AS PO_LINE,
		MAX(RBKP.BUDAT)  OVER (PARTITION BY RSEG.EBELN,RSEG.EBELP ORDER BY RSEG.EBELN,RSEG.EBELP,RBKP.BUDAT DESC ) AS INV_DATE,
		SUM(CASE WHEN RSEG.SHKZG = 'S' THEN RSEG.MENGE ELSE RSEG.MENGE * -1 END) AS INVOICEDQTY,
		SUM(CASE WHEN RSEG.SHKZG = 'S' THEN RSEG.WRBTR ELSE RSEG.WRBTR * -1 END) AS INVOICEDAMOUNT
	from 
	{{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU197_RSEG') }} as RSEG 
	left join {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU237_RBKP') }} as RBKP
	on RSEG.BELNR = RBKP.BELNR
	group by RSEG.EBELN,RSEG.EBELP,RSEG.SHKZG,RBKP.BUDAT
),
INVOICE AS (
	SELECT 
		PURCHASE_ORDER,
		PO_LINE,
		INV_DATE,
		SUM(INVOICEDQTY) AS INVOICEDQTY,
		SUM(INVOICEDAMOUNT) AS INVOICEDAMOUNT
	FROM INVOICE_DATE
		GROUP BY  PURCHASE_ORDER,PO_LINE,INV_DATE 
),
FINAL_LOGIC_DATA AS (
	SELECT 
		PO.PURCHASE_ORDER,
		PO.PO_LINE,
		PO.PO_TYPE,
		PO_TYPE.PO_TYPE_TEXT,
		PO.VENDOR,
		LFA1.VENDOR_NAME,
		PO.MATERIAL,
		PO.MATERIAL_DESCRIPTION,
		PO.BUYER,
		TO_DATE(PO.PO_DATE,'YYYYMMDD') AS PO_DATE,
		TO_DATE(GR.GR_DATE,'YYYYMMDD') AS GR_DATE,
		TO_DATE(INV.INV_DATE,'YYYYMMDD') AS INVOICE_DATE,
		YEAR(DATEADD(YEAR,CASE WHEN MONTH(CASE WHEN GR.GR_DATE <> '' THEN TO_DATE(GR.GR_DATE,'YYYYMMDD') ELSE TO_DATE(INV.INV_DATE,'YYYYMMDD') END) <= 3 THEN 0 ELSE 1 END,
			   CASE WHEN GR.GR_DATE <> '' THEN TO_DATE(GR.GR_DATE,'YYYYMMDD') ELSE TO_DATE(INV.INV_DATE,'YYYYMMDD') END)) AS FISCAL,
		MONTH(DATEADD(MONTH,CASE WHEN MONTH(CASE WHEN GR.GR_DATE <> '' THEN TO_DATE(GR.GR_DATE,'YYYYMMDD') ELSE TO_DATE(INV.INV_DATE,'YYYYMMDD') END) <= 3 THEN 9 ELSE -3 END,
			   CASE WHEN GR.GR_DATE <> '' THEN TO_DATE(GR.GR_DATE,'YYYYMMDD') ELSE TO_DATE(INV.INV_DATE,'YYYYMMDD') END)) AS FISCAL_PERIOD,
		ZEROIFNULL(PO.PO_QTY) AS PO_QUANTITY,
		ZEROIFNULL(GR.GR_QTY) AS GR_QUANTITY,
		ZEROIFNULL(INV.INVOICEDQTY) AS INVOICE_QTY,
		PO.PO_VALUE,
		PIR.PRICE * PO.PO_QTY AS PIR_VALUE,
		DATEDIFF(DAY,TO_DATE(GR.GR_DATE,'YYYYMMDD'),CURRENT_DATE) AS AGE,
		CASE  WHEN AGE > 120 THEN '> 120'
			  WHEN AGE >91 AND AGE <= 120 THEN '> 90'
			  WHEN AGE >61 AND AGE <= 90 THEN '> 60'
			  WHEN AGE >31 AND AGE <= 60 THEN '> 30'
			 ELSE 'CURRENT' END AS AGE_BUCKET,
		CASE WHEN PO_QUANTITY - INVOICE_QTY = 0 THEN ( CASE WHEN PO_QUANTITY - GR_QUANTITY = 0 THEN 'X' ELSE 'Y' END ) ELSE
		  ( CASE WHEN GR_QUANTITY = 0  THEN 'X' ELSE 'Y' END ) END AS FLAG
	FROM PURCHASE_ORDER AS PO
		LEFT JOIN GR
		ON PO.PURCHASE_ORDER = GR.PURCHASE_ORDER
		AND PO.PO_LINE = GR.PO_LINE
		LEFT JOIN INVOICE AS INV
		ON LTRIM(PO.PURCHASE_ORDER,0) = LTRIM(INV.PURCHASE_ORDER,0)
		AND LTRIM(PO.PO_LINE,0) = LTRIM(INV.PO_LINE,0)
		LEFT JOIN PIR ON PO.PIR = PIR.PIR
		LEFT JOIN LFA1 ON PO.VENDOR = LFA1.VENDOR
		LEFT JOIN PO_TYPE ON PO_TYPE.PO_TYPE = PO.PO_TYPE
		WHERE 
		FLAG = 'Y'
),
FINAL_DATA AS (
	SELECT 
        PURCHASE_ORDER,
        PO_LINE,
        PO_TYPE,
        PO_TYPE_TEXT,
        VENDOR,
        VENDOR_NAME,
        MATERIAL,
        MATERIAL_DESCRIPTION,
        BUYER,
        PO_DATE,
        GR_DATE,
        INVOICE_DATE,
        FISCAL,
        FISCAL_PERIOD,
        PO_QUANTITY,
        GR_QUANTITY,
        INVOICE_QTY,
        PO_VALUE,
        PIR_VALUE,
        PIR_VALUE - PO_VALUE AS DIFFERENCE,
        AGE,
        AGE_BUCKET
	FROM FINAL_LOGIC_DATA
),
SOURCE_DATA AS (
	SELECT 
	    PURCHASE_ORDER,
        PO_LINE,
        PO_TYPE,
        PO_TYPE_TEXT,
        VENDOR,
        VENDOR_NAME,
        MATERIAL,
        MATERIAL_DESCRIPTION,
        BUYER,
        PO_DATE,
        GR_DATE,
        INVOICE_DATE,
        FISCAL,
        FISCAL_PERIOD,
        PO_QUANTITY,
        GR_QUANTITY,
        INVOICE_QTY,
        PO_VALUE,
        PIR_VALUE,
        DIFFERENCE,
        AGE,
        AGE_BUCKET
	FROM FINAL_DATA
	),
	TRANSFORM_DATA AS ( 
    SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		PURCHASE_ORDER,
		PO_LINE,
		PO_TYPE,
		PO_TYPE_TEXT,
		VENDOR,
		VENDOR_NAME,
		MATERIAL,
		MATERIAL_DESCRIPTION,
		BUYER,
		PO_DATE,
		GR_DATE,
		INVOICE_DATE,
		FISCAL,
		FISCAL_PERIOD,
		PO_QUANTITY,
		GR_QUANTITY,
		INVOICE_QTY,
		PO_VALUE,
		PIR_VALUE,
		DIFFERENCE,
		AGE,
		AGE_BUCKET,
		SHA2('HASH_ME') AS _ROW_HASH -- ADDS COLUMN TO TABLE ON FULL REFRESH.
    FROM SOURCE_DATA
),
	TYPE_DATA AS (
    SELECT 
		CAST( _AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		CAST( _ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
		CAST( PURCHASE_ORDER AS VARCHAR(16777216)) AS  PURCHASE_ORDER,
		CAST( PO_LINE AS VARCHAR(16777216)) AS  PO_LINE,
		CAST( PO_TYPE AS VARCHAR(16777216)) AS  PO_TYPE,
		CAST( PO_TYPE_TEXT AS VARCHAR(16777216)) AS  PO_TYPE_TEXT,
		CAST( VENDOR AS VARCHAR(16777216)) AS  VENDOR,
		CAST( VENDOR_NAME AS VARCHAR(16777216)) AS  VENDOR_NAME,
		CAST( MATERIAL AS VARCHAR(16777216)) AS  MATERIAL,
		CAST( MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS  MATERIAL_DESCRIPTION,
		CAST( BUYER AS VARCHAR(16777216)) AS  BUYER,
		CAST( PO_DATE AS DATE) AS  PO_DATE,
		CAST( GR_DATE AS DATE) AS  GR_DATE,
		CAST( INVOICE_DATE AS DATE) AS  INVOICE_DATE,
		CAST( FISCAL AS NUMBER(38,0)) AS  FISCAL,
		CAST( FISCAL_PERIOD AS NUMBER(38,0)) AS  FISCAL_PERIOD,
		CAST( PO_QUANTITY AS NUMBER(38,0)) AS  PO_QUANTITY,
		CAST( GR_QUANTITY AS NUMBER(38,0)) AS  GR_QUANTITY,
		CAST( INVOICE_QTY AS NUMBER(38,0)) AS  INVOICE_QTY,
		CAST( PO_VALUE AS NUMBER(38,2)) AS  PO_VALUE,
		CAST( PIR_VALUE AS NUMBER(38,2)) AS  PIR_VALUE,
		CAST( DIFFERENCE AS NUMBER(38,2)) AS  DIFFERENCE,
		CAST( AGE AS NUMBER(38,0)) AS  AGE,
		CAST( AGE_BUCKET AS VARCHAR(16777216)) AS AGE_BUCKET
    FROM TRANSFORM_DATA
)


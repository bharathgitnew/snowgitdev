WITH GR as (  
    SELECT 
        EBELN as PO_NUMBER,
        TO_NUMBER(EBELP) as PO_LINE_NUMBER,
        BUDAT as GR_DATE,
        SUM(CASE WHEN SHKZG = 'S' THEN MENGE ELSE MENGE * -1 END) AS QTY_RECEIVED
    FROM {{ ref('BRONZE__TEA_DIRECT_PURCHASING__SAPAPI_ZCDV_T_CMTU217_EKBE') }} 
    WHERE BEWTP = 'E' 
    GROUP BY EBELN,EBELP,BUDAT
),
 
PO as (
    SELECT  
        PO_NUMBER,
        TO_NUMBER(LINE_ITEM) as PO_LINE_NUMBER,
        REQUESTED_DELIVERY_DATE as PLANNED_DELIVERY_DATE,
        VENDOR as SUPPLIER_CODE,
        VENDOR_NAME as SUPPLIER_NAME,
        SUBSTR(PART_NUMBER,3) as PART_NUMBER,
        PART_NUMBER as TEL_PART_NUMBER,
        DESCRIPTION,
        CONFIRMED_QTY as PO_QTY,
        CURRENCY, 
        NET_PRICE as PRICE,
        LINE_TOTAL as SPEND
    FROM {{ ref('GOLD__TEA_DIRECT_PURCHASING__PURCHASE_ORDER_MASTER') }}  
    WHERE (PO_TYPE = 'ZP20' or PO_TYPE = 'ZP21' or PO_TYPE = 'ZP22' or PO_TYPE = 'ZR20' or PO_TYPE = 'ZS20') 
    AND VENDOR NOT IN ('BA0000100','BA0010200','BA0010300','BA0010500','BA0012000','BA0013300','BA0013600')
    QUALIFY(ROW_NUMBER() OVER (PARTITION BY PO_NUMBER,LINE_ITEM ORDER BY REQUESTED_DELIVERY_DATE DESC) = 1) 
),
 
PO_LINE as ( 
    SELECT 
        DISTINCT EKPO_PURCHASING_DOCUMENT_NUMBER as PO_NUMBER,
        TO_NUMBER(ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP) as PO_LINE_NUMBER,
        PURCHASING_GROUP,
        EKPO_COMPANY_CODE as COMPANYCODE,
        PURCHASE_ORDER_UNIT_OF_MEASURE as UNIT 
    FROM {{ ref('GOLD__TEA_DIRECT_PURCHASING__PURCHASE_ORDER_DELIVERY_LINE') }}   
    WHERE EKKO_COMPANY_CODE = '3200'
),
 
SOURCE_DATA AS (
	SELECT  
        PO.PO_NUMBER AS PO_NUMBER,
        PO.PO_LINE_NUMBER AS PO_LINE_NUMBER,
        PLANNED_DELIVERY_DATE,
        TO_VARCHAR(TO_DATE(GR.GR_DATE, 'YYYYMMDD'), 'MM/DD/YYYY') AS ACCEPTANCE_DATE, 
        SUPPLIER_CODE,
        SUPPLIER_NAME,
        PART_NUMBER,
        TEL_PART_NUMBER,
        DESCRIPTION,
        PO_LINE.UNIT AS UNIT,
        GR.QTY_RECEIVED AS QTY_RECEIVED,
        PO.CURRENCY AS CURRENCY,
        PRICE,
        PRICE * QTY_RECEIVED as SPEND,
        MONTH(TO_DATE(GR.GR_DATE, 'YYYYMMDD')) as MONTH_OF_ACCEPTANCE_DATE
    FROM PO
    INNER JOIN PO_LINE 
    ON PO.PO_NUMBER = PO_LINE.PO_NUMBER AND PO.PO_LINE_NUMBER = PO_LINE.PO_LINE_NUMBER
    LEFT JOIN GR 
    ON PO.PO_NUMBER = GR.PO_NUMBER AND PO.PO_LINE_NUMBER = GR.PO_LINE_NUMBER
),

TRANSFORM_DATA AS ( 
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('HASH_ME') AS _ROW_HASH, -- ADDS COLUMN TO TABLE ON FULL REFRESH.
        PO_NUMBER,
        PO_LINE_NUMBER,
        PLANNED_DELIVERY_DATE,
        ACCEPTANCE_DATE, 
        SUPPLIER_CODE,
        SUPPLIER_NAME,
        PART_NUMBER,
        TEL_PART_NUMBER,
        DESCRIPTION,
        UNIT,
        QTY_RECEIVED,
        CURRENCY,
        PRICE,
        SPEND,
        MONTH_OF_ACCEPTANCE_DATE
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT 
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        PO_NUMBER,
        PO_LINE_NUMBER,
        PLANNED_DELIVERY_DATE,
        ACCEPTANCE_DATE, 
        SUPPLIER_CODE,
        SUPPLIER_NAME,
        PART_NUMBER,
        TEL_PART_NUMBER,
        DESCRIPTION,
        UNIT,
        QTY_RECEIVED,
        CURRENCY,
        PRICE,
        SPEND,
        MONTH_OF_ACCEPTANCE_DATE
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
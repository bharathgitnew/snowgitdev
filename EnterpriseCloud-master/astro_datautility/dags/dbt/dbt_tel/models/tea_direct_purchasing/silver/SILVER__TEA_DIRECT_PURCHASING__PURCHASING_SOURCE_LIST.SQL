    select
        MATNR as MATERIAL_NUMBER,
        WERKS as PLANT,
        ZEORD as NUMBER_OF_SOURCE_LIST_RECORD,
        ERDAT as DATE_ON_WHICH_THE_RECORD_WAS_CREATED,
        ERNAM as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
        VDATU as SOURCE_LIST_RECORD_VALID_FROM,
        BDATU as SOURCE_LIST_RECORD_VALID_TO,
        LIFNR as VENDORS_ACCOUNT_NUMBER,
        FLIFN as INDICATOR_FIXED_SUPPLIER,
        EBELN as AGREEMENT_NUMBER,

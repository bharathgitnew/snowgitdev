        FRESW as FIXED_ISSUING_PLANT_IN_CASE_OF_STOCK_TRANSPORT_ORDER,
        EMATN as MATERIAL_NUMBER_CORRESPONDING_TO_MANUFACTURER_PART_NUMBER,
        NOTKZ as BLOCKED_SOURCE_OF_SUPPLY,
        EKORG as PURCHASING_ORGANIZATION,

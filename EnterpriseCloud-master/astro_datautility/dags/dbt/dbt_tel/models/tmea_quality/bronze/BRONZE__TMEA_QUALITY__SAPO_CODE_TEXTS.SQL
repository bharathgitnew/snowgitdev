{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='SAPO_CODE_TEXTS',
        unique_key = ['MANDT',
    'KATALOGART',
    'CODEGRUPPE',
    'CODE',
    'SPRACHE',
    'VERSION'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	KATALOGART,
	CODEGRUPPE,
	CODE,
	SPRACHE,
	VERSION,
	GUELTIGAB,
	KURZTEXT,
	LTEXTV,
	INAKTIV,
	GELOESCHT
	FROM {{source('SAP_ORACLE_LIVE', 'QPCT')}}
),


transform_data as 
(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDT as MANDT,
	KATALOGART as KATALOGART,
	CODEGRUPPE as CODEGRUPPE,
	CODE as CODE,
	SPRACHE as SPRACHE,
	VERSION as VERSION,
	GUELTIGAB as GUELTIGAB,
	KURZTEXT as KURZTEXT,
	LTEXTV as LTEXTV,
	INAKTIV as INAKTIV,
	GELOESCHT as GELOESCHT
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	MANDT,
	KATALOGART,
	CODEGRUPPE,
	CODE,
	SPRACHE,
	VERSION,
	GUELTIGAB,
	KURZTEXT,
	LTEXTV,
	INAKTIV,
	GELOESCHT
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
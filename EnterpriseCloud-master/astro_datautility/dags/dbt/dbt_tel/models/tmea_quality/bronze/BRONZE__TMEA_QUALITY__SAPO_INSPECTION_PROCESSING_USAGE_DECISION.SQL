	CAST(VCODEGRP AS varchar(16777216)) AS VCODEGRP,
	CAST(VCODE AS varchar(16777216)) AS VCODE,
	CAST(VERSIONAM AS varchar(16777216)) AS VERSIONAM,
	CAST(VERSIONCD AS varchar(16777216)) AS VERSIONCD,
	CAST(VBEWERTUNG AS varchar(16777216)) AS VBEWERTUNG,
	CAST(DBEWERTUNG AS varchar(16777216)) AS DBEWERTUNG,

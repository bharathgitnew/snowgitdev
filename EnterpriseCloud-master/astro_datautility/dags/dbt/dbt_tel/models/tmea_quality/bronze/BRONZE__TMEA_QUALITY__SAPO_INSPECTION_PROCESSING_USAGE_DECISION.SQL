	VAEDATUM,
	VEZEITAEN,
	STAFO,
	TEILLOS,
	VORGLFNR
	FROM {{ source("SAP_ORACLE_LIVE", "QAVE") }}
)
,
transform_data as 
(
    SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDANT as MANDANT,
	PRUEFLOS as PRUEFLOS,
	KZART as KZART,
	ZAEHLER as ZAEHLER,

	VORGLFNR as VORGLFNR
	FROM SOURCE_DATA
), 

type_data as 
(
    SELECT 
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(MANDANT AS varchar(16777216)) AS MANDANT,
	CAST(PRUEFLOS AS varchar(16777216)) AS PRUEFLOS,
	CAST(KZART AS varchar(16777216)) AS KZART,

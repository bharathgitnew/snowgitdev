{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='SAPO_CODE_GROUP_TEXTS',
        unique_key = ['MANDANT',
    'KATALOGART',
    'CODEGRUPPE',
    'SPRACHE'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDANT,
	KATALOGART,
	CODEGRUPPE,
	SPRACHE,
	KURZTEXT,
	LTEXTV,
	INAKTIV
	FROM {{source('SAP_ORACLE_LIVE', 'QPGT')}}
),


transform_data as 
(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDANT as MANDANT,
	KATALOGART as KATALOGART,
	CODEGRUPPE as CODEGRUPPE,
	SPRACHE as SPRACHE,
	KURZTEXT as KURZTEXT,
	LTEXTV as LTEXTV,
	INAKTIV as INAKTIV
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	MANDANT,
	KATALOGART,
	CODEGRUPPE,
	SPRACHE,
	KURZTEXT,
	LTEXTV,
	INAKTIV
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
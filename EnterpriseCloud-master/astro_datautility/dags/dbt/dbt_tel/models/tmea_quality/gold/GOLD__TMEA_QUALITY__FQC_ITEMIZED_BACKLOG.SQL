{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'FQC_ITEMIZED_BACKLOG',
        transient = false
) }}

WITH FQC_RECEIVE AS (
    SELECT
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    DESTINATION_STORAGE_TYPE AS STORAGE_TYPE,
    CONFIRMATION_DATE_1 AS DATE,
    iff(1=1, 'RECEIVE', NULL) AS TRANSACTION
    FROM  {{ ref('SILVER__TMEA_QUALITY__TRANSFER_ORDER_ITEM') }}
    WHERE DESTINATION_STORAGE_TYPE = '935'
    AND WAREHOUSE_NUMBER = '010'
    AND CONFIRMATION_DATE_1 > '2021-02-01'
    ),

FQC_RELEASE AS(
    SELECT
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    SOURCE_STORAGE_TYPE AS STORAGE_TYPE,
    CONFIRMATION_DATE_1 AS DATE,
    iff(1=1, 'RELEASE', NULL) AS TRANSACTION
    FROM {{ ref('SILVER__TMEA_QUALITY__TRANSFER_ORDER_ITEM') }}
    WHERE SOURCE_STORAGE_TYPE = '935'
    AND WAREHOUSE_NUMBER = '010'
    AND CONFIRMATION_DATE_1 > '2021-02-01'
    ),

source_data AS (
SELECT  MATERIAL_NUMBER,
    	MATERIAL_DESCRIPTION,
    	STORAGE_TYPE,
    	DATE,
    	TRANSACTION
    FROM FQC_RECEIVE
UNION ALL
SELECT  MATERIAL_NUMBER,
    	MATERIAL_DESCRIPTION,
    	STORAGE_TYPE,
    	DATE,
    	TRANSACTION
    FROM FQC_RELEASE
),

transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
    	MATERIAL_NUMBER,
    	MATERIAL_DESCRIPTION,
    	STORAGE_TYPE,
    	DATE,
    	TRANSACTION
    FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
	    CAST(MATERIAL_DESCRIPTION AS  VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
	    CAST(STORAGE_TYPE AS VARCHAR(16777216)) AS STORAGE_TYPE,
	    CAST(DATE AS  DATE) AS DATE,
	    CAST(TRANSACTION AS VARCHAR(16777216)) AS TRANSACTION
    FROM transform_data
)

SELECT * from type_data
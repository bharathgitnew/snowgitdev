        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'FQC_BACKLOG',
        transient = false
) }}


WITH MOVE
AS (
	SELECT MATERIAL_NUMBER,
		MATERIAL_DESCRIPTION,
		SOURCE_STORAGE_TYPE AS STORAGE_TYPE,
		CONFIRMATION_DATE_1 AS DATE,
		COUNT(QUANT_2) * - 1 AS STOCK
	FROM {{ ref('SILVER__TMEA_QUALITY__TRANSFER_ORDER_ITEM') }}
	WHERE SOURCE_STORAGE_TYPE = '935'
		AND WAREHOUSE_NUMBER = '010'
		AND PLANT = '0010'
		AND CONFIRMATION_DATE_1 > '2021-02-01'
	GROUP BY MATERIAL_NUMBER,
		MATERIAL_DESCRIPTION,
		SOURCE_STORAGE_TYPE,
		CONFIRMATION_DATE_1

	UNION

	SELECT MATERIAL_NUMBER,
		MATERIAL_DESCRIPTION,
		DESTINATION_STORAGE_TYPE AS STORAGE_TYPE,
		CONFIRMATION_DATE_1 AS DATE,
		COUNT(QUANT_2) AS STOCK
	FROM {{ ref('SILVER__TMEA_QUALITY__TRANSFER_ORDER_ITEM') }}
	WHERE DESTINATION_STORAGE_TYPE = '935'
		AND WAREHOUSE_NUMBER = '010'
		AND PLANT = '0010'
		AND CONFIRMATION_DATE_1 > '2021-02-01'
	GROUP BY MATERIAL_NUMBER,
		MATERIAL_DESCRIPTION,
		DESTINATION_STORAGE_TYPE,
		CONFIRMATION_DATE_1
	),
FINAL_MOVE
AS (
	SELECT DATE,
		SUM(STOCK) AS STOCK
	FROM MOVE
	GROUP BY DATE
	),
ISSUE_RECEIPT
AS (
	SELECT DATE,
		SUM(STOCK) AS RECEIPT_ISSUE
	FROM FINAL_MOVE
	GROUP BY DATE
	),
CURRENT_STOCK_COUNT
AS (
	SELECT 1 AS RANK,
		COUNT(*) AS COUNT_VALUE
	FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }}
	WHERE WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX = '010'
		AND PLANT = '0010'
		AND STORAGE_TYPE = '935'
		AND IS_DELETED = 'No'
		AND CLIENT = '300'
	),
MAX_DATE
AS (
	SELECT 1 AS RANK,
		MAX(DATE) AS DATE
	FROM ISSUE_RECEIPT
	),
JOIN_STOCK
AS (
	SELECT CURRENT_STOCK_COUNT.COUNT_VALUE AS COUNT_VALUE,
		MAX_DATE.DATE
	FROM CURRENT_STOCK_COUNT AS CURRENT_STOCK_COUNT
	JOIN MAX_DATE AS MAX_DATE ON CURRENT_STOCK_COUNT.RANK = MAX_DATE.RANK
	),
MERGE_DATA
AS (
	SELECT ISSUE_RECEIPT.DATE,
		SUM(ISSUE_RECEIPT.RECEIPT_ISSUE) AS TRANSACTION,
		CASE
			WHEN JOIN_STOCK.COUNT_VALUE > 0
				THEN JOIN_STOCK.COUNT_VALUE
			ELSE 0
			END AS COUNT_VALUE,
		SUM((
				CASE
					WHEN JOIN_STOCK.COUNT_VALUE > 0
						THEN JOIN_STOCK.COUNT_VALUE
					ELSE 0
					END
				) - TRANSACTION) OVER (
			PARTITION BY NULL ORDER BY ISSUE_RECEIPT.DATE ASC ROWS BETWEEN CURRENT ROW
					AND UNBOUNDED FOLLOWING
			) AS STOCK
	FROM ISSUE_RECEIPT AS ISSUE_RECEIPT
	LEFT JOIN JOIN_STOCK AS JOIN_STOCK ON JOIN_STOCK.DATE = ISSUE_RECEIPT.DATE
	GROUP BY ISSUE_RECEIPT.DATE,
		COUNT_VALUE
	),
SOURCE_DATA
AS (
	SELECT DATE,
		TRANSACTION,
		CASE
			WHEN COUNT_VALUE > 0
				THEN COUNT_VALUE
			ELSE LAG(STOCK, 1, 0) OVER (
					PARTITION BY NULL ORDER BY DATE DESC
					)
			END AS FQC_BACKLOG
	FROM MERGE_DATA
	),
TRANSFORM_DATA
AS (
	SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        DATE,
		TRANSACTION,
		FQC_BACKLOG
	FROM SOURCE_DATA
	),
TYPE_DATA
AS (
	SELECT
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(DATE AS DATE) AS DATE,
		CAST(TRANSACTION AS  NUMBER(38,0)) AS TRANSACTION,
		CAST(FQC_BACKLOG AS  NUMBER(38,0)) AS FQC_BACKLOG
	FROM TRANSFORM_DATA
	)
SELECT *
FROM TYPE_DATA
    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='DISPLAY_LIST_OF_TASKS_LIST_OF_NOTIFICATIONS',
    	transient=false
) }}



with source_data as (
SELECT 
	QMSM.NOTIFICATION_NO AS  NOTIFICATION,
	QMEL.DATE_OF_NOTIFICATION AS DATE_OF_NOTIFICATION,
	QMSM.TASK_CODE AS  TASK_CODE,
	QMEL.MATERIAL_NUMBER AS  MATERIAL,
	QPCT.SHORT_TEXT_FOR_CODE_UP_TO_40_CHARACTERS_IN_LENGTH AS  TASK_CODE_TEXT,
	QMSM.PERSON_RESPONSIBLE_FOR_TASK_PARTNER_NUMBER AS  DESCEMPLOYEERESP_FOR_JOB,
	QMSM.PLANNED_START_DATE AS  PLANNED_START_DATE,
	QMSM.PLANNED_FINISH_DATE AS  PLANNED_FINISH,
	QMSM.DATE_ON_WHICH_THE_TASK_WAS_COMPLETED AS  COMPLETION_DATE,
	QMSM.PERSON_WHO_COMPLETED_THE_TASK AS  COMPLETED_BY,
	TJ02T.INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM AS  TASK_STATUS
FROM {{ ref('SILVER__TMEA_QUALITY__QUALITY_NOTIFICATION_TASKS') }} QMSM
JOIN {{ ref('SILVER__TMEA_QUALITY__QUALITY_NOTIFICATION') }} QMEL ON QMSM.NOTIFICATION_NO = QMEL.NOTIFICATION_NO
LEFT JOIN {{ ref('SILVER__TMEA_QUALITY__CODE_TEXTS') }} QPCT ON QMSM.CODE_GROUP_TASKS = QPCT.CODE_GROUP AND QMSM.TASK_CODE = QPCT.CODE AND QMSM.VERSION_NUMBER = QPCT.VERSION_NUMBER
LEFT JOIN {{ ref('SILVER__TMEA_QUALITY__INDIVIDUAL_OBJECT_STATUS') }} JEST ON QMSM.OBJECT_NUMBER_FOR_STATUS_MANAGEMENT = JEST.OBJECT_NUMBER
LEFT JOIN {{ ref('SILVER__TMEA_QUALITY__SYSTEM_STATUS_TEXTS') }} TJ02T ON JEST.OBJECT_STATUS = TJ02T.SYSTEM_STATUS
WHERE 
JEST.INDICATOR_STATUS_IS_INACTIVE = ' ' 
AND TJ02T.LANGUAGE_KEY = 'E'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
and QMSM.DELETE_DATA_RECORD != 'X'
),

transform_data as (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
    NOTIFICATION,
	DATE_OF_NOTIFICATION,
    TASK_CODE,
    MATERIAL,
    TASK_CODE_TEXT,
    DESCEMPLOYEERESP_FOR_JOB,
    PLANNED_START_DATE,
    PLANNED_FINISH,
    COMPLETION_DATE,
    COMPLETED_BY,
    TASK_STATUS
from source_data
)
select * from transform_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'RTVS_STOCK',
        transient = false
) }}

with source_data as (
    SELECT MARD.PLANT,
        MARC.MRP_CONTROLLER_MATERIALS_PLANNER,
        T024D.CONTROLLER_NAME,
        MARD.STORAGE_LOCATION,
        MARD.MATERIAL_NUMBER as MATERIAL,
        MAKT.MATERIAL_DESCRIPTION,
        MARD.VALUATED_UNRESTRICTED_USE_STOCK AS QTY,
        MBEW.STANDARD_PRICE,
        STANDARD_PRICE * QTY AS EXTENDED_COST
    FROM {{ ref('SILVER__TMEA_QUALITY__STORAGE_LOCATION_DATA_FOR_MATERIAL') }} MARD
        JOIN {{ ref('SILVER__TMEA_QUALITY__PLANT_DATA_FOR_MATERIAL') }} MARC
        ON MARD.MATERIAL_NUMBER = MARC.MATERIAL_NUMBER
        AND MARD.PLANT = MARC.PLANT
        JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }} MAKT
        ON MARC.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
        JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_VALUATION') }} MBEW
        ON MBEW.VALUATION_AREA = MARD.PLANT
        AND MBEW.MATERIAL_NUMBER = MARD.MATERIAL_NUMBER
        JOIN {{ ref('SILVER__TMEA_QUALITY__MRP_CONTROLLERS') }} T024D
        ON T024D.PLANT = MARC.PLANT
        AND T024D.MRP_CONTROLLER = MARC.MRP_CONTROLLER_MATERIALS_PLANNER
    WHERE MARD.VALUATED_UNRESTRICTED_USE_STOCK > '0'
        AND MARD.PLANT = '0010'
        AND MARD.STORAGE_LOCATION =  'RTVS'
        AND MBEW.VALUATION_TYPE = ' '
),

transform_data as (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        PLANT,
        MRP_CONTROLLER_MATERIALS_PLANNER,
        CONTROLLER_NAME,
        STORAGE_LOCATION,
        MATERIAL,
        MATERIAL_DESCRIPTION,
        QTY,
        STANDARD_PRICE,
        EXTENDED_COST
    FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(MRP_CONTROLLER_MATERIALS_PLANNER AS VARCHAR(9)) AS MRP_CONTROLLER_MATERIALS_PLANNER,
        CAST(CONTROLLER_NAME AS VARCHAR(16777216)) AS CONTROLLER_NAME,
        CAST(STORAGE_LOCATION AS VARCHAR(16777216)) AS STORAGE_LOCATION,
        CAST(MATERIAL AS VARCHAR(16777216)) AS MATERIAL,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(120)) AS MATERIAL_DESCRIPTION,
        CAST(QTY AS NUMBER(38,10)) AS QTY,
        CAST(STANDARD_PRICE AS NUMBER(38,10)) AS STANDARD_PRICE,
        CAST(EXTENDED_COST AS NUMBER(38,12)) AS EXTENDED_COST
    FROM transform_data
)

SELECT * from type_data
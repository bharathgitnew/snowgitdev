    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='MATERIAL_GOODS_ISSUE_FOR_MANUFACTURING_ORDER',
    	transient=false
) }}

WITH ref_cte_DOCUMENT_SEGMENT_MATERIAL as (
    select * from {{ ref('SILVER__TMEA_QUALITY__DOCUMENT_SEGMENT_MATERIAL') }}
),

ref_cte_HEADER_MATERIAL_DOCUMENT as (
    select * from {{ ref('SILVER__TMEA_QUALITY__HEADER_MATERIAL_DOCUMENT') }}
),

ref_cte_MATERIAL_DESCRIPTIONS as (
    select * from {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }}
),



source_data as (
SELECT 
MSEG.NUMBER_OF_MATERIAL_DOCUMENT,
MSEG.MATERIAL_NUMBER,
MAKT.MATERIAL_DESCRIPTION,
MSEG.POSTING_DATE_IN_THE_DOCUMENT AS MATERIAL_MOVEMENT_POSTING_DATE,
MSEG.QUANTITY,
MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT
from ref_cte_document_segment_material    MSEG
JOIN ref_cte_MATERIAL_DESCRIPTIONS    MAKT 
    ON MSEG.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
left JOIN ref_cte_header_material_document    MKPF 
    ON MKPF.NUMBER_OF_MATERIAL_DOCUMENT = MSEG.NUMBER_OF_MATERIAL_DOCUMENT 
    AND MKPF.MATERIAL_DOCUMENT_YEAR = MSEG.MATERIAL_DOCUMENT_YEAR
WHERE MOVEMENT_TYPE_INVENTORY_MANAGEMENT = '261'
AND MSEG.PLANT = '0010'
),
transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	NUMBER_OF_MATERIAL_DOCUMENT,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	MATERIAL_MOVEMENT_POSTING_DATE,
	QUANTITY,
	MOVEMENT_TYPE_INVENTORY_MANAGEMENT
from source_data
),

type_data as (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
	CAST(NUMBER_OF_MATERIAL_DOCUMENT as VARCHAR(16777216)) as NUMBER_OF_MATERIAL_DOCUMENT,
	CAST(MATERIAL_NUMBER as VARCHAR(16777216)) as MATERIAL_NUMBER,
	CAST(MATERIAL_DESCRIPTION as VARCHAR(16777216)) as MATERIAL_DESCRIPTION,
	CAST(MATERIAL_MOVEMENT_POSTING_DATE as DATE) as MATERIAL_MOVEMENT_POSTING_DATE,
	CAST(QUANTITY as NUMBER) as QUANTITY,
	CAST(MOVEMENT_TYPE_INVENTORY_MANAGEMENT as VARCHAR(16777216)) as MOVEMENT_TYPE_INVENTORY_MANAGEMENT
from transform_data 
)
select * from type_data
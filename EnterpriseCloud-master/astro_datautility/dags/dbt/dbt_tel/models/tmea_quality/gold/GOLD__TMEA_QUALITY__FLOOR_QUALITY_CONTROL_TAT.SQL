      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='FLOOR_QUALITY_CONTROL_TAT',
      transient=false
) }}

WITH source_data as
(
    SELECT DISTINCT
IN_BOUND.MATERIAL_NUMBER AS MATERIAL,
IN_BOUND.MATERIAL_DESCRIPTION AS MATERIAL_DESCRIPTION,
IN_BOUND.SOURCE_STORAGE_TYPE AS IN_BOUND_SOURCE_STORAGE_TYPE,
IN_BOUND.QUANT AS IN_BOUND_QUANT1,
IN_BOUND.DESTINATION_STORAGE_TYPE AS IN_BOUND_DEST_STORAGE_TYPE,
IN_BOUND.CONFIRMATION_DATE_1 AS IN_BOUND_CONF_DATE,
OUT_BOUND.SOURCE_STORAGE_TYPE AS OUT_BOUND_SOURCE_STORAGE_TYPE,
OUT_BOUND.DESTINATION_STORAGE_TYPE AS OUT_BOUND_DEST_STORAGE_TYPE,
OUT_BOUND.CONFIRMATION_DATE_1 AS OUT_BOUND_CONF_DATE,
DATEDIFF(DAY,IN_BOUND.CONFIRMATION_DATE_1,OUT_BOUND.CONFIRMATION_DATE_1) AS MATERIAL_TAT
FROM {{ ref('SILVER__TMEA_QUALITY__TRANSFER_ORDER_ITEM') }} AS IN_BOUND
JOIN {{ ref('SILVER__TMEA_QUALITY__TRANSFER_ORDER_ITEM') }} AS OUT_BOUND ON IN_BOUND.QUANT_2 = OUT_BOUND.QUANT
WHERE IN_BOUND.WAREHOUSE_NUMBER = '010'
AND IN_BOUND.DESTINATION_STORAGE_TYPE = '935'
ORDER BY IN_BOUND.CONFIRMATION_DATE_1 DESC
)

,transform_data as
(
  SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
    MATERIAL,
    MATERIAL_DESCRIPTION,
    IN_BOUND_SOURCE_STORAGE_TYPE,
    IN_BOUND_QUANT1,
    IN_BOUND_DEST_STORAGE_TYPE,
    IN_BOUND_CONF_DATE,
    OUT_BOUND_SOURCE_STORAGE_TYPE,
    OUT_BOUND_DEST_STORAGE_TYPE,
    OUT_BOUND_CONF_DATE,
    MATERIAL_TAT
  FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		    cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(MATERIAL AS VARCHAR(16777216)) AS MATERIAL,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(IN_BOUND_SOURCE_STORAGE_TYPE AS VARCHAR(16777216)) AS IN_BOUND_SOURCE_STORAGE_TYPE,
        CAST(IN_BOUND_QUANT1 AS VARCHAR(16777216)) AS IN_BOUND_QUANT1,
        CAST(IN_BOUND_DEST_STORAGE_TYPE AS VARCHAR(16777216)) AS IN_BOUND_DEST_STORAGE_TYPE,
        CAST(IN_BOUND_CONF_DATE AS TIMESTAMP_LTZ(9)) AS IN_BOUND_CONF_DATE,
        CAST(OUT_BOUND_SOURCE_STORAGE_TYPE AS VARCHAR(16777216)) AS OUT_BOUND_SOURCE_STORAGE_TYPE,
        CAST(OUT_BOUND_DEST_STORAGE_TYPE AS VARCHAR(16777216)) AS OUT_BOUND_DEST_STORAGE_TYPE,
        CAST(OUT_BOUND_CONF_DATE AS TIMESTAMP_LTZ(9)) AS OUT_BOUND_CONF_DATE,
        CAST(MATERIAL_TAT AS NUMBER(9,0)) AS MATERIAL_TAT
    FROM transform_data
)

SELECT * from type_data
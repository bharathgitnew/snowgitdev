WITH GR AS(
select 
MSEG.VENDOR_ACCOUNT_NUMBER,
LFA1.NAME_1 AS SUPPLIER_NAME,
Month(MSEG.POSTING_DATE_IN_THE_DOCUMENT) AS Month,
year(MSEG.POSTING_DATE_IN_THE_DOCUMENT) as year,
sum(MSEG.GOODS_RECEIPT_QUANTITY_IN_ORDER_UNIT) AS GOODS_RECEIPT_QUANTITY
from {{ ref('SILVER__TMEA_QUALITY__DOCUMENT_SEGMENT_MATERIAL') }}    MSEG
left JOIN {{ ref('SILVER__TMEA_QUALITY__VENDOR_MASTER') }}    LFA1 ON MSEG.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE MSEG.PLANT = '0010'
AND MSEG.STORAGE_LOCATION = '0010'
AND MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT = '101'
AND MSEG.POSTING_DATE_IN_THE_DOCUMENT >= '2021-03-01'
GROUP BY VENDOR_ACCOUNT_NUMBER, SUPPLIER_NAME, MONTH, YEAR
ORDER BY month,year ASC   
), 

DATE_CTE AS (
SELECT 
DISTINCT(YEAR(CALENDAR_DATE)) AS YEAR_ALL,
MONTH(CALENDAR_DATE) AS MONTH_ALL
FROM {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
WHERE YEAR_ALL BETWEEN (SELECT MIN(YEAR) FROM GR) AND (SELECT MAX(YEAR) FROM GR)
ORDER BY 1,2
),

GR_WITH_ZERO AS(
SELECT
VENDOR_ACCOUNT_NUMBER,
SUPPLIER_NAME,
MONTH,
YEAR,
GOODS_RECEIPT_QUANTITY
FROM GR
UNION ALL
SELECT
VENDOR_ACCOUNT_NUMBER,
SUPPLIER_NAME,
MONTH_ALL,
YEAR_ALL,
0 AS GOODS_RECEIPT_QUANTITY
FROM DATE_CTE
LEFT JOIN GR
),

COMPLETE_GR AS(
SELECT 
VENDOR_ACCOUNT_NUMBER,
SUPPLIER_NAME,
YEAR,
MONTH,
SUM(GOODS_RECEIPT_QUANTITY) AS GOODS_RECEIPT_QUANTITY
FROM GR_WITH_ZERO
GROUP BY VENDOR_ACCOUNT_NUMBER, SUPPLIER_NAME, YEAR, MONTH
),

Complaint AS(
SELECT 
QMEL.NOTIFICATION_NO,
QMEL.VENDOR_ACCOUNT_NUMBER,
LFA1.name_1 AS SUPPLIER_NAME,
Month(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Month,
YEAR(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Year,
QMEL.DEFECTIVE_QUANTITY_INTERNAL AS REJECT_QUANTITY
FROM {{ ref('SILVER__TMEA_QUALITY__QUALITY_NOTIFICATION') }}    QMEL
LEFT JOIN {{ ref('SILVER__TMEA_QUALITY__VENDOR_MASTER') }}    LFA1 ON QMEL.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND (QMEL.NOTIFICATION_TYPE = 'Q1' or QMEL.NOTIFICATION_TYPE = 'VF' or QMEL.NOTIFICATION_TYPE = 'F2')
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED >= '2024-04-01'
and CODE_GROUP_CODING = 'SUPPLIER'
union all 
SELECT 
QMEL.NOTIFICATION_NO,
QMEL.VENDOR_ACCOUNT_NUMBER,
LFA1.name_1 AS SUPPLIER_NAME,
Month(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Month,
YEAR(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Year,
QMEL.COMPLAINT_QUANTITY AS REJECT_QUANTITY
FROM {{ ref('SILVER__TMEA_QUALITY__QUALITY_NOTIFICATION') }}    QMEL
LEFT JOIN {{ ref('SILVER__TMEA_QUALITY__VENDOR_MASTER') }}    LFA1 ON QMEL.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND (QMEL.NOTIFICATION_TYPE = 'Q1' or QMEL.NOTIFICATION_TYPE = 'VF' or QMEL.NOTIFICATION_TYPE = 'F2')
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED BETWEEN '2023-04-01'AND '2024-03-31'
and CODE_GROUP_CODING = 'SUPPLIER'
union ALL
SELECT 
QMEL.NOTIFICATION_NO,
QMEL.VENDOR_ACCOUNT_NUMBER,
LFA1.name_1 AS SUPPLIER_NAME,
Month(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Month,
YEAR(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Year,
QMEL.COMPLAINT_QUANTITY as REJECT_QUANTITY 
FROM {{ ref('SILVER__TMEA_QUALITY__QUALITY_NOTIFICATION') }}    QMEL
LEFT JOIN {{ ref('SILVER__TMEA_QUALITY__VENDOR_MASTER') }}    LFA1 ON QMEL.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND QMEL.NOTIFICATION_TYPE = 'Q6'
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED < '2023-04-01'
and CODE_GROUP_CODING = 'SUPPLIER'
),

complaints as ( 
select
VENDOR_ACCOUNT_NUMBER,
SUPPLIER_NAME,
year,
month,
sum(REJECT_QUANTITY) as QTY
from Complaint
group by VENDOR_ACCOUNT_NUMBER,SUPPLIER_NAME,month,year
),

VARIABLES as (
select 
GR.VENDOR_ACCOUNT_NUMBER as VENDOR_ACCOUNT_NUMBER,
GR.SUPPLIER_NAME as SUPPLIER_NAME,
SD.SUPPLIER_GROUP AS SUPPLIER_GROUP_NAME,                       
to_number(GR.year,4,0) as calyear,
GR.month as calmonth,
to_number(Complaints.QTY) as numerator,
to_number(GR.GOODS_RECEIPT_QUANTITY) as denominator
from complete_GR as GR
left join Complaints as Complaints
    on GR.VENDOR_ACCOUNT_NUMBER = Complaints.VENDOR_ACCOUNT_NUMBER
    and GR.Month = Complaints.Month
    and GR.year = Complaints.year
LEFT JOIN {{ ref('SILVER__TMEA_QUALITY__SUPPLIER_DETAILS') }}  AS  SD
    ON SD.SUPPLIER_SAP_ID_NUMBER = GR.VENDOR_ACCOUNT_NUMBER
WHERE SUPPLIER_GROUP_NAME is not null
),

SUPPLIER_GROUP_BY AS (
select 
VENDOR_ACCOUNT_NUMBER,
SUPPLIER_GROUP_NAME,
TRY_TO_DATE(CONCAT(CALYEAR,'-',CALMONTH),'YYYY-MM') AS DATE,
calyear,
calmonth,
SUM(numerator) AS REJECT_QTY,
SUM(denominator) AS GR_QTY
from VARIABLES
GROUP BY VENDOR_ACCOUNT_NUMBER,SUPPLIER_GROUP_NAME, calyear, calmonth
ORDER BY CALYEAR, CALMONTH DESC
),

MONTHLY_ROLLING_AVERAGE AS (
SELECT *,
sum(REJECT_QTY) over (order by SUPPLIER_GROUP_NAME,calyear,calmonth asc rows between 2 preceding and current row) as REJECT_QUANTITY_sum_3,
sum(GR_QTY) over (order by SUPPLIER_GROUP_NAME,calyear,calmonth asc rows between 2 preceding and current row) as GOODS_RECEIPT_QUANTITY_sum_3,
sum(REJECT_QTY) over (order by SUPPLIER_GROUP_NAME,calyear,calmonth asc rows between 5 preceding and current row) as REJECT_QUANTITY_sum_6,
sum(GR_QTY) over (order by SUPPLIER_GROUP_NAME,calyear,calmonth asc rows between 5 preceding and current row) as GOODS_RECEIPT_QUANTITY_sum_6
FROM SUPPLIER_GROUP_BY
),

result as(
select 
VENDOR_ACCOUNT_NUMBER AS SUPPLIER_NUMBER,
SUPPLIER_GROUP_NAME,
calyear,
calmonth as calmonthnum,
SUBSTRING('JAN FEB MAR APR MAY JUN JUL AUG SEP OCT NOV DEC ', (calmonth * 4) - 3, 3) as calmonth,
TRY_TO_DATE(CONCAT(CALYEAR,'-',CALMONTHNUM),'YYYY-MM') AS DATE,
REJECT_QTY,
GR_QTY,
REJECT_QUANTITY_sum_3 AS REJECT_QTY_3mo,
GOODS_RECEIPT_QUANTITY_sum_3 AS GR_QTY_3mo,
REJECT_QUANTITY_sum_6 AS REJECT_QTY_6mo,
GOODS_RECEIPT_QUANTITY_sum_6 AS GR_QTY_6mo,
ROUND(DIV0(REJECT_QTY,GR_QTY)*1000000) as PPM_month,
ROUND(DIV0(REJECT_QUANTITY_sum_3,GOODS_RECEIPT_QUANTITY_sum_3)*1000000) as PPM_3_month,
ROUND(DIV0(REJECT_QUANTITY_sum_6,GOODS_RECEIPT_QUANTITY_sum_6)*1000000) as PPM_6_month
from MONTHLY_ROLLING_AVERAGE
),
SOURCE_DATA as(
 SELECT * from supplier_group_by
),
TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	VENDOR_ACCOUNT_NUMBER,
	SUPPLIER_GROUP_NAME,
	DATE,
	CALYEAR,
	CALMONTH,
	REJECT_QTY,
	GR_QTY

FROM SOURCE_DATA
)

,
TYPE_DATA AS (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	VENDOR_ACCOUNT_NUMBER,
	SUPPLIER_GROUP_NAME,
	CAST(DATE as DATE) as DATE,
	CAST(CALYEAR as NUMBER(38,0)) as CALYEAR,
	CAST(CALMONTH as NUMBER(38,0)) as CALMONTH,
	CAST(REJECT_QTY as NUMBER(38,0)) as REJECT_QTY,
	CAST(GR_QTY as NUMBER(38,0)) as GR_QTY
from transform_data
)
SELECT * FROM TYPE_DATA
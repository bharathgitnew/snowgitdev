WITH MOVE
AS (
	SELECT MKPF.POSTING_DATE_IN_THE_DOCUMENT AS POSTING_DATE,
		MSEG.MATERIAL_NUMBER,
		MSEG.PLANT,
		MSEG.STORAGE_LOCATION,
		SUM(IFF(MSEG.DEBIT_CREDIT_INDICATOR = 'S', MSEG.QUANTITY, MSEG.QUANTITY * - 1)) AS VALUATED_UNRESTRICTED_USE_STOCK
	FROM {{ ref('SILVER__TMEA_QUALITY__DOCUMENT_SEGMENT_MATERIAL') }} AS MSEG
	JOIN {{ ref('SILVER__TMEA_QUALITY__HEADER_MATERIAL_DOCUMENT') }} AS MKPF ON MSEG.NUMBER_OF_MATERIAL_DOCUMENT = MKPF.NUMBER_OF_MATERIAL_DOCUMENT
		AND MKPF.MATERIAL_DOCUMENT_YEAR = MSEG.MATERIAL_DOCUMENT_YEAR
		AND MKPF.POSTING_DATE_IN_THE_DOCUMENT > '2022-07-05'
		AND MSEG.PLANT = '0010'
		AND MSEG.STORAGE_LOCATION =  'RTVS'
	GROUP BY MKPF.POSTING_DATE_IN_THE_DOCUMENT,
		MSEG.MATERIAL_NUMBER,
		PLANT,
		STORAGE_LOCATION
	),
FINAL_MOVE
AS (
	SELECT PLANT,
		STORAGE_LOCATION,
		MATERIAL_NUMBER,
		POSTING_DATE,
		SUM(VALUATED_UNRESTRICTED_USE_STOCK) AS VALUATED_UNRESTRICTED_USE_STOCK
	FROM MOVE
	WHERE VALUATED_UNRESTRICTED_USE_STOCK != 0
	GROUP BY PLANT,
		STORAGE_LOCATION,
		MATERIAL_NUMBER,
		POSTING_DATE
	),
ISSUE_RECEIPT
AS (
	SELECT PLANT,
		POSTING_DATE,
		CASE
			WHEN VALUATED_UNRESTRICTED_USE_STOCK - LEAD(VALUATED_UNRESTRICTED_USE_STOCK, 1, 0) OVER (
					PARTITION BY MATERIAL_NUMBER ORDER BY POSTING_DATE DESC
					) < 0
				THEN - 1
			WHEN VALUATED_UNRESTRICTED_USE_STOCK - LEAD(VALUATED_UNRESTRICTED_USE_STOCK, 1, 0) OVER (
					PARTITION BY MATERIAL_NUMBER ORDER BY POSTING_DATE DESC
					) = 0
				THEN 0
			ELSE 1
			END AS RECEIPT_ISSUE
	FROM FINAL_MOVE
	),
CURRENT_STOCK_COUNT
AS (
	SELECT 1 AS RANK,
		COUNT(*) AS COUNT_VALUE
	FROM {{ ref('SILVER__TMEA_QUALITY__STORAGE_LOCATION_DATA_FOR_MATERIAL') }}
	WHERE PLANT = '0010'
		AND VALUATED_UNRESTRICTED_USE_STOCK > 0
		AND STORAGE_LOCATION = 'RTVS'
	),
MAX_DATE
AS (
	SELECT 1 AS RANK,
		MAX(POSTING_DATE) AS DATE
	FROM ISSUE_RECEIPT
	),
JOIN_STOCK
AS (
	SELECT CURRENT_STOCK_COUNT.COUNT_VALUE AS COUNT_VALUE,
		MAX_DATE.DATE
	FROM CURRENT_STOCK_COUNT AS CURRENT_STOCK_COUNT
	JOIN MAX_DATE AS MAX_DATE ON CURRENT_STOCK_COUNT.RANK = MAX_DATE.RANK
	),
MERGE_DATA
AS (
	SELECT ISSUE_RECEIPT.POSTING_DATE,
		SUM(ISSUE_RECEIPT.RECEIPT_ISSUE) AS RTVS_TRANSACTIONS,
		CASE
			WHEN JOIN_STOCK.COUNT_VALUE > 0
				THEN JOIN_STOCK.COUNT_VALUE
			ELSE 0
			END AS COUNT_VALUE,
		SUM((
				CASE
					WHEN JOIN_STOCK.COUNT_VALUE > 0
						THEN JOIN_STOCK.COUNT_VALUE
					ELSE 0
					END
				) - RTVS_TRANSACTIONS) OVER (
			PARTITION BY NULL ORDER BY POSTING_DATE ASC ROWS BETWEEN CURRENT ROW
					AND UNBOUNDED FOLLOWING
			) AS STOCK
	FROM ISSUE_RECEIPT AS ISSUE_RECEIPT
	LEFT JOIN JOIN_STOCK AS JOIN_STOCK ON JOIN_STOCK.DATE = ISSUE_RECEIPT.POSTING_DATE
	GROUP BY ISSUE_RECEIPT.POSTING_DATE,
		COUNT_VALUE
	),
SOURCE_DATA
AS (
	SELECT POSTING_DATE ,
		RTVS_TRANSACTIONS,
		CASE
			WHEN COUNT_VALUE > 0
				THEN COUNT_VALUE
			ELSE LAG(STOCK, 1, 0) OVER (
					PARTITION BY NULL ORDER BY POSTING_DATE DESC
					)
			END AS RTVS_BACKLOG
	FROM MERGE_DATA
	),
TRANSFORM_DATA
AS (
	SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        POSTING_DATE,
		RTVS_TRANSACTIONS,
		RTVS_BACKLOG
	FROM SOURCE_DATA
	),
TYPE_DATA
AS (
	SELECT
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(POSTING_DATE AS TIMESTAMP_LTZ(9)) AS POSTING_DATE,
		CAST(RTVS_TRANSACTIONS AS FLOAT) AS RTVS_TRANSACTIONS,
		CAST(RTVS_BACKLOG AS FLOAT) AS RTVS_BACKLOG
	FROM TRANSFORM_DATA
	)
SELECT *
FROM TYPE_DATA
WITH MOVE
AS (
	SELECT QAVE.DATE_OF_CODE_USED_FOR_USAGE_DECISION AS DATE,
		COUNT(LQUA.QUANT) * - 1 AS STOCK
	FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }} LQUA
	FULL OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__ASSIGNMENT_TASK_LISTS_MATERIALS') }} MAPL ON MAPL.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
		AND MAPL.PLANT = LQUA.PLANT
	LEFT OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__INSPECTION_PROCESSING_USAGE_DECISION') }} QAVE ON QAVE.INSPECTION_LOT_NUMBER = LQUA.INSPECTION_LOT_NUMBER
	WHERE LQUA.STORAGE_TYPE = '903'
		AND LQUA.PLANT = '0010'
		AND (
			MAPL.KEY_FOR_TASK_LIST_GROUP IS NULL
			OR MAPL.KEY_FOR_TASK_LIST_GROUP <> '00000615'
			)
		AND QAVE.DATE_OF_CODE_USED_FOR_USAGE_DECISION IS NOT NULL
	GROUP BY QAVE.DATE_OF_CODE_USED_FOR_USAGE_DECISION

	UNION

	SELECT LQUA.DATE_OF_LAST_PLACEMENT_INTO_STOCK AS DATE,
		COUNT(LQUA.QUANT) AS STOCK
	FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }} LQUA
	FULL OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__ASSIGNMENT_TASK_LISTS_MATERIALS') }} MAPL ON MAPL.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
		AND MAPL.PLANT = LQUA.PLANT
	LEFT OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__INSPECTION_PROCESSING_USAGE_DECISION') }} QAVE ON QAVE.INSPECTION_LOT_NUMBER = LQUA.INSPECTION_LOT_NUMBER
	WHERE LQUA.STORAGE_TYPE = '903'
		AND LQUA.PLANT = '0010'
		AND (
			MAPL.KEY_FOR_TASK_LIST_GROUP IS NULL
			OR MAPL.KEY_FOR_TASK_LIST_GROUP <> '00000615'
			)
	GROUP BY LQUA.DATE_OF_LAST_PLACEMENT_INTO_STOCK
	),
FINAL_MOVE
AS (
	SELECT DATE,
		SUM(STOCK) AS STOCK
	FROM MOVE
	GROUP BY DATE
	),
ISSUE_RECEIPT
AS (
	SELECT DATE,
		SUM(STOCK) AS RECEIPT_ISSUE
	FROM FINAL_MOVE
	GROUP BY DATE
	),
STOCK
AS (
	SELECT LQUA.MATERIAL_NUMBER,
		 LQUA.PLANT,
		 LQUA.INSPECTION_LOT_NUMBER,
		 LQUA.QUANT
	FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }} LQUA
	FULL OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__ASSIGNMENT_TASK_LISTS_MATERIALS') }} MAPL ON MAPL.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
		AND MAPL.PLANT = LQUA.PLANT
	LEFT OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__INSPECTION_PROCESSING_USAGE_DECISION') }} QAVE ON QAVE.INSPECTION_LOT_NUMBER = LQUA.INSPECTION_LOT_NUMBER
	WHERE LQUA.STORAGE_TYPE = '903'
		AND LQUA.PLANT = '0010'
		AND LQUA.IS_DELETED = 'No'
		AND LQUA.CLIENT = '300'
		AND (
			MAPL.KEY_FOR_TASK_LIST_GROUP IS NULL
			OR MAPL.KEY_FOR_TASK_LIST_GROUP <> '00000615'
			)
	),
CURRENT_STOCK_COUNT
AS (
	SELECT 1 AS RANK,
		COUNT(QUANT) AS COUNT_VALUE
	FROM STOCK
	),
MAX_DATE
AS (
	SELECT 1 AS RANK,
		MAX(DATE) AS DATE
	FROM ISSUE_RECEIPT
	),
JOIN_STOCK
AS (
	SELECT CURRENT_STOCK_COUNT.COUNT_VALUE AS COUNT_VALUE,
		MAX_DATE.DATE
	FROM CURRENT_STOCK_COUNT AS CURRENT_STOCK_COUNT
	JOIN MAX_DATE AS MAX_DATE ON CURRENT_STOCK_COUNT.RANK = MAX_DATE.RANK
	),
MERGE_DATA
AS (
	SELECT ISSUE_RECEIPT.DATE,
		SUM(ISSUE_RECEIPT.RECEIPT_ISSUE) AS TRANSACTION,
		CASE
			WHEN JOIN_STOCK.COUNT_VALUE > 0
				THEN JOIN_STOCK.COUNT_VALUE
			ELSE 0
			END AS COUNT_VALUE,
		SUM((
				CASE
					WHEN JOIN_STOCK.COUNT_VALUE > 0
						THEN JOIN_STOCK.COUNT_VALUE
					ELSE 0
					END
				) - TRANSACTION) OVER (
			PARTITION BY NULL ORDER BY ISSUE_RECEIPT.DATE ASC ROWS BETWEEN CURRENT ROW
					AND UNBOUNDED FOLLOWING
			) AS STOCK
	FROM ISSUE_RECEIPT AS ISSUE_RECEIPT
	LEFT JOIN JOIN_STOCK AS JOIN_STOCK ON JOIN_STOCK.DATE = ISSUE_RECEIPT.DATE
	GROUP BY ISSUE_RECEIPT.DATE,
		COUNT_VALUE
	),
SOURCE_DATA
AS (
	SELECT DATE,
		TRANSACTION,
		CASE
			WHEN COUNT_VALUE > 0
				THEN COUNT_VALUE
			ELSE LAG(STOCK, 1, 0) OVER (
					PARTITION BY NULL ORDER BY DATE DESC
					)
			END AS IQC_BACKLOG
	FROM MERGE_DATA
	),
TRANSFORM_DATA
AS (
	SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        DATE,
		TRANSACTION,
		IQC_BACKLOG
	FROM SOURCE_DATA
	),
TYPE_DATA
AS (
	SELECT
	cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(DATE AS DATE) AS DATE,
		CAST(TRANSACTION AS  NUMBER(38,0)) AS TRANSACTION,
		CAST(IQC_BACKLOG AS  NUMBER(38,0)) AS IQC_BACKLOG
	FROM TRANSFORM_DATA
	)
SELECT *
FROM TYPE_DATA
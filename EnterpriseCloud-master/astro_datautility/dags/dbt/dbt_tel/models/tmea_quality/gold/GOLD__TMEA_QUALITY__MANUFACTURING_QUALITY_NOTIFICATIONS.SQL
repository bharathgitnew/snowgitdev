{{ config(
    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='MANUFACTURING_QUALITY_NOTIFICATIONS',
    	transient=false
) }}

WITH ref_cte_MATERIAL_DESCRIPTIONS as (
    select * from {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }}
),

ref_cte_QUALITY_NOTIFICATION as (
    select * from {{ ref('SILVER__TMEA_QUALITY__QUALITY_NOTIFICATION') }}
),



source_data as (
SELECT 
notification_no,
QMEL.MATERIAL_NUMBER,
MAKT.MATERIAL_DESCRIPTION,
QMEL.NOTIFICATION_TYPE,
QMEL.COMPLAINT_QUANTITY,
CODE_GROUP_CODING,
QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
LEFT JOIN ref_cte_MATERIAL_DESCRIPTIONS    MAKT 
    ON QMEL.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND QMEL.NOTIFICATION_TYPE = 'VF' 
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED >= '2023-04-01'
and CODE_GROUP_CODING = 'TMEA'
UNION ALL 
SELECT 
notification_no,
QMEL.MATERIAL_NUMBER,
MAKT.MATERIAL_DESCRIPTION,
QMEL.NOTIFICATION_TYPE,
QMEL.COMPLAINT_QUANTITY as COMPLAINT_QUANTITY,
CODE_GROUP_CODING,
QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
LEFT JOIN ref_cte_MATERIAL_DESCRIPTIONS    MAKT 
    ON QMEL.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND QMEL.NOTIFICATION_TYPE = 'Q6'
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED < '2023-04-01'
and CODE_GROUP_CODING = 'TMEA'),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	NOTIFICATION_NO,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	NOTIFICATION_TYPE,
	COMPLAINT_QUANTITY,
	CODE_GROUP_CODING,
	DATE_ON_WHICH_RECORD_WAS_CREATED
from source_data
),

type_data as (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
	CAST(NOTIFICATION_NO as VARCHAR(16777216)) as NOTIFICATION_NO,
	CAST(MATERIAL_NUMBER as VARCHAR(16777216)) as MATERIAL_NUMBER,
	CAST(MATERIAL_DESCRIPTION as VARCHAR(16777216)) as MATERIAL_DESCRIPTION,
	CAST(NOTIFICATION_TYPE as VARCHAR(16777216)) as NOTIFICATION_TYPE,
	CAST(COMPLAINT_QUANTITY as NUMBER) as COMPLAINT_QUANTITY,
	CAST(CODE_GROUP_CODING as VARCHAR(16777216)) as CODE_GROUP_CODING,
	CAST(DATE_ON_WHICH_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_RECORD_WAS_CREATED
from transform_data 
)
select * from type_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'RTVS_ITEMIZED_BACKLOG',
        transient = false
) }}

with source_data as (
    SELECT DISTINCT
        MSEG.PLANT,
        MSEG.MATERIAL_NUMBER,
        MAKT.MATERIAL_DESCRIPTION,
        MSEG.STORAGE_LOCATION,
        MSEG.DEBIT_CREDIT_INDICATOR,
        IFF (MSEG.DEBIT_CREDIT_INDICATOR = 'S','RECIEVE','RELEASE') AS RECIEVE_RELEASE_IND,
        IFF (MSEG.DEBIT_CREDIT_INDICATOR = 'S', '1', '-1') AS RECIEVE_RELEASE_COUNT,
        IFF (MSEG.DEBIT_CREDIT_INDICATOR = 'S', '1', '') AS RECIEVE_COUNT,
        IFF (MSEG.DEBIT_CREDIT_INDICATOR = 'H', '1', '') AS RELEASE_COUNT,
        MKPF.POSTING_DATE_IN_THE_DOCUMENT AS POSTING_DATE
    FROM {{ ref('SILVER__TMEA_QUALITY__DOCUMENT_SEGMENT_MATERIAL') }} MSEG
        JOIN {{ ref('SILVER__TMEA_QUALITY__HEADER_MATERIAL_DOCUMENT') }} MKPF
        ON MSEG.NUMBER_OF_MATERIAL_DOCUMENT = MKPF.NUMBER_OF_MATERIAL_DOCUMENT
        AND MKPF.MATERIAL_DOCUMENT_YEAR = MSEG.MATERIAL_DOCUMENT_YEAR
        JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }} MAKT
        ON MSEG.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
    WHERE MSEG.PLANT = '0010'
        AND MSEG.STORAGE_LOCATION =  'RTVS'
        AND MKPF.POSTING_DATE_IN_THE_DOCUMENT > '2022-07-05'
),

transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        PLANT,
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        STORAGE_LOCATION,
        DEBIT_CREDIT_INDICATOR,
        RECIEVE_RELEASE_IND,
        RECIEVE_RELEASE_COUNT,
        RECIEVE_COUNT,
        RELEASE_COUNT,
        POSTING_DATE
    FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(STORAGE_LOCATION AS VARCHAR(16777216)) AS STORAGE_LOCATION,
        CAST(DEBIT_CREDIT_INDICATOR AS VARCHAR(16777216)) AS DEBIT_CREDIT_INDICATOR,
        CAST(RECIEVE_RELEASE_IND AS VARCHAR(16777216)) AS RECIEVE_RELEASE_IND,
        CAST(RECIEVE_RELEASE_COUNT AS VARCHAR(16777216)) AS RECIEVE_RELEASE_COUNT,
        CAST(RECIEVE_COUNT AS VARCHAR(16777216)) AS RECIEVE_COUNT,
        CAST(RELEASE_COUNT AS VARCHAR(16777216)) AS RELEASE_COUNT,
        CAST(POSTING_DATE AS TIMESTAMP_LTZ(9)) AS POSTING_DATE
    FROM transform_data
)

SELECT * from type_data
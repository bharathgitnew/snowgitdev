WITH ref_cte_DOCUMENT_SEGMENT_MATERIAL
AS (
	SELECT *
	FROM {{ ref('SILVER__TMEA_QUALITY__DOCUMENT_SEGMENT_MATERIAL') }}
	),
ref_cte_MATERIAL_DESCRIPTIONS
AS (
	SELECT *
	FROM {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }}
	),
ref_cte_QUALITY_NOTIFICATION
AS (
	SELECT *
	FROM {{ ref('SILVER__TMEA_QUALITY__QUALITY_NOTIFICATION') }}
	),
GR 
AS (
SELECT MSEG.MATERIAL_NUMBER,
	Month(MSEG.POSTING_DATE_IN_THE_DOCUMENT) AS Month,
	year(MSEG.POSTING_DATE_IN_THE_DOCUMENT) as year,
	sum(MSEG.GOODS_RECEIPT_QUANTITY_IN_ORDER_UNIT) AS GOODS_RECEIPT_QUANTITY
from ref_cte_document_segment_material    MSEG
WHERE MSEG.PLANT = '0010'
	AND MSEG.STORAGE_LOCATION = '0010'
	AND MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT = '101'
	AND MSEG.POSTING_DATE_IN_THE_DOCUMENT >= '2021-03-01'
GROUP BY MATERIAL_NUMBER, MONTH, YEAR
ORDER BY month,year ASC  
), 

DATE_CTE AS (
SELECT 
DISTINCT(YEAR(CALENDAR_DATE)) AS YEAR_ALL,
MONTH(CALENDAR_DATE) AS MONTH_ALL
FROM {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}
WHERE YEAR_ALL BETWEEN (
	SELECT MIN(YEAR) FROM GR) AND (SELECT MAX(YEAR) FROM GR)
ORDER BY 1,2
),

GR_WITH_ZERO AS(
SELECT
MATERIAL_NUMBER,
MONTH,
YEAR,
GOODS_RECEIPT_QUANTITY
FROM GR

UNION ALL

SELECT
MATERIAL_NUMBER,
MONTH_ALL,
YEAR_ALL,
0 AS GOODS_RECEIPT_QUANTITY
FROM DATE_CTE
LEFT JOIN GR
),

COMPLETE_GR AS(
SELECT 
MATERIAL_NUMBER,
YEAR,
MONTH,
SUM(GOODS_RECEIPT_QUANTITY) AS GOODS_RECEIPT_QUANTITY
FROM GR_WITH_ZERO
GROUP BY MATERIAL_NUMBER, YEAR, MONTH
),

Complaint AS(
SELECT 
QMEL.NOTIFICATION_NO,
QMEL.MATERIAL_NUMBER,
QMEL.NOTIFICATION_TYPE,
Month(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Month,
YEAR(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Year,
QMEL.DEFECTIVE_QUANTITY_INTERNAL AS REJECT_QUANTITY
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND (QMEL.NOTIFICATION_TYPE = 'Q1' or QMEL.NOTIFICATION_TYPE = 'VF' or QMEL.NOTIFICATION_TYPE = 'F2')
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED >= '2024-04-01'
and CODE_GROUP_CODING = 'SUPPLIER'
union ALL
SELECT 
QMEL.NOTIFICATION_NO,
QMEL.MATERIAL_NUMBER,
QMEL.NOTIFICATION_TYPE,
Month(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Month,
YEAR(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Year,
QMEL.COMPLAINT_QUANTITY AS REJECT_QUANTITY
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND (QMEL.NOTIFICATION_TYPE = 'Q1' or QMEL.NOTIFICATION_TYPE = 'VF' or QMEL.NOTIFICATION_TYPE = 'F2')
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED BETWEEN '2023-04-01' AND '2024-03-31'
and CODE_GROUP_CODING = 'SUPPLIER'
union ALL
SELECT 
	QMEL.NOTIFICATION_NO,
	QMEL.MATERIAL_NUMBER,
	QMEL.NOTIFICATION_TYPE,
	Month(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Month,
	YEAR(QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED) AS Year,
	QMEL.COMPLAINT_QUANTITY AS REJECT_QUANTITY 
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
AND QMEL.NOTIFICATION_TYPE = 'Q6'
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED < '2023-04-01'
and CODE_GROUP_CODING = 'SUPPLIER'
),

complaints as ( 
select
	MATERIAL_NUMBER,
	NOTIFICATION_TYPE,
	year,
	month,
	sum(REJECT_QUANTITY) as QTY
from Complaint
group by MATERIAL_NUMBER,NOTIFICATION_TYPE,month,year
),

Final as (
select 
	GR.MATERIAL_NUMBER,
	MAKT.MATERIAL_DESCRIPTION,
	COMPLAINTS.NOTIFICATION_TYPE,
	to_number(GR.year,4,0) as calyear,
	GR.month as calmonthnum,
	SUBSTRING('JAN FEB MAR APR MAY JUN JUL AUG SEP OCT NOV DEC ', (calmonthnum * 4) - 3, 3) as calmonth,
	TRY_TO_DATE(CONCAT(CALYEAR,'-',CALMONTHNUM),'YYYY-MM') AS DATE,
	to_number(Complaints.QTY) as REJECT_QUANTITY,
	to_number(GR.GOODS_RECEIPT_QUANTITY) as GR_QTY,
	sum(REJECT_QUANTITY)  over (order by GR.MATERIAL_NUMBER,calyear,calmonthnum asc rows between 2 preceding and current row) as REJECT_QUANTITY_SUM_3,
	sum(GR_QTY) over (order by GR.MATERIAL_NUMBER,calyear,calmonthnum asc rows between 2 preceding and current row) as GR_QTY_sum_3,
	ROUND(DIV0(REJECT_QUANTITY,GR_QTY)*1000000) as PPM_month,
	ROUND(DIV0(REJECT_QUANTITY,GR_QTY_sum_3)*1000000) as PPM_3_month
from complete_GR as GR
left join Complaints as Complaints
    on GR.MATERIAL_NUMBER = Complaints.MATERIAL_NUMBER
    and GR.Month = Complaints.Month
    and GR.year = Complaints.year
LEFT JOIN ref_cte_MATERIAL_DESCRIPTIONS    MAKT
    ON MAKT.MATERIAL_NUMBER = GR.MATERIAL_NUMBER
),
source_data as(
SELECT
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	NOTIFICATION_TYPE,
	CALYEAR,
	CALMONTHNUM,
	CALMONTH,
	DATE,
	REJECT_QUANTITY,
	GR_QTY,
	REJECT_QUANTITY_SUM_3,
	GR_QTY_SUM_3,
	PPM_MONTH,
	PPM_3_MONTH
FROM FINAL ORDER BY CALYEAR,CALMONTHNUM ASC
),
transform_data as (
SELECT 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	NOTIFICATION_TYPE,
	CALYEAR,
	CALMONTHNUM,
	CALMONTH,
	DATE,
	REJECT_QUANTITY,
	GR_QTY,
	REJECT_QUANTITY_SUM_3,
	GR_QTY_SUM_3,
	PPM_MONTH,
	PPM_3_MONTH
FROM FINAL
),
type_data as (
SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH ,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	NOTIFICATION_TYPE,
	CALYEAR,
	CALMONTHNUM,
	CALMONTH,
	DATE,
	REJECT_QUANTITY,
	GR_QTY,
	REJECT_QUANTITY_SUM_3,
	GR_QTY_SUM_3,
	PPM_MONTH,
	PPM_3_MONTH
FROM transform_data
)
SELECT * FROM type_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'IQC_ITEMIZED_BACKLOG',
        transient = false
) }}

WITH IQC_RECEIVE AS(
    SELECT
    LQUA.MATERIAL_NUMBER,
    MAKT.MATERIAL_DESCRIPTION,
    LQUA.STORAGE_TYPE,
    LQUA.DATE_OF_LAST_PLACEMENT_INTO_STOCK AS DATE,
    IFF(1=1,'RECEIVE',NULL) AS TRANSACTION
    FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }}   LQUA
    full OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__ASSIGNMENT_TASK_LISTS_MATERIALS') }}  MAPL ON MAPL.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER AND MAPL.PLANT = LQUA.PLANT
    JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }}  MAKT ON MAKT.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
    WHERE LQUA.STORAGE_TYPE = '903'
    AND LQUA.PLANT = '0010'
     AND LQUA.IS_DELETED = 'No'
    AND LQUA.CLIENT = '300'
    AND (MAPL.KEY_FOR_TASK_LIST_GROUP is null OR MAPL.KEY_FOR_TASK_LIST_GROUP <> '00000615') 
    ),
    
IQC_RELEASE AS (
    SELECT
    LQUA.MATERIAL_NUMBER,
    MAKT.MATERIAL_DESCRIPTION,
    LQUA.STORAGE_TYPE,
    QAVE.DATE_OF_CODE_USED_FOR_USAGE_DECISION AS DATE,
    IFF(1=1,'RELEASE',NULL) AS TRANSACTION
    FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }}  LQUA
    full OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__ASSIGNMENT_TASK_LISTS_MATERIALS') }} MAPL ON MAPL.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER AND MAPL.PLANT = LQUA.PLANT
    left outer JOIN {{ ref('SILVER__TMEA_QUALITY__INSPECTION_PROCESSING_USAGE_DECISION') }} QAVE ON QAVE.INSPECTION_LOT_NUMBER = LQUA.INSPECTION_LOT_NUMBER 
    JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }} MAKT ON MAKT.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
    WHERE LQUA.STORAGE_TYPE = '903'
    AND LQUA.PLANT = '0010'
        AND LQUA.IS_DELETED = 'No'
    AND LQUA.CLIENT = '300'
    AND (MAPL.KEY_FOR_TASK_LIST_GROUP is null OR MAPL.KEY_FOR_TASK_LIST_GROUP <> '00000615') 
    AND DATE IS NOT NULL
    ),
    
source_data AS (
SELECT  MATERIAL_NUMBER,
	    MATERIAL_DESCRIPTION,
	    STORAGE_TYPE,
	    DATE,
	    TRANSACTION 
    FROM IQC_RECEIVE 
UNION ALL 
SELECT  MATERIAL_NUMBER,
	    MATERIAL_DESCRIPTION,
	    STORAGE_TYPE,
	    DATE,
	    TRANSACTION 
    FROM IQC_RELEASE
),

transform_data as (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        MATERIAL_NUMBER,
	    MATERIAL_DESCRIPTION,
	    STORAGE_TYPE,
	    DATE,
	    TRANSACTION
    FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
	    CAST(MATERIAL_DESCRIPTION AS  VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
	    CAST(STORAGE_TYPE AS VARCHAR(16777216)) AS STORAGE_TYPE,
	    CAST(DATE AS  DATE) AS DATE,
	    CAST(TRANSACTION AS VARCHAR(16777216)) AS TRANSACTION
    FROM transform_data
)

SELECT * from type_data
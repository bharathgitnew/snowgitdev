{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'IQC_STOCK',
        transient = false
) }}

with source_data as (
    SELECT LQUA.MATERIAL_NUMBER,
        MAKT.MATERIAL_DESCRIPTION_MATCHCODES,
        LQUA.PLANT,
        LQUA.INSPECTION_LOT_NUMBER,
        QAVE.DATE_OF_CODE_USED_FOR_USAGE_DECISION AS UD_DATE,
        LQUA.STORAGE_TYPE,
        LQUA.STORAGE_BIN,
        CALCULATION_NEXT_REQUIRMENT_DATE.DELIVERY_ORDER_FINISH_DATE AS NEXT_REQUIRMENT_DATE,
        LQUA.DATE_OF_LAST_PLACEMENT_INTO_STOCK AS DATE_OF_LAST_PLACEMENT_INTO_STOCK,
        QAVE.DATE_OF_CODE_USED_FOR_USAGE_DECISION - LQUA.DATE_OF_LAST_PLACEMENT_INTO_STOCK AS IQC_TAT,
        TRY_TO_TIME(LQUA.TIME_OF_LAST_PLACEMENT_INTO_STOCK) AS TIME_OF_LAST_PLACEMENT_INTO_STOCK,
        LQUA.TOTAL_QUANTITY,
        LQUA.BASE_UNIT_OF_MEASURE,
        MARC.PURCHASING_GROUP,
        T024.DESCRIPTION_OF_PURCHASING_GROUP,
        LQUA.WEIGHT_OF_MATERIAL,
        LQUA.WEIGHT_UNIT,
        MARA.MATERIAL_GROUP,
        T023T.MATERIAL_GROUP_DESCRIPTION AS MATL_GRP_DESC,
        MBEW.PRICE_UNIT,
        MBEW.STANDARD_PRICE,
        MARC.PLANNED_DELIVERY_TIME_IN_DAYS,
        MARC.GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS,
        MARC.MRP_CONTROLLER_MATERIALS_PLANNER,
        T024D.CONTROLLER_NAME,
        MAPL.KEY_FOR_TASK_LIST_GROUP as KEY_TASK_LIST_GROUP,
        LQUA.QUANT
    FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }} LQUA
        JOIN {{ ref('SILVER__TMEA_QUALITY__CALCULATION_NEXT_REQUIRMENT_DATE') }} AS CALCULATION_NEXT_REQUIRMENT_DATE 
        ON CALCULATION_NEXT_REQUIRMENT_DATE.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
        AND CALCULATION_NEXT_REQUIRMENT_DATE.PLANT = LQUA.PLANT
        JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }} MAKT 
        ON MAKT.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
        JOIN {{ ref('SILVER__TMEA_QUALITY__PLANT_DATA_FOR_MATERIAL') }} MARC 
        ON MARC.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER 
        AND MARC.PLANT = LQUA.PLANT
        JOIN {{ ref('SILVER__TMEA_QUALITY__GENERAL_MATERIAL_DATA') }} MARA 
        ON MARA.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
        JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_GROUP_DESCRIPTIONS') }} T023T 
        ON T023T.MATERIAL_GROUP = MARA.MATERIAL_GROUP
        JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_VALUATION') }} MBEW 
        ON MBEW.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER 
        AND MBEW.VALUATION_AREA = LQUA.PLANT
        JOIN {{ ref('SILVER__TMEA_QUALITY__PURCHASING_GROUPS') }} T024 
        ON T024.PURCHASING_GROUP = MARC.PURCHASING_GROUP
        AND T024.CLIENT = LQUA.CLIENT
        JOIN {{ ref('SILVER__TMEA_QUALITY__MRP_CONTROLLERS') }} T024D 
        ON T024D.PLANT = LQUA.PLANT 
        AND T024D.MRP_CONTROLLER = MARC.MRP_CONTROLLER_MATERIALS_PLANNER
        AND T024D.CLIENT = LQUA.CLIENT
        FULL OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__ASSIGNMENT_TASK_LISTS_MATERIALS') }} MAPL 
        ON MAPL.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER 
        AND MAPL.PLANT = LQUA.PLANT
        LEFT OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__INSPECTION_PROCESSING_USAGE_DECISION') }} QAVE 
        ON QAVE.INSPECTION_LOT_NUMBER = LQUA.INSPECTION_LOT_NUMBER 
    WHERE LQUA.STORAGE_TYPE = '903'
        AND LQUA.PLANT = '0010'
        AND LQUA.IS_DELETED = 'No'
        AND LQUA.CLIENT = '300'
        AND (MAPL.KEY_FOR_TASK_LIST_GROUP is null OR MAPL.KEY_FOR_TASK_LIST_GROUP <> '00000615')
),

transform_data as (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION_MATCHCODES,
        PLANT,
        INSPECTION_LOT_NUMBER,
        UD_DATE,
        STORAGE_TYPE,
        STORAGE_BIN,
        NEXT_REQUIRMENT_DATE,
        DATE_OF_LAST_PLACEMENT_INTO_STOCK,
        IQC_TAT,
        TIME_OF_LAST_PLACEMENT_INTO_STOCK,
        TOTAL_QUANTITY,
        BASE_UNIT_OF_MEASURE,
        PURCHASING_GROUP,
        DESCRIPTION_OF_PURCHASING_GROUP,
        WEIGHT_OF_MATERIAL,
        WEIGHT_UNIT,
        MATERIAL_GROUP,
        MATL_GRP_DESC,
        PRICE_UNIT,
        STANDARD_PRICE,
        PLANNED_DELIVERY_TIME_IN_DAYS,
        GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS,
        MRP_CONTROLLER_MATERIALS_PLANNER,
        CONTROLLER_NAME,
        KEY_TASK_LIST_GROUP,
        QUANT
    FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_DESCRIPTION_MATCHCODES AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION_MATCHCODES,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(INSPECTION_LOT_NUMBER AS VARCHAR(16777216)) AS INSPECTION_LOT_NUMBER,
        CAST(UD_DATE AS TIMESTAMP_LTZ(9)) AS UD_DATE,
        CAST(STORAGE_TYPE AS VARCHAR(16777216)) AS STORAGE_TYPE,
        CAST(STORAGE_BIN AS VARCHAR(16777216)) AS STORAGE_BIN,
        CAST(NEXT_REQUIRMENT_DATE AS TIMESTAMP_LTZ(9)) AS NEXT_REQUIRMENT_DATE,
        CAST(DATE_OF_LAST_PLACEMENT_INTO_STOCK AS TIMESTAMP_LTZ(9)) AS DATE_OF_LAST_PLACEMENT_INTO_STOCK,
        CAST(IQC_TAT AS NUMBER(9,0)) AS IQC_TAT,
        CAST(TIME_OF_LAST_PLACEMENT_INTO_STOCK AS TIME(9)) AS TIME_OF_LAST_PLACEMENT_INTO_STOCK,
        CAST(TOTAL_QUANTITY AS NUMBER(38,10)) AS TOTAL_QUANTITY,
        CAST(BASE_UNIT_OF_MEASURE AS VARCHAR(16777216)) AS BASE_UNIT_OF_MEASURE,
        CAST(PURCHASING_GROUP AS VARCHAR(16777216)) AS PURCHASING_GROUP,
        CAST(DESCRIPTION_OF_PURCHASING_GROUP AS VARCHAR(54)) AS DESCRIPTION_OF_PURCHASING_GROUP,
        CAST(WEIGHT_OF_MATERIAL AS NUMBER(38,10)) AS WEIGHT_OF_MATERIAL,
        CAST(WEIGHT_UNIT AS VARCHAR(16777216)) AS WEIGHT_UNIT,
        CAST(MATERIAL_GROUP AS VARCHAR(27)) AS MATERIAL_GROUP,
        CAST(MATL_GRP_DESC AS VARCHAR(16777216)) AS MATL_GRP_DESC,
        CAST(PRICE_UNIT AS NUMBER(38,10)) AS PRICE_UNIT,
        CAST(STANDARD_PRICE AS NUMBER(38,10)) AS STANDARD_PRICE,
        CAST(PLANNED_DELIVERY_TIME_IN_DAYS AS NUMBER(38,10)) AS PLANNED_DELIVERY_TIME_IN_DAYS,
        CAST(GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS AS NUMBER(38,10)) AS GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS,
        CAST(MRP_CONTROLLER_MATERIALS_PLANNER AS VARCHAR(16777216)) AS MRP_CONTROLLER_MATERIALS_PLANNER,
        CAST(CONTROLLER_NAME AS VARCHAR(16777216)) AS CONTROLLER_NAME,
        CAST(KEY_TASK_LIST_GROUP AS VARCHAR(16777216)) AS KEY_TASK_LIST_GROUP,
        CAST(QUANT AS VARCHAR(16777216)) AS QUANT
    FROM transform_data
)

SELECT * from type_data
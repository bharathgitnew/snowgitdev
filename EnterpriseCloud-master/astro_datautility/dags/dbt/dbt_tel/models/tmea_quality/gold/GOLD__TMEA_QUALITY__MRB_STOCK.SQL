{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'MRB_STOCK',
        transient = false
) }}

with source_data as (
    SELECT
    LQUA.PLANT,
    LQUA.MATERIAL_NUMBER,
    MAKT.MATERIAL_DESCRIPTION,
    LQUA.STORAGE_TYPE,
    LQUA.STORAGE_BIN,
    MARC.MRP_CONTROLLER_MATERIALS_PLANNER,
    T024D.CONTROLLER_NAME,
    LQUA.TOTAL_QUANTITY,
    LQUA.AVAILABLE_STOCK,
    LQUA.BASE_UNIT_OF_MEASURE,
    TO_NUMBER(FIRST_VALUE(MBEW.STANDARD_PRICE) OVER (PARTITION BY MBEW.MATERIAL_NUMBER ORDER BY MBEW._CAPTUREDATETIME DESC),10,2) AS STANDARD_COST,
    STANDARD_COST * LQUA.TOTAL_QUANTITY AS EXTENDED_COST,
    MARA.MATERIAL_GROUP,
    LQUA.DATE_OF_LAST_MOVEMENT AS DATE_OF_LAST_MOVEMENT,
    LQUA.TIME_OF_LAST_MOVEMENT,
    LQUA.DATE_OF_LAST_PLACEMENT_INTO_STOCK AS DATE_OF_LAST_PLACEMENT_INTO_STOCK,
    CURRENT_DATE - LQUA.DATE_OF_LAST_PLACEMENT_INTO_STOCK AS DAYS_IN_MRB

    FROM {{ ref('SILVER__TMEA_QUALITY__QUANTS') }}   LQUA
    JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_DESCRIPTIONS') }}  MAKT ON LQUA.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
    LEFT OUTER JOIN {{ ref('SILVER__TMEA_QUALITY__ASSIGNMENT_TASK_LISTS_MATERIALS') }} MAPL ON LQUA.PLANT = MAPL.PLANT AND LQUA.MATERIAL_NUMBER = MAPL.MATERIAL_NUMBER
    JOIN {{ ref('SILVER__TMEA_QUALITY__PLANT_DATA_FOR_MATERIAL') }}     MARC ON MARC.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER AND MARC.PLANT =  LQUA.PLANT
    JOIN {{ ref('SILVER__TMEA_QUALITY__MRP_CONTROLLERS') }}    T024D ON T024D.MRP_CONTROLLER = MARC.MRP_CONTROLLER_MATERIALS_PLANNER AND MARC.PLANT = T024D.PLANT
    JOIN {{ ref('SILVER__TMEA_QUALITY__GENERAL_MATERIAL_DATA') }}    MARA ON MARA.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER
    JOIN {{ ref('SILVER__TMEA_QUALITY__MATERIAL_VALUATION') }}      MBEW ON MBEW.VALUATION_AREA = LQUA.PLANT AND MBEW.MATERIAL_NUMBER = LQUA.MATERIAL_NUMBER

    WHERE LQUA.WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX = '010'
    AND LQUA.PLANT = '0010'
    AND LQUA.STORAGE_TYPE = '930'
    AND LQUA.IS_DELETED = 'No'
    AND LQUA.CLIENT = '300'
    AND MBEW.VALUATION_TYPE = ' '
)

, transform_data as (
    SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	STORAGE_TYPE,
	STORAGE_BIN,
	MRP_CONTROLLER_MATERIALS_PLANNER,
	CONTROLLER_NAME,
	TOTAL_QUANTITY,
	AVAILABLE_STOCK,
	BASE_UNIT_OF_MEASURE,
	STANDARD_COST,
	EXTENDED_COST,
	MATERIAL_GROUP,
	DATE_OF_LAST_MOVEMENT,
	TIME_OF_LAST_MOVEMENT,
	DATE_OF_LAST_PLACEMENT_INTO_STOCK,
	DAYS_IN_MRB
    FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(STORAGE_TYPE AS VARCHAR(16777216)) AS STORAGE_TYPE,
        CAST(STORAGE_BIN AS VARCHAR(16777216)) AS STORAGE_BIN,
        CAST(MRP_CONTROLLER_MATERIALS_PLANNER AS VARCHAR(16777216)) AS MRP_CONTROLLER_MATERIALS_PLANNER,
        CAST(CONTROLLER_NAME AS VARCHAR(16777216)) AS CONTROLLER_NAME,
        CAST(TOTAL_QUANTITY AS NUMBER(38,10)) AS TOTAL_QUANTITY,
        CAST(AVAILABLE_STOCK AS NUMBER(38,10)) AS AVAILABLE_STOCK,
        CAST(BASE_UNIT_OF_MEASURE AS VARCHAR(16777216)) AS BASE_UNIT_OF_MEASURE,
        CAST(STANDARD_COST AS NUMBER(10,2)) AS STANDARD_COST,
        CAST(EXTENDED_COST AS NUMBER(38,12)) AS EXTENDED_COST,
        CAST(MATERIAL_GROUP AS VARCHAR(27)) AS MATERIAL_GROUP,
        CAST(DATE_OF_LAST_MOVEMENT AS TIMESTAMP_LTZ(9)) AS DATE_OF_LAST_MOVEMENT,
        CAST(TIME_OF_LAST_MOVEMENT AS VARCHAR(16777216)) AS TIME_OF_LAST_MOVEMENT,
        CAST(DATE_OF_LAST_PLACEMENT_INTO_STOCK AS TIMESTAMP_LTZ(9)) AS DATE_OF_LAST_PLACEMENT_INTO_STOCK,
        CAST(DAYS_IN_MRB AS NUMBER(9,0)) AS DAYS_IN_MRB
    FROM transform_data
)

SELECT * from type_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='INSPECTION_PROCESSING_USAGE_DECISION',
        unique_key = ['CLIENT',
    'INSPECTION_LOT_NUMBER',
    'INSPECTION_LOT_PARTIAL_LOT_SINGLE_UNIT_INTERVAL',
    'COUNTER_FOR_USAGE_DECISION'],
        transient=false
) }}

with source_data as
(
    SELECT
		MANDANT AS CLIENT ,
		PRUEFLOS AS INSPECTION_LOT_NUMBER ,
		KZART AS INSPECTION_LOT_PARTIAL_LOT_SINGLE_UNIT_INTERVAL ,
		ZAEHLER AS COUNTER_FOR_USAGE_DECISION ,
		VKATART AS CATALOG ,
		VWERKS AS PLANT ,
		VAUSWAHLMG AS SELECTED_SET_OF_THE_USAGE_DECISION ,
		VCODEGRP AS CODE_GROUP_OF_THE_USAGE_DECISION ,
		VCODE AS USAGE_DECISION_CODE ,
		VERSIONAM AS VERSION_NUMBER_OF_THE_SELECTED_SET_RECORD ,
		VERSIONCD AS VERSION_NUMBER_OF_THE_CODE_RECORD ,
		VBEWERTUNG AS CODE_VALUATION ,
		DBEWERTUNG AS DYNAMIC_MODIF_VALUATION_ACCORDING_TO_WORST_CASE_PRINCIPLE ,
		VFOLGEAKTI AS FOLLOW_UP_ACTION ,
		QKENNZAHL AS QUALITY_SCORE ,
		LTEXTKZ AS LONG_TEXT_FOR_USAGE_DECISION ,
		VNAME AS PERSON_WHO_MADE_THE_USAGE_DECISION ,
		VDATUM AS DATE_OF_CODE_USED_FOR_USAGE_DECISION ,
		VEZEITERF AS TIME_WHEN_USAGE_DECISION_WAS_RECORDED ,
		VAENAME AS PERSON_WHO_CHANGED_THE_USAGE_DECISION ,
		VAEDATUM AS CHANGE_DATE_OF_USAGE_DECISION ,
		VEZEITAEN AS TIME_WHEN_USAGE_DECISION_CHANGED ,
		STAFO AS UPDATE_GROUP_FOR_STATISTICS_UPDATE ,
		TEILLOS AS PARTIAL_LOT_NUMBER ,
		VORGLFNR AS CURRENT_NODE_NUMBER_FROM_ORDER_COUNTER_APLZL ,

		_CAPTUREDATETIME
    FROM {{ ref('BRONZE__TMEA_QUALITY__SAPO_INSPECTION_PROCESSING_USAGE_DECISION') }}
), 

transform_data as 
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, -- Adds column to table on full refresh.
		_CAPTUREDATETIME,
 		CLIENT AS CLIENT ,
		INSPECTION_LOT_NUMBER AS INSPECTION_LOT_NUMBER ,
		INSPECTION_LOT_PARTIAL_LOT_SINGLE_UNIT_INTERVAL AS INSPECTION_LOT_PARTIAL_LOT_SINGLE_UNIT_INTERVAL ,
		COUNTER_FOR_USAGE_DECISION AS COUNTER_FOR_USAGE_DECISION ,
		CATALOG AS CATALOG ,
		PLANT AS PLANT ,
		SELECTED_SET_OF_THE_USAGE_DECISION AS SELECTED_SET_OF_THE_USAGE_DECISION ,
		CODE_GROUP_OF_THE_USAGE_DECISION AS CODE_GROUP_OF_THE_USAGE_DECISION ,
		USAGE_DECISION_CODE AS USAGE_DECISION_CODE ,
		VERSION_NUMBER_OF_THE_SELECTED_SET_RECORD AS VERSION_NUMBER_OF_THE_SELECTED_SET_RECORD ,
		VERSION_NUMBER_OF_THE_CODE_RECORD AS VERSION_NUMBER_OF_THE_CODE_RECORD ,
		CODE_VALUATION AS CODE_VALUATION ,
		DYNAMIC_MODIF_VALUATION_ACCORDING_TO_WORST_CASE_PRINCIPLE AS DYNAMIC_MODIF_VALUATION_ACCORDING_TO_WORST_CASE_PRINCIPLE ,
		FOLLOW_UP_ACTION AS FOLLOW_UP_ACTION ,
		QUALITY_SCORE AS QUALITY_SCORE ,
		LONG_TEXT_FOR_USAGE_DECISION AS LONG_TEXT_FOR_USAGE_DECISION ,
		PERSON_WHO_MADE_THE_USAGE_DECISION AS PERSON_WHO_MADE_THE_USAGE_DECISION ,
		try_to_date(DATE_OF_CODE_USED_FOR_USAGE_DECISION, 'YYYYMMDD') AS DATE_OF_CODE_USED_FOR_USAGE_DECISION ,
		TIME_WHEN_USAGE_DECISION_WAS_RECORDED AS TIME_WHEN_USAGE_DECISION_WAS_RECORDED ,
		PERSON_WHO_CHANGED_THE_USAGE_DECISION AS PERSON_WHO_CHANGED_THE_USAGE_DECISION ,
		try_to_date(CHANGE_DATE_OF_USAGE_DECISION, 'YYYYMMDD') AS CHANGE_DATE_OF_USAGE_DECISION ,
		TIME_WHEN_USAGE_DECISION_CHANGED AS TIME_WHEN_USAGE_DECISION_CHANGED ,
		UPDATE_GROUP_FOR_STATISTICS_UPDATE AS UPDATE_GROUP_FOR_STATISTICS_UPDATE ,
		PARTIAL_LOT_NUMBER AS PARTIAL_LOT_NUMBER ,
		CURRENT_NODE_NUMBER_FROM_ORDER_COUNTER_APLZL AS CURRENT_NODE_NUMBER_FROM_ORDER_COUNTER_APLZL 
        FROM source_data
), 

type_data as
(
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		CAST(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast( CLIENT AS varchar(16777216)) AS CLIENT ,
		cast( INSPECTION_LOT_NUMBER AS varchar(16777216)) AS INSPECTION_LOT_NUMBER ,
		cast( INSPECTION_LOT_PARTIAL_LOT_SINGLE_UNIT_INTERVAL AS varchar(16777216)) AS INSPECTION_LOT_PARTIAL_LOT_SINGLE_UNIT_INTERVAL ,
		cast( COUNTER_FOR_USAGE_DECISION AS varchar(16777216)) AS COUNTER_FOR_USAGE_DECISION ,
		cast( CATALOG AS varchar(16777216)) AS CATALOG ,
		cast( PLANT AS varchar(16777216)) AS PLANT ,
		cast( SELECTED_SET_OF_THE_USAGE_DECISION AS varchar(16777216)) AS SELECTED_SET_OF_THE_USAGE_DECISION ,
		cast( CODE_GROUP_OF_THE_USAGE_DECISION AS varchar(16777216)) AS CODE_GROUP_OF_THE_USAGE_DECISION ,
		cast( USAGE_DECISION_CODE AS varchar(16777216)) AS USAGE_DECISION_CODE ,
		cast( VERSION_NUMBER_OF_THE_SELECTED_SET_RECORD AS varchar(16777216)) AS VERSION_NUMBER_OF_THE_SELECTED_SET_RECORD ,
		cast( VERSION_NUMBER_OF_THE_CODE_RECORD AS varchar(16777216)) AS VERSION_NUMBER_OF_THE_CODE_RECORD ,
		cast( CODE_VALUATION AS varchar(16777216)) AS CODE_VALUATION ,
		cast( DYNAMIC_MODIF_VALUATION_ACCORDING_TO_WORST_CASE_PRINCIPLE AS varchar(16777216)) AS DYNAMIC_MODIF_VALUATION_ACCORDING_TO_WORST_CASE_PRINCIPLE ,
		cast( FOLLOW_UP_ACTION AS varchar(16777216)) AS FOLLOW_UP_ACTION ,
		cast( QUALITY_SCORE AS NUMBER(38,10)) AS QUALITY_SCORE ,
		cast( LONG_TEXT_FOR_USAGE_DECISION AS varchar(16777216)) AS LONG_TEXT_FOR_USAGE_DECISION ,
		cast( PERSON_WHO_MADE_THE_USAGE_DECISION AS varchar(16777216)) AS PERSON_WHO_MADE_THE_USAGE_DECISION ,
		cast( DATE_OF_CODE_USED_FOR_USAGE_DECISION AS DATE) AS DATE_OF_CODE_USED_FOR_USAGE_DECISION ,
		cast( TIME_WHEN_USAGE_DECISION_WAS_RECORDED AS varchar(16777216)) AS TIME_WHEN_USAGE_DECISION_WAS_RECORDED ,
		cast( PERSON_WHO_CHANGED_THE_USAGE_DECISION AS varchar(16777216)) AS PERSON_WHO_CHANGED_THE_USAGE_DECISION ,
		cast( CHANGE_DATE_OF_USAGE_DECISION AS DATE) AS CHANGE_DATE_OF_USAGE_DECISION ,
		cast( TIME_WHEN_USAGE_DECISION_CHANGED AS varchar(16777216)) AS TIME_WHEN_USAGE_DECISION_CHANGED ,
		cast( UPDATE_GROUP_FOR_STATISTICS_UPDATE AS varchar(16777216)) AS UPDATE_GROUP_FOR_STATISTICS_UPDATE ,
		cast( PARTIAL_LOT_NUMBER AS varchar(16777216)) AS PARTIAL_LOT_NUMBER ,
		cast( CURRENT_NODE_NUMBER_FROM_ORDER_COUNTER_APLZL AS varchar(16777216)) AS CURRENT_NODE_NUMBER_FROM_ORDER_COUNTER_APLZL 
    FROM transform_data
)

SELECT * FROM type_data
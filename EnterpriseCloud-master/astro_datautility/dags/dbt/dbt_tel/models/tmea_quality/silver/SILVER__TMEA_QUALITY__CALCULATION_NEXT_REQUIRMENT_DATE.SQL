      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='CALCULATION_NEXT_REQUIRMENT_DATE',
      transient=false
) }}

with ODS_COMMON_HEADER_DATA_FOR_MRP_DOCUMENT as
(
SELECT * FROM {{ ref('SILVER__TMEA_QUALITY__HEADER_DATA_FOR_MRP_DOCUMENT') }}
)
,ODS_COMMON_MRP_TABLE as
(
SELECT * FROM {{ ref('SILVER__TMEA_QUALITY__MRP_TABLE') }}
)
,RunningTotalData AS
(
  SELECT NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,MRP_ELEMENT,AVAILABILITY_INDICATOR,RECEIPT_ISSUE_INDICATOR,QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
  ITEM_NUMBER_OF_MRP_LIST ,DELIVERY_ORDER_FINISH_DATE,sum(CASE WHEN RECEIPT_ISSUE_INDICATOR = '-' THEN -1 ELSE 1 END * QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED) over(partition by NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE order by ITEM_NUMBER_OF_MRP_LIST Rows Between Unbounded Preceding And Current Row) RunningTotal
  FROM
  ODS_COMMON_MRP_TABLE

  WHERE 1=1
  --AND NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = '1372635919'
 AND (MRP_ELEMENT= 'WB'  OR (AVAILABILITY_INDICATOR = 'X' AND RECEIPT_ISSUE_INDICATOR = '-'))
)
,Calculations AS
(
  SELECT NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
  ,MIN(CASE WHEN RunningTotal < 0 THEN ITEM_NUMBER_OF_MRP_LIST ELSE NULL END ) AS NegativePos
  ,MIN(CASE WHEN RunningTotal = 0 THEN ITEM_NUMBER_OF_MRP_LIST ELSE NULL END ) AS ZeroPos
  ,MIN(ITEM_NUMBER_OF_MRP_LIST) AS NeverNegativePos
  FROM RunningTotalData
--  WHERE NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = '1364634647'
  GROUP BY NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
)
,
NeededRow AS
(
    select
     ODS_COMMON_MRP_TABLE.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,ODS_COMMON_MRP_TABLE.ITEM_NUMBER_OF_MRP_LIST, ODS_COMMON_MRP_TABLE.DELIVERY_ORDER_FINISH_DATE ,ODS_COMMON_MRP_TABLE.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
       ,RunningTotalData.RunningTotal
        ,ODS_COMMON_MRP_TABLE.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED-(ODS_COMMON_MRP_TABLE.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED+RunningTotalData.RunningTotal) NeededQty
        ,CurrentRow.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED CurrentQty
    FROM ODS_COMMON_MRP_TABLE
    JOIN ODS_COMMON_MRP_TABLE CurrentRow
      ON CurrentRow.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = ODS_COMMON_MRP_TABLE.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
      AND CurrentRow.MRP_ELEMENT = 'WB'
    JOIN Calculations
      ON Calculations.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = ODS_COMMON_MRP_TABLE.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
     AND COALESCE(Calculations.NegativePos,Calculations.ZeroPos,Calculations.NeverNegativePos) = ODS_COMMON_MRP_TABLE.ITEM_NUMBER_OF_MRP_LIST
    JOIN RunningTotalData
    ON RunningTotalData.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = Calculations.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
     AND COALESCE(Calculations.NegativePos,Calculations.ZeroPos,Calculations.NeverNegativePos) = RunningTotalData.ITEM_NUMBER_OF_MRP_LIST
)
,source_data as
(
    SELECT 
     NeededRow.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
	   ITEM_NUMBER_OF_MRP_LIST,
	   DELIVERY_ORDER_FINISH_DATE,
	   QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
	   RunningTotal,
	   NeededQty,
	   CurrentQty, 
     ODS_COMMON_HEADER_DATA_FOR_MRP_DOCUMENT.PLANT,
     ODS_COMMON_HEADER_DATA_FOR_MRP_DOCUMENT.MATERIAL_NUMBER
	FROM NeededRow
	JOIN ODS_COMMON_HEADER_DATA_FOR_MRP_DOCUMENT
           ON NeededRow.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = ODS_COMMON_HEADER_DATA_FOR_MRP_DOCUMENT.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
)

 ,transform_data as
(
    SELECT 
      '{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
  NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
	ITEM_NUMBER_OF_MRP_LIST,
	DELIVERY_ORDER_FINISH_DATE,
	QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
	RunningTotal,
	NeededQty,
	CurrentQty,
	PLANT,
	MATERIAL_NUMBER
	FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		    cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE AS VARCHAR(16777216)) AS NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        CAST(ITEM_NUMBER_OF_MRP_LIST AS VARCHAR(16777216)) AS ITEM_NUMBER_OF_MRP_LIST,
        CAST(DELIVERY_ORDER_FINISH_DATE AS DATE) AS DELIVERY_ORDER_FINISH_DATE,
        CAST(QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED AS NUMBER(38,10)) AS QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        CAST(RUNNINGTOTAL AS NUMBER(38,10)) AS RUNNINGTOTAL,
        CAST(NEEDEDQTY AS NUMBER(38,10)) AS NEEDEDQTY,
        CAST(CURRENTQTY AS NUMBER(38,10)) AS CURRENTQTY,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER
    FROM transform_data
)

SELECT * from type_data
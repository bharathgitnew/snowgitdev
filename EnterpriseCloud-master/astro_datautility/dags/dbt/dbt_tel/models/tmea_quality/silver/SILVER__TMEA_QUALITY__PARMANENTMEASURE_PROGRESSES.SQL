{{ config(
        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='PARMANENTMEASURE_PROGRESSES'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	TROUBLEID AS TROUBLEID,
	PROGRESSID AS PROGRESSID,
	REGISTEREDAT AS REGISTEREDAT,
	PROCESSDEADLINE AS PROCESSDEADLINE,
	PROCESSEDAT AS PROCESSEDAT,
	PROCESSDUEDATE AS PROCESSDUEDATE,
	PROCESSEDBY AS PROCESSEDBY,
	PROCESSEDBYNAME AS PROCESSEDBYNAME,
	INSTRUCTBY AS INSTRUCTBY,
	INSTRUCTBYNAME AS INSTRUCTBYNAME,
	ISEND AS ISEND,
	JOBNO AS JOBNO,
	NOTES AS NOTES,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_QUALITY__QVICS_C_TMEA_PARMANENTMEASURE_PROGRESSES') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_QUALITY__QVICS_C_TMEA_PARMANENTMEASURE_PROGRESSES') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	TROUBLEID,
	PROGRESSID,
	REGISTEREDAT,
	PROCESSDEADLINE,
	PROCESSEDAT,
	PROCESSDUEDATE,
	PROCESSEDBY,
	PROCESSEDBYNAME,
	INSTRUCTBY,
	INSTRUCTBYNAME,
	ISEND,
	JOBNO,
	NOTES
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	TROUBLEID,
	PROGRESSID,
	REGISTEREDAT,
	PROCESSDEADLINE,
	PROCESSEDAT,
	PROCESSDUEDATE,
	PROCESSEDBY,
	PROCESSEDBYNAME,
	INSTRUCTBY,
	INSTRUCTBYNAME,
	ISEND,
	JOBNO,
	NOTES
 from transform_data 
)
SELECT * from type_data
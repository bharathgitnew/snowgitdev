{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='CODE_TEXTS',
        unique_key = ['CLIENT',
    'CATALOG',
    'CODE_GROUP',
    'CODE',
    'LANGUAGE_KEY',
    'VERSION_NUMBER'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		KATALOGART as CATALOG,
		CODEGRUPPE as CODE_GROUP,
		CODE as CODE,
		SPRACHE as LANGUAGE_KEY,
		VERSION as VERSION_NUMBER,
		GUELTIGAB as VALID_FROM_DATE,
		KURZTEXT as SHORT_TEXT_FOR_CODE_UP_TO_40_CHARACTERS_IN_LENGTH,
		LTEXTV as LONG_TEXT_EXISTS_FOR_THE_CODE,
		INAKTIV as STATUS_OF_CODE_GROUP_OR_CODE_RECORD,
		GELOESCHT as DATA_RECORD_WAS_DELETED,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_QUALITY__SAPO_CODE_TEXTS') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		CATALOG,
		CODE_GROUP,
		CODE,
		LANGUAGE_KEY,
		VERSION_NUMBER,
		TRY_TO_DATE(VALID_FROM_DATE,'YYYYMMDD')  AS VALID_FROM_DATE, 
		SHORT_TEXT_FOR_CODE_UP_TO_40_CHARACTERS_IN_LENGTH,
		LONG_TEXT_EXISTS_FOR_THE_CODE,
		STATUS_OF_CODE_GROUP_OR_CODE_RECORD,
		DATA_RECORD_WAS_DELETED
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(CATALOG as VARCHAR) as CATALOG,
		cast(CODE_GROUP as VARCHAR) as CODE_GROUP,
		cast(CODE as VARCHAR) as CODE,
		cast(LANGUAGE_KEY as VARCHAR) as LANGUAGE_KEY,
		cast(VERSION_NUMBER as VARCHAR) as VERSION_NUMBER,
		cast(VALID_FROM_DATE as DATE) as VALID_FROM_DATE,
		cast(SHORT_TEXT_FOR_CODE_UP_TO_40_CHARACTERS_IN_LENGTH as VARCHAR) as SHORT_TEXT_FOR_CODE_UP_TO_40_CHARACTERS_IN_LENGTH,
		cast(LONG_TEXT_EXISTS_FOR_THE_CODE as VARCHAR) as LONG_TEXT_EXISTS_FOR_THE_CODE,
		cast(STATUS_OF_CODE_GROUP_OR_CODE_RECORD as VARCHAR) as STATUS_OF_CODE_GROUP_OR_CODE_RECORD,
		cast(DATA_RECORD_WAS_DELETED as VARCHAR) as DATA_RECORD_WAS_DELETED
    from transform_data
)
select * from type_data
{{ config(
        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='TROUBLE_MAILADDRESSES'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	BUID AS BUID,
	TROUBLEINPUT AS TROUBLEINPUT,
	FIRSTACTIONCONTACT AS FIRSTACTIONCONTACT,
	TROUBLEIMPORTANTCLAIMINPUT AS TROUBLEIMPORTANTCLAIMINPUT,
	CLAIMSURVEYASSIGNED AS CLAIMSURVEYASSIGNED,
	PARMANENTCOMPLETION AS PARMANENTCOMPLETION,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_QUALITY__QVICS_C_TMEA_TROUBLE_MAILADDRESSES') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_QUALITY__QVICS_C_TMEA_TROUBLE_MAILADDRESSES') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	BUID,
	TROUBLEINPUT,
	FIRSTACTIONCONTACT,
	TROUBLEIMPORTANTCLAIMINPUT,
	CLAIMSURVEYASSIGNED,
	PARMANENTCOMPLETION
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	BUID,
	TROUBLEINPUT,
	FIRSTACTIONCONTACT,
	TROUBLEIMPORTANTCLAIMINPUT,
	CLAIMSURVEYASSIGNED,
	PARMANENTCOMPLETION
 from transform_data 
)
SELECT * from type_data
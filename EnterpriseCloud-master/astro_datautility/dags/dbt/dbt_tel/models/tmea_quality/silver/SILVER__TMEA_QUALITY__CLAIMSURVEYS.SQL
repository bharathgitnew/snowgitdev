{{ config(
        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='CLAIMSURVEYS'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	TROUBLEID AS TROUBLEID,
	MANAGENO AS MANAGENO,
	ISIMPORTANTCLAIM AS ISIMPORTANTCLAIM,
	JUDGEID AS JUDGEID,
	JUDGE AS JUDGE,
	JUDGENAME AS JUDGENAME,
	JUDGMENTREASON AS JUDGMENTREASON,
	JUDGMENTREASON_NOTAG AS JUDGMENTREASON_NOTAG,
	JUDGEDAT AS JUDGEDAT,
	M_CLAIMSURVEYFACTORID AS M_CLAIMSURVEYFACTORID,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_QUALITY__QVICS_C_TMEA_CLAIMSURVEYS') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_QUALITY__QVICS_C_TMEA_CLAIMSURVEYS') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	TROUBLEID,
	MANAGENO,
	ISIMPORTANTCLAIM,
	JUDGEID,
	JUDGE,
	JUDGENAME,
	JUDGMENTREASON,
	JUDGMENTREASON_NOTAG,
	JUDGEDAT,
	M_CLAIMSURVEYFACTORID
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	TROUBLEID,
	MANAGENO,
	ISIMPORTANTCLAIM,
	JUDGEID,
	JUDGE,
	JUDGENAME,
	JUDGMENTREASON,
	JUDGMENTREASON_NOTAG,
	JUDGEDAT,
	M_CLAIMSURVEYFACTORID
 from transform_data 
)
SELECT * from type_data
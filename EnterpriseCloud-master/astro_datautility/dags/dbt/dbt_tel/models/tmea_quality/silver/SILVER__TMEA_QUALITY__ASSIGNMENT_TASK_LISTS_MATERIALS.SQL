{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='ASSIGNMENT_TASK_LISTS_MATERIALS',
    unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'PLANT',
    'TASK_LIST_TYPE',
    'KEY_FOR_TASK_LIST_GROUP',
    'GROUP_COUNTER',
    'COUNTER_FOR_ADDITIONAL_CRITERIA',
    'INTERNAL_COUNTER']
) }}

with source_data as
(
    SELECT
		MANDT  AS CLIENT ,
		MATNR  AS MATERIAL_NUMBER ,
		WERKS  AS PLANT ,
		PLNTY  AS TASK_LIST_TYPE ,
		PLNNR  AS KEY_FOR_TASK_LIST_GROUP ,
		PLNAL  AS GROUP_COUNTER ,
		ZKRIZ  AS COUNTER_FOR_ADDITIONAL_CRITERIA ,
		ZAEHL  AS INTERNAL_COUNTER ,
		DATUV  AS VALID_FROM_DATE ,
		TECHV  AS TECHNICAL_STATUS_FROM ,
		AENNR  AS CHANGE_NUMBER ,
		LOEKZ  AS DELETION_INDICATOR ,
		PARKZ  AS INDICATOR_INACTIVE_CHANGES ,
		ANDAT  AS DATE_RECORD_CREATED_ON ,
		ANNAM  AS USER_WHO_CREATED_RECORD ,
		AEDAT  AS DATE_OF_LAST_CHANGE ,
		AENAM  AS NAME_OF_PERSON_WHO_CHANGED_OBJECT ,
		LIFNR  AS VENDOR_ACCOUNT_NUMBER ,
		KUNR  AS ACCOUNT_NUMBER_OF_CUSTOMER ,
		SUCHFELD  AS SEARCH_FIELD_FOR_CUSTOMER_SPECIFIC_TASK_LIST_SELECTION ,
		VBELN  AS SALES_DOCUMENT ,
		POSNR  AS SALES_DOCUMENT_ITEM ,
		PSPNR  AS WORK_BREAKDOWN_STRUCTURE_ELEMENT_WBS_ELEMENT ,
		MS_OBJECT  AS OBJECT_FOR_MULTIPLE_SPECIFICATIONS ,
		MS_OBJTYPE  AS TYPE_OF_OBJECT_FOR_MULTIPLE_SPECIFICATIONS ,
           _CAPTUREDATETIME	

        FROM {{ ref('BRONZE__TMEA_QUALITY__SAPO_ASSIGNMENT_TASK_LISTS_MATERIALS') }}
        
        )
,transform_data as
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, -- Adds column to table on full refresh.
        _CAPTUREDATETIME	AS	_CAPTUREDATETIME	,
		CLIENT  AS CLIENT ,
		MATERIAL_NUMBER  AS MATERIAL_NUMBER ,
		PLANT  AS PLANT ,
		TASK_LIST_TYPE  AS TASK_LIST_TYPE ,
		KEY_FOR_TASK_LIST_GROUP  AS KEY_FOR_TASK_LIST_GROUP ,
		GROUP_COUNTER  AS GROUP_COUNTER ,
		COUNTER_FOR_ADDITIONAL_CRITERIA  AS COUNTER_FOR_ADDITIONAL_CRITERIA ,
		INTERNAL_COUNTER  AS INTERNAL_COUNTER ,
		TRY_TO_DATE(VALID_FROM_DATE,'YYYYMMDD')  AS VALID_FROM_DATE,
		TECHNICAL_STATUS_FROM  AS TECHNICAL_STATUS_FROM ,
		CHANGE_NUMBER  AS CHANGE_NUMBER ,
		DELETION_INDICATOR  AS DELETION_INDICATOR ,
		INDICATOR_INACTIVE_CHANGES  AS INDICATOR_INACTIVE_CHANGES ,
		TRY_TO_DATE(DATE_RECORD_CREATED_ON,'YYYYMMDD')  AS DATE_RECORD_CREATED_ON ,
		USER_WHO_CREATED_RECORD  AS USER_WHO_CREATED_RECORD ,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE,'YYYYMMDD')  AS DATE_OF_LAST_CHANGE ,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT  AS NAME_OF_PERSON_WHO_CHANGED_OBJECT ,
		VENDOR_ACCOUNT_NUMBER  AS VENDOR_ACCOUNT_NUMBER ,
		ACCOUNT_NUMBER_OF_CUSTOMER  AS ACCOUNT_NUMBER_OF_CUSTOMER ,
		SEARCH_FIELD_FOR_CUSTOMER_SPECIFIC_TASK_LIST_SELECTION  AS SEARCH_FIELD_FOR_CUSTOMER_SPECIFIC_TASK_LIST_SELECTION ,
		SALES_DOCUMENT  AS SALES_DOCUMENT ,
		SALES_DOCUMENT_ITEM  AS SALES_DOCUMENT_ITEM ,
		WORK_BREAKDOWN_STRUCTURE_ELEMENT_WBS_ELEMENT  AS WORK_BREAKDOWN_STRUCTURE_ELEMENT_WBS_ELEMENT ,
		OBJECT_FOR_MULTIPLE_SPECIFICATIONS  AS OBJECT_FOR_MULTIPLE_SPECIFICATIONS ,
		TYPE_OF_OBJECT_FOR_MULTIPLE_SPECIFICATIONS  AS TYPE_OF_OBJECT_FOR_MULTIPLE_SPECIFICATIONS 
        FROM source_data
        )
,type_data as 
(
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9) ) as _CAPTUREDATETIME	,   
		cast( CLIENT  AS VARCHAR(16777216))  AS CLIENT ,
		cast( MATERIAL_NUMBER  AS VARCHAR(16777216))  AS MATERIAL_NUMBER ,
		cast( PLANT  AS VARCHAR(16777216))  AS PLANT ,
		cast( TASK_LIST_TYPE  AS VARCHAR(16777216))  AS TASK_LIST_TYPE ,
		cast( KEY_FOR_TASK_LIST_GROUP  AS VARCHAR(16777216))  AS KEY_FOR_TASK_LIST_GROUP ,
		cast( GROUP_COUNTER  AS VARCHAR(16777216))  AS GROUP_COUNTER ,
		cast( COUNTER_FOR_ADDITIONAL_CRITERIA  AS VARCHAR(16777216))  AS COUNTER_FOR_ADDITIONAL_CRITERIA ,
		cast( INTERNAL_COUNTER  AS VARCHAR(16777216))  AS INTERNAL_COUNTER ,
		cast( VALID_FROM_DATE  AS DATE)  AS VALID_FROM_DATE ,
		cast( TECHNICAL_STATUS_FROM  AS VARCHAR(16777216))  AS TECHNICAL_STATUS_FROM ,
		cast( CHANGE_NUMBER  AS VARCHAR(16777216))  AS CHANGE_NUMBER ,
		cast( DELETION_INDICATOR  AS VARCHAR(16777216))  AS DELETION_INDICATOR ,
		cast( INDICATOR_INACTIVE_CHANGES  AS VARCHAR(16777216))  AS INDICATOR_INACTIVE_CHANGES ,
		cast( DATE_RECORD_CREATED_ON  AS DATE)  AS DATE_RECORD_CREATED_ON ,
		cast( USER_WHO_CREATED_RECORD  AS VARCHAR(16777216))  AS USER_WHO_CREATED_RECORD ,
		cast( DATE_OF_LAST_CHANGE  AS DATE)  AS DATE_OF_LAST_CHANGE ,
		cast( NAME_OF_PERSON_WHO_CHANGED_OBJECT  AS VARCHAR(16777216))  AS NAME_OF_PERSON_WHO_CHANGED_OBJECT ,
		cast( VENDOR_ACCOUNT_NUMBER  AS VARCHAR(16777216))  AS VENDOR_ACCOUNT_NUMBER ,
		cast( ACCOUNT_NUMBER_OF_CUSTOMER  AS VARCHAR(16777216))  AS ACCOUNT_NUMBER_OF_CUSTOMER ,
		cast( SEARCH_FIELD_FOR_CUSTOMER_SPECIFIC_TASK_LIST_SELECTION  AS VARCHAR(16777216))  AS SEARCH_FIELD_FOR_CUSTOMER_SPECIFIC_TASK_LIST_SELECTION ,
		cast( SALES_DOCUMENT  AS VARCHAR(16777216))  AS SALES_DOCUMENT ,
		cast( SALES_DOCUMENT_ITEM  AS VARCHAR(16777216))  AS SALES_DOCUMENT_ITEM ,
		cast( WORK_BREAKDOWN_STRUCTURE_ELEMENT_WBS_ELEMENT  AS VARCHAR(16777216))  AS WORK_BREAKDOWN_STRUCTURE_ELEMENT_WBS_ELEMENT ,
		cast( OBJECT_FOR_MULTIPLE_SPECIFICATIONS  AS VARCHAR(16777216))  AS OBJECT_FOR_MULTIPLE_SPECIFICATIONS ,
		cast( TYPE_OF_OBJECT_FOR_MULTIPLE_SPECIFICATIONS  AS VARCHAR(16777216))  AS TYPE_OF_OBJECT_FOR_MULTIPLE_SPECIFICATIONS 
		 from transform_data
    )
select * from type_data
{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='SALES_DISTRIBUTION_DOCUMENT_EXPORT_CONTROL_ITEM_DATA',
    unique_key = ['CLIENT',
        'SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER',
        'ITEM_NUMBER',
        'LEGAL_REGULATION_FOR_LEGAL_CONTROL'
    ],
    transient=false
) }}

with source_data as (
    SELECT 
        MANDT AS CLIENT,
        VBELN AS SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        POSNR AS ITEM_NUMBER,
        GEGRU AS LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        ALNUM AS EXPORT_CONTROL_CLASS,
        EMBGR AS GROUPING_FOR_LEGAL_CONTROL,
        GEART AS LICENSE_TYPE,
        GENNR AS INTERNAL_LICENSE_NUMBER,
        EXKUA AS EXCHANGE_RATE_FOR_EXPORT_LICENSE,
        EXWAE AS CURRENCY_OF_EXPORT_LICENSE,
        MODCO AS CHANGE_INDICATOR_FOR_EXPORT_CONTROL,
        AHBAS AS BASIS_DOCUMENT_CATEGORY_FOR_FOREIGN_TRADE_PROCESSING,
        SECGK AS SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        _DATAAGING AS DATA_FILTER_VALUE_FOR_DATA_AGING,
        _CAPTUREDATETIME
    FROM {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_SALES_DISTRIBUTION_DOCUMENT_EXPORT_CONTROL_ITEM_DATA') }}
),

transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        CLIENT,
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        ITEM_NUMBER,
        LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        EXPORT_CONTROL_CLASS,
        GROUPING_FOR_LEGAL_CONTROL,
        LICENSE_TYPE,
        INTERNAL_LICENSE_NUMBER,
        EXCHANGE_RATE_FOR_EXPORT_LICENSE,
        CURRENCY_OF_EXPORT_LICENSE,
        CHANGE_INDICATOR_FOR_EXPORT_CONTROL,
        BASIS_DOCUMENT_CATEGORY_FOR_FOREIGN_TRADE_PROCESSING,
        SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        DATA_FILTER_VALUE_FOR_DATA_AGING,
        _CAPTUREDATETIME
	FROM SOURCE_DATA
), 

type_data as (
    SELECT 
        _AUDIT_LOG_ID,
        _ROW_HASH,
        CLIENT,
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        CAST(ITEM_NUMBER as NUMBER(38,0)) as ITEM_NUMBER,
        LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        EXPORT_CONTROL_CLASS,
        GROUPING_FOR_LEGAL_CONTROL,
        LICENSE_TYPE,
        INTERNAL_LICENSE_NUMBER,
        CAST(EXCHANGE_RATE_FOR_EXPORT_LICENSE as NUMBER(38,10)) AS EXCHANGE_RATE_FOR_EXPORT_LICENSE,
        CURRENCY_OF_EXPORT_LICENSE,
        CHANGE_INDICATOR_FOR_EXPORT_CONTROL,
        BASIS_DOCUMENT_CATEGORY_FOR_FOREIGN_TRADE_PROCESSING,
        SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        DATA_FILTER_VALUE_FOR_DATA_AGING,
        CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME
    FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
WITH MAIN
AS (
	SELECT DISTINCT VBAK.SALES_DOCUMENT,
		VBAP.SALES_DOCUMENT_ITEM,
		VBAP.REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS,
		VBAK.SALES_DOCUMENT_TYPE,
		VBAP.MATERIAL_NUMBER,
		SPLIT_PART(VBAP.MATERIAL_NUMBER, '-', 0) AS PRODUCT_TYPE_ABBREVIATION,
		VBAP.SHORT_TEXT_FOR_SALES_ORDER_ITEM AS PRODUCT_TYPE,
		KNA1.NAME_1 AS CUSTOMER_NAME,
		-- TRY_TO_DATE(VBAK.DOCUMENT_DATE_DATE_RECEIVEDSENT, 'YYYYMMDD') AS DOCUMENT_DATE,
		-- TRY_TO_DATE(VBAK.REQUESTED_DELIVERY_DATE, 'YYYYMMDD') AS CUSTOMER_REQUESTED_DELIVERY_DATE,
		-- TRY_TO_DATE(VBKD.CUSTOMER_PURCHASE_ORDER_DATE, 'YYYYMMDD') AS SUPPLIER_PO_CREATION_DATE
        VBAK.DOCUMENT_DATE_DATE_RECEIVEDSENT AS DOCUMENT_DATE,
        VBAK.REQUESTED_DELIVERY_DATE AS CUSTOMER_REQUESTED_DELIVERY_DATE,
        VBKD.CUSTOMER_PURCHASE_ORDER_DATE AS SUPPLIER_PO_CREATION_DATE
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_HEADER_DATA') }} VBAK
	JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_ITEM_DATA') }} VBAP ON VBAK.SALES_DOCUMENT = VBAP.SALES_DOCUMENT
	JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_PARTNER') }} VBPA ON VBPA.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = VBAK.SALES_DOCUMENT
	LEFT JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_DATA_IN_CUSTOMER_MASTER') }} KNA1 ON VBPA.CUSTOMER_NUMBER = KNA1.CUSTOMER_NUMBER
	JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_BUSINESS_DATA') }} VBKD ON VBKD.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = VBAK.SALES_DOCUMENT
	WHERE VBAK.SALES_DOCUMENT_TYPE = 'ZMAC'
		AND VBAP.MATERIAL_NUMBER LIKE '%-A0%'
		AND LENGTH(PRODUCT_TYPE_ABBREVIATION) = '2'
		AND VBAP.MATERIAL_NUMBER NOT LIKE 'SC%'
		AND VBAP.MATERIAL_NUMBER NOT LIKE 'SW%'
		AND VBAP.MATERIAL_NUMBER NOT LIKE 'MLM%'
		AND VBPA.ITEM_NUMBER_OF_THE_SD_DOCUMENT = '000000'
		AND VBPA.PARTNER_FUNCTION = 'WE'
		AND DOCUMENT_DATE > '2021-01-01'
		AND VBAP.REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS = ' '
        AND (VBAK.SALES_DOCUMENT <> '0000110821' AND VBAK.SALES_DOCUMENT <> '0000111426') --REMOVING FROM DATA SINCE NO SALES ORDER RECORD IN AFPO, ACTUAL_FINISH_DATE FIELD
	),
PROD_ORD_ALL
AS (
	SELECT AFPO.ORDER_NUMBER,
		AFPO.SALES_ORDER_NUMBER,
		AFPO.SALES_ORDER_ITEM,
		AFPO.MATERIAL_NUMBER_FOR_ORDER,
		AUFK.OBJECT_NUMBER,
		JEST.OBJECT_STATUS
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ORDER_ITEM') }} AFPO
	JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ORDER_MASTER_DATA') }} AUFK ON AFPO.ORDER_NUMBER = AUFK.ORDER_NUMBER
	JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__INDIVIDUAL_OBJECT_STATUS') }} AS JEST ON AUFK.OBJECT_NUMBER = JEST.OBJECT_NUMBER
	WHERE AFPO.SALES_ORDER_NUMBER <> ' '
		AND AFPO.MATERIAL_NUMBER_FOR_ORDER LIKE '%-A0%'
		AND AFPO.MATERIAL_NUMBER_FOR_ORDER NOT LIKE 'SC%'
		AND AFPO.MATERIAL_NUMBER_FOR_ORDER NOT LIKE 'SW%'
		AND AFPO.MATERIAL_NUMBER_FOR_ORDER NOT LIKE 'SW%'
		AND AFPO.MATERIAL_NUMBER_FOR_ORDER NOT LIKE 'MLM%'
		AND JEST.INDICATOR_STATUS_IS_INACTIVE <> 'X'
	),
PROD_ORD
AS (
	SELECT DISTINCT ORDER_NUMBER AS PRODUCTION_ORDER_NUMBER,
		SALES_ORDER_NUMBER AS SALES_ORDER_NUMBER1
	FROM PROD_ORD_ALL
	WHERE Order_number NOT IN (
			SELECT order_number
			FROM PROD_ORD_ALL
			WHERE OBJECT_STATUS = 'I0045'
			)
	),
PRODUCTION_SHIP_DATE_VIEW
AS (
	SELECT SALES_DOCUMENT AS SALES_DOCUMENT_2,
		SALES_DOCUMENT_ITEM AS SALES_DOCUMENT_ITEM_2,
		--TRY_TO_DATE(VBEP.SCHEDULE_LINE_DATE, 'YYYYMMDD') AS PRODUCTION_SHIP_DATE
        VBEP.SCHEDULE_LINE_DATE AS PRODUCTION_SHIP_DATE
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_SCHEDULE_LINE_DATA') }} VBEP
	WHERE VBEP.CONFIRMED_QUANTITY = '1' qualify ROW_NUMBER() OVER (
			PARTITION BY SALES_DOCUMENT,
			SALES_DOCUMENT_ITEM ORDER BY _capturedatetime DESC
			) = 1
	),
ACTUAL_SHIP_DATE_VIEW
AS (
	SELECT PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
		MATERIAL_NUMBER AS MATERIAL_NUMBER1,
		-- TRY_TO_DATE((VBFA.DATE_ON_WHICH_RECORD_WAS_CREATED), 'YYYYMMDD') AS ACTUAL_SHIP_DATE
        MAX(VBFA.DATE_ON_WHICH_RECORD_WAS_CREATED) AS ACTUAL_SHIP_DATE
	FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_FLOW') }} VBFA
	WHERE DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = 'R'
		AND MOVEMENT_TYPE_ = '601'
    GROUP BY PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT, MATERIAL_NUMBER1

	),
CURRENT_COMMIT_DATE_VIEW
AS (
	SELECT OBJECT_VALUE,
		TRY_TO_DATE(MAX(NEW_CONTENTS_OF_CHANGED_FIELD), 'YYYYMMDD') AS CURRENT_COMMIT_DATE
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__CHANGE_DOCUMENT_ITEMS') }} CDPOS
	WHERE OBJECT_CLASS = 'VERKBELEG'
		AND TABLE_NAME = 'VBEP'
		AND FIELD_NAME = 'EDATU'
	GROUP BY OBJECT_VALUE
	),
ORIGINAL_COMMIT_DATE_VIEW
AS (
	SELECT OBJECT_VALUE AS OBJECT_VALUE_1,
		TRY_TO_DATE(MIN(OLD_CONTENTS_OF_CHANGED_FIELD), 'YYYYMMDD') AS ORIGINAL_COMMIT_DATE
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__CHANGE_DOCUMENT_ITEMS') }} CDPOS
	WHERE OBJECT_CLASS = 'VERKBELEG'
		AND TABLE_NAME = 'VBEP'
		AND FIELD_NAME = 'EDATU'
	GROUP BY OBJECT_VALUE
	),
PLANNED_BASIC_START_VIEW
AS (
	SELECT SALES_ORDER_NUMBER,
		ITEM_NUMBER_IN_SALES_ORDER,
		PLANNING_MATERIAL,
		PLANNED_ORDER_NUMBER,
		-- TRY_TO_DATE(PLAF.ORDER_START_DATE_IN_PLANNED_ORDER, 'YYYYMMDD') AS PLANNED_ORDER_BASIC_START,
        PLAF.ORDER_START_DATE_IN_PLANNED_ORDER AS PLANNED_ORDER_BASIC_START,
		(_CAPTUREDATETIME),
		IS_DELETED
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANNED_ORDER') }} PLAF
	WHERE SALES_ORDER_NUMBER IS NOT NULL
		AND SALES_ORDER_NUMBER <> ' '
		AND IS_DELETED = 'No'
	),
CHECKOUT_START_FINISH_VIEW
AS (
	SELECT ORDER_NUMBER AS ORDER_NUMBER1,
		-- TRY_TO_DATE(BASIC_START_DATE, 'YYYYMMDD') AS CHECKOUT_BASIC_START,
        BASIC_START_DATE AS CHECKOUT_BASIC_START,
		-- TRY_TO_DATE(BASIC_FINISH_DATE, 'YYYYMMDD') AS CHECKOUT_BASIC_FINISH
        BASIC_FINISH_DATE AS CHECKOUT_BASIC_FINISH
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ORDER_HEADER_DATA_PP_ORDERS') }}
	),
PLANNED_FINISH_VIEW
AS (
	SELECT SALES_ORDER_NUMBER,
		ITEM_NUMBER_IN_SALES_ORDER,
		PLANNING_MATERIAL,
		-- TRY_TO_DATE(PLAF.ORDER_FINISH_DATE_IN_THE_PLANNED_ORDER, 'YYYYMMDD') AS PLANNED_ORDER_FINISH,
        PLAF.ORDER_FINISH_DATE_IN_THE_PLANNED_ORDER AS PLANNED_ORDER_FINISH,
		(_CAPTUREDATETIME),
		IS_DELETED
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANNED_ORDER') }} AS PLAF
	WHERE SALES_ORDER_NUMBER IS NOT NULL
		AND SALES_ORDER_NUMBER <> ' '
		AND IS_DELETED = 'No'
	),
PROD_BUILD_START_ALL
AS (
	SELECT AFPO.ORDER_NUMBER,
		AFPO.SALES_ORDER_NUMBER,
		AFPO.SALES_ORDER_ITEM,
		-- TRY_TO_DATE(AFPO.START_DATE_OF_PLANNED_ORDER, 'YYYYMMDD') AS SALES_ORDER_MMR_BUILD_START,
        AFPO.START_DATE_OF_PLANNED_ORDER AS SALES_ORDER_MMR_BUILD_START,
		AFPO.MATERIAL_NUMBER_FOR_ORDER,
		JEST.OBJECT_STATUS,
		AFPO._capturedatetime
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ORDER_ITEM') }} AFPO
	JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ORDER_MASTER_DATA') }} AUFK ON AFPO.ORDER_NUMBER = AUFK.ORDER_NUMBER
	JOIN  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__INDIVIDUAL_OBJECT_STATUS') }} AS JEST ON AUFK.OBJECT_NUMBER = JEST.OBJECT_NUMBER
	WHERE AFPO.SALES_ORDER_NUMBER IS NOT NULL
		AND AFPO.SALES_ORDER_NUMBER <> ' '
	),
PROD_BUILD_START
AS (
	SELECT DISTINCT ORDER_NUMBER AS ORDER_NUMBER1,
		SALES_ORDER_NUMBER AS SALES_ORDER_NUMBER1,
		(SALES_ORDER_MMR_BUILD_START) AS SALES_ORDER_MMR_BUILD_START
	FROM PROD_BUILD_START_ALL
	WHERE ORDER_NUMBER1 NOT IN (
			SELECT ORDER_NUMBER
			FROM PROD_BUILD_START_ALL
			WHERE OBJECT_STATUS = 'I0045'
			) qualify ROW_NUMBER() OVER (
			PARTITION BY SALES_ORDER_NUMBER ORDER BY SALES_ORDER_MMR_BUILD_START ASC
			) = 1
	),
PLANNED_BUILD_START
AS (
	SELECT SALES_ORDER_NUMBER,
	-- TRY_TO_DATE(ORDER_START_DATE_IN_PLANNED_ORDER, 'YYYYMMDD') AS PLANNED_ORDER_MMR_BUILD_START
    ORDER_START_DATE_IN_PLANNED_ORDER AS PLANNED_ORDER_MMR_BUILD_START
	FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANNED_ORDER') }} AS PLAF
    WHERE SALES_ORDER_NUMBER IS NOT NULL
    AND SALES_ORDER_NUMBER <> ' '
    and is_deleted = 'No'
   qualify ROW_NUMBER() OVER (
			PARTITION BY SALES_ORDER_NUMBER ORDER BY PLANNED_ORDER_MMR_BUILD_START ASC	) = 1
	),
REPAIR_COMPLETE_DATE 
AS (
    SELECT 
    ORDER_NUMBER,
    SALES_ORDER_NUMBER,
    MATERIAL_NUMBER_FOR_ORDER,
    ACTUAL_DELIVERYFINISH_DATE AS ACTUAL_FINISH_DATE
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ORDER_ITEM') }} AFPO
    ),
before_source_data
AS (
	SELECT *
  --       PLANNED_ORDER_NUMBER,
		-- PRODUCTION_ORDER_NUMBER,
		-- SALES_DOCUMENT,
		-- SALES_DOCUMENT_ITEM,
		-- SALES_DOCUMENT_TYPE,
		-- MATERIAL_NUMBER,
		-- PRODUCT_TYPE_ABBREVIATION,
		-- PRODUCT_TYPE,
		-- CUSTOMER_NAME,
		-- DOCUMENT_DATE,
		-- SUPPLIER_PO_CREATION_DATE,
		-- CUSTOMER_REQUESTED_DELIVERY_DATE,
		-- PRODUCTION_SHIP_DATE,
		-- PLANNED_ORDER_BASIC_START,
		-- CHECKOUT_BASIC_START,
		-- PLANNED_ORDER_FINISH,
		-- CHECKOUT_BASIC_FINISH,
		-- ORIGINAL_COMMIT_DATE,
		-- CURRENT_COMMIT_DATE,
		-- PLANNED_ORDER_MMR_BUILD_START,
		-- SALES_ORDER_MMR_BUILD_START,
  --       ACTUAL_FINISH_DATE,
		-- ACTUAL_SHIP_DATE
	FROM MAIN
	LEFT JOIN PROD_ORD ON PROD_ORD.SALES_ORDER_NUMBER1 = MAIN.SALES_DOCUMENT
	LEFT JOIN PRODUCTION_SHIP_DATE_VIEW ON PRODUCTION_SHIP_DATE_VIEW.SALES_DOCUMENT_2 = MAIN.SALES_DOCUMENT
		AND PRODUCTION_SHIP_DATE_VIEW.SALES_DOCUMENT_ITEM_2 = MAIN.SALES_DOCUMENT_ITEM
	LEFT JOIN ACTUAL_SHIP_DATE_VIEW ON ACTUAL_SHIP_DATE_VIEW.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT = MAIN.SALES_DOCUMENT
		AND ACTUAL_SHIP_DATE_VIEW.MATERIAL_NUMBER1 = MAIN.MATERIAL_NUMBER
	LEFT JOIN CURRENT_COMMIT_DATE_VIEW ON CURRENT_COMMIT_DATE_VIEW.OBJECT_VALUE = MAIN.SALES_DOCUMENT
	LEFT JOIN ORIGINAL_COMMIT_DATE_VIEW ON ORIGINAL_COMMIT_DATE_VIEW.OBJECT_VALUE_1 = MAIN.SALES_DOCUMENT
	LEFT JOIN PLANNED_BASIC_START_VIEW ON PLANNED_BASIC_START_VIEW.SALES_ORDER_NUMBER = MAIN.SALES_DOCUMENT
		AND PLANNED_BASIC_START_VIEW.ITEM_NUMBER_IN_SALES_ORDER = MAIN.SALES_DOCUMENT_ITEM
		AND PLANNED_BASIC_START_VIEW.PLANNING_MATERIAL = MAIN.MATERIAL_NUMBER
	LEFT JOIN PLANNED_FINISH_VIEW ON PLANNED_FINISH_VIEW.SALES_ORDER_NUMBER = MAIN.SALES_DOCUMENT
		AND PLANNED_FINISH_VIEW.ITEM_NUMBER_IN_SALES_ORDER = MAIN.SALES_DOCUMENT_ITEM
		AND PLANNED_FINISH_VIEW.PLANNING_MATERIAL = MAIN.MATERIAL_NUMBER
	LEFT JOIN PROD_BUILD_START ON PROD_BUILD_START.SALES_ORDER_NUMBER1 = MAIN.SALES_DOCUMENT
	LEFT JOIN CHECKOUT_START_FINISH_VIEW ON CHECKOUT_START_FINISH_VIEW.ORDER_NUMBER1 = PROD_ORD.PRODUCTION_ORDER_NUMBER
	LEFT JOIN PLANNED_BUILD_START ON PLANNED_BUILD_START.SALES_ORDER_NUMBER = MAIN.SALES_DOCUMENT
    LEFT JOIN REPAIR_COMPLETE_DATE ON MAIN.MATERIAL_NUMBER = REPAIR_COMPLETE_DATE.MATERIAL_NUMBER_FOR_ORDER
        AND ORDER_NUMBER = PRODUCTION_ORDER_NUMBER
	),
SOURCE_DATA as(
 SELECT PLANNED_ORDER_NUMBER,
		PRODUCTION_ORDER_NUMBER,
		SALES_DOCUMENT,
		SALES_DOCUMENT_ITEM,
		SALES_DOCUMENT_TYPE,
		MATERIAL_NUMBER,
		PRODUCT_TYPE_ABBREVIATION,
		PRODUCT_TYPE,
		CUSTOMER_NAME,
		DOCUMENT_DATE,
		SUPPLIER_PO_CREATION_DATE,
		CUSTOMER_REQUESTED_DELIVERY_DATE,
		PRODUCTION_SHIP_DATE,
		PLANNED_ORDER_BASIC_START,
		CHECKOUT_BASIC_START,
		PLANNED_ORDER_FINISH,
		CHECKOUT_BASIC_FINISH,
		ORIGINAL_COMMIT_DATE,
		CURRENT_COMMIT_DATE,
		PLANNED_ORDER_MMR_BUILD_START,
		SALES_ORDER_MMR_BUILD_START,
        ACTUAL_FINISH_DATE,
		ACTUAL_SHIP_DATE
    FROM before_source_data

),
TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	PLANNED_ORDER_NUMBER,
	PRODUCTION_ORDER_NUMBER,
	SALES_DOCUMENT,
	SALES_DOCUMENT_ITEM,
	SALES_DOCUMENT_TYPE,
	MATERIAL_NUMBER,
	PRODUCT_TYPE_ABBREVIATION,
	PRODUCT_TYPE,
	CUSTOMER_NAME,
	DOCUMENT_DATE,
	SUPPLIER_PO_CREATION_DATE,
	CUSTOMER_REQUESTED_DELIVERY_DATE,
	PRODUCTION_SHIP_DATE,
	PLANNED_ORDER_BASIC_START,
	CHECKOUT_BASIC_START,
	PLANNED_ORDER_FINISH,
	CHECKOUT_BASIC_FINISH,
	ORIGINAL_COMMIT_DATE,
	CURRENT_COMMIT_DATE,
	PLANNED_ORDER_MMR_BUILD_START,
	SALES_ORDER_MMR_BUILD_START,
	ACTUAL_FINISH_DATE,
	ACTUAL_SHIP_DATE

FROM SOURCE_DATA
)
SELECT * FROM TRANSFORM_DATA
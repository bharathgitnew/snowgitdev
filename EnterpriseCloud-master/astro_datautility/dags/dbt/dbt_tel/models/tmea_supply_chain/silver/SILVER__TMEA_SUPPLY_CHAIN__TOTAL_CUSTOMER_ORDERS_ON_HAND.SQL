{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='TOTAL_CUSTOMER_ORDERS_ON_HAND',
        unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'PLANT',
    'SPECIAL_STOCK_INDICATOR',
    'SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER',
    'ITEM_NUMBER_OF_THE_SD_DOCUMENT'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		MATNR as MATERIAL_NUMBER,
		WERKS as PLANT,
		SOBKZ as SPECIAL_STOCK_INDICATOR,
		VBELN as SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
		POSNR as ITEM_NUMBER_OF_THE_SD_DOCUMENT,
		LFGJA as FISCAL_YEAR_OF_CURRENT_PERIOD,
		LFMON as CURRENT_PERIOD_POSTING_PERIOD,
		SALAB as VALUATED_UNRESTRICTED_USE_STOCK,
		SAINS as STOCK_IN_QUALITY_INSPECTION,
		SASPE as BLOCKED_STOCK,
		SAEIN as TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES,
		ERSDA as CREATED_ON,
		KZBWS as VALUATION_OF_SPECIAL_STOCK,
		SATRA as STOCK_IN_TRANSIT,
		SARUE as MXXXH_REC_ALREADY_EXISTS_FOR_PER_BEFORE_LAST_OF_MXXX_PER,
		SABWE as VALUATED_GOODS_RECEIPT_BLOCKED_STOCK_SALES_ORDER,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_TOTAL_CUSTOMER_ORDERS_ON_HAND') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		MATERIAL_NUMBER,
		PLANT,
		SPECIAL_STOCK_INDICATOR,
		SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
		ITEM_NUMBER_OF_THE_SD_DOCUMENT,
		FISCAL_YEAR_OF_CURRENT_PERIOD,
		CURRENT_PERIOD_POSTING_PERIOD,
		VALUATED_UNRESTRICTED_USE_STOCK,
		STOCK_IN_QUALITY_INSPECTION,
		BLOCKED_STOCK,
		TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES,
		TRY_TO_DATE(CREATED_ON,'YYYYMMDD')  AS CREATED_ON, 
		VALUATION_OF_SPECIAL_STOCK,
		STOCK_IN_TRANSIT,
		MXXXH_REC_ALREADY_EXISTS_FOR_PER_BEFORE_LAST_OF_MXXX_PER,
		VALUATED_GOODS_RECEIPT_BLOCKED_STOCK_SALES_ORDER
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(MATERIAL_NUMBER as VARCHAR) as MATERIAL_NUMBER,
		cast(PLANT as VARCHAR) as PLANT,
		cast(SPECIAL_STOCK_INDICATOR as VARCHAR) as SPECIAL_STOCK_INDICATOR,
		cast(SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as VARCHAR) as SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
		cast(ITEM_NUMBER_OF_THE_SD_DOCUMENT as VARCHAR) as ITEM_NUMBER_OF_THE_SD_DOCUMENT,
		cast(FISCAL_YEAR_OF_CURRENT_PERIOD as VARCHAR) as FISCAL_YEAR_OF_CURRENT_PERIOD,
		cast(CURRENT_PERIOD_POSTING_PERIOD as VARCHAR) as CURRENT_PERIOD_POSTING_PERIOD,
		cast(VALUATED_UNRESTRICTED_USE_STOCK as NUMBER(38,10)) as VALUATED_UNRESTRICTED_USE_STOCK,
		cast(STOCK_IN_QUALITY_INSPECTION as NUMBER(38,10)) as STOCK_IN_QUALITY_INSPECTION,
		cast(BLOCKED_STOCK as NUMBER(38,10)) as BLOCKED_STOCK,
		cast(TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES as NUMBER(38,10)) as TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES,
		cast(CREATED_ON as DATE) as CREATED_ON,
		cast(VALUATION_OF_SPECIAL_STOCK as VARCHAR) as VALUATION_OF_SPECIAL_STOCK,
		cast(STOCK_IN_TRANSIT as NUMBER(38,10)) as STOCK_IN_TRANSIT,
		cast(MXXXH_REC_ALREADY_EXISTS_FOR_PER_BEFORE_LAST_OF_MXXX_PER as VARCHAR) as MXXXH_REC_ALREADY_EXISTS_FOR_PER_BEFORE_LAST_OF_MXXX_PER,
		cast(VALUATED_GOODS_RECEIPT_BLOCKED_STOCK_SALES_ORDER as NUMBER(38,10)) as VALUATED_GOODS_RECEIPT_BLOCKED_STOCK_SALES_ORDER
    from transform_data
)
select * from type_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='INVENTORY_DATA_PER_QUANT',
        unique_key = ['CLIENT',
    'WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX',
    'NUMBER_OF_SYSTEM_INVENTORY_RECORD',
    'ITEM_NUMBER_IN_INVENTORY_DOCUMENT',
    'QUANT',
    'INVENTORY_RECOUNT_NUMBER'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		LGNUM as WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		IVNUM as NUMBER_OF_SYSTEM_INVENTORY_RECORD,
		IVPOS as ITEM_NUMBER_IN_INVENTORY_DOCUMENT,
		LQNUM as QUANT,
		NANUM as INVENTORY_RECOUNT_NUMBER,
		ISTAT as ITEM_STATUS_OF_INVENTORY_AT_QUANT_LEVEL,
		NVERS as INVENTORY_RECOUNT_VERSION,
		ISEIT as INVENTORY_PAGE,
		LGTYP as STORAGE_TYPE,
		LGPLA as STORAGE_BIN,
		PLPOS as POSITION_IN_STORAGE_BIN,
		MATNR as MATERIAL_NUMBER,
		WERKS as PLANT,
		CHARG as BATCH_NUMBER,
		LETYP as STORAGE_UNIT_TYPE,
		ANZLE as NUMBER_OF_STORAGE_UNITS_CORRESPONDING_TO_COUNTED_QUANTITY,
		MENGE as COUNTED_QUANTITY_IN_STOCKKEEPING_UNIT,
		MEINS as BASE_UNIT_OF_MEASURE,
		MENGA as COUNTED_QUANTITY_IN_ALTERNATIVE_UNIT_OF_MEASURE,
		ALTME as ALTERNATIVE_UNIT_OF_MEASURE_FOR_STOCKKEEPING_UNIT,
		UMREZ as NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		UMREN as DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		BESTQ as STOCK_CATEGORY_IN_THE_WAREHOUSE_MANAGEMENT_SYSTEM,
		SOBKZ as SPECIAL_STOCK_INDICATOR,
		SONUM as SPECIAL_STOCK_NUMBER,
		WDATU as DATE_OF_GOODS_RECEIPT,
		GESME as TOTAL_QUANTITY,
		IDATU as DATE_OF_INVENTORY,
		KZINV as INVENTORY_METHOD,
		IRNUM as INVENTORY_REFERENCE_NUMBER,
		TANUM as TRANSFER_ORDER_NUMBER_OF_CONTINUOUS_INVENTORY_PROCEDURE,
		TAPOS as TRANSFER_ORDER_ITEM_OF_CONTINUOUS_INVENTORY_PROCEDURE,
		LENUM as STORAGE_UNIT_NUMBER,
		VFDAT as SHELF_LIFE_EXPIRATION_OR_BEST_BEFORE_DATE,
		LGORT as STORAGE_LOCATION,
		UNAME as NAME_OF_COUNTER_FOR_SYSTEM_INVENTORY_RECORD,
		QUINV as INDICATOR_FOR_QUANT_INVENTORY,
		SGT_SCAT as STOCK_SEGMENT,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_INVENTORY_DATA_PER_QUANT') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		NUMBER_OF_SYSTEM_INVENTORY_RECORD,
		ITEM_NUMBER_IN_INVENTORY_DOCUMENT,
		QUANT,
		INVENTORY_RECOUNT_NUMBER,
		ITEM_STATUS_OF_INVENTORY_AT_QUANT_LEVEL,
		INVENTORY_RECOUNT_VERSION,
		INVENTORY_PAGE,
		STORAGE_TYPE,
		STORAGE_BIN,
		POSITION_IN_STORAGE_BIN,
		MATERIAL_NUMBER,
		PLANT,
		BATCH_NUMBER,
		STORAGE_UNIT_TYPE,
		NUMBER_OF_STORAGE_UNITS_CORRESPONDING_TO_COUNTED_QUANTITY,
		COUNTED_QUANTITY_IN_STOCKKEEPING_UNIT,
		BASE_UNIT_OF_MEASURE,
		COUNTED_QUANTITY_IN_ALTERNATIVE_UNIT_OF_MEASURE,
		ALTERNATIVE_UNIT_OF_MEASURE_FOR_STOCKKEEPING_UNIT,
		NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		STOCK_CATEGORY_IN_THE_WAREHOUSE_MANAGEMENT_SYSTEM,
		SPECIAL_STOCK_INDICATOR,
		SPECIAL_STOCK_NUMBER,
		try_to_date(DATE_OF_GOODS_RECEIPT, 'YYYYMMDD') as DATE_OF_GOODS_RECEIPT,
		TOTAL_QUANTITY,
		try_to_date(DATE_OF_INVENTORY, 'YYYYMMDD') as DATE_OF_INVENTORY,
		INVENTORY_METHOD,
		INVENTORY_REFERENCE_NUMBER,
		TRANSFER_ORDER_NUMBER_OF_CONTINUOUS_INVENTORY_PROCEDURE,
		TRANSFER_ORDER_ITEM_OF_CONTINUOUS_INVENTORY_PROCEDURE,
		STORAGE_UNIT_NUMBER,
		try_to_date(SHELF_LIFE_EXPIRATION_OR_BEST_BEFORE_DATE, 'YYYYMMDD') as SHELF_LIFE_EXPIRATION_OR_BEST_BEFORE_DATE,
		STORAGE_LOCATION,
		NAME_OF_COUNTER_FOR_SYSTEM_INVENTORY_RECORD,
		INDICATOR_FOR_QUANT_INVENTORY,
		STOCK_SEGMENT
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX as VARCHAR) as WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		cast(NUMBER_OF_SYSTEM_INVENTORY_RECORD as VARCHAR) as NUMBER_OF_SYSTEM_INVENTORY_RECORD,
		cast(ITEM_NUMBER_IN_INVENTORY_DOCUMENT as VARCHAR) as ITEM_NUMBER_IN_INVENTORY_DOCUMENT,
		cast(QUANT as VARCHAR) as QUANT,
		cast(INVENTORY_RECOUNT_NUMBER as VARCHAR) as INVENTORY_RECOUNT_NUMBER,
		cast(ITEM_STATUS_OF_INVENTORY_AT_QUANT_LEVEL as VARCHAR) as ITEM_STATUS_OF_INVENTORY_AT_QUANT_LEVEL,
		cast(INVENTORY_RECOUNT_VERSION as VARCHAR) as INVENTORY_RECOUNT_VERSION,
		cast(INVENTORY_PAGE as VARCHAR) as INVENTORY_PAGE,
		cast(STORAGE_TYPE as VARCHAR) as STORAGE_TYPE,
		cast(STORAGE_BIN as VARCHAR) as STORAGE_BIN,
		cast(POSITION_IN_STORAGE_BIN as VARCHAR) as POSITION_IN_STORAGE_BIN,
		cast(MATERIAL_NUMBER as VARCHAR) as MATERIAL_NUMBER,
		cast(PLANT as VARCHAR) as PLANT,
		cast(BATCH_NUMBER as VARCHAR) as BATCH_NUMBER,
		cast(STORAGE_UNIT_TYPE as VARCHAR) as STORAGE_UNIT_TYPE,
		cast(NUMBER_OF_STORAGE_UNITS_CORRESPONDING_TO_COUNTED_QUANTITY as NUMBER(38,10)) as NUMBER_OF_STORAGE_UNITS_CORRESPONDING_TO_COUNTED_QUANTITY,
		cast(COUNTED_QUANTITY_IN_STOCKKEEPING_UNIT as NUMBER(38,10)) as COUNTED_QUANTITY_IN_STOCKKEEPING_UNIT,
		cast(BASE_UNIT_OF_MEASURE as VARCHAR) as BASE_UNIT_OF_MEASURE,
		cast(COUNTED_QUANTITY_IN_ALTERNATIVE_UNIT_OF_MEASURE as NUMBER(38,10)) as COUNTED_QUANTITY_IN_ALTERNATIVE_UNIT_OF_MEASURE,
		cast(ALTERNATIVE_UNIT_OF_MEASURE_FOR_STOCKKEEPING_UNIT as VARCHAR) as ALTERNATIVE_UNIT_OF_MEASURE_FOR_STOCKKEEPING_UNIT,
		cast(NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE as NUMBER(38,10)) as NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		cast(DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE as NUMBER(38,10)) as DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		cast(STOCK_CATEGORY_IN_THE_WAREHOUSE_MANAGEMENT_SYSTEM as VARCHAR) as STOCK_CATEGORY_IN_THE_WAREHOUSE_MANAGEMENT_SYSTEM,
		cast(SPECIAL_STOCK_INDICATOR as VARCHAR) as SPECIAL_STOCK_INDICATOR,
		cast(SPECIAL_STOCK_NUMBER as VARCHAR) as SPECIAL_STOCK_NUMBER,
		cast(DATE_OF_GOODS_RECEIPT as DATE) as DATE_OF_GOODS_RECEIPT,
		cast(TOTAL_QUANTITY as NUMBER(38,10)) as TOTAL_QUANTITY,
		cast(DATE_OF_INVENTORY as DATE) as DATE_OF_INVENTORY,
		cast(INVENTORY_METHOD as VARCHAR) as INVENTORY_METHOD,
		cast(INVENTORY_REFERENCE_NUMBER as VARCHAR) as INVENTORY_REFERENCE_NUMBER,
		cast(TRANSFER_ORDER_NUMBER_OF_CONTINUOUS_INVENTORY_PROCEDURE as VARCHAR) as TRANSFER_ORDER_NUMBER_OF_CONTINUOUS_INVENTORY_PROCEDURE,
		cast(TRANSFER_ORDER_ITEM_OF_CONTINUOUS_INVENTORY_PROCEDURE as VARCHAR) as TRANSFER_ORDER_ITEM_OF_CONTINUOUS_INVENTORY_PROCEDURE,
		cast(STORAGE_UNIT_NUMBER as VARCHAR) as STORAGE_UNIT_NUMBER,
		cast(SHELF_LIFE_EXPIRATION_OR_BEST_BEFORE_DATE as DATE) as SHELF_LIFE_EXPIRATION_OR_BEST_BEFORE_DATE,
		cast(STORAGE_LOCATION as VARCHAR) as STORAGE_LOCATION,
		cast(NAME_OF_COUNTER_FOR_SYSTEM_INVENTORY_RECORD as VARCHAR) as NAME_OF_COUNTER_FOR_SYSTEM_INVENTORY_RECORD,
		cast(INDICATOR_FOR_QUANT_INVENTORY as VARCHAR) as INDICATOR_FOR_QUANT_INVENTORY,
		cast(STOCK_SEGMENT as VARCHAR) as STOCK_SEGMENT
	from transform_data
)
select * from type_data
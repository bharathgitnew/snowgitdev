{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='CHANGE_DOCUMENT_HEADER',
        unique_key = ['CLIENT',
    'OBJECT_CLASS',
    'OBJECT_VALUE',
    'CHANGE_NUMBER_OF_DOCUMENT'],
        transient=false
) }}

with source_data as (
    select
        MANDANT as CLIENT,
		OBJECTCLAS as OBJECT_CLASS,
		OBJECTID as OBJECT_VALUE,
		CHANGENR as CHANGE_NUMBER_OF_DOCUMENT,
		USERNAME as USER_NAME_OF_THE_PERSON_RESPONSIBLE_IN_CHANGE_DOCUMENT,
		UDATE as CREATION_DATE_OF_THE_CHANGE_DOCUMENT,
		UTIME as TIME_CHANGED,
		TCODE as TRANSACTION_IN_WHICH_A_CHANGE_WAS_MADE,
		PLANCHNGNR as PLANNED_CHANGE_NUMBER,
		ACT_CHNGNO as CHANGE_NUMBER_OF_THE_DOCUMENT_CREATED_BY_THIS_CHANGE,
		WAS_PLANND as FLAG_CHANGE_CREATED_FROM_PLANNED_CHANGES,
		CHANGE_IND as APPLICATION_OBJECT_CHANGE_TYPE_U_I_E_D,
		LANGU as LANGUAGE_KEY,
		VERSION as THREE_BYTE_FIELD,
		DATAAGING as DATA_FILTER_VALUE_FOR_DATA_AGING,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_CHANGE_DOCUMENT_HEADER') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		OBJECT_CLASS,
		OBJECT_VALUE,
		CHANGE_NUMBER_OF_DOCUMENT,
		USER_NAME_OF_THE_PERSON_RESPONSIBLE_IN_CHANGE_DOCUMENT,
		try_to_date(CREATION_DATE_OF_THE_CHANGE_DOCUMENT, 'YYYYMMDD') as CREATION_DATE_OF_THE_CHANGE_DOCUMENT,
		TIME_CHANGED,
		TRANSACTION_IN_WHICH_A_CHANGE_WAS_MADE,
		PLANNED_CHANGE_NUMBER,
		CHANGE_NUMBER_OF_THE_DOCUMENT_CREATED_BY_THIS_CHANGE,
		FLAG_CHANGE_CREATED_FROM_PLANNED_CHANGES,
		APPLICATION_OBJECT_CHANGE_TYPE_U_I_E_D,
		LANGUAGE_KEY,
		THREE_BYTE_FIELD,
		try_to_date(DATA_FILTER_VALUE_FOR_DATA_AGING, 'YYYYMMDD') as DATA_FILTER_VALUE_FOR_DATA_AGINg
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(OBJECT_CLASS as VARCHAR) as OBJECT_CLASS,
		cast(OBJECT_VALUE as VARCHAR) as OBJECT_VALUE,
		cast(CHANGE_NUMBER_OF_DOCUMENT as VARCHAR) as CHANGE_NUMBER_OF_DOCUMENT,
		cast(USER_NAME_OF_THE_PERSON_RESPONSIBLE_IN_CHANGE_DOCUMENT as VARCHAR) as USER_NAME_OF_THE_PERSON_RESPONSIBLE_IN_CHANGE_DOCUMENT,
		cast(CREATION_DATE_OF_THE_CHANGE_DOCUMENT as DATE) as CREATION_DATE_OF_THE_CHANGE_DOCUMENT,
		cast(TIME_CHANGED as VARCHAR) as TIME_CHANGED,
		cast(TRANSACTION_IN_WHICH_A_CHANGE_WAS_MADE as VARCHAR) as TRANSACTION_IN_WHICH_A_CHANGE_WAS_MADE,
		cast(PLANNED_CHANGE_NUMBER as VARCHAR) as PLANNED_CHANGE_NUMBER,
		cast(CHANGE_NUMBER_OF_THE_DOCUMENT_CREATED_BY_THIS_CHANGE as VARCHAR) as CHANGE_NUMBER_OF_THE_DOCUMENT_CREATED_BY_THIS_CHANGE,
		cast(FLAG_CHANGE_CREATED_FROM_PLANNED_CHANGES as VARCHAR) as FLAG_CHANGE_CREATED_FROM_PLANNED_CHANGES,
		cast(APPLICATION_OBJECT_CHANGE_TYPE_U_I_E_D as VARCHAR) as APPLICATION_OBJECT_CHANGE_TYPE_U_I_E_D,
		cast(LANGUAGE_KEY as VARCHAR) as LANGUAGE_KEY,
		cast(THREE_BYTE_FIELD as VARCHAR) as THREE_BYTE_FIELD,
		cast(DATA_FILTER_VALUE_FOR_DATA_AGING as DATE) as DATA_FILTER_VALUE_FOR_DATA_AGING
    from transform_data
)
select * from type_data
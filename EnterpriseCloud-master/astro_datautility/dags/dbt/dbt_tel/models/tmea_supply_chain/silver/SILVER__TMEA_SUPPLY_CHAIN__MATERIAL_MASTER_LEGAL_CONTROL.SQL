{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='MATERIAL_MASTER_LEGAL_CONTROL',
        unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'DEPARTURE_COUNTRY'],
        transient=false
) }}

with source_data as
(
    SELECT
		MANDT  AS CLIENT ,
		MATNR  AS MATERIAL_NUMBER ,
		ALAND  AS DEPARTURE_COUNTRY ,
		GEGRU  AS LEGAL_REGULATION_FOR_LEGAL_CONTROL ,
		ALNUM  AS EXPORT_CONTROL_CLASS ,
		EMBGR  AS GROUPING_FOR_LEGAL_CONTROL ,
		PMAST  AS INDIVIDUAL_MAINTAINENCE_MATERIAL_MASTER ,
		SECGK  AS SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS ,
		_CAPTUREDATETIME
    FROM {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_MATERIAL_MASTER_LEGAL_CONTROL') }}
), 

transform_data as 
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, -- Adds column to table on full refresh.
		_CAPTUREDATETIME,
		CLIENT  AS CLIENT ,
		MATERIAL_NUMBER  AS MATERIAL_NUMBER ,
		DEPARTURE_COUNTRY  AS DEPARTURE_COUNTRY ,
		LEGAL_REGULATION_FOR_LEGAL_CONTROL  AS LEGAL_REGULATION_FOR_LEGAL_CONTROL ,
		EXPORT_CONTROL_CLASS  AS EXPORT_CONTROL_CLASS ,
		GROUPING_FOR_LEGAL_CONTROL  AS GROUPING_FOR_LEGAL_CONTROL ,
		INDIVIDUAL_MAINTAINENCE_MATERIAL_MASTER  AS INDIVIDUAL_MAINTAINENCE_MATERIAL_MASTER ,
		SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS  AS SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS 
        FROM source_data
), 

type_data as
(
    SELECT
           CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
           CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
           CAST(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast( CLIENT  AS VARCHAR(16777216))  AS CLIENT ,
		cast( MATERIAL_NUMBER  AS VARCHAR(16777216))  AS MATERIAL_NUMBER ,
		cast( DEPARTURE_COUNTRY  AS VARCHAR(16777216))  AS DEPARTURE_COUNTRY ,
		cast( LEGAL_REGULATION_FOR_LEGAL_CONTROL  AS VARCHAR(16777216))  AS LEGAL_REGULATION_FOR_LEGAL_CONTROL ,
		cast( EXPORT_CONTROL_CLASS  AS VARCHAR(16777216))  AS EXPORT_CONTROL_CLASS ,
		cast( GROUPING_FOR_LEGAL_CONTROL  AS VARCHAR(16777216))  AS GROUPING_FOR_LEGAL_CONTROL ,
		cast( INDIVIDUAL_MAINTAINENCE_MATERIAL_MASTER  AS VARCHAR(16777216)) AS INDIVIDUAL_MAINTAINENCE_MATERIAL_MASTER ,
		cast( SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS  AS VARCHAR(16777216))  AS SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS 
    FROM transform_data
)

SELECT * FROM type_data
{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='PLANT_MAINTENANCE_OBJECT_LIST',
    unique_key = ['CLIENT',
    'OBJECT_LIST_NUMBER',
    'OBJECT_LIST_COUNTERS']
) }}

with source_data as
(
    SELECT
        MANDT AS CLIENT,
        OBKNR AS OBJECT_LIST_NUMBER,
        OBZAE AS OBJECT_LIST_COUNTERS,
        EQUNR AS EQUIPMENT_NUMBER,
        IHNUM AS NOTIFICATION_NO,
        BAUTL AS ASSEMBLY,
        ILOAN AS LOCATION_AND_ACCOUNT_ASSIGNMENT_FOR_TECHNICAL_OBJECT,
        SORTF AS OBJECT_LIST_SORT_FIELD,
        BEARB AS PROCESSING_INDICATOR,
        OBJVW AS OBJECT_LIST_USAGE,
        SERNR AS SERIAL_NUMBER,
        MATNR AS MATERIAL_NUMBER,
        DATUM AS DATE,
        EQSNR AS EQSE_NUMBER,
        TASER AS TABLE_FOR_SERIAL_NUMBERS,
        UII AS UNIQUE_ITEM_IDENTIFIER,
        EAM_BADI_FLAG AS ENTRY_CREATED_BY_BADI_FOR_OBJECT_LIST_GENERATION,
        _CAPTUREDATETIME
    FROM {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_PLANT_MAINTENANCE_OBJECT_LIST') }}
        
        )
,transform_data as
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, -- Adds column to table on full refresh.
        _CAPTUREDATETIME,
        CLIENT,
        OBJECT_LIST_NUMBER,
        OBJECT_LIST_COUNTERS,
        EQUIPMENT_NUMBER,
        NOTIFICATION_NO,
        ASSEMBLY,
        LOCATION_AND_ACCOUNT_ASSIGNMENT_FOR_TECHNICAL_OBJECT,
        OBJECT_LIST_SORT_FIELD,
        PROCESSING_INDICATOR,
        OBJECT_LIST_USAGE,
        SERIAL_NUMBER,
        MATERIAL_NUMBER,
        try_to_date(DATE, 'YYYYMMDD') as DATE,
        EQSE_NUMBER,
        TABLE_FOR_SERIAL_NUMBERS,
        UNIQUE_ITEM_IDENTIFIER,
        ENTRY_CREATED_BY_BADI_FOR_OBJECT_LIST_GENERATION
        FROM source_data
        )
,type_data as 
(
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
         cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
       CAST(CLIENT AS VARCHAR(16777216)) AS CLIENT ,
        CAST(OBJECT_LIST_NUMBER AS NUMBER(38,10)) AS OBJECT_LIST_NUMBER ,
        CAST(OBJECT_LIST_COUNTERS AS NUMBER(38,10)) AS OBJECT_LIST_COUNTERS ,
        CAST(EQUIPMENT_NUMBER AS VARCHAR(16777216)) AS EQUIPMENT_NUMBER ,
        CAST(NOTIFICATION_NO AS VARCHAR(16777216)) AS NOTIFICATION_NO ,
        CAST(ASSEMBLY AS VARCHAR(16777216)) AS ASSEMBLY ,
        CAST(LOCATION_AND_ACCOUNT_ASSIGNMENT_FOR_TECHNICAL_OBJECT AS VARCHAR(16777216)) AS LOCATION_AND_ACCOUNT_ASSIGNMENT_FOR_TECHNICAL_OBJECT ,
        CAST(OBJECT_LIST_SORT_FIELD AS VARCHAR(16777216)) AS OBJECT_LIST_SORT_FIELD ,
        CAST(PROCESSING_INDICATOR AS VARCHAR(16777216)) AS PROCESSING_INDICATOR ,
        CAST(OBJECT_LIST_USAGE AS VARCHAR(16777216)) AS OBJECT_LIST_USAGE ,
        CAST(SERIAL_NUMBER AS VARCHAR(16777216)) AS SERIAL_NUMBER ,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER ,
        CAST(DATE AS DATE) AS DATE ,
        CAST(EQSE_NUMBER AS VARCHAR(16777216)) AS EQSE_NUMBER ,
        CAST(TABLE_FOR_SERIAL_NUMBERS AS VARCHAR(16777216)) AS TABLE_FOR_SERIAL_NUMBERS ,
        CAST(UNIQUE_ITEM_IDENTIFIER AS VARCHAR(16777216)) AS UNIQUE_ITEM_IDENTIFIER ,
        CAST(ENTRY_CREATED_BY_BADI_FOR_OBJECT_LIST_GENERATION AS VARCHAR(16777216)) AS ENTRY_CREATED_BY_BADI_FOR_OBJECT_LIST_GENERATION 
    from transform_data
    )
select * from type_data
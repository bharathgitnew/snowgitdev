{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='LEGAL_CONTROL_EXPORT_CONTROL_CLASSES_FOR_LICENSE',
    unique_key = ['CLIENT','LEGAL_REGULATION_FOR_LEGAL_CONTROL','LICENSE_TYPE','EXPORT_CONTROL_CLASS_ACCORDING_THE_LEGAL_REG_FOR_LEGAL_CTRL','INTERNAL_LICENSE_NUMBER','LEGAL_CONTROL_SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS'],
    transient=false
) }}

with source_data as(
    SELECT 
        _CAPTUREDATETIME,
        MANDT AS CLIENT,
        GEGRU AS LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        GEART AS LICENSE_TYPE,
        ALNUM AS EXPORT_CONTROL_CLASS_ACCORDING_THE_LEGAL_REG_FOR_LEGAL_CTRL,
        GENNR AS INTERNAL_LICENSE_NUMBER,
        SECGK AS LEGAL_CONTROL_SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        IS_DELETED
    from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_LEGAL_CONTROL_EXPORT_CONTROL_CLASSES_FOR_LICENSE') }}
),

transform_data as(
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        _CAPTUREDATETIME,
        CLIENT,
        LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        LICENSE_TYPE,
        EXPORT_CONTROL_CLASS_ACCORDING_THE_LEGAL_REG_FOR_LEGAL_CTRL,
        INTERNAL_LICENSE_NUMBER,
        LEGAL_CONTROL_SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        IS_DELETED
    from source_data
),

type_data as(
    SELECT 
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        CLIENT,
        LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        LICENSE_TYPE,
        EXPORT_CONTROL_CLASS_ACCORDING_THE_LEGAL_REG_FOR_LEGAL_CTRL,
        INTERNAL_LICENSE_NUMBER,
        LEGAL_CONTROL_SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        IS_DELETED
    from transform_data
)

select * from type_data
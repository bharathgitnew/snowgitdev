	PHYSICAL_INVENTORY_INDICATOR_QUALITY_INSP_STCK_FOLLOW_YR_,
	DATE_OF_LAST_POSTED_COUNT,
	CAST(TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES as NUMBER(38,10)) AS TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES,
	CAST(RESTRICTED_USE_STOCK_IN_PREVIOUS_PERIOD as NUMBER(38,10)) AS RESTRICTED_USE_STOCK_IN_PREVIOUS_PERIOD,

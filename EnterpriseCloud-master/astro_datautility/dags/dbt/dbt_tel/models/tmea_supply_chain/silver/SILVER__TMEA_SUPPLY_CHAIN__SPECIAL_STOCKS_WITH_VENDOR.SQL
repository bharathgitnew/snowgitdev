    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
    CLIENT,
	MATERIAL_NUMBER,
	PLANT,
	BATCH_NUMBER,
	SPECIAL_STOCK_INDICATOR,
	ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
	FISCAL_YEAR_OF_CURRENT_PERIOD,

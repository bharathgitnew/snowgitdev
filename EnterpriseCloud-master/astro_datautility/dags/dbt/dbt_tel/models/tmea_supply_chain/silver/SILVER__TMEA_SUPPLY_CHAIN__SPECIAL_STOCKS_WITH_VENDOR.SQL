	LBUML AS STOCK_IN_TRANSFER_FOR_SUBCONTRACTING_PLANT_TO_PLANT_,
	SGT_SCAT AS STOCK_SEGMENT
from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_SPECIAL_STOCKS_WITH_VENDOR') }}
),


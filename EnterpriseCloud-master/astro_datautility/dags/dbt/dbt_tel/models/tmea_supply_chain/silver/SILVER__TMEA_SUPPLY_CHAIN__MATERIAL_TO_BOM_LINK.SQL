{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='MATERIAL_TO_BOM_LINK',
        unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'PLANT',
    'BOM_USAGE',
    'BILL_OF_MATERIAL',
    'ALTERNATIVE_BOM'],
        transient=false
) }}

with source_data as (
    select
		_CAPTUREDATETIME,
        MANDT as CLIENT,
		MATNR as MATERIAL_NUMBER,
		WERKS as PLANT,
		STLAN as BOM_USAGE,
		STLNR as BILL_OF_MATERIAL,
		STLAL as ALTERNATIVE_BOM,
		LOSVN as FROM_LOT_SIZE,
		LOSBS as TO_LOT_SIZE,
		ANDAT as DATE_RECORD_CREATED_ON,
		ANNAM as USER_WHO_CREATED_RECORD,
		AEDAT as DATE_OF_LAST_CHANGE,
		AENAM as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		CSLTY as INDICATOR_CONFIGURED_MATERIAL_MATERIAL_VARIANT,
		IS_DELETED
    from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_MATERIAL_TO_BOM_LINK') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		MATERIAL_NUMBER,
		PLANT,
		BOM_USAGE,
		BILL_OF_MATERIAL,
		ALTERNATIVE_BOM,
		FROM_LOT_SIZE,
		TO_LOT_SIZE,
		TRY_TO_DATE(DATE_RECORD_CREATED_ON, 'YYYYMMDD') as DATE_RECORD_CREATED_ON,
		USER_WHO_CREATED_RECORD,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE, 'YYYYMMDD') as DATE_OF_LAST_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		INDICATOR_CONFIGURED_MATERIAL_MATERIAL_VARIANT,
		IS_DELETED
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        CLIENT,
		MATERIAL_NUMBER,
		PLANT,
		BOM_USAGE,
		BILL_OF_MATERIAL,
		ALTERNATIVE_BOM,
		cast(FROM_LOT_SIZE as NUMBER(38,10)) as FROM_LOT_SIZE,
		cast(TO_LOT_SIZE as NUMBER(38,10)) as TO_LOT_SIZE,
		cast(DATE_RECORD_CREATED_ON as DATE) as DATE_RECORD_CREATED_ON,
		USER_WHO_CREATED_RECORD,
		cast(DATE_OF_LAST_CHANGE as DATE) as DATE_OF_LAST_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		INDICATOR_CONFIGURED_MATERIAL_MATERIAL_VARIANT,
		IS_DELETED
    from transform_data
)
select * from type_data
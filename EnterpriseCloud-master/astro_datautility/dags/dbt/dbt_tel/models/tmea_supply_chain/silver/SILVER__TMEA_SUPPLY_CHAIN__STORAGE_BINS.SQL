        REIHF_SORT_FIELD_FOR_STORAGE_BIN,
        VERIFICATION_FIELD_FOR_MOBILE_DATA_ENTRY,
        ZONE,
        X_COORDINATE,
        Y_COORDINATE,
        Z_COORDINATE
    from source_data
),


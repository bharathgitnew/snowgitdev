{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='OBJECT_MANAGEMENT_RECORD',
        unique_key = ['CLIENT',
    'CHANGE_NUMBER',
    'OBJECT_CATEGORY',
    'IDENTIFICATION_OF_OBJECT_TO_BE_CHANGED'],
        transient=false
) }}

with source_data as
(
    SELECT
		MANDT  AS CLIENT ,
		AENNR  AS CHANGE_NUMBER ,
		AETYP  AS OBJECT_CATEGORY ,
		OBJKT  AS IDENTIFICATION_OF_OBJECT_TO_BE_CHANGED ,
		USOBJ  AS CHANGE_OBJECT ,
		CCVMS  AS INDICATOR_PLANNED_RECORD ,
		OITXT  AS OBJECT_MANAGEMENT_RECORD_DESCRIPTION ,
		LTXSP  AS LONG_TEXT_LANGUAGE ,
		AEDAT  AS DATE_OF_LAST_CHANGE ,
		AENAM  AS NAME_OF_PERSON_WHO_CHANGED_OBJECT ,
		ANDAT  AS DATE_RECORD_CREATED_ON ,
		ANNAM  AS USER_WHO_CREATED_RECORD ,
		OBJDT  AS DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED ,
		OBJNM  AS USER_WHO_LAST_CHANGED_THE_OBJECT ,
		CCLCK  AS INDICATOR_OBJECT_LOCKED_FOR_CHANGES ,
		AEOST  AS BASELINING_FOR_OBJECT_WAS_PERFORMED ,
		REVLV  AS REVISION_LEVEL ,
		AEDTZ  AS ENGINEERING_CHANGE_MANAGEMENT_ALTERNATIVE_DATE_COUNTER ,
		CCSTO  AS PARTIAL_KEY_FOR_STATUS_IN_ENGINEERING_CHANGE_MANAGEMENT ,
		CCOAA  AS CHANGE_TYPE_FOR_OBJECT ,
		CONT1  AS SIGNATURE,
		_CAPTUREDATETIME 
    FROM {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_OBJECT_MANAGEMENT_RECORD') }}
), 

transform_data as 
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH ,-- Adds column to table on full refresh.
		_CAPTUREDATETIME, 
		CLIENT ,
		CHANGE_NUMBER ,
		OBJECT_CATEGORY ,
		IDENTIFICATION_OF_OBJECT_TO_BE_CHANGED ,
		CHANGE_OBJECT ,
		INDICATOR_PLANNED_RECORD ,
		OBJECT_MANAGEMENT_RECORD_DESCRIPTION ,
		LONG_TEXT_LANGUAGE ,
		try_to_date(DATE_OF_LAST_CHANGE, 'YYYYMMDD') as DATE_OF_LAST_CHANGE ,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT ,
		try_to_date(DATE_RECORD_CREATED_ON, 'YYYYMMDD') as DATE_RECORD_CREATED_ON ,
		USER_WHO_CREATED_RECORD ,
		try_to_date(DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED, 'YYYYMMDD') as DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED ,
		USER_WHO_LAST_CHANGED_THE_OBJECT ,
		INDICATOR_OBJECT_LOCKED_FOR_CHANGES ,
		BASELINING_FOR_OBJECT_WAS_PERFORMED ,
		REVISION_LEVEL ,
		ENGINEERING_CHANGE_MANAGEMENT_ALTERNATIVE_DATE_COUNTER ,
		PARTIAL_KEY_FOR_STATUS_IN_ENGINEERING_CHANGE_MANAGEMENT ,
		CHANGE_TYPE_FOR_OBJECT ,
		SIGNATURE 
        FROM source_data
), 

type_data as
(
    SELECT
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast( CLIENT  AS VARCHAR(16777216))  AS CLIENT ,
		cast( CHANGE_NUMBER  AS VARCHAR(16777216))  AS CHANGE_NUMBER ,
		cast( OBJECT_CATEGORY  AS VARCHAR(16777216))  AS OBJECT_CATEGORY ,
		cast( IDENTIFICATION_OF_OBJECT_TO_BE_CHANGED  AS VARCHAR(16777216))  AS IDENTIFICATION_OF_OBJECT_TO_BE_CHANGED ,
		cast( CHANGE_OBJECT  AS VARCHAR(16777216))  AS CHANGE_OBJECT ,
		cast( INDICATOR_PLANNED_RECORD  AS VARCHAR(16777216))  AS INDICATOR_PLANNED_RECORD ,
		cast( OBJECT_MANAGEMENT_RECORD_DESCRIPTION  AS VARCHAR(16777216))  AS OBJECT_MANAGEMENT_RECORD_DESCRIPTION ,
		cast( LONG_TEXT_LANGUAGE  AS VARCHAR(16777216))  AS LONG_TEXT_LANGUAGE ,
		cast( DATE_OF_LAST_CHANGE  AS DATE)  AS DATE_OF_LAST_CHANGE ,
		cast( NAME_OF_PERSON_WHO_CHANGED_OBJECT  AS VARCHAR(16777216))  AS NAME_OF_PERSON_WHO_CHANGED_OBJECT ,
		cast( DATE_RECORD_CREATED_ON  AS DATE)  AS DATE_RECORD_CREATED_ON ,
		cast( USER_WHO_CREATED_RECORD  AS VARCHAR(16777216))  AS USER_WHO_CREATED_RECORD ,
		cast( DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED  AS DATE)  AS DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED ,
		cast( USER_WHO_LAST_CHANGED_THE_OBJECT  AS VARCHAR(16777216))  AS USER_WHO_LAST_CHANGED_THE_OBJECT ,
		cast( INDICATOR_OBJECT_LOCKED_FOR_CHANGES  AS VARCHAR(16777216))  AS INDICATOR_OBJECT_LOCKED_FOR_CHANGES ,
		cast( BASELINING_FOR_OBJECT_WAS_PERFORMED  AS VARCHAR(16777216))  AS BASELINING_FOR_OBJECT_WAS_PERFORMED ,
		cast( REVISION_LEVEL  AS VARCHAR(16777216))  AS REVISION_LEVEL ,
		cast( ENGINEERING_CHANGE_MANAGEMENT_ALTERNATIVE_DATE_COUNTER  AS VARCHAR(16777216))  AS ENGINEERING_CHANGE_MANAGEMENT_ALTERNATIVE_DATE_COUNTER ,
		cast( PARTIAL_KEY_FOR_STATUS_IN_ENGINEERING_CHANGE_MANAGEMENT  AS VARCHAR(16777216))  AS PARTIAL_KEY_FOR_STATUS_IN_ENGINEERING_CHANGE_MANAGEMENT ,
		cast( CHANGE_TYPE_FOR_OBJECT  AS VARCHAR(16777216))  AS CHANGE_TYPE_FOR_OBJECT ,
		cast( SIGNATURE  AS VARCHAR(16777216))  AS SIGNATURE 
    FROM transform_data
)

SELECT * FROM type_data
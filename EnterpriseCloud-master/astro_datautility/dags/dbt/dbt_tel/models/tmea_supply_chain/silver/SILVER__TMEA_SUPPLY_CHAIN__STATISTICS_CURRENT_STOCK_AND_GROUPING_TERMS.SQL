{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='STATISTICS_CURRENT_STOCK_AND_GROUPING_TERMS',
        unique_key = ['STORAGE_LOCATION',
    'CLIENT',
    'MATERIAL_NUMBER',
    'STATISTIC_ORIGIN',
    'VERSION_NUMBER_IN_THE_INFORMATION_STRUCTURE',
    'PLANT'],
        transient=false
) }}

with source_data as (
	SELECT
		BASME AS BASE_UNIT_OF_MEASURE,
 	 	BKLAS AS VALUATION_CLASS,
 	 	DISMM AS MRP_TYPE,
 	 	DISPO AS MRP_CONTROLLER,
 	 	EISBE AS SAFETY_STOCK,
 	 	GSBER AS BUSINESS_AREA,
 	 	HWAER AS CURRENCY_KEY,
 	 	LETZTABG AS DATE_LAST_GOODS_ISSUE,
 	 	LETZTBEW AS DATE_LAST_GOODS_MOVEMENT,
 	 	LETZTVER AS DATE_LAST_CONSUMPTION,
 	 	LETZTZUG AS DATE_LAST_RECEIPT,
 	 	LGORT AS STORAGE_LOCATION,
 	 	MANDT AS CLIENT,
 	 	MATKL AS MATERIAL_GROUP,
 	 	MATNR AS MATERIAL_NUMBER,
 	 	MBWBEST AS QUANTITY_OF_VALUATED_STOCK,
 	 	MKOBEST AS QUANTITY_OF_CONSIGNMENT_STOCK,
 	 	MTART AS MATERIAL_TYPE,
 	 	SPART AS DIVISION,
 	 	SSOUR AS STATISTIC_ORIGIN,
 	 	VRSIO AS VERSION_NUMBER_IN_THE_INFORMATION_STRUCTURE,
 	 	VWDAT AS POINTER_TO_ADMINISTRATIVE_DATA,
 	 	WBWBEST AS VALUE_OF_VALUATED_STOCK,
 	 	WERKS AS PLANT,
		_CAPTUREDATETIME
	from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_STATISTICS_CURRENT_STOCK_AND_GROUPING_TERMS') }}
),

transform_data as (
	SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, -- Adds column to table on full refresh.		
		_CAPTUREDATETIME,
		BASE_UNIT_OF_MEASURE,
 	 	VALUATION_CLASS,
 	 	MRP_TYPE,
 	 	MRP_CONTROLLER,
 	 	SAFETY_STOCK,
 	 	BUSINESS_AREA,
 	 	CURRENCY_KEY,
 	 	try_to_date(DATE_LAST_GOODS_ISSUE, 'YYYYMMDD') as DATE_LAST_GOODS_ISSUE,
 	 	try_to_date(DATE_LAST_GOODS_MOVEMENT, 'YYYYMMDD') as DATE_LAST_GOODS_MOVEMENT,
 	 	try_to_date(DATE_LAST_CONSUMPTION, 'YYYYMMDD') as DATE_LAST_CONSUMPTION,
 	 	try_to_date(DATE_LAST_RECEIPT, 'YYYYMMDD') as DATE_LAST_RECEIPT,
 	 	STORAGE_LOCATION,
 	 	CLIENT,
 	 	MATERIAL_GROUP,
 	 	MATERIAL_NUMBER,
 	 	QUANTITY_OF_VALUATED_STOCK,
 	 	QUANTITY_OF_CONSIGNMENT_STOCK,
 	 	MATERIAL_TYPE,
 	 	DIVISION,
 	 	STATISTIC_ORIGIN,
 	 	VERSION_NUMBER_IN_THE_INFORMATION_STRUCTURE,
 	 	POINTER_TO_ADMINISTRATIVE_DATA,
 	 	VALUE_OF_VALUATED_STOCK,
 	 	PLANT
	from source_data
),

type_data as (
	SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME AS TIMESTAMP_NTZ(9)) AS _CAPTUREDATETIME,
		CAST(BASE_UNIT_OF_MEASURE AS VARCHAR) AS BASE_UNIT_OF_MEASURE,
 	 	CAST(VALUATION_CLASS AS VARCHAR) AS VALUATION_CLASS,
 	 	CAST(MRP_TYPE AS VARCHAR) AS MRP_TYPE,
 	 	CAST(MRP_CONTROLLER AS VARCHAR) AS MRP_CONTROLLER,
 	 	CAST(SAFETY_STOCK AS NUMBER(38,10)) AS SAFETY_STOCK,
 	 	CAST(BUSINESS_AREA AS VARCHAR) AS BUSINESS_AREA,
 	 	CAST(CURRENCY_KEY AS VARCHAR) AS CURRENCY_KEY,
 	 	CAST(DATE_LAST_GOODS_ISSUE AS DATE) AS DATE_LAST_GOODS_ISSUE,
 	 	CAST(DATE_LAST_GOODS_MOVEMENT AS DATE) AS DATE_LAST_GOODS_MOVEMENT,
 	 	CAST(DATE_LAST_CONSUMPTION AS DATE) AS DATE_LAST_CONSUMPTION,
 	 	CAST(DATE_LAST_RECEIPT AS DATE) AS DATE_LAST_RECEIPT,
 	 	CAST(STORAGE_LOCATION AS VARCHAR) AS STORAGE_LOCATION,
 	 	CAST(CLIENT AS VARCHAR) AS CLIENT,
 	 	CAST(MATERIAL_GROUP AS VARCHAR) AS MATERIAL_GROUP,
 	 	CAST(MATERIAL_NUMBER AS VARCHAR) AS MATERIAL_NUMBER,
 	 	CAST(QUANTITY_OF_VALUATED_STOCK AS NUMBER(38,10)) AS QUANTITY_OF_VALUATED_STOCK,
 	 	CAST(QUANTITY_OF_CONSIGNMENT_STOCK AS NUMBER(38,10)) AS QUANTITY_OF_CONSIGNMENT_STOCK,
 	 	CAST(MATERIAL_TYPE AS VARCHAR) AS MATERIAL_TYPE,
 	 	CAST(DIVISION AS VARCHAR) AS DIVISION,
 	 	CAST(STATISTIC_ORIGIN AS VARCHAR) AS STATISTIC_ORIGIN,
 	 	CAST(VERSION_NUMBER_IN_THE_INFORMATION_STRUCTURE AS VARCHAR) AS VERSION_NUMBER_IN_THE_INFORMATION_STRUCTURE,
 	 	CAST(POINTER_TO_ADMINISTRATIVE_DATA AS VARCHAR) AS POINTER_TO_ADMINISTRATIVE_DATA,
 	 	CAST(PLANT AS VARCHAR) AS PLANT,
 	 	CAST(VALUE_OF_VALUATED_STOCK AS NUMBER(38,10)) AS VALUE_OF_VALUATED_STOCK

	from transform_data
)
select * from type_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='PURCHASING_SOURCE_LIST',
        unique_key = ['CLIENT',
     'MATERIAL_NUMBER',
     'PLANT',
     'NUMBER_OF_SOURCE_LIST_RECORD'],
        transient=false
) }}

with source_data as
(
    SELECT
		MANDT  AS CLIENT ,
		MATNR  AS MATERIAL_NUMBER ,
		WERKS  AS PLANT ,
		ZEORD  AS NUMBER_OF_SOURCE_LIST_RECORD ,
		ERDAT  AS DATE_ON_WHICH_RECORD_WAS_CREATED ,
		ERNAM  AS NAME_OF_PERSON_WHO_CREATED_THE_OBJECT ,
		VDATU  AS SOURCE_LIST_RECORD_VALID_FROM ,
		BDATU  AS SOURCE_LIST_RECORD_VALID_TO ,
		LIFNR  AS VENDORS_ACCOUNT_NUMBER ,
		FLIFN  AS INDICATOR_FIXED_VENDOR ,
		EBELN  AS AGREEMENT_NUMBER ,
		EBELP  AS AGREEMENT_ITEM ,
		FEBEL  AS FIXED_OUTLINE_PURCHASE_AGREEMENT_ITEM ,
		RESWK  AS PLANT_FROM_WHICH_MATERIAL_IS_PROCURED ,
		FRESW  AS FIXED_ISSUING_PLANT_IN_CASE_OF_STOCK_TRANSPORT_ORDER ,
		EMATN  AS MATERIAL_NUMBER_CORRESPONDING_TO_MANUFACTURER_PART_NUMBER ,
		NOTKZ  AS BLOCKED_SOURCE_OF_SUPPLY ,
		EKORG  AS PURCHASING_ORGANIZATION ,
		VRTYP  AS PURCHASING_DOCUMENT_CATEGORY ,
		EORTP  AS CATEGORY_OF_SOURCE_LIST_RECORD ,
		AUTET  AS SOURCE_LIST_USAGE_IN_MATERIALS_PLANNING ,
		MEINS  AS PURCHASE_ORDER_UNIT_OF_MEASURE ,
		LOGSY  AS LOGICAL_SYSTEM ,
		SOBKZ  AS SPECIAL_STOCK_INDICATOR ,
		SRM_CONTRACT_ID  AS CENTRAL_CONTRACT ,
		SRM_CONTRACT_ITM  AS CENTRAL_CONTRACT_ITEM_NUMBER ,
		_CAPTUREDATETIME,
		IS_DELETED
    FROM {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_PURCHASING_SOURCE_LIST') }}
), 

transform_data as 
(
    SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
 		CLIENT  AS CLIENT ,
		MATERIAL_NUMBER  AS MATERIAL_NUMBER ,
		PLANT  AS PLANT ,
		NUMBER_OF_SOURCE_LIST_RECORD  AS NUMBER_OF_SOURCE_LIST_RECORD ,
		try_to_date(DATE_ON_WHICH_RECORD_WAS_CREATED, 'YYYYMMDD')  AS DATE_ON_WHICH_RECORD_WAS_CREATED ,
		NAME_OF_PERSON_WHO_CREATED_THE_OBJECT  AS NAME_OF_PERSON_WHO_CREATED_THE_OBJECT ,
		try_to_date(SOURCE_LIST_RECORD_VALID_FROM, 'YYYYMMDD')  AS SOURCE_LIST_RECORD_VALID_FROM ,
		try_to_date(SOURCE_LIST_RECORD_VALID_TO, 'YYYYMMDD')  AS SOURCE_LIST_RECORD_VALID_TO ,
		VENDORS_ACCOUNT_NUMBER  AS VENDORS_ACCOUNT_NUMBER ,
		INDICATOR_FIXED_VENDOR  AS INDICATOR_FIXED_VENDOR ,
		AGREEMENT_NUMBER  AS AGREEMENT_NUMBER ,
		AGREEMENT_ITEM  AS AGREEMENT_ITEM ,
		FIXED_OUTLINE_PURCHASE_AGREEMENT_ITEM  AS FIXED_OUTLINE_PURCHASE_AGREEMENT_ITEM ,
		PLANT_FROM_WHICH_MATERIAL_IS_PROCURED  AS PLANT_FROM_WHICH_MATERIAL_IS_PROCURED ,
		FIXED_ISSUING_PLANT_IN_CASE_OF_STOCK_TRANSPORT_ORDER  AS FIXED_ISSUING_PLANT_IN_CASE_OF_STOCK_TRANSPORT_ORDER ,
		MATERIAL_NUMBER_CORRESPONDING_TO_MANUFACTURER_PART_NUMBER  AS MATERIAL_NUMBER_CORRESPONDING_TO_MANUFACTURER_PART_NUMBER ,
		BLOCKED_SOURCE_OF_SUPPLY  AS BLOCKED_SOURCE_OF_SUPPLY ,
		PURCHASING_ORGANIZATION  AS PURCHASING_ORGANIZATION ,
		PURCHASING_DOCUMENT_CATEGORY  AS PURCHASING_DOCUMENT_CATEGORY ,
		CATEGORY_OF_SOURCE_LIST_RECORD  AS CATEGORY_OF_SOURCE_LIST_RECORD ,
		SOURCE_LIST_USAGE_IN_MATERIALS_PLANNING  AS SOURCE_LIST_USAGE_IN_MATERIALS_PLANNING ,
		PURCHASE_ORDER_UNIT_OF_MEASURE  AS PURCHASE_ORDER_UNIT_OF_MEASURE ,
		LOGICAL_SYSTEM  AS LOGICAL_SYSTEM ,
		SPECIAL_STOCK_INDICATOR  AS SPECIAL_STOCK_INDICATOR ,
		CENTRAL_CONTRACT  AS CENTRAL_CONTRACT ,
		CENTRAL_CONTRACT_ITEM_NUMBER  AS CENTRAL_CONTRACT_ITEM_NUMBER ,
		IS_DELETED
        FROM source_data
), 

type_data as
(
    SELECT
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast( CLIENT  AS VARCHAR(16777216))  AS CLIENT ,
		cast( MATERIAL_NUMBER  AS VARCHAR(16777216))  AS MATERIAL_NUMBER ,
		cast( PLANT  AS VARCHAR(16777216))  AS PLANT ,
		cast( NUMBER_OF_SOURCE_LIST_RECORD  AS VARCHAR(16777216))  AS NUMBER_OF_SOURCE_LIST_RECORD ,
		cast( DATE_ON_WHICH_RECORD_WAS_CREATED  AS DATE)  AS DATE_ON_WHICH_RECORD_WAS_CREATED ,
		cast( NAME_OF_PERSON_WHO_CREATED_THE_OBJECT  AS VARCHAR(16777216))  AS NAME_OF_PERSON_WHO_CREATED_THE_OBJECT ,
		cast( SOURCE_LIST_RECORD_VALID_FROM  AS DATE)  AS SOURCE_LIST_RECORD_VALID_FROM ,
		cast( SOURCE_LIST_RECORD_VALID_TO  AS DATE)  AS SOURCE_LIST_RECORD_VALID_TO ,
		cast( VENDORS_ACCOUNT_NUMBER  AS VARCHAR(16777216))  AS VENDORS_ACCOUNT_NUMBER ,
		cast( INDICATOR_FIXED_VENDOR  AS VARCHAR(16777216))  AS INDICATOR_FIXED_VENDOR ,
		cast( AGREEMENT_NUMBER  AS VARCHAR(16777216))  AS AGREEMENT_NUMBER ,
		cast( AGREEMENT_ITEM  AS VARCHAR(16777216))  AS AGREEMENT_ITEM ,
		cast( FIXED_OUTLINE_PURCHASE_AGREEMENT_ITEM  AS VARCHAR(16777216))  AS FIXED_OUTLINE_PURCHASE_AGREEMENT_ITEM ,
		cast( PLANT_FROM_WHICH_MATERIAL_IS_PROCURED  AS VARCHAR(16777216))  AS PLANT_FROM_WHICH_MATERIAL_IS_PROCURED ,
		cast( FIXED_ISSUING_PLANT_IN_CASE_OF_STOCK_TRANSPORT_ORDER  AS VARCHAR(16777216))  AS FIXED_ISSUING_PLANT_IN_CASE_OF_STOCK_TRANSPORT_ORDER ,
		cast( MATERIAL_NUMBER_CORRESPONDING_TO_MANUFACTURER_PART_NUMBER  AS VARCHAR(16777216))  AS MATERIAL_NUMBER_CORRESPONDING_TO_MANUFACTURER_PART_NUMBER ,
		cast( BLOCKED_SOURCE_OF_SUPPLY  AS VARCHAR(16777216))  AS BLOCKED_SOURCE_OF_SUPPLY ,
		cast( PURCHASING_ORGANIZATION  AS VARCHAR(16777216))  AS PURCHASING_ORGANIZATION ,
		cast( PURCHASING_DOCUMENT_CATEGORY  AS VARCHAR(16777216))  AS PURCHASING_DOCUMENT_CATEGORY ,
		cast( CATEGORY_OF_SOURCE_LIST_RECORD  AS VARCHAR(16777216))  AS CATEGORY_OF_SOURCE_LIST_RECORD ,
		cast( SOURCE_LIST_USAGE_IN_MATERIALS_PLANNING  AS VARCHAR(16777216))  AS SOURCE_LIST_USAGE_IN_MATERIALS_PLANNING ,
		cast( PURCHASE_ORDER_UNIT_OF_MEASURE  AS VARCHAR(16777216))  AS PURCHASE_ORDER_UNIT_OF_MEASURE ,
		cast( LOGICAL_SYSTEM  AS VARCHAR(16777216))  AS LOGICAL_SYSTEM ,
		cast( SPECIAL_STOCK_INDICATOR  AS VARCHAR(16777216))  AS SPECIAL_STOCK_INDICATOR ,
		cast( CENTRAL_CONTRACT  AS VARCHAR(16777216))  AS CENTRAL_CONTRACT ,
		cast( CENTRAL_CONTRACT_ITEM_NUMBER  AS VARCHAR(16777216))  AS CENTRAL_CONTRACT_ITEM_NUMBER ,
		cast( IS_DELETED  AS VARCHAR(16777216))  AS IS_DELETED 
    FROM transform_data
)

SELECT * FROM type_data
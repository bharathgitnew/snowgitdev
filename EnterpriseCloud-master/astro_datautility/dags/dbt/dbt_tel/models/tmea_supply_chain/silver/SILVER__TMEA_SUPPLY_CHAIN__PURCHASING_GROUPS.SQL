{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='PURCHASING_GROUPS',
        unique_key = ['CLIENT',
     'PURCHASING_GROUP'],
        transient=false
) }}

with source_data as
(
    SELECT
 		MANDT  AS CLIENT ,
		EKGRP  AS PURCHASING_GROUP ,
		EKNAM  AS DESCRIPTION_OF_PURCHASING_GROUP ,
		EKTEL  AS TELEPHONE_NUMBER_OF_PURCHASING_GROUP ,
		LDEST  AS SPOOL_OUTPUT_DEVICE ,
		TELFX  AS FAX_NUMBER_OF_PURCHASING_GROUP ,
		TEL_NUMBER  AS TELEPHONE_NO_DIALLING_CODENUMBER ,
		TEL_EXTENS  AS TELEPHONE_NO_EXTENSION ,
		SMTP_ADDR  AS EMAIL_ADDRESS ,      
		_CAPTUREDATETIME
    FROM {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_PURCHASING_GROUPS') }}
), 

transform_data as 
(
    SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
		CLIENT  AS CLIENT ,
		PURCHASING_GROUP  AS PURCHASING_GROUP ,
		DESCRIPTION_OF_PURCHASING_GROUP  AS DESCRIPTION_OF_PURCHASING_GROUP ,
		TELEPHONE_NUMBER_OF_PURCHASING_GROUP  AS TELEPHONE_NUMBER_OF_PURCHASING_GROUP ,
		SPOOL_OUTPUT_DEVICE  AS SPOOL_OUTPUT_DEVICE ,
		FAX_NUMBER_OF_PURCHASING_GROUP  AS FAX_NUMBER_OF_PURCHASING_GROUP ,
		TELEPHONE_NO_DIALLING_CODENUMBER  AS TELEPHONE_NO_DIALLING_CODENUMBER ,
		TELEPHONE_NO_EXTENSION  AS TELEPHONE_NO_EXTENSION ,
		EMAIL_ADDRESS  AS EMAIL_ADDRESS 
        FROM source_data
), 

type_data as
(
    SELECT
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast( CLIENT  AS VARCHAR(16777216))  AS CLIENT ,
		cast( PURCHASING_GROUP  AS VARCHAR(16777216))  AS PURCHASING_GROUP ,
		cast( DESCRIPTION_OF_PURCHASING_GROUP  AS VARCHAR(16777216))  AS DESCRIPTION_OF_PURCHASING_GROUP ,
		cast( TELEPHONE_NUMBER_OF_PURCHASING_GROUP  AS VARCHAR(16777216))  AS TELEPHONE_NUMBER_OF_PURCHASING_GROUP ,
		cast( SPOOL_OUTPUT_DEVICE  AS VARCHAR(16777216))  AS SPOOL_OUTPUT_DEVICE ,
		cast( FAX_NUMBER_OF_PURCHASING_GROUP  AS VARCHAR(16777216))  AS FAX_NUMBER_OF_PURCHASING_GROUP ,
		cast( TELEPHONE_NO_DIALLING_CODENUMBER  AS VARCHAR(16777216))  AS TELEPHONE_NO_DIALLING_CODENUMBER ,
		cast( TELEPHONE_NO_EXTENSION  AS VARCHAR(16777216))  AS TELEPHONE_NO_EXTENSION ,
		cast( EMAIL_ADDRESS  AS VARCHAR(16777216))  AS EMAIL_ADDRESS 
    FROM transform_data
)

SELECT * FROM type_data
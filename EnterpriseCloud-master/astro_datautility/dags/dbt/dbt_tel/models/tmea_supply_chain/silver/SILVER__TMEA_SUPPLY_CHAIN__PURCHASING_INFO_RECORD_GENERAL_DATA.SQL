		cast(AVAILABLE_DELIVERABLE_UNTIL as DATE) as AVAILABLE_DELIVERABLE_UNTIL,
		cast(PRIOR_VENDOR as VARCHAR) as PRIOR_VENDOR,
		cast(NUMBER_OF_POINTS as NUMBER) as NUMBER_OF_POINTS,
		cast(POINTS_UNIT as VARCHAR) as POINTS_UNIT,
		cast(REGULAR_VENDOR as VARCHAR) as REGULAR_VENDOR,
		cast(MANUFACTURER as VARCHAR) as MANUFACTURER
    from transform_data

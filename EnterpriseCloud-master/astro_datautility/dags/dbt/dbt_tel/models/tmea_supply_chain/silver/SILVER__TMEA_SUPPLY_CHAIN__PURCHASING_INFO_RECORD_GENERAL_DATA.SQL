		NUMBER_OF_DAYS_FOR_FIRST_REMINDER_EXPEDITER,
		NUMBER_OF_DAYS_FOR_SECOND_REMINDER_EXPEDITER,
		NUMBER_OF_DAYS_FOR_THIRD_REMINDER_EXPEDITER,
		CERTIFICATE_NUMBER,
		TRY_TO_DATE(CERTIFICATE_OF_ORIGIN_VALID_UNTIL, 'YYYYMMDD') as CERTIFICATE_OF_ORIGIN_VALID_UNTIL,
		COUNTRY_OF_ISSUE_OF_CERTIFICATE_OF_ORIGIN,
		CERTIFICATE_CATEGORY,
		NUMBER,
		BASE_UNIT_OF_MEASURE,
		REGION_STATE_PROVINCE_COUNTY,
		VARIABLE_PURCHASE_ORDER_UNIT_ACTIVE,
		VENDOR_SUBRANGE,
		SORT_SEQUENCE_NUMBER,
		VENDOR_MATERIAL_GROUP,
		RETURN_AGREEMENT,
		TRY_TO_DATE(AVAILABLE_DELIVERABLE_FROM, 'YYYYMMDD') as AVAILABLE_DELIVERABLE_FROM,
		TRY_TO_DATE(AVAILABLE_DELIVERABLE_UNTIL, 'YYYYMMDD') as AVAILABLE_DELIVERABLE_UNTIL,
		PRIOR_VENDOR,
		NUMBER_OF_POINTS,
		POINTS_UNIT,
		REGULAR_VENDOR,
		MANUFACTURER
    from source_data
),


		LTSSF as SORT_SEQUENCE_NUMBER,
		WGLIF as VENDOR_MATERIAL_GROUP,
		RUECK as RETURN_AGREEMENT,
		LIFAB as AVAILABLE_DELIVERABLE_FROM,
		LIFBI as AVAILABLE_DELIVERABLE_UNTIL,

),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		NUMBER_OF_PURCHASING_INFO_RECORD,
		MATERIAL_NUMBER,
		MATERIAL_GROUP,
		VENDOR_S_ACCOUNT_NUMBER,
		PURCHASING_INFO_GENERAL_DATA_FLAGGED_FOR_DELETION,
		TRY_TO_DATE(DATE_ON_WHICH_RECORD_WAS_CREATED, 'YYYYMMDD') as DATE_ON_WHICH_RECORD_WAS_CREATED,

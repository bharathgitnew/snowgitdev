{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='MASTER_WARRANTY_OBJECT_ASSIGNMENT',
        unique_key = ['CLIENT',
    'OBJECT_NUMBER',
    'WARRANTY_TYPE'],
        transient=false
) }} 

with source_data as (
    select
        MANDT as CLIENT,
        J_OBJNR as OBJECT_NUMBER,
        GAART as WARRANTY_TYPE,
        MGANR as MASTER_WARRANTY_NUMBER,
        GWLDT as WARRANTY_DATE,
        GWLEN as DATE_ON_WHICH_THE_WARRANTY_ENDS,
        ERDAT as DATE_ON_WHICH_RECORD_WAS_CREATED,
        ERZEI as TIME,
        LVORM as DELETION_INDICATOR,
        BEGRU as AUTHORIZATION_GROUP,
        GENER as ORIGIN_INDICATOR_FOR_ENTRY_IN_TABLE_IMPH,
        GAERB as INDICATOR_PASS_ON_WARRANTY,
        WAGET as INDICATOR_WHETHER_TECHNICAL_OBJECT_SHOULD_INHERIT_WARRANTY,
        _CAPTUREDATETIME
    FROM {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_MASTER_WARRANTY_OBJECT_ASSIGNMENT') }}
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        _CAPTUREDATETIME,
        CLIENT,
        OBJECT_NUMBER,
        WARRANTY_TYPE,
        MASTER_WARRANTY_NUMBER,
        try_to_date(WARRANTY_DATE, 'YYYYMMDD') as WARRANTY_DATE,
        try_to_date(DATE_ON_WHICH_THE_WARRANTY_ENDS, 'YYYYMMDD') as DATE_ON_WHICH_THE_WARRANTY_ENDS,
        try_to_date(DATE_ON_WHICH_RECORD_WAS_CREATED, 'YYYYMMDD') as DATE_ON_WHICH_RECORD_WAS_CREATED,
        TIME,
        DELETION_INDICATOR,
        AUTHORIZATION_GROUP,
        ORIGIN_INDICATOR_FOR_ENTRY_IN_TABLE_IMPH,
        INDICATOR_PASS_ON_WARRANTY,
        INDICATOR_WHETHER_TECHNICAL_OBJECT_SHOULD_INHERIT_WARRANTY
    from source_data
),

type_data as (
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
        cast(OBJECT_NUMBER as VARCHAR) as OBJECT_NUMBER,
        cast(WARRANTY_TYPE as VARCHAR) as WARRANTY_TYPE,
        cast(MASTER_WARRANTY_NUMBER as VARCHAR) as MASTER_WARRANTY_NUMBER,
        cast(WARRANTY_DATE as DATE) as WARRANTY_DATE,
        cast(DATE_ON_WHICH_THE_WARRANTY_ENDS as DATE) as DATE_ON_WHICH_THE_WARRANTY_ENDS,
        cast(DATE_ON_WHICH_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_RECORD_WAS_CREATED,
        cast(TIME as VARCHAR) as TIME,
        cast(DELETION_INDICATOR as VARCHAR) as DELETION_INDICATOR,
        cast(AUTHORIZATION_GROUP as VARCHAR) as AUTHORIZATION_GROUP,
        cast(ORIGIN_INDICATOR_FOR_ENTRY_IN_TABLE_IMPH as VARCHAR) as ORIGIN_INDICATOR_FOR_ENTRY_IN_TABLE_IMPH,
        cast(INDICATOR_PASS_ON_WARRANTY as VARCHAR) as INDICATOR_PASS_ON_WARRANTY,
        cast(INDICATOR_WHETHER_TECHNICAL_OBJECT_SHOULD_INHERIT_WARRANTY as VARCHAR) as INDICATOR_WHETHER_TECHNICAL_OBJECT_SHOULD_INHERIT_WARRANTY
    from transform_data
)
select * from type_data
		PLNMG as PLANNED_QUANTITY,
		ENTMG as WITHDRAWAL_QUANTITY,
		UPLMG as ORIGINALLY_PLANNED_QUANTITY,
		ENTLI as DATE_TYPE_DAY_WEEK_MONTH_INTERVAL,
		ENTLU as PERIOD_INDICATOR_DAY_WEEK_MONTH_POSTING_PERIOD,
		PERXX as PLANNING_PERIOD,
		SERNR as BOM_EXPLOSION_NUMBER,
		VERID as PRODUCTION_VERSION,
		ERFME as UNIT_OF_ENTRY,
		ERFMG as QUANTITY_IN_UNIT_OF_ENTRY,
		UMREZ as NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		UMREN as DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,

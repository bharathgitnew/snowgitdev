    select
		_CAPTUREDATETIME,
        MANDT as CLIENT,
		BDZEI as INDEPENDENT_REQUIREMENTS_POINTER,
		PDATU as DELIVERY_ORDER_FINISH_DATE,
		WDATU as REQSTD_DATE,
		AENAM as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		LAEDA as DATE_OF_LAST_CHANGE,

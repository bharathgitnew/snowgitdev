		LOEVR as DELETION_INDICATOR,
		CUOBJ as CONFIGURATION_INTERNAL_OBJECT_NUMBER,
		STPKT as SUPPORTING_POINT_FOR_INDEPENDENT_REQUIREMENTS,
		TECHS as PARAMETER_VARIANT_STANDARD_VARIANT,
		FSH_SEASON_YEAR as SEASON_YEAR,
		FSH_SEASON as SEASON,
		FSH_COLLECTION as FASHION_COLLECTION,
		FSH_THEME as FASHION_THEME
    from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_INDEPENDENT_REQUIREMENTS_DATA') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		INDEPENDENT_REQUIREMENTS_POINTER,
		TRY_TO_DATE(DELIVERY_ORDER_FINISH_DATE, 'YYYYMMDD') as DELIVERY_ORDER_FINISH_DATE,
		TRY_TO_DATE(REQSTD_DATE, 'YYYYMMDD') as REQSTD_DATE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE, 'YYYYMMDD') as DATE_OF_LAST_CHANGE,
		BASE_UNIT_OF_MEASURE,
		PLANNED_QUANTITY,
		WITHDRAWAL_QUANTITY,
		ORIGINALLY_PLANNED_QUANTITY,
		DATE_TYPE_DAY_WEEK_MONTH_INTERVAL,
		PERIOD_INDICATOR_DAY_WEEK_MONTH_POSTING_PERIOD,
		PLANNING_PERIOD,
		BOM_EXPLOSION_NUMBER,
		PRODUCTION_VERSION,
		UNIT_OF_ENTRY,
		QUANTITY_IN_UNIT_OF_ENTRY,
		NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		FIXMG_PLANNED_QUANTITY,
		INDICATOR_LONG_TEXT_EXISTS,
		DELETION_INDICATOR,
		CONFIGURATION_INTERNAL_OBJECT_NUMBER,
		SUPPORTING_POINT_FOR_INDEPENDENT_REQUIREMENTS,
		PARAMETER_VARIANT_STANDARD_VARIANT,
		SEASON_YEAR,
		SEASON,
		FASHION_COLLECTION,
		FASHION_THEME
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		CLIENT,
		INDEPENDENT_REQUIREMENTS_POINTER,
		cast(DELIVERY_ORDER_FINISH_DATE as DATE) as DELIVERY_ORDER_FINISH_DATE,
		cast(REQSTD_DATE as DATE) as REQSTD_DATE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		cast(DATE_OF_LAST_CHANGE as DATE) as DATE_OF_LAST_CHANGE,
		BASE_UNIT_OF_MEASURE,
		cast(PLANNED_QUANTITY as NUMBER(38,10)) as PLANNED_QUANTITY,
		cast(WITHDRAWAL_QUANTITY as NUMBER(38,10)) as WITHDRAWAL_QUANTITY,
		cast(ORIGINALLY_PLANNED_QUANTITY as NUMBER(38,10)) as ORIGINALLY_PLANNED_QUANTITY,
		DATE_TYPE_DAY_WEEK_MONTH_INTERVAL,
		PERIOD_INDICATOR_DAY_WEEK_MONTH_POSTING_PERIOD,
		PLANNING_PERIOD,
		BOM_EXPLOSION_NUMBER,
		PRODUCTION_VERSION,
		UNIT_OF_ENTRY,
		cast(QUANTITY_IN_UNIT_OF_ENTRY as NUMBER(38,10)) as QUANTITY_IN_UNIT_OF_ENTRY,
		cast(NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE as NUMBER(38,10)) as NUMERATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		cast(DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE as NUMBER(38,10)) as DENOMINATOR_FOR_CONVERSION_TO_BASE_UNITS_OF_MEASURE,
		cast(FIXMG_PLANNED_QUANTITY as NUMBER(38,10)) as FIXMG_PLANNED_QUANTITY,
		INDICATOR_LONG_TEXT_EXISTS,
		DELETION_INDICATOR,
		CONFIGURATION_INTERNAL_OBJECT_NUMBER,
		SUPPORTING_POINT_FOR_INDEPENDENT_REQUIREMENTS,
		PARAMETER_VARIANT_STANDARD_VARIANT,
		SEASON_YEAR,
		SEASON,
		FASHION_COLLECTION,
		FASHION_THEME
    from transform_data
)

{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='ASSIGNMENT_IM_STORAGE_LOCATION_TO_WM_WAREHOUSE_NUMBER',
        unique_key = ['CLIENT',
    'PLANT',
    'STORAGE_LOCATION'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		WERKS as PLANT,
		LGORT as STORAGE_LOCATION,
		LGNUM as WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		OBEST as EXTENT_WAREHOUSE_MANAGEMENT,
		LGNTB as DO_NOT_ADOPT_STORAGE_LOCATION_INTO_TRANSFER_REQUIREMENT,
		SLGOR as STANDARD_STORAGE_LOCATION_OF_PLANT_IN_THIS_WAREHOUSE_NUMBER,
		OBTYP as PICKING_AREA_STORAGE_TYPE_FOR_LEAN_WM,
		LGREF as STORAGE_LOC_REF,
		CENSY as REFERENCE_TO_CENTRAL_ERP_SYSTEM,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_SUPPLY_CHAIN__SAPO_ASSIGNMENT_IM_STORAGE_LOCATION_TO_WM_WAREHOUSE_NUMBER') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		PLANT,
		STORAGE_LOCATION,
		WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		EXTENT_WAREHOUSE_MANAGEMENT,
		DO_NOT_ADOPT_STORAGE_LOCATION_INTO_TRANSFER_REQUIREMENT,
		STANDARD_STORAGE_LOCATION_OF_PLANT_IN_THIS_WAREHOUSE_NUMBER,
		PICKING_AREA_STORAGE_TYPE_FOR_LEAN_WM,
		STORAGE_LOC_REF,
		REFERENCE_TO_CENTRAL_ERP_SYSTEM
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(PLANT as VARCHAR) as PLANT,
		cast(STORAGE_LOCATION as VARCHAR) as STORAGE_LOCATION,
		cast(WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX as VARCHAR) as WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		cast(EXTENT_WAREHOUSE_MANAGEMENT as VARCHAR) as EXTENT_WAREHOUSE_MANAGEMENT,
		cast(DO_NOT_ADOPT_STORAGE_LOCATION_INTO_TRANSFER_REQUIREMENT as VARCHAR) as DO_NOT_ADOPT_STORAGE_LOCATION_INTO_TRANSFER_REQUIREMENT,
		cast(STANDARD_STORAGE_LOCATION_OF_PLANT_IN_THIS_WAREHOUSE_NUMBER as VARCHAR) as STANDARD_STORAGE_LOCATION_OF_PLANT_IN_THIS_WAREHOUSE_NUMBER,
		cast(PICKING_AREA_STORAGE_TYPE_FOR_LEAN_WM as VARCHAR) as PICKING_AREA_STORAGE_TYPE_FOR_LEAN_WM,
		cast(STORAGE_LOC_REF as VARCHAR) as STORAGE_LOC_REF,
		cast(REFERENCE_TO_CENTRAL_ERP_SYSTEM as VARCHAR) as REFERENCE_TO_CENTRAL_ERP_SYSTEM
    from transform_data
)
select * from type_data
{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='SAPO_METRICS_RESULTS',
    unique_key = [],
    transient=false	
) }} 


with source_data as ( 
    SELECT
        _CAPTUREDATETIME,
        RECNO,
        TRANS_DOC_NUM,
        TRANS_DOC_ITEM,
        TRANS_DOC_TYPE,
        TRANS_DOC_TYPE_TEXT,
        TIME,
        CATEGORY,
        SUBCATEGORY,
        TRANS_DATE,
        TRANS_TIME,
        USERNAME,
        TRANS_DOC,
        TRANS_CODE,
        MATERIAL,
        MATERIAL_DESCR,
        PLANT,
        LGORT,
        WAREHOUSE,
        QUANTITY,
        UNIT_OF_MEAS,
        SOURCE_STOR_TYPE,
        SOURCE_STOR_TYPE_TXT,
        SOURCE_STOR_BIN,
        SOURCE_DATE,
        SOURCE_TIME,
        DEST_STOR_TYPE,
        DEST_STOR_TYPE_TXT,
        DEST_STOR_BIN,
        DEST_DATE,
        DEST_TIME,
        TRANS_TIME_DAYS,
        TRANS_TIME_HOURS,
        ADJUSTED_DAYS,
        LABOR_CAPACITY
    FROM {{ source('SAP_ORACLE_LIVE','ZMM_MET_RESULTS') }}
),
	
transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        _CAPTUREDATETIME,
        RECNO,
        TRANS_DOC_NUM,
        TRANS_DOC_ITEM,
        TRANS_DOC_TYPE,
        TRANS_DOC_TYPE_TEXT,
        TIME,
        CATEGORY,
        SUBCATEGORY,
        TRANS_DATE,
        TRANS_TIME,
        USERNAME,
        TRANS_DOC,
        TRANS_CODE,
        MATERIAL,
        MATERIAL_DESCR,
        PLANT,
        LGORT,
        WAREHOUSE,
        QUANTITY,
        UNIT_OF_MEAS,
        SOURCE_STOR_TYPE,
        SOURCE_STOR_TYPE_TXT,
        SOURCE_STOR_BIN,
        SOURCE_DATE,
        SOURCE_TIME,
        DEST_STOR_TYPE,
        DEST_STOR_TYPE_TXT,
        DEST_STOR_BIN,
        DEST_DATE,
        DEST_TIME,
        TRANS_TIME_DAYS,
        TRANS_TIME_HOURS,
        ADJUSTED_DAYS,
        LABOR_CAPACITY
    FROM source_data
),

type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		CAST(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        RECNO,
        TRANS_DOC_NUM,
        TRANS_DOC_ITEM,
        TRANS_DOC_TYPE,
        TRANS_DOC_TYPE_TEXT,
        TIME,
        CATEGORY,
        SUBCATEGORY,
        TRANS_DATE,
        TRANS_TIME,
        USERNAME,
        TRANS_DOC,
        TRANS_CODE,
        MATERIAL,
        MATERIAL_DESCR,
        PLANT,
        LGORT,
        WAREHOUSE,
        CAST(QUANTITY AS NUMBER(38,10)) AS QUANTITY,
        UNIT_OF_MEAS,
        SOURCE_STOR_TYPE,
        SOURCE_STOR_TYPE_TXT,
        SOURCE_STOR_BIN,
        SOURCE_DATE,
        SOURCE_TIME,
        DEST_STOR_TYPE,
        DEST_STOR_TYPE_TXT,
        DEST_STOR_BIN,
        DEST_DATE,
        DEST_TIME,
        TRANS_TIME_DAYS,
        TRANS_TIME_HOURS,
        ADJUSTED_DAYS,
        LABOR_CAPACITY
    FROM transform_data
)

select * from type_data

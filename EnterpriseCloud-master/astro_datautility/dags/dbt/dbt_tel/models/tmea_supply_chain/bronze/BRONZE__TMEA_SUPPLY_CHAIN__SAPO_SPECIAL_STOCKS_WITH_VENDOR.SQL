
{{ config(
	materialized='tel_incremental',
	incremental_strategy='merge',
	alias='SAPO_SPECIAL_STOCKS_WITH_VENDOR',
	unique_key = ['MANDT','MATNR','WERKS','CHARG','SOBKZ','LIFNR']
) }}

with source_data as (
SELECT
	_CAPTUREDATETIME,
	MANDT,
	MATNR,
	WERKS,
	CHARG,
	SOBKZ,
	LIFNR,
	LFGJA,
	LFMON,
	LBSPR,
	LBLAB,
	LBINS,
	LBVLA,
	LBVIN,
	LBILL,
	LBILQ,
	LBVLL,
	LBVLQ,
	LBFLL,
	LBFLQ,
	LBDLL,
	LBEIN,
	LBVEI,
	ERSDA,
	LBJIN,
	LBRUE,
	LBUML,
	SGT_SCAT
FROM {{source('SAP_ORACLE_LIVE', 'MSLB')}}
),

transform_data as (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDT as MANDT,
	MATNR as MATNR,
	WERKS as WERKS,
	CHARG as CHARG,
	SOBKZ as SOBKZ,
	LIFNR as LIFNR,
	LFGJA as LFGJA,
	LFMON as LFMON,
	LBSPR as LBSPR,
	LBLAB as LBLAB,
	LBINS as LBINS,
	LBVLA as LBVLA,
	LBVIN as LBVIN,
	LBILL as LBILL,
	LBILQ as LBILQ,
	LBVLL as LBVLL,
	LBVLQ as LBVLQ,
	LBFLL as LBFLL,
	LBFLQ as LBFLQ,
	LBDLL as LBDLL,
	LBEIN as LBEIN,
	LBVEI as LBVEI,
	ERSDA as ERSDA,
	LBJIN as LBJIN,
	LBRUE as LBRUE,
	LBUML as LBUML,
	SGT_SCAT as SGT_SCAT
FROM SOURCE_DATA
),

type_data as
(
SELECT
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	MANDT,
	MATNR,
	WERKS,
	CHARG,
	SOBKZ,
	LIFNR,
	LFGJA,
	LFMON,
	LBSPR,
	CAST(LBLAB as NUMBER(38,10)) AS LBLAB,
	CAST(LBINS as NUMBER(38,10)) AS LBINS,
	CAST(LBVLA as NUMBER(38,10)) AS LBVLA,
	CAST(LBVIN as NUMBER(38,10)) AS LBVIN,
	LBILL,
	LBILQ,
	LBVLL,
	LBVLQ,
	LBFLL,
	LBFLQ,
	LBDLL,
	CAST(LBEIN as NUMBER(38,10)) AS LBEIN,
	CAST(LBVEI as NUMBER(38,10)) AS LBVEI,
	ERSDA,
	LBJIN,
	LBRUE,
	CAST(LBUML as NUMBER(38,10)) AS LBUML,
	SGT_SCAT
FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA

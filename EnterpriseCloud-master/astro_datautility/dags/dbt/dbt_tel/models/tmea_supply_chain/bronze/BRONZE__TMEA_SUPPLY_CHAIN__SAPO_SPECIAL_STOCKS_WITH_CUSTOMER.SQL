	materialized='tel_incremental',
	incremental_strategy='merge',
	alias='SAPO_SPECIAL_STOCKS_WITH_CUSTOMER',
	unique_key = ['MANDT','MATNR','WERKS','CHARG','SOBKZ','KUNNR']
) }}

with source_data as (
SELECT
	_CAPTUREDATETIME,
	MANDT,
	MATNR,
	WERKS,
	CHARG,
	SOBKZ,
	KUNNR,
	LFGJA,
	LFMON,
	KUSPR,
	KULAB,
	KUINS,
	KUVLA,
	KUVIN,
	KUILL,
	KUILQ,
	KUVLL,
	KUVLQ,
	KUFLL,
	KUFLQ,
	KUDLL,
	KUEIN,
	KUVEI,
	ERSDA,
	KUJIN,
	KURUE,
	KUUML,
	SGT_SCAT,
	FSH_SEASON_YEAR,
	FSH_SEASON,
	FSH_COLLECTION,
	FSH_THEME,
	FSH_SALLOC_QTY
FROM {{source('SAP_ORACLE_LIVE', 'MSKU')}}
),

transform_data as (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDT as MANDT,
	MATNR as MATNR,
	WERKS as WERKS,
	CHARG as CHARG,
	SOBKZ as SOBKZ,
	KUNNR as KUNNR,
	LFGJA as LFGJA,
	LFMON as LFMON,
	KUSPR as KUSPR,
	KULAB as KULAB,
	KUINS as KUINS,
	KUVLA as KUVLA,
	KUVIN as KUVIN,
	KUILL as KUILL,
	KUILQ as KUILQ,
	KUVLL as KUVLL,
	KUVLQ as KUVLQ,
	KUFLL as KUFLL,
	KUFLQ as KUFLQ,
	KUDLL as KUDLL,
	KUEIN as KUEIN,
	KUVEI as KUVEI,
	ERSDA as ERSDA,
	KUJIN as KUJIN,
	KURUE as KURUE,
	KUUML as KUUML,
	SGT_SCAT as SGT_SCAT,
	FSH_SEASON_YEAR as FSH_SEASON_YEAR,
	FSH_SEASON as FSH_SEASON,
	FSH_COLLECTION as FSH_COLLECTION,
	FSH_THEME as FSH_THEME,
	FSH_SALLOC_QTY as FSH_SALLOC_QTY
FROM SOURCE_DATA
),

type_data as
(
SELECT
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	MANDT,
	MATNR,
	WERKS,
	CHARG,
	SOBKZ,
	KUNNR,
	LFGJA,
	LFMON,
	KUSPR,
	CAST(KULAB as NUMBER(38,10)) AS KULAB,
	CAST(KUINS as NUMBER(38,10)) AS KUINS,
	CAST(KUVLA as NUMBER(38,10)) AS KUVLA,
	CAST(KUVIN as NUMBER(38,10)) AS KUVIN,
	KUILL,
	KUILQ,
	KUVLL,
	KUVLQ,
	KUFLL,
	KUFLQ,
	KUDLL,
	CAST(KUEIN as NUMBER(38,10)) AS KUEIN,
	CAST(KUVEI as NUMBER(38,10)) AS KUVEI,
	ERSDA,
	KUJIN,
	KURUE,
	CAST(KUUML as NUMBER(38,10)) AS KUUML,
	SGT_SCAT,
	FSH_SEASON_YEAR,
	FSH_SEASON,
	FSH_COLLECTION,
	FSH_THEME,
	CAST(FSH_SALLOC_QTY as NUMBER(38,10)) AS FSH_SALLOC_QTY
FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA

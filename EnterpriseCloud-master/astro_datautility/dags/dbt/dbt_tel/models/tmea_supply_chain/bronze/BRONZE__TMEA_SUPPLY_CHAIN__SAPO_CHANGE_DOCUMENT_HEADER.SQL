{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='SAPO_CHANGE_DOCUMENT_HEADER',
        unique_key = ['MANDANT',
    'OBJECTCLAS',
    'OBJECTID',
    'CHANGENR'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDANT,
	OBJECTCLAS,
	OBJECTID,
	CHANGENR,
	USERNAME,
	UDATE,
	UTIME,
	TCODE,
	PLANCHNGNR,
	ACT_CHNGNO,
	WAS_PLANND,
	CHANGE_IND,
	LANGU,
	VERSION,
	_DATAAGING
	FROM {{source('SAP_ORACLE_LIVE', 'CDHDR')}}
),


transform_data as 
(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDANT as MANDANT,
	OBJECTCLAS as OBJECTCLAS,
	OBJECTID as OBJECTID,
	CHANGENR as CHANGENR,
	USERNAME as USERNAME,
	UDATE as UDATE,
	UTIME as UTIME,
	TCODE as TCODE,
	PLANCHNGNR as PLANCHNGNR,
	ACT_CHNGNO as ACT_CHNGNO,
	WAS_PLANND as WAS_PLANND,
	CHANGE_IND as CHANGE_IND,
	LANGU as LANGU,
	VERSION as VERSION,
	_DATAAGING as DATAAGING
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	MANDANT,
	OBJECTCLAS,
	OBJECTID,
	CHANGENR,
	USERNAME,
	UDATE,
	UTIME,
	TCODE,
	PLANCHNGNR,
	ACT_CHNGNO,
	WAS_PLANND,
	CHANGE_IND,
	LANGU,
	VERSION,
	DATAAGING
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
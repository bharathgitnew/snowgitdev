    SELECT
        DATA_SOURCE.TOOL_ID,
        DATA_SOURCE.MATERIAL_NUMBER,
        DATA_SOURCE.MATERIAL_DESCRIPTION,
        DATA_SOURCE.Higher_Level_Mat,
        DATA_SOURCE.Higher_Level_Mat_Desc,

    materialized = 'tel_incremental',
    incremental_strategy = 'insert_overwrite',
) }}

WITH ONE AS (
    select
        SOLD_TO,
        SOLD_TO_NAME,
        SOLD_TO_STATE,
        SOLD_TO_CNTRY,
        SHIP_TO,
        SHIP_TO_NAME,
        SHIP_TO_STATE,
        SHIP_TO_CNTRY,
        ENDUSER,
        ORDER_TYPE,
        ORDER_NO,
        -- PARTIAL_OR_NO_PARTIAL,
        -- DELIVERY_PRIORITY,
        PO_DETAILS,
        ORDER_ITEM,
        ITEM_CATEGORY,
        MATERIAL,
        MATERIAL_DESCRIPTION,
        -- PLANT,
        -- PLANT_DESCRIPTION,
        PRICE_EACH,
        TO_NUMBER(EXTPRICE, 20, 2) AS EXTPRICE,
        ORDER_CURRENCY,
        -- PLANNER,
        DELIVERY,
        DEL_ITEM,
        TO_NUMBER(QTY_SHIPPED, 20, 2) AS QTY_SHIPPED,
        -- U_OF_M,
        -- GROSS_WEIGHT,
        -- GROSS_WEIGHT_UNIT,
        COMMMODITY_CODE,
        ECCN,
        -- ROUTE_DESC,
        -- BILL_OF_LADING,
        -- INCO_1,
        -- INCO_2,
        BOOK_DATE,
        FIRST_DATE,
        CONF_DATE,
        PICK_DATE,
        SHIP_DATE,
        -- INTERCO_INV,
        SALES_INV,
        INV_DATE,
        CREATED_BY,
        SERIAL_NUMBER,
        ORDER_DATE,
        MATERIAL_NUMBER,
        DEPARTURE_COUNTRY,
        LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        EXPORT_CONTROL_CLASS,
        GROUPING_FOR_LEGAL_CONTROL,
        SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        MAEX.INDIVIDUAL_MAINTAINENCE_MATERIAL_MASTER
    from {{ ref('GOLD__TMEA_SUPPLY_CHAIN__SHIPMENT_HISTORY_REPORT') }} as ZSHIP
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_MASTER_LEGAL_CONTROL') }} MAEX 
        ON ZSHIP.MATERIAL = MAEX.MATERIAL_NUMBER
        AND ZSHIP.SHIP_TO_CNTRY = MAEX.DEPARTURE_COUNTRY
),

TWO AS(
    select
        DISTINCT VBEX.INTERNAL_LICENSE_NUMBER,
        VBEX.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        VBEX.ITEM_NUMBER,
        EMBK.EXTERNAL_LICENSE_NUMBER,
        EMBK.VALIDITY_END_DATE,
        EMBK.VALIDITY_START_DATE,
        TO_NUMBER(EMBK.MAXIMUM_LICENSE_VALUE, 10, 2) AS MAXIMUM_LICENSE_VALUE,
        TO_NUMBER(EMBK.MAXIMUM_LICENSE_QUANTITY, 20, 2) AS MAXIMUM_LICENSE_QUANTITY,
        EMBK.NUMBER_OF_SD_DOCUMENT_ASSIGNED_TO_LICENSE,
        T606Y.EXPORT_CONTROL_CLASS_ACCORDING_THE_LEGAL_REG_FOR_LEGAL_CTRL,
        T606X.COUNTRY_OF_DESTINATION
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DISTRIBUTION_DOCUMENT_EXPORT_CONTROL_ITEM_DATA') }} VBEX
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__LEGAL_CONTROL_LICENSE_MASTER_HEADER_DATA') }} EMBK 
        ON VBEX.INTERNAL_LICENSE_NUMBER = EMBK.INTERNAL_LICENSE_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__LEGAL_CONTROL_EXPORT_CONTROL_CLASSES_FOR_LICENSE') }} T606Y 
        ON VBEX.INTERNAL_LICENSE_NUMBER = T606Y.INTERNAL_LICENSE_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__LEGAL_CONTROL_DESTINATION_COUNTRIES_FOR_LICENSE') }} T606X 
        ON T606Y.INTERNAL_LICENSE_NUMBER = T606X.INTERNAL_LICENSE_NUMBER
),

MAIN AS (
    SELECT DISTINCT 
        *
    FROM ONE
    LEFT JOIN TWO 
        ON ORDER_NO = SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
        AND ORDER_ITEM = ITEM_NUMBER
    WHERE
        (
            EXTERNAL_LICENSE_NUMBER <> 'NLR'
            OR EXTERNAL_LICENSE_NUMBER IS NULL
        ) -- AND SHIP_DATE BETWEEN '2024-11-01' AND '2024-11-30'
),

KIT_MATERIAL_NUMBERS AS (
    SELECT DISTINCT 
        MATERIAL,
        MATERIAL_DESCRIPTION,
        COMMMODITY_CODE
    FROM MAIN
    WHERE COMMMODITY_CODE = 'SEE TARIFF SHEET'
),

KIT_BOM AS (
    SELECT
        ROOT_PART_NUMBER AS KIT_ROOT_PART_NUMBER,
        MATERIAL_DESCRIPTION AS KIT_MATERIAL_DESCRIPTION,
        PARENT_PART_NUMBER AS KIT_PARENT_PART_NUMBER,
        CHILD_PART_NUMBER AS KIT_CHILD_PART_NUMBER,
        CHILD_MATERIAL_DESCRIPTION AS KIT_CHILD_MATERIAL_DESCRIPTION,
        BOM_ITEM_NUMBER AS KIT_BOM_ITEM_NUMBER,
        TO_NUMBER(COMPONENT_QUANTITY, 10, 0) AS KIT_COMPONENT_QUANTITY,
        TRY_TO_NUMBER(MARA.TEL_PRICE, 10, 2) AS KIT_TEL_PRICE,
        KIT_COMPONENT_QUANTITY * KIT_TEL_PRICE AS KIT_EXT_PRICE,
        LEVEL
    FROM {{ ref('GOLD__TMEA_SUPPLY_CHAIN__BOM') }}
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_MATERIAL_DATA') }} MARA 
        ON CHILD_PART_NUMBER = MATERIAL_NUMBER
    -- WHERE LEVEL = '1'
    WHERE
        KIT_ROOT_PART_NUMBER IN (
            SELECT distinct MATERIAL FROM KIT_MATERIAL_NUMBERS
        )
    -- ORDER BY
    --     KIT_ROOT_PART_NUMBER,
    --     KIT_BOM_ITEM_NUMBER
),

OUTPUT AS (
    SELECT
        *
    FROM MAIN
    LEFT JOIN KIT_BOM ON MATERIAL = KIT_ROOT_PART_NUMBER
),

source_data as (
    SELECT
        *,
        CASE
            WHEN KIT_BOM_ITEM_NUMBER IS NULL THEN 'NO KIT'
            WHEN KIT_BOM_ITEM_NUMBER IS NOT NULL THEN 'YES KIT'
        END AS KIT_INCLUDED,
        CASE
            WHEN KIT_INCLUDED = 'NO KIT' THEN QTY_SHIPPED
            WHEN KIT_INCLUDED = 'YES KIT' THEN KIT_COMPONENT_QUANTITY
        END AS REPORT_LINE_ITEM_EXT_QTY,
        CASE
            WHEN KIT_INCLUDED = 'NO KIT' THEN EXTPRICE
            WHEN KIT_INCLUDED = 'YES KIT' THEN KIT_EXT_PRICE
        END AS REPORT_LINE_ITEM_EXT_PRICE
    FROM OUTPUT
),

transform_data as (
    select 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        *
    from source_data
),


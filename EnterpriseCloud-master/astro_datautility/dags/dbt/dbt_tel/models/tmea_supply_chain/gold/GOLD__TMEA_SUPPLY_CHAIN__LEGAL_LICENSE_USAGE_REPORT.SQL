        PRICE_EACH,
        EXTPRICE,
        ORDER_CURRENCY,
        DELIVERY,
        DEL_ITEM,
        QTY_SHIPPED,
        COMMMODITY_CODE,
        ECCN,
        BOOK_DATE,
        FIRST_DATE,
        CONF_DATE,
        PICK_DATE,
        SHIP_DATE,
        SALES_INV,
        INV_DATE,
        CREATED_BY,
        SERIAL_NUMBER,
        ORDER_DATE,
        MATERIAL_NUMBER,
        DEPARTURE_COUNTRY,
        LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        EXPORT_CONTROL_CLASS,
        GROUPING_FOR_LEGAL_CONTROL,
        SPECIAL_CHARACTERISTICS_CODE_FOR_GOODS,
        INDIVIDUAL_MAINTAINENCE_MATERIAL_MASTER,
        INTERNAL_LICENSE_NUMBER,
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        ITEM_NUMBER,
        EXTERNAL_LICENSE_NUMBER,
        VALIDITY_END_DATE,
        VALIDITY_START_DATE,
        MAXIMUM_LICENSE_VALUE,
        MAXIMUM_LICENSE_QUANTITY,
        NUMBER_OF_SD_DOCUMENT_ASSIGNED_TO_LICENSE,
        EXPORT_CONTROL_CLASS_ACCORDING_THE_LEGAL_REG_FOR_LEGAL_CTRL,
        COUNTRY_OF_DESTINATION,
        KIT_ROOT_PART_NUMBER,
        KIT_MATERIAL_DESCRIPTION,
        KIT_PARENT_PART_NUMBER,
        KIT_CHILD_PART_NUMBER,
        KIT_CHILD_MATERIAL_DESCRIPTION,
        KIT_BOM_ITEM_NUMBER,
        KIT_COMPONENT_QUANTITY,
        KIT_TEL_PRICE,
        KIT_EXT_PRICE,
        LEVEL,
        KIT_INCLUDED,
        REPORT_LINE_ITEM_EXT_QTY,
        REPORT_LINE_ITEM_EXT_PRICE,
    from transform_data
)


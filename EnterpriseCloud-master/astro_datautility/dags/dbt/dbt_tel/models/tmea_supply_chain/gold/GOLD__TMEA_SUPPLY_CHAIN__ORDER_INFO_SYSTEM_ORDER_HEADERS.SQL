WITH STATUS
AS (
	SELECT JSTO.OBJECT_NUMBER,
		JSTO.OBJECT_CATEGORY,
		JEST.OBJECT_STATUS,
		CASE 
			WHEN substr(JEST.OBJECT_STATUS, 1, 1) = 'I'
				THEN TJ02T.INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM
			END AS INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM,
		TJ04.POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY,
		TJ04.STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION,
		ROW_NUMBER() OVER (
			PARTITION BY JSTO.OBJECT_NUMBER ORDER BY JSTO.OBJECT_NUMBER,
				TJ04.POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY,
				TJ04.STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION,
				INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM
			) AS rn
	FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__STATUS_OBJECT_INFORMATION') }}  AS JSTO
	LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__INDIVIDUAL_OBJECT_STATUS') }}  AS JEST ON JEST.OBJECT_NUMBER = JSTO.OBJECT_NUMBER
		AND jest.CLIENT = jsto.CLIENT
	LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__STATUS_CONTROL_FOR_OBJECT_TYPE') }}  AS TJ04 ON TJ04.SYSTEM_STATUS = JEST.OBJECT_STATUS
		AND TJ04.OBJECT_CATEGORY = JSTO.OBJECT_CATEGORY
	LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SYSTEM_STATUS') }}  AS TJ02 ON TJ02.SYSTEM_STATUS = JEST.OBJECT_STATUS
	LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SYSTEM_STATUS_TEXTS') }} AS TJ02T ON TJ02T.SYSTEM_STATUS = TJ02.SYSTEM_STATUS
	WHERE JEST.INDICATOR_STATUS_IS_INACTIVE <> 'X'
		AND TJ02.DO_NOT_DISPLAY_STATUS_FLAG <> 'X'
		AND TJ02T.LANGUAGE_KEY = 'E'
		AND JSTO.OBJECT_CATEGORY = 'ORH'
		AND jSTO.CLIENT = '300'
	),
Str_value
AS (
	SELECT OBJECT_NUMBER,
		CASE 
			WHEN max(rn) > 8
				THEN 'X'
			ELSE ''
			END AS star
	FROM STATUS
	GROUP BY OBJECT_NUMBER
	),
Values_merge
AS (
	SELECT OBJECT_NUMBER,
		listagg(INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM, ' ') within
	GROUP (
			ORDER BY OBJECT_NUMBER,
				POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY,
				STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION,
				INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM
			) AS STATUS
	FROM STATUS
	WHERE rn <= 8
	GROUP BY OBJECT_NUMBER
	),
Status_value
AS (
	SELECT substr(Values_merge.OBJECT_NUMBER, 3, 14) AS OBJECT_NUMBER,
		CASE 
			WHEN str_value.star = 'X'
				THEN CONCAT (
						STATUS,
						' *'
						)
			ELSE STATUS
			END AS STATUS
	FROM Values_merge
	LEFT JOIN str_value ON Values_merge.OBJECT_NUMBER = str_value.OBJECT_NUMBER
	),


with source_data as (
    SELECT 
        AEOI.CHANGE_NUMBER AS CHANGE_NUMBER,
        AEOI.CHANGE_OBJECT AS CHANGE_OBJECT,
        MAKT.MATERIAL_DESCRIPTION AS MATERIAL_DESCRIPTION,
        MARA.MATERIAL_GROUP AS MATERIAL_GROUP,
        T023T.MATERIAL_GROUP_DESCRIPTION AS MATL_GRP_DESC,
        MARC.PURCHASING_GROUP AS PURCHASING_GROUP,
        PURCHORG.DESCRIPTION_OF_PURCHASING_GROUP AS DESCRIPTION_OF_PURCHASING_GROUP,
        MARC.PROCUREMENT_TYPE AS PROCUREMENT_TYPE,
        AEOI.DATE_RECORD_CREATED_ON AS DATE_RECORD_CREATED_ON,
        AEOI.USER_WHO_CREATED_RECORD AS USER_WHO_CREATED_RECORD,
        AEOI.DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED AS DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED,
        AEOI.USER_WHO_LAST_CHANGED_THE_OBJECT AS USER_WHO_LAST_CHANGED_THE_OBJECT
        FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__OBJECT_MANAGEMENT_RECORD') }}  AEOI
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_DESCRIPTIONS') }}  MAKT ON MAKT.MATERIAL_NUMBER = AEOI.CHANGE_OBJECT
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_MATERIAL_DATA') }}   MARA ON MARA.MATERIAL_NUMBER = AEOI.CHANGE_OBJECT
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }}    MARC ON MARC.MATERIAL_NUMBER = AEOI.CHANGE_OBJECT
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_GROUPS') }} AS PURCHORG ON PURCHORG.PURCHASING_GROUP = MARC.PURCHASING_GROUP
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_GROUP_DESCRIPTIONS') }} AS T023T ON T023T.MATERIAL_GROUP = MARA.MATERIAL_GROUP
        WHERE AEOI.OBJECT_CATEGORY = '41'
        AND MARC.PROCUREMENT_TYPE = 'F'
        AND AEOI.CHANGE_OBJECT NOT LIKE 'Z%'
        AND AEOI.CHANGE_OBJECT NOT LIKE 'A%'
        AND AEOI.CHANGE_OBJECT NOT LIKE 'M%'
        AND PURCHORG.DESCRIPTION_OF_PURCHASING_GROUP <> 'UNASIGHNED'
        AND MARC.PURCHASING_GROUP <> 'SPR'
        AND MARC.PURCHASING_GROUP <> 'MFG'
        AND PURCHORG.CLIENT = '300'
        ORDER BY AEOI.DATE_RECORD_CREATED_ON DESC
)

, transform_data as (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH ,
        CHANGE_NUMBER,
        CHANGE_OBJECT,
        MATERIAL_DESCRIPTION,
        MATERIAL_GROUP,
        MATL_GRP_DESC,
        PURCHASING_GROUP,
        DESCRIPTION_OF_PURCHASING_GROUP,
        PROCUREMENT_TYPE,
        DATE_RECORD_CREATED_ON,
        USER_WHO_CREATED_RECORD,
        DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED,
        USER_WHO_LAST_CHANGED_THE_OBJECT
        FROM source_data
)

,type_data as (
    SELECT
    cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(CHANGE_NUMBER AS VARCHAR(16777216)) AS CHANGE_NUMBER,
        CAST(CHANGE_OBJECT AS VARCHAR(16777216)) AS CHANGE_OBJECT,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(120)) AS MATERIAL_DESCRIPTION,
        CAST(MATERIAL_GROUP AS VARCHAR(27)) AS MATERIAL_GROUP,
        CAST(MATL_GRP_DESC AS VARCHAR(16777216)) AS MATL_GRP_DESC,
        CAST(PURCHASING_GROUP AS VARCHAR(9)) AS PURCHASING_GROUP,
        CAST(DESCRIPTION_OF_PURCHASING_GROUP AS VARCHAR(54)) AS DESCRIPTION_OF_PURCHASING_GROUP,
        CAST(PROCUREMENT_TYPE AS VARCHAR(3)) AS PROCUREMENT_TYPE,
        CAST(DATE_RECORD_CREATED_ON AS DATE) AS DATE_RECORD_CREATED_ON,
        CAST(USER_WHO_CREATED_RECORD AS VARCHAR(16777216)) AS USER_WHO_CREATED_RECORD,
        CAST(DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED AS DATE) AS DATE_ON_WHICH_THE_OBJECT_WAS_LAST_CHANGED,
        CAST(USER_WHO_LAST_CHANGED_THE_OBJECT AS VARCHAR(16777216)) AS USER_WHO_LAST_CHANGED_THE_OBJECT
    FROM transform_data
)

SELECT * from type_data
      incremental_strategy='insert_overwrite',
      alias='PURCHASING_PO_CREATED_BY_MONTH',
      transient=false
) }}

WITH source_data as
(
    SELECT DISTINCT EKKO.PURCHASING_DOCUMENT_NUMBER as PURCHASING_DOC_NUM,
    EKKO.DATE_ON_WHICH_RECORD_WAS_CREATED AS CREATE_DATE,
    TO_NUMBER(EKPO.NET_PRICE_IN_PURCHASING_DOCUMENT,10,2) AS NET_PRICE
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_HEADER') }} EKKO
    JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_ITEM') }} EKPO ON EKPO.PURCHASING_DOCUMENT_NUMBER = EKKO.PURCHASING_DOCUMENT_NUMBER
    WHERE EKKO.PURCHASING_DOCUMENT_TYPE = 'NB'
    AND EKKO.PURCHASING_DOC_CATEGORY = 'F'
    AND EKKO.PURCHASING_ORGANIZATION = '0040'
    AND PURCHASING_GROUP = '027'
    AND CREATE_DATE > '2020-04-01'
)

,transform_data as
(
  SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
    PURCHASING_DOC_NUM,
    CREATE_DATE,
    NET_PRICE
  FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(PURCHASING_DOC_NUM AS VARCHAR(30)) AS PURCHASING_DOC_NUM,
        CAST(CREATE_DATE AS TIMESTAMP_LTZ(9)) AS CREATE_DATE,
        CAST(NET_PRICE AS NUMBER(10,2)) AS NET_PRICE
    FROM transform_data
)

SELECT * from type_data
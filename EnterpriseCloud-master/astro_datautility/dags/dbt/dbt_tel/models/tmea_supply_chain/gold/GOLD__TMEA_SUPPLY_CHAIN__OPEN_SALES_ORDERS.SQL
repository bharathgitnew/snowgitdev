WITH OPEN_SALES_ORDERS AS (
    SELECT
        DISTINCT VBEP.client,
        VBAP.ROUTE,
        VS.MATERIAL_NUMBER AS TOOL_ID,
        VBAP.MATERIAL_NUMBER,
        VBAP.SALES_DOCUMENT,
        VBAP.SALES_DOCUMENT_ITEM,
        VBEP.SCHEDULE_LINE_CATEGORY,
        VBAP.REQUIREMENTS_TYPE,
        VBAP.PLANT_OWN_OR_EXTERNAL,
        VBEP.SCHEDULE_LINE_NUMBER,
        VBEP.SCHEDULE_LINE_DATE,
        VBAP.SALES_DOCUMENT_ITEM_CATEGORY,
        VBAP.REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS,
        VBAP.delivery_priority,
        VBAK.DATE_ON_WHICH_RECORD_WAS_CREATED,
        DATEDIFF(
            DAY,
            VBAK.DATE_ON_WHICH_RECORD_WAS_CREATED,
            GETDATE()
        ) AS AGING,
        VBAP.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
        VBEP.ORDER_QUANTITY_IN_SALES_UNITs,
        VBEP.CONFIRMED_QUANTITY,
        VBAK.SALES_DOCUMENT_TYPE,
        VBEP.SCHEDULE_LINE_BLOCKED_FOR_DELIVERY,
        VBEP.ITEM_IS_RELEVANT_FOR_DELIVERY,
        VBAP.NET_PRICE,
        VBAP.short_text_for_sales_order_item AS MATERIAL_DESCRIPTION,
        VBAK.SOLD_TO_PARTY,
        DP.CUSTOMER_NUMBER AS END_USER_FOR_DISTRIBUTION,
        cm.name as END_USER_FOR_DISTRIBUTION_NAME,
        TSCS.NAME,
        tscs.country_key,
        MARC.MRP_CONTROLLER_MATERIALS_PLANNER,
        MC.CONTROLLER_NAME,
        MARC.PROFIT_CENTER,
        MAEX.EXPORT_CONTROL_CLASS,
        MAX(VBEP.SCHEDULE_LINE_DATE) OVER (
            PARTITION BY VBAP.SALES_DOCUMENT,
            VBAP.SALES_DOCUMENT_ITEM
            ORDER BY
                VBEP.SCHEDULE_LINE_DATE DESC ROWS BETWEEN UNBOUNDED PRECEDING
                AND CURRENT ROW
        ) as Max_Date,
        SUM(VBEP.CONFIRMED_QUANTITY) OVER (
            PARTITION BY VBAP.SALES_DOCUMENT,
            VBAP.SALES_DOCUMENT_ITEM
            ORDER BY
                VBEP.SCHEDULE_LINE_DATE desc ROWS BETWEEN UNBOUNDED PRECEDING
                AND CURRENT ROW
        ) AS running_confirmed_qty
    FROM
        {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_ITEM_DATA') }} AS VBAP
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_SCHEDULE_LINE_DATA') }} AS VBEP ON VBAP.SALES_DOCUMENT = VBEP.SALES_DOCUMENT
        AND VBAP.SALES_DOCUMENT_ITEM = VBEP.SALES_DOCUMENT_ITEM --To extract SALES_DOCUMENT_TYPE, DATE_ON_WHICH_RECORD_WAS_CREATED
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_HEADER_DATA') }} AS VBAK ON VBAP.SALES_DOCUMENT = VBAK.SALES_DOCUMENT --// To extract CUSTOMER DATA
        LEFT JOIN {{ ref('GOLD__TMEA_SUPPLY_CHAIN__SPARES_CUSTOMER_SAP') }} AS TSCS ON VBAK.SOLD_TO_PARTY = TSCS.CUSTOMER_NUMBER --// TO EXTRACT MATERIAL PLANNER NUMBER
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} AS MARC ON VBAP.material_number = MARC.material_number
        AND VBAP.PLANT_OWN_OR_EXTERNAL = MARC.PLANT // TO extrac material planner name
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MRP_CONTROLLERS') }} AS MC ON MARC.MRP_CONTROLLER_MATERIALS_PLANNER = MC.mrp_controller
        AND MARC.plant = MC.plant
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PRODUCTION_VALUE_STREAM') }} AS VS ON VBAP.SALES_DOCUMENT = VS.SALES_DOCUMENT
        AND VBAP.SALES_DOCUMENT_ITEM = VBEP.SALES_DOCUMENT_ITEM //WHERE VBEP.SALES_DOCUMENT_ITEM ='000001'
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_MASTER_LEGAL_CONTROL') }} AS MAEX ON MAEX.MATERIAL_NUMBER = VBAP.material_number
        left join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_PARTNER') }} DP ON DP.PARTNER_FUNCTION = 'Z1'
        AND DP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = VBAK.SALES_DOCUMENT
        LEFT JOIN {{ ref('GOLD__TMEA_SUPPLY_CHAIN__SPARES_CUSTOMER_SAP') }} cm on cm.customer_number = dp.customer_number
),
--// Removing Schedule lines created and later deleteted. these lines remain in SALES_DOCUMENT_SCHEDULE_LINE_DATA
Row_change AS (
    SELECT
        DISTINCT CHANGED_TABLE_RECORD_KEY,
        CHANGE_TYPE_U_I_E_D,
        TABLE_NAME
    FROM
        (
            SELECT
                _CAPTUREDATETIME,
                CHANGE_TYPE_U_I_E_D,
                CHANGED_TABLE_RECORD_KEY,
                TABLE_NAME,
                row_number() over(
                    partition by CHANGED_TABLE_RECORD_KEY
                    ORDER BY
                        _CAPTUREDATETIME DESC
                ) AS RowN
            FROM
                {{ ref('SILVER__TMEA_SUPPLY_CHAIN__CHANGE_DOCUMENT_ITEMS') }}
        ) AS SCDI
    WHERE
        TABLE_NAME IN ('VBEP')
        AND RowN = 1
),
--// To extract customer_purchase_order_number
Cust_PO AS (
    SELECT
        DISTINCT sales_and_distribution_document_number,
        VBEP.CUSTOMER_PURCHASE_ORDER_NUMBER
    FROM
        {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_BUSINESS_DATA') }} AS VBKD
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_HEADER_DATA') }} AS VBEP ON VBEP.SALES_DOCUMENT = VBKD.sales_and_distribution_document_number
),
--// Verifying if line has shipped partially or complete
DELIVERY AS (
    SELECT
        DISTINCT LIPS.DELIVERY,
        LIPS.material_number,
        LIPS.DELIVERY_ITEM,
        LIPS.ACTUAL_QUANTITY_DELIVERED_,
        LIPS.DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,
        LIPS.ITEM_NUMBER_OF_THE_REFERENCE_ITEM,
        LIPS.storage_location,
        LIKP.SD_DOCUMENT_CATEGORY,
        LIKP.DATE_ON_WHICH_RECORD_WAS_CREATED AS delivery_date,
        LIPS.is_deleted,
        LIPS.ACTUAL_QUANTITY_DELIVERED_ AS DELIVERED_QTY,
        MAX(LIPS.DELIVERY) OVER (
            PARTITION BY LIPS.material_number,
            LIPS.DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,
            LIPS.ITEM_NUMBER_OF_THE_REFERENCE_ITEM
            ORDER BY
                LIPS.DELIVERY DESC ROWS BETWEEN UNBOUNDED PRECEDING
                AND CURRENT ROW
        ) AS Max_DELIVERY,
        SUM(ACTUAL_QUANTITY_DELIVERED_) over (
            PARTITION BY LIPS.MATERIAL_NUMBER,
            LIPS.DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,
            LIPS.ITEM_NUMBER_OF_THE_REFERENCE_ITEM
            ORDER BY
                LIPS.DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,
                LIPS.ITEM_NUMBER_OF_THE_REFERENCE_ITEM
        ) AS total_DELIVERED
    FROM
        {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SD_DOCUMENT_DELIVERY_ITEM_DATA') }} AS LIPS
        INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SD_DOCUMENT_DELIVERY_HEADER_DATA') }} AS LIKP ON LIPS.DELIVERY = LIKP.DELIVERY
    WHERE
        LIKP.is_deleted = 'No'
        and LIKP.SD_DOCUMENT_CATEGORY = 'J'
        OR LIKP.SD_DOCUMENT_CATEGORY = ' '
        AND STORAGE_LOCATION in ('0010', 'MA01', '0012')
        and OBJECT_NUMBER_AT_ITEM_LEVEL <> ''
),
final AS (
    SELECT
        DISTINCT DELIVERY,
        SALES_ORDERS.TOOL_ID,
        SALES_ORDERS.material_number,
        SALES_ORDERS.ROUTE,
        customer_purchase_order_number,
        SALES_ORDERS.SALES_DOCUMENT,
        SALES_ORDERS.SALES_DOCUMENT_ITEM,
        SALES_ORDERS.SCHEDULE_LINE_NUMBER,
        SALES_ORDERS.SCHEDULE_LINE_DATE,
        SALES_ORDERS.SCHEDULE_LINE_BLOCKED_FOR_DELIVERY,
        SALES_ORDERS.DATE_ON_WHICH_RECORD_WAS_CREATED,
        SALES_ORDERS.AGING,
        SALES_ORDERS.MATERIAL_DESCRIPTION,
        SALES_ORDERS.PROFIT_CENTER,
        SALES_ORDERS.SCHEDULE_LINE_CATEGORY,
        SALES_ORDERS.delivery_priority,
        SALES_ORDERS.SOLD_TO_PARTY,
        SALES_ORDERS.NAME,
        SALES_ORDERS.END_USER_FOR_DISTRIBUTION,
        SALES_ORDERS.END_USER_FOR_DISTRIBUTION_NAME,
        SALES_ORDERS.REQUIREMENTS_TYPE,
        SALES_ORDERS.REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS,
        SALES_ORDERS.SALES_DOCUMENT_TYPE,
        SALES_ORDERS.PLANT_OWN_OR_EXTERNAL,
        SALES_ORDERS.ITEM_IS_RELEVANT_FOR_DELIVERY,
        CAST(CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS AS NUMBER(32, 2)) AS CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
        CAST(CONFIRMED_QUANTITY AS NUMBER(32, 2)) AS CONFIRMED_QUANTITY,
        CAST(CONFIRMED_QUANTITY AS NUMBER(32, 2)) AS OPEN_QTY,
        CAST (SALES_ORDERS.NET_PRICE AS NUMBER(32, 2)) AS NET_PRICE,
        CAST (NET_PRICE * CONFIRMED_QUANTITY AS NUMBER(32, 2)) AS NET_VALUE,
        --//CAST(running_confirmed_qty AS NUMBER(32, 2)) AS running_confirmed_qty,
        CAST(DELIVERY.DELIVERED_QTY AS NUMBER(32, 2)) AS DELIVERED_QTY,
        CAST(total_DELIVERED AS NUMBER(32, 2)) AS total_DELIVERED,
        max_date,
        MAX_delivery,
        MRP_CONTROLLER_MATERIALS_PLANNER,
        CONTROLLER_NAME,
        EXPORT_CONTROL_CLASS,
        country_key,
        CASE
            WHEN CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS = TOTAL_DELIVERED THEN 'Closed'
            WHEN OPEN_QTY = DELIVERED_QTY
            AND SCHEDULE_LINE_DATE < Max_Date
            AND dELIVERY < max_dELIVERY THEN 'Closed'
            WHEN OPEN_QTY = DELIVERED_QTY
            AND dELIVERY < max_dELIVERY THEN 'Closed'
            WHEN OPEN_QTY < DELIVERED_QTY
            AND delivery < max_delivery THEN 'Closed'
            WHEN OPEN_QTY > DELIVERED_QTY
            AND running_confirmed_qty = total_delivered
            and SCHEDULE_LINE_DATE < Max_Date THEN 'Closed'
            WHEN delivered_qty > 0
            and CONFIRMED_QUANTITY = OPEN_QTY
            AND SCHEDULE_LINE_DATE < Max_Date THEN 'Closed'
            ELSE 'Open'
        END AS flag,
        CASE
            WHEN delivery IS NOT null THEN 'Partial'
            ELSE 'All'
        END AS DELIVERY_STATUS,
        CASE
            WHEN CHANGE_TYPE_U_I_E_D <> 'D'
            OR CHANGE_TYPE_U_I_E_D IS null THEN 'Y'
        END AS SCHEDULE_LINE_ACTIVE,
        CASE
            WHEN delivery_priority = 1 THEN '1-Down'
            WHEN delivery_priority = 2 THEN '2-Rush'
            WHEN delivery_priority = 3 THEN '3-Expedite'
            WHEN delivery_priority = 99 THEN '99-Routine'
        END AS DELIVERY_PRIORITY_DESCRIPTION,
        CASE
            WHEN SOLD_TO_PARTY = '0000009369' then 'TEE'
            WHEN SOLD_TO_PARTY = '0000009390' then 'TEA'
            WHEN SOLD_TO_PARTY = '0000009805' then 'TSI'
            WHEN SOLD_TO_PARTY = '0000010061' then 'TEL/TFE'
            WHEN SOLD_TO_PARTY = '0000010102' then 'TES'
            WHEN SOLD_TO_PARTY = '0000009374' then 'TET'
            WHEN SOLD_TO_PARTY = '0000009379' then 'TEK'
            else 'NO GENPO'
        END AS GENPO,
        CASE
            WHEN SCHEDULE_LINE_BLOCKED_FOR_DELIVERY = 'ZG' then 'FT US Entity Block'
            ELSE 'Released'
        END AS Delivery_Block_Status,
        CASE
            WHEN EXPORT_CONTROL_CLASS = 'NOECCN' then 'ITC Block'
            else 'Released'
        END AS EXPORT_BLOCK_STATUS,
        --//"LINE_BLOCK_STATUS"
        case
            when country_key = 'US' then 'Released'
            when SCHEDULE_LINE_BLOCKED_FOR_DELIVERY = 'ZG'
            and EXPORT_CONTROL_CLASS <> 'NOECCN' then 'FT US Entity Block'
            when SCHEDULE_LINE_BLOCKED_FOR_DELIVERY = '02' then 'Administrative Block'
            when EXPORT_CONTROL_CLASS = 'NOECCN'
            and SCHEDULE_LINE_BLOCKED_FOR_DELIVERY <> 'ZG'
            or SCHEDULE_LINE_BLOCKED_FOR_DELIVERY = '02' then 'ITC Block'
            when EXPORT_CONTROL_CLASS = 'NOECCN'
            and SCHEDULE_LINE_BLOCKED_FOR_DELIVERY = 'ZG' then 'Both'
            when SCHEDULE_LINE_BLOCKED_FOR_DELIVERY = ' ' then 'Released'
        end as LINE_BLOCK_STATUS,
        CASE
            WHEN ROUTE like 'FSI%' THEN 'SHORTSHIP'
            WHEN CUSTOMER_PURCHASE_ORDER_NUMBER LIKE 'Short%'
            or CUSTOMER_PURCHASE_ORDER_NUMBER LIKE 'SHORT%' THEN 'SHORTSHIP'
        END AS SHORTSHIP
    FROM
        OPEN_SALES_ORDERS AS SALES_ORDERS
        LEFT JOIN DELIVERY as DELIVERY ON DELIVERY.DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT = SALES_ORDERS.SALES_DOCUMENT
        AND DELIVERY.ITEM_NUMBER_OF_THE_REFERENCE_ITEM = SALES_ORDERS.SALES_DOCUMENT_ITEM
        and SALES_ORDERS.material_number = DELIVERY.material_number //and DELIVERY.ACTUAL_QUANTITY_DELIVERED_ >  SALES_ORDERS.CONFIRMED_QUANTITY
        LEFT JOIN Row_change AS Row_change ON Client || sales_document || sales_document_item || SCHEDULE_LINE_NUMBER = ROW_CHANGE.CHANGED_TABLE_RECORD_KEY
        JOIN Cust_PO AS Cust_PO ON sales_document = Cust_PO.sales_and_distribution_document_number
),
SOURCE_DATA as(
 SELECT DISTINCT *
FROM
    final
WHERE
    DATE_ON_WHICH_RECORD_WAS_CREATED >= '2020-01-01'
    AND SALES_DOCUMENT_TYPE in ('ZSPR', 'ZHOT', 'ZMAC', 'ZUPG')
    AND flag in ('Open')
    AND SCHEDULE_LINE_ACTIVE = 'Y'
    AND CONFIRMED_QUANTITY > 0
    AND PLANT_OWN_OR_EXTERNAL in ('0010')
    AND REQUIREMENTS_TYPE <> 'SE'
    AND SCHEDULE_LINE_CATEGORY not in ('CS')
    AND REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS = ' '
    AND ITEM_IS_RELEVANT_FOR_DELIVERY = 'X'
ORDER BY
    DATE_ON_WHICH_RECORD_WAS_CREATED Desc
),
TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	DELIVERY,
	TOOL_ID,
	MATERIAL_NUMBER,
	ROUTE,
	CUSTOMER_PURCHASE_ORDER_NUMBER,
	SALES_DOCUMENT,
	SALES_DOCUMENT_ITEM,
	SCHEDULE_LINE_NUMBER,
	SCHEDULE_LINE_DATE,
	SCHEDULE_LINE_BLOCKED_FOR_DELIVERY,
	DATE_ON_WHICH_RECORD_WAS_CREATED,
	AGING,
	MATERIAL_DESCRIPTION,
	PROFIT_CENTER,
	SCHEDULE_LINE_CATEGORY,
	DELIVERY_PRIORITY,
	SOLD_TO_PARTY,
	NAME,
	END_USER_FOR_DISTRIBUTION,
	END_USER_FOR_DISTRIBUTION_NAME,
	REQUIREMENTS_TYPE,
	REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS,
	SALES_DOCUMENT_TYPE,
	PLANT_OWN_OR_EXTERNAL,
	ITEM_IS_RELEVANT_FOR_DELIVERY,
	CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
	CONFIRMED_QUANTITY,
	OPEN_QTY,
	NET_PRICE,
	NET_VALUE,
	DELIVERED_QTY,
	TOTAL_DELIVERED,
	MAX_DATE,
	MAX_DELIVERY,
	MRP_CONTROLLER_MATERIALS_PLANNER,
	CONTROLLER_NAME,
	EXPORT_CONTROL_CLASS,
	COUNTRY_KEY,
	FLAG,
	DELIVERY_STATUS,
	SCHEDULE_LINE_ACTIVE,
	DELIVERY_PRIORITY_DESCRIPTION,
	GENPO,
	DELIVERY_BLOCK_STATUS,
	EXPORT_BLOCK_STATUS,
	LINE_BLOCK_STATUS,
	SHORTSHIP

FROM SOURCE_DATA
)

,
TYPE_DATA AS (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	DELIVERY,
	TOOL_ID,
	MATERIAL_NUMBER,
	ROUTE,
	CUSTOMER_PURCHASE_ORDER_NUMBER,
	SALES_DOCUMENT,
	SALES_DOCUMENT_ITEM,
	SCHEDULE_LINE_NUMBER,
	CAST(SCHEDULE_LINE_DATE as DATE) as SCHEDULE_LINE_DATE,
	SCHEDULE_LINE_BLOCKED_FOR_DELIVERY,
	CAST(DATE_ON_WHICH_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_RECORD_WAS_CREATED,
	CAST(AGING as NUMBER(38,0)) as AGING,
	MATERIAL_DESCRIPTION,
	PROFIT_CENTER,
	SCHEDULE_LINE_CATEGORY,
	DELIVERY_PRIORITY,
	SOLD_TO_PARTY,
	NAME,
	END_USER_FOR_DISTRIBUTION,
	END_USER_FOR_DISTRIBUTION_NAME,
	REQUIREMENTS_TYPE,
	REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS,
	SALES_DOCUMENT_TYPE,
	PLANT_OWN_OR_EXTERNAL,
	ITEM_IS_RELEVANT_FOR_DELIVERY,
	CAST(CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS as NUMBER(38,10)) as CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
	CAST(CONFIRMED_QUANTITY as NUMBER(38,10)) as CONFIRMED_QUANTITY,
	CAST(OPEN_QTY as NUMBER(38,10)) as OPEN_QTY,
	CAST(NET_PRICE as NUMBER(38,10)) as NET_PRICE,
	CAST(NET_VALUE as NUMBER(38,10)) as NET_VALUE,
	CAST(DELIVERED_QTY as NUMBER(38,10)) as DELIVERED_QTY,
	CAST(TOTAL_DELIVERED as NUMBER(38,10)) as TOTAL_DELIVERED,
	CAST(MAX_DATE as DATE) as MAX_DATE,
	MAX_DELIVERY,
	MRP_CONTROLLER_MATERIALS_PLANNER,
	CONTROLLER_NAME,
	EXPORT_CONTROL_CLASS,
	COUNTRY_KEY,
	FLAG,
	DELIVERY_STATUS,
	SCHEDULE_LINE_ACTIVE,
	DELIVERY_PRIORITY_DESCRIPTION,
	GENPO,
	DELIVERY_BLOCK_STATUS,
	EXPORT_BLOCK_STATUS,
	LINE_BLOCK_STATUS,
	SHORTSHIP
from transform_data
)
SELECT * FROM TYPE_DATA
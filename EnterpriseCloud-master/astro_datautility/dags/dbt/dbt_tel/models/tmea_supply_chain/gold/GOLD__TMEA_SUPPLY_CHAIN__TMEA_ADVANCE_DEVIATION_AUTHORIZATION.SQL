{{ config(
    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='TMEA_ADVANCE_DEVIATION_AUTHORIZATION',
    	transient=false
) }}

WITH ref_cte_QUALITY_NOTIFICATION as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__QUALITY_NOTIFICATION') }}
),



source_data as (

SELECT 
NOTIFICATION_NO AS ADA_NUMBER,
NOTIFICATION_TYPE,
SHORT_TEXT,
purchasing_group,
PRIORITY_TYPE,
PRIORITY, 
DATE_ON_WHICH_RECORD_WAS_CREATED AS ADA_CREATION_DATE,
MATERIAL_NUMBER,
MATERIAL_GROUP,
VENDOR_ACCOUNT_NUMBER,
PLANT_FOR_MATERIAL,
CODE_GROUP_CODING,
CODING, 
concat(material_number,vendor_account_number) AS PrimaryKey

FROM ref_cte_QUALITY_NOTIFICATION
WHERE NOTIFICATION_TYPE = 'AD'
AND DATE_ON_WHICH_RECORD_WAS_CREATED > '2019-12-31'),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH ,
	ADA_NUMBER,
	NOTIFICATION_TYPE,
	SHORT_TEXT,
	PURCHASING_GROUP,
	PRIORITY_TYPE,
	PRIORITY,
	ADA_CREATION_DATE,
	MATERIAL_NUMBER,
	MATERIAL_GROUP,
	VENDOR_ACCOUNT_NUMBER,
	PLANT_FOR_MATERIAL,
	CODE_GROUP_CODING,
	CODING,
	PRIMARYKEY
from source_data
),

type_data as (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
	CAST(ADA_NUMBER as VARCHAR(16777216)) as ADA_NUMBER,
	CAST(NOTIFICATION_TYPE as VARCHAR(16777216)) as NOTIFICATION_TYPE,
	CAST(SHORT_TEXT as VARCHAR(16777216)) as SHORT_TEXT,
	CAST(PURCHASING_GROUP as VARCHAR(16777216)) as PURCHASING_GROUP,
	CAST(PRIORITY_TYPE as VARCHAR(16777216)) as PRIORITY_TYPE,
	CAST(PRIORITY as VARCHAR(16777216)) as PRIORITY,
	CAST(ADA_CREATION_DATE as DATE) as ADA_CREATION_DATE,
	CAST(MATERIAL_NUMBER as VARCHAR(16777216)) as MATERIAL_NUMBER,
	CAST(MATERIAL_GROUP as VARCHAR(16777216)) as MATERIAL_GROUP,
	CAST(VENDOR_ACCOUNT_NUMBER as VARCHAR(16777216)) as VENDOR_ACCOUNT_NUMBER,
	CAST(PLANT_FOR_MATERIAL as VARCHAR(16777216)) as PLANT_FOR_MATERIAL,
	CAST(CODE_GROUP_CODING as VARCHAR(16777216)) as CODE_GROUP_CODING,
	CAST(CODING as VARCHAR(16777216)) as CODING,
	CAST(PRIMARYKEY as VARCHAR(16777216)) as PRIMARYKEY
from transform_data 
)
select * from type_data
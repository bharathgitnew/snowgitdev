{{ config(
    	materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
    	alias = 'PURCHASING_DISPLAY_WAREHOUSE_STOCKS_OF_MATERIALS',
        transient = false
) }}

with source_data as (
    SELECT  
        MARD.PLANT,
	    MARA.MATERIAL_NUMBER,
	    MARD.STORAGE_LOCATION,
	    MARA.BASE_UNIT_OF_MEASURE,
	    MARD.VALUATED_UNRESTRICTED_USE_STOCK as UNRESTRICTED,
	    MBEW.VALUE_OF_TOTAL_VALUATED_STOCK,
	    MARD.STOCK_IN_QUALITY_INSPECTION as IN_QUALITY_INSP,
	    MARD.TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES as RESTRICTED_USE_STOCK,
	    MARD.BLOCKED_STOCK as BLOCKED,
	    MARD.BLOCKED_STOCK_RETURNS as RETURNS,
	    MARC.PURCHASING_GROUP,
	    T024.DESCRIPTION_OF_PURCHASING_GROUP
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__STORAGE_LOCATION_DATA_FOR_MATERIAL') }} MARD
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_VALUATION') }} MBEW ON MARD.MATERIAL_NUMBER = MBEW.MATERIAL_NUMBER
    	AND MARD.PLANT = MBEW.VALUATION_AREA
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC ON MARD.MATERIAL_NUMBER = MARC.MATERIAL_NUMBER
    	AND MARD.PLANT = MARC.PLANT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_MATERIAL_DATA') }} MARA ON MARD.MATERIAL_NUMBER = MARA.MATERIAL_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANTS') }} T001W ON MARD.PLANT = T001W.PLANT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_GROUPS') }} T024 ON MARC.PURCHASING_GROUP = T024.PURCHASING_GROUP
    WHERE MARD.PLANT = '0010' and  T024.CLIENT = '300'
	AND MARC.PURCHASING_GROUP IN (
		'002',
		'003',
		'007',
		'008',
		'013',
		'025',
		'026',
		'027',
		'028',
		'029'
		)  
        AND MBEW.VALUATION_TYPE <>''
),

transform_data as (
    SELECT  
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, 
        PLANT,
	    MATERIAL_NUMBER,
	    STORAGE_LOCATION,
	    BASE_UNIT_OF_MEASURE,
	    UNRESTRICTED,
	    VALUE_OF_TOTAL_VALUATED_STOCK,
	    IN_QUALITY_INSP,
	    RESTRICTED_USE_STOCK,
	    BLOCKED,
	    RETURNS,
	    PURCHASING_GROUP,
	    DESCRIPTION_OF_PURCHASING_GROUP
    FROM source_data
)

,type_data as (
    SELECT
	cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(MATERIAL_NUMBER AS VARCHAR(54)) AS MATERIAL_NUMBER,
        CAST(STORAGE_LOCATION AS VARCHAR(16777216)) AS STORAGE_LOCATION,
        CAST(BASE_UNIT_OF_MEASURE AS VARCHAR(9)) AS BASE_UNIT_OF_MEASURE,
        CAST(UNRESTRICTED AS NUMBER(38,10)) AS UNRESTRICTED,
        CAST(VALUE_OF_TOTAL_VALUATED_STOCK AS NUMBER(38,10)) AS VALUE_OF_TOTAL_VALUATED_STOCK,
        CAST(IN_QUALITY_INSP AS NUMBER(38,10)) AS IN_QUALITY_INSP,
        CAST(RESTRICTED_USE_STOCK AS NUMBER(38,10)) AS RESTRICTED_USE_STOCK,
        CAST(BLOCKED AS NUMBER(38,10)) AS BLOCKED,
        CAST(RETURNS AS NUMBER(38,10)) AS RETURNS,
        CAST(PURCHASING_GROUP AS VARCHAR(16777216)) AS PURCHASING_GROUP,
        CAST(DESCRIPTION_OF_PURCHASING_GROUP AS VARCHAR(54)) AS DESCRIPTION_OF_PURCHASING_GROUP
    FROM transform_data
)

SELECT * from type_data
with ODS_COMMON_HISTORY_PER_PURCHASING_DOCUMENT as (
  SELECT
    CLIENT,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    NUMBER_OF_MATERIAL_DOCUMENT,
    PURCHASING_DOCUMENT_NUMBER,
    QUANTITY as RCPT_QTY,
    POSTING_DATE_IN_THE_DOCUMENT as RECEIPT_DATE,
    NAME_OF_PERSON_WHO_CREATED_THE_OBJECT as RECEIPT_USER,
    Sum(QUANTITY) Over (
      Partition By PURCHASING_DOCUMENT_NUMBER,
      ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
      CLIENT,
      MATERIAL_NUMBER
      Order By
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        MATERIAL_NUMBER,
        POSTING_DATE_IN_THE_DOCUMENT Rows Between Unbounded Preceding
        And Current Row
    ) as TOTAL_RCPT_QTY
  FROM
    {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HISTORY_PER_PURCHASING_DOCUMENT') }}
  WHERE
    CLIENT = 300
    AND PURCHASE_ORDER_HISTORY_CATEGORY = 'E'
    And TRANS_EVENT_TYPE = '1'
    And MOVEMENT_TYPE in ( '101')
    and NUMBER_OF_MATERIAL_DOCUMENT not in ( select DOCUMENT_NO_OF_A_REFERENCE_DOCUMENT as NUMBER_OF_MATERIAL_DOCUMENT from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__DOCUMENT_SEGMENT_MATERIAL') }}
                                 where Movement_Type_Inventory_Management in ('102') and   CLIENT = 300 and PURCHASE_ORDER_NUMBER <> ''
                             )
),





ODS_COMMON_PURCHASING_INFO_RECORD_PURCHASING_ORGANIZATION_DATA as (
  SELECT
     PLANT,
     PLANNED_DELIVERY_TIME_IN_DAYS AS PO_ITEM_LEAD_TIME,
     NUMBER_OF_PURCHASING_INFO_RECORD
  from
    {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_INFO_RECORD_PURCHASING_ORGANIZATION_DATA') }}

    NEED_DATE,
    NEED_QTY,
    RECEIPT_DATE,
    RCPT_QTY,
    PURCH_GROUP,
    BUYER_NAME,
    PO_ITEM_LEAD_TIME,
    EXPORT_CLASS_CONTROL,
    REQUESTED_DELIVERY_TIME_DAYS,
    SUGGESTED_PO_DATE,
    PO_PLACED_WITHIN_LEAD_TIME,
    RECEIPT_MEETS_NEED_DATE,
    DAYS_INSIDE_LEAD_TIME,
    EXPECTED_RECEIPT_DATE,
    RECEIPT_BEYOND_LEAD_TIME,
    DAYS_BEYOND_LEAD_TIME,
    VENDOR_CONFIRMATION_DATE,
    VENDOR_CONFIRMATION_QTY,
    CONFIRMATION_MEETS_NEED_DATE,
    RECEIPT_MEETS_CONFIRMED_DATE,
    MATERIAL_DOCUMENT_NUMBER,
    SEQUENCE_NUMBER,
    NET_PRICE_IN_PURCHASING_DOC,
    MATERIAL_GROUP,
    MATL_GRP_DESC,
    SYSTEM_LEAD_TIME
  FROM
    source_data
)

source_data as (
  SELECT
    RECEIPT_USER,
    VENDOR,
    VENDOR_NAME,
    PURCHASE_ORDER,
    PO_LINE_ITEM,
    PO_CREATE_DATE,
    PO_QTY,
    MATERIAL,
    MATERIAL_DESCRIPTION,
    PRODUCT_LINE,
    NEED_DATE AS "NEED_DATE",
    CASE WHEN QUANTITY_AS_PER_VENDOR_CONFIRMATION IS NULL THEN NEED_QTY ELSE QUANTITY_AS_PER_VENDOR_CONFIRMATION END AS "NEED_QTY",
    RECEIPT_DATE,
    RCPT_QTY,
    PURCH_GROUP,
    BUYER_NAME,
    PO_ITEM_LEAD_TIME,
    EXPORT_CLASS_CONTROL,
    DATEDIFF('DAY', PO_CREATE_DATE, NEED_DATE) AS "REQUESTED_DELIVERY_TIME_DAYS",
    DATEADD(
      'DAY',-1 * PO_ITEM_LEAD_TIME,
      NEED_DATE
    )
    AS "SUGGESTED_PO_DATE",
    CASE WHEN SUGGESTED_PO_DATE < PO_CREATE_DATE THEN 'Y' ELSE 'N' END AS "PO_PLACED_WITHIN_LEAD_TIME",
    CASE WHEN RECEIPT_DATE <= NEED_DATE THEN 'Y' ELSE 'N' END AS "RECEIPT_MEETS_NEED_DATE",
    DATEDIFF(
      'DAY', PO_CREATE_DATE, SUGGESTED_PO_DATE
    ) AS "DAYS_INSIDE_LEAD_TIME",
    DATEADD(
      'DAY', PO_ITEM_LEAD_TIME,
      PO_CREATE_DATE
    )
    AS "EXPECTED_RECEIPT_DATE",
    CASE WHEN EXPECTED_RECEIPT_DATE < RECEIPT_DATE THEN 'Y' ELSE 'N' END AS "RECEIPT_BEYOND_LEAD_TIME",
    DATEDIFF(
      DAY, RECEIPT_DATE, EXPECTED_RECEIPT_DATE
    ) AS "DAYS_BEYOND_LEAD_TIME",
    CASE WHEN CONFIRMATION_CATEGORY IN ('AB', 'LA') THEN VC.DELIVERY_DATE_OF_VENDOR_CONFIRMATION ELSE ITEM_DELIVERY_DATE END AS "VENDOR_CONFIRMATION_DATE",
    CASE WHEN CONFIRMATION_CATEGORY IN ('AB', 'LA') THEN VC.QUANTITY_AS_PER_VENDOR_CONFIRMATION ELSE NEED_QTY END AS "VENDOR_CONFIRMATION_QTY",
    CASE WHEN VENDOR_CONFIRMATION_DATE <= NEED_DATE THEN 'Y' ELSE 'N' END AS "CONFIRMATION_MEETS_NEED_DATE",
    CASE WHEN RECEIPT_DATE <= VENDOR_CONFIRMATION_DATE THEN 'Y' ELSE 'N' END AS "RECEIPT_MEETS_CONFIRMED_DATE",
    NUMBER_OF_MATERIAL_DOCUMENT as MATERIAL_DOCUMENT_NUMBER,
    SEQ_NUM as SEQUENCE_NUMBER,
    NET_PRICE_IN_PURCHASING_DOC,
    MATERIAL_GROUP,
    MATL_GRP_DESC,
    SYSTEM_LEAD_TIME
  FROM
    (
      SELECT
        HPD.CLIENT,
        HPD.RECEIPT_USER,
        VC.DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
        VC.QUANTITY_AS_PER_VENDOR_CONFIRMATION,
        PDH.VENDOR_ACCOUNT_NUM,
        VM.VENDOR,
        VM.VENDOR_NAME,
        PDI.PURCHASE_ORDER,
        PDI.PO_LINE_ITEM,
        PDH.PO_CREATE_DATE,
        PDI.PO_QTY,
        PDI.MATERIAL,
        MATERIAL_DESCRIPTION,
        PCD.LONG_TEXT AS "PRODUCT_LINE",
        HPD.RECEIPT_DATE,
        HPD.RCPT_QTY,
        MPT.PURCHASING_GROUP AS "PURCH_GROUP",
        EINE.PO_ITEM_LEAD_TIME,
        MPT.EXPORT_CLASS_CONTROL,
        PO.BUYER_NAME,
        HPD.TOTAL_RCPT_QTY,
        VC.TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION,
        VC.CONFIRMATION_CATEGORY,
        RANK() OVER (
          PARTITION BY HPD.CLIENT,
          PDI.PURCHASE_ORDER,
          PDI.PO_LINE_ITEM
          ORDER BY
            CASE WHEN CONFIRMATION_CATEGORY = 'LA' THEN 1 WHEN CONFIRMATION_CATEGORY = 'AB' THEN 2 ELSE 3 END
        ) AS CONFIRMATION_CATEGORY_PRIORITY_FORDATE,
        HPD.NUMBER_OF_MATERIAL_DOCUMENT,
        PDI.SEQ_NUM,
        PDI.NET_PRICE_IN_PURCHASING_DOC,
        PDI.MATERIAL_GROUP,
        MG.MATERIAL_GROUP_DESCRIPTION as MATL_GRP_DESC,
        MPT.SYSTEM_LEAD_TIME
      FROM

       ODS_COMMON_HISTORY_PER_PURCHASING_DOCUMENT HPD ---EKBE
        INNER JOIN ODS_COMMON_PURCHASING_DOCUMENT_ITEM PDI ON PDI.PURCHASE_ORDER = HPD.PURCHASING_DOCUMENT_NUMBER
        AND HPD.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = PDI.PO_LINE_ITEM
        AND HPD.CLIENT = PDI.CLIENT ---EKPO
        INNER JOIN ODS_COMMON_PURCHASING_DOCUMENT_HEADER PDH ON PDH.PURCHASING_DOC_NUM = PDI.PURCHASE_ORDER
        AND PDI.CLIENT = PDH.CLIENT -----EKKO

        LEFT JOIN ODS_COMMON_VENDOR_CONFIRMATION VC ON VC.PURCHASING_DOC_NUM = PDI.PURCHASE_ORDER
        AND VC.ITEM_NUM_PURCHASING_DOC = PDI.PO_LINE_ITEM
        AND HPD.CLIENT = VC.CLIENT --EKES


        LEFT JOIN ODS_COMMON_VENDOR_MANAGEMENT VM ON VM.VENDOR = PDH.VENDOR_ACCOUNT_NUM
        AND HPD.CLIENT = VM.CLIENT --LFA1

		LEFT JOIN ODS_COMMON_MATERIAL_PLANT AS MPT ON PDI.MATERIAL = MPT.MATERIAL_NUMBER
        AND PDI.PLANT = MPT.PLANT
        AND PDI.CLIENT = MPT.CLIENT
        LEFT JOIN ODS_COMMON_PROFIT_CENTER PCD ON PCD.PROFT_CNTR_ID = MPT.PROFIT_CENTER
        AND HPD.CLIENT = PCD.CLIENT --CEPCT
        LEFT JOIN ODS_COMMON_PURCHASING_ORGANIZATIONS PO ON PO.PURCHASING_GROUP = MPT.PURCHASING_GROUP
        AND HPD.CLIENT = PO.CLIENT --T024
        LEFT JOIN ODS_COMMON_MATERIAL_GROUP_DESCRIPTIONS MG ON MG.MATERIAL_GROUP = PDI.MATERIAL_GROUP
        AND MG.CLIENT = PDI.CLIENT
       LEFT JOIN ODS_COMMON_PURCHASING_INFO_RECORD_PURCHASING_ORGANIZATION_DATA EINE ON EINE.NUMBER_OF_PURCHASING_INFO_RECORD =  PDI.NUM_OF_PURCHASING_INFO_RECORD
                  AND  EINE.PLANT =  PDI.PLANT
         where
      (case when vc.SEQ_NUM_OF_VENDOR_CONFIRMATION is NULL then 1 else 0 end or vc.TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION >= HPD.TOTAL_RCPT_QTY)
       qualify(row_number() over(partition by HPD.PURCHASING_DOCUMENT_NUMBER,HPD.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,HPD.TOTAL_RCPT_QTY order by  vc.TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION))= 1
    ) VC
    LEFT JOIN ODS_COMMON_SCHEDULING_AGREEMENT_SCHEDULE_LINES SASL ON SASL.PURCHASING_DOCUMENT_NUMBER = VC.PURCHASE_ORDER
    AND SASL.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = VC.PO_LINE_ITEM
    AND VC.CLIENT = SASL.CLIENT --EKET

WHERE

    (

      (
        (
          (
            TOTAL_RCPT_QTY - RCPT_QTY = 0
            AND TOTAL_NEED_QTY - NEED_QTY = 0
          )
          OR (            TOTAL_RCPT_QTY - RCPT_QTY >= TOTAL_NEED_QTY - NEED_QTY
          )
        )
        AND TOTAL_RCPT_QTY <= TOTAL_NEED_QTY
      )
      OR (
        (
          TOTAL_RCPT_QTY - RCPT_QTY < TOTAL_NEED_QTY
        )
        AND (
          TOTAL_RCPT_QTY > TOTAL_NEED_QTY - NEED_QTY
          AND TOTAL_RCPT_QTY - RCPT_QTY >= TOTAL_NEED_QTY - NEED_QTY
        )
      )
    )
    AND
  CONFIRMATION_CATEGORY_PRIORITY_FORDATE = 1
  and purchase_order not like 'PO%'
  and purchase_order not like 'E%'
),
transform_data as (

        materialized='tel_incremental',
        incremental_strategy='merge',
        alias = 'SHORTAGE_REPORT_DATA_WAREHOUSE_HISTORICAL',
		unique_key = ['LATEST_UPDATE_DATE'],
        transient = false
) }}

WITH source_data AS (
    SELECT * exclude (_AUDIT_LOG_ID, _ROW_HASH )
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SHORTAGE_REPORT_DATA_WAREHOUSE') }} 
    ),
transform_data AS (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
	    SHA2('hash_me') as _ROW_HASH,
        current_timestamp() as LATEST_UPDATE_DATE,
        *
    from source_data
    ),
type_data AS (
    SELECT 
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(LATEST_UPDATE_DATE as TIMESTAMP_LTZ(9)) as LATEST_UPDATE_DATE,
		CLIENT,
		SALES_ORDER_NUMBER_SORT_SEQUENCE,
		REPORT_DATE,
		cast(HIERARCHY_LEVEL as NUMBER(38,10)) as HIERARCHY_LEVEL,
		MATERIAL_LEVEL,
		MATERIAL_NUMBER,
		MATERIAL_DESCRIPTION,
		PARENT_MAT_MATERIAL_NUMBER,
		PARENT_MAKTX_MATERIAL_DESCRIPTION,
		PLANT,
		RECEIPT_REQUIREMENTS_DATE,
		MRP_ELEMENT_NUMBER,
		MRP_ELEMENT_ITEM,
		SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
		cast(QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED as NUMBER(38,10)) as QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
		BASE_UNIT_OF_MEASURE,
		DELNR_MRP_ELEMENT_NUMBER,
		DELPS_MRP_ELEMENT_ITEM,
		DAT00_RECEIPT_REQUIREMENTS_DATE,
		MRP_ELEMENT_DATA,
		ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		VENDOR_NAME,
		ABBREVIATION_FOR_MRP_ELEMENT,
		ITEM_DELIVERY_DATE,
		DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
		EINDT_LAST_DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
		TEXT_LINE,
		PRTXT_TEXT_LINE,
		EXCEPTION_MESSAGE_PRIORITY,
		EXCEPTION_MESSAGE_KEY,
		EXCEPTION_MESSAGE_TEXT,
		AUSSL_EXCEPTION_MESSAGE_KEY,
		AUSLTSTK_EXCEPTION_MESSAGE_TEXT,
		CROSS_PLANT_MATERIAL_STATUS,
		PLANT_SPECIFIC_MATERIAL_STATUS,
		MRP_CONTROLLER,
		NAME_OF_MRP_CONTROLLER,
		PROCUREMENT_TYPE,
		cast(SAFETY_STOCK as NUMBER(38,10)) as SAFETY_STOCK,
		cast(TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS as DEC ) as TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS,
		cast(PLANNED_DELIVERY_TIME_IN_DAYS as DEC ) as PLANNED_DELIVERY_TIME_IN_DAYS,
		cast(VALUATED_UNRESTRICTED_USE_STOCK as NUMBER(38,10)) as VALUATED_UNRESTRICTED_USE_STOCK,
		cast(STOCK_IN_QUALITY_INSPECTION as NUMBER(38,10)) as STOCK_IN_QUALITY_INSPECTION,
		cast(TOTAL_OF_PLANNED_ISSUES as NUMBER(38,10)) as TOTAL_OF_PLANNED_ISSUES,
		cast(PURCHASE_REQUISITIONS as NUMBER(38,10)) as PURCHASE_REQUISITIONS,
		cast(PURCHASE_ORDERS as NUMBER(38,10)) as PURCHASE_ORDERS,
		cast(PRSHORT_TOTAL_OF_PLANNED_ISSUES as NUMBER(38,10)) as PRSHORT_TOTAL_OF_PLANNED_ISSUES,
		cast(POSHORT_TOTAL_OF_PLANNED_ISSUES as NUMBER(38,10)) as POSHORT_TOTAL_OF_PLANNED_ISSUES,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME
	 from transform_data
    )


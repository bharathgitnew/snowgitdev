{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'PURCHASING_METRIC_REQ_TO_PO_TAT',
        transient = false
) }}

with source_data as (
    SELECT 
        EKPO.PLANT,
        EBAN.PURCHASING_GROUP,
        EBAN.PURCHASING_ORGANIZATION,
        EKPO.MATERIAL_GROUP,
        MARC.PROCUREMENT_TYPE,
        EKPO.STORAGE_LOCATION,
        MARC.PROFIT_CENTER,
        LFA1.NAME_1 AS VENDOR_NAME,
        EBAN.PURCHASE_ORDER_NUMBER,
        EBAN.PURCHASE_ORDER_ITEM_NUMBER,
        EKPO.PURCHASE_REQUISITION_NUMBER as PURCHASE_REQUISITION_NUM,
        EKPO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT as ITEM_NUM_OF_PURCHASE_REQUISITION,
        EBAN.MRP_CONTROLLER,
        EKPO.MATERIAL_NUMBER as MATERIAL_NUM,
        EKPO.SHORT_TEXT,
        EKPO.NAME_OF_REQUISITIONER_REQUESTER AS NAME_OF_REQUISITIONER_REQUESTER_CREATED_BY,
        EBAN.DELETION_INDICATOR_IN_PURCHASING_DOCUMENT AS DELETION_IND,
        EBAN.ITEM_DELIVERY_DATE AS DELIVERY_DATE,
        EBAN.PURCHASE_REQUISITION_RELEASE_DATE AS RELEASE_DATE,
        EKPO.PURCHASING_DOCUMENT_ITEM_CHANGE_DATE AS PO_ITEM_CHANGE_DATE,
        EBAN.PURCHASING_DOCUMENT_CREATION_DATE AS PURCHASE_REQ_CREATE_DATE,
        EBAN.DATE_OF_LAST_CHANGE AS PURCHASE_REQ_CHANGED_ON,
        EBAN.ITEM_DELIVERY_DATE AS ITEM_DELIVERY_DATE,
        EBAN.PURCHASE_ORDER_DATE AS PURCHASE_ORDER_DATE,
        DATEDIFF(
            DAY,
            PURCHASE_ORDER_DATE,
            PURCHASE_REQ_CREATE_DATE
        ) AS DAYS_DIFF,
        MARC.PLANNED_DELIVERY_TIME_IN_DAYS,
        MARC.GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS,
        MARC.IN_HOUSE_PRODUCTION_TIME,
        MARC.TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_ITEM') }} EKPO
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASE_REQUISITION') }} EBAN ON EBAN.PURCHASE_REQUISITION_NUMBER = EKPO.PURCHASE_REQUISITION_NUMBER
        AND EBAN.ITEM_NUMBER_OF_PURCHASE_REQUISITION = EKPO.ITEM_NUMBER_OF_PURCHASE_REQUISITION
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_HEADER') }} EKKO ON EKKO.PURCHASING_DOCUMENT_NUMBER = EKPO.PURCHASING_DOCUMENT_NUMBER
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__VENDOR_MASTER') }} LFA1 ON LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR = EKKO.VENDORS_ACCOUNT_NUMBER
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC ON EKPO.MATERIAL_NUMBER = MARC.MATERIAL_NUMBER
        AND EKPO.PLANT = MARC.PLANT
    WHERE NULLIF(EKPO.PURCHASE_REQUISITION_NUMBER, '') IS NOT NULL
        AND EKPO.PLANT = '0010'
        AND DAYS_DIFF IS NOT NULL
    ORDER BY EKPO.PURCHASE_REQUISITION_NUMBER DESC
)

, transform_data as (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        PLANT,
        PURCHASING_GROUP,
        PURCHASING_ORGANIZATION,
        MATERIAL_GROUP,
        PROCUREMENT_TYPE,
        STORAGE_LOCATION,
        PROFIT_CENTER,
        VENDOR_NAME,
        PURCHASE_ORDER_NUMBER,
        PURCHASE_ORDER_ITEM_NUMBER,
        PURCHASE_REQUISITION_NUM,
        ITEM_NUM_OF_PURCHASE_REQUISITION,
        MRP_CONTROLLER,
        MATERIAL_NUM,
        SHORT_TEXT,
        NAME_OF_REQUISITIONER_REQUESTER_CREATED_BY,
        DELETION_IND,
        DELIVERY_DATE,
        RELEASE_DATE,
        PO_ITEM_CHANGE_DATE,
        PURCHASE_REQ_CREATE_DATE,
        PURCHASE_REQ_CHANGED_ON,
        ITEM_DELIVERY_DATE,
        PURCHASE_ORDER_DATE,
        DAYS_DIFF,
        PLANNED_DELIVERY_TIME_IN_DAYS,
        GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS,
        IN_HOUSE_PRODUCTION_TIME,
        TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS
    FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(PLANT AS VARCHAR(12)) AS PLANT,
        CAST(PURCHASING_GROUP AS VARCHAR(16777216)) AS PURCHASING_GROUP,
        CAST(PURCHASING_ORGANIZATION AS VARCHAR(16777216)) AS PURCHASING_ORGANIZATION,
        CAST(MATERIAL_GROUP AS VARCHAR(27)) AS MATERIAL_GROUP,
        CAST(PROCUREMENT_TYPE AS VARCHAR(3)) AS PROCUREMENT_TYPE,
        CAST(STORAGE_LOCATION AS VARCHAR(12)) AS STORAGE_LOCATION,
        CAST(PROFIT_CENTER AS VARCHAR(30)) AS PROFIT_CENTER,
        CAST(VENDOR_NAME AS VARCHAR(105)) AS VENDOR_NAME,
        CAST(PURCHASE_ORDER_NUMBER AS VARCHAR(16777216)) AS PURCHASE_ORDER_NUMBER,
        CAST(PURCHASE_ORDER_ITEM_NUMBER AS VARCHAR(16777216)) AS PURCHASE_ORDER_ITEM_NUMBER,
        CAST(PURCHASE_REQUISITION_NUM AS VARCHAR(30)) AS PURCHASE_REQUISITION_NUM,
        CAST(ITEM_NUM_OF_PURCHASE_REQUISITION AS VARCHAR(15)) AS ITEM_NUM_OF_PURCHASE_REQUISITION,
        CAST(MRP_CONTROLLER AS VARCHAR(16777216)) AS MRP_CONTROLLER,
        CAST(MATERIAL_NUM AS VARCHAR(54)) AS MATERIAL_NUM,
        CAST(SHORT_TEXT AS VARCHAR(120)) AS SHORT_TEXT,
        CAST(NAME_OF_REQUISITIONER_REQUESTER_CREATED_BY AS VARCHAR(36)) AS NAME_OF_REQUISITIONER_REQUESTER_CREATED_BY,
        CAST(DELETION_IND AS VARCHAR(16777216)) AS DELETION_IND,
        CAST(DELIVERY_DATE AS TIMESTAMP_LTZ(9)) AS DELIVERY_DATE,
        CAST(RELEASE_DATE AS TIMESTAMP_LTZ(9)) AS RELEASE_DATE,
        CAST(PO_ITEM_CHANGE_DATE AS TIMESTAMP_LTZ(9)) AS PO_ITEM_CHANGE_DATE,
        CAST(PURCHASE_REQ_CREATE_DATE AS TIMESTAMP_LTZ(9)) AS PURCHASE_REQ_CREATE_DATE,
        CAST(PURCHASE_REQ_CHANGED_ON AS TIMESTAMP_LTZ(9)) AS PURCHASE_REQ_CHANGED_ON,
        CAST(ITEM_DELIVERY_DATE AS TIMESTAMP_LTZ(9)) AS ITEM_DELIVERY_DATE,
        CAST(PURCHASE_ORDER_DATE AS TIMESTAMP_LTZ(9)) AS PURCHASE_ORDER_DATE,
        CAST(DAYS_DIFF AS NUMBER(9,0)) AS DAYS_DIFF,
        CAST(PLANNED_DELIVERY_TIME_IN_DAYS AS NUMBER(38,10)) AS PLANNED_DELIVERY_TIME_IN_DAYS,
        CAST(GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS AS NUMBER(38,10)) AS GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS,
        CAST(IN_HOUSE_PRODUCTION_TIME AS NUMBER(38,10)) AS IN_HOUSE_PRODUCTION_TIME,
        CAST(TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS AS NUMBER(38,10)) AS TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS
    FROM transform_data
)

SELECT * from type_data
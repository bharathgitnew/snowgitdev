with source_data as
(
    select 
        MAKT.MATERIAL_DESCRIPTION as MATERIAL_DESCRIPTION,
        MAKT.MATERIAL_NUMBER as MATERIAL_NUMBER,
        MDTB.RECEIPT_REQUIREMENTS_DATE as RECEIPT_REQUIREMENTS_DATE,
        MDKP.MRP_DATE as MRP_DATE,
        MDTB.PROCUREMENT_TYPE as PROCUREMENT_TYPE,
        MARC.Planned_Delivery_Time_in_Days as PLANNED_DELIVERY_TIME_IN_DAYS,
        MDKP.PLANT_STOCK_ONLY_PLANT_SEGMENT as PLANT_STOCK_ONLY_PLANT_SEGMENT,
        MDTB.MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY as MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        MDTB.MRP_ELEMENT as MRP_ELEMENT,
        MDTB.MRP_ELEMENT_NUMBER as MRP_ELEMENT_NUMBER,
        MDTB.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED as QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        MDTB.SHORTAGE_QUANTITY as SHORTAGE_QUANTITY,
        MARC.Safety_Stock as SAFETY_STOCK,
        MAKT.LANGUAGE_KEY as LANGUAGE_KEY,
        MARC.Plant as PLANT,
        MARC.ABC_Indicator as ABC_INDICATOR,
        MARC.Purchasing_Group as PURCHASING_GROUP,
        MARC.MRP_Type as MRP_TYPE,
        MARC.Reorder_Point as REORDER_POINT,
        MARC.Minimum_Lot_Size as MINIMUM_LOT_SIZE,
        MARC.Maximum_stock_level as MAXIMUM_STOCK_LEVEL,
        MARC.Profit_Center as PROFIT_CENTER,
        MARC.Indicator_Bulk_Material as INDICATOR_BULK_MATERIAL,
        MDTB.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE as NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        MDTB.ITEM_NUMBER_OF_MRP_LIST as ITEM_NUMBER_OF_MRP_LIST,
        MDKP.TYPE_OF_MRP_LIST as TYPE_MRP_LIST,
        MDKP.PLANNING_SCENARIO_LONG_TERM_PLANNING as PLANNING_SCENARIO_LONG_TERM_PLANNING,
        case
        when mdtb.MRP_ELEMENT in ('AR','FE', 'MR', 'PP', 'SB','VC','BB','UL')
        then QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED * -1
        else QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
        end as QTY_RECEIVED,
        case
        when mdtb.MRP_ELEMENT in ('AR','FE', 'MR', 'PP', 'SB','VC','BB','UL')
        then QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED * -1
        else 0
        end as TOTAL_DEMAND,
        case
        when mdtb.MRP_ELEMENT in ('WB','BE','LA','QM','PA','FE','BA','BB')
        then QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
        else 0
        end as TOTAL_SUPPLY
    from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC
    left join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_DESCRIPTIONS') }} MAKT
    on MARC.Material_Number = MAKT.MATERIAL_NUMBER
    left join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HEADER_DATA_FOR_MRP_DOCUMENT') }} MDKP
    on MARC.Material_Number = MDKP.MATERIAL_NUMBER
    and MARC.Plant = MDKP.PLANT
    left join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MRP_TABLE') }} MDTB
    on MDKP.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = MDTB.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
    where
    MARC.Material_Number is not null and 
    MARC.Plant = '0010'
),

transform_data as
(
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, 
        MATERIAL_DESCRIPTION,
        MATERIAL_NUMBER,
        RECEIPT_REQUIREMENTS_DATE,
        MRP_DATE,
        PROCUREMENT_TYPE,
        PLANNED_DELIVERY_TIME_IN_DAYS,
        PLANT_STOCK_ONLY_PLANT_SEGMENT,
        MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        MRP_ELEMENT,
        MRP_ELEMENT_NUMBER,
        QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        SHORTAGE_QUANTITY,
        SAFETY_STOCK,
        LANGUAGE_KEY,
        PLANT,
        ABC_INDICATOR,
        PURCHASING_GROUP,
        MRP_TYPE,
        REORDER_POINT,
        MINIMUM_LOT_SIZE,
        MAXIMUM_STOCK_LEVEL,
        PROFIT_CENTER,
        INDICATOR_BULK_MATERIAL,
        NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        ITEM_NUMBER_OF_MRP_LIST,
        TYPE_MRP_LIST,
        PLANNING_SCENARIO_LONG_TERM_PLANNING,
        QTY_RECEIVED,
        TOTAL_DEMAND,
        TOTAL_SUPPLY
    from
        source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(RECEIPT_REQUIREMENTS_DATE AS DATE) AS RECEIPT_REQUIREMENTS_DATE,
        CAST(MRP_DATE AS DATE) AS MRP_DATE,
        CAST(PROCUREMENT_TYPE AS VARCHAR(16777216)) AS PROCUREMENT_TYPE,
        CAST(PLANNED_DELIVERY_TIME_IN_DAYS AS NUMBER(38,10)) AS PLANNED_DELIVERY_TIME_IN_DAYS,
        CAST(PLANT_STOCK_ONLY_PLANT_SEGMENT AS NUMBER(38,10)) AS PLANT_STOCK_ONLY_PLANT_SEGMENT,
        CAST(MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY AS VARCHAR(16777216)) AS MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        CAST(MRP_ELEMENT AS VARCHAR(16777216)) AS MRP_ELEMENT,
        CAST(MRP_ELEMENT_NUMBER AS VARCHAR(16777216)) AS MRP_ELEMENT_NUMBER,
        CAST(QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED AS NUMBER(38,10)) AS QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        CAST(SHORTAGE_QUANTITY AS NUMBER(38,10)) AS SHORTAGE_QUANTITY,
        CAST(SAFETY_STOCK AS NUMBER(38,10)) AS SAFETY_STOCK,
        CAST(LANGUAGE_KEY AS VARCHAR(16777216)) AS LANGUAGE_KEY,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(ABC_INDICATOR AS VARCHAR(16777216)) AS ABC_INDICATOR,
        CAST(PURCHASING_GROUP AS VARCHAR(16777216)) AS PURCHASING_GROUP,
        CAST(MRP_TYPE AS VARCHAR(16777216)) AS MRP_TYPE,
        CAST(REORDER_POINT AS NUMBER(38,10)) AS REORDER_POINT,
        CAST(MINIMUM_LOT_SIZE AS NUMBER(38,10)) AS MINIMUM_LOT_SIZE,
        CAST(MAXIMUM_STOCK_LEVEL AS NUMBER(38,10)) AS MAXIMUM_STOCK_LEVEL,
        CAST(PROFIT_CENTER AS VARCHAR(16777216)) AS PROFIT_CENTER,
        CAST(INDICATOR_BULK_MATERIAL AS VARCHAR(16777216)) AS INDICATOR_BULK_MATERIAL,
        CAST(NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE AS VARCHAR(16777216)) AS NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        CAST(ITEM_NUMBER_OF_MRP_LIST AS VARCHAR(16777216)) AS ITEM_NUMBER_OF_MRP_LIST,
        CAST(TYPE_MRP_LIST AS VARCHAR(16777216)) AS TYPE_MRP_LIST,
        CAST(PLANNING_SCENARIO_LONG_TERM_PLANNING AS VARCHAR(16777216)) AS PLANNING_SCENARIO_LONG_TERM_PLANNING,
        CAST(QTY_RECEIVED AS NUMBER(38,10)) AS QTY_RECEIVED,
        CAST(TOTAL_DEMAND AS NUMBER(38,10)) AS TOTAL_DEMAND,
        CAST(TOTAL_SUPPLY AS NUMBER(38,10)) AS TOTAL_SUPPLY
    FROM transform_data
)

SELECT * from type_data
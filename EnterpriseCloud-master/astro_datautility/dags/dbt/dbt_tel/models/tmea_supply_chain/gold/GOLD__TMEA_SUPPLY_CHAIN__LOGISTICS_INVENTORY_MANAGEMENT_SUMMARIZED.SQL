WITH SOURCE_DATA AS
(
    SELECT
        MAKT.MATERIAL_DESCRIPTION,
        MAKT.MATERIAL_NUMBER,
        MARC.PROCUREMENT_TYPE,
        MARC.PLANNED_DELIVERY_TIME_IN_DAYS,
        MARC.SAFETY_STOCK,
        MAKT.LANGUAGE_KEY,
        MARC.PLANT,
        MARC.ABC_INDICATOR,
        MARC.PURCHASING_GROUP,
        MARC.MRP_TYPE,
        MARC.REORDER_POINT,
        MARC.MINIMUM_LOT_SIZE,
        MARC.MAXIMUM_STOCK_LEVEL,
        MARC.PROFIT_CENTER,
        MARC.INDICATOR_BULK_MATERIAL,
        MARA.CROSS_PLANT_MATERIAL_STATUS,
        MARA.MATERIAL_GROUP
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC

    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_DESCRIPTIONS') }} MAKT
        ON MARC.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
       AND MAKT.LANGUAGE_KEY = 'E'

    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_MATERIAL_DATA') }} MARA
        ON MARA.MATERIAL_NUMBER = MARC.MATERIAL_NUMBER

    WHERE MARC.MATERIAL_NUMBER IS NOT NULL
      AND MARC.PLANT = '0010'
      AND MARC.PROCUREMENT_TYPE = 'F'
),

MATERIAL_VALUATION AS
(
    SELECT
        MATERIAL_NUMBER,
        STANDARD_PRICE,
        PRICE_UNIT,
        VALUATION_AREA,

        STANDARD_PRICE / NULLIF(PRICE_UNIT,0) AS NET_PRICE

    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_VALUATION') }}

    WHERE VALUATION_AREA = '0010'
),

MRP_DATA AS
(
    SELECT
        MAKT.MATERIAL_NUMBER,
        MDTB.MRP_ELEMENT,
        MDTB.RECEIPT_REQUIREMENTS_DATE,
        MDTB.DELIVERY_ORDER_FINISH_DATE,
        MDKP.MRP_DATE,

        MARC.PROCUREMENT_TYPE,
        MARC.PLANNED_DELIVERY_TIME_IN_DAYS,

        MDKP.PLANT_STOCK_ONLY_PLANT_SEGMENT,
        MDTB.MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        MDTB.MRP_ELEMENT_NUMBER,
        MDTB.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        MDTB.SHORTAGE_QUANTITY,

        MARC.SAFETY_STOCK,
        MARC.PLANT,

        MDTB.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        MDTB.ITEM_NUMBER_OF_MRP_LIST,

        MDKP.TYPE_OF_MRP_LIST,
        MDKP.PLANNING_SCENARIO_LONG_TERM_PLANNING,
        MDTB.EXCEPTION_MESSAGE_KEY,

        MARA.CROSS_PLANT_MATERIAL_STATUS,
        MARA.MATERIAL_GROUP,

        CASE
            WHEN MDTB.MATERIAL_REQUIREMENTS_PLANNING_SEGMENT = '02'
             AND MDTB.RECEIPT_ISSUE_INDICATOR = '-'
            THEN MDTB.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
        END AS TOTAL_DEMAND,

        CASE
            WHEN MDTB.MATERIAL_REQUIREMENTS_PLANNING_SEGMENT = '02'
             AND MDTB.RECEIPT_ISSUE_INDICATOR = '+'
            THEN MDTB.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
        END AS TOTAL_SUPPLY,

        CASE
            WHEN MDTB.MATERIAL_REQUIREMENTS_PLANNING_SEGMENT = '02'
             AND MDTB.RECEIPT_ISSUE_INDICATOR = 'B'
            THEN MDTB.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
        END AS TOTAL_STOCK_OH,

        CASE
            WHEN MDTB.MRP_ELEMENT = 'WB'
            THEN CURRENT_DATE()
            ELSE MDTB.RECEIPT_REQUIREMENTS_DATE
        END AS NRECEIPT_REQUIREMENTS_DATE

    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC

    LEFT JOIN {{ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_DESCRIPTIONS')}} MAKT
        ON MARC.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
       AND MAKT.LANGUAGE_KEY = 'E'

    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_MATERIAL_DATA') }} MARA
        ON MARA.MATERIAL_NUMBER = MARC.MATERIAL_NUMBER

    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HEADER_DATA_FOR_MRP_DOCUMENT') }} MDKP
        ON MARC.MATERIAL_NUMBER = MDKP.MATERIAL_NUMBER
       AND MARC.PLANT = MDKP.PLANT

    INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MRP_TABLE') }} MDTB
        ON MDKP.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE =
           MDTB.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE

    WHERE MARC.MATERIAL_NUMBER IS NOT NULL
      AND MARC.PLANT = '0010'
      AND MARC.PROCUREMENT_TYPE = 'F'
      AND NOT( MDTB.MRP_ELEMENT) IN ('LB')
      AND MDKP.PLANNING_SCENARIO_LONG_TERM_PLANNING = '000'
),

FINAL_DEMAND AS
(
    SELECT
        MATERIAL_NUMBER,

        COALESCE(SUM(TOTAL_DEMAND),0) AS TOTAL_DEMAND_QTY,
        COALESCE(SUM(TOTAL_SUPPLY),0) AS TOTAL_SUPPLY_QTY,
        COALESCE(SUM(TOTAL_STOCK_OH),0) AS TOTAL_STOCK_OH_QTY

    FROM MRP_DATA

    GROUP BY MATERIAL_NUMBER
),

BASE_CALCS AS
(
    SELECT DISTINCT

        SD.MATERIAL_NUMBER,
        SD.MATERIAL_DESCRIPTION,
        SD.CROSS_PLANT_MATERIAL_STATUS,
        SD.PROCUREMENT_TYPE,
        SD.MATERIAL_GROUP,
        SD.PLANNED_DELIVERY_TIME_IN_DAYS,
        SD.LANGUAGE_KEY,
        SD.PLANT,
        SD.ABC_INDICATOR,
        SD.PURCHASING_GROUP,
        SD.MRP_TYPE,
        SD.REORDER_POINT,
        SD.MINIMUM_LOT_SIZE,
        SD.MAXIMUM_STOCK_LEVEL,
        SD.PROFIT_CENTER,
        SD.INDICATOR_BULK_MATERIAL,

        MV.NET_PRICE,

        ZEROIFNULL(SD.SAFETY_STOCK * -1) AS SAFETY_STOCK_QTY,
        ZEROIFNULL(FD.TOTAL_DEMAND_QTY) AS TOTAL_DEMAND_QTY,
        ZEROIFNULL(FD.TOTAL_SUPPLY_QTY) AS TOTAL_SUPPLY_QTY,
        ZEROIFNULL(FD.TOTAL_STOCK_OH_QTY) AS TOTAL_STOCK_OH_QTY,

        ZEROIFNULL(SAFETY_STOCK_QTY)
            + ZEROIFNULL(TOTAL_DEMAND_QTY)
            AS GROSS_DEMAND_QTY

    FROM SOURCE_DATA SD

    LEFT JOIN MATERIAL_VALUATION MV
        ON MV.MATERIAL_NUMBER = SD.MATERIAL_NUMBER
       AND MV.VALUATION_AREA = SD.PLANT

    LEFT JOIN FINAL_DEMAND FD
        ON FD.MATERIAL_NUMBER = SD.MATERIAL_NUMBER
),

FINAL_DATA AS
(
    SELECT

        *,

        ZEROIFNULL(SAFETY_STOCK_QTY * NET_PRICE)
            AS SAFETY_STOCK_AMOUNT,

        ZEROIFNULL(TOTAL_DEMAND_QTY * NET_PRICE)
            AS TOTAL_DEMAND_AMOUNT,

        ZEROIFNULL(TOTAL_SUPPLY_QTY * NET_PRICE)
            AS TOTAL_SUPPLY_AMOUNT,

        ZEROIFNULL(TOTAL_STOCK_OH_QTY * NET_PRICE)
            AS TOTAL_STOCK_OH_AMOUNT,

        ZEROIFNULL(
        GREATEST(
            0,
            TOTAL_STOCK_OH_QTY + GROSS_DEMAND_QTY
        )) AS TOTAL_EXCESS_QTY,


TOTAL_STOCK_OH_QTY + TOTAL_SUPPLY_QTY AS GROSS_SUPPLY,
        ZEROIFNULL(GREATEST(
            0,
            GROSS_SUPPLY
            + GROSS_DEMAND_QTY-TOTAL_EXCESS_QTY

        ) ) AS TOTAL_OVERSUPPLY_QTY

    FROM BASE_CALCS
)

SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    CROSS_PLANT_MATERIAL_STATUS,
    PROCUREMENT_TYPE,
    MATERIAL_GROUP,
    PLANNED_DELIVERY_TIME_IN_DAYS,
    LANGUAGE_KEY,
    PLANT,
    ABC_INDICATOR,
    PURCHASING_GROUP,
    MRP_TYPE,
    REORDER_POINT,
    MINIMUM_LOT_SIZE,
    MAXIMUM_STOCK_LEVEL,
    PROFIT_CENTER,
    INDICATOR_BULK_MATERIAL,

    NET_PRICE,

    SAFETY_STOCK_QTY,
    TOTAL_DEMAND_QTY,
     GROSS_DEMAND_QTY,

    TOTAL_SUPPLY_QTY,
     TOTAL_STOCK_OH_QTY,
     TOTAL_EXCESS_QTY,
     GROSS_SUPPLY,
     TOTAL_OVERSUPPLY_QTY,

    SAFETY_STOCK_AMOUNT,



    TOTAL_SUPPLY_AMOUNT,


    TOTAL_STOCK_OH_AMOUNT,
    TOTAL_EXCESS_QTY * NET_PRICE AS TOTAL_EXCESS_AMOUNT,


    GROSS_DEMAND_QTY * NET_PRICE AS TOTAL_GROSS_DEMAND_AMOUNT,

    TOTAL_OVERSUPPLY_QTY * NET_PRICE AS TOTAL_OVERSUPPLY_AMOUNT,

    (
        TOTAL_STOCK_OH_AMOUNT
        + TOTAL_SUPPLY_AMOUNT
        + TOTAL_GROSS_DEMAND_AMOUNT

    ) AS TOTAL_INV_BALANCE

FROM FINAL_DATA
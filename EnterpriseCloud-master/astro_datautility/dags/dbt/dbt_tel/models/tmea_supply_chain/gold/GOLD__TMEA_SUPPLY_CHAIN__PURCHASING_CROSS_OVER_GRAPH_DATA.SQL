WITH ref_cte_HEADER_DATA_FOR_MRP_DOCUMENT as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HEADER_DATA_FOR_MRP_DOCUMENT') }}
),

ref_cte_MRP_TABLE as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MRP_TABLE') }}
),

ref_cte_PLANNED_ORDER as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANNED_ORDER') }}
),


MRP_DATA AS( SELECT DISTINCT
HDMD.MRP_DATE,
SMT.RECEIPT_REQUIREMENTS_DATE,
SMT.MRP_ELEMENT,
SMT.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
SMT.MRP_ELEMENT_NUMBER,
SMT.MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
TKCM.supplier,
HDMD.MATERIAL_NUMBER,
HDMD.PLANT,
cast (HDMD.SAFETY_STOCK *-1 as number(32,10)) as SAFETY_STOCK,
HDMD.PLANT_STOCK_ONLY_PLANT_SEGMENT,
VS.SALES_DOCUMENT,
VS.MATERIAL_NUMBER AS PEGTO,
ITEM_NUMBER_OF_MRP_LIST,
smt.STORAGE_LOCATION,
CONCAT(HDMD.MATERIAL_NUMBER,TKCM.supplier) as PrimaryKey,
CASE
    WHEN SMT.MRP_ELEMENT = 'BE' AND MRP_ELEMENT_NUMBER LIKE 'RT%' or SMT.MRP_ELEMENT = 'BE'  and
    MRP_ELEMENT_NUMBER LIKE 'EN%' THEN concat('PO ', MRP_ELEMENT_NUMBER)

    WHEN SMT.MRP_ELEMENT = 'BE' AND MRP_ELEMENT_NUMBER NOT LIKE 'RT%' or SMT.MRP_ELEMENT = 'BE'  and
    MRP_ELEMENT_NUMBER NOT LIKE 'EN%' THEN concat('PO ',
    MRP_ELEMENT_NUMBER)

    WHEN SMT.MRP_ELEMENT = 'LA' AND MRP_ELEMENT_NUMBER LIKE 'RT%' or SMT.MRP_ELEMENT = 'LA'  and
    MRP_ELEMENT_NUMBER LIKE 'EN%' THEN concat('PO ', MRP_ELEMENT_NUMBER)

    WHEN SMT.MRP_ELEMENT = 'LA' AND MRP_ELEMENT_NUMBER NOT LIKE 'RT%' or SMT.MRP_ELEMENT = 'LA'  and
    MRP_ELEMENT_NUMBER NOT LIKE 'EN%' THEN concat('PO ',
    CAST(MRP_ELEMENT_NUMBER AS NUMBER(32,0)))

    WHEN SMT.MRP_ELEMENT = 'BA' THEN concat('PR ', CAST(MRP_ELEMENT_NUMBER AS NUMBER(32,0)))
    WHEN SMT.MRP_ELEMENT = 'VC' THEN concat('SPARES ORDER ', CAST(MRP_ELEMENT_NUMBER AS NUMBER(32,0)))
    WHEN SMT.MRP_ELEMENT = 'QM' THEN 'QM LOT'
    WHEN SMT.MRP_ELEMENT = 'VJ' THEN 'DELIVERY'
    WHEN SMT.MRP_ELEMENT = 'PP' THEN MRP_ELEMENT_NUMBER
    WHEN SMT.MRP_ELEMENT = 'WB' THEN 'SAFETY STOCK/STOCK'
    WHEN SMT.MRP_ELEMENT = 'AR' OR SMT.MRP_ELEMENT = 'MR'THEN 'MAT RES'
    WHEN SMT.MRP_ELEMENT = 'PA' THEN 'PLND ORD'
    WHEN SMT.MRP_ELEMENT = 'BB' THEN 'SUBREQ'
    WHEN SMT.MRP_ELEMENT = 'SB' AND VS.SALES_DOCUMENT is null THEN
          SMT.MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY
    WHEN SMT.MRP_ELEMENT = 'SB' THEN VS.MATERIAL_NUMBER
END AS MRP_ELEMENT_DESCRIPTION,


CASE
    WHEN SMT.MRP_ELEMENT = 'BE' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
    WHEN SMT.MRP_ELEMENT = 'QM' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
    WHEN SMT.MRP_ELEMENT = 'PA' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
    WHEN SMT.MRP_ELEMENT = 'WB' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
    WHEN SMT.MRP_ELEMENT = 'BA' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
    WHEN SMT.MRP_ELEMENT = 'LA' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED


END AS TOTAL_SUPPLY,

CASE
    WHEN SMT.MRP_ELEMENT = 'BB' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
    WHEN SMT.MRP_ELEMENT = 'VC' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
    WHEN SMT.MRP_ELEMENT = 'VJ' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
    WHEN SMT.MRP_ELEMENT = 'AR' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
    WHEN SMT.MRP_ELEMENT = 'MR' AND SMT.STORAGE_LOCATION = '0010'THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
    WHEN SMT.MRP_ELEMENT = 'PP' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
    WHEN SMT.MRP_ELEMENT = 'SB' AND VS.SALES_DOCUMENT is null THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
    WHEN SMT.MRP_ELEMENT = 'WB' THEN HDMD.SAFETY_STOCK*-1
    WHEN SMT.MRP_ELEMENT = 'SB' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED*-1
END AS TOTAL_DEMAND,

CASE
    WHEN SMT.MRP_ELEMENT = 'WB' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
END AS STOCK,

CASE
WHEN SMT.MRP_ELEMENT = 'BE' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
WHEN SMT.MRP_ELEMENT = 'PA' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
WHEN SMT.MRP_ELEMENT = 'BA' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
WHEN SMT.MRP_ELEMENT = 'LA' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
WHEN SMT.MRP_ELEMENT = 'QM' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
WHEN SMT.MRP_ELEMENT = 'BB' THEN (QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1)/2
WHEN SMT.MRP_ELEMENT = 'VC' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
WHEN SMT.MRP_ELEMENT = 'VJ' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
WHEN SMT.MRP_ELEMENT = 'AR' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
WHEN SMT.MRP_ELEMENT = 'MR' AND SMT.STORAGE_LOCATION = '0010'THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
WHEN SMT.MRP_ELEMENT = 'PP' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
WHEN SMT.MRP_ELEMENT = 'SB' AND VS.SALES_DOCUMENT is null THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED *-1
WHEN SMT.MRP_ELEMENT = 'WB' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED-HDMD.SAFETY_STOCK
WHEN SMT.MRP_ELEMENT = 'SB' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED*-1
END  AS TOTAL,

CASE
    WHEN SMT.MRP_ELEMENT = 'WB' THEN CURRENT_DATE() ELSE SMT.RECEIPT_REQUIREMENTS_DATE
END AS nRECEIPT_REQUIREMENTS_DATE,


SUM(TOTAL)
 OVER (
      PARTITION BY
      HDMD.MATERIAL_NUMBER
 ORDER BY
      ITEM_NUMBER_OF_MRP_LIST

 ASC ROWS BETWEEN UNBOUNDED PRECEDING
 AND CURRENT ROW  )
  AS BALANCE


FROM ref_cte_MRP_TABLE as SMT
inner join ref_cte_HEADER_DATA_FOR_MRP_DOCUMENT as HDMD
on HDMD.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = smt.number_of_material_requirements_planning_table


left join ref_cte_PLANNED_ORDER PO
on PO.PLANNED_ORDER_NUMBER = SMT.source_number_for_order

left join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PRODUCTION_VALUE_STREAM') }} as VS
on VS.SALES_DOCUMENT = PO.sales_order_number

left join {{ ref('GOLD__TMEA_SUPPLY_CHAIN__KEY_COMPONENTS_MAIN') }} as TKCM
on TKCM.material_number =  HDMD.MATERIAL_NUMBER

),

final AS (SELECT DISTINCT
MRP_DATA.PrimaryKey,
MRP_DATA.MRP_DATE,
MRP_DATA.STORAGE_LOCATION,
nRECEIPT_REQUIREMENTS_DATE as RECEIPT_REQUIREMENTS_DATE,
MRP_DATA.MRP_ELEMENT,
MRP_DATA.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
MRP_DATA.MRP_ELEMENT_NUMBER,
MRP_DATA.MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
MRP_DATA.supplier,
MRP_DATA.MATERIAL_NUMBER,
MRP_DATA.PLANT,
MRP_DATA.SAFETY_STOCK,
MRP_DATA.PLANT_STOCK_ONLY_PLANT_SEGMENT,
MRP_DATA.SALES_DOCUMENT,
MRP_DATA.MRP_ELEMENT_DESCRIPTION,
ITEM_NUMBER_OF_MRP_LIST,
TOTAL_DEMAND,
TOTAL_SUPPLY,
TOTAL,
BALANCE

FROM MRP_DATA
    WHERE  PLANT in ('0010')
    AND MRP_ELEMENT not IN ('LK','LB')

),
source_data as (
SELECT distinct * FROM FINAL
ORDER BY ITEM_NUMBER_OF_MRP_LIST ASC ),


transform_data as (
select
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    PRIMARYKEY,
	MRP_DATE,
    STORAGE_LOCATION,
	RECEIPT_REQUIREMENTS_DATE,
	MRP_ELEMENT,
	QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
	MRP_ELEMENT_NUMBER,
	MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
	SUPPLIER,
	MATERIAL_NUMBER,
	PLANT,
	SAFETY_STOCK,
	PLANT_STOCK_ONLY_PLANT_SEGMENT,
	SALES_DOCUMENT,
	MRP_ELEMENT_DESCRIPTION,
	ITEM_NUMBER_OF_MRP_LIST,
	TOTAL_DEMAND,
	TOTAL_SUPPLY,
	TOTAL,
	BALANCE
from source_data
),

type_data as (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
    cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
	CAST(PRIMARYKEY as VARCHAR(16777216)) as PRIMARYKEY,
	CAST(MRP_DATE as DATE) as MRP_DATE,
	CAST(STORAGE_LOCATION as VARCHAR(16777216)) as STORAGE_LOCATION,
	CAST(RECEIPT_REQUIREMENTS_DATE as DATE) as RECEIPT_REQUIREMENTS_DATE,
	CAST(MRP_ELEMENT as VARCHAR(16777216)) as MRP_ELEMENT,
	CAST(QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED as NUMBER(38,10)) as QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
	CAST(MRP_ELEMENT_NUMBER as VARCHAR(16777216)) as MRP_ELEMENT_NUMBER,
	CAST(MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY as VARCHAR(16777216)) as MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
	CAST(SUPPLIER as VARCHAR(16777216)) as SUPPLIER,
	CAST(MATERIAL_NUMBER as VARCHAR(16777216)) as MATERIAL_NUMBER,
	CAST(PLANT as VARCHAR(16777216)) as PLANT,
	CAST(SAFETY_STOCK as NUMBER(38,10)) as SAFETY_STOCK,
	CAST(PLANT_STOCK_ONLY_PLANT_SEGMENT as NUMBER(38,10)) as PLANT_STOCK_ONLY_PLANT_SEGMENT,
	CAST(SALES_DOCUMENT as VARCHAR(16777216)) as SALES_DOCUMENT,
	CAST(MRP_ELEMENT_DESCRIPTION as VARCHAR(16777216)) as MRP_ELEMENT_DESCRIPTION,
	CAST(ITEM_NUMBER_OF_MRP_LIST as VARCHAR(16777216)) as ITEM_NUMBER_OF_MRP_LIST,
	CAST(TOTAL_DEMAND as NUMBER(38,10)) as TOTAL_DEMAND,
	CAST(TOTAL_SUPPLY as NUMBER(38,10)) as TOTAL_SUPPLY,
	CAST(TOTAL as NUMBER(38,10)) as TOTAL,
	CAST(BALANCE as NUMBER(38,10)) as BALANCE

from transform_data
)
select * from type_data
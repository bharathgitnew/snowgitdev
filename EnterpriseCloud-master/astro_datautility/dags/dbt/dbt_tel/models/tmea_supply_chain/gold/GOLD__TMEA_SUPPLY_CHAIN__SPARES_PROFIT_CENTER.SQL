{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'SPARES_PROFIT_CENTER',
        transient = false
) }}

with source_data as (
    select
        PROFIT_CENTER_MASTER_DATA.CLIENT,
        PROFIT_CENTER_MASTER_DATA.PROFIT_CENTER as PROFT_CNTR_ID,
        PROFIT_CENTER_MASTER_DATA.VALID_TO_DATE as VALID_TO_DATE,
        PROFIT_CENTER_MASTER_DATA.CONTROLLING_AREA as CONTROLLING_AREA_ID,
        PROFIT_CENTER_DESCRIPTION.LONG_TEXT as LONG_TEXT
    from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PROFIT_CENTER_MASTER_DATA') }} as PROFIT_CENTER_MASTER_DATA
    left OUTER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PROFIT_CENTER_DESCRIPTION') }} as PROFIT_CENTER_DESCRIPTION
    on PROFIT_CENTER_MASTER_DATA.PROFIT_CENTER = PROFIT_CENTER_DESCRIPTION.PROFIT_CENTER
    and PROFIT_CENTER_MASTER_DATA.CONTROLLING_AREA = PROFIT_CENTER_DESCRIPTION.CONTROLLING_AREA
    and PROFIT_CENTER_MASTER_DATA.CLIENT = PROFIT_CENTER_DESCRIPTION.CLIENT
    where PROFIT_CENTER_MASTER_DATA.CLIENT = 300
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        CLIENT,
        PROFT_CNTR_ID,
        VALID_TO_DATE,
        CONTROLLING_AREA_ID,
        LONG_TEXT
    from source_data
),

type_data as (
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(CLIENT AS VARCHAR(16777216)) AS CLIENT,
        CAST(PROFT_CNTR_ID AS VARCHAR(16777216)) AS PROFT_CNTR_ID,
        CAST(VALID_TO_DATE AS DATE) AS VALID_TO_DATE,
        CAST(CONTROLLING_AREA_ID AS VARCHAR(16777216)) AS CONTROLLING_AREA_ID,
        CAST(LONG_TEXT AS VARCHAR(16777216)) AS LONG_TEXT
    from transform_data
)

select * from type_data
{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='PURCHASING_METRIC_LATE_PO',
      transient=false
) }}

WITH source_data as
(
SELECT DISTINCT
      EKBE.PURCHASING_DOCUMENT_NUMBER,
	  EKBE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
	  EKPO.PURCHASE_REQUISITION_NUMBER as PURCHASE_REQUISITION_NUM,
	  EKPO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT as ITEM_NUM_OF_PURCHASE_REQUISITION,
	  EKPO.MATERIAL_NUMBER as MATERIAL_NUM,
	  EKPO.SHORT_TEXT,
	  EKKO.PURCHASING_GROUP,
	  EBAN.FIXED_VENDOR,
	  LFA1.NAME_1,
	  EKBE.POSTING_DATE_IN_THE_DOCUMENT,
	  TO_VARCHAR(EKBE.POSTING_DATE_IN_THE_DOCUMENT, 'MM/DD/YYYY') AS POSTING_DELIVERY_DATE,
	  TO_VARCHAR(EKES.DELIVERY_DATE_OF_VENDOR_CONFIRMATION, 'MM/DD/YYYY') AS DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
	  TO_VARCHAR(EKET.ITEM_DELIVERY_DATE, 'MM/DD/YYYY') AS ITEM_DELIVERY_DATE,
	  TO_VARCHAR(IFNULL(EKES.DELIVERY_DATE_OF_VENDOR_CONFIRMATION, EKET.ITEM_DELIVERY_DATE), 'MM/DD/YYYY') AS ITEM_DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
	  DATEDIFF(DAY, ITEM_DELIVERY_DATE_OF_VENDOR_CONFIRMATION, POSTING_DELIVERY_DATE) AS DAYS_DIFF_OTD,
	  TO_VARCHAR(EKET.STATISTICS_RELEVANT_DELIVERY_DATE, 'MM/DD/YYYY') AS ORIGINAL_COMMIT_DATE,
	  IFF(EKET.STATISTICS_RELEVANT_DELIVERY_DATE = EKET.ITEM_DELIVERY_DATE, 'FALSE', 'TRUE') AS SUPPLIER_CHANGES,
	  TO_NUMBER(EBAN.PLANNED_DELIVERY_TIME_IN_DAYS, 10) AS PLANNED_DELIVERY_TIME_IN_DAYS,
	  TO_VARCHAR(EKKO.DATE_ON_WHICH_RECORD_WAS_CREATED, 'MM/DD/YYYY') AS PO_CREATE_DATE
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HISTORY_PER_PURCHASING_DOCUMENT') }} EKBE
    JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SCHEDULING_AGREEMENT_SCHEDULE_LINES') }} EKET ON EKET.PURCHASING_DOCUMENT_NUMBER = EKBE.PURCHASING_DOCUMENT_NUMBER
	    AND EKET.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = EKBE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
    JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_ITEM') }} EKPO ON EKPO.PURCHASING_DOCUMENT_NUMBER = EKET.PURCHASING_DOCUMENT_NUMBER
	    AND EKPO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = EKET.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
    JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASE_REQUISITION') }} EBAN ON EBAN.PURCHASE_REQUISITION_NUMBER = EKPO.PURCHASE_REQUISITION_NUMBER
	    AND EBAN.ITEM_NUMBER_OF_PURCHASE_REQUISITION = EKPO.ITEM_NUMBER_OF_PURCHASE_REQUISITION
    JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_HEADER') }} EKKO ON EKKO.PURCHASING_DOCUMENT_NUMBER = EKPO.PURCHASING_DOCUMENT_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__VENDOR_CONFIRMATIONS') }} EKES ON EKES.PURCHASING_DOCUMENT_NUMBER = EKET.PURCHASING_DOCUMENT_NUMBER
	    AND EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = EKET.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__VENDOR_MASTER') }} LFA1 ON EBAN.FIXED_VENDOR = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
    WHERE EKBE.POSTING_DATE_IN_THE_DOCUMENT >= DATEADD(DAYS, - 365, CURRENT_DATE)
	    AND NULLIF(EKPO.MATERIAL_NUMBER, '') IS NOT NULL


)

,transform_data as
(
  SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH, 
	  PURCHASING_DOCUMENT_NUMBER AS PURCHASING_DOC_NUM,
	  ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS ITEM_NUM_PURCHASING_DOC,
	  PURCHASE_REQUISITION_NUM,
	  ITEM_NUM_OF_PURCHASE_REQUISITION,
	  MATERIAL_NUM,
	  SHORT_TEXT,
	  PURCHASING_GROUP,
	  FIXED_VENDOR,
	  NAME_1,
	  POSTING_DATE_IN_THE_DOCUMENT AS POSTING_DATE_DOC,
	  POSTING_DELIVERY_DATE,
	  DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
	  ITEM_DELIVERY_DATE,
	  ITEM_DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
	  DAYS_DIFF_OTD,
	  ORIGINAL_COMMIT_DATE,
	  SUPPLIER_CHANGES,
	  PLANNED_DELIVERY_TIME_IN_DAYS,
	  PO_CREATE_DATE
  FROM source_data

)

,type_data as (
    SELECT
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(PURCHASING_DOC_NUM AS VARCHAR(30)) AS PURCHASING_DOC_NUM,
        CAST(ITEM_NUM_PURCHASING_DOC AS VARCHAR(15)) AS ITEM_NUM_PURCHASING_DOC,
        CAST(PURCHASE_REQUISITION_NUM AS VARCHAR(30)) AS PURCHASE_REQUISITION_NUM,
        CAST(ITEM_NUM_OF_PURCHASE_REQUISITION AS VARCHAR(15)) AS ITEM_NUM_OF_PURCHASE_REQUISITION,
        CAST(MATERIAL_NUM AS VARCHAR(54)) AS MATERIAL_NUM,
        CAST(SHORT_TEXT AS VARCHAR(120)) AS SHORT_TEXT,
        CAST(PURCHASING_GROUP AS VARCHAR(9)) AS PURCHASING_GROUP,
        CAST(FIXED_VENDOR AS VARCHAR(16777216)) AS FIXED_VENDOR,
        CAST(NAME_1 AS VARCHAR(105)) AS NAME_1,
        CAST(POSTING_DATE_DOC AS VARCHAR(24)) AS POSTING_DATE_DOC,
        CAST(POSTING_DELIVERY_DATE AS VARCHAR(16777216)) AS POSTING_DELIVERY_DATE,
        CAST(DELIVERY_DATE_OF_VENDOR_CONFIRMATION AS DATE) AS DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
        CAST(ITEM_DELIVERY_DATE AS DATE) AS ITEM_DELIVERY_DATE,
        CAST(ITEM_DELIVERY_DATE_OF_VENDOR_CONFIRMATION AS VARCHAR(16777216)) AS ITEM_DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
        CAST(DAYS_DIFF_OTD AS NUMBER(9,0)) AS DAYS_DIFF_OTD,
        CAST(ORIGINAL_COMMIT_DATE AS VARCHAR(16777216)) AS ORIGINAL_COMMIT_DATE,
        CAST(SUPPLIER_CHANGES AS VARCHAR(5)) AS SUPPLIER_CHANGES,
        CAST(PLANNED_DELIVERY_TIME_IN_DAYS AS NUMBER(10,0)) AS PLANNED_DELIVERY_TIME_IN_DAYS,
        CAST(PO_CREATE_DATE AS VARCHAR(16777216)) AS PO_CREATE_DATE
    FROM transform_data
)

SELECT * from type_data
    materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
    alias='PURCHASING_MRB_STOCK',
    transient=false
) }}


with MRB as (
    Select
        distinct 
         qms.MATERIAL_NUMBER
        ,qms.MATERIAL_DESCRIPTION
        ,STORAGE_TYPE
        ,STORAGE_BIN
        ,MRP_CONTROLLER_MATERIALS_PLANNER
        ,CONTROLLER_NAME
        ,TOTAL_QUANTITY
        ,AVAILABLE_STOCK
        ,qms.BASE_UNIT_OF_MEASURE
        ,STANDARD_COST
        ,EXTENDED_COST
        ,qms.MATERIAL_GROUP
        ,CAST (DATE_OF_LAST_MOVEMENT AS DATE) AS DATE_OF_LAST_MOVEMENT
        ,TIME_OF_LAST_MOVEMENT
        ,CAST (DATE_OF_LAST_PLACEMENT_INTO_STOCK AS DATE) AS DATE_OF_LAST_PLACEMENT_INTO_STOCK
        ,DAYS_IN_MRB
        ,listagg(distinct vs.material_number, ' , ') over (partition by qms.material_number) as tool_id
        , CASE
            WHEN tool_id = '' THEN 'NO TOOL SHORTAGE'
            ELSE tool_id
        END AS Shortage_tool_id
    from
        {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MRB_STOCK') }} qms
        left join {{ ref('GOLD__TMEA_SUPPLY_CHAIN__TMEA_SHORTAGE_REPORT_DATA_WAREHOUSE') }} sdw on sdw.material_number = qms.material_number
        LEFT join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PRODUCTION_VALUE_STREAM') }} vs on vs.sales_document = sdw.sales_and_distribution_document_number
),
Stock AS(
    SELECT
        distinct HDMD.MRP_DATE,
        SMT.RECEIPT_REQUIREMENTS_DATE,
        SMT.MRP_ELEMENT,
        SMT.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        SMT.MRP_ELEMENT_NUMBER,
        SMT.MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        HDMD.MATERIAL_NUMBER,
        HDMD.PLANT,
        Case
            when smt.MRP_ELEMENT in ('WB') then QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED
            else 0
        End as TOTAL_STOCK_OH
    FROM
        {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MRP_TABLE') }} as SMT
        join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HEADER_DATA_FOR_MRP_DOCUMENT') }} as HDMD on HDMD.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = smt.number_of_material_requirements_planning_table
        and plant in('0010')
),
final_Stock as (
    select
        stock.MATERIAL_NUMBER,
        max(TOTAL_STOCK_OH) as TOTAL_STOCK_OH
    from
        stock
    group by
        stock.MATERIAL_NUMBER
),
DATA_FORMAT as (
    select
        MRB.MATERIAL_NUMBER,
        MRB.MATERIAL_DESCRIPTION,
        MRB.STORAGE_TYPE,
        STORAGE_BIN,
        MRB.MRP_CONTROLLER_MATERIALS_PLANNER,
        MRB.CONTROLLER_NAME,
        CAST (MRB.AVAILABLE_STOCK AS NUMBER(10, 2)) AS MRB_STOCK,
        MRB.BASE_UNIT_OF_MEASURE,
        CAST (MRB.STANDARD_COST AS NUMBER(10, 2)) AS STANDARD_COST,
        CAST (MRB.EXTENDED_COST AS NUMBER(10, 2)) AS EXTENDED_COST,
        MRB.MATERIAL_GROUP,
        CAST (MRB.DATE_OF_LAST_MOVEMENT AS DATE) AS DATE_OF_LAST_MOVEMENT,
        MRB.TIME_OF_LAST_MOVEMENT,
        CAST (MRB.DATE_OF_LAST_PLACEMENT_INTO_STOCK AS DATE) AS DATE_OF_LAST_PLACEMENT_INTO_MRB,
        DAYS_IN_MRB,
        MRB.SHORTAGE_TOOL_ID,
        FINAL_STOCK.TOTAL_STOCK_OH
    from
        MRB AS MRB
        LEFT JOIN FINAL_STOCK AS FINAL_STOCK ON MRB.MATERIAL_NUMBER = FINAL_STOCK.MATERIAL_NUMBER
),
SOURCE_DATA as(
 SELECT DISTINCT *
FROM
    DATA_FORMAT
),
TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	STORAGE_TYPE,
	STORAGE_BIN,
	MRP_CONTROLLER_MATERIALS_PLANNER,
	CONTROLLER_NAME,
	MRB_STOCK,
	BASE_UNIT_OF_MEASURE,
	STANDARD_COST,
	EXTENDED_COST,
	MATERIAL_GROUP,
	DATE_OF_LAST_MOVEMENT,
	TIME_OF_LAST_MOVEMENT,
	DATE_OF_LAST_PLACEMENT_INTO_MRB,
	DAYS_IN_MRB,
	SHORTAGE_TOOL_ID,
	TOTAL_STOCK_OH

FROM SOURCE_DATA
)

,
TYPE_DATA AS (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	STORAGE_TYPE,
	STORAGE_BIN,
	MRP_CONTROLLER_MATERIALS_PLANNER,
	CONTROLLER_NAME,
	CAST(MRB_STOCK as NUMBER(10, 2)) as MRB_STOCK,
	BASE_UNIT_OF_MEASURE,
	CAST(STANDARD_COST as NUMBER(10, 2)) as STANDARD_COST,
	CAST(EXTENDED_COST as NUMBER(10, 2)) as EXTENDED_COST,
	MATERIAL_GROUP,
	CAST(DATE_OF_LAST_MOVEMENT as DATE) as DATE_OF_LAST_MOVEMENT,
	TIME_OF_LAST_MOVEMENT,
	CAST(DATE_OF_LAST_PLACEMENT_INTO_MRB as DATE) as DATE_OF_LAST_PLACEMENT_INTO_MRB,
	CAST(DAYS_IN_MRB as NUMBER(10, 2)) as DAYS_IN_MRB,
	SHORTAGE_TOOL_ID,
	CAST(TOTAL_STOCK_OH as NUMBER(10, 2)) as TOTAL_STOCK_OH
from transform_data
)
SELECT * FROM TYPE_DATA
WITH source_data AS (
    SELECT MAKT.MATERIAL_DESCRIPTION AS MATERIAL_DESCRIPTION,
        MAKT.MATERIAL_NUMBER AS MATERIAL_NUMBER,
        MDTB.RECEIPT_REQUIREMENTS_DATE AS RECEIPT_REQUIREMENTS_DATE,
        MDKP.MRP_DATE AS MRP_DATE,
        marc.PROCUREMENT_TYPE AS PROCUREMENT_TYPE,
        MARC.Planned_Delivery_Time_in_Days AS PLANNED_DELIVERY_TIME_IN_DAYS,
        MDKP.PLANT_STOCK_ONLY_PLANT_SEGMENT AS PLANT_STOCK_ONLY_PLANT_SEGMENT,
        MDTB.MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY AS MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        MDTB.MRP_ELEMENT AS MRP_ELEMENT,
        MDTB.MRP_ELEMENT_NUMBER AS MRP_ELEMENT_NUMBER,
        MDTB.QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED AS QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        MDTB.SHORTAGE_QUANTITY AS SHORTAGE_QUANTITY,
        MARC.Safety_Stock * - 1 AS SAFETY_STOCK,
        MAKT.LANGUAGE_KEY AS LANGUAGE_KEY,
        MARC.Plant AS PLANT,
        MARC.ABC_Indicator AS ABC_INDICATOR,
        MARC.Purchasing_Group AS PURCHASING_GROUP,
        MARC.MRP_Type AS MRP_TYPE,
        MARC.Reorder_Point AS REORDER_POINT,
        MARC.Minimum_Lot_Size AS MINIMUM_LOT_SIZE,
        MARC.Maximum_stock_level AS MAXIMUM_STOCK_LEVEL,
        MARC.Profit_Center AS PROFIT_CENTER,
        MARC.Indicator_Bulk_Material AS INDICATOR_BULK_MATERIAL,
        MDTB.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE AS NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        MDTB.ITEM_NUMBER_OF_MRP_LIST AS ITEM_NUMBER_OF_MRP_LIST,
        MDKP.TYPE_OF_MRP_LIST AS TYPE_MRP_LIST,
        MDKP.PLANNING_SCENARIO_LONG_TERM_PLANNING AS PLANNING_SCENARIO_LONG_TERM_PLANNING,
        mdtb.EXCEPTION_MESSAGE_KEY,
        GM.CROSS_PLANT_MATERIAL_STATUS,
        CASE WHEN EXCEPTION_MESSAGE_KEY = 'U3' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED ELSE 0 END AS Total_Qty_Overcommit,
        CASE WHEN MATERIAL_REQUIREMENTS_PLANNING_SEGMENT = '02' AND RECEIPT_ISSUE_INDICATOR = '-' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED * - 1 END AS TOTAL_DEMAND,
        CASE WHEN MATERIAL_REQUIREMENTS_PLANNING_SEGMENT = '02' AND RECEIPT_ISSUE_INDICATOR = '+' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED END AS TOTAL_SUPPLY,
        CASE WHEN MATERIAL_REQUIREMENTS_PLANNING_SEGMENT IN ('02') AND RECEIPT_ISSUE_INDICATOR = 'B' THEN QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED END AS TOTAL_STOCK_OH,
        CASE WHEN mdtb.MRP_ELEMENT IN ('WB') THEN CURRENT_DATE () ELSE mdtb.RECEIPT_REQUIREMENTS_DATE END AS RECEIPT_REQUIREMENT_DATE
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_DESCRIPTIONS') }} MAKT ON MARC.Material_Number = MAKT.MATERIAL_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HEADER_DATA_FOR_MRP_DOCUMENT') }} MDKP ON MARC.Material_Number = MDKP.MATERIAL_NUMBER AND MARC.Plant = MDKP.PLANT
    JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_MATERIAL_DATA') }} AS gm ON gm.material_number = marc.material_number
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MRP_TABLE') }} MDTB ON MDKP.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE = MDTB.NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE
    WHERE MARC.Material_Number IS NOT NULL AND MARC.Plant = '0010' AND marc.PROCUREMENT_TYPE = 'F'
    ),
material_valuation AS (
    SELECT DISTINCT mv.material_number,
        mv.standard_price,
        mv.price_unit,
        mv.valuation_area,
        mv.standard_price / mv.price_unit AS net_price
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_VALUATION') }} AS mv
    WHERE VALUATION_AREA IN ('0010')
    ),
transform_data AS (
    SELECT MATERIAL_DESCRIPTION,
        source_data.MATERIAL_NUMBER,
        CROSS_PLANT_MATERIAL_STATUS,
        RECEIPT_REQUIREMENT_DATE,
        MRP_DATE,
        PROCUREMENT_TYPE,
        PLANNED_DELIVERY_TIME_IN_DAYS,
        PLANT_STOCK_ONLY_PLANT_SEGMENT,
        MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        MRP_ELEMENT,
        MRP_ELEMENT_NUMBER,
        QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        SHORTAGE_QUANTITY,
        SAFETY_STOCK,
        LANGUAGE_KEY,
        PLANT,
        ABC_INDICATOR,
        PURCHASING_GROUP,
        MRP_TYPE,
        REORDER_POINT,
        MINIMUM_LOT_SIZE,
        MAXIMUM_STOCK_LEVEL,
        PROFIT_CENTER,
        INDICATOR_BULK_MATERIAL,
        NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        ITEM_NUMBER_OF_MRP_LIST,
        TYPE_MRP_LIST,
        PLANNING_SCENARIO_LONG_TERM_PLANNING,
        net_price,
        ZEROIFNULL(TOTAL_STOCK_OH) AS TOTAL_STOCK_OH,
        ZEROIFNULL(TOTAL_DEMAND) AS TOTAL_DEMAND,
        ZEROIFNULL(TOTAL_SUPPLY) AS TOTAL_SUPPLY
    FROM source_data AS source_data
    LEFT JOIN material_valuation AS material_valuation ON material_valuation.material_number = source_data.MATERIAL_NUMBER AND MATERIAL_VALUATION.VALUATION_AREA = source_data.PLANT
    ),
transform_data2 AS (
    SELECT MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        CROSS_PLANT_MATERIAL_STATUS,
        RECEIPT_REQUIREMENT_DATE,
        MRP_DATE,
        PROCUREMENT_TYPE,
        PLANNED_DELIVERY_TIME_IN_DAYS,
        PLANT_STOCK_ONLY_PLANT_SEGMENT,
        MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        MRP_ELEMENT,
        MRP_ELEMENT_NUMBER,
        QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        SHORTAGE_QUANTITY,
        SAFETY_STOCK,
        LANGUAGE_KEY,
        PLANT,
        ABC_INDICATOR,
        PURCHASING_GROUP,
        MRP_TYPE,
        REORDER_POINT,
        MINIMUM_LOT_SIZE,
        MAXIMUM_STOCK_LEVEL,
        PROFIT_CENTER,
        INDICATOR_BULK_MATERIAL,
        NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        ITEM_NUMBER_OF_MRP_LIST,
        TYPE_MRP_LIST,
        PLANNING_SCENARIO_LONG_TERM_PLANNING,
        NET_PRICE,
        ZEROIFNULL(TOTAL_DEMAND) AS TOTAL_DEMAND,
        ZEROIFNULL(TOTAL_DEMAND * NET_PRICE) AS TOTAL_DEMAND_AMOUNT,
        TOTAL_SUPPLY,
        ZEROIFNULL(TOTAL_SUPPLY * NET_PRICE) AS TOTAL_SUPPLY_AMOUNT,
        TOTAL_STOCK_OH,
        ZEROIFNULL(TOTAL_STOCK_OH * NET_PRICE) AS TOTAL_STOCK_OH_AMOUNT
    FROM transform_data
    ),

final as (
SELECT DISTINCT         
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
	    SHA2('hash_me') as _ROW_HASH,
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        CROSS_PLANT_MATERIAL_STATUS,
        RECEIPT_REQUIREMENT_DATE,
        MRP_DATE,
        PROCUREMENT_TYPE,
        PLANNED_DELIVERY_TIME_IN_DAYS,
        PLANT_STOCK_ONLY_PLANT_SEGMENT,
        MATERIAL_NUMBER_OF_HIGHER_LEVEL_ASSEMBLY,
        MRP_ELEMENT,
        MRP_ELEMENT_NUMBER,
        QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED,
        SHORTAGE_QUANTITY,
        SAFETY_STOCK,
        LANGUAGE_KEY,
        PLANT,
        ABC_INDICATOR,
        PURCHASING_GROUP,
        MRP_TYPE,
        REORDER_POINT,
        MINIMUM_LOT_SIZE,
        MAXIMUM_STOCK_LEVEL,
        PROFIT_CENTER,
        INDICATOR_BULK_MATERIAL,
        NUMBER_OF_MATERIAL_REQUIREMENTS_PLANNING_TABLE,
        ITEM_NUMBER_OF_MRP_LIST,
        TYPE_MRP_LIST,
        PLANNING_SCENARIO_LONG_TERM_PLANNING,
        NET_PRICE,
        TOTAL_DEMAND,
        TOTAL_DEMAND_AMOUNT,
        TOTAL_SUPPLY,
        TOTAL_SUPPLY_AMOUNT,
        TOTAL_STOCK_OH,
        TOTAL_STOCK_OH_AMOUNT
        FROM transform_data2
        WHERE PROCUREMENT_TYPE = 'F' AND plant = '0010'
)
select * from final
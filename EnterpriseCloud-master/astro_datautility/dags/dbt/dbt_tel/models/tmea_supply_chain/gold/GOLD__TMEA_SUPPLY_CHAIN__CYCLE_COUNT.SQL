{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias = 'CYCLE_COUNT',
        transient = false
) }}

with source_data as (
    SELECT
        LINV.DATE_OF_INVENTORY AS Count_Date
        ,LINV.NUMBER_OF_SYSTEM_INVENTORY_RECORD AS Inventory_Record
        ,LINV.ITEM_NUMBER_IN_INVENTORY_DOCUMENT AS Inventory_Record_Item
        ,LINV.INVENTORY_RECOUNT_NUMBER AS Inv_Recount_Num
        ,LINV.MATERIAL_NUMBER AS Material
        ,COALESCE(CASE WHEN LINV.PLANT = '' THEN NULL ELSE LINV.PLANT END  ,STG.PLANT)  AS Plant
        ,LINV.WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX AS Warehouse
        ,LINV.STORAGE_TYPE AS Storage_Type
        ,LINV.STORAGE_BIN AS Storage_Bin
        ,LINV.TOTAL_QUANTITY AS Stock_On_Hand
        ,LINV.BASE_UNIT_OF_MEASURE BUn
        ,LINV.COUNTED_QUANTITY_IN_STOCKKEEPING_UNIT AS Qty_Counted
        ,LINV.COUNTED_QUANTITY_IN_ALTERNATIVE_UNIT_OF_MEASURE AS Alternative_UN
        ,MARC.physical_inventory_indicator_for_cycle_counting
        ,LINV.INVENTORY_METHOD AS Inv_Meth
        ,MBEW.STANDARD_PRICE AS Standard_Price
        ,MBEW.PRICE_UNIT AS Price_Unit
        ,MBEW.STANDARD_PRICE / MBEW.PRICE_UNIT AS UNIT_COST
        ,Counted_quantity_in_stockkeeping_unit - Total_Quantity AS Qty_Var
        ,CASE WHEN Total_Quantity = 0 THEN 0 ELSE (Counted_quantity_in_stockkeeping_unit - Total_Quantity) /  Total_Quantity END AS Perc_Qty_Var
        ,Total_Quantity * (STANDARD_PRICE / PRICE_UNIT) as SOH_Cost
        ,COUNTED_QUANTITY_IN_STOCKKEEPING_UNIT * (STANDARD_PRICE / PRICE_UNIT)  AS Phys_Ct_Cost
        ,(COUNTED_QUANTITY_IN_STOCKKEEPING_UNIT * (STANDARD_PRICE / PRICE_UNIT)) - (Total_Quantity * (STANDARD_PRICE / PRICE_UNIT)) as Dollar_Var
        FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__INVENTORY_DATA_PER_QUANT') }}	 LINV
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_VALUATION') }} MBEW ON MBEW.MATERIAL_NUMBER = LINV.MATERIAL_NUMBER AND VALUATION_AREA = LINV.PLANT AND LINV.CLIENT = MBEW.CLIENT 
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC ON  MARC.MATERIAL_NUMBER = LINV.MATERIAL_NUMBER AND MARC.PLANT = LINV.PLANT AND LINV.CLIENT = MARC.CLIENT
        LEFT JOIN (SELECT DISTINCT STORAGE_LOCATION,CLIENT,PLANT,WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ASSIGNMENT_IM_STORAGE_LOCATION_TO_WM_WAREHOUSE_NUMBER') }}) STG
        ON LINV.WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX = STG.WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX AND LINV.CLIENT = STG.CLIENT
        WHERE ITEM_STATUS_OF_INVENTORY_AT_QUANT_LEVEL = 'L'
        order by 1 desc
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        COUNT_DATE,
        INVENTORY_RECORD,
        INVENTORY_RECORD_ITEM,
        INV_RECOUNT_NUM,
        MATERIAL,
        PLANT,
        WAREHOUSE,
        STORAGE_TYPE,
        STORAGE_BIN,
        STOCK_ON_HAND,
        BUN,
        QTY_COUNTED,
        ALTERNATIVE_UN,
        physical_inventory_indicator_for_cycle_counting,
        INV_METH,
        STANDARD_PRICE,
        PRICE_UNIT,
        UNIT_COST,
        QTY_VAR,
        PERC_QTY_VAR,
        SOH_COST,
        PHYS_CT_COST,
        DOLLAR_VAR
    from source_data
),

type_data as (
    select
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(COUNT_DATE AS DATE) AS COUNT_DATE,
        CAST(INVENTORY_RECORD AS VARCHAR(16777216)) AS INVENTORY_RECORD,
        CAST(INVENTORY_RECORD_ITEM AS VARCHAR(16777216)) AS INVENTORY_RECORD_ITEM,
        CAST(INV_RECOUNT_NUM AS VARCHAR(16777216)) AS INV_RECOUNT_NUM,
        CAST(MATERIAL AS VARCHAR(16777216)) AS MATERIAL,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(WAREHOUSE AS VARCHAR(16777216)) AS WAREHOUSE,
        CAST(STORAGE_TYPE AS VARCHAR(16777216)) AS STORAGE_TYPE,
        CAST(STORAGE_BIN AS VARCHAR(16777216)) AS STORAGE_BIN,
        CAST(STOCK_ON_HAND AS NUMBER(38,10)) AS STOCK_ON_HAND,
        CAST(BUN AS VARCHAR(16777216)) AS BUN,
        CAST(QTY_COUNTED AS NUMBER(38,10)) AS QTY_COUNTED,
        CAST(ALTERNATIVE_UN AS NUMBER(38,10)) AS ALTERNATIVE_UN,
        CAST(PHYSICAL_INVENTORY_INDICATOR_FOR_CYCLE_COUNTING AS VARCHAR(16777216)) AS PHYSICAL_INVENTORY_INDICATOR_FOR_CYCLE_COUNTING,
        CAST(INV_METH AS VARCHAR(16777216)) AS INV_METH,
        CAST(STANDARD_PRICE AS NUMBER(38,10)) AS STANDARD_PRICE,
        CAST(PRICE_UNIT AS NUMBER(38,10)) AS PRICE_UNIT,
        CAST(UNIT_COST AS NUMBER(38,12)) AS UNIT_COST,
        CAST(QTY_VAR AS NUMBER(38,10)) AS QTY_VAR,
        CAST(PERC_QTY_VAR AS NUMBER(38,12)) AS PERC_QTY_VAR,
        CAST(SOH_COST AS NUMBER(38,12)) AS SOH_COST,
        CAST(PHYS_CT_COST AS NUMBER(38,12)) AS PHYS_CT_COST,
        CAST(DOLLAR_VAR AS NUMBER(38,12)) AS DOLLAR_VAR 
    from transform_data
)

select * from type_data
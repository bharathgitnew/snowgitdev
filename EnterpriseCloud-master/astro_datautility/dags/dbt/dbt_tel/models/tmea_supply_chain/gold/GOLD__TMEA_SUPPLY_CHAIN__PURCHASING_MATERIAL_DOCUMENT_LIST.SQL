      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='PURCHASING_MATERIAL_DOCUMENT_LIST',
      transient=false
) }}

WITH source_data as
(
    SELECT
      MSEG.NUMBER_OF_MATERIAL_DOCUMENT,
      MSEG.MATERIAL_DOCUMENT_YEAR,
      MSEG.ITEM_IN_MATERIAL_DOCUMENT,
      MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
      MSEG.MATERIAL_NUMBER,
      MSEG.PLANT,
      MSEG.STORAGE_LOCATION,
      MSEG.ORDER_NUMBER,
      MSEG.SALES_ORDER_NUMBER,
      MSEG.PURCHASE_ORDER_NUMBER,
      MSEG.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
      MSEG.QUANTITY_IN_UNIT_OF_ENTRY,
      MSEG.UNIT_OF_ENTRY,
      MSEG.AMOUNT_IN_LOCAL_CURRENCY,
      MSEG.GOODS_RECIPIENT_SHIP_TO_PARTY,
      MSEG.POSTING_DATE_IN_THE_DOCUMENT as DATE_MATERIAL_WAS_LAST_RECIEVED,
      MKPF.NUMBER_OF_MATERIAL_DOCUMENT as MATERIAL_DOCUMENT,
      MKPF.MATERIAL_DOCUMENT_YEAR as MATERIAL_DOC_YEAR ,
      MKPF.POSTING_DATE_IN_THE_DOCUMENT as POSTING_DATE_IN_THE_DOCUMENT,
      ABS(MSEG.QUANTITY_IN_UNIT_OF_ENTRY) AS QUANTITY_ISSUED,
      SUM(QUANTITY_ISSUED) OVER (
      PARTITION BY MSEG.NUMBER_OF_MATERIAL_DOCUMENT, 
      MSEG.MATERIAL_DOCUMENT_YEAR) AS TOTAL_CONSUMPTION 

      FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__DOCUMENT_SEGMENT_MATERIAL') }} MSEG 
        LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HEADER_MATERIAL_DOCUMENT') }} MKPF ON MKPF.NUMBER_OF_MATERIAL_DOCUMENT = MSEG.NUMBER_OF_MATERIAL_DOCUMENT  
										AND MKPF.MATERIAL_DOCUMENT_YEAR = MSEG.MATERIAL_DOCUMENT_YEAR
      WHERE MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT IN ('261','601')
        AND MSEG.PLANT = '0010'
        AND MKPF.POSTING_DATE_IN_THE_DOCUMENT > '2019-01-01'
)

,transform_data as
(
    SELECT
      '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
      NUMBER_OF_MATERIAL_DOCUMENT,
      MATERIAL_DOCUMENT_YEAR,
      ITEM_IN_MATERIAL_DOCUMENT,
      MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
      MATERIAL_NUMBER,
      PLANT,
      STORAGE_LOCATION,
      ORDER_NUMBER,
      SALES_ORDER_NUMBER,
      PURCHASE_ORDER_NUMBER,
      ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
      QUANTITY_IN_UNIT_OF_ENTRY,
      UNIT_OF_ENTRY,
      AMOUNT_IN_LOCAL_CURRENCY,
      GOODS_RECIPIENT_SHIP_TO_PARTY,
      DATE_MATERIAL_WAS_LAST_RECIEVED,
      MATERIAL_DOCUMENT,
      MATERIAL_DOC_YEAR,
      POSTING_DATE_IN_THE_DOCUMENT,
      QUANTITY_ISSUED,
      TOTAL_CONSUMPTION
  FROM source_data
)

,type_data as (
    SELECT  
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(NUMBER_OF_MATERIAL_DOCUMENT AS VARCHAR(16777216)) AS NUMBER_OF_MATERIAL_DOCUMENT,
        CAST(MATERIAL_DOCUMENT_YEAR AS VARCHAR(16777216)) AS MATERIAL_DOCUMENT_YEAR,
        CAST(ITEM_IN_MATERIAL_DOCUMENT AS VARCHAR(16777216)) AS ITEM_IN_MATERIAL_DOCUMENT,
        CAST(MOVEMENT_TYPE_INVENTORY_MANAGEMENT AS VARCHAR(16777216)) AS MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(STORAGE_LOCATION AS VARCHAR(16777216)) AS STORAGE_LOCATION,
        CAST(ORDER_NUMBER AS VARCHAR(16777216)) AS ORDER_NUMBER,
        CAST(SALES_ORDER_NUMBER AS VARCHAR(16777216)) AS SALES_ORDER_NUMBER,
        CAST(PURCHASE_ORDER_NUMBER AS VARCHAR(16777216)) AS PURCHASE_ORDER_NUMBER,
        CAST(ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS VARCHAR(16777216)) AS ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        CAST(QUANTITY_IN_UNIT_OF_ENTRY AS NUMBER(38,10)) AS QUANTITY_IN_UNIT_OF_ENTRY,
        CAST(UNIT_OF_ENTRY AS VARCHAR(16777216)) AS UNIT_OF_ENTRY,
        CAST(AMOUNT_IN_LOCAL_CURRENCY AS NUMBER(38,10)) AS AMOUNT_IN_LOCAL_CURRENCY,
        CAST(GOODS_RECIPIENT_SHIP_TO_PARTY AS VARCHAR(16777216)) AS GOODS_RECIPIENT_SHIP_TO_PARTY,
        CAST(DATE_MATERIAL_WAS_LAST_RECIEVED AS TIMESTAMP_LTZ(9)) AS DATE_MATERIAL_WAS_LAST_RECIEVED,
        CAST(MATERIAL_DOCUMENT AS VARCHAR(16777216)) AS MATERIAL_DOCUMENT,
        CAST(MATERIAL_DOC_YEAR AS VARCHAR(16777216)) AS MATERIAL_DOC_YEAR,
        CAST(POSTING_DATE_IN_THE_DOCUMENT AS TIMESTAMP_LTZ(9)) AS POSTING_DATE_IN_THE_DOCUMENT,
        CAST(QUANTITY_ISSUED AS NUMBER(38,10)) AS QUANTITY_ISSUED,
        CAST(TOTAL_CONSUMPTION AS NUMBER(38,10)) AS TOTAL_CONSUMPTION
    FROM transform_data
)

SELECT * from type_data
WITH 
HISTORY_PER_PURCHASING_DOCUMENT as (
  SELECT
    CLIENT,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    PURCHASING_DOCUMENT_NUMBER,
    PURCHASE_ORDER_HISTORY_CATEGORY,
    Sum( case DEBIT_CREDIT_INDICATOR when 'S' then QUANTITY else QUANTITY * -1 end )
    as TOTAL_GR_QTY
  FROM
    {{ ref('SILVER__TMEA_SUPPLY_CHAIN__HISTORY_PER_PURCHASING_DOCUMENT') }}
  WHERE
    CLIENT = 300
  AND (  PURCHASE_ORDER_HISTORY_CATEGORY = 'E' )
    And MOVEMENT_TYPE in ( '101','102')
  group by  CLIENT,PURCHASING_DOCUMENT_NUMBER,  ITEM_NUMBER_OF_PURCHASING_DOCUMENT , PURCHASE_ORDER_HISTORY_CATEGORY
),



VENDOR_CONFIRMATIONS as
(
  select
PURCHASING_DOCUMENT_NUMBER,
ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
SEQ_NUM_OF_VENDOR_CONFIRMATION,
DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
sum (QUANTITY_AS_PER_VENDOR_CONFIRMATION - QTY_REDUCED) OVER ( PARTITION BY PURCHASING_DOCUMENT_NUMBER,
ITEM_NUMBER_OF_PURCHASING_DOCUMENT ORDER BY PURCHASING_DOCUMENT_NUMBER,
ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
DELIVERY_DATE_OF_VENDOR_CONFIRMATION  ASC ROWS BETWEEN UNBOUNDED PRECEDING
        AND CURRENT ROW )
as TOTAL_CONF_QTY
from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__VENDOR_CONFIRMATIONS') }}
where QUANTITY_AS_PER_VENDOR_CONFIRMATION - QTY_REDUCED > 0 and  IS_DELETED = 'No'
order by PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT, SEQ_NUM_OF_VENDOR_CONFIRMATION
),
SCHEDULING_AGREEMENT_SCHEDULE_LINES as
(
   select
  PURCHASING_DOCUMENT_NUMBER ,
  ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
  DELIVERY_SCHEDULE_LINE_COUNTER,
  ITEM_DELIVERY_DATE,
  STATISTICS_RELEVANT_DELIVERY_DATE,
  SCHEDULED_QUANTITY,
  SCHEDULED_QUANTITY - QUANTITY_OF_GOODS_RECEIVED as OPEN_GR,
  sum( SCHEDULED_QUANTITY - QUANTITY_OF_GOODS_RECEIVED ) over ( PARTITION BY PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT ORDER BY PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
                    ITEM_DELIVERY_DATE ASC ROWS BETWEEN UNBOUNDED PRECEDING
                    AND CURRENT ROW ) as TOTAL_SCHEDULE_QTY
  from
  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SCHEDULING_AGREEMENT_SCHEDULE_LINES') }}
  where SCHEDULED_QUANTITY - QUANTITY_OF_GOODS_RECEIVED > 0
   and is_DELETED != 'Yes'
  order by PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT , DELIVERY_SCHEDULE_LINE_COUNTER
),
source_data as (
    SELECT

        EKKO.NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
        EKPO.PURCHASING_DOCUMENT_NUMBER,
        EKPO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        TO_NUMBER(EKPO.PURCHASE_ORDER_QUANTITY) AS QTY,
        TO_NUMBER(EKET.SCHEDULED_QUANTITY) AS SCHEDULED_QTY,
        TO_NUMBER(EKET.OPEN_GR) as OPEN_GR,
        TO_NUMBER(EKPO.NET_PRICE_IN_PURCHASING_DOCUMENT,10,2) AS NET_PRICE,
        EKPO.MATERIAL_NUMBER,
        EKPO.SHORT_TEXT,
        LFA1.NAME_1 AS VENDOR_NAME,
        LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
        EKPO.MANUFACTURER_PART_NUMBER,
        EKKO.PURCHASING_GROUP,
        TO_NUMBER(MARC.PLANNED_DELIVERY_TIME_IN_DAYS) AS PLANNED_DELIVERY_TIME_IN_DAYS,
        TO_NUMBER(MARC.GOODS_RECEIPT_PROCESSING_TIME_IN_DAYS) AS GR_PROCESSING_TIME_IN_DAYS,
        EKPO.ORDER_ACKNOWLEDGMENT_REQUIREMENT,
        EKBE.PURCHASE_ORDER_HISTORY_CATEGORY,
        TO_VARCHAR(EKKO.DATE_ON_WHICH_RECORD_WAS_CREATED,'MM/DD/YYYY')AS CREATED_DATE,
        IFF(EKET.ITEM_DELIVERY_DATE = '00000000', NULL, TO_VARCHAR(EKET.ITEM_DELIVERY_DATE,'MM/DD/YYYY')) AS ITEM_DELIVERY_DATE,
        TO_VARCHAR(EKES.DELIVERY_DATE_OF_VENDOR_CONFIRMATION,'MM/DD/YYYY') AS DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
        TO_VARCHAR(IFNULL(DELIVERY_DATE_OF_VENDOR_CONFIRMATION,ITEM_DELIVERY_DATE),'MM/DD/YYYY') AS DELIVERY_DATE,
        IFF(EKET.STATISTICS_RELEVANT_DELIVERY_DATE = '00000000', NULL,TO_VARCHAR(EKET.STATISTICS_RELEVANT_DELIVERY_DATE,'MM/DD/YYYY')) AS NEED_DATE,
        DATEDIFF(DAY,CURRENT_DATE(),DELIVERY_DATE)AS DAYS_PAST_DUE
        FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_HEADER') }} EKKO
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PURCHASING_DOCUMENT_ITEM') }} EKPO ON EKPO.PURCHASING_DOCUMENT_NUMBER = EKKO.PURCHASING_DOCUMENT_NUMBER
        JOIN   SCHEDULING_AGREEMENT_SCHEDULE_LINES EKET ON EKET.PURCHASING_DOCUMENT_NUMBER = EKPO.PURCHASING_DOCUMENT_NUMBER AND EKET.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = EKPO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} MARC ON MARC.MATERIAL_NUMBER = EKPO.MATERIAL_NUMBER AND MARC.PLANT = EKPO.PLANT
        JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__VENDOR_MASTER') }} LFA1 ON LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR = EKKO.VENDORS_ACCOUNT_NUMBER
        LEFT JOIN HISTORY_PER_PURCHASING_DOCUMENT EKBE ON EKBE.PURCHASING_DOCUMENT_NUMBER = EKPO.PURCHASING_DOCUMENT_NUMBER AND EKBE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = EKPO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
        LEFT JOIN VENDOR_CONFIRMATIONS EKES ON EKES.PURCHASING_DOCUMENT_NUMBER = EKET.PURCHASING_DOCUMENT_NUMBER AND EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = EKET.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
        WHERE
        EKPO.PLANT = '0010'
        AND EKPO.STORAGE_LOCATION = '0010'
        AND EKKO.PURCHASING_DOCUMENT_TYPE IN ('NB','ZRT') 
        AND EKKO.PURCHASING_DOC_CATEGORY = 'F'
        AND EKKO.PURCHASING_ORGANIZATION = '0040'
        AND EKPO.DELETION_INDICATOR_IN_PURCHASING_DOCUMENT <> 'L'
        AND EKPO.PURCHASING_DOCUMENT_NUMBER LIKE '00%' OR EKPO.PURCHASING_DOCUMENT_NUMBER LIKE 'RT%' OR  EKPO.PURCHASING_DOCUMENT_NUMBER LIKE 'EN%' OR EKPO.PURCHASING_DOCUMENT_NUMBER LIKE 'ZRT%'
        and EKKO.DATE_ON_WHICH_RECORD_WAS_CREATED >= '2020-01-01'
        and  ( case when EKES.TOTAL_CONF_QTY is NULL then 1 else 0 end or  EKES.TOTAL_CONF_QTY  >= EKET.TOTAL_SCHEDULE_QTY   )
        qualify(row_number() over(partition by EKET.PURCHASING_DOCUMENT_NUMBER,EKET.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,EKET.TOTAL_SCHEDULE_QTY order by EKES.TOTAL_CONF_QTY ))= 1
)

,transform_data as
(
    SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
		NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		PURCHASING_DOCUMENT_NUMBER,
		ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
		QTY,
		SCHEDULED_QTY,
		OPEN_GR,
		NET_PRICE,
		MATERIAL_NUMBER,
		SHORT_TEXT,
		VENDOR_NAME,
    MANUFACTURER_PART_NUMBER,
    ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		PURCHASING_GROUP,
		PLANNED_DELIVERY_TIME_IN_DAYS,
		GR_PROCESSING_TIME_IN_DAYS,
		ORDER_ACKNOWLEDGMENT_REQUIREMENT,
		PURCHASE_ORDER_HISTORY_CATEGORY,
		CREATED_DATE,
		ITEM_DELIVERY_DATE,
		DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
		DELIVERY_DATE,
		NEED_DATE,
		DAYS_PAST_DUE,
    CASE
      WHEN DAYS_PAST_DUE <= '-35' then '> 35 days'
    WHEN DAYS_PAST_DUE <= '-22' then '> 21 days'
    WHEN DAYS_PAST_DUE <= '-15' then '> 14 days'
    WHEN DAYS_PAST_DUE <= '-8' then '> 7 Days' 
    WHEN DAYS_PAST_DUE <= '-1' then '< 7 Days' 
    else 'OK'
    END AS DAYS_PAST_DUE_BUCKETS,
      CASE
    WHEN DAYS_PAST_DUE_BUCKETS = '> 35 days' THEN '1'
    WHEN DAYS_PAST_DUE_BUCKETS= '> 21 days' THEN '2'
    WHEN DAYS_PAST_DUE_BUCKETS= '> 14 days' THEN '3'
    WHEN DAYS_PAST_DUE_BUCKETS=  '> 7 Days' THEN '4'
    WHEN DAYS_PAST_DUE_BUCKETS=  '< 7 Days' THEN '5'
    ELSE  'OK'
    END AS PastDueBucketIndex,  
    CASE
    WHEN DELIVERY_DATE < CURRENT_DATE then 'Past Due' else 'On Track' 
    END AS PO_LINE_STATUS

    FROM source_data
  where CREATED_DATE >= '01/01/2020'
)

,type_data as (
    SELECT
    _AUDIT_LOG_ID,
    _ROW_HASH,
    NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
	  PURCHASING_DOCUMENT_NUMBER,
	  ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
	  QTY,
	  SCHEDULED_QTY,
	  OPEN_GR,
	  NET_PRICE,
	  MATERIAL_NUMBER,
	  SHORT_TEXT,
	  VENDOR_NAME,
	  ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
	  MANUFACTURER_PART_NUMBER,
	  PURCHASING_GROUP,
	  PLANNED_DELIVERY_TIME_IN_DAYS,
	  GR_PROCESSING_TIME_IN_DAYS,
	  ORDER_ACKNOWLEDGMENT_REQUIREMENT,
	  PURCHASE_ORDER_HISTORY_CATEGORY,		
    CAST(CREATED_DATE AS DATE) AS CREATED_DATE,
		CAST(ITEM_DELIVERY_DATE AS DATE) AS ITEM_DELIVERY_DATE,
		CAST(DELIVERY_DATE_OF_VENDOR_CONFIRMATION AS DATE) AS DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
		CAST(DELIVERY_DATE AS DATE) AS DELIVERY_DATE,
		CAST(NEED_DATE AS DATE) AS NEED_DATE,
		CAST(DAYS_PAST_DUE AS NUMBER(38,0)) AS DAYS_PAST_DUE,
    DAYS_PAST_DUE_BUCKETS,
    PastDueBucketIndex,
    PO_LINE_STATUS
    FROM transform_data
)
select * from type_data
	materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
	alias='SUPPLIER_CHANGE_REQUEST_TAT_MILESTONES',
	transient=false
) }}


WITH ref_cte_SUPPL_ACTION_DESCR as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SUPPL_ACTION_DESCR') }}
),

ref_cte_SUPPL_CHANGE_REQUEST as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SUPPL_CHANGE_REQUEST') }}
),

ref_cte_SUPPL_CHG_REQUEST_TRACKER as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SUPPL_CHG_REQUEST_TRACKER') }}
),

ref_cte_SUPPL_USER_INFO as (
    select * from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SUPPL_USER_INFO') }}
),

ONE AS(
select issue_nbr,
REQUEST_ID AS R_ID
from ref_cte_SUPPL_CHANGE_REQUEST
),

TWO AS(
select 
SUPPL_CHG_REQUEST_TRACKER_ID,
SCRT.REQUEST_ID,
SCRT.ACTION_ID AS EVENT_ID,
DESCR AS EVENT,
//SCRT.USERID AS EVENT_BY_ID,
CONCAT(FIRST_NAME, ' ', LAST_NAME) AS EVENT_BY,
ACTION_DT
from ref_cte_SUPPL_CHG_REQUEST_TRACKER   SCRT
LEFT JOIN ref_cte_SUPPL_ACTION_DESCR SAD
    ON SCRT.ACTION_ID = SAD.ACTION_ID
LEFT JOIN ref_cte_SUPPL_USER_INFO    SUI
    ON SCRT.USERID = SUI.USERID
WHERE (EVENT_ID='2' OR EVENT_ID='11' OR EVENT_ID='21' OR EVENT_ID='31' OR EVENT_ID='41') 
),

MAIN AS (
SELECT 
TWO.REQUEST_ID,
ONE.ISSUE_NBR,
TWO.EVENT,
ACTION_DT,
FROM ONE
LEFT JOIN TWO ON R_ID = TWO.REQUEST_ID
ORDER BY ONE.ISSUE_NBR, ACTION_DT
),

source_data as (
SELECT REQUEST_ID,
ISSUE_NBR,
"'Submit (Supplier)'" AS SUBMIT_SUPPLIER,
"'Approve (Quality)'" AS APPROVE_QUALITY,
"'Approve (Technical)'" AS APPROVE_TECHNICAL,
"'Approve (SCS)'" AS APPROVE_SCS,
"'Complete (Collaboration)'" AS COMPLETE_COLLABORATION,
DATEDIFF(DAY,SUBMIT_SUPPLIER,APPROVE_QUALITY) AS SUPPLIER_Q_CT,
DATEDIFF(DAY,APPROVE_QUALITY,APPROVE_TECHNICAL) AS TECH_CT,
DATEDIFF(DAY,APPROVE_TECHNICAL,APPROVE_SCS) AS SCS_CT,
DATEDIFF(DAY,APPROVE_SCS,COMPLETE_COLLABORATION) AS COLLAB_CT,
DATEDIFF(DAY,SUBMIT_SUPPLIER,COMPLETE_COLLABORATION) AS TOTAL_CT
from MAIN
PIVOT(MIN(ACTION_DT) FOR EVENT IN ('Submit (Supplier)','Approve (Quality)','Approve (Technical)','Approve (SCS)','Complete (Collaboration)')) AS P
WHERE REQUEST_ID IS NOT NULL),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	REQUEST_ID,
	ISSUE_NBR,
	SUBMIT_SUPPLIER,
	APPROVE_QUALITY,
	APPROVE_TECHNICAL,
	APPROVE_SCS,
	COMPLETE_COLLABORATION,
	SUPPLIER_Q_CT,
	TECH_CT,
	SCS_CT,
	COLLAB_CT,
	TOTAL_CT
from source_data
),

type_data as (
select
CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
,CAST(REQUEST_ID as NUMBER(38,0)) as REQUEST_ID
,ISSUE_NBR
,CAST(SUBMIT_SUPPLIER as TIMESTAMP_NTZ(9)) as SUBMIT_SUPPLIER
,CAST(APPROVE_QUALITY as TIMESTAMP_NTZ(9)) as APPROVE_QUALITY
,CAST(APPROVE_TECHNICAL as TIMESTAMP_NTZ(9)) as APPROVE_TECHNICAL
,CAST(APPROVE_SCS as TIMESTAMP_NTZ(9)) as APPROVE_SCS
,CAST(COMPLETE_COLLABORATION as TIMESTAMP_NTZ(9)) as COMPLETE_COLLABORATION
,CAST(SUPPLIER_Q_CT as NUMBER(38,0)) as SUPPLIER_Q_CT
,CAST(TECH_CT as NUMBER(38,0)) as TECH_CT
,CAST(SCS_CT as NUMBER(38,0)) as SCS_CT
,CAST(COLLAB_CT as NUMBER(38,0)) as COLLAB_CT
,CAST(TOTAL_CT as NUMBER(38,0)) as TOTAL_CT
from transform_data 
)
select * from type_data
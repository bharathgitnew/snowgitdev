WITH DELIVERY
AS (
	SELECT
    LIKP.CLIENT,
		LIKP.DELIVERY,
		LIKP.REFERENCE_DOCUMENT_NUMBER,
		LIKP.ACTUAL_GOODS_MOVEMENT_DATE,
		LIKP.SHIP_TO_PARTY,
		LIKP.SOLD_TO_PARTY,
		LIKP.DELIVERY_PRIORITY,
		LIKP.ROUTE,
		LIKP.BILL_OF_LADING,
		LIPS.DELIVERY_ITEM,
		LIPS.SHORT_TEXT_FOR_SALES_ORDER_ITEM,
		LIPS.ACTUAL_QUANTITY_DELIVERED_ AS ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS,
		LIPS.NET_PRICE,
		LIPS.BASE_UNIT_OF_MEASURE,
		LIPS.SALES_UNIT,
		LIKP.DELIVERY_TYPE,
		VBUK.TOTAL_GOODS_MOVEMENT_STATUS,
		KNA1.NAME_1 AS NAME_1,
		KNA1.NAME_2 AS NAME_2,
		KNA1.REGION_STATE_PROVINCE_COUNTY,
		KNA1.COUNTRY_KEY
	FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SD_DOCUMENT_DELIVERY_HEADER_DATA') }} AS LIKP
	INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SD_DOCUMENT_DELIVERY_ITEM_DATA') }} AS LIPS ON LIKP.DELIVERY = LIPS.DELIVERY
		AND LIKP.CLIENT = LIPS.CLIENT
	LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_HEADER_STATUS_AND_ADMINISTRATIVE_DATA') }} AS VBUK ON LIKP.DELIVERY = VBUK.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
	LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_DATA_IN_CUSTOMER_MASTER') }} AS KNA1 ON KNA1.CUSTOMER_NUMBER = LIKP.SHIP_TO_PARTY
		AND KNA1.CLIENT = LIKP.CLIENT
	WHERE LIKP.ACTUAL_GOODS_MOVEMENT_DATE is not null
		AND VBUK.TOTAL_GOODS_MOVEMENT_STATUS = 'C'
		AND LIKP.IS_DELETED = 'No'
		AND LIKP.CLIENT = 300
	),

OBJK AS (
		SELECT DISTINCT
      CLIENT,
			MATERIAL_NUMBER,
			SERIAL_NUMBER,
			TABLE_FOR_SERIAL_NUMBERS
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_MAINTENANCE_OBJECT_LIST') }}
		WHERE TABLE_FOR_SERIAL_NUMBERS != 'SER01'
			AND CLIENT = 300
      QUALIFY ROW_NUMBER() OVER (PARTITION BY MATERIAL_NUMBER ORDER BY MATERIAL_NUMBER) = 1
		),

BGMKOBJ AS (
		SELECT
      EQPI.CLIENT,
			EQPI.MATERIAL_NUMBER,
			EQPI.EQUIPMENT_NUMBER,
			EQPI.OBJECT_NUMBER,
			EQPI.SERIAL_NUMBER,
			BGMKOBJ.WARRANTY_DATE,
			BGMKOBJ.DATE_ON_WHICH_THE_WARRANTY_ENDS
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__EQUIPMENT_MASTER_DATA') }} AS EQPI
		LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MASTER_WARRANTY_OBJECT_ASSIGNMENT') }} AS BGMKOBJ ON EQPI.OBJECT_NUMBER = BGMKOBJ.OBJECT_NUMBER
			AND EQPI.CLIENT = BGMKOBJ.CLIENT
		WHERE EQPI.SERIAL_NUMBER <> ''
			AND BGMKOBJ.WARRANTY_DATE is not null
			AND EQPI.CLIENT = '300'
		),

LTAP AS (
		SELECT
      LTAK.CLIENT,
			LTAK.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
			LTAP.WAREHOUSE_NUMBER,
			LTAP.TRANSFER_ORDER_NUMBER,
			LTAP.ITEM_NUMBER_OF_THE_SD_DOCUMENT,
			LTAP.CONFIRMATION_DATE_1
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__TRANSFER_ORDER_ITEM') }} AS LTAP
		INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__WM_TRANSFER_ORDER_HEADER') }} AS LTAK ON LTAK.WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX = LTAP.WAREHOUSE_NUMBER
			AND LTAK.TRANSFER_ORDER_NUMBER = LTAP.TRANSFER_ORDER_NUMBER
			AND LTAK.CLIENT = LTAP.CLIENT
		WHERE LTAK.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER != ' '
			AND LTAP.CLIENT = 300
		),

DOCUMENT_FLOW_DEL AS (
		SELECT
      CLIENT,
			SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT,
			SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT,
			DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT,
			PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
			PRECEDING_ITEM_OF_AN_SD_DOCUMENT,
			REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE,
			LEVEL_OF_THE_DOCUMENT_FLOW_RECORD
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_FLOW') }}
		WHERE DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = 'J'
			AND IS_DELETED = 'No'
			AND CLIENT = 300
		),

DOCUMENT_FLOW_INV AS (
		SELECT
      CLIENT,
			SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT,
			SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT,
			DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT,
			PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
			PRECEDING_ITEM_OF_AN_SD_DOCUMENT,
			REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE,
			LEVEL_OF_THE_DOCUMENT_FLOW_RECORD
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_FLOW') }}
		WHERE DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = 'M'
			AND IS_DELETED = 'No'
			AND CLIENT = 300
		),

DOCUMENT_FLOW_INTERCO AS (
		SELECT
      CLIENT,
			SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT,
			SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT,
			DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT,
			PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
			PRECEDING_ITEM_OF_AN_SD_DOCUMENT,
			REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE,
			LEVEL_OF_THE_DOCUMENT_FLOW_RECORD
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_FLOW') }}
		WHERE DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = '5'
			AND IS_DELETED = 'No'
			AND CLIENT = 300
		),

VBEP_FIRST AS (
		SELECT
      CLIENT,
			SALES_DOCUMENT,
			SALES_DOCUMENT_ITEM,
			SCHEDULE_LINE_DATE,
			CONFIRMED_QUANTITY
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_SCHEDULE_LINE_DATA') }}
		WHERE CLIENT = 300
    QUALIFY ROW_NUMBER() OVER (PARTITION BY SALES_DOCUMENT,SALES_DOCUMENT_ITEM ORDER BY SCHEDULE_LINE_DATE asc) = 1
		),

VBEP_CONF AS (
		SELECT
      CLIENT,
			SALES_DOCUMENT,
			SALES_DOCUMENT_ITEM,
			SCHEDULE_LINE_DATE,
			CONFIRMED_QUANTITY
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_SCHEDULE_LINE_DATA') }}
		WHERE CONFIRMED_QUANTITY <> 0
			AND CLIENT = 300 QUALIFY ROW_NUMBER() OVER (
				PARTITION BY SALES_DOCUMENT,
				SALES_DOCUMENT_ITEM ORDER BY SCHEDULE_LINE_DATE desc
				) = 1
		),

VBPA AS (
		SELECT DISTINCT
      VBPA.CLIENT,
			VBPA.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
			VBPA.CUSTOMER_NUMBER,
			KNA1.NAME_1 AS NAME_1
		FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_PARTNER') }} AS VBPA
		LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_DATA_IN_CUSTOMER_MASTER') }} AS KNA1 ON KNA1.CUSTOMER_NUMBER = VBPA.CUSTOMER_NUMBER
			AND KNA1.CLIENT = VBPA.CLIENT
		WHERE VBPA.PARTNER_FUNCTION = 'Z1'
			AND VBPA.ITEM_NUMBER_OF_THE_SD_DOCUMENT = '000000'
			AND VBPA.CLIENT = 300
		),

SOURCE_DATA AS (
  SELECT
      VBAK.SOLD_TO_PARTY AS SOLD_TO,
	    KNA1_SOLD_TO.NAME_1 AS SOLD_TO_NAME,
	    KNA1_SOLD_TO.REGION_STATE_PROVINCE_COUNTY AS SOLD_TO_STATE,
	    KNA1_SOLD_TO.COUNTRY_KEY AS SOLD_TO_CNTRY,
	    DELIVERY.SHIP_TO_PARTY AS SHIP_TO,
	    DELIVERY.NAME_1 AS SHIP_TO_NAME,
	    DELIVERY.REGION_STATE_PROVINCE_COUNTY AS SHIP_TO_STATE,
	    DELIVERY.COUNTRY_KEY AS SHIP_TO_CNTRY,
	    VBPA.NAME_1 AS ENDUSER,
	    VBAK.SALES_DOCUMENT_TYPE AS ORDER_TYPE,
	    VBAK.SALES_DOCUMENT AS ORDER_NO,
	    CASE
	    	WHEN VBAK.COMPLETE_DELIVERY_DEFINED_FOR_EACH_SALES_ORDER = 'X'
	    		THEN 'NP'
	    	ELSE 'P'
	    	END AS PARTIAL_OR_NO_PARTIAL,
	    DELIVERY.DELIVERY_PRIORITY,
	    VBAK.CUSTOMER_PURCHASE_ORDER_NUMBER AS PO_DETAILS,
	    VBAP.SALES_DOCUMENT_ITEM AS ORDER_ITEM,
	    VBAP.SALES_DOCUMENT_ITEM_CATEGORY AS ITEM_CATEGORY,
	    VBAP.MATERIAL_NUMBER AS MATERIAL,
	    MAKT.MATERIAL_DESCRIPTION AS MATERIAL_DESCRIPTION,
	    MARA.CROSS_PLANT_MATERIAL_STATUS AS STATUS,
	    VBAP.PLANT_OWN_OR_EXTERNAL AS PLANT,
	    T001W.NAME AS PLANT_DESCRIPTION,
	    MBEW.STANDARD_PRICE / MBEW.PRICE_UNIT AS COST_EACH_IN_USD,
	    COST_EACH_IN_USD * DELIVERY.ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS AS EXT_COST_USD,
	    CASE
	    	WHEN VBAK.SD_DOCUMENT_CURRENCY = 'KRW'
	    		THEN DELIVERY.NET_PRICE * 100
	    	ELSE DELIVERY.NET_PRICE
	    	END AS PRICE_EACH,
	    PRICE_EACH * DELIVERY.ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS AS EXTPRICE,
	    VBAK.SD_DOCUMENT_CURRENCY AS ORDER_CURRENCY,
	    MARC.PROFIT_CENTER AS PROFIT_CENTER,
	    MARC.MRP_CONTROLLER_MATERIALS_PLANNER AS PLANNER,
	    MARC.PROCUREMENT_TYPE AS PROCUREMENT_TYPE,
	    VBFA_DEL.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT AS DELIVERY,
	    VBFA_DEL.SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT AS DEL_ITEM,
	    DELIVERY.ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS AS QTY_SHIPPED,
	    DELIVERY.SALES_UNIT AS U_OF_M,
	    VBAP.GROSS_WEIGHT_OF_THE_ITEM AS GROSS_WEIGHT,
	    VBAP.WEIGHT_UNIT AS GROSS_WEIGHT_UNIT,
	    MARC.COMMODITY_CODE_IMPORT_CODE_NUMBER_FOR_FOREIGN_TRADE AS COMMMODITY_CODE,
	    MAEX.EXPORT_CONTROL_CLASS AS ECCN,
	    TVROT.DESCRIPTION_OF_ROUTE AS ROUTE_DESC,
	    DELIVERY.BILL_OF_LADING AS BILL_OF_LADING,
	    VBKD.INCOTERMS_PART_1 AS INCO_1,
	    VBKD.INCOTERMS_PART_2 AS INCO_2,
	    VBAP.DATE_ON_WHICH_RECORD_WAS_CREATED AS BOOK_DATE,
	    VBEP_FIRST.SCHEDULE_LINE_DATE AS FIRST_DATE,
	    VBEP_CONF.SCHEDULE_LINE_DATE AS CONF_DATE,
	    LTAP.CONFIRMATION_DATE_1 AS PICK_DATE,
	    DELIVERY.ACTUAL_GOODS_MOVEMENT_DATE AS SHIP_DATE,
	    MARC.TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS AS TRLT,
	    CASE
	    	WHEN SHIP_DATE = '00000000'
	    		OR FIRST_DATE = '00000000'
	    		THEN 0
	    	ELSE DATEDIFF(DAY, FIRST_DATE, SHIP_DATE)
	    	END AS REQ_SHIP_EL,
	    CASE
	    	WHEN SHIP_DATE = '00000000'
	    		OR CONF_DATE = '00000000'
	    		THEN 0
	    	ELSE DATEDIFF(DAY, CONF_DATE, SHIP_DATE)
	    	END AS CONF_SHIP_EL,
	    CASE
	    	WHEN PICK_DATE = '00000000'
	    		OR FIRST_DATE = '00000000'
	    		THEN 0
	    	ELSE DATEDIFF(DAY, FIRST_DATE, PICK_DATE)
	    	END AS REQ_PICK_EL,
	    CASE
	    	WHEN PICK_DATE = '00000000'
	    		OR CONF_DATE = '00000000'
	    		THEN 0
	    	ELSE DATEDIFF(DAY, CONF_DATE, PICK_DATE)
	    	END AS CONF_PICK_EL,
	    CASE
	    	WHEN SHIP_DATE = '00000000'
	    		OR BOOK_DATE = '00000000'
	    		THEN 0
	    	ELSE DATEDIFF(DAY, BOOK_DATE, SHIP_DATE)
	    	END AS ORDER_SHIP_EL,
	    INTERCO.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT AS INTERCO_INV,
	    VBFA_INV.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT AS SALES_INV,
	    VBRK.BILLING_DATE_FOR_BILLING_INDEX_AND_PRINTOUT AS INV_DATE,
	    VBAK.NAME_OF_PERSON_WHO_CREATED_THE_OBJECT AS CREATED_BY,
	    OBJK.SERIAL_NUMBER,
	    BGMKOBJ.WARRANTY_DATE AS WARR_START,
	    BGMKOBJ.DATE_ON_WHICH_THE_WARRANTY_ENDS AS WARR_END,
	    VBKD.SHIP_TO_PARTY_S_PO_DATE AS ORDER_DATE
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_HEADER_DATA') }} AS VBAK
    INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_ITEM_DATA') }} AS VBAP
	ON VBAK.SALES_DOCUMENT = VBAP.SALES_DOCUMENT
    AND VBAK.CLIENT = VBAP.CLIENT
    LEFT JOIN DOCUMENT_FLOW_DEL AS VBFA_DEL
	ON VBFA_DEL.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT = VBAK.SALES_DOCUMENT
	AND VBFA_DEL.PRECEDING_ITEM_OF_AN_SD_DOCUMENT = VBAP.SALES_DOCUMENT_ITEM
	AND VBFA_DEL.CLIENT = VBAK.CLIENT
    LEFT JOIN DOCUMENT_FLOW_INV AS VBFA_INV
	ON VBFA_INV.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT = VBFA_DEL.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT
	AND VBFA_INV.PRECEDING_ITEM_OF_AN_SD_DOCUMENT = VBFA_DEL.SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT
	AND VBFA_INV.CLIENT = VBAK.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__BILLING_DOCUMENT_HEADER_DATA') }} AS VBRK
	ON VBRK.BILLING_DOCUMENT = VBFA_INV.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT
    LEFT JOIN DELIVERY AS DELIVERY
	ON VBFA_DEL.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT = DELIVERY.DELIVERY
	AND VBFA_DEL.SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT = DELIVERY.DELIVERY_ITEM
    LEFT JOIN VBPA AS VBPA
	ON VBFA_DEL.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT = VBPA.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
	AND VBAK.CLIENT = VBPA.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_BUSINESS_DATA') }} AS VBKD
	ON VBKD.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = VBAK.SALES_DOCUMENT
	AND VBKD.ITEM_NUMBER_OF_THE_SD_DOCUMENT = VBAP.SALES_DOCUMENT_ITEM
    LEFT OUTER JOIN VBEP_FIRST AS VBEP_FIRST
	ON VBEP_FIRST.SALES_DOCUMENT = VBAK.SALES_DOCUMENT
	AND VBEP_FIRST.SALES_DOCUMENT_ITEM = VBAP.SALES_DOCUMENT_ITEM
    LEFT OUTER JOIN VBEP_CONF AS VBEP_CONF
	ON VBEP_CONF.SALES_DOCUMENT = VBAK.SALES_DOCUMENT
	AND VBEP_CONF.SALES_DOCUMENT_ITEM = VBAP.SALES_DOCUMENT_ITEM
    LEFT OUTER JOIN LTAP AS LTAP
	ON LTAP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = DELIVERY.DELIVERY
	AND LTAP.ITEM_NUMBER_OF_THE_SD_DOCUMENT = DELIVERY.DELIVERY_ITEM
    LEFT JOIN DOCUMENT_FLOW_INTERCO AS INTERCO
	ON INTERCO.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT = VBFA_DEL.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT
	AND INTERCO.PRECEDING_ITEM_OF_AN_SD_DOCUMENT = VBFA_DEL.SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT
	AND INTERCO.CLIENT = VBAK.CLIENT
    LEFT JOIN OBJK AS OBJK
	ON OBJK.MATERIAL_NUMBER = VBAP.MATERIAL_NUMBER
	AND OBJK.CLIENT = VBAK.CLIENT
    LEFT JOIN BGMKOBJ AS BGMKOBJ
	ON BGMKOBJ.MATERIAL_NUMBER = VBAP.MATERIAL_NUMBER
	AND BGMKOBJ.SERIAL_NUMBER = OBJK.SERIAL_NUMBER
	AND BGMKOBJ.CLIENT = VBAK.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_VALUATION') }} AS MBEW
	ON VBAP.MATERIAL_NUMBER = MBEW.MATERIAL_NUMBER
	AND VBAP.PLANT_OWN_OR_EXTERNAL = MBEW.VALUATION_AREA
	AND VBAP.CLIENT = MBEW.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} AS MARC
	ON VBAP.MATERIAL_NUMBER = MARC.MATERIAL_NUMBER
	AND VBAP.PLANT_OWN_OR_EXTERNAL = MARC.PLANT
	AND VBAP.CLIENT = MARC.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANTS') }} AS T001W
	ON T001W.PLANT = VBAP.PLANT_OWN_OR_EXTERNAL
	AND VBAP.CLIENT = T001W.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_DATA_IN_CUSTOMER_MASTER') }} AS KNA1_SOLD_TO
	ON KNA1_SOLD_TO.CUSTOMER_NUMBER = VBAK.SOLD_TO_PARTY
	AND KNA1_SOLD_TO.CLIENT = VBAK.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_DESCRIPTIONS') }} AS MAKT
	ON VBAP.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
	AND VBAP.CLIENT = MAKT.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_MASTER_LEGAL_CONTROL') }} AS MAEX
	ON VBAP.MATERIAL_NUMBER = MAEX.MATERIAL_NUMBER
	AND T001W.COUNTRY_KEY = MAEX.DEPARTURE_COUNTRY
    AND VBAP.CLIENT = MAEX.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__GENERAL_MATERIAL_DATA') }} AS MARA
	ON VBAP.MATERIAL_NUMBER = MARA.MATERIAL_NUMBER
	AND VBAP.CLIENT = MARA.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ROUTES_TEXTS') }} AS TVROT
	ON TVROT.ROUTE = DELIVERY.ROUTE
	AND VBAP.CLIENT = TVROT.CLIENT
    WHERE VBAK.CLIENT = '300'
	AND VBAK.SD_DOCUMENT_CATEGORY = 'C'
	AND VBAK.SALES_DOCUMENT_TYPE IN ('ZSPR','ZHOT','ZMAC','ZCSH','ZCSR','ZUPG','ZUPM')
	AND VBAP.SALES_DOCUMENT_ITEM_CATEGORY NOT IN ('ZDRP','ZDRW','ZMDR')
	AND VBAP.REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS != ''
	AND MBEW.VALUATION_TYPE = ' '

),


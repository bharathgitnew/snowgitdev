        INCOTERMS_PART_1,
        INCOTERMS_PART_2,
        DATE_ON_WHICH_RECORD_WAS_CREATED,
        SCHEDULE_LINE_DATE,
        MIN_SCHEDULE_LINE_DATE,
        ACTUAL_GOODS_MOVEMENT_DATE AS ACTUAL_SHIP_DATE,
        YEAR(ACTUAL_GOODS_MOVEMENT_DATE) AS ACTUAL_SHIP_YEAR,
        MONTH(ACTUAL_GOODS_MOVEMENT_DATE) AS ACTUAL_SHIP_MONTH,
        DATE_TRUNC(MONTH, ACTUAL_GOODS_MOVEMENT_DATE) AS ActualShipDate_Start_of_Month,
        DAYOFWEEK (MIN_SCHEDULE_LINE_DATE) AS Confirm_Date_Day_Name,
        BILLING_DOCUMENT,
        BILLING_DATE_FOR_BILLING_INDEX_AND_PRINTOUT,
        BILLING_HEADER_CREATEDBY,
        EXPECTED_SHIP_DATE,
        EXPECTED_LEAD_TM_DAYS,
        ACTUAL_LEAD_TM_DAYS,
        ON_TM_LEAD_TM_DAYS,
        ON_TIME_COMMIT,
        BOOK_DATE_ADJUSTED,
        ACTUAL_LEAD_TM_WORK_DAYS,
CASE 
WHEN DELIVERY_PRIORITY = '01' then 'Emergency'
WHEN DELIVERY_PRIORITY = '02' then 'Rush' 
WHEN DELIVERY_PRIORITY = '03' then 'Expedite'
WHEN DELIVERY_PRIORITY = '99'  then 'Standard' 
END AS Priority,

CASE 
WHEN SOLDTO_CUSTOMER = 9369 then 'TEE'
WHEN SOLDTO_CUSTOMER = 9390 then 'TEA' 
WHEN SOLDTO_CUSTOMER = 9805 then 'TSI'
WHEN SOLDTO_CUSTOMER = 10061 then 'TEL/TFE'
WHEN SOLDTO_CUSTOMER = 10102 then 'TES'
WHEN SOLDTO_CUSTOMER = 9374 then 'TET' 
WHEN SOLDTO_CUSTOMER = 9379 then 'TEK' else 'NO GENPO'
END AS GENPO
    from source_data
WHERE SALES_DOCUMENT_TYPE IN ('ZSPR','ZHOT')
AND ACTUAL_SHIP_DATE >= '2020-01-01'
),


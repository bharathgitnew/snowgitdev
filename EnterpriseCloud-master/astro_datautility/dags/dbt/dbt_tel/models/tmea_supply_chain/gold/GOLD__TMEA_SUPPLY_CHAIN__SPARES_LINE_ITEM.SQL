        SOLDTO_COMPLETE_DELIVERY_DEFINED_FOR_EACH_SALES_ORDER,
        DELIVERY_PRIORITY,
        SALES_DOCUMENT_ITEM_CATEGORY,
        PRICE_EA,
        EXTD_PRICE AS REVENUE,

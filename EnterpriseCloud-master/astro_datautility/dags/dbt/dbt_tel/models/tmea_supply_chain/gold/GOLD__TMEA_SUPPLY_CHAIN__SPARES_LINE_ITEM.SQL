    select
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
        CLIENT,
        DELIVERY,
        DELIVERY_ITEM,
        PLANT,
        PROFIT_CENTER,
        SOLDTO_CUSTOMER,
        COMPANY,
        SHIPTO_CUSTOMER,

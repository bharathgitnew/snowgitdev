WITH Material_plant as
(
    SELECT
        MATERIAL_PLANT.CLIENT AS CLIENT,
        MATERIAL_PLANT.MATERIAL_NUMBER AS MATERIAL_NUMBER,
        MATERIAL_PLANT.PLANT AS PLANT,
        MAKT.MATERIAL_DESCRIPTION,
        MLT.EXPORT_CONTROL_CLASS,
        MATERIAL_PLANT.TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS
    from {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANT_DATA_FOR_MATERIAL') }} AS MATERIAL_PLANT
    left join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__PLANTS') }} as PLANTS
    on MATERIAL_PLANT.PLANT = PLANTS.PLANT AND MATERIAL_PLANT.CLIENT = PLANTS.CLIENT
    left join {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_DESCRIPTIONS') }} as MAKT
    on MATERIAL_PLANT.MATERIAL_NUMBER  = MAKT.MATERIAL_NUMBER
    LEFT OUTER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__MATERIAL_MASTER_LEGAL_CONTROL') }} as MLT
    ON MATERIAL_PLANT.MATERIAL_NUMBER  = MLT.MATERIAL_NUMBER
    AND   PLANTS.COUNTRY_KEY =  MLT.DEPARTURE_COUNTRY
    AND  MATERIAL_PLANT.CLIENT =  MLT.CLIENT
),

DDI_QTY AS
(
	SELECT
        DDI.CLIENT,
        DDI.DELIVERY,
        DDI.DELIVERY_ITEM,
        DDI.PLANT ,
        SDH.SOLD_TO_PARTY AS SOLDTO_CUSTOMER,
        SDH.COMPANY_CODE_TO_BE_BILLED as COMPANY,
        DDH.SHIP_TO_PARTY AS SHIPTO_CUSTOMER,
        DDI.MATERIAL_NUMBER,
        MLT.MATERIAL_DESCRIPTION as MATERIAL_DESCRIPTION,
        DDI.PROFIT_CENTER,
        DDI.NAME_OF_PERSON_WHO_CREATED_THE_OBJECT as DOCUMENT_ITEM_CREATEDB,
        SDH.SALES_DOCUMENT_TYPE,
        SDI.SALES_DOCUMENT,
        SDI.SALES_DOCUMENT_ITEM,
        SDH.CUSTOMER_PURCHASE_ORDER_NUMBER AS SOLDTO_CUSTOMER_PURCHASE_ORDER_NUMBER,
        SDH.COMPLETE_DELIVERY_DEFINED_FOR_EACH_SALES_ORDER AS SOLDTO_COMPLETE_DELIVERY_DEFINED_FOR_EACH_SALES_ORDER,
        SDI.DELIVERY_PRIORITY,
        SDI.SALES_DOCUMENT_ITEM_CATEGORY,
        CASE WHEN SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS = 0 THEN 0 ELSE
        ( SDI.SUBTOTAL_2_FROM_PRICING_PROCEDURE_FOR_CONDITION / SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS )
        end as PRICE_EA,
        CASE WHEN SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS = 0 THEN 0 ELSE
        DDI.ACTUAL_QUANTITY_DELIVERED_ * (SDI.SUBTOTAL_2_FROM_PRICING_PROCEDURE_FOR_CONDITION / SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS) END AS EXTD_PRICE,
        CASE WHEN SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS = 0 THEN 0
        ELSE ( SDI.COST_IN_DOCUMENT_CURRENCY / SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS ) end as COST_EA,
        CASE WHEN SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS = 0 THEN 0
        ELSE DDI.ACTUAL_QUANTITY_DELIVERED_ * (SDI.COST_IN_DOCUMENT_CURRENCY / SDI.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS)
        END AS EXTD_COST,
        SDI.SD_DOCUMENT_CURRENCY,
        DDI.ACTUAL_QUANTITY_DELIVERED_ as ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS,
        DDI.SALES_UNIT,
        DDI.BASE_UNIT_OF_MEASURE,
        DDI.GROSS_WEIGHT,
        DDI.WEIGHT_UNIT AS WEIGHT_UNIT_GEWEI,
        MLT.EXPORT_CONTROL_CLASS as EXPORT_CLASS_CONTROL ,
        DDH.ROUTE,
        RUT.DESCRIPTION_OF_ROUTE,
        DDH.BILL_OF_LADING,
        DDH.INCOTERMS_ AS INCOTERMS_PART_1,
        DDH.INCO2_INCOTERMS_ AS INCOTERMS_PART_2,
        SDI.DATE_ON_WHICH_RECORD_WAS_CREATED AS DATE_ON_WHICH_RECORD_WAS_CREATED,
        SCHEDULE_LINE_DATE AS SCHEDULE_LINE_DATE,
        ACTUAL_GOODS_MOVEMENT_DATE as ACTUAL_GOODS_MOVEMENT_DATE,
        BILLING_INFO.BILLING_DOCUMENT,
        BILLING_INFO.BILLING_DATE_FOR_BILLING_INDEX_AND_PRINTOUT as BILLING_DATE_FOR_BILLING_INDEX_AND_PRINTOUT,
        BILLING_INFO.BILLING_HEADER_CREATEDBY,
        TO_DATE(DATEADD('DAY', (MLT.TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS +
                                (( MLT.TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS / 5 ) * 2 )),SDI.DATE_ON_WHICH_RECORD_WAS_CREATED)) AS EXPECTED_SHIP_DATE,
        DATEDIFF('DAY', SDI.DATE_ON_WHICH_RECORD_WAS_CREATED,EXPECTED_SHIP_DATE) AS EXPECTED_LEAD_TM_DAYS,
        DATEDIFF('DAY',SDI.DATE_ON_WHICH_RECORD_WAS_CREATED,DDH.ACTUAL_GOODS_MOVEMENT_DATE) AS ACTUAL_LEAD_TM_DAYS,
        EXPECTED_LEAD_TM_DAYS -	ACTUAL_LEAD_TM_DAYS as ON_TM_LEAD_TM_DAYS,
        CASE WHEN DAYNAME ( SDI.DATE_ON_WHICH_RECORD_WAS_CREATED ) IN ( 'SAT' , 'SUN' ) THEN
        TO_DATE ( NEXT_DAY (SDI.DATE_ON_WHICH_RECORD_WAS_CREATED , 'MONDAY ' ) )
        ELSE TO_DATE ( SDI.DATE_ON_WHICH_RECORD_WAS_CREATED) END AS BOOK_DATE_ADJUSTED,
        ACTUAL_LEAD_TM_DAYS - 	DATEDIFF(WEEK, SDI.DATE_ON_WHICH_RECORD_WAS_CREATED, DDH.ACTUAL_GOODS_MOVEMENT_DATE)*2 AS ACTUAL_LEAD_TM_WORK_DAYS,
        SUM(ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS) OVER
        (PARTITION BY SDI.SALES_DOCUMENT, DDI.ITEM_NUMBER_OF_THE_REFERENCE_ITEM
                ORDER BY DDI.DELIVERY, DDI.DELIVERY_ITEM, SDI.SALES_DOCUMENT,
                    DDI.ITEM_NUMBER_OF_THE_REFERENCE_ITEM,DDI.DATE_ON_WHICH_RECORD_WAS_CREATED ASC ROWS
                BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) TOTALQTY,

        TOTALQTY - ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS STARTRANGE1

    FROM  {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SD_DOCUMENT_DELIVERY_ITEM_DATA') }} AS DDI
    INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SD_DOCUMENT_DELIVERY_HEADER_DATA') }} AS DDH
    ON DDI.DELIVERY = DDH.DELIVERY AND DDI.CLIENT = DDH.CLIENT
    INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_HEADER_DATA') }} AS SDH
    ON SDH.SALES_DOCUMENT = DDI.DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT AND DDI.CLIENT = SDH.CLIENT
    INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_ITEM_DATA') }} AS SDI ON SDI.SALES_DOCUMENT = DDI.DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT
    AND SDI.SALES_DOCUMENT_ITEM = DDI.ITEM_NUMBER_OF_THE_REFERENCE_ITEM AND DDI.CLIENT = SDI.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_PARTNER') }} SDTC ON SDTC.PARTNER_FUNCTION = 'SOLDTO' AND
    SDTC.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = SDI.SALES_DOCUMENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_PARTNER') }} SHTC ON SHTC.PARTNER_FUNCTION = 'SHIPTO' AND
    SHTC.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = SDI.SALES_DOCUMENT
    Left join Material_plant as MLT on
    DDI.PLANT  = MLT.PLANT and
    DDI.MATERIAL_NUMBER  = MLT.MATERIAL_NUMBER and
    DDI.CLIENT =  MLT.CLIENT
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__ROUTES_TEXTS') }} AS RUT ON DDH.ROUTE = RUT.ROUTE
    LEFT JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_SCHEDULE_LINE_DATA') }} AS SDS ON
    SDI.SALES_DOCUMENT = SDS.SALES_DOCUMENT AND SDS.SCHEDULE_LINE_NUMBER = '0001' AND
    SDI.SALES_DOCUMENT_ITEM = SDS.SALES_DOCUMENT_ITEM
    LEFT JOIN (
                SELECT DISTINCT BDH.CLIENT, BILLING_DOCUMENT,
                BDH.BILLING_DATE_FOR_BILLING_INDEX_AND_PRINTOUT,
                BDH.NAME_OF_PERSON_WHO_CREATED_THE_OBJECT AS BILLING_HEADER_CREATEDBY,
                SDF.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
                SDF.PRECEDING_ITEM_OF_AN_SD_DOCUMENT
                    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__BILLING_DOCUMENT_HEADER_DATA') }} BDH
                    INNER JOIN {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_FLOW') }} SDF
        ON BILLING_DOCUMENT = SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT AND BDH.CLIENT = SDF.CLIENT
            )  BILLING_INFO
    ON BILLING_INFO.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT = DDI.DELIVERY AND
    BILLING_INFO.PRECEDING_ITEM_OF_AN_SD_DOCUMENT = DDI.DELIVERY_ITEM
    where DDI.IS_DELETED = 'No'
),

SQ as (
    SELECT
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        SCHEDULE_LINE_DATE AS MIN_SCHEDULE_LINE_DATE,
        SUM( SALES_DOCUMENT_SCHEDULE_LINE_DATA.CONFIRMED_QUANTITY )
                OVER (PARTITION BY  SALES_DOCUMENT_SCHEDULE_LINE_DATA.CLIENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT_ITEM
                ORDER BY  SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SCHEDULE_LINE_DATE  ASC
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) - SALES_DOCUMENT_SCHEDULE_LINE_DATA.CONFIRMED_QUANTITY as
                STARTRANGE,
        SUM( SALES_DOCUMENT_SCHEDULE_LINE_DATA.CONFIRMED_QUANTITY )
                OVER (PARTITION BY  SALES_DOCUMENT_SCHEDULE_LINE_DATA.CLIENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT_ITEM
                ORDER BY  SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SALES_DOCUMENT ,
                SALES_DOCUMENT_SCHEDULE_LINE_DATA.SCHEDULE_LINE_DATE  ASC
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS TOTALQTY_SCHEDULE
    FROM {{ ref('SILVER__TMEA_SUPPLY_CHAIN__SALES_DOCUMENT_SCHEDULE_LINE_DATA') }} WHERE CONFIRMED_QUANTITY > 0
),

source_data as (
    SELECT
        DDIQTY.CLIENT,DELIVERY,DELIVERY_ITEM,PLANT,SOLDTO_CUSTOMER,COMPANY,SHIPTO_CUSTOMER,MATERIAL_NUMBER,MATERIAL_DESCRIPTION,PROFIT_CENTER,
        DOCUMENT_ITEM_CREATEDB,DDIQTY.SALES_DOCUMENT_TYPE,DDIQTY.SALES_DOCUMENT,
        DDIQTY.SALES_DOCUMENT_ITEM,SOLDTO_CUSTOMER_PURCHASE_ORDER_NUMBER,SOLDTO_COMPLETE_DELIVERY_DEFINED_FOR_EACH_SALES_ORDER,
        DELIVERY_PRIORITY,SALES_DOCUMENT_ITEM_CATEGORY,PRICE_EA,EXTD_PRICE,DDIQTY.COST_EA,
        EXTD_COST,SD_DOCUMENT_CURRENCY,
        ACTUAL_QUANTITY_DELIVERED_IN_SALES_UNITS,SALES_UNIT,BASE_UNIT_OF_MEASURE,GROSS_WEIGHT,WEIGHT_UNIT_GEWEI,
        EXPORT_CLASS_CONTROL,ROUTE,DESCRIPTION_OF_ROUTE,BILL_OF_LADING,INCOTERMS_PART_1,INCOTERMS_PART_2,
        DATE_ON_WHICH_RECORD_WAS_CREATED,DDIQTY.SCHEDULE_LINE_DATE,
        SQ.MIN_SCHEDULE_LINE_DATE AS MIN_SCHEDULE_LINE_DATE,
        ACTUAL_GOODS_MOVEMENT_DATE,BILLING_DOCUMENT,BILLING_DATE_FOR_BILLING_INDEX_AND_PRINTOUT,BILLING_HEADER_CREATEDBY,
        EXPECTED_SHIP_DATE,EXPECTED_LEAD_TM_DAYS,ACTUAL_LEAD_TM_DAYS,ON_TM_LEAD_TM_DAYS,
        DATEDIFF('DAY', MIN_SCHEDULE_LINE_DATE, ACTUAL_GOODS_MOVEMENT_DATE) AS ON_TIME_COMMIT,
        BOOK_DATE_ADJUSTED,
        ACTUAL_LEAD_TM_WORK_DAYS
    FROM DDI_QTY DDIQTY
    INNER JOIN  SQ ON DDIQTY.SALES_DOCUMENT = SQ.SALES_DOCUMENT AND DDIQTY.SALES_DOCUMENT_ITEM =
    SQ.SALES_DOCUMENT_ITEM
    WHERE ((((STARTRANGE1 = 0 AND STARTRANGE = 0 ) OR ( STARTRANGE1 >=STARTRANGE)) AND TOTALQTY<=TOTALQTY_SCHEDULE )
    OR ((STARTRANGE1 < TOTALQTY_SCHEDULE)AND (TOTALQTY >STARTRANGE AND STARTRANGE1 >=STARTRANGE )))
  	AND DATE_ON_WHICH_RECORD_WAS_CREATED > '2020-01-01'
	--AND SALES_DOCUMENT_TYPE IN ('ZSPR','ZHOT','ZRET')
),


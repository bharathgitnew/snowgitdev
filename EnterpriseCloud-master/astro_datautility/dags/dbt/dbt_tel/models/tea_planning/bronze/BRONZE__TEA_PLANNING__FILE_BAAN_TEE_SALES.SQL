{{ config(
        materialized='tel_incremental'    ,
    incremental_strategy='insert_overwrite'    ,
    alias='FILE_BAAN_TEE_SALES'    ,
    enabled=true
) }}
 -- unique_key= ['ORDER_NUMBER',
    --  'LINE_NUMBER']    ,
WITH 
RANKED AS (
    SELECT 
        _FILEDATE AS _FILEDATE,
        T$ORNO AS ORDER_NUMBER,
        T$PONO AS LINE_NUMBER,
        ITEM AS MATERIAL_NUMBER,
        TRY_CAST(T$PRIC AS FLOAT) * TRY_CAST(TRIM(T$OQUA, '"') AS INT) AS ORDER_AMT,
        T$OQUA AS ORDER_QUANTITY,
        T$DQUA AS DELIVERY_QUANTITY,
        T$ODAT AS ORDER_DATE,
        T$DDAT AS DELIVERY_DATE,
        CANCELLED,
        PRIORITY,
        YEARMONTH AS PERIOD,
        T$CUNO AS SOLD_TO_BP,
        ROW_NUMBER() OVER (PARTITION BY T$ORNO, T$PONO ORDER BY _FILEDATE DESC) AS RN
    FROM {{ source('FILE', 'BAAN_TEE_SALES') }}
    WHERE T$ORNO != 'T$ORNO' AND T$PONO != 'T$PONO' AND _FILEDATE=(SELECT MAX(_FILEDATE) FROM {{ source('FILE', 'BAAN_TEE_SALES') }})  
),
SOURCE_DATA AS (
    SELECT * FROM RANKED WHERE RN = 1
),
TRANSFORM_DATA AS (
    SELECT
        _FILEDATE,
        ORDER_NUMBER,
        LINE_NUMBER,
        TRIM(MATERIAL_NUMBER, '"') AS MATERIAL_NUMBER,
        ORDER_AMT,
        TRY_CAST(TRIM(ORDER_QUANTITY, '"') AS INT) AS ORDER_QUANTITY,
        TRY_CAST(TRIM(DELIVERY_QUANTITY, '"') AS INT) AS DELIVERY_QUANTITY,
        TRY_TO_DATE(ORDER_DATE, 'DD/MM/YYYY') AS ORDER_DATE,
        TRY_TO_DATE(DELIVERY_DATE, 'DD/MM/YYYY') AS DELIVERY_DATE,
        TRIM(CANCELLED, '"') AS CANCELLED,
        TRIM(PRIORITY, '"') AS PRIORITY,
        TRIM(PERIOD, '"') AS PERIOD,
        SOLD_TO_BP,
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH -- Adds column to table on full refresh.
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        CAST(_FILEDATE AS VARCHAR(16777216)) AS _FILEDATE,
        CAST(_AUDIT_LOG_ID AS VARCHAR(16777216)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH,
        ORDER_NUMBER,
        LINE_NUMBER,
        MATERIAL_NUMBER,
        CAST(ORDER_AMT AS FLOAT) AS ORDER_AMT,
        CAST(ORDER_QUANTITY AS INT) AS ORDER_QUANTITY,
        CAST(DELIVERY_QUANTITY AS INT) AS DELIVERY_QUANTITY,
        CAST(ORDER_DATE AS DATE) AS ORDER_DATE,
        CAST(DELIVERY_DATE AS DATE) AS DELIVERY_DATE,
        CANCELLED,
        PRIORITY,
        PERIOD,
        SOLD_TO_BP
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
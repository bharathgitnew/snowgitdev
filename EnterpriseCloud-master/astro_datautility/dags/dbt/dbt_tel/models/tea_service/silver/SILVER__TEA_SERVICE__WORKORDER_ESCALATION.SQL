QRY_EmployeeEscalation as (
    SELECT 
        EscalationEmployee.Tel_Com_EscalationIssue
        ,listagg(EscalationEmployee.tel_com_useryominame,',') EmployeeNameList
        ,listagg(EMployee.employeeid,',') EmployeeIdList
    FROM TEL_COM_ESCALATIONTEAMMEMBER_REF EscalationEmployee
    JOIN SYSTEMUSER_REF EMployee
        ON Employee.Id = EscalationEmployee.tel_com_user
        AND EscalationEmployee.tel_com_role  = '100001000'
    GROUP BY EscalationEmployee.Tel_Com_EscalationIssue 
),

MAXDate1 as (
    SELECT 
        tel_com_escalationissue,
        MAX( createdon ) AS maxCreatedon  
    FROM WO_WORKORDERACTIVITY_REF
    WHERE  tel_com_escalationissue  IS NOT NULL
        AND  wo_note  IS NOT NULL
    GROUP BY  tel_com_escalationissue 
),

QRY_LastActivity as (
    SELECT
        MaxRow.tel_com_escalationissue,
        MaxRow.wo_note,
        MaxRow.createdon  
    FROM WO_WORKORDERACTIVITY_REF MaxRow
    JOIN MAXDate1 
        ON   MAXDate1.tel_com_escalationissue  =  MaxRow.tel_com_escalationissue  
        and  MAXDate1.maxCreatedon  =  MaxRow.createdon 
),

MAXDate2 as (
    SELECT
        tel_com_escalationissue,
        MAX( createdon ) AS maxCreatedon
    FROM WO_WORKORDERACTIVITY_REF
    WHERE  tel_com_escalationissue  IS NOT NULL
        AND  wo_nextactionr  IS NOT NULL
    GROUP BY  tel_com_escalationissue
),

QRY_NextActivity as (
    SELECT
        MaxRow.tel_com_escalationissue,
        MaxRow.wo_nextactionr,
        MaxRow.createdon
    FROM WO_WORKORDERACTIVITY_REF MaxRow
    JOIN MAXDate2
        ON   MAXDate2.tel_com_escalationissue  =  MaxRow.tel_com_escalationissue
        and  MAXDate2.maxCreatedon  =  MaxRow.createdon
),

source_data as (
    SELECT
        CASE11.TICKETNUMBER AS CASE_NO,
        CASESTATUS.LOCALIZEDLABEL AS CASE_STATUS,
        CASE11.TITLE AS CASE_TITLE,
        CASETYPE.LOCALIZEDLABEL AS CASE_TYPE,
        CASE 
            WHEN   ESCALATIONISSUE.TEL_COM_CLOSED   = 0 THEN 'No' 
            ELSE 'Yes' 
        END AS CLOSED,
        ESCALATIONISSUE.TEL_COM_CLOSE_DATE_TIME_RTISSQVICS AS CLOSED_DATE_RTISS_QVICS,
        ESCALATIONISSUE.TEL_COM_CLOSEDATETIME AS CLOSED_ON,
        ESCALATIONISSUE.TEL_COM_PERMANENTSOLUTION AS CONFIRMED_SOLUTION,
        ESCALATIONISSUE.TEL_COM_COUNTERMEASURERESOLUTION AS COUNTER_MEASURE_RESOLUTION,
        CREATEDBY.FULLNAME AS CREATED_BY,
        CREATEDBY.EMPLOYEEID AS CREATED_BY_EMP_ID,
        ESCALATIONISSUE.CREATEDON AS CREATED_ON,
        STATE.STATE AS CRM_STATUS,
        CASE 
            WHEN LENGTH(  ACCOUNT.ACCOUNTNUMBER  ) = 9 THEN   PARENT.ADDRESS2_CITY   
            else   ACCOUNT.ADDRESS2_CITY   
        END as CUSTOMER_ADDRESS_CITY,
        CASE 
            WHEN LENGTH(  ACCOUNT.ACCOUNTNUMBER  ) = 9 THEN   PARENT.ADDRESS2_COUNTRY  
            else  ACCOUNT.ADDRESS2_COUNTRY 
        END as CUSTOMER_ADDRESS_COUNTRY,
        CASE 
            WHEN LENGTH(  ACCOUNT.ACCOUNTNUMBER  ) = 9 THEN   PARENT.ADDRESS2_LINE1   
            else   ACCOUNT.ADDRESS2_LINE1  
        END AS CUSTOMER_ADDRESS_LINE1 ,
        CASE 
            WHEN LENGTH(  ACCOUNT.ACCOUNTNUMBER ) = 9 THEN    PARENT.ADDRESS2_LINE2   
            else    ACCOUNT.ADDRESS2_LINE2   
        END AS CUSTOMER_ADDRESS_LINE2,
        CASE 
            WHEN LENGTH(  ACCOUNT.ACCOUNTNUMBER  ) = 9 THEN    PARENT.ADDRESS2_LINE3  
            else    ACCOUNT.ADDRESS2_LINE3   
        END AS CUSTOMER_ADDRESS_LINE3,
        CASE 
            WHEN LENGTH( ACCOUNT.ACCOUNTNUMBER   ) = 9 THEN   PARENT.ADDRESS2_STATEORPROVINCE  
            else   ACCOUNT.ADDRESS2_STATEORPROVINCE   
        END AS CUSTOMER_ADDRESS_STATE,
        CASE 
            WHEN LENGTH(  ACCOUNT.ACCOUNTNUMBER  ) = 9 THEN   PARENT.ADDRESS2_POSTALCODE 
            else   ACCOUNT.ADDRESS2_POSTALCODE 
        END AS CUSTOMER_ADDRESS_ZIP_CODE,
        ESCALATIONISSUE.TEL_COM_DAYSESCALATED AS DAYS_ESCALATED,
        ESCALATIONISSUE.TEL_COM_DETAILINFORMATION AS DETAIL_INFORMATION,
        ESCALATIONCATEGORY.TEL_COM_NAME AS ESCALATION_CATEGORY,
        ESCALATIONCATEGORY.TEL_COM_NAME AS ESCALATION_CATEGORY_CONFIRMED,
        ESCALATIONISSUE.TEL_COM_ESCALATIONENDDATETIME AS ESCALATION_END,
        ESCALATIONLEVEL.TEL_COM_NAME AS ESCALATION_LEVEL,
        ESCALATIONREASON.TEL_COM_NAME AS ESCALATION_REASON,
        ESCALATIONREASONF.TEL_COM_NAME AS ESCALATION_REASON_CONFIRMED,
        ESCALATIONISSUE.TEL_COM_ESCALATIONSTARTDATETIME AS ESCALATION_START,
        ESCALATIONISSUE.TEL_COM_ESCALATIONTITLEPROBLEMSTATEMENT AS ESCALATION_TITLE,
        ACCOUNT.NAME AS FAB,
        CASE 
            WHEN LENGTH(  ACCOUNT.ACCOUNTNUMBER  ) = 9 THEN   PARENT2.NAME  
            WHEN LENGTH(   ACCOUNT.ACCOUNTNUMBER  ) = 7 THEN    PARENT2.NAME  
        END AS GROUP_COMPANY_FAB,
        ESCALATIONISSUE.ID AS GUID,
        ESCALATIONISSUE.TEL_COM_IMPACTEFFECTSONTHECUSTOMER AS IMPACTS_EFFECTS_ON_CUSTOMER,
        ESCALATIONISSUE.TEL_COM_OPEN_DATE_TIME_OF_RTISSQVICS AS ISSUED_DATE_RTISS_QVICS,
        ESCALATIONISSUE.TEL_COM_NAME AS ISSUE_NO,
        EQUIPMENT.COM_SONO AS MACHINE_SERIAL_NO,
        MODIFIEDBY.FULLNAME AS MODIFIED_BY,
        MODIFIEDBY.EMPLOYEEID AS MODIFIED_BY_EMP_ID,
        ESCALATIONISSUE.MODIFIEDON AS MODIFIED_ON,
        QRY_NextActivity.CREATEDON AS MODIFIED_ON_FOR_NEXT_ACTION,
        QRY_LastActivity.CREATEDON AS MODIFIED_ON_FOR_OUTCOME,
        QRY_NextActivity.WO_NEXTACTIONR AS NEXT_ACTION,
        OEL.FULLNAME AS OEL,
        OEL.EMPLOYEEID AS OEL_EMP_ID,
        QRY_LastActivity.WO_NOTE AS OUTCOME,
        CASE 
            WHEN   ESCALATIONISSUE.OWNINGUSER_ENTITYTYPE   = 'systemuser' THEN   OWNERU.FULLNAME 
            WHEN   ESCALATIONISSUE.OWNERID_ENTITYTYPE   = 'team' THEN   OWNERT.NAME   
        END as OWNER,
        ESCALATIONISSUE.TEL_COM_PROBLEMOCCURREDDATETIME AS PROBLEM_OCCURRED,
        PRODUCTLINE.COM_BUNAME AS PRODUCT_LINE,
        ESCALATIONISSUE.TEL_COM_PROGRESSDATE AS PROGRESS_DATE,
        ESCALATIONISSUE.OVERRIDDENCREATEDON AS RECORD_CREATED_ON,
        ESCALATIONISSUE.TEL_COM_RECOVERYDATETIME AS RECOVERED_ON,
        REGION.NAME AS REGION,
        ESCALATIONISSUE.TEL_COM_RELATEDEQUIPMENT AS RELATED_EQUIPMENT,
        ESCALATIONISSUE.TEL_COM_RESPONSIBLEPARTY AS RESPONSIBLE_PARTY,
        ESCALATIONISSUE.TEL_COM_RESULT AS RESULT,
        ESCALATIONISSUE.TEL_COM_RTISSQVICSNO AS RTISS_QVICS_NO,
        ESCALATIONISSUE.TEL_COM_URL_RTISSQVICS AS RTISS_QVICS_URL,
        ESCALATIONISSUE.TEL_COM_SAFETYMEMO AS SAFETY_MEMO,
        ESCALATIONISSUE.TEL_COM_SAFETYTIRSNUMBER AS SAFETY_TIRS_NO,
        STATUSREASON.LOCALIZEDLABEL AS STATUS_REASON,
        ESCALATIONISSUE.TEL_COM_STATUSID_RTISSQVICS AS STATUS_RTISS_QVICS,
        ESCALATIONISSUE.TEL_COM_SUCCESSCRITERIA AS SUCCESS_CRITERIA,
        ESCALATIONISSUE.TEL_COM_SUMMARYFOREXECUTIVE AS SUMMARY_FOR_EXECUTIVE,
        ESCALATIONISSUE.TEL_COM_SUMMARYFORGSM AS SUMMARY_FOR_GSM,
        ESCALATIONISSUE.TEL_COM_SUMMARYFORTELEXECUTIVE AS SUMMARY_FOR_TEL_EXECUTIVE,
        ESCALATIONISSUE.TEL_COM_ASSUMEDCAUSE AS SUSPECTED_CAUSE,
        SYSTEMTYPE.COM_NAME AS SYSTEM_NAME,
        ESCALATIONISSUE.TEL_COM_TARGETENDDATEANDTIME AS TARGET_END,
        EQUIPMENT.COM_TOOLID_EN AS TOOL_ID,
        QRY_EmployeeEscalation.EMPLOYEENAMELIST AS TSS,
        QRY_EmployeeEscalation.EMPLOYEEIDLIST AS TSS_EMP_ID,
        CASE 
            WHEN   ESCALATIONISSUE.TEL_COM_SPECIFYFROM_NONREGISTERED_INWISDOM   = 0 
            THEN 'No' 
        ELSE 'Yes' END AS UNREGISTERED,
        EQUIPMENT.COM_ISFREEPERIODEND AS WARRANTY_END_DATE,
        WO.MSDYN_NAME AS WO_NO,
        WOSTATUS.MSDYN_NAME AS WO_STATE
    FROM TEL_COM_ESCALATIONISSUE_REF ESCALATIONISSUE
    LEFT OUTER JOIN TEL_COM_ESCALATIONCATEGORY_REF ESCALATIONCATEGORY ON ESCALATIONCATEGORY.TEL_COM_ESCALATIONCATEGORYID =  ESCALATIONISSUE.TEL_COM_ESCALATIONCATEGORY
    LEFT OUTER JOIN ACCOUNT_REF ACCOUNT ON ACCOUNT.ID =  ESCALATIONISSUE.TEL_COM_FAB
    LEFT OUTER JOIN ACCOUNT_REF PARENT ON PARENT.ID =  ACCOUNT.PARENTACCOUNTID
    LEFT OUTER JOIN ACCOUNT_REF PARENT2 ON PARENT.PARENTACCOUNTID =  PARENT2.ID
    LEFT OUTER JOIN ACCOUNT_REF PARENT3 ON PARENT2.ACCOUNTNUMBER =  PARENT3.ID
    LEFT OUTER JOIN MSDYN_CUSTOMERASSET_REF EQUIPMENT ON EQUIPMENT.ID =  ESCALATIONISSUE.TEL_COM_SN
    LEFT OUTER JOIN COM_PRODUCTSYSTEMTYPE_REF SYSTEMTYPE ON SYSTEMTYPE.COM_PRODUCTSYSTEMTYPEID =  EQUIPMENT.COM_SYSTEMID
    LEFT OUTER JOIN COM_PRODUCTLINE_REF PRODUCTLINE ON PRODUCTLINE.COM_PRODUCTLINEID =  EQUIPMENT.COM_PRODUCTLINE
    LEFT OUTER JOIN TEL_COM_ESCALATIONREASON_REF ESCALATIONREASON ON ESCALATIONREASON.TEL_COM_ESCALATIONREASONID = ESCALATIONISSUE.TEL_COM_ESCALATIONREASON
    LEFT OUTER JOIN TEL_COM_ESCALATIONREASON_REF ESCALATIONREASONF ON ESCALATIONREASONF.TEL_COM_ESCALATIONREASONID =  ESCALATIONISSUE.TEL_COM_ESCALATIONREASONFIXED
    LEFT OUTER JOIN TEL_COM_ESCALATIONLEVEL_REF ESCALATIONLEVEL ON ESCALATIONLEVEL.TEL_COM_ESCALATIONLEVELID =  ESCALATIONISSUE.TEL_COM_ESCALATIONLEVEL
    LEFT OUTER JOIN SYSTEMUSER_REF OEL ON OEL.ID = ESCALATIONISSUE.TEL_COM_OEL
    LEFT OUTER JOIN SYSTEMUSER_REF CREATEDBY ON CREATEDBY.ID =  ESCALATIONISSUE.CREATEDBY
    LEFT OUTER JOIN SYSTEMUSER_REF MODIFIEDBY ON MODIFIEDBY.ID  = ESCALATIONISSUE.MODIFIEDBY
    LEFT OUTER JOIN MSDYN_WORKORDER_REF WO ON ESCALATIONISSUE.TEL_COM_WONO  = WO.MSDYN_WORKORDERID
    LEFT OUTER JOIN MSDYN_WORKORDERSUBSTATUS_REF WOSTATUS ON WOSTATUS.ID =  WO.MSDYN_SUBSTATUS
    LEFT OUTER JOIN INCIDENT_REF CASE11 ON CASE11.INCIDENTID =  ESCALATIONISSUE.TEL_COM_CASE_TITLE
    LEFT OUTER JOIN TERRITORY_REF REGION ON REGION.TERRITORYID = ESCALATIONISSUE.TEL_COM_REGION
    LEFT OUTER JOIN TEAM_REF OWNERT ON OWNERT.ID =  ESCALATIONISSUE.OWNERID
    LEFT OUTER JOIN SYSTEMUSER_REF OWNERU ON OWNERU.ID =  ESCALATIONISSUE.OWNERID
    LEFT OUTER JOIN STATUSMETADATA_REF as STATUSREASON 
        ON STATUSREASON.ENTITYNAME   = 'tel_com_escalationissue' 
        AND  ESCALATIONISSUE.STATUSCODE   =   STATUSREASON.STATUS
    LEFT OUTER JOIN STATUSMETADATA_REF as STATE 
        ON STATE.ENTITYNAME  = 'tel_com_escalationissue' 
        AND  STATE.STATE =  ESCALATIONISSUE.STATECODE
    LEFT OUTER JOIN GLOBALOPTIONSETMETADATA_REF as CASETYPE 
        ON CASE11.TSC_INQUIRYTYPE =  CASETYPE.OPTION
        AND CASETYPE.OptionSetName  = 'tsc_inquirytype'
    LEFT OUTER JOIN GLOBALOPTIONSETMETADATA_REF as CASESTATUS 
        ON CASESTATUS.OPTION =  CASE11.TSC_CASE_OPEN_CLOSE_STATUS
        AND CASESTATUS.OptionSetName  = 'tsc_case_open_close_status'
    LEFT OUTER JOIN QRY_EmployeeEscalation ON QRY_EmployeeEscalation.TEL_COM_ESCALATIONISSUE =  ESCALATIONISSUE.TEL_COM_ESCALATIONISSUEID
    LEFT OUTER JOIN QRY_LastActivity 
        ON QRY_LastActivity.TEL_COM_ESCALATIONISSUE = ESCALATIONISSUE.ID
    LEFT OUTER JOIN QRY_NextActivity 
        ON ESCALATIONISSUE.ID =  QRY_NextActivity.TEL_COM_ESCALATIONISSUE
),


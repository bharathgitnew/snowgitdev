with CALENDARDATE as  
(
    SELECT
        CALENDAR_DATE,
        FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
        FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF,
        FISCAL_YEAR_QUARTER_SHORT_TEXT AS FISCAL_QTR 
    FROM {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
    WHERE CALENDAR_DATE >= '2019-04-01'
),
TIRS_DATA AS (
    SELECT
        TIRS_NO,
        LEFT(TRY_TO_DATE(INITIAL_REPORTER_DATE_OF_OCCURRENCE, 'YYYY/MM/DD') ,7) AS INCIDENT_MONTH,
        TRY_TO_DATE(INITIAL_REPORTER_DATE_OF_OCCURRENCE, 'YYYY/MM/DD') AS INCIDENT_DATE,
        COMMON_INCIDENT_TITLE_EN AS INCIDENT_TITLE,
        CASE
            WHEN STATUS_EN = '7. Closed' THEN 'Closed' 
            ELSE STATUS_EN
        END AS STATUS,
        COMMON_COMPANY_EN AS COMPANY,
        COMMON_LOCATION_TYPE_EN AS LOCATION_TYPE,
        COMMON_INCIDENT_TYPE_EN AS INCIDENT_TYPE,
        COMMON_CATEGORY_EN AS CATEGORY,
        COMMON_SUB_CATEGORY_EN AS SUB_CATEGORY,
        COMMON_SUB_CATEGORY_OTHER AS SUB_CATEGORY_OTHER,
        COMMON_BU_EN AS BU,
        COMMON_EQUIPMENT_SN AS MACHINE_SN,
        COMMON_OCCURRENCE_PLACE_CUSTOMER_NAME_OR_AREA_EN AS CUSTOMER_NAME_OR_AREA,
        COMMON_LOCATION_DESCRIPTION_BUILDING_OR_LINE_NAME_EN AS LOCATION_OR_BUILDING,
        INITIAL_REPORTER_COMPANY AS REPORTER_COMPANY,
        INITIAL_REPORTER_BU_EN AS REPORTER_BU,
        INITIAL_REPORTER_WORKFLOW_EN AS REPORTER_WORKFLOW,
        INITIAL_EQUIPMENT_INFORMATION_EQUIPMENT_NAME AS EQUIPMENT_NAME,
        INITIAL_EQUIPMENT_INFORMATION_BU_EN AS EQUIPMENT_BU,
        INITIAL_EQUIPMENT_INFORMATION_MODULE_OR_CHAMBER_POSITION AS MODULE_OR_CHAMBER_POSITION,
        INITIAL_EQUIPMENT_INFORMATION_DAMAGED_PORTION AS DAMAGED_PORTION,
        INITIAL_EQUIPMENT_INFORMATION_EXPECTED_MAIN_ROOT_CAUSE_EN AS EXPECTED_MAIN_ROOT_CAUSE,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN,
        INITIAL_OCCURRENCE_SITUATION_DESCRIPTION_EN AS SITUATION_DESCRIPTION,
        INITIAL_OCCURRENCE_SITUATION_TYPE_OF_WORKER_EN AS SITUATION_TYPE_OF_WORKER,
        INITIAL_OCCURRENCE_SITUATION_TASK_EN AS SITUATION_TASK,
        INITIAL_OCCURRENCE_SITUATION_SITUATION_OF_EQUIPMENT_EN AS SITUATION_OF_EQUIPMENT,
        INITIAL_OCCURRENCE_SITUATION_SITUATION_OF_WORKER_EN AS SITUATION_OF_WORKER,
        INITIAL_OCCURRENCE_SITUATION_DAMAGE_TYPE_EN AS DAMAGE_TYPE,
        SECURITY_REGION AS SECURITY_REGION
    FROM {{ ref('SILVER__TEA_SERVICE__ACCIDENTREPORTSFORUS_NOLOCK') }}
        WHERE 
            INITIAL_OCCURRENCE_SITUATION_TASK_EN iLIKE '%Start-up%'
            AND COMMON_COMPANY_EN = 'TEA'
            AND TRY_TO_DATE(INITIAL_REPORTER_DATE_OF_OCCURRENCE, 'YYYY/MM/DD') >= '2019-04-01'
),

source_data as  
(
    SELECT
        DATE.FISCAL_YEAR,
        DATE.FISCAL_HALF,
        DATE.FISCAL_QTR,
        TIRS.INCIDENT_MONTH,
        TIRS.INCIDENT_DATE,
        TIRS.TIRS_NO,
        TIRS.INCIDENT_TITLE,
        TIRS.STATUS,
        TIRS.COMPANY,
        TIRS.LOCATION_TYPE,
        TIRS.INCIDENT_TYPE,
        TIRS.CATEGORY,
        TIRS.SUB_CATEGORY,
        TIRS.SUB_CATEGORY_OTHER,
        TIRS.BU,
        TIRS.MACHINE_SN,
        TIRS.CUSTOMER_NAME_OR_AREA,
        TIRS.LOCATION_OR_BUILDING,
        TIRS.REPORTER_COMPANY,
        TIRS.REPORTER_BU,
        TIRS.REPORTER_WORKFLOW,
        TIRS.EQUIPMENT_NAME,
        TIRS.EQUIPMENT_BU,
        TIRS.MODULE_OR_CHAMBER_POSITION,
        TIRS.DAMAGED_PORTION,
        TIRS.EXPECTED_MAIN_ROOT_CAUSE,
        TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED,
        TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY,
        TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT,
        TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN,
        TIRS.SITUATION_DESCRIPTION,
        TIRS.SITUATION_TYPE_OF_WORKER,
        TIRS.SITUATION_TASK,
        TIRS.SITUATION_OF_EQUIPMENT,
        TIRS.SITUATION_OF_WORKER,
        TIRS.DAMAGE_TYPE,
        TIRS.SECURITY_REGION
    FROM TIRS_DATA AS TIRS
        LEFT OUTER JOIN CALENDARDATE AS DATE
            ON TIRS.INCIDENT_DATE = DATE.CALENDAR_DATE
)
,transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        FISCAL_YEAR,
        FISCAL_HALF,
        FISCAL_QTR,
        INCIDENT_MONTH,
        INCIDENT_DATE,
        TIRS_NO,
        INCIDENT_TITLE,
        STATUS,
        COMPANY,
        LOCATION_TYPE,
        INCIDENT_TYPE,
        CATEGORY,
        SUB_CATEGORY,
        SUB_CATEGORY_OTHER,
        BU,
        MACHINE_SN,
        CUSTOMER_NAME_OR_AREA,
        LOCATION_OR_BUILDING,
        REPORTER_COMPANY,
        REPORTER_BU,
        REPORTER_WORKFLOW,
        EQUIPMENT_NAME,
        EQUIPMENT_BU,
        MODULE_OR_CHAMBER_POSITION,
        DAMAGED_PORTION,
        EXPECTED_MAIN_ROOT_CAUSE,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN,
        SITUATION_DESCRIPTION,
        SITUATION_TYPE_OF_WORKER,
        SITUATION_TASK,
        SITUATION_OF_EQUIPMENT,
        SITUATION_OF_WORKER,
        DAMAGE_TYPE,
        SECURITY_REGION
    FROM source_data 
),
type_data as (
    SELECT 
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(FISCAL_YEAR as VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(FISCAL_HALF as VARCHAR(16777216)) AS FISCAL_HALF,
        CAST(FISCAL_QTR as VARCHAR(16777216)) AS FISCAL_QTR,
        CAST(INCIDENT_MONTH as VARCHAR(16777216)) AS INCIDENT_MONTH,
        CAST(INCIDENT_DATE as DATE) AS INCIDENT_DATE,
        CAST(TIRS_NO as VARCHAR(16777216)) AS TIRS_NO,
        CAST(INCIDENT_TITLE as VARCHAR(16777216)) AS INCIDENT_TITLE,
        CAST(STATUS as VARCHAR(16777216)) AS STATUS,
        CAST(COMPANY as VARCHAR(16777216)) AS COMPANY,
        CAST(LOCATION_TYPE as VARCHAR(16777216)) AS LOCATION_TYPE,
        CAST(INCIDENT_TYPE as VARCHAR(16777216)) AS INCIDENT_TYPE,
        CAST(CATEGORY as VARCHAR(16777216)) AS CATEGORY,
        CAST(SUB_CATEGORY as VARCHAR(16777216)) AS SUB_CATEGORY,
        CAST(SUB_CATEGORY_OTHER as VARCHAR(16777216)) AS SUB_CATEGORY_OTHER,
        CAST(BU as VARCHAR(16777216)) AS BU,
        CAST(MACHINE_SN as VARCHAR(16777216)) AS MACHINE_SN,
        CAST(CUSTOMER_NAME_OR_AREA as VARCHAR(16777216)) AS CUSTOMER_NAME_OR_AREA,
        CAST(LOCATION_OR_BUILDING as VARCHAR(16777216)) AS LOCATION_OR_BUILDING,
        CAST(REPORTER_COMPANY as VARCHAR(16777216)) AS REPORTER_COMPANY,
        CAST(REPORTER_BU as VARCHAR(16777216)) AS REPORTER_BU,
        CAST(REPORTER_WORKFLOW as VARCHAR(16777216)) AS REPORTER_WORKFLOW,
        CAST(EQUIPMENT_NAME as VARCHAR(16777216)) AS EQUIPMENT_NAME,
        CAST(EQUIPMENT_BU as VARCHAR(16777216)) AS EQUIPMENT_BU,
        CAST(MODULE_OR_CHAMBER_POSITION as VARCHAR(16777216)) AS MODULE_OR_CHAMBER_POSITION,
        CAST(DAMAGED_PORTION as VARCHAR(16777216)) AS DAMAGED_PORTION,
        CAST(EXPECTED_MAIN_ROOT_CAUSE as VARCHAR(16777216)) AS EXPECTED_MAIN_ROOT_CAUSE,
        CAST(INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED as VARCHAR(16777216)) AS INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED,
        CAST(INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY as VARCHAR(16777216)) AS INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY,
        CAST(INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT as VARCHAR(16777216)) AS INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT,
        CAST(INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN as VARCHAR(16777216)) AS INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN,
        CAST(SITUATION_DESCRIPTION as VARCHAR(16777216)) AS SITUATION_DESCRIPTION,
        CAST(SITUATION_TYPE_OF_WORKER as VARCHAR(16777216)) AS SITUATION_TYPE_OF_WORKER,
        CAST(SITUATION_TASK as VARCHAR(16777216)) AS SITUATION_TASK,
        CAST(SITUATION_OF_EQUIPMENT as VARCHAR(16777216)) AS SITUATION_OF_EQUIPMENT,
        CAST(SITUATION_OF_WORKER as VARCHAR(16777216)) AS SITUATION_OF_WORKER,
        CAST(DAMAGE_TYPE as VARCHAR(16777216)) AS DAMAGE_TYPE,
        CAST(SECURITY_REGION as VARCHAR(16777216)) AS SECURITY_REGION
    FROM transform_data
)

SELECT * FROM type_data
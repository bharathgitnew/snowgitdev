{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='BaanV_TEA_Configurations',
      transient=false
) }}

with source_data as
(
SELECT
BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION,
UPPER (TRIM ( BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.DESCRIPTION)) AS DESCRIPTION,
BAANCOMMONCOMMONDATA_SOLDTOBUSINESSPARTNERS.INVOICETOBUSINESSPARTNER,
UPPER ( BAANCOMMONCOMMONDATA_BUSINESSPARTNERS_C.NAME) AS C_NAME,
BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.SOLDTOBUSINESSPARTNER,
UPPER ( BAANCOMMONCOMMONDATA_BUSINESSPARTNERS_G.NAME) AS G_NAME,
SUBSTR(BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION,REGEXP_INSTR(BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION, '-') + 1,LENGTH(BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION) - REGEXP_INSTR(BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION, '-') + 1) CUSTOMER_SITE,
BAANCOMMONCOMMONDATA_ADDRESSES.ADDRESS,
UPPER ( BAANCOMMONCOMMONDATA_ADDRESSES.NAME) AS ADDRESS_NAME,
BAANCOMMONCOMMONDATA_ADDRESSES.CITY,
BAANCOMMONCOMMONDATA_ADDRESSES.STATEPROVINCE,
BAANCOMMONCOMMONDATA_ADDRESSES.ZIPCODEPOSTALCODE,
BAANCOMMONCOMMONDATA_ADDRESSES.COUNTRY,
BAANCOMMONCOMMONDATA_ADDRESSES.TELEPHONE,
BAANCOMMONCOMMONDATA_ADDRESSES.FAX,
BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.SERVICECENTER,
BAANFINANCEGENERALLEDGER_SIMPLEINTEGRATIONRELATIONSBYELEMENT.DIMENSIONCODE,
BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.RESPONSIBLEENGINEER,
DECODE ( BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.EXPIREDID , 1, 'Yes', 'No') AS EXPIREDID
FROM
{{ ref('BRONZE__TEA_SERVICE__BAAN_BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS') }} BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS
LEFT OUTER JOIN {{ ref('BRONZE__TEA_SERVICE__BAAN_BAANCOMMONCOMMONDATA_SOLDTOBUSINESSPARTNERS') }} BAANCOMMONCOMMONDATA_SOLDTOBUSINESSPARTNERS ON BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.SOLDTOBUSINESSPARTNER = BAANCOMMONCOMMONDATA_SOLDTOBUSINESSPARTNERS.SOLDTOBUSINESSPARTNER
LEFT OUTER JOIN {{ ref('BRONZE__TEA_SERVICE__BAAN_BAANCOMMONCOMMONDATA_BUSINESSPARTNERS') }} BAANCOMMONCOMMONDATA_BUSINESSPARTNERS_C ON BAANCOMMONCOMMONDATA_SOLDTOBUSINESSPARTNERS.INVOICETOBUSINESSPARTNER = BAANCOMMONCOMMONDATA_BUSINESSPARTNERS_C.BUSINESSPARTNER
LEFT OUTER JOIN {{ ref('BRONZE__TEA_SERVICE__BAAN_BAANCOMMONCOMMONDATA_ADDRESSES') }} BAANCOMMONCOMMONDATA_ADDRESSES ON BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.LOCATIONADDRESS = BAANCOMMONCOMMONDATA_ADDRESSES.ADDRESSCODE
LEFT OUTER JOIN (SELECT STRINGVALUE1, DIMENSIONCODE FROM {{ ref('BRONZE__TEA_SERVICE__BAAN_BAANFINANCEGENERALLEDGER_SIMPLEINTEGRATIONRELATIONSBYELEMENT') }} WHERE INTEGRATIONELEMENT = 'SVC' AND DIMENSIONTYPE = 3) BAANFINANCEGENERALLEDGER_SIMPLEINTEGRATIONRELATIONSBYELEMENT ON BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.SERVICECENTER = BAANFINANCEGENERALLEDGER_SIMPLEINTEGRATIONRELATIONSBYELEMENT.STRINGVALUE1
INNER JOIN {{ ref('BRONZE__TEA_SERVICE__BAAN_BAANCOMMONCOMMONDATA_BUSINESSPARTNERS') }} BAANCOMMONCOMMONDATA_BUSINESSPARTNERS_G ON BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.SOLDTOBUSINESSPARTNER = BAANCOMMONCOMMONDATA_BUSINESSPARTNERS_G.BUSINESSPARTNER
ORDER BY SUBSTR(BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION, 3, LENGTH(BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION) - 2), BAANSERVICECONFIGURATIONCONTROL_CONFIGURATIONS.CONFIGURATION
)

,transform_data as
(
SELECT
source_data.CONFIGURATION AS CONFIGURATION,
source_data.DESCRIPTION AS CONFIGURATION_DESC,
source_data.INVOICETOBUSINESSPARTNER AS INVOICE_TO_BPID,
source_data.C_NAME AS INVOICE_TO_BP,
source_data.SOLDTOBUSINESSPARTNER AS SOLD_TO_BPID,
source_data.G_NAME AS SOLD_TO_BP,
source_data.CUSTOMER_SITE AS CUSTOMER_SITE,
source_data.ADDRESS AS ADDRESS,
source_data.ADDRESS_NAME AS DESCRIPTION,
source_data.CITY AS CITY,
source_data.STATEPROVINCE AS STATE_PROVINCE,
source_data.ZIPCODEPOSTALCODE AS POSTAL_CODE,
source_data.COUNTRY AS COUNTRY,
source_data.TELEPHONE AS TELEPHONE,
source_data.FAX AS FAX,
source_data.SERVICECENTER AS SERVICE_CENTER,
source_data.DIMENSIONCODE AS OFFICE,
source_data.RESPONSIBLEENGINEER AS RESPONSIBLE_ENGINEER,
source_data.EXPIREDID AS EXPIRED
FROM source_data
)

select * from transform_data
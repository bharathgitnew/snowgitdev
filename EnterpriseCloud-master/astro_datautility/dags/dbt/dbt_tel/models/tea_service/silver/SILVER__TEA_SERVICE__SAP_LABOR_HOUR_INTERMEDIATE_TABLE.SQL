with source_data as (
	SELECT
        MANDT    AS CLIENT,
        SEQNO    AS SEQUENCE_NUMBER,
        PRC_STS  AS PROCESS_STATUS,
        AUFNR    AS ORDER_NUMBER,
        VORNR    AS OPERATION_ACTIVITY_NUMBER,
        TRY_TO_DATE(BUDAT,'YYYYMMDD')    AS POSTING_DATE,
        WERKS    AS PLANT ,
        ZSEQUE   AS SEQUENCE,
        ARBPL    AS WORK_CENTER,
        ZKUNNR   AS EMPLOYEE_NO,
        ZACTBC   AS CONFIRMATION_TYPE,
        ZACTWH   AS ACTIVITY_CURRENTLY_TO_BE_CONFIRMED_WORK_HOUR,
        TRY_TO_DATE(C_DATE,'YYYYMMDD')   AS CREATE_DATE,
        C_TIME   AS CREATE_TIME,
        C_USER   AS CREATE_USER_NAME,
        C_PGM    AS CREATE_PROGRAM,
        TRY_TO_DATE(U_DATE,'YYYYMMDD')   AS UPDATE_DATE,
        U_TIME   AS UPDATE_TIME,
        U_USER   AS UPDATE_USER_NAME,
        U_PGM    AS UPDATE_PROGRAM
from {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU230_ZSDT2004') }}   
),
transform_data as (
	SELECT
        CLIENT,
        SEQUENCE_NUMBER,
        PROCESS_STATUS,
        ORDER_NUMBER,
        OPERATION_ACTIVITY_NUMBER,
        POSTING_DATE,
        LEFT(POSTING_DATE,7) AS POSTING_MONTH,
        PLANT,
        SEQUENCE,
        WORK_CENTER,
        EMPLOYEE_NO,
        CONFIRMATION_TYPE,
        ACTIVITY_CURRENTLY_TO_BE_CONFIRMED_WORK_HOUR,
        CREATE_DATE,
        CREATE_TIME,
        CREATE_USER_NAME,
        CREATE_PROGRAM,
        UPDATE_DATE,
        UPDATE_TIME,
        UPDATE_USER_NAME,
        UPDATE_PROGRAM,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH 
    from source_data
	),
    type_data as (
	SELECT
        CAST(CLIENT AS VARCHAR(16777216)) AS CLIENT,
        CAST(SEQUENCE_NUMBER AS NUMBER(38,0)) AS SEQUENCE_NUMBER,
        CAST(PROCESS_STATUS AS VARCHAR(16777216)) AS PROCESS_STATUS,
        CAST(ORDER_NUMBER AS VARCHAR(16777216)) AS ORDER_NUMBER,
        CAST(OPERATION_ACTIVITY_NUMBER AS VARCHAR(16777216)) AS OPERATION_ACTIVITY_NUMBER,
        CAST(POSTING_DATE AS DATE) AS POSTING_DATE,
        CAST(POSTING_MONTH AS VARCHAR(16777216)) AS POSTING_MONTH,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(SEQUENCE AS VARCHAR(16777216)) AS SEQUENCE,
        CAST(WORK_CENTER AS VARCHAR(16777216)) AS WORK_CENTER,
        CAST(EMPLOYEE_NO AS VARCHAR(16777216)) AS EMPLOYEE_NO,
        CAST(CONFIRMATION_TYPE AS VARCHAR(16777216)) AS CONFIRMATION_TYPE,
        CAST(ACTIVITY_CURRENTLY_TO_BE_CONFIRMED_WORK_HOUR AS NUMBER(38,2)) AS WORK_HOURS,
        CAST(CREATE_DATE AS DATE) AS CREATE_DATE,
        CAST(CREATE_TIME AS VARCHAR(16777216)) AS CREATE_TIME,
        CAST(CREATE_USER_NAME AS VARCHAR(16777216)) AS CREATE_USER_NAME,
        CAST(CREATE_PROGRAM AS VARCHAR(16777216)) AS CREATE_PROGRAM,
        CAST(UPDATE_DATE AS DATE) AS UPDATE_DATE,
        CAST(UPDATE_TIME AS VARCHAR(16777216)) AS UPDATE_TIME,
        CAST(UPDATE_USER_NAME AS VARCHAR(16777216)) AS UPDATE_USER_NAME,
        CAST(UPDATE_PROGRAM AS VARCHAR(16777216)) AS UPDATE_PROGRAM,
        CAST('{{ invocation_id }}' AS VARCHAR(16777216)) AS AUDIT_LOG_ID,
        CAST(SHA2('hash_me') AS VARCHAR(16777216)) as _ROW_HASH
    from transform_data
	)

	select * from type_data
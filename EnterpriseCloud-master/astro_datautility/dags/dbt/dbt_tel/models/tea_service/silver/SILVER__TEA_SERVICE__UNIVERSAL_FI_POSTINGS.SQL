{{ config(
        alias = 'UNIVERSAL_FI_POSTINGS',
        materialized='tel_incremental',
        incremental_strategy = 'insert_overwrite',
        tags=["finance"],
        transient = false
) }}

with vbap_cte as (
    select * from {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU010_VBAP') }}
    where IS_DELETED = 'No'
),

universal_pl_data as
(
        SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        OBJECT_NUMBER,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
        SALES_ORDER_NUMBER,
        ITEM_NUMBER_IN_SALES_ORDER
    FROM {{ ref('SILVER__TEA_SERVICE__UNIVERSAL_PL_ACCOUNT_TYPE') }} -- General Ledger
    WHERE ACDOCA_BUSINESS_TRANSACTION_TYPE = 'RFBU'
),

Acdoca_non_blank_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        case when TRIM(VBAP.VBELN)='' OR TRIM(VBAP.POSNR)='' then 'NOVALUE' else vbap.zzorty end AS SALES_CATEGORY,
        case when TRIM(VBAP.VBELN)='' OR TRIM(VBAP.POSNR)='' then 'NOVALUE' else vbap.VBELN end AS SALES_DOCUMENT,
        case when TRIM(VBAP.VBELN)='' OR TRIM(VBAP.POSNR)='' then 'NOVALUE' else vbap.POSNR end AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN vbap_cte  VBAP
            ON universal_pl_data.SALES_ORDER_NUMBER = VBAP.VBELN
            and universal_pl_data.ITEM_NUMBER_IN_SALES_ORDER = VBAP.POSNR
    WHERE TRIM(universal_pl_data.SALES_ORDER_NUMBER)!='' and universal_pl_data.SALES_ORDER_NUMBER IS NOT NULL

),

PR_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        case when trim(VBAP.PS_PSP_PNR_NEW)='' then 'NOVALUE' else vbap.zzorty end AS SALES_CATEGORY,
        case when trim(VBAP.PS_PSP_PNR_NEW)='' then 'NOVALUE' else vbap.VBELN end AS SALES_DOCUMENT,
        case when trim(VBAP.PS_PSP_PNR_NEW)='' then 'NOVALUE' else vbap.POSNR end AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN vbap_cte  VBAP
            ON universal_pl_data.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR = VBAP.PS_PSP_PNR
    WHERE OBJECT_NUMBER like 'PR%'
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY  vbap.VBELN order by vbap.VBELN)) = 1
),

source_data as
(
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        SALES_CATEGORY,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM
    FROM Acdoca_non_blank_data
    UNION
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        SALES_CATEGORY,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM
    FROM PR_Object_data
),
transform_data as
(
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        SALES_CATEGORY,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM source_data
),
type_data as
(
    SELECT
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(ACCOUNTING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS ACCOUNTING_DOCUMENT_NUMBER,
        CAST(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS VARCHAR(16777216)) AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        CAST(PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR AS VARCHAR(16777216)) AS PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        CAST(WBS_ELEMENT_SHORT_IDENTIFICATION AS VARCHAR(16777216)) AS WBS_ELEMENT_SHORT_IDENTIFICATION,
        CAST(ACDOCA_BUSINESS_TRANSACTION_TYPE AS VARCHAR(16777216)) AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
        CAST(LEDGER_IN_GENERAL_LEDGER_ACCOUNTING AS VARCHAR(16777216)) AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        CAST(NAME_1 AS VARCHAR(16777216)) AS NAME_1,
        CAST(ACCOUNT_NUMBER AS VARCHAR(16777216)) AS ACCOUNT_NUMBER,
        CAST(SALES_CATEGORY AS VARCHAR(16777216)) AS SALES_CATEGORY,
        CAST(SALES_DOCUMENT AS VARCHAR(16777216)) AS SALES_DOCUMENT,
        CAST(SALES_DOCUMENT_ITEM AS VARCHAR(16777216)) AS SALES_DOCUMENT_ITEM,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)

SELECT * from type_data
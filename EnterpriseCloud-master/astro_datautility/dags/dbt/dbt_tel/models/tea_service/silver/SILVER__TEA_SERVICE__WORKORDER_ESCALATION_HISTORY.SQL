    SELECT
        TEL_COM_ESCALATIONISSUENAME AS ISSUE_NO, 
        TEL_COM_STATUSFROMNAME AS LEVELFROM, 
        TEL_COM_STATUSTONAME AS LEVELTO, 
        WO_NAME AS LEVELCHANGEDESCRIPTION, 
        MODIFIEDON AS MODIFIEDON_HIST ,
        TRY_TO_TIMESTAMP(TRIM(SPLIT_PART(trim(WO_NAME), ' on ', 2)), 'MM/DD/YYYY HH12:MI:SS PM') AS levelto_startdate 
	FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_WO_ESCALATIONHISTORY') }}
), 

get_history as (
    SELECT
        esc.*,
        hist.LEVELFROM, 
        hist.LEVELTO,
        hist.levelto_startdate, 
        hist.LEVELCHANGEDESCRIPTION, 
        hist.MODIFIEDON_HIST,
        lead(hist.levelto_startdate) over (partition by esc.issue_no order by hist.MODIFIEDON_HIST asc ) as levelto_enddate, 
        datediff(day,levelto_startdate,levelto_enddate) as leveldays
	FROM wo_escalation esc  
    left join escalation_hist hist
        on esc.ISSUE_NO = hist.ISSUE_NO
),


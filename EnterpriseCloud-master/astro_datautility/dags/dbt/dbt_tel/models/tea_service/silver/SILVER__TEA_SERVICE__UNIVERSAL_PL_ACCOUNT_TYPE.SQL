with acdoca_data as (
    SELECT
        --START ACDOCA
        acdoca.RLDNR AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        acdoca.RBUKRS AS COMPANY_CODE,
        acdoca.GJAHR AS FISCAL_YEAR,
        acdoca.BELNR AS ACCOUNTING_DOCUMENT_NUMBER,
        acdoca.DOCLN AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        acdoca.BTTYPE AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
        acdoca.AWREF AS ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        acdoca.AWITEM AS REFERENCE_DOCUMENT_LINE_ITEM,
        acdoca.RACCT AS ACCOUNT_NUMBER,
        acdoca.HSL AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        acdoca.EBELN AS PURCHASING_DOCUMENT_NUMBER,
        acdoca.EBELP AS ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        acdoca.KDAUF AS SALES_ORDER_NUMBER,
        acdoca.KDPOS AS ITEM_NUMBER_IN_SALES_ORDER,
        acdoca.MATNR AS ACDOCA_MATERIAL_NUMBER,
        acdoca.MAT_KDAUF AS SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        acdoca.MAT_KDPOS AS SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        acdoca.OBJNR AS OBJECT_NUMBER,
        acdoca.PAROB1 AS PARTNER_OBJECT,
        acdoca.PS_PSP_PNR_NEW AS WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
        acdoca.PPS_PSP_PNR AS PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR
    FROM {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU024_ACDOCA') }} acdoca -- General Ledger
    WHERE rldnr = '0L' AND (glaccounttype = 'N' OR  glaccounttype='P')
),
bseg_data as
(
    SELECT
        bseg.bukrs,
        bseg.belnr,
        bseg.gjahr,
        bseg.ZFBDT,
        bseg.netdt,
        bseg.buzei,
        bkpf.bktxt,
        bkpf.xblnr,
        kna1.NAME_1
    FROM {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU038_BSEG') }} bseg
            INNER JOIN {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU037_BKPF') }}  bkpf
                ON try_to_number(bkpf.bukrs) = try_to_number(BSEG.bukrs)
                AND try_to_number(bkpf.GJAHR) = try_to_number(BSEG.gjahr)
                AND try_to_number(bkpf.BELNR) = try_to_number(BSEG.belnr)
            INNER JOIN (SELECT NAME_1,CUSTOMER_NUMBER FROM {{ ref('SILVER__TEA_SERVICE__BUSINESS_PARTNERS_GENERAL_DATA') }} WHERE CUSTOMER_FLAG='Y') kna1
                ON bseg.xref1 = kna1.CUSTOMER_NUMBER
),
prps_data as
(
    SELECT
        prps.poski,
        prps.pspnr_new
    FROM {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU040_PRPS') }} prps
),
source_data as (
    SELECT DISTINCT
        acdoca_data.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        acdoca_data.COMPANY_CODE AS COMPANY_CODE,
        acdoca_data.FISCAL_YEAR AS FISCAL_YEAR,
        acdoca_data.ACCOUNTING_DOCUMENT_NUMBER AS ACCOUNTING_DOCUMENT_NUMBER,
        acdoca_data.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        acdoca_data.ACDOCA_BUSINESS_TRANSACTION_TYPE AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
        acdoca_data.ACDOCA_REFERENCE_DOCUMENT_NUMBER AS ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        acdoca_data.REFERENCE_DOCUMENT_LINE_ITEM AS REFERENCE_DOCUMENT_LINE_ITEM,
        acdoca_data.ACCOUNT_NUMBER AS ACCOUNT_NUMBER,
        acdoca_data.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        acdoca_data.PURCHASING_DOCUMENT_NUMBER AS PURCHASING_DOCUMENT_NUMBER,
        acdoca_data.ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        acdoca_data.SALES_ORDER_NUMBER AS SALES_ORDER_NUMBER,
        acdoca_data.ITEM_NUMBER_IN_SALES_ORDER AS ITEM_NUMBER_IN_SALES_ORDER,
        acdoca_data.ACDOCA_MATERIAL_NUMBER AS ACDOCA_MATERIAL_NUMBER,
        acdoca_data.SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY AS SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        acdoca_data.SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY AS SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        acdoca_data.OBJECT_NUMBER AS OBJECT_NUMBER,
        acdoca_data.PARTNER_OBJECT AS PARTNER_OBJECT,
        acdoca_data.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR AS WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
        acdoca_data.PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR AS PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        bseg_data.bukrs AS BSEG_COMPANY_CODE,
        bseg_data.belnr AS BSEG_ACCOUNTING_DOCUMENT_NUMBER,
        bseg_data.gjahr AS BSEG_FISCAL_YEAR,
        bseg_data.NAME_1 AS NAME_1,
        prps_data.poski AS WBS_ELEMENT_SHORT_IDENTIFICATION
    FROM acdoca_data
    LEFT JOIN prps_data
        ON try_to_number(acdoca_data.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR) = try_to_number(prps_data.pspnr_new)
    LEFT JOIN bseg_data 
        ON try_to_number(acdoca_data.COMPANY_CODE) = try_to_number(bseg_data.bukrs)
        AND try_to_number(acdoca_data.ACCOUNTING_DOCUMENT_NUMBER) = try_to_number(bseg_data.belnr)
        AND try_to_number(acdoca_data.FISCAL_YEAR) = try_to_number(bseg_data.gjahr)
        AND try_to_number(acdoca_data.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER) = try_to_number(bseg_data.buzei)
),

transform_data as (
    SELECT DISTINCT
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        REFERENCE_DOCUMENT_LINE_ITEM,
        ACCOUNT_NUMBER,
        AMOUNT_IN_COMPANY_CODE_CURRENCY,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        SALES_ORDER_NUMBER,
        ITEM_NUMBER_IN_SALES_ORDER,
        ACDOCA_MATERIAL_NUMBER,
        SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        OBJECT_NUMBER,
        PARTNER_OBJECT,
        WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        BSEG_COMPANY_CODE,
        BSEG_ACCOUNTING_DOCUMENT_NUMBER,
        BSEG_FISCAL_YEAR,
        NAME_1,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH -- Adds column to table on full refresh.
    FROM source_data
),

type_data as (
    SELECT
        CAST(LEDGER_IN_GENERAL_LEDGER_ACCOUNTING AS VARCHAR(16777216)) AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(ACCOUNTING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS ACCOUNTING_DOCUMENT_NUMBER,
        CAST(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS VARCHAR(16777216)) AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        CAST(ACDOCA_BUSINESS_TRANSACTION_TYPE AS VARCHAR(16777216)) AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
        CAST(ACDOCA_REFERENCE_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        CAST(REFERENCE_DOCUMENT_LINE_ITEM AS VARCHAR(16777216)) AS REFERENCE_DOCUMENT_LINE_ITEM,
        CAST(ACCOUNT_NUMBER AS VARCHAR(16777216)) AS ACCOUNT_NUMBER,
        CAST(AMOUNT_IN_COMPANY_CODE_CURRENCY AS VARCHAR(16777216)) AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        CAST(PURCHASING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS PURCHASING_DOCUMENT_NUMBER,
        CAST(ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS VARCHAR(16777216)) AS ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        CAST(SALES_ORDER_NUMBER AS VARCHAR(16777216)) AS SALES_ORDER_NUMBER,
        CAST(ITEM_NUMBER_IN_SALES_ORDER AS VARCHAR(16777216)) AS ITEM_NUMBER_IN_SALES_ORDER,
        CAST(ACDOCA_MATERIAL_NUMBER AS VARCHAR(16777216)) AS ACDOCA_MATERIAL_NUMBER,
        CAST(SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY AS VARCHAR(16777216)) AS SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        CAST(SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY AS VARCHAR(16777216)) AS SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        CAST(OBJECT_NUMBER AS VARCHAR(16777216)) AS OBJECT_NUMBER,
        CAST(PARTNER_OBJECT AS VARCHAR(16777216)) AS PARTNER_OBJECT,
        CAST(WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR AS VARCHAR(16777216)) AS WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
        CAST(PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR AS VARCHAR(16777216)) AS PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        CAST(BSEG_COMPANY_CODE AS VARCHAR(16777216)) AS BSEG_COMPANY_CODE,
        CAST(BSEG_ACCOUNTING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS BSEG_ACCOUNTING_DOCUMENT_NUMBER,
        CAST(BSEG_FISCAL_YEAR AS VARCHAR(16777216)) AS BSEG_FISCAL_YEAR,
        CAST(NAME_1 AS VARCHAR(16777216)) AS NAME_1,
        CAST(WBS_ELEMENT_SHORT_IDENTIFICATION AS VARCHAR(16777216)) AS WBS_ELEMENT_SHORT_IDENTIFICATION,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)
SELECT * from type_data
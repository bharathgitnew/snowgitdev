with COMMON_SYSTEM__EMPLOYEE as (
    SELECT 
		 EMPLOYEE_ID
		,FULL_NAME
		,FIRST_NAME
		,LAST_NAME
		,EMPLOYEE_STATUS
		,EMAIL_ADDRESS
		,SUPERVISOR_NAME
		,Office_Phone
		,Employee_Type_Code
		,EmployeeTypeFST
		,Salary_Type
		,IS_Expat
		,Is_Manager
        ,Business_Unit_ID
        ,Supervisor_Employee_ID
        ,Current_Home_Company_ID
        ,Current_Home_Department_ID
        ,Current_Host_Company_ID
        ,Current_Host_Department_ID
        ,GroupNameFST
FROM  {{ source('STATIC_OBJECTS', 'D_EMPLOYEE') }} 
WHERE DW_Current_Indicator = 'Y'
),


source_data as (
SELECT
  CASE
  WHEN INVOICE_TO_BPID='20514' AND OFFICE='6330' THEN 'Central'
  WHEN INVOICE_TO_BPID IN ('39729')
  AND OFFICE='6320'
  THEN 'East'
  WHEN SOLD_TO_BPID IN ('305160201','392430001')
  THEN 'East'
  ELSE O.Region
  END AS CustomerRegion
  ,COALESCE(CG.SALESCUSTOMERGROUP, 'Regional') AS CustomerGroup
  ,D.DESCRIPTION AS Office
  ,TEA_BU_CODE AS BU
  ,C.CUSTOMER_SITE AS Fab
  ,C.CONFIGURATION AS Config
  ,CASE
  WHEN CG.SALESCUSTOMERGROUP = 'Intel' AND D.DESCRIPTION IN ('Phoenix, AZ','Albuquerque, NM') THEN 'Bela, Robert'
  WHEN CG.SALESCUSTOMERGROUP = 'Intel' THEN 'Dombroski, Robert'
  WHEN CG.SALESCUSTOMERGROUP = 'TEL GROUP' AND D.DESCRIPTION IN ('Portland, OR') THEN 'Dombroski, Robert'
  WHEN CG.SALESCUSTOMERGROUP = 'GF/IBM/Albany' THEN 'Alongi, Len'
  WHEN CG.SALESCUSTOMERGROUP = 'Micron' THEN 'Valeriano, George'
  WHEN CG.SALESCUSTOMERGROUP = 'TSMC' THEN 'Wagoner, Tyler'
  WHEN D.DESCRIPTION IN ('Portland, OR', 'Phoenix, AZ') THEN 'Valeriano, George'
  ELSE 'Wagoner, Tyler'
  END AS RegionalServiceManager
  ,E.FULL_NAME AS Supervisor
  ,COALESCE(ActiveToolCount,0) AS ActiveToolCount
  ,COALESCE(InactiveToolCount,0) AS InactiveToolCount
  ,C.EXPIRED AS Expired
  ,C.INVOICE_TO_BPID AS CustomerCode
  ,C.SOLD_TO_BPID AS FabCustomerCode
  ,C.ADDRESS
  ,C.CITY
  ,C.STATE_PROVINCE AS State
  ,C.POSTAL_CODE AS ZipCode
  ,C.COUNTRY
  ,C.OFFICE AS OfficeCode
  ,C.SERVICE_CENTER AS SrvCenter
  ,C.RESPONSIBLE_ENGINEER AS SupervisorID
  ,C.SOLD_TO_BP AS SoldToBpName
FROM {{ ref('SILVER__TEA_SERVICE__BAANV_TEA_CONFIGURATIONS') }} C
  LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__CUSTOMERGROUP') }} CG
  ON CUSTOMERCODE = INVOICE_TO_BPID
  LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__BAANV_TEA_DIMENSIONS') }} D
  ON DIMENSIONID = C.OFFICE AND DIMENSIONTYPEID = '3' AND _COMPANYID = 201
  LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__MDM_OFFICE') }} O
  ON OFFICECODE = C.OFFICE
  LEFT OUTER JOIN (SELECT DISTINCT TEA_BU_CODE,BU_CONFIGURATION_CODE FROM {{ ref('SILVER__TEA_SERVICE__BAANV_TEA_BU_MAPPINGS') }}) B
  ON B.BU_CONFIGURATION_CODE = LEFT(C.CONFIGURATION,2)
  LEFT OUTER JOIN (SELECT
  CONFIGURATION,
  COUNT(SERIAL_NUMBER) ActiveToolCount
  FROM {{ ref('SILVER__TEA_SERVICE__BAANV_TEA_OBJECTS') }}
  WHERE EXPIRED='NO'
  AND CHILD_OBJECT='NO'
  AND SYSTEM_STATUS IN ('Pre-Startup','Startup','Pre-Wty','Under-Wty','Wty-Out','Pre-Shipment')
  GROUP BY CONFIGURATION) A
  ON C.CONFIGURATION=A.CONFIGURATION
  LEFT OUTER JOIN (SELECT
  CONFIGURATION
  ,COUNT(SERIAL_NUMBER) AS InactiveToolCount
  FROM {{ ref('SILVER__TEA_SERVICE__BAANV_TEA_OBJECTS') }}
  WHERE EXPIRED = 'NO'
  AND CHILD_OBJECT = 'NO'
  AND SYSTEM_STATUS IN ('Inactive', 'Retired', 'Overseas')
  GROUP BY CONFIGURATION) I
  ON I.CONFIGURATION = C.CONFIGURATION
  LEFT OUTER JOIN COMMON_SYSTEM__EMPLOYEE   E
  ON EMPLOYEE_ID = RESPONSIBLE_ENGINEER AND RESPONSIBLE_ENGINEER IS NOT NULL
)

,transform_data as (
SELECT
  CUSTOMERREGION,
  CUSTOMERGROUP,
  OFFICE,
  BU,
  FAB,
  CONFIG,
  REGIONALSERVICEMANAGER,
  SUPERVISOR,
  ACTIVETOOLCOUNT,
  INACTIVETOOLCOUNT,
  EXPIRED,
  CUSTOMERCODE,
  FABCUSTOMERCODE,
  ADDRESS,
  CITY,
  STATE,
  ZIPCODE,
  COUNTRY,
  OFFICECODE,
  SRVCENTER,
  SUPERVISORID,
  SOLDTOBPNAME,
  '{{ invocation_id }}' AS AUDIT_LOG_ID,
  SHA2('hash_me') AS _ROW_HASH
FROM source_data
)

,type_data as (
    SELECT
        CAST(CUSTOMERREGION AS VARCHAR(16777216)) AS CUSTOMERREGION,
        CAST(CUSTOMERGROUP AS VARCHAR(16777216)) AS CUSTOMERGROUP,
        CAST(OFFICE AS VARCHAR(16777216)) AS OFFICE,
        CAST(BU AS VARCHAR(16777216)) AS BU,
        CAST(FAB AS VARCHAR(16777216)) AS FAB,
        CAST(CONFIG AS VARCHAR(16777216)) AS CONFIG,
        CAST(REGIONALSERVICEMANAGER AS VARCHAR(16777216)) AS REGIONALSERVICEMANAGER,
        CAST(SUPERVISOR AS VARCHAR(16777216)) AS SUPERVISOR,
        CAST(ACTIVETOOLCOUNT AS NUMBER(18,0)) AS ACTIVETOOLCOUNT,
        CAST(INACTIVETOOLCOUNT AS NUMBER(18,0)) AS INACTIVETOOLCOUNT,
        CAST(EXPIRED AS VARCHAR(16777216)) AS EXPIRED,
        CAST(CUSTOMERCODE AS VARCHAR(16777216)) AS CUSTOMERCODE,
        CAST(FABCUSTOMERCODE AS VARCHAR(16777216)) AS FABCUSTOMERCODE,
        CAST(ADDRESS AS VARCHAR(16777216)) AS ADDRESS,
        CAST(CITY AS VARCHAR(16777216)) AS CITY,
        CAST(STATE AS VARCHAR(16777216)) AS STATE,
        CAST(ZIPCODE AS VARCHAR(16777216)) AS ZIPCODE,
        CAST(COUNTRY AS VARCHAR(16777216)) AS COUNTRY,
        CAST(OFFICECODE AS VARCHAR(16777216)) AS OFFICECODE,
        CAST(SRVCENTER AS VARCHAR(16777216)) AS SRVCENTER,
        CAST(SUPERVISORID AS VARCHAR(16777216)) AS SUPERVISORID,
        CAST(SOLDTOBPNAME AS VARCHAR(16777216)) AS SOLDTOBPNAME,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)

SELECT * from type_data
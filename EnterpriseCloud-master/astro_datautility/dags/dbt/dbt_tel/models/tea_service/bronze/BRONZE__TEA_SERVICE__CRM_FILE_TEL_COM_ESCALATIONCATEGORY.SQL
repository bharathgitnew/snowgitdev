with source_data as (
    SELECT
        _FILEDATE,
        _FILENAME,
        _UPLOADDATE,
        JSONFIELD:Id::STRING AS ID, 
        JSONFIELD:SinkCreatedOn::STRING AS SINKCREATEDON, 
        JSONFIELD:SinkModifiedOn::STRING AS SINKMODIFIEDON, 
        JSONFIELD:statecode::STRING AS STATECODE, 

{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='TELQS_PROCESS_ORDER_DETAILS',
    unique_key = ['ID']
) }}

with source_data as
(
    SELECT
         JSONFIELD:ID::NUMBER(38,0) AS ID
        ,JSONFIELD:PONUMBER::STRING AS PONUMBER
        ,JSONFIELD:QUOTENUMBER::STRING AS QUOTENUMBER
        ,JSONFIELD:CUSTOMER::STRING AS CUSTOMER
        ,JSONFIELD:CUSTOMERCODE::STRING AS CUSTOMERCODE
        ,JSONFIELD:PRODUCT::STRING AS PRODUCT
        ,JSONFIELD:POAMOUNT::NUMBER(38,2) AS POAMOUNT
        ,REGEXP_REPLACE(JSONFIELD:PODATE, '\/Date\\(|\\)\/', '')::TIMESTAMP AS PODATE
        ,JSONFIELD:STATUS::NUMBER(38,0) AS STATUS
        ,JSONFIELD:WORKORDER::STRING AS WORKORDER
        ,JSONFIELD:FAB::STRING AS FAB
        ,JSONFIELD:CUSTOMERGROUP::STRING AS CUSTOMERGROUP
        ,JSONFIELD:BUSINESSISSUINGPO::STRING AS BUSINESSISSUINGPO
        ,JSONFIELD:QUOTEREQUESTOR::STRING AS QUOTEREQUESTOR
        ,JSONFIELD:QUOTESUPERVISOR::STRING AS QUOTESUPERVISOR
        ,JSONFIELD:SITESUPERVISOR::STRING AS SITESUPERVISOR
        ,REGEXP_REPLACE(JSONFIELD:RECIEVEDATE, '\/Date\\(|\\)\/', '')::TIMESTAMP AS RECIEVEDATE
        ,REGEXP_REPLACE(JSONFIELD:WORKSTARTDATE, '\/Date\\(|\\)\/', '')::TIMESTAMP AS WORKSTARTDATE
        ,REGEXP_REPLACE(JSONFIELD:PLANNEDENDDATE, '\/Date\\(|\\)\/', '')::TIMESTAMP AS PLANNEDENDDATE
        ,JSONFIELD:PODESCRIPTION::STRING AS PODESCRIPTION
        ,JSONFIELD:FSBCOMMENTS::STRING AS FSBCOMMENTS
        ,JSONFIELD:QUOTEREQUESTOREMPNO::STRING AS QUOTEREQUESTOREMPNO
        ,JSONFIELD:QUOTESUPERVISOREMPNO::STRING AS QUOTESUPERVISOREMPNO
        ,JSONFIELD:SITESUPERVISOREMPNO::STRING AS SITESUPERVISOREMPNO
        ,JSONFIELD:CUSTOMERGROUPID::NUMBER(38,0) AS CUSTOMERGROUPID  
    FROM {{ source("LZ_TELQS", "PROCESS_ORDER_DETAILS") }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source("LZ_TELQS", "PROCESS_ORDER_DETAILS") }})
)

,transform_data as
(
    SELECT
        ID
        ,PONUMBER
        ,QUOTENUMBER
        ,CUSTOMER
        ,CUSTOMERCODE
        ,PRODUCT
        ,POAMOUNT
        ,PODATE
        ,STATUS
        ,WORKORDER
        ,FAB
        ,CUSTOMERGROUP
        ,BUSINESSISSUINGPO
        ,QUOTEREQUESTOR
        ,QUOTESUPERVISOR
        ,SITESUPERVISOR
        ,RECIEVEDATE
        ,WORKSTARTDATE
        ,PLANNEDENDDATE
        ,PODESCRIPTION
        ,FSBCOMMENTS
        ,QUOTEREQUESTOREMPNO
        ,QUOTESUPERVISOREMPNO
        ,SITESUPERVISOREMPNO
        ,CUSTOMERGROUPID
        ,'{{ invocation_id }}' AS AUDIT_LOG_ID
        ,SHA2('hash_me') AS _ROW_HASH
    FROM source_data
)

,type_data as 
(
    select
        CAST(ID AS NUMBER(38,0)) AS ID
        ,CAST(PONUMBER AS VARCHAR(16777216)) AS PONUMBER
        ,CAST(QUOTENUMBER AS VARCHAR(16777216)) AS QUOTENUMBER
        ,CAST(CUSTOMER AS VARCHAR(16777216)) AS CUSTOMER
        ,CAST(CUSTOMERCODE AS VARCHAR(16777216)) AS CUSTOMERCODE
        ,CAST(PRODUCT AS VARCHAR(16777216)) AS PRODUCT
        ,CAST(POAMOUNT AS NUMBER(38,2)) AS POAMOUNT
        ,CAST(PODATE AS TIMESTAMP_NTZ(9)) AS PODATE
        ,CAST(STATUS AS NUMBER(38,0)) AS STATUS
        ,CAST(WORKORDER AS VARCHAR(16777216)) AS WORKORDER
        ,CAST(FAB AS VARCHAR(16777216)) AS FAB
        ,CAST(CUSTOMERGROUP AS VARCHAR(16777216)) AS CUSTOMERGROUP
        ,CAST(BUSINESSISSUINGPO AS VARCHAR(16777216)) AS BUSINESSISSUINGPO
        ,CAST(QUOTEREQUESTOR AS VARCHAR(16777216)) AS QUOTEREQUESTOR
        ,CAST(QUOTESUPERVISOR AS VARCHAR(16777216)) AS QUOTESUPERVISOR
        ,CAST(SITESUPERVISOR AS VARCHAR(16777216)) AS SITESUPERVISOR
        ,CAST(RECIEVEDATE AS TIMESTAMP_NTZ(9)) AS RECIEVEDATE
        ,CAST(WORKSTARTDATE AS TIMESTAMP_NTZ(9)) AS WORKSTARTDATE
        ,CAST(PLANNEDENDDATE AS TIMESTAMP_NTZ(9)) AS PLANNEDENDDATE
        ,CAST(PODESCRIPTION AS VARCHAR(16777216)) AS PODESCRIPTION
        ,CAST(FSBCOMMENTS AS VARCHAR(16777216)) AS FSBCOMMENTS
        ,CAST(QUOTEREQUESTOREMPNO AS VARCHAR(16777216)) AS QUOTEREQUESTOREMPNO
        ,CAST(QUOTESUPERVISOREMPNO AS VARCHAR(16777216)) AS QUOTESUPERVISOREMPNO
        ,CAST(SITESUPERVISOREMPNO AS VARCHAR(16777216)) AS SITESUPERVISOREMPNO
        ,CAST(CUSTOMERGROUPID AS NUMBER(38,0)) AS CUSTOMERGROUPID
        ,CAST(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID
        ,CAST(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
    )
select * from type_data
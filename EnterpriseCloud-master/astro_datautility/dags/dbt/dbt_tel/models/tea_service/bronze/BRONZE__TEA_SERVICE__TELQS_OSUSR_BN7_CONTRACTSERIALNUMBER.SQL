{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='TELQS_OSUSR_BN7_CONTRACTSERIALNUMBER'
) }}

with source_data as
(
SELECT
JSONFIELD:ID::STRING AS ID,
JSONFIELD:SERVICEQUOTEWITHCONTRACTID::STRING AS SERVICEQUOTEWITHCONTRACTID,
JSONFIELD:SOLD_TO_CODE::STRING AS SOLD_TO_CODE,
JSONFIELD:FAB_CODE::STRING AS FAB_CODE,
JSONFIELD:PRODUCT_LINE::STRING AS PRODUCT_LINE,
JSONFIELD:PRODUCT::STRING AS PRODUCT,
JSONFIELD:SERIAL_NBR::STRING AS SERIAL_NBR,
JSONFIELD:CUSTOMER_TOOL_ID::STRING AS CUSTOMER_TOOL_ID,
JSONFIELD:MODEL_NAME::STRING AS MODEL_NAME,
JSONFIELD:SYSTEM_NAME::STRING AS SYSTEM_NAME,
JSONFIELD:WTY_STATUS::STRING AS WTY_STATUS,
JSONFIELD:CONTRACT_SCOPE::STRING AS CONTRACT_SCOPE

FROM {{ source('LZ_TELQS', 'OSUSR_BN7_CONTRACTSERIALNUMBER') }}   
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_BN7_CONTRACTSERIALNUMBER') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
ID,
SERVICEQUOTEWITHCONTRACTID,
SOLD_TO_CODE,
FAB_CODE,
PRODUCT_LINE,
PRODUCT,
SERIAL_NBR,
CUSTOMER_TOOL_ID,
MODEL_NAME,
SYSTEM_NAME,
WTY_STATUS,
CONTRACT_SCOPE
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
ID,
SERVICEQUOTEWITHCONTRACTID,
SOLD_TO_CODE,
FAB_CODE,
PRODUCT_LINE,
PRODUCT,
SERIAL_NBR,
CUSTOMER_TOOL_ID,
MODEL_NAME,
SYSTEM_NAME,
WTY_STATUS,
CONTRACT_SCOPE
from transform_data 
)
SELECT * from type_data
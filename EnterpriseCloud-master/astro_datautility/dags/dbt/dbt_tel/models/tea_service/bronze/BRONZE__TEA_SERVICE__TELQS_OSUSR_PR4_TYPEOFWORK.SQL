{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='TELQS_OSUSR_PR4_TYPEOFWORK'
) }}

with source_data as
(
SELECT
JSONFIELD:ID::STRING AS ID,
JSONFIELD:TYPEOFWORK::STRING AS TYPEOFWORK,
JSONFIELD:IS_ACTIVE::STRING AS IS_ACTIVE,
JSONFIELD:ORDER::STRING AS ORDER_,
JSONFIELD:SAPSALESCATEGORYMAPPING::STRING AS SAPSALESCATEGORYMAPPING,
JSONFIELD:CREATEDBY::STRING AS CREATEDBY,
JSONFIELD:CREATEDON::STRING AS CREATEDON,
JSONFIELD:UPDATEDBY::STRING AS UPDATEDBY,
JSONFIELD:UPDATEDON::STRING AS UPDATEDON,
JSONFIELD:MATERIALMAPPING::STRING AS MATERIALMAPPING,
JSONFIELD:PRODUCTMODIFICATIONMAPPING::STRING AS PRODUCTMODIFICATIONMAPPING,
JSONFIELD:SALESCATEGORYCODE::STRING AS SALESCATEGORYCODE

FROM {{ source('LZ_TELQS', 'OSUSR_PR4_TYPEOFWORK') }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_PR4_TYPEOFWORK') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
ID,
TYPEOFWORK,
IS_ACTIVE,
ORDER_,
SAPSALESCATEGORYMAPPING,
CREATEDBY,
CREATEDON,
UPDATEDBY,
UPDATEDON,
MATERIALMAPPING,
PRODUCTMODIFICATIONMAPPING,
SALESCATEGORYCODE
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
ID,
TYPEOFWORK,
IS_ACTIVE,
ORDER_,
SAPSALESCATEGORYMAPPING,
CREATEDBY,
CREATEDON,
UPDATEDBY,
UPDATEDON,
MATERIALMAPPING,
PRODUCTMODIFICATIONMAPPING,
SALESCATEGORYCODE
from transform_data 
)
SELECT * from type_data
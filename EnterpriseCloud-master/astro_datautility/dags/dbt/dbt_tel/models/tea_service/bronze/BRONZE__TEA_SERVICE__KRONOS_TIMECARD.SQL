    incremental_strategy = 'merge',
    unique_key = ['RECORDID'],
    post_hook = "
        -- RECORDCREATEDDATE represents when the Kronos file was generated 
        -- but the files are batched by periods (current and previous)
        -- so if there is a newer file for the same period, we want to mark the older one as deleted
        delete from {{ this }} as a 
        using (
            select
                CURRENTPERIODSTARTDATE,
                CURRENTPERIODENDDATE,
                max(RECORDCREATEDDATE) as MAX_RECORDCREATEDDATE,
            from {{ this }}
            group by CURRENTPERIODSTARTDATE, CURRENTPERIODENDDATE
        ) as b
        where a.CURRENTPERIODSTARTDATE = b.CURRENTPERIODSTARTDATE and a.CURRENTPERIODENDDATE = b.CURRENTPERIODENDDATE
            and a.RECORDCREATEDDATE < b.MAX_RECORDCREATEDDATE
    ",
) }}



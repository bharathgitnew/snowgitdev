WITH TEQCONTRACTQUOTE AS (
SELECT
    QUOTENUMBER AS QUOTE_NUMBER
    ,TO_DATE(REQUEST_DATE, 'MM/DD/YYYY') AS REQUEST_DATE
    ,UPPER(REQUESTER) AS REQUESTER
    ,REQUESTER_SUPERVISOR
    ,CASE
    WHEN CUSTOMER_NAME = 'UNIVERSITY AT ALBANY (SUNY) (AA4337600)' THEN 'UNIVERSITY AT ALBANY (SUNY)'
    ELSE TRIM(SPLIT_PART(CUSTOMER_NAME, '(', 1))
    END AS CUSTOMER_NAME
    ,CASE
    WHEN CUSTOMER_NAME = 'UNIVERSITY AT ALBANY (SUNY) (AA4337600)' THEN 'AA4337600'
    ELSE LEFT(TRIM(SPLIT_PART(CUSTOMER_NAME, '(', 2)),9)
    END AS CUSTOMER_CODE_A
    ,COMPREHENSIVE AS COMPREHENSIVE_FLAG
    ,CASE
    WHEN LEN(PRODUCTS)>1 THEN PRODUCTS
    ELSE NULL
    END AS PRODUCTS_COVERED
    ,CONTRACT_TYPE
    ,TO_DATE(CONTRACTSTARTDATE, 'MM/DD/YYYY') AS CONTRACT_START
    ,TO_DATE(CONTRACTENDDATE, 'MM/DD/YYYY') AS CONTRACT_END
    ,CONTRACT_TOTAL AS CONTRACT_TOTAL
    ,QUOTE_STATUS
    ,CONTRACT_LENGTH
    ,NEW_CONTRACT
    ,CASE
    WHEN LEN(PREVIOUS_CONTRACT_NUMBER)>1 THEN PREVIOUS_CONTRACT_NUMBER
    ELSE NULL
    END AS PREVIOUS_CONTRACT_NUMBER
    ,COVERED_FAB
    ,TOTAL_BOH_HOURS
    ,TYPE_OF_WORK
    ,DESCRIPTION_OF_WORK
    ,FSC_TEAM
    ,_AUDIT_LOG_ID
    ,_ROW_HASH
FROM {{ ref('SILVER__TEA_SERVICE__SERVICE_CONTRACT_QUOTE_DATA') }}
WHERE 1=1
AND REQUESTER NOT IN ('MELISSA FLORES','Nuno Rodrigues', 'Richard Lazarus') -- These are test/dummy records
AND LEN(QUOTENUMBER) >1
)
,EMPLOYEE AS (
SELECT
    EMPLOYEEID
    ,UPPER(FIRSTNAME)||' '||UPPER(LASTNAME) AS NAME
    ,FULLNAME
    ,SUPERVISORID
    ,SUPERVISOR_NAME AS SUPERVISOR
    ,BU_GROUP AS EMP_BU_GROUP
    ,BU_GROUP_LEADER AS EMP_GROUP_LEADER
FROM {{ ref('SILVER__TEA_SERVICE__EMPLOYEE') }}
QUALIFY (ROW_NUMBER() OVER (PARTITION BY UPPER(FIRSTNAME)||' '||UPPER(LASTNAME) ORDER BY LASTUPDATED DESC, ACTIVE DESC)) = 1)
,CGM AS (
SELECT
    ACCOUNT_NUMBER
    ,CUSTOMER_GROUP
    ,CUSTOMER_GROUP2
FROM  {{ ref('BRONZE__TEA_SERVICE__SHAREPOINT_CUSTOMER_GROUP_MAPPING') }} )
,BUMAP AS (
SELECT
    BU_SOURCE_KEY
    ,BU_GROUP_LEADER
    ,BU_GROUP
    FROM {{ ref('BRONZE__TEA_SERVICE__SHAREPOINT_SERVICE_BUSINESS_UNIT_MAPPING') }} )
    ,COMBINED AS(
    SELECT
    TEQCONTRACTQUOTE.QUOTE_NUMBER
    ,TEQCONTRACTQUOTE.REQUEST_DATE
    ,COALESCE(REQUESTER.FULLNAME,TEQCONTRACTQUOTE.REQUESTER) AS REQUESTER
    ,REQUESTER.SUPERVISOR AS REQUESTER_CURRENT_SUPERVISOR
    ,CGM.CUSTOMER_GROUP
    ,TEQCONTRACTQUOTE.CUSTOMER_NAME
    ,TEQCONTRACTQUOTE.CUSTOMER_CODE_A
    ,TEQCONTRACTQUOTE.PRODUCTS_COVERED
    ,TEQCONTRACTQUOTE.COMPREHENSIVE_FLAG
    ,TEQCONTRACTQUOTE.CONTRACT_TYPE
    ,TEQCONTRACTQUOTE.CONTRACT_START
    ,TEQCONTRACTQUOTE.CONTRACT_END
    ,TEQCONTRACTQUOTE.CONTRACT_TOTAL
    ,TEQCONTRACTQUOTE.QUOTE_STATUS
    ,TEQCONTRACTQUOTE.CONTRACT_LENGTH
    ,TEQCONTRACTQUOTE.TOTAL_BOH_HOURS
    ,TEQCONTRACTQUOTE.NEW_CONTRACT
    ,TEQCONTRACTQUOTE.PREVIOUS_CONTRACT_NUMBER
    ,TEQCONTRACTQUOTE.COVERED_FAB
    ,TEQCONTRACTQUOTE.TYPE_OF_WORK
    ,TEQCONTRACTQUOTE.DESCRIPTION_OF_WORK
    ,TEQCONTRACTQUOTE.FSC_TEAM
    ,CASE
    WHEN BUMAP.BU_GROUP IS NOT NULL THEN BUMAP.BU_GROUP
    WHEN TEQCONTRACTQUOTE.PRODUCTS_COVERED LIKE '%,%' THEN 'Multi BU'
    ELSE NULL
    END AS COVERED_BU_GROUP
    ,CASE
    WHEN BUMAP.BU_GROUP_LEADER IS NOT NULL THEN BUMAP.BU_GROUP_LEADER
    WHEN TEQCONTRACTQUOTE.PRODUCTS_COVERED LIKE '%,%' THEN NULL
    ELSE NULL
    END AS BU_GROUP_LEADER
    ,CGM.CUSTOMER_GROUP2
    ,REQUESTER.EMPLOYEEID AS REQUESTERID
    ,REQUESTER.SUPERVISORID AS REQUESTER_CURRENT_SUPERVISORID
    ,TEQCONTRACTQUOTE.REQUESTER_SUPERVISOR AS ORIGINAL_REQUESTER_SUPERVISOR
FROM TEQCONTRACTQUOTE
LEFT OUTER JOIN EMPLOYEE REQUESTER
ON TEQCONTRACTQUOTE.REQUESTER = REQUESTER.NAME
LEFT OUTER JOIN CGM
ON CGM.ACCOUNT_NUMBER = TEQCONTRACTQUOTE.CUSTOMER_CODE_A
LEFT OUTER JOIN BUMAP
ON BUMAP.BU_SOURCE_KEY = TEQCONTRACTQUOTE.PRODUCTS_COVERED)
,
source_data AS (
SELECT
    QUOTE_NUMBER
    ,REQUEST_DATE
    ,REQUESTER
    ,REQUESTER_CURRENT_SUPERVISOR
    ,CUSTOMER_GROUP
    ,CUSTOMER_NAME
    ,CUSTOMER_CODE_A
    ,PRODUCTS_COVERED
    ,COMPREHENSIVE_FLAG
    ,CONTRACT_TYPE
    ,CONTRACT_START
    ,CONTRACT_END
    ,CONTRACT_TOTAL
    ,QUOTE_STATUS
    ,CONTRACT_LENGTH
    ,TOTAL_BOH_HOURS
    ,NEW_CONTRACT
    ,PREVIOUS_CONTRACT_NUMBER
    ,COVERED_FAB
    ,TYPE_OF_WORK
    ,DESCRIPTION_OF_WORK
    ,FSC_TEAM
    ,COVERED_BU_GROUP
    ,BU_GROUP_LEADER
    ,CUSTOMER_GROUP2
    ,REQUESTERID
    ,REQUESTER_CURRENT_SUPERVISORID
    ,ORIGINAL_REQUESTER_SUPERVISOR
FROM COMBINED
ORDER BY REQUEST_DATE DESC
),
transform_data as(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    QUOTE_NUMBER
    ,REQUEST_DATE
    ,REQUESTER
    ,REQUESTER_CURRENT_SUPERVISOR
    ,CUSTOMER_GROUP
    ,CUSTOMER_NAME
    ,CUSTOMER_CODE_A
    ,PRODUCTS_COVERED
    ,COMPREHENSIVE_FLAG
    ,CONTRACT_TYPE
    ,CONTRACT_START
    ,CONTRACT_END
    ,CONTRACT_TOTAL
    ,QUOTE_STATUS
    ,CONTRACT_LENGTH
    ,TOTAL_BOH_HOURS
    ,NEW_CONTRACT
    ,PREVIOUS_CONTRACT_NUMBER
    ,COVERED_FAB
    ,TYPE_OF_WORK
    ,DESCRIPTION_OF_WORK
    ,FSC_TEAM
    ,COVERED_BU_GROUP
    ,BU_GROUP_LEADER
    ,CUSTOMER_GROUP2
    ,REQUESTERID
    ,REQUESTER_CURRENT_SUPERVISORID
    ,ORIGINAL_REQUESTER_SUPERVISOR
FROM source_data
),
type_data AS (
SELECT
    _AUDIT_LOG_ID
    ,_ROW_HASH
    ,QUOTE_NUMBER
    ,CAST(REQUEST_DATE as DATE) AS REQUEST_DATE
    ,REQUESTER
    ,REQUESTER_CURRENT_SUPERVISOR
    ,CUSTOMER_GROUP
    ,CUSTOMER_NAME
    ,CUSTOMER_CODE_A
    ,PRODUCTS_COVERED
    ,COMPREHENSIVE_FLAG
    ,CONTRACT_TYPE
    ,CAST(CONTRACT_START as DATE) AS CONTRACT_START
    ,CAST(CONTRACT_END as DATE) AS CONTRACT_END
    ,CAST(CONTRACT_TOTAL as NUMBER(38,2)) AS CONTRACT_TOTAL
    ,QUOTE_STATUS
    ,CONTRACT_LENGTH
    ,CAST(TOTAL_BOH_HOURS as NUMBER(38,2)) AS TOTAL_BOH_HOURS
    ,NEW_CONTRACT
    ,PREVIOUS_CONTRACT_NUMBER
    ,COVERED_FAB
    ,TYPE_OF_WORK
    ,DESCRIPTION_OF_WORK
    ,FSC_TEAM
    ,COVERED_BU_GROUP
    ,BU_GROUP_LEADER
    ,CUSTOMER_GROUP2
    ,REQUESTERID
    ,REQUESTER_CURRENT_SUPERVISORID
    ,ORIGINAL_REQUESTER_SUPERVISOR
FROM transform_data
)
SELECT * FROM type_data
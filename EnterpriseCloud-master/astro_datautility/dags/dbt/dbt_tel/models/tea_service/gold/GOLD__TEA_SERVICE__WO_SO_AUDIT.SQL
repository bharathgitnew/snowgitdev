{{ config(
        alias = 'WO_SO_AUDIT',
        materialized='tel_incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with source_data as (
    SELECT 
        W.WO_MSDYN_NAME AS WO_NO
        ,W.WO_WOTITLE AS WO_TITLE 
        ,W.MACHINE_MSDYN_NAME AS MACHINE_SEARCH
        ,PAYMENT_TYPE.LOCALIZEDLABEL AS PAYMENT_TYPE 
        ,MAINCATEGORY.LOCALIZEDLABEL AS MAIN_CATEGORY 
        ,W.WO_NAME AS SUBCATEGORY 
        ,W.WO_PLANNEDSTART AS PLANNED_START_DATE 
        ,W.WO_PLANNEDEND AS PLANNED_END_DATE 
        ,W.PRIMARY_TEL_COM_SALES_DOCUMENT_NO AS PRIMARY_SO 
        ,W.PRIMARY_TEL_COM_SALES_DOC_TYPE_CODE AS PRIMARY_SO_SALES_DOC_TYPE_CODE 
        ,W.SECONDARY_TEL_COM_SALES_DOCUMENT_NO AS SECONDARY_SO 
        ,W.SECONDARY_TEL_COM_SALES_DOC_TYPE_CODE AS SECONDARY_SO_SALES_DOC_TYPE_CODE 
        ,W.TEL_WO_SERVICEORDERNO_3200 AS TEA_SERVICE_ORDER_NO 
        ,W.WO_CREATEDON AS CREATED_DATE 
        ,W.WO_MODIFIEDON AS MODIFIED_DATE 
        ,REGION.NAME AS REGION 
    FROM {{ ref('SILVER__TEA_SERVICE__WO_SUMMARY_DETAILS') }} AS W 
    LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__TERRITORY') }} REGION 
        ON W.WO_WO_REGION = REGION.ID
    LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__OPTIONSET_METADATA') }} AS PAYMENT_TYPE
        ON W.WO_TEL_WO_TYPEOFPAYMENT = PAYMENT_TYPE.OPTION 
        AND PAYMENT_TYPE.OPTIONSETNAME = 'tel_wo_typeofpayment' 
        AND PAYMENT_TYPE.LOCALIZEDLABELLANGUAGECODE = 1033
        AND PAYMENT_TYPE.ENTITYNAME = 'msdyn_workorder'
    LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__OPTIONSET_METADATA') }} AS MAINCATEGORY
        ON W.TEL_WO_MAINCATEGORY_SOREQUEST = MAINCATEGORY.OPTION 
        AND MAINCATEGORY.OPTIONSETNAME = 'tel_wo_maincategory_sorequest' 
        AND MAINCATEGORY.LOCALIZEDLABELLANGUAGECODE = 1033
    WHERE REGION.NAME = 'US' 
        --AND REGION.SOURCE_FLAG = 'WO'
),

transform_data as (
    select 
        WO_NO,
        WO_TITLE,
        MACHINE_SEARCH,
        PAYMENT_TYPE,
        MAIN_CATEGORY,
        SUBCATEGORY,
        PLANNED_START_DATE,
        PLANNED_END_DATE,
        PRIMARY_SO,
        PRIMARY_SO_SALES_DOC_TYPE_CODE,
        SECONDARY_SO,
        SECONDARY_SO_SALES_DOC_TYPE_CODE,
        TEA_SERVICE_ORDER_NO,
        CREATED_DATE,
        MODIFIED_DATE,
        REGION,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    from source_data
),

type_data as (
    select 
       cast(WO_NO as VARCHAR(16777216)) as WO_NO,
       cast(WO_TITLE as VARCHAR(16777216)) as WO_TITLE,
       cast(MACHINE_SEARCH as VARCHAR(16777216)) as MACHINE_SEARCH,
       cast(PAYMENT_TYPE as VARCHAR(16777216)) as PAYMENT_TYPE,
       cast(MAIN_CATEGORY as VARCHAR(16777216)) as MAIN_CATEGORY,
       cast(SUBCATEGORY as VARCHAR(16777216)) as SUBCATEGORY,
       cast(PLANNED_START_DATE as TIMESTAMP_LTZ(9)) as PLANNED_START_DATE,
       cast(PLANNED_END_DATE as TIMESTAMP_LTZ(9)) as PLANNED_END_DATE,
       cast(PRIMARY_SO as VARCHAR(16777216)) as PRIMARY_SO,
       cast(PRIMARY_SO_SALES_DOC_TYPE_CODE as VARCHAR(16777216)) as PRIMARY_SO_SALES_DOC_TYPE_CODE,
       cast(SECONDARY_SO as VARCHAR(16777216)) as SECONDARY_SO,
       cast(SECONDARY_SO_SALES_DOC_TYPE_CODE as VARCHAR(16777216)) as SECONDARY_SO_SALES_DOC_TYPE_CODE,
       cast(TEA_SERVICE_ORDER_NO as VARCHAR(16777216)) as TEA_SERVICE_ORDER_NO,
       cast(CREATED_DATE as TIMESTAMP_LTZ(9)) as CREATED_DATE,
       cast(MODIFIED_DATE as TIMESTAMP_LTZ(9)) as MODIFIED_DATE,
       cast(REGION as VARCHAR(16777216)) as REGION,
       cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID,
       cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    from transform_data
)

select * from type_data
WITH SOITEM_SAP AS
(
  SELECT
    VBAP.POSNR AS "SO_ITEM",
    VBAP.VBELN AS "SO",
    CASE
      WHEN VBAP.ZZBAST IN (NULL, '') THEN 'Awaiting for WF requirement Judge/WF not required'
      WHEN VBAP.ZZBAST = 'A' THEN 'Auto Approval'
      WHEN VBAP.ZZBAST = 'C' THEN 'Approved'
      WHEN VBAP.ZZBAST = 'Q' THEN 'Awaiting WF'
      WHEN VBAP.ZZBAST = 'R' THEN 'Rejected'
      WHEN VBAP.ZZBAST = 'P' THEN 'Partially Approved'
      WHEN VBAP.ZZBAST = 'Z' THEN 'Approved for sales and DP cancellation'
      WHEN VBAP.ZZBAST = 'W' THEN 'Rejected for sales and DP cancellation'
      ELSE 'ERROR'
    END AS "SALES_APPROVAL_STATUS",
    CASE
      WHEN VBAP.ZZAPAST IN (NULL, '') THEN 'Awaiting for WF requirement Judge/WF not required'
      WHEN VBAP.ZZAPAST = 'A' THEN 'Auto Approval'
      WHEN VBAP.ZZAPAST = 'C' THEN 'Approved'
      WHEN VBAP.ZZAPAST = 'Q' THEN 'Awaiting WF'
      WHEN VBAP.ZZAPAST = 'R' THEN 'Rejected'
      WHEN VBAP.ZZAPAST = 'P' THEN 'Partially Approved'
      WHEN VBAP.ZZAPAST = 'Z' THEN 'Approved for sales and DP cancellation'
      WHEN VBAP.ZZAPAST = 'W' THEN 'Rejected for sales and DP cancellation'
      ELSE 'ERROR'
    END AS "DP_APPROVAL_STATUS",
    VBAP.PSTYV AS "ITEM_CATEGORY",
    VBAP.ABGRU AS "REJECTION_REASON",
    VBAP.IS_DELETED,
    VBAP.MATNR AS "MATERIAL_NUMBER"
  FROM {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU010_VBAP') }} as VBAP
),

SOITEM_CRM AS
(
  SELECT
    SOITEM.TEL_COM_CONTRACT_NUMBER AS "CONTRACT_NO",
    SOITEM.TEL_COM_SOW AS "SOW",
    LEFT(SOITEM.TEL_COM_SOW,8) AS "SCOPE",
    SOITEM.TEL_COM_SOITEMNO AS "SO_ITEM"
  FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_TEL_COM_SALESORDERITEM') }} AS SOITEM
),

SOHEADER_SAP AS
(
  SELECT
    VBAK.AUART AS "SO_TYPE",
    VBAK.VBELN AS "SO"
  FROM {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU009_VBAK') }} AS VBAK
),

CON AS
(
  SELECT
      CONTRACT_TITLE,
      MANAGED_BY,
      CONTRACT_NUMBER,
      CONTRACT_TYPE
  FROM {{ ref('SILVER__TEA_SERVICE__CONTRACTS_MASTER') }}
),

SOBUSINESS_SAP AS
(
  SELECT
    RIGHT('0000000000'||VBKD.FPLNR, 10) AS "BILLING_PLAN_NUMBER",
    VBKD.POSNR AS "SO_ITEM",
    VBKD.VBELN AS "SO"
  FROM {{ ref('BRONZE__TEA_SERVICE__SAPH_SAP_US_SDT_EV_VBKD') }} AS VBKD
),

BILLING_ITEMS AS
(
  SELECT
    FPLT.FAKSP AS "BILLING_BLOCK",
    CASE
      WHEN FPLT.AFDAT IS NULL OR FPLT.AFDAT = '' THEN NULL
      ELSE
      LEFT(FPLT.AFDAT,4)||'-'||
      RIGHT(LEFT(FPLT.AFDAT,6),2)||'-'||
      RIGHT(FPLT.AFDAT,2)
    END AS "BILLING_DATE",
    FPLT.FPLTR AS "BILLING_ITEM_NUMBER",
    LEFT(FPLT.AFDAT,4)||'-'||RIGHT(LEFT(FPLT.AFDAT,6),2) AS "BILLING_MONTH",
    RIGHT('0000000000'||FPLT.FPLNR,10) AS "BILLING_PLAN_NUMBER",
    FPLT.FKSAF AS "BILLING_STATUS",
    FPLT.NETPR AS "NET_PRICE"
  FROM {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU192_FPLT') }} AS FPLT
),

DP_REQUEST AS
(
  SELECT
    SOHEADER_SAP.SO_TYPE,
    SOHEADER_SAP.SO,
    SOITEM_SAP.SO_ITEM,
    SOHEADER_SAP.SO||SOITEM_SAP.SO_ITEM AS SO_SOITEM,
    SOITEM_CRM.CONTRACT_NO,
    CON.CONTRACT_TITLE,
    CON.MANAGED_BY,
    CON.CONTRACT_TYPE,
    SOITEM_CRM.SOW,
    SOITEM_CRM.SCOPE,
    SOITEM_SAP.SALES_APPROVAL_STATUS,
    SOITEM_SAP.DP_APPROVAL_STATUS,
    BILLING_ITEMS.BILLING_BLOCK,
    BILLING_ITEMS.BILLING_PLAN_NUMBER,
    BILLING_ITEMS.BILLING_ITEM_NUMBER,
    BILLING_ITEMS.BILLING_DATE,
    BILLING_ITEMS.BILLING_MONTH,
    BILLING_ITEMS.BILLING_STATUS,
    BILLING_ITEMS.NET_PRICE
  FROM SOITEM_SAP
  LEFT JOIN SOITEM_CRM
  ON SOITEM_CRM.SO_ITEM = SOITEM_SAP.SO||SOITEM_SAP.SO_ITEM
  LEFT JOIN SOHEADER_SAP
  ON SOHEADER_SAP.SO = SOITEM_SAP.SO
  LEFT JOIN CON
  ON CON.CONTRACT_NUMBER = SOITEM_CRM.CONTRACT_NO
  LEFT JOIN SOBUSINESS_SAP
  ON SOBUSINESS_SAP.SO = SOITEM_SAP.SO
  AND RIGHT('000000'||SOBUSINESS_SAP.SO_ITEM,6) = RIGHT('000000'||SOITEM_SAP.SO_ITEM,6)
  LEFT JOIN BILLING_ITEMS
  ON BILLING_ITEMS.BILLING_PLAN_NUMBER = SOBUSINESS_SAP.BILLING_PLAN_NUMBER
  WHERE
  SOHEADER_SAP.SO_TYPE = 'ZC11' AND
  SOITEM_CRM.SO_ITEM IS NOT NULL AND
  SOITEM_SAP.IS_DELETED = 'No' AND
  SOITEM_SAP.MATERIAL_NUMBER = 'CONTRACT_BILLING' AND
  IFNULL(SOITEM_SAP.REJECTION_REASON,'') = ''
),

source_data as (
SELECT DISTINCT
    CAST(SO_TYPE AS VARCHAR(16777216)) AS SO_TYPE,
    CAST(SO AS VARCHAR(16777216)) AS SO,
    CAST(SO_ITEM AS VARCHAR(16777216)) AS SO_ITEM,
    CAST(SO_SOITEM AS VARCHAR(16777216)) AS SO_SOITEM,
    CAST(CONTRACT_NO AS VARCHAR(16777216)) AS CONTRACT_NO,
    CAST(CONTRACT_TITLE AS VARCHAR(16777216)) AS CONTRACT_TITLE,
    CAST(MANAGED_BY AS VARCHAR(16777216)) AS CONTRACT_MANAGED_BY,
    CAST(CONTRACT_TYPE AS VARCHAR(16777216)) AS CONTRACT_TYPE,
    CAST(SOW AS VARCHAR(16777216)) AS SOW,
    CAST(SCOPE AS VARCHAR(16777216)) AS SCOPE,
    CAST(SALES_APPROVAL_STATUS AS VARCHAR(16777216)) AS SALES_APPROVAL_STATUS,
    CAST(DP_APPROVAL_STATUS AS VARCHAR(16777216)) AS DP_APPROVAL_STATUS,
    CAST(BILLING_BLOCK AS VARCHAR(16777216)) AS BILLING_BLOCK,
    CAST(BILLING_PLAN_NUMBER AS VARCHAR(16777216)) AS BILLING_PLAN_NUMBER,
    CAST(BILLING_ITEM_NUMBER AS VARCHAR(16777216)) AS BILLING_ITEM_NUMBER,
    CAST(BILLING_DATE AS DATE) AS BILLING_DATE,
    CAST(BILLING_MONTH AS VARCHAR(16777216)) AS BILLING_MONTH,
    CAST(BILLING_STATUS AS VARCHAR(16777216)) AS BILLING_STATUS,
    CAST(NET_PRICE AS DECIMAL(15,2)) AS NET_PRICE
FROM DP_REQUEST
),

transform_data as (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    SO_TYPE,
    SO,
    SO_ITEM,
    SO_SOITEM,
    CONTRACT_NO,
    CONTRACT_TITLE,
    CONTRACT_MANAGED_BY,
    CONTRACT_TYPE,
    SOW,
    SCOPE,
    SALES_APPROVAL_STATUS,
    DP_APPROVAL_STATUS,
    BILLING_BLOCK,
    BILLING_PLAN_NUMBER,
    BILLING_ITEM_NUMBER,
    CAST(BILLING_DATE AS DATE) AS BILLING_DATE,
    BILLING_MONTH,
    BILLING_STATUS,
    CAST(NET_PRICE AS NUMBER(15,2)) AS NET_PRICE
from source_data
),

type_data as (
SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    SO_TYPE,
    SO,
    SO_ITEM,
    SO_SOITEM,
    CONTRACT_NO,
    CONTRACT_TITLE,
    CONTRACT_MANAGED_BY,
    CONTRACT_TYPE,
    SOW,
    SCOPE,
    SALES_APPROVAL_STATUS,
    DP_APPROVAL_STATUS,
    BILLING_BLOCK,
    BILLING_PLAN_NUMBER,
    BILLING_ITEM_NUMBER,
    CAST(BILLING_DATE AS DATE) AS BILLING_DATE,
    BILLING_MONTH,
    BILLING_STATUS,
    CAST(NET_PRICE AS NUMBER(15,2)) AS NET_PRICE
from transform_data
)

SELECT *  FROM type_data
WITH CONTRACTDETAILS AS (
	SELECT
                DISTINCT
                ID_CONTRACT_SUMMARY
		,CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
	FROM {{ ref('SILVER__TEA_SERVICE__CONTRACT_SUMMARY_DETAILS') }}
)
,CONTRACT_MASTER AS (
        SELECT
                DISTINCT
                CONTRACT_NUMBER
                ,CUSTOMER_GROUP
                ,CUSTOMER_NAME AS CUSTOMER
                ,CUSTOMER_CODE
                ,CONTRACT_TITLE
                ,CONTRACT_START_DATE
                ,CONTRACT_END_DATE
                ,CONTRACT_STATUS
                ,CONTRACT_OWNER
        FROM {{ ref('SILVER__TEA_SERVICE__CONTRACTS_MASTER') }}
)
,CSCA AS (
	SELECT
	        MSDYN_AGREEMENTID
		,MSDYN_CUSTOMERASSETID
	FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_CNT_MSDYN_AGREEMENT_MSDYN_CUSTOMERASSET') }}
)
,CS AS (
	SELECT
		ID
                ,CNT_FS_AREA_TERRITORYNAME
		,MSDYN_NAME AS CONTRACT_SCOPE_GROUPID
                ,CNT_CONTRACTSCOPESO AS CONTRACT_SCOPE
		,CNT_FS_AREA_TERRITORYNAME AS REGION
                ,CNT_CONTRACTGROUP  --Uppercase
	FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_MSDYN_AGREEMENT') }}
)
,CA AS (
	SELECT
		ID
		,MSDYN_ACCOUNT
		,COM_PRODUCTLINE
		,MSDYN_NAME AS SERIAL_NUMBER
		,TEL_COM_SAP_PRODUCT_CODE AS SAP_PRODUCT_TYPE
		,COM_TOOLID_EN AS CUSTOMER_TOOL_ID
		,COM_CUSTOMERBY9DIGITS
                ,COM_MACHINEID
	FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_MSDYN_CUSTOMERASSET') }}
)
,PRODUCTLINE AS (
	SELECT
                ID AS PRODUCT_ID -- upper case
                ,COM_BUNAME AS MACHINE_BU
        FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_COM_PRODUCTLINE') }}
)
,CAACC AS (
	SELECT
		ID
		,ACCOUNTNUMBER AS MACHINE_ENDUSER_CODE
		,NAME AS SITE_CUSTOMER_NAME_ENDUSER
	FROM {{ ref('SILVER__TEA_SERVICE__ACCOUNT') }}
)
,CALOC AS (
	SELECT
		ID
		,ACCOUNTNUMBER AS CRM_MACHINE_D_CODE
		,NAME AS FAB_CUSTOMER_NAME_INSTALL_LOCATION
		,COM_COMPANY_E_NAME
	FROM {{ ref('SILVER__TEA_SERVICE__ACCOUNT') }}
)
,COVERED_ALL AS(
      SELECT
        CNT_CONTRUCTNUMBER ,
        TEL_COM_SEARCH_TERM_2_EN,
        ACC.ACCOUNTNUMBER
      FROM {{ ref('SILVER__TEA_SERVICE__CONTRACT_SUMMARY_DETAILS') }} CSD
        LEFT OUTER JOIN {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_CNT_CNT_CONTRACTSUMMARY_ACCOUNT_FAB') }}  AF
                ON UPPER(AF.CNT_CONTRACTSUMMARYID) = UPPER(CSD.ID_CONTRACT_SUMMARY)
        LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__ACCOUNT') }} ACC
                ON UPPER(ACC.ID) = UPPER(AF.ACCOUNTID)
)
,COVEREDFAB AS (
        SELECT DISTINCT
                CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
                ,LISTAGG(DISTINCT ACCOUNTNUMBER, ', ') OVER (PARTITION BY CNT_CONTRUCTNUMBER) AS COVERED_CUSTOMER_CODES
        FROM COVERED_ALL
)
,COVEREDFABNAMES AS (
        SELECT DISTINCT
                CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
                ,LISTAGG(DISTINCT TEL_COM_SEARCH_TERM_2_EN, ', ') OVER (PARTITION BY CNT_CONTRUCTNUMBER) AS COVERED_FABS
        FROM COVERED_ALL
)
,LEGACYOFFICE AS (
        SELECT
                B_CODE
                ,LEGACY_OFFICE
        FROM {{ ref('SILVER__TEA_SERVICE__SERVICE_B_CODE_MAPPING') }}
)
,MACHINES AS (
	SELECT
		SERIAL_NUMBER
		,CUSTOMER_TOOL_ID
                ,TEL_MODEL
		,SWLH_MODEL
		,START_UP_STATUS
                ,WARRANTY_STATUS
                ,CUSTOMER_CODE_B AS WISDOM_B_CODE
                ,CUSTOMER_CODE_D AS WISDOM_D_CODE
                ,MACHINE_HISTORY_REASON
                ,WAFER_SIZE
                ,WARRANTY_START
                ,WARRANTY_END
                ,LOAN_FLAG
                ,ACTIVE_FLAG AS WISDOM_ACTIVE_FLAG
                ,WISDOM_MAC_ID
	FROM {{ ref('GOLD__TEA_SERVICE__GLOBAL_MACHINES') }}
)
,SOURCE AS (
	SELECT
                CS.REGION
                ,CONTRACT_MASTER.CUSTOMER_GROUP
                ,CONTRACT_MASTER.CUSTOMER
                ,CA.SAP_PRODUCT_TYPE
                ,PRODUCTLINE.MACHINE_BU
                ,CA.SERIAL_NUMBER
                ,MACHINES.CUSTOMER_TOOL_ID
                ,WARRANTY_STATUS
		,CONTRACT_MASTER.CONTRACT_NUMBER
		,CONTRACT_MASTER.CONTRACT_TITLE
                ,CONTRACT_MASTER.CONTRACT_START_DATE
                ,CONTRACT_MASTER.CONTRACT_END_DATE
                ,CONTRACT_MASTER.CONTRACT_STATUS
		,CS.CONTRACT_SCOPE
                ,CONTRACT_MASTER.CONTRACT_OWNER
                ,LEGACYOFFICE.LEGACY_OFFICE
                ,COVEREDFABNAMES.COVERED_FABS
                ,COVEREDFAB.COVERED_CUSTOMER_CODES
                ,MACHINES.WISDOM_B_CODE
                ,MACHINES.WISDOM_D_CODE
                ,MACHINES.WISDOM_ACTIVE_FLAG
                ,MACHINES.SWLH_MODEL
                ,MACHINES.TEL_MODEL
                ,MACHINES.WAFER_SIZE
                ,MACHINES.MACHINE_HISTORY_REASON
                ,MACHINES.WARRANTY_START
                ,MACHINES.WARRANTY_END
                ,MACHINES.START_UP_STATUS
                ,MACHINES.LOAN_FLAG
                ,CASE
		        WHEN CONTAINS(COVEREDFAB.COVERED_CUSTOMER_CODES,MACHINES.WISDOM_B_CODE) = 'TRUE' THEN 'Y'
		        ELSE 'N'
		END AS MACHINE_LOCATION_MATCH_FLAG
	FROM CSCA
		LEFT OUTER JOIN CS
			ON UPPER(CS.ID) = UPPER(CSCA.MSDYN_AGREEMENTID )
		LEFT OUTER JOIN  CONTRACTDETAILS
			ON CS.CNT_CONTRACTGROUP = CONTRACTDETAILS.ID_CONTRACT_SUMMARY
		LEFT OUTER JOIN  CA
			ON UPPER(CA.ID) = UPPER(CSCA.MSDYN_CUSTOMERASSETID)
		LEFT OUTER JOIN  PRODUCTLINE
			ON CA.COM_PRODUCTLINE = PRODUCTLINE.PRODUCT_ID
		LEFT OUTER JOIN  CAACC
			ON CA.MSDYN_ACCOUNT = CAACC.ID
		LEFT OUTER JOIN  CALOC
			ON CA.COM_CUSTOMERBY9DIGITS = CALOC.ID
                LEFT OUTER JOIN MACHINES
                ON MACHINES.WISDOM_MAC_ID = CA.COM_MACHINEID
                LEFT OUTER JOIN CONTRACT_MASTER
                ON CONTRACTDETAILS.CONTRACT_NUMBER = CONTRACT_MASTER.CONTRACT_NUMBER
                LEFT OUTER JOIN LEGACYOFFICE
                ON CONTRACT_MASTER.CUSTOMER_CODE = LEGACYOFFICE.B_CODE
                LEFT OUTER JOIN COVEREDFAB
                ON CONTRACTDETAILS.CONTRACT_NUMBER = COVEREDFAB.CONTRACT_NUMBER
                LEFT OUTER JOIN COVEREDFABNAMES
                ON CONTRACTDETAILS.CONTRACT_NUMBER = COVEREDFABNAMES.CONTRACT_NUMBER
        WHERE  1 = 1
                AND LEFT(REGION,2) ='US'
                AND CONTRACT_STATUS <> 'Expired')
,TRANSFORM_DATA AS (
	SELECT
                REGION
                ,CUSTOMER_GROUP
                ,CUSTOMER
                ,SAP_PRODUCT_TYPE
                ,MACHINE_BU
                ,SERIAL_NUMBER
                ,CUSTOMER_TOOL_ID
                ,WARRANTY_STATUS
                ,CONTRACT_NUMBER
                ,CONTRACT_TITLE
                ,CONTRACT_START_DATE
                ,CONTRACT_END_DATE
                ,CONTRACT_STATUS
                ,CONTRACT_SCOPE
                ,CONTRACT_OWNER
                ,LEGACY_OFFICE
                ,COVERED_FABS
                ,COVERED_CUSTOMER_CODES
                ,WISDOM_B_CODE
                ,WISDOM_D_CODE
                ,WISDOM_ACTIVE_FLAG
                ,SWLH_MODEL
                ,TEL_MODEL
                ,WAFER_SIZE
                ,MACHINE_HISTORY_REASON
                ,WARRANTY_START
                ,WARRANTY_END
                ,START_UP_STATUS
                ,LOAN_FLAG
                ,MACHINE_LOCATION_MATCH_FLAG
                ,ROW_NUMBER() over (PARTITION BY SERIAL_NUMBER ORDER BY CONTRACT_NUMBER DESC) AS SN_ROW_NUMBER
        FROM SOURCE
)
,TYPE_DATA AS (
	SELECT
                CAST(REGION as VARCHAR(16777216)) AS REGION
                ,CAST(CUSTOMER_GROUP as VARCHAR(16777216)) AS CUSTOMER_GROUP
                ,CAST(CUSTOMER as VARCHAR(16777216)) AS CUSTOMER
                ,CAST(SAP_PRODUCT_TYPE as VARCHAR(16777216)) AS SAP_PRODUCT_TYPE
                ,CAST(MACHINE_BU as VARCHAR(16777216)) AS MACHINE_BU
                ,CAST(SERIAL_NUMBER as VARCHAR(16777216)) AS SERIAL_NUMBER
                ,CAST(CUSTOMER_TOOL_ID as VARCHAR(16777216)) AS CUSTOMER_TOOL_ID
                ,CAST(WARRANTY_STATUS as VARCHAR(16777216)) AS WARRANTY_STATUS
		,CAST(CONTRACT_NUMBER as VARCHAR(16777216)) AS CONTRACT_NUMBER
		,CAST(CONTRACT_TITLE as VARCHAR(16777216)) AS CONTRACT_TITLE
                ,CAST(CONTRACT_START_DATE as DATE) AS CONTRACT_START_DATE
                ,CAST(CONTRACT_END_DATE as DATE) AS CONTRACT_END_DATE
                ,CAST(CONTRACT_STATUS as VARCHAR(16777216)) AS CONTRACT_STATUS
		,CAST(CONTRACT_SCOPE as VARCHAR(16777216)) AS CONTRACT_SCOPE
                ,CAST(CONTRACT_OWNER as VARCHAR(16777216)) AS CONTRACT_OWNER
                ,CAST(LEGACY_OFFICE as VARCHAR(16777216)) AS LEGACY_OFFICE
                ,CAST(COVERED_FABS as VARCHAR(16777216)) AS COVERED_FABS
                ,CAST(COVERED_CUSTOMER_CODES as VARCHAR(16777216)) AS COVERED_CUSTOMER_CODES
                ,CAST(WISDOM_B_CODE as VARCHAR(16777216)) AS WISDOM_B_CODE
                ,CAST(WISDOM_D_CODE as VARCHAR(16777216)) AS WISDOM_D_CODE
                ,CAST(WISDOM_ACTIVE_FLAG as VARCHAR(16777216)) AS WISDOM_ACTIVE_FLAG
                ,CAST(SWLH_MODEL as VARCHAR(16777216)) AS SWLH_MODEL
                ,CAST(TEL_MODEL as VARCHAR(16777216)) AS TEL_MODEL
                ,CAST(WAFER_SIZE as VARCHAR(16777216)) AS WAFER_SIZE
                ,CAST(MACHINE_HISTORY_REASON as VARCHAR(16777216)) AS MACHINE_HISTORY_REASON
                ,CAST(WARRANTY_START as DATE) AS WARRANTY_START
                ,CAST(WARRANTY_END as DATE) AS WARRANTY_END
                ,CAST(START_UP_STATUS as VARCHAR(16777216)) AS START_UP_STATUS
                ,CAST(LOAN_FLAG as VARCHAR(16777216)) AS LOAN_FLAG
		,CAST(MACHINE_LOCATION_MATCH_FLAG as VARCHAR(16777216)) AS MACHINE_LOCATION_MATCH_FLAG
                ,CAST(SN_ROW_NUMBER as NUMBER(38,0)) AS SN_ROW_NUMBER
        FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
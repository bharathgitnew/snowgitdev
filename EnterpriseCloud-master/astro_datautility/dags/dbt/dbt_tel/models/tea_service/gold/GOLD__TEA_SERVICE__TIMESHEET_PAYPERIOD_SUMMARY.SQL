WITH CONSECUTIVEDAYS AS (
    SELECT DISTINCT
        EMPLOYEEID,
        EVENTDATE,
        DATEADD(d,-1,EVENTDATE) AS PREVIOUSDATE,
        LAG(EVENTDATE) OVER (Partition by EMPLOYEEID ORDER BY EVENTDATE) AS LAGDATE,
        CASE
            WHEN DATEADD(d,-1,EVENTDATE) = LAG(EVENTDATE) OVER (Partition by EMPLOYEEID ORDER BY EVENTDATE)
            THEN 0 
            ELSE 1 
        END AS CONSECUTIVE
    FROM (
        SELECT
            EMPLOYEEID,
            EVENTDATE,
            SUM(HOURSCHARGED)
        FROM {{ ref('SILVER__TEA_SERVICE__KRONOS_TIMESHEET') }}
        WHERE TYPEOFWORKGROUP <> 'Time Off'
            AND EVENTDATE >= '2023-04-01'
            AND EVENTDATE <= CURRENT_DATE
            AND PAYCODENAME <> 'On Call'
        GROUP BY 
        EMPLOYEEID,
        EVENTDATE
    )
),

BATCH AS (
    SELECT
        EMPLOYEEID,
        EVENTDATE,
        PREVIOUSDATE,
        LAGDATE,
        CONSECUTIVE,
        SUM(CONSECUTIVE) OVER(Partition by EMPLOYEEID ORDER BY EVENTDATE) AS BATCHNUMBER
    FROM CONSECUTIVEDAYS
),

BATCHCOUNT AS (
    SELECT
        EMPLOYEEID,
        EVENTDATE,
        PREVIOUSDATE,
        LAGDATE,
        CONSECUTIVE,
        BATCHNUMBER,
        ROW_NUMBER() OVER(Partition by EMPLOYEEID, BATCHNUMBER ORDER BY EVENTDATE) AS BATCHCOUNT
    FROM BATCH
),

MAXDAYS AS (
    SELECT
        EMPLOYEEID,
        PAY_PERIOD_END_DATE,
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE) AS EMP_PAYPERIOD,
        MAX(BATCHCOUNT) AS MAX_CONSECUTIVE_DAYS
    FROM BATCHCOUNT B
    LEFT OUTER JOIN {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}  E
        ON E.Calendar_Date = B.EVENTDATE
    GROUP BY 
        EMPLOYEEID,
        PAY_PERIOD_END_DATE,
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE)
),

TOTALHOURSWORKED AS (
    SELECT
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE) AS EMP_PAYPERIOD,
        PAY_PERIOD_END_DATE AS PAYPERIOD_END,
        EMPLOYEEID,
        SUM(T.HOURSCHARGED) AS TOTAL_HOURS_WORKED
    FROM {{ ref('SILVER__TEA_SERVICE__KRONOS_TIMESHEET') }} T
    LEFT OUTER JOIN {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}  E
        ON E.Calendar_Date = T.EventDate
    WHERE E.PAY_PERIOD_END_DATE >= '2023-04-14'
        AND TYPEOFWORKGROUP <> 'Time Off'
        AND PAYCODENAME <> 'On Call'
    GROUP BY 
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE),
        PAY_PERIOD_END_DATE,
        EMPLOYEEID
),

EMPDIM AS (
    SELECT
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE) AS EMP_PAYPERIOD,
        MAX(DEPARTMENTID) AS DEPT_CODE,
        MAX(BUCODE) AS BU_CODE,
        MAX(OFFICEID) AS OFFICE_CODE
    FROM {{ ref('SILVER__TEA_SERVICE__KRONOS_TIMESHEET') }} T
    LEFT OUTER JOIN {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}  E
        ON E.Calendar_Date = T.EventDate
    WHERE E.PAY_PERIOD_END_DATE >= '2023-04-14'
        AND TYPEOFWORKGROUP <> 'Time Off'
        AND PAYCODENAME <> 'On Call'
        AND EVENTDATE <= CURRENT_DATE
    GROUP BY 
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE)
),

EMPDEPTBU AS (
    SELECT
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE) AS EMP_PAYPERIOD,
        LISTAGG(DISTINCT DEPARTMENTID||'-'||BUCODE, ', ') WITHIN GROUP (ORDER BY DEPARTMENTID||'-'||BUCODE) AS DISTINCT_DEPT_BU_PAYPERIOD
    FROM {{ ref('SILVER__TEA_SERVICE__KRONOS_TIMESHEET') }} T
    LEFT OUTER JOIN {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}  E
        ON E.Calendar_Date = T.EventDate
    WHERE E.PAY_PERIOD_END_DATE >= '2023-04-14'
        AND TYPEOFWORKGROUP <> 'Time Off'
        AND PAYCODENAME <> 'On Call'
        AND EVENTDATE <= CURRENT_DATE
    GROUP BY 
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE)
),

EMPTYPE AS (
    SELECT
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE) AS EMP_PAYPERIOD,
        EMPLOYEETYPE,
        SUM(HOURSCHARGED) AS TOTAL_HOURS
    FROM {{ ref('SILVER__TEA_SERVICE__KRONOS_TIMESHEET') }} T
    LEFT OUTER JOIN {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}  E
        ON E.Calendar_Date = T.EventDate
    WHERE E.PAY_PERIOD_END_DATE >= '2023-04-14'
        AND TYPEOFWORKGROUP <> 'Time Off'
        AND EVENTDATE <= CURRENT_DATE
    GROUP BY 
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE),
        EMPLOYEETYPE
    QUALIFY row_number() over ( partition by EMP_PAYPERIOD order by TOTAL_HOURS DESC) = 1
),

PAYPERIOD AS (
    SELECT 
        FISCAL_YEAR_HALF_YEAR_SHORT_TEXT_ALT AS PAYPERIOD_END_FISCAL_HALF,
        FISCAL_YEAR_QUARTER_SHORT_TEXT AS PAYPERIOD_END_FISCAL_QTR,
        YEAR_MONTH_TEXT AS PAYPERIOD_END_MONTH,
        PAY_PERIOD_END_DATE AS PAYPERIOD_END
    FROM {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}
    WHERE PAY_PERIOD_END_DATE >= '2023-04-14'
        AND IS_PAY_PERIOD_LAST_DAY = 'Yes'
),

EMPLOYEE AS (
    SELECT
        EMPLOYEEID,
        FULLNAME AS EMPLOYEE,
        SUPERVISOR_NAME AS CURRENT_SUPERVISOR,
        EMPLOYEE_TYPE_NAME AS CURRENT_EMP_TYPE
    FROM {{ ref('SILVER__TEA_SERVICE__EMPLOYEE') }}
),

OFFICE AS (
    SELECT DISTINCT
        BAAN_CODE,
        SAP_DESCRIPTION AS OFFICE
    FROM {{ ref('SILVER__TEA_SERVICE__SAP_REGION') }}
    WHERE LEN(BAAN_CODE)>1
),

WRENCH AS (
    SELECT
        PAY_PERIOD_END_DATE,
        EMPLOYEEID,
        (EMPLOYEEID||'/'||PAY_PERIOD_END_DATE) AS EMP_PAYPERIOD,
        COALESCE("'Meeting'",0) AS MEETING,
        COALESCE("'No Code'",0) AS NO_CODE,
        COALESCE("'Paperwork'",0) AS PAPERWORK,
        COALESCE("'Projects'",0) AS PROJECTS,
        COALESCE("'Remote Work'",0) AS REMOTE_WORK,
        COALESCE("'Time Off'",0) AS TIME_OFF,
        COALESCE("'Training'",0) AS TRAINING,
        COALESCE("'Travel'",0) AS TRAVEL,
        COALESCE("'Waiting'",0) AS WAITING,
        COALESCE("'Wrench'",0) AS WRENCH
    from (
        SELECT
            E.PAY_PERIOD_END_DATE,
            T.EMPLOYEEID,
            T.TASKWRENCHTYPE,
            T.HOURSCHARGED
        FROM {{ ref('SILVER__TEA_SERVICE__KRONOS_TIMESHEET') }} T
        LEFT OUTER JOIN {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}  E
            ON E.Calendar_Date = T.EventDate
        WHERE E.PAY_PERIOD_END_DATE >= '2022-01-21'
    ) T PIVOT (SUM(HOURSCHARGED) FOR TASKWRENCHTYPE IN (
        'Meeting',
        'No Code',
        'Paperwork',
        'Projects',
        'Remote Work',
        'Time Off',
        'Training',
        'Travel',
        'Waiting',
        'Wrench'
    )) as P 
),

SOURCE AS (
    SELECT
        PAYPERIOD.PAYPERIOD_END_FISCAL_HALF,
        PAYPERIOD.PAYPERIOD_END_FISCAL_QTR,
        PAYPERIOD.PAYPERIOD_END_MONTH,
        PAYPERIOD.PAYPERIOD_END,
        EMPLOYEE.CURRENT_SUPERVISOR,
        EMPLOYEE.EMPLOYEE,
        TOTALHOURSWORKED.EMPLOYEEID,
        TOTALHOURSWORKED.TOTAL_HOURS_WORKED,
        WRENCH.TIME_OFF,
        TOTALHOURSWORKED.TOTAL_HOURS_WORKED - (WRENCH.WRENCH +WRENCH.MEETING + WRENCH.NO_CODE + WRENCH.PAPERWORK + WRENCH.PROJECTS + WRENCH.REMOTE_WORK + WRENCH.TRAINING+ WRENCH.TRAVEL+ WRENCH.WAITING) AS MAPPING_ERROR,
        (WRENCH.WRENCH/TOTALHOURSWORKED.TOTAL_HOURS_WORKED) AS WRENCH_PERCENTAGE,
        WRENCH.WRENCH,
        WRENCH.MEETING,
        WRENCH.NO_CODE,
        WRENCH.PAPERWORK,
        WRENCH.PROJECTS,
        WRENCH.REMOTE_WORK,
        WRENCH.TRAINING,
        WRENCH.TRAVEL,
        WRENCH.WAITING,
        CASE
            WHEN TOTALHOURSWORKED.TOTAL_HOURS_WORKED > 120  THEN 'Y'
            WHEN MAXDAYS.MAX_CONSECUTIVE_DAYS  > 6 THEN 'Y'
            ELSE 'N'
        END AS RBA_FLAG,
        CASE
            WHEN TOTALHOURSWORKED.TOTAL_HOURS_WORKED > 120  THEN 'Y'
            ELSE 'N'
        END AS RBA_FLAG_HOURS_FLAG,
        CASE
            WHEN MAXDAYS.MAX_CONSECUTIVE_DAYS  > 6 THEN 'Y'
            ELSE 'N'
        END AS RBA_FLAG_CONSECUTIVE_DAYS_FLAG,
        CASE
            WHEN TOTALHOURSWORKED.TOTAL_HOURS_WORKED <= 120 THEN 0
            ELSE TOTALHOURSWORKED.TOTAL_HOURS_WORKED - 120
        END AS HOURS_OVER_120,
        MAX_CONSECUTIVE_DAYS,
        CASE
            WHEN EMPDIM.BU_CODE IN ('5999','33') THEN 'FST'
            WHEN EMPDIM.DEPT_CODE IN ('7600', '7601', '053', '054') Then 'Tech Support'
            ELSE 'Other'
        END AS FSTEMPLOYEEGROUP,
        EMPTYPE.EMPLOYEETYPE AS EMP_TYPE,
        EMPLOYEE.CURRENT_EMP_TYPE,
        EMPDIM.DEPT_CODE,
        EMPDIM.BU_CODE,
        OFFICE.OFFICE,
        EMPDIM.OFFICE_CODE,
        EMPDEPTBU.DISTINCT_DEPT_BU_PAYPERIOD,
        CASE
            WHEN EMPDEPTBU.DISTINCT_DEPT_BU_PAYPERIOD LIKE '%,%' THEN 'Y'
            ELSE 'N'
        END AS DEPT_BU_CHANGE_FLAG
    FROM TOTALHOURSWORKED
    LEFT OUTER JOIN EMPDIM
        ON TOTALHOURSWORKED.EMP_PAYPERIOD = EMPDIM.EMP_PAYPERIOD
    LEFT OUTER JOIN EMPDEPTBU
        ON TOTALHOURSWORKED.EMP_PAYPERIOD = EMPDEPTBU.EMP_PAYPERIOD
    LEFT OUTER JOIN EMPTYPE
        ON TOTALHOURSWORKED.EMP_PAYPERIOD = EMPTYPE.EMP_PAYPERIOD
    LEFT OUTER JOIN WRENCH
        ON TOTALHOURSWORKED.EMP_PAYPERIOD = WRENCH.EMP_PAYPERIOD
    LEFT OUTER JOIN EMPLOYEE
        ON TOTALHOURSWORKED.EMPLOYEEID = EMPLOYEE.EMPLOYEEID
    LEFT OUTER JOIN MAXDAYS
        ON TOTALHOURSWORKED.EMP_PAYPERIOD = MAXDAYS.EMP_PAYPERIOD
    LEFT OUTER JOIN PAYPERIOD
        ON TOTALHOURSWORKED.PAYPERIOD_END = PAYPERIOD.PAYPERIOD_END
    LEFT OUTER JOIN OFFICE
        ON EMPDIM.OFFICE_CODE = OFFICE.BAAN_CODE
),

transform_data as (
    select 
        PAYPERIOD_END_FISCAL_HALF,
        PAYPERIOD_END_FISCAL_QTR,
        PAYPERIOD_END_MONTH,
        PAYPERIOD_END,
        CURRENT_SUPERVISOR,
        EMPLOYEE,
        EMPLOYEEID,
        TOTAL_HOURS_WORKED,
        TIME_OFF,
        WRENCH_PERCENTAGE,
        WRENCH,
        MEETING,
        NO_CODE,
        PAPERWORK,
        PROJECTS,
        REMOTE_WORK,
        TRAINING,
        TRAVEL,
        WAITING,
        MAPPING_ERROR,
        RBA_FLAG,
        RBA_FLAG_HOURS_FLAG,
        HOURS_OVER_120,
        RBA_FLAG_CONSECUTIVE_DAYS_FLAG,
        MAX_CONSECUTIVE_DAYS,
        FSTEMPLOYEEGROUP,
        EMP_TYPE,
        OFFICE,
        DEPT_CODE,
        BU_CODE,
        OFFICE_CODE,
        DEPT_BU_CHANGE_FLAG,
        DISTINCT_DEPT_BU_PAYPERIOD,
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
    from source
),

TYPE_DATA AS (
    SELECT
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        CAST(PAYPERIOD_END_FISCAL_HALF as VARCHAR(16777216)) AS PAYPERIOD_END_FISCAL_HALF,
        CAST(PAYPERIOD_END_FISCAL_QTR as VARCHAR(16777216)) AS PAYPERIOD_END_FISCAL_QTR,
        CAST(PAYPERIOD_END_MONTH as VARCHAR(16777216)) AS PAYPERIOD_END_MONTH,
        CAST(PAYPERIOD_END AS DATE) AS PAYPERIOD_END,
        CAST(CURRENT_SUPERVISOR as VARCHAR(16777216)) AS CURRENT_SUPERVISOR,
        CAST(EMPLOYEE as VARCHAR(16777216)) AS EMPLOYEE,
        CAST(EMPLOYEEID as VARCHAR(16777216)) AS EMPLOYEEID,
        CAST(TOTAL_HOURS_WORKED as NUMBER(38,2)) AS TOTAL_HOURS_WORKED,
        CAST(TIME_OFF as NUMBER(38,2)) AS TIME_OFF,
        CAST(WRENCH_PERCENTAGE as NUMBER(38,2)) AS WRENCH_PERCENTAGE,
        CAST(WRENCH as NUMBER(38,2)) AS WRENCH,
        CAST(MEETING as NUMBER(38,2)) AS MEETING,
        CAST(NO_CODE as NUMBER(38,2)) AS NO_CODE,
        CAST(PAPERWORK as NUMBER(38,2)) AS PAPERWORK,
        CAST(PROJECTS as NUMBER(38,2)) AS PROJECTS,
        CAST(REMOTE_WORK as NUMBER(38,2)) AS REMOTE_WORK,
        CAST(TRAINING as NUMBER(38,2)) AS TRAINING,
        CAST(TRAVEL as NUMBER(38,2)) AS TRAVEL,
        CAST(WAITING as NUMBER(38,2)) AS WAITING,
        CAST(MAPPING_ERROR as NUMBER(38,2)) AS MAPPING_ERROR,
        CAST(RBA_FLAG as VARCHAR(16777216)) AS RBA_FLAG,
        CAST(RBA_FLAG_HOURS_FLAG as VARCHAR(16777216)) AS RBA_FLAG_HOURS_FLAG,
        CAST(HOURS_OVER_120 as NUMBER(38,0)) AS HOURS_OVER_120,
        CAST(RBA_FLAG_CONSECUTIVE_DAYS_FLAG as VARCHAR(16777216)) AS RBA_FLAG_CONSECUTIVE_DAYS_FLAG,
        CAST(MAX_CONSECUTIVE_DAYS as NUMBER(38,0)) AS MAX_CONSECUTIVE_DAYS,
        CAST(FSTEMPLOYEEGROUP as VARCHAR(16777216)) AS FSTEMPLOYEEGROUP,
        CAST(EMP_TYPE as VARCHAR(16777216)) AS EMP_TYPE,
        CAST(OFFICE as VARCHAR(16777216)) AS OFFICE,
        CAST(DEPT_CODE as VARCHAR(16777216)) AS DEPT_CODE,
        CAST(BU_CODE as VARCHAR(16777216)) AS BU_CODE,
        CAST(OFFICE_CODE as VARCHAR(16777216)) AS OFFICE_CODE,
        CAST(DEPT_BU_CHANGE_FLAG as VARCHAR(16777216)) AS DEPT_BU_CHANGE_FLAG,
        CAST(DISTINCT_DEPT_BU_PAYPERIOD as VARCHAR(16777216)) AS DISTINCT_DEPT_BU_PAYPERIOD,
    FROM transform_data
)

SELECT * FROM TYPE_DATA
{{ config(
        alias = 'TSR_STATUS',
        materialized='tel_incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with cost_center as (
    select
        COST_CENTER_CODE,
        SEGMENT_CODE as SECURITY_SEGMENT,
        DEPARTMENT_CODE as SECURITY_DEPARTMENT,
        OFFICE_CODE as SECURITY_OFFICE
    from {{ ref('BRONZE__TEA_SERVICE__FILE_COST_CENTER') }}
),

profit_center as (
    select
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('BRONZE__TEA_SERVICE__FILE_PROFIT_CENTER') }}
),

source_data as (
    SELECT 
        WO_MSDYN_NAME AS WO_NO 
        ,WO_WOTITLE AS WO_TITLE
        ,FAB.NAME AS END_USER
        ,WO.MACHINE_MSDYN_NAME AS MACHINE_NAME 
        ,MAINCATEGORY.LOCALIZEDLABEL AS MAIN_CATEGORY
        ,WO.WO_FCNSIID AS FCN_SI_NO 
        ,WO.WO_NAME AS SUBCATEGORY 
        ,WO.WO_PLANNEDSTART AS PLANNED_START_DATE 
        ,WO.WO_PLANNEDEND AS PLANNED_END_DATE 
        ,WO.MSDYN_SUBJECT AS WO_GROUP_NO 
        ,CASE 
            WHEN WO.WO_OWNERID_ENTITYTYPE='systemuser' THEN OwnerU.FULLNAME 
            WHEN WO.WO_OWNERID_ENTITYTYPE = 'team' THEN OwnerT.NAME 
        END AS OWNER
        ,WO.WOSTATUS_MSDYN_NAME AS WO_STATE 
        ,WOSTATUS.LOCALIZEDLABEL AS WO_STATUS 
        ,WO.WO_CREATEDON AS CREATED_DATE 
        ,WO.WO_TSRTOTALHOURS AS TSR_WORK_HOURS 
        ,WO.WO_TSRNO AS TSR_NO 
        ,WO.WO_TSRISSUEDATE AS TSR_ISSUE_DATE 
        ,WO.WO_TYPE_MSDYN_NAME AS WO_TYPE 
        ,TEAM.NAME AS TEAM 
        ,TEAM_ADMIN.FULLNAME AS TEAM_ADMINISTRATOR
        ,PAYMENT_TYPE.LOCALIZEDLABEL AS PAYMENT_TYPE
        ,TERRITORY.NAME AS REGION 
        ,TSR_LABOR_STATUS.LOCALIZEDLABEL AS CALCULATION_STATUS
        ,CASE WHEN WO.TEL_WO_TRIGGER_SIGNEDTSR_INTEGRATION = TRUE THEN 'Yes' 
            WHEN WO.TEL_WO_TRIGGER_SIGNEDTSR_INTEGRATION = FALSE THEN 'No' 
            ELSE WO.TEL_WO_TRIGGER_SIGNEDTSR_INTEGRATION 
        END AS SIGNED_TSR,

        null as PROFIT_CENTER,
        null as COST_CENTER,
        '<ALL>' as SECURITY_SEGMENT,
        '<ALL>' as SECURITY_DEPARTMENT,
        '<ALL>' as SECURITY_OFFICE

    FROM {{ ref('SILVER__TEA_SERVICE__WO_SUMMARY_DETAILS') }} AS WO 
    LEFT JOIN {{ ref('SILVER__TEA_SERVICE__TERRITORY') }} AS TERRITORY ON WO.WO_WO_REGION = TERRITORY.ID --AND TERRITORY.SOURCE_FLAG = 'WO'
    JOIN {{ ref('SILVER__TEA_SERVICE__WO_TEAM') }} TEAM ON WO.WO_TEAMINCHARGE = TEAM.ID   
    JOIN {{ ref('SILVER__TEA_SERVICE__SYSTEM_USER') }} TEAM_ADMIN ON TEAM.ADMINISTRATORID = TEAM_ADMIN.ID 
    LEFT JOIN {{ ref('SILVER__TEA_SERVICE__OPTIONSET_METADATA') }} TSR_LABOR_STATUS ON 
        WO.WO_TSRLABORSTATUS = TSR_LABOR_STATUS.OPTION AND 
        TSR_LABOR_STATUS.OPTIONSETNAME = 'wo_tsrlaborstatus' AND 
        TSR_LABOR_STATUS.LOCALIZEDLABELLANGUAGECODE = 1033 AND
        TSR_LABOR_STATUS.SOURCE_FLAG = 'GLOBAL'
    LEFT OUTER JOIN (
        SELECT DISTINCT 
            OPTIONSETNAME,
            OPTION,
            LOCALIZEDLABELLANGUAGECODE,
            LOCALIZEDLABEL 
        FROM {{ ref('SILVER__TEA_SERVICE__OPTIONSET_METADATA') }}
        WHERE SOURCE_FLAG = 'GLOBAL'
    ) PAYMENT_TYPE 
        ON WO.WO_TEL_WO_TYPEOFPAYMENT = PAYMENT_TYPE.OPTION 
        AND PAYMENT_TYPE.OPTIONSETNAME = 'tel_wo_typeofpayment' 
        AND PAYMENT_TYPE.LOCALIZEDLABELLANGUAGECODE = 1033
    LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__OPTIONSET_METADATA') }} MAINCATEGORY 
        ON WO.TEL_WO_MAINCATEGORY_SOREQUEST = MAINCATEGORY.OPTION 
        AND MAINCATEGORY.OPTIONSETNAME = 'tel_wo_maincategory_sorequest' 
        AND MAINCATEGORY.LOCALIZEDLABELLANGUAGECODE = 1033
        AND MAINCATEGORY.SOURCE_FLAG = 'GLOBAL'
    LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__ACCOUNT_DETAILS') }} FAB 
        ON WO.MSDYN_SERVICEACCOUNT = FAB.ID 
    LEFT OUTER JOIN (
        SELECT * 
        FROM {{ ref('SILVER__TEA_SERVICE__WO_STATEMETADATA') }} 
        WHERE 
            ENTITYNAME = 'msdyn_workorder' AND 
            LOCALIZEDLABELLANGUAGECODE = 1033
    ) WOSTATUS 
        ON WO.WO_STATECODE = WOSTATUS.STATE 
    LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__WO_TEAM') }} OwnerT 
        ON WO.WO_OWNERID = OwnerT.Id
    LEFT OUTER JOIN {{ ref('SILVER__TEA_SERVICE__SYSTEM_USER') }} OwnerU 
        ON WO.WO_OWNERID = OwnerU.Id
    WHERE 
        TERRITORY.NAME = 'US' 
        AND TSR_LABOR_STATUS.LOCALIZEDLABEL = 'Calculation Complete' 
        AND WO.TEL_WO_FILEINTEGRATIONINFO ILIKE '%TSR%' 
),

transform_data as (
    select 
        WO_NO,
        WO_TITLE,
        END_USER,
        MACHINE_NAME,
        MAIN_CATEGORY,
        FCN_SI_NO,
        SUBCATEGORY,
        PLANNED_START_DATE,
        PLANNED_END_DATE,
        WO_GROUP_NO,
        OWNER,
        WO_STATE,
        WO_STATUS,
        CREATED_DATE,
        TSR_WORK_HOURS,
        TSR_NO,
        TSR_ISSUE_DATE,
        WO_TYPE,
        TEAM,
        TEAM_ADMINISTRATOR,
        PAYMENT_TYPE,
        REGION,
        CALCULATION_STATUS,
        SIGNED_TSR,
        PROFIT_CENTER,
        COST_CENTER,
        SECURITY_SEGMENT,
        SECURITY_DEPARTMENT,
        SECURITY_OFFICE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    from source_data
),

type_data as (
    select 
        cast(WO_NO as VARCHAR(16777216)) as WO_NO,
        cast(WO_TITLE as VARCHAR(16777216)) as WO_TITLE,
        cast(END_USER as VARCHAR(16777216)) as END_USER,
        cast(MACHINE_NAME as VARCHAR(16777216)) as MACHINE_NAME,
        cast(MAIN_CATEGORY as VARCHAR(16777216)) as MAIN_CATEGORY,
        cast(FCN_SI_NO as VARCHAR(16777216)) as FCN_SI_NO,
        cast(SUBCATEGORY as VARCHAR(16777216)) as SUBCATEGORY,
        cast(PLANNED_START_DATE as TIMESTAMP_LTZ(9)) as PLANNED_START_DATE,
        cast(PLANNED_END_DATE as TIMESTAMP_LTZ(9)) as PLANNED_END_DATE,
        cast(WO_GROUP_NO as VARCHAR(16777216)) as WO_GROUP_NO,
        cast(OWNER as VARCHAR(16777216)) as OWNER,
        cast(WO_STATE as VARCHAR(16777216)) as WO_STATE,
        cast(WO_STATUS as VARCHAR(16777216)) as WO_STATUS,
        cast(CREATED_DATE as TIMESTAMP_LTZ(9)) as CREATED_DATE,
        cast(TSR_WORK_HOURS as NUMBER(38,10)) as TSR_WORK_HOURS,
        cast(TSR_NO as VARCHAR(16777216)) as TSR_NO,
        cast(TSR_ISSUE_DATE as TIMESTAMP_LTZ(9)) as TSR_ISSUE_DATE,
        cast(WO_TYPE as VARCHAR(16777216)) as WO_TYPE,
        cast(TEAM as VARCHAR(16777216)) as TEAM,
        cast(TEAM_ADMINISTRATOR as VARCHAR(16777216)) as TEAM_ADMINISTRATOR,
        cast(PAYMENT_TYPE as VARCHAR(16777216)) as PAYMENT_TYPE,
        cast(REGION as VARCHAR(16777216)) as REGION,
        cast(CALCULATION_STATUS as VARCHAR(16777216)) as CALCULATION_STATUS,
        cast(SIGNED_TSR as VARCHAR(16777216)) as SIGNED_TSR,
        CAST(PROFIT_CENTER as VARCHAR(16777216)) as PROFIT_CENTER,
        CAST(COST_CENTER as VARCHAR(16777216)) as COST_CENTER,
        CAST(SECURITY_SEGMENT as VARCHAR(16777216)) as SECURITY_SEGMENT,
        CAST(SECURITY_DEPARTMENT as VARCHAR(16777216)) as SECURITY_DEPARTMENT,
        CAST(SECURITY_OFFICE as VARCHAR(16777216)) as SECURITY_OFFICE,
        cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID,
        cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    from transform_data
)

select * from type_data
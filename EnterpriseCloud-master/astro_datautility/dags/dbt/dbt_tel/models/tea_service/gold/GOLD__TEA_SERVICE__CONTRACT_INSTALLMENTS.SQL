WITH security_cte as (
select
    COST_CENTER_CODE,
    SEGMENT_CODE as SECURITY_SEGMENT,
    DEPARTMENT_CODE as SECURITY_DEPARTMENT,
    OFFICE_CODE as SECURITY_OFFICE
from {{ ref('BRONZE__TEA_SERVICE__FILE_COST_CENTER') }}
),
profit_center as (
    select
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('BRONZE__TEA_SERVICE__FILE_PROFIT_CENTER') }}
),

CALENDARDATE AS (
    SELECT
        CALENDAR_DATE
        , YEAR_MONTH_TEXT
        , FISCAL_YEAR_SHORT_TEXT
        , FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
        , FISCAL_YEAR_QUARTER_SHORT_TEXT
    FROM {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}
),

CRM_OPTIONSET_CONTRACT_STATUS AS (
    SELECT
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM  {{ ref('SILVER__TEA_SERVICE__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'cnt_contract_status'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'GLOBAL'
),
CRM_OPTIONSET_INV_FREQUENCY AS (
    SELECT
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM  {{ ref('SILVER__TEA_SERVICE__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'cnt_invoicefrequency'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'GLOBAL'
),
CRM_ACCOUNT AS (
	SELECT
    	ID
        , COM_COMPANY_E_NAME AS COMPANY_NAME
    FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_ACCOUNT') }}
),
CRM_FAB AS (
	SELECT DISTINCT
    	CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
        , LISTAGG(DISTINCT ACCOUNTNUMBER, ', ') OVER (PARTITION BY CNT_CONTRUCTNUMBER) AS FAB_CODE
        , LISTAGG(DISTINCT NAME, ', ') OVER (PARTITION BY CNT_CONTRUCTNUMBER) AS FAB_NAME
   FROM {{ ref('SILVER__TEA_SERVICE__CONTRACT_SUMMARY_ACCOUNT') }}
),
CRM_CONTRACTS AS (
	SELECT
        CSD.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
        , LISTAGG(DISTINCT CSD.CNT_PRODUCT_CONTRACT_SUMMARY, ', ') OVER (PARTITION BY CSD.CNT_CONTRUCTNUMBER) AS PRODUCT
        , LISTAGG(DISTINCT CSD.CNT_SOWNAMENAME, ', ') OVER (PARTITION BY CSD.CNT_CONTRUCTNUMBER) AS CONTRACT_TYPE_AGG
        , CSD.CNT_SOWNAMENAME AS CNT_SOWNAMENAME
        , CSD.CNT_SUBJECT AS CONTRACT_TITLE
        , CSD.CNT_CONTRACTSTARTDATE AS CONTRACT_START_DATE
		, CSD.CNT_CONTRACTENDDATE AS CONTRACT_END_DATE
        , CSD.CNT_ASSIGNEDSALES AS ACCOUNT_MANAGER
        , CRM_ACCOUNT.COMPANY_NAME AS ORDER_CUSTOMER
        , CRM_CONTRACT_STATUS.LOCALIZEDLABEL AS CONTRACT_STATUS
        , CRM_INV_FREQUENCY.LOCALIZEDLABEL as INVOICE_FREQUENCY
        , CRM_FAB.FAB_CODE AS FAB_CODE
        , CRM_FAB.FAB_NAME AS FAB_NAME
        , CNT_AREAADMIN AS CNT_AREAADMIN
        , sum(CNT_CONTRACTPRICE) OVER (PARTITION BY CSD.CNT_CONTRUCTNUMBER) AS TOTAL_CONTRACT_CRM_AMOUNT
   FROM {{ ref('SILVER__TEA_SERVICE__CONTRACT_SUMMARY_DETAILS') }} AS CSD
        LEFT JOIN CRM_FAB
            ON CSD.CNT_CONTRUCTNUMBER = CRM_FAB.CONTRACT_NUMBER
        LEFT JOIN CRM_OPTIONSET_CONTRACT_STATUS as CRM_CONTRACT_STATUS
            ON try_to_number(CSD.CNT_CONTRACT_STATUS)=try_to_number(CRM_CONTRACT_STATUS.OPTION)
        LEFT JOIN CRM_OPTIONSET_INV_FREQUENCY AS CRM_INV_FREQUENCY
            ON try_to_number(CSD.CNT_INVOICEFREQUENCY)=try_to_number(CRM_INV_FREQUENCY.OPTION)
        LEFT JOIN CRM_ACCOUNT
            ON CSD.CNT_ORDERCUSTOMER = CRM_ACCOUNT.ID
),
CRM_USER AS (
    SELECT
    	SYSTEMUSERID
        , EMPLOYEEID
        , FULLNAME
    FROM {{ ref('BRONZE__TEA_SERVICE__CRM_FILE_SYSTEMUSER') }}
),
MASTER_DATA_SEGMENT AS (
    SELECT DISTINCT
        SAP_CODE
        , SAP_DESCRIPTION AS SEGMENT
    FROM {{ ref('SILVER__TEA_SERVICE__SAP_SEGMENT') }}
),
CGM AS (
SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('BRONZE__TEA_SERVICE__SHAREPOINT_CUSTOMER_GROUP_MAPPING') }}
),
CUSTOMER AS (
-- refactor when SAP master data available
    SELECT
        CUSTOMER.CUSTOMER_NUMBER
        , CUSTOMER.NAME_1 as CUSTOMER_NAME
        , CUSTOMER.SEARCH_TERM_2_FOR_BUSINESS_PARTNER as CUSTOMER_NAME_B
        , CUSTOMER.BUSINESS_PARTNER_NUMBER
        , CUSTOMER.CORPORATION
        , CUSTOMER_A.NAME_1 AS CUSTOMER_A_NAME
        , CGM.CUSTOMER_GROUP
        , CGM.CUSTOMER_GROUP2
    FROM {{ ref('SILVER__TEA_SERVICE__BUSINESS_PARTNERS_GENERAL_DATA') }} AS CUSTOMER
        LEFT JOIN {{ ref('SILVER__TEA_SERVICE__BUSINESS_PARTNERS_GENERAL_DATA') }} AS CUSTOMER_A
            ON CUSTOMER.CORPORATION = CUSTOMER_A.CUSTOMER_NUMBER
        LEFT JOIN CGM
            ON CGM.ACCOUNT_NUMBER = CUSTOMER.CORPORATION
    WHERE CUSTOMER.CUSTOMER_FLAG = 'Y'
),

SOBL AS (
    SELECT
        vbap.VBELN AS SALES_DOCUMENT,
        vbap.POSNR AS SALES_DOCUMENT_ITEM,
        vbrk_bill.VBTYP AS DOCUMENT_CATEGORY,
        vbak.ZZCNZZ AS CONTRACT_NUMBER,
        vbak.AUART AS SALES_DOCUMENT_TYPE,
        vbak.BSTNK AS CUSTOMER_REFERENCE,
        vbap.ARKTX AS VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM,
        vbap.NETWR AS NET_VALUE,
        vbrk_bill.FKART AS BILLING_TYPE,
        vbrp_bill.VBELN AS BILLING_DOCUMENT,
        vbrp_bill.POSNR AS BILLING_DOCUMENT_ITEM,
        vbrp_bill.NETWR AS BILLING_ITEM_AMT,
        vbrk_bill.FKDAT AS BILLING_DATE,
        vbrk_bill.FKSTO AS BILLING_DOC_IS_CANCELED,
        vbrk_bill.SFAKN AS CANCELED_BILLING_DOCUMENT,
        vbrp_bill.FPLNR AS BILLING_PLAN_NUM,
        vbrp_bill.FPLTR AS BILLING_PLAN_ITEM,
        VBFA.VBTYP_N AS SALES_DOC_TYPE,
        VBFA.RFWRT AS ACTUAL_INSTALLMENT_AMT
    FROM (select * from {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU009_VBAK') }} where IS_DELETED = 'No') vbak --Sales Head
        LEFT JOIN ( select * from {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU010_VBAP') }} where IS_DELETED = 'No') vbap --Sales Line
            ON try_to_number(vbap.VBELN) = try_to_number(vbak.VBELN)
        LEFT JOIN {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU064_VBFA') }}  vbfa -- Delivery Line
            ON try_to_number(vbfa.vbelv) = try_to_number(vbap.VBELN) AND try_to_number(vbfa.posnv) = try_to_number(vbap.POSNR)
        LEFT JOIN {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU015_VBRP') }}   vbrp_bill -- Billing Document Item
            ON try_to_number(vbrp_bill.VGBEL)= try_to_number(vbfa.vbelv) AND try_to_number(vbrp_bill.VBELN) = try_to_number(vbfa.VBELN) and try_to_number(vbrp_bill.posnr) = try_to_number(vbfa.posnn)
        LEFT JOIN {{ ref('BRONZE__TEA_SERVICE__SAPAPI_ZCDV_T_CMTU014_VBRK') }}  vbrk_bill -- Billing Document Head
            ON try_to_number(vbrk_bill.VBELN) = try_to_number(vbrp_bill.VBELN)
    WHERE vbak.AUART IN ('ZSC1', 'ZC11')
            AND ((VBFA.VBTYP_N in ('M','N')) OR (VBFA.VBTYP_N is NULL))
),
CANCELLED_BILL AS (
    SELECT DISTINCT
        BILLING_DOCUMENT
        , BILLING_DOCUMENT_ITEM
    FROM SOBL
    WHERE 1=1
        AND BILLING_DOC_IS_CANCELED = TRUE
        AND (CANCELED_BILLING_DOCUMENT <> '' OR CANCELED_BILLING_DOCUMENT IS NOT NULL)
),
CONTRACT_BILL AS (
    SELECT DISTINCT
        BILLING_DATE
        , BILLING_DOCUMENT
        , BILLING_DOCUMENT_ITEM
        , BILLING_PLAN_NUM
        , BILLING_PLAN_ITEM
    FROM SOBL
    WHERE 1=1
        AND SALES_DOCUMENT_TYPE = 'ZC11'
        AND BILLING_DOCUMENT || BILLING_DOCUMENT_ITEM NOT IN (
            SELECT DISTINCT BILLING_DOCUMENT || BILLING_DOCUMENT_ITEM
            FROM CANCELLED_BILL
            )
        -- AND DOCUMENT_CATEGORY <> 'N'
),
REVENUE_RECOGNITION AS (
    SELECT DISTINCT
        CONTRACT_NUMBER
        , BILLING_DOCUMENT
        , BILLING_DOCUMENT_ITEM
        , BILLING_ITEM_AMT
        , SUM(BILLING_ITEM_AMT) OVER (PARTITION BY CONTRACT_NUMBER) AS REVENUE_RECOGNIZED
    FROM SOBL
    WHERE 1=1
        AND SALES_DOCUMENT_TYPE = 'ZC11'
        AND BILLING_TYPE = 'ZC11' --revenue recognition billing
        AND BILLING_DOCUMENT || BILLING_DOCUMENT_ITEM NOT IN (
            SELECT DISTINCT BILLING_DOCUMENT || BILLING_DOCUMENT_ITEM
            FROM CANCELLED_BILL
            )
),
CONTRACT_SCOPE AS (
    SELECT
        CONTRACT_NUMBER
        , SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM
        , SUBSTRING(VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM, CHARINDEX('-', VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM)+1, LEN(VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM)) AS CONTRACT_SCOPE_BY_PRODUCT
        , NET_VALUE
        , SUM(NET_VALUE) OVER(PARTITION BY CONTRACT_NUMBER) AS TOTAL_CONTRACT_AMT_OLD
        , DIV0(NET_VALUE, TOTAL_CONTRACT_AMT_OLD) AS ALLOCATION_BY_SCOPE
    FROM SOBL
    WHERE 1=1
        AND SALES_DOCUMENT_TYPE = 'ZSC1'
        AND CUSTOMER_REFERENCE <> ''
    GROUP BY
        CONTRACT_NUMBER
        , SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM
        , NET_VALUE
        , VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM
),
SOURCE_DATA AS (
    SELECT DISTINCT
        SOBP.VBAP_SALES_CATEGORY AS SALES_CATEGORY
        , SOBP.CONTRACT_NUMBER AS CONTRACT_NUMBER
        , CRM_CONTRACTS.PRODUCT AS PRODUCT
        , MASTER_DATA_SEGMENT.SEGMENT AS BU
        , USER_AM.FULLNAME AS CONTRACT_OWNER
        , CRM_CONTRACTS.CONTRACT_TITLE AS CONTRACT_TITLE
        , CONTRACT_SCOPE.CONTRACT_SCOPE_BY_PRODUCT AS CONTRACT_SCOPE_BY_PRODUCT
        , CRM_CONTRACTS.CONTRACT_START_DATE as CONTRACT_START_DATE
        , CRM_CONTRACTS.CONTRACT_END_DATE AS CONTRACT_END_DATE
        , CRM_CONTRACTS.CONTRACT_STATUS AS CONTRACT_STATUS
        , SOBP.FPLT_BILLING_DATE AS PLANNED_BILLING_DATE
        , CALENDAR_I.YEAR_MONTH_TEXT as PLANNED_BILLING_DATE_YYYY_MM
        , SOBP.BILLING_PLAN_NUMBER_INVOICING_PLAN_NUMBER_FPLNR as BILLING_PLAN_NUMBER_INVOICING_PLAN_NUMBER_FPLNR
        , SOBP.FPLT_ITEM_FOR_BILLING_PLAN_INVOICE_PLAN_PAYMENT_CARDS AS INSTALLMENT_NUMBER
        , SOBP.SETTLEMENT_DATE_FOR_DEADLINE_FKDAT AS SETTLEMENT_DATE_FOR_DEADLINE_FKDAT
        , SOBP.SETTLEMENT_DATE_FOR_DEADLINE_NFDAT AS SETTLEMENT_DATE_FOR_DEADLINE_NFDAT
        , CRM_CONTRACTS.INVOICE_FREQUENCY AS INSTALLMENT_TIMING
        , SOBP.VBAP_SALES_DOCUMENT as ZC11_SALES_ORDER
        , SOBP.VBAK_CUSTOMER_REFERENCE AS PO_NUMBER
        , SOBP.VBAP_ITEM_NUMBER_OF_THE_UNDERLYING_PURCHASE_ORDER AS PO_LINE
        , SOBP.VALUE_TO_BE_BILLED_CALC_ON_DATE_IN_BILLING_INVOICE_PLAN AS PLANNED_INSTALLMENT_AMT
        , SOBL.ACTUAL_INSTALLMENT_AMT AS ACTUAL_INSTALLMENT_AMT
        , SOBP.BILLING_STATUS_FOR_THE_BILLING_PLAN_INVOICE_PLAN_DATE AS BILLING_STATUS
        , SOBL.BILLING_DATE AS BILLING_DATE
        , SOBL.BILLING_DOCUMENT AS BILLING_DOCUMENT
        , REVENUE_RECOGNITION.REVENUE_RECOGNIZED AS CONTRACT_REVENUE_RECOGNIZED
        , CRM_CONTRACTS.TOTAL_CONTRACT_CRM_AMOUNT AS TOTAL_CONTRACT_AMT
        , CRM_CONTRACTS.ORDER_CUSTOMER as ORDER_CUSTOMER
        , CUSTOMER.CUSTOMER_A_NAME as CUSTOMER_NAME
        , CUSTOMER.CUSTOMER_NAME_B AS CUSTOMER_NAME_B
        , CUSTOMER.CUSTOMER_GROUP AS CUSTOMER_GROUP
        , CUSTOMER.CUSTOMER_GROUP2 AS CUSTOMER_GROUP2
        , SOBP.SOLD_TO_PARTY AS CUSTOMER_CODE
        , CRM_CONTRACTS.FAB_CODE AS COVERED_FAB
        , CRM_CONTRACTS.FAB_NAME AS COVERED_FAB_NAME
        , CALENDAR_CS.YEAR_MONTH_TEXT AS CONTRACT_START_YYYY_MM
        , CALENDAR_CS.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS CONTRACT_START_FISCAL_HALF
        , CALENDAR_I.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS PLANNED_BILLING_DATE_FISCAL_HALF
        , USER_AM.FULLNAME AS SITE_SUPERVISOR
        , USER_AM.EMPLOYEEID AS SITE_SUPERVISOR_ID
        , SOBL.SALES_DOC_TYPE AS SALES_DOC_TYPE
        , SOBP.PROFIT_CENTER AS PROFIT_CENTER
        , SOBP.VBAP_COST_CENTER AS COST_CENTER
        , '<ALL>' as SECURITY_SEGMENT
        , '<ALL>' as SECURITY_DEPARTMENT
        , '<ALL>' as SECURITY_OFFICE
        , CRM_CONTRACTS.CONTRACT_TYPE_AGG AS CONTRACT_TYPE_AGG
        , MANAGED.FULLNAME AS MANAGED_BY
        ,DP_APPROVAL_STATUS
        ,CASE
            WHEN DP_APPROVAL_STATUS = 'B1' THEN 'Waiting approval from request department'
            WHEN DP_APPROVAL_STATUS = 'C' THEN 'Approved'
            WHEN DP_APPROVAL_STATUS = 'Q' THEN 'Waiting approval request'
            WHEN DP_APPROVAL_STATUS = 'R' THEN 'Rejected'
            WHEN DP_APPROVAL_STATUS = 'W' THEN 'Sales/Down payment cancellation rejected'
            WHEN DP_APPROVAL_STATUS = 'Z' THEN 'Sales/Down payment cancellation approved'
            WHEN LEN(DP_APPROVAL_STATUS)< 1 THEN 'Not submitted'
            ELSE DP_APPROVAL_STATUS
        END AS DP_APPROVAL_STATUS_DESC
    FROM {{ ref('SILVER__TEA_SERVICE__SALES_ORDER_BILLING_PLAN') }} AS SOBP
        LEFT JOIN SOBL
            ON SOBP.CONTRACT_NUMBER = SOBL.CONTRACT_NUMBER
                AND TRY_TO_NUMBER(SOBP.BILLING_PLAN_NUMBER_INVOICING_PLAN_NUMBER_FPLNR) = TRY_TO_NUMBER(SOBL.BILLING_PLAN_NUM)
                AND TRY_TO_NUMBER(SOBP.FPLT_ITEM_FOR_BILLING_PLAN_INVOICE_PLAN_PAYMENT_CARDS) = TRY_TO_NUMBER(SOBL.BILLING_PLAN_ITEM)
        LEFT JOIN CONTRACT_BILL
        	ON TRY_TO_NUMBER(SOBL.BILLING_PLAN_NUM) = TRY_TO_NUMBER(CONTRACT_BILL.BILLING_PLAN_NUM)
                AND TRY_TO_NUMBER(SOBL.BILLING_PLAN_ITEM) = TRY_TO_NUMBER(CONTRACT_BILL.BILLING_PLAN_ITEM)
                AND TRY_TO_NUMBER(SOBL.BILLING_DOCUMENT)=TRY_TO_NUMBER(CONTRACT_BILL.BILLING_DOCUMENT)
        LEFT JOIN REVENUE_RECOGNITION
            ON SOBL.CONTRACT_NUMBER = REVENUE_RECOGNITION.CONTRACT_NUMBER
        LEFT JOIN CONTRACT_SCOPE
            ON SOBP.CONTRACT_NUMBER = CONTRACT_SCOPE.CONTRACT_NUMBER
        LEFT JOIN CRM_CONTRACTS
            ON SOBP.CONTRACT_NUMBER = CRM_CONTRACTS.CONTRACT_NUMBER
        LEFT JOIN CUSTOMER
            ON SOBP.SOLD_TO_PARTY = CUSTOMER.CUSTOMER_NUMBER
        LEFT JOIN CRM_USER AS USER_AM
            ON CRM_CONTRACTS.ACCOUNT_MANAGER = USER_AM.systemuserid
        LEFT JOIN CRM_USER AS MANAGED
            ON CRM_CONTRACTS.CNT_AREAADMIN = MANAGED.systemuserid
        LEFT JOIN MASTER_DATA_SEGMENT
            ON substring(SOBP.PROFIT_CENTER, 4, 2) = MASTER_DATA_SEGMENT.SAP_CODE
        LEFT JOIN CALENDARDATE AS CALENDAR_I
            ON TRY_TO_DATE(SOBP.FPLT_BILLING_DATE,'YYYYMMDD') = CALENDAR_I.CALENDAR_DATE
        LEFT JOIN CALENDARDATE AS CALENDAR_CS
            ON CAST(TO_TIMESTAMP_TZ(CRM_CONTRACTS.CONTRACT_START_DATE) AS DATE) = CALENDAR_CS.CALENDAR_DATE
        LEFT OUTER JOIN SECURITY_CTE
            ON SOBP.VBAP_COST_CENTER = SECURITY_CTE.COST_CENTER_CODE
        LEFT OUTER JOIN PROFIT_CENTER
            ON SOBP.PROFIT_CENTER = PROFIT_CENTER.PROFIT_CENTER_CODE
    WHERE 1=1
        AND SOBP.SALES_ORGANIZATION = '3200'
    	AND SOBP.SALES_DOCUMENT_TYPE = 'ZC11'
        AND SOBP.BILLING_PLAN_NUMBER_INVOICING_PLAN_NUMBER_FPLNR <> ''
        AND (REASON_FOR_REJECTION_OF_SALES_DOCUMENTS IS NULL OR REASON_FOR_REJECTION_OF_SALES_DOCUMENTS = '')
),

TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS  AUDIT_LOG_ID
        , SHA2('hash_me') as _ROW_HASH
        , SALES_CATEGORY
        , ZC11_SALES_ORDER
        , PO_NUMBER
        , PO_LINE
        , CONTRACT_NUMBER
        , CONTRACT_STATUS
        //, customer region -- master data, based on customer location
        , CONTRACT_OWNER
        , CONTRACT_TITLE
        , TO_VARCHAR(TO_TIMESTAMP_TZ(CONTRACT_START_DATE), 'MM/DD/YYYY') AS CONTRACT_START_DATE
        , TO_VARCHAR(TO_TIMESTAMP_TZ(CONTRACT_END_DATE), 'MM/DD/YYYY') AS CONTRACT_END_DATE
        , TOTAL_CONTRACT_AMT
        , PRODUCT
        , BU
        , INSTALLMENT_TIMING
        , TRY_TO_NUMBER(INSTALLMENT_NUMBER) AS INSTALLMENT_NUMBER
        , TRY_TO_DATE(PLANNED_BILLING_DATE, 'YYYYMMDD') AS PLANNED_BILLING_DATE
        , CASE
        	WHEN TRY_TO_NUMBER(SETTLEMENT_DATE_FOR_DEADLINE_FKDAT) = 0 AND TRY_TO_NUMBER(SETTLEMENT_DATE_FOR_DEADLINE_NFDAT) = 0 THEN NULL
        	ELSE CONCAT (TRY_TO_DATE(SETTLEMENT_DATE_FOR_DEADLINE_FKDAT, 'YYYYMMDD'), ' to ', TRY_TO_DATE(SETTLEMENT_DATE_FOR_DEADLINE_NFDAT, 'YYYYMMDD'))
        END AS INSTALLMENT_DESC
        , PLANNED_INSTALLMENT_AMT
        , ACTUAL_INSTALLMENT_AMT
        , LISTAGG(CONTRACT_SCOPE_BY_PRODUCT,',') AS CONTRACT_SCOPE_BY_PRODUCT
        , CASE
            WHEN BILLING_STATUS = 'A' THEN 'OPEN'
            WHEN BILLING_STATUS = 'B' THEN 'PARTIALLY PROCESSED'
            WHEN BILLING_STATUS = 'C' THEN 'INVOICED'
            WHEN BILLING_STATUS = 'D' THEN 'REJECTED'
            WHEN BILLING_STATUS = 'E' THEN 'BILLING REJECTED'
            ELSE NULL
        END AS BILLING_STATUS
        , TRY_TO_DATE(BILLING_DATE,'YYYYMMDD') AS BILLING_DATE
        , BILLING_DOCUMENT
        , ZEROIFNULL(CONTRACT_REVENUE_RECOGNIZED) AS CONTRACT_REVENUE_RECOGNIZED
        , CUSTOMER_CODE
        , CUSTOMER_NAME
        , CUSTOMER_NAME_B
        , CUSTOMER_GROUP
        , CUSTOMER_GROUP2
        , ORDER_CUSTOMER
        , COVERED_FAB
        , COVERED_FAB_NAME
        , CONTRACT_START_YYYY_MM
        , CONTRACT_START_FISCAL_HALF
        , PLANNED_BILLING_DATE_YYYY_MM
        , PLANNED_BILLING_DATE_FISCAL_HALF
        , SITE_SUPERVISOR
        , SITE_SUPERVISOR_ID
        , SALES_DOC_TYPE
        , CASE
            WHEN SALES_DOC_TYPE='N' THEN '1'
                ELSE '0'
          END AS REVERSAL_FLAG
        ,CASE
            WHEN ACTUAL_INSTALLMENT_AMT IS NOT NULL AND REVERSAL_FLAG = '0' THEN ACTUAL_INSTALLMENT_AMT
            WHEN ACTUAL_INSTALLMENT_AMT IS NOT NULL AND REVERSAL_FLAG = '1' THEN ACTUAL_INSTALLMENT_AMT * -1
            ELSE PLANNED_INSTALLMENT_AMT
          END AS ADJ_INSTALLMENT_AMT
        , PROFIT_CENTER
        , COST_CENTER
        , SECURITY_SEGMENT
        , SECURITY_DEPARTMENT
        , SECURITY_OFFICE
        , CASE
            WHEN CONTRACT_TYPE_AGG = '' THEN NULL
            WHEN CONTRACT_TYPE_AGG LIKE '%,%' THEN 'Comprehensive'
            ELSE CONTRACT_TYPE_AGG
          END AS CONTRACT_TYPE
        , MANAGED_BY
        ,CASE
            WHEN BILLING_DATE IS NOT NULL THEN CONCAT(SUBSTR(BILLING_DATE,1,4),'-',SUBSTR(BILLING_DATE,5,2))
            ELSE CONCAT(SUBSTR(PLANNED_BILLING_DATE,1,4),'-',SUBSTR(PLANNED_BILLING_DATE,5,2))
        END AS PLANNED_BILLING_MONTH_ADJ
        , DP_APPROVAL_STATUS
        , DP_APPROVAL_STATUS_DESC
    FROM SOURCE_DATA
    GROUP BY ALL
),

TYPE_DATA AS (
    SELECT DISTINCT
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
        , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        , SALES_CATEGORY
        , ZC11_SALES_ORDER
        , PO_NUMBER
        , PO_LINE
        , CONTRACT_NUMBER
        , CONTRACT_STATUS
        , CONTRACT_OWNER
        , CONTRACT_TITLE
        , CONTRACT_SCOPE_BY_PRODUCT
        , CAST(CONTRACT_START_DATE AS DATE) AS CONTRACT_START_DATE
        , CAST(CONTRACT_END_DATE AS DATE) AS CONTRACT_END_DATE
        , CAST(TOTAL_CONTRACT_AMT AS NUMBER(38,2)) AS TOTAL_CONTRACT_AMT
        , PRODUCT
        , BU
        , INSTALLMENT_TIMING
        , INSTALLMENT_NUMBER
        , CAST(PLANNED_BILLING_DATE AS DATE) AS PLANNED_BILLING_DATE
        , INSTALLMENT_DESC
        , CAST(PLANNED_INSTALLMENT_AMT AS NUMBER(38,2)) AS PLANNED_INSTALLMENT_AMT
        , CAST(ACTUAL_INSTALLMENT_AMT AS NUMBER(38,2)) AS ACTUAL_INSTALLMENT_AMT
        , CAST(REVERSAL_FLAG AS VARCHAR(1)) AS REVERSAL_FLAG
        , CAST(ADJ_INSTALLMENT_AMT AS NUMBER(38,2)) ADJ_INSTALLMENT_AMT
        , BILLING_STATUS
        , CAST(BILLING_DATE AS DATE) AS BILLING_DATE
        , PLANNED_BILLING_MONTH_ADJ
        , BILLING_DOCUMENT
        , CAST(CONTRACT_REVENUE_RECOGNIZED as VARCHAR(16777216)) as CONTRACT_REVENUE_RECOGNIZED
        , CUSTOMER_CODE
        , CUSTOMER_NAME
        , CUSTOMER_NAME_B
        , CUSTOMER_GROUP
        , CUSTOMER_GROUP2
        , ORDER_CUSTOMER
        , COVERED_FAB
        , COVERED_FAB_NAME
        , CONTRACT_START_YYYY_MM
        , CONTRACT_START_FISCAL_HALF
        , PLANNED_BILLING_DATE_YYYY_MM
        , PLANNED_BILLING_DATE_FISCAL_HALF
        , SITE_SUPERVISOR
        , SITE_SUPERVISOR_ID
        , PROFIT_CENTER
        , COST_CENTER
        , CONTRACT_TYPE
        , MANAGED_BY
        , DP_APPROVAL_STATUS
        , DP_APPROVAL_STATUS_DESC
		-- , CAST(SECURITY_SEGMENT AS VARCHAR(16777216)) AS SECURITY_SEGMENT
        -- , CAST(SECURITY_DEPARTMENT AS VARCHAR(16777216)) AS SECURITY_DEPARTMENT
        -- , CAST(SECURITY_OFFICE as VARCHAR(16777216)) as SECURITY_OFFICE

    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
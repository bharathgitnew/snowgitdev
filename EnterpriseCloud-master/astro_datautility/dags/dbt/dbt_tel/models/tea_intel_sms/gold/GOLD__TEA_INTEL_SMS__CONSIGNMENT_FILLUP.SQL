WITH
DELIVERY_AGG AS (
    SELECT
        DOL.REF_DOC_HDR,
        DOL.REF_DOC_LINE,
        LISTAGG(DOL.PROCESSING_STATUS, '|') AS PROCESSING_STATUSES,
        LISTAGG(DOL.SLOC, '|') AS DELIVERY_SLOCS,
        LISTAGG(DOL.HDR || '-' || DOL.LINE_POSNR, '|') AS DO_LINE_IDS,
        --CASE WHEN MIN(DOL.SLOC) = MAX(DOL.SLOC) THEN MAX(DOL.SLOC) ELSE 'Multiple' END AS SLOC,
        MAX(DOL.ACTUAL_GOODS_MOVEMENT_DATE) AS LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
        --MAX(DOL.CONF_WH_DELIVERY_DATE) AS CONF_WH_DELIVERY_DATE,
        MAX(DOL.CREATED_ON) AS LATEST_DO_CREATED_DATE,
        MAX(DOL.PICKING_DATE) AS LATEST_PICKING_DATE,
        MAX(DOL.DELIVERY_DATE_ZZDDZZ) AS LATEST_DELIVERY_DATE,
        MAX(DOL.HAWB) AS HAWB,
        COUNT(*) AS NUMBER_OF_DO_LINES,
        SUM(DOL.QTY) AS TOTAL_DO_QTY
    FROM {{ ref('SILVER__TEA_INTEL_SMS__DELIVERY_ORDER_LINE_MASTER_PUB') }} AS DOL
    -- Filter out DO lines where qty = 0
    WHERE DOL.QTY > 0
    GROUP BY DOL.REF_DOC_HDR, DOL.REF_DOC_LINE
),

SOURCE_DATA AS (
select distinct
    DA.PROCESSING_STATUSES AS DELIVERY_PROCESSING_STATUSES,
    SOL.VBAK_SALES_DOCUMENT as SALES_ORDER_HEADER_NUMBER,
    SOL.SALES_DOCUMENT_ITEM_POSNR as SALES_ORDER_LINE_NUMBER,
    TRY_TO_DATE(SOL.VBAK_DELIVERY_CREATE_DATE,'YYYYMMDD') as SALES_ORDER_DATE,
    SOL.MATERIAL_NUMBER,
    COALESCE(SOL.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS, 0)  AS SO_QTY,
    DA.DO_LINE_IDS,
    DA.TOTAL_DO_QTY,
    SOL.STORAGE_LOCATION_VBAP AS SALES_ORDER_SLOC,
    DA.DELIVERY_SLOCS,
    DA.HAWB,
    DA.LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
    DA.LATEST_DELIVERY_DATE,
    DA.LATEST_DO_CREATED_DATE,
    DA.LATEST_PICKING_DATE,
    TRY_TO_DATE(SOL.DOCUMENT_DATE,'YYYYMMDD') as SALES_ORDER_DOCUMENT_DATE,
    SOL.VBAK_SOLD_TO_PARTY as SOLD_TO_PARTY_CODE,
    KNA1.NAME1 as SOLD_TO_PARTY,
    TRY_TO_DATE(SOL.VBAP_SHIP_DATE ,'YYYYMMDD') as SHIP_DATE,
    SOL.VBAK_DELIVERY_STATUS as DELIVERY_STATUS,
    TRY_TO_DATE(SOL.SCHEDULED_WAREHOUSE_DELIVERY_DATE, 'YYYYMMDD') AS SCHEDULED_WAREHOUSE_DELIVERY_DATE,
    SOL.VBAK_SALES_DOCUMENT_TYPE as SALES_DOC_TYPE,
    MARA.MAKTX AS MATERIAL_DESCRIPTION,
    SOL.VBAP_MATERIAL_GROUP as MATERIAL_GROUP,
    COALESCE(DA.NUMBER_OF_DO_LINES, 0) AS NUMBER_OF_DO_LINES,
    SOL.REASON_FOR_REJECTION_OF_SALES_DOCUMENTS as REJECTION_REASON
from {{ ref('SILVER__TEA_INTEL_SMS__SALES_ORDER_DELIVERY_LINE') }}  AS SOL
LEFT JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (SOL.VBAK_SOLD_TO_PARTY = KNA1.KUNNR)
LEFT JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU017_MARA') }} AS MARA ON (SOL.MATERIAL_NUMBER = MARA.MATNR)
LEFT JOIN DELIVERY_AGG AS DA ON (
    DA.REF_DOC_HDR = SOL.VBAK_SALES_DOCUMENT AND
    DA.REF_DOC_LINE = SOL.SALES_DOCUMENT_ITEM_POSNR
)
WHERE
    SOL.VBAK_SALES_DOCUMENT_TYPE = 'ZP11' AND
    SOL.REJECTION_STATUS_FOR_SALES_DOCUMENT_ITEM <> 'C'  AND
    ifnull(REASON_FOR_REJECTION_OF_SALES_DOCUMENTS, '') = ''
),
TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        DELIVERY_PROCESSING_STATUSES,
        SALES_ORDER_HEADER_NUMBER,
        SALES_ORDER_LINE_NUMBER,
        SALES_ORDER_DATE,
        MATERIAL_NUMBER,
        SO_QTY,
        DO_LINE_IDS,
        TOTAL_DO_QTY,
        SALES_ORDER_SLOC,
        DELIVERY_SLOCS,
        HAWB,
        LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
        LATEST_DELIVERY_DATE,
        LATEST_DO_CREATED_DATE,
        LATEST_PICKING_DATE,
        SALES_ORDER_DOCUMENT_DATE,
        SOLD_TO_PARTY_CODE,
        SOLD_TO_PARTY,
        SHIP_DATE,
        DELIVERY_STATUS,
        SCHEDULED_WAREHOUSE_DELIVERY_DATE,
        SALES_DOC_TYPE,
        MATERIAL_DESCRIPTION,
        MATERIAL_GROUP,
        NUMBER_OF_DO_LINES
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        _AUDIT_LOG_ID,
        _ROW_HASH,
        DELIVERY_PROCESSING_STATUSES,
        SALES_ORDER_HEADER_NUMBER,
        SALES_ORDER_LINE_NUMBER,
        CAST(SALES_ORDER_DATE AS DATE) AS SALES_ORDER_DATE,
        MATERIAL_NUMBER,
        CAST(SO_QTY AS INT) AS  SO_QTY,
        DO_LINE_IDS,
        CAST(TOTAL_DO_QTY AS INT) AS TOTAL_DO_QTY,
        SALES_ORDER_SLOC,
        DELIVERY_SLOCS,
        HAWB,
        CAST(LATEST_ACTUAL_GOODS_MOVEMENT_DATE AS DATE) AS LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
        CAST(LATEST_DELIVERY_DATE AS DATE) AS LATEST_DELIVERY_DATE,
        CAST(LATEST_DO_CREATED_DATE AS DATE) AS LATEST_DO_CREATED_DATE,
        CAST(LATEST_PICKING_DATE AS DATE) AS LATEST_PICKING_DATE,
        CAST(SALES_ORDER_DOCUMENT_DATE AS DATE) AS SALES_ORDER_DOCUMENT_DATE,
        SOLD_TO_PARTY_CODE,
        SOLD_TO_PARTY,
        CAST(SHIP_DATE AS DATE) AS SHIP_DATE,
        DELIVERY_STATUS,
        CAST(SCHEDULED_WAREHOUSE_DELIVERY_DATE AS DATE) AS SCHEDULED_WAREHOUSE_DELIVERY_DATE,
        SALES_DOC_TYPE,
        MATERIAL_DESCRIPTION,
        MATERIAL_GROUP,
        CAST(NUMBER_OF_DO_LINES AS INT) AS NUMBER_OF_DO_LINES
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
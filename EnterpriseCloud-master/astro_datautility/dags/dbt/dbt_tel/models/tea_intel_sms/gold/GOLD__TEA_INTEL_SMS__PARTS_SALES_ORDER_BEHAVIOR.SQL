WITH ref_SALES_ORDER_LINE_MASTER AS
(
SELECT DISTINCT 
    SALES_ORDER_HEADER_NUMBER AS SALES_ORDER_NBR
    ,SALES_ORDER_LINE_NUMBER AS SALES_ORDER_LINE_NBR
    ,ORDER_PRIORITY
    ,SALES_ORDER_LINE_AMOUNT
    ,SALES_ORDER_QUANTITY
    ,NCDR_NUMBER
    ,ORDER_REASON_CODE
    ,ORDER_REASON
    ,SALES_DOC_TYPE
    ,SALES_DOC_TYPE_DESCRIPTION
    ,MATERIAL_NUMBER
    ,MATERIAL_DESCRIPTION
    ,TOOL_SERIAL_NO
    ,STORAGE_LOCATION
    ,SALES_ORDER_DATE
    ,END_USER_CITY AS SITE
    ,CONSUMABLE_FLAG
    ,CUSTOMER_REFERENCE
    ,END_USER
    ,END_USER_GROUP
    ,END_USER_REGION
FROM {{ source('DE_OPERATIONS', 'SALES_ORDER_LINE_MASTER') }}
WHERE SOLD_TO_PARTY IS NOT NULL
)

,DIM_DELIVERED_QTY_AMT AS
( 
SELECT DISTINCT SO_NUMBER as SALES_ORDER_NBR
   ,SO_LINE AS SALES_ORDER_LINE_NBR
   ,SALES_PRICE
   ,ORDER_TYPE_NAME
   ,SUM(DO_QTY) AS TOTAL_DELIVERY_QUANTITY
   ,ROUND(SALES_PRICE * TOTAL_DELIVERY_QUANTITY, 2) AS TOTAL_DELIVERY_AMOUNT 
FROM {{ source('DE_OPERATIONS', 'SALES_ORDER_WITH_REF_DATA') }}
WHERE DO_QTY <> 0
AND OBDO_NUMBER IS NOT NULL 
AND DO_LINE IS NOT NULL --Include only valid transactions
AND SALES_BILLING_DOCUMENT_IS_CANCELED <> 'X'
AND SOLD_TO_CUSTOMER_GROUP IS NOT NULL
GROUP BY ALL
)

,DIM_SO_REF_DATA AS
(
SELECT DISTINCT SO_NUMBER as SALES_ORDER_NBR
    ,SO_LINE AS SALES_ORDER_LINE_NBR
    ,SOLD_TO_CUSTOMER_GROUP
    ,BU_GROUP
    ,ITEM AS MATERIAL_NUMBER
    ,TRY_TO_NUMBER(TRANSACTION_ID) AS TRANSACTION_ID
    ,TRY_TO_NUMBER(TRANSACTION_ID_ITEM) AS TRANSACTION_ID_ITEM
FROM {{ source('DE_OPERATIONS', 'SALES_ORDER_WITH_REF_DATA') }}
WHERE DO_QTY <> 0
AND OBDO_NUMBER IS NOT NULL 
AND DO_LINE IS NOT NULL --Include only valid transactions
AND SALES_BILLING_DOCUMENT_IS_CANCELED <> 'X'  --exclude consignment fill ups
AND ORDER_TYPE <> 'ZP11'
AND SOLD_TO_CUSTOMER_GROUP IS NOT NULL
)

,DIM_IS_SELLABLE AS
(
SELECT DISTINCT 
    MATERIAL_NUMBER
    ,UPPER(SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT) AS IS_SELLABLE
FROM {{ source('DE_OPERATIONS', 'MATERIAL_MASTER') }}
)

,DIM_MATERIAL_DESCRIPTION AS 
(
SELECT DISTINCT 
    MATNR AS MATERIAL_NUMBER
    ,MEINS AS UNIT_OF_MEASURE
    ,MAKTX AS MATERIAL_DESCRIPTION
FROM {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU017_MARA') }} 
)

,DIM_SERIAL_NO_TO_CONFIGURATION AS
(
SELECT DISTINCT 
    SERIAL_NUMBER
    ,CUSTOMER_TOOL_ID
    ,TEL_MODEL
    ,SWLH_MODEL
FROM {{ source('DE_OPERATIONS', 'US_MACHINES') }}
)

,DIM_CHANGE_COMMENT AS
(
SELECT DISTINCT VBAP_SALES_DOCUMENT AS SALES_ORDER_NBR
    ,SALES_DOCUMENT_ITEM_POSNR AS SALES_ORDER_LINE_NBR
    ,TRIM(CHANGE_COMMENT) AS CHANGE_COMMENT
FROM {{ ref('SILVER__TEA_INTEL_SMS__SALES_ORDER_DELIVERY_LINE') }} 
)

,DIM_INTEL_CONSUMPTION_TRANS_TYPE AS
(
SELECT DISTINCT 
    TRY_TO_NUMBER(NULLIF(NULLIF(UPPER(TRIM(CUSTOMER_TRANSACTION_ID)), 'NOT SPECIFIED'), '')) AS CUSTOMER_TRANSACTION_ID 
    ,TRY_TO_NUMBER(CUSTOMER_TRANSACTION_LINE_ID) AS CUSTOMER_TRANSACTION_LINE_ID
    ,TEL_PART_NUMBER AS MATERIAL_NUMBER
    ,FIRST_VALUE(INTEL_SERIAL_NUMBER) IGNORE NULLS 
    OVER (PARTITION BY TEL_PART_NUMBER, CUSTOMER_TRANSACTION_ID, CUSTOMER_TRANSACTION_LINE_ID ORDER BY CONSUMED_DATE DESC) AS INTEL_TOOL_ID
    ,FIRST_VALUE(TRANSACTION_TYPE) IGNORE NULLS 
    OVER (PARTITION BY TEL_PART_NUMBER, CUSTOMER_TRANSACTION_ID, CUSTOMER_TRANSACTION_LINE_ID ORDER BY CONSUMED_DATE DESC) AS TRANSACTION_TYPE
    ,FIRST_VALUE(TRANSACTION_REASON) IGNORE NULLS 
    OVER (PARTITION BY TEL_PART_NUMBER, CUSTOMER_TRANSACTION_ID, CUSTOMER_TRANSACTION_LINE_ID ORDER BY CONSUMED_DATE DESC) AS TRANSACTION_REASON  
FROM {{ ref('GOLD__TEA_INTEL_SMS__INTEL_CONSUMPTION_HISTORY') }} 
)

,SOURCE_DATA AS
(
SELECT DISTINCT 
    a.SALES_ORDER_NBR
    ,a.SALES_ORDER_LINE_NBR
    ,a.ORDER_PRIORITY
    ,a.SALES_ORDER_DATE AS SO_CREATION_DATE
    ,a.SALES_ORDER_QUANTITY AS TOTAL_ORDER_QUANTITY
    ,a.SALES_ORDER_LINE_AMOUNT
    ,a.TOOL_SERIAL_NO
    ,f.TOTAL_DELIVERY_QUANTITY
    ,f.TOTAL_DELIVERY_AMOUNT
    ,a.NCDR_NUMBER
    ,a.ORDER_REASON_CODE
    ,a.ORDER_REASON
    ,a.SALES_DOC_TYPE
    ,a.SALES_DOC_TYPE_DESCRIPTION
    ,a.MATERIAL_NUMBER
    ,a.MATERIAL_DESCRIPTION
    ,a.STORAGE_LOCATION
    ,a.SITE
    ,a.CONSUMABLE_FLAG
    ,a.CUSTOMER_REFERENCE
    ,a.END_USER
    ,a.END_USER_GROUP
    ,a.END_USER_REGION AS STATE
    ,CASE 
    WHEN LEFT(b.MATERIAL_NUMBER, 2) = 'BT'
        THEN '3DI'
        WHEN LEFT(b.MATERIAL_NUMBER, 2) = 'P5'
        THEN 'TMEA'
        WHEN LEFT(b.MATERIAL_NUMBER, 2) = 'TF'
        THEN 'TMEA'
        ELSE LEFT(b.BU_GROUP, 2) END AS BU_GROUP
    ,CASE 
    WHEN UPPER(b.SOLD_TO_CUSTOMER_GROUP) like '%INTEL%'
        THEN d.TRANSACTION_TYPE
        ELSE NULL
    END AS INTEL_TRANSACTION_TYPE
   ,CASE 
    WHEN UPPER(b.SOLD_TO_CUSTOMER_GROUP) like '%INTEL%'
        THEN d.TRANSACTION_REASON
        ELSE NULL
    END AS INTEL_TRANSACTION_REASON
    ,COALESCE(c.CUSTOMER_TOOL_ID, d.INTEL_TOOL_ID) AS CUSTOMER_TOOL_ID
    ,c.TEL_MODEL
    ,c.SWLH_MODEL
    ,b.SOLD_TO_CUSTOMER_GROUP
    ,CASE 
    WHEN e.CHANGE_COMMENT = '' 
        THEN NULL
       ELSE e.CHANGE_COMMENT 
    END AS CHANGE_COMMENT
    ,d.CUSTOMER_TRANSACTION_ID as INTEL_TRANSACTION_ID
    ,d.CUSTOMER_TRANSACTION_LINE_ID as INTEL_TRANSACTION_LINE_ID
    ,g.IS_SELLABLE
    ,h.UNIT_OF_MEASURE
FROM ref_SALES_ORDER_LINE_MASTER a
LEFT JOIN DIM_SO_REF_DATA b
ON a.SALES_ORDER_NBR = b.SALES_ORDER_NBR
AND a.SALES_ORDER_LINE_NBR = b.SALES_ORDER_LINE_NBR
LEFT JOIN DIM_SERIAL_NO_TO_CONFIGURATION c
ON a.TOOL_SERIAL_NO = c.SERIAL_NUMBER
LEFT JOIN DIM_INTEL_CONSUMPTION_TRANS_TYPE d
ON b.MATERIAL_NUMBER = d.MATERIAL_NUMBER
AND b.TRANSACTION_ID = d.CUSTOMER_TRANSACTION_ID
AND b.TRANSACTION_ID_ITEM = d.CUSTOMER_TRANSACTION_LINE_ID
LEFT JOIN DIM_CHANGE_COMMENT e
ON a.SALES_ORDER_NBR = e.SALES_ORDER_NBR
AND a.SALES_ORDER_LINE_NBR = e.SALES_ORDER_LINE_NBR
LEFT JOIN DIM_DELIVERED_QTY_AMT f
ON a.SALES_ORDER_NBR = f.SALES_ORDER_NBR
AND a.SALES_ORDER_LINE_NBR = f.SALES_ORDER_LINE_NBR
LEFT JOIN DIM_IS_SELLABLE g
ON a.MATERIAL_NUMBER = g.MATERIAL_NUMBER
LEFT JOIN DIM_MATERIAL_DESCRIPTION h
ON a.MATERIAL_NUMBER = h.MATERIAL_NUMBER
)

,TRANSFORM_DATA AS (
SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID
    ,SHA2('hash_me') AS _ROW_HASH
    ,SALES_ORDER_NBR
    ,SALES_ORDER_LINE_NBR
    ,ORDER_PRIORITY
    ,SO_CREATION_DATE
    ,TOTAL_ORDER_QUANTITY
    ,SALES_ORDER_LINE_AMOUNT
    ,TOOL_SERIAL_NO
    ,TOTAL_DELIVERY_QUANTITY
    ,TOTAL_DELIVERY_AMOUNT
    ,NCDR_NUMBER
    ,ORDER_REASON_CODE
    ,ORDER_REASON
    ,SALES_DOC_TYPE
    ,SALES_DOC_TYPE_DESCRIPTION
    ,MATERIAL_NUMBER
    ,MATERIAL_DESCRIPTION
    ,STORAGE_LOCATION
    ,SITE
    ,CONSUMABLE_FLAG
    ,CUSTOMER_REFERENCE
    ,END_USER
    ,END_USER_GROUP
    ,STATE
    ,BU_GROUP
    ,INTEL_TRANSACTION_TYPE
    ,INTEL_TRANSACTION_REASON
    ,CUSTOMER_TOOL_ID
    ,TEL_MODEL
    ,SWLH_MODEL
    ,SOLD_TO_CUSTOMER_GROUP
    ,CHANGE_COMMENT
    ,INTEL_TRANSACTION_ID
    ,INTEL_TRANSACTION_LINE_ID
    ,REGEXP_SUBSTR(CUSTOMER_TOOL_ID, '^([A-Za-z]+)') AS TOOL_ID_PREFIX
    ,CASE WHEN UPPER(CHANGE_COMMENT) like '%INTERNATIONAL%CROSS%' THEN 'Yes'
        WHEN UPPER(CHANGE_COMMENT) like '%INTERNATIONAL%XSITE%' THEN 'Yes'
        WHEN UPPER(CHANGE_COMMENT) like '%FROM IR%' THEN 'Yes'
        WHEN UPPER(CHANGE_COMMENT) like '%FROM F24%' THEN 'Yes'
        WHEN UPPER(CHANGE_COMMENT) like '%FROM F28%' THEN 'Yes'
        WHEN UPPER(CHANGE_COMMENT) like '%FROM IR%' THEN 'Yes'
        ELSE 'No'
    END AS IS_RETURN_XSITE  
    ,IS_SELLABLE
    ,UNIT_OF_MEASURE
FROM SOURCE_DATA
WHERE SOLD_TO_CUSTOMER_GROUP IS NOT NULL  -- Consignment Fill Up does not count
AND TRIM(SALES_DOC_TYPE) <> 'ZPR1'
),

TYPE_DATA as (
    SELECT 
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    SALES_ORDER_NBR
    ,SALES_ORDER_LINE_NBR
    ,ORDER_PRIORITY
    ,SO_CREATION_DATE
    ,TOTAL_ORDER_QUANTITY
    ,SALES_ORDER_LINE_AMOUNT
    ,TOOL_SERIAL_NO
    ,TOTAL_DELIVERY_QUANTITY
    ,TOTAL_DELIVERY_AMOUNT
    ,NCDR_NUMBER
    ,ORDER_REASON_CODE
    ,ORDER_REASON
    ,SALES_DOC_TYPE
    ,SALES_DOC_TYPE_DESCRIPTION
    ,MATERIAL_NUMBER
    ,MATERIAL_DESCRIPTION
    ,STORAGE_LOCATION
    ,SITE
    ,CONSUMABLE_FLAG
    ,CUSTOMER_REFERENCE
    ,END_USER
    ,END_USER_GROUP
    ,STATE
    ,BU_GROUP
    ,INTEL_TRANSACTION_TYPE
    ,INTEL_TRANSACTION_REASON
    ,CUSTOMER_TOOL_ID
    ,TEL_MODEL
    ,SWLH_MODEL
    ,SOLD_TO_CUSTOMER_GROUP
    ,CHANGE_COMMENT
    ,INTEL_TRANSACTION_ID
    ,INTEL_TRANSACTION_LINE_ID
    ,TOOL_ID_PREFIX
    ,IS_RETURN_XSITE
    ,IS_SELLABLE
    ,UNIT_OF_MEASURE
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
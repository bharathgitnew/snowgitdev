WITH TEE_STOCK
AS (
	SELECT T$ITEM
		,suM(T$STOC) AS Stock
	
	FROM {{ ref('BRONZE__TEA_INTEL_SMS__FILE_STOCK_TEE_CRYSTAL') }}
	WHERE T$CWAR IN (
			'112'
			,'DE2'
			,'11B'
			,'11C'
			,'724'
			,'711'
			,'928'
			,'933'
			,'111'
			)
		AND SUBSTR(T$ITEM, 1, 2) IN (
			'CT'
			,'ES'
			,'RE'
			)
	
	GROUP BY T$ITEM
	)
	,Storage_location
AS (
	SELECT TWLAD.WERKS AS s_plant
		,twlad.LGORT AS S_STORAGE_LOCATION
		,adrc.region AS region
	
	FROM {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU203_TWLAD') }} AS twlad
	
	LEFT JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU087_ADRC') }} AS adrc ON twlad.adrnr = adrc.ADDRNUMBER
	
	WHERE nation = 'I'
	)
	,Stocks
AS (
	SELECT stock.Plant
		,stock.Material_number
		,stock.SPEC_STOCK_PARTNER
		,stock.SPEC_STOCK_PARTNER_NAME
		,stock.STORAGE_LOCATION
		,stock.STORAGE_LOCATION_NAME
		,CASE 
			WHEN stock.STORAGE_LOCATION = ''
				THEN kNA1.REGIO
			ELSE twlad.region
			END AS region
		,sum(stock.UNRESTRICTED_STOCK) AS UNRESTRICTED_STOCK
		,Sum(stock.ALLOCATED_STOCK) AS ALLOCATED_STOCK
		,sum(stock.CUSTOMER_CONSIGNMENT_QTY) AS CUSTOMER_CONSIGNMENT_QTY
	
	FROM {{ ref('SILVER__TEA_INTEL_SMS__PART_STOCK_OVERVIEW_REPORT') }} AS stock
	
	LEFT JOIN Storage_location AS twlad ON twlad.S_STORAGE_LOCATION = stock.STORAGE_LOCATION
		AND TWLAD.S_Plant = stock.Plant
	
	LEFT JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU020_KNA1') }} AS kna1 ON stock.SPEC_STOCK_PARTNER = knA1.KUNNR
	
	GROUP BY stock.Plant
		,stock.Material_number
		,stock.SPEC_STOCK_PARTNER
		,stock.SPEC_STOCK_PARTNER_NAME
		,stock.STORAGE_LOCATION
		,stock.STORAGE_LOCATION_NAME
		,kNA1.REGIO
		,twlad.region
	)
	,total_stock
AS (
	SELECT plant
		,material_number
		,region
		,sum(UNRESTRICTED_STOCK - ALLOCATED_STOCK + CUSTOMER_CONSIGNMENT_QTY) AS stock
	
	FROM stocks
	
	WHERE (
			STORAGE_LOCATION_NAME ilike '%INT%'
			OR STORAGE_LOCATION = ''
			)
		AND (
			STORAGE_LOCATION_NAME NOT ilike '%NIC%'
			AND STORAGE_LOCATION_NAME NOT ilike '%NCDR%'
			AND STORAGE_LOCATION_NAME NOT ilike '%SCRP%'
			AND STORAGE_LOCATION_NAME NOT ilike '%FCN%'
			AND STORAGE_LOCATION_NAME NOT ilike '%RSRV%'
			)
	
	GROUP BY plant
		,material_number
		,region
	)
	,OR_B_STOCK AS (
		SELECT
			material_number,
			SUM(UNRESTRICTED_STOCK - ALLOCATED_STOCK + CUSTOMER_CONSIGNMENT_QTY) AS OR_B_STOCK
		FROM stocks
		WHERE
			STORAGE_LOCATION IN ('F430','A530','E330')
		OR SPEC_STOCK_PARTNER IN ('DC0010168','DC0010169')
		GROUP BY material_number
	)
	,AZ_B_STOCK AS (
		SELECT
			material_number,
			SUM(UNRESTRICTED_STOCK - ALLOCATED_STOCK + CUSTOMER_CONSIGNMENT_QTY) AS AZ_B_STOCK
		FROM stocks
		WHERE STORAGE_LOCATION IN ('D930','B230')
		OR SPEC_STOCK_PARTNER = 'DC0010166'

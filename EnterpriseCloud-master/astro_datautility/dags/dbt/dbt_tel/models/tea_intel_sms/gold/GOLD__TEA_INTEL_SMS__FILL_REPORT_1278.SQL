					THEN ZEROIFNULL(MSQLOW)
				ELSE ZEROIFNULL(MSQHIGH)
				END) OVER (PARTITION BY CONSOLIDATED_SPN) AS MAX_MSQ
	
	FROM {{ ref('BRONZE__TEA_INTEL_SMS__FILE_INTEL_VFBOM') }}
	)
	,VFBOM

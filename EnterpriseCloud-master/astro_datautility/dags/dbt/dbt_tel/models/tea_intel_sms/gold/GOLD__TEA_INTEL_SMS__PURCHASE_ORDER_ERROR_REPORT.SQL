with cost_center as (
    select
        COST_CENTER_CODE,
        SEGMENT_CODE as SECURITY_SEGMENT,
        DEPARTMENT_CODE as SECURITY_DEPARTMENT,
        OFFICE_CODE as SECURITY_OFFICE
    from {{ ref('BRONZE__TEA_INTEL_SMS__FILE_COST_CENTER') }}
),

profit_center as (
    select
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('BRONZE__TEA_INTEL_SMS__FILE_PROFIT_CENTER') }}
),

pdd as (
    select distinct
        --PO
        EKPO_PURCHASING_DOCUMENT_NUMBER             as PO_NUMBER_EKPO, --EKPO
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP   as PO_LINE_EKPO, --EKPO
        MATERIAL_NUMBER_MATNR                      as PO_MATERIAL_NUM_EKPO, --EKPO
        REQUEST_SERIAL_NUMBER                      as PO_SERIAL_NUM_EKPO,
        --NO BATCH IN EKPO/EKKO
        EKPO_STORAGE_LOCATION                      as PO_STORAGE_LOC_EKPO, --EKPO
        PURCHASE_ORDER_QUANTITY                    as PO_QUANTITY_EKPO, --EKPO

        --DO
        LIPS_DELIVERY                              as DO_NUMBER_LIPS,
        DELIVERY_ITEM_POSNR                        as DO_LINE_LIPS,
        MATERIAL_NUMBER                            as DO_MATERIAL_NUM_LIPS, --LIPS
        LIPS_SERIAL_NO                             as DO_SERIAL_NUM_LIPS,
        BATCH_NUMBER                               as DO_BATCH_LIPS, --LIPS
        RECEIVING_ISSUING_STORAGE_LOCATION         as DO_STORAGE_LOC_LIPS, -- LIPS
        ACTUAL_QUANTITY_DELIVERED                  as DO_QUANTITY_LIPS --LIPS
    from {{ ref('SILVER__TEA_INTEL_SMS__PURCHASE_ORDER_DELIVERY_LINE') }}
),

asn_po as (
    select
        asn.ASN_ID              as ASN_ID_ASN_PO,
        asn.DOCUMENT_NUMBER    as DOCUMENT_NUMBER_ASN_PO,
        asn.LINE_NUMBER        as LINE_NUMBER_ASN_PO,
        asn.MATERIAL_NUMBER    as MATERIAL_NUMBER_ASN_PO,
        asn.WMS_BATCH          as WMS_BATCH_ASN_PO,
        asn.SERIAL_NUMBER      as SERIAL_NUMBER_ASN_PO,
        asn.STORAGE_LOCATION   as STORAGE_LOCATION_ASN_PO,
        asn.EXPECTED_QUANTITY  as EXPECTED_QUANTITY_ASN_PO,

        rec.DOCUMENT_NUMBER    as DOCUMENT_NUMBER_REC_PO,
        rec.LINE_NUMBER        as LINE_NUMBER_REC_PO,
        rec.MATERIAL_NUMBER    as MATERIAL_NUMBER_REC_PO,
        rec.WMS_BATCH          as WMS_BATCH_REC_PO,
        rec.SERIAL_NUMBER      as SERIAL_NUMBER_REC_PO,
        rec.STORAGE_LOCATION   as STORAGE_LOCATION_REC_PO,
        rec.RECEIPT_QUANTITY   as RECEIPT_QUANTITY_REC_PO
    from {{ ref('SILVER__TEA_INTEL_SMS__TPL_ASN') }} asn
    left join {{ ref('SILVER__TEA_INTEL_SMS__TPL_RECEIVING_ADVICE') }} rec on
        asn.DOCUMENT_NUMBER = rec.DOCUMENT_NUMBER and
        asn.LINE_NUMBER = rec.LINE_NUMBER
),

asn_do as (
    select
        asn.ASN_ID              as ASN_ID_ASN_DO,
        asn.DOCUMENT_NUMBER    as DOCUMENT_NUMBER_ASN_DO,
        asn.LINE_NUMBER        as LINE_NUMBER_ASN_DO,
        asn.MATERIAL_NUMBER    as MATERIAL_NUMBER_ASN_DO,
        asn.WMS_BATCH          as WMS_BATCH_ASN_DO,
        asn.SERIAL_NUMBER      as SERIAL_NUMBER_ASN_DO,
        asn.STORAGE_LOCATION   as STORAGE_LOCATION_ASN_DO,
        asn.EXPECTED_QUANTITY  as EXPECTED_QUANTITY_ASN_DO,

        rec.DOCUMENT_NUMBER    as DOCUMENT_NUMBER_REC_DO,
        rec.LINE_NUMBER        as LINE_NUMBER_REC_DO,
        rec.MATERIAL_NUMBER    as MATERIAL_NUMBER_REC_DO,
        rec.WMS_BATCH          as WMS_BATCH_REC_DO,
        rec.SERIAL_NUMBER      as SERIAL_NUMBER_REC_DO,
        rec.STORAGE_LOCATION   as STORAGE_LOCATION_REC_DO,
        rec.RECEIPT_QUANTITY   as RECEIPT_QUANTITY_REC_DO
    from {{ ref('SILVER__TEA_INTEL_SMS__TPL_ASN') }}  asn
    left join {{ ref('SILVER__TEA_INTEL_SMS__TPL_RECEIVING_ADVICE') }} rec on
        asn.DOCUMENT_NUMBER = rec.DOCUMENT_NUMBER and
        to_number(asn.LINE_NUMBER) = to_number(rec.LINE_NUMBER)
),

pdd2 as (
    select
        EKPO_PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
        count(distinct LIPS_DELIVERY ||'|'||DELIVERY_ITEM_POSNR) as AGGR_DELIVERIES_ASN,
        sum(ACTUAL_QUANTITY_DELIVERED) as AGGR_DELIVERED_QTY_LIPS
    from {{ ref('SILVER__TEA_INTEL_SMS__PURCHASE_ORDER_DELIVERY_LINE') }}
    group by EKPO_PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP
),

aggr as (
    select
        asn.DOCUMENT_NUMBER,
        asn.LINE_NUMBER,
        sum(EXPECTED_QUANTITY) as AGGR_EXPECTED_QTY_ASN,
        sum(RECEIPT_QUANTITY) as AGGR_RECEIVED_QTY_REC
    from {{ ref('SILVER__TEA_INTEL_SMS__TPL_ASN') }} asn
    left join {{ ref('SILVER__TEA_INTEL_SMS__TPL_RECEIVING_ADVICE') }} rec on
        asn.DOCUMENT_NUMBER = rec.DOCUMENT_NUMBER and
        to_number(asn.LINE_NUMBER) = to_number(rec.LINE_NUMBER)
    group by asn.DOCUMENT_NUMBER, asn.LINE_NUMBER
),

source_data as (
    select
        PO_NUMBER_EKPO, --EKPO
        PO_LINE_EKPO, --EKPO
        PO_MATERIAL_NUM_EKPO, --EKPO
        PO_SERIAL_NUM_EKPO,
        --NO BATCH IN EKPO/EKKO
        PO_STORAGE_LOC_EKPO, --EKPO
        PO_QUANTITY_EKPO, --EKPO

        --DO
        DO_NUMBER_LIPS,
        DO_LINE_LIPS,
        DO_MATERIAL_NUM_LIPS, --LIPS
        DO_SERIAL_NUM_LIPS,
        DO_BATCH_LIPS, --LIPS
        DO_STORAGE_LOC_LIPS, -- LIPS
        DO_QUANTITY_LIPS, --LIPS
        DOCUMENT_NUMBER_ASN_DO,
        DOCUMENT_NUMBER_ASN_PO,
        LINE_NUMBER_ASN_DO,
        LINE_NUMBER_ASN_PO,
        MATERIAL_NUMBER_ASN_DO,
        MATERIAL_NUMBER_ASN_PO,
        WMS_BATCH_ASN_DO,
        WMS_BATCH_ASN_PO,
        SERIAL_NUMBER_ASN_DO,
        SERIAL_NUMBER_ASN_PO,
        STORAGE_LOCATION_ASN_DO,
        STORAGE_LOCATION_ASN_PO,
        EXPECTED_QUANTITY_ASN_DO,
        EXPECTED_QUANTITY_ASN_PO,
        DOCUMENT_NUMBER_REC_DO,
        DOCUMENT_NUMBER_REC_PO,
        LINE_NUMBER_REC_DO,
        LINE_NUMBER_REC_PO,
        MATERIAL_NUMBER_REC_DO,
        MATERIAL_NUMBER_REC_PO,
        WMS_BATCH_REC_DO,
        WMS_BATCH_REC_PO,
        SERIAL_NUMBER_REC_DO,
        SERIAL_NUMBER_REC_PO,
        STORAGE_LOCATION_REC_DO,
        STORAGE_LOCATION_REC_PO,
        RECEIPT_QUANTITY_REC_DO,
        RECEIPT_QUANTITY_REC_PO,
        AGGR_EXPECTED_QTY_ASN,
        AGGR_RECEIVED_QTY_REC,
        AGGR_DELIVERIES_ASN,
        AGGR_DELIVERED_QTY_LIPS,

        null as PROFIT_CENTER,
        null as COST_CENTER,

        '<ALL>' as SECURITY_SEGMENT,
        '<ALL>' as SECURITY_DEPARTMENT,
        '<ALL>' as SECURITY_OFFICE
    from pdd
    left join asn_po on
        PO_NUMBER_EKPO = DOCUMENT_NUMBER_ASN_PO and
        to_number(PO_LINE_EKPO) = to_number(LINE_NUMBER_ASN_PO)
    left join asn_do on
        DO_NUMBER_LIPS = DOCUMENT_NUMBER_ASN_DO and
        to_number(DO_LINE_LIPS) = to_number(LINE_NUMBER_ASN_DO)
    left join pdd2 on
        PO_NUMBER_EKPO = pdd2.EKPO_PURCHASING_DOCUMENT_NUMBER and
        to_number(PO_LINE_EKPO) = to_number(ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP)
    left join aggr on
        aggr.DOCUMENT_NUMBER = PO_NUMBER_EKPO and
        to_number(aggr.LINE_NUMBER) = to_number(PO_LINE_EKPO)
),

	transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH,
		PO_NUMBER_EKPO,
		--EKPO
		PO_LINE_EKPO,
		--EKPO
		PO_MATERIAL_NUM_EKPO,
		--EKPO
		PO_SERIAL_NUM_EKPO,
		--NO BATCH IN EKPO/EKKO
		PO_STORAGE_LOC_EKPO,
		--EKPO
		PO_QUANTITY_EKPO,
		--EKPO
		
		--DO
		DO_NUMBER_LIPS,
		DO_LINE_LIPS,
		DO_MATERIAL_NUM_LIPS,
		--LIPS
		DO_SERIAL_NUM_LIPS,
		DO_BATCH_LIPS,
		--LIPS
		DO_STORAGE_LOC_LIPS,
		-- LIPS
		DO_QUANTITY_LIPS,
		--LIPS
		
		--Next Lines being used for mering the two versions of these fields
		case when len(DOCUMENT_NUMBER_ASN_DO) >1 then DOCUMENT_NUMBER_ASN_DO else DOCUMENT_NUMBER_ASN_PO       end as DOCUMENT_NUMBER_ASN,
		case when len(LINE_NUMBER_ASN_DO) >1 then LINE_NUMBER_ASN_DO else LINE_NUMBER_ASN_PO                   end as LINE_NUMBER_ASN,
		case when len(MATERIAL_NUMBER_ASN_DO) >1 then MATERIAL_NUMBER_ASN_DO else MATERIAL_NUMBER_ASN_PO       end as MATERIAL_NUMBER_ASN,
		case when len(WMS_BATCH_ASN_DO) >1 then WMS_BATCH_ASN_DO else WMS_BATCH_ASN_PO                         end as WMS_BATCH_ASN,
		case when len(SERIAL_NUMBER_ASN_DO) >1 then SERIAL_NUMBER_ASN_DO else SERIAL_NUMBER_ASN_PO             end as SERIAL_NUMBER_ASN,
		case when len(STORAGE_LOCATION_ASN_DO) >1 then STORAGE_LOCATION_ASN_DO else STORAGE_LOCATION_ASN_PO    end as STORAGE_LOCATION_ASN,
		case when len(EXPECTED_QUANTITY_ASN_DO) >1 then EXPECTED_QUANTITY_ASN_DO else EXPECTED_QUANTITY_ASN_PO end as EXPECTED_QUANTITY_ASN,
		case when len(DOCUMENT_NUMBER_REC_DO) >1 then DOCUMENT_NUMBER_REC_DO else DOCUMENT_NUMBER_REC_PO    end as DOCUMENT_NUMBER_REC,
		case when len(LINE_NUMBER_REC_DO) >1 then LINE_NUMBER_REC_DO else LINE_NUMBER_REC_PO                end as LINE_NUMBER_REC,
		case when len(MATERIAL_NUMBER_REC_DO) >1 then MATERIAL_NUMBER_REC_DO else MATERIAL_NUMBER_REC_PO    end as MATERIAL_NUMBER_REC,
		case when len(WMS_BATCH_REC_DO) >1 then WMS_BATCH_REC_DO else WMS_BATCH_REC_PO                      end as WMS_BATCH_REC,
		case when len(SERIAL_NUMBER_REC_DO) >1 then SERIAL_NUMBER_REC_DO else SERIAL_NUMBER_REC_PO          end as SERIAL_NUMBER_REC,
		case when len(STORAGE_LOCATION_REC_DO) >1 then STORAGE_LOCATION_REC_DO else STORAGE_LOCATION_REC_PO end as STORAGE_LOCATION_REC,
		case when len(RECEIPT_QUANTITY_REC_DO) >1 then RECEIPT_QUANTITY_REC_DO else RECEIPT_QUANTITY_REC_PO end as RECEIPT_QUANTITY_REC,
		case
		when PO_QUANTITY_EKPO > AGGR_EXPECTED_QTY_ASN then 'ASN Missing Qty'
		when PO_QUANTITY_EKPO < AGGR_EXPECTED_QTY_ASN then 'ASN Over Qty'
		else 'Match'
		end as ASN_QUANTITY_FLAG,
		case
		when PO_QUANTITY_EKPO > AGGR_RECEIVED_QTY_REC then 'Rec Missing Qty'
		when PO_QUANTITY_EKPO < AGGR_RECEIVED_QTY_REC then 'Rec Over Qty'
		else 'Match'
		end as RECEIPT_QUANTITY_FLAG,
		AGGR_DELIVERIES_ASN,
		AGGR_DELIVERED_QTY_LIPS,
		case
		when PO_QUANTITY_EKPO > AGGR_DELIVERED_QTY_LIPS then 'Actual Missing Qty'
		when PO_QUANTITY_EKPO < AGGR_DELIVERED_QTY_LIPS then 'Actual Over Qty'
		else 'Match'
		end as AGGR_DELIVERED_FLAG,
		PROFIT_CENTER,
		COST_CENTER,
		SECURITY_SEGMENT,
		SECURITY_DEPARTMENT,
		SECURITY_OFFICE 
    from source_data
),

	type_data as (
    select
		cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		cast(PO_NUMBER_EKPO as VARCHAR(16777216)) as PO_NUMBER_EKPO,
		cast(PO_LINE_EKPO as VARCHAR(16777216)) as PO_LINE_EKPO,
		cast(PO_MATERIAL_NUM_EKPO as VARCHAR(16777216)) as PO_MATERIAL_NUM_EKPO,
		cast(PO_SERIAL_NUM_EKPO as VARCHAR(16777216)) as PO_SERIAL_NUM_EKPO,
		cast(PO_STORAGE_LOC_EKPO as VARCHAR(16777216)) as PO_STORAGE_LOC_EKPO,
		cast(PO_QUANTITY_EKPO as VARCHAR(16777216)) as PO_QUANTITY_EKPO,
		cast(DO_NUMBER_LIPS as VARCHAR(16777216)) as DO_NUMBER_LIPS,
		cast(DO_LINE_LIPS as VARCHAR(16777216)) as DO_LINE_LIPS,
		cast(DO_MATERIAL_NUM_LIPS as VARCHAR(16777216)) as DO_MATERIAL_NUM_LIPS,
		cast(DO_SERIAL_NUM_LIPS as VARCHAR(16777216)) as DO_SERIAL_NUM_LIPS,
		cast(DO_BATCH_LIPS as VARCHAR(16777216)) as DO_BATCH_LIPS,
		cast(DO_STORAGE_LOC_LIPS as VARCHAR(16777216)) as DO_STORAGE_LOC_LIPS,
		cast(DO_QUANTITY_LIPS as VARCHAR(16777216)) as DO_QUANTITY_LIPS,
		cast(DOCUMENT_NUMBER_ASN as VARCHAR(16777216)) as DOCUMENT_NUMBER_ASN,
		cast(LINE_NUMBER_ASN as VARCHAR(16777216)) as LINE_NUMBER_ASN,
		cast(MATERIAL_NUMBER_ASN as VARCHAR(16777216)) as MATERIAL_NUMBER_ASN,
		cast(WMS_BATCH_ASN as VARCHAR(16777216)) as WMS_BATCH_ASN,
		cast(SERIAL_NUMBER_ASN as VARCHAR(16777216)) as SERIAL_NUMBER_ASN,
		cast(STORAGE_LOCATION_ASN as VARCHAR(16777216)) as STORAGE_LOCATION_ASN,
		cast(EXPECTED_QUANTITY_ASN as VARCHAR(16777216)) as EXPECTED_QUANTITY_ASN,
		cast(DOCUMENT_NUMBER_REC as VARCHAR(16777216)) as DOCUMENT_NUMBER_REC,
		cast(LINE_NUMBER_REC as VARCHAR(16777216)) as LINE_NUMBER_REC,
		cast(MATERIAL_NUMBER_REC as VARCHAR(16777216)) as MATERIAL_NUMBER_REC,
		cast(WMS_BATCH_REC as VARCHAR(16777216)) as WMS_BATCH_REC,
		cast(SERIAL_NUMBER_REC as VARCHAR(16777216)) as SERIAL_NUMBER_REC,
		cast(STORAGE_LOCATION_REC as VARCHAR(16777216)) as STORAGE_LOCATION_REC,
		cast(RECEIPT_QUANTITY_REC as VARCHAR(16777216)) as RECEIPT_QUANTITY_REC,
		cast(ASN_QUANTITY_FLAG as VARCHAR(16777216)) as ASN_QUANTITY_FLAG,
		cast(RECEIPT_QUANTITY_FLAG as VARCHAR(16777216)) as RECEIPT_QUANTITY_FLAG,
		cast(AGGR_DELIVERIES_ASN as NUMBER(38,0)) as AGGR_DELIVERIES_ASN,
		cast(AGGR_DELIVERED_QTY_LIPS as NUMBER(38,10)) as AGGR_DELIVERED_QTY_LIPS,
		cast(AGGR_DELIVERED_FLAG as VARCHAR(16777216)) as AGGR_DELIVERED_FLAG,
		CAST(PROFIT_CENTER AS VARCHAR(16777216)) AS PROFIT_CENTER,
		CAST(COST_CENTER AS VARCHAR(16777216)) AS COST_CENTER,
		cast(SECURITY_SEGMENT as VARCHAR(16777216)) as SECURITY_SEGMENT,
		cast(SECURITY_DEPARTMENT as VARCHAR(16777216)) as SECURITY_DEPARTMENT,
		cast(SECURITY_OFFICE as VARCHAR(16777216)) as SECURITY_OFFICE
    from transform_data
)

select * from type_data
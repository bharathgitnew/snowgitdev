        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        alias='BUSINESS_PARTNERS_3200_ADDRESS',
        transient=false
) }}

WITH DISTINCTBP AS (
        SELECT
        DISTINCT CORPORATION AS BUSINESS_PARTNER_NUMBER
        ,CORPORATION
    FROM {{ ref('SILVER__TEA_INTEL_SMS__BUSINESS_PARTNERS_GENERAL_DATA') }}
        WHERE 1=1 AND LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B'
        AND EXTENDED_TO_COMPANY_3200  = 'Y'
        UNION
        SELECT
        DISTINCT BUSINESS_PARTNER_NUMBER
        ,CORPORATION
    FROM {{ ref('SILVER__TEA_INTEL_SMS__BUSINESS_PARTNERS_GENERAL_DATA') }}
        WHERE EXTENDED_TO_COMPANY_3200  = 'Y'
),

BPGENERAL AS (
SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
        ,NAME_1_OF_ORGANIZATION
        ,CASE
        WHEN LEN(SEARCH_TERM_2_FOR_BUSINESS_PARTNER) < 1 THEN NULL
        ELSE SEARCH_TERM_2_FOR_BUSINESS_PARTNER
        END AS SEARCH_TERM_2
        ,NAME_1_OF_ORGANIZATION AS CORPORATION_NAME
        ,STREET_AND_HOUSE_NUMBER
        ,CITY
        ,REGION
        ,POSTAL_CODE
        ,IDENTIFICATION_NUMBER
        ,EXTENDED_TO_COMPANY_3200
        ,SEARCH_TERM_1_FOR_BUSINESS_PARTNER AS SEARCH_TERM_1
        ,NAME_1
        ,COUNTRY_KEY AS COUNTRY
        ,CUSTOMER_FLAG
        ,VENDOR_FLAG
        ,SORT_FIELD
    FROM {{ ref('SILVER__TEA_INTEL_SMS__BUSINESS_PARTNERS_GENERAL_DATA') }}
        WHERE IDENTIFICATION_TYPE = '1100'
),

STANDARDNAME AS (
SELECT
        NAME_1_OF_ORGANIZATION AS CORPORATION_NAME
        ,CORPORATION
        ,RECORDCOUNT
        ,ROW_NUMBER() OVER(Partition by CORPORATION ORDER BY RECORDCOUNT DESC) AS RN
        FROM(
        SELECT
        NAME_1_OF_ORGANIZATION
        ,CORPORATION
        ,COUNT(*) AS RECORDCOUNT
    FROM {{ ref('SILVER__TEA_INTEL_SMS__BUSINESS_PARTNERS_GENERAL_DATA') }}
        WHERE EXTENDED_TO_COMPANY_3200  = 'Y'
        GROUP BY
        NAME_1_OF_ORGANIZATION
        ,CORPORATION)
),

CGM AS (
SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('BRONZE__TEA_INTEL_SMS__SHAREPOINT_CUSTOMER_GROUP_MAPPING') }}
)
,SOURCE AS (
    SELECT
    CGM.CUSTOMER_GROUP
    ,CGM.CUSTOMER_GROUP2
    ,LEFT(DISTINCTBP.BUSINESS_PARTNER_NUMBER ,1) AS BUSINESS_PARTNER_SERIES
    ,DISTINCTBP.BUSINESS_PARTNER_NUMBER
    ,STANDARDNAME.CORPORATION_NAME
    ,DISTINCTBP.CORPORATION
    ,BPGENERAL.SEARCH_TERM_1
    ,BPGENERAL.SEARCH_TERM_2
    ,BPGENERAL.NAME_1_OF_ORGANIZATION
    ,BPGENERAL.STREET_AND_HOUSE_NUMBER
    ,BPGENERAL.CITY
    ,CASE
    WHEN BPGENERAL.COUNTRY = 'US' THEN BPGENERAL.REGION
    ELSE NULL
    END AS US_STATE
    ,BPGENERAL.POSTAL_CODE
    ,BPGENERAL.COUNTRY
    ,BPGENERAL.REGION
    ,BPGENERAL.SORT_FIELD
    ,BPGENERAL.IDENTIFICATION_NUMBER
    ,BPGENERAL.CUSTOMER_FLAG
    ,BPGENERAL.VENDOR_FLAG
    ,BPGENERAL.EXTENDED_TO_COMPANY_3200
    ,'Y' AS EXTENDED_TO_COMPANY_3200_ADJ
    FROM DISTINCTBP
    INNER JOIN BPGENERAL
        ON DISTINCTBP.BUSINESS_PARTNER_NUMBER = BPGENERAL.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN STANDARDNAME
        ON DISTINCTBP.CORPORATION = STANDARDNAME.CORPORATION AND STANDARDNAME.RN = 1
    LEFT JOIN CGM
        ON CGM.ACCOUNT_NUMBER = DISTINCTBP.CORPORATION
)
,TRANSFORM_DATA as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        CUSTOMER_GROUP,
        CUSTOMER_GROUP2,
        BUSINESS_PARTNER_SERIES,
        BUSINESS_PARTNER_NUMBER,
        CORPORATION_NAME,
        CORPORATION,
        SEARCH_TERM_1,
        SEARCH_TERM_2,
        NAME_1_OF_ORGANIZATION,
        STREET_AND_HOUSE_NUMBER,
        CITY,
        US_STATE,
        POSTAL_CODE,
        COUNTRY,
        REGION,
        SORT_FIELD,
        IDENTIFICATION_NUMBER,
        CUSTOMER_FLAG,
        VENDOR_FLAG,
        EXTENDED_TO_COMPANY_3200,
        EXTENDED_TO_COMPANY_3200_ADJ
from SOURCE
)
,TYPE_DATA AS (
SELECT
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        CUSTOMER_GROUP,
        CUSTOMER_GROUP2,
        BUSINESS_PARTNER_SERIES,
        BUSINESS_PARTNER_NUMBER,
        CORPORATION_NAME,
        CORPORATION,
        SEARCH_TERM_1,
        SEARCH_TERM_2,
        NAME_1_OF_ORGANIZATION,
        STREET_AND_HOUSE_NUMBER,
        CITY,
        US_STATE,
        POSTAL_CODE,
        COUNTRY,
        REGION,
        SORT_FIELD,
        IDENTIFICATION_NUMBER,
        CUSTOMER_FLAG,
        VENDOR_FLAG,
        EXTENDED_TO_COMPANY_3200,
        EXTENDED_TO_COMPANY_3200_ADJ
FROM TRANSFORM_DATA)

SELECT * FROM TRANSFORM_DATA
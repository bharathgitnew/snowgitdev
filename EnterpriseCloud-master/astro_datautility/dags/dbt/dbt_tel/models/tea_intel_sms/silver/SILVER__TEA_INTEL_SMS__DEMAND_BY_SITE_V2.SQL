WITH
-- SAP delivery order aggregate by sales order
DELIV AS (
    SELECT 
        LIPS.VGBEL AS REF_DOC, 
        LIPS.VGPOS AS REF_DOC_POSNR,
        CASE WHEN MIN(LIKP.VBELN) = MAX(LIKP.VBELN) THEN MAX(LIKP.VBELN) ELSE 'Multiple DOs' END AS DO_HDR,
        MIN(NULLIF(LIKP.WADATIST, '00000000')) AS GOODS_MOVEMENT_DATE,
        SUM(LIPS.LFIMG) AS DELIVERED_QTY,
        COUNT(*) AS DELIVERY_LINE_COUNT,
        COUNT(DISTINCT(LIPS.VGBEL)) AS DELIVERY_HDR_COUNT
    FROM {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU013_LIPS') }} AS LIPS
    JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU012_LIKP') }} AS LIKP ON (LIPS.VBELN = LIKP.VBELN)
    WHERE LIPS.MATNR IS NOT NULL
    GROUP BY LIPS.VGBEL, LIPS.VGPOS
),
-- subset of columns with pre-processing for SAP sales order data
SAP_BASE AS (
    SELECT
        VBAP.MATNR AS ITEM,
        MAX(MARA.MAKTX) AS MATERIAL_DESC,
        VBAK.AUART AS SALES_DOC_TYPE,
        DATE_TRUNC('MONTH', TRY_TO_DATE(VBAK.ERDAT, 'YYYYMMDD')) AS PERIOD,
        --LEFT(VBAK.ERDAT, 6) AS PERIOD,
        VBAK.KUNNR AS SOLD_TO_BP_CODE,
        MAX(KNA1.NAME1) AS SOLD_TO_BP,
        SUM(
            CASE 
                WHEN VBAK.AUART IN ('ZPR2', 'ZPR1') 
                THEN -1 * DELIV.DELIVERED_QTY 
                ELSE DELIV.DELIVERED_QTY 
            END
        ) AS DELIVERED_QTY,
        SUM(
            CASE 
                WHEN VBAK.AUART IN ('ZPR2', 'ZPR1') 
                THEN -1 * CAST(VBAP.KWMENG AS INT) 
                ELSE CAST(VBAP.KWMENG AS INT)
            END
        ) AS SO_QTY,
        'SAP' AS SOURCE
    FROM {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU009_VBAK') }} AS VBAK
    JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU010_VBAP') }} AS VBAP ON (VBAP.VBELN = VBAK.VBELN)
    JOIN DELIV ON (VBAK.VBELN = DELIV.REF_DOC AND VBAP.POSNR = DELIV.REF_DOC_POSNR)
    LEFT JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU017_MARA') }} AS MARA ON (MARA.MATNR = VBAP.MATNR)
    LEFT JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (
        VBAK.KUNNR = KNA1.KUNNR
    )
    WHERE VBAK.AUART IN (
        'ZPR2', 'ZPR1', 'ZT10', 'ZP12', 'ZP10', 'ZR10', 'ZR11'
    )
    GROUP BY 
        VBAP.MATNR, 
        VBAK.AUART, 
        DATE_TRUNC('MONTH', TRY_TO_DATE(VBAK.ERDAT, 'YYYYMMDD')), 
        VBAK.KUNNR
),
-- Combine BAAN sales orders and select service orders
BAAN_SALES_DATA AS (
    SELECT 
        ITEM,
        'BAAN' AS SALES_DOC_TYPE,
        MATERIAL_ORDER_DATE AS ORDER_DATE, 
        SOLD_TO_BPID AS SOLDTO_BPID, 
        SOLD_TO_BP AS SOLDTO_BP,
        CASE 
            WHEN UPPER(DELIVERY_TYPE) = 'TO WAREHOUSE' 
            THEN ORDERED_QTY * -1 
            ELSE ORDERED_QTY 
        END AS DELIVERED_QTY,
        'BAAN' AS SOURCE
    -- REFERENCE TO BAAN SERVICE ORDER TABLE
    FROM {{ ref('SILVER__TEA_INTEL_SMS__SERVICEORDER') }}
    WHERE 
        LEFT(SERVICE_ORDER_NO, 3) NOT IN ('IPO','FCN','FAC','EVL','MOD') AND
        CANCELLED_DATE IS NULL

    UNION ALL

    SELECT
        ITEM,
        'BAAN' AS SALES_DOC_TYPE,
        ORDER_DATE,
        SOLDTO_BPID,
        SOLDTO_BP,
        DELIVERED_QTY,
        'BAAN' AS SOURCE
    -- REFERENCE TO BAAN SALES ORDER TABLE
    FROM {{ ref('SILVER__TEA_INTEL_SMS__SALESORDER') }}
    WHERE CANCELLED != 'Yes'
),
BAAN_BASE AS (
    SELECT
        BSO.ITEM,
        BSO.SALES_DOC_TYPE,
        BSO.SOURCE,
        MAX(MARA.MAKTX) AS MATERIAL_DESC,
        DATE_TRUNC('MONTH', BSO.ORDER_DATE) AS PERIOD,
        --YEAR(BSO.ORDER_DATE) || LPAD(MONTH(BSO.ORDER_DATE), 2, '0') AS PERIOD,
        BSO.SOLDTO_BPID AS SOLD_TO_BP_CODE,
        MAX(BSO.SOLDTO_BP) AS SOLD_TO_BP,
        SUM(BSO.DELIVERED_QTY) AS DELIVERED_QTY
    FROM BAAN_SALES_DATA AS BSO
    LEFT JOIN {{ ref('BRONZE__TEA_INTEL_SMS__SAPAPI_ZCDV_T_CMTU017_MARA') }} AS MARA ON (MARA.MATNR = BSO.ITEM)
    WHERE 
        BSO.ITEM BETWEEN 'CS' AND 'TZ' AND
        BSO.ORDER_DATE IS NOT NULL
    GROUP BY 
        BSO.ITEM,
        BSO.SALES_DOC_TYPE,
        BSO.SOURCE,
        DATE_TRUNC('MONTH', BSO.ORDER_DATE),
        BSO.SOLDTO_BPID
),
REPORT AS (
    SELECT 
        SAP_BASE.ITEM,
        SAP_BASE.MATERIAL_DESC, 
        SAP_BASE.SOLD_TO_BP_CODE,
        SAP_BASE.SOLD_TO_BP,
        SAP_BASE.PERIOD,
        SAP_BASE.SALES_DOC_TYPE,
        SAP_BASE.SO_QTY,
        SAP_BASE.DELIVERED_QTY,
        CASE WHEN SAP_BASE.SO_QTY < SAP_BASE.DELIVERED_QTY THEN 'X' END AS POTENTIAL_DATA_CORRUPTION_FLAG,
        SAP_BASE.SOURCE
    FROM SAP_BASE
    
    UNION ALL
    
    SELECT
        BAAN_BASE.ITEM,
        BAAN_BASE.MATERIAL_DESC,
        BAAN_BASE.SOLD_TO_BP_CODE,
        BAAN_BASE.SOLD_TO_BP,
        BAAN_BASE.PERIOD,
        BAAN_BASE.SALES_DOC_TYPE,
        BAAN_BASE.DELIVERED_QTY AS SO_QTY,
        BAAN_BASE.DELIVERED_QTY,
        NULL AS POTENTIAL_DATA_CORRUPTION_FLAG,
        BAAN_BASE.SOURCE
    FROM BAAN_BASE
),
SOURCE_DATA AS (
    SELECT 
        ITEM, MATERIAL_DESC, SOLD_TO_BP_CODE, SOLD_TO_BP, PERIOD, SALES_DOC_TYPE, 
        SO_QTY, DELIVERED_QTY, POTENTIAL_DATA_CORRUPTION_FLAG, SOURCE,
        COUNTRY,REGION,SEARCH_TERM_1,SEARCH_TERM_2
    FROM REPORT as REPORT
  left join  {{ ref('SILVER__TEA_INTEL_SMS__BUSINESS_PARTNERS_3200_ADDRESS') }} as region 
on REPORT.SOLD_TO_BP_CODE = region.BUSINESS_PARTNER_NUMBER 
),
	TRANSFORM_DATA AS (
    SELECT 
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		ITEM,
		MATERIAL_DESC,
		SOLD_TO_BP_CODE,
		SOLD_TO_BP,
		PERIOD,
		SALES_DOC_TYPE,
		SO_QTY,
		DELIVERED_QTY,
		POTENTIAL_DATA_CORRUPTION_FLAG,
		SOURCE,
		COUNTRY,
		REGION,
		SEARCH_TERM_1,
		SEARCH_TERM_2
    FROM SOURCE_DATA
),
	TYPE_DATA AS (
    SELECT 
		CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
		CAST(ITEM AS VARCHAR(16777216)) AS ITEM,
		CAST(MATERIAL_DESC AS VARCHAR(16777216)) AS MATERIAL_DESC,
		CAST(SOLD_TO_BP_CODE AS VARCHAR(16777216)) AS SOLD_TO_BP_CODE,
		CAST(SOLD_TO_BP AS VARCHAR(16777216)) AS SOLD_TO_BP,
		CAST(PERIOD AS DATE) AS PERIOD,
		CAST(SALES_DOC_TYPE AS VARCHAR(16777216)) AS SALES_DOC_TYPE,
		CAST(SO_QTY AS FLOAT) AS SO_QTY,
		CAST(DELIVERED_QTY AS FLOAT) AS DELIVERED_QTY,
		CAST(POTENTIAL_DATA_CORRUPTION_FLAG AS VARCHAR(16777216)) AS POTENTIAL_DATA_CORRUPTION_FLAG,
		CAST(SOURCE AS VARCHAR(16777216)) AS SOURCE,
		CAST(COUNTRY AS VARCHAR(16777216)) AS COUNTRY,
		CAST(REGION AS VARCHAR(16777216)) AS REGION,
		CAST(SEARCH_TERM_1 AS VARCHAR(16777216)) AS SEARCH_TERM_1,
		CAST(SEARCH_TERM_2 AS VARCHAR(16777216)) AS SEARCH_TERM_2
    FROM TRANSFORM_DATA
)
SELECT * 
FROM TYPE_DATA
{{ config(
    materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
    alias='FAT_COMPLETION_TIME',
    transient=false
) }}

WITH CTE_WISDOM_MACHINE
AS (
	SELECT DISTINCT MAC_LIST_MACHINE_SN,
		CASE WHEN MAC_LIST_EQUIPMENT_MOVE_IN_DATE IS NULL AND MAC_LIST_ACCEPTANCE_DATE IS NOT NULL THEN 'ERROR' WHEN MAC_LIST_EQUIPMENT_MOVE_IN_DATE IS NULL AND MAC_LIST_ACCEPTANCE_DATE IS NULL THEN 'PENDING' WHEN MAC_LIST_ACCEPTANCE_DATE IS NULL THEN 'OPEN' WHEN MAC_LIST_ACCEPTANCE_DATE IS NOT NULL THEN 'CLOSED' END AS STATUS,
		MAC_LIST_BU_NAME,
		CASE WHEN MAC_LIST_BU_NAME = 'CCS' THEN 'On Time FAT FSI' WHEN MAC_LIST_BU_NAME = 'GCIB' THEN 'On Time FAT Epion' END AS INDICATOR,
		MAC_LIST_COMPANY_NAME,
		MAC_LIST_MODEL_NAME,
		MAC_LIST_REGION_NAME,
		TO_DATE(MAC_LIST_EQUIPMENT_MOVE_IN_DATE) AS MAC_LIST_EQUIPMENT_MOVE_IN_DATE,
		TO_DATE(MAC_LIST_ACCEPTANCE_DATE) AS MAC_LIST_ACCEPTANCE_DATE,
		CASE WHEN STATUS = 'CLOSED' THEN (DATEDIFF(day, MAC_LIST_EQUIPMENT_MOVE_IN_DATE, MAC_LIST_ACCEPTANCE_DATE)) WHEN STATUS = 'OPEN' THEN (DATEDIFF(day, MAC_LIST_EQUIPMENT_MOVE_IN_DATE, CURRENT_DATE)) END AS DURATION_OF_DAYS,
		TO_NUMBER(((DURATION_OF_DAYS) / 7 * 5), 10, 0) AS DURATION_OF_BUSINESS_DAYS,
		CASE WHEN STATUS = 'CLOSED' THEN TO_DATE(MAC_LIST_ACCEPTANCE_DATE) WHEN STATUS = 'OPEN' THEN TO_DATE(CURRENT_DATE) END AS REPORT_DATE,
        CASE WHEN MAC_LIST_BU_NAME IN ('EV', 'BS' )THEN 'Inactive'
        ELSE 'Active'
        END AS ACTIVE_FLAG
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__WISDOM_MACHINE_DETAILS') }}   
	WHERE (MAC_LIST_BU_NAME = 'CCS' OR MAC_LIST_BU_NAME = 'GCIB')
    AND MAC_LIST_MODEL_NAME <> 'MAGELLAN'
    AND MAC_LIST_MODEL_NAME NOT ILIKE '%MERCURY%'
    AND MAC_LIST_MODEL_NAME NOT ILIKE '%POLARIS%'
    AND MAC_LIST_MODEL_NAME <> 'Yield Hunter'
	ORDER BY MAC_LIST_EQUIPMENT_MOVE_IN_DATE DESC
	),
CALENDARDATE
AS (
	SELECT calendar_date,
		FISCAL_YEAR_SHORT_TEXT,
		MONTH_ABBREVIATION_TEXT,
		MONTH_OF_FISCAL_YEAR_NUMBER
	FROM {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
	),
CTE_GOALS
AS (
	SELECT FY,
		INDICATORS_KPIS,
		TARGET
	FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__TMEA_MANAGEMENT_KPI_GOALS') }}
	WHERE FOCUS_AREA = 'Tech Support'
	),
CTE_OUTPUT
AS (
	SELECT *
	FROM CTE_WISDOM_MACHINE
	LEFT JOIN CALENDARDATE ON CALENDAR_DATE = REPORT_DATE
	LEFT JOIN CTE_GOALS ON CALENDARDATE.FISCAL_YEAR_SHORT_TEXT = CTE_GOALS.FY AND CTE_WISDOM_MACHINE.INDICATOR = CTE_GOALS.INDICATORS_KPIS
	),
CTE_RAW_DATA
AS (
	SELECT MAC_LIST_MACHINE_SN,
		STATUS,
        ACTIVE_FLAG,
		MAC_LIST_BU_NAME,
		INDICATOR,
		MAC_LIST_COMPANY_NAME,
		MAC_LIST_MODEL_NAME,
		MAC_LIST_REGION_NAME,
		MAC_LIST_EQUIPMENT_MOVE_IN_DATE,
		MAC_LIST_ACCEPTANCE_DATE,
		DURATION_OF_DAYS,
		DURATION_OF_BUSINESS_DAYS,
		TARGET,
		FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
		MONTH_ABBREVIATION_TEXT AS MONTH,
		MONTH_OF_FISCAL_YEAR_NUMBER
	FROM CTE_OUTPUT
	),
CTE_KPI
AS (
	SELECT STATUS,
		MAC_LIST_BU_NAME,
		FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
		MONTH_ABBREVIATION_TEXT AS MONTH,
		MONTH_OF_FISCAL_YEAR_NUMBER,
		COUNT(MAC_LIST_BU_NAME) AS TOOL_COUNT,
		TO_NUMBER(AVG(DURATION_OF_BUSINESS_DAYS), 10, 2) AS FAT_BUSINESS_DAYS_AVERAGE
	FROM CTE_OUTPUT
	GROUP BY STATUS,
		MAC_LIST_BU_NAME,
		FISCAL_YEAR_SHORT_TEXT,
		MONTH_ABBREVIATION_TEXT,
		MONTH_OF_FISCAL_YEAR_NUMBER
	ORDER BY FISCAL_YEAR_SHORT_TEXT,
		MONTH_OF_FISCAL_YEAR_NUMBER
	),
source_data
AS (
	SELECT MAC_LIST_MACHINE_SN,
		STATUS,
        ACTIVE_FLAG,
		MAC_LIST_BU_NAME,
		INDICATOR,
		MAC_LIST_COMPANY_NAME,
		MAC_LIST_MODEL_NAME,
		MAC_LIST_REGION_NAME,
		MAC_LIST_EQUIPMENT_MOVE_IN_DATE,
		MAC_LIST_ACCEPTANCE_DATE,
		DURATION_OF_DAYS,
		DURATION_OF_BUSINESS_DAYS,
		TARGET,
		FISCAL_YEAR,
		MONTH,
		MONTH_OF_FISCAL_YEAR_NUMBER
	FROM CTE_RAW_DATA
),
TRANSFORM_DATA AS (
SELECT
	'{ invocation_id }' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	MAC_LIST_MACHINE_SN,
	STATUS,
	ACTIVE_FLAG,
	MAC_LIST_BU_NAME,
	INDICATOR,
	MAC_LIST_COMPANY_NAME,
	MAC_LIST_MODEL_NAME,
	MAC_LIST_REGION_NAME,
	MAC_LIST_EQUIPMENT_MOVE_IN_DATE,
	MAC_LIST_ACCEPTANCE_DATE,
	DURATION_OF_DAYS,
	DURATION_OF_BUSINESS_DAYS,
	TARGET,
	FISCAL_YEAR,
	MONTH,
	MONTH_OF_FISCAL_YEAR_NUMBER

FROM SOURCE_DATA
)

,
TYPE_DATA AS (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	MAC_LIST_MACHINE_SN,
	STATUS,
	ACTIVE_FLAG,
	MAC_LIST_BU_NAME,
	INDICATOR,
	MAC_LIST_COMPANY_NAME,
	MAC_LIST_MODEL_NAME,
	MAC_LIST_REGION_NAME,
	CAST(MAC_LIST_EQUIPMENT_MOVE_IN_DATE as DATE) as MAC_LIST_EQUIPMENT_MOVE_IN_DATE,
	CAST(MAC_LIST_ACCEPTANCE_DATE as DATE) as MAC_LIST_ACCEPTANCE_DATE,
	CAST(DURATION_OF_DAYS as NUMBER(38,0)) as DURATION_OF_DAYS,
	CAST(DURATION_OF_BUSINESS_DAYS as NUMBER(38,0)) as DURATION_OF_BUSINESS_DAYS,
	TARGET,
	FISCAL_YEAR,
	MONTH,
	CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER
from transform_data
)
SELECT * FROM TYPE_DATA
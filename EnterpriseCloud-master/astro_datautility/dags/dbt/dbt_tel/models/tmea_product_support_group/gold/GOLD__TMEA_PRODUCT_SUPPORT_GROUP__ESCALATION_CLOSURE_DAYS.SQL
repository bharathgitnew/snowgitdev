{{ config(
	materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
	alias='ESCALATION_CLOSURE_DAYS',
	transient=false
) }}

WITH ref_cte_CALENDAR_DATE as (
    select * from {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
),

ref_cte_TMEA_MANAGEMENT_KPI_GOALS as (
    select * from {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__TMEA_MANAGEMENT_KPI_GOALS') }}
),

RAW_DATA AS(
select 
case_no,
ISSUE_NO,
WO_NO,
product_line,
ESCALATION_LEVEL,
ESCALATION_REASON,
ESCALATION_START,
ESCALATION_END,
case when ESCALATION_END is NULL then 'OPEN' else 'CLOSE' end as Status,
case when ESCALATION_END is NULL then (CURRENT_DATE)  else TO_DATE(ESCALATION_END) end as DATE,
case when ESCALATION_END is NULL then DATEDIFF(DAY,ESCALATION_START,CURRENT_DATE) else DATEDIFF(DAY,ESCALATION_START,ESCALATION_END) end as DAYS,
CASE
    WHEN PRODUCT_LINE = 'CCS' THEN 'CCS Escalation Closure Days' 
    WHEN PRODUCT_LINE = 'GCIB' THEN 'GCBI Escalation Closure Days'
    END as KPI,
TO_NUMBER(((DAYS)/7*5),10,0) AS BUSINESS_DAYS,
REGION,
CUSTOMER_ADDRESS_COUNTRY
from {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__WORKORDER_ESCALATION') }} 
where PRODUCT_LINE in ('CCS','GCIB')
),

CALENDARDATE AS(
select 
calendar_date,
-- FISCAL_YEAR_NUMBER,
FISCAL_YEAR_SHORT_TEXT,
-- QUARTER_TEXT,
-- QUARTER_SHORT_TEXT,
-- MONTH_TEXT,
MONTH_ABBREVIATION_TEXT,
MONTH_OF_FISCAL_YEAR_NUMBER
-- MONTH_OF_YEAR_NUMBER,
-- FISCAL_QUARTER_TEXT,
-- FISCAL_YEAR_HALF_YEAR_SHORT_TEXT,
-- FISCAL_YEAR_QUARTER_SHORT_TEXT,
-- FISCAL_YEAR_MONTH_SHORT_TEXT
from ref_cte_CALENDAR_DATE
where calendar_date > '2020-01-01'

),
SP_GOALS AS(
SELECT 
FY,
INDICATORS_KPIS,
FOCUS_AREA,
TARGET
FROM ref_cte_TMEA_MANAGEMENT_KPI_GOALS
WHERE FOCUS_AREA = 'Tech Support'
),

MAX_ESCALATION AS(
SELECT
ISSUE_NO AS PK,
MAX(LEFT(LEVELTO,100)) AS MAX_ESCALATION_LEVEL
FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__WORKORDER_ESCALATION_HISTORY') }}
GROUP BY ISSUE_NO
),

MAIN AS(
SELECT * FROM RAW_DATA
LEFT JOIN CALENDARDATE
    ON CALENDAR_DATE = DATE
LEFT JOIN SP_GOALS
    ON INDICATORS_KPIS = KPI
    AND FISCAL_YEAR_SHORT_TEXT = FY
LEFT JOIN MAX_ESCALATION
    ON ISSUE_NO = PK
),

source_data as (
SELECT CASE_NO,
ISSUE_NO,
WO_NO,
PRODUCT_LINE,
STATUS,
ESCALATION_LEVEL,
ESCALATION_REASON,
MAX_ESCALATION_LEVEL,
ESCALATION_START,
ESCALATION_END,
REGION,
CUSTOMER_ADDRESS_COUNTRY,
DATE,
calendar_date,
DAYS,
BUSINESS_DAYS,
KPI,
FOCUS_AREA,
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
MONTH_ABBREVIATION_TEXT AS MONTH ,
MONTH_OF_FISCAL_YEAR_NUMBER,
TARGET
FROM MAIN),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	CASE_NO,
	ISSUE_NO,
	WO_NO,
	PRODUCT_LINE,
	STATUS,
	ESCALATION_LEVEL,
	ESCALATION_REASON,
	MAX_ESCALATION_LEVEL,
	ESCALATION_START,
	ESCALATION_END,
	REGION,
	CUSTOMER_ADDRESS_COUNTRY,
	DATE,
	CALENDAR_DATE,
	DAYS,
	BUSINESS_DAYS,
	KPI,
	FOCUS_AREA,
	FISCAL_YEAR,
	MONTH,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	TARGET
from source_data
),

type_data as (
select
CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
,CASE_NO
,ISSUE_NO
,WO_NO
,PRODUCT_LINE
,STATUS
,ESCALATION_LEVEL
,ESCALATION_REASON
,MAX_ESCALATION_LEVEL
,CAST(ESCALATION_START as TIMESTAMP_NTZ(9)) as ESCALATION_START
,CAST(ESCALATION_END as TIMESTAMP_NTZ(9)) as ESCALATION_END
,REGION
,CUSTOMER_ADDRESS_COUNTRY
,CAST(DATE as DATE) as DATE
,CAST(CALENDAR_DATE as DATE) as CALENDAR_DATE
,CAST(DAYS as NUMBER(38,0)) as DAYS
,CAST(BUSINESS_DAYS as NUMBER(38,0)) as BUSINESS_DAYS
,KPI
,FOCUS_AREA
,FISCAL_YEAR
,MONTH
,CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER
,TARGET
from transform_data 
)
select * from type_data
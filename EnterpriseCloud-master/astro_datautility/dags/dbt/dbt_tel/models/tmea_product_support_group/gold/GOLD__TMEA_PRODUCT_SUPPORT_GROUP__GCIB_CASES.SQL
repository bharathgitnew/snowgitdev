{{ config(
    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='GCIB_CASES',
    	transient=false
) }}

WITH source_data
AS (
	SELECT CASE_NO,
		case_title,
		case_type,
		fab,
		machine_serial_no,
		person_in_charge AS CREATED_BY,
		open_date_time,
		MODIFIEDON AS MODIFIED_ON,
		MODIFIEDBY,
		STATUS_REASON,
		PRIORITY,
		CASE_STATUS,
		PRODUCT_CATEGORY,
		OWNER
	FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__TSC_US_CASE') }}
	WHERE CASE_STATUS = 'Open'
		AND (
			CASE_TYPE = 'Technical Support'
			OR CASE_TYPE = 'Parts Support'
			OR CASE_TYPE = 'Inquiry'
			OR CASE_TYPE = 'Others'
			)
		AND PRODUCT_CATEGORY = 'EPION'
	),
transform_data
AS (
	SELECT 
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		CASE_NO,
		CASE_TITLE,
		CASE_TYPE,
		FAB,
		MACHINE_SERIAL_NO,
		CREATED_BY,
		OPEN_DATE_TIME,
		MODIFIED_ON,
		MODIFIEDBY,
		STATUS_REASON,
		PRIORITY,
		CASE_STATUS,
		PRODUCT_CATEGORY,
		OWNER
	FROM source_data
	),
type_data
AS (
	SELECT 
		CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		CAST(CASE_NO AS VARCHAR(16777216)) AS CASE_NO,
		CAST(CASE_TITLE AS VARCHAR(16777216)) AS CASE_TITLE,
		CAST(CASE_TYPE AS VARCHAR(16777216)) AS CASE_TYPE,
		CAST(FAB AS VARCHAR(16777216)) AS FAB,
		CAST(MACHINE_SERIAL_NO AS VARCHAR(16777216)) AS MACHINE_SERIAL_NO,
		CAST(CREATED_BY AS VARCHAR(16777216)) AS CREATED_BY,
		CAST(OPEN_DATE_TIME AS TIMESTAMP_NTZ(9)) AS OPEN_DATE_TIME,
		CAST(MODIFIED_ON AS VARCHAR(16777216)) AS MODIFIED_ON,
		CAST(MODIFIEDBY AS VARCHAR(16777216)) AS MODIFIEDBY,
		CAST(STATUS_REASON AS VARCHAR(16777216)) AS STATUS_REASON,
		CAST(PRIORITY AS VARCHAR(16777216)) AS PRIORITY,
		CAST(CASE_STATUS AS VARCHAR(16777216)) AS CASE_STATUS,
		CAST(PRODUCT_CATEGORY AS VARCHAR(16777216)) AS PRODUCT_CATEGORY,
		CAST(OWNER AS VARCHAR(16777216)) AS OWNER
	FROM transform_data
	)
SELECT *
FROM type_data
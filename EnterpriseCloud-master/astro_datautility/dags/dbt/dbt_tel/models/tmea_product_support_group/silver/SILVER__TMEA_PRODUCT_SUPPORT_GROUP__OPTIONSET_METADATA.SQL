{{ config(
        alias = 'OPTIONSET_METADATA',
        materialized='tel_incremental',
        incremental_strategy = 'insert_overwrite',
        transiet = 'false'
) }}

with source_data as (
    SELECT
        ENTITYNAME AS ENTITYNAME,
        OPTIONSETNAME AS OPTIONSETNAME,
        OPTION AS OPTION,
        ISUSERLOCALIZEDLABEL AS ISUSERLOCALIZEDLABEL,
        LOCALIZEDLABELLANGUAGECODE AS LOCALIZEDLABELLANGUAGECODE,
        LOCALIZEDLABEL AS LOCALIZEDLABEL,
        'GLOBAL' AS SOURCE_FLAG
    FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_GLOBALOPTIONSETMETADATA') }}
    UNION ALL
    SELECT
        ENTITYNAME AS ENTITYNAME,
        OPTIONSETNAME AS OPTIONSETNAME,
        OPTION AS OPTION,
        ISUSERLOCALIZEDLABEL AS ISUSERLOCALIZEDLABEL,
        LOCALIZEDLABELLANGUAGECODE AS LOCALIZEDLABELLANGUAGECODE,
        LOCALIZEDLABEL AS LOCALIZEDLABEL,
        'LOCAL' AS SOURCE_FLAG
    FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_OPTIONSETMETADATA') }}
),

transform_data as (
    SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        ENTITYNAME,
        OPTIONSETNAME,
        OPTION,
        ISUSERLOCALIZEDLABEL,
        LOCALIZEDLABELLANGUAGECODE,
        LOCALIZEDLABEL,
        SOURCE_FLAG
	FROM source_data
),

type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(ENTITYNAME AS VARCHAR(16777216)) AS ENTITYNAME,
        CAST(OPTIONSETNAME AS VARCHAR(16777216)) AS OPTIONSETNAME,
        CAST(OPTION AS VARCHAR(16777216)) AS OPTION,
        CAST(ISUSERLOCALIZEDLABEL AS VARCHAR(16777216)) AS ISUSERLOCALIZEDLABEL,
        CAST(LOCALIZEDLABELLANGUAGECODE AS VARCHAR(16777216)) AS LOCALIZEDLABELLANGUAGECODE,
        CAST(LOCALIZEDLABEL AS VARCHAR(16777216)) AS LOCALIZEDLABEL,
        CAST(SOURCE_FLAG AS VARCHAR(16777216)) AS SOURCE_FLAG
    FROM transform_data
)

SELECT * FROM type_data
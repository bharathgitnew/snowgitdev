WITH CALENDARDATE AS (
    SELECT
        CALENDAR_DATE
        , YEAR_MONTH_TEXT
        , FISCAL_YEAR_SHORT_TEXT
        , FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
        , FISCAL_YEAR_QUARTER_SHORT_TEXT
    FROM {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}
),
--SAP CUSTOMER_GROUP MASTER FILE
CGM AS (
    SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__SHAREPOINT_CUSTOMER_GROUP_MAPPING') }}
),
--SAP CUSTOMER MASTER DATA
CUSTOMER AS (
    SELECT
        CUSTOMER.CUSTOMER_NUMBER
        , CUSTOMER.NAME_1 as CUSTOMER_NAME
        , CUSTOMER.SEARCH_TERM_2_FOR_BUSINESS_PARTNER as CUSTOMER_NAME_B
        , CUSTOMER.BUSINESS_PARTNER_NUMBER
        , CUSTOMER.CORPORATION
        , CUSTOMER_A.NAME_1 AS CUSTOMER_A_NAME
        , CGM.CUSTOMER_GROUP as CUSTOMER_GROUP
        , CGM.CUSTOMER_GROUP2 as CUSTOMER_GROUP2
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__BUSINESS_PARTNERS_GENERAL_DATA') }} AS CUSTOMER
        LEFT JOIN {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__BUSINESS_PARTNERS_GENERAL_DATA') }}  AS CUSTOMER_A
            ON CUSTOMER.CORPORATION = CUSTOMER_A.CUSTOMER_NUMBER
        LEFT JOIN CGM
            ON CGM.ACCOUNT_NUMBER = CUSTOMER.CORPORATION
    WHERE CUSTOMER.CUSTOMER_FLAG = 'Y'
),
--CRM CONTRACT ATTRIBUTES
CRM_OPTIONSET_CONTRACT_STATUS AS (
    SELECT
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM  {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'cnt_contract_status'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
),
CRM_OPTIONSET_INV_FREQUENCY AS (
    SELECT
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM  {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'cnt_invoicefrequency'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
),
CONTRACT_SCOPE AS (
    SELECT DISTINCT
        CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTSCOPESO, ', ') AS CONTRACT_SCOPE_BY_PRODUCT,
        LISTAGG(DISTINCT mapping.BU_GROUP, ', ') AS PRODUCTS,
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__CONTRACT_SUMMARY_DETAILS') }} CONTRACT_SUMMARY_DETAILS
    LEFT JOIN {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__OPTIONSET_METADATA') }} OPTIONSET_METADATA
        ON try_to_number(CONTRACT_SUMMARY_DETAILS.cnt_contract_status) = try_to_number(OPTIONSET_METADATA.OPTION)
    left join {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__SHAREPOINT_SERVICE_BUSINESS_UNIT_MAPPING') }} as mapping
        on regexp_substr(CNT_CONTRACTSCOPESO, '\\((\\w+)\\)$', 1, 1, 'ie') = mapping.BU_SOURCE_KEY
        or regexp_substr(CNT_CONTRACTSCOPESO, '^(\\w+)[-_]', 1, 1, 'ie') = mapping.BU_SOURCE_KEY
    WHERE OPTIONSET_METADATA.LOCALIZEDLABELLANGUAGECODE = '1033'
    GROUP BY CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER
),
CRM_USER AS (
    SELECT
    	CRM.SYSTEMUSERID AS SYSTEMUSERID,
        CRM.EMPLOYEEID AS  EMPLOYEEID,
        CONCAT(crm.LASTNAME, ', ', crm.FIRSTNAME) AS FULLNAME_crm,
        CONCAT(tea.LASTNAME, ', ', tea.FIRSTNAME) AS FULLNAME_tea,
        COALESCE(FULLNAME_tea, FULLNAME_crm) AS FULLNAME
    FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_SYSTEMUSER') }} crm
    LEFT JOIN {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__TEACOMMON_EMPLOYEE') }} tea
    on crm.employeeid = tea.employeeid
),
CRM_ACCOUNT AS (
    SELECT
        CSD.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
        ,LISTAGG(DISTINCT ACC.ACCOUNTNUMBER, ', ') AS COVERED_FAB
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__CONTRACT_SUMMARY_DETAILS') }} CSD
    LEFT OUTER JOIN {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_CNT_CNT_CONTRACTSUMMARY_ACCOUNT_FAB') }} AF
    ON AF.CNT_CONTRACTSUMMARYID = CSD.ID_CONTRACT_SUMMARY
    LEFT OUTER JOIN {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_ACCOUNT') }} ACC
    ON ACC.ID = AF.ACCOUNTID
    group by all
),
CRM_HOURS AS (
    SELECT
        C.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER,
        sum(A.WO_DURATION_HR) AS CRM_HOURS
    FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_MSDYN_TIMEENTRY') }} AS A
    LEFT JOIN {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_MSDYN_WORKORDER') }} AS B
    ON A.WO_WORKORDERNO=B.ID
    LEFT JOIN {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_CNT_CONTRACTSUMMARY') }} AS C
    ON B.TEL_WO_CONTRACTGROUP=C.ID
    WHERE C.CNT_CONTRUCTNUMBER IS NOT NULL
    GROUP BY all
),
WORK_ORDERS AS (
    SELECT
        C.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT B.MSDYN_NAME, ', ') AS WORK_ORDER
    FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_MSDYN_WORKORDER') }} AS B
    LEFT JOIN {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_CNT_CONTRACTSUMMARY') }} AS C
    ON B.TEL_WO_CONTRACTGROUP=C.ID
    group by all
),
CRM_CONTRACT_AMOUNT AS (
	SELECT DISTINCT
		CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER,
		sum(CNT_CONTRACTPRICE) AS TOTAL_CONTRACT_CRM_AMOUNT
	FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__CONTRACT_SUMMARY_DETAILS') }}
    group by CNT_CONTRUCTNUMBER
),
CRM_AGGREEMENTS as (
    select
        CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT CONTRACT_SUMMARY_DETAILS.CNT_SOWNAMENAME, ', ') AS CONTRACT_TYPE_AGG,
        CASE
            WHEN CONTRACT_TYPE_AGG = '' THEN NULL
            WHEN CONTRACT_TYPE_AGG LIKE '%,%' THEN 'Comprehensive'
            ELSE CONTRACT_TYPE_AGG
        END AS CONTRACT_TYPE,
    from {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__CONTRACT_SUMMARY_DETAILS') }} AS CONTRACT_SUMMARY_DETAILS
    group by CONTRACT_NUMBER
),
CRM_CONTRACTS AS (
	SELECT
        CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER,
        CONTRACT_SUMMARY_DETAILS.CNT_PRODUCT AS BU,
        CONTRACT_SUMMARY_DETAILS.CNT_SUBJECT AS CONTRACT_TITLE,
        CONTRACT_SUMMARY_DETAILS.CNT_OFFICE_NAME AS FAB,
        CONCAT(CONTRACT_SUMMARY_DETAILS.CNT_PRODUCT, ' ', CNT_OFFICE_NAME) AS COVERED_CONFIGS,
        CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTTYPEDETAIL as CONTRACT_TYPE_DESC,
        CONTRACT_SUMMARY_DETAILS.CNT_ASSIGNEDSALES AS CONTRACTOWNERID,
        CONTRACT_SUMMARY_DETAILS.OWNERIDNAME AS CONTRACT_OWNER,
        CRM_CONTRACT_AMOUNT.TOTAL_CONTRACT_CRM_AMOUNT,
        CAST(CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTSTARTDATE AS DATE) AS CONTRACT_START_DATE,
        CAST(CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTENDDATE AS DATE) AS CONTRACT_END_DATE,
        CONTRACT_SUMMARY_DETAILS.CNT_ASSIGNEDSALESNAME AS CONTRACT_OWNER_CONTRACT_SUMMARY,
        CONTRACT_SUMMARY_DETAILS.CNT_ASSIGNEDSALESNAME AS SITE_SUPERVISOR_CONTRACT_SUMMARY,
        CONTRACT_SUMMARY_DETAILS.TEL_CNT_SUPERVISOR AS SITE_SUPERVISOR2,
        CONTRACT_SUMMARY_DETAILS.CNT_CONTRACT_STATUS AS CONTRACT_STATUS_CONTRACT_SUMMARY,
        coalesce(CONTRACT_SUMMARY_DETAILS.CNT_PRODUCT, CONTRACT_SCOPE.PRODUCTS) AS PRODUCT,
        WORK_ORDERS.WORK_ORDER,
        CRM_HOURS.CRM_HOURS,
        CONTRACT_SCOPE.CONTRACT_SCOPE_BY_PRODUCT,
        CONTRACT_SUMMARY_DETAILS.CNT_CUSOTMERNAME AS MAIN_FAB,
        CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTDOCNUMBER as BAAN_CONTRACT_NUMBER,
        CONTRACT_SUMMARY_DETAILS.CNT_ASSIGNEDSALES AS ACCOUNT_MANAGER,
        CONTRACT_SUMMARY_DETAILS.CNT_DESCRIPTION AS NOTES,
        CRM_INV_FREQUENCY.LOCALIZEDLABEL as INVOICE_FREQUENCY,
        CONTRACT_SUMMARY_DETAILS.CNT_AREAADMIN as CNT_AREAADMIN,
        CRM_AGGREEMENTS.CONTRACT_TYPE_AGG,
        CRM_AGGREEMENTS.CONTRACT_TYPE,
        CONTRACT_SUMMARY_DETAILS.OWNINGBUSINESSUNITNAME,
        CONTRACT_SUMMARY_DETAILS.CNT_CUSTOMERCODE5DIGITSNAME,
        CONTRACT_SUMMARY_DETAILS.CNT_CUSOTMER,
    FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_CNT_CONTRACTSUMMARY') }} AS CONTRACT_SUMMARY_DETAILS
        LEFT JOIN CRM_HOURS
            ON CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER=CRM_HOURS.CONTRACT_NUMBER
        LEFT JOIN CONTRACT_SCOPE
            ON CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER=CONTRACT_SCOPE.CONTRACT_NUMBER
        LEFT JOIN CRM_CONTRACT_AMOUNT
            ON CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER=CRM_CONTRACT_AMOUNT.CONTRACT_NUMBER
        LEFT JOIN WORK_ORDERS
            ON CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER=WORK_ORDERS.CONTRACT_NUMBER
        LEFT JOIN CRM_OPTIONSET_CONTRACT_STATUS as CRM_CONTRACT_STATUS
            ON try_to_number(CONTRACT_SUMMARY_DETAILS.CNT_CONTRACT_STATUS)=try_to_number(CRM_CONTRACT_STATUS.OPTION)
        LEFT JOIN CRM_OPTIONSET_INV_FREQUENCY AS CRM_INV_FREQUENCY
            ON try_to_number(CONTRACT_SUMMARY_DETAILS.CNT_INVOICEFREQUENCY)=try_to_number(CRM_INV_FREQUENCY.OPTION)
        LEFT JOIN CRM_AGGREEMENTS
            ON CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER = CRM_AGGREEMENTS.CONTRACT_NUMBER
    WHERE CNT_REGIONNAME LIKE '%US%'
),
CRM_POS AS (
    SELECT
        CNT_CONTRUCTNUMBER,
        LISTAGG(DISTINCT CNT_REALORDERNUMBER, ', ') AS PO_NUMBER
    FROM  {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__CONTRACT_SUMMARY_PURCHASE_ORDER_DETAILS') }}
    GROUP BY CNT_CONTRUCTNUMBER
),

--SAP SALES ORDER
SO_ZSC1 AS (
    SELECT
        VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT VBAK_SALES_DOCUMENT, ', ') WITHIN GROUP (ORDER BY VBAK_SALES_DOCUMENT) AS ZSC1_SALES_ORDER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZSC1')
    GROUP BY VBAK_CONTRACT_NUMBER
),
SO_ZC10 AS (
    SELECT
        VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT VBAK_SALES_DOCUMENT, ', ') AS ZC10_SALES_ORDER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZC10')
    GROUP BY VBAK_CONTRACT_NUMBER
),
SO_ZC11 AS (
    SELECT
        VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT VBAK_SALES_DOCUMENT, ', ') AS ZC11_SALES_ORDER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZC11')
    GROUP BY VBAK_CONTRACT_NUMBER
),
SO_ZC12 AS (
    SELECT
        VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT VBAK_SALES_DOCUMENT, ', ') AS ZC12_SALES_ORDER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZC12')
    GROUP BY VBAK_CONTRACT_NUMBER
),
SO_ZSC0 AS (
    SELECT
        VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT VBAK_SALES_DOCUMENT, ', ') AS ZSC0_SALES_ORDER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZSC0')
    GROUP BY VBAK_CONTRACT_NUMBER
),
SO_ZS10 AS (
    SELECT
        VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
        LISTAGG(DISTINCT VBAK_SALES_DOCUMENT, ', ') AS ZS10_SALES_ORDER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZS10')
    GROUP BY VBAK_CONTRACT_NUMBER
),
--SAP CONTRACT TOTAL AMOUNT
CONTRACT_AMOUNT AS (
	SELECT DISTINCT
		VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
		SUM(NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY) AS TOTAL_CONTRACT_SAP_AMOUNT
	FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }}
	WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZSC1')
    GROUP BY VBAK_CONTRACT_NUMBER
),
--SAP PURCHASE ORDER
PO_ZC11 as (
    SELECT
    CONTRACT_NUMBER
    ,LISTAGG(DISTINCT VBAK_CUSTOMER_REFERENCE,', ') AS PO_NUMBER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_PLAN') }}
    WHERE LEFT(CONTRACT_NUMBER,1) = 'T'
    AND SALES_ORGANIZATION = '3200'
    AND SALES_DOCUMENT_TYPE = 'ZC11'
    AND LEFT(CONTRACT_NUMBER,1) = 'T'
    GROUP BY CONTRACT_NUMBER
),
--SAP COVERED CUSTOMER CODE
CUSTOMER_CONTRACT AS (
    SELECT DISTINCT
    SOBP.CONTRACT_NUMBER,
    CUSTOMER.CUSTOMER_NUMBER,
    SOBP.SOLD_TO_PARTY AS CUSTOMER_CODE,
    CUSTOMER.CUSTOMER_A_NAME as CUSTOMER_NAME,
    CUSTOMER.CUSTOMER_NAME_B AS CUSTOMER_NAME_B,
    CUSTOMER.CORPORATION AS CORPORATION,
    CUSTOMER.CUSTOMER_GROUP AS CUSTOMER_GROUP,
    CUSTOMER.CUSTOMER_GROUP2 AS CUSTOMER_GROUP2
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_PLAN') }} AS SOBP
    LEFT JOIN CUSTOMER
    ON SOBP.SOLD_TO_PARTY = CUSTOMER.CUSTOMER_NUMBER
    WHERE SALES_DOCUMENT_TYPE IN ('ZC11')
),
--SAP NON BILL CONTRACT
CUSTOMER_NOBILLCONTRACT AS (
    SELECT DISTINCT
    SOM.CONTRACT_NUMBER,
    CUSTOMER.CUSTOMER_NUMBER,
    SOM.SOLD_TO_PARTY_CODE AS CUSTOMER_CODE,
    CUSTOMER.CUSTOMER_A_NAME as CUSTOMER_NAME,
    CUSTOMER.CUSTOMER_NAME_B AS CUSTOMER_NAME_B,
    CUSTOMER.CORPORATION AS CORPORATION,
    CUSTOMER.CUSTOMER_GROUP AS CUSTOMER_GROUP,
    CUSTOMER.CUSTOMER_GROUP2 AS CUSTOMER_GROUP2,
    SALES_DOC_TYPE as SALES_DOCUMENT_TYPE
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_MASTER') }} AS SOM
    LEFT JOIN CUSTOMER
    ON SOM.SOLD_TO_PARTY_CODE = CUSTOMER.CUSTOMER_NUMBER
    WHERE SALES_DOCUMENT_TYPE IN ('ZSC0')
),

--CONSOLIDATE SAP DATA
SOBL AS (
    SELECT
         SOBL.VBAK_SALES_ORGANIZATION AS SALES_ORGANIZATION
        , SOBL.VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER
        , SOSL.ORDER_NUMBER AS SAP_SERVICE_ORDER
        , SOBL.VBAK_SALES_DOCUMENT
        , SOBL.VBAK_SALES_DOCUMENT_TYPE AS SALES_DOCUMENT_TYPE
        , CONTRACT_AMOUNT.TOTAL_CONTRACT_SAP_AMOUNT
        , SO_ZSC1.ZSC1_SALES_ORDER
        , SO_ZC10.ZC10_SALES_ORDER
        , SO_ZC11.ZC11_SALES_ORDER
        , SO_ZC12.ZC12_SALES_ORDER
        , SO_ZSC0.ZSC0_SALES_ORDER
        , SO_ZS10.ZS10_SALES_ORDER
        , COALESCE(CUSTOMER_CONTRACT.CUSTOMER_CODE, CUSTOMER_NOBILLCONTRACT.CUSTOMER_CODE) AS CUSTOMER_CODE
        , COALESCE(CUSTOMER_CONTRACT.CUSTOMER_NAME,CUSTOMER_NOBILLCONTRACT.CUSTOMER_NAME) AS CUSTOMER_NAME
        , COALESCE(CUSTOMER_CONTRACT.CUSTOMER_NAME_B, CUSTOMER_NOBILLCONTRACT.CUSTOMER_NAME_B) AS CUSTOMER_NAME_B
        , COALESCE(CUSTOMER_CONTRACT.CORPORATION, CUSTOMER_NOBILLCONTRACT.CORPORATION) AS CORPORATION
        , COALESCE(CUSTOMER_CONTRACT.CUSTOMER_GROUP, CUSTOMER_NOBILLCONTRACT.CUSTOMER_GROUP) AS CUSTOMER_GROUP
        , COALESCE(CUSTOMER_CONTRACT.CUSTOMER_GROUP2, CUSTOMER_NOBILLCONTRACT.CUSTOMER_GROUP2) AS CUSTOMER_GROUP2
        , PO_ZC11.PO_NUMBER
    FROM {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_LINE') }} AS SOBL
        LEFT JOIN {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_SCHEDULE_LINE') }} AS SOSL
            ON SOBL.VBAK_SALES_DOCUMENT=SOSL.VBAK_SALES_DOCUMENT
            AND SOBL.SALES_DOCUMENT_ITEM_POSNR=SOSL.SALES_DOCUMENT_ITEM_POSNR
        LEFT JOIN {{ ref('SILVER__TMEA_PRODUCT_SUPPORT_GROUP__SALES_ORDER_BILLING_PLAN') }} AS SOBP
            ON SOBP.VBAP_SALES_DOCUMENT=SOBL.VBAP_SALES_DOCUMENT
            AND SOBP.SALES_DOCUMENT_ITEM_POSNR=SOBL.SALES_DOCUMENT_ITEM_POSNR
            AND SOBP.CONTRACT_NUMBER = SOBL.VBAK_CONTRACT_NUMBER
        LEFT JOIN CUSTOMER_CONTRACT
            ON SOBL.VBAK_CONTRACT_NUMBER = CUSTOMER_CONTRACT.CONTRACT_NUMBER
        LEFT JOIN SO_ZSC1
            ON SOBL.VBAK_CONTRACT_NUMBER=SO_ZSC1.CONTRACT_NUMBER
        LEFT JOIN SO_ZC10
            ON SOBL.VBAK_CONTRACT_NUMBER=SO_ZC10.CONTRACT_NUMBER
        LEFT JOIN SO_ZC11
            ON SOBL.VBAK_CONTRACT_NUMBER=SO_ZC11.CONTRACT_NUMBER
        LEFT JOIN SO_ZC12
            ON SOBL.VBAK_CONTRACT_NUMBER=SO_ZC12.CONTRACT_NUMBER
        LEFT JOIN SO_ZSC0
            ON SOBL.VBAK_CONTRACT_NUMBER=SO_ZSC0.CONTRACT_NUMBER
        LEFT JOIN SO_ZS10
            ON SOBL.VBAK_CONTRACT_NUMBER=SO_ZS10.CONTRACT_NUMBER
        LEFT JOIN PO_ZC11
            ON SOBL.VBAK_CONTRACT_NUMBER=PO_ZC11.CONTRACT_NUMBER
        LEFT JOIN CONTRACT_AMOUNT
            ON SOBL.VBAK_CONTRACT_NUMBER = CONTRACT_AMOUNT.CONTRACT_NUMBER
        LEFT JOIN CUSTOMER_NOBILLCONTRACT
            ON SOBL.VBAK_CONTRACT_NUMBER = CUSTOMER_NOBILLCONTRACT.CONTRACT_NUMBER
    WHERE SOBL.VBAK_SALES_ORGANIZATION = '3200'

),
final_data AS (
    SELECT DISTINCT
        coalesce(SOBL.CONTRACT_NUMBER, CRM_CONTRACTS.CONTRACT_NUMBER) AS CONTRACT_NUMBER
        , CRM_CONTRACTS.PRODUCT AS PRODUCT
        , USER_AM.FULLNAME AS CONTRACT_OWNER
        , USER_AM.EMPLOYEEID AS CONTRACT_OWNER_ID
        , COALESCE(CAST(TRY_TO_NUMBER(LEFT(REPLACE(CONTRACT_TITLE,',',''),POSITION('hrs',lower(REPLACE(CONTRACT_TITLE,',','')))-1)) AS NUMERIC(38,10)),
                CAST(TRY_TO_NUMBER(LEFT(REPLACE(CONTRACT_TITLE,',',''),POSITION('hrs.',lower(REPLACE(CONTRACT_TITLE,',','')))-1)) AS NUMERIC(38,10)))
        AS COVERED_HOURS
        , CRM_CONTRACTS.CONTRACT_TITLE AS CONTRACT_TITLE
        , CRM_CONTRACTS.CONTRACT_SCOPE_BY_PRODUCT
        , CRM_CONTRACTS.CONTRACT_START_DATE as CONTRACT_START_DATE
        , CRM_CONTRACTS.CONTRACT_END_DATE AS CONTRACT_END_DATE
        , CRM_CONTRACTS.TOTAL_CONTRACT_CRM_AMOUNT
        , SOBL.TOTAL_CONTRACT_SAP_AMOUNT
        -- , SOBL.CUSTOMER_NAME
        -- , SOBL.CUSTOMER_NAME_B
        -- , SOBL.CORPORATION
        -- , SOBL.CUSTOMER_GROUP
        -- , SOBL.CUSTOMER_GROUP2
        -- , SOBL.CUSTOMER_CODE
        , ACCOUNT.PARENTACCOUNTIDNAME AS CUSTOMER_NAME
        , SOBL.CUSTOMER_NAME_B
        , SOBL.CORPORATION
        , CGM.CUSTOMER_GROUP
        , CGM.CUSTOMER_GROUP2
        , ACCOUNT.ACCOUNTNUMBER as CUSTOMER_CODE
        , FAB.COVERED_FAB AS COVERED_FAB
        , CALENDAR_CS.YEAR_MONTH_TEXT AS CONTRACT_START_YYYY_MM
        , CALENDAR_CS.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS CONTRACT_START_FISCAL_HALF
        , USER_AM.FULLNAME AS SITE_SUPERVISOR
        , USER_AM.EMPLOYEEID AS SITE_SUPERVISOR_ID
        , CRM_CONTRACTS.CRM_HOURS
        , CRM_CONTRACTS.WORK_ORDER
        , CRM_CONTRACTS.MAIN_FAB
        , CRM_CONTRACTS.BAAN_CONTRACT_NUMBER
        , CRM_CONTRACTS.INVOICE_FREQUENCY AS INSTALLMENT_TIMING
        , CRM_CONTRACTS.NOTES
        , CRM_CONTRACTS.CONTRACT_TYPE_DESC AS QUOTE_RENEWAL_NO
        , CRM_CONTRACTS.CONTRACT_TYPE
        , CRM_CONTRACT_STATUS.LOCALIZEDLABEL AS CONTRACT_STATUS
        , SOBL.ZSC1_SALES_ORDER
        , SOBL.ZC10_SALES_ORDER
        , SOBL.ZC11_SALES_ORDER
        , SOBL.ZC12_SALES_ORDER
        , SOBL.ZSC0_SALES_ORDER
        , SOBL.ZS10_SALES_ORDER
        -- , SOBL.PO_NUMBER
        , CRM_POS.PO_NUMBER
        , USER_MANAGED_BY.FULLNAME_crm AS MANAGED_BY
        , SOBL.CONTRACT_NUMBER is not null AS IN_SAP
        , CRM_CONTRACTS.CONTRACT_NUMBER is not null AS IN_CRM
    FROM CRM_CONTRACTS
    FULL JOIN SOBL
        ON SOBL.CONTRACT_NUMBER = CRM_CONTRACTS.CONTRACT_NUMBER
    LEFT JOIN CRM_USER AS USER_AM
        ON lower(CRM_CONTRACTS.ACCOUNT_MANAGER) = lower(USER_AM.systemuserid)
    LEFT JOIN CRM_USER AS USER_MANAGED_BY
        ON lower(CRM_CONTRACTS.CNT_AREAADMIN) = lower(USER_MANAGED_BY.systemuserid)
    LEFT JOIN CRM_ACCOUNT AS FAB
        ON CRM_CONTRACTS.CONTRACT_NUMBER = FAB.CONTRACT_NUMBER
    LEFT JOIN CONTRACT_SCOPE AS CS
        ON CRM_CONTRACTS.CONTRACT_NUMBER = CS.CONTRACT_NUMBER
    LEFT JOIN CRM_OPTIONSET_CONTRACT_STATUS as CRM_CONTRACT_STATUS
        ON CRM_CONTRACTS.CONTRACT_STATUS_CONTRACT_SUMMARY=CRM_CONTRACT_STATUS.OPTION
    LEFT JOIN CALENDARDATE AS CALENDAR_CS
        ON CRM_CONTRACTS.CONTRACT_START_DATE = CALENDAR_CS.CALENDAR_DATE
    LEFT JOIN {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__CRM_FILE_ACCOUNT') }} ACCOUNT
        ON ACCOUNT.ID = CRM_CONTRACTS.CNT_CUSOTMER
    LEFT OUTER JOIN CGM
        ON ACCOUNT.ACCOUNTNUMBER = CGM.ACCOUNT_NUMBER
    LEFT JOIN CRM_POS
        ON CRM_CONTRACTS.CONTRACT_NUMBER = CRM_POS.CNT_CONTRUCTNUMBER
    WHERE 1=1
        AND (SOBL.SALES_ORGANIZATION = '3200' or (not IN_SAP and CRM_CONTRACTS.OWNINGBUSINESSUNITNAME = 'US'))
        AND coalesce(SOBL.CONTRACT_NUMBER, CRM_CONTRACTS.CONTRACT_NUMBER) <> ''

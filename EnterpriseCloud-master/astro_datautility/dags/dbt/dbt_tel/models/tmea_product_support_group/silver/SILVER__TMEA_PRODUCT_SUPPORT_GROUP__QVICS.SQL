{{ config(
        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='QVICS'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	USEFULPOINT AS USEFULPOINT,
	CREATEDAT AS CREATEDAT,
	CREATEDBY AS CREATEDBY,
	CREATEDBYNAME AS CREATEDBYNAME,
	UPDATEDAT AS UPDATEDAT,
	UPDATEDBY AS UPDATEDBY,
	UPDATEDBYNAME AS UPDATEDBYNAME,
	DELETEDAT AS DELETEDAT,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__QVICS_C_TMEA_QVICS') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__QVICS_C_TMEA_QVICS') }})
    )
    ,transform_data as
    (
    SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	_FILEDATE,
	_FILENAME,
	ID,
	USEFULPOINT,
	CREATEDAT,
	CREATEDBY,
	CREATEDBYNAME,
	UPDATEDAT,
	UPDATEDBY,
	UPDATEDBYNAME,
	DELETEDAT
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	ID,
	USEFULPOINT,
	CREATEDAT,
	CREATEDBY,
	CREATEDBYNAME,
	UPDATEDAT,
	UPDATEDBY,
	UPDATEDBYNAME,
	DELETEDAT
 from transform_data 
)
SELECT * from type_data
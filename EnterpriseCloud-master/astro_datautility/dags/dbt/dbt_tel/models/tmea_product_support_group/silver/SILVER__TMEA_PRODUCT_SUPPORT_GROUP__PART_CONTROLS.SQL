	ARRIVALDATE,
	NOTES,
	CREATEDAT,
	UPDATEDAT,
	PARTDISPOSAL,
	DISPOSALDATE,
	PARTARCHIVEDEPARTMENT
 from transform_data 
)
SELECT * from type_data
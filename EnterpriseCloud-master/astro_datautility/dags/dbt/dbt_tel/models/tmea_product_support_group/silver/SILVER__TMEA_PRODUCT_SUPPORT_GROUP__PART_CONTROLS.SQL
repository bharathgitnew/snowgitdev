        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='PART_CONTROLS'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	PARTID AS PARTID,
	REGISTEREDAT AS REGISTEREDAT,
	SENDINGCHARGEPERSON AS SENDINGCHARGEPERSON,
	SENDINGCHARGEPERSONNAME AS SENDINGCHARGEPERSONNAME,
	SHIPPINGCHARGEPERSON AS SHIPPINGCHARGEPERSON,
	SHIPPINGCHARGEPERSONNAME AS SHIPPINGCHARGEPERSONNAME,
	SHIPPINGADDRESS AS SHIPPINGADDRESS,
	SHIPPINGMETHOD AS SHIPPINGMETHOD,
	SHIPPINGSCHEDULEDATE AS SHIPPINGSCHEDULEDATE,
	ARRIVALDATE AS ARRIVALDATE,
	NOTES AS NOTES,
	CREATEDAT AS CREATEDAT,
	UPDATEDAT AS UPDATEDAT,
	PARTDISPOSAL AS PARTDISPOSAL,
	DISPOSALDATE AS DISPOSALDATE,
	PARTARCHIVEDEPARTMENT AS PARTARCHIVEDEPARTMENT,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__QVICS_C_TMEA_PART_CONTROLS') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__QVICS_C_TMEA_PART_CONTROLS') }})
    )
    ,transform_data as
    (
    SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	_FILEDATE,
	_FILENAME,
	ID,
	PARTID,
	REGISTEREDAT,
	SENDINGCHARGEPERSON,
	SENDINGCHARGEPERSONNAME,
	SHIPPINGCHARGEPERSON,

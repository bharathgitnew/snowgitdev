        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='EmergentMeasures'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	TROUBLEID AS TROUBLEID,
	CAUSEIDENTIFICATIONDATE AS CAUSEIDENTIFICATIONDATE,
	EXECUTIONDATE AS EXECUTIONDATE,
	MEASURES AS MEASURES,
	MEASURES_NOTAG AS MEASURES_NOTAG,
	ROOTCAUSE AS ROOTCAUSE,
	ROOTCAUSE_NOTAG AS ROOTCAUSE_NOTAG,
	COUNTERMEASURE AS COUNTERMEASURE,
	COUNTERMEASURE_NOTAG AS COUNTERMEASURE_NOTAG,
	CLAIMSURVEYDEMANDID AS CLAIMSURVEYDEMANDID,
	INFORMATIONDEVELOPMENTID AS INFORMATIONDEVELOPMENTID,
	CLAIMFROMCUSTOMER AS CLAIMFROMCUSTOMER,
	CLAIMFROMCUSTOMER_NOTAG AS CLAIMFROMCUSTOMER_NOTAG,
	ISREPORTNECESSITY AS ISREPORTNECESSITY,
	ISNEEDDESIREDDEADLINE AS ISNEEDDESIREDDEADLINE,
	DESIREDDELIVERYDATE AS DESIREDDELIVERYDATE,
	ANSWERLANGUAGE AS ANSWERLANGUAGE,
	CREATEDAT AS CREATEDAT,
	UPDATEDAT AS UPDATEDAT,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__QVICS_EMERGENTMEASURES') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_PRODUCT_SUPPORT_GROUP__QVICS_EMERGENTMEASURES') }})
    )
    ,transform_data as
    (
    SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	_FILEDATE,
	_FILENAME,
	ID,
	TROUBLEID,
	CAUSEIDENTIFICATIONDATE,
	EXECUTIONDATE,
	MEASURES,
	MEASURES_NOTAG,
	ROOTCAUSE,
	ROOTCAUSE_NOTAG,
	COUNTERMEASURE,
	COUNTERMEASURE_NOTAG,
	CLAIMSURVEYDEMANDID,
	INFORMATIONDEVELOPMENTID,
	CLAIMFROMCUSTOMER,
	CLAIMFROMCUSTOMER_NOTAG,
	ISREPORTNECESSITY,
	ISNEEDDESIREDDEADLINE,
	DESIREDDELIVERYDATE,
	ANSWERLANGUAGE,
	CREATEDAT,
	UPDATEDAT
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	ID,
	TROUBLEID,
	CAUSEIDENTIFICATIONDATE,
	EXECUTIONDATE,
	MEASURES,
	MEASURES_NOTAG,
	ROOTCAUSE,
	ROOTCAUSE_NOTAG,
	COUNTERMEASURE,
	COUNTERMEASURE_NOTAG,
	CLAIMSURVEYDEMANDID,
	INFORMATIONDEVELOPMENTID,
	CLAIMFROMCUSTOMER,
	CLAIMFROMCUSTOMER_NOTAG,
	ISREPORTNECESSITY,
	ISNEEDDESIREDDEADLINE,
	DESIREDDELIVERYDATE,
	ANSWERLANGUAGE,
	CREATEDAT,
	UPDATEDAT
 from transform_data 
)
SELECT * from type_data
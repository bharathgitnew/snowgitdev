	materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
	alias='SUPPLIER_QUALITY_NOTIFICATIONS',
	transient=false
) }}


WITH ref_cte_QUALITY_NOTIFICATION as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__QUALITY_NOTIFICATION') }}
),
ref_cte_VENDOR_MASTER as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__VENDOR_MASTER') }}
),
P3 AS(
SELECT
'PHASE_3' AS PHASE,
QMEL.NOTIFICATION_NO AS QUALITY_NOTIFICATIONS,
QMEL.NOTIFICATION_TYPE,
QMEL.CODE_GROUP_CODING,
QMEL.DEFECTIVE_QUANTITY_INTERNAL AS REJECT_QTY,
QMEL.DEFECTIVE_QUANTITY_INTERNAL,
QMEL.COMPLAINT_QUANTITY,
QMEL.MATERIAL_NUMBER,
QMEL.vendor_account_number AS SUPPLIER_NUMBER,
LFA1.name_1 AS SUPPLIER,
QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED,
QMEL.NUMBER_OF_MATERIAL_DOCUMENT,
QMEL.PURCHASING_DOCUMENT_NUMBER,
QMEL.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
JOIN ref_cte_VENDOR_MASTER    LFA1 ON QMEL.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
and CODE_GROUP_CODING = 'SUPPLIER'
AND (QMEL.NOTIFICATION_TYPE = 'Q1' or QMEL.NOTIFICATION_TYPE = 'VF' or QMEL.NOTIFICATION_TYPE = 'F2')
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED >= '2024-04-01'
),
P2 AS(
SELECT
'PHASE_2' AS PHASE,
QMEL.NOTIFICATION_NO AS QUALITY_NOTIFICATIONS,
QMEL.NOTIFICATION_TYPE,
QMEL.CODE_GROUP_CODING,
QMEL.COMPLAINT_QUANTITY AS REJECT_QTY,
QMEL.DEFECTIVE_QUANTITY_INTERNAL,
QMEL.COMPLAINT_QUANTITY,
QMEL.MATERIAL_NUMBER,
QMEL.vendor_account_number AS SUPPLIER_NUMBER,
LFA1.name_1 AS SUPPLIER,
QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED,
QMEL.NUMBER_OF_MATERIAL_DOCUMENT,
QMEL.PURCHASING_DOCUMENT_NUMBER,
QMEL.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
JOIN ref_cte_VENDOR_MASTER   LFA1 ON QMEL.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
and CODE_GROUP_CODING = 'SUPPLIER'
AND (QMEL.NOTIFICATION_TYPE = 'Q1' or QMEL.NOTIFICATION_TYPE = 'VF' or QMEL.NOTIFICATION_TYPE = 'F2')
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED BETWEEN '2023-04-01' AND '2024-03-31'
),
P1 AS (
SELECT 
'PHASE_1' AS PHASE,
QMEL.NOTIFICATION_NO AS QUALITY_NOTIFICATIONS,
QMEL.NOTIFICATION_TYPE,
QMEL.CODE_GROUP_CODING,
QMEL.COMPLAINT_QUANTITY AS REJECT_QTY,
QMEL.DEFECTIVE_QUANTITY_INTERNAL,
QMEL.COMPLAINT_QUANTITY,
QMEL.MATERIAL_NUMBER,
QMEL.vendor_account_number AS SUPPLIER_NUMBER,
LFA1.name_1 AS SUPPLIER,
QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED,
QMEL.NUMBER_OF_MATERIAL_DOCUMENT,
QMEL.PURCHASING_DOCUMENT_NUMBER,
QMEL.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
FROM ref_cte_QUALITY_NOTIFICATION    QMEL
JOIN ref_cte_VENDOR_MASTER    LFA1 ON QMEL.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE QMEL.CLIENT = '300'
AND QMEL.PLANT_FOR_MATERIAL = '0010'
and CODE_GROUP_CODING = 'SUPPLIER'
AND QMEL.NOTIFICATION_TYPE = 'Q6'
AND QMEL.DATE_ON_WHICH_RECORD_WAS_CREATED < '2023-04-01'
),
SOURCE AS (
SELECT * FROM P1
UNION ALL 
SELECT * FROM P2
UNION ALL 
SELECT * FROM P3
),
source_data as (
SELECT 
	PHASE,
	QUALITY_NOTIFICATIONS,
	NOTIFICATION_TYPE,
	CODE_GROUP_CODING,
	REJECT_QTY,
	DEFECTIVE_QUANTITY_INTERNAL,
	COMPLAINT_QUANTITY,
	SOURCE.MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	SUPPLIER_NUMBER,
	SUPPLIER,
	DATE_ON_WHICH_RECORD_WAS_CREATED,
	NUMBER_OF_MATERIAL_DOCUMENT,
	PURCHASING_DOCUMENT_NUMBER,
	ITEM_NUMBER_OF_PURCHASING_DOCUMENT
FROM SOURCE
LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__MATERIAL_DESCRIPTIONS') }}  MAKT
    ON MAKT.MATERIAL_NUMBER = SOURCE.MATERIAL_NUMBER
WHERE CODE_GROUP_CODING = 'SUPPLIER'
ORDER BY DATE_ON_WHICH_RECORD_WAS_CREATED DESC
),
transform_data as(
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	PHASE,
	QUALITY_NOTIFICATIONS,
	NOTIFICATION_TYPE,
	CODE_GROUP_CODING,
	REJECT_QTY,
	DEFECTIVE_QUANTITY_INTERNAL,
	COMPLAINT_QUANTITY,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	SUPPLIER_NUMBER,
	SUPPLIER,
	DATE_ON_WHICH_RECORD_WAS_CREATED,
	NUMBER_OF_MATERIAL_DOCUMENT,
	PURCHASING_DOCUMENT_NUMBER,
	ITEM_NUMBER_OF_PURCHASING_DOCUMENT
FROM source_data
),
type_data as (
select 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	PHASE,
	QUALITY_NOTIFICATIONS,
	NOTIFICATION_TYPE,
	CODE_GROUP_CODING,
	REJECT_QTY,
	DEFECTIVE_QUANTITY_INTERNAL,
	COMPLAINT_QUANTITY,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	SUPPLIER_NUMBER,
	SUPPLIER,
	DATE_ON_WHICH_RECORD_WAS_CREATED,
	NUMBER_OF_MATERIAL_DOCUMENT,
	PURCHASING_DOCUMENT_NUMBER,
	ITEM_NUMBER_OF_PURCHASING_DOCUMENT
from transform_data
)
select * from type_data


{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='BOMS_ITEM_SELECTION',
    unique_key = ['CLIENT','BOM_CATEGORY','BILL_OF_MATERIAL','ALTERNATIVE_BOM','BOM_ITEM_NODE_NUMBER','INTERNAL_COUNTER'],
    transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		STLTY as BOM_CATEGORY,
		STLNR as BILL_OF_MATERIAL,
		STLAL as ALTERNATIVE_BOM,
		STLKN as BOM_ITEM_NODE_NUMBER,
		STASZ as INTERNAL_COUNTER,
		DATUV as VALID_FROM_DATE,
		TECHV as TECHNICAL_STATUS_FROM,
		AENNR as CHANGE_NUMBER,
		LKENZ as DELETION_INDICATOR,
		ANDAT as DATE_RECORD_CREATED_ON,
		ANNAM as USER_WHO_CREATED_RECORD,
		AEDAT as DATE_OF_LAST_CHANGE,
		AENAM as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		DVDAT as DATE_OF_LAST_DATE_SHIFT,
		DVNAM as NAME_OF_THE_USER_WHO_CARRIED_OUT_THE_DATE_SHIFT,
		AEHLP as DATE_SHIFT_HIERARCHY_INDICATOR,
		STVKN as INHERITED_NODE_NUMBER_OF_BOM_ITEM,
		IDPOS as ITEM_GROUP,
		IDVAR as COMPONENT_VARIANT,
		LPSRT as SORT_KEY_WITHIN_A_LOGICAL_ITEM,
		_CAPTUREDATETIME,
		IS_DELETED
    from {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_BOMS_ITEM_SELECTION') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        CLIENT,
		BOM_CATEGORY,
		BILL_OF_MATERIAL,
		ALTERNATIVE_BOM,
		BOM_ITEM_NODE_NUMBER,
		INTERNAL_COUNTER,
		TRY_TO_DATE(VALID_FROM_DATE, 'YYYYMMDD') as VALID_FROM_DATE,
		TECHNICAL_STATUS_FROM,
		CHANGE_NUMBER,
		DELETION_INDICATOR,
		TRY_TO_DATE(DATE_RECORD_CREATED_ON, 'YYYYMMDD') as DATE_RECORD_CREATED_ON,
		USER_WHO_CREATED_RECORD,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE, 'YYYYMMDD') as DATE_OF_LAST_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		TRY_TO_DATE(DATE_OF_LAST_DATE_SHIFT, 'YYYYMMDD') as DATE_OF_LAST_DATE_SHIFT,
		NAME_OF_THE_USER_WHO_CARRIED_OUT_THE_DATE_SHIFT,
		DATE_SHIFT_HIERARCHY_INDICATOR,
		INHERITED_NODE_NUMBER_OF_BOM_ITEM,
		ITEM_GROUP,
		COMPONENT_VARIANT,
		SORT_KEY_WITHIN_A_LOGICAL_ITEM,
		_CAPTUREDATETIME,
		IS_DELETED
    from source_data
),

type_data as (
    select
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		CLIENT,
		BOM_CATEGORY,
		BILL_OF_MATERIAL,
		ALTERNATIVE_BOM,
		BOM_ITEM_NODE_NUMBER,
		INTERNAL_COUNTER,
		cast(VALID_FROM_DATE as DATE) as VALID_FROM_DATE,
		TECHNICAL_STATUS_FROM,
		CHANGE_NUMBER,
		DELETION_INDICATOR,
		cast(DATE_RECORD_CREATED_ON as DATE) as DATE_RECORD_CREATED_ON,
		USER_WHO_CREATED_RECORD,
		cast(DATE_OF_LAST_CHANGE as DATE) as DATE_OF_LAST_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		cast(DATE_OF_LAST_DATE_SHIFT as DATE) as DATE_OF_LAST_DATE_SHIFT,
		NAME_OF_THE_USER_WHO_CARRIED_OUT_THE_DATE_SHIFT,
		DATE_SHIFT_HIERARCHY_INDICATOR,
		INHERITED_NODE_NUMBER_OF_BOM_ITEM,
		ITEM_GROUP,
		COMPONENT_VARIANT,
		SORT_KEY_WITHIN_A_LOGICAL_ITEM,
		IS_DELETED
    from transform_data
)
select * from type_data
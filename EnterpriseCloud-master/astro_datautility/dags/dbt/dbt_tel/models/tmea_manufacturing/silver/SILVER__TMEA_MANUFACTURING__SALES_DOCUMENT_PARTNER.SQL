{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='SALES_DOCUMENT_PARTNER',
        unique_key = ['CLIENT',
    'SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER',
    'ITEM_NUMBER_OF_THE_SD_DOCUMENT',
    'PARTNER_FUNCTION'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		VBELN as SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
		POSNR as ITEM_NUMBER_OF_THE_SD_DOCUMENT,
		PARVW as PARTNER_FUNCTION,
		KUNNR as CUSTOMER_NUMBER,
		LIFNR as ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		PERNR as PERSONNEL_NUMBER,
		PARNR as NUMBER_OF_CONTACT_PERSON,
		ADRNR as ADDRESS,
		ABLAD as UNLOADING_POINT,
		LAND1 as COUNTRY_KEY,
		ADRDA as ADDRESS_INDICATOR,
		XCPDK as INDICATOR_IS_THE_ACCOUNT_A_ONE_TIME_ACCOUNT,
		HITYP as CUSTOMER_HIERARCHY_TYPE,
		PRFRE as RELEVANT_FOR_PRICE_DETERMINATION_ID,
		BOKRE as INDICATOR_CUSTOMER_IS_REBATE_RELEVANT,
		HISTUNR as LEVEL_NUMBER_WITHIN_HIERARCHY,
		KNREF as CUSTOMER_DESCRIPTION_OF_PARTNER_PLANT_STORAGE_LOCATION,
		LZONE as TRANSPORTATION_ZONE_TO_OR_FROM_WHICH_THE_GOODS_ARE_DELIVERED,
		HZUOR as ASSIGNMENT_TO_HIERARCHY,
		STCEG as VAT_REGISTRATION_NUMBER,
		PARVW_FF as INDICATOR_FURTHER_PARTNERS_IN_THIS_FUNCTION_VBPA2,
		ADRNP as PERSON_NUMBER,
		KALE as MAINTAIN_APPOINTMENTS_IN_CALENDAR,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_SALES_DOCUMENT_PARTNER') }}
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
		ITEM_NUMBER_OF_THE_SD_DOCUMENT,
		PARTNER_FUNCTION,
		CUSTOMER_NUMBER,
		ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		PERSONNEL_NUMBER,
		NUMBER_OF_CONTACT_PERSON,
		ADDRESS,
		UNLOADING_POINT,
		COUNTRY_KEY,
		ADDRESS_INDICATOR,
		INDICATOR_IS_THE_ACCOUNT_A_ONE_TIME_ACCOUNT,
		CUSTOMER_HIERARCHY_TYPE,
		RELEVANT_FOR_PRICE_DETERMINATION_ID,
		INDICATOR_CUSTOMER_IS_REBATE_RELEVANT,
		LEVEL_NUMBER_WITHIN_HIERARCHY,
		CUSTOMER_DESCRIPTION_OF_PARTNER_PLANT_STORAGE_LOCATION,
		TRANSPORTATION_ZONE_TO_OR_FROM_WHICH_THE_GOODS_ARE_DELIVERED,
		ASSIGNMENT_TO_HIERARCHY,
		VAT_REGISTRATION_NUMBER,
		INDICATOR_FURTHER_PARTNERS_IN_THIS_FUNCTION_VBPA2,
		PERSON_NUMBER,
		MAINTAIN_APPOINTMENTS_IN_CALENDAR
    from source_data
),

type_data as (
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as VARCHAR) as SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
		cast(ITEM_NUMBER_OF_THE_SD_DOCUMENT as VARCHAR) as ITEM_NUMBER_OF_THE_SD_DOCUMENT,
		cast(PARTNER_FUNCTION as VARCHAR) as PARTNER_FUNCTION,
		cast(CUSTOMER_NUMBER as VARCHAR) as CUSTOMER_NUMBER,
		cast(ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR as VARCHAR) as ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		cast(PERSONNEL_NUMBER as VARCHAR) as PERSONNEL_NUMBER,
		cast(NUMBER_OF_CONTACT_PERSON as VARCHAR) as NUMBER_OF_CONTACT_PERSON,
		cast(ADDRESS as VARCHAR) as ADDRESS,
		cast(UNLOADING_POINT as VARCHAR) as UNLOADING_POINT,
		cast(COUNTRY_KEY as VARCHAR) as COUNTRY_KEY,
		cast(ADDRESS_INDICATOR as VARCHAR) as ADDRESS_INDICATOR,
		cast(INDICATOR_IS_THE_ACCOUNT_A_ONE_TIME_ACCOUNT as VARCHAR) as INDICATOR_IS_THE_ACCOUNT_A_ONE_TIME_ACCOUNT,
		cast(CUSTOMER_HIERARCHY_TYPE as VARCHAR) as CUSTOMER_HIERARCHY_TYPE,
		cast(RELEVANT_FOR_PRICE_DETERMINATION_ID as VARCHAR) as RELEVANT_FOR_PRICE_DETERMINATION_ID,
		cast(INDICATOR_CUSTOMER_IS_REBATE_RELEVANT as VARCHAR) as INDICATOR_CUSTOMER_IS_REBATE_RELEVANT,
		cast(LEVEL_NUMBER_WITHIN_HIERARCHY as VARCHAR) as LEVEL_NUMBER_WITHIN_HIERARCHY,
		cast(CUSTOMER_DESCRIPTION_OF_PARTNER_PLANT_STORAGE_LOCATION as VARCHAR) as CUSTOMER_DESCRIPTION_OF_PARTNER_PLANT_STORAGE_LOCATION,
		cast(TRANSPORTATION_ZONE_TO_OR_FROM_WHICH_THE_GOODS_ARE_DELIVERED as VARCHAR) as TRANSPORTATION_ZONE_TO_OR_FROM_WHICH_THE_GOODS_ARE_DELIVERED,
		cast(ASSIGNMENT_TO_HIERARCHY as VARCHAR) as ASSIGNMENT_TO_HIERARCHY,
		cast(VAT_REGISTRATION_NUMBER as VARCHAR) as VAT_REGISTRATION_NUMBER,
		cast(INDICATOR_FURTHER_PARTNERS_IN_THIS_FUNCTION_VBPA2 as VARCHAR) as INDICATOR_FURTHER_PARTNERS_IN_THIS_FUNCTION_VBPA2,
		cast(PERSON_NUMBER as VARCHAR) as PERSON_NUMBER,
		cast(MAINTAIN_APPOINTMENTS_IN_CALENDAR as VARCHAR) as MAINTAIN_APPOINTMENTS_IN_CALENDAR
    from transform_data
)
select * from type_data
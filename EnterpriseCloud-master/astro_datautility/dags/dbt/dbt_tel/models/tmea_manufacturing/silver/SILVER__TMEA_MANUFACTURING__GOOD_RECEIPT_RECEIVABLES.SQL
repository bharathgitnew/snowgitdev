WITH ref_cte_DOCUMENT_SEGMENT_MATERIAL as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__DOCUMENT_SEGMENT_MATERIAL') }}
),

ref_cte_INSPECTION_LOT_RECORD as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__INSPECTION_LOT_RECORD') }}
),

ref_cte_MATERIAL_DESCRIPTIONS as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__MATERIAL_DESCRIPTIONS') }}
),

ref_cte_VENDOR_MASTER as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__VENDOR_MASTER') }}
),



source_data as (

select 
MSEG.MATERIAL_NUMBER,
MAKT.MATERIAL_DESCRIPTION,
MSEG.PLANT,
MSEG.STORAGE_LOCATION,
MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
MSEG.POSTING_DATE_IN_THE_DOCUMENT,
MSEG.GOODS_RECEIPT_QUANTITY_IN_ORDER_UNIT AS GOODS_RECEIPT_QUANTITY,
MSEG.VENDOR_ACCOUNT_NUMBER AS SUPPLIER_NUMBER,
LFA1.NAME_1 AS SUPPLIER_NAME,
QALS.INSPECTION_LOT_NUMBER,
MSEG.NUMBER_OF_MATERIAL_DOCUMENT,
MSEG.ITEM_IN_MATERIAL_DOCUMENT,
MSEG.MATERIAL_DOCUMENT_YEAR
from ref_cte_document_segment_material    MSEG
LEFT JOIN ref_cte_MATERIAL_DESCRIPTIONS    MAKT ON MSEG.MATERIAL_NUMBER = MAKT.MATERIAL_NUMBER
LEFT JOIN ref_cte_INSPECTION_LOT_RECORD    QALS ON QALS.NUMBER_OF_MATERIAL_DOCUMENT = MSEG.NUMBER_OF_MATERIAL_DOCUMENT AND MSEG.MATERIAL_DOCUMENT_YEAR = QALS.MATERIAL_DOCUMENT_YEAR AND MSEG.CLIENT = QALS.CLIENT AND MSEG.ITEM_IN_MATERIAL_DOCUMENT = QALS.ITEM_IN_MATERIAL_DOCUMENT
JOIN ref_cte_VENDOR_MASTER    LFA1 ON MSEG.VENDOR_ACCOUNT_NUMBER = LFA1.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
WHERE MSEG.PLANT = '0010'
AND MSEG.POSTING_DATE_IN_THE_DOCUMENT >= '2021-03-01'
AND MSEG.STORAGE_LOCATION = '0010'
AND MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT = '101'
ORDER BY DATE_ON_WHICH_THE_DATA_RECORD_WAS_CREATED ASC),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	PLANT,
	STORAGE_LOCATION,
	MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
	POSTING_DATE_IN_THE_DOCUMENT,
	GOODS_RECEIPT_QUANTITY,
	SUPPLIER_NUMBER,
	SUPPLIER_NAME,
	INSPECTION_LOT_NUMBER,
	NUMBER_OF_MATERIAL_DOCUMENT,
	ITEM_IN_MATERIAL_DOCUMENT,
	MATERIAL_DOCUMENT_YEAR
from source_data
),

type_data as (
select
	cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
	cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
	CAST(MATERIAL_NUMBER as VARCHAR(16777216)) as MATERIAL_NUMBER,
	CAST(MATERIAL_DESCRIPTION as VARCHAR(16777216)) as MATERIAL_DESCRIPTION,
	CAST(PLANT as VARCHAR(16777216)) as PLANT,
	CAST(STORAGE_LOCATION as VARCHAR(16777216)) as STORAGE_LOCATION,
	CAST(MOVEMENT_TYPE_INVENTORY_MANAGEMENT as VARCHAR(16777216)) as MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
	CAST(POSTING_DATE_IN_THE_DOCUMENT as DATE) as POSTING_DATE_IN_THE_DOCUMENT,
	CAST(GOODS_RECEIPT_QUANTITY as NUMBER(38,10)) as GOODS_RECEIPT_QUANTITY,
	CAST(SUPPLIER_NUMBER as VARCHAR(16777216)) as SUPPLIER_NUMBER,
	CAST(SUPPLIER_NAME as VARCHAR(16777216)) as SUPPLIER_NAME,
	CAST(INSPECTION_LOT_NUMBER as VARCHAR(16777216)) as INSPECTION_LOT_NUMBER,
	CAST(NUMBER_OF_MATERIAL_DOCUMENT as VARCHAR(16777216)) as NUMBER_OF_MATERIAL_DOCUMENT,
	CAST(ITEM_IN_MATERIAL_DOCUMENT as VARCHAR(16777216)) as ITEM_IN_MATERIAL_DOCUMENT,
	CAST(MATERIAL_DOCUMENT_YEAR as VARCHAR(16777216)) as MATERIAL_DOCUMENT_YEAR
from transform_data 
)
select * from type_data
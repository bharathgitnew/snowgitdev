{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='MATERIAL_DATA_FOR_EACH_WAREHOUSE_NUMBER',
        unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		MATNR as MATERIAL_NUMBER,
		LGNUM as WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		LVORM as DELETION_FLAG_FOR_ALL_MATERIAL_DATA_OF_A_WAREHOUSE_NUMBER,
		LGBKZ as STORAGE_SECTION_INDICATORS,
		LTKZE as STORAGE_TYPE_INDICATOR_FOR_STOCK_PLACEMENT,
		LTKZA as STORAGE_TYPE_INDICATOR_FOR_STOCK_REMOVAL,
		LHMG1 as LOADING_EQUIPMENT_QUANTITY_1,
		LHMG2 as LOADING_EQUIPMENT_QUANTITY_2,
		LHMG3 as LOADING_EQUIPMENT_QUANTITY_3,
		LHME1 as UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_1,
		LHME2 as UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_2,
		LHME3 as UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_3,
		LETY1 as FIRST_STORAGE_UNIT_TYPE,
		LETY2 as SECOND_STORAGE_UNIT_TYPE,
		LETY3 as THIRD_STORAGE_UNIT_TYPE,
		LVSME as WAREHOUSE_MANAGEMENT_UNIT_OF_MEASURE,
		KZZUL as INDICATOR_ALLOW_ADDITION_TO_EXISTING_STOCK,
		BLOCK as BULK_STORAGE_INDICATOR,
		KZMBF as INDICATOR_MESSAGE_TO_INVENTORY_MANAGEMENT,
		BSSKZ as SPECIAL_MOVEMENT_INDICATOR_FOR_WAREHOUSE_MANAGEMENT,
		MKAPV as CAPACITY_USAGE,
		BEZME as UNIT_OF_MEASURE_FOR_CAPACITY_CONSUMPTION,
		PLKPT as PICKING_STORAGE_TYPE_FOR_ROUGH_CUT_AND_DETAILED_PLANNING,
		VOMEM as DEFAULT_FOR_UNIT_OF_MEASURE_FROM_MATERIAL_MASTER_RECORD,
		L2SKR as MATERIAL_RELEVANCE_FOR_2_STEP_PICKING,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_MATERIAL_DATA_FOR_EACH_WAREHOUSE_NUMBER') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		MATERIAL_NUMBER,
		WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		DELETION_FLAG_FOR_ALL_MATERIAL_DATA_OF_A_WAREHOUSE_NUMBER,
		STORAGE_SECTION_INDICATORS,
		STORAGE_TYPE_INDICATOR_FOR_STOCK_PLACEMENT,
		STORAGE_TYPE_INDICATOR_FOR_STOCK_REMOVAL,
		LOADING_EQUIPMENT_QUANTITY_1,
		LOADING_EQUIPMENT_QUANTITY_2,
		LOADING_EQUIPMENT_QUANTITY_3,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_1,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_2,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_3,
		FIRST_STORAGE_UNIT_TYPE,
		SECOND_STORAGE_UNIT_TYPE,
		THIRD_STORAGE_UNIT_TYPE,
		WAREHOUSE_MANAGEMENT_UNIT_OF_MEASURE,
		INDICATOR_ALLOW_ADDITION_TO_EXISTING_STOCK,
		BULK_STORAGE_INDICATOR,
		INDICATOR_MESSAGE_TO_INVENTORY_MANAGEMENT,
		SPECIAL_MOVEMENT_INDICATOR_FOR_WAREHOUSE_MANAGEMENT,
		CAPACITY_USAGE,
		UNIT_OF_MEASURE_FOR_CAPACITY_CONSUMPTION,
		PICKING_STORAGE_TYPE_FOR_ROUGH_CUT_AND_DETAILED_PLANNING,
		DEFAULT_FOR_UNIT_OF_MEASURE_FROM_MATERIAL_MASTER_RECORD,
		MATERIAL_RELEVANCE_FOR_2_STEP_PICKING
    from source_data
),

type_data as (
    select
		CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
		CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
		CLIENT,
		MATERIAL_NUMBER,
		WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		DELETION_FLAG_FOR_ALL_MATERIAL_DATA_OF_A_WAREHOUSE_NUMBER,
		STORAGE_SECTION_INDICATORS,
		STORAGE_TYPE_INDICATOR_FOR_STOCK_PLACEMENT,
		STORAGE_TYPE_INDICATOR_FOR_STOCK_REMOVAL,
		cast(LOADING_EQUIPMENT_QUANTITY_1 as NUMBER(38,10)) as LOADING_EQUIPMENT_QUANTITY_1,
		cast(LOADING_EQUIPMENT_QUANTITY_2 as NUMBER(38,10)) as LOADING_EQUIPMENT_QUANTITY_2,
		cast(LOADING_EQUIPMENT_QUANTITY_3 as NUMBER(38,10)) as LOADING_EQUIPMENT_QUANTITY_3,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_1,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_2,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_3,
		FIRST_STORAGE_UNIT_TYPE,
		SECOND_STORAGE_UNIT_TYPE,
		THIRD_STORAGE_UNIT_TYPE,
		WAREHOUSE_MANAGEMENT_UNIT_OF_MEASURE,
		INDICATOR_ALLOW_ADDITION_TO_EXISTING_STOCK,
		BULK_STORAGE_INDICATOR,
		INDICATOR_MESSAGE_TO_INVENTORY_MANAGEMENT,
		SPECIAL_MOVEMENT_INDICATOR_FOR_WAREHOUSE_MANAGEMENT,
		cast(CAPACITY_USAGE as NUMBER(38,10)) as CAPACITY_USAGE,
		UNIT_OF_MEASURE_FOR_CAPACITY_CONSUMPTION,
		PICKING_STORAGE_TYPE_FOR_ROUGH_CUT_AND_DETAILED_PLANNING,
		DEFAULT_FOR_UNIT_OF_MEASURE_FROM_MATERIAL_MASTER_RECORD,
		MATERIAL_RELEVANCE_FOR_2_STEP_PICKING
    from transform_data
)
select * from type_data
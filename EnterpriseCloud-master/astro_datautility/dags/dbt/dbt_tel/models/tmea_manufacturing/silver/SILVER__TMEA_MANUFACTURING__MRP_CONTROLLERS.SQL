{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='MRP_CONTROLLERS',
    unique_key = ['CLIENT',
    'PLANT',
    'MRP_CONTROLLER']
) }}

with source_data as
(
    SELECT
		MANDT  AS CLIENT ,
		WERKS  AS PLANT ,
		DISPO  AS MRP_CONTROLLER ,
		DSNAM  AS CONTROLLER_NAME ,
		DSTEL  AS TEL_NO_MRP_CONTRL ,
		EKGRP  AS PURCHASING_GROUP ,
		MEMPF  AS RECIPIENT_NAME ,
		GSBER  AS BUSINESS_AREA ,
		PRCTR  AS PROFIT_CENTER ,
		USRTYP AS RECIPIENT_TYPE ,
		USRKEY AS RECIPIENT ,
           _CAPTUREDATETIME	
        FROM {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_MRP_CONTROLLERS') }}
        
        )
,transform_data as
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
		CLIENT  AS CLIENT ,
		PLANT  AS PLANT ,
		MRP_CONTROLLER  AS MRP_CONTROLLER ,
		CONTROLLER_NAME  AS CONTROLLER_NAME ,
		TEL_NO_MRP_CONTRL  AS TEL_NO_MRP_CONTRL ,
		PURCHASING_GROUP  AS PURCHASING_GROUP ,
		RECIPIENT_NAME  AS RECIPIENT_NAME ,
		BUSINESS_AREA  AS BUSINESS_AREA ,
		PROFIT_CENTER  AS PROFIT_CENTER ,
		RECIPIENT_TYPE  AS RECIPIENT_TYPE ,
		RECIPIENT  AS RECIPIENT -- Adds column to table on full refresh.
        FROM source_data
        )
,type_data as 
(
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,	
		cast( CLIENT  AS VARCHAR(16777216))  AS CLIENT ,
		cast( PLANT  AS VARCHAR(16777216))  AS PLANT ,
		cast( MRP_CONTROLLER  AS VARCHAR(16777216))  AS MRP_CONTROLLER ,
		cast( CONTROLLER_NAME  AS VARCHAR(16777216))  AS CONTROLLER_NAME ,
		cast( TEL_NO_MRP_CONTRL  AS VARCHAR(16777216))  AS TEL_NO_MRP_CONTRL ,
		cast( PURCHASING_GROUP  AS VARCHAR(16777216))  AS PURCHASING_GROUP ,
		cast( RECIPIENT_NAME  AS VARCHAR(16777216))  AS RECIPIENT_NAME ,
		cast( BUSINESS_AREA  AS VARCHAR(16777216))  AS BUSINESS_AREA ,
		cast( PROFIT_CENTER  AS VARCHAR(16777216))  AS PROFIT_CENTER ,
		cast( RECIPIENT_TYPE  AS VARCHAR(16777216))  AS RECIPIENT_TYPE ,
		cast( RECIPIENT  AS VARCHAR(16777216))  AS RECIPIENT 
    from transform_data
    )
select * from type_data
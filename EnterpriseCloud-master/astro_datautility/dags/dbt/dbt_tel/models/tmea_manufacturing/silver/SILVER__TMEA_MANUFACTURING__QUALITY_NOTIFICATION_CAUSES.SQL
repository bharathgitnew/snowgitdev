{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='QUALITY_NOTIFICATION_CAUSES',
        unique_key = ['CLIENT',
    'NOTIFICATION_NO',
    'ITEM_NUMBER_IN_ITEM_RECORD',
    'SEQUENTIAL_NUMBER_FOR_CAUSE'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		QMNUM as NOTIFICATION_NO,
		FENUM as ITEM_NUMBER_IN_ITEM_RECORD,
		URNUM as SEQUENTIAL_NUMBER_FOR_CAUSE,
		ERNAM as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		ERDAT as DATE_ON_WHICH_RECORD_WAS_CREATED,
		AENAM as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		AEDAT as DATE_OF_LAST_CHANGE,
		URTXT as CAUSE_TEXT,
		URKAT as CATALOG_TYPE_CAUSES,
		URGRP as CODE_GROUP_CAUSES,
		URCOD as CAUSE_CODE,
		URVER as VERSION_NUMBER,
		INDTX as OBJECT_LONG_TEXT_AVAILABLE,
		KZMLA as PRIMARY_LANGUAGE_INDICATOR_FOR_TEXT_SEGMENT,
		ERZEIT as TIME_AT_WHICH_RECORD_WAS_ADDED,
		AEZEIT as TIME_OF_CHANGE,
		VUKAT as CATALOG_TYPE_PARTY_RESPONSIBLE,
		VUGRP as CODE_GROUP_PARTY_RESPONSIBLE,
		VUCOD as CODE_FOR_PARTY_RESPONSIBLE,
		PARVW as FUNCTION_FOR_PARTY_RESPONSIBLE,
		PARNR as PARTY_RESPONSIBLE_FOR_CAUSE_PARTNER_NUMBER,
		BAUTL as CAUSE_ASSEMBLY,
		URMENGE as QUANTITY,
		URMGEIN as UNIT_OF_MEASURE_FOR_ITEM,
		KZLOESCH as DELETE_DATA_RECORD,
		QURNUM as SORT_NUMBER_FOR_CAUSE,
		AUTKZ as DATA_RECORD_CREATED_WITH_FUNCTION_CREATE_WITH_COPY_MODEL,
		INVOLVPERC as INVOLVMENT_IN_PERCENTAGE,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_QUALITY_NOTIFICATION_CAUSES') }}
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		NOTIFICATION_NO,
		ITEM_NUMBER_IN_ITEM_RECORD,
		SEQUENTIAL_NUMBER_FOR_CAUSE,
		NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		TRY_TO_DATE(DATE_ON_WHICH_RECORD_WAS_CREATED, 'YYYYMMDD') as DATE_ON_WHICH_RECORD_WAS_CREATED,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE, 'YYYYMMDD') as DATE_OF_LAST_CHANGE,
		CAUSE_TEXT,
		CATALOG_TYPE_CAUSES,
		CODE_GROUP_CAUSES,
		CAUSE_CODE,
		VERSION_NUMBER,
		OBJECT_LONG_TEXT_AVAILABLE,
		PRIMARY_LANGUAGE_INDICATOR_FOR_TEXT_SEGMENT,
		TIME_AT_WHICH_RECORD_WAS_ADDED,
		TIME_OF_CHANGE,
		CATALOG_TYPE_PARTY_RESPONSIBLE,
		CODE_GROUP_PARTY_RESPONSIBLE,
		CODE_FOR_PARTY_RESPONSIBLE,
		FUNCTION_FOR_PARTY_RESPONSIBLE,
		PARTY_RESPONSIBLE_FOR_CAUSE_PARTNER_NUMBER,
		CAUSE_ASSEMBLY,
		QUANTITY,
		UNIT_OF_MEASURE_FOR_ITEM,
		DELETE_DATA_RECORD,
		SORT_NUMBER_FOR_CAUSE,
		DATA_RECORD_CREATED_WITH_FUNCTION_CREATE_WITH_COPY_MODEL,
		INVOLVMENT_IN_PERCENTAGE
    from source_data
),

type_data as (
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(NOTIFICATION_NO as VARCHAR) as NOTIFICATION_NO,
		cast(ITEM_NUMBER_IN_ITEM_RECORD as VARCHAR) as ITEM_NUMBER_IN_ITEM_RECORD,
		cast(SEQUENTIAL_NUMBER_FOR_CAUSE as VARCHAR) as SEQUENTIAL_NUMBER_FOR_CAUSE,
		cast(NAME_OF_PERSON_WHO_CREATED_THE_OBJECT as VARCHAR) as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		cast(DATE_ON_WHICH_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_RECORD_WAS_CREATED,
		cast(NAME_OF_PERSON_WHO_CHANGED_OBJECT as VARCHAR) as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		cast(DATE_OF_LAST_CHANGE as DATE) as DATE_OF_LAST_CHANGE,
		cast(CAUSE_TEXT as VARCHAR) as CAUSE_TEXT,
		cast(CATALOG_TYPE_CAUSES as VARCHAR) as CATALOG_TYPE_CAUSES,
		cast(CODE_GROUP_CAUSES as VARCHAR) as CODE_GROUP_CAUSES,
		cast(CAUSE_CODE as VARCHAR) as CAUSE_CODE,
		cast(VERSION_NUMBER as VARCHAR) as VERSION_NUMBER,
		cast(OBJECT_LONG_TEXT_AVAILABLE as VARCHAR) as OBJECT_LONG_TEXT_AVAILABLE,
		cast(PRIMARY_LANGUAGE_INDICATOR_FOR_TEXT_SEGMENT as VARCHAR) as PRIMARY_LANGUAGE_INDICATOR_FOR_TEXT_SEGMENT,
		cast(TIME_AT_WHICH_RECORD_WAS_ADDED as VARCHAR) as TIME_AT_WHICH_RECORD_WAS_ADDED,
		cast(TIME_OF_CHANGE as VARCHAR) as TIME_OF_CHANGE,
		cast(CATALOG_TYPE_PARTY_RESPONSIBLE as VARCHAR) as CATALOG_TYPE_PARTY_RESPONSIBLE,
		cast(CODE_GROUP_PARTY_RESPONSIBLE as VARCHAR) as CODE_GROUP_PARTY_RESPONSIBLE,
		cast(CODE_FOR_PARTY_RESPONSIBLE as VARCHAR) as CODE_FOR_PARTY_RESPONSIBLE,
		cast(FUNCTION_FOR_PARTY_RESPONSIBLE as VARCHAR) as FUNCTION_FOR_PARTY_RESPONSIBLE,
		cast(PARTY_RESPONSIBLE_FOR_CAUSE_PARTNER_NUMBER as VARCHAR) as PARTY_RESPONSIBLE_FOR_CAUSE_PARTNER_NUMBER,
		cast(CAUSE_ASSEMBLY as VARCHAR) as CAUSE_ASSEMBLY,
		cast(QUANTITY as NUMBER(38,10)) as QUANTITY,
		cast(UNIT_OF_MEASURE_FOR_ITEM as VARCHAR) as UNIT_OF_MEASURE_FOR_ITEM,
		cast(DELETE_DATA_RECORD as VARCHAR) as DELETE_DATA_RECORD,
		cast(SORT_NUMBER_FOR_CAUSE as VARCHAR) as SORT_NUMBER_FOR_CAUSE,
		cast(DATA_RECORD_CREATED_WITH_FUNCTION_CREATE_WITH_COPY_MODEL as VARCHAR) as DATA_RECORD_CREATED_WITH_FUNCTION_CREATE_WITH_COPY_MODEL,
		cast(INVOLVMENT_IN_PERCENTAGE as VARCHAR) as INVOLVMENT_IN_PERCENTAGE
    from transform_data
)
select * from type_data
		BEGDA as START_DATE,
		SEQNR as NUMBER_OF_INFOTYPE_RECORD_WITH_SAME_KEY,
		AEDTM as DATE_OF_LAST_CHANGE,
		UNAME as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		HISTO as HISTORICAL_RECORD_FLAG,
		ITXEX as TEXT_EXISTS_FOR_INFOTYPE,
		REFEX as REFERENCE_FIELDS_EXIST_PRIMARYSECONDARY_COSTS,
		ORDEX as CONFIRMATION_FIELDS_EXIST,
		ITBLD as INFOTYPE_SCREEN_CONTROL,
		PREAS as REASON_FOR_CHANGING_MASTER_DATA,
		FLAG1 as RESERVED_FIELDUNUSED_FIELD,
		FLAG2 as FLAG2_RESERVED_FIELDUNUSED_FIELD,
		FLAG3 as FLAG3_RESERVED_FIELDUNUSED_FIELD,
		FLAG4 as FLAG4_RESERVED_FIELDUNUSED_FIELD,
		RESE1 as RESERVED_FIELDUNUSED_FIELD_OF_LENGTH_2,
		RESE2 as RESE2_RESERVED_FIELDUNUSED_FIELD_OF_LENGTH_2,
		GRPVL as GROUPING_VALUE_FOR_PERSONNEL_ASSIGNMENTS,
		MASSN as ACTION_TYPE,
		MASSG as REASON_FOR_ACTION,
		STAT1 as CUSTOMER_SPECIFIC_STATUS,

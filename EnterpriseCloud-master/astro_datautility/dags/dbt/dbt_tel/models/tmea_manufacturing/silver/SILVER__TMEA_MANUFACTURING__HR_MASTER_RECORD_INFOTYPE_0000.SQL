        MANDT as CLIENT,
		PERNR as PERSONNEL_NUMBER,
		SUBTY as SUBTYPE,
		OBJPS as OBJECT_IDENTIFICATION,
		SPRPS as LOCK_INDICATOR_FOR_HR_MASTER_DATA_RECORD,

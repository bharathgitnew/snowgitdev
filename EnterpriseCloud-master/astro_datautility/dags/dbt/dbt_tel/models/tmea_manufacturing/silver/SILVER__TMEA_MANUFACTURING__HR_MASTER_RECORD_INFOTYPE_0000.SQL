		STAT3 as SPECIAL_PAYMENT_STATUS,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_HR_MASTER_RECORD_INFOTYPE_0000') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		PERSONNEL_NUMBER,
		SUBTYPE,
		OBJECT_IDENTIFICATION,
		LOCK_INDICATOR_FOR_HR_MASTER_DATA_RECORD,
		TRY_TO_DATE(END_DATE,'YYYYMMDD')  AS END_DATE,
		TRY_TO_DATE(START_DATE,'YYYYMMDD')  AS START_DATE,
		NUMBER_OF_INFOTYPE_RECORD_WITH_SAME_KEY,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE,'YYYYMMDD')  AS DATE_OF_LAST_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		HISTORICAL_RECORD_FLAG,
		TEXT_EXISTS_FOR_INFOTYPE,
		REFERENCE_FIELDS_EXIST_PRIMARYSECONDARY_COSTS,
		CONFIRMATION_FIELDS_EXIST,

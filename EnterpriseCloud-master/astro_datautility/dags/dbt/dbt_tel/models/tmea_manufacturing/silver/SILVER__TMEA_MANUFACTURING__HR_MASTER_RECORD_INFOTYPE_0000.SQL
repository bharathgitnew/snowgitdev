		FLAG2_RESERVED_FIELDUNUSED_FIELD,
		FLAG3_RESERVED_FIELDUNUSED_FIELD,
		FLAG4_RESERVED_FIELDUNUSED_FIELD,
		RESERVED_FIELDUNUSED_FIELD_OF_LENGTH_2,
		RESE2_RESERVED_FIELDUNUSED_FIELD_OF_LENGTH_2,
		GROUPING_VALUE_FOR_PERSONNEL_ASSIGNMENTS,
		ACTION_TYPE,
		REASON_FOR_ACTION,
		CUSTOMER_SPECIFIC_STATUS,
		EMPLOYMENT_STATUS,
		SPECIAL_PAYMENT_STATUS
    from source_data
),


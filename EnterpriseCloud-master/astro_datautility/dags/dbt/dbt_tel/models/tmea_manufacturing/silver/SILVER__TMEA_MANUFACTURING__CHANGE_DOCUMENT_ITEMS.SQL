{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='CHANGE_DOCUMENT_ITEMS',
        unique_key = ['CLIENT',
    'OBJECT_CLASS',
    'OBJECT_VALUE',
    'CHANGE_NUMBER_OF_DOCUMENT',
    'TABLE_NAME',
    'CHANGED_TABLE_RECORD_KEY',
    'FIELD_NAME',
    'CHANGE_TYPE_U_I_E_D'],
        transient=false
) }}

with source_data as (
    select
        MANDANT as CLIENT,
		OBJECTCLAS as OBJECT_CLASS,
		OBJECTID as OBJECT_VALUE,
		CHANGENR as CHANGE_NUMBER_OF_DOCUMENT,
		TABNAME as TABLE_NAME,
		TABKEY as CHANGED_TABLE_RECORD_KEY,
		FNAME as FIELD_NAME,
		CHNGIND as CHANGE_TYPE_U_I_E_D,
		TEXT_CASE as FLAG_X_TEXT_CHANGE,
		UNIT_OLD as CHANGE_DOCUMENTS_UNIT_REFERENCED,
		UNIT_NEW as UNIT_NEW_CHANGE_DOCUMENTS_UNIT_REFERENCED,
		CUKY_OLD as CHANGE_DOCUMENTS_REFERENCED_CURRENCY,
		CUKY_NEW as CUKY_NEW_CHANGE_DOCUMENTS_REFERENCED_CURRENCY,
		VALUE_NEW as NEW_CONTENTS_OF_CHANGED_FIELD,
		VALUE_OLD as OLD_CONTENTS_OF_CHANGED_FIELD,
		DATAAGING as DATA_FILTER_VALUE_FOR_DATA_AGING,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_CHANGE_DOCUMENT_ITEMS') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		OBJECT_CLASS,
		OBJECT_VALUE,
		CHANGE_NUMBER_OF_DOCUMENT,
		TABLE_NAME,
		CHANGED_TABLE_RECORD_KEY,
		FIELD_NAME,
		CHANGE_TYPE_U_I_E_D,
		FLAG_X_TEXT_CHANGE,
		CHANGE_DOCUMENTS_UNIT_REFERENCED,
		UNIT_NEW_CHANGE_DOCUMENTS_UNIT_REFERENCED,
		CHANGE_DOCUMENTS_REFERENCED_CURRENCY,
		CUKY_NEW_CHANGE_DOCUMENTS_REFERENCED_CURRENCY,
		NEW_CONTENTS_OF_CHANGED_FIELD,
		OLD_CONTENTS_OF_CHANGED_FIELD,
		try_to_date(DATA_FILTER_VALUE_FOR_DATA_AGING, 'YYYYMMDD') as DATA_FILTER_VALUE_FOR_DATA_AGING
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(OBJECT_CLASS as VARCHAR) as OBJECT_CLASS,
		cast(OBJECT_VALUE as VARCHAR) as OBJECT_VALUE,
		cast(CHANGE_NUMBER_OF_DOCUMENT as VARCHAR) as CHANGE_NUMBER_OF_DOCUMENT,
		cast(TABLE_NAME as VARCHAR) as TABLE_NAME,
		cast(CHANGED_TABLE_RECORD_KEY as VARCHAR) as CHANGED_TABLE_RECORD_KEY,
		cast(FIELD_NAME as VARCHAR) as FIELD_NAME,
		cast(CHANGE_TYPE_U_I_E_D as VARCHAR) as CHANGE_TYPE_U_I_E_D,
		cast(FLAG_X_TEXT_CHANGE as VARCHAR) as FLAG_X_TEXT_CHANGE,
		cast(CHANGE_DOCUMENTS_UNIT_REFERENCED as VARCHAR) as CHANGE_DOCUMENTS_UNIT_REFERENCED,
		cast(UNIT_NEW_CHANGE_DOCUMENTS_UNIT_REFERENCED as VARCHAR) as UNIT_NEW_CHANGE_DOCUMENTS_UNIT_REFERENCED,
		cast(CHANGE_DOCUMENTS_REFERENCED_CURRENCY as VARCHAR) as CHANGE_DOCUMENTS_REFERENCED_CURRENCY,
		cast(CUKY_NEW_CHANGE_DOCUMENTS_REFERENCED_CURRENCY as VARCHAR) as CUKY_NEW_CHANGE_DOCUMENTS_REFERENCED_CURRENCY,
		cast(NEW_CONTENTS_OF_CHANGED_FIELD as VARCHAR) as NEW_CONTENTS_OF_CHANGED_FIELD,
		cast(OLD_CONTENTS_OF_CHANGED_FIELD as VARCHAR) as OLD_CONTENTS_OF_CHANGED_FIELD,
		cast(DATA_FILTER_VALUE_FOR_DATA_AGING as DATE) as DATA_FILTER_VALUE_FOR_DATA_AGING
    from transform_data
)
select * from type_data
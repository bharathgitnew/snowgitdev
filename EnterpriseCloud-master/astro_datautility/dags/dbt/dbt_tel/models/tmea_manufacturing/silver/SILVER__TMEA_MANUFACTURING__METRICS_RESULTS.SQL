{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='METRICS_RESULTS',
    unique_key = [],
    transient=false	
) }} 


with source_data as ( 
    SELECT
        _CAPTUREDATETIME,
        RECNO                AS CHARACTER_FIELD_OF_LENGTH_6,
        TRANS_DOC_NUM        AS TRANSACTIONAL_DOCUMENT_NUMBER,
        TRANS_DOC_ITEM       AS TRANSACTIONAL_DOCUMENT_LINE_ITEM,
        TRANS_DOC_TYPE       AS TRANSACTIONAL_DOCUMENT_TYPE,
        TRANS_DOC_TYPE_TEXT  AS TRANSACTIONAL_DOCUMENT_TYPE_TEXT,
        TIME                 AS TIME_PHASE_PAST_FUTURE,
        CATEGORY             AS TRANSACTION_CATEGORY,
        SUBCATEGORY          AS TRANSACTION_SUB_CATEGORY,
        TRANS_DATE           AS TRANSACTION_DATE,
        TRANS_TIME           AS TRANSACTION_TIME,
        USERNAME             AS USER_NAME,
        TRANS_DOC            AS TRANSACTIONAL_DOCUMENT,
        TRANS_CODE           AS TRANSACTION_CODE,
        MATERIAL             AS MATERIAL_NUMBER,
        MATERIAL_DESCR       AS MATERIAL_DESCRIPTION,
        PLANT                AS PLANT,
        LGORT                AS STORAGE_LOCATION,
        WAREHOUSE            AS WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
        QUANTITY             AS QUANTITY,
        UNIT_OF_MEAS         AS UNIT_OF_ENTRY,
        SOURCE_STOR_TYPE     AS SOURCE_STORAGE_TYPE,
        SOURCE_STOR_TYPE_TXT AS SOURCE_STORAGE_TYPE_TEXT,
        SOURCE_STOR_BIN      AS SOURCE_STORAGE_BIN,
        SOURCE_DATE          AS SOURCE_DATE,
        SOURCE_TIME          AS SOURCE_TIME,
        DEST_STOR_TYPE       AS DESTINATION_STORAGE_TYPE,
        DEST_STOR_TYPE_TXT   AS DESTINATION_STORAGE_TYPE_TEXT,
        DEST_STOR_BIN        AS DESTINATION_STORAGE_BIN,
        DEST_DATE            AS DESTINATION_DATE,
        DEST_TIME            AS DESTINATION_TIME,
        TRANS_TIME_DAYS      AS TRANSACTION_TIME_IN_DAYS,
        TRANS_TIME_HOURS     AS TRANSACTION_TIME_IN_HOURS,
        ADJUSTED_DAYS        AS ADJUSTED_DAYS,
        LABOR_CAPACITY       AS LABOR_CAPACITY
    FROM {{ ref('BRONZE__TMEA_MANUFACTURING__SAPO_METRICS_RESULTS') }}
),
	
transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        _CAPTUREDATETIME,
        CHARACTER_FIELD_OF_LENGTH_6,
        TRANSACTIONAL_DOCUMENT_NUMBER,
        TRANSACTIONAL_DOCUMENT_LINE_ITEM,
        TRANSACTIONAL_DOCUMENT_TYPE,
        TRANSACTIONAL_DOCUMENT_TYPE_TEXT,
        TIME_PHASE_PAST_FUTURE,
        TRANSACTION_CATEGORY,
        TRANSACTION_SUB_CATEGORY,
        try_to_date(TRANSACTION_DATE, 'YYYYMMDD') AS TRANSACTION_DATE,
        TRANSACTION_TIME,
        USER_NAME,
        TRANSACTIONAL_DOCUMENT,
        TRANSACTION_CODE,
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        PLANT,
        STORAGE_LOCATION,
        WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
        QUANTITY,
        UNIT_OF_ENTRY,
        SOURCE_STORAGE_TYPE,
        SOURCE_STORAGE_TYPE_TEXT,
        SOURCE_STORAGE_BIN,
        try_to_date(SOURCE_DATE, 'YYYYMMDD') AS SOURCE_DATE,
        SOURCE_TIME,
        DESTINATION_STORAGE_TYPE,
        DESTINATION_STORAGE_TYPE_TEXT,
        DESTINATION_STORAGE_BIN,
        try_to_date(DESTINATION_DATE, 'YYYYMMDD') AS DESTINATION_DATE,
        DESTINATION_TIME,
        TRANSACTION_TIME_IN_DAYS,
        TRANSACTION_TIME_IN_HOURS,
        ADJUSTED_DAYS,
        LABOR_CAPACITY
    FROM source_data
),

type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
		CAST(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        CHARACTER_FIELD_OF_LENGTH_6,
        TRANSACTIONAL_DOCUMENT_NUMBER,
        TRANSACTIONAL_DOCUMENT_LINE_ITEM,
        TRANSACTIONAL_DOCUMENT_TYPE,
        TRANSACTIONAL_DOCUMENT_TYPE_TEXT,
        TIME_PHASE_PAST_FUTURE,
        TRANSACTION_CATEGORY,
        TRANSACTION_SUB_CATEGORY,
        CAST(TRANSACTION_DATE AS DATE) AS TRANSACTION_DATE,
        TRANSACTION_TIME,
        USER_NAME,
        TRANSACTIONAL_DOCUMENT,
        TRANSACTION_CODE,
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        PLANT,
        STORAGE_LOCATION,
        WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
        CAST(QUANTITY AS NUMBER(38,10)) AS QUANTITY,
        UNIT_OF_ENTRY,
        SOURCE_STORAGE_TYPE,
        SOURCE_STORAGE_TYPE_TEXT,
        SOURCE_STORAGE_BIN,
        CAST(SOURCE_DATE AS DATE) AS SOURCE_DATE,
        SOURCE_TIME,
        DESTINATION_STORAGE_TYPE,
        DESTINATION_STORAGE_TYPE_TEXT,
        DESTINATION_STORAGE_BIN,
        CAST(DESTINATION_DATE AS DATE) AS DESTINATION_DATE,
        DESTINATION_TIME,
        TRANSACTION_TIME_IN_DAYS,
        TRANSACTION_TIME_IN_HOURS,
        ADJUSTED_DAYS,
        LABOR_CAPACITY
    FROM transform_data
)

SELECT * FROM type_data

WITH ref_cte_CALENDAR_DATE as (
    select * from {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
),

ref_cte_GENERAL_DATA_IN_CUSTOMER_MASTER as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__GENERAL_DATA_IN_CUSTOMER_MASTER') }}
),

ref_cte_SALES_DOCUMENT_FLOW as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_FLOW') }}
),

ref_cte_SALES_DOCUMENT_HEADER_DATA as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_HEADER_DATA') }}
),

ref_cte_SALES_DOCUMENT_ITEM_DATA as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_ITEM_DATA') }}
),

ref_cte_TMEA_PRODUCTION_PLANNING as (
    select * from {{ ref('GOLD__TMEA_MANUFACTURING__PRODUCTION_PLANNING') }}
),
 
CTE_TOOLS AS(
SELECT DISTINCT 
PP.SALES_DOCUMENT,
TOOL_NUMBER,
CASE
    WHEN SPLIT_PART(SHORT_TEXT_FOR_SALES_ORDER_ITEM, ' ',1) = 'MERC.' THEN 'MERC'
    ELSE SPLIT_PART(SHORT_TEXT_FOR_SALES_ORDER_ITEM, ' ',1)
END AS TOOL
FROM ref_cte_TMEA_PRODUCTION_PLANNING  PP
LEFT JOIN ref_cte_SALES_DOCUMENT_ITEM_DATA  VBAP
    ON TOOL_NUMBER = MATERIAL_NUMBER
WHERE PRD_ORD_ACTUAL_SHIP_DATE IS NOT NULL
),

CTE_GOODS_ISSUE AS( --SELECTING THE MIN GOODS ISSUE DATE ON A LEVEL
SELECT 
PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
MATERIAL_NUMBER,
MIN(DATE_ON_WHICH_RECORD_WAS_CREATED) AS GOODS_ISSUE
FROM ref_cte_SALES_DOCUMENT_FLOW
WHERE DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = 'R'
AND MOVEMENT_TYPE_ = '601'
GROUP BY PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT, MATERIAL_NUMBER
),

CTE_REQ_DELIV_DATE AS (
SELECT 
SALES_DOCUMENT AS SALES_DOC,
REQUESTED_DELIVERY_DATE,
NAME_1 AS CUSTOMER
FROM ref_cte_SALES_DOCUMENT_HEADER_DATA VBAK
LEFT JOIN ref_cte_GENERAL_DATA_IN_CUSTOMER_MASTER   KNA1
    ON SOLD_TO_PARTY = KNA1.CUSTOMER_NUMBER
),

CTE_CALENDARDATE AS(
select 
calendar_date,
-- YEAR_NUMBER,
-- FISCAL_YEAR_NUMBER,
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
-- QUARTER_TEXT,
-- QUARTER_SHORT_TEXT,
MONTH_TEXT AS MONTH,
MONTH_ABBREVIATION_TEXT,
MONTH_OF_FISCAL_YEAR_NUMBER,
-- MONTH_OF_YEAR_NUMBER,
FISCAL_QUARTER_TEXT,
FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
-- FISCAL_YEAR_QUARTER_SHORT_TEXT
-- FISCAL_YEAR_MONTH_SHORT_TEXT
from ref_cte_CALENDAR_DATE
),

MAIN AS (
SELECT 
SALES_DOCUMENT AS SALES_ORDER,
TOOL_NUMBER,
TOOL,
CUSTOMER,
REQUESTED_DELIVERY_DATE AS COMMITTED_SHIP_DATE,
GOODS_ISSUE AS ACTUAL_SHIP_DATE,
FISCAL_YEAR,
MONTH,
MONTH_ABBREVIATION_TEXT,
MONTH_OF_FISCAL_YEAR_NUMBER,
FISCAL_QUARTER_TEXT,
FISCAL_YEAR_HALF_YEAR_SHORT_TEXT,
DATEDIFF(DAY,GOODS_ISSUE,REQUESTED_DELIVERY_DATE) AS DAYS,
CASE
    WHEN DAYS < 0 THEN 'LATE'
    WHEN DAYS >=0 THEN 'ON TIME'
END AS STATUS
FROM CTE_TOOLS
LEFT JOIN CTE_GOODS_ISSUE 
    ON SALES_DOCUMENT = PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT
    AND TOOL_NUMBER = MATERIAL_NUMBER
LEFT JOIN CTE_REQ_DELIV_DATE
    ON SALES_DOCUMENT = SALES_DOC
LEFT JOIN CTE_CALENDARDATE
    ON GOODS_ISSUE = CALENDAR_DATE
WHERE GOODS_ISSUE > '2024-04-01'
),

source_data as (
SELECT * FROM MAIN),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	SALES_ORDER,
	TOOL_NUMBER,
	TOOL,
	CUSTOMER,
	COMMITTED_SHIP_DATE,
	ACTUAL_SHIP_DATE,
	FISCAL_YEAR,
	MONTH,
	MONTH_ABBREVIATION_TEXT,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	FISCAL_QUARTER_TEXT,
	FISCAL_YEAR_HALF_YEAR_SHORT_TEXT,
	DAYS,
	STATUS
from source_data
),

type_data as (
select
CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
,SALES_ORDER
,TOOL_NUMBER
,TOOL
,CUSTOMER
,CAST(COMMITTED_SHIP_DATE as DATE) as COMMITTED_SHIP_DATE
,CAST(ACTUAL_SHIP_DATE as DATE) as ACTUAL_SHIP_DATE
,FISCAL_YEAR
,MONTH
,MONTH_ABBREVIATION_TEXT
,CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER
,FISCAL_QUARTER_TEXT
,FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
,CAST(DAYS as NUMBER(38,0)) as DAYS
,STATUS
from transform_data 
)
select * from type_data
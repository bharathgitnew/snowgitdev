{{ config(
    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='SHORTAGE_REPORT_MFG',
    	transient=false
) }}

WITH 
source_data AS (
    SELECT
        CLIENT,
        SALES_ORDER_NUMBER_SORT_SEQUENCE AS SO_SEQUENCE,
        REPORT_DATE,
        HIERARCHY_LEVEL,
        MATERIAL_LEVEL,
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        PARENT_MAT_MATERIAL_NUMBER AS HIGHER_LEVEL_MAT,
        PARENT_MAKTX_MATERIAL_DESCRIPTION AS HIGHER_LEVEL_MAT_DESC,
        -- Initial MODULE_STEP_1 calculation
        CASE 
            WHEN HIGHER_LEVEL_MAT IS NULL OR TRIM(HIGHER_LEVEL_MAT) = '' THEN MATERIAL_NUMBER
            WHEN HIGHER_LEVEL_MAT LIKE '%-A%' AND HIERARCHY_LEVEL = 2 THEN MATERIAL_NUMBER
            ELSE NULL
        END AS MODULE_STEP_1,
        PLANT,
        TRY_TO_DATE(TO_VARCHAR(RECEIPT_REQUIREMENTS_DATE),'YYYYMMDD') AS REQUIREMENT_DATE,
        
        MRP_ELEMENT_NUMBER,
        MRP_ELEMENT_ITEM,
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER AS SALES_ORDER,
        QUANTITY_RECEIVED_OR_QUANTITY_REQUIRED  AS REQUIRED_QTY,
        BASE_UNIT_OF_MEASURE  AS Units,
        DELNR_MRP_ELEMENT_NUMBER,
        DELPS_MRP_ELEMENT_ITEM,
        TRY_TO_DATE(TO_VARCHAR(DAT00_RECEIPT_REQUIREMENTS_DATE),'YYYYMMDD') AS RECEIPT_DATE,
        MRP_ELEMENT_DATA,
        ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
        VENDOR_NAME AS SUPPLIER_NAME,
        ABBREVIATION_FOR_MRP_ELEMENT AS MRP_ELEMENT,
        ITEM_DELIVERY_DATE,
        DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
        EINDT_LAST_DELIVERY_DATE_OF_VENDOR_CONFIRMATION,
        TEXT_LINE AS BUYER_COMMENTS,
        PRTXT_TEXT_LINE ,
        EXCEPTION_MESSAGE_PRIORITY,
        EXCEPTION_MESSAGE_KEY,
        EXCEPTION_MESSAGE_TEXT,
        AUSSL_EXCEPTION_MESSAGE_KEY,
        AUSLTSTK_EXCEPTION_MESSAGE_TEXT,
        CROSS_PLANT_MATERIAL_STATUS,
        PLANT_SPECIFIC_MATERIAL_STATUS,
        MRP_CONTROLLER,
        NAME_OF_MRP_CONTROLLER  AS BUYER_NAME,
        PROCUREMENT_TYPE,
        SAFETY_STOCK AS SAFETY_STOCK_QTY,
        TOTAL_REPLENISHMENT_LEAD_TIME_IN_WORKDAYS,
        PLANNED_DELIVERY_TIME_IN_DAYS,
        VALUATED_UNRESTRICTED_USE_STOCK as QTY_IN_STOCK,
        STOCK_IN_QUALITY_INSPECTION as QTY_IN_QM_LOT,
        TOTAL_OF_PLANNED_ISSUES,
        PURCHASE_REQUISITIONS,
        PURCHASE_ORDERS,
        PRSHORT_TOTAL_OF_PLANNED_ISSUES,
        POSHORT_TOTAL_OF_PLANNED_ISSUES,
        _CAPTUREDATETIME AS SHORTAGES_LIST_UPDATED
    FROM
        {{ ref('SILVER__TMEA_MANUFACTURING__SHORTAGE_REPORT_DATA_WAREHOUSE') }}
),
CTE_ValueStream AS (
    SELECT 
        SALES_DOCUMENT, 
        PRODUCT_TYPE_ABBREVIATION,
        MATERIAL_NUMBER AS Tool_Number, 
        CASE 
            WHEN PRODUCT_TYPE_ABBREVIATION = 'Z2' THEN 'Zeta'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'Z3' THEN 'Zeta'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'AV' THEN 'Acrevia'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'GB' THEN 'Acrevia'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'MP' THEN 'Mercury'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'UT' THEN 'UT+'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'AN' THEN 'Antares'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'FN' THEN 'Finesta'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'B1' THEN 'Burnish'
            WHEN PRODUCT_TYPE_ABBREVIATION = 'P2' THEN 'Poseidon 2'
            ELSE NULL
        END AS PRODUCT_LINE, 
        COALESCE(CHECKOUT_BASIC_START, PLANNED_ORDER_BASIC_START) AS CHECKOUT_START, 
        COALESCE(CHECKOUT_BASIC_FINISH, PLANNED_ORDER_FINISH) AS CHECKOUT_FINISH,
        COALESCE(SALES_ORDER_MMR_BUILD_START, PLANNED_ORDER_MMR_BUILD_START) AS MMR_DATE,
        ROW_NUMBER() OVER (PARTITION BY MATERIAL_NUMBER ORDER BY SALES_DOCUMENT) AS rn
    FROM    
      {{ ref('GOLD__TMEA_MANUFACTURING__PRODUCTION_VALUE_STREAM') }}
),

-- Index the rows first, then filter for HIERARCHY_LEVEL, and ensure sorted order for filling the MODULE_STEP_1 column
indexed_data AS (
    SELECT *,
        ROW_NUMBER() OVER (ORDER BY SO_SEQUENCE ASC) AS RowNum  -- Create a consistent ordering based on SO_SEQUENCE
    FROM
        source_data
    WHERE
        HIERARCHY_LEVEL <> 0  -- Filter to include only rows where HIERARCHY_LEVEL does not equal 0
        AND MRP_ELEMENT <> 'Stock'
),
final_data AS (
    SELECT 
        id.*,
        COALESCE(
            id.MODULE_STEP_1,
            LAST_VALUE(id.MODULE_STEP_1 IGNORE NULLS) 
            OVER (PARTITION BY id.SALES_ORDER ORDER BY id.RowNum 
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
        ) AS FILLED_MODULE_STEP_1
    FROM 
        indexed_data id
),
transform_data AS (
    SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
    ROW_NUMBER() OVER (ORDER BY fd.SO_SEQUENCE ASC) AS Index_Column,  -- Adding index column starting from 1
    fd.SO_SEQUENCE,
    LTRIM(fd.SALES_ORDER, '0') AS SALES_ORDER,
    fd.MRP_ELEMENT_NUMBER,
    fd.DELNR_MRP_ELEMENT_NUMBER AS DELNR_MRP_NUMBER,
    cvs.PRODUCT_TYPE_ABBREVIATION,
    cvs.PRODUCT_LINE,
    cvs.Tool_Number,
    fd.HIERARCHY_LEVEL,
    fd.HIGHER_LEVEL_MAT,
    fd.HIGHER_LEVEL_MAT_DESC,
    fd.MATERIAL_NUMBER,
    fd.MATERIAL_DESCRIPTION,
    COALESCE(fd.FILLED_MODULE_STEP_1, fd.MODULE_STEP_1) AS MODULE_STEP_1, -- Use filled or original as final MODULE_STEP_1
    fd.PROCUREMENT_TYPE,
    cvs.CHECKOUT_START,
    cvs.CHECKOUT_FINISH,
    cvs.MMR_DATE,
    fd.REQUIREMENT_DATE,
    fd.RECEIPT_DATE,
    fd.REQUIRED_QTY,
    fd.Units,
    fd.QTY_IN_STOCK,
    fd.QTY_IN_QM_LOT,
    fd.SAFETY_STOCK_QTY,
    CASE 
        WHEN (REQUIRED_QTY + QTY_IN_STOCK) >= 0 THEN 'No'
        ELSE 'Yes'
    END AS ENOUGH_SAFETY_STOCK,
    fd.MRP_ELEMENT,
    fd.BUYER_NAME,
    fd.BUYER_COMMENTS,
    fd.SUPPLIER_NAME,
    fd.SHORTAGES_LIST_UPDATED,   
FROM
    final_data fd
LEFT JOIN 
    (SELECT *
     FROM CTE_ValueStream
     WHERE rn = 1) cvs ON fd.SALES_ORDER = cvs.SALES_DOCUMENT
WHERE 
    fd.MRP_ELEMENT IN ('PurRqs', 'PO-LI', 'RcvdNt', 'QM lot', 'ShipNt')    
ORDER BY 
    fd.SO_SEQUENCE ASC

),
TYPE_DATA as (
    select
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        Index_Column::NUMBER(18,0) as Index_Column,
        SO_SEQUENCE::NUMBER(18,0) as SO_SEQUENCE,
        SALES_ORDER,
        MRP_ELEMENT_NUMBER,
        DELNR_MRP_NUMBER,
        PRODUCT_TYPE_ABBREVIATION,
        PRODUCT_LINE,
        Tool_Number,
        HIERARCHY_LEVEL::NUMBER(38,10) as HIERARCHY_LEVEL ,
        HIGHER_LEVEL_MAT,
        HIGHER_LEVEL_MAT_DESC,
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        MODULE_STEP_1,
        PROCUREMENT_TYPE,
        CHECKOUT_START::DATE as CHECKOUT_START,
        CHECKOUT_FINISH::DATE as CHECKOUT_FINISH,
        MMR_DATE::DATE as MMR_DATE,
        REQUIREMENT_DATE::DATE as REQUIREMENT_DATE,
        RECEIPT_DATE::DATE as RECEIPT_DATE,
        REQUIRED_QTY::NUMBER(38,10) as REQUIRED_QTY,
        Units,
        QTY_IN_STOCK::NUMBER(38,10) as QTY_IN_STOCK,
        QTY_IN_QM_LOT::NUMBER(38,10) as QTY_IN_QM_LOT,
        SAFETY_STOCK_QTY::NUMBER(38,10) as SAFETY_STOCK_QTY,
        ENOUGH_SAFETY_STOCK,
        MRP_ELEMENT,
        BUYER_NAME,
        BUYER_COMMENTS,
        SUPPLIER_NAME,
        SHORTAGES_LIST_UPDATED::TIMESTAMP_LTZ as SHORTAGES_LIST_UPDATED
    from transform_data
)

select * from TYPE_DATA
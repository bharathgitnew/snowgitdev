{{ config(
	materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
	alias='PRODUCTION_TOOL_BUILD_HOURS',
	transient=false
) }}

WITH ref_cte_BOM_ITEM as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__BOM_ITEM') }}
),

ref_cte_CALENDAR_DATE as (
    select * from {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
),

ref_cte_MATERIAL_TO_BOM_LINK as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__MATERIAL_TO_BOM_LINK') }}
),

ref_cte_TMEA_MANAGEMENT_KPI_GOALS as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__TMEA_MANAGEMENT_KPI_GOALS') }}
),

ref_cte_TMEA_PRODUCTION_PLANNING as (
    select * from {{ ref('GOLD__TMEA_MANUFACTURING__PRODUCTION_PLANNING') }}
),



CTE_Z2_SA AS (
select 
MAST.MATERIAL_NUMBER,
-- STPO.BOM_COMPONENT,
'Z2 S/A' AS SA,
from ref_cte_MATERIAL_TO_BOM_LINK   MAST
LEFT JOIN ref_cte_BOM_ITEM  STPO
    ON MAST.BILL_OF_MATERIAL = STPO.BILL_OF_MATERIAL
WHERE PLANT = '0010'
AND MATERIAL_NUMBER LIKE 'Z2-A%'
AND BOM_COMPONENT LIKE 'Z2-M%'
),

CTE_ALL_TOOLS AS(
SELECT DISTINCT
TOOL_NUMBER AS PK,
CASE
    WHEN SA IS NULL THEN PRODUCT_TYPE_ABBREVIATION
    ELSE SA
    END AS PRODUCT
FROM ref_cte_TMEA_PRODUCTION_PLANNING
LEFT JOIN CTE_Z2_SA
    ON PK=MATERIAL_NUMBER
),

CTE_TOOL_HOURS AS(
SELECT 
PRODUCT,
TOOL_NUMBER as TOOL_HEADER,
CONCAT(PRODUCT,' Build Hours Average') AS INDICATOR,
PRD_ORDER,
(TO_NUMBER(OP_ACTUAL_HOURS_ENTERED,10, 2)) as HOURS,
PRD_ORD_ACTUAL_SHIP_DATE AS SHIP_DATE
FROM ref_cte_TMEA_PRODUCTION_PLANNING
LEFT JOIN CTE_ALL_TOOLS
    ON PK = TOOL_NUMBER
WHERE PRD_ORD_ACTUAL_SHIP_DATE IS NOT NULL
),

CTE_CALENDARDATE AS(
select 
calendar_date,
-- YEAR_NUMBER,
-- FISCAL_YEAR_NUMBER,
FISCAL_YEAR_SHORT_TEXT,
-- QUARTER_TEXT,
-- QUARTER_SHORT_TEXT,
-- MONTH_TEXT,
MONTH_ABBREVIATION_TEXT,
MONTH_OF_FISCAL_YEAR_NUMBER,
-- MONTH_OF_YEAR_NUMBER,
FISCAL_QUARTER_TEXT,
FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
-- FISCAL_YEAR_QUARTER_SHORT_TEXT,
-- FISCAL_YEAR_MONTH_SHORT_TEXT
from ref_cte_CALENDAR_DATE
),

MAIN AS(
SELECT 
PRODUCT,
INDICATOR,
TOOL_HEADER,
SUM(HOURS) AS HOURS,
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
MONTH_ABBREVIATION_TEXT AS MONTH,
YEAR(SHIP_DATE) AS YEAR,
MONTH_OF_FISCAL_YEAR_NUMBER,
FISCAL_QUARTER_TEXT as FISCAL_QUARTER,
FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FY_H,
TARGET
FROM CTE_TOOL_HOURS
LEFT JOIN CTE_CALENDARDATE
    ON SHIP_DATE = CALENDAR_DATE
LEFT JOIN ref_cte_TMEA_MANAGEMENT_KPI_GOALS AS GOALS
    ON INDICATOR = GOALS.INDICATORS_KPIS
    AND FY_H = GOALS.FY
GROUP BY PRODUCT,INDICATOR,TOOL_HEADER,FISCAL_YEAR,MONTH,YEAR,MONTH_OF_FISCAL_YEAR_NUMBER,FY_H,TARGET,FISCAL_QUARTER_TEXT
),
source_data as (
SELECT * FROM MAIN),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	PRODUCT,
	INDICATOR,
	TOOL_HEADER,
	HOURS,
	FISCAL_YEAR,
	MONTH,
	YEAR,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	FISCAL_QUARTER,
	FY_H,
	TARGET
from source_data
),

type_data as (
select
CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
,PRODUCT
,INDICATOR
,TOOL_HEADER
,CAST(HOURS as NUMBER(38,10)) as HOURS
,FISCAL_YEAR
,MONTH
,YEAR
,CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER
,FISCAL_QUARTER
,FY_H
,CAST(TARGET as  NUMBER(38,0)) as TARGET
from transform_data 
)
select * from type_data
WITH SOURCE_DATA AS (

    SELECT
        MAPL.MATERIAL_NUMBER AS MATERIAL,
        MAPL.PLANT AS PLANT,
        PLPO.ACTIVITY_NUMBER AS ACTIVITY_NUMBER,
        CRHD.WORK_CENTER AS WORK_CENTER,
        PLPO.OPERATION_SHORT_TEXT AS DESCRIPTION,
        PLPO.BASE_QUANTITY as BASE_QTY,
        ZEROIFNULL(PLPO.STANDARD_VALUE_VGW03) AS LABOUR,
        PLPO.VALID_FROM_DATE AS DATE_FROM
    FROM
        {{ ref('SILVER__TMEA_MANUFACTURING__ASSIGNMENT_TASK_LISTS_MATERIALS') }} AS MAPL
        LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__TASK_LIST_OPERATION_ACTIVITY') }} AS PLPO
        ON PLPO.KEY_FOR_TASK_LIST_GROUP = MAPL.KEY_FOR_TASK_LIST_GROUP
        AND PLPO.TASK_LIST_TYPE = MAPL.TASK_LIST_TYPE
        LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__WORK_CENTER_HEADER') }} AS CRHD
        ON PLPO.OBJECT_ID_ARBID = CRHD.OBJECT_ID_OF_THE_RESOURCE
    WHERE
        MAPL.PLANT = '0010'
        AND MAPL.TASK_LIST_TYPE = 'N'
        AND MAPL.DELETION_INDICATOR != 'X'
        AND PLPO.DELETION_INDICATOR != 'X'
),
TRANSFORM_DATA AS (
	SELECT
		'{{ INVOCATION_ID }}' AS _AUDIT_LOG_ID,
		SHA2('HASH_ME') AS _ROW_HASH,
		MATERIAL,
		PLANT,
		ACTIVITY_NUMBER,
		WORK_CENTER,
		DESCRIPTION,
		BASE_QTY,
		LABOUR,
		DATE_FROM
	FROM
		SOURCE_DATA
),
TYPE_DATA AS (
	SELECT 
	cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		MATERIAL,
		PLANT,
		ACTIVITY_NUMBER,
		WORK_CENTER,
		DESCRIPTION,
		BASE_QTY::NUMBER(38,10) AS BASE_QTY,
		LABOUR::NUMBER(38,10) AS LABOUR,
		DATE_FROM::DATE AS DATE_FROM
	FROM
		TRANSFORM_DATA

)

SELECT
	*
FROM
	TYPE_DATA

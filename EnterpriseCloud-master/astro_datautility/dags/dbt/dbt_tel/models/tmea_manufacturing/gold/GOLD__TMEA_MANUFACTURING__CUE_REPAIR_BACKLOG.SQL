{{ config(
    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='CUE_REPAIR_BACKLOG',
    	transient=false
) }}

WITH
CREATED AS(
select 
TO_VARCHAR(TMEA_SALES_ORDER_CREATED_DATE, 'YYYY MMMM') AS YEAR_MONTH,
COUNT(YEAR_MONTH) AS SLS_ORD_CREATED
from {{ ref('GOLD__TMEA_MANUFACTURING__CUE_DASHBOARD') }}
WHERE REJECTION_REASON IS NULL
GROUP BY YEAR_MONTH
),

COMPLETED AS(
select 
TO_VARCHAR(TECHNICAL_COMPLETION_DATE, 'YYYY MMMM') AS YEAR_MONTH2,
COUNT(YEAR_MONTH2) AS SLS_ORD_COMPLETED
from {{ ref('GOLD__TMEA_MANUFACTURING__CUE_DASHBOARD') }}
WHERE YEAR_MONTH2 IS NOT NULL
AND REJECTION_REASON IS NULL
GROUP BY YEAR_MONTH2
),

MAIN AS (
SELECT * FROM CREATED
LEFT JOIN COMPLETED 
    ON CREATED.YEAR_MONTH = COMPLETED.YEAR_MONTH2
),

OUTPUT AS (
SELECT 
YEAR_MONTH,
SLS_ORD_CREATED,
SLS_ORD_COMPLETED,
TO_NUMBER(SUM(TO_NUMBER(SLS_ORD_CREATED) - TO_NUMBER(SLS_ORD_COMPLETED)) OVER (PARTITION BY 1 ORDER BY TO_DATE(YEAR_MONTH, 'YYYY MMMM') ASC)) AS SLS_ORD_BACKLOG
FROM MAIN
),

source_data as (
SELECT YEAR_MONTH,
	SLS_ORD_CREATED,
	SLS_ORD_COMPLETED,
	SLS_ORD_BACKLOG,
	to_date(YEAR_MONTH, 'YYYY MMMM') as DATE_INDEX FROM OUTPUT
order by to_date(YEAR_MONTH, 'YYYY MMMM') DESC),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	YEAR_MONTH,
	SLS_ORD_CREATED,
	SLS_ORD_COMPLETED,
	SLS_ORD_BACKLOG,
	DATE_INDEX

from source_data
),

type_data as (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	CAST(YEAR_MONTH as VARCHAR(16777216)) as YEAR_MONTH,
	CAST(SLS_ORD_CREATED as NUMBER(38,0)) as SLS_ORD_CREATED,
	CAST(SLS_ORD_COMPLETED as NUMBER(38,0)) as SLS_ORD_COMPLETED,
	CAST(SLS_ORD_BACKLOG as NUMBER(38,0)) as SLS_ORD_BACKLOG,
	CAST(DATE_INDEX as  DATE) as DATE_INDEX
from transform_data 
)
select * from type_data
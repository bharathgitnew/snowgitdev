WITH 
STATUS
AS (
	SELECT JSTO.OBJECT_NUMBER,
		JSTO.OBJECT_CATEGORY,
		JEST.OBJECT_STATUS,
		CASE 
			WHEN substr(JEST.OBJECT_STATUS, 1, 1) = 'I'
				THEN TJ02T.INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM
			END AS INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM,
		TJ04.POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY,
		TJ04.STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION,
		ROW_NUMBER() OVER (
			PARTITION BY JSTO.OBJECT_NUMBER ORDER BY JSTO.OBJECT_NUMBER,
				TJ04.POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY,
				TJ04.STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION,
				INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM
			) AS rn
	FROM {{ ref('SILVER__TMEA_MANUFACTURING__STATUS_OBJECT_INFORMATION') }} AS JSTO
	LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__INDIVIDUAL_OBJECT_STATUS') }} AS JEST ON JEST.OBJECT_NUMBER = JSTO.OBJECT_NUMBER
		AND jest.CLIENT = jsto.CLIENT
	LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__STATUS_CONTROL_FOR_OBJECT_TYPE') }} AS TJ04 ON TJ04.SYSTEM_STATUS = JEST.OBJECT_STATUS
		AND TJ04.OBJECT_CATEGORY = JSTO.OBJECT_CATEGORY
	LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__SYSTEM_STATUS') }} AS TJ02 ON TJ02.SYSTEM_STATUS = JEST.OBJECT_STATUS
	LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__SYSTEM_STATUS_TEXTS') }} AS TJ02T ON TJ02T.SYSTEM_STATUS = TJ02.SYSTEM_STATUS
	WHERE JEST.INDICATOR_STATUS_IS_INACTIVE <> 'X'
		AND TJ02.DO_NOT_DISPLAY_STATUS_FLAG <> 'X'
		AND TJ02T.LANGUAGE_KEY = 'E'
--		AND JSTO.OBJECT_CATEGORY = 'ORH'
		AND jSTO.CLIENT = '300'
	),
   

Str_value
AS (
	SELECT OBJECT_NUMBER,
		CASE 
			WHEN max(rn) > 8
				THEN 'X'
			ELSE ''
			END AS star
	FROM STATUS where OBJECT_CATEGORY  = 'ORH'
	GROUP BY OBJECT_NUMBER
	),
Values_merge
AS (
	SELECT OBJECT_NUMBER,
		listagg(INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM, ' ') within
	GROUP (
			ORDER BY OBJECT_NUMBER,
				POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY,
				STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION,
				INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM
			) AS STATUS
	FROM STATUS
	WHERE rn <= 8
	GROUP BY OBJECT_NUMBER
	),

item_Values_merge AS (
	SELECT OBJECT_NUMBER,
		listagg(INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM, ' ') within
	GROUP (
			ORDER BY OBJECT_NUMBER,
				POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY,
				STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION,
				INDIVIDUAL_STATUS_OF_AN_OBJECT_SHORT_FORM
			) AS STATUS
	FROM STATUS 
	WHERE ( STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION is  null or  
	POSITION_OF_THE_STATUS_IN_THE_STATUS_DISPLAY <> STATUS_DISPLAY_PRIORITY_AT_A_PARTICULAR_POSITION )
	GROUP BY OBJECT_NUMBER
	),
    
Status_value
AS (
	SELECT substr(Values_merge.OBJECT_NUMBER, 3, 14) AS OBJECT_NUMBER,
		CASE 
			WHEN str_value.star = 'X'
				THEN CONCAT (
						STATUS,
						' *'
						)
			ELSE STATUS
			END AS STATUS
	FROM Values_merge
	LEFT JOIN str_value ON Values_merge.OBJECT_NUMBER = str_value.OBJECT_NUMBER
	),
afru_sum
AS (
	SELECT CLIENT,
		ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER AS ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER,
		GENERAL_COUNTER_FOR_ORDER AS GENERAL_COUNTER_FOR_ORDER,
		COMPLETION_CONFIRMATION_NUMBER_FOR_THE_OPERATION AS Confirmation,
		sum(PREVIOUSLY_CONFIRMED_YIELD_IN_ORDER_UNIT_OF_MEASURE) AS Prev_Conf_Yield,
		sum(ISM03_ACTIVITY_CURRENTLY_TO_BE_CONFIRMED) AS Act_Curr_To_Be_Conf,
		sum(YIELD_TO_BE_CONFIRMED) AS Yield_To_Be_Conf,
		sum(SCRAP_TO_BE_CONFIRMED) AS Scrap_To_Be_Conf
	FROM {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_CONFIRMATIONS') }}
	WHERE client = '300'
	GROUP BY CLIENT,
		ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER,
		GENERAL_COUNTER_FOR_ORDER,
		COMPLETION_CONFIRMATION_NUMBER_FOR_THE_OPERATION
	),
afru
AS (
	SELECT CLIENT,
		ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER AS ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER,
		GENERAL_COUNTER_FOR_ORDER AS GENERAL_COUNTER_FOR_ORDER,
		COMPLETION_CONFIRMATION_NUMBER_FOR_THE_OPERATION AS Confirmation,
		CONFIRMATION_COUNTER AS conf_counter,
		ENTRY_DATE_OF_CONFIRMATION AS completed_on,
		NAME_OF_PERSON_WHO_ENTERED_THE_CONFIRMATION AS Completed_By,
		DATE_OF_LAST_CHANGE AS Last_Chg_Date,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT AS Changed_By,
		POSTING_DATE AS Posting_Date,
		OBJECT_ID AS Object_ID,
		PLANT AS PLANT,
		CONFIRMED_START_DATE_OF_EXECUTION AS Conf_Start_of_Exec,
		CONFIRMED_TIME_FOR_START_EXECUTION AS Conf_Time_For_Exec,
		CONFIRMED_FINISH_DATE_OF_EXECUTION AS Conf_Fin_Date_of_Exec,
		CONFIRMED_TIME_FOR_FINISH_EXECUTION AS Conf_Time_For_Fin_Exec,
		ACTIVITY_NUMBER AS Activity_Nbr_1,
		OPERATION_QUANTITY AS Operation_Qty,
		ACTUAL_WORK AS Actual_Work_1,
		UNIT_FOR_WORK AS Act_Wrk_Unit,
		REMAINING_WORK AS Rem_Work,
		UNIT_OF_MEASURE_FOR_REMAINING_WORK AS Rem_Wrk_UOM,
		ILE03_UNIT_OF_MEASURE_FOR_THE_ACTIVITY_TO_BE_CONFIRMED AS UOM_For_Act
	FROM {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_CONFIRMATIONS') }}
	WHERE client = '300' qualify ROW_NUMBER() OVER (
			PARTITION BY ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER,
			GENERAL_COUNTER_FOR_ORDER ORDER BY ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER,
				GENERAL_COUNTER_FOR_ORDER
			) = 1
	),
source_data
AS (
	SELECT afko.ORDER_NUMBER AS Prd_Order,
		afvc.COMPLETION_CONFIRMATION_NUMBER_FOR_THE_OPERATION AS Confirmations,
		afvc.CONFIRMATION_COUNTER AS Counter,
		afvc.ACTIVITY_NUMBER AS activity_nbr,
		afvc.STANDARD_TEXT_KEY AS std_text_key,
		aufk.CREATED_ON AS Prd_Ord_Entered_On,
		aufk.ENTERED_BY AS Prd_Ord_Entered_By,
		afvv.LATEST_SCHEDULED_START_EXECUTION_DATE AS basic_start,
		afvv.LATEST_SCHEDULED_FINISH_WAIT_TIME_DATE AS basic_end,
		AFPO.START_DATE_OF_PLANNED_ORDER AS planned_start_date,
		AFPO.SALES_ORDER_NUMBER AS SALES_ORDER,
		afpo.MATERIAL_NUMBER_FOR_ORDER AS Material,
		makt.MATERIAL_DESCRIPTION AS Material_Description,
		AFPO.TOTAL_PLANNED_ORDER_QUANTITY AS Ord_Qty,
		AFPO.ACTUAL_DELIVERYFINISH_DATE AS Act_Dlv_Fin_Date,
		AFPO.DELIV_DATE_FR_PLANNED_ORD AS Dlv_Date_From_Plnd_Ord,
		AFPO.BASIC_FINISH_DATE AS Basic_Fin_Date,
		AFPO.SCHEDULED_FINISH AS Sched_Fin_Date,
		AFPO.VALUE_OF_GOODS_RECEIVED_IN_LOCAL_CURRENCY AS Good_Recv_Value,
		afvc.CONTROL_KEY AS CONTROL_KEY,
		afvc.STANDARD_TEXT_KEY AS Std_Txt_Key,
		afvc.OPERATION_SHORT_TEXT AS Op_Short_Text,
		afvv.WORK_INVOLVED_IN_THE_ACTIVITY AS Wrk_Inv_In_Activity,
		afvv.UNIT_FOR_WORK AS Unit,
		afvv.ACTUAL_WORK AS Actual_Work,
		afru.Confirmation AS Confirmation_1,
		afru.conf_counter AS Counter_1,
		afru.completed_on AS completed_on,
		afru.Completed_By AS Completed_By,
		afru.Last_Chg_Date AS Last_Chg_Date,
		afru.Changed_By AS Changed_By,
		afru.Posting_Date AS Posting_Date,
		afru.Object_ID AS Object_ID,
		afru.PLANT AS PLANT,
		afru_sum.Prev_Conf_Yield AS Prev_Conf_Yield,
		afru_sum.Yield_To_Be_Conf,
		afru_sum.Scrap_To_Be_Conf,
		afru.conf_Start_of_Exec,
		afru.Conf_Time_For_Exec,
		afru.Conf_Fin_Date_of_Exec,
		afru.Conf_Time_For_Fin_Exec,
		afko.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER AS Routing_Nbr,
		afvc.GENERAL_COUNTER_FOR_ORDER AS Counter_2,
		afru.Activity_Nbr_1,
		afru.Operation_Qty,
		afru.Actual_Work_1,
		afru.Act_Wrk_Unit,
		afru.Rem_Work,
		afru.Rem_Wrk_UOM,
		afvv.VGW03_STANDARD_VALUE AS Std_Work,
		afvv.VGE03_UNIT_OF_MEASUREMENT_OF_STANDARD_VALUE AS Std_Wrk_UOM,
		afvv.ISM03_PREVIOUSLY_CONFIRMED_ACTIVITY AS Prev_Conf_Activity,
		afru_sum.Act_Curr_To_Be_Conf,
		afru.UOM_For_Act,
		Status_value.STATUS,
        Item_status.Status as Item_status
	FROM {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_ITEM') }} AS AFPO
	LEFT OUTER JOIN {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_HEADER_DATA_PP_ORDERS') }} AS AFKO ON AFPO.ORDER_NUMBER = AFKO.ORDER_NUMBER
		AND AFPO.CLIENT = AFKO.CLIENT
	LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_MASTER_DATA') }} AS AUFK ON AFKO.ORDER_NUMBER = AUFK.ORDER_NUMBER
		AND AFKO.CLIENT = AUFK.CLIENT
	LEFT JOIN Status_value ON Status_value.OBJECT_NUMBER = AUFK.ORDER_NUMBER
	LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__MATERIAL_DESCRIPTIONS') }} AS MAKT ON AFPO.MATERIAL_NUMBER_FOR_ORDER = MAKT.MATERIAL_NUMBER
		AND AFKO.CLIENT = MAKT.CLIENT
	LEFT OUTER JOIN {{ ref('SILVER__TMEA_MANUFACTURING__OPERATION_WITHIN_AN_ORDER') }} AS AFVC ON AFKO.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER = AFVC.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER
		AND AFVC.CLIENT = AFKO.CLIENT
	LEFT OUTER JOIN {{ ref('SILVER__TMEA_MANUFACTURING__DB_STRUCTURE_OF_THE_QUANTITIESDATES_VALUES_IN_THE_OPERATION') }} AS AFVV ON AFVC.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER = AFVV.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER
		AND AFVC.GENERAL_COUNTER_FOR_ORDER = AFVV.GENERAL_COUNTER_FOR_ORDER
		AND AFKO.CLIENT = AFVV.CLIENT
	LEFT JOIN afru AS afru ON afru.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER = AFVC.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER
		AND afru.GENERAL_COUNTER_FOR_ORDER = AFVC.GENERAL_COUNTER_FOR_ORDER
		AND AFKO.CLIENT = afru.CLIENT
	LEFT JOIN afru_sum AS afru_sum ON afru_sum.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER = AFVC.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER
		AND afru_sum.GENERAL_COUNTER_FOR_ORDER = AFVC.GENERAL_COUNTER_FOR_ORDER
		AND afru_sum.CLIENT = AFKO.CLIENT
    left join item_Values_merge as Item_status
    on Item_status.OBJECT_NUMBER = afvc.Object_number
	WHERE afvc.CONTROL_KEY != 'ZPIC'
		AND AFKO.CLIENT = '300'
		AND AFVC.IS_DELETED = 'No'
    
),


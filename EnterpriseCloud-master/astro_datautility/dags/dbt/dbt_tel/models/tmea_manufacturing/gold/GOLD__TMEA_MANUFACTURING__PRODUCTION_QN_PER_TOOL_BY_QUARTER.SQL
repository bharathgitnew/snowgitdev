    materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
    alias='PRODUCTION_QN_PER_TOOL_BY_QUARTER',
    transient=false
) }}


WITH ref_cte_CALENDAR_DATE as (
    select * from {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
),

ref_cte_TMEA_PRODUCTION_VALUE_STREAM as (
    select * from {{ ref('GOLD__TMEA_MANUFACTURING__PRODUCTION_VALUE_STREAM') }}
),

ref_cte_TMEA_QN_TOOL_SCORECARD as (
    select * from {{ ref('GOLD__TMEA_MANUFACTURING__QN_TOOL_SCORECARD') }}
),
CTE_QN_TOOL_SCORECARD AS(
SELECT 
NOTIFICATION_NO,
QNTS.DATE_ON_WHICH_RECORD_WAS_CREATED,
TOOL_TYPE,
QNTS.MATERIAL_NUMBER,
LEFT(QNTS.MATERIAL_NUMBER,2) AS PROD_ABRV,
MATERIAL_LAST_CHARACTERS,
CAUSE_CODE_GROUP_TEXT,
DISPO_DECISION,
PROBLEM_CODE_TEXT
FROM ref_cte_TMEA_QN_TOOL_SCORECARD    QNTS
WHERE TOOL_TYPE <> 'NOT TOOL SPECIFIC'
AND TOOL_TYPE <> 'REDLINE'
AND DATE_ON_WHICH_RECORD_WAS_CREATED >= '2023-04-01'
),

CTE_TOOL_SHIP_DATE AS(
SELECT 
PRODUCT_TYPE_ABBREVIATION,
RIGHT(MATERIAL_NUMBER,4) AS TOOL_NUMBER,
DOCUMENT_DATE,
CHECKOUT_BASIC_FINISH,
ACTUAL_FINISH_DATE,
ACTUAL_SHIP_DATE
FROM ref_cte_TMEA_PRODUCTION_VALUE_STREAM
),

CTE_CALENDARDATE AS(
select 
calendar_date,
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
MONTH_ABBREVIATION_TEXT AS MONTH,
MONTH_OF_FISCAL_YEAR_NUMBER,
FISCAL_QUARTER_TEXT AS FISCAL_QUARTER
from ref_cte_CALENDAR_DATE
),

MAIN AS (
SELECT * FROM CTE_QN_TOOL_SCORECARD
LEFT JOIN CTE_TOOL_SHIP_DATE
    ON PRODUCT_TYPE_ABBREVIATION = PROD_ABRV
    AND TOOL_NUMBER = MATERIAL_LAST_CHARACTERS
LEFT JOIN CTE_CALENDARDATE
    ON CALENDAR_DATE = ACTUAL_SHIP_DATE
),

source_data as (
SELECT DISTINCT
NOTIFICATION_NO,
DATE_ON_WHICH_RECORD_WAS_CREATED,
TOOL_TYPE,
PROD_ABRV AS PRODUCT_TYPE_ABBREVIATION,
MATERIAL_LAST_CHARACTERS AS TOOL_NUMBER,
MATERIAL_NUMBER,
CAUSE_CODE_GROUP_TEXT,
DISPO_DECISION,
PROBLEM_CODE_TEXT,
DOCUMENT_DATE,
CHECKOUT_BASIC_FINISH,
ACTUAL_FINISH_DATE,
ACTUAL_SHIP_DATE,
FISCAL_YEAR,
MONTH,
MONTH_OF_FISCAL_YEAR_NUMBER,
FISCAL_QUARTER
FROM MAIN
),

TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	NOTIFICATION_NO,
	DATE_ON_WHICH_RECORD_WAS_CREATED,
	TOOL_TYPE,
	PRODUCT_TYPE_ABBREVIATION,
	TOOL_NUMBER,
	MATERIAL_NUMBER,
	CAUSE_CODE_GROUP_TEXT,
	DISPO_DECISION,
	PROBLEM_CODE_TEXT,
	DOCUMENT_DATE,
	CHECKOUT_BASIC_FINISH,
	ACTUAL_FINISH_DATE,
	ACTUAL_SHIP_DATE,
	FISCAL_YEAR,
	MONTH,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	FISCAL_QUARTER

FROM SOURCE_DATA
)

,
TYPE_DATA AS (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	NOTIFICATION_NO,
	CAST(DATE_ON_WHICH_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_RECORD_WAS_CREATED,
	TOOL_TYPE,
	PRODUCT_TYPE_ABBREVIATION,
	TOOL_NUMBER,
	MATERIAL_NUMBER,
	CAUSE_CODE_GROUP_TEXT,
	DISPO_DECISION,
	PROBLEM_CODE_TEXT,
	CAST(DOCUMENT_DATE as DATE) as DOCUMENT_DATE,
	CAST(CHECKOUT_BASIC_FINISH as DATE) as CHECKOUT_BASIC_FINISH,
	CAST(ACTUAL_FINISH_DATE as DATE) as ACTUAL_FINISH_DATE,
	CAST(ACTUAL_SHIP_DATE as DATE) as ACTUAL_SHIP_DATE,
	FISCAL_YEAR,
	MONTH,
	CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER,
	FISCAL_QUARTER
from transform_data
)
SELECT * FROM TYPE_DATA
    materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
    alias='PRODUCTION_TOOL_QN_SUMMARY',
    transient=false
) }}


WITH QN_TOOL AS(
SELECT
NOTIFICATION_NO,
DATE_ON_WHICH_RECORD_WAS_CREATED,
ACTUAL_FINISH_DATE,
TOOL_NUMBER,
MATERIAL_NUMBER,
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FY_H,
FISCAL_QUARTER_TEXT AS FISCAL_QUARTER,
MONTH_ABBREVIATION_TEXT AS MONTH,
CALENDAR_DATE.MONTH_OF_FISCAL_YEAR_NUMBER,
TOOL_TYPE,
PRODUCT_TYPE_ABBREVIATION,
CASE
    WHEN PRODUCT_TYPE_ABBREVIATION = 'Z2' THEN 'Z2 QN Summary'
    WHEN PRODUCT_TYPE_ABBREVIATION = 'AV' THEN 'AV QN Summary'
    WHEN PRODUCT_TYPE_ABBREVIATION = 'AN' THEN 'AN QN Summary'
    WHEN PRODUCT_TYPE_ABBREVIATION = 'Z3' THEN 'Z3 QN Summary'
    WHEN PRODUCT_TYPE_ABBREVIATION = 'MP' THEN 'MP QN Summary'
    WHEN PRODUCT_TYPE_ABBREVIATION = 'UT' THEN 'UT QN Summary'
END AS INDICATOR,
FROM {{ ref('GOLD__TMEA_MANUFACTURING__PRODUCTION_QN_PER_TOOL_BY_QUARTER') }}
LEFT JOIN {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
    ON ACTUAL_FINISH_DATE = CALENDAR_DATE

),

QN_TOOL_GROUPING AS(
SELECT 
FISCAL_YEAR,
FY_H,
FISCAL_QUARTER,
MONTH,
MONTH_OF_FISCAL_YEAR_NUMBER,
TOOL_TYPE,
PRODUCT_TYPE_ABBREVIATION,
INDICATOR,
COUNT(NOTIFICATION_NO) AS NOTIFICATION_NO_COUNT,
COUNT(DISTINCT TOOL_NUMBER) AS TOOL_DISTINCT_COUNT,
LISTAGG(DISTINCT(MATERIAL_NUMBER), ' ') AS NOTES
FROM QN_TOOL
GROUP BY FISCAL_YEAR,FY_H,FISCAL_QUARTER,MONTH,MONTH_OF_FISCAL_YEAR_NUMBER,TOOL_TYPE,PRODUCT_TYPE_ABBREVIATION,INDICATOR
ORDER BY FISCAL_YEAR,FISCAL_QUARTER
),

GOAL AS (
SELECT
FY,
FISCAL_QUARTER AS FY_Q,
FOCUS_AREA,
TARGET,
INDICATORS_KPIS
FROM {{ ref('SILVER__TMEA_MANUFACTURING__TMEA_MANAGEMENT_KPI_GOALS') }}
WHERE (INDICATORS_KPIS = 'Z2 QN Summary'
    OR INDICATORS_KPIS = 'AV QN Summary'
    OR INDICATORS_KPIS = 'AN QN Summary'
    OR INDICATORS_KPIS = 'Z3 QN Summary'
    OR INDICATORS_KPIS = 'MP QN Summary'
    OR INDICATORS_KPIS = 'UT QN Summary')
),

OUTPUT AS(
SELECT * FROM QN_TOOL_GROUPING
LEFT JOIN GOAL
    ON QN_TOOL_GROUPING.FISCAL_YEAR = GOAL.FY
    AND QN_TOOL_GROUPING.FISCAL_QUARTER = GOAL.FY_Q
    AND QN_TOOL_GROUPING.INDICATOR=GOAL.INDICATORS_KPIS
),
SOURCE_DATA as(
 SELECT * FROM OUTPUT
),
TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	FISCAL_YEAR,
	FY_H,
	FISCAL_QUARTER,
	MONTH,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	TOOL_TYPE,
	PRODUCT_TYPE_ABBREVIATION,
	INDICATOR,
	NOTIFICATION_NO_COUNT,
	TOOL_DISTINCT_COUNT,
	NOTES,
	FY,
	FY_Q,
	FOCUS_AREA,
	TARGET,
	INDICATORS_KPIS

FROM SOURCE_DATA
)

,
TYPE_DATA AS (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	FISCAL_YEAR,
	FY_H,
	FISCAL_QUARTER,
	MONTH,
	CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER,
	TOOL_TYPE,
	PRODUCT_TYPE_ABBREVIATION,
	INDICATOR,
	CAST(NOTIFICATION_NO_COUNT as NUMBER(38,0)) as NOTIFICATION_NO_COUNT,
	CAST(TOOL_DISTINCT_COUNT as NUMBER(38,0)) as TOOL_DISTINCT_COUNT,
	NOTES,
	FY,
	FY_Q,
	FOCUS_AREA,
	CAST(TARGET as NUMBER(38,0)) as TARGET,
	INDICATORS_KPIS
from transform_data
)
SELECT * FROM TYPE_DATA
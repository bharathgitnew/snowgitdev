{{ config(
	materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
	alias='MATERIAL_DOCUMENT_LIST',
	transient=false
) }}

WITH ref_cte_DOCUMENT_SEGMENT_MATERIAL as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__DOCUMENT_SEGMENT_MATERIAL') }}
),

ref_cte_HEADER_MATERIAL_DOCUMENT as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__HEADER_MATERIAL_DOCUMENT') }}
),
source_data as
(
    SELECT
      MSEG.NUMBER_OF_MATERIAL_DOCUMENT,
      MSEG.MATERIAL_DOCUMENT_YEAR,
      MSEG.ITEM_IN_MATERIAL_DOCUMENT,
      MSEG.MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
      MSEG.MATERIAL_NUMBER,
      MSEG.PLANT,
      MSEG.STORAGE_LOCATION,
      MSEG.ORDER_NUMBER,
      MSEG.SALES_ORDER_NUMBER,
      MSEG.PURCHASE_ORDER_NUMBER,
      MSEG.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
      MSEG.QUANTITY_IN_UNIT_OF_ENTRY,
      MSEG.UNIT_OF_ENTRY,
      MSEG.AMOUNT_IN_LOCAL_CURRENCY,
      MSEG.GOODS_RECIPIENT_SHIP_TO_PARTY,
      MSEG.POSTING_DATE_IN_THE_DOCUMENT as DATE_MATERIAL_WAS_LAST_RECIEVED,
      MKPF.NUMBER_OF_MATERIAL_DOCUMENT as MATERIAL_DOCUMENT,
      MKPF.MATERIAL_DOCUMENT_YEAR as MATERIAL_DOC_YEAR ,
      MKPF.POSTING_DATE_IN_THE_DOCUMENT as POSTING_DATE_IN_THE_DOCUMENT,
      MKPF.USER_NAME,
      ABS(MSEG.QUANTITY_IN_UNIT_OF_ENTRY) AS QUANTITY_ISSUED,
      SUM(QUANTITY_ISSUED) OVER (
      PARTITION BY MSEG.NUMBER_OF_MATERIAL_DOCUMENT, 
      MSEG.MATERIAL_DOCUMENT_YEAR) AS TOTAL_CONSUMPTION 

      FROM ref_cte_DOCUMENT_SEGMENT_MATERIAL    MSEG 
        LEFT JOIN ref_cte_HEADER_MATERIAL_DOCUMENT  MKPF ON MKPF.NUMBER_OF_MATERIAL_DOCUMENT = MSEG.NUMBER_OF_MATERIAL_DOCUMENT  
										AND MKPF.MATERIAL_DOCUMENT_YEAR = MSEG.MATERIAL_DOCUMENT_YEAR
      WHERE MSEG.PLANT = '0010'
        AND MKPF.POSTING_DATE_IN_THE_DOCUMENT > '2019-01-01'
)

, transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	NUMBER_OF_MATERIAL_DOCUMENT,
	MATERIAL_DOCUMENT_YEAR,
	ITEM_IN_MATERIAL_DOCUMENT,
	MOVEMENT_TYPE_INVENTORY_MANAGEMENT,
	MATERIAL_NUMBER,
	PLANT,
	STORAGE_LOCATION,
	ORDER_NUMBER,
	SALES_ORDER_NUMBER,
	PURCHASE_ORDER_NUMBER,
	ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
	QUANTITY_IN_UNIT_OF_ENTRY,
	UNIT_OF_ENTRY,
	AMOUNT_IN_LOCAL_CURRENCY,
	GOODS_RECIPIENT_SHIP_TO_PARTY,
	DATE_MATERIAL_WAS_LAST_RECIEVED,
	MATERIAL_DOCUMENT,
	MATERIAL_DOC_YEAR,
	POSTING_DATE_IN_THE_DOCUMENT,
	USER_NAME,
	QUANTITY_ISSUED,
	TOTAL_CONSUMPTION
from source_data
),

type_data as (
select
CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
,NUMBER_OF_MATERIAL_DOCUMENT
,MATERIAL_DOCUMENT_YEAR
,ITEM_IN_MATERIAL_DOCUMENT
,MOVEMENT_TYPE_INVENTORY_MANAGEMENT
,MATERIAL_NUMBER
,PLANT
,STORAGE_LOCATION
,ORDER_NUMBER
,SALES_ORDER_NUMBER
,PURCHASE_ORDER_NUMBER
,ITEM_NUMBER_OF_PURCHASING_DOCUMENT
,CAST(QUANTITY_IN_UNIT_OF_ENTRY as NUMBER(38,10)) as QUANTITY_IN_UNIT_OF_ENTRY
,UNIT_OF_ENTRY
,CAST(AMOUNT_IN_LOCAL_CURRENCY as NUMBER(38,10)) as AMOUNT_IN_LOCAL_CURRENCY
,GOODS_RECIPIENT_SHIP_TO_PARTY
,CAST(DATE_MATERIAL_WAS_LAST_RECIEVED as DATE) as DATE_MATERIAL_WAS_LAST_RECIEVED
,MATERIAL_DOCUMENT
,MATERIAL_DOC_YEAR
,CAST(POSTING_DATE_IN_THE_DOCUMENT as DATE) as POSTING_DATE_IN_THE_DOCUMENT
,USER_NAME
,CAST(QUANTITY_ISSUED as NUMBER(38,10)) as QUANTITY_ISSUED
,CAST(TOTAL_CONSUMPTION as NUMBER(38,10)) as TOTAL_CONSUMPTION
from transform_data 
)
select * from type_data
WITH ref_cte_MATERIAL_DESCRIPTIONS as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__MATERIAL_DESCRIPTIONS') }}
),

ref_cte_PLANNED_ORDER as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__PLANNED_ORDER') }}
),

ref_cte_TMEA_PRODUCTION_OPERATION_LEVEL_SYSTEM_STATUS as (
    select * from {{ ref('GOLD__TMEA_MANUFACTURING__PRODUCTION_OPERATION_LEVEL_SYSTEM_STATUS') }}
),

ref_cte_TMEA_PRODUCTION_VALUE_STREAM as (
    select * from {{ ref('GOLD__TMEA_MANUFACTURING__PRODUCTION_VALUE_STREAM') }}
),

ref_cte_TMEA_WORK_CALENDAR as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__TMEA_WORK_CALENDAR') }}
),

ref_cte_TMEA_ZPRODORDINFO as (
    select * from {{ ref('GOLD__TMEA_MANUFACTURING__ZPRODORDINFO') }}
),

PRODUCTION_ORDERS AS(
SELECT 
	PVS.SALES_DOCUMENT,
    NULL AS PLANNED_ORDER_NUMBER,
	PVS.MATERIAL_NUMBER AS TOOL_NUMBER,
	PVS.PRODUCT_TYPE_ABBREVIATION,
	PVS.PRODUCT_TYPE,
	PVS.PRODUCTION_ORDER_NUMBER AS PRODUCTION_ORDER_NUMBER_FOR_A_LEVEL,
	MATERIAL,
	MATERIAL_DESCRIPTION,
	ACTIVITY_NBR,
	STD_TEXT_KEY,
	OP_SHORT_TEXT,
	ORD_QTY,
	STD_WORK,
	STD_WRK_UOM,
	PREV_CONF_YIELD,
	PREV_CONF_ACTIVITY,
	PREV_CONF_ACTIVITY AS PRD_ORD_ACTUAL_HOURS_ENTERED,
	SALES_ORDER_MMR_BUILD_START,
	month(SALES_ORDER_MMR_BUILD_START) AS SALES_ORDER_MMR_BUILD_START_MONTH,
	monthname(SALES_ORDER_MMR_BUILD_START) AS SALES_ORDER_MMR_BUILD_START_MONTH_NAME,
	year(SALES_ORDER_MMR_BUILD_START) AS SALES_ORDER_MMR_BUILD_START_YEAR,
	PRD_ORDER,
    CONFIRMATIONS,
	YIELD_TO_BE_CONF as PRD_ORD_YIELD_TO_BE_CONF,
	UOM_FOR_ACT,
	STATUS AS PROD_ORDER_STATUS,
    (STD_WORK * ORD_QTY) AS PRD_ORD_STANDARD_HOURS_RELEASED,
    contains(STATUS,'DLV') AS PRD_ORD_DLV,
    contains(STATUS,'TECO') AS PRD_ORD_TECO,
    CASE
    WHEN (PRD_ORD_DLV = 'TRUE') THEN PRD_ORD_STANDARD_HOURS_RELEASED
       ELSE 0
       END AS PRD_ORD_TOTAL_COMPLETED_STD_WORK,
	BASIC_START,
	year(BASIC_START) AS BASIC_START_YEAR,
	month(BASIC_START) AS BASIC_START_MONTH,
	monthname(BASIC_START) AS BASIC_START_MONTH_NAME,
	BASIC_END,
	CONF_START_OF_EXEC,
	CONF_FIN_DATE_OF_EXEC,
	ACT_DLV_FIN_DATE AS PRD_ORD_ACT_DLV_FIN_DATE,
	year(ACT_DLV_FIN_DATE) AS PRD_ORD_ACT_DLV_FIN_DATE_YEAR,
	month(ACT_DLV_FIN_DATE) AS PRD_ORD_ACT_DLV_FIN_DATE_MONTH,
	monthname(ACT_DLV_FIN_DATE) AS PRD_ORD_ACT_DLV_FIN_DATE_MONTH_NAME,
	DATEDIFF(day, BASIC_START, BASIC_END) + 1 AS PRD_ORD_PLANNED_CYCLE_TIME_IN_DAYS,
	DATEDIFF(day, CONF_START_OF_EXEC, CONF_FIN_DATE_OF_EXEC) + 1 AS PRD_ORD_ACTUAL_CYCLE_TIME_IN_DAYS,
	(PRD_ORD_PLANNED_CYCLE_TIME_IN_DAYS - PRD_ORD_ACTUAL_CYCLE_TIME_IN_DAYS) AS PRD_ORD_DELTA_CYCLE_TIME_IN_DAYS,
	(
		SELECT count(DATE)
		FROM ref_cte_TMEA_WORK_CALENDAR
		WHERE DATE BETWEEN to_date(BASIC_START)
				AND to_date(BASIC_END)
		) AS PRD_ORD_PLANNED_CYCLE_TIME_IN_BUSINESS_DAYS,
	(
		SELECT count(DATE)
		FROM ref_cte_TMEA_WORK_CALENDAR
		WHERE DATE BETWEEN to_date(CONF_START_OF_EXEC)
				AND to_date(CONF_FIN_DATE_OF_EXEC)
		) AS PRD_ORD_ACTUAL_CYCLE_TIME_IN_BUSINESS_DAYS,
	(PRD_ORD_PLANNED_CYCLE_TIME_IN_BUSINESS_DAYS - PRD_ORD_ACTUAL_CYCLE_TIME_IN_BUSINESS_DAYS) AS PRD_ORD_DELTA_CYCLE_TIME_IN_BUSINESS_DAYS,
	PVS.ACTUAL_SHIP_DATE AS PRD_ORD_ACTUAL_SHIP_DATE,
    NULL AS TOTAL_PLANNED_ORDER_QUANTITY,
    NULL AS ORDER_START_DATE_IN_PLANNED_ORDER,
    NULL AS ORDER_FINISH_DATE_IN_THE_PLANNED_ORDER
FROM ref_cte_TMEA_ZPRODORDINFO ZPROD
RIGHT JOIN ref_cte_TMEA_PRODUCTION_VALUE_STREAM AS PVS ON PVS.SALES_DOCUMENT = SALES_ORDER
-- WHERE PRD_ORD_TECO <> 'TRUE'
order by tool_number desc
),

PLANNED_ORDERS AS(
SELECT 
PLAF.SALES_ORDER_NUMBER AS SALES_DOCUMENT,
PLAF.PLANNED_ORDER_NUMBER,
PVS.MATERIAL_NUMBER AS TOOL_NUMBER,
PVS.PRODUCT_TYPE_ABBREVIATION,
PVS.PRODUCT_TYPE,

SALES_ORDER_MMR_BUILD_START_MONTH,
SALES_ORDER_MMR_BUILD_START_MONTH_NAME,
SALES_ORDER_MMR_BUILD_START_YEAR,
-- CONFIRMATIONS,
PRD_ORD_YIELD_TO_BE_CONF,
-- UOM_FOR_ACT,
PROD_ORDER_STATUS,

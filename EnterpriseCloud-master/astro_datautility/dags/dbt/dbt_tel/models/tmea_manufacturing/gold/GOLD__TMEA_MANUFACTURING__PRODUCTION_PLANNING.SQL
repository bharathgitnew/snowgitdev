BASIC_END AS PRD_ORD_BASIC_END,
-- CONF_START_OF_EXEC,
-- CONF_FIN_DATE_OF_EXEC,
PRD_ORD_ACT_DLV_FIN_DATE,
PRD_ORD_ACT_DLV_FIN_DATE_YEAR,
PRD_ORD_ACT_DLV_FIN_DATE_MONTH,
PRD_ORD_ACT_DLV_FIN_DATE_MONTH_NAME,
-- PLANNED_CYCLE_TIME_IN_DAYS,
-- ACTUAL_CYCLE_TIME_IN_DAYS,
-- DELTA_CYCLE_TIME_IN_DAYS,
PRD_ORD_PLANNED_CYCLE_TIME_IN_BUSINESS_DAYS,
PRD_ORD_ACTUAL_CYCLE_TIME_IN_BUSINESS_DAYS,
PRD_ORD_DELTA_CYCLE_TIME_IN_BUSINESS_DAYS,
PRD_ORD_ACTUAL_SHIP_DATE,
YEAR(PRD_ORD_ACTUAL_SHIP_DATE) AS PRD_ORD_ACTUAL_SHIP_DATE_YEAR,
MONTH(PRD_ORD_ACTUAL_SHIP_DATE) AS PRD_ORD_ACTUAL_SHIP_DATE_MONTH,
MONTHNAME(PRD_ORD_ACTUAL_SHIP_DATE) AS PRD_ORD_ACTUAL_SHIP_DATE_MONTH_NAME,
-- TOTAL_PLANNED_ORDER_QUANTITY,
ORDER_START_DATE_IN_PLANNED_ORDER,
ORDER_FINISH_DATE_IN_THE_PLANNED_ORDER,
CASE
    WHEN PRD_ORD_BASIC_START IS NULL THEN ORDER_START_DATE_IN_PLANNED_ORDER
    ELSE PRD_ORD_BASIC_START
    END AS PRD_PLN_START,
CASE
    WHEN PRD_ORD_BASIC_END IS NULL THEN ORDER_FINISH_DATE_IN_THE_PLANNED_ORDER
    ELSE PRD_ORD_BASIC_END
    END AS PRD_PLN_END
FROM PROD_PLN_UNION
),

OP_LEVEL AS(
SELECT 
SALES_ORDER,
PRD_ORDER AS OP_PRD_ORD,
ACTIVITY_NBR AS OP_ACTIVITY_NBR,
BASIC_START AS OP_BASIC_START,
BASIC_END AS OP_BASIC_END,
-- MATERIAL AS OP_MATERIAL,
-- MATERIAL_DESCRIPTION AS OP_MATERIAL_DESCRIPTION,
ORD_QTY AS OP_ORD_QTY, 
STD_WORK AS OP_STD_WORK,
(OP_ORD_QTY * OP_STD_WORK) AS OP_STANDARD_HOURS_RELEASED,
PREV_CONF_ACTIVITY AS OP_ACTUAL_HOURS_ENTERED,
contains(ITEM_STATUS,'PCNF') AS OP_LEVEL_PCNF,
contains(ITEM_STATUS,'CNF') AS OP_LEVEL_CNF,
contains(ITEM_STATUS,'TECO') AS OP_LEVEL_TECO,
CASE
    WHEN (OP_LEVEL_PCNF = 'TRUE' OR OP_LEVEL_CNF = 'TRUE') THEN OP_STANDARD_HOURS_RELEASED
    WHEN (OP_LEVEL_PCNF = 'FALSE' OR OP_LEVEL_CNF = 'FALSE') THEN 0
    END AS OP_TOTAL_COMPLETED_STD_WORK,
CONCAT(activity_nbr, ' ',op_short_text) AS OP_TASK
FROM ref_cte_TMEA_PRODUCTION_OPERATION_LEVEL_SYSTEM_STATUS
-- WHERE OP_LEVEL_TECO = 'FALSE'
),

OUTPUT AS(
SELECT * FROM PROD_PLN
LEFT JOIN OP_LEVEL ON PROD_PLN.PRD_ORDER = OP_LEVEL.OP_PRD_ORD AND PROD_PLN.ACTIVITY_NBR = OP_LEVEL.OP_ACTIVITY_NBR
),


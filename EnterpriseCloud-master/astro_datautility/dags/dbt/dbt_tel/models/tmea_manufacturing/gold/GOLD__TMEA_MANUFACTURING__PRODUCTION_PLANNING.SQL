NULL AS SALES_ORDER_MMR_BUILD_START_MONTH_NAME,
NULL AS SALES_ORDER_MMR_BUILD_START_YEAR,
NULL AS PRD_ORDER,
NULL AS CONFIRMATIONS,
NULL AS PRD_ORD_YIELD_TO_BE_CONF,
NULL AS UOM_FOR_ACT,
NULL AS PROD_ORDER_STATUS,
NULL AS PRD_ORD_STANDARD_HOURS_RELEASED,
NULL AS PRD_ORD_DLV,
NULL AS PRD_ORD_TECO,
NULL AS PRD_ORD_TOTAL_COMPLETED_STD_WORK,
NULL AS BASIC_START,
NULL AS BASIC_START_YEAR,
NULL AS BASIC_START_MONTH,
NULL AS BASIC_START_MONTH_NAME,
NULL AS BASIC_END,
NULL AS CONF_START_OF_EXEC,
NULL AS CONF_FIN_DATE_OF_EXEC,
NULL AS PRD_ORD_ACT_DLV_FIN_DATE,
NULL AS PRD_ORD_ACT_DLV_FIN_DATE_YEAR,
NULL AS PRD_ORD_ACT_DLV_FIN_DATE_MONTH,
NULL AS PRD_ORD_ACT_DLV_FIN_DATE_MONTH_NAME,
NULL AS PRD_ORD_PLANNED_CYCLE_TIME_IN_DAYS,
NULL AS PRD_ORD_ACTUAL_CYCLE_TIME_IN_DAYS,
NULL AS PRD_ORD_DELTA_CYCLE_TIME_IN_DAYS,
NULL AS PRD_ORD_PLANNED_CYCLE_TIME_IN_BUSINESS_DAYS,
NULL AS PRD_ORD_ACTUAL_CYCLE_TIME_IN_BUSINESS_DAYS,
NULL AS PRD_ORD_DELTA_CYCLE_TIME_IN_BUSINESS_DAYS,
NULL AS PRD_ORD_ACTUAL_SHIP_DATE,
PLAF.TOTAL_PLANNED_ORDER_QUANTITY,
PLAF.ORDER_START_DATE_IN_PLANNED_ORDER,
PLAF.ORDER_FINISH_DATE_IN_THE_PLANNED_ORDER
FROM ref_cte_PLANNED_ORDER    PLAF
RIGHT JOIN ref_cte_TMEA_PRODUCTION_VALUE_STREAM AS PVS ON PVS.SALES_DOCUMENT = SALES_ORDER_NUMBER
LEFT JOIN ref_cte_MATERIAL_DESCRIPTIONS    MAKT ON PLAF.PLANNING_MATERIAL = MAKT.MATERIAL_NUMBER
WHERE PLANNING_PLANT = '0010'
AND SALES_ORDER_NUMBER IS NOT NULL
AND IS_DELETED = 'No'
),

PROD_PLN_UNION AS (
SELECT * FROM PRODUCTION_ORDERS
UNION  
SELECT * FROM PLANNED_ORDERS
),

PROD_PLN AS(
SELECT 
SALES_DOCUMENT,
PLANNED_ORDER_NUMBER,
PRD_ORDER,
TOOL_NUMBER,
PRODUCT_TYPE_ABBREVIATION,
-- PRODUCT_TYPE,
-- PRODUCTION_ORDER_NUMBER_FOR_A_LEVEL,
MATERIAL,
MATERIAL_DESCRIPTION,
CASE
    WHEN PLANNED_ORDER_NUMBER IS NULL THEN 'PRD'
    ELSE 'PLN'
    END AS TYPE,
CONCAT(TYPE, ': ', IFNULL(PRD_ORDER, PLANNED_ORDER_NUMBER),' ',MATERIAL , ' ', MATERIAL_DESCRIPTION) AS PROD_TASK,
-- //CONCAT(PRD_ORDER, ' ',MATERIAL , ' ',ACTIVITY_NBR) AS CHECKOUT_TASK,
ACTIVITY_NBR,
-- STD_TEXT_KEY,
-- OP_SHORT_TEXT,
-- ORD_QTY,
-- STD_WORK,
-- STD_WRK_UOM,
-- PREV_CONF_YIELD,

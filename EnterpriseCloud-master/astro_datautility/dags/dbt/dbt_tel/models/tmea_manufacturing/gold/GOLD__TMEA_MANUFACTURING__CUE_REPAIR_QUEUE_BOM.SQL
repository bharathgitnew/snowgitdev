    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='CUE_REPAIR_QUEUE_BOM',
    	transient=false
) }}

WITH ref_cte_MATERIAL_DESCRIPTIONS as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__MATERIAL_DESCRIPTIONS') }}
),

ref_cte_PURCHASE_REQUISITION as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__PURCHASE_REQUISITION') }}
),

ref_cte_RESERVATIONDEPENDENT_REQUIREMENTS as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__RESERVATIONDEPENDENT_REQUIREMENTS') }}
),

ref_cte_SCHEDULING_AGREEMENT_SCHEDULE_LINES as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SCHEDULING_AGREEMENT_SCHEDULE_LINES') }}
),

ref_cte_STORAGE_LOCATION_DATA_FOR_MATERIAL as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__STORAGE_LOCATION_DATA_FOR_MATERIAL') }}
),


OPEN_ORDERS AS(
SELECT 
TMEA_SALES_DOCUMENT AS SALES_DOCUMENT,
TMEA_ORDER_NUMBER AS ORDER_NUMBER_
FROM {{ ref('GOLD__TMEA_MANUFACTURING__CUE_DASHBOARD') }}
WHERE TECHNICAL_COMPLETION_DATE IS NULL
AND ORDER_NUMBER_ IS NOT NULL
),

COMPONENTS AS(
SELECT
NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS,
ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS,
ORDER_NUMBER,
CASE
    WHEN MATERIAL_NUMBER IS NULL THEN BOM_ITEM_TEXT_LINE_1
    WHEN MATERIAL_NUMBER = ' ' THEN BOM_ITEM_TEXT_LINE_1
    ELSE MATERIAL_NUMBER
END AS MATERIAL,
ITEM_TEXT,
REQUIREMENT_QUANTITY,
QUANTITY_WITHDRAWN
FROM ref_cte_RESERVATIONDEPENDENT_REQUIREMENTS    RESB
WHERE ORDER_NUMBER IS NOT NULL
    AND ORDER_NUMBER <> ' '
),

PURCHASE_REQ_INFO AS(
SELECT
RESB.NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS AS PK1,
RESB.ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS AS PK2,
RESB.SALES_ORDER_NUMBER,
RESB.ITEM_NUMBER_IN_SALES_ORDER,
RESB.ORDER_NUMBER,
RESB.ORDER_ITEM_NUMBER,
EBAN.QUANTITY_ORDERED_AGAINST_THIS_PURCHASE_REQUISITION,
EBAN.ITEM_DELIVERY_DATE,
EKET.ITEM_DELIVERY_DATE AS DLV_DATE,
CASE
    WHEN EBAN.PURCHASE_ORDER_NUMBER IS NULL THEN EBAN.ITEM_DELIVERY_DATE
    ELSE EKET.ITEM_DELIVERY_DATE
    END AS DELIVERY_DATE,
EBAN.PURCHASE_REQUISITION_NUMBER,
EBAN.PURCHASE_ORDER_NUMBER,
EBAN.PURCHASING_DOCUMENT_CREATION_DATE,
EBAN.PURCHASE_ORDER_DATE,
EBAN.PURCHASE_REQUISITION_RELEASE_DATE
FROM ref_cte_RESERVATIONDEPENDENT_REQUIREMENTS    RESB
LEFT JOIN ref_cte_PURCHASE_REQUISITION    EBAN 
    ON RESB.NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS = EBAN.SETTLEMENT_RESERVATION_NUMBER
    AND RESB.ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS = EBAN.ITEM_NUMBER_OF_THE_SETTLEMENT_RESERVATION
LEFT JOIN ref_cte_SCHEDULING_AGREEMENT_SCHEDULE_LINES    EKET
    ON EKET.PURCHASING_DOCUMENT_NUMBER = EBAN.PURCHASE_ORDER_NUMBER
    AND EKET.PURCHASE_REQUISITION_NUMBER = EBAN.PURCHASE_REQUISITION_NUMBER
WHERE RESB.DIRECT_PROCUREMENT_INDICATOR = 'F'

),

MARD AS(
SELECT 
MATERIAL_NUMBER,
VALUATED_UNRESTRICTED_USE_STOCK AS ON_HAND_QTY
FROM ref_cte_STORAGE_LOCATION_DATA_FOR_MATERIAL    MARD
WHERE MARD.PLANT = '0010'
AND MARD.STORAGE_LOCATION = '0010'
),

OUTPUT AS(
SELECT * FROM OPEN_ORDERS
LEFT JOIN COMPONENTS
    ON OPEN_ORDERS.ORDER_NUMBER_ = COMPONENTS.ORDER_NUMBER
LEFT JOIN PURCHASE_REQ_INFO
    ON PURCHASE_REQ_INFO.PK1 = COMPONENTS.NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS
    AND PURCHASE_REQ_INFO.PK2 = COMPONENTS.ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS
LEFT JOIN MARD
    ON MARD.MATERIAL_NUMBER = COMPONENTS.MATERIAL
LEFT JOIN ref_cte_MATERIAL_DESCRIPTIONS    MAKT
    ON MAKT.MATERIAL_NUMBER = COMPONENTS.MATERIAL
),

source_data as (
SELECT SALES_DOCUMENT,
ORDER_NUMBER_,
MATERIAL,
MATERIAL_DESCRIPTION,
ITEM_TEXT,
REQUIREMENT_QUANTITY,
QUANTITY_WITHDRAWN,
ON_HAND_QTY,
PURCHASE_REQUISITION_NUMBER,
PURCHASE_ORDER_NUMBER,
QUANTITY_ORDERED_AGAINST_THIS_PURCHASE_REQUISITION,
PURCHASING_DOCUMENT_CREATION_DATE AS PURCHASE_REQUISITION_CREATE_DATE,
PURCHASE_ORDER_DATE AS PO_CREATE_DATE,
DELIVERY_DATE AS ITEM_DELIVERY_DATE

FROM OUTPUT  
ORDER BY SALES_DOCUMENT ASC),

transform_data as (
select 	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	SALES_DOCUMENT,
	ORDER_NUMBER_,
	MATERIAL,
	MATERIAL_DESCRIPTION,
	ITEM_TEXT,
	REQUIREMENT_QUANTITY,
	QUANTITY_WITHDRAWN,
	ON_HAND_QTY,
	PURCHASE_REQUISITION_NUMBER,
	PURCHASE_ORDER_NUMBER,
	QUANTITY_ORDERED_AGAINST_THIS_PURCHASE_REQUISITION,
	PURCHASE_REQUISITION_CREATE_DATE,
	PO_CREATE_DATE,
	ITEM_DELIVERY_DATE

from source_data
),

type_data as (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	CAST(SALES_DOCUMENT as VARCHAR(16777216)) as SALES_DOCUMENT,
	CAST(ORDER_NUMBER_ as VARCHAR(16777216)) as ORDER_NUMBER_,
	CAST(MATERIAL as VARCHAR(16777216)) as MATERIAL,
	CAST(MATERIAL_DESCRIPTION as VARCHAR(16777216)) as MATERIAL_DESCRIPTION,
	CAST(ITEM_TEXT as VARCHAR(16777216)) as ITEM_TEXT,
	CAST(REQUIREMENT_QUANTITY as NUMBER(38,10)) as REQUIREMENT_QUANTITY,
	CAST(QUANTITY_WITHDRAWN as NUMBER(38,10)) as QUANTITY_WITHDRAWN,
	CAST(ON_HAND_QTY as NUMBER(38,10)) as ON_HAND_QTY,
	CAST(PURCHASE_REQUISITION_NUMBER as VARCHAR(16777216)) as PURCHASE_REQUISITION_NUMBER,
	CAST(PURCHASE_ORDER_NUMBER as VARCHAR(16777216)) as PURCHASE_ORDER_NUMBER,
	CAST(QUANTITY_ORDERED_AGAINST_THIS_PURCHASE_REQUISITION as NUMBER(38,10)) as QUANTITY_ORDERED_AGAINST_THIS_PURCHASE_REQUISITION,
	CAST(PURCHASE_REQUISITION_CREATE_DATE as DATE) as PURCHASE_REQUISITION_CREATE_DATE,
	CAST(PO_CREATE_DATE as DATE) as PO_CREATE_DATE,
	CAST(ITEM_DELIVERY_DATE as DATE) as ITEM_DELIVERY_DATE
from transform_data 
)
select * from type_data
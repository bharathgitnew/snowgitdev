WITH ref_cte_CUE_REPAIR_TICKET_ONLINE as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__CUE_REPAIR_TICKET_ONLINE') }}
),

ref_cte_GENERAL_DATA_IN_CUSTOMER_MASTER as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__GENERAL_DATA_IN_CUSTOMER_MASTER') }}
),

ref_cte_INCOMING_PART_INSPECTION_ONLINE as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__INCOMING_PART_INSPECTION_ONLINE') }}
),

ref_cte_ORDER_ITEM as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_ITEM') }}
),

ref_cte_ORDER_MASTER_DATA as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_MASTER_DATA') }}
),

ref_cte_REJECTION_REASONS_FOR_SALES_DOCUMENTS_TEXTS as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__REJECTION_REASONS_FOR_SALES_DOCUMENTS_TEXTS') }}
),

ref_cte_SALES_DOCUMENT_FLOW as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_FLOW') }}
),

ref_cte_SALES_DOCUMENT_HEADER_DATA as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_HEADER_DATA') }}
),

ref_cte_SALES_DOCUMENT_ITEM_CATEGORIES_TEXTS as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_ITEM_CATEGORIES_TEXTS') }}
),

ref_cte_SALES_DOCUMENT_ITEM_DATA as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_ITEM_DATA') }}
),

ref_cte_SALES_DOCUMENT_BUSINESS_DATA as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_DOCUMENT_BUSINESS_DATA') }}
),

ref_cte_RMA_SAPH as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__RMA_SAPH') }}
),

ref_cte_SALES_ORDER_BILLING_PLAN as (
    select * from {{ ref('SILVER__TMEA_MANUFACTURING__SALES_ORDER_BILLING_PLAN') }}
),

 ref_cte_ZCDV_T_CMTU090_AUFK as (
     select * from {{ ref('BRONZE__TMEA_MANUFACTURING__SAPAPI_ZCDV_T_CMTU090_AUFK') }}
 ),

SALES_DOCS AS(
select 
VBAK.SALES_DOCUMENT,
VBAP.SALES_DOCUMENT_ITEM,
VBAK.SALES_DOCUMENT_TYPE,
VBAK.NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
VBKD.YOUR_REFERENCE,
VBAP.SALES_DOCUMENT_ITEM_CATEGORY,
VBAP.MATERIAL_NUMBER_USED_BY_CUSTOMER,
CASE
    WHEN MATERIAL_NUMBER LIKE 'CT%' THEN 'CT'
    WHEN MATERIAL_NUMBER LIKE 'RE%' THEN 'RE'
    WHEN MATERIAL_NUMBER LIKE 'ES%' THEN 'ES'
    ELSE 'OTHER'
        END AS REPAIR_TYPE,
VBAP.MATERIAL_NUMBER,
VBAP.SHORT_TEXT_FOR_SALES_ORDER_ITEM,
VBAK.DATE_ON_WHICH_RECORD_WAS_CREATED,
TO_DECIMAL(VBAK.NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY,10,2) AS NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY,
VBAK.SD_DOCUMENT_CURRENCY,
VBAK.CUSTOMER_PURCHASE_ORDER_NUMBER,
VBAK.CUSTOMER_PURCHASE_ORDER_DATE,
VBAK.REQUESTED_DELIVERY_DATE,
KNA1.NAME_1 AS TMEA_CUSTOMER
from ref_cte_SALES_DOCUMENT_HEADER_DATA    VBAK
JOIN ref_cte_SALES_DOCUMENT_ITEM_DATA    VBAP
    ON VBAK.SALES_DOCUMENT = VBAP.SALES_DOCUMENT
    AND VBAK.CLIENT = VBAP.CLIENT
LEFT JOIN ref_cte_GENERAL_DATA_IN_CUSTOMER_MASTER     KNA1
    ON VBAK.SOLD_TO_PARTY = KNA1.CUSTOMER_NUMBER
    AND VBAK.CLIENT = KNA1.CLIENT
LEFT JOIN ref_cte_SALES_DOCUMENT_BUSINESS_DATA VBKD
    ON VBAP.SALES_DOCUMENT = VBKD.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
    AND VBAP.SALES_DOCUMENT_ITEM = VBKD.ITEM_NUMBER_OF_THE_SD_DOCUMENT
WHERE VBAK.CLIENT = '300'
AND VBAK.SALES_ORGANIZATION = '0010'
AND VBAK.SALES_DOCUMENT_TYPE = 'ZRAS' 
AND VBAP.SALES_DOCUMENT_ITEM = '000101'
AND VBAP.SHORT_TEXT_FOR_SALES_ORDER_ITEM NOT LIKE 'REPAIR%'
AND VBAK.DATE_ON_WHICH_RECORD_WAS_CREATED > '2020-08-01'
order by sales_document,sales_document_item
),


ORDER_MASTER_DATA AS(
SELECT 
AUFK.SALES_ORDER_NUMBER,
AUFK.ORDER_NUMBER,
AUFK.ENTERED_BY,
AUFK.CREATED_ON AS SERVICE_ORDER_CREATED_DATE,
AUFK.TECHNICAL_COMPLETION_DATE
FROM ref_cte_ORDER_MASTER_DATA    AUFK
),


ACTUAL_SHIP AS(
SELECT 
PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
max(DATE_ON_WHICH_RECORD_WAS_CREATED) AS ACTUAL_SHIP_DATE
FROM ref_cte_SALES_DOCUMENT_FLOW    VBFA
WHERE DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = 'R'
AND MOVEMENT_TYPE_ = '601'
GROUP BY PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT
),

REJECTED_ORDERS AS(
SELECT DISTINCT
SALES_DOCUMENT AS SD,
REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS
from ref_cte_sales_document_item_data
where REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS IS NOT NULL 
AND REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS <> ' '
ORDER BY SALES_DOCUMENT DESC
),


REJECTION_REASONS AS (
SELECT 
REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS,
DESCRIPTION
FROM ref_cte_REJECTION_REASONS_FOR_SALES_DOCUMENTS_TEXTS    TVAGT
WHERE LANGUAGE_KEY = 'E'
AND CLIENT = '300'
),

REPAIR_RATE AS (
select DISTINCT
VBAP.SALES_DOCUMENT AS RR_SALES_DOCUMENT,  
max(VBAP.SALES_DOCUMENT_ITEM) AS RR_SALES_DOCUMENT_ITEM,
TVAPT.DESCRIPTION AS REPAIR_RATE_DESCRIPTION
from ref_cte_sales_document_item_data    VBAP
JOIN ref_cte_SALES_DOCUMENT_ITEM_CATEGORIES_TEXTS    TVAPT
    ON VBAP.SALES_DOCUMENT_ITEM_CATEGORY = TVAPT.SALES_DOCUMENT_ITEM_CATEGORY
WHERE TVAPT.LANGUAGE_KEY = 'E'
AND TVAPT.CLIENT = '300'
group by RR_SALES_DOCUMENT,REPAIR_RATE_DESCRIPTION
order by sales_document desc
),

AVERAGE_REVENUE AS(
SELECT 
VBAP.MATERIAL_NUMBER AS MATERIAL_NUMBER1,
TO_DECIMAL(AVG(NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY),10,2) AS AVERAGE_REVENUE
from ref_cte_SALES_DOCUMENT_HEADER_DATA    VBAK
JOIN ref_cte_SALES_DOCUMENT_ITEM_DATA    VBAP
    ON VBAK.SALES_DOCUMENT = VBAP.SALES_DOCUMENT
    AND VBAK.CLIENT = VBAP.CLIENT
WHERE VBAK.CLIENT = '300'
AND VBAK.SALES_ORGANIZATION = '0010'
AND VBAK.SALES_DOCUMENT_TYPE = 'ZRAS' 
AND VBAP.SALES_DOCUMENT_ITEM = '000101'
AND VBAP.SHORT_TEXT_FOR_SALES_ORDER_ITEM NOT LIKE 'REPAIR%'
AND VBAK.DATE_ON_WHICH_RECORD_WAS_CREATED > '2021-08-01'
GROUP BY MATERIAL_NUMBER,SHORT_TEXT_FOR_SALES_ORDER_ITEM
),

REPAIR_TICKET AS(
SELECT
INSERT (TMEA_RMA_SALES_ORDER,1,0,'00') AS TMEA_RMA_SALES_ORDER,
SERIAL,
TO_DATE(REPAIR_START_DATE) AS REPAIR_START_DATE,
TO_DATE(REPAIR_COMPLETION_DATE) AS REPAIR_COMPLETION_DATE,
TO_DATE(ESTIMATED_COMPLETION_DATE) AS ESTIMATED_COMPLETION_DATE,
COMMENTS AS REPAIR_TICKET_COMMENTS
FROM ref_cte_CUE_REPAIR_TICKET_ONLINE
),

INCOMING_INSPECTION AS(
SELECT 
INSERT (TMEA_RMA_SALES_ORDER,1,0,'00') AS TMEA_RMA_SALES_ORDER1,
TMEA_SERVICE_WORK_ORDER,
TO_DATE(CREATED) AS INCOMING_PART_INSPECTION_CREATE_DATE,
TO_DATE(PRICING_INFO_SENT_TO_TMEA) AS PRICING_INFO_SENT_TO_TMEA
FROM ref_cte_INCOMING_PART_INSPECTION_ONLINE
),

RMA_SAPH as (
select distinct 
RMA_SAPH.SO_HDR,
RMA_SAPH.VENDOR_RMA_NUMBER,
RMA_SAPH.PO_RMA_NUMBER,
RMA_SAPH.CUSTOMER_DESC,
TRY_TO_DATE(SALES_ORDER_BILLING_PLAN.VBAK_DELIVERY_CREATE_DATE, 'YYYYMMDD') AS TEA_SALES_ORDER_CREATED_DATE,
TRY_TO_DATE(VBAK_CUSTOMER_REFERENCE_DATE, 'YYYYMMDD') AS TEA_CUSTOMER_PURCHASE_ORDER_DATE,
TRY_TO_DATE(IDAT2,'YYYYMMDD') AS TEA_CMP_DATE
from ref_cte_RMA_SAPH AS RMA_SAPH
LEFT JOIN ref_cte_SALES_ORDER_BILLING_PLAN AS SALES_ORDER_BILLING_PLAN
    ON SALES_ORDER_BILLING_PLAN.VBAK_SALES_DOCUMENT = RMA_SAPH.SO_HDR
LEFT JOIN ref_cte_ZCDV_T_CMTU090_AUFK AS AUFK
    ON RMA_SAPH.SO_HDR = AUFK.KDAUF
where vendor = 'BA0013600'
),

MAIN AS(
SELECT * FROM SALES_DOCS
LEFT JOIN ORDER_MASTER_DATA 
    ON SALES_DOCS.SALES_DOCUMENT = ORDER_MASTER_DATA.SALES_ORDER_NUMBER 
LEFT JOIN ACTUAL_SHIP 
    ON SALES_DOCS.SALES_DOCUMENT = ACTUAL_SHIP.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT
LEFT JOIN REJECTED_ORDERS 
    ON SALES_DOCS.SALES_DOCUMENT = REJECTED_ORDERS.SD
LEFT JOIN REJECTION_REASONS 
    ON REJECTED_ORDERS.REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS = REJECTION_REASONS.REASON_FOR_REJECTION_OF_QUOTATIONS_AND_SALES_ORDERS
LEFT JOIN REPAIR_TICKET 
    ON SALES_DOCS.SALES_DOCUMENT = REPAIR_TICKET.TMEA_RMA_SALES_ORDER
LEFT JOIN INCOMING_INSPECTION 
    ON SALES_DOCS.SALES_DOCUMENT = INCOMING_INSPECTION.TMEA_RMA_SALES_ORDER1
LEFT JOIN AVERAGE_REVENUE 
    ON SALES_DOCS.MATERIAL_NUMBER = AVERAGE_REVENUE.MATERIAL_NUMBER1
LEFT JOIN REPAIR_RATE 
    ON SALES_DOCS.SALES_DOCUMENT = REPAIR_RATE.RR_SALES_DOCUMENT
    AND SALES_DOCS.SALES_DOCUMENT_ITEM = REPAIR_RATE.RR_SALES_DOCUMENT_ITEM
LEFT JOIN RMA_SAPH
    ON RMA_SAPH.PO_RMA_Number = SALES_DOCS.YOUR_REFERENCE
),

source_data as (
SELECT SALES_DOCUMENT AS TMEA_SALES_DOCUMENT,
CUSTOMER_PURCHASE_ORDER_NUMBER,
YOUR_REFERENCE AS TMEA_REFERENCE,
PO_RMA_Number AS TEA_RMA,
ORDER_NUMBER AS TMEA_ORDER_NUMBER,
REPAIR_RATE_DESCRIPTION,
DESCRIPTION AS REJECTION_REASON,
NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
MATERIAL_NUMBER_USED_BY_CUSTOMER,
REPAIR_TYPE,
MATERIAL_NUMBER,
SHORT_TEXT_FOR_SALES_ORDER_ITEM,
TMEA_CUSTOMER,
CUSTOMER_DESC AS TEA_CUSTOMER,
CASE 
    WHEN ORDER_NUMBER IS NULL THEN 'UNBOOKED_REVENUE'
    WHEN TECHNICAL_COMPLETION_DATE IS NOT NULL THEN 'REVENUE' 
    ELSE 'BOOKED_REVENUE'
    END AS REVENUE_TYPE,
NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY,
TO_DECIMAL(SUM(NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY) OVER (PARTITION BY YEAR(DATE_ON_WHICH_RECORD_WAS_CREATED) ORDER BY DATE_ON_WHICH_RECORD_WAS_CREATED ASC),10,2) AS YEARLY_RUNNING_TOTAL,
CASE
    WHEN REVENUE_TYPE = 'REVENUE' THEN NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY
    ELSE AVERAGE_REVENUE
    END AS REPAIR_REVENUE,
SD_DOCUMENT_CURRENCY,
TEA_SALES_ORDER_CREATED_DATE,
DATE_ON_WHICH_RECORD_WAS_CREATED AS TMEA_SALES_ORDER_CREATED_DATE,
SERVICE_ORDER_CREATED_DATE AS TMEA_SERVICE_ORDER_CREATED_DATE,
INCOMING_PART_INSPECTION_CREATE_DATE AS TMEA_INCOMING_PART_INSPECTION_CREATE_DATE,
PRICING_INFO_SENT_TO_TMEA AS TMEA_PRICING_INFO_SENT_TO_ORDER_ADMIN,
TEA_CUSTOMER_PURCHASE_ORDER_DATE,
CUSTOMER_PURCHASE_ORDER_DATE AS TMEA_CUSTOMER_PURCHASE_ORDER_DATE,
REPAIR_START_DATE,
REPAIR_COMPLETION_DATE,
TECHNICAL_COMPLETION_DATE,
ESTIMATED_COMPLETION_DATE,
CASE
    WHEN TECHNICAL_COMPLETION_DATE IS NOT NULL THEN TECHNICAL_COMPLETION_DATE
    ELSE ESTIMATED_COMPLETION_DATE    
    END AS REPAIR_REVENUE_DATE,
YEAR(REPAIR_REVENUE_DATE) AS REPAIR_REVENUE_DATE_YEAR,
MONTH(REPAIR_REVENUE_DATE) AS REPAIR_REVENUE_DATE_MONTH,
MONTHNAME(REPAIR_REVENUE_DATE) AS REPAIR_REVENUE_DATE_MONTHNAME,
ACTUAL_SHIP_DATE AS TMEA_ACTUAL_SHIP_DATE,
TEA_CMP_DATE,
REPAIR_TICKET_COMMENTS
FROM MAIN
ORDER BY SALES_DOCUMENT DESC),

transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	TMEA_SALES_DOCUMENT,
	CUSTOMER_PURCHASE_ORDER_NUMBER,
	TMEA_REFERENCE,
	TEA_RMA,
	TMEA_ORDER_NUMBER,
	REPAIR_RATE_DESCRIPTION,
	REJECTION_REASON,
	NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
	MATERIAL_NUMBER_USED_BY_CUSTOMER,
	REPAIR_TYPE,
	MATERIAL_NUMBER,
	SHORT_TEXT_FOR_SALES_ORDER_ITEM,
	TMEA_CUSTOMER,
	TEA_CUSTOMER,
	REVENUE_TYPE,
	NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY,
	YEARLY_RUNNING_TOTAL,
	REPAIR_REVENUE,
	SD_DOCUMENT_CURRENCY,
	TEA_SALES_ORDER_CREATED_DATE,
	TMEA_SALES_ORDER_CREATED_DATE,
	TMEA_SERVICE_ORDER_CREATED_DATE,
	TMEA_INCOMING_PART_INSPECTION_CREATE_DATE,
	TMEA_PRICING_INFO_SENT_TO_ORDER_ADMIN,
	TEA_CUSTOMER_PURCHASE_ORDER_DATE,
	TMEA_CUSTOMER_PURCHASE_ORDER_DATE,
	REPAIR_START_DATE,
	REPAIR_COMPLETION_DATE,
	TECHNICAL_COMPLETION_DATE,
	ESTIMATED_COMPLETION_DATE,
	REPAIR_REVENUE_DATE,
	REPAIR_REVENUE_DATE_YEAR,
	REPAIR_REVENUE_DATE_MONTH,
	REPAIR_REVENUE_DATE_MONTHNAME,
	TMEA_ACTUAL_SHIP_DATE,
	TEA_CMP_DATE,
	REPAIR_TICKET_COMMENTS
from source_data
),

type_data as (
select
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(TMEA_SALES_DOCUMENT AS VARCHAR(16777216)) AS TMEA_SALES_DOCUMENT,
	CAST(CUSTOMER_PURCHASE_ORDER_NUMBER AS VARCHAR(16777216)) AS CUSTOMER_PURCHASE_ORDER_NUMBER,
	CAST(TMEA_REFERENCE AS VARCHAR(16777216)) AS TMEA_REFERENCE,
	CAST(TEA_RMA AS VARCHAR(16777216)) AS TEA_RMA,
	CAST(TMEA_ORDER_NUMBER AS VARCHAR(16777216)) AS TMEA_ORDER_NUMBER,
	CAST(REPAIR_RATE_DESCRIPTION AS VARCHAR(16777216)) AS REPAIR_RATE_DESCRIPTION,
	CAST(REJECTION_REASON AS VARCHAR(16777216)) AS REJECTION_REASON,
	CAST(NAME_OF_PERSON_WHO_CREATED_THE_OBJECT AS VARCHAR(16777216)) AS NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
	CAST(MATERIAL_NUMBER_USED_BY_CUSTOMER AS VARCHAR(16777216)) AS MATERIAL_NUMBER_USED_BY_CUSTOMER,
	CAST(REPAIR_TYPE AS VARCHAR(16777216)) AS REPAIR_TYPE,
	CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
	CAST(SHORT_TEXT_FOR_SALES_ORDER_ITEM AS VARCHAR(16777216)) AS SHORT_TEXT_FOR_SALES_ORDER_ITEM,
	CAST(TMEA_CUSTOMER AS VARCHAR(16777216)) AS TMEA_CUSTOMER,
	CAST(TEA_CUSTOMER AS VARCHAR(16777216)) AS TEA_CUSTOMER,
	CAST(REVENUE_TYPE AS VARCHAR(16777216)) AS REVENUE_TYPE,
	CAST(NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY AS NUMBER(38,10)) AS NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY,
	CAST(YEARLY_RUNNING_TOTAL AS NUMBER(38,10)) AS YEARLY_RUNNING_TOTAL,
	CAST(REPAIR_REVENUE AS NUMBER(38,10)) AS REPAIR_REVENUE,
	CAST(SD_DOCUMENT_CURRENCY AS VARCHAR(16777216)) AS SD_DOCUMENT_CURRENCY,
	CAST(TEA_SALES_ORDER_CREATED_DATE AS DATE) AS TEA_SALES_ORDER_CREATED_DATE,
	CAST(TMEA_SALES_ORDER_CREATED_DATE AS DATE) AS TMEA_SALES_ORDER_CREATED_DATE,
	CAST(TMEA_SERVICE_ORDER_CREATED_DATE AS DATE) AS TMEA_SERVICE_ORDER_CREATED_DATE,
	CAST(TMEA_INCOMING_PART_INSPECTION_CREATE_DATE AS DATE) AS TMEA_INCOMING_PART_INSPECTION_CREATE_DATE,
	CAST(TMEA_PRICING_INFO_SENT_TO_ORDER_ADMIN AS DATE) AS TMEA_PRICING_INFO_SENT_TO_ORDER_ADMIN,
	CAST(TEA_CUSTOMER_PURCHASE_ORDER_DATE AS DATE) AS TEA_CUSTOMER_PURCHASE_ORDER_DATE,
	CAST(TMEA_CUSTOMER_PURCHASE_ORDER_DATE AS DATE) AS TMEA_CUSTOMER_PURCHASE_ORDER_DATE,
	CAST(REPAIR_START_DATE AS DATE) AS REPAIR_START_DATE,
	CAST(REPAIR_COMPLETION_DATE AS DATE) AS REPAIR_COMPLETION_DATE,
	CAST(TECHNICAL_COMPLETION_DATE AS DATE) AS TECHNICAL_COMPLETION_DATE,
	CAST(ESTIMATED_COMPLETION_DATE AS DATE) AS ESTIMATED_COMPLETION_DATE,
	CAST(REPAIR_REVENUE_DATE AS DATE) AS REPAIR_REVENUE_DATE,
	CAST(REPAIR_REVENUE_DATE_YEAR AS NUMBER(38,0)) AS REPAIR_REVENUE_DATE_YEAR,
	CAST(REPAIR_REVENUE_DATE_MONTH AS NUMBER(38,0)) AS REPAIR_REVENUE_DATE_MONTH,
	CAST(REPAIR_REVENUE_DATE_MONTHNAME AS VARCHAR(16777216)) AS REPAIR_REVENUE_DATE_MONTHNAME,
	CAST(TMEA_ACTUAL_SHIP_DATE AS DATE) AS TMEA_ACTUAL_SHIP_DATE,
	CAST(TEA_CMP_DATE AS DATE) AS TEA_CMP_DATE,
	CAST(REPAIR_TICKET_COMMENTS AS VARCHAR(16777216)) AS REPAIR_TICKET_COMMENTS
from transform_data 
)
select * from type_data
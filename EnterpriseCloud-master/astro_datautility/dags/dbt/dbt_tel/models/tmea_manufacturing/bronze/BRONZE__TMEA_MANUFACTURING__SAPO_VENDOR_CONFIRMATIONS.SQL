{{ config(
    materialized='tel_incremental',
    incremental_strategy='merge',
    alias='SAPO_VENDOR_CONFIRMATIONS',
    unique_key = ['MANDT',
    'EBELN',
    'EBELP',
    'ETENS']
) }}

WITH source_data
AS (
	SELECT 
        MANDT,
		EBELN,
		EBELP,
		ETENS,
		EBTYP,
		EINDT,
		LPEIN,
		UZEIT,
		ERDAT,
		EZEIT,
		MENGE,
		DABMG,
		ESTKZ,
		LOEKZ,
		KZDIS,
		XBLNR,
		VBELN,
		VBELP,
		MPROF,
		EMATN,
		MAHNZ,
		CHARG,
		UECHA,
		REF_ETENS,
		IMWRK,
		_CAPTUREDATETIME
	FROM {{ source("SAP_ORACLE_LIVE", "EKES") }}
	),
TRANSFORM_IS_DELETED
AS (
	SELECT 
        TGT.MANDT,
		TGT.EBELN,
		TGT.EBELP,
		TGT.ETENS,
		TGT.EBTYP,
		TGT.EINDT,
		TGT.LPEIN,
		TGT.UZEIT,
		TGT.ERDAT,
		TGT.EZEIT,
		TGT.MENGE,
		TGT.DABMG,
		TGT.ESTKZ,
		TGT.LOEKZ,
		TGT.KZDIS,
		TGT.XBLNR,
		TGT.VBELN,
		TGT.VBELP,
		TGT.MPROF,
		TGT.EMATN,
		TGT.MAHNZ,
		TGT.CHARG,
		TGT.UECHA,
		TGT.REF_ETENS,
		TGT.IMWRK,
		TGT._CAPTUREDATETIME,
		TGT._AUDIT_LOG_ID,
		TGT._ROW_HASH
	FROM {{this}} TGT
	LEFT JOIN source_data SRC ON TGT.MANDT = SRC.MANDT
		AND TGT.EBELN = SRC.EBELN
		AND TGT.EBELP = SRC.EBELP
		AND TGT.ETENS = SRC.ETENS
	WHERE SRC.MANDT IS NULL
	),
TRANSFORM_DATA
AS (
	SELECT 
        MANDT,
		EBELN,
		EBELP,
		ETENS,
		EBTYP,
		EINDT,
		LPEIN,
		UZEIT,
		ERDAT,
		EZEIT,
		MENGE,
		DABMG,
		ESTKZ,
		LOEKZ,
		KZDIS,
		XBLNR,
		VBELN,
		VBELP,
		MPROF,
		EMATN,
		MAHNZ,
		CHARG,
		UECHA,
		REF_ETENS,
		IMWRK,
		_CAPTUREDATETIME,
		'No' AS IS_DELETED,
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('HASH_ME') AS _ROW_HASH -- ADDS COLUMN TO TABLE ON FULL REFRESH.
	FROM source_data
	
	UNION
	
	SELECT 
        MANDT,
		EBELN,
		EBELP,
		ETENS,
		EBTYP,
		EINDT,
		LPEIN,
		UZEIT,
		ERDAT,
		EZEIT,
		MENGE,
		DABMG,
		ESTKZ,
		LOEKZ,
		KZDIS,
		XBLNR,
		VBELN,
		VBELP,
		MPROF,
		EMATN,
		MAHNZ,
		CHARG,
		UECHA,
		REF_ETENS,
		IMWRK,
		_CAPTUREDATETIME,
		'Yes' AS IS_DELETED,
		_AUDIT_LOG_ID,
		SHA2('HASH_ME') AS _ROW_HASH
	FROM TRANSFORM_IS_DELETED
	),
TYPE_DATA
AS (
	SELECT 
		CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
		CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
        CAST(MANDT AS VARCHAR(16777216)) AS MANDT,
		CAST(EBELN AS VARCHAR(16777216)) AS EBELN,
		CAST(EBELP AS VARCHAR(16777216)) AS EBELP,
		CAST(ETENS AS VARCHAR(16777216)) AS ETENS,
		CAST(EBTYP AS VARCHAR(16777216)) AS EBTYP,
		CAST(EINDT AS VARCHAR(16777216)) AS EINDT,
		CAST(LPEIN AS VARCHAR(16777216)) AS LPEIN,
		CAST(UZEIT AS VARCHAR(16777216)) AS UZEIT,
		CAST(ERDAT AS VARCHAR(16777216)) AS ERDAT,
		CAST(EZEIT AS VARCHAR(16777216)) AS EZEIT,
		CAST(MENGE AS NUMBER(38, 10)) AS MENGE,
		CAST(DABMG AS NUMBER(38, 10)) AS DABMG,
		CAST(ESTKZ AS VARCHAR(16777216)) AS ESTKZ,
		CAST(LOEKZ AS VARCHAR(16777216)) AS LOEKZ,
		CAST(KZDIS AS VARCHAR(16777216)) AS KZDIS,
		CAST(XBLNR AS VARCHAR(16777216)) AS XBLNR,
		CAST(VBELN AS VARCHAR(16777216)) AS VBELN,
		CAST(VBELP AS VARCHAR(16777216)) AS VBELP,
		CAST(MPROF AS VARCHAR(16777216)) AS MPROF,
		CAST(EMATN AS VARCHAR(16777216)) AS EMATN,
		CAST(MAHNZ AS NUMBER(38, 10)) AS MAHNZ,
		CAST(CHARG AS VARCHAR(16777216)) AS CHARG,
		CAST(UECHA AS VARCHAR(16777216)) AS UECHA,
		CAST(REF_ETENS AS VARCHAR(16777216)) AS REF_ETENS,
		CAST(IMWRK AS VARCHAR(16777216)) AS IMWRK,
		CAST(IS_DELETED AS VARCHAR(16777216)) AS IS_DELETED
	FROM TRANSFORM_DATA
	)
SELECT *
FROM TYPE_DATA
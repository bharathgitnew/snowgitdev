(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	_CAPTUREDATETIME,
	MANDT AS MANDT,
	PERNR AS PERNR,
	SUBTY AS SUBTY,
	OBJPS AS OBJPS,
	SPRPS AS SPRPS,

{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='SAPO_CHANGE_DOCUMENT_ITEMS',
        unique_key = ['MANDANT',
    'OBJECTCLAS',
    'OBJECTID',
    'CHANGENR',
    'TABNAME',
    'TABKEY',
    'FNAME',
    'CHNGIND'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDANT,
	OBJECTCLAS,
	OBJECTID,
	CHANGENR,
	TABNAME,
	TABKEY,
	FNAME,
	CHNGIND,
	TEXT_CASE,
	UNIT_OLD,
	UNIT_NEW,
	CUKY_OLD,
	CUKY_NEW,
	VALUE_NEW,
	VALUE_OLD,
	_DATAAGING
	FROM {{source('SAP_ORACLE_LIVE', 'CDPOS')}}
),


transform_data as 
(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDANT as MANDANT,
	OBJECTCLAS as OBJECTCLAS,
	OBJECTID as OBJECTID,
	CHANGENR as CHANGENR,
	TABNAME as TABNAME,
	TABKEY as TABKEY,
	FNAME as FNAME,
	CHNGIND as CHNGIND,
	TEXT_CASE as TEXT_CASE,
	UNIT_OLD as UNIT_OLD,
	UNIT_NEW as UNIT_NEW,
	CUKY_OLD as CUKY_OLD,
	CUKY_NEW as CUKY_NEW,
	VALUE_NEW as VALUE_NEW,
	VALUE_OLD as VALUE_OLD,
	_DATAAGING as DATAAGING
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	MANDANT,
	OBJECTCLAS,
	OBJECTID,
	CHANGENR,
	TABNAME,
	TABKEY,
	FNAME,
	CHNGIND,
	TEXT_CASE,
	UNIT_OLD,
	UNIT_NEW,
	CUKY_OLD,
	CUKY_NEW,
	VALUE_NEW,
	VALUE_OLD,
	DATAAGING
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
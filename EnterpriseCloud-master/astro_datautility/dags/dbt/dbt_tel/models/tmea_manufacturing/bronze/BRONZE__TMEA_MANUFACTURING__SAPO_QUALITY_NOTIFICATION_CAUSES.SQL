	INDTX as INDTX,
	KZMLA as KZMLA,
	ERZEIT as ERZEIT,
	AEZEIT as AEZEIT,
	VUKAT as VUKAT,
	VUGRP as VUGRP,
	VUCOD as VUCOD,
	PARVW as PARVW,
	PARNR as PARNR,
	BAUTL as BAUTL,
	URMENGE as URMENGE,
	URMGEIN as URMGEIN,
	KZLOESCH as KZLOESCH,
	QURNUM as QURNUM,
	AUTKZ as AUTKZ,
	INVOLVPERC as INVOLVPERC
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	MANDT,

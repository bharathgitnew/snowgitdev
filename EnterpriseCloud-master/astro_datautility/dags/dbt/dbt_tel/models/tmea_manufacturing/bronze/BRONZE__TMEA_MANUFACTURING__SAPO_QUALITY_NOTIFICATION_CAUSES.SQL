	URMGEIN,
	KZLOESCH,
	QURNUM,
	AUTKZ,
	INVOLVPERC
	FROM {{source('SAP_ORACLE_LIVE', 'QMUR')}}
),


transform_data as 
(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    _CAPTUREDATETIME,
	MANDT as MANDT,
	QMNUM as QMNUM,
	FENUM as FENUM,
	URNUM as URNUM,
	ERNAM as ERNAM,
	ERDAT as ERDAT,
	AENAM as AENAM,
	AEDAT as AEDAT,
	URTXT as URTXT,

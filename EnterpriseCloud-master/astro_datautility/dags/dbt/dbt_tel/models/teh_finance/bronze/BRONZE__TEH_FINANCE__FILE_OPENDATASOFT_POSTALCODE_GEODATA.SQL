{{ config(
        materialized='tel_incremental'    ,
    incremental_strategy='insert_overwrite'    ,
    alias='FILE_OPENDATASOFT_POSTALCODE_GEODATA'    ,
    unique_key= []    ,
    enabled=true
) }}


WITH 
SOURCE_DATA AS (
    SELECT *
    FROM {{ source('FILE', 'OPENDATASOFT_POSTALCODE_GEODATA') }}
),
TRANSFORM_DATA AS (
    SELECT
        COUNTRY_CODE,
        POSTAL_CODE,
        PLACE_NAME,
        ADMIN_NAME1,
        ADMIN_CODE1,
        ADMIN_NAME2,
        ADMIN_CODE2,
        ADMIN_NAME3,
        ADMIN_CODE3,
        LATITUDE,
        LONGITUDE,
        ACCURACY,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        CAST(COUNTRY_CODE AS VARCHAR(16777216)) AS COUNTRY_CODE,
        CAST(POSTAL_CODE AS VARCHAR(16777216)) AS POSTAL_CODE,
        CAST(PLACE_NAME AS VARCHAR(16777216)) AS PLACE_NAME,
        CAST(ADMIN_NAME1 AS VARCHAR(16777216)) AS ADMIN_NAME1,
        CAST(ADMIN_CODE1 AS VARCHAR(16777216)) AS ADMIN_CODE1,
        CAST(ADMIN_NAME2 AS VARCHAR(16777216)) AS ADMIN_NAME2,
        CAST(ADMIN_CODE2 AS VARCHAR(16777216)) AS ADMIN_CODE2,
        CAST(ADMIN_NAME3 AS VARCHAR(16777216)) AS ADMIN_NAME3,
        CAST(ADMIN_CODE3 AS VARCHAR(16777216)) AS ADMIN_CODE3,
        CAST(LATITUDE AS FLOAT) AS LATITUDE,
        CAST(LONGITUDE AS FLOAT) AS LONGITUDE,
        CAST(ACCURACY AS FLOAT) AS ACCURACY,
        CAST(AUDIT_LOG_ID AS VARCHAR(16777216)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA


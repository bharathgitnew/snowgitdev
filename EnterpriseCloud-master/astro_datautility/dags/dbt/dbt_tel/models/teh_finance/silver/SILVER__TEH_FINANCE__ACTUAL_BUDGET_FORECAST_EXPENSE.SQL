    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='ACTUAL_BUDGET_FORECAST_EXPENSE',
        tags=["finance"],
    	transient=false
) }} 

WITH LEDGER_MD AS (
    SELECT DISTINCT
        BASE_GL_TYPE
        , FINANCIAL_ACCOUNT_TYPE
        , FINANCIAL_STATUTORY_CATEGORY
        , ORACLE_CODE
        , SAP_CODE
        , ORACLE_GL_ALIAS
        , SENSITIVE_INDICATOR
        , SECURITY_IS_EXPENSE
        , FOR_EXPENSE_REPORTING
    FROM {{ ref('SILVER__TEH_FINANCE__ORACLE_ACCOUNT_MAP') }}
)
, STD_DEPT_HIERARCHY AS (
    SELECT * FROM {{ ref('SILVER__TEH_FINANCE__ORACLE_STANDARD_DEPT_HIERARCHY') }}
)
, FUNCTIONAL_DEPT_HIERARCHY AS (
    SELECT * FROM {{ ref('SILVER__TEH_FINANCE__ORACLE_FUNCTIONAL_DEPT_HIERARCHY') }}
)
,ORACLE_DEPARTMENT AS (
    SELECT DISTINCT 
        ORACLE_CODE,
        ORACLE_DESCRIPTION 
    FROM {{ ref('SILVER__TEH_FINANCE__SAP_DEPARTMENT') }} 
)
, ABF AS (
    SELECT
        ENTITY
        , SCENARIO
        , YEAR
        , FISCAL_HALF
        , FISCAL_QTR
        , PERIOD
        , ORACLE_ACCOUNT_NUMBER
        , SAP_ACCOUNT_NUMBER
        , SEGMENTCODE AS ORACLE_SEGMENT
        , DEPARTMENTCODE AS ORACLE_DEPARTMENT
        , OFFICECODE AS ORACLE_OFFICE
        , AMOUNT
        , CURRENCY
        , PROFIT_CENTER
        , VERSION
        , FORECASTBUDGET_FILEDATE
    FROM {{ ref('SILVER__TEH_FINANCE__ACTUAL_BUDGET_FORECAST_MASTER') }}
)

,ACTUAL_SOURCE_DATA AS (
    SELECT
        ABF.ENTITY
        , ABF.SCENARIO
        , LEDGER_MD.BASE_GL_TYPE
        , ABF.YEAR
        , ABF.FISCAL_HALF
        , ABF.FISCAL_QTR
        , ABF.PERIOD
        , ABF.ORACLE_SEGMENT
        , STD_DEPT_HIERARCHY.ORACLE_PARENT
        , STD_DEPT_HIERARCHY.ORACLE_PARENT_ALIAS
        , ABF.ORACLE_DEPARTMENT
        , ORACLE_DEPARTMENT.ORACLE_DESCRIPTION AS ORACLE_DEPARTMENT_ALIAS
        , FUNCTIONAL_DEPT_HIERARCHY.FUNCTIONAL_DEPARTMENT
        , ABF.ORACLE_OFFICE
        , ABF.ORACLE_ACCOUNT_NUMBER
        , LEDGER_MD.ORACLE_GL_ALIAS
        , LEDGER_MD.SENSITIVE_INDICATOR
        , LEDGER_MD.FINANCIAL_ACCOUNT_TYPE
        , LEDGER_MD.FINANCIAL_STATUTORY_CATEGORY
        , ABF.AMOUNT
        , ABF.CURRENCY
        , PROFIT_CENTER
        , ABF.VERSION
        , ABF.FORECASTBUDGET_FILEDATE
    FROM ABF
        LEFT JOIN LEDGER_MD
            ON ABF.SAP_ACCOUNT_NUMBER = LEDGER_MD.SAP_CODE
        LEFT JOIN STD_DEPT_HIERARCHY
            ON ABF.ORACLE_DEPARTMENT = STD_DEPT_HIERARCHY.ORACLE_DEPARTMENT
        LEFT JOIN ORACLE_DEPARTMENT
            ON ABF.ORACLE_DEPARTMENT = ORACLE_DEPARTMENT.ORACLE_CODE
        LEFT JOIN FUNCTIONAL_DEPT_HIERARCHY
            ON ABF.ORACLE_DEPARTMENT = FUNCTIONAL_DEPT_HIERARCHY.DEPARTMENT
    WHERE LEDGER_MD.FOR_EXPENSE_REPORTING = 'true'
)
,BUDGET_SOURCE_DATA AS (
    SELECT DISTINCT
        ABF.ENTITY
        , ABF.SCENARIO
        , LEDGER_MD.BASE_GL_TYPE
        , ABF.YEAR
        , ABF.FISCAL_HALF
        , ABF.FISCAL_QTR
        , ABF.PERIOD
        , ABF.ORACLE_SEGMENT
        , STD_DEPT_HIERARCHY.ORACLE_PARENT
        , STD_DEPT_HIERARCHY.ORACLE_PARENT_ALIAS
        , ABF.ORACLE_DEPARTMENT
        , ORACLE_DEPARTMENT.ORACLE_DESCRIPTION AS ORACLE_DEPARTMENT_ALIAS
        , FUNCTIONAL_DEPT_HIERARCHY.FUNCTIONAL_DEPARTMENT
        , ABF.ORACLE_OFFICE
        , ABF.ORACLE_ACCOUNT_NUMBER
        , LEDGER_MD.ORACLE_GL_ALIAS
        , LEDGER_MD.SENSITIVE_INDICATOR
        , LEDGER_MD.FINANCIAL_ACCOUNT_TYPE
        , LEDGER_MD.FINANCIAL_STATUTORY_CATEGORY
        , ABF.AMOUNT
        , ABF.CURRENCY
        , ABF.PROFIT_CENTER
        , ABF.VERSION
        , ABF.FORECASTBUDGET_FILEDATE
    FROM ABF
        LEFT JOIN LEDGER_MD
            ON ABF.ORACLE_ACCOUNT_NUMBER = LEDGER_MD.ORACLE_CODE
        LEFT JOIN STD_DEPT_HIERARCHY
            ON ABF.ORACLE_DEPARTMENT = STD_DEPT_HIERARCHY.ORACLE_DEPARTMENT
        LEFT JOIN ORACLE_DEPARTMENT
            ON ABF.ORACLE_DEPARTMENT = ORACLE_DEPARTMENT.ORACLE_CODE
        LEFT JOIN FUNCTIONAL_DEPT_HIERARCHY
            ON ABF.ORACLE_DEPARTMENT = FUNCTIONAL_DEPT_HIERARCHY.DEPARTMENT
    WHERE LEDGER_MD.FOR_EXPENSE_REPORTING = 'true'
        AND ABF.SCENARIO IN ('Original Budget','Revised Budget')
)
,FORECAST_SOURCE_DATA AS (
    SELECT DISTINCT
        ABF.ENTITY
        , ABF.SCENARIO
        , LEDGER_MD.BASE_GL_TYPE
        , ABF.YEAR
        , ABF.FISCAL_HALF
        , ABF.FISCAL_QTR
        , ABF.PERIOD
        , ABF.ORACLE_SEGMENT
        , STD_DEPT_HIERARCHY.ORACLE_PARENT
        , STD_DEPT_HIERARCHY.ORACLE_PARENT_ALIAS
        , ABF.ORACLE_DEPARTMENT
        , ORACLE_DEPARTMENT.ORACLE_DESCRIPTION AS ORACLE_DEPARTMENT_ALIAS
        , FUNCTIONAL_DEPT_HIERARCHY.FUNCTIONAL_DEPARTMENT
        , ABF.ORACLE_OFFICE
        , ABF.ORACLE_ACCOUNT_NUMBER
        , LEDGER_MD.ORACLE_GL_ALIAS
        , LEDGER_MD.SENSITIVE_INDICATOR
        , LEDGER_MD.FINANCIAL_ACCOUNT_TYPE
        , LEDGER_MD.FINANCIAL_STATUTORY_CATEGORY
        , ABF.AMOUNT
        , ABF.CURRENCY
        , ABF.PROFIT_CENTER
        , ABF.VERSION
        , ABF.FORECASTBUDGET_FILEDATE
    FROM ABF
        LEFT JOIN LEDGER_MD
            ON ABF.ORACLE_ACCOUNT_NUMBER = LEDGER_MD.ORACLE_CODE
        LEFT JOIN STD_DEPT_HIERARCHY
            ON ABF.ORACLE_DEPARTMENT = STD_DEPT_HIERARCHY.ORACLE_DEPARTMENT
        LEFT JOIN ORACLE_DEPARTMENT
            ON ABF.ORACLE_DEPARTMENT = ORACLE_DEPARTMENT.ORACLE_CODE
        LEFT JOIN FUNCTIONAL_DEPT_HIERARCHY
            ON ABF.ORACLE_DEPARTMENT = FUNCTIONAL_DEPT_HIERARCHY.DEPARTMENT
    WHERE LEDGER_MD.FOR_EXPENSE_REPORTING = 'true'
        AND ABF.SCENARIO = 'Forecast'
        
)
,SOURCE_DATA AS (
    SELECT *
    FROM ACTUAL_SOURCE_DATA
    UNION ALL 
    SELECT *
    FROM BUDGET_SOURCE_DATA
    UNION ALL 
    SELECT *
    FROM FORECAST_SOURCE_DATA
)
, PC_NAME AS (
    SELECT
          ENTITY
        , SCENARIO
        , BASE_GL_TYPE AS EXPENSE_ACCOUNT_TYPE
        , YEAR AS FISCAL_YEAR
        , FISCAL_HALF
        , FISCAL_QTR as FISCAL_QUARTER
        , PERIOD AS FISCAL_PERIOD
        , ORACLE_SEGMENT
        , ORACLE_PARENT AS ORACLE_PARENT_DEPARTMENT
        , ORACLE_PARENT_ALIAS AS ORACLE_PARENT_DEPARTMENT_NAME
        , ORACLE_DEPARTMENT
        , ORACLE_DEPARTMENT_ALIAS AS ORACLE_DEPARTMENT_NAME
        , FUNCTIONAL_DEPARTMENT
        , ORACLE_OFFICE
        , ORACLE_ACCOUNT_NUMBER
        , ORACLE_GL_ALIAS AS ORACLE_ACCOUNT_NAME
        , SENSITIVE_INDICATOR
        , FINANCIAL_ACCOUNT_TYPE
        , FINANCIAL_STATUTORY_CATEGORY
        , AMOUNT
        , CURRENCY
        , PROFIT_CENTER
        , PC.PROFIT_CENTER_NAME
        , VERSION
        , FORECASTBUDGET_FILEDATE
    FROM SOURCE_DATA
        LEFT JOIN {{ ref('SILVER__TEH_FINANCE__PROFIT_CENTER') }} AS PC
            ON SOURCE_DATA.PROFIT_CENTER = PC.PROFIT_CENTER_CODE
)
, TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') AS _ROW_HASH
        , ENTITY
        , SCENARIO
        , EXPENSE_ACCOUNT_TYPE
        , FISCAL_YEAR
        , FISCAL_HALF
        , FISCAL_QUARTER
        , FISCAL_PERIOD
        , ORACLE_SEGMENT
        , ORACLE_PARENT_DEPARTMENT
        , ORACLE_PARENT_DEPARTMENT_NAME
        , ORACLE_DEPARTMENT
        , ORACLE_DEPARTMENT_NAME
        , FUNCTIONAL_DEPARTMENT
        , ORACLE_OFFICE
        , ORACLE_ACCOUNT_NUMBER
        , ORACLE_ACCOUNT_NAME
        , SENSITIVE_INDICATOR
        , FINANCIAL_ACCOUNT_TYPE
        , FINANCIAL_STATUTORY_CATEGORY
        , AMOUNT
        , CURRENCY
        , PROFIT_CENTER
        , PROFIT_CENTER_NAME
        , VERSION
        , FORECASTBUDGET_FILEDATE
    FROM PC_NAME
)

, TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        , ENTITY
        , SCENARIO
        , EXPENSE_ACCOUNT_TYPE
        , FISCAL_YEAR
        , FISCAL_HALF
        , FISCAL_QUARTER
        , FISCAL_PERIOD
        , ORACLE_SEGMENT
        , ORACLE_PARENT_DEPARTMENT
        , ORACLE_PARENT_DEPARTMENT_NAME
        , ORACLE_DEPARTMENT
        , ORACLE_DEPARTMENT_NAME
        , FUNCTIONAL_DEPARTMENT
        , ORACLE_OFFICE
        , ORACLE_ACCOUNT_NUMBER
        , ORACLE_ACCOUNT_NAME
        , SENSITIVE_INDICATOR
        , FINANCIAL_ACCOUNT_TYPE 
        , FINANCIAL_STATUTORY_CATEGORY
        , CAST(AMOUNT AS NUMBER(38,2)) AS AMOUNT
        , CURRENCY
        , PROFIT_CENTER
        , PROFIT_CENTER_NAME
        , VERSION
        , FORECASTBUDGET_FILEDATE
    FROM TRANSFORM_DATA 
)

SELECT * FROM TYPE_DATA


WITH LEDGER_MD AS (
    SELECT DISTINCT
        BASE_GL_TYPE
        , SAP_CODE
        , SAP_ACCT_DESCRIPTION
        , FINANCIAL_ACCOUNT_TYPE
        , FINANCIAL_STATUTORY_CATEGORY
        , SENSITIVE_INDICATOR
        , SECURITY_IS_EXPENSE
        , FOR_EXPENSE_REPORTING
    FROM {{ ref('SILVER__TEH_FINANCE__ORACLE_ACCOUNT_MAP') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY SAP_CODE ORDER BY _FILEDATE DESC, _FILEDATE DESC )) = 1
)
, DEPT AS (
    SELECT * FROM {{ ref('SILVER__TEH_FINANCE__SAP_DEPARTMENT') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY ORACLE_CODE ORDER BY _FILEDATE DESC, _FILEDATE DESC )) = 1
)
, STANDARD_DEPT_HIERARCHY AS (
    SELECT DISTINCT
        ORACLE_DEPARTMENT
        , ORACLE_DEPARTMENT_ALIAS
    FROM {{ ref('SILVER__TEH_FINANCE__ORACLE_STANDARD_DEPT_HIERARCHY') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY ORACLE_DEPARTMENT ORDER BY _FILEDATE DESC, _FILEDATE DESC )) = 1
)
, FUNCTIONAL_DEPT_HIERARCHY AS (
    SELECT * FROM {{ ref('SILVER__TEH_FINANCE__ORACLE_FUNCTIONAL_DEPT_HIERARCHY') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY DEPARTMENT ORDER BY _FILEDATE DESC, _FILEDATE DESC )) = 1
)
, SEGMENT AS (
	SELECT 
		ORACLE_CODE,
		ORACLE_DESCRIPTION,
		SAP_CODE,
		SAP_DESCRIPTION,
		BAAN_CODE,
		BAAN_DESCRIPTION
	FROM {{ ref('SILVER__TEH_FINANCE__SAP_SEGMENT') }}
	QUALIFY (ROW_NUMBER() OVER (PARTITION BY SAP_CODE ORDER BY _FILEDATE DESC, _FILEDATE DESC )) = 1
)
, REGION AS (
    SELECT
        ORACLE_CODE,
		ORACLE_DESCRIPTION,
		SAP_CODE,
		SAP_DESCRIPTION,
		BAAN_CODE
    FROM {{ ref('SILVER__TEH_FINANCE__SAP_REGION') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY ORACLE_CODE ORDER BY _FILEDATE DESC, _FILEDATE DESC )) = 1
)
, CALENDAR AS (
	SELECT DISTINCT
        CALENDAR_DATE,
		FISCAL_YEAR_SHORT_TEXT,
	    MONTH_ABBREVIATION_TEXT,
        YEAR_MONTH_TEXT AS REPORTING_PERIOD,
		FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
		FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF,
		FISCAL_YEAR_QUARTER_SHORT_TEXT AS FISCAL_QTR
    FROM {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}
)

, SAP_ACTUALS as (
	SELECT DISTINCT
		'Expense' AS ACCOUNT_TYPE,
		'SAP Actuals'AS SCENARIO,
		DA.CALENDAR_YEAR_MONTH AS REPORTING_PERIOD,
		CALENDAR.FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
		DA.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF,
		DA.SEGMENT_CODE AS SAP_SEGMENT_CODE,
		DA.SEGMENT AS SAP_SEGMENT_NAME,
		SEGMENT.ORACLE_CODE AS ORACLE_SEGMENT_CODE,
		SEGMENT.ORACLE_DESCRIPTION AS ORACLE_SEGMENT_NAME,
		SEGMENT.BAAN_CODE AS BAAN_SEGMENT_CODE,
		SEGMENT.BAAN_DESCRIPTION AS BAAN_SEGMENT_NAME,
		Case
            WHEN DA.SEGMENT LIKE 'Admin' THEN 'Admin'
            WHEN DA.SEGMENT NOT LIKE 'Admin' THEN SUBSTR(DA.SEGMENT,4)
        END AS BU,
		DA.OFFICE_CODE as SAP_OFFICE_CODE,
		DA.OFFICE AS SAP_OFFICE_NAME,
		REGION.ORACLE_CODE AS ORACLE_OFFICE_CODE,
		REGION.ORACLE_DESCRIPTION AS ORACLE_OFFICE_NAME,
		REGION.BAAN_CODE AS BAAN_OFFICE_CODE,
		NULL AS BAAN_OFFICE_NAME,
        DA.DEPARTMENT_CODE AS SAP_DEPARTMENT_CODE,
        DA.DEPARTMENT AS SAP_DEPARTMENT,
        DEPT.ORACLE_CODE AS ORACLE_DEPARTMENT_CODE,
        DEPT.ORACLE_DESCRIPTION
        , DEPT.BAAN_CODE AS BAAN_DEPARTMENT_CODE,
        NULL AS BAAN_DEPARTMENT,
        LEDGER_MD.FINANCIAL_ACCOUNT_TYPE
        , LEDGER_MD.FINANCIAL_STATUTORY_CATEGORY
        , LEDGER_MD.SENSITIVE_INDICATOR
        , DA.PURCHASING_DOCUMENT_NUMBER
        , DA.COST_CENTER
        , DA.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING
		, sum(AMOUNT_IN_COMPANY_CODE_CURRENCY) as amount
	FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS') }} AS DA
    	LEFT JOIN CALENDAR
		    ON DA.POSTING_DATE = CALENDAR.CALENDAR_DATE
	    LEFT JOIN SEGMENT
		    ON DA.SEGMENT_CODE = SEGMENT.SAP_CODE
        LEFT JOIN REGION
		    ON DA.OFFICE_CODE = REGION.SAP_CODE
        LEFT JOIN LEDGER_MD
            ON DA.ACCOUNT_NUMBER = LEDGER_MD.SAP_CODE
        LEFT JOIN DEPT
            ON DA.DEPARTMENT_CODE = DEPT.SAP_CODE
	WHERE 1=1
        AND LEDGER_MD.FOR_EXPENSE_REPORTING = 'true'
    GROUP BY 
		REPORTING_PERIOD,
        DA.CALENDAR_YEAR_MONTH,
        CALENDAR.FISCAL_YEAR_SHORT_TEXT,
        DA.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT,
        DA.SEGMENT_CODE,
        DA.SEGMENT,
        SEGMENT.ORACLE_CODE,
		SEGMENT.ORACLE_DESCRIPTION,
		SEGMENT.BAAN_CODE,
		SEGMENT.BAAN_DESCRIPTION,
        DA.OFFICE_CODE,
        DA.OFFICE,
        REGION.ORACLE_CODE,
		REGION.ORACLE_DESCRIPTION
		, REGION.BAAN_CODE
        , DA.DEPARTMENT_CODE
        , DA.DEPARTMENT
        , DEPT.ORACLE_CODE
        , DEPT.ORACLE_DESCRIPTION
        , DEPT.BAAN_CODE
        , LEDGER_MD.FINANCIAL_ACCOUNT_TYPE
        , LEDGER_MD.FINANCIAL_STATUTORY_CATEGORY
        , LEDGER_MD.SENSITIVE_INDICATOR
        , DA.PURCHASING_DOCUMENT_NUMBER
        , DA.COST_CENTER
        , DA.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING
)

, BAAN_ACTUALS as (
	SELECT
		'Expense' AS ACCOUNT_TYPE,
		'BAAN Actuals' AS SCENARIO,
        CALENDAR_YEAR_MONTH AS REPORTING_PERIOD,
		BAAN.FISCAL_YEAR AS FISCAL_YEAR,
		BAAN.FISCAL_HALF AS FISCAL_HALF,
		SEGMENT.SAP_CODE AS SAP_SEGMENT_CODE,
		SEGMENT.SAP_DESCRIPTION AS SAP_SEGMENT_NAME,
		BAAN.SEGMENT_ORACLE_CODE AS ORACLE_SEGMENT_CODE,
		BAAN.SEGMENT_ORACLE AS ORACLE_SEGMENT_NAME,
		BAAN.SEGMENTCODE AS BAAN_SEGMENT_CODE,
		BAAN.SEGMENTDESCRIPTION AS BAAN_SEGMENT_NAME,
		Case
            When SAP_SEGMENT_NAME like 'Admin' Then 'Admin'
            When SAP_SEGMENT_NAME not like 'Admin' Then SUBSTR(SAP_SEGMENT_NAME,4)
        END AS BU,
		REGION.SAP_CODE AS SAP_OFFICE_CODE,
		REGION.SAP_DESCRIPTION AS SAP_OFFICE_NAME,
		REGION.ORACLE_CODE AS ORACLE_OFFICE_CODE,
		REGION.ORACLE_DESCRIPTION AS ORACLE_OFFICE_NAME,
		BAAN.OFFICECODE AS BAAN_OFFICE_CODE,
		BAAN.OFFICEDESCRIPTION AS BAAN_OFFICE_NAME,
        DEPT.SAP_CODE AS SAP_DEPARTMENT_CODE,
        NULL AS SAP_DEPARTMENT,
        BAAN.ORACLE_DEPARTMENT_CODE,
        BAAN.DEPARTMENTCODE AS BAAN_DEPARTMENT_CODE,
        BAAN.DEPARTMENTDESCRIPTION AS BAAN_DEPARTMENT,
        BAAN.PURCHASEORDERNUMBERANDLINE,
        -- case 
        -- when POSITION('-',PURCHASEORDERNUMBERANDLINE,1)=0
        -- then LEN(PURCHASEORDERNUMBERANDLINE)-1
        -- else POSITION('-',PURCHASEORDERNUMBERANDLINE,1)-1 
        -- end as substr_len,
        -- SUBSTR(PURCHASEORDERNUMBERANDLINE,1,substr_len) as PURCHASEORDERNUMBERANDLINE,
        BAAN.DEPARTMENTCODE AS COST_CENTER,
        FINANCIALDOCUMENTLINEID AS GL,       
		CAST(BAAN.AMOUNT AS NUMBER(38,2)) AS AMOUNT
	FROM {{ ref('BRONZE__TEH_FINANCE__TELUSDWPROD1_FINANCIALTRANSACTIONS') }} as BAAN
		LEFT JOIN SEGMENT
			ON BAAN.SEGMENT_ORACLE_CODE = segment.ORACLE_CODE
		LEFT JOIN REGION
			ON CONCAT('R', TRIM(BAAN.OFFICECODE)) = REGION.ORACLE_CODE
        LEFT JOIN DEPT
            ON BAAN.ORACLE_DEPARTMENT_CODE = DEPT.ORACLE_CODE
	WHERE 1=1
		AND LEFT(BAAN.FINANCIALACCOUNTNUMBER, 1) = '6'
		AND REPORTING_PERIOD < '2023-05'
)

, ACTUALS_BOTH AS (
        SELECT
    		ACCOUNT_TYPE,
    		SCENARIO,
    		REPORTING_PERIOD,
    		FISCAL_YEAR,
    		FISCAL_HALF,
    		SAP_SEGMENT_CODE,
    		SAP_SEGMENT_NAME,
    		ORACLE_SEGMENT_CODE,
    		ORACLE_SEGMENT_NAME,
    		BAAN_SEGMENT_CODE,
    		BAAN_SEGMENT_NAME,
    		BU,
    		SAP_OFFICE_CODE,
    		SAP_OFFICE_NAME,
    		ORACLE_OFFICE_CODE,
    		ORACLE_OFFICE_NAME,
    		BAAN_OFFICE_CODE,
    		BAAN_OFFICE_NAME,
            SAP_DEPARTMENT_CODE,
            SAP_DEPARTMENT,
            ORACLE_DEPARTMENT_CODE,
            BAAN_DEPARTMENT_CODE,
            BAAN_DEPARTMENT,
            PURCHASING_DOCUMENT_NUMBER,
            COST_CENTER,
            LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    		AMOUNT 
    	FROM SAP_ACTUALS

    	UNION ALL

    	SELECT 
    		ACCOUNT_TYPE,
    		SCENARIO,
    		REPORTING_PERIOD,
    		FISCAL_YEAR,
    		FISCAL_HALF,
    		SAP_SEGMENT_CODE,
    		SAP_SEGMENT_NAME,
    		ORACLE_SEGMENT_CODE,
    		ORACLE_SEGMENT_NAME,
    		BAAN_SEGMENT_CODE,
    		BAAN_SEGMENT_NAME,
    		BU,
    		SAP_OFFICE_CODE,
    		SAP_OFFICE_NAME,
    		ORACLE_OFFICE_CODE,
    		ORACLE_OFFICE_NAME,
    		BAAN_OFFICE_CODE,
    		BAAN_OFFICE_NAME,
            SAP_DEPARTMENT_CODE,
            SAP_DEPARTMENT,
            ORACLE_DEPARTMENT_CODE,
            BAAN_DEPARTMENT_CODE,
            BAAN_DEPARTMENT,
            PURCHASEORDERNUMBERANDLINE as PURCHASING_DOCUMENT_NUMBER,
            COST_CENTER,
            GL AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    		AMOUNT 
    	FROM BAAN_ACTUALS
    )
, SOURCE_DATA as (
    SELECT
        ACCOUNT_TYPE,
        SCENARIO,
        REPORTING_PERIOD,
        FISCAL_YEAR,
        FISCAL_HALF,
        SAP_SEGMENT_CODE,
        SAP_SEGMENT_NAME,
        ORACLE_SEGMENT_CODE,
        ORACLE_SEGMENT_NAME,
        BAAN_SEGMENT_CODE,
        BAAN_SEGMENT_NAME,
        BU,
        SAP_OFFICE_CODE,
        SAP_OFFICE_NAME,
        ORACLE_OFFICE_CODE,
        ORACLE_OFFICE_NAME,
        BAAN_OFFICE_CODE,
        BAAN_OFFICE_NAME,
        SAP_DEPARTMENT_CODE,
        SAP_DEPARTMENT,
        ORACLE_DEPARTMENT_CODE,
        BAAN_DEPARTMENT_CODE,
        BAAN_DEPARTMENT,
        PURCHASING_DOCUMENT_NUMBER,
        COST_CENTER,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        AMOUNT
    FROM ACTUALS_BOTH
        LEFT JOIN STANDARD_DEPT_HIERARCHY
            ON ACTUALS_BOTH.ORACLE_DEPARTMENT_CODE = STANDARD_DEPT_HIERARCHY.ORACLE_DEPARTMENT
)

, TRANSFORM_DATA AS (
    SELECT
        ACCOUNT_TYPE,
        SCENARIO,
        REPORTING_PERIOD,
        FISCAL_YEAR,
        FISCAL_HALF,
        SAP_SEGMENT_CODE,
        SAP_SEGMENT_NAME,
        ORACLE_SEGMENT_CODE,
        ORACLE_SEGMENT_NAME,
        BAAN_SEGMENT_CODE,
        BAAN_SEGMENT_NAME,
        BU,
        SAP_OFFICE_CODE,
        SAP_OFFICE_NAME,
        ORACLE_OFFICE_CODE,
        ORACLE_OFFICE_NAME,
        BAAN_OFFICE_CODE,
        BAAN_OFFICE_NAME,
        SAP_DEPARTMENT_CODE,
        SAP_DEPARTMENT,
        ORACLE_DEPARTMENT_CODE,
        BAAN_DEPARTMENT_CODE,
        BAAN_DEPARTMENT,
        PURCHASING_DOCUMENT_NUMBER,
        COST_CENTER,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        AMOUNT,
        '{{ invocation_id }}' AS AUDIT_LOG_ID
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
        CAST(ACCOUNT_TYPE AS VARCHAR(16777216)) AS ACCOUNT_TYPE,
        CAST(SCENARIO AS VARCHAR(16777216)) AS SCENARIO,
        CAST(REPORTING_PERIOD AS VARCHAR(16777216)) AS REPORTING_PERIOD,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(FISCAL_HALF AS VARCHAR(16777216)) AS FISCAL_HALF,
        CAST(SAP_SEGMENT_CODE AS VARCHAR(16777216)) AS SAP_SEGMENT_CODE,
        CAST(SAP_SEGMENT_NAME AS VARCHAR(16777216)) AS SAP_SEGMENT_NAME,
        CAST(ORACLE_SEGMENT_CODE AS VARCHAR(16777216)) AS ORACLE_SEGMENT_CODE,
        CAST(ORACLE_SEGMENT_NAME AS VARCHAR(16777216)) AS ORACLE_SEGMENT_NAME,
        CAST(BAAN_SEGMENT_CODE AS VARCHAR(16777216)) AS BAAN_SEGMENT_CODE,
        CAST(BAAN_SEGMENT_NAME AS VARCHAR(16777216)) AS BAAN_SEGMENT_NAME,
        CAST(BU AS VARCHAR(16777216)) AS BU,
        CAST(SAP_OFFICE_CODE AS VARCHAR(16777216)) AS SAP_OFFICE_CODE,
        CAST(SAP_OFFICE_NAME AS VARCHAR(16777216)) AS SAP_OFFICE_NAME,
        CAST(ORACLE_OFFICE_CODE AS VARCHAR(16777216)) AS ORACLE_OFFICE_CODE,
        CAST(ORACLE_OFFICE_NAME AS VARCHAR(16777216)) AS ORACLE_OFFICE_NAME,
        CAST(BAAN_OFFICE_CODE AS VARCHAR(16777216)) AS BAAN_OFFICE_CODE,
        CAST(BAAN_OFFICE_NAME AS VARCHAR(16777216)) AS BAAN_OFFICE_NAME,
        CAST(SAP_DEPARTMENT_CODE AS VARCHAR(16777216)) AS SAP_DEPARTMENT_CODE,
        CAST(SAP_DEPARTMENT AS VARCHAR(16777216)) AS SAP_DEPARTMENT,
        CAST(ORACLE_DEPARTMENT_CODE AS VARCHAR(16777216)) AS ORACLE_DEPARTMENT_CODE,
        CAST(BAAN_DEPARTMENT_CODE AS VARCHAR(16777216)) AS BAAN_DEPARTMENT_CODE,
        CAST(BAAN_DEPARTMENT AS VARCHAR(16777216)) AS BAAN_DEPARTMENT,
        PURCHASING_DOCUMENT_NUMBER,
        COST_CENTER,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        CAST(AMOUNT AS NUMBER(38,2)) AS AMOUNT,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    FROM TRANSFORM_DATA
)


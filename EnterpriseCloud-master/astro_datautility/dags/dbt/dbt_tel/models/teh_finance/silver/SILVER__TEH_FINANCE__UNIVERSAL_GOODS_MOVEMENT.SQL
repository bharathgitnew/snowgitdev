with vbap_cte as (
    select * from {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU010_VBAP') }}
    where IS_DELETED = 'No'
),

universal_pl_data as
(
        SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        OBJECT_NUMBER,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
        SALES_ORDER_NUMBER,
        ITEM_NUMBER_IN_SALES_ORDER
    FROM {{ ref('SILVER__TEH_FINANCE__SAPH_NEW_ACDOCA_UNIVERSAL_PL_ACCOUNT_TYPE') }} -- General Ledger
    WHERE ACDOCA_BUSINESS_TRANSACTION_TYPE = 'RMWA'
),

OR_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        case when TRIM(AUFK.KDAUF)='' OR TRIM(AUFK.KDPOS)='' then 'NOVALUE' else vbap.zzorty end AS SALES_CATEGORY,
        case when TRIM(AUFK.KDAUF)='' OR TRIM(AUFK.KDPOS)='' then 'NOVALUE' else vbap.VBELN end AS SALES_DOCUMENT,
        case when TRIM(AUFK.KDAUF)='' OR TRIM(AUFK.KDPOS)='' then 'NOVALUE' else vbap.POSNR end AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU090_AUFK') }}  AUFK
            ON universal_pl_data.OBJECT_NUMBER = AUFK.OBJNR
        JOIN vbap_cte  VBAP
            ON AUFK.KDAUF = VBAP.VBELN and AUFK.KDPOS = VBAP.POSNR
    WHERE OBJECT_NUMBER like 'OR%'

),

OV_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        case when TRIM(AUFK.KDAUF)='' OR TRIM(AUFK.KDPOS)='' then 'NOVALUE' else vbap.zzorty end AS SALES_CATEGORY,
        case when TRIM(AUFK.KDAUF)='' OR TRIM(AUFK.KDPOS)='' then 'NOVALUE' else vbap.VBELN end AS SALES_DOCUMENT,
        case when TRIM(AUFK.KDAUF)='' OR TRIM(AUFK.KDPOS)='' then 'NOVALUE' else vbap.POSNR end AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU089_AFVC') }}  AFVC
            ON universal_pl_data.OBJECT_NUMBER = AFVC.OBJNR
        JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU119_AFKO') }}  AFKO
            ON AFVC.AUFPL = AFKO.AUFPL
        JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU090_AUFK') }}  AUFK
            ON AFKO.AUFNR = AUFK.AUFNR
        JOIN vbap_cte  VBAP
            ON AUFK.KDAUF = VBAP.VBELN and AUFK.KDPOS = VBAP.POSNR
    WHERE OBJECT_NUMBER like 'OV%'

),

PR_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        case when trim(VBAP.PS_PSP_PNR_NEW)='' then 'NOVALUE' else vbap.zzorty end AS SALES_CATEGORY,
        case when trim(VBAP.PS_PSP_PNR_NEW)='' then 'NOVALUE' else vbap.VBELN end AS SALES_DOCUMENT,
        case when trim(VBAP.PS_PSP_PNR_NEW)='' then 'NOVALUE' else vbap.POSNR end AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN vbap_cte  VBAP
            ON universal_pl_data.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR = VBAP.PS_PSP_PNR_NEW
    WHERE OBJECT_NUMBER like 'PR%'
),

VB_Object_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        case when TRIM(VBAP.VBELN)='' OR TRIM(VBAP.POSNR)='' then 'NOVALUE' else vbap.zzorty end AS SALES_CATEGORY,
        case when TRIM(VBAP.VBELN)='' OR TRIM(VBAP.POSNR)='' then 'NOVALUE' else vbap.VBELN end AS SALES_DOCUMENT,
        case when TRIM(VBAP.VBELN)='' OR TRIM(VBAP.POSNR)='' then 'NOVALUE' else vbap.POSNR end AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN vbap_cte  VBAP
            ON universal_pl_data.SALES_ORDER_NUMBER = VBAP.VBELN and universal_pl_data.ITEM_NUMBER_IN_SALES_ORDER = VBAP.POSNR
    WHERE OBJECT_NUMBER like 'VB%'
),

NO_OR_OV_PR_VB_data as
(
        SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        case when TRIM(VBFA.VBELV)='' AND TRIM(VBFA.POSNV)='' then 'NOVALUE' else vbap.zzorty end AS SALES_CATEGORY,
        case when TRIM(VBFA.VBELV)='' AND TRIM(VBFA.POSNV)='' then 'NOVALUE' else vbap.VBELN end AS SALES_DOCUMENT,
        case when TRIM(VBFA.VBELV)='' AND TRIM(VBFA.POSNV)='' then 'NOVALUE' else vbap.POSNR end AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU064_VBFA') }}  VBFA
            ON universal_pl_data.PURCHASING_DOCUMENT_NUMBER = VBFA.VBELN
                AND universal_pl_data.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = VBFA.POSNN
        JOIN vbap_cte  VBAP
            ON VBFA.VBELV = VBAP.VBELN and VBFA.POSNV = VBAP.POSNR
    WHERE OBJECT_NUMBER not like 'OR%' and OBJECT_NUMBER not like 'OV%' and OBJECT_NUMBER not like 'PR%' and OBJECT_NUMBER not like 'VB%'
        AND VBFA.VBTYP_V IN ('C','H','G')
),


WITH CEPCT AS (
SELECT * 
FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU091_CEPCT') }}
WHERE SPRAS='EN'
AND TO_DATE(DATBI,'YYYYMMDD')>CURRENT_DATE
)
,SOURCE_DATA AS (
SELECT 
	CEPC.PRCTR AS PROFIT_CENTER_CODE,
	CEPCT.LTEXT AS PROFIT_CENTER_NAME,
	CEPC.VERAK AS COMPANY_CODE,
	TO_DATE(CEPC.UPDATE_DATE,'YYYYMMDD') AS UPDATE_DATE
FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU035_CEPC') }} CEPC
LEFT JOIN CEPCT 
on CEPC.PRCTR=CEPCT.PRCTR
)
,TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	PROFIT_CENTER_CODE,
	PROFIT_CENTER_NAME,
	COMPANY_CODE,
	CAST(UPDATE_DATE AS DATE) AS UPDATE_DATE
FROM SOURCE_DATA
)
SELECT * FROM TRANSFORM_DATA


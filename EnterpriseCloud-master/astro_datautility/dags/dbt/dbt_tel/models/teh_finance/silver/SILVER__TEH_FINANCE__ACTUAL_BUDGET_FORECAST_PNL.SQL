    	materialized='tel_incremental',
    	incremental_strategy='insert_overwrite',
    	alias='ACTUAL_BUDGET_FORECAST_PNL',
        tags=["finance"],
    	transient=false
) }} 

WITH SOURCE_DATA AS (
	SELECT
		ORACLE_ACCOUNT_NUMBER,
        SAP_ACCOUNT_NUMBER,
        ACCOUNT_TYPE,
		ENTITY,
		DEPARTMENTCODE,
		SEGMENTCODE,
		OFFICECODE,
		FINANCIALPRODUCTCODE,
        PRODUCT_TYPE,
        PRODUCT_TYPE_CATEGORY,
        REVENUE_SOURCE,
        PRODUCT_TYPE_GROUP,
        PRODUCT_TYPE_GROUP_LEGACY,
        STATUTORY_GROUP,
        PRELIM_CLOSE_RPT,
		CUSTOMERCODE,
        CORPORATION,
        CORPORATION_NAME,
        CUSTOMER_GROUP,
		SCENARIO,
		YEAR,
		PERIOD,
        CALENDAR_YEAR_MONTH,
        FISCAL_HALF,
	    FISCAL_QTR,
		CURRENCY,
        AMOUNT,
		VERSION,
		FORECASTBUDGET_FILEDATE
	FROM {{ ref('SILVER__TEH_FINANCE__ACTUAL_BUDGET_FORECAST_MASTER') }}
	WHERE ACCOUNT_TYPE IN ('Revenue','COGS')
	AND CALENDAR_YEAR_MONTH>'2016-03'
)
,FINAL_DATA AS (
	SELECT 
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		ORACLE_ACCOUNT_NUMBER,
        SAP_ACCOUNT_NUMBER,
        ACCOUNT_TYPE,
		ENTITY,
		DEPARTMENTCODE,
		SEGMENTCODE,
		OFFICECODE,
		FINANCIALPRODUCTCODE,
        PRODUCT_TYPE,
        PRODUCT_TYPE_CATEGORY,
        REVENUE_SOURCE,
        PRODUCT_TYPE_GROUP,
        PRODUCT_TYPE_GROUP_LEGACY,
        STATUTORY_GROUP,
        PRELIM_CLOSE_RPT,
		CUSTOMERCODE,
        CORPORATION,
        CORPORATION_NAME,
        CUSTOMER_GROUP,
		SCENARIO,
		YEAR,
		PERIOD,
        CALENDAR_YEAR_MONTH,
        FISCAL_HALF,
	    FISCAL_QTR,
		CURRENCY,
        AMOUNT,
		CASE WHEN SCENARIO = 'Actual' THEN 'Working'
		ELSE VERSION
		END AS VERSION,
		FORECASTBUDGET_FILEDATE
	FROM SOURCE_DATA
)
,type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(ORACLE_ACCOUNT_NUMBER AS VARCHAR(16777216)) AS ORACLE_ACCOUNT_NUMBER,
		CAST(SAP_ACCOUNT_NUMBER AS VARCHAR(16777216)) AS SAP_ACCOUNT_NUMBER,
        CAST(ACCOUNT_TYPE AS VARCHAR(16777216)) AS ACCOUNT_TYPE,
		CAST(ENTITY AS VARCHAR(16777216)) AS ENTITY,
		CAST(DEPARTMENTCODE AS VARCHAR(16777216)) AS DEPARTMENTCODE,
		CAST(SEGMENTCODE AS VARCHAR(16777216)) AS SEGMENTCODE,
		CAST(OFFICECODE AS VARCHAR(16777216)) AS OFFICECODE,
		CAST(FINANCIALPRODUCTCODE AS VARCHAR(16777216)) AS FINANCIALPRODUCTCODE,
        CAST(PRODUCT_TYPE AS VARCHAR(16777216)) AS PRODUCT_TYPE,
        CAST(PRODUCT_TYPE_CATEGORY AS VARCHAR(16777216)) AS PRODUCT_TYPE_CATEGORY,
        CAST(REVENUE_SOURCE AS VARCHAR(16777216)) AS REVENUE_SOURCE,
        CAST(PRODUCT_TYPE_GROUP AS VARCHAR(16777216)) AS PRODUCT_TYPE_GROUP,
        CAST(PRODUCT_TYPE_GROUP_LEGACY AS VARCHAR(16777216)) AS PRODUCT_TYPE_GROUP_LEGACY,
        CAST(STATUTORY_GROUP AS VARCHAR(16777216)) AS STATUTORY_GROUP,
        CAST(PRELIM_CLOSE_RPT AS VARCHAR(16777216)) AS PRELIM_CLOSE_RPT,
		CAST(CUSTOMERCODE AS VARCHAR(16777216)) AS CUSTOMERCODE,
        CAST(CORPORATION AS VARCHAR(16777216)) AS CORPORATION,
        CAST(CORPORATION_NAME AS VARCHAR(16777216)) AS CORPORATION_NAME,
        CAST(CUSTOMER_GROUP AS VARCHAR(16777216)) AS CUSTOMER_GROUP,
        CAST(SCENARIO AS VARCHAR(16777216)) AS SCENARIO,
		CAST(YEAR AS VARCHAR(16777216)) AS YEAR,
		CAST(PERIOD AS VARCHAR(16777216)) AS PERIOD,
		CAST(CALENDAR_YEAR_MONTH AS VARCHAR(16777216)) AS CALENDAR_YEAR_MONTH,  
		CAST(FISCAL_HALF AS VARCHAR(16777216)) AS FISCAL_HALF,  
		CAST(FISCAL_QTR AS VARCHAR(16777216)) AS FISCAL_QTR,  
		CAST(CURRENCY AS VARCHAR(16777216)) AS CURRENCY,
		CAST(AMOUNT AS NUMBER(38,2)) AS AMOUNT,
		VERSION,
		FORECASTBUDGET_FILEDATE
    FROM FINAL_DATA
)
SELECT * from type_data


WITH DIM_PRODUCT_TYPE AS (
	SELECT 
        PT.PRODUCT_TYPE_ID,
        pt.PRODUCT_TYPE_NAME,
		pt.PRODUCT_TYPE_GROUP,
		pt.PRODUCT_TYPE_CATEGORY
	FROM {{ source('STATIC_OBJECTS', 'D_PRODUCT_TYPE') }} AS PT
	WHERE DW_CURRENT_INDICATOR='Y'
	AND COMPANY_ID='201'
)
,SEGMENT AS (
	SELECT 
		ORACLE_CODE,
		ORACLE_DESCRIPTION,
		SAP_CODE,
		SAP_DESCRIPTION,
		BAAN_CODE,
		BAAN_DESCRIPTION
	FROM {{ ref('SILVER__TEH_FINANCE__SAP_SEGMENT') }}
	QUALIFY (ROW_NUMBER() OVER (PARTITION BY SAP_CODE ORDER BY _FILEDATE DESC,_FILEDATE DESC )) = 1
)
,ACTUALS_DATA as (
	SELECT DISTINCT
		DASL.PNL_CATEGORY AS ACCOUNT_TYPE,
		'SAP Actuals'AS SCENARIO,
		CALENDAR_YEAR_MONTH AS REPORTING_PERIOD,
		DATE.FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
		DASL.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF,
		sc.BAAN_PRODUCT_TYPE AS PRODUCT_TYPE_CODE,
        pt.PRODUCT_TYPE_NAME,
		pt.PRODUCT_TYPE_GROUP,
		pt.PRODUCT_TYPE_CATEGORY,
		DASL.SEGMENT_CODE AS SAP_SEGMENT_CODE,
		DASL.SEGMENT AS SAP_SEGMENT_NAME,
		SEGMENT.ORACLE_CODE AS ORACLE_SEGMENT_CODE,
		SEGMENT.ORACLE_DESCRIPTION AS ORACLE_SEGMENT_NAME,
		SEGMENT.BAAN_CODE AS BAAN_SEGMENT_CODE,
		SEGMENT.BAAN_DESCRIPTION AS BAAN_SEGMENT_NAME,
		Case When DASL.SEGMENT like 'Admin' Then 'Admin' When DASL.SEGMENT not like 'Admin' Then SUBSTR(DASL.SEGMENT,4) END AS BU,
		DASL.OFFICE_CODE as SAP_OFFICE_CODE,
		DASL.OFFICE AS SAP_OFFICE_NAME,
		REGION.ORACLE_CODE AS ORACLE_OFFICE_CODE,
		REGION.ORACLE_DESCRIPTION AS ORACLE_OFFICE_NAME,
		REGION.BAAN_CODE AS BAAN_OFFICE_CODE,
		NULL AS BAAN_OFFICE_NAME,
		sbc.LEGACY_OFFICE_CODE, 
		sbc.LEGACY_OFFICE,
		NULL AS ORACLE_CUSTOMER_CODE,
		DASL.END_USER AS SAP_CUSTOMER_NUMBER,
		DASL.END_USER_NAME AS CUSTOMER_NAME,
		DASL.CORPORATION AS SAP_A_CUSTOMER_CODE,
		DASL.CUSTOMER_GROUP,
		sum(AMOUNT_IN_COMPANY_CODE_CURRENCY) AS AMOUNT
	FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS_SALES_LINE') }}  AS DASL
    	LEFT JOIN {{ source('STATIC_OBJECTS', 'CALENDARDATE') }} AS DATE
		ON DASL.POSTING_DATE=CALENDAR_DATE
        LEFT JOIN {{ ref('SILVER__TEH_FINANCE__SAP_SALES_CATEGORY') }} as sc
		ON DASL.SALES_CATEGORY=sc.SAP_SALES_CATEGORY
        LEFT JOIN DIM_PRODUCT_TYPE as pt 
		ON sc.BAAN_PRODUCT_TYPE=pt.PRODUCT_TYPE_ID
	    LEFT JOIN SEGMENT
		ON DASL.SEGMENT_CODE=segment.SAP_CODE
        LEFT JOIN {{ ref('SILVER__TEH_FINANCE__SAP_REGION') }} as region
		ON DASL.office_code=region.sap_code
        LEFT JOIN {{ ref('SILVER__TEH_FINANCE__SERVICE_B_CODE_MAPPING') }} as sbc
		ON DASL.END_USER=sbc.B_CODE
        
	WHERE LEFT(ACCOUNT_NUMBER,1) IN ('4','5')
	AND DASL.COMPANY_CODE='3200'
    GROUP BY 
		DASL.PNL_CATEGORY,
		REPORTING_PERIOD,
		DASL.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT,
		DASL.FISCAL_YEAR_QUARTER_SHORT_TEXT,
		DASL.SALES_CATEGORY,
		DASL.SALES_CATEGORY_NAME,
        DATE.FISCAL_YEAR_SHORT_TEXT,
        sc.BAAN_PRODUCT_TYPE,
		pt.PRODUCT_TYPE_NAME,
		pt.PRODUCT_TYPE_GROUP,
		pt.PRODUCT_TYPE_CATEGORY,
        DASL.SEGMENT_CODE,
        DASL.SEGMENT,
        SEGMENT.ORACLE_CODE,
		SEGMENT.ORACLE_DESCRIPTION,
		SEGMENT.BAAN_CODE,
		SEGMENT.BAAN_DESCRIPTION,
        DASL.OFFICE_CODE,
        DASL.OFFICE,
        REGION.ORACLE_CODE,
		REGION.ORACLE_DESCRIPTION,
		REGION.BAAN_CODE,
        sbc.LEGACY_OFFICE_CODE, 
		sbc.LEGACY_OFFICE,
        DASL.END_USER,
		DASL.END_USER_NAME,
		DASL.CORPORATION,
		DASL.CUSTOMER_GROUP
        
)

,CALENDAR AS (
	SELECT DISTINCT
		FISCAL_YEAR_SHORT_TEXT,
	    MONTH_ABBREVIATION_TEXT,
        YEAR_MONTH_TEXT AS REPORTING_PERIOD,
		FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
		FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF,
		FISCAL_YEAR_QUARTER_SHORT_TEXT AS FISCAL_QTR
    FROM {{ source('STATIC_OBJECTS', 'CALENDARDATE') }}
)
,CUSTOMER AS (
	SELECT DISTINCT 
		CUSTOMER_ID,
		CUSTOMER_NAME,
		CUSTOMER_GROUP_TEL 
	FROM {{ source('STATIC_OBJECTS', 'D_CUSTOMER') }}
	WHERE DW_CURRENT_INDICATOR='Y'
)
,REGION AS (
	SELECT 
		ORACLE_CODE,
		ORACLE_DESCRIPTION,
		SAP_CODE,
		SAP_DESCRIPTION,
		BAAN_CODE
	FROM {{ ref('SILVER__TEH_FINANCE__SAP_REGION') }}
	QUALIFY (ROW_NUMBER() OVER (PARTITION BY ORACLE_CODE ORDER BY _FILEDATE DESC,_FILEDATE DESC )) = 1
)
,APRIL_ACTUALS as (
	SELECT
		BAAN.FINANCIAL_ACCOUNT_TYPE AS ACCOUNT_TYPE,
		'BAAN Actuals' AS SCENARIO,
		BAAN.CALENDAR_YEAR_MONTH AS REPORTING_PERIOD,
		BAAN.FISCAL_YEAR AS FISCAL_YEAR,
		BAAN.FISCAL_HALF AS FISCAL_HALF,
		BAAN.FINANCIAL_PRODUCT_TYPE_CODE AS PRODUCT_TYPE_CODE,
		PT.PRODUCT_TYPE_NAME,
		PT.PRODUCT_TYPE_GROUP,
		PT.PRODUCT_TYPE_CATEGORY,
		SEGMENT.SAP_CODE AS SAP_SEGMENT_CODE,
		SEGMENT.SAP_DESCRIPTION AS SAP_SEGMENT_NAME,
		BAAN.SEGMENT_ORACLE_CODE AS ORACLE_SEGMENT_CODE,
		BAAN.SEGMENT_ORACLE AS ORACLE_SEGMENT_NAME,
		BAAN.SEGMENT_CODE AS BAAN_SEGMENT_CODE,
		BAAN.SEGMENT_NAME AS BAAN_SEGMENT_NAME,
		Case When SAP_SEGMENT_NAME like 'Admin' Then 'Admin' When SAP_SEGMENT_NAME not like 'Admin' Then SUBSTR(SAP_SEGMENT_NAME,4) END AS BU,
		REGION.SAP_CODE AS SAP_OFFICE_CODE,
		REGION.SAP_DESCRIPTION AS SAP_OFFICE_NAME,
		REGION.ORACLE_CODE AS ORACLE_OFFICE_CODE,
		REGION.ORACLE_DESCRIPTION AS ORACLE_OFFICE_NAME,
		BAAN.OFFICE_CODE AS BAAN_OFFICE_CODE,
		BAAN.OFFICE_NAME AS BAAN_OFFICE_NAME,
		NULL AS LEGACY_OFFICE_CODE, 
		NULL AS LEGACY_OFFICE,
		BAAN.CUSTOMER_CODE AS ORACLE_CUSTOMER_CODE,
		NULL AS SAP_CUSTOMER_NUMBER,
		BAAN.CUSTOMER_NAME AS CUSTOMER_NAME,
		NULL AS SAP_A_CUSTOMER_CODE,
		BAAN.CUSTOMER_GROUP AS CUSTOMER_GROUP,
		CAST(BAAN.AMOUNT AS NUMBER(38,2)) AS AMOUNT

	FROM {{ ref('BRONZE__TEH_FINANCE__TELUSDWPROD1_REVENUEANDCOGSDETAILS') }} as BAAN
		LEFT JOIN DIM_PRODUCT_TYPE as PT
			ON BAAN.FINANCIAL_PRODUCT_TYPE_CODE=PT.PRODUCT_TYPE_ID
		LEFT JOIN SEGMENT
			ON BAAN.SEGMENT_ORACLE_CODE=segment.ORACLE_CODE
		LEFT JOIN REGION
			ON CONCAT('R',TRIM(BAAN.OFFICE_CODE))=REGION.ORACLE_CODE
	WHERE 1=1
		AND LEFT(BAAN.FINANCIAL_ACCOUNT_NUMBER,1) IN ('4','5')
		AND BAAN.COMPANY_NAME='TEA'
		AND BAAN.CALENDAR_YEAR_MONTH < '2023-05'
)


,SOURCE_DATA as (
	SELECT
		ACCOUNT_TYPE,
		SCENARIO,
		REPORTING_PERIOD,
		FISCAL_YEAR,
		FISCAL_HALF,
		PRODUCT_TYPE_CODE,
		PRODUCT_TYPE_NAME,
		PRODUCT_TYPE_GROUP,
		PRODUCT_TYPE_CATEGORY,
		SAP_SEGMENT_CODE,
		SAP_SEGMENT_NAME,
		ORACLE_SEGMENT_CODE,
		ORACLE_SEGMENT_NAME,
		BAAN_SEGMENT_CODE,
		BAAN_SEGMENT_NAME,
		BU,
		SAP_OFFICE_CODE,
		SAP_OFFICE_NAME,
		ORACLE_OFFICE_CODE,
		ORACLE_OFFICE_NAME,
		BAAN_OFFICE_CODE,
		BAAN_OFFICE_NAME,
		LEGACY_OFFICE_CODE,
		LEGACY_OFFICE,
		ORACLE_CUSTOMER_CODE,
		SAP_CUSTOMER_NUMBER,
		CUSTOMER_NAME,
		SAP_A_CUSTOMER_CODE,
		CUSTOMER_GROUP,
		CASE WHEN ACCOUNT_TYPE='COGS' THEN -1*AMOUNT
		WHEN ACCOUNT_TYPE='Revenue' THEN -1*AMOUNT
		ELSE 0 
		END AS AMOUNT 
	FROM ACTUALS_DATA
	UNION ALL
	SELECT 
		ACCOUNT_TYPE,
		SCENARIO,
		REPORTING_PERIOD,
		FISCAL_YEAR,
		FISCAL_HALF,
		PRODUCT_TYPE_CODE,
		PRODUCT_TYPE_NAME,
		PRODUCT_TYPE_GROUP,
		PRODUCT_TYPE_CATEGORY,
		SAP_SEGMENT_CODE,
		SAP_SEGMENT_NAME,
		ORACLE_SEGMENT_CODE,
		ORACLE_SEGMENT_NAME,
		BAAN_SEGMENT_CODE,
		BAAN_SEGMENT_NAME,
		BU,
		SAP_OFFICE_CODE,
		SAP_OFFICE_NAME,
		ORACLE_OFFICE_CODE,
		ORACLE_OFFICE_NAME,
		BAAN_OFFICE_CODE,
		BAAN_OFFICE_NAME,
		LEGACY_OFFICE_CODE,
		LEGACY_OFFICE,
		ORACLE_CUSTOMER_CODE,
		SAP_CUSTOMER_NUMBER,
		CUSTOMER_NAME,
		SAP_A_CUSTOMER_CODE,
		CUSTOMER_GROUP,
		CASE WHEN ACCOUNT_TYPE='COGS' THEN -1*AMOUNT
		WHEN ACCOUNT_TYPE='Revenue' THEN AMOUNT
		ELSE 0 
		END AS AMOUNT 
	FROM APRIL_ACTUALS
)

,TRANSFORM_DATA AS (
	SELECT 
		ACCOUNT_TYPE,
		SCENARIO,
		REPORTING_PERIOD,
		FISCAL_YEAR,
		FISCAL_HALF,
		PRODUCT_TYPE_CODE,
		PRODUCT_TYPE_NAME,
		PRODUCT_TYPE_GROUP,
		PRODUCT_TYPE_CATEGORY,
		SAP_SEGMENT_CODE,
		SAP_SEGMENT_NAME,
		ORACLE_SEGMENT_CODE,
		ORACLE_SEGMENT_NAME,
		BAAN_SEGMENT_CODE,
		BAAN_SEGMENT_NAME,
		BU,
		SAP_OFFICE_CODE,
		SAP_OFFICE_NAME,
		ORACLE_OFFICE_CODE,
		ORACLE_OFFICE_NAME,
		BAAN_OFFICE_CODE,
		LEGACY_OFFICE_CODE,
		LEGACY_OFFICE,
		ORACLE_CUSTOMER_CODE,
		SAP_CUSTOMER_NUMBER,
		CUSTOMER_NAME,
		SAP_A_CUSTOMER_CODE,
		CUSTOMER_GROUP,
		AMOUNT,
		'{{ invocation_id }}' AS AUDIT_LOG_ID
	FROM SOURCE_DATA
)

,TYPE_DATA as (
    SELECT
        CAST(ACCOUNT_TYPE AS VARCHAR(16777216)) AS ACCOUNT_TYPE,
        CAST(SCENARIO AS VARCHAR(16777216)) AS SCENARIO,
        CAST(REPORTING_PERIOD AS VARCHAR(16777216)) AS REPORTING_PERIOD,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(FISCAL_HALF AS VARCHAR(16777216)) AS FISCAL_HALF,
        CAST(PRODUCT_TYPE_CODE AS VARCHAR(16777216)) AS PRODUCT_TYPE_CODE,
        CAST(PRODUCT_TYPE_NAME AS VARCHAR(16777216)) AS PRODUCT_TYPE_NAME,
        CAST(PRODUCT_TYPE_GROUP AS VARCHAR(16777216)) AS PRODUCT_TYPE_GROUP,
        CAST(PRODUCT_TYPE_CATEGORY AS VARCHAR(16777216)) AS PRODUCT_TYPE_CATEGORY,
        CAST(SAP_SEGMENT_CODE AS VARCHAR(16777216)) AS SAP_SEGMENT_CODE,
        CAST(SAP_SEGMENT_NAME AS VARCHAR(16777216)) AS SAP_SEGMENT_NAME,
        CAST(ORACLE_SEGMENT_CODE AS VARCHAR(16777216)) AS ORACLE_SEGMENT_CODE,
        CAST(ORACLE_SEGMENT_NAME AS VARCHAR(16777216)) AS ORACLE_SEGMENT_NAME,
        CAST(BAAN_SEGMENT_CODE AS VARCHAR(16777216)) AS BAAN_SEGMENT_CODE,
        CAST(BAAN_SEGMENT_NAME AS VARCHAR(16777216)) AS BAAN_SEGMENT_NAME,
        CAST(BU AS VARCHAR(16777216)) AS BU,
        CAST(SAP_OFFICE_CODE AS VARCHAR(16777216)) AS SAP_OFFICE_CODE,
        CAST(SAP_OFFICE_NAME AS VARCHAR(16777216)) AS SAP_OFFICE_NAME,
        CAST(ORACLE_OFFICE_CODE AS VARCHAR(16777216)) AS ORACLE_OFFICE_CODE,
        CAST(ORACLE_OFFICE_NAME AS VARCHAR(16777216)) AS ORACLE_OFFICE_NAME,
        CAST(BAAN_OFFICE_CODE AS VARCHAR(16777216)) AS BAAN_OFFICE_CODE,
        CAST(LEGACY_OFFICE_CODE AS VARCHAR(16777216)) AS LEGACY_OFFICE_CODE,
        CAST(LEGACY_OFFICE AS VARCHAR(16777216)) AS LEGACY_OFFICE,
        CAST(ORACLE_CUSTOMER_CODE AS VARCHAR(16777216)) AS ORACLE_CUSTOMER_CODE,
        CAST(SAP_CUSTOMER_NUMBER AS VARCHAR(16777216)) AS SAP_CUSTOMER_NUMBER,
        CAST(CUSTOMER_NAME AS VARCHAR(16777216)) AS CUSTOMER_NAME,
        CAST(SAP_A_CUSTOMER_CODE AS VARCHAR(16777216)) AS SAP_A_CUSTOMER_CODE,
        CAST(CUSTOMER_GROUP AS VARCHAR(16777216)) AS CUSTOMER_GROUP,
        CAST(AMOUNT AS NUMBER(38,2)) AS AMOUNT,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    FROM TRANSFORM_DATA
)

SELECT * from TYPE_DATA


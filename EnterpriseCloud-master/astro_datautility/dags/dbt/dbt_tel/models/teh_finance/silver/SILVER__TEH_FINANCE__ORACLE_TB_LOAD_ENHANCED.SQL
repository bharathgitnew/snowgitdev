WITH DA_REF AS (
    SELECT * FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS') }}   
) 
,FISCAL_PERIOD_LIST_23 AS
(
    SELECT DISTINCT 
        FISCAL_YEAR AS FY,
        CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP
    FROM DA_REF
    WHERE FY='2023'
)
,FISCAL_PERIOD_LIST_24 AS
(
    SELECT DISTINCT 
        FISCAL_YEAR AS FY,
        CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP
    FROM DA_REF
    WHERE FY='2024'
)
,FISCAL_PERIOD_LIST_25 AS
(
    SELECT DISTINCT 
        FISCAL_YEAR AS FY,
        CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP
    FROM DA_REF
    WHERE FY='2025'
)
,FISCAL_PERIOD_LIST_26 AS
(
    SELECT DISTINCT 
        FISCAL_YEAR AS FY,
        CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP
    FROM DA_REF
    WHERE FY='2026'
)
, ACCOUNT_LIST_23 AS
(
    SELECT DISTINCT 
    FISCAL_YEAR AS FY,
    CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP,
    COMPANY_CODE AS CC,
    ACCOUNT_NUMBER AS AN
    FROM DA_REF
    WHERE FY='2023'
)
, ACCOUNT_LIST_24 AS
(
    SELECT DISTINCT 
    FISCAL_YEAR AS FY,
    CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP,
    COMPANY_CODE AS CC,
    ACCOUNT_NUMBER AS AN
    FROM DA_REF
    WHERE FY='2024'
)
, ACCOUNT_LIST_25 AS
(
    SELECT DISTINCT 
    FISCAL_YEAR AS FY,
    CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP,
    COMPANY_CODE AS CC,
    ACCOUNT_NUMBER AS AN
    FROM DA_REF
    WHERE FY='2025'
)
, ACCOUNT_LIST_26 AS
(
    SELECT DISTINCT 
    FISCAL_YEAR AS FY,
    CAST(FINANCIAL_PERIOD as NUMBER(38,0)) AS FP,
    COMPANY_CODE AS CC,
    ACCOUNT_NUMBER AS AN
    FROM DA_REF
    WHERE FY='2026'
)
, PARAMETER_SET_23 AS (
    SELECT DISTINCT
    AL_23.FY,
    CAST(FPL_23.FP as NUMBER(38,0)) as FP,
    AL_23.CC,
    AL_23.AN
    FROM FISCAL_PERIOD_LIST_23 FPL_23
        CROSS JOIN ACCOUNT_LIST_23 AL_23
        WHERE LEFT(AL_23.AN,1) IN ('1','2','3')
        AND AL_23.FY='2023'
)
, PARAMETER_SET_24 AS (
    SELECT DISTINCT
    AL_24.FY,
    CAST(FPL_24.FP as NUMBER(38,0)) as FP,
    AL_24.CC,
    AL_24.AN
    FROM FISCAL_PERIOD_LIST_24 FPL_24
        CROSS JOIN ACCOUNT_LIST_24 AL_24
        WHERE LEFT(AL_24.AN,1) IN ('1','2','3')
        AND AL_24.FY='2024'
)
, PARAMETER_SET_25 AS (
    SELECT DISTINCT
    AL_25.FY,
    CAST(FPL_25.FP as NUMBER(38,0)) as FP,
    AL_25.CC,
    AL_25.AN
    FROM FISCAL_PERIOD_LIST_25 FPL_25
        CROSS JOIN ACCOUNT_LIST_25 AL_25
        WHERE LEFT(AL_25.AN,1) IN ('1','2','3')
        AND AL_25.FY='2025'
)
, PARAMETER_SET_26 AS (
    SELECT DISTINCT
    AL_26.FY,
    CAST(FPL_26.FP as NUMBER(38,0)) as FP,
    AL_26.CC,
    AL_26.AN
    FROM FISCAL_PERIOD_LIST_26 FPL_26
        CROSS JOIN ACCOUNT_LIST_26 AL_26
        WHERE LEFT(AL_26.AN,1) IN ('1','2','3')
        AND AL_26.FY='2026'
)
,PARAMETER_SET AS (
SELECT *
FROM PARAMETER_SET_23
UNION ALL 
SELECT *
FROM PARAMETER_SET_24
UNION ALL
SELECT *
FROM PARAMETER_SET_25
UNION ALL
SELECT *
FROM PARAMETER_SET_26
)
,
BS_ACCOUNT_CUMULATION AS
(
    SELECT 
    FISCAL_YEAR,
    FINANCIAL_PERIOD AS FISCAL_PERIOD,
    COMPANY_CODE,
    ACCOUNT_NUMBER AS LEDGER_ACCOUNT,
    AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT
    FROM DA_REF
    WHERE LEFT(ACCOUNT_NUMBER,1) IN ('1','2','3')
),
GSACCOUNT AS
(
  SELECT DISTINCT
        AL.FY,
        AL.FP,
        AL.CC,
        NULL AS PROFIT_CENTER,
        AL.AN,
        SUM(IFNULL(BAC.AMOUNT,0.00)) OVER(PARTITION BY AL.FY,AL.CC,AL.AN ORDER BY AL.FP) AS END_BALANCE
  FROM PARAMETER_SET AL
  LEFT OUTER JOIN BS_ACCOUNT_CUMULATION  BAC
  ON AL.FY=BAC.FISCAL_YEAR
  AND AL.CC=BAC.COMPANY_CODE
  AND AL.AN=BAC.LEDGER_ACCOUNT
  AND AL.FP=BAC.FISCAL_PERIOD
)
,
NET_EARNINGS AS (
    SELECT 
        FY,
        FP,
        CC,
        NULL AS PROFIT_CENTER,
        '3-NET EARNINGS CALCULATION' AS AN,
        -1*SUM(END_BALANCE) AS END_BALANCE
    FROM GSACCOUNT
        GROUP BY 
        FY,
        FP,
        CC
)
,TOTAL_INCOME_STATMENT AS (
    SELECT * FROM NET_EARNINGS
    UNION 
    SELECT * FROM GSACCOUNT 
)
,Final_BS_Account_Cumulation AS (
    SELECT 
        FY AS FISCAL_YEAR,
        FP AS FISCAL_PERIOD,
        CC AS COMPANY_CODE,
        PROFIT_CENTER,
        NULL AS SALES_CATEGORY,
        NULL AS WBS_ELEMENT,
        NULL AS CUSTOMER,
        AN AS LEDGER_ACCOUNT,
        END_BALANCE AS AMOUNT
    FROM TOTAL_INCOME_STATMENT
)
,Non_BS_Account AS
(
    SELECT 
        FISCAL_YEAR,
        FINANCIAL_PERIOD AS FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        SALES_CATEGORY,
        CASE WHEN WBS_ELEMENT='No WBS Element' THEN NULL ELSE WBS_ELEMENT END AS WBS_ELEMENT,
        END_USER AS CUSTOMER,
        ACCOUNT_NUMBER AS LEDGER_ACCOUNT,
        SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) AS AMOUNT
    FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS_SALES_LINE_ENHANCED') }}
    WHERE LEFT(ACCOUNT_NUMBER,1) in ('4','5')
    GROUP BY 
        FISCAL_YEAR,
        FINANCIAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        SALES_CATEGORY,
        WBS_ELEMENT,
        END_USER,
        ACCOUNT_NUMBER
),
BS_Account_Non_Cumulation AS
(
    SELECT 
        FISCAL_YEAR,
        FINANCIAL_PERIOD AS FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        NULL AS SALES_CATEGORY,
        NULL AS WBS_ELEMENT,
        NULL AS CUSTOMER,
        ACCOUNT_NUMBER AS LEDGER_ACCOUNT,
        SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) AS AMOUNT
    FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS') }}
    WHERE LEFT(ACCOUNT_NUMBER,1) in ('6','7','8','9')
    GROUP BY 
        FISCAL_YEAR,
        FINANCIAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        ACCOUNT_NUMBER
),
C_Account_Non_Cumulation AS
(
    SELECT 
        FISCAL_YEAR,
        FINANCIAL_PERIOD AS FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        NULL AS SALES_CATEGORY,
        WBS_ELEMENT,
        NULL AS CUSTOMER,
        ACCOUNT_NUMBER AS LEDGER_ACCOUNT,
        SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) AS AMOUNT
    FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS') }}
    WHERE LEFT(ACCOUNT_NUMBER,1) in ('C')
    GROUP BY 
        FISCAL_YEAR,
        FINANCIAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        ACCOUNT_NUMBER,
        WBS_ELEMENT
),
SOURCE_DATA as
(
    SELECT
        FISCAL_YEAR,
        CAST(FISCAL_PERIOD as NUMBER(38,0)) as FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        SALES_CATEGORY,
        WBS_ELEMENT,
        CUSTOMER,
        LEDGER_ACCOUNT,
        AMOUNT
    FROM Non_BS_Account
    UNION ALL
    SELECT
        FISCAL_YEAR,
        CAST(FISCAL_PERIOD as NUMBER(38,0)) as FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        NULL AS SALES_CATEGORY,
        NULL AS WBS_ELEMENT,
        NULL AS CUSTOMER,
        LEDGER_ACCOUNT,
        AMOUNT
    FROM Final_BS_Account_Cumulation
	UNION ALL
    SELECT
        FISCAL_YEAR,
        CAST(FISCAL_PERIOD as NUMBER(38,0)) as FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        SALES_CATEGORY,
        WBS_ELEMENT,
        CUSTOMER,
        LEDGER_ACCOUNT,
        AMOUNT
    FROM BS_Account_Non_Cumulation
    UNION ALL
    SELECT
        FISCAL_YEAR,
        CAST(FISCAL_PERIOD as NUMBER(38,0)) as FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        SALES_CATEGORY,
        WBS_ELEMENT,
        CUSTOMER,
        LEDGER_ACCOUNT,
        AMOUNT
    FROM C_Account_Non_Cumulation
),
TRANSFORM_DATA AS (
    SELECT 
        FISCAL_YEAR,
        CAST(FISCAL_PERIOD as NUMBER(38,0)) as FISCAL_PERIOD,
        COMPANY_CODE,
        PROFIT_CENTER,
        SALES_CATEGORY,
        WBS_ELEMENT,
        CUSTOMER,
        LEDGER_ACCOUNT,
        AMOUNT,
        SHA2('hash_me') as _ROW_HASH,
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
    FROM SOURCE_DATA
),
TYPE_DATA as (
    SELECT
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(FISCAL_PERIOD AS NUMBER(38,0)) AS FISCAL_PERIOD,
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(PROFIT_CENTER AS VARCHAR(16777216)) AS PROFIT_CENTER,
        CAST(SALES_CATEGORY AS VARCHAR(16777216)) AS SALES_CATEGORY,
        CAST(WBS_ELEMENT AS VARCHAR(16777216)) AS WBS_ELEMENT,
        CAST(CUSTOMER AS VARCHAR(16777216)) AS CUSTOMER,
        CAST(LEDGER_ACCOUNT AS VARCHAR(16777216)) AS LEDGER_ACCOUNT,
        CAST(AMOUNT AS NUMBER(38,2)) AS AMOUNT
    FROM TRANSFORM_DATA
)

SELECT * from TYPE_DATA


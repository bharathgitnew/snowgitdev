WITH SOURCE_DATA AS (
    SELECT
        A.T$LEAC AS LEDGER_ACC
        , B.T$DESC AS LEDGER_ACC_DESC
        , A.T$OCMP AS ORIGINAL_COMPANY
        , A.T$OTYP AS TRANSACTION_TYPE
        , A.T$ODOC AS DOCUMENT
        , A.T$OLIN AS LINE
        , A.T$FDOC AS ORIGINAL_DOCUMENT_NO
        , A.T$OSRL AS SEQUENCE_NUMBER
        , A.T$CATG AS TRANSACTION_CATEGORY
        , A.T$TRAN AS TYPE_OF_TRANSACTION
        , A.T$TXTA AS TRANSACTION_TEXT
        , A.T$REFR AS REFERENCE
        , CASE
            WHEN A.T$DBCR = 1 THEN (A.T$AMTH$1 * 1)
            WHEN A.T$DBCR = 2 THEN (A.T$AMTH$1 * -1)
          END AS AMOUNT
        , A.T$DCDT AS DOC_DATE
        , A.T$DATE AS FINALIZATION_DATE
        , A.T$VPRD AS FINANCIAL_PERIOD
        , A.T$VYER AS FISCAL_YEAR
        , A.T$BPID AS BUSINESS_PARTNER_ID
        , BP.T$NAMA AS BUSINESS_PARTNER_NAME
        ,CASE
            WHEN LEFT(A.T$DIM5,1) = 'C' THEN SUBSTR(A.T$DIM5, 2, 5)
            ELSE NULL
        END AS CUSTOMER_CODE
        , CUST.T$NAMA AS CUSTOMER_NAME
        , A.T$DIM1 as DEPT
        , A.T$DIM2 as SEGMENT
        , A.T$DIM3 as OFFICE
        , A.T$DIM4 as PRODUCT_TYPE
        , A.T$DIM5 as CUSTOMER_EMPLOYEE
    FROM {{ ref('BRONZE__TEH_FINANCE__BAAN_TTFGLD106200') }} A
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__BAAN_TTFGLD008200') }} B
        ON A.T$LEAC = B.T$LEAC
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__BAAN_TTCCOM100200') }} BP
        ON A.T$BPID = BP.T$BPID
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__BAAN_TTCCOM100200') }} CUST
        ON CUSTOMER_CODE = CUST.T$BPID
    WHERE A.T$VYER = '2023'
)

, TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') AS _ROW_HASH
        , LEDGER_ACC
        , LEDGER_ACC_DESC
        , ORIGINAL_COMPANY
        , TRANSACTION_TYPE
        , DOCUMENT
        , LINE
        , ORIGINAL_DOCUMENT_NO
        , SEQUENCE_NUMBER
        , TRANSACTION_CATEGORY
        , TYPE_OF_TRANSACTION
        , TRANSACTION_TEXT
        , REFERENCE
        , AMOUNT
        , DOC_DATE
        , FINALIZATION_DATE
        , FINANCIAL_PERIOD
        , FISCAL_YEAR
        , BUSINESS_PARTNER_ID
        , BUSINESS_PARTNER_NAME
        , CUSTOMER_CODE
        , CUSTOMER_NAME
        , DEPT
        , SEGMENT
        , OFFICE
        , PRODUCT_TYPE
        , CUSTOMER_EMPLOYEE
    FROM SOURCE_DATA
)

, TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        , CAST(LEDGER_ACC AS VARCHAR(12)) AS LEDGER_ACC
        , CAST(LEDGER_ACC_DESC AS VARCHAR(30)) AS LEDGER_ACC_DESC
        , CAST(ORIGINAL_COMPANY AS NUMBER(38,0)) AS ORIGINAL_COMPANY
        , CAST(TRANSACTION_TYPE AS VARCHAR(3)) AS TRANSACTION_TYPE
        , CAST(DOCUMENT AS NUMBER(38,0)) AS DOCUMENT
        , CAST(LINE AS NUMBER(38,0)) AS LINE
        , CAST(ORIGINAL_DOCUMENT_NO AS NUMBER(38,0)) AS ORIGINAL_DOCUMENT_NO
        , CAST(SEQUENCE_NUMBER AS NUMBER(38,0)) AS SEQUENCE_NUMBER
        , CAST(TRANSACTION_CATEGORY AS NUMBER(38,0)) AS TRANSACTION_CATEGORY
        , CAST(TYPE_OF_TRANSACTION AS NUMBER(38,0)) AS TYPE_OF_TRANSACTION
        , CAST(TRANSACTION_TEXT AS VARCHAR(255)) AS TRANSACTION_TEXT
        , CAST(REFERENCE AS VARCHAR(32)) AS REFERENCE
        , CAST(AMOUNT AS NUMBER(38,10)) AS AMOUNT
        , CAST(DOC_DATE AS TIMESTAMP_NTZ(9)) AS DOC_DATE
        , CAST(FINALIZATION_DATE AS TIMESTAMP_NTZ(9)) AS FINALIZATION_DATE
        , CAST(FINANCIAL_PERIOD AS VARCHAR(13)) AS FINANCIAL_PERIOD
        , CAST(FISCAL_YEAR AS VARCHAR(15)) AS FISCAL_YEAR
        , CAST(BUSINESS_PARTNER_ID AS VARCHAR(9)) AS BUSINESS_PARTNER_ID
        , CAST(BUSINESS_PARTNER_NAME AS VARCHAR(255)) AS BUSINESS_PARTNER_NAME
        , CAST(CUSTOMER_CODE AS VARCHAR(9)) AS CUSTOMER_CODE
        , CAST(CUSTOMER_NAME AS VARCHAR(255)) AS CUSTOMER_NAME
        , CAST(DEPT AS VARCHAR(10)) AS DEPT
        , CAST(SEGMENT AS VARCHAR(10)) AS SEGMENT
        , CAST(OFFICE AS VARCHAR(10)) AS OFFICE
        , CAST(PRODUCT_TYPE AS VARCHAR(10)) AS PRODUCT_TYPE
        , CAST(CUSTOMER_EMPLOYEE AS VARCHAR(10)) AS CUSTOMER_EMPLOYEE
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
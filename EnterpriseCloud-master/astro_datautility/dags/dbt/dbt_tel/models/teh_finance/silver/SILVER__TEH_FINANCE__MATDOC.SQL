WITH 
SOURCE_DATA AS (
    SELECT 
        EBELN AS PO_HDR, 
        EBELP AS PO_LINE,
        LGORT AS SLOC, 
        MATNR AS MATERIAL_NUMBER, 
        RECORD_TYPE,
        WERKS AS PLANT,
        BUKRS AS COMPANY_CODE,
        MENGU AS QTY_UPDATING_IN_MATERIAL_MASTER_RECORD,
        WERTU AS VALUE_UPDATING_IN_MATERIAL_MASTER_RECORD,
        KZBWS AS VALUATION_OF_SPECIAL_STOCK,
        SOBKZ AS SPECIAL_STOCK, 
        STOCK_QTY,
        BLDAT AS DOCUMENT_DATE,
        BUDAT AS POSTING_DATE,
        AEDAT AS CHANGED_ON_DATE
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU025_MATDOC') }} AS MATDOC
),
TRANSFORM_DATA AS (
    SELECT
        PO_HDR, 
        PO_LINE,
        CASE WHEN NULLIF(PO_HDR, '') IS NOT NULL THEN PO_HDR || '-' || PO_LINE ELSE NULL END AS PO_LINE_ID,
        SLOC, 
        MATERIAL_NUMBER, 
        RECORD_TYPE,
        PLANT,
        COMPANY_CODE,
        QTY_UPDATING_IN_MATERIAL_MASTER_RECORD,
        VALUE_UPDATING_IN_MATERIAL_MASTER_RECORD,
        VALUATION_OF_SPECIAL_STOCK,
        SPECIAL_STOCK, 
        STOCK_QTY,
        TRY_TO_DATE(DOCUMENT_DATE, 'YYYYMMDD') AS DOCUMENT_DATE,
        TRY_TO_DATE(POSTING_DATE, 'YYYYMMDD') AS POSTING_DATE,
        TRY_TO_DATE(CHANGED_ON_DATE, 'YYYYMMDD') AS CHANGED_ON_DATE,
        '{{ invocation_id }}' as AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        CAST(PO_HDR AS VARCHAR(16777216)) AS PO_HDR,
        CAST(PO_LINE AS VARCHAR(16777216)) AS PO_LINE,
        CAST(PO_LINE_ID AS VARCHAR(16777216)) AS PO_LINE_ID,
        CAST(SLOC AS VARCHAR(16777216)) AS SLOC,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER, 
        CAST(RECORD_TYPE AS VARCHAR(16777216)) AS RECORD_TYPE,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(QTY_UPDATING_IN_MATERIAL_MASTER_RECORD AS VARCHAR(16777216)) AS QTY_UPDATING_IN_MATERIAL_MASTER_RECORD,
        CAST(VALUE_UPDATING_IN_MATERIAL_MASTER_RECORD AS VARCHAR(16777216)) AS VALUE_UPDATING_IN_MATERIAL_MASTER_RECORD,
        CAST(VALUATION_OF_SPECIAL_STOCK AS VARCHAR(16777216)) AS VALUATION_OF_SPECIAL_STOCK,
        CAST(SPECIAL_STOCK AS VARCHAR(16777216)) AS SPECIAL_STOCK,
        CAST(STOCK_QTY AS INT) AS STOCK_QTY,
        CAST(DOCUMENT_DATE AS DATE) AS DOCUMENT_DATE,
        CAST(POSTING_DATE AS DATE) AS POSTING_DATE,
        CAST(CHANGED_ON_DATE AS DATE) AS CHANGED_ON_DATE,
        CAST(AUDIT_LOG_ID AS VARCHAR(16777216)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA


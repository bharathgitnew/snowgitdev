        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        CAST(AMOUNT_IN_COMPANY_CODE_CURRENCY AS VARCHAR(16777216)) AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        RSEG_DOCUMENT_NUMBER,
        RSEG_PURCHASING_DOC,
        RSEG_ARIBA_ITEM_NUMBER,
        RSEG_PLANT,
        COST_CENTER_CODE,
        COST_CENTER_NAME,

        ACCOUNT_TYPE,
        POSTING_KEY,
        DOCUMENT_TYPE,
        ACCOUNT_DESCRIPTION,
        ACCOUNT_NUMBER,
        ACCOUNT_NAME,
        ACDOCA_VENDOR_NUMBER,
        CUSTOMER_NUMBER,
        VENDOR_NUMBER,
        VENDOR_NAME,
        COUNTRY,
        CITY,
        SHIP_TO_CITY,
        SHIP_TO_REGION,
        ACCOUNTING_DOCUMENT,
        ACCOUNTING_DOCUMENT_TYPE,
        DOC_TYPE_DESCRIPTION,
        REFERENCE_DOCUMENT,
        REFERENCE_DOCUMENT_LINE_ITEM,
        PURCHASE_ORDER,
        PURCHASE_ORDER_LINE_ITEM,
        PURCHASE_ORDER_DOC_TYPE,
        CONDITION_TYPE,
        CONDITION_DESC,
        PURCHASE_ORDER_NOTE,
        QUANTITY,
        TAX_CONDITION,
        TAX_BASE AS TAX_BASE,
        SHIPPING_HANDLING_AMOUNT AS SHIPPING_HANDLING_AMOUNT,
        TAX_ON_INVOICE,
        COMPANY_CODE,
        COMPANY_NAME,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        POSTING_DATE,
        DOCUMENT_DATE,
        AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY,
        DEBIT_CREDIT_INDICATOR_DRCRK,
        ITEM_TEXT,
        OFFSETTING_ACCOUNT_NUMBER,
        DOCUMENT_HEADER_TEXT_BKPF,
        REFERENCE_BKPF,
        OFFICE,
        TAX_JURISDICTION,
        TAX_CODE,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        AMOUNT_IN_COMPANY_CODE_CURRENCY,
        RSEG_DOCUMENT_NUMBER,
        RSEG_PURCHASING_DOC,
        RSEG_ARIBA_ITEM_NUMBER,
        RSEG_PLANT,
        COST_CENTER_CODE,
        COST_CENTER_NAME,
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME
	from source_data
	),

	type_data as (
	SELECT
        DISTINCT
        _AUDIT_LOG_ID,
        _ROW_HASH,
        ACCOUNT_TYPE,
        POSTING_KEY,
        DOCUMENT_TYPE,
        ACCOUNT_DESCRIPTION,
        ACCOUNT_NUMBER,
        ACCOUNT_NAME,
        ACDOCA_VENDOR_NUMBER,
        CUSTOMER_NUMBER,
        VENDOR_NUMBER,
        VENDOR_NAME,
        COUNTRY,
        CITY,
        SHIP_TO_CITY,
        SHIP_TO_REGION,
        ACCOUNTING_DOCUMENT,
        ACCOUNTING_DOCUMENT_TYPE,
        DOC_TYPE_DESCRIPTION,
        REFERENCE_DOCUMENT,
        REFERENCE_DOCUMENT_LINE_ITEM,
        PURCHASE_ORDER,
        PURCHASE_ORDER_LINE_ITEM,
        PURCHASE_ORDER_DOC_TYPE,
        CONDITION_TYPE,
        CONDITION_DESC,
        PURCHASE_ORDER_NOTE,
        QUANTITY,
        TAX_CONDITION,
        TAX_BASE,
        SHIPPING_HANDLING_AMOUNT,
        TAX_ON_INVOICE,
        COMPANY_CODE,
        COMPANY_NAME,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        CAST(POSTING_DATE AS VARCHAR(16777216)) AS POSTING_DATE,
        CAST(DOCUMENT_DATE AS VARCHAR(16777216)) AS DOCUMENT_DATE,
        CAST(AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY AS VARCHAR(16777216)) AS AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY,
        DEBIT_CREDIT_INDICATOR_DRCRK,
        ITEM_TEXT,
        OFFSETTING_ACCOUNT_NUMBER,
        DOCUMENT_HEADER_TEXT_BKPF,
        REFERENCE_BKPF,
        OFFICE,
        TAX_JURISDICTION,

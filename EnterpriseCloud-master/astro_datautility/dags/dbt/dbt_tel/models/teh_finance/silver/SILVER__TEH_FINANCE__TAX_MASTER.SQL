with CUSTOMER_GROUP_MAPPING AS
(
    SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('BRONZE__TEH_FINANCE__SHAREPOINT_CUSTOMER_GROUP_MAPPING') }}
),
CUSTOMER AS (
    SELECT DISTINCT
        CUSTOMER.CUSTOMER_NUMBER
        , CUSTOMER.NAME_1 AS CUSTOMER_NAME
        , CUSTOMER.SEARCH_TERM_2_FOR_BUSINESS_PARTNER AS CUSTOMER_NAME_B
        , CUSTOMER.BUSINESS_PARTNER_NUMBER
        , CUSTOMER.CORPORATION
        , CUSTOMER_A.NAME_1 AS CUSTOMER_A_NAME
        , CUSTOMER_GROUP_MAPPING.CUSTOMER_GROUP AS CUSTOMER_GROUP
        , CUSTOMER_GROUP_MAPPING.CUSTOMER_GROUP2 AS CUSTOMER_GROUP2
        , CUSTOMER.CITY
        , CUSTOMER.REGION
  FROM {{ ref('SILVER__TEH_FINANCE__BUSINESS_PARTNERS_GENERAL_DATA') }} AS CUSTOMER
        LEFT JOIN {{ ref('SILVER__TEH_FINANCE__BUSINESS_PARTNERS_GENERAL_DATA') }}  AS CUSTOMER_A
            ON CUSTOMER.CORPORATION = CUSTOMER_A.CUSTOMER_NUMBER
        LEFT JOIN CUSTOMER_GROUP_MAPPING
            ON CUSTOMER_GROUP_MAPPING.ACCOUNT_NUMBER = CUSTOMER.CORPORATION
    WHERE CUSTOMER.CUSTOMER_FLAG = 'Y'
),
RSEG_DATA AS
(
    SELECT
         EBELN,
         EBELP,
         BELNR,
         WERKS,
         MENGE,
         WRBTR,
         BNKAN
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU197_RSEG') }}
),
VENDOR AS (
    SELECT DISTINCT
        VENDOR.LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR AS VENDOR_NUMBER
        , VENDOR.LFA1_NAME_1_NAME1 AS VENDOR_NAME
        , VENDOR.LFA1_COUNTRY_KEY_LAND1 AS COUNTRY
        , VENDOR.LFA1_CITY_ORT01 AS CITY
        , VENDOR.LFA1_REGION AS REGION
    FROM {{ ref('SILVER__TEH_FINANCE__BUSINESS_PARTNERS_GENERAL_DATA') }}  AS VENDOR
),
SHIP_ADDRESS AS
(
    SELECT
        ADDRNUMBER,
        NAME1,
        CITY1,
        POSTCODE1,
        STREET,
        HOUSENUM1,
        REGION,
        COUNTRY
    FROM  {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU087_ADRC') }}
),
DOC_TYPE_DESC AS
(
    SELECT DISTINCT
        BLART,
        LTEXT
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPO_DOCUMENT_TYPE_TEXTS') }}
    WHERE SPRAS = 'E'
        AND MANDT = '000'
),
account_type as (
    Select *
    From {{ ref('BRONZE__TEH_FINANCE__SAPH_SAP_FIM_EV_SKAT') }} as account_type
    Where account_type.SPRAS='EN'
),
billing_type_text as (
    Select *
    From {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU163_TVFKT') }} as billing_type_text
    Where billing_type_text.SPRAS='EN'
),
PO_type_text as (
    Select *
    From {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU129_T161T') }} as PO_type_text
    Where PO_type_text.SPRAS = 'EN'
),
profit_center as (
    select
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('BRONZE__TEH_FINANCE__FILE_PROFIT_CENTER') }}
),
cost_center as (
    select
        COST_CENTER_CODE,
        COST_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('BRONZE__TEH_FINANCE__FILE_COST_CENTER') }}
),
PURCHASE_ORDER_DETAILS AS
(
    SELECT
        EKKO.EBELN AS EKKO_EBELN,
        EKKO.KNUMV AS EKKO_KNUMV,
        EKKO.BSART AS EKKO_BSART,
        EKPO.EBELN AS EKPO_EBELN,
        EKPO.TXZ01 AS EKPO_TXZ01,
        EKPO.EBELP AS EKPO_EBELP,
        EKPO.ADRN2 AS EKPO_ADRN2
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU027_EKKO') }} EKKO
    INNER JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU028_EKPO') }} EKPO
    ON EKKO.EBELN=EKPO.EBELN
),
PRCD_DETAILS AS
(
    SELECT
        KSCHL,
        KNUMV,
        KPOSN
    FROM  {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU029_PRCD_ELEMENTS') }}
),
BSET_DATA AS
(
    SELECT
        BUKRS,
        BELNR,
        BUZEI,
        GJAHR,
        HWSTE,
        KSCHL,
        TXJCD,
        MWSKZ
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU045_BSET') }}
),
COND_DATA AS
(
    SELECT
        KSCHL,
        VTEXT
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU139_T685T') }}
    WHERE SPRAS='EN'
),
BKPF_DATA AS
(
    SELECT
        BUKRS,
        BELNR,
        GJAHR,
        BKTXT,
        XBLNR
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU037_BKPF') }}
),
BSEG_DATA AS
(
    SELECT
        BELNR,
        BUKRS,
        GJAHR,
        BUZEI,
        TXBHW
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU038_BSEG') }}
),
ACDOCA_DETAILS AS
(
    SELECT
        ACCOUNT_TYPE,
        POSTING_KEY,
        DOCUMENT_TYPE,
        ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
        CUSTOMER_NUMBER,
        ACCOUNTING_DOCUMENT_NUMBER,
        ASSIGNMENT_NUMBER,
        REFERENCE_DOCUMENT_NUMBER,
        REFERENCE_DOCUMENT_LINE_ITEM,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNT_NUMBER,
        BILLING_TYPE,
        LTRIM(POSTING_PERIOD,'0') AS FiscalPeriod,
        NUMBER_OF_LINE_ITEM_WITHIN_ACCOUNTING_DOCUMENT,
        try_to_date(POSTING_DATE_IN_THE_DOCUMENT,'YYYYMMDD') AS PostingDate,
        try_to_date(DOCUMENT_DATE_IN_DOCUMENT,'YYYYMMDD') AS DocumentDate,
        AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY AS AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY,
        DEBIT_CREDIT_INDICATOR_DRCRK AS DEBIT_CREDIT_INDICATOR_DRCRK,
        ITEM_TEXT AS ITEM_TEXT,
        OFFSETTING_ACCOUNT_NUMBER AS OFFSETTING_ACCOUNT_NUMBER,
        PROFIT_CENTER,
        COST_CENTER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY
  FROM   {{ ref('SILVER__TEH_FINANCE__SAPH_UNIVERSAL_JOURNAL_ENTRY_LINE') }}
  WHERE LEDGER_IN_GENERAL_LEDGER_ACCOUNTING='0L'
  GROUP BY ALL
),
source_data as (
    SELECT DISTINCT
        ACCOUNT_TYPE,
        POSTING_KEY,
        DOCUMENT_TYPE,
        Case
            When ACCOUNT_TYPE='A' Then 'Assets'
            When ACCOUNT_TYPE='D' Then 'Customers'
            When ACCOUNT_TYPE='K' Then 'Vendors'
            When ACCOUNT_TYPE='M' Then 'Material'
            When ACCOUNT_TYPE='S' Then 'G/L Accounts'
            Else Null
        End As ACCOUNT_DESCRIPTION,
        account_type.SAKNR AS ACCOUNT_NUMBER,
        account_type.MCOD1 AS ACCOUNT_NAME,
        ACDOCA.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR AS ACDOCA_VENDOR_NUMBER,
        ACDOCA.CUSTOMER_NUMBER AS CUSTOMER_NUMBER,
        VENDOR.VENDOR_NUMBER AS VENDOR_NUMBER,
        VENDOR.VENDOR_NAME AS VENDOR_NAME,
        VENDOR.COUNTRY AS COUNTRY,
        VENDOR.CITY AS CITY,
        SHIP_ADDRESS.CITY1 as SHIP_TO_CITY,
        SHIP_ADDRESS.REGION AS SHIP_TO_REGION,
        ACDOCA.ACCOUNTING_DOCUMENT_NUMBER AS ACCOUNTING_DOCUMENT,
        ACDOCA.DOCUMENT_TYPE AS ACCOUNTING_DOCUMENT_TYPE,
        DOC_TYPE_DESC.LTEXT AS DOC_TYPE_DESCRIPTION,
        ACDOCA.REFERENCE_DOCUMENT_NUMBER AS REFERENCE_DOCUMENT,
        ACDOCA.REFERENCE_DOCUMENT_LINE_ITEM AS REFERENCE_DOCUMENT_LINE_ITEM,
        ACDOCA.PURCHASING_DOCUMENT_NUMBER AS PURCHASE_ORDER,
        ACDOCA.ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS PURCHASE_ORDER_LINE_ITEM,
        PO_type_text.BATXT AS PURCHASE_ORDER_DOC_TYPE,
        PRCD_DETAILS.KSCHL AS CONDITION_TYPE,
        SCOND.VTEXT AS CONDITION_DESC,
        PURCHASE_ORDER_DETAILS.EKPO_TXZ01 AS PURCHASE_ORDER_NOTE,
        RSEG.MENGE AS QUANTITY,
        BCOND.VTEXT AS TAX_CONDITION,
        COALESCE(RSEG.WRBTR,BSEG_DATA.TXBHW) AS TAX_BASE,
        RSEG.BNKAN AS SHIPPING_HANDLING_AMOUNT,
        BSET_DATA.HWSTE AS TAX_ON_INVOICE,
        ACDOCA.COMPANY_CODE AS COMPANY_CODE,
        Case
            When ACDOCA.COMPANY_CODE = '1100' Then 'TEL'
            When ACDOCA.COMPANY_CODE = '1200' Then 'TTS'
            When ACDOCA.COMPANY_CODE = '1500' Then 'TKL'
            When ACDOCA.COMPANY_CODE = '1600' Then 'TML'
            When ACDOCA.COMPANY_CODE = '1700' Then 'TFE'
            When ACDOCA.COMPANY_CODE = '1800' Then 'TELBP'
            When ACDOCA.COMPANY_CODE = '1900' Then 'TAC'
            When ACDOCA.COMPANY_CODE = '3100' Then 'TEH'
            When ACDOCA.COMPANY_CODE = '3200' Then 'TEA'
            When ACDOCA.COMPANY_CODE = '3300' Then 'TTCA'
            When ACDOCA.COMPANY_CODE = '3400' Then 'TVC'
            When ACDOCA.COMPANY_CODE = '3500' Then 'TMEA'
            Else Null
        End AS COMPANY_NAME,
        ACDOCA.FISCAL_YEAR AS FISCAL_YEAR,
        FiscalPeriod AS FISCAL_PERIOD,
        PostingDate AS POSTING_DATE,
        DocumentDate AS DOCUMENT_DATE,
        ACDOCA.AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY,
        ACDOCA.DEBIT_CREDIT_INDICATOR_DRCRK,
        ACDOCA.ITEM_TEXT,
        ACDOCA.OFFSETTING_ACCOUNT_NUMBER,
        BKPF.BKTXT as DOCUMENT_HEADER_TEXT_BKPF,
        BKPF.XBLNR as REFERENCE_BKPF,
        PROFIT_CENTER.OFFICE AS OFFICE,
        BSET_DATA.TXJCD as TAX_JURISDICTION,
        BSET_DATA.MWSKZ as TAX_CODE,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        RSEG.EBELN AS RSEG_DOCUMENT_NUMBER,
        RSEG.EBELP AS RSEG_PURCHASING_DOC,
        RSEG.BELNR AS RSEG_ARIBA_ITEM_NUMBER,
        RSEG.WERKS AS RSEG_PLANT,
        NUMBER_OF_LINE_ITEM_WITHIN_ACCOUNTING_DOCUMENT,
        COALESCE(ACDOCA.COST_CENTER,'') AS COST_CENTER_CODE,
        COALESCE(cost_center.COST_CENTER_NAME,'') AS COST_CENTER_NAME,
        COALESCE(ACDOCA.PROFIT_CENTER,'') AS PROFIT_CENTER_CODE,
        COALESCE(profit_center.PROFIT_CENTER_NAME,'') AS PROFIT_CENTER_NAME
    FROM ACDOCA_DETAILS ACDOCA
        LEFT OUTER JOIN BKPF_DATA BKPF
            ON BKPF.BUKRS = ACDOCA.COMPANY_CODE
            AND BKPF.BELNR = ACDOCA.ACCOUNTING_DOCUMENT_NUMBER
            AND BKPF.GJAHR = ACDOCA.FISCAL_YEAR
        LEFT OUTER JOIN PURCHASE_ORDER_DETAILS
            ON PURCHASE_ORDER_DETAILS.EKKO_EBELN = ACDOCA.PURCHASING_DOCUMENT_NUMBER
            AND PURCHASE_ORDER_DETAILS.EKPO_EBELN = ACDOCA.PURCHASING_DOCUMENT_NUMBER
            AND PURCHASE_ORDER_DETAILS.EKPO_EBELP = ACDOCA.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
        LEFT OUTER JOIN PRCD_DETAILS
            ON PURCHASE_ORDER_DETAILS.EKKO_KNUMV = PRCD_DETAILS.KNUMV
            AND TRY_TO_NUMBER(PURCHASE_ORDER_DETAILS.EKPO_EBELP)=TRY_TO_NUMBER(PRCD_DETAILS.KPOSN)
        LEFT OUTER JOIN BSET_DATA
            ON BSET_DATA.BUKRS = ACDOCA.COMPANY_CODE
            AND BSET_DATA.BELNR = ACDOCA.ACCOUNTING_DOCUMENT_NUMBER
            AND BSET_DATA.BUZEI = ACDOCA.NUMBER_OF_LINE_ITEM_WITHIN_ACCOUNTING_DOCUMENT
            AND BSET_DATA.GJAHR = ACDOCA.FISCAL_YEAR
        LEFT JOIN account_type
            ON (ACDOCA.ACCOUNT_NUMBER = account_type.SAKNR)
        LEFT JOIN billing_type_text
            ON (ACDOCA.BILLING_TYPE = billing_type_text.FKART)
        LEFT JOIN profit_center
            ON (ACDOCA.PROFIT_CENTER = profit_center.PROFIT_CENTER_CODE)
        LEFT OUTER JOIN cost_center
            ON (ACDOCA.COST_CENTER=cost_center.COST_CENTER_CODE)
        LEFT JOIN PO_type_text
            ON (PURCHASE_ORDER_DETAILS.EKKO_BSART = PO_type_text.BSART)
        LEFT JOIN DOC_TYPE_DESC
            ON ACDOCA.DOCUMENT_TYPE = DOC_TYPE_DESC.BLART
        LEFT JOIN VENDOR
            ON ACDOCA.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR = VENDOR.VENDOR_NUMBER
        LEFT JOIN COND_DATA SCOND
            ON SCOND.KSCHL = PRCD_DETAILS.KSCHL
        LEFT JOIN COND_DATA BCOND
            ON BCOND.KSCHL = BSET_DATA.KSCHL
        LEFT JOIN RSEG_DATA AS RSEG
            ON RSEG.EBELN=PURCHASE_ORDER_DETAILS.EKPO_EBELN
            AND RSEG.EBELP=PURCHASE_ORDER_DETAILS.EKPO_EBELP
            AND TRY_TO_NUMBER(RSEG.BELNR)=TRY_TO_NUMBER(ACDOCA.reference_document_number)
        left join customer cust
            ON ACDOCA.customer_number=cust.customer_number
        LEFT JOIN SHIP_ADDRESS
            ON PURCHASE_ORDER_DETAILS.EKPO_ADRN2=SHIP_ADDRESS.ADDRNUMBER
        LEFT JOIN BSEG_DATA
            ON BSEG_DATA.BELNR=ACDOCA.reference_document_number
            AND BSEG_DATA.BUKRS=ACDOCA.COMPANY_CODE
            AND BSEG_DATA.GJAHR=ACDOCA.FISCAL_YEAR
            AND BSEG_DATA.BUZEI=ACDOCA.NUMBER_OF_LINE_ITEM_WITHIN_ACCOUNTING_DOCUMENT
	),


WITH
MATDOC_AGG AS (
    SELECT 
        LGORT, 
        MATNR, 
        EBELN, 
        EBELP, 
        SUM(STOCK_QTY) AS STOCK_QTY,
        MIN(TRY_TO_DATE(MATDOC.BLDAT, 'YYYYMMDD')) AS MATDOC_CREATION_DATE,
        MAX(TRY_TO_DATE(MATDOC.BLDAT, 'YYYYMMDD')) AS LATEST_MATDOC_DATE
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU025_MATDOC') }} AS MATDOC
    WHERE NULLIF(MATNR, '') IS NOT NULL
    GROUP BY LGORT, MATNR, EBELN, EBELP
),
SOURCE_DATA AS (
    SELECT 
        EKKO.EBELN AS PO_HDR,
        EKPO.EBELP AS PO_LINE,
        EKPO.BUKRS AS COMPANY_CODE,
        TRY_TO_DATE(EKKO.AEDAT, 'YYYYMMDD') AS PO_DATE,
        EKPO.MENGE AS UNIT_QTY,
        EKPO.NETWR AS NET_ORDER_VALUE,
        --EKPO.BRTWR AS GROSS_ORDER_VALUE,
        EKPO.MATNR AS MATERIAL_ID,
        LEFT(EKPO.MATNR, 2) AS PRODUCT_LINE,
        MARA.MAKTX AS MATERIAL_DESC,
        EKKO.LIFNR AS VENDOR_ACCOUNT_NUMBER,
        LFA1.NAME1 AS VENDOR_NAME,
        EKPO.LGORT AS SLOC,
        EKKO.BSART AS PO_DOC_TYPE,
        MATDOC_AGG.MATDOC_CREATION_DATE,
        EKPO.MENGE AS PO_QTY,
        COALESCE(MATDOC_AGG.STOCK_QTY, 0) AS MATDOC_STOCK_QTY,
        EKKO.WAERS AS CURRENCY
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU028_EKPO') }} AS EKPO
    JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU027_EKKO') }} AS EKKO ON (EKPO.EBELN = EKKO.EBELN)
    LEFT JOIN MATDOC_AGG ON (
        EKPO.LGORT = MATDOC_AGG.LGORT AND 
        EKPO.MATNR = MATDOC_AGG.MATNR AND
        EKPO.EBELN = MATDOC_AGG.EBELN AND
        EKPO.EBELP = MATDOC_AGG.EBELP
    )
    JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU017_MARA') }} AS MARA ON (MARA.MATNR = EKPO.MATNR)
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU061_LFA1') }} AS LFA1 ON (LFA1.LIFNR = EKKO.LIFNR)
    WHERE 
        TRY_TO_DATE(EKKO.AEDAT, 'YYYYMMDD') >= DATEADD(YEAR, -2, CURRENT_DATE()) AND
        NULLIF(EKPO.MATNR, '') IS NOT NULL
),
TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        COMPANY_CODE,
        PO_HDR,
        PO_LINE,
        CAST(PO_DATE AS DATE) AS PO_DATE,
        CAST(UNIT_QTY AS INT) AS UNIT_QTY,
        CAST(NET_ORDER_VALUE AS FLOAT) AS NET_ORDER_VALUE,
        MATERIAL_ID,
        PRODUCT_LINE,
        MATERIAL_DESC,
        VENDOR_ACCOUNT_NUMBER,
        VENDOR_NAME,
        SLOC,
        PO_DOC_TYPE,
        CAST(MATDOC_CREATION_DATE AS DATE) AS MATDOC_CREATION_DATE,
        CAST(PO_QTY AS INT) AS PO_QTY,
        CAST(MATDOC_STOCK_QTY AS INT) AS MATDOC_STOCK_QTY,
        CURRENCY,
        (CASE WHEN PO_QTY <> 0 THEN (NET_ORDER_VALUE/PO_QTY) ELSE 0 END) AS UNIT_COST
    FROM SOURCE_DATA
)
SELECT * FROM TRANSFORM_DATA


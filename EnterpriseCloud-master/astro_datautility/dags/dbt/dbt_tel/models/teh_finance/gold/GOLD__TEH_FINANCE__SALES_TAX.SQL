--BKPF CTE TO GET PERIOD, DOC DATE, POSTING DATE, AND CURRENCY OF ACCOUNTING DOCUMENT
with BKPF as (
    SELECT
        MONAT AS PERIOD,
        BLDAT AS DOCUMENT_DATE,
        BUDAT AS POSTING_DATE,
        WAERS AS DOCUMENT_CURRENCY,
        BUKRS,
        GJAHR,
        BELNR
    FROM ODS.SAPAPI.ZCDV_T_CMTU037_BKPF
),

--SKAT CTE TO GET THE GENERAL LEDGER ACCOUNT NAME IN ENGLISH IN THE Z001 CHART OF ACCOUNTS(a structured list of general ledger (G/L) accounts used by one or more company codes)
SKAT AS (
    SELECT
        TXT50 AS GL_ACCOUNT_NAME,
        SAKNR
    FROM ODS.SAPAPI.ZCDV_T_CMTU121_SKAT
    WHERE SPRAS = 'EN' AND KTOPL = 'Z001'

),

--CUSTOMER CTE TO GET CUSTOMER CODE(B CODE). FILTER IS PARTNER FUNCTION = PAYER
CUSTOMER AS (
    SELECT 
        KUNNR AS CUSTOMER,
        VBELN
    FROM ODS.SAPAPI.ZCDV_T_CMTU047_VBPA
    WHERE PARVW = 'PY'
),

--CCODE CTE TO GET C-CODE. FILTER IS SET TO PARTNER FUNCTION = SHIP TO PARTY
CCODE AS (
    SELECT 
        KUNNR AS CCODE,
        VBELN
    FROM ODS.SAPAPI.ZCDV_T_CMTU047_VBPA
    WHERE PARVW = 'SH'
),

--BSEG CTE TO GET THE BILLING DOCUMENT. FILTER TO NOT BLANK OR NULL
BSEG AS (
    SELECT 
        BSEG.VBELN AS BILLING_DOCUMENT,
        BUKRS,
        GJAHR,
        BELNR
    FROM ODS.SAPAPI.ZCDV_T_CMTU038_BSEG BSEG
    WHERE BSEG.VBELN != '' AND BSEG.VBELN IS NOT NULL

),

--KNA1 CTE TO GET THE BUSINESS PARTNER NAME(BASED ON C-CODE). THEN WE CONCATENATE ADDRESS, CITY, STATE, ZIPCODE, AND COUNTRY TO GET THE SHIP TO ADDRESS
KNA1 AS (
    SELECT 
        NAME1 AS BUSINESS_PARTNER,
        CONCAT(STRAS,', ',MCOD3,', ',REGIO,', ',PSTLZ,', ',LAND1) AS SHIP_TO_ADDRESS,
        KUNNR
    FROM ODS.SAPAPI.ZCDV_T_CMTU020_KNA1
),

--COMBINING ALL DATA TO GET EXPECTED OUTPUT
COMBINED AS (
    SELECT 
        BSET.BUKRS AS COMPANY_CODE,
        BSET.GJAHR AS FISCAL_YEAR,
        BKPF.PERIOD AS PERIOD,
        HKONT AS GL_ACCOUNT,
        SKAT.GL_ACCOUNT_NAME AS GL_ACCOUNT_NAME,
        BSET.BELNR AS DOCUMENT_NUMBER,
        BSET.TXGRP AS GROUP_INDICATOR,
        BKPF.DOCUMENT_DATE AS DOCUMENT_DATE,
        BKPF.POSTING_DATE AS POSTING_DATE,
        CUSTOMER.CUSTOMER AS CUSTOMER,
        CCODE.CCODE AS CCODE,
        KNA1.BUSINESS_PARTNER AS BUSINESS_PARTNER,
        KNA1.SHIP_TO_ADDRESS AS SHIP_TO_ADDRESS,
        BSET.MWSKZ AS TAX_CODE,
        TXJCD AS TAX_JURISDICTION,
        BKPF.DOCUMENT_CURRENCY AS DOCUMENT_CURRENCY,
        cast(BSET.KBETR as number(6,4)) AS PERCENTAGE,
        BSET.HWBAS AS LC_TAX_BASE,
        BSET.HWSTE AS LC_TAX_AMOUNT,
        BSET.SHKZG AS DEBIT_CREDIT_INDICATOR,
        BSET.KSCHL AS CONDITION_TYPE,
        BSEG.BILLING_DOCUMENT AS BILLING_DOCUMENT
    FROM ODS.SAPAPI.ZCDV_T_CMTU045_BSET BSET
        JOIN BSEG 
            ON BSET.BUKRS = BSEG.BUKRS --COMPANY CODE
            AND BSET.GJAHR = BSEG.GJAHR --FISCAL YEAR
            AND BSET.BELNR = BSEG.BELNR -- DOC NUMBER
        JOIN BKPF 
            ON BSET.BUKRS = BKPF.BUKRS --COMPANY CODE
            AND BSET.GJAHR = BKPF.GJAHR --FISCAL YEAR
            AND BSET.BELNR = BKPF.BELNR -- DOC NUMBER
        JOIN SKAT
            ON BSET.HKONT = SKAT.SAKNR --G/L ACCOUNT
        LEFT JOIN CUSTOMER
            ON BSEG.BILLING_DOCUMENT = CUSTOMER.VBELN --BILLING DOC
        LEFT JOIN CCODE 
            ON BSEG.BILLING_DOCUMENT = CCODE.VBELN --BILLING DOC
        JOIN KNA1
            ON CCODE.CCODE =  KNA1.KUNNR --CUSTOMER
),

-- PERCENTAGE CALCULATION CTE. THIS IS BASED ON THE REQUESTORS REQUIREMENT TO GROUP THE DOCUMENT ITEMS, SUM THEIR PERCENTAGES, AND DIVIDE BY 10. THIS WILL THEN GIVE DESIRED OUTPUT OR USER
-- SIMILIAR REQUIREMENT AS ABOVE FOR THE TAX AMOUNT
PERCENTAGE_CALC AS (
    SELECT 
        SUM(PERCENTAGE)/10 AS ROLLUP,
        SUM(LC_TAX_AMOUNT) AS TAX_AMOUNT,
        COMPANY_CODE,
        FISCAL_YEAR,
        DOCUMENT_NUMBER,
        GROUP_INDICATOR    
    FROM COMBINED
    GROUP BY 
        COMPANY_CODE,
        FISCAL_YEAR,
        DOCUMENT_NUMBER,
        GROUP_INDICATOR
),

-- FINAL CTE TO ADD IN THE ROLLED UP PERCENTAGE VALUES BASED ON REQUIREMENTS. USER WANTS TO ONLY SEE RECORD WITH CONDITION TYPE 4. SO THE PERCENTAGE AND TAX AMOUNT ROLL UP WITH REPLACE THE PERCENTAGE AND TAX AMOUNT OF THE JR4 RECORD
SOURCE_DATA AS (
    SELECT 
        C.COMPANY_CODE,
        C.FISCAL_YEAR,
        PERIOD,
        GL_ACCOUNT,
        GL_ACCOUNT_NAME,
        C.DOCUMENT_NUMBER,
        C.GROUP_INDICATOR,
        DOCUMENT_DATE,
        POSTING_DATE,
        CUSTOMER,
        CCODE,
        BUSINESS_PARTNER,
        SHIP_TO_ADDRESS,
        TAX_CODE,
        TAX_JURISDICTION,
        DOCUMENT_CURRENCY,
        P.ROLLUP AS PERCENTAGE,
        CASE
            WHEN DEBIT_CREDIT_INDICATOR = 'H' THEN LC_TAX_BASE * -1
            WHEN DEBIT_CREDIT_INDICATOR = 'S' THEN LC_TAX_BASE
        END AS LC_TAX_BASE,
        CASE
            WHEN P.TAX_AMOUNT = 0 THEN 0
            WHEN DEBIT_CREDIT_INDICATOR = 'H' THEN P.TAX_AMOUNT * -1
            WHEN DEBIT_CREDIT_INDICATOR = 'S' THEN P.TAX_AMOUNT 
        END AS LC_TAX_AMOUNT,
        DEBIT_CREDIT_INDICATOR,
        CONDITION_TYPE,
        BILLING_DOCUMENT     
    FROM COMBINED C
        LEFT JOIN PERCENTAGE_CALC P
            ON C.COMPANY_CODE = P.COMPANY_CODE
            AND C.FISCAL_YEAR = P.FISCAL_YEAR
            AND C.DOCUMENT_NUMBER  = P.DOCUMENT_NUMBER
            AND C.GROUP_INDICATOR  = P.GROUP_INDICATOR
    WHERE C.CONDITION_TYPE = 'JR4'
),

TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        COMPANY_CODE,
        FISCAL_YEAR,
        PERIOD,
        GL_ACCOUNT,
        GL_ACCOUNT_NAME,
        DOCUMENT_NUMBER,
        GROUP_INDICATOR,
        DOCUMENT_DATE,
        POSTING_DATE,
        CUSTOMER,
        CCODE,
        BUSINESS_PARTNER,
        SHIP_TO_ADDRESS,
        TAX_CODE,
        TAX_JURISDICTION,
        DOCUMENT_CURRENCY,
        PERCENTAGE,
        LC_TAX_BASE,
        LC_TAX_AMOUNT,
        DEBIT_CREDIT_INDICATOR,
        CONDITION_TYPE,
        BILLING_DOCUMENT
FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        COMPANY_CODE,
        FISCAL_YEAR,
        PERIOD,
        GL_ACCOUNT,
        GL_ACCOUNT_NAME,
        DOCUMENT_NUMBER,
        DOCUMENT_DATE,
        POSTING_DATE,
        CUSTOMER,
        CCODE,
        BUSINESS_PARTNER,
        SHIP_TO_ADDRESS,
        TAX_CODE,
        TAX_JURISDICTION,
        DOCUMENT_CURRENCY,
        CAST(PERCENTAGE as NUMBER(24,10)) as PERCENTAGE,
        CAST(LC_TAX_BASE as NUMBER(24,10)) as LC_TAX_BASE,
        CAST(LC_TAX_AMOUNT as FLOAT) as LC_TAX_AMOUNT,
        DEBIT_CREDIT_INDICATOR,
        CONDITION_TYPE,
        GROUP_INDICATOR,
        BILLING_DOCUMENT 
from TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA


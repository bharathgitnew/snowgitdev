WITH ACDOCA AS (
    SELECT
        COMPANY_CODE
        , POSTING_DATE
        , ACCOUNTING_DOCUMENT_NUMBER
        , SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER
        , ACCOUNT_NUMBER
        , ASSIGNMENT_NUMBER
        , COST_CENTER
        , NULLIF(SALES_ORDER_NUMBER, '') AS SALES_ORDER_NUMBER
        , NULLIF(ITEM_NUMBER_IN_SALES_ORDER, '') AS ITEM_NUMBER_IN_SALES_ORDER
        , RELATED_SALES_DOCUMENT
        , RELATED_SALES_DOCUMENT_ITEM
        , AMOUNT_IN_COMPANY_CODE_CURRENCY
        , ITEM_TEXT
    FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS') }}
)

, IPR AS (
    SELECT DISTINCT
        VBELN AS SALES_DOCUMENT
        , POSNR AS SALES_DOCUMENT_ITEM
        , ZZIPRID AS IPR_NUMBER
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU016_ZSDT0163') }}
    WHERE (ZZIPRID <> '' OR ZZIPRID IS NOT NULL)
)

, BP AS (
    SELECT DISTINCT
    	SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER AS SALES_DOCUMENT
        , ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM
        , CUSTOMER_NUMBER
    FROM {{ ref('SILVER__TEH_FINANCE__BUSINESS_PARTNERS') }}
    WHERE PARTNER_FUNCTION = 'SH'
)

, BP_DETAIL AS (
    SELECT DISTINCT
    	CUSTOMER_NUMBER
        , NAME_1
        , CITY
        , REGION
    FROM {{ ref('SILVER__TEH_FINANCE__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE CUSTOMER_FLAG = 'Y'
)

, SALES_DOCUMENTS AS (
    SELECT
        VBAK_SALES_DOCUMENT AS SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM_POSNR AS SALES_DOCUMENT_ITEM
        , SALES_DOCUMENT_TYPE
    FROM {{ ref('SILVER__TEH_FINANCE__SALES_ORDER') }}
    WHERE VBAK_SALES_ORGANIZATION = '3200'
)

, SOURCE_DATA AS (
    SELECT
        ACDOCA.POSTING_DATE
        , ACDOCA.ACCOUNTING_DOCUMENT_NUMBER
        , ACDOCA.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER
        , ACDOCA.ACCOUNT_NUMBER
        , ACDOCA.COST_CENTER
        , ACDOCA.RELATED_SALES_DOCUMENT
        , ACDOCA.RELATED_SALES_DOCUMENT_ITEM
        , ACDOCA.SALES_ORDER_NUMBER
        , ACDOCA.ITEM_NUMBER_IN_SALES_ORDER
        , IPR_SO_ONLY.SALES_DOCUMENT AS IPR_SALES_DOCUMENT
        , IPR.IPR_NUMBER
        , SD.SALES_DOCUMENT_TYPE
        , BP.CUSTOMER_NUMBER AS SHIP_TO
        , BP_DETAIL.NAME_1 AS SHIP_TO_NAME
        , BP_DETAIL.CITY AS SHIP_TO_CITY
        , BP_DETAIL.REGION AS SHIP_TO_STATE
        , ACDOCA.ITEM_TEXT
        , ACDOCA.AMOUNT_IN_COMPANY_CODE_CURRENCY
    FROM ACDOCA
        LEFT JOIN SALES_DOCUMENTS AS SD
            ON TRY_TO_NUMBER(COALESCE(ACDOCA.related_SALES_DOCUMENT, ACDOCA.SALES_ORDER_NUMBER)) = SD.SALES_DOCUMENT
            and TRY_TO_NUMBER(COALESCE(ACDOCA.RELATED_SALES_DOCUMENT_ITEM, ACDOCA.ITEM_NUMBER_IN_SALES_ORDER)) = SD.SALES_DOCUMENT_ITEM
        LEFT JOIN IPR
            ON COALESCE(ACDOCA.RELATED_SALES_DOCUMENT, ACDOCA.SALES_ORDER_NUMBER) = TRY_TO_NUMBER(IPR.SALES_DOCUMENT)
            AND COALESCE(ACDOCA.RELATED_SALES_DOCUMENT_ITEM, ACDOCA.ITEM_NUMBER_IN_SALES_ORDER) = TRY_TO_NUMBER(IPR.SALES_DOCUMENT_ITEM)
        LEFT JOIN 
            (SELECT DISTINCT SALES_DOCUMENT, IPR_NUMBER FROM IPR) AS IPR_SO_ONLY
                ON ACDOCA.ITEM_TEXT = IPR_SO_ONLY.IPR_NUMBER
        LEFT JOIN BP
            ON COALESCE(ACDOCA.RELATED_SALES_DOCUMENT, ACDOCA.SALES_ORDER_NUMBER, IPR_SO_ONLY.SALES_DOCUMENT) = BP.SALES_DOCUMENT
            AND TRY_TO_NUMBER(BP.SALES_DOCUMENT_ITEM) = 0
        LEFT JOIN BP_DETAIL
            ON BP.CUSTOMER_NUMBER = BP_DETAIL.CUSTOMER_NUMBER
    WHERE 1=1
        AND ACDOCA.COMPANY_CODE = '3200'
        AND ACDOCA.ACCOUNT_NUMBER in ('6130800005', '7130800005')
        AND (
            ( SD.SALES_DOCUMENT_TYPE IN ('ZF11', 'ZS14') )
            OR
            ( SD.SALES_DOCUMENT_TYPE IS NULL --no sales order reference
                AND (REGEXP_LIKE(LEFT(ITEM_TEXT,8), 'TEA[0-9]{5}') -- IPR number in text field
                    OR ( LEN(ITEM_TEXT) = 5 AND REGEXP_LIKE(LEFT(ITEM_TEXT,5), '[0-9]{5}') )
                    )
            )
        )
)

, transform_data as (
    SELECT
        POSTING_DATE
        , ACCOUNTING_DOCUMENT_NUMBER
        , SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER
        , ACCOUNT_NUMBER
        , COST_CENTER
        , COALESCE(RELATED_SALES_DOCUMENT, SALES_ORDER_NUMBER, IPR_SALES_DOCUMENT) as SALES_DOCUMENT
        , NULLIF(TRY_TO_NUMBER(COALESCE(RELATED_SALES_DOCUMENT_ITEM, ITEM_NUMBER_IN_SALES_ORDER)), 0) AS SALES_DOCUMENT_ITEM
        , SHIP_TO
        , SHIP_TO_NAME
        , SHIP_TO_CITY
        , SHIP_TO_STATE
        , CASE
            WHEN SALES_DOCUMENT_ITEM IS NOT NULL THEN IPR_NUMBER
            ELSE ITEM_TEXT
        END as IPR_NUMBER
        , ITEM_TEXT
        , AMOUNT_IN_COMPANY_CODE_CURRENCY
        , '{{ invocation_id }}' AS AUDIT_LOG_ID
    FROM SOURCE_DATA
)

, type_data as (
    select
        CAST(POSTING_DATE AS DATE) AS POSTING_DATE
        , ACCOUNTING_DOCUMENT_NUMBER
        , SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER
        , ACCOUNT_NUMBER
        , COST_CENTER
        , SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM
        , SHIP_TO
        , SHIP_TO_NAME
        , SHIP_TO_CITY
        , SHIP_TO_STATE
        , IPR_NUMBER
        , ITEM_TEXT
        , CAST(AMOUNT_IN_COMPANY_CODE_CURRENCY AS NUMBER(38,2)) AS AMOUNT_IN_COMPANY_CODE_CURRENCY
        , AUDIT_LOG_ID
    FROM TRANSFORM_DATA
)

select * from type_data


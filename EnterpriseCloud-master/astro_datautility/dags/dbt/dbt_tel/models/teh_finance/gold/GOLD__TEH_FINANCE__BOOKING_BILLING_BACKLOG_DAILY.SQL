WITH SALES_DOC_PARTNER_DATA as (
	SELECT DISTINCT
    	SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as SALES_DOCUMENT
        , ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM
        , CUSTOMER_NUMBER
    FROM {{ ref('SILVER__TEH_FINANCE__BUSINESS_PARTNERS') }}
    WHERE PARTNER_FUNCTION = 'Z6'
),
CUSTOMER AS (
	SELECT DISTINCT
    	CUSTOMER_NUMBER
        , NAME_1 AS CUSTOMER_NAME
    FROM {{ ref('SILVER__TEH_FINANCE__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE CUSTOMER_FLAG = 'Y'
),
VBAP_HISTORY AS (
    SELECT
        PRCTR as PROFIT_CENTER
        , KOSTL AS COST_CENTER
        , ZZORTY AS SALES_CATEGORY
        , ZZORZZ AS ORDER_REASON
        , VBELN AS SALES_DOCUMENT
        , POSNR AS SALES_DOCUMENT_ITEM
        , MATNR AS MATERIAL_NUMBER
        , NETWR AS ORDER_AMOUNT
        , ABGRU AS REJECTION_REASON
        , SNAPSHOT_DATE-1 as SNAPSHOT_DATE
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU010_VBAP_HIST') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1
),
VBAK AS (
    SELECT DISTINCT
        VBAK_SALES_ORGANIZATION AS SALES_ORGANIZATION
        , VBAK_SOLD_TO_PARTY AS SOLD_TO_PARTY
        , VBAK_SALES_DOCUMENT AS SALES_DOCUMENT
        , VBAK_SALES_DOCUMENT_TYPE as SALES_DOCUMENT_TYPE
        , DOCUMENT_DATE as SALES_DOCUMENT_DATE
    FROM {{ ref('SILVER__TEH_FINANCE__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_ORGANIZATION = '3200'
),
VBRP_HISTORY AS (
    SELECT
        VBELN AS BILLING_DOCUMENT
        , POSNR AS BILLING_DOCUMENT_ITEM
        , AUBEL AS SALES_DOCUMENT
        , AUPOS AS SALES_DOCUMENT_ITEM
        , NETWR AS BILLING_AMOUNT
     FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU015_VBRP_HIST') }}
     QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1
),
VBRK_HISTORY AS (
    SELECT
        VBELN as BILLING_DOCUMENT
        , FKART as BILLING_TYPE
        , FKSTO AS BILLING_DOC_IS_CANCELED
        , SFAKN as CANCELLED_BILLING_DOC
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU014_VBRK_HIST') }}
    WHERE 1=1 
        AND VKORG = '3200'
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN ORDER BY SNAPSHOT_DATE DESC )) = 1
),
VBEP_HISTORY AS (
    SELECT 
        VBELN AS SALES_DOCUMENT,
        POSNR AS SALES_DOCUMENT_ITEM,
        EDATU AS SCHEDULE_LINE_DATE
    FROM {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU011_VBEP_HIST') }} 
    WHERE 1=1 
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN,POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1
),
BILLING AS (
    SELECT
        VBRP_HISTORY.BILLING_DOCUMENT AS BILLING_DOCUMENT
        , VBRP_HISTORY.BILLING_DOCUMENT_ITEM
        , VBRP_HISTORY.SALES_DOCUMENT
        , VBRP_HISTORY.SALES_DOCUMENT_ITEM
        , VBRP_HISTORY.BILLING_AMOUNT
        , VBRK_HISTORY.BILLING_DOC_IS_CANCELED
        , VBRK_HISTORY.CANCELLED_BILLING_DOC
    FROM VBRP_HISTORY
        INNER JOIN VBRK_HISTORY
            ON TRY_TO_NUMBER(VBRP_HISTORY.BILLING_DOCUMENT) = TRY_TO_NUMBER(VBRK_HISTORY.BILLING_DOCUMENT)
    WHERE 1=1
        AND (VBRK_HISTORY.BILLING_DOC_IS_CANCELED = FALSE OR VBRK_HISTORY.BILLING_DOC_IS_CANCELED is null) --ignore cancelled billing documents
        AND (CANCELLED_BILLING_DOC = '' OR CANCELLED_BILLING_DOC IS NULL)
        AND VBRK_HISTORY.BILLING_TYPE <> 'ZC12' --ignore down payments
),
TOTAL_BILLING AS (
    SELECT
        SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM
        , SUM(BILLING_AMOUNT) AS BILLING_AMOUNT
    FROM BILLING
    GROUP BY SALES_DOCUMENT, SALES_DOCUMENT_ITEM
),

MASTER_DATA_SEGMENT AS (
    SELECT DISTINCT
        SAP_CODE
        , SAP_DESCRIPTION AS SEGMENT
    FROM {{ ref('SILVER__TEH_FINANCE__SAP_SEGMENT') }}
),

SOURCE_DATA AS (
    SELECT
        VBAP_HISTORY.PROFIT_CENTER AS PROFIT_CENTER
        , MASTER_DATA_SEGMENT.SEGMENT AS BU
        , VBAP_HISTORY.SALES_CATEGORY AS SALES_CATEGORY
        , VBAK.SOLD_TO_PARTY AS SOLD_TO_PARTY
        , CUSTOMER.CUSTOMER_NAME AS CUSTOMER_NAME
        , SALES_DOC_PARTNER_DATA.CUSTOMER_NUMBER AS END_USER
        , VBAP_HISTORY.ORDER_REASON AS ORDER_REASON
        , VBAK.SALES_DOCUMENT_TYPE AS SALES_DOCUMENT_TYPE
        , VBAK.SALES_DOCUMENT_DATE AS SALES_DOCUMENT_DATE
        , VBAP_HISTORY.SALES_DOCUMENT AS SALES_DOCUMENT
        , VBAP_HISTORY.SALES_DOCUMENT_ITEM AS SALES_DOCUMENT_ITEM
        , VBAP_HISTORY.MATERIAL_NUMBER AS MATERIAL_NUMBER
        , ROUND(VBAP_HISTORY.ORDER_AMOUNT, 2) AS ORDER_AMOUNT
        , ZEROIFNULL(TOTAL_BILLING.BILLING_AMOUNT) AS BILLING_AMOUNT
        , ROUND(VBAP_HISTORY.ORDER_AMOUNT - ZEROIFNULL(TOTAL_BILLING.BILLING_AMOUNT), 2) as BACKLOG_AMOUNT
        , VBEP_HISTORY.SCHEDULE_LINE_DATE
    FROM VBAP_HISTORY
        INNER JOIN VBAK
            ON TRY_TO_NUMBER(VBAP_HISTORY.SALES_DOCUMENT) = TRY_TO_NUMBER(VBAK.SALES_DOCUMENT)
        LEFT JOIN VBEP_HISTORY
            ON TRY_TO_NUMBER(VBAP_HISTORY.SALES_DOCUMENT) = TRY_TO_NUMBER(VBEP_HISTORY.SALES_DOCUMENT)
            AND TRY_TO_NUMBER(VBAP_HISTORY.SALES_DOCUMENT_ITEM) = TRY_TO_NUMBER(VBEP_HISTORY.SALES_DOCUMENT_ITEM)
        LEFT JOIN TOTAL_BILLING
            ON TRY_TO_NUMBER(VBAP_HISTORY.SALES_DOCUMENT) = TRY_TO_NUMBER(TOTAL_BILLING.SALES_DOCUMENT) 
            AND TRY_TO_NUMBER(VBAP_HISTORY.SALES_DOCUMENT_ITEM) = TRY_TO_NUMBER(TOTAL_BILLING.SALES_DOCUMENT_ITEM)
    	LEFT JOIN SALES_DOC_PARTNER_DATA
        	ON TRY_TO_NUMBER(VBAP_HISTORY.SALES_DOCUMENT) = TRY_TO_NUMBER(SALES_DOC_PARTNER_DATA.SALES_DOCUMENT)
            AND 0 = TRY_TO_NUMBER(SALES_DOC_PARTNER_DATA.SALES_DOCUMENT_ITEM)
        LEFT JOIN CUSTOMER
            ON VBAK.SOLD_TO_PARTY = CUSTOMER.CUSTOMER_NUMBER
        LEFT JOIN MASTER_DATA_SEGMENT
            ON substring(VBAP_HISTORY.PROFIT_CENTER, 4, 2) = MASTER_DATA_SEGMENT.SAP_CODE
    WHERE 1=1
        AND VBAK.SALES_ORGANIZATION = '3200'
        AND VBAK.SALES_DOCUMENT_TYPE IN ('ZP10', 'ZR11', 'ZS11', 'ZRR0', 'ZR10')
        AND VBAP_HISTORY.ORDER_AMOUNT <> 0
        AND BACKLOG_AMOUNT <> 0
        AND (VBAP_HISTORY.REJECTION_REASON = '' OR VBAP_HISTORY.REJECTION_REASON IS NULL) -- SALES ORDER LINE IS NOT REJECTED
),

TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , BU
        , SALES_CATEGORY
        , SOLD_TO_PARTY
        , CUSTOMER_NAME
        , END_USER
        , ORDER_REASON
        , SALES_DOCUMENT_TYPE
        , TO_VARCHAR(TRY_TO_DATE(SALES_DOCUMENT_DATE, 'YYYYMMDD'), 'MM/DD/YYYY') AS SALES_DOCUMENT_DATE
        , SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM
        , MATERIAL_NUMBER
        , ORDER_AMOUNT
        , BILLING_AMOUNT
        , BACKLOG_AMOUNT
        , TO_VARCHAR(TRY_TO_DATE(SCHEDULE_LINE_DATE, 'YYYYMMDD'), 'MM/DD/YYYY') AS SCHEDULE_LINE_DATE
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        , CAST(BU as VARCHAR(16777216)) AS BU
        , CAST(SALES_CATEGORY as VARCHAR(16777216)) AS SALES_CATEGORY
        , CAST(SOLD_TO_PARTY as VARCHAR(16777216)) AS SOLD_TO_PARTY
        , CAST(CUSTOMER_NAME as VARCHAR(16777216)) AS CUSTOMER_NAME
        , CAST(END_USER AS VARCHAR(16777216)) AS END_USER
        , CAST(ORDER_REASON as VARCHAR(16777216)) AS ORDER_REASON
        , CAST(SALES_DOCUMENT_TYPE as VARCHAR(16777216)) AS SALES_DOCUMENT_TYPE
        , CAST(SALES_DOCUMENT_DATE as DATE) as SALES_DOCUMENT_DATE
        , CAST(SALES_DOCUMENT as VARCHAR(16777216)) AS SALES_DOCUMENT
        , CAST(SALES_DOCUMENT_ITEM as VARCHAR(16777216)) AS SALES_DOCUMENT_ITEM
        , CAST(MATERIAL_NUMBER as VARCHAR(16777216)) AS MATERIAL_NUMBER
        , CAST(ORDER_AMOUNT AS NUMBER(38,2)) AS ORDER_AMOUNT
        , CAST(BILLING_AMOUNT AS NUMBER(38,2)) AS BILLING_AMOUNT
        , CAST(BACKLOG_AMOUNT AS NUMBER(38,2)) AS BACKLOG_AMOUNT
        , CAST(SCHEDULE_LINE_DATE as DATE) as SCHEDULE_LINE_DATE
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA


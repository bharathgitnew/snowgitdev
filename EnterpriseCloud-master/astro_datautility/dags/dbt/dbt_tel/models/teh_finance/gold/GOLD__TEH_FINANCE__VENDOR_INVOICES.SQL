{{ config(
      alias = 'VENDOR_INVOICES',
       materialized='tel_incremental',
      incremental_strategy = 'insert_overwrite',
       transient = false
) }} 
WITH RSEG_DATA AS
(
      SELECT
        RSEG_ARIBA_ITEM_NUMBER,
        RSEG_DOCUMENT_NUMBER,
        RSEG_PLANT,
        SUM(QUANTITY) AS QUANTITY,
        SUM(TAX_BASE) AS TAX_BASE,
        SUM(SHIPPING_HANDLING_AMOUNT) AS SHIPPING_HANDLING_AMOUNT
    FROM
        (
            SELECT DISTINCT
                RSEG_ARIBA_ITEM_NUMBER,
                PURCHASE_ORDER_LINE_ITEM,
                RSEG_DOCUMENT_NUMBER,
                RSEG_PLANT,
                QUANTITY,
                TAX_BASE,
                SHIPPING_HANDLING_AMOUNT
            FROM {{ ref('SILVER__TEH_FINANCE__TAX_MASTER') }}
        )
    GROUP BY RSEG_ARIBA_ITEM_NUMBER,RSEG_DOCUMENT_NUMBER,RSEG_PLANT
),
bseg_data as
(
    SELECT
        REFERENCE_DOCUMENT,
        COMPANY_CODE,
        FISCAL_YEAR,
        SUM(TAX_BASE) AS TAX_BASE
    FROM 
    (
        SELECT DISTINCT
            REFERENCE_DOCUMENT,
            COMPANY_CODE,
            FISCAL_YEAR,
            TAX_BASE
        FROM {{ ref('SILVER__TEH_FINANCE__TAX_MASTER') }}
    )
    GROUP BY ALL
),
invoice_sum as
(
    SELECT
        ACCOUNTING_DOCUMENT,
        VENDOR_NUMBER,
        SUM(ABS(AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY)) AS TOTAL_INVOICE_PRICE,
        COMPANY_CODE,
        FISCAL_YEAR,
        FISCAL_PERIOD
  FROM {{ ref('SILVER__TEH_FINANCE__TAX_MASTER') }}
  GROUP BY ALL
),
SOURCE_DATA AS (
    SELECT
        TAX_MASTER.ACCOUNT_TYPE,
        TAX_MASTER.POSTING_KEY,
        TAX_MASTER.DOCUMENT_TYPE,
        TAX_MASTER.ACCOUNT_DESCRIPTION,
        TAX_MASTER.ACCOUNT_NUMBER,
        TAX_MASTER.ACCOUNT_NAME,
        TAX_MASTER.ACDOCA_VENDOR_NUMBER,
        TAX_MASTER.CUSTOMER_NUMBER,
        TAX_MASTER.VENDOR_NAME,
        TAX_MASTER.COUNTRY,
        TAX_MASTER.CITY,
        TAX_MASTER.SHIP_TO_CITY,
        TAX_MASTER.SHIP_TO_REGION,
        TAX_MASTER.ACCOUNTING_DOCUMENT,
        TAX_MASTER.ACCOUNTING_DOCUMENT_TYPE,
        TAX_MASTER.DOC_TYPE_DESCRIPTION,
        TAX_MASTER.REFERENCE_DOCUMENT,
        TAX_MASTER.REFERENCE_DOCUMENT_LINE_ITEM,
        TAX_MASTER.PURCHASE_ORDER,
        TAX_MASTER.PURCHASE_ORDER_LINE_ITEM,
        TAX_MASTER.PURCHASE_ORDER_DOC_TYPE,
        TAX_MASTER.CONDITION_TYPE,
        TAX_MASTER.CONDITION_DESC,
        TAX_MASTER.PURCHASE_ORDER_NOTE,
        RSEG_DATA.QUANTITY AS QUANTITY,
        TAX_MASTER.TAX_CONDITION,
        COALESCE(RSEG_DATA.TAX_BASE,BSEG_DATA.TAX_BASE) AS TAX_BASE,
        RSEG_DATA.SHIPPING_HANDLING_AMOUNT,
        TAX_MASTER.TAX_ON_INVOICE,
        invoice_sum.TOTAL_INVOICE_PRICE,
        TAX_MASTER.COMPANY_CODE,
        TAX_MASTER.COMPANY_NAME,
        TAX_MASTER.FISCAL_YEAR,
        TAX_MASTER.FISCAL_PERIOD,
        TAX_MASTER.POSTING_DATE,
        TAX_MASTER.DOCUMENT_DATE,
        TAX_MASTER.RSEG_DOCUMENT_NUMBER,
        TAX_MASTER.COST_CENTER_CODE,
        TAX_MASTER.COST_CENTER_NAME,
        TAX_MASTER.PROFIT_CENTER_CODE,
        TAX_MASTER.PROFIT_CENTER_NAME
    FROM {{ ref('SILVER__TEH_FINANCE__TAX_MASTER') }} TAX_MASTER
        INNER JOIN invoice_sum 
            ON invoice_sum.ACCOUNTING_DOCUMENT=TAX_MASTER.ACCOUNTING_DOCUMENT
            AND invoice_sum.COMPANY_CODE=tax_master.COMPANY_CODE
            AND invoice_sum.FISCAL_YEAR=tax_master.FISCAL_YEAR
            AND invoice_sum.FISCAL_PERIOD=TAX_MASTER.FISCAL_PERIOD
            AND invoice_sum.VENDOR_NUMBER=TAX_MASTER.VENDOR_NUMBER
        LEFT JOIN RSEG_DATA
            ON RSEG_DATA.RSEG_ARIBA_ITEM_NUMBER=TAX_MASTER.REFERENCE_DOCUMENT
        LEFT JOIN BSEG_DATA
            ON BSEG_DATA.REFERENCE_DOCUMENT=TAX_MASTER.REFERENCE_DOCUMENT    
            AND BSEG_DATA.COMPANY_CODE=TAX_MASTER.COMPANY_CODE
            AND BSEG_DATA.FISCAL_YEAR=TAX_MASTER.FISCAL_YEAR 
    GROUP BY ALL
),
TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        ACCOUNT_TYPE,
        POSTING_KEY,
        DOCUMENT_TYPE,
        ACCOUNT_DESCRIPTION,
        ACCOUNT_NUMBER,
        ACCOUNT_NAME,
        ACDOCA_VENDOR_NUMBER AS VENDOR_NUMBER,
        CUSTOMER_NUMBER,
        VENDOR_NAME,
        COUNTRY,
        CITY,
        SHIP_TO_CITY,
        SHIP_TO_REGION,
        ACCOUNTING_DOCUMENT,
        ACCOUNTING_DOCUMENT_TYPE,
        DOC_TYPE_DESCRIPTION,
        REFERENCE_DOCUMENT,
        REFERENCE_DOCUMENT_LINE_ITEM,
        PURCHASE_ORDER,
        PURCHASE_ORDER_LINE_ITEM,
        PURCHASE_ORDER_DOC_TYPE,
        CONDITION_TYPE,
        CONDITION_DESC,
        PURCHASE_ORDER_NOTE,
        QUANTITY,
        TAX_CONDITION,
        TAX_BASE,
        SHIPPING_HANDLING_AMOUNT,
        TAX_ON_INVOICE,
        TOTAL_INVOICE_PRICE,
        COMPANY_CODE,
        COMPANY_NAME,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        POSTING_DATE,
        DOCUMENT_DATE,
        COST_CENTER_CODE,
        COST_CENTER_NAME,
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME
    FROM SOURCE_DATA
    GROUP BY ALL
),
TYPE_DATA AS (
    SELECT 
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ACCOUNT_TYPE,
        POSTING_KEY,
        DOCUMENT_TYPE,
        ACCOUNT_DESCRIPTION,
        ACCOUNT_NUMBER,
        ACCOUNT_NAME,
        VENDOR_NUMBER,
        CUSTOMER_NUMBER,
        VENDOR_NAME,
        COUNTRY,
        CITY,
        SHIP_TO_CITY,
        SHIP_TO_REGION,
        ACCOUNTING_DOCUMENT,
        ACCOUNTING_DOCUMENT_TYPE,
        DOC_TYPE_DESCRIPTION,
        REFERENCE_DOCUMENT,
        REFERENCE_DOCUMENT_LINE_ITEM,
        PURCHASE_ORDER,
        PURCHASE_ORDER_LINE_ITEM,
        PURCHASE_ORDER_DOC_TYPE,
        CONDITION_TYPE,
        CONDITION_DESC,
        PURCHASE_ORDER_NOTE,
        CAST(QUANTITY AS VARCHAR(16777216)) AS QUANTITY,
        TAX_CONDITION,
        CAST(TAX_BASE AS VARCHAR(16777216)) AS TAX_BASE,
        CAST(SHIPPING_HANDLING_AMOUNT AS VARCHAR(16777216)) SHIPPING_HANDLING_AMOUNT,
        TAX_ON_INVOICE,
        CAST(TOTAL_INVOICE_PRICE AS VARCHAR(16777216)) AS TOTAL_INVOICE_PRICE,
        COMPANY_CODE,
        COMPANY_NAME,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        POSTING_DATE,
        DOCUMENT_DATE,
        COST_CENTER_CODE,
        COST_CENTER_NAME,
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA


    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    END_USER AS CUSTOMER,
    END_USER_NAME AS CUSTOMER_NAME,
    END_USER_GROUP AS CUSTOMER_GROUP,
    END_USER_CITY AS CUSTOMER_CITY,
    END_USER_REGION AS CUSTOMER_STATE,
    END_USER_COUNTRY AS CUSTOMER_COUNTRY,
    SOLD_TO_PARTY,
    SOLD_TO_PARTY_NAME,
    SOLD_TO_PARTY_COUNTRY,
    ORACLE_PRODUCT_TYPE_GROUP,
    document_type,
    COMPANY_ID_OF_TRADING_PARTNER,
    TRADING_PARTNER_NAME,
    TRADING_PARTNER_COUNTRY,
    SHIP_TO_PARTY,
    SHIP_TO_PARTY_NAME,
    SHIP_TO_PARTY_COUNTRY,
    XREF1,
    XREF1_NAME,
    XREF1_COUNTRY,
    PAYER,
    PAYER_NAME,
    -- COMPANY_NAME_ACC,
    -- COMPANY_ID_OF_TRADING_PARTNER,
    -- NAME1 AS COMPANY_NAME,
    PAYER_COUNTRY,
    INTERCOMPANY_FLAG,
    AMOUNT,
    '{{ invocation_id }}' AS AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH
FROM SOURCE_DATA
)
,TYPE_DATA AS (
SELECT
    CAST(AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
    CAST(_ROW_HASH as varchar(128)) as _ROW_HASH,
    COMPANY_CODE,
    ACCOUNTING_DOCUMENT_LINE,
    ACCOUNT_TYPE,
    ACCOUNT_DESCRIPTION,
    ACCOUNT_NUMBER,
    ACCOUNT_NAME,
    WBS_CATEGORY,
    PROFIT_CENTER,
    COST_CENTER,
    FISCAL_YEAR,
    FINANCIAL_PERIOD,
    CALENDAR_YEAR_MONTH,
    POSTING_DATE,
    DOCUMENT_DATE,
    SALES_ORDER_LINE,
    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    CUSTOMER,
    CUSTOMER_NAME,
    CUSTOMER_GROUP,
    CUSTOMER_CITY,
    CUSTOMER_STATE,
    CUSTOMER_COUNTRY,
    SOLD_TO_PARTY,
    SOLD_TO_PARTY_NAME,
    SOLD_TO_PARTY_COUNTRY,
    ORACLE_PRODUCT_TYPE_GROUP,
    document_type,
    COMPANY_ID_OF_TRADING_PARTNER,
    TRADING_PARTNER_NAME,
    TRADING_PARTNER_COUNTRY,
    SHIP_TO_PARTY,
    SHIP_TO_PARTY_NAME,
    SHIP_TO_PARTY_COUNTRY,
    XREF1,
    XREF1_NAME,
    XREF1_COUNTRY,
    PAYER,
    PAYER_NAME,
    PAYER_COUNTRY,
    -- COMPANY_NAME_ACC AS VARCHAR(16777216)) AS COMPANY_NAME_ACC,
    -- COMPANY_ID_OF_TRADING_PARTNER AS VARCHAR(16777216)) AS COMPANY_ID_OF_TRADING_PARTNER,
    -- COMPANY_NAME AS VARCHAR(16777216)) AS COMPANY_NAME,
    INTERCOMPANY_FLAG,
    CAST(AMOUNT AS NUMBER(38,2)) AS AMOUNT

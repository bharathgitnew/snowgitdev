{{ config(
        materialized='tel_incremental'    ,
     incremental_strategy='insert_overwrite'    ,
     alias='INTERCOMPANY_REVENUE_COGS'    ,
     transient=false
) }}
with INT as(
    SELECT
        INTER.COMPANY_CODE,
        INTER.FISCAL_YEAR,
        INTER.DOCUMENT_TYPE,
        INTER.ACCOUNTING_DOCUMENT_LINE,
        INTER.INTERCOMPANY_FLAG,
        INTER.PAYER,
    FROM {{ ref('SILVER__TEH_FINANCE__UNIVERSAL_INTERCOMPANY_PARTS') }} INTER
),

SHIP_TO as (
    SELECT
        VBPA.VBELN,
        VBPA.KUNNR
    from {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU047_VBPA') }} VBPA
    WHERE VBPA.POSNR = '000000'
    AND PARVW = 'SH'
),
SOURCE_DATA AS (
SELECT
    DASL.COMPANY_CODE,
    DASL.ACCOUNTING_DOCUMENT_LINE,
    DASL.ACCOUNT_TYPE,
    DASL.ACCOUNT_DESCRIPTION,
    DASL.ACCOUNT_NUMBER,
    DASL.ACCOUNT_NAME,
    DASL.WBS_CATEGORY,
    DASL.PROFIT_CENTER,
    DASL.COST_CENTER,
    DASL.FISCAL_YEAR,
    DASL.FINANCIAL_PERIOD,
    DASL.CALENDAR_YEAR_MONTH,
    DASL.POSTING_DATE,
    DASL.DOCUMENT_DATE,
    DASL.SALES_ORDER_LINE,
    DASL.SALES_CATEGORY,
    DASL.SALES_CATEGORY_NAME,
    DASL.END_USER,
    DASL.END_USER_NAME,
    DASL.END_USER_GROUP,
    DASL.END_USER_CITY,
    DASL.END_USER_REGION,
    DASL.END_USER_COUNTRY,
    DASL.SOLD_TO_PARTY,
    DASL.SOLD_TO_PARTY_NAME,
    KNAST.LAND1 AS SOLD_TO_PARTY_COUNTRY,
    SHIP_TO.KUNNR AS SHIP_TO_PARTY,
    KNASH.NAME1 AS SHIP_TO_PARTY_NAME,
    KNASH.LAND1 AS SHIP_TO_PARTY_COUNTRY,
    DASL.document_type,
    DASL.ORACLE_PRODUCT_TYPE_GROUP,
    DASL.COMPANY_ID_OF_TRADING_PARTNER,
    T880.NAME1 AS TRADING_PARTNER_NAME,
    T880.CNTRY AS TRADING_PARTNER_COUNTRY,
    DASL.XREF1,
    KNAX.NAME1 AS XREF1_NAME,
    KNAX.LAND1 AS XREF1_COUNTRY,
    VBRK.KUNRG AS PAYER,
    KNAP.NAME1 AS PAYER_NAME,
    -- INT.NAME1 AS COMPANY_NAME_ACC,
    -- DASL.COMPANY_ID_OF_TRADING_PARTNER,
    KNAP.LAND1 AS PAYER_COUNTRY,
    CASE
    WHEN ACCOUNT_NUMBER='5110100000' THEN INT.INTERCOMPANY_FLAG
    WHEN ACCOUNT_NUMBER='4110100001' OR ACCOUNT_NUMBER='4110100000' THEN DASL.INTERCOMPANY_FLAG
    WHEN ACCOUNT_NUMBER='5110100004' THEN INTL.INTERCOMPANY_FLAG
    ELSE 'No value'
    END AS INTERCOMPANY_FLAG,
    DASL.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT
FROM {{ ref('SILVER__TEH_FINANCE__DAILY_ACTUALS_SALES_LINE') }} DASL
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU014_VBRK') }}  VBRK
    ON DASL.REFERENCE_DOCUMENT_NUMBER = VBRK.VBELN
    LEFT JOIN {{ ref('SILVER__TEH_FINANCE__INTERCOMPANY_LABOR_COGS') }} INTL
    ON DASL.ACCOUNTING_DOCUMENT_LINE = INTL.ACCOUNTING_DOCUMENT_LINE
    AND DASL.COMPANY_CODE = INTL.COMPANY_CODE
    AND DASL.FISCAL_YEAR = INTL.FISCAL_YEAR
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__SAPH_SAP_FIM_EV_T880') }} T880
    ON DASL.COMPANY_ID_OF_TRADING_PARTNER = T880.RCOMP
    LEFT JOIN INT
    ON DASL.ACCOUNTING_DOCUMENT_LINE = INT.ACCOUNTING_DOCUMENT_LINE
    AND DASL.COMPANY_CODE = INT.COMPANY_CODE
    AND DASL.FISCAL_YEAR = INT.FISCAL_YEAR
    AND DASL.DOCUMENT_TYPE = INT.DOCUMENT_TYPE
    LEFT JOIN SHIP_TO
    ON DASL.SALES_DOCUMENT = SHIP_TO.VBELN
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU020_KNA1') }} KNAX
    ON DASL.XREF1 = KNAX.KUNNR
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU020_KNA1') }} KNAP
    ON VBRK.KUNRG = KNAP.KUNNR
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU020_KNA1') }} KNAST
    ON DASL.SOLD_TO_PARTY = KNAST.KUNNR
    LEFT JOIN {{ ref('BRONZE__TEH_FINANCE__SAPAPI_ZCDV_T_CMTU020_KNA1') }} KNASH
    ON SHIP_TO.KUNNR = KNASH.KUNNR

)
,TRANSFORM_DATA AS (

with source_data AS (
    SELECT DISTINCT ID,
	APPENDED_DATE,
	LAG(SET_START_DATE) OVER (
		PARTITION BY [ID] ORDER BY APPENDED_DATE
		) AS PREVIOUS_SSD,
	SET_START_DATE,
	COALESCE(DATEDIFF(DAY, PREVIOUS_SSD, SET_START_DATE), 0) AS DAY_DIFF_PREVIOUS_SSD,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_SSD <> 0
			THEN 1
		ELSE NULL
		END AS IS_SSD_CHURN,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_SSD < 0
			THEN 'PULL'
		WHEN DAY_DIFF_PREVIOUS_SSD > 0
			THEN 'PUSH'
		ELSE NULL
		END AS SSD_CHURN_TYPE,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_SSD <> 0
			THEN ABS(DAY_DIFF_PREVIOUS_SSD)
		ELSE NULL
		END AS SSD_PUSH_PULL_DAYS,
	
	-- TEL Start Date
	LAG(TEL_START_DATE) OVER (
		PARTITION BY [ID] ORDER BY APPENDED_DATE
		) AS PREVIOUS_TSD,
	TEL_START_DATE,
	COALESCE(DATEDIFF(DAY, PREVIOUS_TSD, TEL_START_DATE), 0) AS DAY_DIFF_PREVIOUS_TSD,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_TSD <> 0
			THEN 1
		ELSE NULL
		END AS IS_TSD_CHURN,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_TSD < 0
			THEN 'PULL'
		WHEN DAY_DIFF_PREVIOUS_TSD > 0
			THEN 'PUSH'
		ELSE NULL
		END AS TSD_CHURN_TYPE,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_TSD <> 0
			THEN ABS(DAY_DIFF_PREVIOUS_TSD)
		ELSE NULL
		END AS TSD_PUSH_PULL_DAYS,
	-- TEL Finish Date
	LAG(TEL_FINISH_DATE) OVER (
		PARTITION BY [ID] ORDER BY APPENDED_DATE
		) AS PREVIOUS_TFD,
	TEL_FINISH_DATE,
	COALESCE(DATEDIFF(DAY, PREVIOUS_TFD, TEL_FINISH_DATE), 0) AS DAY_DIFF_PREVIOUS_TFD,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_TFD <> 0
			THEN 1
		ELSE NULL
		END AS IS_TFD_CHURN,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_TFD < 0
			THEN 'PULL'
		WHEN DAY_DIFF_PREVIOUS_TFD > 0
			THEN 'PUSH'
		ELSE NULL
		END AS TFD_CHURN_TYPE,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_TFD <> 0
			THEN ABS(DAY_DIFF_PREVIOUS_TFD)
		ELSE NULL
		END AS TFD_PUSH_PULL_DAYS,
	-- SL1 Sign Off Start Date
	LAG(SL1_SIGNOFF_START_DATE) OVER (
		PARTITION BY [ID] ORDER BY APPENDED_DATE
		) AS PREVIOUS_SL1_SO_SD,
	SL1_SIGNOFF_START_DATE,
	COALESCE(DATEDIFF(DAY, PREVIOUS_SL1_SO_SD, SL1_SIGNOFF_START_DATE), 0) AS DAY_DIFF_PREVIOUS_SL1_SO_SD,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_SL1_SO_SD <> 0
			THEN 1
		ELSE NULL
		END AS IS_SL1_SOSD_CHURN,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_SL1_SO_SD < 0
			THEN 'PULL'
		WHEN DAY_DIFF_PREVIOUS_SL1_SO_SD > 0
			THEN 'PUSH'
		ELSE NULL
		END AS SL1_SOSD_CHURN_TYPE,
	CASE 
		WHEN DAY_DIFF_PREVIOUS_SL1_SO_SD <> 0
			THEN ABS(DAY_DIFF_PREVIOUS_SL1_SO_SD)
		ELSE NULL
		END AS SL1_SOSD_PUSH_PULL_DAYS,
	-- SL1 Sign Off Finish Date
	LAG(SL1_SIGNOFF_FINISH_DATE) OVER (
		PARTITION BY [ID] ORDER BY APPENDED_DATE
		) AS PREVIOUS_SL1_SO_FD,
	SL1_SIGNOFF_FINISH_DATE,
	COALESCE(DATEDIFF(DAY, PREVIOUS_SL1_SO_FD, SL1_SIGNOFF_FINISH_DATE), 0) as DAY_DIFF_SL1_SIGNOFF_FINISH_DATE,
	CASE 
		WHEN DAY_DIFF_SL1_SIGNOFF_FINISH_DATE <> 0
			THEN 1
		ELSE NULL
		END AS IS_SL1_SOFD_CHURN,
	CASE 
		WHEN DAY_DIFF_SL1_SIGNOFF_FINISH_DATE < 0
			THEN 'PULL'
		WHEN DAY_DIFF_SL1_SIGNOFF_FINISH_DATE > 0
			THEN 'PUSH'
		ELSE NULL
		END AS SL1_SOFD_CHURN_TYPE,
	CASE 
		WHEN DAY_DIFF_SL1_SIGNOFF_FINISH_DATE <> 0
			THEN ABS(DAY_DIFF_SL1_SIGNOFF_FINISH_DATE)
		eLSE NULL
		END AS SL1_SOFD_PUSH_PULL_DAYS,
	-- SL2 Sign Off Start Date
	LAG(SL2_SIGNOFF_START_DATE) OVER (
		PARTITION BY [ID] ORDER BY APPENDED_DATE
		) AS PREVIOUS_SL2_SO_SD,
	SL2_SIGNOFF_START_DATE,
	COALESCE(DATEDIFF(DAY, PREVIOUS_SL2_SO_SD, SL2_SIGNOFF_START_DATE), 0) as DAY_DIFF_SL2_SIGNOFF_START_DATE,
	CASE 
		WHEN DAY_DIFF_SL2_SIGNOFF_START_DATE <> 0
			THEN 1
		ELSE NULL
		END AS IS_SL2_SOSD_CHURN,
	CASE 
		WHEN DAY_DIFF_SL2_SIGNOFF_START_DATE < 0
			THEN 'PULL'
		WHEN DAY_DIFF_SL2_SIGNOFF_START_DATE > 0
			THEN 'PUSH'
		ELSE NULL
		END AS SL2_SOSD_CHURN_TYPE,
	CASE 
		WHEN DAY_DIFF_SL2_SIGNOFF_START_DATE <> 0
			THEN ABS(DAY_DIFF_SL2_SIGNOFF_START_DATE)
		ELSE NULL
		END AS SL2_SOSD_PUSH_PULL_DAYS,
	-- SL2 Sign Off Finish Date
	LAG(SL2_SIGNOFF_FINISH_DATE) OVER (
		PARTITION BY [ID] ORDER BY APPENDED_DATE
		) AS PREVIOUS_SL2_SO_FD,
	SL2_SIGNOFF_FINISH_DATE,
	COALESCE(DATEDIFF(DAY, PREVIOUS_SL2_SO_FD, SL2_SIGNOFF_FINISH_DATE), 0) as DAY_DIFF_SL2_SIGNOFF_FINISH_DATE,
	CASE 
		WHEN DAY_DIFF_SL2_SIGNOFF_FINISH_DATE <> 0
			THEN 1
		ELSE NULL
		END AS IS_SL2_SOFD_CHURN,
	CASE 
		WHEN DAY_DIFF_SL2_SIGNOFF_FINISH_DATE < 0
			THEN 'PULL'
		WHEN DAY_DIFF_SL2_SIGNOFF_FINISH_DATE > 0
			THEN 'PUSH'
		ELSE NULL
		END AS SL2_SOFD_CHURN_TYPE,
	CASE 
		WHEN DAY_DIFF_SL2_SIGNOFF_FINISH_DATE <> 0
			THEN ABS(DAY_DIFF_SL2_SIGNOFF_FINISH_DATE)
		ELSE NULL
		END AS SL2_SOFD_PUSH_PULL_DAYS  
       FROM {{ ref('SILVER__TEH_PRODUCT_SUPPORT__SIRFIS_TOOL_INSTALLATION_SCHEDULE_HISTORY') }}
),


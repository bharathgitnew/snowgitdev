{{ config(
      materialized='tel_incremental'
      , incremental_strategy='merge'
      , alias='SIRFIS_TIS_CURRENT_MILESTONES'
      , unique_key=['ID', 'MILESTONES_NAME']
      , transient=false
) }}

WITH 
SOURCE_DATA AS (
SELECT DISTINCT 
INSTALL_SCHEDULE_ID
/*2025-01-13 is the API ingestion date, Original _FILEDATE can be inconsistent with snapshot date due to manual ingestion, a
and hence the case when. - Leah QI*/
, CASE WHEN SNAPSHOT_DATE < '2025-01-13' THEN SNAPSHOT_DATE
     ELSE _FILEDATE END AS _FILEDATE
, CASE WHEN UPPER(MILESTONES_NAME) = 'CONVERT' THEN 'CONVERSION'
       WHEN UPPER(MILESTONES_NAME) = 'MRCL' THEN 'MIRACLE'
       ELSE UPPER(MILESTONES_NAME)  END AS MILESTONES_NAME
, MILESTONES_START 
, MILESTONES_FINISH
, MILESTONES_DURATION_DAYS
FROM {{ ref('SILVER__TEH_PRODUCT_SUPPORT__SIRFIS_TOOL_INSTALLATION_BASE') }}
WHERE UPPER(STATE) <> 'PAST' 
)

, TRANSFORM_DATA AS (
SELECT DISTINCT
'{{ invocation_id }}' AS _AUDIT_LOG_ID
, SHA2('hash_me') AS _ROW_HASH
, INSTALL_SCHEDULE_ID AS ID
, MILESTONES_NAME
, TO_DATE(FIRST_VALUE(MILESTONES_START) OVER (PARTITION by INSTALL_SCHEDULE_ID, MILESTONES_NAME order by _FILEDATE DESC)) AS MILESTONE_START_DATE
, TO_DATE(FIRST_VALUE(MILESTONES_FINISH) OVER (PARTITION by INSTALL_SCHEDULE_ID, MILESTONES_NAME order by _FILEDATE DESC)) AS MILESTONE_FINISH_DATE
, FIRST_VALUE(MILESTONES_DURATION_DAYS) OVER (PARTITION by INSTALL_SCHEDULE_ID, MILESTONES_NAME order by _FILEDATE DESC) AS MILESTONES_DURATION_DAYS
FROM SOURCE_DATA
)

, TYPE_DATA AS
(     SELECT DISTINCT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
      , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH 
      , ID
      , MILESTONES_NAME
	, CAST(MILESTONE_START_DATE AS DATE) AS MILESTONE_START_DATE
	, CAST(MILESTONE_FINISH_DATE AS DATE) AS MILESTONE_FINISH_DATE
      , CAST(MILESTONES_DURATION_DAYS AS NUMBER(9,0)) AS MILESTONES_DURATION_DAYS
      FROM TRANSFORM_DATA

)
SELECT * FROM TYPE_DATA
WHERE MILESTONES_NAME IS NOT NULL
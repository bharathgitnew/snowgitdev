      , incremental_strategy='merge'
      , alias='SIRFIS_TIS_MILESTONES_HISTORY'
      , unique_key=['ID', '_FILEDATE', 'MILESTONES_NAME']
      , transient=false
) }}
/* Due to ODS history collecting data every even hour
   we need to collecting an DAILY accumulative transactional table based on ID & FILE_DATE & MILESTONE_NAME as grain
 */
--API & FILE merged, API 2025-01-13 onward

WITH SOURCE_DATA AS (
SELECT DISTINCT 
    INSTALL_SCHEDULE_ID  
    , CASE WHEN SNAPSHOT_DATE < '2025-01-13' THEN SNAPSHOT_DATE
     ELSE _FILEDATE END AS _FILEDATE
    , CASE 
        WHEN UPPER(MILESTONES_NAME) = 'CONVERT' THEN 'CONVERSION'
        WHEN UPPER(MILESTONES_NAME) = 'MRCL' THEN 'MIRACLE'
        ELSE UPPER(MILESTONES_NAME)  
    END AS MILESTONES_NAME
    , TO_DATE(FIRST_VALUE(MILESTONES_START) OVER (
        PARTITION BY INSTALL_SCHEDULE_ID, MILESTONES_NAME, TO_DATE(_FILEDATE) 
        ORDER BY _FILEDATE DESC
    )) AS MILESTONES_START
    , TO_DATE(FIRST_VALUE(MILESTONES_FINISH) OVER (
        PARTITION BY INSTALL_SCHEDULE_ID, MILESTONES_NAME, TO_DATE(_FILEDATE) 
        ORDER BY _FILEDATE DESC
    )) AS MILESTONES_FINISH
FROM {{ ref('SILVER__TEH_PRODUCT_SUPPORT__SIRFIS_TOOL_INSTALLATION_BASE') }}
WHERE UPPER(STATE) <> 'PAST' 
)

, transform_data as (
    SELECT DISTINCT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') AS _ROW_HASH   
        , INSTALL_SCHEDULE_ID AS ID
        , _FILEDATE
        , MILESTONES_NAME
        , MILESTONES_START AS MILESTONES_START_DATE
        , MILESTONES_FINISH AS MILESTONES_FINISH_DATE
    from source_data
)

, TYPE_DATA AS
(     SELECT DISTINCT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
      , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH 
      , ID
      , CAST(_FILEDATE AS DATE) AS _FILEDATE
      , MILESTONES_NAME
	  , CAST(MILESTONES_START_DATE AS DATE) AS MILESTONE_START_DATE
	  , CAST(MILESTONES_FINISH_DATE AS DATE) AS MILESTONE_FINISH_DATE
      FROM TRANSFORM_DATA

)
SELECT * FROM TYPE_DATA
WHERE MILESTONES_NAME IS NOT NULL
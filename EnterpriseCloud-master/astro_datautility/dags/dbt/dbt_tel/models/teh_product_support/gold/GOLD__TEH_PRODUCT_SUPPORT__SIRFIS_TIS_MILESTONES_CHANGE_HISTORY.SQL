/* Due to ODS history collecting data every even hour
   we need to collecting an DAILY accumulative transactional table based on ID & FILE_DATE & MILESTONE_NAME as grain
 */
WITH SOURCE AS (
  SELECT DISTINCT 
  INSTALL_SCHEDULE_ID
  , CASE WHEN SNAPSHOT_DATE < '2025-01-13' THEN SNAPSHOT_DATE ELSE _FILEDATE END AS _FILEDATE
  , MILESTONES_NAME
  , MILESTONES_START
  , MILESTONES_FINISH
  FROM {{ ref('SILVER__TEH_PRODUCT_SUPPORT__SIRFIS_TOOL_INSTALLATION_BASE') }}
  WHERE UPPER(STATE) <> 'PAST' 
  
)

, SOURCE_DATA AS (
SELECT DISTINCT 
    INSTALL_SCHEDULE_ID,  
    TO_DATE(_FILEDATE) AS _FILEDATE,
    CASE 
        WHEN UPPER(MILESTONES_NAME) = 'CONVERT' THEN 'CONVERSION'
        WHEN UPPER(MILESTONES_NAME) = 'MRCL' THEN 'MIRACLE'
        ELSE UPPER(MILESTONES_NAME)  
    END AS MILESTONES_NAME,
    TO_DATE(FIRST_VALUE(MILESTONES_START) OVER (
        PARTITION BY INSTALL_SCHEDULE_ID, MILESTONES_NAME, TO_DATE(_FILEDATE) 
        ORDER BY _FILEDATE DESC
    )) AS MILESTONES_START,
    TO_DATE(FIRST_VALUE(MILESTONES_FINISH) OVER (
        PARTITION BY INSTALL_SCHEDULE_ID, MILESTONES_NAME, TO_DATE(_FILEDATE) 
        ORDER BY _FILEDATE DESC
    )) AS MILESTONES_FINISH
FROM SOURCE
)

--Calculate the changes from previous and latter  
, TRANSFORM_DATA AS (
SELECT DISTINCT 
'{{ invocation_id }}' AS _AUDIT_LOG_ID
, SHA2('hash_me') AS _ROW_HASH
, INSTALL_SCHEDULE_ID AS ID
, _FILEDATE AS EVENT_DATE
, MILESTONES_NAME
, TO_DATE(LAG(MILESTONES_START) OVER (PARTITION BY ID, MILESTONES_NAME ORDER BY EVENT_DATE)) AS PREVIOUS_MILESTONES_START_DATE
, TO_DATE(MILESTONES_START) AS MILESTONES_START_DATE
, COALESCE(DATEDIFF(DAY, PREVIOUS_MILESTONES_START_DATE, MILESTONES_START), 0) AS DAY_DIFF_MILESTONES_START
, CASE WHEN DAY_DIFF_MILESTONES_START <> 0 THEN 1
  ELSE NULL 
  END AS IS_MILESTONES_START_DATE_CHURN
, TO_DATE(LAG(MILESTONES_FINISH) OVER (PARTITION BY ID, MILESTONES_NAME ORDER BY EVENT_DATE)) AS PREVIOUS_MILESTONES_FINISH_DATE
, TO_DATE(MILESTONES_FINISH) AS MILESTONES_FINISH_DATE
, COALESCE(DATEDIFF(DAY, PREVIOUS_MILESTONES_FINISH_DATE, MILESTONES_FINISH), 0) AS DAY_DIFF_MILESTONES_FINISH
, CASE WHEN DAY_DIFF_MILESTONES_FINISH <> 0 THEN 1
  ELSE NULL 
  END AS IS_MILESTONES_FINISH_DATE_CHURN
, CASE WHEN DAY_DIFF_MILESTONES_START < 0 THEN 'PULL'
       WHEN DAY_DIFF_MILESTONES_START > 0 THEN 'PUSH'
       ELSE NULL
  END AS MILESTONE_START_CHURN_TYPE
, CASE WHEN DAY_DIFF_MILESTONES_FINISH < 0 THEN 'PULL'
       WHEN DAY_DIFF_MILESTONES_FINISH > 0 THEN 'PUSH'
       ELSE NULL
  END AS MILESTONE_FINISH_CHURN_TYPE
FROM SOURCE_DATA
)

, TYPE_DATA AS 

(SELECT 
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
      , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH 
      , ID
      , CAST(EVENT_DATE AS DATE) AS EVENT_DATE
      , MILESTONES_NAME
      , CAST(PREVIOUS_MILESTONES_START_DATE AS DATE) AS PREVIOUS_MILESTONES_START_DATE
      , CAST(MILESTONES_START_DATE AS DATE) AS MILESTONES_START_DATE
      , CAST(DAY_DIFF_MILESTONES_START AS NUMBER(9,0)) AS DAY_DIFF_MILESTONES_START
      , CAST(IS_MILESTONES_START_DATE_CHURN AS NUMBER(1,0)) AS IS_MILESTONES_START_DATE_CHURN
      , CAST(PREVIOUS_MILESTONES_FINISH_DATE AS DATE) AS PREVIOUS_MILESTONES_FINISH_DATE
      , CAST(MILESTONES_FINISH_DATE AS DATE) AS MILESTONES_FINISH_DATE
      , CAST(DAY_DIFF_MILESTONES_FINISH AS NUMBER(9,0)) AS DAY_DIFF_MILESTONES_FINISH
      , CAST(IS_MILESTONES_FINISH_DATE_CHURN AS NUMBER(1,0)) AS IS_MILESTONES_FINISH_DATE_CHURN
      , MILESTONE_START_CHURN_TYPE
      , MILESTONE_FINISH_CHURN_TYPE
      FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
    TO_DATE(S.DECON_FINISH_DATE) AS DECON_FINISH_DATE, 
    TO_DATE(S.DEMO_START_DATE) AS DEMO_START_DATE, 
    TO_DATE(S.DEMO_FINISH_DATE) AS DEMO_FINISH_DATE, 
    TO_DATE(S.SET_START_DATE) AS SET_START_DATE, 
    TO_DATE(S.SET_FINISH_DATE) AS SET_FINISH_DATE, 
    TO_DATE(S.PREFAC_START_DATE) AS PREFAC_START_DATE, 
    TO_DATE(S.PREFAC_FINISH_DATE) AS PREFAC_FINISH_DATE,

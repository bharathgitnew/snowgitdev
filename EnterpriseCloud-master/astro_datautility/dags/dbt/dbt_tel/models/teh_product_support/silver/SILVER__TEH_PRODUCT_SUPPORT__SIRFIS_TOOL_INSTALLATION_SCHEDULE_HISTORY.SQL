TRANSFORM_DATA AS
(
SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID
	,SHA2('hash_me') AS _ROW_HASH
    ,ID
    ,APPENDED_DATE
    ,BUSINESS_UNIT
    ,BUSINESS_UNIT_SHORT_TEXT
    ,EVENT_TYPE
    ,STATE
    ,MANUFACTURER_NAME
    ,MANUFACTURER_NUMBER
    ,BATCH
    ,BUILDING
    ,SITE
    ,MODEL
    ,ENTITY
    ,ENTITY_LEFT_3
    ,CEID
    ,PROCESS
    ,ORIGINAL_SITE
    ,ORIGINAL_ENTITY_LEFT_3
    ,CK_DESCRIPTION
    ,PUBLISHED_DATE 
    ,DECON_START_DATE
    ,DECON_FINISH_DATE
    ,DEMO_START_DATE
    ,DEMO_FINISH_DATE
    ,SET_START_DATE
    ,SET_FINISH_DATE
    ,PREFAC_START_DATE
    ,PREFAC_FINISH_DATE
    ,SL1_SIGNOFF_START_DATE
    ,SL1_SIGNOFF_FINISH_DATE
    ,SL2_SIGNOFF_START_DATE
    ,SL2_SIGNOFF_FINISH_DATE
    ,CONVERT_START_DATE
    ,CONVERT_FINISH_DATE
    ,CASE WHEN UPPER(EVENT_TYPE) = 'DEMO' THEN DEMO_START_DATE
          WHEN UPPER(EVENT_TYPE) = 'INSTALL' THEN SET_START_DATE
          WHEN UPPER(EVENT_TYPE) = 'INSTALL-CONV' THEN SET_START_DATE 
          WHEN UPPER(EVENT_TYPE) = 'CONV-FAC' THEN CONVERT_START_DATE 
          WHEN UPPER(EVENT_TYPE) = 'CONV' THEN CONVERT_START_DATE
          ELSE NULL END AS TEL_START_DATE
    ,CASE WHEN UPPER(EVENT_TYPE) = 'DEMO' THEN DEMO_FINISH_DATE
          WHEN UPPER(EVENT_TYPE) = 'INSTALL' THEN SUPPLIER_QUAL_FINISH_DATE
          WHEN UPPER(EVENT_TYPE) = 'INSTALL-CONV' THEN SUPPLIER_QUAL_FINISH_DATE 
          WHEN UPPER(EVENT_TYPE) = 'CONV-FAC' THEN SUPPLIER_QUAL_FINISH_DATE
          WHEN UPPER(EVENT_TYPE) = 'CONV' THEN SUPPLIER_QUAL_FINISH_DATE
          ELSE NULL END AS TEL_FINISH_DATE
    , FA 
    , LIFE
    , CRITICAL
    , SET_DOCK_DATE
    , SUPPLIER_QUAL_START_DATE
    , SUPPLIER_QUAL_FINISH_DATE
    , SL1_CONSTRUCTION_START_DATE 
    , SL1_CONSTRUCTION_FINISH_DATE
    , SL2_CONSTRUCTION_START_DATE 
    , SL2_CONSTRUCTION_FINISH_DATE 
    , MIRACLE_FINISH_DATE
FROM source_data

( 
SELECT DISTINCT
    S.ID AS ID, 
    S.APPENDED_DATE AS APPENDED_DATE,
    UPPER(BU_LOOKUP_SOURCE_REF.BUSINESS_UNIT) AS BUSINESS_UNIT,
    BU_LOOKUP_SOURCE_REF.ACRONYM AS BUSINESS_UNIT_SHORT_TEXT, 

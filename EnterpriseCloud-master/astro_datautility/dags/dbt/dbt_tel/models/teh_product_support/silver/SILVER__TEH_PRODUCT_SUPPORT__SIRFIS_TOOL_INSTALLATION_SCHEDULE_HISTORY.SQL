    TO_DATE(S.SL2_SIGNOFF_START) AS SL2_SIGNOFF_START_DATE, 
    TO_DATE(S.SL2_SIGNOFF_FINISH) AS SL2_SIGNOFF_FINISH_DATE,
    TO_DATE(S.CONVERT_START) AS CONVERT_START_DATE, 
    TO_DATE(S.CONVERT_FINISH) AS CONVERT_FINISH_DATE,
    TO_DATE(SUPPLIER_QUAL_START) AS SUPPLIER_QUAL_START_DATE,
    TO_DATE(SUPPLIER_QUAL_FINISH) AS SUPPLIER_QUAL_FINISH_DATE, 
    S.MANUFACTURER_NAME, 
    S.MANUFACTURER_NUMBER,
    S.BATCH, 
    S.FA, 
    S.LIFE,
    UPPER(S.IMPACT) AS CRITICAL, 

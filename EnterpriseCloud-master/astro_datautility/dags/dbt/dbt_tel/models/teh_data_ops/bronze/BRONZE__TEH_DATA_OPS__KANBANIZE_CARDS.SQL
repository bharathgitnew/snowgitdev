
{{ config(
    alias = 'KANBANIZE_CARDS',
    materialized = 'tel_incremental',
    incremental_strategy = 'merge',
    unique_key = ['CARD_ID'],
) }}

with source_data as (
    select
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE,
        JSONFIELD:card_id::STRING as CARD_ID, 
        JSONFIELD:custom_id::STRING as CUSTOM_ID, 
        JSONFIELD:board_id::STRING as BOARD_ID, 
        JSONFIELD:workflow_id::STRING as WORKFLOW_ID, 
        JSONFIELD:title::STRING as TITLE, 
        JSONFIELD:owner_user_id::STRING as OWNER_USER_ID, 
        JSONFIELD:type_id::STRING as TYPE_ID, 
        JSONFIELD:color::STRING as COLOR, 
        JSONFIELD:is_blocked::STRING as IS_BLOCKED, 
        JSONFIELD:section::STRING as SECTION, 
        JSONFIELD:column_id::STRING as COLUMN_ID, 
        JSONFIELD:lane_id::STRING as LANE_ID, 
        JSONFIELD:position::STRING as POSITION, 
        JSONFIELD:description::STRING as DESCRIPTION, 
        JSONFIELD:size::STRING as SIZE, 
        JSONFIELD:priority::STRING as PRIORITY, 
        JSONFIELD:deadline::STRING as DEADLINE, 
        JSONFIELD:reporter::STRING as REPORTER, 
        JSONFIELD:created_at::STRING as CREATED_AT, 
        JSONFIELD:revision::STRING as REVISION, 
        JSONFIELD:last_modified::STRING as LAST_MODIFIED, 
        JSONFIELD:in_current_position_since::STRING as IN_CURRENT_POSITION_SINCE, 
        JSONFIELD:first_start_time::STRING as FIRST_START_TIME, 
        JSONFIELD:first_end_time::STRING as FIRST_END_TIME, 
        JSONFIELD:last_start_time::STRING as LAST_START_TIME, 
        JSONFIELD:last_end_time::STRING as LAST_END_TIME, 
        JSONFIELD:block_reason::STRING as BLOCK_REASON, 
        JSONFIELD:child_card_stats::STRING as CHILD_CARD_STATS, 
        JSONFIELD:custom_fields::STRING as CUSTOM_FIELDS, 
        JSONFIELD:tag_ids::STRING as TAG_IDS, 
        JSONFIELD:finished_subtask_count::STRING as FINISHED_SUBTASK_COUNT, 
        JSONFIELD:unfinished_subtask_count::STRING as UNFINISHED_SUBTASK_COUNT, 
        JSONFIELD:comment_count::STRING as COMMENT_COUNT, 
        JSONFIELD:comments::VARIANT as COMMENTS,
        JSONFIELD:current_cycle_time::STRING as CURRENT_CYCLE_TIME, 
        JSONFIELD:current_block_time::STRING as CURRENT_BLOCK_TIME, 
        JSONFIELD:current_logged_time::STRING as CURRENT_LOGGED_TIME, 
        JSONFIELD:description_html::STRING as DESCRIPTION_HTML, 
        JSONFIELD:state::STRING as STATE, 
    from {{ source('KANBANIZE', 'CARDS') }} 
    {% if is_tel_incremental() %}where _FILEDATE > ifnull((select max(_FILEDATE) from {{this}}), '1970-01-01'){% endif %}
    qualify row_number() over (partition by CARD_ID order by _FILEDATE desc) = 1
),

transform_data as (
    select 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE,
        CARD_ID,
        CUSTOM_ID,
        BOARD_ID,
        WORKFLOW_ID,
        TITLE,
        OWNER_USER_ID,
        TYPE_ID,
        COLOR,
        IS_BLOCKED,
        SECTION,
        COLUMN_ID,
        LANE_ID,
        POSITION,
        DESCRIPTION,
        SIZE,
        PRIORITY,
        DEADLINE,
        REPORTER,
        CREATED_AT,
        REVISION,
        LAST_MODIFIED,
        IN_CURRENT_POSITION_SINCE,
        FIRST_START_TIME,
        FIRST_END_TIME,
        LAST_START_TIME,
        LAST_END_TIME,
        BLOCK_REASON,
        CHILD_CARD_STATS,
        CUSTOM_FIELDS,
        TAG_IDS,
        FINISHED_SUBTASK_COUNT,
        UNFINISHED_SUBTASK_COUNT,
        COMMENT_COUNT,
        COMMENTS,
        CURRENT_CYCLE_TIME,
        CURRENT_BLOCK_TIME,
        CURRENT_LOGGED_TIME,
        DESCRIPTION_HTML,
        STATE,
    from source_data
),

type_data as (

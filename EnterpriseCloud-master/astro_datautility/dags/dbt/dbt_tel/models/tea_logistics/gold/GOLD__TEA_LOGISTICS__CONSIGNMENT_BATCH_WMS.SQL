{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        tags=["insert_overwrite_tea_logistics"],
        alias='CONSIGNMENT_BATCH_WMS',
        transient=false
) }}

WITH
WMS_BATCH_LKUP AS (
    SELECT
        SLBC.MCHB_BATCH_NUMBER,
        SLBC.MCHB_STORAGE_LOCATION AS SLOC,
        CASE 
            WHEN LENGTH(SLBC.MCHB_BATCH_NUMBER) < 10 THEN LPAD(SLBC.MCHB_BATCH_NUMBER, 10, '0') 
            ELSE SLBC.MCHB_BATCH_NUMBER
        END AS SAP_BATCH_NUMBER,
        SLBC.AUSP_CHARACTERISTIC_VALUE AS WMS_BATCH
    FROM {{ ref('SILVER__TEA_LOGISTICS__STORAGE_LOCATION_BATCH_CHARACTERISTICS') }} AS SLBC
    --FROM COMMON.SAPH.STORAGE_LOCATION_BATCH_CHARACTERISTICS AS SLBC
    WHERE AUSP_INTERNAL_CHARACTERISTIC IN ('0000000012') AND SLBC.MCHB_PLANT = '3200'
),
WMS_BATCH_DEDUP AS (
    SELECT 
        SAP_BATCH_NUMBER, 
        SLOC, 
        CASE 
            WHEN COUNT(DISTINCT(WMS_BATCH)) <= 1 THEN MAX(WMS_BATCH)
            -- If more than one WMS batch is found, concatenate using a "|"
            ELSE LISTAGG(DISTINCT(WMS_BATCH), '|')
        END AS WMS_BATCH
    FROM WMS_BATCH_LKUP 
    GROUP BY SAP_BATCH_NUMBER, SLOC
),
SOURCE_DATA AS (
    SELECT 
        MCHB.MATNR AS MATERIAL_NUMBER,
        MCHB.CHARG AS SAP_BATCH,
        WB.WMS_BATCH,
        MCHB.LGORT AS SLOC,
        MCHB.CLABS AS UNRESTRICTED_STOCK, 
        MCHB.CUMLM AS STOCK_IN_TRANSFER,
        MCHB.CINSM AS STOCK_IN_QUALITY_INSPECTION,
        MCHB.CEINM AS STOCK_IN_RESTRICTED_BATCHES,
        MCHB.CSPEM AS BLOCKED_STOCK,
        TRY_TO_DATE(MCHB.ERSDA, 'YYYYMMDD') AS SAP_MCHB_RECORD_CREATION_DATE
    FROM {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU105_MCHB') }} AS MCHB
    --FROM ODS.SAPAPI.ZCDV_T_CMTU105_MCHB AS MCHB
    JOIN WMS_BATCH_DEDUP AS WB ON (WB.SAP_BATCH_NUMBER = MCHB.CHARG AND WB.SLOC = MCHB.LGORT)
),
TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH, -- Adds column to table on full refresh.
        MATERIAL_NUMBER,
        SAP_BATCH,
        WMS_BATCH,
        SLOC,
        UNRESTRICTED_STOCK,
        STOCK_IN_TRANSFER,
        STOCK_IN_QUALITY_INSPECTION,
        STOCK_IN_RESTRICTED_BATCHES,
        BLOCKED_STOCK,
        SAP_MCHB_RECORD_CREATION_DATE
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(16777216)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(SAP_BATCH AS VARCHAR(16777216)) AS SAP_BATCH,
        CAST(WMS_BATCH AS VARCHAR(16777216)) AS WMS_BATCH,
        CAST(SLOC AS VARCHAR(16777216)) AS SLOC,
        CAST(UNRESTRICTED_STOCK AS INT) AS UNRESTRICTED_STOCK,
        CAST(STOCK_IN_TRANSFER AS INT) AS STOCK_IN_TRANSFER,
        CAST(STOCK_IN_QUALITY_INSPECTION AS INT) AS STOCK_IN_QUALITY_INSPECTION,
        CAST(STOCK_IN_RESTRICTED_BATCHES AS INT) AS STOCK_IN_RESTRICTED_BATCHES,
        CAST(BLOCKED_STOCK AS INT) AS BLOCKED_STOCK,
        CAST(SAP_MCHB_RECORD_CREATION_DATE AS DATE) AS SAP_MCHB_RECORD_CREATION_DATE
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
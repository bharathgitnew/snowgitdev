{{ config(
        materialized='tel_incremental'    ,
     incremental_strategy='insert_overwrite',
        tags=["insert_overwrite_tea_logistics"],
     alias='DECONTAMINATION'    ,
     transient=false
) }}

WITH CRM_OPTIONSET_DECON_FORM_TYPE AS (
    SELECT 
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM {{ ref('SILVER__TEA_LOGISTICS__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'tel_com_decontaminationformtypecode'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'GLOBAL'
),
CRM_OPTIONSET_COPPER_CONTAMINATION AS (
    SELECT 
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM {{ ref('SILVER__TEA_LOGISTICS__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'tel_com_ispartcoppercontaminated'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'GLOBAL'
),
CRM_OPTIONSET_REPLACEMENT_ARRANGED AS (
    SELECT 
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM {{ ref('SILVER__TEA_LOGISTICS__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'tel_com_replacementarrangement'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'GLOBAL'
),
CRM_OPTIONSET_INNER_PACKAGE AS (
    SELECT 
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM {{ ref('SILVER__TEA_LOGISTICS__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'tel_com_innerpackageopenedunopened'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'GLOBAL'
),
CRM_DECON AS (
    SELECT
        TEL_COM_DECONTAMINATIONID
        , TEL_NAME
        , TEL_COM_DECONTAMINATIONFORMTYPECODE
        , TEL_COM_PARTNUMBER
        , TEL_COM_DECONTAMINATION
        , TEL_COM_REPLACEMENTARRANGEMENT
        , TEL_COM_INNERPACKAGEOPENEDUNOPENED
        , TEL_COM_PROCESSCHEMICALSEXPOSEDTO
        , TEL_COM_PARTPURGEDCLEANED
        , TEL_COM_PROCESSDETAILSONPARTDRIED
        , TEL_COM_ISPARTCOPPERCONTAMINATED
    FROM {{ ref('BRONZE__TEA_LOGISTICS__CRM_FILE_TEL_COM_DECONTAMINATION') }}
),
SOURCE_DATA AS(
    SELECT
        TEL_COM_DECONTAMINATIONID
        , TEL_NAME AS DECONTAMINATION_NO
        , CRM_OPTIONSET_DECON_FORM_TYPE.LOCALIZEDLABEL AS DECONTAMINATION_FORM_TYPE
        , TEL_COM_PARTNUMBER as PART_NUMBER
        , TEL_COM_DECONTAMINATION 
        , CRM_OPTIONSET_COPPER_CONTAMINATION.LOCALIZEDLABEL AS COPPER_CONTAMINATION
        , CRM_OPTIONSET_REPLACEMENT_ARRANGED.LOCALIZEDLABEL AS REPLACEMENT_ARRANGED
        , CRM_OPTIONSET_INNER_PACKAGE.LOCALIZEDLABEL AS INNER_PACKAGE
        , TEL_COM_PROCESSCHEMICALSEXPOSEDTO AS PROCESS_CHEMICAL_EXPOSED_TO
        , TEL_COM_PARTPURGEDCLEANED AS PART_PURGED_CLEANED
        , TEL_COM_PROCESSDETAILSONPARTDRIED AS PROCESS_DETAILS_ON_PART_DRIED
    FROM CRM_DECON
        LEFT JOIN CRM_OPTIONSET_DECON_FORM_TYPE
            ON CRM_DECON.TEL_COM_DECONTAMINATIONFORMTYPECODE = CRM_OPTIONSET_DECON_FORM_TYPE.OPTION
        LEFT JOIN CRM_OPTIONSET_COPPER_CONTAMINATION
            ON CRM_DECON.TEL_COM_ISPARTCOPPERCONTAMINATED = CRM_OPTIONSET_COPPER_CONTAMINATION.OPTION
        LEFT JOIN CRM_OPTIONSET_REPLACEMENT_ARRANGED
            ON CRM_DECON.TEL_COM_REPLACEMENTARRANGEMENT = CRM_OPTIONSET_REPLACEMENT_ARRANGED.OPTION
        LEFT JOIN CRM_OPTIONSET_INNER_PACKAGE
            ON CRM_DECON.TEL_COM_INNERPACKAGEOPENEDUNOPENED = CRM_OPTIONSET_INNER_PACKAGE.OPTION
),
TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') AS _ROW_HASH
        , TEL_COM_DECONTAMINATIONID
        , DECONTAMINATION_NO
        , DECONTAMINATION_FORM_TYPE
        , PART_NUMBER
        , CASE
            WHEN TEL_COM_DECONTAMINATION = TRUE THEN 'No'
            ELSE 'Yes'
        END AS IS_PART_CONTAMINATED
        , COPPER_CONTAMINATION
        , REPLACEMENT_ARRANGED
        , INNER_PACKAGE
        , PROCESS_CHEMICAL_EXPOSED_TO
        , PART_PURGED_CLEANED
        , PROCESS_DETAILS_ON_PART_DRIED
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
          CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        , CAST(TEL_COM_DECONTAMINATIONID AS VARCHAR(16777216)) as TEL_COM_DECONTAMINATIONID
        , CAST(DECONTAMINATION_NO AS VARCHAR(16777216)) as DECONTAMINATION_NO
        , CAST(DECONTAMINATION_FORM_TYPE AS VARCHAR(16777216)) as DECONTAMINATION_FORM_TYPE
        , CAST(PART_NUMBER AS VARCHAR(16777216)) as PART_NUMBER
        , CAST(IS_PART_CONTAMINATED AS VARCHAR(16777216)) as IS_PART_CONTAMINATED
        , CAST(COPPER_CONTAMINATION AS VARCHAR(16777216)) as COPPER_CONTAMINATION
        , CAST(REPLACEMENT_ARRANGED AS VARCHAR(16777216)) as REPLACEMENT_ARRANGED
        , CAST(INNER_PACKAGE AS VARCHAR(16777216)) as INNER_PACKAGE
        , CAST(PROCESS_CHEMICAL_EXPOSED_TO AS VARCHAR(16777216)) as PROCESS_CHEMICAL_EXPOSED_TO
        , CAST(PART_PURGED_CLEANED AS VARCHAR(16777216)) as PART_PURGED_CLEANED
        , CAST(PROCESS_DETAILS_ON_PART_DRIED AS VARCHAR(16777216)) as PROCESS_DETAILS_ON_PART_DRIED
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
        tags=["insert_overwrite_tea_logistics"],
    alias='MATERIAL_MASTER_INTEL',
    transient=false
) }}

with Sales_price as (
select distinct
    MATERIAL_NUMBER,
    to_number(CONDITION_AMOUNT,10,2) as Sales_price
from {{ ref('GOLD__TEA_LOGISTICS__PRICE_MATRIX') }} 
where CONDITION_TYPE = 'ZP21'
and   CUSTOMER_PRICE_GROUP = '01' 
and ( try_to_date(VALIDITY_END_DATE_OF_THE_CONDITION_RECORD,'YYYYMMDD') >= current_date
and try_to_date(VALIDITY_START_DATE_OF_THE_CONDITION_RECORD,'YYYYMMDD') <= current_date  )
  qualify ROW_NUMBER() OVER (
			PARTITION BY MATERIAL_NUMBER
			 ORDER BY MATERIAL_NUMBER,VALIDITY_START_DATE_OF_THE_CONDITION_RECORD desc) = 1
),

source_data as (
select distinct
    MATERIAL_MASTER.MATERIAL_NUMBER AS MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT,
    AVAILABLE_FOR_SALE_TEXT,
    MATERIAL_GROUP_2_TEXT,
    STANDARD_COST,
    SALES_PRICE.SALES_PRICE,
    Max(PLANNED_DELIVERY_TIME_IN_DAYS) OVER (PARTITION BY MATERIAL_MASTER.MATERIAL_NUMBER) as MAX_LT,
    BASE_UNIT_OF_MEASURE AS BASE_UOM,
    INTEL_FLAG,
    COUNTRY_OF_ORIGIN,
    ABC_GLOBAL,ABC_INTEL,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS,
    ORDER_ITEM_NAME
from {{ ref('GOLD__TEA_LOGISTICS__MASTER_MATERIAL_REPORT') }} as MATERIAL_MASTER
left join Sales_price on Sales_price.MATERIAL_NUMBER = MATERIAL_MASTER.MATERIAL_NUMBER
where INTEL_FLAG = '1' or INTEL_FLAG = '2' or ABC_INTEL <> '' OR SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT = 'sellable'
),

transform_data as (
select
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT,
    AVAILABLE_FOR_SALE_TEXT,
    MATERIAL_GROUP_2_TEXT,
    STANDARD_COST,
    SALES_PRICE,
    MAX_LT,
    BASE_UOM,
    INTEL_FLAG,
    COUNTRY_OF_ORIGIN,
    ABC_GLOBAL,
    ABC_INTEL,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS,
    ORDER_ITEM_NAME
from source_data
),

type_data as (
select
    CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT,
    AVAILABLE_FOR_SALE_TEXT,
    MATERIAL_GROUP_2_TEXT,
    CAST(STANDARD_COST as NUMBER(38,2)) as STANDARD_COST,
    CAST(SALES_PRICE as NUMBER(38,2)) as SALES_PRICE,
    MAX_LT,
    BASE_UOM,
    INTEL_FLAG,
    COUNTRY_OF_ORIGIN,
    ABC_GLOBAL,
    ABC_INTEL,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS,
    ORDER_ITEM_NAME
from transform_data
)

select * from type_data
current_workflow_metrics as (
    with step_1 as (
        select 
            rma_id,
            created_dt,
            submitted_dt,
            issued_dt,
            received_dt,
            inspected_dt,
            investigated_dt,
            completed_dt,
            cancelled_dt,
            deleted_dt
        from stg_1
    ),
    step_2 as (
        select *            
        from step_1 
        unpivot (
            workflow_date for workflow in (
                created_dt,
                submitted_dt,
                issued_dt,
                received_dt,
                inspected_dt,
                investigated_dt,
                completed_dt,
                cancelled_dt,
                deleted_dt
            )
        )
    ),
    step_3 as (
        select distinct
            rma_id 
            , max(workflow_date) max_workflow_date
        from step_2
        group by 1 
    ),
    step_4 as (
        select distinct
            a.rma_id
            , a.workflow as current_workflow
            , a.workflow_date as current_workflow_date
        from step_2 a
        inner join step_3 b 
            on a.rma_id = b.rma_id
            and a.workflow_date = b.max_workflow_date
    )
    select 
    rma_id,
    current_workflow,
    current_workflow_date
    from step_4
),


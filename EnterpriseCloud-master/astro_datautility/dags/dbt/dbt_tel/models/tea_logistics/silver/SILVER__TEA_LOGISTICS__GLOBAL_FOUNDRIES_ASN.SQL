WITH 
VBAK_SRC AS (
  SELECT VBELN, ERDAT, BSTNK
  FROM {{ ref('BRONZE__TEA_LOGISTICS__ZCDV_T_CMTU009_VBAK') }}
),
VBAP_SRC AS (
  SELECT VBELN, POSNR, MATNR, POSEX
  FROM {{ ref('BRONZE__TEA_LOGISTICS__ZCDV_T_CMTU010_VBAP') }}
),
VBFA_SRC AS (
  SELECT VBELV, POSNV, VBELN, POSNN, VBTYP_N
  FROM {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU064_VBFA') }}
),
LIPS_SRC AS (
  SELECT VBELN, POSNR, LGORT, ARKTX, LFIMG, VGBEL, VGPOS, MEINS
  FROM {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU013_LIPS') }}
),
LIKP_SRC AS (
  SELECT VBELN, KUNNR, WADATIST,LFART
  FROM {{ ref('BRONZE__TEA_LOGISTICS__ZCDV_T_CMTU012_LIKP') }}
),
BUT000_SRC AS (
  SELECT PARTNER, BU_SORT1
  FROM {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU053_BUT000') }}
),

SOURCE_DATA AS (
SELECT DISTINCT 
  LIPS.VBELN AS DELIVERY_NUMBER,
  LIKP.LFART AS DELIVERY_TYPE,
  LIPS.POSNR AS DELIVERY_ITEM,
  LIPS.LGORT AS STORAGE_LOCATION,
  LIKP.KUNNR AS SHIP_TO_PARTY,
  BP.BU_SORT1 AS SHIP_TO_NAME,
  VBAP.MATNR AS MATERIAL_NUMBER,
  LIPS.ARKTX AS ITEM_DESCRIPTION,
  LIPS.LFIMG AS DELIVERED_QTY,
  LIPS.VGBEL AS REFERENCE_DOCUMENT,
  LIPS.VGPOS AS REFERENCE_ITEM,
  LIPS.MEINS AS QTY_UNIT,
  VBAK.ERDAT AS ORDER_DATE,
  CONCAT(VBAP.VBELN, LTRIM(VBAP.POSNR, '0')) AS KEY,
  LIKP.WADATIST AS ACTUAL_GOODS_MVMNT_DATE,
  VBAK.BSTNK AS CUSTOMER_PO_NUMBER,
  VBAP.POSEX AS CUSTOMER_PO_LINE
FROM
  LIPS_SRC AS LIPS
  LEFT JOIN LIKP_SRC AS LIKP ON LIKP.VBELN = LIPS.VBELN
  LEFT JOIN VBFA_SRC AS VBFA ON VBFA.VBELN = LIPS.VBELN
  AND VBFA.POSNN = LIPS.POSNR
  AND VBFA.VBTYP_N = 'J'
  LEFT JOIN VBAP_SRC AS VBAP ON VBAP.VBELN = VBFA.VBELV
  AND VBAP.POSNR = VBFA.POSNV
  LEFT JOIN VBAK_SRC AS VBAK ON VBAK.VBELN = VBAP.VBELN
  LEFT JOIN BUT000_SRC AS BP ON BP.PARTNER = LIKP.KUNNR
)

,TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
  DELIVERY_NUMBER,
  DELIVERY_TYPE,
  DELIVERY_ITEM,
	STORAGE_LOCATION,
	SHIP_TO_PARTY,
	SHIP_TO_NAME,
	MATERIAL_NUMBER,
	ITEM_DESCRIPTION,
	DELIVERED_QTY::NUMBER AS DELIVERED_QTY,
	REFERENCE_DOCUMENT,
	REFERENCE_ITEM,
	QTY_UNIT,
	--TO_VARCHAR(TRY_TO_DATE(ORDER_DATE, 'YYYYMMDD'),'MM/DD/YYYY') AS ORDER_DATE,
	TO_VARCHAR(TRY_TO_DATE(NULLIF(ORDER_DATE, '00000000'), 'YYYYMMDD'),'MM/DD/YYYY') AS ORDER_DATE,
  KEY,
	--TO_VARCHAR(TRY_TO_DATE(ACTUAL_GOODS_MVMNT_DATE, 'YYYYMMDD'),'MM/DD/YYYY') AS ACTUAL_GOODS_MVMNT_DATE, 
  TO_VARCHAR(TRY_TO_DATE(NULLIF(ACTUAL_GOODS_MVMNT_DATE, '00000000'), 'YYYYMMDD'),'MM/DD/YYYY') AS ACTUAL_GOODS_MVMNT_DATE, 
	CUSTOMER_PO_NUMBER,
	CUSTOMER_PO_LINE
FROM SOURCE_DATA
)

,type_data as 
(
    select
    CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	DELIVERY_NUMBER,
  DELIVERY_TYPE,
	DELIVERY_ITEM,
	STORAGE_LOCATION,
	SHIP_TO_PARTY,
	SHIP_TO_NAME,
	MATERIAL_NUMBER,
	ITEM_DESCRIPTION,
	DELIVERED_QTY,
	REFERENCE_DOCUMENT,
	REFERENCE_ITEM,
	QTY_UNIT,
  ORDER_DATE,
	KEY,
	ACTUAL_GOODS_MVMNT_DATE,
	CUSTOMER_PO_NUMBER,
	CUSTOMER_PO_LINE
    from transform_data
    )
select * from type_data
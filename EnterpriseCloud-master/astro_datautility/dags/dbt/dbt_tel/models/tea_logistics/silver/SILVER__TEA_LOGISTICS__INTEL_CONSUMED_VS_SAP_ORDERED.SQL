{{ config(
        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        tags=["insert_overwrite_tea_logistics"],
        alias='INTEL_CONSUMED_VS_SAP_ORDERED',
        transient=false
) }}

WITH
INTEL AS (
    SELECT 
        Z.ZTRID AS TRID, 
        Z.ZMATNR AS MATNR, 
        TRY_CAST(MIN(REGEXP_SUBSTR(Z.ZDOCI, '\\d{4}-\\d{2}-\\d{2}')) AS DATE) AS FIRST_FILE_DATE,
        TRY_CAST(MIN(REGEXP_SUBSTR(Z.ZDOCI, '\\d{4}-\\d{2}-\\d{2}')) AS DATE) AS LATEST_FILE_DATE,
        SUM(Z.ZQTYZ) AS INTEL_REPORTED_QTY
    FROM {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU231_ZSDT0176') }} AS Z
    GROUP BY Z.ZTRID, Z.ZMATNR
),
TEL AS (
    SELECT 
        VBAP.ZZTIZZ AS TRID,
        VBAP.MATNR, 
        CASE WHEN MAX(VBAK.AUART) = MIN(VBAK.AUART) THEN MAX(VBAK.AUART) ELSE 'Multiple' END AS SALES_DOC_TYPE,
        MAX(VBAK.ERDAT) AS SAP_LATEST_CREATED_DATE, 
        MAX(VBAK.AUDAT) AS SAP_LATEST_DOCUMENT_DATE,
        SUM(VBAP.KWMENG) AS SAP_ORDERED_QTY,
        SUM(VBAP.NETWR) AS SAP_ORDER_AMT_IN_DOCUMENT_CURRENCY
    FROM {{ ref('BRONZE__TEA_LOGISTICS__ZCDV_T_CMTU009_VBAK') }} AS VBAK
    JOIN {{ ref('BRONZE__TEA_LOGISTICS__ZCDV_T_CMTU010_VBAP') }} AS VBAP ON (VBAP.VBELN = VBAK.VBELN)
    WHERE 
        NULLIF(TRIM(VBAP.ZZTIZZ), '') IS NOT NULL AND
        VBAK.AUART IN ('ZP12', 'ZPR2', 'ZPR1', 'ZP11')
    GROUP BY VBAP.ZZTIZZ, VBAP.MATNR
),
TRANSFORM_DATA AS (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        INTEL.TRID,
        INTEL.MATNR,
        INTEL.FIRST_FILE_DATE,
        INTEL.LATEST_FILE_DATE,
        INTEL.INTEL_REPORTED_QTY,
        COALESCE(TEL.SAP_ORDERED_QTY, 0) AS SAP_ORDERED_QTY, 
        TEL.SAP_ORDER_AMT_IN_DOCUMENT_CURRENCY,
        TRY_TO_DATE(TEL.SAP_LATEST_CREATED_DATE, 'YYYYMMDD') AS SAP_LATEST_CREATED_DATE,
        TRY_TO_DATE(TEL.SAP_LATEST_DOCUMENT_DATE, 'YYYYMMDD') AS SAP_LATEST_DOCUMENT_DATE,
        TEL.SALES_DOC_TYPE
    FROM INTEL
    LEFT JOIN TEL ON (TEL.TRID = INTEL.TRID AND TEL.MATNR = INTEL.MATNR)
),
TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(TRID AS VARCHAR(16777216)) AS TRANSACTION_ID,
        CAST(MATNR AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(FIRST_FILE_DATE AS DATE) AS FIRST_INTEL_FILE_DATE,
        CAST(LATEST_FILE_DATE AS DATE) AS LATEST_INTEL_FILE_DATE,
        CAST(INTEL_REPORTED_QTY AS INT) AS INTEL_REPORTED_QTY,
        CAST(SAP_ORDERED_QTY AS INT) AS SAP_ORDERED_QTY,
        CAST(SAP_ORDER_AMT_IN_DOCUMENT_CURRENCY AS FLOAT) AS SAP_ORDER_AMT_IN_DOCUMENT_CURRENCY,
        CAST(SAP_LATEST_CREATED_DATE AS DATE) AS SAP_LATEST_CREATED_DATE,
        CAST(SAP_LATEST_DOCUMENT_DATE AS DATE) AS SAP_LATEST_DOCUMENT_DATE
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
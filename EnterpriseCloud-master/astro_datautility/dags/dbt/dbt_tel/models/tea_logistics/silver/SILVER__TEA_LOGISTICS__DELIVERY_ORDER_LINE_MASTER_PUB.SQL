        materialized='tel_incremental',
        incremental_strategy='insert_overwrite',
        tags=["insert_overwrite_tea_logistics"],
        alias='DELIVERY_ORDER_LINE_MASTER_PUB',
        transient=false
) }}


WITH 
SLOC_CTE AS (
    SELECT LGORT, MAX(LGOBE) AS LGOBE
    FROM {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU080_T001L') }} AS T001L
    GROUP BY LGORT
),
SOURCE_DATA AS (
    SELECT 
        -- DO header
        LIPS.VBELN AS HDR, 
        -- DO line
        LIPS.POSNR AS LINE_NUM,
        LIPS.ERDAT AS CREATED_ON,
        LIKP.LFDAT AS DELIVERY_DATE,
        LIKP.WADAT AS PLANNED_GOODS_MOVEMENT_DATE,
        LIKP.WADATIST AS ACTUAL_GOODS_MOVEMENT_DATE,
        LIKP.LFART AS DELIVERY_TYPE_CODE,
        TLVKT.VTEXT AS DELIVERY_TYPE_DESC,
        LIPS.LFIMG AS QTY,
        LIPS.MATNR,
        LIPS.WERKS AS PLANT,
        LIPS.CHARG AS BATCH,
        LIKP.KODAT AS PICKING_DATE,
        LIKP.KOUHR AS PICKING_TIME,
        -- C implies complete
        LIPS.KOSTA AS PICKING_STATUS,
        LIPS.GBSTA AS PROCESSING_STATUS,
        -- Reference document (ref doc) can be a sales order or a purchase order.
        LIPS.VGBEL AS REF_DOC_HDR,
        LIPS.VGPOS AS REF_DOC_LINE,
        -- Receiving Storage Location
        LIPS.LGORT AS SLOC,
        SLOC_CTE.LGOBE AS SLOC_DESC,
        LIKP.KUNNR AS SHIP_TO_PARTY_CODE,
        KNA1.NAME1 AS SHIP_TO_PARTY_NAME,
        LIKP.ZZDDZZ AS DELIVERY_DATE_ZZDDZZ,
        LIKP.ZZCWDD AS CONF_WH_DELIVERY_DATE,
        LIKP.ZZPDDTR AS PLANNED_DELIVERY_DATE_TO_RECEIVER,
        -- HAWB : House Airway Bill / 3PL tracking #
        LIKP.ZZHAWB AS HAWB,
        LIPS.ZZRZZZ AS REMARKS
    FROM {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU013_LIPS') }} AS LIPS
    JOIN {{ ref('BRONZE__TEA_LOGISTICS__ZCDV_T_CMTU012_LIKP') }} AS LIKP ON (LIKP.VBELN = LIPS.VBELN)
    LEFT JOIN {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (KNA1.KUNNR = LIKP.KUNNR)
    LEFT JOIN {{ ref('BRONZE__TEA_LOGISTICS__SAPAPI_ZCDV_T_CMTU200_TVLKT') }} AS TLVKT ON (
        LIKP.LFART = TLVKT.LFART AND TLVKT.SPRAS = 'EN'
    )
    LEFT JOIN SLOC_CTE ON (
        LIPS.LGORT = SLOC_CTE.LGORT
    )
    -- filter out rows where Deleted = 'Yes'
    WHERE TRIM(LOWER(LIPS.IS_DELETED)) NOT LIKE 'y%'
),
TRANSFORM_DATA AS (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        HDR, 
        LINE_NUM,
        TRY_TO_DATE(CREATED_ON, 'YYYYMMDD') AS CREATED_ON,
        TRY_TO_DATE(DELIVERY_DATE, 'YYYYMMDD') AS DELIVERY_DATE,
        TRY_TO_DATE(PLANNED_GOODS_MOVEMENT_DATE, 'YYYYMMDD') AS PLANNED_GOODS_MOVEMENT_DATE,
        TRY_TO_DATE(ACTUAL_GOODS_MOVEMENT_DATE, 'YYYYMMDD') AS ACTUAL_GOODS_MOVEMENT_DATE,
        DELIVERY_TYPE_CODE,
        DELIVERY_TYPE_DESC,
        QTY,
        MATNR,
        PLANT,
        BATCH,
        TRY_TO_DATE(PICKING_DATE, 'YYYYMMDD') AS PICKING_DATE,
        PICKING_TIME,
        PICKING_STATUS,
        PROCESSING_STATUS,
        REF_DOC_HDR,
        REF_DOC_LINE,
        REF_DOC_HDR || REF_DOC_LINE AS REF_DOC_ID,
        SLOC,
        SLOC_DESC,
        SHIP_TO_PARTY_CODE,
        SHIP_TO_PARTY_NAME,
        TRY_TO_DATE(DELIVERY_DATE_ZZDDZZ, 'YYYYMMDD') AS DELIVERY_DATE_ZZDDZZ,
        TRY_TO_DATE(CONF_WH_DELIVERY_DATE, 'YYYYMMDD') AS CONF_WH_DELIVERY_DATE,
        TRY_TO_DATE(PLANNED_DELIVERY_DATE_TO_RECEIVER, 'YYYYMMDD') AS PLANNED_DELIVERY_DATE_TO_RECEIVER,
        HAWB,
        REMARKS
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(16777216)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH,
        CAST(HDR AS VARCHAR(16777216)) AS HDR,
        CAST(LINE_NUM AS VARCHAR(16777216)) AS LINE_POSNR,
        TRY_CAST(CREATED_ON AS DATE) AS CREATED_ON,
        TRY_CAST(DELIVERY_DATE AS DATE) AS DELIVERY_DATE,
        TRY_CAST(PLANNED_GOODS_MOVEMENT_DATE AS DATE) AS PLANNED_GOODS_MOVEMENT_DATE,
        TRY_CAST(ACTUAL_GOODS_MOVEMENT_DATE AS DATE) AS ACTUAL_GOODS_MOVEMENT_DATE,
        CAST(DELIVERY_TYPE_CODE AS VARCHAR(16777216)) AS DELIVERY_TYPE_CODE,
        CAST(DELIVERY_TYPE_DESC AS VARCHAR(16777216)) AS DELIVERY_TYPE_DESC,
        CAST(QTY AS FLOAT) AS QTY,
        CAST(MATNR AS VARCHAR(16777216)) AS MATNR,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(BATCH AS VARCHAR(16777216)) AS BATCH,
        CAST(PICKING_DATE AS DATE) AS PICKING_DATE,
        CAST(PICKING_TIME AS VARCHAR(16777216)) AS PICKING_TIME,
        CAST(PICKING_STATUS AS VARCHAR(16777216)) AS PICKING_STATUS,
        CAST(PROCESSING_STATUS AS VARCHAR(16777216)) AS PROCESSING_STATUS,
        CAST(REF_DOC_HDR AS VARCHAR(16777216)) AS REF_DOC_HDR,
        CAST(REF_DOC_LINE AS VARCHAR(16777216)) AS REF_DOC_LINE,
        CAST(REF_DOC_ID AS VARCHAR(16777216)) AS REF_DOC_ID,
        CAST(SLOC AS VARCHAR(16777216)) AS SLOC,
        CAST(SLOC_DESC AS VARCHAR(16777216)) AS SLOC_DESC,
        CAST(SHIP_TO_PARTY_CODE AS VARCHAR(16777216)) AS SHIP_TO_PARTY_CODE,
        CAST(SHIP_TO_PARTY_NAME AS VARCHAR(16777216)) AS SHIP_TO_PARTY_NAME,
        CAST(DELIVERY_DATE_ZZDDZZ AS DATE) AS DELIVERY_DATE_ZZDDZZ,
        CAST(CONF_WH_DELIVERY_DATE AS DATE) AS CONF_WH_DELIVERY_DATE,
        CAST(PLANNED_DELIVERY_DATE_TO_RECEIVER AS DATE) AS PLANNED_DELIVERY_DATE_TO_RECEIVER,
        CAST(HAWB AS VARCHAR(16777216)) AS HAWB,
        CAST(REMARKS AS VARCHAR(16777216)) AS REMARKS
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
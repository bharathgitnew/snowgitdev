with source_data as (
    	SELECT
		ID AS SALES_DISTRICT_ID,
 	 	STATECODE,
 	 	STATUSCODE,
 	 	TEL_COM_WF_TARGET_AREA_FLAG,
 	 	MODIFIEDBY,
 	 	MODIFIEDBY_ENTITYTYPE,
 	 	MODIFIEDONBEHALFBY,
 	 	MODIFIEDONBEHALFBY_ENTITYTYPE,
 	 	CREATEDONBEHALFBY,

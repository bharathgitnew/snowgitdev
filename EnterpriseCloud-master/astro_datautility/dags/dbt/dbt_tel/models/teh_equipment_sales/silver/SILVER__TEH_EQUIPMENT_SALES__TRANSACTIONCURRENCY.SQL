{{ config(
    	materialized='tel_incremental',
    	incremental_strategy='merge',
    	alias='TRANSACTIONCURRENCY',
    	unique_key = ['TRANSACTION_CURRENCY_ID'],
    	transient=false
) }}

with source_data as (
	SELECT
		ID AS TRANSACTION_CURRENCY_ID,
 	 	STATECODE,
 	 	STATUSCODE,
 	 	ORGANIZATIONID,
 	 	ORGANIZATIONID_ENTITYTYPE,
 	 	CREATEDONBEHALFBY,
 	 	CREATEDONBEHALFBY_ENTITYTYPE,
 	 	MODIFIEDBY,
 	 	MODIFIEDBY_ENTITYTYPE,
 	 	CREATEDBY,
 	 	CREATEDBY_ENTITYTYPE,
 	 	MODIFIEDONBEHALFBY,
 	 	MODIFIEDONBEHALFBY_ENTITYTYPE,
 	 	CURRENCYPRECISION,
 	 	MODIFIEDONBEHALFBYYOMINAME,
 	 	CURRENCYNAME,
 	 	VERSIONNUMBER,
 	 	ENTITYIMAGE_TIMESTAMP,
 	 	MODIFIEDBYYOMINAME,
 	 	CREATEDBYYOMINAME,
 	 	OVERRIDDENCREATEDON,
 	 	ENTITYIMAGEID,
 	 	CREATEDONBEHALFBYNAME,
 	 	UNIQUEDSCID,
 	 	MODIFIEDBYNAME,
 	 	ENTITYIMAGE_URL,
 	 	MODIFIEDON,
 	 	CREATEDBYNAME,
 	 	ISOCURRENCYCODE,
 	 	CREATEDONBEHALFBYYOMINAME,
 	 	TRANSACTIONCURRENCYID,
 	 	CREATEDON,
 	 	EXCHANGERATE,
 	 	IMPORTSEQUENCENUMBER,
 	 	CURRENCYSYMBOL,
 	 	MODIFIEDONBEHALFBYNAME
	FROM {{ ref('BRONZE__TEH_EQUIPMENT_SALES__CRM_FILE_TRANSACTIONCURRENCY') }}
)

,transform_data as (
	SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        TRANSACTION_CURRENCY_ID,
        STATECODE,
        STATUSCODE,
        ORGANIZATIONID,
        ORGANIZATIONID_ENTITYTYPE,
        CREATEDONBEHALFBY,
        CREATEDONBEHALFBY_ENTITYTYPE,
        MODIFIEDBY,
        MODIFIEDBY_ENTITYTYPE,
        CREATEDBY,
        CREATEDBY_ENTITYTYPE,
        MODIFIEDONBEHALFBY,
        MODIFIEDONBEHALFBY_ENTITYTYPE,
        CURRENCYPRECISION,
        MODIFIEDONBEHALFBYYOMINAME,
        CURRENCYNAME,
        VERSIONNUMBER,
        ENTITYIMAGE_TIMESTAMP,
        MODIFIEDBYYOMINAME,
        CREATEDBYYOMINAME,
        OVERRIDDENCREATEDON,
        ENTITYIMAGEID,
        CREATEDONBEHALFBYNAME,
        UNIQUEDSCID,
        MODIFIEDBYNAME,
        ENTITYIMAGE_URL,
        MODIFIEDON,
        CREATEDBYNAME,
        ISOCURRENCYCODE,
        CREATEDONBEHALFBYYOMINAME,
        TRANSACTIONCURRENCYID,
        CREATEDON,
        EXCHANGERATE,
        IMPORTSEQUENCENUMBER,
        CURRENCYSYMBOL,
        MODIFIEDONBEHALFBYNAME
FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(TRANSACTION_CURRENCY_ID AS VARCHAR(16777216)) AS TRANSACTION_CURRENCY_ID,
        CAST(STATECODE AS NUMBER(38,0)) AS STATECODE,
        CAST(STATUSCODE AS NUMBER(38,0)) AS STATUSCODE,
        CAST(ORGANIZATIONID AS VARCHAR(16777216)) AS ORGANIZATIONID,
        CAST(ORGANIZATIONID_ENTITYTYPE AS VARCHAR(16777216)) AS ORGANIZATIONID_ENTITYTYPE,
        CAST(CREATEDONBEHALFBY AS VARCHAR(16777216)) AS CREATEDONBEHALFBY,
        CAST(CREATEDONBEHALFBY_ENTITYTYPE AS VARCHAR(16777216)) AS CREATEDONBEHALFBY_ENTITYTYPE,
        CAST(MODIFIEDBY AS VARCHAR(16777216)) AS MODIFIEDBY,
        CAST(MODIFIEDBY_ENTITYTYPE AS VARCHAR(16777216)) AS MODIFIEDBY_ENTITYTYPE,
        CAST(CREATEDBY AS VARCHAR(16777216)) AS CREATEDBY,
        CAST(CREATEDBY_ENTITYTYPE AS VARCHAR(16777216)) AS CREATEDBY_ENTITYTYPE,
        CAST(MODIFIEDONBEHALFBY AS VARCHAR(16777216)) AS MODIFIEDONBEHALFBY,
        CAST(MODIFIEDONBEHALFBY_ENTITYTYPE AS VARCHAR(16777216)) AS MODIFIEDONBEHALFBY_ENTITYTYPE,
        CAST(CURRENCYPRECISION AS NUMBER(38,0)) AS CURRENCYPRECISION,
        CAST(MODIFIEDONBEHALFBYYOMINAME AS VARCHAR(16777216)) AS MODIFIEDONBEHALFBYYOMINAME,
        CAST(CURRENCYNAME AS VARCHAR(16777216)) AS CURRENCYNAME,
        CAST(VERSIONNUMBER AS NUMBER(38,0)) AS VERSIONNUMBER,
        CAST(ENTITYIMAGE_TIMESTAMP AS NUMBER(38,0)) AS ENTITYIMAGE_TIMESTAMP,
        CAST(MODIFIEDBYYOMINAME AS VARCHAR(16777216)) AS MODIFIEDBYYOMINAME,
        CAST(CREATEDBYYOMINAME AS VARCHAR(16777216)) AS CREATEDBYYOMINAME,
        CAST(OVERRIDDENCREATEDON AS TIMESTAMP_LTZ(9)) AS OVERRIDDENCREATEDON,
        CAST(ENTITYIMAGEID AS VARCHAR(16777216)) AS ENTITYIMAGEID,
        CAST(CREATEDONBEHALFBYNAME AS VARCHAR(16777216)) AS CREATEDONBEHALFBYNAME,
        CAST(UNIQUEDSCID AS VARCHAR(16777216)) AS UNIQUEDSCID,
        CAST(MODIFIEDBYNAME AS VARCHAR(16777216)) AS MODIFIEDBYNAME,
        CAST(ENTITYIMAGE_URL AS VARCHAR(16777216)) AS ENTITYIMAGE_URL,
        CAST(MODIFIEDON AS TIMESTAMP_LTZ(9)) AS MODIFIEDON,
        CAST(CREATEDBYNAME AS VARCHAR(16777216)) AS CREATEDBYNAME,
        CAST(ISOCURRENCYCODE AS VARCHAR(16777216)) AS ISOCURRENCYCODE,
        CAST(CREATEDONBEHALFBYYOMINAME AS VARCHAR(16777216)) AS CREATEDONBEHALFBYYOMINAME,
        CAST(TRANSACTIONCURRENCYID AS VARCHAR(16777216)) AS TRANSACTIONCURRENCYID,
        CAST(CREATEDON AS TIMESTAMP_LTZ(9)) AS CREATEDON,
        CAST(EXCHANGERATE AS NUMBER(38,10)) AS EXCHANGERATE,
        CAST(IMPORTSEQUENCENUMBER AS NUMBER(38,0)) AS IMPORTSEQUENCENUMBER,
        CAST(CURRENCYSYMBOL AS VARCHAR(16777216)) AS CURRENCYSYMBOL,
        CAST(MODIFIEDONBEHALFBYNAME AS VARCHAR(16777216)) AS MODIFIEDONBEHALFBYNAME
FROM transform_data
)

SELECT * from type_data
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='QUOTE_ACTION_LIFECYCLE',
      transient=false
) }}

WITH source_data as 
(SELECT DISTINCT
TEL_QUOTE_ID AS QUOTE_ID,
FIRST_VALUE(TEL_QUOTE_STATUS) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS LATEST_QUOTE_STATUS,
FIRST_VALUE(PRODUCT_LINE) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS BUSINESS_UNIT,
FIRST_VALUE(CATEGORY) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS CATEGORY,
FIRST_VALUE(MODEL) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS MODEL,
FIRST_VALUE(TEL_QUOTE_NODE_PROCESS) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS TEL_QUOTE_NODE_PROCESS,
FIRST_VALUE(QUOTE_AMT) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS QUOTE_AMT,
FIRST_VALUE(REQUEST_NUMBER) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS QRF_NUMBER,
MAX(STATUS_DATE) OVER (PARTITION BY TEL_QUOTE_ID) AS LATEST_QUOTE_STATUS_DATE,
MIN(PUBLISH_DATE_REGION) OVER (PARTITION BY TEL_QUOTE_ID) AS INITIAL_QUOTE_PUBLISH_DATE, 
FIRST_VALUE(QUOTE_TYPE) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS QUOTE_TYPE,
FIRST_VALUE(REFERENCE_1) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE DESC) AS DESCRIPTION
FROM  {{ ref('BRONZE__TEH_EQUIPMENT_SALES__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }}
WHERE 
  REQTYPE = 'QRF'
), 
LATEST_QUOTE_REFRESH AS
( SELECT DISTINCT QUOTE_ID AS QRF_NUMBER, 
MAX(ACTION_DATE) AS LATEST_REFRESH_DATE
FROM  {{ ref('BRONZE__TEH_EQUIPMENT_SALES__TELCUSTOMER_EQUIPMENT_QUOTE_TRACKING') }} 
WHERE UPPER(ACTION) = 'REFRESHED' AND REQUEST_TYPE = 'QRF'
GROUP BY 1
)
, transform_data as (
  SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        source.QUOTE_ID,
        source.LATEST_QUOTE_STATUS,
        source.BUSINESS_UNIT,
        source.CATEGORY,
        source.MODEL,
        source.TEL_QUOTE_NODE_PROCESS,
        source.QUOTE_AMT,
        source.QRF_NUMBER,
        source.LATEST_QUOTE_STATUS_DATE,
        source.INITIAL_QUOTE_PUBLISH_DATE,
        CASE WHEN source.LATEST_QUOTE_STATUS = 'DNO' THEN NULL
        --not refreshing the ones hasnt been published yet
        WHEN LATESTQR.LATEST_REFRESH_DATE IS NOT NULL AND TO_DATE(INITIAL_QUOTE_PUBLISH_DATE) > TO_DATE(LATESTQR.LATEST_REFRESH_DATE) THEN NULL
        --not refreshing the ones that are no longer active
        WHEN LATESTQR.LATEST_REFRESH_DATE IS NOT NULL AND TO_DATE(LATESTQR.LATEST_REFRESH_DATE) > TO_DATE(LATEST_QUOTE_STATUS_DATE) THEN NULL
        WHEN LATESTQR.LATEST_REFRESH_DATE IS NULL THEN 0
        ELSE 1 END AS IS_REFRESHED,
        CASE WHEN source.LATEST_QUOTE_STATUS = 'DNO' THEN NULL
        WHEN LATESTQR.LATEST_REFRESH_DATE IS NOT NULL AND TO_DATE(INITIAL_QUOTE_PUBLISH_DATE) > TO_DATE(LATESTQR.LATEST_REFRESH_DATE) THEN NULL
        WHEN LATESTQR.LATEST_REFRESH_DATE IS NOT NULL AND TO_DATE(LATESTQR.LATEST_REFRESH_DATE) > TO_DATE(LATEST_QUOTE_STATUS_DATE) THEN NULL
        ELSE LATESTQR.LATEST_REFRESH_DATE END AS LATEST_REFRESH_DATE,
        source.QUOTE_TYPE,
        source.DESCRIPTION
FROM source_data source
  LEFT JOIN LATEST_QUOTE_REFRESH LATESTQR
  ON source.QRF_NUMBER = LATESTQR.QRF_NUMBER
)

, type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(QUOTE_ID AS VARCHAR(16777216)) AS QUOTE_ID,
        CAST(LATEST_QUOTE_STATUS AS VARCHAR(16777216)) AS LATEST_QUOTE_STATUS,
        CAST(BUSINESS_UNIT AS VARCHAR(16777216)) AS BUSINESS_UNIT,
        CAST(CATEGORY AS VARCHAR(16777216)) AS CATEGORY,
        CAST(MODEL AS VARCHAR(16777216)) AS MODEL,
        CAST(TEL_QUOTE_NODE_PROCESS AS VARCHAR(16777216)) AS TEL_QUOTE_NODE_PROCESS,
        CAST(QUOTE_AMT AS NUMBER(38,0)) AS QUOTE_AMT,
        CAST(QRF_NUMBER AS NUMBER(38,0)) AS QRF_NUMBER,
        CAST(LATEST_QUOTE_STATUS_DATE AS DATE) AS LATEST_QUOTE_STATUS_DATE,
        CAST(INITIAL_QUOTE_PUBLISH_DATE AS DATE) AS INITIAL_QUOTE_PUBLISH_DATE,
        CAST(IS_REFRESHED AS NUMBER(1,0)) AS IS_QUOTE_REFRESHED,
        CAST(LATEST_REFRESH_DATE AS DATE) AS LATEST_QUOTE_REFRESH_DATE,
        CAST(QUOTE_TYPE AS VARCHAR(16777216)) AS QUOTE_TYPE,
        CAST(DESCRIPTION AS VARCHAR(16777216)) AS DESCRIPTION
FROM transform_data
)
SELECT * FROM type_data
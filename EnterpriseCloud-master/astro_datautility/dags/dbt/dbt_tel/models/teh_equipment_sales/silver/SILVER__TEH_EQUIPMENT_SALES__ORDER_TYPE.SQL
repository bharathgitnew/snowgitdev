        CAST(OWNINGTEAM_ENTITYTYPE AS VARCHAR(16777216)) AS OWNINGTEAM_ENTITYTYPE,
        CAST(OWNINGBUSINESSUNIT AS VARCHAR(16777216)) AS OWNINGBUSINESSUNIT,
        CAST(OWNINGBUSINESSUNIT_ENTITYTYPE AS VARCHAR(16777216)) AS OWNINGBUSINESSUNIT_ENTITYTYPE,
        CAST(OWNINGUSER AS VARCHAR(16777216)) AS OWNINGUSER,
        CAST(OWNINGUSER_ENTITYTYPE AS VARCHAR(16777216)) AS OWNINGUSER_ENTITYTYPE,
        CAST(MODIFIEDBY AS VARCHAR(16777216)) AS MODIFIEDBY,
        CAST(MODIFIEDBY_ENTITYTYPE AS VARCHAR(16777216)) AS MODIFIEDBY_ENTITYTYPE,
        CAST(CREATEDBY AS VARCHAR(16777216)) AS CREATEDBY,

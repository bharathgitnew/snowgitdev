        CAST(VERSIONNUMBER AS NUMBER(38,0)) AS VERSIONNUMBER,
        CAST(OWNINGBUSINESSUNITNAME AS VARCHAR(16777216)) AS OWNINGBUSINESSUNITNAME,
        CAST(MODIFIEDONBEHALFBYNAME AS VARCHAR(16777216)) AS MODIFIEDONBEHALFBYNAME,
        CAST(OWNERIDNAME AS VARCHAR(16777216)) AS OWNERIDNAME,

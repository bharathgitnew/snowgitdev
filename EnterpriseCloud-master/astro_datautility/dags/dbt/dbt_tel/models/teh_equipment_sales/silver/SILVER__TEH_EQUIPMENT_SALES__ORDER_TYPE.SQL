        SHA2('hash_me') AS _ROW_HASH,
        ORDER_TYPE_ID,
        STATECODE,
        STATUSCODE,
        OWNINGTEAM,
        OWNINGTEAM_ENTITYTYPE,
        OWNINGBUSINESSUNIT,
        OWNINGBUSINESSUNIT_ENTITYTYPE,
        OWNINGUSER,
        OWNINGUSER_ENTITYTYPE,
        MODIFIEDBY,
        MODIFIEDBY_ENTITYTYPE,
        CREATEDBY,
        CREATEDBY_ENTITYTYPE,

{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='TEL_CUSTOMER_QUOTE_REQUEST'
) }}

with source_data as
(
    select
    	qrf.REQUEST_NUMBER                                  as REQUEST_NO,
    	qrf.REV                                             as REVISION_NO,
    	qrf.REQUEST_NUMBER || '-' || lpad(qrf.REV, 2, '0')  as QRF_KEY,
    	qrf.EQUIPMENT_QUOTE_TEL_QUOTE_ID,
    	qrf.TEL_QUOTE_ID                                    as QUOTE_NO,
    	upper(qrf.STATUS)                                   as QRF_STATUS,
    	qrf.TEL_QUOTE_STATUS                                as QUOTE_STATUS,
    	qrf.QUOTE_TYPE,
    	qrf.SPECIFIC_REQUEST_TYPE                           as REQUEST_TYPE,
    	upper(qrf.COMPANY)								    as END_USER,
    	coalesce(upper(qrf.FAB), upper(qrf.FABS))		    as FAB,
    	upper(qrf.CATEGORY)							        as CATEGORY,
    	qrf.NODES										    as NODE,
    	qrf.PRODUCT_LINE,
    	qrf.MODEL,
    	qrf.REQUEST_DATE                                    as QRF_ORIGINAL_REQUESTED,
    	qrf.PUBLISH_DATE_REGION                             as QRF_PUBLISHED,
    	REQUEST_REVISION_DATE                               as QRF_REVISION_REQUESTED,
    	REVISE_DATE_REGION                                  as QRF_REVISED,
    	qrf.REVERTED_DATE                                   as QRF_REVERTED,
    	qrf.CANCEL_DATE                                     as QRF_CANCELED,
    	qrf.ON_HOLD_DATE                                    as QRF_PUT_ON_HOLD,
    	qrf.RELEASE_FROM_HOLD_DATE                          as QRF_RELEASED_FROM_HOLD,
    	qrf.QUOTE_CURRENCY,
    	qrf.QUOTE_AMT                                       as QUOTE_AMOUNT,
    	upper(qrf.DESCRIPTION)							    as DESCRIPTION,
    	upper(qrf.REFERENCE_1)							    as TEL_REFERENCE,
    	qrf.TEL_COMMENT,
    	qrf.BIS_CUSTOMER_CODE							    as END_USER_CODE,
    	qrf.ACTIVE                                          as IS_ACTIVE
    from {{ref('BRONZE__TEH_EQUIPMENT_SALES__TELCUSTOMER_TELCUST_ARF_QRF_DATA')}} qrf
	where qrf.REQTYPE ilike 'QRF'
),
transform_data as (
    select 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        REQUEST_NO,
		REVISION_NO,
		QRF_KEY,
		EQUIPMENT_QUOTE_TEL_QUOTE_ID,
		QUOTE_NO,
		QRF_STATUS,
		QUOTE_STATUS,
		QUOTE_TYPE,
		REQUEST_TYPE,
		END_USER,
		FAB,
		CATEGORY,
		NODE,
		PRODUCT_LINE,
		MODEL,
		QRF_ORIGINAL_REQUESTED,
		QRF_PUBLISHED,
		QRF_REVISION_REQUESTED,
		QRF_REVISED,
		QRF_REVERTED,
		QRF_CANCELED,
		QRF_PUT_ON_HOLD,
		QRF_RELEASED_FROM_HOLD,
		QUOTE_CURRENCY,
		QUOTE_AMOUNT,
		DESCRIPTION,
		TEL_REFERENCE,
		TEL_COMMENT,
		END_USER_CODE,
		IS_ACTIVE
    from source_data
) ,
type_data as
(
SELECT
    cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
    cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
    REQUEST_NO,
	REVISION_NO,
	QRF_KEY,
	EQUIPMENT_QUOTE_TEL_QUOTE_ID,
	QUOTE_NO,
	QRF_STATUS,
	QUOTE_STATUS,
	QUOTE_TYPE,
	REQUEST_TYPE,
	END_USER,
	FAB,
	CATEGORY,
	NODE,
	PRODUCT_LINE,
	MODEL,
	QRF_ORIGINAL_REQUESTED,
	QRF_PUBLISHED,
	QRF_REVISION_REQUESTED,
	QRF_REVISED,
	QRF_REVERTED,
	QRF_CANCELED,
	QRF_PUT_ON_HOLD,
	QRF_RELEASED_FROM_HOLD,
	QUOTE_CURRENCY,
	QUOTE_AMOUNT,
	DESCRIPTION,
	TEL_REFERENCE,
	TEL_COMMENT,
	END_USER_CODE,
	IS_ACTIVE
from transform_data 
)
select * from type_data
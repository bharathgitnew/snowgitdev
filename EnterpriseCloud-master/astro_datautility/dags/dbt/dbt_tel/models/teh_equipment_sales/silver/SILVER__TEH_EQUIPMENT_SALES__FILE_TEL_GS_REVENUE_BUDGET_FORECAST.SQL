    alias='FILE_TEL_GS_REVENUE_BUDGET_FORECAST',
    enabled=true
) }}

with source_data as
(

    SELECT
        FISCALYEAR,
        QUARTER,
        SALESMONTH,
        BUSINESSUNITCODE,
        KA,
        BUSINESSUNITNAME,
        SUBBUSINESSUNITNAME,
        SALESORDERNUMBER,
        ACCOUNTCODE,
        ACCOUNTNAME,
        CUSTOMERCODE,
        CUSTOMERNAME,
        ENDUSERCODE,
        ENDUSERNAME,
        OPPORTUNITY,
        PRODUCTNAME,
        LEVEL,
        LEVEL2,
        SALESAMOUNT,
        DIRECTMARGIN,
        SALESAMOUNT100M,
        DIRECTMARGIN100M,
        QUANTITY,
        EUROPEREQUESTDATE,
        DELIVERYDATE,
        CUSTOMCLEARENCEDATE,
        ONDOCKDATE,
        SALESDATE,
        MACHINESERIALNUMBER,
        SALESCATEGORYCODE,
        SALESCATEGORYNAME,
        AREA,
        AREANAME,
        DISTRIBUTIONFLAG,
        LOANFLAG,
        CSTFLAG,
        INVESTMENTCODE,
        PROCESSOFRECORD,
        BACKUP,
        DEGREEOFSALESUNCERTAINTY,
        INVESTMENTSUBCODE,
        DEVICE1CODE,
        DEVICE1NAME,
        DEVICE2CODE,
        DEVICE2NAME,
        _FILENAME
    FROM
    {{ ref('BRONZE__TEH_EQUIPMENT_SALES__SALES_OPERATIONS_TEL_GS_REVENUE_BUDGET_FORECAST') }}
)

,transform_data as
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        FISCALYEAR,
        QUARTER,
        case
        when length(SALESMONTH)=10
        then to_date(SALESMONTH,'YYYY-MM-DD')
        when length(SALESMONTH)=7 then to_date(SALESMONTH,'YYYY/MM')
        else null
        end as SALESMONTH,
        BUSINESSUNITCODE,
        case when length(BUSINESSUNITCODE)=2
        then cast(BUSINESSUNITCODE as text)
        end as BUSINESSUNITCODE_TEXT,
        KA,
        BUSINESSUNITNAME,
        SUBBUSINESSUNITNAME,
        SPLIT_PART(BUSINESSUNITCODE, '-', 3) AS SUBSUSINESSUNITNAME2,
        SALESORDERNUMBER,
        ACCOUNTCODE,
        ACCOUNTNAME,
        CUSTOMERCODE,
        CUSTOMERNAME,
        ENDUSERCODE,
        ENDUSERNAME,
        OPPORTUNITY,
        PRODUCTNAME,
        LEVEL,
        LEVEL2,
        regexp_replace(SALESAMOUNT,',') AS SALESAMOUNT,
        regexp_replace(DIRECTMARGIN,',') AS DIRECTMARGIN,
        SALESAMOUNT100M,
        DIRECTMARGIN100M,
        QUANTITY,
        EUROPEREQUESTDATE,
        DELIVERYDATE,
        CUSTOMCLEARENCEDATE,
        ONDOCKDATE,
        SALESDATE,
        MACHINESERIALNUMBER,
        SALESCATEGORYCODE,
        SALESCATEGORYNAME,
        AREA,
        AREANAME,
        DISTRIBUTIONFLAG,
        LOANFLAG,
        CSTFLAG,
        INVESTMENTCODE,
        PROCESSOFRECORD,
        BACKUP,
        DEGREEOFSALESUNCERTAINTY,
        INVESTMENTSUBCODE,
        DEVICE1CODE,
        DEVICE1NAME,
        DEVICE2CODE,
        DEVICE2NAME,
        _FILENAME,
        regexp_substr(_FILENAME,'\\d+++++++') as FILEDATE,
        TO_DATE(FILEDATE,'YYYYMMDD') as _FILEDATE,
        CASE WHEN regexp_substr(_FILENAME, '([ \\w]+)\\.csv') ILIKE '%Budget%' THEN 'BUDGET'
        WHEN regexp_substr(_FILENAME, '([ \\w]+)\\.csv') ILIKE '%Actual%' THEN 'ACTUAL'
        WHEN regexp_substr(_FILENAME, '([ \\w]+)\\.csv') ILIKE '%FCST%' THEN 'FORECAST'
        ELSE null
        end	AS SOURCETYPE
FROM source_data
)
,type_data as
(
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        cast(FISCALYEAR as VARCHAR(16777216)) as FISCALYEAR,
        cast(QUARTER as VARCHAR(16777216)) as QUARTER,
        cast(SALESMONTH as DATE) as SALESMONTH,
        cast(BUSINESSUNITCODE as VARCHAR(16777216)) as BUSINESSUNITCODE,
        cast(BUSINESSUNITCODE_TEXT as VARCHAR(16777216)) as BUSINESSUNITCODE_TEXT,
        cast(KA as VARCHAR(16777216)) as KA,
        cast(BUSINESSUNITNAME as VARCHAR(16777216)) as BUSINESSUNITNAME,
        cast(SUBBUSINESSUNITNAME as VARCHAR(16777216)) as SUBBUSINESSUNITNAME,
        cast(SUBSUSINESSUNITNAME2 as VARCHAR(16777216)) as SUBUSINESSUNITNAME2,
        cast(SALESORDERNUMBER as VARCHAR(16777216)) as SALESORDERNUMBER,
        cast(ACCOUNTCODE as VARCHAR(16777216)) as ACCOUNTCODE,
        cast(ACCOUNTNAME as VARCHAR(16777216)) as ACCOUNTNAME,
        cast(CUSTOMERCODE as VARCHAR(16777216)) as CUSTOMERCODE,
        cast(CUSTOMERNAME as VARCHAR(16777216)) as CUSTOMERNAME,
        cast(ENDUSERCODE as VARCHAR(16777216)) as ENDUSERCODE,
        cast(ENDUSERNAME as VARCHAR(16777216)) as ENDUSERNAME,
        cast(OPPORTUNITY as VARCHAR(16777216)) as OPPORTUNITY,
        cast(PRODUCTNAME as VARCHAR(16777216)) as PRODUCTNAME,
        cast(LEVEL as VARCHAR(16777216)) as LEVEL,
        cast(LEVEL2 as VARCHAR(16777216)) as LEVEL2,
        try_cast(SALESAMOUNT as NUMBER(38,0)) as SALESAMOUNT,
        try_cast(DIRECTMARGIN as NUMBER(38,0)) as DIRECTMARGIN,
        try_cast(SALESAMOUNT100M as NUMBER(38,0)) as SALESAMOUNT100M,
        try_cast(DIRECTMARGIN100M as NUMBER(38,0)) as DIRECTMARGIN100M,
        try_cast(QUANTITY as NUMBER(38,0)) as QUANTITY,
        cast(EUROPEREQUESTDATE as TIMESTAMP_NTZ(9)) as EUROPEREQUESTDATE,
        cast(DELIVERYDATE as TIMESTAMP_NTZ(9)) as DELIVERYDATE,
        cast(CUSTOMCLEARENCEDATE as TIMESTAMP_NTZ(9)) as CUSTOMCLEARANCEDATE,
        cast(ONDOCKDATE as TIMESTAMP_NTZ(9)) as ONDOCKDATE,
        cast(SALESDATE as TIMESTAMP_NTZ(9)) as SALESDATE,
        cast(MACHINESERIALNUMBER as VARCHAR(16777216)) as MACHINESERIALNUMBER,
        cast(SALESCATEGORYCODE as VARCHAR(16777216)) as SALESCATEGORYCODE,
        cast(SALESCATEGORYNAME as VARCHAR(16777216)) as SALESCATEGORYNAME,
        cast(AREA as VARCHAR(16777216)) as AREA,
        cast(AREANAME as VARCHAR(16777216)) as AREANAME,
        cast(DISTRIBUTIONFLAG as VARCHAR(16777216)) as DISTRIBUTIONFLAG,
        cast(LOANFLAG as VARCHAR(16777216)) as LOANFLAG,
        cast(CSTFLAG as VARCHAR(16777216)) as CSTFLAG,
        cast(INVESTMENTCODE as VARCHAR(16777216)) as INVESTMENTCODE,
        cast(PROCESSOFRECORD as VARCHAR(16777216)) as PROCESSOFRECORD,
        try_cast(BACKUP as NUMBER(38,0)) as BACKUP,
        try_cast(DEGREEOFSALESUNCERTAINTY as NUMBER(38,0)) as DEGREEOFSALESUNCERTAINTY,
        cast(INVESTMENTSUBCODE as VARCHAR(16777216)) as INVESTMENTSUBCODE,
        cast(DEVICE1CODE as VARCHAR(16777216)) as DEVICE1CODE,
        cast(DEVICE1NAME as VARCHAR(16777216)) as DEVICE1NAME,
        cast(DEVICE2CODE as VARCHAR(16777216)) as DEVICE2CODE,
        cast(DEVICE2NAME as VARCHAR(16777216)) as DEVICE2NAME,
        cast(_FILENAME as VARCHAR(16777216)) as _FILENAME,
        cast(_FILEDATE as DATE) as _FILEDATE,
        cast(SOURCETYPE as VARCHAR(16777216)) as SOURCETYPE
from transform_data
    )
select * from type_data
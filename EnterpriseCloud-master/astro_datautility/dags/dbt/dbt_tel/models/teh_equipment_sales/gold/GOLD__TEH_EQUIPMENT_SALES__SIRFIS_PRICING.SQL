{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
        alias='SIRFIS_PRICING',
      transient=false
) }}

WITH PURCHASE_ORDER_PAST_PRICING as(
    SELECT
        PRICE_KEY,
        LINE_AMOUNT
    FROM
        (SELECT DISTINCT PRICE_KEY, 
            LINE_AMOUNT,
            ROW_NUMBER() OVER (PARTITION BY PRICE_KEY ORDER BY LATEST_PURCHASE_ORDER_TIMESTAMP DESC) as rn
        FROM {{ ref('GOLD__TEH_EQUIPMENT_SALES__PURCHASE_ORDER_CHANGE_ORDER') }}
        ) WHERE rn = 1
),

PURCHASE_ORDER_PRICING as(
    SELECT DISTINCT PURCHASE_ORDER_LINE_ID, 
        LINE_AMOUNT AS AMOUNT
    FROM {{ ref('GOLD__TEH_EQUIPMENT_SALES__PURCHASE_ORDER_CHANGE_ORDER') }}
),

LATEST_QUOTE_PRICE as(
    SELECT QUOTE_SEARCH_KEY,
        MEDIAN(QUOTE_AMT) AS QUOTE_AMT
    FROM
        (SELECT DISTINCT 
            QUOTE_SEARCH_KEY,
            QUOTE_AMT,
            ROW_NUMBER() OVER (PARTITION BY QUOTE_ID ORDER BY LATEST_QUOTE_STATUS_DATE DESC) as rn
        FROM {{ ref('GOLD__TEH_EQUIPMENT_SALES__LATEST_QUOTE_PRICE') }}
        WHERE QUOTE_SEARCH_KEY IS NOT NULL
        ) WHERE rn = 1 
GROUP BY 1
),

INLINE AS(
    SELECT DISTINCT PRICE_KEY,
        PRICE_ESTIMATE
    FROM {{ ref('SILVER__TEH_EQUIPMENT_SALES__SIRFIS_PRICE_ESTIMATE_INLINE') }}
),

SOURCE_DATA as(
    SELECT DISTINCT a.ID, 
        a.PURCHASE_ORDER_KEY,
        a.PRICE_KEY,
        a.PO_STATUS, 
        a.EXPECTED_FORECAST_STATUS,
        CASE 
            WHEN b.CATEGORY = 'PK' THEN 'PKD' 
            WHEN b.CATEGORY = 'CK' THEN 'CK' 
            WHEN b.CATEGORY = 'MT' THEN 'MT' 
            WHEN b.CATEGORY = 'PKD' THEN 'PKD' 
            ELSE 'OTHER'
        END AS CATEGORY_QRF_KEY,
        CASE
            WHEN b.CATEGORY = 'CK' THEN NULL
            ELSE CATEGORY_QRF_KEY || '-' || UPPER(b.CEID) || '-' || b.PROCESS
        END AS QUOTE_SEARCH_KEY
    FROM {{ ref('GOLD__TEH_EQUIPMENT_SALES__SIRFIS_LIFECYCLE') }} a
    INNER JOIN {{ ref('GOLD__TEH_EQUIPMENT_SALES__SIRFIS_ITEM_HIERARCHY') }} b
    ON a.ID = b.ID
),

transform_data as(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        SOURCE_DATA.ID,
        SOURCE_DATA.PRICE_KEY,
        SOURCE_DATA.PO_STATUS,
        SOURCE_DATA.EXPECTED_FORECAST_STATUS,
        CASE
        WHEN SOURCE_DATA.PO_STATUS = 1 THEN PURCHASE_ORDER_PRICING.AMOUNT
        ELSE NULL
        END AS CURRENT_AMOUNT,
        CASE
        WHEN SOURCE_DATA.PO_STATUS = 1 THEN PURCHASE_ORDER_PRICING.AMOUNT
        WHEN SOURCE_DATA.PO_STATUS = 0 THEN ROUND(COALESCE(LATEST_QUOTE_PRICE.QUOTE_AMT, PURCHASE_ORDER_PAST_PRICING.LINE_AMOUNT), 0)
        ELSE NULL
        END AS PRICE_ESTIMATE_DEV,
        CASE
        WHEN PRICE_ESTIMATE_DEV IS NULL THEN INLINE.PRICE_ESTIMATE
        ELSE PRICE_ESTIMATE_DEV
        END AS PRICE_ESTIMATE
FROM SOURCE_DATA
    LEFT JOIN PURCHASE_ORDER_PRICING
    ON SOURCE_DATA.PURCHASE_ORDER_KEY = PURCHASE_ORDER_PRICING.PURCHASE_ORDER_LINE_ID
    LEFT JOIN PURCHASE_ORDER_PAST_PRICING
    ON SOURCE_DATA.PRICE_KEY = PURCHASE_ORDER_PAST_PRICING.PRICE_KEY
    LEFT JOIN LATEST_QUOTE_PRICE
    ON SOURCE_DATA.QUOTE_SEARCH_KEY = LATEST_QUOTE_PRICE.QUOTE_SEARCH_KEY
    LEFT JOIN INLINE 
    ON SOURCE_DATA.PRICE_KEY = INLINE.PRICE_KEY
),

type_data as(
    select
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(ID AS VARCHAR(16777216)) AS ID,
        CAST(PRICE_KEY AS VARCHAR(16777216)) AS PRICE_KEY,
        CAST(PO_STATUS AS NUMBER(38,0)) AS PO_STATUS,
        CAST(EXPECTED_FORECAST_STATUS AS VARCHAR(16777216)) AS EXPECTED_FORECAST_STATUS,
        CAST(CURRENT_AMOUNT AS NUMBER(38,0)) AS CURRENT_AMOUNT,
        CAST(PRICE_ESTIMATE_DEV AS NUMBER(38,0)) AS PRICE_ESTIMATE_DEV,
        CAST(PRICE_ESTIMATE AS NUMBER(38,0)) AS PRICE_ESTIMATE
from transform_data
)

select * from type_data
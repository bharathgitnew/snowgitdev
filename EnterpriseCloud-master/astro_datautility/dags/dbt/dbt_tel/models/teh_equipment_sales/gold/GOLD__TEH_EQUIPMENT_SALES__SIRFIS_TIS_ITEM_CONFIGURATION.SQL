WITH SOURCE AS ( 
  SELECT DISTINCT 
      INSTALL_SCHEDULE_ID
    , CASE WHEN SNAPSHOT_DATE < '2025-01-13' THEN SNAPSHOT_DATE ELSE _FILEDATE END AS _FILEDATE
    , MANUFACTURER_NAME
    , MANUFACTURER_NUMBER
    , EVENT_TYPE
    , BUILDING
    , SITE
    , MODEL
    , ENTITY_CODE
    , ENTITY_TYPE
    , CE_ID
    , CAPACITY_PROCESS
    , ORIGIN_SITE
    , ORIGIN_ENTITY_CODE
    , CK_DESCRIPTION
    , BATCH
    , FUNCTIONAL_AREA
    , LIFE
    , STATE
  FROM {{ ref('SILVER__TEH_EQUIPMENT_SALES__SIRFIS_TOOL_INSTALLATION_BASE') }}
  WHERE UPPER(STATE) <> 'PAST'
)

, SOURCE_DATA AS(
  SELECT DISTINCT 
    INSTALL_SCHEDULE_ID AS ID
  , FIRST_VALUE(MANUFACTURER_NAME) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS MANUFACTURER_NAME
  , FIRST_VALUE(MANUFACTURER_NUMBER) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS MANUFACTURER_NUMBER
  , UPPER(FIRST_VALUE(EVENT_TYPE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC)) AS EVENT_TYPE
  , FIRST_VALUE(BUILDING) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS BUILDING
  , FIRST_VALUE(SITE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS SITE
  , FIRST_VALUE(MODEL) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS MODEL
  , FIRST_VALUE(ENTITY_CODE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS ENTITY
  , UPPER(FIRST_VALUE(ENTITY_TYPE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC)) AS ENTITY_LEFT_3
  , FIRST_VALUE(CE_ID) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS CEID
  , FIRST_VALUE(CAPACITY_PROCESS) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS PROCESS
  , FIRST_VALUE(ORIGIN_SITE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS ORIGIN_SITE
  , FIRST_VALUE(ORIGIN_ENTITY_CODE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS ORIGIN_ENTITY
  , FIRST_VALUE(CK_DESCRIPTION) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS CK_DESCRIPTION
  , FIRST_VALUE(BATCH) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS BATCH
  , FIRST_VALUE(FUNCTIONAL_AREA) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS FUNCTIONAL_AREA
  , FIRST_VALUE(LIFE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC) AS LIFE
  , UPPER(FIRST_VALUE(STATE) OVER (PARTITION BY INSTALL_SCHEDULE_ID ORDER BY _FILEDATE DESC)) AS STATE
FROM SOURCE
)

, BU_LOOKUP_SOURCE_REF AS (	
SELECT 
    BUSINESS_UNIT_LOOKUP_ID
    , CREATED_ON
    , TYPE
    , MATCH_VALUE
    , BUSINESS_UNIT
    , ACRONYM
FROM {{ ref('BRONZE__TEH_EQUIPMENT_SALES__SIRFIS_BUSINESS_UNIT_LOOKUP') }}
)

, TRANSFORM_DATA AS(
  SELECT DISTINCT
  '{{ invocation_id }}' AS _AUDIT_LOG_ID
  , SHA2('hash_me') as _ROW_HASH
  , FACT.ID
  , FACT.MANUFACTURER_NAME
  , FACT.MANUFACTURER_NUMBER
  , UPPER(DIM_BU.BUSINESS_UNIT) AS BUSINESS_UNIT 
  , DIM_BU.ACRONYM AS BUSINESS_UNIT_SHORT_TEXT
  , FACT.EVENT_TYPE
  , FACT.BUILDING
  , FACT.SITE 
  , FACT.MODEL
  --Leah Qi: as per Liam Dohn VP - 2025-01-30 TEL_MODEL is our brand name and must stay case sensitive 
  , CASE WHEN MODEL IN ('REPAIR CART', 'REPAIR CART 6KW') THEN 'BLITS - Cart'
         WHEN MODEL IN ('SDTC X2 DUSTI', 'SDX20 6KW LD_DU') THEN 'BLITS - Cell'
         WHEN MODEL IN ('SDX20 6KW GEN3', 'SDX20 FRAME 6KW', 'SDX4 FRAME 6KW') THEN 'BLITS - Module'
         WHEN MODEL IN ('ACT M', 'ACT12') THEN 'CT - ACT'
         WHEN MODEL IN ('D-PRO Z', 'L-PRO Z', 'PRO-Z') THEN 'LITHIUS Pro Z'
         WHEN MODEL IN ('LITHIUS PRO-V', 'L-PRO V') THEN 'LITHIUS Pro V'
         WHEN MODEL IN ('MZETA EP1', 'ZETA PLUS 300') THEN 'MZETA'
         WHEN MODEL IN ('P12XL', 'PRECIOXL') THEN 'Precio XL'
         WHEN MODEL IN ('HOP UNIT', 'HTP') THEN 'Prexa - HOP'
         WHEN MODEL IN ('SYNAPSE SI', 'SYNAPSE V') THEN 'Synapse'
         WHEN MODEL IN ('BX PLATFORM', 'VIGUS') THEN 'Tactras'
         WHEN MODEL IN ('SCCM', 'TELIUS SCCM') THEN 'Telius'
         WHEN MODEL LIKE '%INDY PLUS%' THEN 'TELINDY'
         WHEN MODEL like '%TRIAS%' THEN 'Triase'
         WHEN MODEL = 'SDTT' THEN 'BLITS - Other'
         WHEN MODEL = 'CELLESTA+' THEN 'CELLESTA'
         WHEN MODEL = 'CELLESTA-I' THEN 'CELLESTA - i'
         WHEN MODEL = 'IEX' THEN 'CELLESTA - iEX'
         WHEN MODEL = 'CERTAS' THEN 'Certas LEAGA'
         WHEN MODEL = 'FILTER STATION' THEN 'CT - FPR'
         WHEN MODEL = 'WIS' THEN 'CT - WIS'
         WHEN MODEL = 'EP1 (EPISODE 1)' THEN 'EP1 - SD'
         WHEN MODEL = 'EXIM - IGZO' THEN 'EXIM'
         WHEN MODEL = 'NGT' THEN 'LITHIUS'
         WHEN MODEL = 'PRO-AP' THEN 'LITHIUS Pro AP'
         WHEN MODEL = 'PRO-DICE' THEN 'LITHIUS Pro DICE'
         WHEN MODEL = 'L-PRO V-PI' THEN 'LITHIUS Pro V-PI'
         WHEN MODEL = 'PROZ+BOW WAFER' THEN 'LITHIUS Pro Z + BOW'
         WHEN MODEL = 'CELLESTAINS300Z' THEN 'NS300Z'
         WHEN MODEL = 'PRECIO V93000' THEN 'Precio'
         WHEN MODEL = 'PREXA V93K' THEN 'Prexa'
         WHEN MODEL = 'SC CO2' THEN 'SPS - SCD'
         WHEN MODEL = 'FORMULA' THEN 'TELFORMULA'
         WHEN MODEL = 'MRT' THEN 'TPS - MRT'
         WHEN MODEL = 'TTT4 FRAME' THEN 'TS'
         ELSE MODEL
         END AS TEL_MODEL
  , FACT.ENTITY
  , FACT.ENTITY_LEFT_3 
  , FACT.CEID
  , FACT.PROCESS
  , FACT.ORIGIN_SITE
  , FACT.ORIGIN_ENTITY
  , LEFT(FACT.ORIGIN_ENTITY, 3) AS ORIGIN_ENTITY_LEFT_3
  , FACT.CK_DESCRIPTION 
  , FACT.BATCH 
  , FACT.FUNCTIONAL_AREA 
  , FACT.LIFE
 FROM SOURCE_DATA FACT
 LEFT JOIN BU_LOOKUP_SOURCE_REF DIM_BU ON
 FACT.ENTITY_LEFT_3 = UPPER(LEFT(DIM_BU.MATCH_VALUE, 3))
)

,TYPE_DATA as (
    SELECT DISTINCT
          CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        , CAST(ID AS VARCHAR(16777216)) AS ID
        , CAST(MANUFACTURER_NAME AS VARCHAR(16777216)) AS MANUFACTURER_NAME
        , CAST(MANUFACTURER_NUMBER AS VARCHAR(16777216)) AS MANUFACTURER_NUMBER
        , CAST(BUSINESS_UNIT AS VARCHAR(16777216)) AS BUSINESS_UNIT
        , CAST(BUSINESS_UNIT_SHORT_TEXT AS VARCHAR(16777216)) AS BUSINESS_UNIT_SHORT_TEXT
        , CAST(EVENT_TYPE AS VARCHAR(16777216)) AS EVENT_TYPE
        , CAST(BUILDING AS VARCHAR(16777216)) AS BUILDING 
        , CAST(SITE AS VARCHAR(16777216)) AS SITE
        , CAST(MODEL AS VARCHAR(16777216)) AS MODEL
        , CAST(TEL_MODEL AS VARCHAR(16777216)) AS TEL_MODEL
        , CAST(ENTITY AS VARCHAR(16777216)) AS ENTITY
        , CAST(ENTITY_LEFT_3 AS VARCHAR(16777216)) AS ENTITY_LEFT_3
        , CAST(CEID AS VARCHAR(16777216)) AS CEID
        , CAST(PROCESS AS VARCHAR(16777216)) AS PROCESS
        , CAST(ORIGIN_SITE AS VARCHAR(16777216)) AS ORIGIN_SITE
        , CAST(ORIGIN_ENTITY AS VARCHAR(16777216)) AS ORIGIN_ENTITY 
        , CAST(ORIGIN_ENTITY_LEFT_3 AS VARCHAR(16777216)) AS ORIGIN_ENTITY_LEFT_3 
        , CAST(CK_DESCRIPTION AS VARCHAR(16777216)) AS CK_DESCRIPTION 
        , CAST(BATCH AS VARCHAR(16777216)) AS BATCH
        , CAST(FUNCTIONAL_AREA AS VARCHAR(16777216)) AS FUNCTIONAL_AREA
        , CAST(LIFE AS VARCHAR(16777216)) AS LIFE 
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
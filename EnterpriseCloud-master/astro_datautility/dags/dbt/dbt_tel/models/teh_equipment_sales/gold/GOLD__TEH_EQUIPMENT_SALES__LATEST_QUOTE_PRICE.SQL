{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='LATEST_QUOTE_PRICE',
      transient=false
) }}

WITH STEP_ONE
AS (
	SELECT DISTINCT QUOTE_ID,
		  CASE 
			WHEN CATEGORY = 'CK'
				THEN 'CK'
			WHEN CATEGORY = 'MOD'
				THEN 'OTHER'
			WHEN CATEGORY = 'MT'
				THEN 'MT'  
			WHEN CATEGORY = 'OTHER'
				THEN 'OTHER'
			WHEN CATEGORY = 'PKD'
				THEN 'PKD'
			WHEN CATEGORY = 'SERVICE'
				THEN 'OTHER'
			ELSE 'OTHER'
			END AS CATEGORY,
		MODEL,
		QUOTE_AMT,
		TO_DATE(LATEST_QUOTE_STATUS_DATE) AS LATEST_QUOTE_STATUS_DATE,
		  CAST(Y.VALUE AS VARCHAR(16777216)) AS NEW_TEL_QUOTE_NODE_PROCESS
	FROM {{ ref('SILVER__TEH_EQUIPMENT_SALES__QUOTE_ACTION_LIFECYCLE') }},
		LATERAL FLATTEN(INPUT => SPLIT(TEL_QUOTE_NODE_PROCESS, '|')) Y
	WHERE TEL_QUOTE_NODE_PROCESS IS NOT NULL
	),
STEP_TWO
AS (
	SELECT QUOTE_ID,
		CATEGORY,
		MODEL,
		QUOTE_AMT,
		LATEST_QUOTE_STATUS_DATE,
		NEW_TEL_QUOTE_NODE_PROCESS,
		RTRIM(substring(NEW_TEL_QUOTE_NODE_PROCESS, 0, REGEXP_INSTR(NEW_TEL_QUOTE_NODE_PROCESS, ':')), ':') AS PROCESS,
		LTRIM(substring(NEW_TEL_QUOTE_NODE_PROCESS, REGEXP_INSTR(NEW_TEL_QUOTE_NODE_PROCESS, ':')), ':') AS NEW_TEL_QUOTE_NODE
	FROM STEP_ONE
	),
 STEP_THREE
AS (
	SELECT QUOTE_ID,
		CATEGORY,
		MODEL,
		QUOTE_AMT,
		LATEST_QUOTE_STATUS_DATE,
		PROCESS,
		CAST(Z.VALUE AS VARCHAR(16777216)) AS CEID
	FROM STEP_TWO,
		LATERAL FLATTEN(INPUT => SPLIT(NEW_TEL_QUOTE_NODE, ',')) Z
	),
source_data
AS (
SELECT  QUOTE_ID,
		CATEGORY,
		MODEL,
		QUOTE_AMT,
		LATEST_QUOTE_STATUS_DATE,
		PROCESS,
		CEID,
	  CASE 
		WHEN CATEGORY = 'CK'
			THEN NULL
		ELSE CATEGORY || '-' || UPPER(CEID) || '-' || PROCESS
		END AS QUOTE_SEARCH_KEY,
		'{{ invocation_id }}' AS _AUDIT_LOG_ID
FROM STEP_THREE
	),
transform_data
AS (
SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        QUOTE_ID,
        CATEGORY,
        MODEL,
        QUOTE_AMT,
        LATEST_QUOTE_STATUS_DATE,
        PROCESS,
        CEID,
        QUOTE_SEARCH_KEY
FROM source_data
	),
type_data
AS (
	SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(QUOTE_ID AS VARCHAR(16777216)) AS QUOTE_ID,
        CAST(CATEGORY AS  VARCHAR(16777216)) AS CATEGORY,
        CAST(MODEL AS  VARCHAR(16777216)) AS MODEL,
        CAST(QUOTE_AMT AS  NUMBER(38,0)) AS QUOTE_AMT,
        CAST(LATEST_QUOTE_STATUS_DATE AS  DATE) AS LATEST_QUOTE_STATUS_DATE,
        CAST(PROCESS AS  VARCHAR(16777216)) AS PROCESS,
        CAST(CEID AS  VARCHAR(16777216)) AS CEID,
        CAST(QUOTE_SEARCH_KEY AS  VARCHAR(16777216)) AS QUOTE_SEARCH_KEY
from transform_data
	)
SELECT *
FROM type_data
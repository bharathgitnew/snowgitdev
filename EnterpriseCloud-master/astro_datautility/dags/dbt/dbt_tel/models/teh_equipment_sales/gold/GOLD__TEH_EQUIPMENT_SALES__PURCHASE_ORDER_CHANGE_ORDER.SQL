amt_churn
AS (
	SELECT DISTINCT PURCHASE_ORDER_LINE_ID,
		CASE 
			WHEN COUNT(DISTINCT TOTAL_AMOUNT) > 1
				THEN 1
			WHEN COUNT(DISTINCT TOTAL_AMOUNT) = 1
				THEN 0
			END AS IS_TOTAL_AMT_CHURN
	FROM purchase_order_change_order_src
	GROUP BY 1
	),

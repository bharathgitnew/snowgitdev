      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='SIRFIS_ITEM_HIERARCHY',
      transient=false
) }}

with source_data AS (
    SELECT DISTINCT
        ID AS ID,
        BUSINESS_UNIT AS BUSINESS_UNIT,
        BUSINESS_UNIT_SHORT_TEXT AS BUSINESS_UNIT_SHORT_TEXT,
        SITE AS SITE,
        CATEGORY AS CATEGORY,
        UEID AS UEID,
        MODEL AS MODEL,
        COPY_EXACT_ID AS CEID,
        ENTITY AS ENTITY,
        PROCESS AS PROCESS,
        REUSE_SITE AS REUSE_SITE,
        REUSE_CEID AS REUSE_CEID,
        REUSE_PROCESS AS REUSE_PROCESS,
        CASE WHEN IS_PART_ORDER = 'Yes' THEN 1 ELSE 0 END AS IS_PART_ORDER,
        DESCRIPTION AS DESCRIPTION
    FROM {{ ref('GOLD__TEH_EQUIPMENT_SALES__FORECAST_HISTORY') }}
    WHERE REVISION_DESC_ORDER = 1
),

transform_data AS
(   
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        ID AS ID,
        BUSINESS_UNIT AS BUSINESS_UNIT,
        BUSINESS_UNIT_SHORT_TEXT AS BUSINESS_UNIT_SHORT_TEXT,
        CASE WHEN ENTITY = 'PXT403' THEN 'PVD'
        WHEN LEFT(ENTITY, 3) in ('BEC', 'CAR', 'CAT', 'CFS', 'OXS', 'OXT', 'SRT', 'ACT', 'CCT', 'CLE',
        'DEV', 'GCT', 'PEB', 'RCT', 'RPD', 'SLM', 'SOX', 'SXD', 'TAK', 'TAN', 'TBH', 'TBJ', 'TBR',
        'TCX', 'TNI', 'TTA', 'TTB', 'TTC', 'TTG', 'TTK', 'ZSK', 'ZTE') THEN 'FS'
        ELSE BUSINESS_UNIT_SHORT_TEXT END AS UNIVERSAL_BU,
        SITE AS SITE,
        CATEGORY AS CATEGORY,
        MODEL AS MODEL,
        CEID AS CEID,
        ENTITY AS ENTITY,
        PROCESS AS PROCESS,
        REUSE_SITE AS REUSE_SITE,
        REUSE_CEID AS REUSE_CEID,
        REUSE_PROCESS AS REUSE_PROCESS,
        IS_PART_ORDER AS IS_PART_ORDER,
        DESCRIPTION AS DESCRIPTION
FROM source_data
)

,type_data as (
    SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        CAST(ID AS VARCHAR(16777216)) AS ID,
        CAST(BUSINESS_UNIT AS VARCHAR(16777216)) AS BUSINESS_UNIT,
        CAST(BUSINESS_UNIT_SHORT_TEXT AS VARCHAR(16777216)) AS BUSINESS_UNIT_SHORT_TEXT,
        CAST(UNIVERSAL_BU AS VARCHAR(16777216)) AS UNIVERSAL_BU,
        CAST(SITE AS VARCHAR(16777216)) AS SITE,
        CAST(CATEGORY AS VARCHAR(16777216)) AS CATEGORY,
        CAST(MODEL AS VARCHAR(16777216)) AS MODEL,
        CAST(CEID AS VARCHAR(16777216)) AS CEID,
        CAST(ENTITY AS VARCHAR(16777216)) AS ENTITY,
        CAST(PROCESS AS VARCHAR(16777216)) AS PROCESS,
        CAST(REUSE_SITE AS VARCHAR(16777216)) AS REUSE_SITE,
        CAST(REUSE_CEID AS VARCHAR(16777216)) AS REUSE_CEID,
        CAST(REUSE_PROCESS AS VARCHAR(16777216)) AS REUSE_PROCESS,
        CAST(IS_PART_ORDER AS NUMBER(1,0)) AS IS_PART_ORDER,
        CAST(DESCRIPTION AS VARCHAR(16777216)) AS DESCRIPTION
FROM transform_data
)

SELECT * from type_data
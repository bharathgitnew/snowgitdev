    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='TEL_SALES_CRM_DATA_AUDIT_REPORT_BOOKING_LOANER_CURRENT_HALF_NEXT_HALF',
    transient=false
) }}

WITH
SOURCE_DATA AS (

select
    SALES_ACCOUNT,
    END_USER,
    FAB                                     as FAB_LINE,
    SUB_BU                                  as PRODUCT_SUB_BU,
    SALES_REPORTING_FLAG                    as SALES_REPORTING,
    IS_PLACEHOLDER                          as BU_PLACEHOLDER,
    SALES_CATEGORY,
    ORDER_ITEM,
    OPPORTUNITY_TITLE_FREE_TEXT,
    MODEL,
    OPPORTUNITY_ID,
    PROJECT_NO,
    SALES_ORDER_NO                          as SO_NO,
    Customer_Forecast_ID,
    SERIAL_NO,
    CUSTOMER_TOOL_ID,
    BOOKING_CONFIDENCE_BU,
    BOOKING_CONFIDENCE_ACCOUNT,
    ACCOUNT_BOOKING_FY_HALF                 as ACCOUNT_FY_HALF,
    CORPORATE_BU_BOOKING_FY_HALF            as BU_FY_HALF,
    IS_BOOKING_ACTUAL                       as END_USER_BOOKING_DATE_ACTUAL,
    END_USER_BOOKING_DATE_BU,
    END_USER_BOOKING_DATE_ACCOUNT,
    PO_Receipt_Date,
    SHIP_DATE,
    IS_LOANER                               as LOANER,
    LOAN_EXPIRATION_DATE                    as LOANER_EXPIRY_DATE,
    ACCOUNT_COMMENTS,
    BU_COMMENTS,
    BOOKING_CURRENCY,
    BOOKING_AMOUNT,
    END_USER_BOOKING_AMOUNT_JPY,
    VPA,
    QUOTE_NO, 
    PURCHASE_ORDER_NO                       as PO_NO,
    ACCOUNT_SALES_PERSON                    as SALES_PERSON_ACCOUNT,    
    BU_SALES_PERSON                         as SALES_PERSON_BU,
    Sales_Comments_to_SAP                   as SALES_COMMENTS_CRM_SAP,
    Assistants_Comments_from_SAP            as ASSISTANTS_COMMENTS_SAP_CRM,  
    OPPORTUNITY_TITLE,
    CRM_URL,
    DATA_SNAPSHOT,
    DATA_SNAPSHOT_TIMESTAMP,
    BOOKING_CONFIDENCE_ACCOUNT              as Update_Check_Confidence,
    END_USER_BOOKING_DATE_ACCOUNT           as Update_Check_Booking_Date
from {{ ref('GOLD__TEH_EQUIPMENT_SALES__SALES_CRM_OPPORTUNITIES') }}
where ((END_USER_BOOKING_DATE_BU >= BEGINNING_OF_CURRENT_FY_HALF and END_USER_BOOKING_DATE_BU <= END_OF_NEXT_FY_HALF)
        or (END_USER_BOOKING_DATE_ACCOUNT >= BEGINNING_OF_CURRENT_FY_HALF and END_USER_BOOKING_DATE_ACCOUNT <= END_OF_NEXT_FY_HALF))
    and IS_BOOKING_ACTUAL = 'No' 
    -- and END_USER_BOOKING_AMOUNT_JPY > 0
    and SALES_ACCOUNT not ilike 'intel'
    and IS_LOANER = 'Yes'
    and (CONFIDENCE_ACCOUNT_SHORT not in ('G', 'L')
        or CONFIDENCE_ACCOUNT_SHORT is null)
    -- and (CONFIDENCE_BU_SHORT NOT IN ('D', 'G', 'L', '--') 
    --     or CONFIDENCE_BU_SHORT IS NOT NULL))
),
TRANSFORM_DATA AS (
SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        SALES_ACCOUNT,
        END_USER,
        FAB_LINE,
        PRODUCT_SUB_BU,
        SALES_REPORTING,
        BU_PLACEHOLDER,
        SALES_CATEGORY,
        ORDER_ITEM,
        OPPORTUNITY_TITLE_FREE_TEXT,
        MODEL,
        OPPORTUNITY_ID,
        PROJECT_NO,
        SO_NO,
        CUSTOMER_FORECAST_ID,
        SERIAL_NO,
        CUSTOMER_TOOL_ID,
        BOOKING_CONFIDENCE_BU,
        BOOKING_CONFIDENCE_ACCOUNT,
        ACCOUNT_FY_HALF,
        BU_FY_HALF,
        END_USER_BOOKING_DATE_ACTUAL,
        END_USER_BOOKING_DATE_BU,
        END_USER_BOOKING_DATE_ACCOUNT,
        PO_RECEIPT_DATE,
        SHIP_DATE,
        LOANER,
        LOANER_EXPIRY_DATE,
        ACCOUNT_COMMENTS,
        BU_COMMENTS,
        BOOKING_CURRENCY,
        BOOKING_AMOUNT,
        END_USER_BOOKING_AMOUNT_JPY,
        VPA,
        QUOTE_NO,
        PO_NO,
        SALES_PERSON_ACCOUNT,
        SALES_PERSON_BU,
        SALES_COMMENTS_CRM_SAP,
        ASSISTANTS_COMMENTS_SAP_CRM,
        OPPORTUNITY_TITLE,
        CRM_URL,
        DATA_SNAPSHOT,
        DATA_SNAPSHOT_TIMESTAMP,
        UPDATE_CHECK_CONFIDENCE,
        UPDATE_CHECK_BOOKING_DATE
FROM SOURCE_DATA

)

,
TYPE_DATA AS (
SELECT
        cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
        SALES_ACCOUNT,
        END_USER,
        FAB_LINE,
        PRODUCT_SUB_BU,
        SALES_REPORTING,
        BU_PLACEHOLDER,
        SALES_CATEGORY,
        ORDER_ITEM,
        OPPORTUNITY_TITLE_FREE_TEXT,
        MODEL,
        OPPORTUNITY_ID,
        PROJECT_NO,
        SO_NO,
        CUSTOMER_FORECAST_ID,
        SERIAL_NO,
        CUSTOMER_TOOL_ID,
        BOOKING_CONFIDENCE_BU,
        BOOKING_CONFIDENCE_ACCOUNT,
        ACCOUNT_FY_HALF,
        BU_FY_HALF,
        END_USER_BOOKING_DATE_ACTUAL,
        CAST(END_USER_BOOKING_DATE_BU as DATE) as END_USER_BOOKING_DATE_BU,
        CAST(END_USER_BOOKING_DATE_ACCOUNT as DATE) as END_USER_BOOKING_DATE_ACCOUNT,
        CAST(PO_RECEIPT_DATE as DATE) as PO_RECEIPT_DATE,
        CAST(SHIP_DATE as DATE) as SHIP_DATE,
        LOANER,
        CAST(LOANER_EXPIRY_DATE as DATE) as LOANER_EXPIRY_DATE,
        ACCOUNT_COMMENTS,
        BU_COMMENTS,
        BOOKING_CURRENCY,
        CAST(BOOKING_AMOUNT as NUMBER(38,10)) as BOOKING_AMOUNT,
        CAST(END_USER_BOOKING_AMOUNT_JPY as NUMBER(38,0)) as END_USER_BOOKING_AMOUNT_JPY,
        VPA,
        QUOTE_NO,
        PO_NO,
        SALES_PERSON_ACCOUNT,
        SALES_PERSON_BU,
        SALES_COMMENTS_CRM_SAP,
        ASSISTANTS_COMMENTS_SAP_CRM,
        OPPORTUNITY_TITLE,
        CRM_URL,
        CAST(DATA_SNAPSHOT as DATE) as DATA_SNAPSHOT,
        CAST(DATA_SNAPSHOT_TIMESTAMP as TIMESTAMP_NTZ(9)) as DATA_SNAPSHOT_TIMESTAMP,
        UPDATE_CHECK_CONFIDENCE,
        CAST(UPDATE_CHECK_BOOKING_DATE as DATE) as UPDATE_CHECK_BOOKING_DATE
FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
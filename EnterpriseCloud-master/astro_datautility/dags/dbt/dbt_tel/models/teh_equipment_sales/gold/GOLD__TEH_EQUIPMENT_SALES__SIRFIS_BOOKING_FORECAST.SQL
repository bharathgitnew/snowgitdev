with
sirfis
as
(
select *
from {{ ref('GOLD__TEH_EQUIPMENT_SALES__SIRFIS_DELIVERY_SCHEDULE') }}
where SALES_CATEGORY_TYPE ilike any ('Equipment', 'Pre-kit')
qualify row_number() over (partition by ADJUSTED_SITE, CATEGORY, ENTITY order by DATA_SNAPSHOT desc) = 1
),
sirfisflat
as
(
select * 
from {{ ref('GOLD__TEH_EQUIPMENT_SALES__SIRFIS_DELIVERY_SCHEDULE') }}
where SALES_CATEGORY_TYPE ilike any ('Equipment', 'Pre-kit')
qualify row_number() over (partition by ADJUSTED_SITE, SALES_CATEGORY_TYPE, ENTITY order by CATEGORY asc, DATA_SNAPSHOT desc) = 1
),
sirfisrollup
as
(
select distinct
    ADJUSTED_SITE,
    ENTITY,
    listagg(distinct CATEGORY, ', ') within group (order by CATEGORY asc)     as SIRFIS_CATEGORY, 
    sum(ESTIMATED_BOOKING_AMOUNT)                                             as ESTIMATED_BOOKING_AMOUNT,
    max(PO_FIRST_LISTED_DATE)                                                 as MAX_PO_FIRST_LISTED_DATE,
    listagg(PO_FIRST_LISTED_DATE, ', ') within group (order by CATEGORY asc)  as PO_FIRST_LISTED_DATE_MT_PK,
    max(RTD_BASE_BOOKING_DATE)                                                as MAX_RTD_BASE_BOOKING_DATE,
    listagg(RTD_BASE_BOOKING_DATE, ', ') within group (order by CATEGORY asc) as RTD_BASE_BOOKING_DATE_MT_PK,
    max(REQUESTED_TENDER_DATE)                                                as MAX_REQUESTED_TENDER_DATE,
    listagg(REQUESTED_TENDER_DATE, ', ') within group (order by CATEGORY asc) as REQUESTED_TENDER_DATE_MT_PK,
    max(SUPPLIER_TENDER_DATE)                                                 as MAX_SUPPLIER_TENDER_DATE,
    listagg(SUPPLIER_TENDER_DATE, ', ') within group (order by CATEGORY asc)  as SUPPLIER_TENDER_DATE_MT_PK,
    listagg(RECORD_CREATED_DATE, ', ') within group (order by CATEGORY asc)   as RECORD_CREATED_DATE_MT_PK,
    listagg(DATA_SNAPSHOT, ', ') within group (order by CATEGORY asc)         as DATA_SNAPSHOT_MT_PK,
    max(SIRFIS_RELEASED_DATE)                                                 as MAX_SIRFIS_RELEASED_DATE,
    listagg(SIRFIS_RELEASED_DATE, ', ') within group (order by CATEGORY asc)  as SIRFIS_RELEASED_DATE_MT_PK,
    listagg(FORECAST_ID, ', ') within group (order by CATEGORY asc)           as SIRFIS_FORECAST_ID,
    listagg(TOOL_PROCUREMENT_ID, ', ') within group (order by CATEGORY asc)   as TOOL_PROCUREMENT_ID,
    listagg(UNIQUE_EQUIPMENT_ID, ', ') within group (order by CATEGORY asc)   as UNIQUE_EQUIPMENT_ID,
    listagg(COPY_EXACT_ID, ', ') within group (order by CATEGORY asc)         as COPY_EXACT_ID,
    listagg(distinct FORECAST_KEY)                                            as FORECAST_KEY
from sirfis
group by ADJUSTED_SITE, SALES_CATEGORY_TYPE, ENTITY
-- having max(REQUESTED_TENDER_DATE) >= '4/1/2024'
),
SOURCE_DATA AS (
    select 
      rollup.SIRFIS_FORECAST_ID,
      rollup.TOOL_PROCUREMENT_ID,
      rollup.UNIQUE_EQUIPMENT_ID,
      rollup.COPY_EXACT_ID,
      'Intel'                 as END_USER,
      flat.AREA,
      flat.SITE,
      rollup.ADJUSTED_SITE,
      flat.SUB_BU,
      flat.SALES_CATEGORY_TYPE,
      rollup.SIRFIS_CATEGORY  as CATEGORY,
      rollup.ENTITY,
      flat.SUPPLIER_MAP,
      flat.MODEL_QUOTE_NO,
      flat.DESCRIPTION,
      flat.PROCESS,
      flat.PO_NO,
      flat.PO_LINE_ITEM_NO,
      flat.PO_NO_LINE_ITEM_NO,
      rollup.MAX_PO_FIRST_LISTED_DATE,
      rollup.PO_FIRST_LISTED_DATE_MT_PK,
      rollup.MAX_RTD_BASE_BOOKING_DATE,
      rollup.RTD_BASE_BOOKING_DATE_MT_PK,
      flat.IS_PO_RELEASED,
      rollup.MAX_REQUESTED_TENDER_DATE,
      rollup.REQUESTED_TENDER_DATE_MT_PK,
      rollup.MAX_SUPPLIER_TENDER_DATE,
      rollup.SUPPLIER_TENDER_DATE_MT_PK,
      flat.BOOKING_CURRENCY,
      rollup.ESTIMATED_BOOKING_AMOUNT,
      rollup.RECORD_CREATED_DATE_MT_PK,
      rollup.DATA_SNAPSHOT_MT_PK,
      rollup.MAX_SIRFIS_RELEASED_DATE,
      rollup.SIRFIS_RELEASED_DATE_MT_PK,
      rollup.FORECAST_KEY,
      DateSirfis.fiscal_year_short_text                               as SIRFIS_Booking_FY, 
      DateSirfis.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT_ALT                 as SIRFIS_Booking_FY_Half,
      DateSirfis.fiscal_year_quarter_short_text                       as SIRFIS_Booking_FY_Q,
      to_date(DateSirfis.fiscal_year_beginning_date)                  as SIRFIS_Booking_Beginning_of_FY,
      to_date(DateSirfis.fiscal_year_ending_date)                     as SIRFIS_Booking_End_of_FY,
      to_date(DateSirfis.fiscal_half_year_beginning_date)             as SIRFIS_Booking_Beginning_of_FY_Half,
      to_date(DateSirfis.fiscal_half_year_ending_date)                as SIRFIS_Booking_End_of_FY_Half,
      to_date(DateSirfis.fiscal_quarter_beginning_date)               as SIRFIS_Booking_Beginning_of_FY_Q,
      to_date(DateSirfis.fiscal_quarter_ending_date)                  as SIRFIS_Booking_End_of_FY_Q,
      DateCurrent.FISCAL_YEAR_BEGINNING_DATE                          as Beginning_of_Current_FY,
      DateCurrent.FISCAL_YEAR_ENDING_DATE                             as End_of_Current_FY,
  	  DateCurrent.FISCAL_HALF_YEAR_BEGINNING_DATE                     as Beginning_of_Current_FY_Half,
  	  DateCurrent.FISCAL_HALF_YEAR_ENDING_DATE                        as End_of_Current_FY_Half,
  	  DateCurrent.FISCAL_QUARTER_BEGINNING_DATE                       as Beginning_of_Current_FY_Q,
  	  DateCurrent.FISCAL_QUARTER_ENDING_DATE                          as End_of_Current_FY_Q,
  	  dateadd(year, 1, Beginning_of_Current_FY)                       as Beginning_of_Next_FY,
  	  dateadd(year, 1, End_of_Current_FY)                             as End_of_Next_FY,
  	  dateadd(month, 6, Beginning_of_Current_FY_Half)                 as Beginning_of_Next_FY_Half,
  	  dateadd(day, -1, dateadd(year, 1, Beginning_of_Current_FY_Half)) as End_of_Next_FY_Half,
  	  dateadd(month, 3, Beginning_of_Current_FY_Q)                    as Beginning_of_Next_FY_Q,
  	  dateadd(day, -1, dateadd(month, 6, Beginning_of_Current_FY_Q))  as End_of_Next_FY_Q,
      dateadd(year, -1, Beginning_of_Current_FY)                      as Beginning_of_Previous_FY,
  	  dateadd(year, -1, End_of_Current_FY)                            as End_of_Previous_FY,
  	  dateadd(month, -6, Beginning_of_Current_FY_Half)                as Beginning_of_Previous_FY_Half,
  	  dateadd(day, -1, Beginning_of_Current_FY_Half)                  as End_of_Previous_FY_Half,
  	  dateadd(month, -3, Beginning_of_Current_FY_Q)                   as Beginning_of_Previous_FY_Q,
  	  dateadd(day, -1, Beginning_of_Current_FY_Q)                     as End_of_Previous_FY_Q,
  	  dateadd(year, -2, Beginning_of_Current_FY)                      as Beginning_of_2_FY_Ago,
  	  dateadd(year, 2, End_of_Current_FY)                             as End_of_2_FY_Ahead,
      rollup.MAX_RTD_BASE_BOOKING_DATE                                as SIRFIS_Booking_Forecast_FK_Date
    from sirfisrollup rollup
    left outer join sirfisflat flat on flat.FORECAST_KEY = rollup.FORECAST_KEY
    left outer join {{ source('STATIC_OBJECTS', 'CALENDARDATE') }} DateSirfis on DateSirfis.calendar_date = rollup.MAX_RTD_BASE_BOOKING_DATE
    left outer join {{ source('STATIC_OBJECTS', 'CALENDARDATE') }} DateCurrent on DateCurrent.calendar_date = current_date()
),

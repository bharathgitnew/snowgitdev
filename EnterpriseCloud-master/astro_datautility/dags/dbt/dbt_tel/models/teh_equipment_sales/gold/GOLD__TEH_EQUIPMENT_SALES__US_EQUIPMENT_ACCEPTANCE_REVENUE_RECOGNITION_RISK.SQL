(
select *
from {{ ref('SILVER__TEH_EQUIPMENT_SALES__SIRFIS_TOOL_INSTALLATION_SCHEDULE') }}
where not SITE like any ('F24', 'F28', 'F68') 
qualify row_number() over (partition by ENTITY_CODE order by _APPENDEDDATE desc) = 1
),
SOURCE_DATA AS (
SELECT 
    risk.*, 
    tis.SUPPLIER_QUAL_FINISH, 
    tis.MRCL_FINISH,
    tis._APPENDEDDATE        as SIRFIS_TIS_APPENDED
FROM AllRisk risk
left outer join SIRFIS_TIS tis on tis.ENTITY_CODE = risk.CUSTOMER_TOOL_ID
WHERE Adjusted_Serial_No IS NOT NULL
    AND Adjusted_Serial_No <> ''
    AND Adjusted_Serial_No NOT ILIKE 'TBD' 
    AND Adjusted_Serial_No NOT ILIKE 'NONE'
    AND Adjusted_Serial_No <> '0'
	AND SALES_ACCOUNT <> 'N/A'
),

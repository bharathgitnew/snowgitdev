    {{ config(
            materialized='tel_incremental',
            incremental_strategy='insert_overwrite',
            alias='GBOMREPORTS_CP',
            unique_key=[],
            transient=false
) }}

    with source_data as (
        SELECT
            _FILEDATE,
            _FILENAME,
            _UPLOADDATE,
            CP,
            CP_STATUS,
            CLASS_OF_CHANGE,
            CORRESPONDING_CP_NO,
            TITLE,
            DATE_OF_ISSUE,
            CHANGE_CATEGORY,
            CHANGE_CATEGORY_OTHER_DETAIL,
            REASON_TML_INFO,
            OPEN_DATE,
            PRICE_CHANGED,
            PN_CHANGED,
            AFFECTED_PART,
            EXISTING_TOOLS,
            SPARE_PARTS_IN_STOCK,
            PRIORITY,
            EVALUATION,
            REQUIRE_SOME_MODIFICATIONS,
            AFFECTED_PART_SPARE,
            AFFECTED_PART_FIXTURE,
            AFFECTED_PART_SOFTWARE,
            INPUT_TITLE,
            ECP_NO,
            SUPPLIER_NO
        FROM {{ source('ADS', 'GBOMREPORTS_CP') }}
        WHERE _UPLOADDATE = (SELECT MAX(_UPLOADDATE) FROM {{ source('ADS', 'GBOMREPORTS_CP') }})
    ),
    transform_data as (
        SELECT
            _FILEDATE,
            _FILENAME,
            _UPLOADDATE,
            '{{ invocation_id }}' AS _AUDIT_LOG_ID,
            SHA2('hash_me') as _ROW_HASH,
            CP,
            CP_STATUS,
            CLASS_OF_CHANGE,
            CORRESPONDING_CP_NO,
            TITLE,
            DATE_OF_ISSUE,
            CHANGE_CATEGORY,
            CHANGE_CATEGORY_OTHER_DETAIL,
            REASON_TML_INFO,
            OPEN_DATE,
            PRICE_CHANGED,
            PN_CHANGED,
            AFFECTED_PART,
            EXISTING_TOOLS,
            SPARE_PARTS_IN_STOCK,
            PRIORITY,
            EVALUATION,
            REQUIRE_SOME_MODIFICATIONS,
            AFFECTED_PART_SPARE,
            AFFECTED_PART_FIXTURE,
            AFFECTED_PART_SOFTWARE,
            INPUT_TITLE,
            ECP_NO,
            SUPPLIER_NO
        FROM source_data
    ),
    type_data as (
        SELECT
            CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
            CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
            CAST(_UPLOADDATE AS TIMESTAMP_NTZ(9)) AS _UPLOADDATE,
            CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
            CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
            CP,
            CP_STATUS,
            CLASS_OF_CHANGE,
            CORRESPONDING_CP_NO,
            TITLE,
            DATE_OF_ISSUE,
            CHANGE_CATEGORY,
            CHANGE_CATEGORY_OTHER_DETAIL,
            REASON_TML_INFO,
            OPEN_DATE,
            PRICE_CHANGED,
            PN_CHANGED,
            AFFECTED_PART,
            EXISTING_TOOLS,
            SPARE_PARTS_IN_STOCK,
            PRIORITY,
            EVALUATION,
            REQUIRE_SOME_MODIFICATIONS,
            AFFECTED_PART_SPARE,
            AFFECTED_PART_FIXTURE,
            AFFECTED_PART_SOFTWARE,
            INPUT_TITLE,
            ECP_NO,
            SUPPLIER_NO
        FROM transform_data
    )
    SELECT * FROM type_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy = 'merge',
        alias = 'CONSIGNMENT_TRANSACTION',
        unique_key = ['MESSAGE_ID',
     'ROSETTANET_LINE_NUMBER'],
        transient = false
) }}

with source_data as
(
    SELECT
        MESSAGE_ID,
        MESSAGE_LINE_NBR,
        ITEM_CODE,
        CUSTOMER_ITEM_CODE,
        CUSTOMER_ITEM_DESC,
        QTY,
        CUSTOMER_CONSUMABLE,
        PROCESSED,
        RECONCILED,
        CUSTOMER_STOCKROOM,
        WAREHOUSE,
        CUSTOMER_TRANS_TYPE,
        CUSTOMER_TRANS_REASON,
        BAAN_ORDER_ORIGIN,
        BAAN_ORDER_NBR,
        BAAN_ORDER_LINE_NBR,
        GMT_CONSUMPTION_DT,
        MESSAGE_DT,
        CONTACT,
        CONTACT_PHONE,
        ERROR_MESSAGE,
        CUSTOMER_FACTORY,
        ERROR,
        SERIAL_NBR,
        CUSTOMER_SERIAL_NBR,
        PROCESS_DT,
        CUSTOMER_TRANS_ID,
        CUSTOMER_TRANS_LINE_NBR,
        NCDR_NBR,
        PIP,
        CUSTOMER_REF_1,
        DISPOSITION,
        SALES_ORG,
        SALES_UNIT,
        CURRENCY,
        _Filedate
        FROM {{ ref('BRONZE__TEA_GCE_AFS__ROSETTA_CONSIGNMENT_TRANSACTION') }}
        WHERE  _FileDate > IFNULL((SELECT MAX(SNOWFLAKE_REFRESH_DATE) FROM {{ this }}),'1970-01-01')
)

,transform_data as
(
    SELECT
        MESSAGE_ID AS MESSAGE_ID,
        MESSAGE_LINE_NBR AS ROSETTANET_LINE_NUMBER,
        ITEM_CODE AS TEL_PART_NUMBER,
        CUSTOMER_ITEM_CODE AS CUSTOMER_PART_NUMBER,
        CUSTOMER_ITEM_DESC AS CUSTOMER_PART_DESCRIPTION,
        QTY AS QUANTITY,
        CUSTOMER_CONSUMABLE AS CONSUMABLE_FLAG,
        PROCESSED AS TRANSFERRED_FLAG,
        RECONCILED AS RECONCILED_FLAG,
        CUSTOMER_STOCKROOM AS STOCK_ROOM,
        WAREHOUSE AS WAREHOUSE,
        CUSTOMER_TRANS_TYPE AS TRANSACTION_TYPE,
        CUSTOMER_TRANS_REASON AS TRANSACTION_REASON,
        BAAN_ORDER_ORIGIN AS ORDER_ORIGIN,
        BAAN_ORDER_NBR AS SERVICE_ORDER_NUMBER,
        BAAN_ORDER_LINE_NBR AS POSITION_NUMBER,
        GMT_CONSUMPTION_DT AS DATE_CONSUMED,
        MESSAGE_DT AS DATE_RECEIVED,
        CONTACT AS CONTACT_NAME,
        CONTACT_PHONE AS CONTACT_PHONE,
        ERROR_MESSAGE AS ERROR_MESSAGE,
        CUSTOMER_FACTORY AS FACTORY_NAME,
        ERROR AS ERROR_FLAG,
        SERIAL_NBR AS TEL_SERIAL_NUMBER,
        CUSTOMER_SERIAL_NBR AS INTEL_SERIAL_NUMBER,
        PROCESS_DT AS TRANSFERRED_DATE,
        CUSTOMER_TRANS_ID AS CUSTOMER_TRANSACTION_ID,
        CUSTOMER_TRANS_LINE_NBR AS CUSTOMER_TRANSACTION_LINE_ID,
        NCDR_NBR AS NCDR_NUMBER,
        PIP AS ROSETTANET_PIP,
        CUSTOMER_REF_1 AS WIINGS_ISSUE_ID,
        DISPOSITION AS DISPOSITION,
        SALES_ORG AS SALES_ORG,
        SALES_UNIT AS SALES_UNIT,
        CURRENCY AS CURRENCY,
        _Filedate as SNOWFLAKE_REFRESH_DATE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    FROM source_data
)

,type_data as
(
    SELECT
        CAST(MESSAGE_ID AS VARCHAR(16777216)) AS MESSAGE_ID,
        CAST(ROSETTANET_LINE_NUMBER AS NUMBER(38,0)) AS ROSETTANET_LINE_NUMBER,
        CAST(TEL_PART_NUMBER AS VARCHAR(16777216)) AS TEL_PART_NUMBER,
        CAST(CUSTOMER_PART_NUMBER AS VARCHAR(16777216)) AS CUSTOMER_PART_NUMBER,
        CAST(CUSTOMER_PART_DESCRIPTION AS VARCHAR(16777216)) AS CUSTOMER_PART_DESCRIPTION,
        CAST(QUANTITY AS NUMBER(38,0)) AS QUANTITY,
        CAST(CONSUMABLE_FLAG AS NUMBER(2,0)) AS CONSUMABLE_FLAG,
        CAST(TRANSFERRED_FLAG AS NUMBER(2,0)) AS TRANSFERRED_FLAG,
        CAST(RECONCILED_FLAG AS NUMBER(2,0)) AS RECONCILED_FLAG,
        CAST(STOCK_ROOM AS VARCHAR(16777216)) AS STOCK_ROOM,
        CAST(WAREHOUSE AS VARCHAR(16777216)) AS WAREHOUSE,
        CAST(TRANSACTION_TYPE AS VARCHAR(16777216)) AS TRANSACTION_TYPE,
        CAST(TRANSACTION_REASON AS VARCHAR(16777216)) AS TRANSACTION_REASON,
        CAST(ORDER_ORIGIN AS NUMBER(38,0)) AS ORDER_ORIGIN,
        CAST(SERVICE_ORDER_NUMBER AS VARCHAR(16777216)) AS SERVICE_ORDER_NUMBER,
        CAST(POSITION_NUMBER AS NUMBER(38,0)) AS POSITION_NUMBER,
        CAST(DATE_CONSUMED AS TIMESTAMP_NTZ(9)) AS DATE_CONSUMED,
        CAST(DATE_RECEIVED AS TIMESTAMP_NTZ(9)) AS DATE_RECEIVED,
        CAST(CONTACT_NAME AS VARCHAR(16777216)) AS CONTACT_NAME,
        CAST(CONTACT_PHONE AS VARCHAR(16777216)) AS CONTACT_PHONE,
        CAST(ERROR_MESSAGE AS VARCHAR(16777216)) AS ERROR_MESSAGE,
        CAST(FACTORY_NAME AS VARCHAR(16777216)) AS FACTORY_NAME,
        CAST(ERROR_FLAG AS NUMBER(2,0)) AS ERROR_FLAG,
        CAST(TEL_SERIAL_NUMBER AS VARCHAR(16777216)) AS TEL_SERIAL_NUMBER,
        CAST(INTEL_SERIAL_NUMBER AS VARCHAR(16777216)) AS INTEL_SERIAL_NUMBER,
        CAST(TRANSFERRED_DATE AS TIMESTAMP_NTZ(9)) AS TRANSFERRED_DATE,
        CAST(CUSTOMER_TRANSACTION_ID AS VARCHAR(16777216)) AS CUSTOMER_TRANSACTION_ID,
        CAST(CUSTOMER_TRANSACTION_LINE_ID AS NUMBER(38,0)) AS CUSTOMER_TRANSACTION_LINE_ID,
        CAST(NCDR_NUMBER AS VARCHAR(16777216)) AS NCDR_NUMBER,
        CAST(ROSETTANET_PIP AS VARCHAR(16777216)) AS ROSETTANET_PIP,
        CAST(WIINGS_ISSUE_ID AS VARCHAR(16777216)) AS WIINGS_ISSUE_ID,
        CAST(DISPOSITION AS NUMBER(38,0)) AS DISPOSITION,
        CAST(SALES_ORG AS VARCHAR(16777216)) AS SALES_ORG,
        CAST(SALES_UNIT AS VARCHAR(16777216)) AS SALES_UNIT,
        CAST(CURRENCY AS VARCHAR(16777216)) AS CURRENCY,
        CAST(SNOWFLAKE_REFRESH_DATE AS TIMESTAMP_NTZ(9))  AS SNOWFLAKE_REFRESH_DATE,
        CAST(AUDIT_LOG_ID AS VARCHAR(128))  AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128))  AS _ROW_HASH
    FROM transform_data
)

SELECT * FROM type_data
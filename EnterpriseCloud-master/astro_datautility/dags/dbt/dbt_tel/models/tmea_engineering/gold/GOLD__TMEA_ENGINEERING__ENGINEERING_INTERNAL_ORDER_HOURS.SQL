WITH ref_cte_CATS_DATABASE_TABLE_FOR_TIME_SHEET as (
    select * from {{ ref('SILVER__TMEA_ENGINEERING__CATS_DATABASE_TABLE_FOR_TIME_SHEET') }}
),
ref_cte_ORDER_MASTER_DATA as (
    select * from {{ ref('SILVER__TMEA_ENGINEERING__ORDER_MASTER_DATA') }}
),
ref_cte_CALENDAR_DATE as (
    select * from {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
),
ref_cte_PRODUCTION_SUPERVISOR as (
    select * from {{ ref('SILVER__TMEA_ENGINEERING__PRODUCTION_SUPERVISOR') }}
),
TIMECARD AS(
SELECT 
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
FISCAL_HALF_YEAR_TEXT AS FISCAL_HALF_YEAR,
FISCAL_QUARTER_TEXT AS FISCAL_QUARTER,
MONTH_ABBREVIATION_TEXT AS MONTH,
MONTH_OF_FISCAL_YEAR_NUMBER,
DATE AS TIMESHEET_DATE,
PERSONNEL_NUMBER,
CATSDB.HOURS,
CATSDB.ATTENDANCE_OR_ABSENCE_TYPE,
CATSDB.MISC_ATTENDANCE_INPUTS,
T024F.DESCRIPTION_OF_PRODUCTION_SUPERVISOR,
CATSDB.RECEIVER_ORDER AS INTERNAL_ORDER_NUMBER,
AUFK.DESCRIPTION AS INTERNAL_ORDER_DESCRIPTION,
CONCAT(CATSDB.RECEIVER_ORDER,' ',AUFK.DESCRIPTION) AS INTERNAL_ORDER

FROM ref_cte_CATS_DATABASE_TABLE_FOR_TIME_SHEET CATSDB
LEFT JOIN ref_cte_ORDER_MASTER_DATA AUFK
    ON CATSDB.RECEIVER_ORDER = AUFK.ORDER_NUMBER
LEFT JOIN ref_cte_PRODUCTION_SUPERVISOR T024F
    ON CATSDB.MISC_ATTENDANCE_INPUTS = T024F.PRODUCTION_SUPERVISOR
LEFT JOIN ref_cte_CALENDAR_DATE
    ON DATE = CALENDAR_DATE

WHERE DATE BETWEEN '2020-04-01' AND CURRENT_DATE()
-- AND AUFK.ORDER_CATEGORY = '01'
-- AND AUFK.PLANT = '0010'
ORDER BY FISCAL_YEAR,MONTH_OF_FISCAL_YEAR_NUMBER 
),

SAP_EMPLOYEEID AS (
select distinct  
PA0001.PERSONNEL_NUMBER AS SAP_ID,
PA0001.FORMATTED_NAME_OF_EMPLOYEE_OR_APPLICANT AS EMPLOYEE_NAME,
PA0001.START_DATE,
PA0001.END_DATE,
PA0001.SUPERVISOR_AREA,
PA0001_S.FORMATTED_NAME_OF_EMPLOYEE_OR_APPLICANT AS SUPERVISOR_NAME
from {{ ref('SILVER__TMEA_ENGINEERING__HR_MASTER_RECORD_INFOTYPE_0001') }} PA0001
LEFT JOIN {{ ref('SILVER__TMEA_ENGINEERING__HR_MASTER_RECORD_INFOTYPE_0001') }} PA0001_S
    ON PA0001.SUPERVISOR_AREA = PA0001_S.PERSONNEL_NUMBER
order by end_date desc
),

OUTPUT AS(
SELECT * FROM TIMECARD
LEFT JOIN SAP_EMPLOYEEID 
    ON TIMECARD.PERSONNEL_NUMBER = SAP_EMPLOYEEID.SAP_ID
WHERE TIMECARD.TIMESHEET_DATE BETWEEN start_date and end_date
),
SOURCE_DATA as(
 SELECT DISTINCT
FISCAL_YEAR,
FISCAL_HALF_YEAR,
FISCAL_QUARTER,
MONTH,
MONTH_OF_FISCAL_YEAR_NUMBER,
TIMESHEET_DATE,
-- START_DATE,
-- END_DATE,
PERSONNEL_NUMBER,
EMPLOYEE_NAME,
SUPERVISOR_NAME,
ATTENDANCE_OR_ABSENCE_TYPE,
MISC_ATTENDANCE_INPUTS,
DESCRIPTION_OF_PRODUCTION_SUPERVISOR AS MISC_DESCRIPTION,
HOURS,
INTERNAL_ORDER_NUMBER,
INTERNAL_ORDER_DESCRIPTION,
INTERNAL_ORDER
FROM OUTPUT


),
TRANSFORM_DATA AS (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	FISCAL_YEAR,
	FISCAL_HALF_YEAR,
	FISCAL_QUARTER,
	MONTH,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	TIMESHEET_DATE,
	-- START_DATE,
	-- END_DATE,
	PERSONNEL_NUMBER,	
	EMPLOYEE_NAME,
	SUPERVISOR_NAME,
	ATTENDANCE_OR_ABSENCE_TYPE,
	MISC_ATTENDANCE_INPUTS,
	MISC_DESCRIPTION,
	HOURS,
	INTERNAL_ORDER_NUMBER,
	INTERNAL_ORDER_DESCRIPTION,
	INTERNAL_ORDER

FROM SOURCE_DATA
)

,
TYPE_DATA AS (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	FISCAL_YEAR,
	FISCAL_HALF_YEAR,
	FISCAL_QUARTER,
	MONTH,
	CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER,
	CAST(TIMESHEET_DATE as DATE) as TIMESHEET_DATE,
	-- START_DATE,
	-- END_DATE,
	PERSONNEL_NUMBER,	
	EMPLOYEE_NAME,
	SUPERVISOR_NAME,
	ATTENDANCE_OR_ABSENCE_TYPE,
	MISC_ATTENDANCE_INPUTS,
	MISC_DESCRIPTION,
	CAST(HOURS as NUMBER(38,10)) as HOURS,
	INTERNAL_ORDER_NUMBER,
	INTERNAL_ORDER_DESCRIPTION,
	INTERNAL_ORDER
from transform_data
)
SELECT * FROM TYPE_DATA
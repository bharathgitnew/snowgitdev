{{ config(
        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='APPROVALLOGS'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	APPROVALACTIVITYID AS APPROVALACTIVITYID,
	OPERATOR AS OPERATOR,
	OPERATORNAME AS OPERATORNAME,
	ACTION_J AS ACTION_J,
	ACTION_E AS ACTION_E,
	COMMENT AS COMMENT,
	OPERATEDAT AS OPERATEDAT,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_APPROVALLOGS') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_APPROVALLOGS') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	APPROVALACTIVITYID,
	OPERATOR,
	OPERATORNAME,
	ACTION_J,
	ACTION_E,
	COMMENT,
	OPERATEDAT
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	APPROVALACTIVITYID,
	OPERATOR,
	OPERATORNAME,
	ACTION_J,
	ACTION_E,
	COMMENT,
	OPERATEDAT
 from transform_data 
)
SELECT * from type_data
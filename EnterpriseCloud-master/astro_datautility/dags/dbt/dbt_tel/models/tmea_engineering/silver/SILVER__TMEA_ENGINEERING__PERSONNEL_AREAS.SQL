        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='PERSONNEL_AREAS',
        unique_key = ['CLIENT',
    'PERSONNEL_AREA'],
        transient=false
) }}


with source_data as (
SELECT 
    MANDT AS CLIENT,
    PERSA AS PERSONNEL_AREA,
    MOLGA AS COUNTRY_GROUPING,
    BUKRS AS COMPANY_CODE,
    NAME1 AS PERSONNEL_AREA_TEXT,
    NAME2 AS NAME_2,
    STRAS AS STREET_AND_HOUSE_NUMBER,
    PFACH AS PO_BOX,
    PSTLZ AS POSTAL_CODE,
    ORT01 AS CITY,
    LAND1 AS COUNTRY,
    REGIO AS REGION,
    COUNC AS COUNTY_CODE,
    CITYC AS CITY_CODE,
    ADRNR AS ADDRESS,
    _CAPTUREDATETIME
FROM {{ ref('BRONZE__TMEA_ENGINEERING__SAPO_PERSONNEL_AREAS') }}
),
transform_data as 
(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	CLIENT,
    PERSONNEL_AREA,
    COUNTRY_GROUPING,
    COMPANY_CODE,
    PERSONNEL_AREA_TEXT,
    NAME_2,
    STREET_AND_HOUSE_NUMBER,
    PO_BOX,
    POSTAL_CODE,
    CITY,
    COUNTRY,
    REGION,
    COUNTY_CODE,
    CITY_CODE,
    ADDRESS,
    _CAPTUREDATETIME
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	_AUDIT_LOG_ID,
	_ROW_HASH,
	CLIENT,
    PERSONNEL_AREA,
    COUNTRY_GROUPING,
    COMPANY_CODE,
    PERSONNEL_AREA_TEXT,
    NAME_2,
    STREET_AND_HOUSE_NUMBER,
    PO_BOX,
    POSTAL_CODE,
    CITY,
    COUNTRY,
    REGION,
    COUNTY_CODE,
    CITY_CODE,
    ADDRESS,
    CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
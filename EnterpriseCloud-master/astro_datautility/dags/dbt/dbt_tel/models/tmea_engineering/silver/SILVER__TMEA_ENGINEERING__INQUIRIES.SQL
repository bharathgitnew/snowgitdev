{{ config(
        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='INQUIRIES'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	QVICSID AS QVICSID,
	REPORTER AS REPORTER,
	REPORTERNAME AS REPORTERNAME,
	SUBJECT AS SUBJECT,
	INQUIRYDATE AS INQUIRYDATE,
	COMPLETIONDATE AS COMPLETIONDATE,
	LOCALCORPORATIONID AS LOCALCORPORATIONID,
	STATUSID AS STATUSID,
	CLASSIFICATIONID AS CLASSIFICATIONID,
	CREATEDAT AS CREATEDAT,
	CREATEDBY AS CREATEDBY,
	CREATEDBYNAME AS CREATEDBYNAME,
	UPDATEDAT AS UPDATEDAT,
	UPDATEDBY AS UPDATEDBY,
	UPDATEDBYNAME AS UPDATEDBYNAME,
	DELETEDAT AS DELETEDAT,
	MACHINELOGSTATUSID AS MACHINELOGSTATUSID,
	LOGSTORAGELOCATION AS LOGSTORAGELOCATION,
	PRIORITYID AS PRIORITYID,
	RELATEDQVICSIDLIST AS RELATEDQVICSIDLIST,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_INQUIRIES') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_INQUIRIES') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	QVICSID,
	REPORTER,
	REPORTERNAME,
	SUBJECT,
	INQUIRYDATE,
	COMPLETIONDATE,
	LOCALCORPORATIONID,
	STATUSID,
	CLASSIFICATIONID,
	CREATEDAT,
	CREATEDBY,
	CREATEDBYNAME,
	UPDATEDAT,
	UPDATEDBY,
	UPDATEDBYNAME,
	DELETEDAT,
	MACHINELOGSTATUSID,
	LOGSTORAGELOCATION,
	PRIORITYID,
	RELATEDQVICSIDLIST
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	QVICSID,
	REPORTER,
	REPORTERNAME,
	SUBJECT,
	INQUIRYDATE,
	COMPLETIONDATE,
	LOCALCORPORATIONID,
	STATUSID,
	CLASSIFICATIONID,
	CREATEDAT,
	CREATEDBY,
	CREATEDBYNAME,
	UPDATEDAT,
	UPDATEDBY,
	UPDATEDBYNAME,
	DELETEDAT,
	MACHINELOGSTATUSID,
	LOGSTORAGELOCATION,
	PRIORITYID,
	RELATEDQVICSIDLIST
 from transform_data 
)
SELECT * from type_data
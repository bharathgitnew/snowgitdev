        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='ApprovalActivities'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	TROUBLEID AS TROUBLEID,
	SEQUENCE AS SEQUENCE,
	APPROVALNAME_J AS APPROVALNAME_J,
	APPROVALNAME_E AS APPROVALNAME_E,
	APPROVALCATEGORY AS APPROVALCATEGORY,
	APPROVER AS APPROVER,
	APPROVERNAME AS APPROVERNAME,
	APPROVEDAT AS APPROVEDAT,
	LABELNAME_J AS LABELNAME_J,
	LABELNAME_E AS LABELNAME_E,
	ISCURRENT AS ISCURRENT,
	NEXTID AS NEXTID,
	ISSKIPPABLE AS ISSKIPPABLE,
	ISSKIPPED AS ISSKIPPED,
	VERIFIERID AS VERIFIERID,
	VERIFYCATEGORY_J AS VERIFYCATEGORY_J,
	VERIFYCATEGORY_E AS VERIFYCATEGORY_E,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_APPROVALACTIVITIES') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_APPROVALACTIVITIES') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	TROUBLEID,
	SEQUENCE,
	APPROVALNAME_J,
	APPROVALNAME_E,
	APPROVALCATEGORY,
	APPROVER,
	APPROVERNAME,
	APPROVEDAT,
	LABELNAME_J,
	LABELNAME_E,
	ISCURRENT,
	NEXTID,
	ISSKIPPABLE,
	ISSKIPPED,
	VERIFIERID,
	VERIFYCATEGORY_J,
	VERIFYCATEGORY_E
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	TROUBLEID,
	SEQUENCE,
	APPROVALNAME_J,
	APPROVALNAME_E,
	APPROVALCATEGORY,
	APPROVER,
	APPROVERNAME,
	APPROVEDAT,
	LABELNAME_J,
	LABELNAME_E,
	ISCURRENT,
	NEXTID,
	ISSKIPPABLE,
	ISSKIPPED,
	VERIFIERID,
	VERIFYCATEGORY_J,
	VERIFYCATEGORY_E
 from transform_data 
)
SELECT * from type_data
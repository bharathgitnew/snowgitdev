	ISRETURNTARGET,
	RETURNTARGETCHECKEDAT,
	ISRENTALPRODUCT,
	NOTES,
	PRICE,
	ISCUPOLLUTIONPRODUCT,
	EXCHANGEID
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	QVICSID,
	PARTCATEGORY,
	NCDRREQUIREDSTATUSID,
	NCDRNUMBER,
	PARTNUMBER,
	PARTNAME,
	PARTTYPE,
	PARTSN,
	PARTSUBCATEGORYID,
	QUANTITY,
	MANUFACTURER,
	SUPPLIER,
	COUNTRY,
	SONO,
	ISRETURNTARGET,
	RETURNTARGETCHECKEDAT,
	ISRENTALPRODUCT,
	NOTES,
	PRICE,
	ISCUPOLLUTIONPRODUCT,
	EXCHANGEID
 from transform_data 
)
SELECT * from type_data
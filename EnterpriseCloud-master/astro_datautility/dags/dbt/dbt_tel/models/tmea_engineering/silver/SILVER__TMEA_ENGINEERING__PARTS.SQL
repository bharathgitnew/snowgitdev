        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='PARTS'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	QVICSID AS QVICSID,
	PARTCATEGORY AS PARTCATEGORY,
	NCDRREQUIREDSTATUSID AS NCDRREQUIREDSTATUSID,
	NCDRNUMBER AS NCDRNUMBER,
	PARTNUMBER AS PARTNUMBER,
	PARTNAME AS PARTNAME,
	PARTTYPE AS PARTTYPE,
	PARTSN AS PARTSN,
	PARTSUBCATEGORYID AS PARTSUBCATEGORYID,
	QUANTITY AS QUANTITY,
	MANUFACTURER AS MANUFACTURER,
	SUPPLIER AS SUPPLIER,
	COUNTRY AS COUNTRY,
	SONO AS SONO,
	ISRETURNTARGET AS ISRETURNTARGET,
	RETURNTARGETCHECKEDAT AS RETURNTARGETCHECKEDAT,
	ISRENTALPRODUCT AS ISRENTALPRODUCT,
	NOTES AS NOTES,
	PRICE AS PRICE,
	ISCUPOLLUTIONPRODUCT AS ISCUPOLLUTIONPRODUCT,
	EXCHANGEID AS EXCHANGEID,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_PARTS') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_PARTS') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	QVICSID,
	PARTCATEGORY,
	NCDRREQUIREDSTATUSID,
	NCDRNUMBER,
	PARTNUMBER,
	PARTNAME,
	PARTTYPE,
	PARTSN,
	PARTSUBCATEGORYID,
	QUANTITY,

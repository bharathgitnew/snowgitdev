{{ config(
        materialized='tel_incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='ANNOUNCEMENTS'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	ANNOUNCEMENT_J AS ANNOUNCEMENT_J,
	ANNOUNCEMENT_E AS ANNOUNCEMENT_E,
	ANNOUNCEDAT AS ANNOUNCEDAT,
	VALIDUNTIL AS VALIDUNTIL,
	CREATEDAT AS CREATEDAT,
	UPDATEDAT AS UPDATEDAT,
	DELETEDAT AS DELETEDAT,
	_FILEDATE,
	_FILENAME
FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_ANNOUNCEMENTS') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('BRONZE__TMEA_ENGINEERING__QVICS_C_TMEA_ANNOUNCEMENTS') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	ANNOUNCEMENT_J,
	ANNOUNCEMENT_E,
	ANNOUNCEDAT,
	VALIDUNTIL,
	CREATEDAT,
	UPDATEDAT,
	DELETEDAT
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	ANNOUNCEMENT_J,
	ANNOUNCEMENT_E,
	ANNOUNCEDAT,
	VALIDUNTIL,
	CREATEDAT,
	UPDATEDAT,
	DELETEDAT
 from transform_data 
)
SELECT * from type_data
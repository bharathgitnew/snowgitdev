WITH STEP_ONE
AS (
	SELECT DISTINCT QUOTE_ID,
		   CASE 
			WHEN CATEGORY = 'CK'
				THEN 'CK'
			WHEN CATEGORY = 'MOD'
				THEN 'OTHER'
			WHEN CATEGORY = 'MT'
				THEN 'MT'  
			WHEN CATEGORY = 'OTHER'
				THEN 'OTHER'
			WHEN CATEGORY = 'PKD'
				THEN 'PKD'
			WHEN CATEGORY = 'SERVICE'
				THEN 'OTHER'
            -- Leah added on 2025-09-26 - CK Search Expansion
            WHEN CATEGORY IS NULL AND UPPER(QUOTE_TYPE) = 'CONVERSION'
            THEN 'CK'
			ELSE 'OTHER'
		END AS CATEGORY,
        --Leah added - 2025-09-26    
        BUSINESS_UNIT,
		MODEL,
		QUOTE_AMT,
		TO_DATE(LATEST_QUOTE_STATUS_DATE) AS LATEST_QUOTE_STATUS_DATE,
		  CAST(Y.VALUE AS VARCHAR(16777216)) AS NEW_TEL_QUOTE_NODE_PROCESS
	FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__QUOTE_ACTION_LIFECYCLE') }},
		LATERAL FLATTEN(INPUT => SPLIT(TEL_QUOTE_NODE_PROCESS, '|')) Y
	WHERE TEL_QUOTE_NODE_PROCESS IS NOT NULL
	),
STEP_TWO
AS (
	SELECT QUOTE_ID,
		CATEGORY,
		BUSINESS_UNIT,
		MODEL,
		QUOTE_AMT,
		LATEST_QUOTE_STATUS_DATE,
		NEW_TEL_QUOTE_NODE_PROCESS,
		RTRIM(substring(NEW_TEL_QUOTE_NODE_PROCESS, 0, REGEXP_INSTR(NEW_TEL_QUOTE_NODE_PROCESS, ':')), ':') AS PROCESS,
		LTRIM(substring(NEW_TEL_QUOTE_NODE_PROCESS, REGEXP_INSTR(NEW_TEL_QUOTE_NODE_PROCESS, ':')), ':') AS NEW_TEL_QUOTE_NODE
	FROM STEP_ONE
	),
 STEP_THREE
AS (
	SELECT QUOTE_ID,
		CATEGORY,
		BUSINESS_UNIT,
		MODEL,
		QUOTE_AMT,
		LATEST_QUOTE_STATUS_DATE,
		PROCESS,
		CAST(Z.VALUE AS VARCHAR(16777216)) AS CEID
	FROM STEP_TWO,
		LATERAL FLATTEN(INPUT => SPLIT(NEW_TEL_QUOTE_NODE, ',')) Z
	),
source_data
AS (
SELECT  QUOTE_ID,
		CATEGORY,
		BUSINESS_UNIT,
		MODEL,
		QUOTE_AMT,
		LATEST_QUOTE_STATUS_DATE,
		PROCESS,
		CEID,
	       --2025-09-03 Leah commented out, this is for CK search.  Maximize search capability although CK is FROM... TO...
	 -- CASE WHEN CATEGORY = 'CK' THEN NULL ELSE 
        CASE WHEN CATEGORY = 'CK' AND BUSINESS_UNIT = 'TS'
        THEN CATEGORY || '-' || UPPER(CEID)
        ELSE CATEGORY || '-' || UPPER(CEID) || '-' || PROCESS END AS QUOTE_SEARCH_KEY
FROM STEP_THREE
	),
transform_data
AS (
SELECT  
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH,
		QUOTE_ID,
		CATEGORY,
		BUSINESS_UNIT,
		MODEL,
		QUOTE_AMT,
		LATEST_QUOTE_STATUS_DATE,
		PROCESS,
		CEID,
		QUOTE_SEARCH_KEY
	FROM source_data
	),
type_data
AS (
	SELECT 	
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	QUOTE_ID,
	CATEGORY,
	BUSINESS_UNIT,
	MODEL,
	CAST(QUOTE_AMT AS  NUMBER(38,0)) AS QUOTE_AMT,
	CAST(LATEST_QUOTE_STATUS_DATE AS  DATE) AS LATEST_QUOTE_STATUS_DATE,
	PROCESS,
	CEID,
	QUOTE_SEARCH_KEY
	    from transform_data
	)
SELECT *
FROM type_data
{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='QUOTE_CONFIG_CHURN_HISTORY',
      transient=false
) }}

WITH source_data as 
(SELECT *
FROM  {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }}
WHERE 
  REQTYPE = 'QRF'
), 

transform_data AS
( SELECT DISTINCT 
TEL_QUOTE_ID AS QUOTE_ID, 
LPAD(REV, 2, '00') as REVISION_NUMBER,
--TEL_QUOTE_TYPE
UPPER(LAG(TEL_QUOTE_TYPE) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV)) AS PREVIOUS_TEL_QUOTE_TYPE,
UPPER(TEL_QUOTE_TYPE) AS TEL_QUOTE_TYPE, 
CASE WHEN TEL_QUOTE_TYPE = '' OR LAG(TEL_QUOTE_TYPE) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) = '' THEN NULL
WHEN (TEL_QUOTE_TYPE <> '' OR LAG(TEL_QUOTE_TYPE) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) <> '')
AND TEL_QUOTE_TYPE <> LAG(TEL_QUOTE_TYPE) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) THEN 1 ELSE NULL END AS IS_QUOTETYPE_CHURN,
--Lead Time
LAG(LEAD_TIME || '-' || LEAD_TIME_UNIT) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE) AS PREVIOUS_LEAD_TIME,
LEAD_TIME || '-' || LEAD_TIME_UNIT AS LEAD_TIME, 
CASE WHEN LEAD_TIME || '-' || LEAD_TIME_UNIT = '' OR LAG(LEAD_TIME || '-' || LEAD_TIME_UNIT) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) = '' THEN NULL
WHEN (LEAD_TIME || '-' || LEAD_TIME_UNIT <> '' OR LAG(LEAD_TIME || '-' || LEAD_TIME_UNIT) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) <> '')
AND LEAD_TIME || '-' || LEAD_TIME_UNIT <> LAG(LEAD_TIME || '-' || LEAD_TIME_UNIT) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE ASC) THEN 1 ELSE NULL END AS IS_LEADTIME_CHURN,
--TEL QUOTE STATUS
UPPER(LAG(TEL_QUOTE_STATUS) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE)) AS PREVIOUS_QUOTE_STATUS,
UPPER(TEL_QUOTE_STATUS) AS QUOTE_STATUS,
CASE WHEN TEL_QUOTE_STATUS = '' OR LAG(TEL_QUOTE_STATUS) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) = '' THEN NULL
WHEN (TEL_QUOTE_STATUS <> '' OR LAG(TEL_QUOTE_STATUS) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) <> '')
AND TEL_QUOTE_STATUS <> LAG(TEL_QUOTE_STATUS) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE ASC) THEN 1 ELSE NULL END AS IS_QUOTE_STATUS_CHURN,
--Category
UPPER(LAG(CATEGORY) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE)) AS PREVIOUS_CATEGORY,
UPPER(CATEGORY) AS CATEGORY, 
CASE WHEN CATEGORY = '' OR LAG(CATEGORY) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) = '' THEN NULL
WHEN (CATEGORY <> '' OR LAG(CATEGORY) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) <> '')
AND CATEGORY <> LAG(CATEGORY) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE ASC) THEN 1 ELSE NULL END AS IS_CATEGORY_CHURN,
--Entity
LAG(ENTITY) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) AS PREVIOUS_ENTITY,
ENTITY, 
CASE WHEN ENTITY = '' OR LAG(ENTITY) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) = '' THEN NULL
WHEN (ENTITY <> '' OR LAG(ENTITY) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) <> '')
AND ENTITY <> LAG(ENTITY) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) THEN 1 ELSE NULL END AS IS_ENTITY_CHURN,
--Node
UPPER(LAG(TEL_QUOTE_NODE_PROCESS) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE)) AS PREVIOUS_NODE,
UPPER(TEL_QUOTE_NODE_PROCESS) AS NODE,
CASE WHEN TEL_QUOTE_NODE_PROCESS = '' OR LAG(TEL_QUOTE_NODE_PROCESS) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) = '' THEN NULL
WHEN (TEL_QUOTE_NODE_PROCESS <> '' OR LAG(TEL_QUOTE_NODE_PROCESS) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) <> '')
AND TEL_QUOTE_NODE_PROCESS <> LAG(TEL_QUOTE_NODE_PROCESS) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE ASC) THEN 1 ELSE NULL END AS IS_NODE_CHURN,
--Description
LAG(REFERENCE_1) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY STATUS_DATE) AS PREVIOUS_DESCRIPTION,
REFERENCE_1 AS DESCRIPTION,
CASE WHEN REFERENCE_1 = '' OR LAG(REFERENCE_1) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) = '' THEN NULL
WHEN (REFERENCE_1 <> '' OR LAG(REFERENCE_1) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE) <> '')
AND REFERENCE_1 <> LAG(REFERENCE_1) OVER (PARTITION BY QUOTE_ID ORDER BY STATUS_DATE ASC) THEN 1 ELSE NULL END AS IS_DESCRIPTION_CHURN, 
--Amount
LAG(QUOTE_AMT) OVER (PARTITION BY TEL_QUOTE_ID ORDER BY REV) AS PREVIOUS_QUOTE_AMT,
QUOTE_AMT, 
CASE WHEN QUOTE_AMT IS NULL OR LAG(QUOTE_AMT) OVER (PARTITION BY QUOTE_ID ORDER BY REV) IS NULL THEN NULL
WHEN (QUOTE_AMT IS NOT NULL OR LAG(QUOTE_AMT) OVER (PARTITION BY QUOTE_ID ORDER BY REV) IS NOT NULL)
AND QUOTE_AMT <> LAG(QUOTE_AMT) OVER (PARTITION BY QUOTE_ID ORDER BY REV) THEN 1 ELSE NULL END AS IS_AMOUNT_CHURN,
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
SHA2('hash_me') AS _ROW_HASH
FROM source_data
)

,type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        QUOTE_ID,
        REVISION_NUMBER,
        --TEL Quote Type
        PREVIOUS_TEL_QUOTE_TYPE,
        TEL_QUOTE_TYPE,
        CAST(IS_QUOTETYPE_CHURN AS NUMBER(1,0)) AS IS_QUOTETYPE_CHURN,
        --Lead Time
        PREVIOUS_LEAD_TIME,
        LEAD_TIME,
        CAST(IS_LEADTIME_CHURN AS NUMBER(1,0)) AS IS_LEADTIME_CHURN,
        --Quote Status
        PREVIOUS_QUOTE_STATUS,
        QUOTE_STATUS,
        CAST(IS_QUOTE_STATUS_CHURN AS NUMBER(1,0)) AS IS_QUOTE_STATUS_CHURN,
        --Category
        PREVIOUS_CATEGORY,
        CATEGORY,
        CAST(IS_CATEGORY_CHURN AS NUMBER(1,0)) AS IS_CATEGORY_CHURN,
        --Entity
        PREVIOUS_ENTITY,
        ENTITY,
        CAST(IS_ENTITY_CHURN AS NUMBER(1,0)) AS IS_ENTITY_CHURN,
        --Node
        PREVIOUS_NODE,
        NODE,
        CAST(IS_NODE_CHURN AS NUMBER(1,0)) AS IS_NODE_CHURN,
        --Descrption
        PREVIOUS_DESCRIPTION,
        DESCRIPTION,
        CAST(IS_DESCRIPTION_CHURN AS NUMBER(1,0)) AS IS_DESCRIPTION_CHURN,
        --Quote Amount
        PREVIOUS_QUOTE_AMT,
        QUOTE_AMT,
        CAST(IS_AMOUNT_CHURN AS NUMBER(1,0)) AS IS_AMOUNT_CHURN
        FROM transform_data
) 
SELECT * FROM type_data
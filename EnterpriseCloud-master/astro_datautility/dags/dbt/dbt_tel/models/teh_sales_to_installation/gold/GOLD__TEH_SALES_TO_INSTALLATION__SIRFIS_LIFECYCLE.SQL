{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
        alias='SIRFIS_LIFECYCLE',
      transient=false
) }}

with ref_PURCHASE_ORDER_CHANGE_ORDER_data as (
  SELECT
    PURCHASE_ORDER_LINE_ID,
    LATEST_PURCHASE_ORDER_LINE_STATUS,
    LATEST_OVERALL_STATUS, 
    PURCHASE_ORDER_ACCEPTANCE_DATE
  FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__INTEL_PURCHASE_ORDER_CHANGE_ORDER') }}
),

source_data_sirfis_lifecycle_min_dates AS (
    SELECT DISTINCT
        ID,
        MIN(_APPENDEDDATE) AS ENTERED_DATE
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
    GROUP BY ID
),

sirfis_lifecycle_max_date AS (
    SELECT 
        MAX(_APPENDEDDATE) AS VAR_MAX_DATE
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
),

source_data_sirfis_lifecycle_min_notnull_dates AS (
    SELECT DISTINCT 
        ID, 
        FIRST_VALUE(CONTRACTUAL_TENDER_DATE) IGNORE NULLS OVER (PARTITION BY ID ORDER BY _APPENDEDDATE ASC) AS INITIAL_CTD
        FROM  {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
),

INITIAL_PO_DATE AS
( 
  --does not include the whole population  
  SELECT DISTINCT ID, 
  MIN(_APPENDEDDATE) AS INITIAL_PO_DATE, 
  ID || '-' || INITIAL_PO_DATE AS PO_ISSUE_KEY
  FROM  {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
  WHERE PURCHASE_ORDER_KEY IS NOT NULL
  AND PURCHASE_ORDER_KEY <> ''
  GROUP BY 1
), 

 RTD_AT_PO_ISSUED_DATE AS
(SELECT DISTINCT ID,
 REQUESTED_TENDER_DATE, 
 ID || '-' || _APPENDEDDATE AS PO_ISSUE_KEY
 FROM  {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
 )
 ,

source_data_sirfis_lifecycle_largest_dates AS (
    SELECT DISTINCT 
        ID, 
        MAX(CONTRACTUAL_TENDER_DATE) AS LARGEST_CTD,
        COUNT(DISTINCT CONTRACTUAL_TENDER_DATE) AS NUM_CTD_CHANGES
        FROM  {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
        GROUP BY ID
),

source_data_sirfis_lifecycle AS (
    SELECT DISTINCT
        ID,
        PURCHASE_ORDER_NUMBER,
        IS_PURCHASE_ORDER,
        PURCHASE_ORDER_LINE_NUMBER,
        PURCHASE_ORDER_KEY,
        BUILD_TIME,
        IS_CRITICAL,
        STATE,
        READ_ONLY,
        SUPPLIER_MAP,
        CONVERSION_LOCATION,
        PRICE_KEY,
        TRANSIT_TIME,
        INTEL_RELEASED_DATE,
        PRIMARY_SUPPLIER_TENDER_DATE,
        SUPPLIER_TENDER_DATE,
        REQUESTED_DELIVERY_DATE,
        CONTRACTUAL_TENDER_DATE,
        REQUESTED_TENDER_DATE,
        SET_START_DATE,
        EXPECTED_SUPPLIER_DELIVERY_DATE,
        COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE) AS ALL_STD_RESPONSES,
        _APPENDEDDATE, 
        RESPONSE_COMMENT
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
    WHERE REVISION_DESC_ORDER=1
),

transform_data AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        source_data_sirfis_lifecycle.ID as ID,
        CASE 
            WHEN IS_PURCHASE_ORDER = 'Yes' THEN 1
            ELSE 0 
        END AS PO_STATUS,
        PURCHASE_ORDER_NUMBER,
        PURCHASE_ORDER_LINE_NUMBER,
        PURCHASE_ORDER_KEY,
        BUILD_TIME,
        CASE 
            WHEN IS_CRITICAL = 'Yes' THEN 1
            ELSE 0 
        END AS IS_CRITICAL,
        STATE,
        READ_ONLY,
        SUPPLIER_MAP,
        CONVERSION_LOCATION,
        PRICE_KEY,
        TRANSIT_TIME,
        INTEL_RELEASED_DATE,
        PRIMARY_SUPPLIER_TENDER_DATE,
        SUPPLIER_TENDER_DATE,
        REQUESTED_DELIVERY_DATE,
        CONTRACTUAL_TENDER_DATE,
        source_data_sirfis_lifecycle.REQUESTED_TENDER_DATE,
        SET_START_DATE,
        EXPECTED_SUPPLIER_DELIVERY_DATE,
        _APPENDEDDATE as LATEST_DATE,
        ENTERED_DATE,
        ALL_STD_RESPONSES,
        CASE 
            WHEN LATEST_DATE < CURRENT_DATE() THEN 0
            WHEN LATEST_DATE = CURRENT_DATE() THEN 1 
        END AS IS_CURRENT,
        CASE WHEN ref_PURCHASE_ORDER_CHANGE_ORDER_data.LATEST_PURCHASE_ORDER_LINE_STATUS = 'DELETE' THEN 'DELETED'
             WHEN IS_CURRENT = 1 AND (source_data_sirfis_lifecycle.SUPPLIER_TENDER_DATE is null OR source_data_sirfis_lifecycle.ALL_STD_RESPONSES > (select VAR_MAX_DATE from sirfis_lifecycle_max_date)) THEN 'CURRENT'
             WHEN IS_CURRENT = 1 AND PO_STATUS = 1 AND source_data_sirfis_lifecycle.ALL_STD_RESPONSES <=(select VAR_MAX_DATE from sirfis_lifecycle_max_date) THEN 'LIKELY SHIPPED'
             WHEN IS_CURRENT = 1 AND PO_STATUS = 0 AND source_data_sirfis_lifecycle.ALL_STD_RESPONSES <= (select VAR_MAX_DATE from sirfis_lifecycle_max_date) THEN 'DELETED'
             WHEN IS_CURRENT = 0 AND PO_STATUS = 0 THEN 'DELETED'
             WHEN IS_CURRENT = 0 AND ref_PURCHASE_ORDER_CHANGE_ORDER_data.LATEST_OVERALL_STATUS <> 'ACCEPTED' THEN 'DELETED'
             WHEN IS_CURRENT = 0 AND ref_PURCHASE_ORDER_CHANGE_ORDER_data.LATEST_OVERALL_STATUS = 'ACCEPTED' AND source_data_sirfis_lifecycle.ALL_STD_RESPONSES > (select VAR_MAX_DATE from sirfis_lifecycle_max_date) THEN 'DELETED'
             WHEN IS_CURRENT = 0 AND ref_PURCHASE_ORDER_CHANGE_ORDER_data.LATEST_OVERALL_STATUS = 'ACCEPTED' AND source_data_sirfis_lifecycle.ALL_STD_RESPONSES is null THEN 'DELETED'
             WHEN IS_CURRENT = 0 AND ref_PURCHASE_ORDER_CHANGE_ORDER_data.LATEST_OVERALL_STATUS = 'ACCEPTED' AND source_data_sirfis_lifecycle.ALL_STD_RESPONSES <= (select VAR_MAX_DATE from sirfis_lifecycle_max_date) THEN 'SHIPPED'
             ELSE 'EXCEPTION' END AS EXPECTED_FORECAST_STATUS,
        INITIAL_CTD, 
        CASE WHEN source_data_sirfis_lifecycle_largest_dates.NUM_CTD_CHANGES > 1 THEN source_data_sirfis_lifecycle_largest_dates.LARGEST_CTD
             WHEN source_data_sirfis_lifecycle_largest_dates.NUM_CTD_CHANGES IS null THEN null
             WHEN source_data_sirfis_lifecycle_largest_dates.NUM_CTD_CHANGES = 1 THEN INITIAL_CTD
             END AS OPTIMAL_CTD,
        DATEDIFF(day, PRIMARY_SUPPLIER_TENDER_DATE, OPTIMAL_CTD) AS STD_TO_CTD_DIFF_IN_DAYS,
        CASE WHEN OPTIMAL_CTD IS NULL THEN NULL
             WHEN OPTIMAL_CTD IS NOT NULL AND PRIMARY_SUPPLIER_TENDER_DATE = OPTIMAL_CTD THEN 'MEET'
             WHEN OPTIMAL_CTD IS NOT NULL AND PRIMARY_SUPPLIER_TENDER_DATE < OPTIMAL_CTD THEN 'BEAT'
             WHEN OPTIMAL_CTD IS NOT NULL AND PRIMARY_SUPPLIER_TENDER_DATE > OPTIMAL_CTD THEN 'MISS'
             END AS STD_TO_CTD_PERFORMANCE,
        CASE WHEN INITIAL_PO_DATE.INITIAL_PO_DATE IS NULL THEN NULL
             ELSE INITIAL_PO_DATE.INITIAL_PO_DATE END AS INITIAL_PO_DATE, 
        CASE WHEN INITIAL_PO_DATE IS NULL THEN NULL
             ELSE TO_DATE(DATEADD(day, - BUILD_TIME, RTD_AT_PO_ISSUED_DATE.REQUESTED_TENDER_DATE)) END AS INITIAL_PO_DUE_DATE, 
        CASE WHEN INITIAL_PO_DATE IS NULL THEN NULL
             WHEN INITIAL_PO_DATE IS NOT NULL AND INITIAL_PO_DUE_DATE >= INITIAL_PO_DATE THEN 0
             ELSE 1
             END AS WAS_PO_LATE,
        CASE WHEN PO_STATUS = 1 AND EXPECTED_FORECAST_STATUS = 'CURRENT' THEN NULL
             WHEN EXPECTED_FORECAST_STATUS <> 'CURRENT' THEN null
             WHEN PO_STATUS = 0 AND EXPECTED_FORECAST_STATUS = 'CURRENT' AND DATEADD(day, BUILD_TIME, CURRENT_DATE) >=source_data_sirfis_lifecycle.REQUESTED_TENDER_DATE
             THEN 'PO OVERDUE'
            WHEN PO_STATUS = 0 AND EXPECTED_FORECAST_STATUS = 'CURRENT' AND DATEADD(day, BUILD_TIME, CURRENT_DATE)  < source_data_sirfis_lifecycle.REQUESTED_TENDER_DATE
             THEN 'PO NOT OVERDUE' END AS IS_PO_OVERDUE,
        CASE WHEN ref_PURCHASE_ORDER_CHANGE_ORDER_data.PURCHASE_ORDER_ACCEPTANCE_DATE IS NULL 
             THEN DATEADD(DAY, -BUILD_TIME, source_data_sirfis_lifecycle.REQUESTED_TENDER_DATE)
             ELSE ref_PURCHASE_ORDER_CHANGE_ORDER_data.PURCHASE_ORDER_ACCEPTANCE_DATE END AS BOOKING_DATE,
        CASE WHEN ref_PURCHASE_ORDER_CHANGE_ORDER_data.PURCHASE_ORDER_ACCEPTANCE_DATE IS NULL 
             THEN DATEADD(DAY, -BUILD_TIME, source_data_sirfis_lifecycle.PRIMARY_SUPPLIER_TENDER_DATE)
             ELSE ref_PURCHASE_ORDER_CHANGE_ORDER_data.PURCHASE_ORDER_ACCEPTANCE_DATE END AS BOOKING_DATE_STD,
        source_data_sirfis_lifecycle.RESPONSE_COMMENT
    FROM source_data_sirfis_lifecycle
         INNER JOIN source_data_sirfis_lifecycle_min_dates
                    ON source_data_sirfis_lifecycle.id=source_data_sirfis_lifecycle_min_dates.id
         LEFT OUTER JOIN ref_PURCHASE_ORDER_CHANGE_ORDER_data
                    ON source_data_sirfis_lifecycle.PURCHASE_ORDER_KEY=ref_PURCHASE_ORDER_CHANGE_ORDER_data.PURCHASE_ORDER_LINE_ID
         LEFT JOIN source_data_sirfis_lifecycle_min_notnull_dates
                    ON source_data_sirfis_lifecycle.ID = source_data_sirfis_lifecycle_min_notnull_dates.ID
         LEFT JOIN source_data_sirfis_lifecycle_largest_dates
                    ON source_data_sirfis_lifecycle.ID = source_data_sirfis_lifecycle_largest_dates.ID
         LEFT JOIN INITIAL_PO_DATE 
                    ON source_data_sirfis_lifecycle.ID = INITIAL_PO_DATE.ID
         LEFT JOIN RTD_AT_PO_ISSUED_DATE 
                    ON INITIAL_PO_DATE.PO_ISSUE_KEY = RTD_AT_PO_ISSUED_DATE.PO_ISSUE_KEY
)

,type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ID,
        CAST(PO_STATUS AS NUMBER(1,0)) AS PO_STATUS,
        PURCHASE_ORDER_NUMBER,
        PURCHASE_ORDER_LINE_NUMBER,
        PURCHASE_ORDER_KEY,
        BUILD_TIME,
        CAST(IS_CRITICAL AS NUMBER(1,0)) AS IS_CRITICAL,
        STATE,
        READ_ONLY,
        SUPPLIER_MAP,
        CONVERSION_LOCATION,
        PRICE_KEY,
        CAST(TRANSIT_TIME AS NUMBER(38,0)) AS TRANSIT_TIME,
        CAST(INTEL_RELEASED_DATE AS DATE) AS INTEL_RELEASED_DATE,
        CAST(PRIMARY_SUPPLIER_TENDER_DATE AS DATE) AS PRIMARY_SUPPLIER_TENDER_DATE,
        CAST(SUPPLIER_TENDER_DATE AS DATE) AS SUPPLIER_TENDER_DATE,
        CAST(REQUESTED_DELIVERY_DATE AS DATE) AS REQUESTED_DELIVERY_DATE,
        CAST(CONTRACTUAL_TENDER_DATE AS DATE) AS CONTRACTUAL_TENDER_DATE,
        CAST(REQUESTED_TENDER_DATE AS DATE) AS REQUESTED_TENDER_DATE,
        CAST(SET_START_DATE AS DATE) AS SET_START_DATE,
        CAST(EXPECTED_SUPPLIER_DELIVERY_DATE AS DATE) AS EXPECTED_SUPPLIER_DELIVERY_DATE,
        CAST(LATEST_DATE AS DATE) AS LATEST_DATE,
        CAST(ENTERED_DATE AS DATE) AS ENTERED_DATE,
        CAST(ALL_STD_RESPONSES AS TIMESTAMP_NTZ(9)) AS ALL_STD_RESPONSES,
        CAST(IS_CURRENT AS NUMBER(1,0)) AS IS_CURRENT,
        EXPECTED_FORECAST_STATUS,
        CAST(INITIAL_CTD AS DATE) AS INITIAL_CONTRACTUAL_TENDER_DATE, 
        CAST(OPTIMAL_CTD AS DATE) AS OPTIMAL_CONTRACTUAL_TENDER_DATE, 
        STD_TO_CTD_PERFORMANCE,
        STD_TO_CTD_DIFF_IN_DAYS,
        CAST(INITIAL_PO_DATE AS DATE) AS INITIAL_PO_DATE,
        CAST(WAS_PO_LATE AS NUMBER(1,0)) AS WAS_PO_LATE, 
        CAST(IS_PO_OVERDUE AS VARCHAR(16777216)) AS IS_PO_OVERDUE,
        CAST(BOOKING_DATE AS DATE) AS BOOKING_DATE,
        CAST(BOOKING_DATE_STD AS DATE) AS BOOKING_DATE_STD,
        RESPONSE_COMMENT
    FROM transform_data
)

SELECT * from type_data
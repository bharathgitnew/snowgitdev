      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='QUOTE_ACTION_HISTORY',
      transient=false
) }}

WITH source_data as 
(SELECT DISTINCT
TEL_QUOTE_ID, 
EQUIPMENT_QUOTE_ID AS QRF_NUMBER, 
QUOTE_CURRENCY, 
QUOTE_AMT, 
LEAD_TIME,
LEAD_TIME_UNIT,
ESA, 
ESA_LITE_CANDIDATE,
ESA_LITE_QUARTER,
ESA_LITE_COMMENTS, 
equipment_quote_tel_quote_id
FROM  {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_EQUIPMENT_QUOTE_TQ_AUDIT') }}
), 

ARFQRF AS
( SELECT DISTINCT 
 REQUEST_NUMBER, 
 REV, 
 EQUIPMENT_QUOTE_TEL_QUOTE_ID,
 THRESHOLD_COUNT,
 THRESHOLD_DURATION,
 THRESHOLD_OTHER,
 THRESHOLD_SITE, 
 THRESHOLD_TIER
FROM  {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }} 
WHERE REQTYPE = 'QRF'
), 

QRFTRACKING AS
(SELECT DISTINCT QUOTE_ID, 
QUOTE_SEQ,
ACTION_DATE AS QRF_ACTION_DATE_TIME,
ACTION AS QRF_ACTION
FROM  {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_EQUIPMENT_QUOTE_TRACKING') }} 
WHERE REQUEST_TYPE = 'QRF'
),


transform_data as (
  SELECT 
  '{{ invocation_id }}' AS _AUDIT_LOG_ID,
  SHA2('hash_me') AS _ROW_HASH,
  source.TEL_QUOTE_ID, 
  source.QRF_NUMBER,
  ARFQRF.REV AS QRF_REVISION_NUMBER, 
  source.QUOTE_CURRENCY, 
  source.QUOTE_AMT, 
  source.LEAD_TIME, 
  source.LEAD_TIME_UNIT, 
  source.ESA, 
  source.ESA_LITE_CANDIDATE, 
  source.ESA_LITE_QUARTER, 
  source.ESA_LITE_COMMENTS,
  QRFTRACKING.QRF_ACTION_DATE_TIME, 
  QRFTRACKING.QRF_ACTION, 
  ARFQRF.THRESHOLD_COUNT, 
  ARFQRF.THRESHOLD_DURATION, 
  ARFQRF.THRESHOLD_OTHER, 
  ARFQRF.THRESHOLD_SITE, 
  ARFQRF.THRESHOLD_TIER
  FROM source_data source
  LEFT JOIN ARFQRF
  ON source.equipment_quote_tel_quote_id = ARFQRF.equipment_quote_tel_quote_id
  LEFT JOIN QRFTRACKING 
  ON ARFQRF.REQUEST_NUMBER = QRFTRACKING.QUOTE_ID
  AND ARFQRF.REV = QRFTRACKING.QUOTE_SEQ
)

, type_data as (
    SELECT  
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    TEL_QUOTE_ID,
    CAST(QRF_NUMBER AS NUMBER(38,0)) AS QRF_NUMBER,
    CAST(QRF_REVISION_NUMBER AS NUMBER(38,0)) AS QRF_REVISION_NUMBER,
    QUOTE_CURRENCY,
    CAST(QUOTE_AMT AS NUMBER(38,0)) AS QUOTE_AMT,
    CAST(LEAD_TIME AS NUMBER(38,0)) AS LEAD_TIME,
    LEAD_TIME_UNIT,
    ESA,
    ESA_LITE_CANDIDATE,
    ESA_LITE_QUARTER,
    ESA_LITE_COMMENTS,
    CAST(QRF_ACTION_DATE_TIME AS DATE) AS QRF_ACTION_DATE, 
    QRF_ACTION,
    THRESHOLD_COUNT,
    THRESHOLD_DURATION,
    THRESHOLD_OTHER,
    THRESHOLD_SITE,
    THRESHOLD_TIER
    FROM transform_data
)
SELECT * FROM type_data
{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='SIRFIS_CANCELLATION_CHURN_HISTORY',
      transient=false
) }}

WITH SOURCE_DATA AS (
  SELECT DISTINCT ID
    , _appendeddate AS EVENT_DATE
    , REQUEST_CANCELLATION_FEE
  FROM
   {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }} 
),
TRANSFORM_DATA AS (
    SELECT 
    DISTINCT ID
    , EVENT_DATE
    , LAG(REQUEST_CANCELLATION_FEE) OVER (PARTITION BY ID ORDER BY EVENT_DATE) AS PREVIOUS_IS_REQUEST_CANCELLATION_STATUS
    , REQUEST_CANCELLATION_FEE AS IS_REQUEST_CANCELLATION
    , CASE WHEN REQUEST_CANCELLATION_FEE IS NULL OR LAG(REQUEST_CANCELLATION_FEE) OVER (PARTITION BY ID ORDER BY EVENT_DATE) IS NULL THEN NULL
        WHEN (REQUEST_CANCELLATION_FEE IS NOT NULL OR LAG(REQUEST_CANCELLATION_FEE) OVER (PARTITION BY ID ORDER BY EVENT_DATE) IS NOT NULL)
        AND REQUEST_CANCELLATION_FEE <> LAG(REQUEST_CANCELLATION_FEE) OVER (PARTITION BY ID ORDER BY EVENT_DATE ASC) THEN 1 ELSE NULL END AS IS_REQUEST_CANCELLATION_CHURN
FROM SOURCE_DATA),
filter_data as (
    select 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    ID,
    EVENT_DATE,
    PREVIOUS_IS_REQUEST_CANCELLATION_STATUS,
    IS_REQUEST_CANCELLATION
    from TRANSFORM_DATA 
    WHERE IS_REQUEST_CANCELLATION_CHURN = 1
),
type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ID,
        EVENT_DATE::DATE as EVENT_DATE,
        PREVIOUS_IS_REQUEST_CANCELLATION_STATUS::BOOLEAN as PREVIOUS_IS_REQUEST_CANCELLATION_STATUS,
        IS_REQUEST_CANCELLATION::BOOLEAN as IS_REQUEST_CANCELLATION
 from filter_data    
)

SELECT
  * FROM type_data
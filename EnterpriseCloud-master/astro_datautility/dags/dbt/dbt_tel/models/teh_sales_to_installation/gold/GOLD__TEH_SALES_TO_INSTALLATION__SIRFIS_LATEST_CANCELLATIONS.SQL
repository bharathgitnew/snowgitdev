{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='SIRFIS_LATEST_CANCELLATIONS',
      transient=false
) }}

WITH 
SOURCE_DATA as (
    select
     ID,
    MIN(_appendeddate) over (partition by ID ) AS INITIAL_CANCEL_FLAG_DATE,
    REQUEST_CANCELLATION_FEE AS LATEST_CANCELLATION_STATUS,
    RESPONSE_CURRENT_CANCELLATION_FEE AS CURRENT_CANCELLATION_FEE,
    RESPONSE_HAS_NEXT_CANCELLATION_FEE AS LATEST_NEXT_CANCELLATION_FEE_STATUS,
    RESPONSE_IS_PART_OF_NEGOTIATION AS LATEST_IS_PART_OF_NEGOTIATION_STATUS,
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }} 
    WHERE REQUEST_CANCELLATION_FEE = 'TRUE'
    qualify row_number() over(partition by ID order by _APPENDEDDATE desc) = 1
    
),
TRANSFORM_DATA AS
(
  SELECT 
  '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
   ID
  , INITIAL_CANCEL_FLAG_DATE
  , LATEST_CANCELLATION_STATUS
  , CURRENT_CANCELLATION_FEE
  , LATEST_NEXT_CANCELLATION_FEE_STATUS
  , LATEST_IS_PART_OF_NEGOTIATION_STATUS
  FROM SOURCE_DATA 
),
type_data as (
  SELECT 
      CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
      CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
      ID,
      INITIAL_CANCEL_FLAG_DATE::DATE as INITIAL_CANCEL_FLAG_DATE,
      LATEST_CANCELLATION_STATUS::BOOLEAN as LATEST_CANCELLATION_STATUS,
      CURRENT_CANCELLATION_FEE::NUMBER(38,0) as CURRENT_CANCELLATION_FEE,
      LATEST_NEXT_CANCELLATION_FEE_STATUS::BOOLEAN as LATEST_NEXT_CANCELLATION_FEE_STATUS,
      LATEST_IS_PART_OF_NEGOTIATION_STATUS::BOOLEAN as LATEST_IS_PART_OF_NEGOTIATION_STATUS
  from transform_data    
)

SELECT
  * FROM type_data
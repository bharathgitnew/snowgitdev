{{ config(
    materialized='tel_incremental',
	incremental_strategy='insert_overwrite',
    alias='SALES_CRM_REVENUE_RECOGNITION',
    unique_key=['SALES_DOCUMENT_ITEM_NUMBER'],
    transient=false
) }}

with SALES_DOCUMENT as (
    SELECT DISTINCT TEL_SM_SALES_DOC_ITEM_NO
    , tel_sm_opportunity_title
    , STATECODE
    , TEL_SM_REVENUE_RECOGNITION
    , TEL_SM_SALESAMNT
    , TEL_SM_SALESAMNT_JPY
    , TEL_SM_ENDUSER_SALESAMNT
    , TEL_SM_ENDUSER_SALESAMNT_JPY
    , TEL_SM_REV_REC_CRITERIANAME
    , tel_sm_salesdate_est_act_status
    , TEL_SM_ENDUSER_SALESDATE
    , TEL_SM_ENDUSER_SALESDATE_ACCNT
    from {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SALES_DOCUMENT') }}
    WHERE TEL_SM_SALES_DOC_ITEM_NO IS NOT NULL
), 

DIM_REVENUE_CONFIDENCE as (
select DISTINCT 
		OPTION as OPTION_CODE,
		LOCALIZEDLABEL as REVENUE_CONFIDENCE
    FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SALES_GLOBALOPTIONSETMETADATA') }}
WHERE LocalizedLabelLanguageCode = 1033 
    AND OptionSetName = 'tel_sm_order_confidence'
),

DIM_REVREC_STATUS as (
SELECT DISTINCT 
		OPTION as OPTION_CODE,
		LOCALIZEDLABEL as REVREC_STATUS
  FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SALES_GLOBALOPTIONSETMETADATA') }}
  WHERE LocalizedLabelLanguageCode = 1033 
    AND OptionSetName = 'tel_sm_salesdate_est_act_status'
), 

DIM_OPPORTUNITY as 
(SELECT DISTINCT TEL_SM_CRM_OPPORTUNITY_ID
, OPPORTUNITY_ID
, tel_sm_order_confidence
, tel_sm_sales_district
, sm_account_name
FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__OPPORTUNITY') }}
), 

DIM_ORDER_TYPE as (
    select * from {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__ORDER_TYPE') }}
),

DIM_DISTRICT as (
    select DISTINCT 
      sales_district_id
    , tel_com_sales_district AS sales_district
    from {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SALES_DISTRICT') }}
),

DIM_ACCOUNT as (
    select * from {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SALES_CRM_ACCOUNT') }}
),

MAIN AS
(SELECT DISTINCT 
--Grain
SD.TEL_SM_SALES_DOC_ITEM_NO AS SALES_DOCUMENT_ITEM_NUMBER
, OPP.TEL_SM_CRM_OPPORTUNITY_ID AS OPPORTUNITY_ID
, SD.STATECODE AS STATE_CODE
, SD.TEL_SM_REV_REC_CRITERIANAME AS REVREC_CRITERIA
, SD.TEL_SM_REVENUE_RECOGNITION AS REVREC_CRITERIA_FLAG
, CF.REVENUE_CONFIDENCE AS REVENUE_CONFIDENCE
, REVREC.REVREC_STATUS AS REVREC_STATUS
, SD.TEL_SM_SALESAMNT AS SALES_AMOUNT
, SD.TEL_SM_SALESAMNT_JPY AS SALES_AMOUNT_JPY_ADJUSTED --TEL's Sales Amount after adjustments
, SD.TEL_SM_ENDUSER_SALESAMNT AS END_USER_SALES_AMOUNT
, SD.TEL_SM_ENDUSER_SALESAMNT_JPY AS END_USER_SALES_AMOUNT_JPY --Sales Amount to the customer
, SD.TEL_SM_ENDUSER_SALESDATE AS BU_SALES_DATE
, SD.TEL_SM_ENDUSER_SALESDATE_ACCNT AS ACCNT_SALES_DATE
, DIST.sales_district AS SALES_DISTRICT
, accnt.SALES_ACCOUNT_TI AS SALES_ACCOUNT  
FROM 
SALES_DOCUMENT SD
LEFT JOIN DIM_OPPORTUNITY OPP
ON SD.tel_sm_opportunity_title = OPP.OPPORTUNITY_ID
LEFT JOIN DIM_REVENUE_CONFIDENCE CF
ON OPP.tel_sm_order_confidence = CF.OPTION_CODE
LEFT JOIN DIM_REVREC_STATUS REVREC
ON SD.tel_sm_salesdate_est_act_status = REVREC.OPTION_CODE
LEFT JOIN DIM_DISTRICT DIST
ON OPP.tel_sm_sales_district = DIST.sales_district_id
LEFT JOIN DIM_ACCOUNT accnt
ON OPP.sm_account_name = accnt.account_id
), 

TRANSFORM_DATA AS 
(SELECT 
 '{{ invocation_id }}' AS _AUDIT_LOG_ID
 , SHA2('hash_me') AS _ROW_HASH 
 , SALES_DOCUMENT_ITEM_NUMBER 
 , CASE WHEN STATE_CODE = 0 
 THEN 'YES' ELSE 'NO' END AS IS_ACTIVE
 , OPPORTUNITY_ID 
 , CASE WHEN REVREC_CRITERIA_FLAG ilike 'true' then 'YES' 
 ELSE 'NO' END AS REVREC_CRITERIA_FLAG
 , UPPER(REVREC_CRITERIA) AS REVREC_CRITERIA 
 , UPPER(REVENUE_CONFIDENCE) AS REVENUE_CONFIDENCE
 , UPPER(REVREC_STATUS) AS REVREC_STATUS
 , ROUND(SALES_AMOUNT, 0) AS SALES_AMOUNT
 , ROUND(SALES_AMOUNT_JPY_ADJUSTED, 0) AS SALES_AMOUNT_JPY_ADJUSTED
 , ROUND(END_USER_SALES_AMOUNT, 0) AS END_USER_SALES_AMOUNT
 , ROUND(END_USER_SALES_AMOUNT_JPY, 0) AS END_USER_SALES_AMOUNT_JPY
 , BU_SALES_DATE
 , ACCNT_SALES_DATE
 , CASE WHEN UPPER(REVREC_STATUS) = 'ACTUAL' AND BU_SALES_DATE <= CURRENT_DATE() THEN BU_SALES_DATE
   ELSE NULL END AS ACTUAL_SALES_DATE
, COALESCE(ACTUAL_SALES_DATE, ACCNT_SALES_DATE) AS ADJUSTED_ACCT_SALES_DATE
, COALESCE(ACTUAL_SALES_DATE, BU_SALES_DATE) AS ADJUSTED_BU_SALES_DATE
 FROM MAIN
 --WHERE UPPER(SALES_DISTRICT) NOT IN ('TAIWAN', 'KOREA', 'JAPAN')
 --As Per Naoko Cole 2024.12.12
 WHERE UPPER(SALES_DISTRICT) || '-' || UPPER(SALES_ACCOUNT) IN 
        ('CHINA-INTEL', 'CHINA-TI', 	'EUROPE-GF/IBM', 'EUROPE-REGIONAL', 'EUROPE-TI', 'EUROPE-INTEL', 
    'EUROPE-MICRON', 'NORTH AMERICA-TI', 'NORTH AMERICA-INTEL', 'NORTH AMERICA-MICRON', 'NORTH AMERICA-REGIONAL', 	
    'NORTH AMERICA-GF/IBM', 'NORTH AMERICA-TSMC', 'NORTH AMERICA-SAMSUNG', 	
    'NORTH AMERICA-TEL GROUP', 	'SEA & OTHERS-TI', 	'SEA & OTHERS-INTEL', 	'SEA & OTHERS-MICRON'
        )
), 

TYPE_DATA AS
(     SELECT 
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
      , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
      , SALES_DOCUMENT_ITEM_NUMBER
      , IS_ACTIVE
      , OPPORTUNITY_ID
      , REVREC_CRITERIA_FLAG
      , REVREC_CRITERIA
      , REVENUE_CONFIDENCE
      , REVREC_STATUS
      , CAST(SALES_AMOUNT AS NUMBER(38,0)) AS SALES_AMOUNT
      , CAST(SALES_AMOUNT_JPY_ADJUSTED AS NUMBER(38,0)) AS SALES_AMOUNT_JPY_ADJUSTED
      , CAST(END_USER_SALES_AMOUNT AS NUMBER(38,0)) AS END_USER_SALES_AMOUNT
      , CAST(END_USER_SALES_AMOUNT_JPY AS NUMBER(38,0)) AS END_USER_SALES_AMOUNT_JPY
      , CAST(BU_SALES_DATE AS DATE) AS BU_SALES_DATE
      , CAST(ACCNT_SALES_DATE AS DATE) AS ACCNT_SALES_DATE
      , CAST(ACTUAL_SALES_DATE AS DATE) AS ACTUAL_SALES_DATE
      , CAST(ADJUSTED_ACCT_SALES_DATE AS DATE) AS ADJUSTED_ACCT_SALES_DATE
      , CAST(ADJUSTED_BU_SALES_DATE AS DATE) AS ADJUSTED_BU_SALES_DATE
      FROM TRANSFORM_DATA

)
SELECT * FROM TYPE_DATA
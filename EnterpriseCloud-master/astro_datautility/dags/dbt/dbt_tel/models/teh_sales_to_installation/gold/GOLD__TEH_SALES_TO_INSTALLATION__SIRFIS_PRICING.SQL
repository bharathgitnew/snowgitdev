WITH PURCHASE_ORDER_PAST_PRICING as(
    SELECT
        PRICE_KEY,
        LINE_AMOUNT
    FROM
        (SELECT DISTINCT PRICE_KEY, 
            LINE_AMOUNT,
            ROW_NUMBER() OVER (PARTITION BY PRICE_KEY ORDER BY LATEST_PURCHASE_ORDER_TIMESTAMP DESC) as rn
        FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__INTEL_PURCHASE_ORDER_CHANGE_ORDER') }}
        ) WHERE rn = 1
),

PURCHASE_ORDER_PRICING AS (
    SELECT DISTINCT 
        PURCHASE_ORDER_LINE_ID, 
        LINE_AMOUNT AS AMOUNT
   FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__INTEL_PURCHASE_ORDER_CHANGE_ORDER') }}
),

LATEST_QUOTE_PRICE AS (
    SELECT DISTINCT
        QUOTE_SEARCH_KEY,
        MEDIAN(QUOTE_AMT) AS QUOTE_AMT
    FROM (
        SELECT DISTINCT 
            QUOTE_SEARCH_KEY,
            QUOTE_AMT,
            ROW_NUMBER() OVER (PARTITION BY QUOTE_ID ORDER BY LATEST_QUOTE_STATUS_DATE DESC) AS rn
        FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__LATEST_QUOTE_PRICE') }}
        WHERE QUOTE_SEARCH_KEY IS NOT NULL
        ) WHERE rn = 1 
    GROUP BY QUOTE_SEARCH_KEY
),

INLINE AS (
    SELECT DISTINCT 
        PRICE_KEY,
        PRICE_ESTIMATE
    FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SIRFIS_PRICE_ESTIMATE_INLINE') }}
),

HAS_QUOTE AS (
    SELECT DISTINCT 
        REGEXP_SUBSTR(a.model, '^[^-]+') AS EXTRACTED_MODEL
    FROM GOLD.TEH_SALES_TO_INSTALLATION.SIRFIS_ITEM_HIERARCHY a
    LEFT JOIN GOLD.TEH_SALES_TO_INSTALLATION.QUOTE_ACTION_LIFECYCLE b
        ON a.MODEL = b.QUOTE_ID
    WHERE b.quote_amt IS NOT NULL
),

QUOTE_AMOUNT AS (
    SELECT DISTINCT 
        QUOTE_ID, 
        QUOTE_AMT AS QUOTE_AMOUNT
    FROM {{ref('GOLD__TEH_SALES_TO_INSTALLATION__QUOTE_ACTION_LIFECYCLE')}}
),

SOURCE_DATA AS (
    SELECT DISTINCT 
        a.ID, 
        a.PURCHASE_ORDER_KEY,
        a.PRICE_KEY,
        a.PO_STATUS, 
        a.EXPECTED_FORECAST_STATUS,
        b.MODEL,
        CASE 
            WHEN b.CATEGORY = 'PK' THEN 'PKD' 
            WHEN b.CATEGORY = 'CK' THEN 'CK' 
            WHEN b.CATEGORY = 'MT' THEN 'MT' 
            WHEN b.CATEGORY = 'PKD' THEN 'PKD' 
            ELSE 'OTHER'
        END AS CATEGORY_QRF_KEY,
        --Leah 2025-09-25 below has to be this way, because the quote is breaking down by each CEID, theres no from and to in the quote
        CASE WHEN b.CATEGORY = 'CK' AND b.business_unit_short_text = 'TS' THEN CATEGORY_QRF_KEY || '-' || UPPER(b.CEID)
            ELSE CATEGORY_QRF_KEY || '-' || UPPER(b.CEID) || '-' || b.PROCESS
        END AS QUOTE_SEARCH_KEY
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__SIRFIS_LIFECYCLE') }} a
    INNER JOIN {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__SIRFIS_ITEM_HIERARCHY') }} b
    ON a.ID = b.ID
),

TRANSFORM_ONE AS (
    SELECT DISTINCT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        SOURCE_DATA.ID,
        SOURCE_DATA.PRICE_KEY, 
        SOURCE_DATA.PO_STATUS,
        SOURCE_DATA.EXPECTED_FORECAST_STATUS,
        SOURCE_DATA.MODEL,
        SOURCE_DATA.QUOTE_SEARCH_KEY,
        PURCHASE_ORDER_PRICING.AMOUNT AS CURRENT_AMOUNT,
        QUOTE_AMOUNT.QUOTE_AMOUNT AS QUOTE_AMOUNT,
        LATEST_QUOTE_PRICE.QUOTE_AMT AS LATEST_QUOTE_AMT,
        PURCHASE_ORDER_PAST_PRICING.LINE_AMOUNT AS PAST_LINE_AMOUNT,
        INLINE.PRICE_ESTIMATE AS INLINE_PRICE_ESTIMATE,
        CASE 
            WHEN HAS_QUOTE.EXTRACTED_MODEL IS NOT NULL THEN TRUE 
            ELSE FALSE 
        END AS HAS_QUOTE_FLAG
    FROM SOURCE_DATA
    LEFT JOIN PURCHASE_ORDER_PRICING
        ON SOURCE_DATA.PURCHASE_ORDER_KEY = PURCHASE_ORDER_PRICING.PURCHASE_ORDER_LINE_ID
    LEFT JOIN PURCHASE_ORDER_PAST_PRICING
        ON SOURCE_DATA.PRICE_KEY = PURCHASE_ORDER_PAST_PRICING.PRICE_KEY
    LEFT JOIN LATEST_QUOTE_PRICE
        ON LATEST_QUOTE_PRICE.QUOTE_SEARCH_KEY like '%' || SOURCE_DATA.QUOTE_SEARCH_KEY || '%'
        --CONTAINS (SOURCE_DATA.QUOTE_SEARCH_KEY, LATEST_QUOTE_PRICE.QUOTE_SEARCH_KEY)
    LEFT JOIN INLINE 
        ON SOURCE_DATA.PRICE_KEY = INLINE.PRICE_KEY
    LEFT JOIN QUOTE_AMOUNT
        ON SOURCE_DATA.MODEL = QUOTE_AMOUNT.QUOTE_ID
    LEFT JOIN HAS_QUOTE
        ON REGEXP_SUBSTR(SOURCE_DATA.MODEL, '^[^-]+') = HAS_QUOTE.EXTRACTED_MODEL
)
,

-- TRANSFORM_TWO AS(
FINAL_TRANSFORM AS (
    SELECT DISTINCT 
        _AUDIT_LOG_ID,
        _ROW_HASH,
        ID,
        CURRENT_AMOUNT,
        COALESCE(CASE 
            WHEN PO_STATUS = 1 THEN CURRENT_AMOUNT
            WHEN PO_STATUS = 0 AND HAS_QUOTE_FLAG = TRUE
                THEN QUOTE_AMOUNT
            WHEN PO_STATUS = 0 AND HAS_QUOTE_FLAG = FALSE
                THEN ROUND(COALESCE(LATEST_QUOTE_AMT, PAST_LINE_AMOUNT), 0)
            ELSE NULL
        END, INLINE_PRICE_ESTIMATE) AS PRICE_ESTIMATE
        -- ,INLINE_PRICE_ESTIMATE
    FROM TRANSFORM_ONE
),

TYPE_DATA AS (
    SELECT DISTINCT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ID,
        CAST(CURRENT_AMOUNT AS NUMBER(38,0)) AS CURRENT_AMOUNT,
        CAST(PRICE_ESTIMATE AS NUMBER(38,0)) AS PRICE_ESTIMATE
    FROM FINAL_TRANSFORM
)

SELECT * FROM TYPE_DATA
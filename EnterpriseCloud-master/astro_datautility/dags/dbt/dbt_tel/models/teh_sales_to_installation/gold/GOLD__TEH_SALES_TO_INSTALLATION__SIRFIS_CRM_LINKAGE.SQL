        SM_SERIAL_NO,
        TEL_SM_CRM_OPPORTUNITY_ID,
        SM_TEL_SO_NO,
        TEL_SM_PROJECT_NO,
        SUPPLIER_NUMBER,
        TEL_SM_TELREGIONCODE,
        SITE,
        TEL_SM_TELPRODUCTCATEGORY,
        CATEGORY,
        TEL_SM_ORDER_TYPENAME,
        PROCESS,
        COPY_EXACT_ID,
        ENTITY,
        SM_CUSTOMER_TOOL_ID,
        PURCHASE_ORDER_LINE_ID,
        PURCHASE_ORDER_NUMBER,
        PURCHASE_ORDER_LINE_NUMBER,
        SM_PO_NO,
        TEL_SM_BOOKINGDATE,
        TEL_SM_PODATE,
        SM_BOOK_AMOUNT,
        TEL_SM_ORDER_CONFIDENCE,
        ORDER_CONFIDENCE,
        TEL_SM_BOOKING_SALES_STATUS,
        BOOKING_SALES_STATUS,
        TEL_SM_MODEL,
        TEL_SM_TELMODELNAME,
        TEL_SM_TELMODELCODE,
        TEL_SM_MATERIAL_NUMBER,
        convert_timezone('UTC', REQUESTED_TENDER_DATE) as REQUESTED_TENDER_DATE,
        convert_timezone('UTC', SUPPLIER_TENDER_DATE) as SUPPLIER_TENDER_DATE,
        convert_timezone('UTC', CONTRACTUAL_TENDER_DATE) as CONTRACTUAL_TENDER_DATE,
        convert_timezone('UTC', LAST_SUPPLIER_TENDER_DATE) as LAST_SUPPLIER_TENDER_DATE,
        TEL_SM_SHIPDATE,
        TEL_SM_CONFIRM_CUSTOMS_CLEARANCEDATE,
        READ_ONLY,
        SUPPLIER_MAP,
        SM_ACCOUNT_GROUP_CD,
        SM_ACCOUNT_GROUP_NAMENAME,
        SM_ACCOUNT_CD,
        SM_ACCOUNT_NAMENAME,
        NAME,
        TEL_SM_SLOT_REQUIRED,
        TEL_SM_SLOT_RESERVED,
        FILEDATE
    from source_data
),


with optionsetmetadata as (
    select
        ENTITYNAME,
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    from {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__CRM_FILE_GLOBALOPTIONSETMETADATA') }}
    where ISUSERLOCALIZEDLABEL = 'False' and LOCALIZEDLABELLANGUAGECODE = '1033'
),

source_data as (
    select 
        crm_sirfis.ID as ID,
        crm_sirfis.TEL_SM_OPPORTUNITYTITLE as OPPORTUNITY_GUID,
        opp.OPPORTUNITYID as OPPORTUNITYID,
        crm_sirfis.TEL_NAME as SIRFIS_ID,
        crm_sirfis.TEL_SM_UE_ID as UEID,
        crm_sirfis.TEL_SM_RELEASEDT as RELEASE_DATE,
        opp.SM_SERIAL_NO as SM_SERIAL_NO,
        opp.TEL_SM_CRM_OPPORTUNITY_ID as TEL_SM_CRM_OPPORTUNITY_ID,
        opp.SM_TEL_SO_NO as SM_TEL_SO_NO,
        opp.TEL_SM_PROJECT_NO as TEL_SM_PROJECT_NO,
        crm_sirfis.TEL_SM_SUPPLIERNUMBER as SUPPLIER_NUMBER,
        crm_sirfis.TEL_SM_TELREGIONCODE as TEL_SM_TELREGIONCODE,
        crm_sirfis.TEL_SM_SITE as SITE,
        crm_sirfis.TEL_SM_TELPRODUCTCATEGORY as TEL_SM_TELPRODUCTCATEGORY,
        crm_sirfis.TEL_SM_CATEGORY as CATEGORY,
        opp.TEL_SM_ORDER_TYPENAME as TEL_SM_ORDER_TYPENAME,
        crm_sirfis.TEL_SM_PROCESS as PROCESS,
        crm_sirfis.TEL_SM_CEID as COPY_EXACT_ID,
        crm_sirfis.TEL_SM_ENTITY as ENTITY,
        opp.SM_CUSTOMER_TOOL_ID as SM_CUSTOMER_TOOL_ID,
        crm_sirfis.TEL_SM_PONUMBER || '-' || lpad(crm_sirfis.TEL_SM_POLINE, 5, '0') as PURCHASE_ORDER_LINE_ID,
        crm_sirfis.TEL_SM_PONUMBER as PURCHASE_ORDER_NUMBER,
        lpad(crm_sirfis.TEL_SM_POLINE, 5, '0') as PURCHASE_ORDER_LINE_NUMBER,
        opp.SM_PO_NO as SM_PO_NO,
        opp.TEL_SM_BOOKINGDATE as TEL_SM_BOOKINGDATE,
        opp.TEL_SM_PODATE as TEL_SM_PODATE,
        opp.SM_BOOK_AMOUNT as SM_BOOK_AMOUNT,
        opp.TEL_SM_ORDER_CONFIDENCE as TEL_SM_ORDER_CONFIDENCE,
        conf_options.LOCALIZEDLABEL as ORDER_CONFIDENCE,
        opp.TEL_SM_BOOKING_SALES_STATUS as TEL_SM_BOOKING_SALES_STATUS,
        booking_options.LOCALIZEDLABEL as BOOKING_SALES_STATUS,
        crm_sirfis.TEL_SM_MODEL as TEL_SM_MODEL,
        crm_sirfis.TEL_SM_TELMODELNAME as TEL_SM_TELMODELNAME,
        crm_sirfis.TEL_SM_TELMODELCODE as TEL_SM_TELMODELCODE,
        opp.TEL_SM_MATERIAL_NUMBER as TEL_SM_MATERIAL_NUMBER,
        crm_sirfis.TEL_SM_RTD as REQUESTED_TENDER_DATE,
        crm_sirfis.TEL_SM_NEWSTD as SUPPLIER_TENDER_DATE,
        crm_sirfis.TEL_SM_CTD as CONTRACTUAL_TENDER_DATE,
        crm_sirfis.TEL_SM_LASTSTD as LAST_SUPPLIER_TENDER_DATE,
        opp.TEL_SM_SHIPDATE as TEL_SM_SHIPDATE,
        opp.TEL_SM_CONFIRM_CUSTOMS_CLEARANCEDATE as TEL_SM_CONFIRM_CUSTOMS_CLEARANCEDATE,
        crm_sirfis.TEL_SM_READONLY as READ_ONLY,
        crm_sirfis.TEL_SM_SUPPLIERMAP as SUPPLIER_MAP,
        opp.SM_ACCOUNT_GROUP_CD as SM_ACCOUNT_GROUP_CD,
        opp.SM_ACCOUNT_GROUP_NAMENAME as SM_ACCOUNT_GROUP_NAMENAME,
        opp.SM_ACCOUNT_CD as SM_ACCOUNT_CD,
        opp.SM_ACCOUNT_NAMENAME as SM_ACCOUNT_NAMENAME,
        opp.NAME as NAME,
        opp.TEL_SM_SLOT_REQUIRED as TEL_SM_SLOT_REQUIRED,
        opp.TEL_SM_SLOT_RESERVED as TEL_SM_SLOT_RESERVED,
        opp._FILEDATE as FILEDATE
    from {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__CRM_FILE_TEL_SM_SIRFISFCST') }} as crm_sirfis
    left join {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__CRM_FILE_OPPORTUNITY') }} as opp on
        opp.ID = crm_sirfis.TEL_SM_OPPORTUNITYTITLE
    left join optionsetmetadata as conf_options on 
        conf_options.ENTITYNAME = 'opportunity' and 
        conf_options.OPTIONSETNAME = 'tel_sm_order_confidence' and 
        conf_options.OPTION = opp.TEL_SM_ORDER_CONFIDENCE
    left join optionsetmetadata as booking_options on 
        booking_options.ENTITYNAME = 'opportunity' and 
        booking_options.OPTIONSETNAME = 'tel_sm_booking_sales_status' and 
        booking_options.OPTION = opp.TEL_SM_BOOKING_SALES_STATUS
),


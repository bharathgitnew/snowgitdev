    	materialized='tel_incremental',
    	incremental_strategy='merge',
    	alias='SALES_CRM_OPPORTUNITY_FLOW',
    	unique_key=['OPPORTUNITY_ID'],
    	transient=false
) }} 


WITH SOURCE_DATA AS
(
    SELECT DISTINCT
    TEL_SM_CRM_OPPORTUNITY_ID, 
    NAME, 
    TEL_SM_OVERALL_STATUS, 
    TEL_SM_BOOKING_CONFIDENCE_ACCNT, 
    TEL_SM_ORDER_CONFIDENCE, 
    TEL_SM_BOOKING_SALES_STATUS, 
    SM_PO_NO, 
    TEL_SM_ENDUSER_BOOKING_AMOUNT, 
    TEL_SM_SHIPDATE, 
    TEL_SM_BOOKINGDATE, 
    TEL_SM_ENDUSER_BOOKINGDATE_ACCNT, 
    TEL_SM_ENDUSER_BOOKINGDATE, 
    TEL_SM_TECH_ACCEPT_TSR_CSTMR_SIGNDATE, 
    TEL_SM_PODATE, 
    tel_sm_enduser_bookingdate_act, 
    tel_sm_requested_ex_fctrydate, 
    tel_sm_local_subsidiary_po_receivedate, 
    statecode,
    tel_sm_sales_district, 
    sm_account_name
    FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__OPPORTUNITY') }}
    WHERE TEL_SM_CRM_OPPORTUNITY_ID IS NOT NULL
),

--going into snapshot history table to grab information not necessarily the latest...
SOURCE_DATA_DATES AS
(
    SELECT 
    OPPORTUNITY_ID,
    MIN(_FILEDATE) AS ADDED_DATE,
    MAX(_FILEDATE) AS LATEST_DATE
FROM 
    ( SELECT 
        TEL_SM_CRM_OPPORTUNITY_ID AS OPPORTUNITY_ID,
        _FILEDATE,
        ROW_NUMBER() OVER (PARTITION BY TEL_SM_CRM_OPPORTUNITY_ID ORDER BY _FILEDATE DESC) AS rn
    FROM 
        {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__OPPORTUNITY_SNAPSHOT') }}
    WHERE 
        TEL_SM_CRM_OPPORTUNITY_ID IS NOT NULL)
WHERE 
    rn = 1
GROUP BY 
    OPPORTUNITY_ID
), 

ACCOUNT as (
    select * from {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SALES_CRM_ACCOUNT') }}
),

--look up table for booking confident account level - moving it to ODS layer 
BOOKING_CONFIDENT as (
select DISTINCT 
		OPTION as BOOKING_CONFIDENCE_ACCNT_NBR,
		LOCALIZEDLABEL as BOOKING_CONFIDENCE_ACCNT_LVL
    FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__OPTIONSET_METADATA') }}
    where 
        ISUSERLOCALIZEDLABEL = 'False' 
        AND LOCALIZEDLABELLANGUAGECODE = '1033'
        AND ENTITYNAME = 'opportunity' 
        AND OPTIONSETNAME = 'tel_sm_booking_confidence_accnt' 

), 

--look up table for booking confidence BU level - Moving it to ODS layer after
BOOKING_CONFIDENT_BU as (
select DISTINCT 
		OPTION as BOOKING_CONFIDENCE_BU_NBR,
		LOCALIZEDLABEL as BOOKING_CONFIDENCE_BU_LVL
    FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__OPTIONSET_METADATA') }}
    where 
        ISUSERLOCALIZEDLABEL = 'False' 
        AND LOCALIZEDLABELLANGUAGECODE = '1033'
        AND ENTITYNAME = 'opportunity' 
        AND OPTIONSETNAME = 'tel_sm_order_confidence' 

), 

-- look up table for Booking Sales Status - Moving it to ODS layer after
BOOKING_SALES_STATUS as (
select DISTINCT 
		OPTIONSETNAME, 
		OPTION as BOOKING_SALES_STATUS_NBR,
		LOCALIZEDLABEL as BOOKING_SALES_STATUS
    FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__OPTIONSET_METADATA') }}
    where 
        ISUSERLOCALIZEDLABEL = 'False' 
        AND LOCALIZEDLABELLANGUAGECODE = '1033'
        AND ENTITYNAME = 'opportunity' 
        AND OPTIONSETNAME = 'tel_sm_booking_sales_status' 

), 

-- grabbing per each opportunity ID, latest information
SOURCE_DATA_MAIN AS
(SELECT DISTINCT 
        TEL_SM_CRM_OPPORTUNITY_ID as OPPORTUNITY_ID 
        , NAME AS OPPORTUNITY_TITLE
        , TEL_SM_OVERALL_STATUS AS STATUS_REASON_NBR
        , TEL_SM_BOOKING_CONFIDENCE_ACCNT AS BOOKING_CONFIDENCE_ACCNT_NBR
        , TEL_SM_ORDER_CONFIDENCE AS BOOKING_CONFIDENCE_BU_NBR
        , TEL_SM_BOOKING_SALES_STATUS AS BOOKING_SALES_STATUS_NBR
        , SM_PO_NO AS PURCHASE_ORDER_NBR
        , TEL_SM_ENDUSER_BOOKING_AMOUNT AS BOOKING_AMT
        , TEL_SM_SHIPDATE AS SHIP_DATE
        , TEL_SM_BOOKINGDATE AS BOOKING_DATE
        , TEL_SM_ENDUSER_BOOKINGDATE_ACCNT AS ACCNT_LVL_BOOKING_DATE
        , TEL_SM_ENDUSER_BOOKINGDATE AS END_USER_BOOKING_DATE
        , TEL_SM_TECH_ACCEPT_TSR_CSTMR_SIGNDATE AS TECHNICAL_ACCEPTANCE_DATE
        , TEL_SM_PODATE AS PURCHASE_ORDER_DATE
        , tel_sm_enduser_bookingdate_act AS IS_BOOKING_ACTUAL
        , tel_sm_requested_ex_fctrydate AS REQUESTED_EX_FACTORY_DATE
        , tel_sm_local_subsidiary_po_receivedate AS SUBSIDIARY_PO_RECEIPT_DATE
        , statecode AS STATE_CODE
        , tel_sm_sales_district
        , sm_account_name
        FROM SOURCE_DATA
), 

DISTRICT as (
    select DISTINCT 
      sales_district_id
    , tel_com_sales_district AS sales_district
    from {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__SALES_DISTRICT') }}
),

transform_data AS
(
    SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    d.OPPORTUNITY_ID,
    m.OPPORTUNITY_TITLE,
    bc.BOOKING_CONFIDENCE_ACCNT_LVL as BOOKING_CONFIDENCE_ACCT,
    bcbu.BOOKING_CONFIDENCE_BU_LVL AS BOOKING_CONFIDENCE_BU,
    UPPER(bs.BOOKING_SALES_STATUS) AS BOOKING_SALES_STATUS,
    d.ADDED_DATE, 
    d.LATEST_DATE, 
    --Account can be in ITEM CONFIGURATION
    ROUND(m.BOOKING_AMT, 0) AS BOOKING_AMT, 
    m.PURCHASE_ORDER_NBR, 
    --Milestone Dates begins
    TO_DATE(m.SHIP_DATE) AS SHIP_DATE, 
    TO_DATE(m.BOOKING_DATE) AS BOOKING_DATE, 
    TO_DATE(m.ACCNT_LVL_BOOKING_DATE) AS ACCNT_BOOKING_DATE, 
    TO_DATE(m.END_USER_BOOKING_DATE) AS END_USER_BOOKING_DATE, 
    TO_DATE(m.TECHNICAL_ACCEPTANCE_DATE) AS TECHNICAL_ACCEPTANCE_DATE,
    TO_DATE(m.PURCHASE_ORDER_DATE) AS PURCHASE_ORDER_DATE,
    CASE WHEN m.IS_BOOKING_ACTUAL ilike 'false' 
    THEN 'NO' ELSE 'YES' END AS IS_BOOKING_ACTUAL,
    CASE WHEN IS_BOOKING_ACTUAL = 'YES' AND BOOKING_DATE <=CURRENT_DATE() 
    THEN BOOKING_DATE ELSE NULL
    END AS ACTUAL_BOOKING_DATE,
    COALESCE(ACTUAL_BOOKING_DATE, ACCNT_BOOKING_DATE) AS ADJUSTED_ACCT_BOOKING_DATE,
    COALESCE(ACTUAL_BOOKING_DATE, END_USER_BOOKING_DATE) AS ADJUSTED_BU_BOOKING_DATE,
    m.REQUESTED_EX_FACTORY_DATE, 
    m.SUBSIDIARY_PO_RECEIPT_DATE, 
    CASE WHEN m.STATE_CODE = 2
    THEN 'NO' ELSE 'YES' END AS IS_ACTIVE
    FROM SOURCE_DATA_DATES d 
    LEFT JOIN SOURCE_DATA_MAIN m
    ON d.OPPORTUNITY_ID = m.OPPORTUNITY_ID
    LEFT JOIN BOOKING_CONFIDENT bc
    ON m.BOOKING_CONFIDENCE_ACCNT_NBR = bc.BOOKING_CONFIDENCE_ACCNT_NBR
    LEFT JOIN BOOKING_CONFIDENT_BU bcbu
    ON m.BOOKING_CONFIDENCE_BU_NBR = bcbu.BOOKING_CONFIDENCE_BU_NBR
    LEFT JOIN BOOKING_SALES_STATUS bs
    ON m.BOOKING_SALES_STATUS_NBR = bs.BOOKING_SALES_STATUS_NBR
    LEFT JOIN DISTRICT DIST
    ON m.tel_sm_sales_district = DIST.sales_district_id
    LEFT JOIN ACCOUNT accnt
    ON m.sm_account_name = accnt.account_id
    --AS PER Naoko Cole 2024-11-18
    WHERE UPPER(DIST.SALES_DISTRICT) || '-' || UPPER(accnt.SALES_ACCOUNT_TI)
    IN ('CHINA-INTEL', 'CHINA-TI', 	'EUROPE-GF/IBM', 'EUROPE-REGIONAL', 'EUROPE-TI', 'EUROPE-INTEL', 
    'EUROPE-MICRON', 'NORTH AMERICA-TI', 'NORTH AMERICA-INTEL', 'NORTH AMERICA-MICRON', 'NORTH AMERICA-REGIONAL', 	
    'NORTH AMERICA-GF/IBM', 'NORTH AMERICA-TSMC', 'NORTH AMERICA-SAMSUNG', 	
    'NORTH AMERICA-TEL GROUP', 	'SEA & OTHERS-TI', 	'SEA & OTHERS-INTEL', 	'SEA & OTHERS-MICRON' 
        ) 
), 

TYPE_DATA AS
( SELECT
  CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID, 
  CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
  OPPORTUNITY_ID,
  OPPORTUNITY_TITLE,
  BOOKING_CONFIDENCE_ACCT,
  BOOKING_CONFIDENCE_BU,
  BOOKING_SALES_STATUS,
  CAST(ADDED_DATE AS DATE) AS ADDED_DATE,
  CAST(LATEST_DATE AS DATE) AS LATEST_DATE,
  PURCHASE_ORDER_NBR,
  CAST(BOOKING_AMT AS NUMBER(38,0)) AS BOOKING_AMT,
  --Milestone dates
  CAST(SHIP_DATE AS DATE) AS SHIP_DATE,
  CAST(BOOKING_DATE AS DATE) AS BOOKING_DATE,
  CAST(ACCNT_BOOKING_DATE AS DATE) AS ACCNT_BOOKING_DATE,
  CAST(END_USER_BOOKING_DATE AS DATE) AS BU_BOOKING_DATE,
  CAST(TECHNICAL_ACCEPTANCE_DATE AS DATE) AS TECHNICAL_ACCEPTANCE_DATE,
  CAST(PURCHASE_ORDER_DATE AS DATE) AS PURCHASE_ORDER_DATE, 
  IS_BOOKING_ACTUAL, 
  CAST(ACTUAL_BOOKING_DATE AS DATE) AS ACTUAL_BOOKING_DATE,
  CAST(ADJUSTED_ACCT_BOOKING_DATE AS DATE) AS ADJUSTED_ACCT_BOOKING_DATE,
  CAST(ADJUSTED_BU_BOOKING_DATE AS DATE) AS ADJUSTED_BU_BOOKING_DATE,
  CAST(REQUESTED_EX_FACTORY_DATE AS DATE) AS REQUESTED_EX_FACTORY_DATE,
  CAST(SUBSIDIARY_PO_RECEIPT_DATE AS DATE) AS SUBSIDIARY_PO_RECEIPT_DATE, 
  IS_ACTIVE
  FROM transform_data
)

SELECT *
FROM TYPE_DATA
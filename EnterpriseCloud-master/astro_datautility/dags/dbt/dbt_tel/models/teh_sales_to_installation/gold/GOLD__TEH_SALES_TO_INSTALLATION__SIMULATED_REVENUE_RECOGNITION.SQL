sirfis_rtd_churn_history AS (
SELECT ID,
PREVIOUS_RTD
FROM
(SELECT DISTINCT ID, 
TO_DATE(_APPENDEDDATE) AS CHANGE_TO_DATE, 
TO_DATE(REQUESTED_TENDER_DATE) AS REQUESTED_TENDER_DATE,
TO_DATE(PREVIOUS_RTD) AS PREVIOUS_RTD, 
ROW_NUMBER() OVER (PARTITION BY ID ORDER BY _APPENDEDDATE DESC) AS REVISION_DESC_ORDER
FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__SIRFIS_EVENT_CHANGE_HISTORY') }}
WHERE IS_RTD_CHURN = 1 
) WHERE REVISION_DESC_ORDER = 1
),

source_data_sirfis_previous_rtd AS (
    SELECT DISTINCT 
        sirfis_unique_rtd_counts.ID
        , CASE WHEN sirfis_unique_rtd_counts.NUM_UNIQUE_RTDS = 1 THEN SIRFIS_LIFECYCLE_RTD_DATES.INITIAL_RTD
             WHEN sirfis_unique_rtd_counts.NUM_UNIQUE_RTDS = 2 THEN SIRFIS_LIFECYCLE_RTD_DATES.INITIAL_RTD
             WHEN sirfis_unique_rtd_counts.NUM_UNIQUE_RTDS > 2 THEN sirfis_rtd_churn_history.PREVIOUS_RTD
          END AS PREVIOUS_RTD
    FROM SIRFIS_UNIQUE_RTD_COUNTS 
    LEFT JOIN SIRFIS_LIFECYCLE_RTD_DATES
    ON SIRFIS_UNIQUE_RTD_COUNTS.ID = SIRFIS_LIFECYCLE_RTD_DATES.ID
    LEFT JOIN sirfis_rtd_churn_history
    ON sirfis_unique_rtd_counts.ID = sirfis_rtd_churn_history.ID

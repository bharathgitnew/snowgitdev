      incremental_strategy='insert_overwrite',
      alias='SIRFIS_ITEM_EVALUATION',
      transient=false
) }}

WITH SIRFIS_ITEM_RTD_CHURN_SEVERITY as
(
    SELECT DISTINCT ID,
                TO_DATE(REQUESTED_TENDER_DATE) as REQUESTED_TENDER_DATE,
                TO_DATE(_APPENDEDDATE) as CHURN_CALENDAR_DATE,
                ROW_NUMBER() OVER (PARTITION BY ID ORDER BY _APPENDEDDATE DESC) as REVISION_DESC_ORDER
    FROM
        {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__SIRFIS_EVENT_CHANGE_HISTORY') }}
    WHERE IS_RTD_CHURN = 1
)
,SIRFIS_ITEM_LAST_CHURN_RECORD AS
(   SELECT 
        DISTINCT HISTORY.ID,
        TO_DATE(HISTORY.REQUESTED_TENDER_DATE) as REQUESTED_TENDER_DATE,
        TO_DATE(HISTORY._APPENDEDDATE) as CHURN_CALENDAR_DATE,
        HISTORY.STATUS_KEY
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }} HISTORY
    LEFT JOIN SIRFIS_ITEM_RTD_CHURN_SEVERITY SEVERITY
        ON HISTORY.STATUS_KEY = SEVERITY.ID || '-' || SEVERITY.CHURN_CALENDAR_DATE
    WHERE SEVERITY.REVISION_DESC_ORDER = 1
)
,SIRFIS_ITEM_RTD_CHURN as
(
    SELECT 
        DISTINCT ID,
        COUNT(DISTINCT REQUESTED_TENDER_DATE) as NUM_RTD_CHURNS
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }} 
    GROUP BY 1
)
,SIRFIS_ITEM_INITIAL_LT AS
(
    SELECT 
        DISTINCT ID,
        TO_DATE(_APPENDEDDATE) as ENTERED_DATE,
        BUILD_TIME,
        REQUESTED_TENDER_DATE as INITIAL_REQUESTED_TENDER_DATE
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
    WHERE REVISION_ASC_ORDER=1
)
,SIRFIS_ITEM_LATEST_BT AS
(       SELECT 
            DISTINCT ID,
            BUILD_TIME AS LATEST_BT
        FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
        WHERE REVISION_DESC_ORDER = 1
)
,SOURCE_DATA AS
(       SELECT 
            DISTINCT ID,
            CATEGORY as LATEST_CATEGORY,
            BUSINESS_UNIT_SHORT_TEXT as LATEST_BU                  
        FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__SIRFIS_ITEM_HIERARCHY') }}
)
,transform_data AS
(
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        SOURCE_DATA.ID,
        CASE 
            WHEN SIRFIS_ITEM_RTD_CHURN.NUM_RTD_CHURNS = 1 THEN 0
            WHEN SIRFIS_ITEM_RTD_CHURN.NUM_RTD_CHURNS > 1 THEN 1
        END AS IS_RTD_CHURN,
        CASE 
            WHEN SOURCE_DATA.LATEST_CATEGORY NOT IN ('MT', 'PK', 'PKD') THEN NULL
            WHEN SOURCE_DATA.LATEST_BU = 'TS' THEN NULL
            WHEN SOURCE_DATA.LATEST_BU <> 'TS' AND SOURCE_DATA.LATEST_CATEGORY IN ('MT', 'PK', 'PKD') AND SIRFIS_ITEM_LATEST_BT.LATEST_BT < 100
                THEN TO_DATE(DATEADD(day, -(100 + 70), SIRFIS_ITEM_INITIAL_LT.INITIAL_REQUESTED_TENDER_DATE))
            WHEN SOURCE_DATA.LATEST_BU <> 'TS' AND SOURCE_DATA.LATEST_CATEGORY IN ('MT', 'PK', 'PKD') AND SIRFIS_ITEM_LATEST_BT.LATEST_BT >= 100
                THEN TO_DATE(DATEADD(day, -(SIRFIS_ITEM_LATEST_BT.LATEST_BT + 70), SIRFIS_ITEM_INITIAL_LT.INITIAL_REQUESTED_TENDER_DATE))
            ELSE NULL
        END AS INITIAL_FSCT_NEEDED_BY_DATE,
        CASE 
            WHEN INITIAL_FSCT_NEEDED_BY_DATE IS NOT NULL AND INITIAL_FSCT_NEEDED_BY_DATE >= TO_DATE(SIRFIS_ITEM_INITIAL_LT.ENTERED_DATE)
                THEN 1
            WHEN INITIAL_FSCT_NEEDED_BY_DATE IS NOT NULL AND INITIAL_FSCT_NEEDED_BY_DATE < TO_DATE(SIRFIS_ITEM_INITIAL_LT.ENTERED_DATE)
                THEN 0
            ELSE NULL
        END AS INITIAL_FCST_LT_TYPE,
        CASE 
            WHEN IS_RTD_CHURN = 0 THEN INITIAL_FSCT_NEEDED_BY_DATE
            WHEN IS_RTD_CHURN = 1 AND SOURCE_DATA.LATEST_BU <> 'TS' AND SOURCE_DATA.LATEST_CATEGORY IN ('MT', 'PK', 'PKD') AND SIRFIS_ITEM_LATEST_BT.LATEST_BT < 100
                THEN TO_DATE(DATEADD(day, -(100 + 70), SIRFIS_ITEM_LAST_CHURN_RECORD.REQUESTED_TENDER_DATE))
            WHEN IS_RTD_CHURN = 1 AND SOURCE_DATA.LATEST_BU <> 'TS' AND SOURCE_DATA.LATEST_CATEGORY IN ('MT', 'PK', 'PKD') AND SIRFIS_ITEM_LATEST_BT.LATEST_BT >= 100
                THEN TO_DATE(DATEADD(day, -(SIRFIS_ITEM_LATEST_BT.LATEST_BT + 70), SIRFIS_ITEM_LAST_CHURN_RECORD.REQUESTED_TENDER_DATE))
            ELSE NULL
        END AS LATEST_FSCT_NEEDED_BY_DATE,
        CASE 
            WHEN IS_RTD_CHURN = 0 THEN INITIAL_FCST_LT_TYPE
            WHEN IS_RTD_CHURN = 1 AND LATEST_FSCT_NEEDED_BY_DATE IS NOT NULL AND LATEST_FSCT_NEEDED_BY_DATE >= SIRFIS_ITEM_LAST_CHURN_RECORD.CHURN_CALENDAR_DATE
                THEN 1
            WHEN SIRFIS_ITEM_RTD_CHURN.NUM_RTD_CHURNS > 1 AND LATEST_FSCT_NEEDED_BY_DATE IS NOT NULL AND LATEST_FSCT_NEEDED_BY_DATE < SIRFIS_ITEM_LAST_CHURN_RECORD.CHURN_CALENDAR_DATE
                THEN 0
        END AS LATEST_FCST_LT_TYPE
    FROM SOURCE_DATA
    LEFT JOIN SIRFIS_ITEM_INITIAL_LT
    ON SOURCE_DATA.ID = SIRFIS_ITEM_INITIAL_LT.ID
    LEFT JOIN SIRFIS_ITEM_RTD_CHURN
    ON SOURCE_DATA.ID = SIRFIS_ITEM_RTD_CHURN.ID
    LEFT JOIN SIRFIS_ITEM_LATEST_BT
    ON SOURCE_DATA.ID = SIRFIS_ITEM_LATEST_BT.ID
    LEFT JOIN SIRFIS_ITEM_LAST_CHURN_RECORD
    ON SOURCE_DATA.ID = SIRFIS_ITEM_LAST_CHURN_RECORD.ID
)
,type_data as (
    SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    ID,
    CAST(IS_RTD_CHURN AS NUMBER(1,0)) AS IS_RTD_CHURN,
    CAST(INITIAL_FSCT_NEEDED_BY_DATE AS DATE) AS INITIAL_FSCT_NEEDED_BY_DATE,
    CAST(INITIAL_FCST_LT_TYPE AS NUMBER(1,0)) AS INITIAL_FCST_LT_TYPE,
    CAST(LATEST_FSCT_NEEDED_BY_DATE AS DATE) AS LATEST_FSCT_NEEDED_BY_DATE,
    CAST(LATEST_FCST_LT_TYPE AS NUMBER(1,0)) AS LATEST_FCST_LT_TYPE
    FROM TRANSFORM_DATA
             )
  
SELECT * from type_data
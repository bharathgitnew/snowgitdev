      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='SIRFIS_CONFIG_PO_BT_CHANGE_HISTORY',
      transient=false
) }}

with source_data as (
    SELECT DISTINCT ID,
        _APPENDEDDATE as EVENT_DATE,
        REQUESTED_TENDER_DATE,
        LAG(BUILD_TIME) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_BUILD_TIME,
        BUILD_TIME,
        CASE WHEN BUILD_TIME = '' OR LAG(BUILD_TIME) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) = '' THEN NULL
        WHEN (BUILD_TIME <> '' OR LAG(BUILD_TIME) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) <> '')
        AND BUILD_TIME <> LAG(BUILD_TIME) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE ASC) THEN 1 ELSE NULL END AS IS_BUILDTIME_CHURN,
        LAG(PURCHASE_ORDER_KEY) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_PO_NUMBER,
        PURCHASE_ORDER_KEY,
        CASE WHEN PURCHASE_ORDER_KEY = '' OR LAG(PURCHASE_ORDER_KEY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) = '' THEN NULL
        WHEN (PURCHASE_ORDER_KEY <> '' OR LAG(PURCHASE_ORDER_KEY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) <> '')
        AND PURCHASE_ORDER_KEY <> LAG(PURCHASE_ORDER_KEY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE ASC) THEN 1 ELSE NULL END AS IS_PO_CHURN,
        LAG(CATEGORY) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_CATEGORY,
        CATEGORY,
        CASE WHEN LAG(CATEGORY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) IS NULL 
            THEN NULL
            WHEN LAG(CATEGORY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) = CATEGORY THEN NULL
            WHEN LAG(CATEGORY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) <> CATEGORY THEN 1 END AS IS_CATEGORY_CHURN,
        LAG(COPY_EXACT_ID) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_CEID,
        COPY_EXACT_ID AS CEID,
        CASE WHEN COPY_EXACT_ID = '' OR LAG(COPY_EXACT_ID) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) = '' THEN NULL
        WHEN (COPY_EXACT_ID <> '' OR LAG(COPY_EXACT_ID) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) <> '')
        AND COPY_EXACT_ID <> LAG(COPY_EXACT_ID) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE ASC) THEN 1 ELSE NULL END AS IS_CEID_CHURN,
        LAG(ENTITY) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_ENTITY,
        ENTITY,
        CASE WHEN LAG(ENTITY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) IS NULL 
            THEN NULL
            WHEN LAG(ENTITY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) = ENTITY THEN NULL
            WHEN LAG(ENTITY) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) <> ENTITY THEN 1 END AS IS_ENTITY_CHURN,
        LAG(PROCESS) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_PROCESS,
        PROCESS,
        CASE WHEN LAG(PROCESS) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) IS NULL 
            THEN NULL
            WHEN LAG(PROCESS) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) = PROCESS THEN NULL
            WHEN LAG(PROCESS) OVER (PARTITION BY ID ORDER BY _APPENDEDDATE) <> PROCESS THEN 1 END AS IS_PROCESS_CHURN
     FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        ID,
        EVENT_DATE,
        REQUESTED_TENDER_DATE,
        PREVIOUS_BUILD_TIME,
        BUILD_TIME,
        IS_BUILDTIME_CHURN,
        PREVIOUS_PO_NUMBER,
        PURCHASE_ORDER_KEY,
        IS_PO_CHURN,
        PREVIOUS_CATEGORY,
        CATEGORY,
        IS_CATEGORY_CHURN,
        PREVIOUS_CEID,
        CEID,
        IS_CEID_CHURN,
        PREVIOUS_ENTITY,
        ENTITY,
        IS_ENTITY_CHURN,
        PREVIOUS_PROCESS,
        PROCESS,
        IS_PROCESS_CHURN
    from source_data
),

type_data as (
    select
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ID,
        CAST(EVENT_DATE AS DATE) AS EVENT_DATE,
        CAST(REQUESTED_TENDER_DATE AS DATE) AS REQUESTED_TENDER_DATE,
        PREVIOUS_BUILD_TIME,
        BUILD_TIME,
        CAST(IS_BUILDTIME_CHURN AS NUMBER(38,0)) AS IS_BUILDTIME_CHURN,
        PREVIOUS_PO_NUMBER,
        PURCHASE_ORDER_KEY,
        CAST(IS_PO_CHURN AS NUMBER(38,0)) AS IS_PO_CHURN,
        PREVIOUS_CATEGORY,
        CATEGORY,
        CAST(IS_CATEGORY_CHURN AS NUMBER(38,0)) AS IS_CATEGORY_CHURN,
        PREVIOUS_CEID,
        CEID,
        CAST(IS_CEID_CHURN AS NUMBER(38,0)) AS IS_CEID_CHURN,
        PREVIOUS_ENTITY,
        ENTITY,
        CAST(IS_ENTITY_CHURN AS NUMBER(38,0)) AS IS_ENTITY_CHURN,
        PREVIOUS_PROCESS,
        PROCESS,
        CAST(IS_PROCESS_CHURN AS NUMBER(38,0)) AS IS_PROCESS_CHURN
    from transform_data
)

select * from type_data
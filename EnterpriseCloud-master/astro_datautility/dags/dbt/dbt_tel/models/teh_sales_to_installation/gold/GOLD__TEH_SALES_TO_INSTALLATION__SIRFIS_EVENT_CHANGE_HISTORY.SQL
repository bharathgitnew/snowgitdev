with source_data AS (
    SELECT 
        DISTINCT ID, 
        _APPENDEDDATE,
        LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_RTD,
        REQUESTED_TENDER_DATE,
        LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER(PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_STD,
        COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE) AS ALL_STD_RESPONSES,
        LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE) AS PREVIOUS_CTD,
        CONTRACTUAL_TENDER_DATE,
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),REQUESTED_TENDER_DATE),0) = 0 THEN NULL ELSE 1 END AS IS_RTD_CHURN, 
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),REQUESTED_TENDER_DATE),0) < 0 THEN 'PULL'
             WHEN IFNULL(DATEDIFF(DAY,LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),REQUESTED_TENDER_DATE),0) > 0 THEN 'PUSH' ELSE NULL END AS RTD_CHURN_TYPE,
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),REQUESTED_TENDER_DATE),0) < 0 THEN ABS(IFNULL(DATEDIFF(DAY,LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),REQUESTED_TENDER_DATE),0))
             WHEN IFNULL(DATEDIFF(DAY,LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),REQUESTED_TENDER_DATE),0) = 0 THEN NULL
             ELSE ABS(IFNULL(DATEDIFF(DAY,LAG(REQUESTED_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),REQUESTED_TENDER_DATE),0)) END AS RTD_PUSH_PULL_DAYS,
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)),0) = 0 THEN NULL ELSE 1 END AS IS_STD_CHURN, 
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)),0) < 0 THEN 'PULL'
             WHEN IFNULL(DATEDIFF(DAY,LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)),0) > 0 THEN 'PUSH'
             ELSE NULL END AS STD_CHURN_TYPE,
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)),0) < 0 THEN ABS(IFNULL(DATEDIFF(DAY,LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)),0))
             WHEN IFNULL(DATEDIFF(DAY,LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)),0) = 0 THEN NULL
             ELSE ABS(IFNULL(DATEDIFF(DAY,LAG(COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE)),0)) END AS STD_PUSH_PULL_DAYS, 
             CASE WHEN IFNULL(DATEDIFF(DAY,LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),CONTRACTUAL_TENDER_DATE),0) = 0 THEN NULL ELSE 1 END AS IS_CTD_CHURN, 
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),CONTRACTUAL_TENDER_DATE),0) < 0 THEN 'PULL'
             WHEN IFNULL(DATEDIFF(DAY,LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),CONTRACTUAL_TENDER_DATE),0) > 0 THEN 'PUSH' ELSE NULL END AS CTD_CHURN_TYPE,
        CASE WHEN IFNULL(DATEDIFF(DAY,LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),CONTRACTUAL_TENDER_DATE),0) < 0 THEN ABS(IFNULL(DATEDIFF(DAY,LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),CONTRACTUAL_TENDER_DATE),0))
             WHEN IFNULL(DATEDIFF(DAY,LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),CONTRACTUAL_TENDER_DATE),0) = 0 THEN NULL
             ELSE ABS(IFNULL(DATEDIFF(DAY,LAG(CONTRACTUAL_TENDER_DATE) OVER (PARTITION BY [ID] ORDER BY _APPENDEDDATE),CONTRACTUAL_TENDER_DATE),0)) END AS CTD_PUSH_PULL_DAYS
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY') }}
),

transform_data AS
(   
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        ID AS ID,
        _APPENDEDDATE AS _APPENDEDDATE,
        PREVIOUS_RTD,
        REQUESTED_TENDER_DATE AS REQUESTED_TENDER_DATE,
        PREVIOUS_STD, 
        ALL_STD_RESPONSES AS ALL_STD_RESPONSES,
        PREVIOUS_CTD,
        CONTRACTUAL_TENDER_DATE,
        IS_RTD_CHURN AS IS_RTD_CHURN,
        RTD_CHURN_TYPE AS RTD_CHURN_TYPE,
        RTD_PUSH_PULL_DAYS AS RTD_PUSH_PULL_DAYS,
        IS_STD_CHURN AS IS_STD_CHURN,
        STD_CHURN_TYPE AS STD_CHURN_TYPE,
        STD_PUSH_PULL_DAYS AS STD_PUSH_PULL_DAYS, 
        IS_CTD_CHURN, 
        CTD_CHURN_TYPE, 
        CTD_PUSH_PULL_DAYS
    FROM source_data
)

,type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ID,
        CAST(_APPENDEDDATE AS DATE) AS _APPENDEDDATE,
        CAST(PREVIOUS_RTD AS DATE) AS PREVIOUS_RTD,
        CAST(REQUESTED_TENDER_DATE AS DATE) AS REQUESTED_TENDER_DATE,
        CAST(PREVIOUS_STD AS DATE) AS PREVIOUS_STD,
        CAST(ALL_STD_RESPONSES AS DATE) AS ALL_STD_RESPONSES,
        CAST(PREVIOUS_CTD AS DATE) AS PREVIOUS_CTD,
        CAST(CONTRACTUAL_TENDER_DATE AS DATE) AS CONTRACTUAL_TENDER_DATE,
        CAST(IS_RTD_CHURN AS NUMBER(1,0)) AS IS_RTD_CHURN,
        RTD_CHURN_TYPE,
        CAST(RTD_PUSH_PULL_DAYS AS NUMBER(9,0)) AS RTD_PUSH_PULL_DAYS,
        CAST(IS_STD_CHURN AS NUMBER(1,0)) AS IS_STD_CHURN,
        STD_CHURN_TYPE,
        CAST(STD_PUSH_PULL_DAYS AS NUMBER(9,0)) AS STD_PUSH_PULL_DAYS, 
        CAST(IS_CTD_CHURN AS NUMBER(1,0)) AS IS_CTD_CHURN,
        CTD_CHURN_TYPE,
        CAST(CTD_PUSH_PULL_DAYS AS NUMBER(9,0)) AS CTD_PUSH_PULL_DAYS
    FROM transform_data
)

SELECT * from type_data
amt_churn
AS (
	SELECT DISTINCT PURCHASE_ORDER_LINE_ID,
		CASE
			WHEN COUNT(DISTINCT TOTAL_AMOUNT) > 1
				THEN 1
			WHEN COUNT(DISTINCT TOTAL_AMOUNT) = 1
				THEN 0
			END AS IS_TOTAL_AMT_CHURN
	FROM purchase_order_change_order_src
	GROUP BY 1
	),
purchase_order_change_order_source
AS (
	SELECT
		co.PURCHASE_ORDER_LINE_ID,
		PURCHASE_ORDER_NUMBER,
		PURCHASE_ORDER_LINE_NUMBER,
		REVISION_NUMBER AS LATEST_REVISION_NUMBER,
		QUOTE_ID,
		UPPER(RECORD_TYPE) AS LATEST_RECORD_TYPE,
		PURCHASE_ORDER_TIMESTAMP AS LATEST_PURCHASE_ORDER_TIMESTAMP,
		LOAD_TIMESTAMP AS LATEST_LOAD_TIMESTAMP,
		REVISION_TIMESTAMP AS LATEST_REVISION_TIMESTAMP,
		PURCHASE_ORDER_TYPE,
		PURCHASE_TYPE,
		NET_TERMS_DAYS,
		PERCENT_DUE,
		REQUESTED_QTY,
		UNIT_OF_MEASURE,
		FREIGHT_ON_BOARD,
		INCO_TERM,
		CURRENCY,
		REQUESTED_UNIT_PRICE,
		LINE_AMOUNT,
		TOTAL_AMOUNT,
		TAX_EXEMPT,
		TAX_EXEMPT_CODE,
		CUSTOMER_ITEM_NUMBER,
		ACCOUNT_NUMBER,
		ITEM_DESCRIPTION,
		TRIM(REGEXP_REPLACE(ITEM_DESCRIPTION, '\\([^)]*\\)', '')) AS ITEM_DESCRIPTION_BRACKET_REMOVED,
		PURCHASE_ORDER_LINE_STATUS AS LATEST_PURCHASE_ORDER_LINE_STATUS,
		OVERALL_STATUS AS LATEST_OVERALL_STATUS,
		TEL_HEADER_STATUS AS LATEST_TEL_HEADER_STATUS,
		TEL_LINE_STATUS AS LATEST_TEL_LINE_STATUS,
		HEADER_REASON AS LATEST_HEADER_REASON,
		LINE_REASON AS LATEST_LINE_REASON,
		PURCHASE_ORDER_ACCEPTANCE_DATE,
		LPAD(PURCHASE_ORDER_ACCEPTANCE_REVISION_NUMBER, 2, '0') AS PURCHASE_ORDER_ACCEPTANCE_REVISION_NUMBER,
		REQUESTED_TENDER_DATE,
		PURCHASE_ORDER_REV_ACTION_TIMESTAMP,
		CASE
			WHEN IS_PART_ORDER = 'No'
				THEN 0
			ELSE 1
			END AS IS_PART_ORDER,
		ORIGINAL_BUSINESS_UNIT,
		SUB_BUSINESS_UNIT,
		CATEGORY_SHORT_TEXT AS CATEGORY,
		UPPER(SITE) AS SITE,
		MODEL,
		COPY_EXACT_ID,
		ENTITY,
		PROCESS,
		SHIPPING_TO_NAME,
		SHIPPING_SERVICE_LEVEL_CODE,
		SHIP_TO_COUNTRY,
		SHIP_TO_REGION,
		SHIP_TO_CITY,
		SHIPPING_CONDITION,
		SHIP_TO_ADDRESS,
		SPECIAL_HANDLING_INSTRUCTION,
		BILL_TO_NAME,
		BILL_TO_COUNTRY,
		BILL_TO_REGION,
		BILL_TO_CITY,
		BILL_TO_LOCATION_ID,
		BILL_TO_ADDRESS,
		      --For CK, Condition I
        CASE WHEN CATEGORY_SHORT_TEXT = 'CK'
               AND ORIGINAL_BUSINESS_UNIT = 'TS'
               AND ITEM_DESCRIPTION like '%CNV KIT%' THEN
                CONCAT(
                    CATEGORY_SHORT_TEXT, '-',
                    -- Extract skip tokens after 'CNV KIT'
                    REGEXP_SUBSTR(ITEM_DESCRIPTION_BRACKET_REMOVED, '[^ \\-]+', 1, 3), '-',
                    REGEXP_SUBSTR(ITEM_DESCRIPTION_BRACKET_REMOVED, '[^ \\-]+', 1, 5)
                      )
         --For CK, condition II
               WHEN CATEGORY_SHORT_TEXT = 'CK'
               AND ORIGINAL_BUSINESS_UNIT <> 'TS'
               AND ITEM_DESCRIPTION like '%CNV KIT%' THEN
                CONCAT(
                    CATEGORY_SHORT_TEXT, '-',
                    -- Extract 4 tokens after 'CNV KIT'
                    REGEXP_SUBSTR(ITEM_DESCRIPTION_BRACKET_REMOVED, '[^ \\-]+', 1, 3), '-',
                    REGEXP_SUBSTR(ITEM_DESCRIPTION_BRACKET_REMOVED, '[^ \\-]+', 1, 4), '-',
                    REGEXP_SUBSTR(ITEM_DESCRIPTION_BRACKET_REMOVED, '[^ \\-]+', 1, 5), '-',
                    REGEXP_SUBSTR(ITEM_DESCRIPTION_BRACKET_REMOVED, '[^ \\-]+', 1, 6)
                )
          --For CK, condition III
             WHEN CATEGORY_SHORT_TEXT = 'CK'
                  AND ORIGINAL_BUSINESS_UNIT = 'TS'
                  AND ITEM_DESCRIPTION NOT LIKE '%CNV KIT%' THEN
                CONCAT(
                    CATEGORY_SHORT_TEXT, '-',
                    -- Left part before TO
                    REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION_BRACKET_REMOVED, ' TO ', 1), '^[^/\\\- ]+'), '\\', ''), '-',
                   -- REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION, ' TO ', 1), '[^/\\\- ]+$'), '\\', ''), '-',
                    -- Right part after TO
                    REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION_BRACKET_REMOVED, ' TO ', 2), '^[^/\\\- ]+'), '\\', '')
                   -- REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION, ' TO ', 2), '[^/\\\- ]+$'), '\\', '')
                      )
            --For CK, condition IV
             WHEN CATEGORY_SHORT_TEXT = 'CK'
                  AND ORIGINAL_BUSINESS_UNIT <> 'TS'
                  AND ITEM_DESCRIPTION NOT LIKE '%CNV KIT%' THEN
                CONCAT(
                    CATEGORY_SHORT_TEXT, '-',
                    -- Left part before TO
                    REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION_BRACKET_REMOVED, ' TO ', 1), '^[^/\\\- ]+'), '\\', ''), '-',
                    REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION_BRACKET_REMOVED, ' TO ', 1), '[^/\\\- ]+$'), '\\', ''), '-',
                    --Right part after TO
                    REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION_BRACKET_REMOVED, ' TO ', 2), '^[^/\\\- ]+'), '\\', ''), '-',
                    REPLACE(REGEXP_SUBSTR(SPLIT_PART(ITEM_DESCRIPTION_BRACKET_REMOVED, ' TO ', 2), '[^/\\\- ]+$'), '\\', '')
                      )
        ELSE CONCAT(CATEGORY_SHORT_TEXT, '-', UPPER(COPY_EXACT_ID), '-', PROCESS)
        END AS PRICE_KEY,
		IS_TOTAL_AMT_CHURN,
		NET_TERMS_DAYS2,
		PERCENT_DUE2,
		DETECTED_QUOTE_NUMBER
	FROM purchase_order_change_order_src co
	INNER JOIN amt_churn AS amt_churn ON co.PURCHASE_ORDER_LINE_ID = amt_churn.PURCHASE_ORDER_LINE_ID
	WHERE REVISION_DESC_ORDER = 1
	),

WITH ACTION_REQUEST_FORM_LATEST AS
(
SELECT DISTINCT 
REQUEST_NUMBER,
FIRST_VALUE(STATUS) OVER (PARTITION BY REQUEST_NUMBER ORDER BY REV DESC) as ARF_STATUS,
FIRST_VALUE(Product_Line) OVER (PARTITION BY REQUEST_NUMBER ORDER BY REV DESC) as BUSINESS_UNIT, 
FIRST_VALUE(Fab) OVER (PARTITION BY REQUEST_NUMBER ORDER BY REV DESC) as SITE,
FIRST_VALUE(MODEL) OVER (PARTITION BY REQUEST_NUMBER ORDER BY REV DESC) as MODEL,
FIRST_VALUE(NODES) OVER (PARTITION BY REQUEST_NUMBER ORDER BY REV DESC) as PROCESS,
FIRST_VALUE(DESCRIPTION) OVER (PARTITION BY REQUEST_NUMBER ORDER BY REV DESC) as DESCRIPTION,
FIRST_VALUE(Specific_Request_Type) OVER (PARTITION BY REQUEST_NUMBER ORDER BY REV DESC) as REQUEST_TYPE
FROM {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }}
WHERE REQTYPE = 'ARF'
), 
QUOTE_REQUEST_FORM_HISTORY AS
 ( SELECT DISTINCT 
REQUEST_NUMBER, 
LPAD(REV, 2, '00') AS QRF_REVISION_NUMBER,
UPPER(STATUS) AS QRF_STATUS,
CASE WHEN REV = '0' THEN TO_DATE(REQUEST_DATE) ELSE TO_DATE(PUBLISH_DATE_REGION) END AS QRF_INTEL_REQUEST_DATE,
TO_DATE(PUBLISH_DATE_REGION) AS QRF_TEL_PUBLISH_DATE, 
TO_DATE(REQUEST_REVISION_DATE) AS QRF_REVISION_DATE
FROM {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }}
WHERE REQTYPE = 'QRF' 
)
,
REVERTED_REV_POS_PARTIAL AS
(SELECT 
DISTINCT REQUEST_NUMBER 
, LPAD(TO_NUMBER(MAX(REV))+1, 2, '00') AS SUBMITTED_POS
FROM {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }}
WHERE UPPER(STATUS) = 'REVERTED'
AND REQTYPE = 'QRF'
GROUP BY 1
), 
REVERTED_REV_POS_COMPLETE AS (
SELECT DISTINCT main.REQUEST_NUMBER, 
CASE WHEN FIRST_VALUE(main.QRF_STATUS) OVER (PARTITION BY main.REQUEST_NUMBER ORDER BY main.QRF_REVISION_NUMBER DESC) = 'REVERTED'
THEN FIRST_VALUE(main.QRF_REVISION_NUMBER) OVER (PARTITION BY main.REQUEST_NUMBER ORDER BY main.QRF_REVISION_NUMBER DESC)
WHEN SUM(TO_NUMBER(CONTAINS(main.QRF_STATUS, 'REVERTED'))) OVER (PARTITION BY main.REQUEST_NUMBER) > 0 
AND FIRST_VALUE(main.QRF_STATUS) OVER (PARTITION BY main.REQUEST_NUMBER ORDER BY main.QRF_REVISION_NUMBER DESC) <> 'REVERTED'
THEN partial.SUBMITTED_POS
ELSE NULL END AS SUBMITTED_POS_FINAL
FROM QUOTE_REQUEST_FORM_HISTORY main
LEFT JOIN REVERTED_REV_POS_PARTIAL partial
ON main.REQUEST_NUMBER = partial.REQUEST_NUMBER
), 
GET_REVERTED_INITIAL_SUBMITTED_DATE AS (
SELECT DISTINCT m.REQUEST_NUMBER,
 m.QRF_REVISION_NUMBER,
 m.QRF_INTEL_REQUEST_DATE, 
 m.QRF_TEL_PUBLISH_DATE
 FROM QUOTE_REQUEST_FORM_HISTORY m
 INNER JOIN REVERTED_REV_POS_COMPLETE p
 ON m.REQUEST_NUMBER = p.REQUEST_NUMBER
 AND m.QRF_REVISION_NUMBER = p.SUBMITTED_POS_FINAL
 )
,
--transform & type
transform_data as(
SELECT DISTINCT 
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
SHA2('hash_me') AS _ROW_HASH,
MAIN.REQUEST_NUMBER AS QRF_NUMBER, 
--If TEL Reverted then take the next earliest Requested Date available
CASE WHEN SUM(TO_NUMBER(CONTAINS(QRF_STATUS, 'REVERTED'))) OVER (PARTITION BY MAIN.REQUEST_NUMBER) > 0 
THEN REVERTED.QRF_INTEL_REQUEST_DATE 
--If INTEL did revise on this QRF then take the revision date rather
WHEN COUNT(DISTINCT MAIN.QRF_REVISION_DATE) OVER (PARTITION BY MAIN.REQUEST_NUMBER) > 0  
THEN FIRST_VALUE(MAIN.QRF_REVISION_DATE IGNORE NULLS) OVER (PARTITION BY MAIN.REQUEST_NUMBER ORDER BY MAIN.QRF_REVISION_NUMBER ASC)
ELSE TO_DATE(MIN(MAIN.QRF_INTEL_REQUEST_DATE) OVER (PARTITION BY MAIN.REQUEST_NUMBER)) END AS INITIAL_QRF_SUBMITTED_DATE,
TO_DATE(MAX(MAIN.QRF_INTEL_REQUEST_DATE) OVER (PARTITION BY MAIN.REQUEST_NUMBER)) as LATEST_QRF_SUBMITTED_DATE,
--If TEL Reverted then take the next earliest Requested Date available
CASE WHEN SUM(TO_NUMBER(CONTAINS(QRF_STATUS, 'REVERTED'))) OVER (PARTITION BY MAIN.REQUEST_NUMBER) > 0 
THEN REVERTED.QRF_TEL_PUBLISH_DATE
--If INTEL did revise on this QRF then take its associated publish date rather
WHEN COUNT(DISTINCT MAIN.QRF_REVISION_DATE) OVER (PARTITION BY MAIN.REQUEST_NUMBER) > 0
THEN FIRST_VALUE(MAIN.QRF_TEL_PUBLISH_DATE IGNORE NULLS) OVER (PARTITION BY MAIN.REQUEST_NUMBER ORDER BY 
CASE WHEN MAIN.QRF_REVISION_DATE IS NOT NULL THEN 0 ELSE 1 END,
MAIN.QRF_REVISION_NUMBER ASC)
ELSE TO_DATE(MIN(MAIN.QRF_TEL_PUBLISH_DATE) OVER (PARTITION BY MAIN.REQUEST_NUMBER)) END AS INITIAL_QRF_PUBLISH_DATE, 
FIRST_VALUE(MAIN.QRF_STATUS) OVER (PARTITION BY MAIN.REQUEST_NUMBER ORDER BY MAIN.QRF_REVISION_NUMBER DESC) as LATEST_QRF_STATUS,
UPPER(ARF_LATEST.BUSINESS_UNIT) AS BUSINESS_UNIT, 
UPPER(ARF_LATEST.SITE) AS SITE,
UPPER(ARF_LATEST.MODEL) AS MODEL, 
UPPER(ARF_LATEST.PROCESS) AS PROCESS, 
UPPER(ARF_LATEST.DESCRIPTION) AS DESCRIPTION, 
UPPER(ARF_LATEST.REQUEST_TYPE) AS REQUEST_TYPE 
FROM QUOTE_REQUEST_FORM_HISTORY MAIN
LEFT JOIN ACTION_REQUEST_FORM_LATEST ARF_LATEST
ON MAIN.REQUEST_NUMBER = ARF_LATEST.REQUEST_NUMBER
LEFT JOIN GET_REVERTED_INITIAL_SUBMITTED_DATE REVERTED
ON MAIN.REQUEST_NUMBER = REVERTED.REQUEST_NUMBER
)

,type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(QRF_NUMBER AS NUMBER(38,0)) AS QRF_NUMBER,
        CAST(INITIAL_QRF_SUBMITTED_DATE AS DATE) AS INITIAL_QRF_SUBMITTED_DATE,
        CAST(LATEST_QRF_SUBMITTED_DATE AS DATE) AS LATEST_QRF_SUBMITTED_DATE,
        CAST(INITIAL_QRF_PUBLISH_DATE AS DATE) AS INITIAL_QRF_PUBLISH_DATE,
        LATEST_QRF_STATUS,
        BUSINESS_UNIT,
        SITE,
        MODEL,
        PROCESS,
        DESCRIPTION,
        REQUEST_TYPE
    FROM transform_data
)

SELECT * from type_data
{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
        alias='SIRFIS_LIFECYCLE_TMEA',
      transient=false
) }}

WITH INITIAL_PO_DATE AS
( 
  --does not include the whole population  
  SELECT DISTINCT ID, 
  MIN(_APPENDEDDATE) AS INITIAL_PO_DATE, 
  ID || '-' || INITIAL_PO_DATE AS PO_ISSUE_KEY
  FROM  {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY_TMEA') }}
  WHERE PURCHASE_ORDER_KEY IS NOT NULL
  AND PURCHASE_ORDER_KEY <> ''
  GROUP BY 1
), 

source_data_sirfis_lifecycle_min_dates AS (
    SELECT DISTINCT
        ID,
        MIN(_APPENDEDDATE) AS ENTERED_DATE
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY_TMEA') }}
    GROUP BY ID
),

source_data_sirfis_lifecycle AS (
    SELECT DISTINCT
        ID,
        PURCHASE_ORDER_NUMBER,
        IS_PURCHASE_ORDER,
        PURCHASE_ORDER_LINE_NUMBER,
        PURCHASE_ORDER_KEY,
        BUILD_TIME,
        IS_CRITICAL,
        STATE,
        READ_ONLY,
        SUPPLIER_MAP,
        CONVERSION_LOCATION,
        PRICE_KEY,
        TRANSIT_TIME,
        INTEL_RELEASED_DATE,
        PRIMARY_SUPPLIER_TENDER_DATE,
        SUPPLIER_TENDER_DATE,
        REQUESTED_DELIVERY_DATE,
        CONTRACTUAL_TENDER_DATE,
        REQUESTED_TENDER_DATE,
        SET_START_DATE,
        EXPECTED_SUPPLIER_DELIVERY_DATE,
        COALESCE(SUPPLIER_TENDER_DATE, LAST_SUPPLIER_TENDER_DATE) AS ALL_STD_RESPONSES, 
        _APPENDEDDATE
    FROM {{ ref('GOLD__TEH_SALES_TO_INSTALLATION__FORECAST_HISTORY_TMEA') }}
    WHERE REVISION_DESC_ORDER=1
), 

transform_data AS (
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
SHA2('hash_me') AS _ROW_HASH,
main.ID, 
CASE 
WHEN main._APPENDEDDATE < CURRENT_DATE() THEN 0
WHEN main._APPENDEDDATE = CURRENT_DATE() THEN 1 
END AS IS_CURRENT,
CASE 
WHEN main.IS_PURCHASE_ORDER = 'Yes' THEN 1
ELSE 0 
END AS PO_STATUS,
main.PURCHASE_ORDER_NUMBER,
main.PURCHASE_ORDER_LINE_NUMBER,
main.PURCHASE_ORDER_KEY,
main.BUILD_TIME,
CASE 
WHEN main.IS_CRITICAL = 'Yes' THEN 1
ELSE 0 
END AS IS_CRITICAL,
main.STATE,
main.READ_ONLY,
main.SUPPLIER_MAP,
main.CONVERSION_LOCATION,
main.PRICE_KEY,
main.TRANSIT_TIME,
main.INTEL_RELEASED_DATE,
main.PRIMARY_SUPPLIER_TENDER_DATE,
main.SUPPLIER_TENDER_DATE,
main.REQUESTED_DELIVERY_DATE,
main.CONTRACTUAL_TENDER_DATE,
main.REQUESTED_TENDER_DATE,
main.SET_START_DATE,
main.EXPECTED_SUPPLIER_DELIVERY_DATE,
main.ALL_STD_RESPONSES, 
main._APPENDEDDATE AS LATEST_DATE,
Min_Dates.ENTERED_DATE,
INITIAL_PO_DATE.INITIAL_PO_DATE
FROM source_data_sirfis_lifecycle Main
LEFT JOIN source_data_sirfis_lifecycle_min_dates Min_Dates
ON main.ID = Min_Dates.ID
LEFT JOIN INITIAL_PO_DATE 
on main.ID = INITIAL_PO_DATE.ID
), 

type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ID,
        CAST(IS_CURRENT AS NUMBER(1,0)) AS IS_CURRENT,
        CAST(PO_STATUS AS NUMBER(1,0)) AS PO_STATUS,
        CAST(PURCHASE_ORDER_NUMBER AS NUMBER(38,0)) AS PURCHASE_ORDER_NUMBER,
        CAST(PURCHASE_ORDER_LINE_NUMBER AS NUMBER(38,0)) AS PURCHASE_ORDER_LINE_NUMBER,
        CAST(PURCHASE_ORDER_KEY AS VARCHAR(16777216)) AS PURCHASE_ORDER_KEY,
        CAST(BUILD_TIME AS NUMBER(38,0)) AS BUILD_TIME,
        CAST(IS_CRITICAL AS NUMBER(1,0)) AS IS_CRITICAL,
        STATE,
        READ_ONLY,
        SUPPLIER_MAP,
        CONVERSION_LOCATION,
        PRICE_KEY,
        CAST(TRANSIT_TIME AS NUMBER(38,0)) AS TRANSIT_TIME,
        CAST(INTEL_RELEASED_DATE AS DATE) AS INTEL_RELEASED_DATE,
        CAST(PRIMARY_SUPPLIER_TENDER_DATE AS DATE) AS PRIMARY_SUPPLIER_TENDER_DATE,
        CAST(SUPPLIER_TENDER_DATE AS DATE) AS SUPPLIER_TENDER_DATE,
        CAST(REQUESTED_DELIVERY_DATE AS DATE) AS REQUESTED_DELIVERY_DATE,
        CAST(CONTRACTUAL_TENDER_DATE AS DATE) AS CONTRACTUAL_TENDER_DATE,
        CAST(REQUESTED_TENDER_DATE AS DATE) AS REQUESTED_TENDER_DATE,
        CAST(SET_START_DATE AS DATE) AS SET_START_DATE,
        CAST(EXPECTED_SUPPLIER_DELIVERY_DATE AS DATE) AS EXPECTED_SUPPLIER_DELIVERY_DATE,
        CAST(ALL_STD_RESPONSES AS DATE) AS ALL_STD_RESPONSES, 
        CAST(LATEST_DATE AS DATE) AS LATEST_DATE,
        CAST(ENTERED_DATE AS DATE) AS ENTERED_DATE,
        CAST(INITIAL_PO_DATE AS DATE) AS INITIAL_PO_DATE
    FROM transform_data
)

SELECT * FROM transform_data
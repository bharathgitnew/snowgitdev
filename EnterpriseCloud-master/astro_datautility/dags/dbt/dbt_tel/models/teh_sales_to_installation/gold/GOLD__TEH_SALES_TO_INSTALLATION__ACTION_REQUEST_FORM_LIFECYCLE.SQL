      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='ACTION_REQUEST_FORM_LIFECYCLE',
      transient=false
) }}

with ref_Action_request_form_hist as
(
     SELECT *, 
     ROW_NUMBER() OVER (PARTITION BY REQUEST_NUMBER ORDER BY ACTION_REQUEST_REVISION_NUMBER DESC) AS REVISION_DESC_ORDER
    FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__ACTION_REQUEST_FORM_HISTORY') }}
)
,ref_Action_request_form_history_Data as
(
        SELECT *
    FROM ref_Action_request_form_hist
    WHERE REVISION_DESC_ORDER=1
)

, ref_qrf_history as
(SELECT DISTINCT REQUEST_NUMBER AS QRF_NUMBER, 
 CASE WHEN SUM(TO_NUMBER(CONTAINS(UPPER(STATUS), 'REVERTED'))) OVER (PARTITION BY REQUEST_NUMBER) > 0 THEN
 1 ELSE 0 END AS IS_QRF_REVERTED
 FROM {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }}
WHERE 
  REQTYPE = 'QRF'
)

, ref_qrf_reverted as
(SELECT DISTINCT REQUEST_NUMBER AS QRF_NUMBER, 
 TO_DATE(MIN(REVERTED_DATE)) AS QRF_REVERTED_DATE
 FROM {{ ref('BRONZE__TEH_SALES_TO_INSTALLATION__TELCUSTOMER_TELCUST_ARF_QRF_DATA') }}
WHERE 
  REQTYPE = 'QRF'
GROUP BY 1
)

--for if associated QRF number whos reverted, then grab the next closest Publish Date if available 
, ref_arf_next_published as
(SELECT DISTINCT a.REQUEST_NUMBER, 
FIRST_VALUE(a.ARF_TEL_PUBLISH_DATE) OVER (PARTITION BY a.REQUEST_NUMBER ORDER BY a.ARF_TEL_PUBLISH_DATE) AS NEXT_PUBLISHED_DATE
FROM ref_Action_request_form_hist a LEFT JOIN 
ref_qrf_reverted b
ON a.REQUEST_NUMBER = b.QRF_NUMBER
WHERE a.ARF_TEL_PUBLISH_DATE  >= b.QRF_REVERTED_DATE
)

,source_data_I as 
(
    SELECT 
        DISTINCT ref_Action_request_form_history_Data.REQUEST_NUMBER AS REQUEST_NUMBER,
        ref_Action_request_form_history_Data.ACTION_REQUEST_REVISION_NUMBER AS LATEST_REQUEST_REVISION_NUMBER,     
        ref_Action_request_form_history_Data.REQUEST_STATUS AS LATEST_REQUEST_STATUS,    
        ref_Action_request_form_history_Data.ARF_STATUS_DATE AS LATEST_REQUEST_STATUS_DATE,   
        ref_Action_request_form_history_Data.REQUESTOR AS REQUESTOR,
        ref_Action_request_form_history_Data.ARF_PRIORITY AS REQUEST_PRIORITY,      
        ref_Action_request_form_history_Data.ARF_TYPE AS REQUEST_TYPE,     
        ref_Action_request_form_history_Data.BUSINESS_UNIT AS BUSINESS_UNIT,    
        ref_Action_request_form_history_Data.SITE AS SITE,     
        ref_Action_request_form_history_Data.MODEL AS MODEL,      
        ref_Action_request_form_history_Data.PROCESS AS PROCESS,       
        ref_Action_request_form_history_Data.INTEL_DESCRIPTION AS DESCRIPTION,       
        b.REQUEST_ENTERED_DATE,       
        b.REQUEST_INITIAL_PUBLISH_DATE,       
        b.REQUEST_INITIAL_APPROVAL_DATE,       
        b.REQUEST_LAST_PUBLISH_DATE,       
        b.REQUEST_LAST_APPROVAL_DATE
    FROM ref_Action_request_form_history_Data INNER JOIN
        (SELECT DISTINCT REQUEST_NUMBER,
            MIN(ARF_INTEL_REQUEST_DATE) AS REQUEST_ENTERED_DATE,
            MIN(ARF_TEL_PUBLISH_DATE) AS REQUEST_INITIAL_PUBLISH_DATE,
            MIN(ARF_INTEL_APPROVAL_DATE) AS REQUEST_INITIAL_APPROVAL_DATE,
            MAX(ARF_TEL_PUBLISH_DATE) AS REQUEST_LAST_PUBLISH_DATE,
            MAX(ARF_INTEL_APPROVAL_DATE) AS REQUEST_LAST_APPROVAL_DATE
        FROM {{ ref('SILVER__TEH_SALES_TO_INSTALLATION__ACTION_REQUEST_FORM_HISTORY') }}
        GROUP BY 1) b
    ON ref_Action_request_form_history_Data.REQUEST_NUMBER = b.REQUEST_NUMBER
)

, source_data_II as
(SELECT DISTINCT 
REQUEST_NUMBER 
, FIRST_VALUE(RELEASE_FROM_HOLD_DATE IGNORE NULLS) OVER (PARTITION BY REQUEST_NUMBER ORDER BY RELEASE_FROM_HOLD_DATE ASC) AS INITIAL_RELEASE_FROM_HOLD_DATE
, FIRST_VALUE(ARF_REVISION_DATE IGNORE NULLS) OVER (PARTITION BY REQUEST_NUMBER ORDER BY ARF_REVISION_DATE ASC) AS INITIAL_REQUEST_REVISION_DATE
FROM ref_Action_request_form_hist
)

, source_data as
(SELECT source_data_I.REQUEST_NUMBER,
      source_data_I.LATEST_REQUEST_REVISION_NUMBER,
      source_data_I.LATEST_REQUEST_STATUS,
      source_data_I.LATEST_REQUEST_STATUS_DATE,
      source_data_I.REQUESTOR,
      source_data_I.REQUEST_PRIORITY,
      source_data_I.REQUEST_TYPE,
      source_data_I.BUSINESS_UNIT,
      source_data_I.SITE,
      source_data_I.MODEL,
      source_data_I.PROCESS,
      source_data_I.DESCRIPTION,
      source_data_I.REQUEST_ENTERED_DATE,
      source_data_I.REQUEST_INITIAL_PUBLISH_DATE,
      source_data_I.REQUEST_INITIAL_APPROVAL_DATE,
      source_data_I.REQUEST_LAST_PUBLISH_DATE,
      source_data_I.REQUEST_LAST_APPROVAL_DATE, 
      source_data_II.INITIAL_RELEASE_FROM_HOLD_DATE, 
      source_data_II.INITIAL_REQUEST_REVISION_DATE, 
      ref_arf_next_published.NEXT_PUBLISHED_DATE,
      ref_qrf_history.IS_QRF_REVERTED, 
      ref_qrf_reverted.QRF_REVERTED_DATE
      FROM source_data_I LEFT JOIN
      source_data_II 
      ON source_data_I.REQUEST_NUMBER = source_data_II.REQUEST_NUMBER
      LEFT JOIN ref_qrf_history
      ON source_data_I.REQUEST_NUMBER = ref_qrf_history.QRF_NUMBER
      LEFT JOIN ref_qrf_reverted
      ON source_data_I.REQUEST_NUMBER = ref_qrf_reverted.QRF_NUMBER
      LEFT JOIN ref_arf_next_published
      ON source_data_I.REQUEST_NUMBER = ref_arf_next_published.REQUEST_NUMBER
)

,transform_data as 
(
  SELECT 
      '{{ invocation_id }}' AS _AUDIT_LOG_ID,
      SHA2('hash_me') as _ROW_HASH, 
      REQUEST_NUMBER,
      LATEST_REQUEST_REVISION_NUMBER,
      LATEST_REQUEST_STATUS,
      CASE WHEN LATEST_REQUEST_STATUS = 'ACTIVE' THEN 'ACTIVE'
      WHEN LATEST_REQUEST_STATUS = 'CANCELLED' THEN 'CANCELLED'
      WHEN LATEST_REQUEST_STATUS IS NULL THEN NULL
      WHEN LATEST_REQUEST_STATUS = 'SUBMITTED' THEN 'OPEN'
      ELSE 'IN PROGRESS' END AS TEL_ARF_STATUS,
      LATEST_REQUEST_STATUS_DATE,
      REQUESTOR,
      REQUEST_PRIORITY,
      REQUEST_TYPE,
      BUSINESS_UNIT,
      SITE,
      MODEL,
      PROCESS,
      DESCRIPTION,
      REQUEST_ENTERED_DATE,
      CASE WHEN IS_QRF_REVERTED = 1 THEN NEXT_PUBLISHED_DATE
      ELSE REQUEST_INITIAL_PUBLISH_DATE END AS REQUEST_INITIAL_PUBLISH_DATE,
      REQUEST_INITIAL_APPROVAL_DATE,
      REQUEST_LAST_PUBLISH_DATE,
      REQUEST_LAST_APPROVAL_DATE, 
      LEAST(COALESCE(INITIAL_RELEASE_FROM_HOLD_DATE, INITIAL_REQUEST_REVISION_DATE), COALESCE(INITIAL_REQUEST_REVISION_DATE, INITIAL_RELEASE_FROM_HOLD_DATE)) AS LEAST_DATE,
      GREATEST(COALESCE(INITIAL_RELEASE_FROM_HOLD_DATE, INITIAL_REQUEST_REVISION_DATE), COALESCE(INITIAL_REQUEST_REVISION_DATE, INITIAL_RELEASE_FROM_HOLD_DATE)) AS GREATEST_DATE, 
      CASE WHEN 
      --when QRF reverted then use the initially reverted date
      IS_QRF_REVERTED = 1 THEN QRF_REVERTED_DATE
      -- when there is no initial release from holding or initially request revised date then use the entered date
      WHEN IS_QRF_REVERTED IS NULL OR IS_QRF_REVERTED = 0 AND LEAST_DATE IS NULL THEN REQUEST_ENTERED_DATE
      -- when either initial released or initially request revision or both present, and if they both the same date and both of them earlier or on the same 
      --date as the initial publish date then use one of them as the initially submitted date
      WHEN IS_QRF_REVERTED IS NULL OR IS_QRF_REVERTED = 0 AND LEAST_DATE IS NOT NULL AND LEAST_DATE = GREATEST_DATE AND LEAST_DATE <= REQUEST_INITIAL_PUBLISH_DATE 
      THEN LEAST_DATE
      -- if the date is later than the initial publish date then use the request entered date
      WHEN IS_QRF_REVERTED IS NULL OR IS_QRF_REVERTED = 0 AND LEAST_DATE IS NOT NULL AND LEAST_DATE = GREATEST_DATE AND LEAST_DATE > REQUEST_INITIAL_PUBLISH_DATE 
      THEN REQUEST_ENTERED_DATE
      --  if they both not the same date
      WHEN IS_QRF_REVERTED IS NULL OR IS_QRF_REVERTED = 0 AND LEAST_DATE IS NOT NULL AND LEAST_DATE <> GREATEST_DATE AND LEAST_DATE > REQUEST_INITIAL_PUBLISH_DATE
      THEN REQUEST_ENTERED_DATE
      WHEN IS_QRF_REVERTED IS NULL OR IS_QRF_REVERTED = 0 AND LEAST_DATE IS NOT NULL AND LEAST_DATE <> GREATEST_DATE AND LEAST_DATE <= REQUEST_INITIAL_PUBLISH_DATE OR GREATEST_DATE <= REQUEST_INITIAL_PUBLISH_DATE
      THEN GREATEST_DATE
      ELSE REQUEST_ENTERED_DATE
      END AS REQUEST_INITIAL_SUBMITTED_DATE, 
      IS_QRF_REVERTED
  FROM source_data
),

type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID, 
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(REQUEST_NUMBER AS NUMBER(38,0)) AS REQUEST_NUMBER,
        LATEST_REQUEST_REVISION_NUMBER,
        LATEST_REQUEST_STATUS,
        TEL_ARF_STATUS,
        CAST(LATEST_REQUEST_STATUS_DATE AS DATE) AS LATEST_REQUEST_STATUS_DATE,
        REQUESTOR,
        REQUEST_PRIORITY,
        REQUEST_TYPE,
        BUSINESS_UNIT,
        SITE,
        MODEL,
        PROCESS,
        DESCRIPTION,
        CAST(REQUEST_ENTERED_DATE AS DATE) AS REQUEST_ENTERED_DATE,
        CAST(REQUEST_INITIAL_PUBLISH_DATE AS DATE) AS REQUEST_INITIAL_PUBLISH_DATE,
        CAST(REQUEST_INITIAL_APPROVAL_DATE AS DATE) AS REQUEST_INITIAL_APPROVAL_DATE,
        CAST(REQUEST_LAST_PUBLISH_DATE AS DATE) AS REQUEST_LAST_PUBLISH_DATE,
        CAST(REQUEST_LAST_APPROVAL_DATE AS DATE) AS REQUEST_LAST_APPROVAL_DATE, 
        CAST(REQUEST_INITIAL_SUBMITTED_DATE AS DATE) AS REQUEST_INITIAL_SUBMITTED_DATE, 
        CAST(IS_QRF_REVERTED AS NUMBER(1,0)) AS IS_QRF_REVERTED
    FROM transform_data
)

SELECT * from type_data
    CUSTOMER_PO,
    WAREHOUSE,
    ORDERED_QTY,
    DELIVERY_DATE,
    INVOICE_DATE,
    ORDER_PRIORITY
  from source_data
)

,type_data as 
(
    select
        _AUDIT_LOG_ID,
        _ROW_HASH,
        cast(SRVLINE as VARCHAR(16777216)) as SRVLINE,
        cast(ITEM as VARCHAR(16777216)) as ITEM,
        cast(ITEM_DESCRIPTION as VARCHAR(16777216)) as ITEM_DESCRIPTION,
        cast(SOLD_TO_BPID as VARCHAR(16777216)) as SOLD_TO_BPID,

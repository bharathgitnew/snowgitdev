{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='SAPO_LOWER_LEVEL_SETS_IN_SETS',
        unique_key = ['MANDT',
    'SETCLASS',
    'SUBCLASS',
    'SETNAME',
    'LINEID'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	SETCLASS,
	SUBCLASS,
	SETNAME,
	LINEID,
	SUBSETCLS,
	SUBSETSCLS,
	SUBSETNAME,
	SEQNR
	FROM {{source('SAP_ORACLE_LIVE', 'SETNODE')}}
),


transform_data as 
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	SETCLASS as SETCLASS,
	SUBCLASS as SUBCLASS,
	SETNAME as SETNAME,
	LINEID as LINEID,
	SUBSETCLS as SUBSETCLS,
	SUBSETSCLS as SUBSETSCLS,
	SUBSETNAME as SUBSETNAME,
	SEQNR as SEQNR
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	SETCLASS,
	SUBCLASS,
	SETNAME,
	LINEID,
	SUBSETCLS,
	SUBSETSCLS,
	SUBSETNAME,
	CAST(SEQNR AS NUMBER(38,12)) AS SEQNR
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
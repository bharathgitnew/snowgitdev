WITH ref_cte_ACTUAL_LINE_ITEMS as (
    select * from {{ ref('SILVER__TMEA_FINANCE__ACTUAL_LINE_ITEMS') }}
),

ref_cte_BILLING_DOCUMENT_ITEM_DATA as (
    select * from {{ ref('SILVER__TMEA_FINANCE__BILLING_DOCUMENT_ITEM_DATA') }}
),

ref_cte_CO_OBJECT_DOCUMENT_HEADER as (
    select * from {{ ref('SILVER__TMEA_FINANCE__CO_OBJECT_DOCUMENT_HEADER') }}
),

ref_cte_CO_OBJECT_LINE_ITEMS_BY_PERIOD as (
    select * from {{ ref('SILVER__TMEA_FINANCE__CO_OBJECT_LINE_ITEMS_BY_PERIOD') }}
),

ref_cte_GENERAL_DATA_IN_CUSTOMER_MASTER as (
    select * from {{ ref('SILVER__TMEA_FINANCE__GENERAL_DATA_IN_CUSTOMER_MASTER') }}
),

ref_cte_PROFIT_CENTER_DESCRIPTION as (
    select * from {{ ref('SILVER__TMEA_FINANCE__PROFIT_CENTER_DESCRIPTION') }}
),

COEP AS (
SELECT 
COEP.document_number,COEP.posting_row,
concat(COEP.fiscal_year,COEP.period) as PERIODYEAR,
COEP.PROFITABILITY_SEGMENT_NUMBER_CO_PA,
COEP.cost_element,
COEP.TOTAL_VALUE_IN_OBJECT_CURRENCY,
COEP.DEBIT_CREDIT_INDICATOR,
COEP.partner_object,
COEP.object_number,
COEP.MATERIAL_NUMBER,
COBK.reference_procedure,
COBK.reference_document_number, 
coep.TOTAL_QUANTITY,
case when COBK.reference_procedure = 'AUAK' 
then substr(COEP.partner_object,3,10) 
WHEN  COBK.reference_procedure = 'BKPF' THEN substr(cOEP.object_number,7,10)
when COBK.reference_procedure = 'VBRK' then vbrp.sales_document 
else '' end as SALES_ORDER_NUMBER,
case when COBK.reference_procedure = 'AUAK' 
then substr(COEP.partner_object,13,20) 
WHEN  COBK.reference_procedure = 'BKPF' THEN '0001'
else vbrp.sales_document_item end as ITEM_NUMBER_IN_SALES_ORDER
FROM ref_cte_co_object_line_items_by_period as COEP
left join ref_cte_CO_OBJECT_DOCUMENT_HEADER as COBK
on COBK.document_number = COEP.document_number
left join ref_cte_billing_document_item_data as vbrp
on COBK.reference_document_number = vbrp.billing_document
and coep.material_number = vbrp.material_entered
WhERE 
COEP.PROFITABILITY_SEGMENT_NUMBER_CO_PA <> '0000000000'
and cost_element BETWEEN '0000400000' AND '0000499999'
),
 
CE10010 as (
select PERIODYEAR ,
PROFITABILITY_SEGMENT_NUMBER_COPA ,
PROFITABILITY_SEGMENT_CHANGES_COPA,
SALES_ORDER_NUMBER,
ITEM_NUMBER_IN_SALES_ORDER,
PRODUCT_NUMBER,
MATERIAL_ENTERED,
SALES_DOCUMENT_TYPE,
reference_procedure,
ITEM_NUMBER_FROM_REFERENCE_DOCUMENT_COPA,
profit_center,
plant,
SUM(sales_quantity) as sales_quantity,
customer,
posting_date,
case when reference_procedure = 'AUAK' then SALES_ORDER_NUMBER
when reference_procedure = 'VBRK' then SALES_ORDER_NUMBER
else 
PROFITABILITY_SEGMENT_NUMBER_COPA
end as SALES_ORDER_NUMBER_new,
case when reference_procedure = 'AUAK' then ITEM_NUMBER_IN_SALES_ORDER
when reference_procedure = 'VBRK' then ITEM_NUMBER_IN_SALES_ORDER
else PROFITABILITY_SEGMENT_CHANGES_COPA
end as ITEM_NUMBER_IN_SALES_ORDER_new
from ref_cte_ACTUAL_LINE_ITEMS 
group by PERIODYEAR ,
PROFITABILITY_SEGMENT_CHANGES_COPA, SALES_ORDER_NUMBER,ITEM_NUMBER_IN_SALES_ORDER,PRODUCT_NUMBER,
MATERIAL_ENTERED,SALES_DOCUMENT_TYPE,PROFITABILITY_SEGMENT_NUMBER_COPA,
ITEM_NUMBER_FROM_REFERENCE_DOCUMENT_COPA,reference_procedure,customer,profit_center,plant,posting_date),
fymonth as (select distinct PERIODYEAR,FISCAL_YEAR_SHORT_TEXT ,
MONTH_TEXT , POSTING_DATE,
MONTH_OF_FISCAL_YEAR_NUMBER from CE10010 as CE10010
LEFT JOIN {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
    ON POSTING_DATE = CALENDAR_DATE ),
 
source_data as (
select COEP.document_number ,coep.posting_row,COEP.PERIODYEAR,
COEP.cost_element ,
COEP.reference_procedure,
COEP.reference_document_number,
COEP.PROFITABILITY_SEGMENT_NUMBER_CO_PA,
fymonth.POSTING_DATE AS POSTING_DATE,
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
MONTH_TEXT AS MONTH,
MONTH_OF_FISCAL_YEAR_NUMBER,
CE10010.customer,
NAME_1 AS CUSTOMER_NAME,
CE10010.sales_order_number as sales_order_number,
CE10010.ITEM_NUMBER_IN_SALES_ORDER as ITEM_NUMBER_IN_SALES_ORDER,
CE10010.plant,
CE10010.PRODUCT_NUMBER as MatERIAL_ENTERED ,
CE10010.SALES_DOCUMENT_TYPE,
TO_NUMBER(CE10010.profit_center) AS profit_center,
CEPC.GENERAL_NAME AS PROFIT_CENTER_DESCRIPTION,
CE10010.PROFITABILITY_SEGMENT_NUMBER_COPA,
CE10010.ITEM_NUMBER_FROM_REFERENCE_DOCUMENT_COPA,
COEP.TOTAL_QUANTITY,
(COEP.TOTAL_VALUE_IN_OBJECT_CURRENCY) as TOTAL_VALUE_IN_OBJECT_CURRENCY,
COEP.DEBIT_CREDIT_INDICATOR
FROM COEP as COEP
left join CE10010 as CE10010
ON CE10010.sales_order_number_new = coep.sales_order_number
AND CE10010.ITEM_NUMBER_IN_SALES_ORDER_new = coep.ITEM_NUMBER_IN_SALES_ORDER
and CE10010.PERIODYEAR = COEP.PERIODYEAR
LEFT JOIN fymonth
 ON coep.PERIODYEAR = fymonth.PERIODYEAR
-- {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
--     ON POSTING_DATE = CALENDAR_DATE
LEFT JOIN ref_cte_PROFIT_CENTER_DESCRIPTION AS CEPC
    ON CEPC.PROFIT_CENTER = CE10010.profit_center
LEFT JOIN ref_cte_GENERAL_DATA_IN_CUSTOMER_MASTER KNA1
    ON CUSTOMER = CUSTOMER_NUMBER
qualify(row_number() over(partition by COEP.document_number ,coep.posting_row order by 
COEP.document_number ,coep.posting_row)= 1)
),
transform_data as (
select 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	DOCUMENT_NUMBER,
	POSTING_ROW,
	PERIODYEAR,
	COST_ELEMENT,
	REFERENCE_PROCEDURE,
	REFERENCE_DOCUMENT_NUMBER,
	PROFITABILITY_SEGMENT_NUMBER_CO_PA,
	POSTING_DATE,
	FISCAL_YEAR,
	MONTH,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	CUSTOMER,
	CUSTOMER_NAME,
	SALES_ORDER_NUMBER,
	ITEM_NUMBER_IN_SALES_ORDER,
	PLANT,
	MATERIAL_ENTERED,
	SALES_DOCUMENT_TYPE,
	PROFIT_CENTER,
	PROFIT_CENTER_DESCRIPTION,
	PROFITABILITY_SEGMENT_NUMBER_COPA,
	ITEM_NUMBER_FROM_REFERENCE_DOCUMENT_COPA,
	TOTAL_QUANTITY,
	TOTAL_VALUE_IN_OBJECT_CURRENCY,
	DEBIT_CREDIT_INDICATOR
from source_data
where POSTING_DATE IS NOT NULL
-- AND PROFIT_CENTER BETWEEN '0000600000' AND '0000699999'
-- and periodyear = '2025005'
-- and fiscal_year = 'FY23'
),

type_data as (
select
CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
,DOCUMENT_NUMBER
,POSTING_ROW
,PERIODYEAR
,COST_ELEMENT
,REFERENCE_PROCEDURE
,REFERENCE_DOCUMENT_NUMBER
,PROFITABILITY_SEGMENT_NUMBER_CO_PA
,CAST(POSTING_DATE as DATE) as POSTING_DATE
,FISCAL_YEAR
,MONTH
,CAST(MONTH_OF_FISCAL_YEAR_NUMBER as NUMBER(38,0)) as MONTH_OF_FISCAL_YEAR_NUMBER
,CUSTOMER
,CUSTOMER_NAME
,SALES_ORDER_NUMBER
,ITEM_NUMBER_IN_SALES_ORDER
,PLANT
,MATERIAL_ENTERED
,SALES_DOCUMENT_TYPE
,CAST(PROFIT_CENTER as NUMBER(38,0)) as PROFIT_CENTER
,PROFIT_CENTER_DESCRIPTION
,PROFITABILITY_SEGMENT_NUMBER_COPA
,ITEM_NUMBER_FROM_REFERENCE_DOCUMENT_COPA
,CAST(TOTAL_QUANTITY as NUMBER(38,10)) as TOTAL_QUANTITY
,CAST(TOTAL_VALUE_IN_OBJECT_CURRENCY as NUMBER(38,10)) as TOTAL_VALUE_IN_OBJECT_CURRENCY
,DEBIT_CREDIT_INDICATOR
from transform_data 
)
select * from type_data
ORDER BY POSTING_DATE DESC
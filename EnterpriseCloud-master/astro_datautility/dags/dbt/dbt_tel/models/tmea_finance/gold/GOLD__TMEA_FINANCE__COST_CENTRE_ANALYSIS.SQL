-- Deduplicated COSP: removes duplicate rows caused by 2026-05-26 reload
-- where CO_KEY_SUBNUMBER was loaded as '' vs ' '
COSP_DEDUPED AS (
    SELECT *
    FROM {{ ref('SILVER__TMEA_FINANCE__CO_OBJECT_COST_TOTALS_FOR_EXTERNAL_POSTINGS') }}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY OBJECT_NUMBER, COST_ELEMENT, FISCAL_YEAR, 
                     VALUE_TYPE, VERSION, DEBIT_CREDIT_INDICATOR,
                     TRIM(CO_KEY_SUBNUMBER), TRIM(CO_BUSINESS_TRANSACTION),
                     TRANSACTION_CURRENCY, PERIOD_BLOCK
        ORDER BY _CAPTUREDATETIME DESC
    ) = 1
),

one AS (
    SELECT SET_NAME, SUBORDINATE_SET_ID
    FROM {{ ref('SILVER__TMEA_FINANCE__LOWER_LEVEL_SETS_IN_SETS') }}
    WHERE client = '300'
      AND set_name = 'RALL2004'
      AND SUBCLASS_OF_A_SUBORDINATE_SET = '0010'
),

two AS (
    SELECT 
        SETLEAF.set_name,
        SETHEADERT.SHORT_DESCRIPTION_OF_A_SET,
        SETLEAF.from_value,
        SETLEAF.to_value
    FROM {{ ref('SILVER__TMEA_FINANCE__VALUES_IN_SETS') }} SETLEAF
    LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__SHORT_DESCRIPTION_OF_SETS') }} SETHEADERT
        ON SETLEAF.SET_NAME = SETHEADERT.SET_NAME
    WHERE SETLEAF.client = '300'
      AND SETHEADERT.LANGUAGE_KEY = 'E'
      AND SETHEADERT.CLIENT = '300'
      AND SETHEADERT.SET_CLASS = '0102'
),

GROUPING AS (
    SELECT * FROM one
    LEFT JOIN two ON one.SUBORDINATE_SET_ID = two.set_name
),


transform_data as (
  SELECT 
      '{{ invocation_id }}' AS _AUDIT_LOG_ID,
      SHA2('hash_me') as _ROW_HASH,
      COST_CENTER_OWNER,
      COST_CENTER_ AS COST_CENTER,
      COST_CENTER_DESCRIPTION,
      COST_ELEMENT_GROUP,
      COST_ELEMENT,
      LTRIM(COST_ELEMENT, '0') || ' - ' || COALESCE(COST_ELEMENT_DESCRIPTOIN, '') AS COST_ELE_DEC,
      COST_ELEMENT_DESCRIPTOIN,
      COST_DESCRIPTION,
      FISCAL_YEAR,
      MONTH,
      CONCAT(FISCAL_YEAR,' ',MONTH) AS FY_MONTH,
      CASE
          WHEN MONTH = 'APR' THEN 1
          WHEN MONTH = 'MAY' THEN 2
          WHEN MONTH = 'JUN' THEN 3
          WHEN MONTH = 'JUL' THEN 4
          WHEN MONTH = 'AUG' THEN 5
          WHEN MONTH = 'SEP' THEN 6
          WHEN MONTH = 'OCT' THEN 7
          WHEN MONTH = 'NOV' THEN 8
          WHEN MONTH = 'DEC' THEN 9
          WHEN MONTH = 'JAN' THEN 10
          WHEN MONTH = 'FEB' THEN 11
          WHEN MONTH = 'MAR' THEN 12
          ELSE NULL
      END AS MONTH_NUM,
      DATE_FROM_PARTS(FISCAL_YEAR, MONTH_NUM, 1) AS MONTH_DATE,
      COST
  FROM CTE_OUTPUT
  -- ORDER BY FISCAL_YEAR, MONTH_NUM, COST_CENTER_, COST_ELEMENT;

),


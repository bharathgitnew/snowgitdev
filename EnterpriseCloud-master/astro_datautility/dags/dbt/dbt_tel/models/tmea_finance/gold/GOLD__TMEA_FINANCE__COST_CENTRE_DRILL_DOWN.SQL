WITH source_data AS (
SELECT
    RIGHT(co.OBJECT_NUMBER, 10)                          AS COST_CENTER,
    cct.DESCRIPTION                                      AS CO_OBJECT_NAME,
    co.COST_ELEMENT,
    gl.GL_ACCOUNT_SHORT_TEXT                             AS COST_ELEMENT_NAME,
    gl.GL_ACCOUNT_LONG_TEXT                             AS COST_ELEMENT_DESCR,
    LTRIM(co.COST_ELEMENT, '0') || ' - ' || COALESCE(gl.GL_ACCOUNT_SHORT_TEXT, '') AS COST_ELE_DEC,
    co.TOTAL_VALUE_IN_CONTROLLING_AREA_CURRENCY          AS VAL_CO_AREA_CRCY,
    co.TOTAL_VALUE_IN_OBJECT_CURRENCY                    AS VAL_OBJ_CRCY,
    co.TOTAL_VALUE_IN_TRANSACTION_CURRENCY               AS VAL_TRAN_CURR,
    co.FIXED_VALUE_IN_CONTROLLING_AREA_CURRENCY          AS VBL_VAL_CO_CRCY,
    co.FISCAL_YEAR,
    co.PERIOD,
    hdr.FROM_PERIOD,
    hdr.TO_PERIOD,
    hdr.POSTING_DATE,
    hdr.DOCUMENT_DATE,
    hdr.DATE_DOCUMENT_WAS_CREATED                        AS CREATED_ON,
    hdr.VALUE_DATE_FOR_CURRENCY_TRANSLATION              AS VALUE_DATE,
    co.DOCUMENT_NUMBER,
    co.POSTING_ROW,
    co.DOCUMENT_ITEM_NUMBER                              AS ITEM,
    co.POSTING_ROW_OF_REFERENCE_DOCUMENT                 AS FI_POSTING_ITEM,
    co.POSTING_ROW_IN_OPERATIVE_VERSION                  AS ROW_IN_OP_VERSION,
    hdr.DOCUMENT_TYPE_OF_FI_REFERENCE_DOCUMENT           AS DOCUMENT_TYPE,
    hdr.DOCUMENT_HEADER_TEXT,
    hdr.REFERENCE_DOCUMENT_NUMBER                        AS REF_DOCUMENT_NUMBER,
    hdr.FISCAL_YEAR_OF_REFERENCE_DOCUMENT                AS REF_FISCAL_YEAR,
    hdr.COMPANY_CODE_OF_FI_DOCUMENT                      AS REF_COMPANY_CODE,
    co.CO_BUSINESS_TRANSACTION                           AS BUSINESS_TRANSACTION,
    hdr.ORIGINAL_CO_BUSINESS_TRANSACTION                 AS ORIGINAL_BUS_TRANS,
    hdr.REFERENCE_PROCEDURE,
    hdr.REFERENCE_ORGANISATIONAL_UNITS                   AS REFERENCE_ORG_UNIT,
    CASE co.CO_BUSINESS_TRANSACTION
        WHEN 'COIN' THEN 'External Posting (Invoice/AP)'
        WHEN 'RKL'  THEN 'Internal Allocation'
        WHEN 'KZPI' THEN 'Periodic Reposting'
        WHEN 'KOAO' THEN 'Internal Order Settlement'
        WHEN 'KSPA' THEN 'Cost Center Splitting'
        WHEN 'COIE' THEN 'Internal Order Expense'
        WHEN 'RKIU' THEN 'Indirect Activity Allocation'
        WHEN 'KAZI' THEN 'Activity Allocation'
        WHEN 'RMWE' THEN 'Goods Receipt'
        WHEN 'RMRP' THEN 'Invoice Receipt'
        WHEN 'RFBU' THEN 'FI Posting'
        ELSE co.CO_BUSINESS_TRANSACTION
    END                                                  AS TRANSACTION_TYPE_DESCRIPTION,
    co.DEBIT_CREDIT_INDICATOR                            AS DR_CR_INDICATOR,
    co.DEBIT_TYPE,
    co.TRANSACTION_CURRENCY,
    co.CURRENCY_KEY                                      AS CO_AREA_CURRENCY,
    co.UNIT_OF_MEASURE                                   AS OBJECT_CURRENCY,
    co.POSTED_UNIT_OF_MEASURE,
    co.TOTAL_QUANTITY,
    hdr.EXCHANGE_RATE_TYPE,
    co.OBJECT_NUMBER                                     AS OBJECT,
    co.OBJECT_CLASS                                      AS OBJECT_TYPE,
    co.OFFSETTING_ACCOUNT_NUMBER                          AS OFFSETTING_ACCT_NO,
    co.OFFSETTING_ACCOUNT_TYPE,
    CASE 
        WHEN co.OFFSETTING_ACCOUNT_TYPE = 'K' THEN vm.NAME_1
        WHEN co.OFFSETTING_ACCOUNT_TYPE = 'S' THEN gl_off.GL_ACCOUNT_LONG_TEXT
        ELSE NULL
    END                                                  AS NAME_OF_OFFSETTING_ACCOUNT,
    co.PARTNER_OBJECT,
    co.SOURCE_OBJECT_COST_CENTER_ACTIVITY_TYPE           AS PARTNER_CCTR,
    co.COST_ELEMENT_OF_PARTNER,
    co.PURCHASING_DOCUMENT_NUMBER                         AS PURCHASING_DOCUMENT,
    co.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    po.SHORT_TEXT                                         AS PURCHASE_ORDER_TEXT,
    io.ORDER_NUMBER                                        AS INTERNAL_ORDERS,
    co.MATERIAL_NUMBER,
    co.PERSONNEL_NUMBER,
    co.PLANT,
    co.COMPANY_CODE,
    co.BUSINESS_AREA,
    co.FUNCTIONAL_AREA,
    co.CONTROLLING_AREA,
    hdr.CONTROLLING_AREA_CURRENCY                        AS REPORT_CURRENCY,
    co.LEDGER_FOR_CONTROLLING_OBJECTS                     AS LEDGER,
    co.VALUE_TYPE,
    co.VERSION,
    hdr.IDENTIFIER_FOR_REVERSAL_DOCUMENT                 AS REVERSAL_DOCUMENT,
    hdr.INDICATOR_DOCUMENT_WAS_REVERSED                  AS REVERSED,
    hdr.USER_NAME,
    co.TIME_CREATED_GREENWICH_MEANTIME                   AS TIME_CREATED,
    hdr.TIME_OF_ENTRY
FROM {{ ref('SILVER__TMEA_FINANCE__CO_OBJECT_LINE_ITEMS_BY_PERIOD') }} co
LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__CO_OBJECT_DOCUMENT_HEADER') }} hdr
    ON co.DOCUMENT_NUMBER = hdr.DOCUMENT_NUMBER
    AND co.FISCAL_YEAR = hdr.FISCAL_YEAR
    AND co.CONTROLLING_AREA = hdr.CONTROLLING_AREA
LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__COST_CENTER_TEXTS') }} cct
    ON RIGHT(co.OBJECT_NUMBER, 10) = cct.COST_CENTER
    AND cct.LANGUAGE_KEY = 'E'
LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__GL_ACCOUNT_MASTER_RECORD') }} gl
    ON co.COST_ELEMENT = gl.GL_ACCOUNT_NUMBER
    AND gl.LANGUAGE_KEY = 'E'
    AND gl.CHART_OF_ACCOUNTS = '0010'
LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__VENDOR_MASTER') }} vm
    ON co.OFFSETTING_ACCOUNT_NUMBER = vm.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
    AND co.OFFSETTING_ACCOUNT_TYPE = 'K'
LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__GL_ACCOUNT_MASTER_RECORD') }} gl_off
    ON co.OFFSETTING_ACCOUNT_NUMBER = gl_off.GL_ACCOUNT_NUMBER
    AND gl_off.LANGUAGE_KEY = 'E'
    AND gl_off.CHART_OF_ACCOUNTS = '0010'
    AND co.OFFSETTING_ACCOUNT_TYPE = 'S'
-- FIXED: ROW_NUMBER prevents fan-out from multiple ITEM_TEXT per PO+item
LEFT JOIN (
    SELECT PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT, ITEM_TEXT AS SHORT_TEXT
    FROM {{ ref('SILVER__TMEA_FINANCE__ACCOUNTING_DOCUMENT_SEGMENT') }}
    WHERE TRIM(ITEM_TEXT) <> '' AND ITEM_TEXT IS NOT NULL
      AND PURCHASING_DOCUMENT_NUMBER IS NOT NULL AND TRIM(PURCHASING_DOCUMENT_NUMBER) <> ''
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT
        ORDER BY LENGTH(ITEM_TEXT) DESC
    ) = 1
) po
    ON co.PURCHASING_DOCUMENT_NUMBER = po.PURCHASING_DOCUMENT_NUMBER
    AND co.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = po.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
-- Internal Orders: join on FI document number from CO header
LEFT JOIN (
    SELECT DISTINCT ACCOUNTING_DOCUMENT_NUMBER, FISCAL_YEAR, COMPANY_CODE, 
           NUMBER_OF_LINE_ITEM_WITHIN_ACCOUNTING_DOCUMENT, ORDER_NUMBER
    FROM {{ ref('SILVER__TMEA_FINANCE__ACCOUNTING_DOCUMENT_SEGMENT') }}
    WHERE ORDER_NUMBER IS NOT NULL AND TRIM(ORDER_NUMBER) <> ''
) io
    ON hdr.REFERENCE_DOCUMENT_NUMBER = io.ACCOUNTING_DOCUMENT_NUMBER
    AND co.FISCAL_YEAR = io.FISCAL_YEAR
    AND co.COMPANY_CODE = io.COMPANY_CODE
    AND co.POSTING_ROW_OF_REFERENCE_DOCUMENT = io.NUMBER_OF_LINE_ITEM_WITHIN_ACCOUNTING_DOCUMENT
WHERE co.VALUE_TYPE = '04'
  AND co.VERSION = '000'
  AND co.OBJECT_NUMBER LIKE 'KS%'
  AND RIGHT(co.OBJECT_NUMBER, 10) IN (
      SELECT DISTINCT COST_CENTER_ 
      from  {{ ref('GOLD__TMEA_FINANCE__COST_CENTER_ACCOUNT_VARIANCE_2') }}
      -- FROM COPPER.TMEA_FINANCE.FINANCE_COST_CENTER_ACCOUNT_VARIANCE_2
  )
),



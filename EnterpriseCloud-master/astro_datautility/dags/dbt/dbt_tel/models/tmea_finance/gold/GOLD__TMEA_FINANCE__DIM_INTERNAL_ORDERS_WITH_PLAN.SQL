WITH COSP_DEDUPED AS (
    SELECT *
    FROM {{ ref('SILVER__TMEA_FINANCE__CO_OBJECT_COST_TOTALS_FOR_EXTERNAL_POSTINGS') }}
    WHERE OBJECT_NUMBER LIKE 'ORS-%'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY OBJECT_NUMBER, COST_ELEMENT, FISCAL_YEAR, 
                     VALUE_TYPE, VERSION, DEBIT_CREDIT_INDICATOR,
                     TRIM(CO_KEY_SUBNUMBER), TRIM(CO_BUSINESS_TRANSACTION),
                     TRANSACTION_CURRENCY, PERIOD_BLOCK
        ORDER BY _CAPTUREDATETIME DESC
    ) = 1
),

ACTUAL AS (
    SELECT 
        sgm.COST_CENTER,
        CSKT.DESCRIPTION AS COST_CENTER_DESCRIPTION,
        sgm.ORDER_NUMBER AS INTERNAL_ORDER,
        omd.DESCRIPTION AS INTERNAL_ORDER_DESCRIPTION,
        sgm.COST_ELEMENT,
        SKAT.GL_ACCOUNT_LONG_TEXT AS COST_ELEMENT_DESCRIPTION,
        sgm.FISCAL_YEAR,
        '000 - ACTUAL COST' AS COST_DESCRIPTION,
        CASE hdr.FISCAL_PERIOD
            WHEN '01' THEN 'APR' WHEN '02' THEN 'MAY' WHEN '03' THEN 'JUN'
            WHEN '04' THEN 'JUL' WHEN '05' THEN 'AUG' WHEN '06' THEN 'SEP'
            WHEN '07' THEN 'OCT' WHEN '08' THEN 'NOV' WHEN '09' THEN 'DEC'
            WHEN '10' THEN 'JAN' WHEN '11' THEN 'FEB' WHEN '12' THEN 'MAR'
        END AS MONTH,
        SUM(sgm.AMOUNT_IN_LOCAL_CURRENCY) AS COST
    FROM {{ ref('SILVER__TMEA_FINANCE__ACCOUNTING_DOCUMENT_SEGMENT') }} sgm
    INNER JOIN {{ ref('SILVER__TMEA_FINANCE__ACCOUNTING_DOCUMENT_HEADER') }} hdr
        ON sgm.ACCOUNTING_DOCUMENT_NUMBER = hdr.ACCOUNTING_DOCUMENT_NUMBER
        AND sgm.FISCAL_YEAR = hdr.FISCAL_YEAR
        AND sgm.COMPANY_CODE = hdr.COMPANY_CODE
    LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_MASTER_DATA') }} omd
        ON sgm.ORDER_NUMBER = omd.ORDER_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__GL_ACCOUNT_MASTER_RECORD') }} SKAT
        ON sgm.COST_ELEMENT = SKAT.GL_ACCOUNT_NUMBER
        AND SKAT.LANGUAGE_KEY = 'E'
        AND SKAT.CHART_OF_ACCOUNTS = '0010'
    LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__COST_CENTER_TEXTS') }} CSKT
        ON sgm.COST_CENTER = CSKT.COST_CENTER
        AND CSKT.LANGUAGE_KEY = 'E'
        AND CSKT.CLIENT = '300'
    WHERE sgm.ORDER_NUMBER ILIKE 'S%'
      AND TRIM(sgm.COST_CENTER) <> ''
      AND TRIM(sgm.COST_ELEMENT) <> ''
      AND omd.DESCRIPTION NOT ILIKE '%close%'
      AND omd.DESCRIPTION NOT ILIKE '%do not use%'
    GROUP BY sgm.COST_CENTER, CSKT.DESCRIPTION, sgm.ORDER_NUMBER, omd.DESCRIPTION,
             sgm.COST_ELEMENT, SKAT.GL_ACCOUNT_LONG_TEXT, sgm.FISCAL_YEAR, hdr.FISCAL_PERIOD
),

PLAN_RAW AS (
    SELECT 
        cc_map.COST_CENTER,
        CSKT.DESCRIPTION AS COST_CENTER_DESCRIPTION,
        REPLACE(COSP.OBJECT_NUMBER, 'OR', '') AS INTERNAL_ORDER,
        omd.DESCRIPTION AS INTERNAL_ORDER_DESCRIPTION,
        COSP.COST_ELEMENT,
        SKAT.GL_ACCOUNT_LONG_TEXT AS COST_ELEMENT_DESCRIPTION,
        COSP.FISCAL_YEAR,
        COSP.VERSION || ' - PLAN COST' AS COST_DESCRIPTION,
        ROUND(COSP.TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS APR,
        ROUND(COSP.WTG002_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS MAY,
        ROUND(COSP.WTG003_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS JUN,
        ROUND(COSP.WTG004_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS JUL,
        ROUND(COSP.WTG005_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS AUG,
        ROUND(COSP.WTG006_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS SEP,
        ROUND(COSP.WTG007_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS OCT,
        ROUND(COSP.WTG008_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS NOV,
        ROUND(COSP.WTG009_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS DEC,
        ROUND(COSP.WTG010_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS JAN,
        ROUND(COSP.WTG011_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS FEB,
        ROUND(COSP.WTG012_TOTAL_VALUE_IN_TRANSACTION_CURRENCY, 2) AS MAR
    FROM COSP_DEDUPED COSP
    LEFT JOIN {{ ref('SILVER__TMEA_MANUFACTURING__ORDER_MASTER_DATA') }} omd
        ON REPLACE(COSP.OBJECT_NUMBER, 'OR', '') = omd.ORDER_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__GL_ACCOUNT_MASTER_RECORD') }} SKAT
        ON COSP.COST_ELEMENT = SKAT.GL_ACCOUNT_NUMBER
        AND SKAT.LANGUAGE_KEY = 'E'
        AND SKAT.CHART_OF_ACCOUNTS = '0010'
    LEFT JOIN (
        SELECT DISTINCT 
            REPLACE(PARTNER_OBJECT, 'OR', '') AS ORDER_NUMBER,
            CASE 
                WHEN OBJECT_NUMBER LIKE 'KS%' THEN RIGHT(OBJECT_NUMBER, 10)
                WHEN OBJECT_NUMBER LIKE 'KL%' THEN SUBSTR(OBJECT_NUMBER, 7, 10)
            END AS COST_CENTER
        FROM {{ ref('SILVER__TMEA_FINANCE__CO_OBJECT_LINE_ITEMS_BY_PERIOD') }}
        WHERE (OBJECT_NUMBER LIKE 'KS%' OR OBJECT_NUMBER LIKE 'KL%') 
          AND PARTNER_OBJECT LIKE 'ORS-%'
    ) cc_map
        ON REPLACE(COSP.OBJECT_NUMBER, 'OR', '') = cc_map.ORDER_NUMBER
    LEFT JOIN {{ ref('SILVER__TMEA_FINANCE__COST_CENTER_TEXTS') }} CSKT
        ON cc_map.COST_CENTER = CSKT.COST_CENTER
        AND CSKT.LANGUAGE_KEY = 'E'
        AND CSKT.CLIENT = '300'
    WHERE COSP.VALUE_TYPE = '01'
      AND omd.ORDER_NUMBER ILIKE 'S%'
      AND omd.DESCRIPTION NOT ILIKE '%close%'
      AND omd.DESCRIPTION NOT ILIKE '%do not use%'
),

PLAN AS (
    SELECT COST_CENTER, COST_CENTER_DESCRIPTION, INTERNAL_ORDER, INTERNAL_ORDER_DESCRIPTION,
           COST_ELEMENT, COST_ELEMENT_DESCRIPTION, FISCAL_YEAR, COST_DESCRIPTION, MONTH, COST
    FROM PLAN_RAW
    UNPIVOT(COST FOR MONTH IN (APR, MAY, JUN, JUL, AUG, SEP, OCT, NOV, DEC, JAN, FEB, MAR))
),

COMBINES AS (
    SELECT
        COST_CENTER,
        COST_CENTER_DESCRIPTION,
        INTERNAL_ORDER,
        INTERNAL_ORDER_DESCRIPTION,
        COST_ELEMENT,
        LTRIM(COST_ELEMENT, '0') || ' - ' || COALESCE(COST_ELEMENT_DESCRIPTION, '') AS COST_ELE_DEC,
        COST_ELEMENT_DESCRIPTION,
        FISCAL_YEAR,
        COST_DESCRIPTION,
        MONTH,
        CONCAT(FISCAL_YEAR, ' ', MONTH) AS FY_MONTH,
        COST
    FROM ACTUAL
    UNION ALL
    SELECT
        COST_CENTER,
        COST_CENTER_DESCRIPTION,
        INTERNAL_ORDER,
        INTERNAL_ORDER_DESCRIPTION,
        COST_ELEMENT,
        LTRIM(COST_ELEMENT, '0') || ' - ' || COALESCE(COST_ELEMENT_DESCRIPTION, '') AS COST_ELE_DEC,
        COST_ELEMENT_DESCRIPTION,
        FISCAL_YEAR,
        COST_DESCRIPTION,
        MONTH,
        CONCAT(FISCAL_YEAR, ' ', MONTH) AS FY_MONTH,
        COST
    FROM PLAN
),

transform_data as(
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
  	COST_CENTER,
    COST_CENTER_DESCRIPTION,
    INTERNAL_ORDER,
    INTERNAL_ORDER_DESCRIPTION,
    COST_ELEMENT,
    COST_ELE_DEC,
    COST_ELEMENT_DESCRIPTION,
    FISCAL_YEAR,
    COST_DESCRIPTION,
    MONTH,
    FY_MONTH,
    COST
FROM COMBINES
),

type_data as(
SELECT
    _AUDIT_LOG_ID,
    _ROW_HASH,
  	COST_CENTER,
    COST_CENTER_DESCRIPTION,
    INTERNAL_ORDER,
    INTERNAL_ORDER_DESCRIPTION,
    COST_ELEMENT,
    COST_ELE_DEC,
    COST_ELEMENT_DESCRIPTION,
    FISCAL_YEAR,
    COST_DESCRIPTION,
    MONTH,
    FY_MONTH,
    COST
FROM transform_data
)

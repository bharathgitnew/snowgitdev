    WHEN MONTH = 'JAN' THEN FISCAL_YEAR
    WHEN MONTH = 'FEB' THEN FISCAL_YEAR
    WHEN MONTH = 'MAR' THEN FISCAL_YEAR
    WHEN MONTH = 'APR' THEN CASE_A
    WHEN MONTH = 'MAY' THEN CASE_A
    WHEN MONTH = 'JUN' THEN CASE_A
    WHEN MONTH = 'Jul' THEN CASE_A
    WHEN MONTH = 'Aug' THEN CASE_A
    WHEN MONTH = 'Sep' THEN CASE_A
    WHEN MONTH = 'Oct' THEN CASE_A
    WHEN MONTH = 'Nov' THEN CASE_A
    WHEN MONTH = 'DEC' THEN CASE_A

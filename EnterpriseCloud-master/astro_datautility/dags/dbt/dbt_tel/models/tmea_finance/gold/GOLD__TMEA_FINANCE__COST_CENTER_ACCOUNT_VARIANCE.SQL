type_data as (
select
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
	CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
	CAST(COST_CENTER_OWNER as VARCHAR(16777216)) as COST_CENTER_OWNER,
	CAST(COST_CENTER_ as VARCHAR(16777216)) as COST_CENTER_,
	CAST(COST_CENTER_DESCRIPTION as VARCHAR(16777216)) as COST_CENTER_DESCRIPTION,

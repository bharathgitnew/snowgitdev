   Union all 
 SELECT COST_CENTER_OWNER,
COST_CENTER_,
COST_CENTER_DESCRIPTION,
COST_ELEMENT_GROUP,
COST_ELEMENT,
COST_ELEMENT_DESCRIPTOIN,
'VARIANCE' as COST_DESCRIPTION,  
FISCAL_YEAR,
MONTH ,
variance as value 
 from CTE
     Union all 
 SELECT COST_CENTER_OWNER,
COST_CENTER_,
COST_CENTER_DESCRIPTION,
COST_ELEMENT_GROUP,
COST_ELEMENT,
COST_ELEMENT_DESCRIPTOIN,
'VARIANCE_RATIO' as COST_DESCRIPTION,  
FISCAL_YEAR,
MONTH ,
variance_ratio as value 
 from CTE
),


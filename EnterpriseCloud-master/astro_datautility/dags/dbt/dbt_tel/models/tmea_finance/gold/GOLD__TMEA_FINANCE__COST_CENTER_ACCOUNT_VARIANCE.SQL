COST_CENTER_,
COST_CENTER_DESCRIPTION,
COST_ELEMENT_GROUP,
COST_ELEMENT,
COST_ELEMENT_DESCRIPTOIN,
'PLAN' as COST_DESCRIPTION, 
FISCAL_YEAR,
MONTH ,
Plan_value as value
  from CTE
  Union all 
 SELECT COST_CENTER_OWNER,
COST_CENTER_,
COST_CENTER_DESCRIPTION,
COST_ELEMENT_GROUP,
COST_ELEMENT,
COST_ELEMENT_DESCRIPTOIN,
'ACTUAL' as COST_DESCRIPTION, 

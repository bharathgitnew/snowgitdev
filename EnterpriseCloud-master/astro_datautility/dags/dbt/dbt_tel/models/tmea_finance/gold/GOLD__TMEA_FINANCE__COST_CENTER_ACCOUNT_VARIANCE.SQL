    ON CSKS.COST_CENTER = COST_CENTER_
LEFT JOIN GROUPING 
    ON TO_NUMBER(COST_ELEMENT)>=TO_NUMBER(FROM_VALUE) and TO_NUMBER(COST_ELEMENT) <=TO_NUMBER(TO_VALUE)


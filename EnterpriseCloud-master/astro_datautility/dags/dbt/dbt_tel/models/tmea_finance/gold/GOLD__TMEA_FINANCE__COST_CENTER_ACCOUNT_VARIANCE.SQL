	CAST(COST_ELEMENT_DESCRIPTOIN as VARCHAR(16777216)) as COST_ELEMENT_DESCRIPTOIN,
	CAST(COST_DESCRIPTION as VARCHAR(16777216)) as COST_DESCRIPTION,
	CAST(FISCAL_YEAR as VARCHAR(16777216)) as FISCAL_YEAR,
	CAST(MONTH as VARCHAR(16777216)) as MONTH,
	CAST(VALUE as NUMBER(38,2)) as VALUE
from transform_data 
)
select * from type_data
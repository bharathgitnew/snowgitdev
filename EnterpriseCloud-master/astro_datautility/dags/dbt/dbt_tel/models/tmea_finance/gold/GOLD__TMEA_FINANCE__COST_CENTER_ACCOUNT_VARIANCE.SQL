CTE_DISTINCT as (
   SELECT COST_CENTER_OWNER,
COST_CENTER_,
COST_CENTER_DESCRIPTION,
COST_ELEMENT_GROUP,
COST_ELEMENT,
COST_ELEMENT_DESCRIPTOIN,
FISCAL_YEAR,MONTH
    from UNPIVOT_ACTUAL_CUR_MONTH
  union 
     SELECT COST_CENTER_OWNER,
COST_CENTER_,
COST_CENTER_DESCRIPTION,
COST_ELEMENT_GROUP,
COST_ELEMENT,
COST_ELEMENT_DESCRIPTOIN,
FISCAL_YEAR,MONTH
    from UNPIVOT_PLAN_CUR_MONTH
),

CTE as (
SELECT distinct a.COST_CENTER_OWNER,
a.COST_CENTER_,
a.COST_CENTER_DESCRIPTION,
a.COST_ELEMENT_GROUP,
a.COST_ELEMENT,
a.COST_ELEMENT_DESCRIPTOIN,
a.FISCAL_YEAR,
a.MONTH,
zeroifnull(b.VALUE) as Plan_value,
zeroifnull(c.VALUE) as Actual_value,
Actual_value - Plan_value as variance,
case when Plan_value != 0 then variance/Plan_value * 100 else 0  end as variance_ratio
  from CTE_DISTINCT as a
  left join UNPIVOT_PLAN_CUR_MONTH as b
  on a.COST_CENTER_ = b.COST_CENTER_ and a.COST_ELEMENT_GROUP = b.COST_ELEMENT_GROUP and a.COST_ELEMENT = b.COST_ELEMENT
  and a.FISCAL_YEAR = b.FISCAL_YEAR and a.month = b.month
  left join UNPIVOT_ACTUAL_CUR_MONTH as c
  on a.COST_CENTER_ = c.COST_CENTER_ and a.COST_ELEMENT_GROUP = c.COST_ELEMENT_GROUP and a.COST_ELEMENT = c.COST_ELEMENT
  and a.FISCAL_YEAR = c.FISCAL_YEAR and a.month = c.month
),
CTE_UNION as (

{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='LOWER_LEVEL_SETS_IN_SETS',
        unique_key = ['CLIENT',
    'SET_CLASS',
    'ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS',
    'SET_NAME',
    'SET_LINE_COUNTER'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		SETCLASS as SET_CLASS,
		SUBCLASS as ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS,
		SETNAME as SET_NAME,
		LINEID as SET_LINE_COUNTER,
		SUBSETCLS as CLASS_OF_A_SUBORDINATE_SET,
		SUBSETSCLS as SUBCLASS_OF_A_SUBORDINATE_SET,
		SUBSETNAME as SUBORDINATE_SET_ID,
		SEQNR as SEQUENTIAL_NUMBER_OF_SET_LINE,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_FINANCE__SAPO_LOWER_LEVEL_SETS_IN_SETS') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		SET_CLASS,
		ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS,
		SET_NAME,
		SET_LINE_COUNTER,
		CLASS_OF_A_SUBORDINATE_SET,
		SUBCLASS_OF_A_SUBORDINATE_SET,
		SUBORDINATE_SET_ID,
		SEQUENTIAL_NUMBER_OF_SET_LINE
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR(16777216)) as CLIENT,
		cast(SET_CLASS as VARCHAR(16777216)) as SET_CLASS,
		cast(ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS as VARCHAR(16777216)) as ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS,
		cast(SET_NAME as VARCHAR(16777216)) as SET_NAME,
		cast(SET_LINE_COUNTER as VARCHAR(16777216)) as SET_LINE_COUNTER,
		cast(CLASS_OF_A_SUBORDINATE_SET as VARCHAR(16777216)) as CLASS_OF_A_SUBORDINATE_SET,
		cast(SUBCLASS_OF_A_SUBORDINATE_SET as VARCHAR(16777216)) as SUBCLASS_OF_A_SUBORDINATE_SET,
		cast(SUBORDINATE_SET_ID as VARCHAR(16777216)) as SUBORDINATE_SET_ID,
		cast(SEQUENTIAL_NUMBER_OF_SET_LINE as NUMBER(38,12)) as SEQUENTIAL_NUMBER_OF_SET_LINE
    from transform_data
)
select * from type_data
{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='PROFIT_CENTER_DESCRIPTION',
        unique_key = ['CLIENT',
    'LANGUAGE_KEY',
    'PROFIT_CENTER',
    'VALID_TO_DATE',
    'CONTROLLING_AREA'],
        transient=false
) }}

with source_data as
(
    SELECT
		MANDT  AS CLIENT ,
		SPRAS  AS LANGUAGE_KEY ,
		PRCTR  AS PROFIT_CENTER ,
		DATBI  AS VALID_TO_DATE ,
		KOKRS  AS CONTROLLING_AREA ,
		KTEXT  AS GENERAL_NAME ,
		LTEXT  AS LONG_TEXT ,
		MCTXT  AS SEARCH_TERM_FOR_MATCHCODE_SEARCH ,
		_CAPTUREDATETIME
    FROM {{ ref('BRONZE__TMEA_FINANCE__SAPO_PROFIT_CENTER_DESCRIPTION') }}
), 

transform_data as 
(
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
		CLIENT  AS CLIENT ,
		LANGUAGE_KEY  AS LANGUAGE_KEY ,
		PROFIT_CENTER  AS PROFIT_CENTER ,
		try_to_date(VALID_TO_DATE, 'YYYYMMDD')  AS VALID_TO_DATE ,
		CONTROLLING_AREA  AS CONTROLLING_AREA ,
		GENERAL_NAME  AS GENERAL_NAME ,
		LONG_TEXT  AS LONG_TEXT ,
		SEARCH_TERM_FOR_MATCHCODE_SEARCH  AS SEARCH_TERM_FOR_MATCHCODE_SEARCH -- Adds column to table on full refresh.
        FROM source_data
), 

type_data as
(
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		CAST(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast( CLIENT  AS VARCHAR(16777216))  AS CLIENT ,
		cast( LANGUAGE_KEY  AS VARCHAR(16777216))  AS LANGUAGE_KEY ,
		cast( PROFIT_CENTER  AS VARCHAR(16777216))  AS PROFIT_CENTER ,
		cast( VALID_TO_DATE  AS DATE)  AS VALID_TO_DATE ,
		cast( CONTROLLING_AREA  AS VARCHAR(16777216))  AS CONTROLLING_AREA ,
		cast( GENERAL_NAME  AS VARCHAR(16777216))  AS GENERAL_NAME ,
		cast( LONG_TEXT  AS VARCHAR(16777216))  AS LONG_TEXT ,
		cast( SEARCH_TERM_FOR_MATCHCODE_SEARCH  AS VARCHAR(16777216))  AS SEARCH_TERM_FOR_MATCHCODE_SEARCH 
    FROM transform_data
)

SELECT * FROM type_data
		cast(REFERENCE_PROCEDURE as VARCHAR) as REFERENCE_PROCEDURE,
		cast(REFERENCE_ORGANISATIONAL_UNITS as VARCHAR) as REFERENCE_ORGANISATIONAL_UNITS,

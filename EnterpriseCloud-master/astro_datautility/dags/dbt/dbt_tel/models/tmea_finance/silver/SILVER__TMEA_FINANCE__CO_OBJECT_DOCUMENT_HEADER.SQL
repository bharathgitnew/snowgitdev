		cast(NUMBER_OF_POSTING_ROWS_SENT_TO_EXTERNAL_SYSTEMS as VARCHAR) as NUMBER_OF_POSTING_ROWS_SENT_TO_EXTERNAL_SYSTEMS,
		cast(FOR_ALE_CO_DOCUMENT_NUMBER_IN_GENERATING_SYSTEM as VARCHAR) as FOR_ALE_CO_DOCUMENT_NUMBER_IN_GENERATING_SYSTEM,
		cast(LOGICAL_SYSTEM_OF_SOURCE_DOCUMENT as VARCHAR) as LOGICAL_SYSTEM_OF_SOURCE_DOCUMENT,

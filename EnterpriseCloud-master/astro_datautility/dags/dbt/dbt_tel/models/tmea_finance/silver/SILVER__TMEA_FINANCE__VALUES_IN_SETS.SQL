{{ config(
        materialized='tel_incremental',
        incremental_strategy='merge',
        alias='VALUES_IN_SETS',
        unique_key = ['CLIENT',
    'SET_CLASS',
    'ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS',
    'SET_NAME',
    'SET_LINE_COUNTER'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		SETCLASS as SET_CLASS,
		SUBCLASS as ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS,
		SETNAME as SET_NAME,
		LINEID as SET_LINE_COUNTER,
		VALSIGN as SIGN_FIELD_IN_CREATION_OF_SELECT_OPTIONS_TABLES,
		VALOPTION as OPTION_FIELD_IN_STRUCTURE_OF_SELECT_OPTIONS_TABLES,
		VALFROM as FROM_VALUE,
		VALTO as TO_VALUE,
		SEQNR as SEQUENTIAL_NUMBER_OF_SET_LINE,
		_CAPTUREDATETIME
    from {{ ref('BRONZE__TMEA_FINANCE__SAPO_VALUES_IN_SETS') }}
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		SET_CLASS,
		ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS,
		SET_NAME,
		SET_LINE_COUNTER,
		SIGN_FIELD_IN_CREATION_OF_SELECT_OPTIONS_TABLES,
		OPTION_FIELD_IN_STRUCTURE_OF_SELECT_OPTIONS_TABLES,
		FROM_VALUE,
		TO_VALUE,
		SEQUENTIAL_NUMBER_OF_SET_LINE
    from source_data
),

type_data as (
    select
		cast(_AUDIT_LOG_ID as varchar(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
        cast(CLIENT as VARCHAR(16777216)) as CLIENT,
		cast(SET_CLASS as VARCHAR(16777216)) as SET_CLASS,
		cast(ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS as VARCHAR(16777216)) as ORGANIZATIONAL_UNIT_AS_SET_SUBCLASS,
		cast(SET_NAME as VARCHAR(16777216)) as SET_NAME,
		cast(SET_LINE_COUNTER as VARCHAR(16777216)) as SET_LINE_COUNTER,
		cast(SIGN_FIELD_IN_CREATION_OF_SELECT_OPTIONS_TABLES as VARCHAR(16777216)) as SIGN_FIELD_IN_CREATION_OF_SELECT_OPTIONS_TABLES,
		cast(OPTION_FIELD_IN_STRUCTURE_OF_SELECT_OPTIONS_TABLES as VARCHAR(16777216)) as OPTION_FIELD_IN_STRUCTURE_OF_SELECT_OPTIONS_TABLES,
		cast(FROM_VALUE as VARCHAR(16777216)) as FROM_VALUE,
		cast(TO_VALUE as VARCHAR(16777216)) as TO_VALUE,
		cast(SEQUENTIAL_NUMBER_OF_SET_LINE as NUMBER(38,12)) as SEQUENTIAL_NUMBER_OF_SET_LINE
    from transform_data
)
select * from type_data
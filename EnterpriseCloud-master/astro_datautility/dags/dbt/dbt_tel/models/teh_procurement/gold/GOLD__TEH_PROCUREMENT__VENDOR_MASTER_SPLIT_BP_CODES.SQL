with customer_partner_function as 
(
    SELECT DISTINCT KUNNR as BUSINESS_PARTNER,KUNN2 
    FROM {{ ref('BRONZE__TEH_PROCUREMENT__SAPH_SAP_SDM_EV_KNVP') }}   
    WHERE  KUNN2 ilike 'C%' 
    AND PARVW = 'SH' 
    AND VKORG = '3200' --and KUNN2 = 'CZ0000200'
),

source_data as (
    with vendor_data as
    (
    SELECT DISTINCT 
    BPGD.BUSINESS_PARTNER_NUMBER	AS 	BUSINESS_PARTNER
    ,BPGD.NAME_1_OF_ORGANIZATION	AS 	NAME_ORG_1
    ,PARTNERFUNCTION.PARTNER_FUNCTION AS PARTNER_FUNCTION_CODE
    ,PARTNERFUNCTION.REFERENCE_TO_OTHER_VENDOR AS PARTNER_FUNCTION_NUMBER
    ,BPGD.SEARCH_TERM_1_FOR_BUSINESS_PARTNER	AS 	SEARCH_TERM_1
    ,BPGD.SEARCH_TERM_2_FOR_BUSINESS_PARTNER	AS 	SEARCH_TERM_2
    ,BPGD.CORPORATION	AS 	CORPORATION_CODE
    ,BPGD.OFFICE	AS 	OFFICE
    ,BPGD.BUSINESS_PARTNER_GROUPING	AS 	BU_GROUP
    ,BPGD.AUTHORIZATION_GROUP	AS 	AUTHORIZATION_GROUP
    ,BPGD.DATE_ON_WHICH_THE_OBJECT_WAS_CREATED	AS 	CREATED_ON
    ,BPGD.USER_WHO_CREATED_THE_OBJECT	AS 	CREATED_BY
    ,BPGD.DATE_WHEN_OBJECT_WAS_LAST_CHANGED	AS 	LAST_CHANGED_ON 
    ,DUN.IDENTIFICATION_NUMBER AS DUN_AND_BRADSTREET_NUMBER
    ,ARIBA.IDENTIFICATION_NUMBER AS ARIBA_NETWORK_NUMBER 
    ,BPGD.LFA1_CUSTOMER_NUMBER AS VENDOR_GENERAL_DATA_CUSTOMER_NO 		
    ,BPGD.PURCHASING_BLOCK_AT_PURCHASING_ORGANIZATION_LEVEL 	AS 	PURCHASE_ORG_BLOCK
    ,BPGD.LFA1_FUNCTION_THAT_WILL_BE_BLOCKED 	AS 	BLOCK_FUNCTION
    ,BPGD.LFA1_SUPPLIER_ACCOUNT_GROUP 	AS 	ACCOUNT_GROUP
    ,BPGD.RECONCILIATION_ACCOUNT_IN_GENERAL_LEDGER	AS 	RECONCILIATION_ACCOUNT
    ,SAPACCOUNT.ACCOUNT_LONG_DESCRIPTION AS RECONCILIATION_ACCOUNT_DESCRIPTION
    ,BPGD.LIST_OF_RESPECTED_PAYMENT_METHODS	AS 	PAYMENT_METHOD
    ,CASE 
        WHEN BPGD.POSTING_BLOCK_FOR_COMPANY_CODE = 'true' THEN 'X'
        WHEN BPGD.POSTING_BLOCK_FOR_COMPANY_CODE = 'false' THEN ''
        WHEN BPGD.POSTING_BLOCK_FOR_COMPANY_CODE IS NULL THEN NULL
        ELSE NULL
     END AS POSTING_BLOCK_FOR_COMPANY_CODE --adding case statement to change format as requested by nicole 5/15/2025
    ,BPGD.DELETION_FLAG_FOR_MASTER_RECORD	AS 	DELETION_FLAG_FOR_COMPANY_CODE
    ,BPGD.BLOCK_KEY_FOR_PAYMENT	AS 	PAYMENT_BLOCK 
    ,BPGD.INDICATOR_FOR_WITHHOLDING_TAX_TYPE AS Withholding_Tax_Type
    ,BPGD.INDICATOR_SUBJECT_TO_WITHHOLDING_TAX AS Subject_To_WithholdingTax
    ,BPGD.TYPE_OF_RECIPIENT AS Recipient_Type
    ,BPGD.WITHHOLDING_TAX_IDENTIFICATION_NUMBER AS Withholding_Tax_ID
    ,BPGD.WITHHOLDING_TAX_CODE AS WITHHOLDING_TAX_CODE 
    ,BPGD.LFB1_TERMS_OF_PAYMENT_KEY AS PAYMENT_TERMS_COMPANY_CODE
    ,BPGD.TERMS_OF_PAYMENT_KEY AS PAYMENT_TERMS_PURCHASE_ORG
    ,BPGD.INCOTERMS_INCO1 AS INCOTERMS 
    ,BANK.PARTNER_BANK_TYPE AS BANK_ID
    ,BANK.BANK_COUNTRY_KEY AS BANK_CTRY
    ,BANK.BANK_KEYS AS BANK_KEY
    ,BANK.BANK_ACCOUNT_NUMBER AS BANK_ACCT
    ,BANK.ACCOUNT_HOLDER_NAME AS ACCOUNT_HOLDER_NAME
    ,BANK.IBAN AS IBAN_NO
    ,BANK.BNKA_NAME_OF_BANK AS NAME_OF_BANK
    ,BANK.BNKA_BANK_NUMBER AS BANK_NUMBER
    ,BANK.BNKA_SWIFT_BIC_FOR_INTERNATIONAL_PAYMENTS AS SWIFT_BIC
    ,ADDRESS.HOUSE_NUMBER
    ,ADDRESS.STREET
    ,ADDRESS.CITY_POSTAL_CODE AS POSTAL_CODE
    ,ADDRESS.CITY AS CITY
    ,ADDRESS.COUNTRY_KEY AS COUNTRY 
    ,ADDRESS.REGION AS REGION 
    ,ADDRESS.FIRST_TELEPHONE_NO_DIALLING_CODE_NUMBER AS PHONE
    ,ADDRESS.FIRST_TELEPHONE_NO_EXTENSION AS PHONE_EXT
    ,ADDRESS.FIRST_FAX_NO_DIALLING_CODE_NUMBER AS FAX
    ,ADDRESS.FIRST_FAX_NO_EXTENSION AS FAX_EXT
    ,ADDRESS.ADR6_EMAIL_ADDRESS AS EMAIL 
    ,TO_TIMESTAMP(ADDRESS.VALIDITY_START_OF_A_BUSINESS_PARTNER_ADDRESS, 'YYYYMMDDHH24MISS') AS ADDRESS_VALID_FROM
    ,TO_TIMESTAMP(ADDRESS.VALIDITY_END_OF_A_BUSINESS_PARTNER_ADDRESS, 'YYYYMMDDHH24MISS') AS ADDRESS_VALID_TO
    --,((TO_TIMESTAMP(REGEXP_SUBSTR(ADDRESS.VALIDITY_START_OF_A_BUSINESS_PARTNER_ADDRESS, '/Date\\((\\d+)[\\+\\-]\\d+\\)', 1, 1, 'e')::NUMBER, 3)||REGEXP_SUBSTR(ADDRESS.VALIDITY_START_OF_A_BUSINESS_PARTNER_ADDRESS, '/Date\\(\\d+([\\+\\-]\\d+)\\)', 1, 1, 'e'))::TIMESTAMP_TZ)::TIMESTAMP_LTZ AS ADDRESS_VALID_FROM
    --,((TO_TIMESTAMP(REGEXP_SUBSTR(ADDRESS.VALIDITY_END_OF_A_BUSINESS_PARTNER_ADDRESS, '/Date\\((\\d+)[\\+\\-]\\d+\\)', 1, 1, 'e')::NUMBER, 3)||REGEXP_SUBSTR(ADDRESS.VALIDITY_END_OF_A_BUSINESS_PARTNER_ADDRESS, '/Date\\(\\d+([\\+\\-]\\d+)\\)', 1, 1, 'e'))::TIMESTAMP_TZ)::TIMESTAMP_LTZ AS ADDRESS_VALID_TO
    ,ADDRESS.NAME_1 AS ADRC_NAME_1
    ,ADDRESS.NAME_2 AS ADRC_NAME_2
    ,ADDRESS.STREET_2 AS ADRC_STREET_2
    ,ADDRESS.SEARCH_TERM_1 AS ADRC_SEARCH_TERM_1
    ,TAX_ID_1.TAX_NUM AS SOCIAL_SECURITY
    ,TAX_ID_2.TAX_NUM AS BUSINESS_EIN_NUMBER
    ,BPGD.LFB1_COMPANY_CODE AS LFB1_COMPANY_CODE
    ,BPGD.COMPANY_CODE AS LFBW_COMPANY_CODE
    ,ADDRESS.ADRC_VERSION_ID_FOR_INTERNATIONAL_ADDRESSES AS NATION 
    ,BPGD.VENDOR_S_ACCOUNT_NUMBER AS LFM1_BUS_PARTNER 
    ,BPGD.PURCHASING_ORGANIZATION AS LFM1_PURCH_ORG 
    ,BPGD.MINORITY_INDICATOR AS MINORITY_INDICATOR
    ,BPGD.CERTIFICATION_DATE AS CERTIFICATION_DATE
    ,IKT.DTAWS AS INSTRUCTION_KEY
    ,IKT.TEXT AS INSTRUCTION_KEY_TEXT
    FROM {{ ref('SILVER__TEH_PROCUREMENT__BUSINESS_PARTNERS_GENERAL_DATA') }} BPGD 
    LEFT OUTER JOIN (SELECT DISTINCT BUT0ID_BUSINESS_PARTNER_NUMBER,IDENTIFICATION_NUMBER FROM {{ ref('SILVER__TEH_PROCUREMENT__BUSINESS_PARTNERS_GENERAL_DATA') }} WHERE IDENTIFICATION_TYPE = 'BUP001') AS DUN ON BPGD.BUSINESS_PARTNER_NUMBER = DUN.BUT0ID_BUSINESS_PARTNER_NUMBER 
    LEFT OUTER JOIN (SELECT DISTINCT BUT0ID_BUSINESS_PARTNER_NUMBER,IDENTIFICATION_NUMBER FROM {{ ref('SILVER__TEH_PROCUREMENT__BUSINESS_PARTNERS_GENERAL_DATA') }} WHERE IDENTIFICATION_TYPE = 'BUP007') AS ARIBA ON BPGD.BUSINESS_PARTNER_NUMBER = ARIBA.BUT0ID_BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN {{ ref('SILVER__TEH_PROCUREMENT__BANK_DETAILS') }} BANK ON BPGD.BUSINESS_PARTNER_NUMBER = BANK.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR AND BANK.BANK_CONTROL_KEY = BANK.TIBAN_BANK_CONTROL_KEY
    LEFT OUTER JOIN {{ ref('SILVER__TEH_PROCUREMENT__BUSINESS_PARTNER_FUNCTION') }} PARTNERFUNCTION ON BPGD.BUSINESS_PARTNER_NUMBER = PARTNERFUNCTION.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
    LEFT OUTER JOIN {{ ref('SILVER__TEH_PROCUREMENT__ADDRESS_DETAILS') }} AS ADDRESS ON BPGD.BUSINESS_PARTNER_NUMBER = ADDRESS.BUSINESS_PARTNER_NUMBER 
    LEFT OUTER JOIN {{ ref('SILVER__TEH_PROCUREMENT__TAX_DETAILS') }} AS TAX_ID_1 ON BPGD.BUSINESS_PARTNER_NUMBER = TAX_ID_1.BUSINESS_PARTNER AND TAX_ID_1.TAX_NUMBER_CATEGORY = 'US1' 
    LEFT OUTER JOIN {{ ref('SILVER__TEH_PROCUREMENT__TAX_DETAILS') }} AS TAX_ID_2 ON BPGD.BUSINESS_PARTNER_NUMBER = TAX_ID_2.BUSINESS_PARTNER AND TAX_ID_2.TAX_NUMBER_CATEGORY = 'US2' 
    LEFT OUTER JOIN {{ ref('SILVER__TEH_PROCUREMENT__INSTRUCTION_KEY_EXPLANATION') }} AS IKT 
    ON IKT.BANKS = 'US' AND  
    BPGD.LFA1_LANGUAGE_KEY = IKT.SPRAS AND 
    BPGD.LIST_OF_RESPECTED_PAYMENT_METHODS = IKT.ZLSCH AND 
    BPGD.LFA1_INSTRUCTION_KEY_FOR_DATA_MEDIUM_EXCHANGE = IKT.DTAWS 
    LEFT OUTER JOIN {{ ref('SILVER__TEH_PROCUREMENT__SAP_ACCOUNT') }} SAPACCOUNT ON BPGD.RECONCILIATION_ACCOUNT_IN_GENERAL_LEDGER = SAPACCOUNT.ACCOUNT_NUMBER  
    ) 
    /* A-code "Corporation vendors" for the US */
    SELECT * FROM vendor_data 
    WHERE BU_GROUP = 'ZAZ0'                                         /*"Corporation vendors" for the US*/
    AND LFB1_COMPANY_CODE = '3100'                                  /*LFB1 Company Code=3100 for US */
    AND (LFBW_COMPANY_CODE = '3100' OR LFBW_COMPANY_CODE IS NULL)   /*LFBW Company Code=3100 for US -or- NULL LFBW Company Code*/
    AND NATION = ''                                                 /*Return "regular" address line, not the International version */
    UNION 
    /* B-code "Office vendors" for the US */
    SELECT * FROM vendor_data
    WHERE (LFB1_COMPANY_CODE = '3100')                              /*LFB1 Company Code=3100 for US*/
    AND (LFBW_COMPANY_CODE = '3100' OR LFBW_COMPANY_CODE IS NULL)   /*LFBW Company Code=3100 for US -or- NULL LFBW Company Code*/
    AND NATION = ''                                                 /*Return "regular" address line, not the International version */
    AND ((BU_GROUP = 'ZB00' AND AUTHORIZATION_GROUP = 'US')         /*B-code "Office vendors" for the US*/
        OR (LFM1_BUS_PARTNER ILIKE 'BA%' AND LFM1_PURCH_ORG = '3200') /*Need “BA” Offices Extended to LFM1 Purch Org 3200*/
        OR (LFM1_PURCH_ORG = '3200' AND BU_GROUP = 'ZB00' AND AUTHORIZATION_GROUP = 'GRP')) /*Need “BZ77” which has LFM1 Purch Org 3200*/
    UNION 
    /* E-code "Remit-To vendors" for the US */ 
    SELECT * FROM vendor_data 
    WHERE BU_GROUP = 'ZE00' AND AUTHORIZATION_GROUP = 'US'          /*E-code "Remit-To vendors" for the US*/
    AND LFB1_COMPANY_CODE = '3100'                                  /*LFB1 Company Code=3100 for US */
    AND (LFBW_COMPANY_CODE = '3100' OR LFBW_COMPANY_CODE IS NULL)   /*LFBW Company Code=3100 for US -or- NULL LFBW Company Code*/
    AND NATION = ''                                                 /*Return "regular" address line, not the International version*/
    UNION 
    /* C-CODE Customer vendors for US */
    SELECT * FROM vendor_data
    WHERE BU_GROUP='ZC00' AND AUTHORIZATION_GROUP='US' AND NATION=''
    UNION
    SELECT * FROM vendor_data 
    where BUSINESS_PARTNER IN (select KUNN2 from customer_partner_function) /*C Code */
    ),	


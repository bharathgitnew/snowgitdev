with VENDOR as
(
    SELECT DISTINCT
        VENDOR.LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR AS VENDOR_NUMBER
        , VENDOR.LFA1_NAME_1_NAME1 AS VENDOR_NAME
        , VENDOR.LFA1_COUNTRY_KEY_LAND1 AS COUNTRY
        , VENDOR.LFA1_CITY_ORT01 AS CITY
        , VENDOR.LFA1_REGION AS REGION
        ,VENDOR.MINORITY_INDICATOR
    FROM {{ ref('SILVER__TEH_PROCUREMENT__BUSINESS_PARTNERS_GENERAL_DATA') }} AS VENDOR --where LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR='BZ7008038'
),
source_data as
(
    SELECT DISTINCT
        ACDOCA.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR AS VENDOR_NUMBER,
        VENDOR.VENDOR_NAME AS VENDOR_NAME,
        SUM(ABS(ACDOCA.AMOUNT_IN_BALANCE_TRANSACTION_CURRENCY)) AS TOTAL_INVOICE_PRICE,
        ACDOCA.FISCAL_YEAR AS FISCAL_YEAR,
        LTRIM(ACDOCA.POSTING_PERIOD,'0') AS FISCAL_PERIOD,
        MAX(LEFT(ACDOCA.POSTING_DATE_IN_THE_DOCUMENT,4)) AS CALENDAR_YEAR,
        MAX(ACDOCA.POSTING_DATE_IN_THE_DOCUMENT) as POSTING_DATE,
        COALESCE(VENDOR.MINORITY_INDICATOR,'NOVALUE') AS TYPE,
        CASE 
            WHEN VENDOR.MINORITY_INDICATOR='Z01' THEN 'Disabled-Owned'
            WHEN VENDOR.MINORITY_INDICATOR='Z02' THEN 'Minority-Owned'
            WHEN VENDOR.MINORITY_INDICATOR='Z03' THEN 'SmallBusiness-Owned'
            WHEN VENDOR.MINORITY_INDICATOR='Z04' THEN 'Veteran-Owned'
            WHEN VENDOR.MINORITY_INDICATOR='Z05' THEN 'Women-Owned'
            ELSE 'NOVALUE'
        END DIVERSE_TYPE
    FROM {{ ref('SILVER__TEH_PROCUREMENT__UNIVERSAL_JOURNAL_ENTRY_LINE') }} ACDOCA
        LEFT JOIN VENDOR
            ON ACDOCA.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR = VENDOR.VENDOR_NUMBER
    WHERE POSTING_KEY = '31' 
            AND ACCOUNT_TYPE='K' 
            AND LEFT(PURCHASING_DOCUMENT_NUMBER,1)!='4'
            --AND DIVERSE_TYPE!='NOVALUE' change filter as specified by nicole 4/24/2025
            AND LEDGER_IN_GENERAL_LEDGER_ACCOUNTING='0L'
    GROUP BY
        ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
        VENDOR_NAME,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        TYPE,
        DIVERSE_TYPE
    ORDER BY VENDOR_NUMBER,FISCAL_YEAR,FISCAL_PERIOD
),
TRANSFORM_DATA AS ( 
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('HASH_ME') AS _ROW_HASH, -- ADDS COLUMN TO TABLE ON FULL REFRESH.
        VENDOR_NUMBER,
        VENDOR_NAME,
        TOTAL_INVOICE_PRICE,
        (fiscal_year::INT +1) AS FISCAL_YEAR,
        FISCAL_PERIOD,
        CALENDAR_YEAR,
        TO_CHAR(TO_DATE(POSTING_DATE, 'YYYYMMDD'), 'YYYY-MM-DD') AS POSTING_DATE,
        TYPE,
        DIVERSE_TYPE
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT 
        _AUDIT_LOG_ID,
        _ROW_HASH,
        VENDOR_NUMBER,
        VENDOR_NAME,
        CAST(TOTAL_INVOICE_PRICE AS NUMBER(38,2)) AS  TOTAL_INVOICE_PRICE,
        CAST(FISCAL_YEAR AS VARCHAR) AS FISCAL_YEAR,
        CAST(FISCAL_PERIOD AS VARCHAR) AS FISCAL_PERIOD,
        CALENDAR_YEAR,
        POSTING_DATE,
        TYPE,
        DIVERSE_TYPE
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
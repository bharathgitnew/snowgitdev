WITH PO as (
SELECT DISTINCT 
    EKPO_PURCHASING_DOCUMENT_NUMBER as PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP as ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    EKKO_COMPANY_CODE,
    PURCHASING_DOCUMENT_TYPE,
    to_date(DELIVERY_CREATE_DATE,'yyyymmdd') as PURCHASE_ORDER_CREATION_DATE,
    VENDOR_S_ACCOUNT_NUMBER,
    PURCHASING_ORGANIZATION_EKORG,
    CURRENCY_KEY,
    EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT,
    SHORT_TEXT,
    PLANT, 
    PURCHASE_ORDER_QUANTITY, 
    PURCHASE_ORDER_UNIT_OF_MEASURE, 
    NET_PRICE_IN_PURCHASING_DOCUMENT,
    PRICE_UNIT,
    NET_ORDER_VALUE_IN_PO_CURRENCY,
    REJECTION_INDICATOR
    DELIVERY_COMPLETED_INDICATOR,
    FINAL_INVOICE_INDICATOR,
    GOODS_RECEIPT_INDICATOR,
    GOODS_RECEIPT_NON_VALUATED,
    OUTWARD_DELIVERY_COMPLETED_INDICATOR,
    RETURNS_ITEM,
    ACCOUNT_ASSIGNMENT_CATEGORY,
    MATERIAL_NUMBER_MATNR
    FROM {{ ref('SILVER__TEH_PROCUREMENT__PURCHASE_ORDER_AGREEMENT_SCHEDULE_LINE') }}
    WHERE EKKO_COMPANY_CODE = '3200' 
    AND EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT NOT IN ('L','S')
    AND PURCHASING_DOCUMENT_TYPE in ('ZZNB','ZZFO') 
),

PO_GR_INVOICE AS (
    SELECT 
        EBELN AS PURCHASING_DOCUMENT_NUMBER, 
        EBELP AS ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        GJAHR AS YEAR,
        BELNR AS DOCUMENT,
        BUZEI AS ITEM,
        BEWTP AS TYPE,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'E' THEN MENGE
             WHEN SHKZG = 'H' AND BEWTP = 'E' THEN MENGE * -1 
        END AS GR_QTY,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'E' THEN WRBTR
        WHEN SHKZG = 'H' AND BEWTP = 'E' THEN WRBTR * -1 --changed from DMBTR to WRBTR
        END AS GR_AMT,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'E' THEN WRBTR 
             WHEN SHKZG = 'H' AND BEWTP = 'E' THEN WRBTR * -1 
        END AS GR_AMOUNT_IN_DOCUMENTCURRENCY,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'E' THEN AREWR            
             WHEN SHKZG = 'H' AND BEWTP = 'E' THEN AREWR * -1 
        END AS GR_CLEARING_AMOUNT,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'E' THEN REEWR 
             WHEN SHKZG = 'H' AND BEWTP = 'E' THEN REEWR * -1 
        END AS GR_VALUE_AMOUNT,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'Q' THEN MENGE
             WHEN SHKZG = 'H' AND BEWTP = 'Q' THEN MENGE * -1 
        END AS INV_QTY,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'Q' THEN DMBTR 
             WHEN SHKZG = 'H' AND BEWTP = 'Q' THEN DMBTR * -1 
        END AS INV_AMT,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'Q' THEN WRBTR 
             WHEN SHKZG = 'H' AND BEWTP = 'Q' THEN WRBTR * -1 
        END AS INV_AMOUNT_IN_DOCUMENTCURRENCY,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'Q' THEN AREWR            
             WHEN SHKZG = 'H' AND BEWTP = 'Q' THEN AREWR * -1 
        END AS INV_CLEARING_AMOUNT,
        CASE WHEN SHKZG = 'S' AND BEWTP = 'Q' THEN REEWR 
             WHEN SHKZG = 'H' AND BEWTP = 'Q' THEN REEWR * -1 
        END AS INV_VALUE_AMOUNT
    FROM {{ ref('BRONZE__TEH_PROCUREMENT__SAPAPI_ZCDV_T_CMTU217_EKBE') }}
),

PO_GR_INVOICE_SUM AS (
    SELECT
    PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    SUM(GR_QTY) AS GR_QTY,
    SUM(GR_AMT) AS GR_AMT,
    SUM(GR_AMOUNT_IN_DOCUMENTCURRENCY) AS GR_AMOUNT_IN_DOCUMENTCURRENCY,
    SUM(GR_CLEARING_AMOUNT) AS GR_CLEARING_AMOUNT,
    SUM(GR_VALUE_AMOUNT) AS GR_VALUE_AMOUNT,
    SUM(INV_QTY) AS INV_QTY,
    SUM(INV_AMT) AS INV_AMT,
    SUM(INV_AMOUNT_IN_DOCUMENTCURRENCY) AS INV_AMOUNT_IN_DOCUMENTCURRENCY,
    SUM(INV_CLEARING_AMOUNT) AS INV_CLEARING_AMOUNT,
    SUM(INV_VALUE_AMOUNT) AS INV_VALUE_AMOUNT
    FROM PO_GR_INVOICE
    GROUP BY PURCHASING_DOCUMENT_NUMBER, ITEM_NUMBER_OF_PURCHASING_DOCUMENT
),

AGG_VALUE AS (
    SELECT PO.PURCHASING_DOCUMENT_NUMBER AS PURCHASING_DOCUMENT_NUMBER,
    PO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    PO.EKKO_COMPANY_CODE AS EKKO_COMPANY_CODE,
    PO.PURCHASING_DOCUMENT_TYPE AS PURCHASING_DOCUMENT_TYPE,
    PO.EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT AS EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT,
    PO.PURCHASE_ORDER_CREATION_DATE AS PURCHASE_ORDER_CREATION_DATE,
    PO.VENDOR_S_ACCOUNT_NUMBER AS VENDOR_S_ACCOUNT_NUMBER,
    PO.PURCHASING_ORGANIZATION_EKORG AS PURCHASING_ORGANIZATION_EKORG,
    PO.CURRENCY_KEY AS CURRENCY_KEY,
    PO.SHORT_TEXT AS SHORT_TEXT,
    PO.PLANT AS PLANT, 
    PO.PURCHASE_ORDER_QUANTITY AS PURCHASE_ORDER_QUANTITY, 
    PO.PURCHASE_ORDER_UNIT_OF_MEASURE AS PURCHASE_ORDER_UNIT_OF_MEASURE, 
    PO.NET_PRICE_IN_PURCHASING_DOCUMENT AS NET_PRICE_IN_PURCHASING_DOCUMENT,
    PO.PRICE_UNIT AS PRICE_UNIT,
    PO.NET_ORDER_VALUE_IN_PO_CURRENCY AS NET_ORDER_VALUE_IN_PO_CURRENCY,
    PO.DELIVERY_COMPLETED_INDICATOR AS DELIVERY_COMPLETED_INDICATOR,
    PO.FINAL_INVOICE_INDICATOR AS FINAL_INVOICE_INDICATOR,
    PO.GOODS_RECEIPT_INDICATOR AS GOODS_RECEIPT_INDICATOR,
    PO.GOODS_RECEIPT_NON_VALUATED AS GOODS_RECEIPT_NON_VALUATED,
    PO.OUTWARD_DELIVERY_COMPLETED_INDICATOR AS OUTWARD_DELIVERY_COMPLETED_INDICATOR,
    PO.RETURNS_ITEM AS RETURNS_ITEM,
    PO.ACCOUNT_ASSIGNMENT_CATEGORY AS ACCOUNT_ASSIGNMENT_CATEGORY,
    PO.MATERIAL_NUMBER_MATNR AS MATERIAL_NUMBER_MATNR,
    PO_GR_INVOICE.GR_QTY AS GR_QTY,
    PO_GR_INVOICE.GR_AMT AS GR_AMT,
    PO_GR_INVOICE.GR_AMOUNT_IN_DOCUMENTCURRENCY AS GR_AMOUNT_IN_DOCUMENTCURRENCY,
    PO_GR_INVOICE.GR_CLEARING_AMOUNT AS GR_CLEARING_AMOUNT,
    PO_GR_INVOICE.GR_VALUE_AMOUNT AS GR_VALUE_AMOUNT,
    PO_GR_INVOICE.INV_QTY AS INV_QTY,
    PO_GR_INVOICE.INV_AMT AS INV_AMT,
    PO_GR_INVOICE.INV_AMOUNT_IN_DOCUMENTCURRENCY AS INV_AMOUNT_IN_DOCUMENTCURRENCY,
    PO_GR_INVOICE.INV_CLEARING_AMOUNT AS INV_CLEARING_AMOUNT,
    PO_GR_INVOICE.INV_VALUE_AMOUNT AS INV_VALUE_AMOUNT
    FROM PO AS PO
    LEFT JOIN PO_GR_INVOICE_SUM AS PO_GR_INVOICE
    ON PO.PURCHASING_DOCUMENT_NUMBER = PO_GR_INVOICE.PURCHASING_DOCUMENT_NUMBER 
    AND PO.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = PO_GR_INVOICE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT 
),

ARIBA_PO_HEADER AS (
    SELECT 
    PURCHASEORDERID,
    COMPANYCODE,
    CREATEDATE 
    FROM {{ ref('SILVER__TEH_PROCUREMENT__PURCHASEORDER_HEADER') }}
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PURCHASEORDERID ORDER BY PURCHASEORDERID,PURCHASEORDERVERSIONKEY DESC) = 1
),

ARIBA_PO AS (
    SELECT 
    SUBSTRING(POLINE.PURCHASEORDERIDKEY,0,7) AS PURCHASEORDERIDKEY_1,
    POLINE.PURCHASEORDERLINEITEMKEY,
    ARIBA_PO_HEADER.COMPANYCODE,
    ARIBA_PO_HEADER.CREATEDATE,
    SUPPLIERLOCATIONCODE,
    AMOUNTCURRENCYCODE,
    DESCRIPTIONDESCRIPTION,
    QUANTITY,
    DESCRIPTIONUNITOFMEASURECODE,
    AMOUNTAMOUNT/NULLIFZERO(QUANTITY),
    AMOUNTAMOUNT
    FROM {{ ref('SILVER__TEH_PROCUREMENT__PURCHASEORDER_LINEITEM') }} POLINE 
    LEFT JOIN ARIBA_PO_HEADER ON PURCHASEORDERIDKEY_1 = ARIBA_PO_HEADER.PURCHASEORDERID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PURCHASEORDERIDKEY_1,POLINE.PURCHASEORDERLINEITEMKEY ORDER BY PURCHASEORDERIDKEY_1,POLINE.PURCHASEORDERVERSIONKEY DESC) = 1
),

ARIBA_RECEIPT AS (
    SELECT 
    ERPPONUMBER, 
    ERPPOLINENUMBER, 
    SUM(NUMBERACCEPTED) AS ARIBA_GR_QTY,
    SUM(GROSSAMOUNTACCEPTEDAMOUNT) AS ARIBA_GR_AMT 
    FROM {{ ref('SILVER__TEH_PROCUREMENT__RECEIPT_LINEITEM') }}
    GROUP BY 1,2
),

ARIBA_INVOICE AS (
    SELECT 
    SUBSTRING(ORDERCODE,0,7) AS "ORDERCODE", 
    ORDERLINEITEMNUMBERINCOLLECTION, 
    SUM(QUANTITY) AS ARIBA_INV_QTY,
    SUM(AMOUNTAMOUNT) AS ARIBA_INV_AMT 
    FROM {{ ref('SILVER__TEH_PROCUREMENT__INVOICE_LINEITEM') }}
    GROUP BY 1,2
),

ARIBA_CTE AS (
    SELECT DISTINCT 
    ARIBA_PO.PURCHASEORDERIDKEY_1 AS ARIBA_PURCHASING_DOCUMENT_NUMBER,
    ARIBA_PO.PURCHASEORDERLINEITEMKEY AS ARIBA_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    ARIBA_PO.COMPANYCODE AS ARIBA_COMAPNYCODE,
    ARIBA_PO.CREATEDATE AS ARIBA_CREATEDATE,
    ARIBA_PO.SUPPLIERLOCATIONCODE AS ARIBA_SUPPLIERLOCATIONCODE,
    ARIBA_PO.AMOUNTCURRENCYCODE AS ARIBA_CURRENCYCODE,
    ARIBA_PO.DESCRIPTIONDESCRIPTION AS ARIBA_SHORTTEXT,
    ARIBA_PO.QUANTITY AS ARIBA_PURCHASE_ORDER_QUANTITY,
    ARIBA_PO.DESCRIPTIONUNITOFMEASURECODE AS ARIBA_UNIT_OF_MEASURE,
    ARIBA_PO.AMOUNTAMOUNT/NULLIFZERO(QUANTITY) AS ARIBA_NET_PRICE_IN_PURCHASING_DOCUMENT,
    ARIBA_PO.AMOUNTAMOUNT AS ARIBA_NET_ORDER_VALUE_IN_PO_CURRENCY,
    ARIBA_RECEIPT.ARIBA_GR_QTY,
    ARIBA_RECEIPT.ARIBA_GR_AMT,
    ARIBA_INVOICE.ARIBA_INV_QTY,
    ARIBA_INVOICE.ARIBA_INV_AMT
    FROM ARIBA_PO 
    LEFT JOIN ARIBA_RECEIPT
    ON ARIBA_PO.PURCHASEORDERIDKEY_1 = ARIBA_RECEIPT.ERPPONUMBER
    AND TRY_TO_NUMBER(ARIBA_PO.PURCHASEORDERLINEITEMKEY) = TRY_TO_NUMBER(ARIBA_RECEIPT.ERPPOLINENUMBER)
    LEFT JOIN ARIBA_INVOICE
    ON ARIBA_PO.PURCHASEORDERIDKEY_1 = ARIBA_INVOICE.ORDERCODE
    AND TRY_TO_NUMBER(ARIBA_PO.PURCHASEORDERLINEITEMKEY) = TRY_TO_NUMBER(ARIBA_INVOICE.ORDERLINEITEMNUMBERINCOLLECTION)
),

CTE_SAP_ARIBA AS (
    SELECT 
    AGG_VALUE.PURCHASING_DOCUMENT_NUMBER AS PURCHASING_DOCUMENT_NUMBER,
    AGG_VALUE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    AGG_VALUE.EKKO_COMPANY_CODE AS EKKO_COMPANY_CODE,
    AGG_VALUE.PURCHASING_DOCUMENT_TYPE AS PURCHASING_DOCUMENT_TYPE,
    AGG_VALUE.EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT AS EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT,
    AGG_VALUE.PURCHASE_ORDER_CREATION_DATE AS PURCHASE_ORDER_CREATION_DATE,
    AGG_VALUE.VENDOR_S_ACCOUNT_NUMBER AS VENDOR_S_ACCOUNT_NUMBER,
    AGG_VALUE.PURCHASING_ORGANIZATION_EKORG AS PURCHASING_ORGANIZATION_EKORG,
    AGG_VALUE.CURRENCY_KEY AS CURRENCY_KEY,
    AGG_VALUE.SHORT_TEXT AS SHORT_TEXT,
    AGG_VALUE.PLANT AS PLANT, 
    AGG_VALUE.PURCHASE_ORDER_QUANTITY AS PURCHASE_ORDER_QUANTITY, 
    AGG_VALUE.PURCHASE_ORDER_UNIT_OF_MEASURE AS PURCHASE_ORDER_UNIT_OF_MEASURE, 
    AGG_VALUE.NET_PRICE_IN_PURCHASING_DOCUMENT AS NET_PRICE_IN_PURCHASING_DOCUMENT,
    AGG_VALUE.PRICE_UNIT AS PRICE_UNIT,
    AGG_VALUE.NET_ORDER_VALUE_IN_PO_CURRENCY AS NET_ORDER_VALUE_IN_PO_CURRENCY,
    AGG_VALUE.DELIVERY_COMPLETED_INDICATOR AS DELIVERY_COMPLETED_INDICATOR,
    AGG_VALUE.FINAL_INVOICE_INDICATOR AS FINAL_INVOICE_INDICATOR,
    AGG_VALUE.GOODS_RECEIPT_INDICATOR AS GOODS_RECEIPT_INDICATOR,
    AGG_VALUE.GOODS_RECEIPT_NON_VALUATED AS GOODS_RECEIPT_NON_VALUATED,
    AGG_VALUE.OUTWARD_DELIVERY_COMPLETED_INDICATOR AS OUTWARD_DELIVERY_COMPLETED_INDICATOR,
    AGG_VALUE.RETURNS_ITEM AS RETURNS_ITEM,
    AGG_VALUE.ACCOUNT_ASSIGNMENT_CATEGORY AS ACCOUNT_ASSIGNMENT_CATEGORY,
    AGG_VALUE.MATERIAL_NUMBER_MATNR AS MATERIAL_NUMBER_MATNR,
    AGG_VALUE.GR_QTY AS GR_QTY,
    AGG_VALUE.GR_AMT AS GR_AMT,
    AGG_VALUE.GR_AMOUNT_IN_DOCUMENTCURRENCY AS GR_AMOUNT_IN_DOCUMENTCURRENCY,
    AGG_VALUE.GR_CLEARING_AMOUNT AS GR_CLEARING_AMOUNT,
    AGG_VALUE.GR_VALUE_AMOUNT AS GR_VALUE_AMOUNT,
    AGG_VALUE.INV_QTY AS INV_QTY,
    AGG_VALUE.INV_AMT AS INV_AMT,
    AGG_VALUE.INV_AMOUNT_IN_DOCUMENTCURRENCY AS INV_AMOUNT_IN_DOCUMENTCURRENCY,
    AGG_VALUE.INV_CLEARING_AMOUNT AS INV_CLEARING_AMOUNT,
    AGG_VALUE.INV_VALUE_AMOUNT AS INV_VALUE_AMOUNT,
    ARIBA_CTE.ARIBA_PURCHASING_DOCUMENT_NUMBER,
    ARIBA_CTE.ARIBA_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    ARIBA_CTE.ARIBA_COMAPNYCODE,
    ARIBA_CTE.ARIBA_CREATEDATE,
    ARIBA_CTE.ARIBA_SUPPLIERLOCATIONCODE,
    ARIBA_CTE.ARIBA_CURRENCYCODE,
    ARIBA_CTE.ARIBA_SHORTTEXT,
    ARIBA_CTE.ARIBA_PURCHASE_ORDER_QUANTITY,
    ARIBA_CTE.ARIBA_UNIT_OF_MEASURE,
    ARIBA_CTE.ARIBA_NET_PRICE_IN_PURCHASING_DOCUMENT,
    ARIBA_CTE.ARIBA_NET_ORDER_VALUE_IN_PO_CURRENCY,
    ARIBA_CTE.ARIBA_GR_QTY,
    ARIBA_CTE.ARIBA_GR_AMT,
    ARIBA_CTE.ARIBA_INV_QTY,
    ARIBA_CTE.ARIBA_INV_AMT
    FROM AGG_VALUE 
    JOIN ARIBA_CTE
    ON AGG_VALUE.PURCHASING_DOCUMENT_NUMBER = ARIBA_CTE.ARIBA_PURCHASING_DOCUMENT_NUMBER
    AND AGG_VALUE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = ARIBA_CTE.ARIBA_ITEM_NUMBER_OF_PURCHASING_DOCUMENT
),

SOURCE_DATA AS (
    SELECT 
    PURCHASING_DOCUMENT_NUMBER AS S4_PURCHASING_DOCUMENT_NUMBER,
    ARIBA_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT AS S4_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    ARIBA_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    PURCHASING_DOCUMENT_TYPE,
    EKKO_COMPANY_CODE AS S4_COMPANY_CODE,
    ARIBA_COMAPNYCODE,
    PURCHASE_ORDER_CREATION_DATE AS S4_PO_CREATEDATE,
    ARIBA_CREATEDATE,
    VENDOR_S_ACCOUNT_NUMBER AS S4_SUPPLIERCODE,
    ARIBA_SUPPLIERLOCATIONCODE AS ARIBA_SUPPLIERCODE,
    CURRENCY_KEY AS S4_CURRENCYCODE,
    ARIBA_CURRENCYCODE,
    SHORT_TEXT AS S4_SHORTTEXT,
    ARIBA_SHORTTEXT,
    PURCHASE_ORDER_QUANTITY AS S4_PURCHASE_ORDER_QUANTITY,
    ARIBA_PURCHASE_ORDER_QUANTITY,
    PURCHASE_ORDER_UNIT_OF_MEASURE AS S4_UNIT_OF_MEASURE,
    ARIBA_UNIT_OF_MEASURE,
    NET_ORDER_VALUE_IN_PO_CURRENCY AS S4_NET_ORDER_VALUE_IN_PO_CURRENCY,
    ARIBA_NET_ORDER_VALUE_IN_PO_CURRENCY,
    NET_PRICE_IN_PURCHASING_DOCUMENT AS S4_NET_PRICE_IN_PURCHASING_DOCUMENT,
    ARIBA_NET_PRICE_IN_PURCHASING_DOCUMENT,
    GR_QTY AS S4_GR_QTY, 
    ARIBA_GR_QTY,
    GR_AMT AS S4_GR_AMT,
    ARIBA_GR_AMT,
    INV_QTY AS S4_INV_QTY,
    ARIBA_INV_QTY,
    INV_CLEARING_AMOUNT AS S4_GR_IR_AMOUNT,
    ARIBA_INV_AMT,
    GR_QTY * NET_PRICE_IN_PURCHASING_DOCUMENT AS S4_GR_VALUE
    FROM CTE_SAP_ARIBA
),

TRANSFORM_DATA AS (
SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    S4_PURCHASING_DOCUMENT_NUMBER,
    ARIBA_PURCHASING_DOCUMENT_NUMBER,
    S4_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    ARIBA_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    PURCHASING_DOCUMENT_TYPE,
    S4_COMPANY_CODE,
    ARIBA_COMAPNYCODE,
    S4_PO_CREATEDATE,
    ARIBA_CREATEDATE,
    S4_SUPPLIERCODE,
    ARIBA_SUPPLIERCODE,
    S4_CURRENCYCODE,
    ARIBA_CURRENCYCODE,
    S4_SHORTTEXT,
    ARIBA_SHORTTEXT,
    S4_PURCHASE_ORDER_QUANTITY,
    ARIBA_PURCHASE_ORDER_QUANTITY,
    S4_UNIT_OF_MEASURE,
    ARIBA_UNIT_OF_MEASURE,
    S4_NET_ORDER_VALUE_IN_PO_CURRENCY,
    ARIBA_NET_ORDER_VALUE_IN_PO_CURRENCY,
    S4_NET_PRICE_IN_PURCHASING_DOCUMENT,
    ARIBA_NET_PRICE_IN_PURCHASING_DOCUMENT,
    S4_GR_QTY, 
    ARIBA_GR_QTY,
    S4_GR_AMT,
    ARIBA_GR_AMT,
    S4_INV_QTY,
    ARIBA_INV_QTY,
    S4_GR_IR_AMOUNT,
    ARIBA_INV_AMT,
    S4_GR_VALUE
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    S4_PURCHASING_DOCUMENT_NUMBER,
    ARIBA_PURCHASING_DOCUMENT_NUMBER,
    S4_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    ARIBA_ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    PURCHASING_DOCUMENT_TYPE,
    S4_COMPANY_CODE,
    ARIBA_COMAPNYCODE,
    S4_PO_CREATEDATE,
    ARIBA_CREATEDATE,
    S4_SUPPLIERCODE,
    ARIBA_SUPPLIERCODE,
    S4_CURRENCYCODE,
    ARIBA_CURRENCYCODE,
    S4_SHORTTEXT,
    ARIBA_SHORTTEXT,
    S4_PURCHASE_ORDER_QUANTITY,
    ARIBA_PURCHASE_ORDER_QUANTITY,
    S4_UNIT_OF_MEASURE,
    ARIBA_UNIT_OF_MEASURE,
    S4_NET_ORDER_VALUE_IN_PO_CURRENCY,
    ARIBA_NET_ORDER_VALUE_IN_PO_CURRENCY,
    S4_NET_PRICE_IN_PURCHASING_DOCUMENT,
    ARIBA_NET_PRICE_IN_PURCHASING_DOCUMENT,
    S4_GR_QTY, 
    ARIBA_GR_QTY,
    S4_GR_AMT,
    ARIBA_GR_AMT,
    S4_INV_QTY,
    ARIBA_INV_QTY,
    S4_GR_IR_AMOUNT,
    ARIBA_INV_AMT,
    S4_GR_VALUE
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
            When COMPANY_CODE = '3400' Then 'TVC'
            When COMPANY_CODE = '3500' Then 'TMEA'
            When COMPANY_CODE = '3700' Then 'TTAD'
        Else Null
        End As COMPANY_NAME
	FROM source_data
    WHERE ADDRESS_VALID_TO >= CURRENT_DATE()
    QUALIFY(ROW_NUMBER() OVER (PARTITION BY BUSINESS_PARTNER ORDER BY  ADDRESS_VALID_FROM DESC))= 1

WITH
SOURCE_DATA AS (
    SELECT 
        ACDOCA.LIFNR AS VENDOR_ID,
        LFA1.NAME1 AS VENDOR_NAME,
        LEFT(ACDOCA.BLDAT, 4) AS YR,
        SUBSTRING(ACDOCA.BLDAT, 5, 2) AS MO,
        ACDOCA.BLART,
        SUM(CASE 
            WHEN ACDOCA.DRCRK = 'S' THEN ACDOCA.HSL
            WHEN ACDOCA.DRCRK = 'H' THEN ACDOCA.HSL * -1
            ELSE 0
        END) AS TTL_INVOICED_AMT,
        --SUM(ACDOCA.HSL) AS TTL_INVOICED_AMT,
        CAL.FISCAL_YEAR_number - 1 AS FISCAL_YEAR,
        CAL.MONTH_OF_FISCAL_YEAR_NUMBER AS FISCAL_PERIOD,
        ACDOCA.RTCUR as CURRENCY --adding fiscal year, period and currency as requested by Mary 5/29/2025
    FROM {{ ref('BRONZE__TEH_PROCUREMENT__SAPAPI_ZCDV_T_CMTU024_ACDOCA') }} AS ACDOCA
    --FROM {{ ref('BRONZE__TEH_PROCUREMENT__SAPAPI_ZCDV_T_CMTU197_RSEG') }} AS RSEG
    --JOIN {{ ref('BRONZE__TEH_PROCUREMENT__SAPAPI_ZCDV_T_CMTU237_RBKP') }} AS RBKP ON (RBKP.BELNR = RSEG.BELNR)
    LEFT JOIN {{ ref('BRONZE__TEH_PROCUREMENT__SAPAPI_ZCDV_T_CMTU061_LFA1') }} AS LFA1 ON (ACDOCA.LIFNR = LFA1.LIFNR)
    JOIN COMMON.DE_SAP_MASTER_DATA.CALENDAR_DATE AS CAL ON TRY_TO_DATE(ACDOCA.BLDAT,'YYYYMMDD') = CAL.CALENDAR_DATE
    WHERE ACDOCA.KOART = 'K' and ACDOCA.RLDNR = '0L' and ACDOCA.BLART in ('AA','KR','KG','RE')
    GROUP BY ACDOCA.LIFNR, LFA1.NAME1, LEFT(ACDOCA.BLDAT, 4), SUBSTRING(ACDOCA.BLDAT, 5, 2), CURRENCY, FISCAL_YEAR, FISCAL_PERIOD,ACDOCA.BLART
    ORDER BY VENDOR_NAME, VENDOR_ID, YR, MO
),
TRANSFORM_DATA AS (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        VENDOR_ID, 
        VENDOR_NAME, 
        YR, 
        MO, 
        TTL_INVOICED_AMT,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        CURRENCY
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        _AUDIT_LOG_ID AS _AUDIT_LOG_ID,
        _ROW_HASH AS _ROW_HASH,
        VENDOR_ID AS VENDOR_ID,
        VENDOR_NAME AS VENDOR_NAME,
        YR AS YR,
        MO AS MO,
        CAST(TTL_INVOICED_AMT AS FLOAT) AS TTL_INVOICED_AMT,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        CURRENCY
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
{{ config(
    alias = 'SERVICENOW_SYS_DB_OBJECT',
    materialized = 'tel_incremental',
    incremental_strategy = 'merge',
    unique_key = ['SYS_ID'],
) }}

with source_data as (
    select
        _FILEDATE,
        JSONFIELD:"sys_id"::VARCHAR(16777216) as SYS_ID,
        JSONFIELD:"sys_created_on"::string as SYS_CREATED_ON,
        JSONFIELD:"sys_created_by"::string as SYS_CREATED_BY,
        JSONFIELD:"sys_updated_on"::string as SYS_UPDATED_ON,
        JSONFIELD:"sys_updated_by"::string as SYS_UPDATED_BY,
        JSONFIELD:"sys_mod_count"::string as SYS_MOD_COUNT,        
        JSONFIELD:"filter_extension"::string as FILTER_EXTENSION,
        JSONFIELD:"create_access"::string as CREATE_ACCESS,
        JSONFIELD:"alter_access"::string as ALTER_ACCESS,
        JSONFIELD:"access"::string as ACCESS,
        JSONFIELD:"live_feed_enabled"::string as LIVE_FEED_ENABLED,
        JSONFIELD:"is_df_table"::string as IS_DF_TABLE,
        JSONFIELD:"sys_class_name"::string as SYS_CLASS_NAME,
        JSONFIELD:"is_extendable"::string as IS_EXTENDABLE,
        JSONFIELD:"user_role"::string as USER_ROLE,
        JSONFIELD:"create_access_controls"::string as CREATE_ACCESS_CONTROLS,
        JSONFIELD:"delete_access"::string as DELETE_ACCESS,
        JSONFIELD:"sys_class_path"::string as SYS_CLASS_PATH,
        JSONFIELD:"caller_access"::string as CALLER_ACCESS,
        JSONFIELD:"client_scripts_access"::string as CLIENT_SCRIPTS_ACCESS,
        JSONFIELD:"extension_model"::string as EXTENSION_MODEL,
        JSONFIELD:"actions_access"::string as ACTIONS_ACCESS,
        JSONFIELD:"sys_name"::string as SYS_NAME,
        JSONFIELD:"sys_scope"::string as SYS_SCOPE,
        JSONFIELD:"is_data_interface"::string as IS_DATA_INTERFACE,
        JSONFIELD:"sys_class_code"::string as SYS_CLASS_CODE,
        JSONFIELD:"read_access"::string as READ_ACCESS,
        JSONFIELD:"super_class"::string as SUPER_CLASS,
        JSONFIELD:"ws_access"::string as WS_ACCESS,
        JSONFIELD:"label"::string as LABEL,
        JSONFIELD:"update_access"::string as UPDATE_ACCESS,
        JSONFIELD:"sys_package"::string as SYS_PACKAGE,
        JSONFIELD:"sys_update_name"::string as SYS_UPDATE_NAME,
        JSONFIELD:"scriptable_table"::string as SCRIPTABLE_TABLE,
        JSONFIELD:"configuration_access"::string as CONFIGURATION_ACCESS,
        JSONFIELD:"name"::string as NAME,
        JSONFIELD:"number_ref"::string as NUMBER_REF,
        JSONFIELD:"sys_policy"::string as SYS_POLICY,
    from {{ source('SERVICENOW', 'SYS_DB_OBJECT') }} 
    where _FILEDATE > ifnull((select max(_FILEDATE) from {{ this }}), '1970-01-01')
    qualify row_number() over (partition by SYS_ID order by _FILEDATE desc, _UPLOADDATE desc) = 1
),

transform_data as (
    select 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        current_timestamp()::timestamp_ntz as _REFRESHDATE,
        *,
    from source_data
),

type_data as (
    select 
        _AUDIT_LOG_ID,
        _ROW_HASH,
        _FILEDATE,
        _REFRESHDATE,
        SYS_ID::VARCHAR(16777216) as SYS_ID,
        convert_timezone('UTC', 'America/Chicago', SYS_CREATED_ON) as SYS_CREATED_ON,
        SYS_CREATED_BY::VARCHAR(16777216) as SYS_CREATED_BY,
        convert_timezone('UTC', 'America/Chicago', SYS_UPDATED_ON) as SYS_UPDATED_ON,
        SYS_UPDATED_BY::VARCHAR(16777216) as SYS_UPDATED_BY,
        SYS_MOD_COUNT::NUMBER(38,0) as SYS_MOD_COUNT,
        FILTER_EXTENSION::VARCHAR(16777216) as FILTER_EXTENSION,
        CREATE_ACCESS::BOOLEAN as CREATE_ACCESS,
        ALTER_ACCESS::BOOLEAN as ALTER_ACCESS,
        ACCESS::VARCHAR(16777216) as ACCESS,
        LIVE_FEED_ENABLED::BOOLEAN as LIVE_FEED_ENABLED,
        IS_DF_TABLE::BOOLEAN as IS_DF_TABLE,
        SYS_CLASS_NAME::VARCHAR(16777216) as SYS_CLASS_NAME,
        IS_EXTENDABLE::BOOLEAN as IS_EXTENDABLE,
        USER_ROLE::VARCHAR(16777216) as USER_ROLE,
        CREATE_ACCESS_CONTROLS::BOOLEAN as CREATE_ACCESS_CONTROLS,
        DELETE_ACCESS::BOOLEAN as DELETE_ACCESS,
        SYS_CLASS_PATH::VARCHAR(16777216) as SYS_CLASS_PATH,
        CALLER_ACCESS::VARCHAR(16777216) as CALLER_ACCESS,
        CLIENT_SCRIPTS_ACCESS::BOOLEAN as CLIENT_SCRIPTS_ACCESS,
        EXTENSION_MODEL::VARCHAR(16777216) as EXTENSION_MODEL,
        ACTIONS_ACCESS::BOOLEAN as ACTIONS_ACCESS,
        SYS_NAME::VARCHAR(16777216) as SYS_NAME,
        SYS_SCOPE::VARCHAR(16777216) as SYS_SCOPE,
        IS_DATA_INTERFACE::BOOLEAN as IS_DATA_INTERFACE,
        SYS_CLASS_CODE::VARCHAR(16777216) as SYS_CLASS_CODE,
        READ_ACCESS::BOOLEAN as READ_ACCESS,
        SUPER_CLASS::VARCHAR(16777216) as SUPER_CLASS,
        WS_ACCESS::BOOLEAN as WS_ACCESS,
        LABEL::VARCHAR(16777216) as LABEL,
        UPDATE_ACCESS::BOOLEAN as UPDATE_ACCESS,
        SYS_PACKAGE::VARCHAR(16777216) as SYS_PACKAGE,
        SYS_UPDATE_NAME::VARCHAR(16777216) as SYS_UPDATE_NAME,
        SCRIPTABLE_TABLE::BOOLEAN as SCRIPTABLE_TABLE,
        CONFIGURATION_ACCESS::BOOLEAN as CONFIGURATION_ACCESS,
        NAME::VARCHAR(16777216) as NAME,
        NUMBER_REF::VARCHAR(16777216) as NUMBER_REF,
        SYS_POLICY::VARCHAR(16777216) as SYS_POLICY,
    from transform_data
)

select * from type_data

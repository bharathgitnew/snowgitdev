    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='TGIS_RELEASE_SUMMARY'
) }}


with source_data as
(
    SELECT
        JSONFIELD:id::STRING AS ID,
        JSONFIELD:rls_mng_nm::STRING AS RLS_MNG_NM,
        JSONFIELD:workflow_name_ja::STRING AS WORKFLOW_NAME_JA,
        JSONFIELD:workflow_name_en::STRING AS WORKFLOW_NAME_EN,
        JSONFIELD:complete_result_category::STRING AS COMPLETE_RESULT_CATEGORY,
        JSONFIELD:complete_result_category_ja::STRING AS COMPLETE_RESULT_CATEGORY_JA,
        JSONFIELD:complete_result_category_en::STRING AS COMPLETE_RESULT_CATEGORY_EN,
        JSONFIELD:last_step_number::STRING AS LAST_STEP_NUMBER,
        JSONFIELD:progress_step_number::STRING AS PROGRESS_STEP_NUMBER,
        JSONFIELD:progress_step_name_ja::STRING AS PROGRESS_STEP_NAME_JA,
        JSONFIELD:progress_step_name_en::STRING AS PROGRESS_STEP_NAME_EN,
        JSONFIELD:input_lang::STRING AS INPUT_LANG,
        JSONFIELD:system_category_id::STRING AS SYSTEM_CATEGORY_ID,
        JSONFIELD:system_category_ja::STRING AS SYSTEM_CATEGORY_JA,
        JSONFIELD:system_category_en::STRING AS SYSTEM_CATEGORY_EN,
        JSONFIELD:system_id::STRING AS SYSTEM_ID,
        JSONFIELD:system_ja::STRING AS SYSTEM_JA,
        JSONFIELD:system_en::STRING AS SYSTEM_EN,
        JSONFIELD:subject_ja::STRING AS SUBJECT_JA,
        JSONFIELD:subject_en::STRING AS SUBJECT_EN,
        JSONFIELD:content_ja::STRING AS CONTENT_JA,
        JSONFIELD:content_en::STRING AS CONTENT_EN,
        JSONFIELD:is_priority_id::STRING AS IS_PRIORITY_ID,
        JSONFIELD:is_priority_ja::STRING AS IS_PRIORITY_JA,
        JSONFIELD:is_priority_en::STRING AS IS_PRIORITY_EN,
        JSONFIELD:is_priority_reason_ja::STRING AS IS_PRIORITY_REASON_JA,
        JSONFIELD:is_priority_reason_en::STRING AS IS_PRIORITY_REASON_EN,
        JSONFIELD:answer_deadline::STRING AS ANSWER_DEADLINE,
        CONVERT_TIMEZONE('UTC', 'US/Central',LEFT(((REGEXP_REPLACE(JSONFIELD:delivery_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ),POSITION(' -',(REGEXP_REPLACE(JSONFIELD:delivery_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ)-1)::TIMESTAMP_LTZ)::TIMESTAMP_NTZ AS DELIVERY_DATE,
        JSONFIELD:registered_telnm::STRING AS REGISTERED_TELNM,
        JSONFIELD:registered_telname::STRING AS REGISTERED_TELNAME,
        CONVERT_TIMEZONE('UTC', 'US/Central',LEFT(((REGEXP_REPLACE(JSONFIELD:registered_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ),POSITION(' -',(REGEXP_REPLACE(JSONFIELD:registered_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ)-1)::TIMESTAMP_LTZ)::TIMESTAMP_NTZ AS REGISTERED_DATE,
        CONVERT_TIMEZONE('UTC', 'US/Central',LEFT(((REGEXP_REPLACE(JSONFIELD:updated_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ),POSITION(' -',(REGEXP_REPLACE(JSONFIELD:updated_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ)-1)::TIMESTAMP_LTZ)::TIMESTAMP_NTZ AS UPDATED_DATE,
        _FILEDATE,
        _FILENAME
    FROM {{ source("TGIS", "RELEASE_SUMMARY") }}
    WHERE _FILEDATE = (
        SELECT MAX(RUN_TIME)
        FROM {{ source('TGIS', 'CONTROLTABLE') }}
        WHERE TABLE_NAME = 'dwh_release_summary'
        ))

,transform_data as (
    SELECT
        ID,
        RLS_MNG_NM,
        WORKFLOW_NAME_JA,
        WORKFLOW_NAME_EN,
        COMPLETE_RESULT_CATEGORY,
        COMPLETE_RESULT_CATEGORY_JA,
        COMPLETE_RESULT_CATEGORY_EN,
        LAST_STEP_NUMBER,
        PROGRESS_STEP_NUMBER,
        PROGRESS_STEP_NAME_JA,
        PROGRESS_STEP_NAME_EN,
        INPUT_LANG,
        SYSTEM_CATEGORY_ID,
        SYSTEM_CATEGORY_JA,
        SYSTEM_CATEGORY_EN,
        SYSTEM_ID,
        SYSTEM_JA,
        SYSTEM_EN,
        SUBJECT_JA,
        SUBJECT_EN,
        CONTENT_JA,
        CONTENT_EN,
        IS_PRIORITY_ID,
        IS_PRIORITY_JA,
        IS_PRIORITY_EN,
        IS_PRIORITY_REASON_JA,
        IS_PRIORITY_REASON_EN,
        ANSWER_DEADLINE,
        DELIVERY_DATE,
        REGISTERED_TELNM,
        REGISTERED_TELNAME,
        REGISTERED_DATE,
        UPDATED_DATE,
        _FILEDATE,
        _FILENAME,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    from source_data
)

,type_data as (
    SELECT
        CAST(ID AS VARCHAR(16777216)) AS ID,
        CAST(RLS_MNG_NM AS VARCHAR(16777216)) AS RLS_MNG_NM,
        CAST(WORKFLOW_NAME_JA AS VARCHAR(16777216)) AS WORKFLOW_NAME_JA,
        CAST(WORKFLOW_NAME_EN AS VARCHAR(16777216)) AS WORKFLOW_NAME_EN,
        CAST(COMPLETE_RESULT_CATEGORY AS VARCHAR(16777216)) AS COMPLETE_RESULT_CATEGORY,
        CAST(COMPLETE_RESULT_CATEGORY_JA AS VARCHAR(16777216)) AS COMPLETE_RESULT_CATEGORY_JA,
        CAST(COMPLETE_RESULT_CATEGORY_EN AS VARCHAR(16777216)) AS COMPLETE_RESULT_CATEGORY_EN,
        CAST(LAST_STEP_NUMBER AS VARCHAR(16777216)) AS LAST_STEP_NUMBER,
        CAST(PROGRESS_STEP_NUMBER AS VARCHAR(16777216)) AS PROGRESS_STEP_NUMBER,
        CAST(PROGRESS_STEP_NAME_JA AS VARCHAR(16777216)) AS PROGRESS_STEP_NAME_JA,
        CAST(PROGRESS_STEP_NAME_EN AS VARCHAR(16777216)) AS PROGRESS_STEP_NAME_EN,
        CAST(INPUT_LANG AS VARCHAR(16777216)) AS INPUT_LANG,
        CAST(SYSTEM_CATEGORY_ID AS VARCHAR(16777216)) AS SYSTEM_CATEGORY_ID,
        CAST(SYSTEM_CATEGORY_JA AS VARCHAR(16777216)) AS SYSTEM_CATEGORY_JA,
        CAST(SYSTEM_CATEGORY_EN AS VARCHAR(16777216)) AS SYSTEM_CATEGORY_EN,
        CAST(SYSTEM_ID AS VARCHAR(16777216)) AS SYSTEM_ID,
        CAST(SYSTEM_JA AS VARCHAR(16777216)) AS SYSTEM_JA,
        CAST(SYSTEM_EN AS VARCHAR(16777216)) AS SYSTEM_EN,
        CAST(SUBJECT_JA AS VARCHAR(16777216)) AS SUBJECT_JA,
        CAST(SUBJECT_EN AS VARCHAR(16777216)) AS SUBJECT_EN,
        CAST(CONTENT_JA AS VARCHAR(16777216)) AS CONTENT_JA,
        CAST(CONTENT_EN AS VARCHAR(16777216)) AS CONTENT_EN,
        CAST(IS_PRIORITY_ID AS VARCHAR(16777216)) AS IS_PRIORITY_ID,
        CAST(IS_PRIORITY_JA AS VARCHAR(16777216)) AS IS_PRIORITY_JA,
        CAST(IS_PRIORITY_EN AS VARCHAR(16777216)) AS IS_PRIORITY_EN,
        CAST(IS_PRIORITY_REASON_JA AS VARCHAR(16777216)) AS IS_PRIORITY_REASON_JA,
        CAST(IS_PRIORITY_REASON_EN AS VARCHAR(16777216)) AS IS_PRIORITY_REASON_EN,
        CAST(ANSWER_DEADLINE AS VARCHAR(16777216)) AS ANSWER_DEADLINE,
        CAST(DELIVERY_DATE AS VARCHAR(16777216)) AS DELIVERY_DATE,
        CAST(REGISTERED_TELNM AS VARCHAR(16777216)) AS REGISTERED_TELNM,
        CAST(REGISTERED_TELNAME AS VARCHAR(16777216)) AS REGISTERED_TELNAME,
        CAST(REGISTERED_DATE AS VARCHAR(16777216)) AS REGISTERED_DATE,
        CAST(UPDATED_DATE AS VARCHAR(16777216)) AS UPDATED_DATE,
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) as _FILEDATE,
		CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
		CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
	FROM transform_data
)

SELECT * FROM type_data
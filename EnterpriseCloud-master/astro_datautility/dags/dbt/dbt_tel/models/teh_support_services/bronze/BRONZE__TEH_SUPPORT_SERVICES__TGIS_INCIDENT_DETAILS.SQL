{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='TGIS_INCIDENT_DETAILS'
) }}


with source_data as
(
    SELECT
        JSONFIELD:id::STRING AS ID,
        JSONFIELD:incident_mng_nm::STRING AS INCIDENT_MNG_NM,
        JSONFIELD:history_nm::STRING AS HISTORY_NM,
        JSONFIELD:status_id::STRING AS STATUS_ID,
        JSONFIELD:status_ja::STRING AS STATUS_JA,
        JSONFIELD:status_en::STRING AS STATUS_EN,
        JSONFIELD:status_condition_id::STRING AS STATUS_CONDITION_ID,
        JSONFIELD:status_condition_ja::STRING AS STATUS_CONDITION_JA,
        JSONFIELD:status_condition_en::STRING AS STATUS_CONDITION_EN,
        JSONFIELD:input_lang::STRING AS INPUT_LANG,
        JSONFIELD:content_ja::STRING AS CONTENT_JA,
        JSONFIELD:content_en::STRING AS CONTENT_EN,
        JSONFIELD:urgency_id::STRING AS URGENCY_ID,
        JSONFIELD:last_urgency_ja::STRING AS LAST_URGENCY_JA,
        JSONFIELD:last_urgency_en::STRING AS LAST_URGENCY_EN,
        JSONFIELD:urgency_reason_ja::STRING AS URGENCY_REASON_JA,
        JSONFIELD:urgency_reason_en::STRING AS URGENCY_REASON_EN,
        JSONFIELD:registered_telnm::STRING AS REGISTERED_TELNM,
        JSONFIELD:registered_telname::STRING AS REGISTERED_TELNAME,
        CONVERT_TIMEZONE('UTC', 'US/Central',LEFT(((REGEXP_REPLACE(JSONFIELD:registered_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ),POSITION(' -',(REGEXP_REPLACE(JSONFIELD:registered_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ)-1)::TIMESTAMP_LTZ)::TIMESTAMP_NTZ AS REGISTERED_DATE,
        _FILEDATE,
        _FILENAME
    FROM {{ source("TGIS", "INCIDENT_DETAILS") }}
    WHERE _FILEDATE = (
        SELECT MAX(RUN_TIME)
        FROM {{ source('TGIS', 'CONTROLTABLE') }}
        WHERE TABLE_NAME = 'dwh_incident_details'
        )
)

,transform_data as (
    SELECT
        ID,
        INCIDENT_MNG_NM,
        HISTORY_NM,
        STATUS_ID,
        STATUS_JA,
        STATUS_EN,
        STATUS_CONDITION_ID,
        STATUS_CONDITION_JA,
        STATUS_CONDITION_EN,
        INPUT_LANG,
        CONTENT_JA,
        CONTENT_EN,
        URGENCY_ID,
        LAST_URGENCY_JA,
        LAST_URGENCY_EN,
        URGENCY_REASON_JA,
        URGENCY_REASON_EN,
        REGISTERED_TELNM,
        REGISTERED_TELNAME,
        REGISTERED_DATE,
        _FILEDATE,
        _FILENAME,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    from source_data
)

,type_data as (
    SELECT
        CAST (ID AS VARCHAR(16777216)) AS ID,
        CAST (INCIDENT_MNG_NM AS VARCHAR(16777216)) AS INCIDENT_MNG_NM,
        CAST (HISTORY_NM AS VARCHAR(16777216)) AS HISTORY_NM,
        CAST (STATUS_ID AS VARCHAR(16777216)) AS STATUS_ID,
        CAST (STATUS_JA AS VARCHAR(16777216)) AS STATUS_JA,
        CAST (STATUS_EN AS VARCHAR(16777216)) AS STATUS_EN,
        CAST (STATUS_CONDITION_ID AS VARCHAR(16777216)) AS STATUS_CONDITION_ID,
        CAST (STATUS_CONDITION_JA AS VARCHAR(16777216)) AS STATUS_CONDITION_JA,
        CAST (STATUS_CONDITION_EN AS VARCHAR(16777216)) AS STATUS_CONDITION_EN,
        CAST (INPUT_LANG AS VARCHAR(16777216)) AS INPUT_LANG,
        CAST (CONTENT_JA AS VARCHAR(16777216)) AS CONTENT_JA,
        CAST (CONTENT_EN AS VARCHAR(16777216)) AS CONTENT_EN,
        CAST (URGENCY_ID AS VARCHAR(16777216)) AS URGENCY_ID,
        CAST (LAST_URGENCY_JA AS VARCHAR(16777216)) AS LAST_URGENCY_JA,
        CAST (LAST_URGENCY_EN AS VARCHAR(16777216)) AS LAST_URGENCY_EN,
        CAST (URGENCY_REASON_JA AS VARCHAR(16777216)) AS URGENCY_REASON_JA,
        CAST (URGENCY_REASON_EN AS VARCHAR(16777216)) AS URGENCY_REASON_EN,
        CAST (REGISTERED_TELNM AS VARCHAR(16777216)) AS REGISTERED_TELNM,
        CAST (REGISTERED_TELNAME AS VARCHAR(16777216)) AS REGISTERED_TELNAME,
        CAST (REGISTERED_DATE AS TIMESTAMP_NTZ(9)) AS REGISTERED_DATE,
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) as _FILEDATE,
		CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
		CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
	FROM transform_data
)

SELECT * FROM type_data
        JSONFIELD:last_status_id::STRING AS LAST_STATUS_ID,
        JSONFIELD:last_status_ja::STRING AS LAST_STATUS_JA,
        JSONFIELD:last_status_en::STRING AS LAST_STATUS_EN,
        JSONFIELD:last_status_condition_id::STRING AS LAST_STATUS_CONDITION_ID,
        JSONFIELD:last_status_condition_ja::STRING AS LAST_STATUS_CONDITION_JA,
        JSONFIELD:last_status_condition_en::STRING AS LAST_STATUS_CONDITION_EN,
        JSONFIELD:input_lang::STRING AS INPUT_LANG,
        JSONFIELD:subject_ja::STRING AS SUBJECT_JA,
        JSONFIELD:subject_en::STRING AS SUBJECT_EN,
        JSONFIELD:system_category_id::STRING AS SYSTEM_CATEGORY_ID,
        JSONFIELD:system_category_ja::STRING AS SYSTEM_CATEGORY_JA,
        JSONFIELD:system_category_en::STRING AS SYSTEM_CATEGORY_EN,
        JSONFIELD:system_id::STRING AS SYSTEM_ID,
        JSONFIELD:system_ja::STRING AS SYSTEM_JA,
        JSONFIELD:system_en::STRING AS SYSTEM_EN,
        JSONFIELD:repeat_category_id::STRING AS REPEAT_CATEGORY_ID,
        JSONFIELD:repeat_category_ja::STRING AS REPEAT_CATEGORY_JA,
        JSONFIELD:repeat_category_en::STRING AS REPEAT_CATEGORY_EN,
        JSONFIELD:cause_category_id::STRING AS CAUSE_CATEGORY_ID,
        JSONFIELD:cause_category_ja::STRING AS CAUSE_CATEGORY_JA,
        JSONFIELD:cause_category_en::STRING AS CAUSE_CATEGORY_EN,
        JSONFIELD:last_urgency_id::STRING AS LAST_URGENCY_ID,
        JSONFIELD:last_urgency_ja::STRING AS LAST_URGENCY_JA,
        JSONFIELD:last_urgency_en::STRING AS LAST_URGENCY_EN,
        JSONFIELD:last_urgency_reason_ja::STRING AS LAST_URGENCY_REASON_JA,
        JSONFIELD:last_urgency_reason_en::STRING AS LAST_URGENCY_REASON_EN,
        JSONFIELD:notes_ja::STRING AS NOTES_JA,
        JSONFIELD:notes_en::STRING AS NOTES_EN,
        JSONFIELD:registered_telnm::STRING AS REGISTERED_TELNM,
        JSONFIELD:registered_telname::STRING AS REGISTERED_TELNAME,
        JSONFIELD:proxy_registered_telnm::STRING AS PROXY_REGISTERED_TELNM,
        JSONFIELD:proxy_registered_telname::STRING AS PROXY_REGISTERED_TELNAME,
        CONVERT_TIMEZONE('UTC', 'US/Central',LEFT(((REGEXP_REPLACE(JSONFIELD:registered_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ),POSITION(' -',(REGEXP_REPLACE(JSONFIELD:registered_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ)-1)::TIMESTAMP_LTZ)::TIMESTAMP_NTZ AS REGISTERED_DATE,
        CONVERT_TIMEZONE('UTC', 'US/Central',LEFT(((REGEXP_REPLACE(JSONFIELD:updated_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ),POSITION(' -',(REGEXP_REPLACE(JSONFIELD:updated_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ)-1)::TIMESTAMP_LTZ)::TIMESTAMP_NTZ AS UPDATED_DATE,
        JSONFIELD:incharge_groupid::STRING AS INCHARGE_GROUPID,
        JSONFIELD:incharge_group_ja::STRING AS INCHARGE_GROUP_JA,
        JSONFIELD:incharge_group_en::STRING AS INCHARGE_GROUP_EN,
        CONVERT_TIMEZONE('UTC', 'US/Central',LEFT(((REGEXP_REPLACE(JSONFIELD:delivery_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ),POSITION(' -',(REGEXP_REPLACE(JSONFIELD:delivery_date, '\/Date\\(|\\)\/', '')::TIMESTAMP)::TIMESTAMP_LTZ)-1)::TIMESTAMP_LTZ)::TIMESTAMP_NTZ AS ETA,
        _FILEDATE,
        _FILENAME
    FROM {{ source("TGIS", "INCIDENT_SUMMARY") }}
    WHERE _FILEDATE = (
        SELECT MAX(RUN_TIME)
        FROM {{ source('TGIS', 'CONTROLTABLE') }}
        WHERE TABLE_NAME = 'dwh_incident_summary'
        ) 
)

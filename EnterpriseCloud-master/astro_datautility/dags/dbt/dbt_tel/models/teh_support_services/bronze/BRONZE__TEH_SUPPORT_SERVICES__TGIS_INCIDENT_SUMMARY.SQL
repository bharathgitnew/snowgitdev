with source_data as
(
    SELECT
        JSONFIELD:id::STRING AS ID,
        JSONFIELD:incident_mng_nm::STRING AS INCIDENT_MNG_NM,
        JSONFIELD:last_history_nm::STRING AS LAST_HISTORY_NM,
        JSONFIELD:matter_category_id::STRING AS MATTER_CATEGORY_ID,

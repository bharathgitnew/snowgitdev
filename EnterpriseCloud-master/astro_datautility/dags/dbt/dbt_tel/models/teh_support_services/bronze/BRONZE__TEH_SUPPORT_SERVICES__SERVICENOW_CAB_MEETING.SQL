        JSONFIELD:"sys_class_name"::string as SYS_CLASS_NAME,
        JSONFIELD:"cmn_schedule_span_origin"::string as CMN_SCHEDULE_SPAN_ORIGIN,
        JSONFIELD:"complete_preapproved_changes"::string as COMPLETE_PREAPPROVED_CHANGES,
        JSONFIELD:"notification_lead_time"::string as NOTIFICATION_LEAD_TIME,

        SYS_CLASS_NAME::VARCHAR(16777216) as SYS_CLASS_NAME,
        CMN_SCHEDULE_SPAN_ORIGIN::VARCHAR(16777216) as CMN_SCHEDULE_SPAN_ORIGIN,

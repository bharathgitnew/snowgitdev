        JSONFIELD:"actual_end"::string as ACTUAL_END,
        JSONFIELD:"end"::string as END_DATETIME,
        JSONFIELD:"state"::string as STATE,
        JSONFIELD:"manager"::string as MANAGER,
        JSONFIELD:"modified_fields"::string as MODIFIED_FIELDS,
        JSONFIELD:"board_members"::string as BOARD_MEMBERS,
        JSONFIELD:"cmn_schedule_span_exclude"::string as CMN_SCHEDULE_SPAN_EXCLUDE,
        JSONFIELD:"agenda_locked"::string as AGENDA_LOCKED,
        JSONFIELD:"end_sdt"::string as END_SDT,
        JSONFIELD:"start"::string as START_DATETIME,
        JSONFIELD:"active"::string as ACTIVE,
        JSONFIELD:"delegates"::string as DELEGATES,
        JSONFIELD:"sys_tags"::string as SYS_TAGS,
        JSONFIELD:"change_range_start"::string as CHANGE_RANGE_START,
        JSONFIELD:"conference_details"::string as CONFERENCE_DETAILS,
        JSONFIELD:"organizer"::string as ORGANIZER,
        JSONFIELD:"name"::string as NAME,
        JSONFIELD:"locations"::string as LOCATIONS,
        JSONFIELD:"start_sdt"::string as START_SDT,
        JSONFIELD:"cab_definition"::string as CAB_DEFINITION,
    from {{ source('SERVICENOW', 'CAB_MEETING') }} 
    where _FILEDATE > ifnull((select max(_FILEDATE) from {{ this }}), '1970-01-01')
    qualify row_number() over (partition by SYS_ID order by _FILEDATE desc, _UPLOADDATE desc) = 1
),

transform_data as (
    select 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        current_timestamp()::timestamp_ntz as _REFRESHDATE,
        *,
    from source_data
),

type_data as (
    select 
        _AUDIT_LOG_ID,
        _ROW_HASH,
        _FILEDATE,
        _REFRESHDATE,
        SYS_ID::VARCHAR(16777216) as SYS_ID,
        convert_timezone('UTC', 'America/Chicago', SYS_CREATED_ON) as SYS_CREATED_ON,
        SYS_CREATED_BY::VARCHAR(16777216) as SYS_CREATED_BY,
        convert_timezone('UTC', 'America/Chicago', SYS_UPDATED_ON) as SYS_UPDATED_ON,
        SYS_UPDATED_BY::VARCHAR(16777216) as SYS_UPDATED_BY,
        SYS_MOD_COUNT::NUMBER(38,0) as SYS_MOD_COUNT,

        BOARD_MEMBERS::VARCHAR(16777216) as BOARD_MEMBERS,
        CMN_SCHEDULE_SPAN_EXCLUDE::VARCHAR(16777216) as CMN_SCHEDULE_SPAN_EXCLUDE,
        AGENDA_LOCKED::BOOLEAN as AGENDA_LOCKED,
        END_SDT::VARCHAR(16777216) as END_SDT,
        convert_timezone('UTC', 'America/Chicago', START_DATETIME) as START_DATETIME,
        ACTIVE::BOOLEAN as ACTIVE,
        DELEGATES::VARCHAR(16777216) as DELEGATES,
        SYS_TAGS::VARCHAR(16777216) as SYS_TAGS,
        convert_timezone('UTC', 'America/Chicago', CHANGE_RANGE_START) as CHANGE_RANGE_START,
        CONFERENCE_DETAILS::VARCHAR(16777216) as CONFERENCE_DETAILS,
        ORGANIZER::VARCHAR(16777216) as ORGANIZER,
        NAME::VARCHAR(16777216) as NAME,
        LOCATIONS::VARCHAR(16777216) as LOCATIONS,
        START_SDT::VARCHAR(16777216) as START_SDT,
        CAB_DEFINITION::VARCHAR(16777216) as CAB_DEFINITION,
    from transform_data
)


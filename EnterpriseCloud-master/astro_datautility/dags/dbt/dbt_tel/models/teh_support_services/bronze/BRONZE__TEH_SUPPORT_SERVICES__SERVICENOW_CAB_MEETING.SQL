        convert_timezone('UTC', 'America/Chicago', CHANGE_RANGE_END) as CHANGE_RANGE_END,
        IGNORE_CHANGE_DATE_RANGE::BOOLEAN as IGNORE_CHANGE_DATE_RANGE,
        TIME_PER_AGENDA_ITEM::VARCHAR(16777216) as TIME_PER_AGENDA_ITEM,
        MEETING_NOTES::VARCHAR(16777216) as MEETING_NOTES,
        CHANGE_CONDITION::VARCHAR(16777216) as CHANGE_CONDITION,
        CMN_SCHEDULE_SPAN_END::VARCHAR(16777216) as CMN_SCHEDULE_SPAN_END,

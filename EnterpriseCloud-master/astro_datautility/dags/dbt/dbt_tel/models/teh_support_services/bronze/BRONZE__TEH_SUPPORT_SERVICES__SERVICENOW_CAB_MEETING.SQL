with source_data as (
    select
        _FILEDATE,
        JSONFIELD:"sys_id"::VARCHAR(16777216) as SYS_ID,
        JSONFIELD:"sys_created_on"::string as SYS_CREATED_ON,
        JSONFIELD:"sys_created_by"::string as SYS_CREATED_BY,
        JSONFIELD:"sys_updated_on"::string as SYS_UPDATED_ON,
        JSONFIELD:"sys_updated_by"::string as SYS_UPDATED_BY,
        JSONFIELD:"sys_mod_count"::string as SYS_MOD_COUNT,        
        JSONFIELD:"auto_add_agenda_decisions"::string as AUTO_ADD_AGENDA_DECISIONS,
        JSONFIELD:"change_range_end"::string as CHANGE_RANGE_END,
        JSONFIELD:"ignore_change_date_range"::string as IGNORE_CHANGE_DATE_RANGE,
        JSONFIELD:"time_per_agenda_item"::string as TIME_PER_AGENDA_ITEM,
        JSONFIELD:"meeting_notes"::string as MEETING_NOTES,

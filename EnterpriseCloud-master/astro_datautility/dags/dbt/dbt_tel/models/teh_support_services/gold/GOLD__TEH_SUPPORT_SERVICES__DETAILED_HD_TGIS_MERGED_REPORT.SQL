with first_comment_data as
(
    SELECT
        INCIDENT_SUMMARY_INCIDENT_MNG_NM AS INCIDENT_SUMMARY_INCIDENT_MNG_NM_MIN,
        INCIDENT_DETAILS_CONTENT_EN AS MIN_INCIDENT_COMMENT_EN,
        INCIDENT_DETAILS_CONTENT_JA AS MIN_INCIDENT_COMMENT_JA
FROM {{ ref('GOLD__TEH_SUPPORT_SERVICES__HELPDESK_TGIS_MASTER') }}
WHERE INCIDENT_DETAILS_HISTORY_NM=1
),

source_data as (
    SELECT
        CASE_NUMBER,
        INCIDENT_SUMMARY_INCIDENT_MNG_NM,
        CASE_TITLE,
        INCIDENT_SUMMARY_SUBJECT_EN,
        INCIDENT_SUMMARY_SUBJECT_JA,
        INCIDENT_SUMMARY_LAST_URGENCY_EN,
        URGENCY,
        PRIMARY_CONTACT,
        INCIDENT_SUMMARY_REGISTERED_TELNAME,
        CREATED_ON,
        INCIDENT_SUMMARY_REGISTERED_DATE,
        INCIDENT_SUMMARY_SYSTEM_EN,
        SYSTEM,
        REQUESTOR_CASE_TYPE,
        REQUESTOR_CASE_SUB_TYPE,
        INCIDENT_SUMMARY_INCHARGE_GROUP_EN,
        WORKED_BY,
        INCIDENT_DETAILS_STATUS_CONDITION_EN AS INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN,
        INCIDENT_DETAILS_CONTENT_JA,
        STATUS,
        INCIDENT_DETAILS_CONTENT_EN,
        DESCRIPTION,
        MODIFIED_ON,
        MODIFIED_BY,
        AGE_DAYS,
        ITHD_ETA,
        TGIS_ETA,
        LISTAGG(RELATED_CASE,',') AS RELATED_CASE,
        COUNT_OF_RELATED_CASES,
        COUNT_OF_RELATED_ICD_CASES,
        LAST_REFRESH_DATETIME,
        TGISNUMBER,
        FUNCTION_AREA,
        QUEUE,
        RESOLVED_ON,
        PMO_UPDATE,
        PROJECT,
        INCIDENT_DETAILS_CONTENT_EN AS CONTENT_EN,
        INCIDENT_DETAILS_REGISTERED_TELNAME AS REGISTERED_TELNAME,
        INCIDENT_DETAILS_REGISTERED_DATE AS ICD_UPDATED_DATE,
        ICD_CASE_SUB_TYPE
    FROM {{ ref('GOLD__TEH_SUPPORT_SERVICES__HELPDESK_TGIS_MASTER') }}
    WHERE MAX_RECORD_COUNTER=1 OR INCIDENT_SUMMARY_INCIDENT_MNG_NM='No T-GIS'
    GROUP BY
        CASE_NUMBER,
        INCIDENT_SUMMARY_INCIDENT_MNG_NM,
        CASE_TITLE,
        INCIDENT_SUMMARY_SUBJECT_EN,
        INCIDENT_SUMMARY_SUBJECT_JA,
        INCIDENT_SUMMARY_LAST_URGENCY_EN,
        URGENCY,
        PRIMARY_CONTACT,
        INCIDENT_SUMMARY_REGISTERED_TELNAME,
        CREATED_ON,
        INCIDENT_SUMMARY_REGISTERED_DATE,
        INCIDENT_SUMMARY_SYSTEM_EN,
        SYSTEM,
        REQUESTOR_CASE_TYPE,
        REQUESTOR_CASE_SUB_TYPE,
        INCIDENT_SUMMARY_INCHARGE_GROUP_EN,
        WORKED_BY,
        INCIDENT_DETAILS_STATUS_CONDITION_EN,
        INCIDENT_DETAILS_CONTENT_JA,
        STATUS,
        INCIDENT_DETAILS_CONTENT_EN,
        DESCRIPTION,
        MODIFIED_ON,
        MODIFIED_BY,
        AGE_DAYS,
        ITHD_ETA,
        TGIS_ETA,
        COUNT_OF_RELATED_CASES,
        COUNT_OF_RELATED_ICD_CASES,
        LAST_REFRESH_DATETIME,
        TGISNUMBER,
        FUNCTION_AREA,
        QUEUE,
        RESOLVED_ON,
        PMO_UPDATE,
        PROJECT,
        INCIDENT_DETAILS_REGISTERED_TELNAME,
        INCIDENT_DETAILS_REGISTERED_DATE,
        ICD_CASE_SUB_TYPE
),
transform_data as
(
SELECT
    DISTINCT
    CASE_NUMBER,
    CASE
        WHEN INCIDENT_SUMMARY_INCIDENT_MNG_NM='No T-GIS' and TGISNUMBER IS NOT NULL
            THEN TGISNUMBER
        ELSE INCIDENT_SUMMARY_INCIDENT_MNG_NM
    END AS TGIS_ID,
    CASE
        WHEN CASE_TITLE IS NOT NULL
            THEN CASE_TITLE
        ELSE
            INCIDENT_SUMMARY_SUBJECT_EN
    END AS TITLE_EN,
    CASE
        WHEN INCIDENT_DETAILS_CONTENT_EN IS NOT NULL
            THEN MIN_INCIDENT_COMMENT_EN
        ELSE
            DESCRIPTION
    END AS DESCRIPTION_EN,
    URGENCY AS ITHD_URGENCY,
    STATUS AS ITHD_STATUS,
    INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN AS TGIS_STATUS,
    CASE
        WHEN PRIMARY_CONTACT IS NOT NULL
            THEN PRIMARY_CONTACT
        ELSE
            INCIDENT_SUMMARY_REGISTERED_TELNAME
    END AS ISSUER,
    HELPDESK_TGIS_MASTER.FUNCTION_AREA,
    CREATED_ON AS ITHD_ISSUE_DATE,
    WORKED_BY AS WORKED_BY_ITHD,
    INCIDENT_SUMMARY_INCHARGE_GROUP_EN AS L2_GROUP_TGIS,
         (CASE
        WHEN STATUS IS NULL OR TRIM(STATUS)='' OR INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IS NULL  OR TRIM(INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN)='' THEN ''
        WHEN STATUS='In Progress' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IN('Accepted(Service Desk)','Accepted(Company/Genpo IS)','L1 dispatching(Service Desk)','L1 In Progress(Service Desk)','L2 dispatching','L2 In Progress','Problem Escalation','Change Escalation','Service Request Escalation','L1 In Progress(Company/Genpo IS)','L1 dispatching(Company/Genpo IS)','L1 Answered(Service Desk)','L2 Answered','L1 Answered(Company/Genpo IS)','L1 Compatible','L1 Answered','IS Compatible','L2 Compatible')THEN 'Yes'
        WHEN STATUS='Resolved - Pending Confirmation' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN='Resolved – Pending Confirmation' THEN 'Yes'
        WHEN STATUS='Resolved - Closed' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN='Resolved' THEN 'Yes'
        WHEN STATUS='Canceled' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IN('Resolved – Pending Confirmation','Resolved','Canceled') THEN 'Yes'
        WHEN STATUS='On hold' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN NOT IN('Resolved') THEN 'Yes'
        ELSE 'NO'
    END) AS PROGRESS_UPDATE,
    INCIDENT_SUMMARY_REGISTERED_DATE AS TGIS_ISSUE_DATE,
    QUEUE AS QUEUE,
    REQUESTOR_CASE_TYPE AS REQUESTOR_CASE_TYPE,
    REQUESTOR_CASE_SUB_TYPE AS REQUESTOR_CASE_SUB_TYPE,
    CASE
        WHEN INCIDENT_SUMMARY_SYSTEM_EN IS NOT NULL
            THEN INCIDENT_SUMMARY_SYSTEM_EN
        ELSE
            SYSTEM
    END AS SYSTEM_NAME,
    RESOLVED_ON AS RESOLVED_ON,
    ITHD_ETA AS ITHD_ETA,
    TGIS_ETA AS TGIS_ETA,
    CASE WHEN ITHD_ETA=TGIS_ETA THEN 'Y' ELSE 'N' END AS ETA_MATCH_FLAG,
    CASE
        WHEN INCIDENT_DETAILS_CONTENT_EN IS NOT NULL
            THEN INCIDENT_DETAILS_CONTENT_EN
        ELSE
            DESCRIPTION
    END AS LATEST_TIMELINE_EN,
    CASE
        WHEN INCIDENT_SUMMARY_REGISTERED_DATE IS NOT NULL
            THEN INCIDENT_SUMMARY_REGISTERED_DATE
        ELSE MODIFIED_ON
    END AS UPDATED_ON,
    CASE
        WHEN INCIDENT_SUMMARY_REGISTERED_TELNAME IS NOT NULL
            THEN INCIDENT_SUMMARY_REGISTERED_TELNAME
        ELSE MODIFIED_BY
    END AS UPDATED_BY,
    DATEDIFF(day,ITHD_ISSUE_DATE,CURRENT_TIMESTAMP()) AS AGE_IN_ITHD,
    RELATED_CASE AS RELATED_CASE,
    COUNT_OF_RELATED_CASES AS COUNT_OF_RELATED_CASES,
    COUNT_OF_RELATED_ICD_CASES AS COUNT_OF_RELATED_ICD_CASES,
    PMO_UPDATE AS PMO_UPDATE,
    PROJECT,
    INCIDENT_DETAILS_CONTENT_EN AS CONTENT_EN,
    REGISTERED_TELNAME,
    ICD_UPDATED_DATE,
    SYSTEM,
    ICD_CASE_SUB_TYPE,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH -- Adds column to table on full refresh.
FROM source_data HELPDESK_TGIS_MASTER
    LEFT JOIN first_comment_data ON first_comment_data.INCIDENT_SUMMARY_INCIDENT_MNG_NM_MIN=HELPDESK_TGIS_MASTER.INCIDENT_SUMMARY_INCIDENT_MNG_NM
),

type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CASE_NUMBER,
        TGIS_ID,
        TITLE_EN,
        DESCRIPTION_EN,
        ITHD_URGENCY,
        ITHD_STATUS,
        TGIS_STATUS,
        ISSUER,
        FUNCTION_AREA AS FUNCTIONAL_TEAM,
        ITHD_ISSUE_DATE,
        WORKED_BY_ITHD,
        L2_GROUP_TGIS AS L2_GROUP_TGIS,
        PROGRESS_UPDATE AS PROGRESS_UPDATE,
        TGIS_ISSUE_DATE,
        QUEUE AS QUEUE,
        REQUESTOR_CASE_TYPE AS REQUESTOR_CASE_TYPE,
        REQUESTOR_CASE_SUB_TYPE AS REQUESTOR_CASE_SUB_TYPE,
        SYSTEM_NAME,
        RESOLVED_ON AS RESOLVED_ON,
        ITHD_ETA,
        TGIS_ETA,
        ETA_MATCH_FLAG,
        LATEST_TIMELINE_EN,
        UPDATED_ON,
        UPDATED_BY,
        CAST(AGE_IN_ITHD AS NUMBER(38,0)) AS AGE_IN_ITHD,
        RELATED_CASE,
        COUNT_OF_RELATED_CASES,
        COUNT_OF_RELATED_ICD_CASES,
        PMO_UPDATE,
        PROJECT,
        CONTENT_EN,
        REGISTERED_TELNAME,
        ICD_UPDATED_DATE,
        SYSTEM,
        ICD_CASE_SUB_TYPE
    FROM transform_data
)

SELECT * from type_data
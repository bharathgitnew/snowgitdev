{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='HELPDESK_TGIS_REPORT_DETAILED',
      transient=false
) }}

with first_comment_data as
(
    SELECT
        INCIDENT_SUMMARY_INCIDENT_MNG_NM AS INCIDENT_SUMMARY_INCIDENT_MNG_NM_MIN,
        INCIDENT_DETAILS_CONTENT_EN AS MIN_INCIDENT_COMMENT_EN,
        INCIDENT_DETAILS_CONTENT_JA AS MIN_INCIDENT_COMMENT_JA
FROM {{ ref('GOLD__TEH_SUPPORT_SERVICES__HELPDESK_TGIS_MASTER') }}
WHERE INCIDENT_DETAILS_HISTORY_NM=1
),

source_data as (
    SELECT
        CASE_NUMBER,
        INCIDENT_SUMMARY_INCIDENT_MNG_NM,
        CASE_TITLE,
        INCIDENT_SUMMARY_SUBJECT_EN,
        INCIDENT_SUMMARY_SUBJECT_JA,
        INCIDENT_SUMMARY_LAST_URGENCY_EN,
        URGENCY,
        PRIMARY_CONTACT,
        INCIDENT_SUMMARY_REGISTERED_TELNAME,
        CREATED_ON,
        INCIDENT_SUMMARY_REGISTERED_DATE,
        INCIDENT_SUMMARY_SYSTEM_EN,
        SYSTEM,
        REQUESTOR_CASE_TYPE,
        REQUESTOR_CASE_SUB_TYPE,
        INCIDENT_SUMMARY_INCHARGE_GROUP_EN,
        WORKED_BY,
        INCIDENT_DETAILS_STATUS_CONDITION_EN AS INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN,
        INCIDENT_DETAILS_CONTENT_JA,
        STATUS,
        INCIDENT_DETAILS_CONTENT_EN,
        DESCRIPTION,
        MODIFIED_ON,
        MODIFIED_BY,
        AGE_DAYS,
        ITHD_ETA,
        TGIS_ETA,
        LISTAGG(RELATED_CASE,',') AS RELATED_CASE,
        COUNT_OF_RELATED_CASES,
        COUNT_OF_RELATED_ICD_CASES,
        LAST_REFRESH_DATETIME,
        TGISNUMBER
    FROM {{ ref('GOLD__TEH_SUPPORT_SERVICES__HELPDESK_TGIS_MASTER') }}
    WHERE MAX_RECORD_COUNTER=1 OR INCIDENT_SUMMARY_INCIDENT_MNG_NM='No T-GIS'
    GROUP BY
        CASE_NUMBER,
        INCIDENT_SUMMARY_INCIDENT_MNG_NM,
        CASE_TITLE,
        INCIDENT_SUMMARY_SUBJECT_EN,
        INCIDENT_SUMMARY_SUBJECT_JA,
        INCIDENT_SUMMARY_LAST_URGENCY_EN,
        URGENCY,
        PRIMARY_CONTACT,
        INCIDENT_SUMMARY_REGISTERED_TELNAME,
        CREATED_ON,
        INCIDENT_SUMMARY_REGISTERED_DATE,
        INCIDENT_SUMMARY_SYSTEM_EN,
        SYSTEM,
        REQUESTOR_CASE_TYPE,
        REQUESTOR_CASE_SUB_TYPE,
        INCIDENT_SUMMARY_INCHARGE_GROUP_EN,
        WORKED_BY,
        INCIDENT_DETAILS_STATUS_CONDITION_EN,
        INCIDENT_DETAILS_CONTENT_JA,
        STATUS,
        INCIDENT_DETAILS_CONTENT_EN,
        DESCRIPTION,
        MODIFIED_ON,
        MODIFIED_BY,
        AGE_DAYS,
        ITHD_ETA,
        TGIS_ETA,
        COUNT_OF_RELATED_CASES,
        COUNT_OF_RELATED_ICD_CASES,
        LAST_REFRESH_DATETIME,
        TGISNUMBER
),
transform_data as 
(
SELECT
    DISTINCT
    CASE_NUMBER,
    CASE 
        WHEN INCIDENT_SUMMARY_INCIDENT_MNG_NM='No T-GIS' and TGISNUMBER IS NOT NULL
            THEN TGISNUMBER
        ELSE INCIDENT_SUMMARY_INCIDENT_MNG_NM 
    END AS TGIS_ID,
    CASE 
        WHEN CASE_TITLE IS NOT NULL
            THEN CASE_TITLE
        ELSE
            INCIDENT_SUMMARY_SUBJECT_EN
    END AS TITLE_EN,
    CASE 
        WHEN CASE_TITLE IS NOT NULL
            THEN CASE_TITLE
        ELSE
            INCIDENT_SUMMARY_SUBJECT_JA
    END AS TITLE_JA,
    INCIDENT_SUMMARY_LAST_URGENCY_EN AS TGIS_URGENCY,
    URGENCY AS ITHD_URGENCY,
    CASE 
        WHEN INCIDENT_SUMMARY_LAST_URGENCY_EN IS NOT NULL
            THEN INCIDENT_SUMMARY_LAST_URGENCY_EN
        ELSE
            URGENCY
    END AS URGENCY,
    CASE 
        WHEN PRIMARY_CONTACT IS NOT NULL
            THEN PRIMARY_CONTACT
        ELSE
            INCIDENT_SUMMARY_REGISTERED_TELNAME
    END AS ISSUER,
    CREATED_ON AS ITHD_ISSUE_DATE,
    INCIDENT_SUMMARY_REGISTERED_DATE AS TGIS_ISSUE_DATE,
    CASE 
        WHEN CREATED_ON IS NOT NULL
            THEN CREATED_ON
        ELSE
            INCIDENT_SUMMARY_REGISTERED_DATE
    END AS ISSUE_DATE,
    CASE 
        WHEN INCIDENT_SUMMARY_SYSTEM_EN IS NOT NULL
            THEN INCIDENT_SUMMARY_SYSTEM_EN
        ELSE
            SYSTEM
    END AS SYSTEM_NAME,
    REQUESTOR_CASE_TYPE AS CASE_TYPE,
    REQUESTOR_CASE_SUB_TYPE AS CASE_SUB_TYPE,
    CASE 
        WHEN INCIDENT_SUMMARY_INCHARGE_GROUP_EN IS NOT NULL
            THEN INCIDENT_SUMMARY_INCHARGE_GROUP_EN
        ELSE
            WORKED_BY
    END AS PIC,
    CASE 
        WHEN INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IS NOT NULL
            THEN INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN
        ELSE
            STATUS
    END AS STATUS,
    CASE 
        WHEN INCIDENT_DETAILS_CONTENT_EN IS NOT NULL
            THEN MIN_INCIDENT_COMMENT_EN
        ELSE
            DESCRIPTION
    END AS DESCRIPTION_EN,
    CASE 
        WHEN INCIDENT_DETAILS_CONTENT_JA IS NOT NULL
            THEN MIN_INCIDENT_COMMENT_JA
        ELSE
            DESCRIPTION
    END AS DESCRIPTION_JA,
    CASE
        WHEN INCIDENT_DETAILS_CONTENT_EN IS NOT NULL
            THEN INCIDENT_DETAILS_CONTENT_EN
        ELSE
            DESCRIPTION 
    END AS LATEST_TIMELINE_EN,
    CASE
        WHEN INCIDENT_DETAILS_CONTENT_JA IS NOT NULL
            THEN INCIDENT_DETAILS_CONTENT_JA
        ELSE
            DESCRIPTION 
    END AS LATEST_TIMELINE_JA,
    CASE 
        WHEN INCIDENT_SUMMARY_REGISTERED_DATE IS NOT NULL
            THEN INCIDENT_SUMMARY_REGISTERED_DATE
        ELSE MODIFIED_ON
    END AS UPDATED_ON,
    CASE 
        WHEN INCIDENT_SUMMARY_REGISTERED_TELNAME IS NOT NULL
            THEN INCIDENT_SUMMARY_REGISTERED_TELNAME
        ELSE MODIFIED_BY
    END AS UPDATED_BY,
    DATEDIFF(day,ITHD_ISSUE_DATE,CURRENT_TIMESTAMP()) AS AGE_IN_ITHD,
    DATEDIFF(day,INCIDENT_SUMMARY_REGISTERED_DATE,CURRENT_TIMESTAMP()) AS AGE_IN_TGIS,
    CASE
        WHEN AGE_IN_TGIS IS NULL THEN AGE_IN_ITHD
        WHEN AGE_IN_ITHD IS NULL THEN AGE_IN_TGIS
        WHEN AGE_IN_ITHD>AGE_IN_TGIS 
            THEN AGE_IN_ITHD
        ELSE AGE_IN_TGIS
    END AS MAX_AGE,
    STATUS AS ITHD_STATUS,
    INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN AS TGIS_STATUS,
     (CASE 
        WHEN STATUS IS NULL OR TRIM(STATUS)='' OR INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IS NULL  OR TRIM(INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN)='' THEN ''
        WHEN STATUS='New' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IN('Unassigned(Service Desk)','Unassigned(Company/Genpo IS)') THEN 'Yes'
        WHEN STATUS='In Progress' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IN('Accepted(Service Desk)','Accepted(Company/Genpo IS)','L1 dispatching(Service Desk)','L1 In Progress(Service Desk)','L2 dispatching','L2 In Progress','Problem Escalation','Change Escalation','Service Request Escalation','L1 In Progress(Company/Genpo IS)','L1 dispatching(Company/Genpo IS)','L1 Answered(Service Desk)','L2 Answered','L1 Answered(Company/Genpo IS)','L1 In Progress','L1 Answered','Company/Genpo IS In Progress','L2 In Progress','Company/Genpo IS Answered','L1 dispatching')THEN 'Yes'
        WHEN STATUS='Resolved - Pending Confirmation' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN='Resolved - Pending Confirmation' THEN 'Yes'
        WHEN STATUS='Resolved - Closed' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN='Resolved' THEN 'Yes'
        WHEN STATUS='Canceled' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IN('Resolved - Pending Confirmation','Resolved','Canceled') THEN 'Yes'
        WHEN STATUS='On hold' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN NOT IN('Resolved') THEN 'Yes' 
        ELSE 'NO'
    END) as STATUS_MATCH,
    CASE 
        WHEN STATUS=INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN
            THEN 'MATCH'
        ELSE 'NOT MATCH'
    END AS STATUS_INDICATOR,
    ITHD_ETA AS ITHD_ETA,
    TGIS_ETA AS TGIS_ETA,
    RELATED_CASE AS RELATED_CASE,
    COUNT_OF_RELATED_CASES AS COUNT_OF_RELATED_CASES,
    COUNT_OF_RELATED_ICD_CASES AS COUNT_OF_RELATED_ICD_CASES,
    LAST_REFRESH_DATETIME AS LAST_REFRESH_DATETIME
FROM source_data HELPDESK_TGIS_MASTER
    LEFT JOIN first_comment_data ON first_comment_data.INCIDENT_SUMMARY_INCIDENT_MNG_NM_MIN=HELPDESK_TGIS_MASTER.INCIDENT_SUMMARY_INCIDENT_MNG_NM
),

type_data as (
    SELECT
        CAST(CASE_NUMBER AS VARCHAR(16777216)) AS CASE_NUMBER,
        CAST(TGIS_ID AS VARCHAR(16777216)) AS TGIS_ID,
        CAST(TITLE_EN AS VARCHAR(16777216)) AS TITLE_EN,
        CAST(TITLE_JA AS VARCHAR(16777216)) AS TITLE_JA,
        CAST(TGIS_URGENCY AS VARCHAR(16777216)) AS TGIS_URGENCY,
        CAST(ITHD_URGENCY AS VARCHAR(16777216)) AS ITHD_URGENCY,
        CAST(URGENCY AS VARCHAR(16777216)) AS URGENCY,
        CAST(ISSUER AS VARCHAR(16777216)) AS ISSUER,
        CAST(ITHD_ISSUE_DATE AS TIMESTAMP_NTZ(9)) AS ITHD_ISSUE_DATE,
        CAST(TGIS_ISSUE_DATE AS TIMESTAMP_NTZ(9)) AS TGIS_ISSUE_DATE,
        CAST(ISSUE_DATE AS TIMESTAMP_NTZ(9)) AS ISSUE_DATE,
        CAST(SYSTEM_NAME AS VARCHAR(16777216)) AS SYSTEM_NAME,
        CAST(CASE_TYPE AS VARCHAR(16777216)) AS CASE_TYPE,
        CAST(CASE_SUB_TYPE AS VARCHAR(16777216)) AS CASE_SUB_TYPE,
        CAST(PIC AS VARCHAR(16777216)) AS PIC,
        CAST(STATUS AS VARCHAR(16777216)) AS STATUS,
        CAST(DESCRIPTION_EN AS VARCHAR(16777216)) AS DESCRIPTION_EN,
        CAST(DESCRIPTION_JA AS VARCHAR(16777216)) AS DESCRIPTION_JA,
        CAST(LATEST_TIMELINE_EN AS VARCHAR(16777216)) AS LATEST_TIMELINE_EN,
        CAST(LATEST_TIMELINE_JA AS VARCHAR(16777216)) AS LATEST_TIMELINE_JA,
        CAST(UPDATED_ON AS TIMESTAMP_NTZ(9)) AS UPDATED_ON,
        CAST(UPDATED_BY AS VARCHAR(16777216)) AS UPDATED_BY,
        CAST(AGE_IN_ITHD AS VARCHAR(16777216)) AS AGE_IN_ITHD,
        CAST(AGE_IN_TGIS AS VARCHAR(16777216)) AS AGE_IN_TGIS,
        CAST(MAX_AGE AS NUMERIC(38,0)) AS MAX_AGE,
        CAST(ITHD_STATUS AS VARCHAR(16777216)) AS ITHD_STATUS,
        CAST(TGIS_STATUS AS VARCHAR(16777216)) AS TGIS_STATUS,
        CAST(STATUS_MATCH AS VARCHAR(3)) AS STATUS_MATCH,
        CAST(STATUS_INDICATOR AS VARCHAR(16777216)) AS STATUS_INDICATOR,
        CAST(ITHD_ETA AS VARCHAR(16777216)) AS ITHD_ETA,
        CAST(TGIS_ETA AS VARCHAR(16777216)) AS TGIS_ETA,
        CAST(RELATED_CASE AS VARCHAR(16777216)) AS RELATED_CASE,
        CAST(COUNT_OF_RELATED_CASES AS VARCHAR(16777216)) AS COUNT_OF_RELATED_CASES,
        CAST(COUNT_OF_RELATED_ICD_CASES AS VARCHAR(16777216)) AS COUNT_OF_RELATED_ICD_CASES,
        CAST(LAST_REFRESH_DATETIME AS TIMESTAMP_NTZ) AS LAST_REFRESH_DATETIME
    FROM transform_data
)

SELECT * from type_data
with ref_relationship_info as
(
    SELECT
        RI.MAIN_MNG_NM AS TGIS_ID,
        RI_COUNT.COUNT_OF_RELATED_CASES,
        RI_ICD_COUNT.COUNT_OF_RELATED_ICD_CASES,
        RI.SUB_MNG_NM AS RELATED_CASE
    FROM {{ ref('SILVER__TEH_SUPPORT_SERVICES__RELATIONSHIP_INFO') }}  AS RI
    INNER JOIN
    (
        SELECT
            MAIN_MNG_NM AS TGIS_ID,
            MAX(SUB_FUNCTION_ID) AS MAX_RELATED_CASE_ID
        FROM {{ ref('SILVER__TEH_SUPPORT_SERVICES__RELATIONSHIP_INFO') }}
        GROUP BY MAIN_MNG_NM
    ) AS RI_MAX
    ON RI.MAIN_MNG_NM=RI_MAX.TGIS_ID
        AND RI.SUB_FUNCTION_ID=RI_MAX.MAX_RELATED_CASE_ID
    LEFT JOIN
    (
        SELECT
            MAIN_MNG_NM AS TGIS_ID,
            COUNT(distinct SUB_MNG_NM) AS COUNT_OF_RELATED_CASES
        FROM {{ ref('SILVER__TEH_SUPPORT_SERVICES__RELATIONSHIP_INFO') }}
        WHERE SUB_MNG_NM LIKE ('%PRB%') OR SUB_MNG_NM LIKE ('%SVC%')
        GROUP BY MAIN_MNG_NM
    ) AS RI_COUNT
    ON RI.MAIN_MNG_NM=RI_COUNT.TGIS_ID
    LEFT JOIN
    (
        SELECT
            MAIN_MNG_NM AS TGIS_ID,
            COUNT(distinct SUB_MNG_NM) AS COUNT_OF_RELATED_ICD_CASES
        FROM {{ ref('SILVER__TEH_SUPPORT_SERVICES__RELATIONSHIP_INFO') }}
        WHERE SUB_MNG_NM LIKE ('%ICD%')
        GROUP BY MAIN_MNG_NM
    ) AS RI_ICD_COUNT
    ON RI.MAIN_MNG_NM=RI_ICD_COUNT.TGIS_ID

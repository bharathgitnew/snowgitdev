materialized='tel_incremental',
incremental_strategy='insert_overwrite',
alias='HELPDESK_METRICS_DYN',
transient=false
) }}

with source_data as (
select 
CREATED_ON,
SNAPSHOT_DATE,
CASE_NUMBER,
RESOLVED_ON,
STATUS
from 
{{ ref('GOLD__TEH_SUPPORT_SERVICES__HELPDESK_CASE_DETAILS_HIST') }} H
where SNAPSHOT_DATE >= '2025-04-01'
),
opened_tickets as (
SELECT
EXTRACT(YEAR FROM H.CREATED_ON) TKT_YEAR,
EXTRACT(MONTH FROM H.CREATED_ON) TKT_MONTH,
COUNT(DISTINCT H.CASE_NUMBER) AS TICKETS_OPENED
FROM source_data H 
WHERE 
EXTRACT(YEAR FROM H.CREATED_ON) = EXTRACT(YEAR FROM H.SNAPSHOT_DATE)
AND EXTRACT(MONTH FROM H.CREATED_ON) = EXTRACT(MONTH FROM H.SNAPSHOT_DATE)-1
GROUP BY TKT_YEAR,TKT_MONTH
),
resolved_tickets as (
SELECT
DATE_PART (YEAR, H.SNAPSHOT_DATE) AS TKT_YEAR,
DATE_PART (MONTH, H.SNAPSHOT_DATE)-1 AS TKT_MONTH,
COUNT(DISTINCT H.CASE_NUMBER) AS TICKETS_RESOLVED
FROM
source_data AS H
WHERE
H.STATUS IN ('Resolved - Pending Confirmation','Resolved - Closed')
AND TRY_TO_DATE (H.RESOLVED_ON, 'yyyy-mm-DD"T"hh24:mi:ss"Z"') < H.SNAPSHOT_DATE
AND DATE_TRUNC ('MONTH', H.SNAPSHOT_DATE) = H.SNAPSHOT_DATE
AND DATE_PART ( YEAR,TRY_TO_DATE (H.RESOLVED_ON, 'yyyy-mm-DD"T"hh24:mi:ss"Z"')) = DATE_PART (YEAR, H.SNAPSHOT_DATE)
AND DATE_PART ( MONTH,TRY_TO_DATE (H.RESOLVED_ON, 'yyyy-mm-DD"T"hh24:mi:ss"Z"'))= DATE_PART (MONTH, H.SNAPSHOT_DATE) - 1
GROUP BY TKT_YEAR, TKT_MONTH
),
filtered_cases as (
select *, 
EXTRACT(YEAR FROM SNAPSHOT_DATE) AS SNAP_YEAR,
EXTRACT(MONTH FROM SNAPSHOT_DATE) AS SNAP_MONTH
FROM source_data
WHERE STATUS IN ('New', 'In Progress', 'On Hold')
AND CREATED_ON < SNAPSHOT_DATE
QUALIFY MIN(SNAPSHOT_DATE) OVER (PARTITION BY DATE_TRUNC('month', SNAPSHOT_DATE)) = SNAPSHOT_DATE
),
backlog_tickets as (
SELECT 
EXTRACT(YEAR FROM SNAPSHOT_DATE) AS TKT_YEAR,
EXTRACT(MONTH FROM SNAPSHOT_DATE)-1 AS TKT_MONTH,
COUNT(DISTINCT CASE_NUMBER) AS TICKETS_BACKLOG
FROM filtered_cases
GROUP BY 
EXTRACT(YEAR FROM SNAPSHOT_DATE),
EXTRACT(MONTH FROM SNAPSHOT_DATE)
)
,transform_data as(
select 
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
SHA2('hash_me') as _ROW_HASH ,
CONCAT(OT.TKT_YEAR, '-', LPAD(OT.TKT_MONTH, 2, '0')) as YEAR_MONTH,
OT.TICKETS_OPENED,
RT.TICKETS_RESOLVED,
BT.TICKETS_BACKLOG
from opened_tickets OT
left join 
resolved_tickets RT 
on ot.TKT_YEAR=rt.TKT_YEAR 
and ot.TKT_MONTH=rt.TKT_MONTH
left join backlog_tickets  BT 
on BT.TKT_YEAR=rt.TKT_YEAR 
and BT.TKT_MONTH=rt.TKT_MONTH

),type_data as
(
select
CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
YEAR_MONTH,
TICKETS_OPENED::NUMBER(18,0) as TICKETS_OPENED,
TICKETS_RESOLVED::NUMBER(18,0) as TICKETS_RESOLVED,
TICKETS_BACKLOG::NUMBER(18,0) as TICKETS_BACKLOG
from 
transform_data
)
select distinct * from type_data
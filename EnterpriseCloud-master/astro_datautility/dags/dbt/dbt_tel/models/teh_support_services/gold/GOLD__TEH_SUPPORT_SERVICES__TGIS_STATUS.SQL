source_data as
(
  SELECT
    ID,
    CASE_NUMBER AS IT_HELPDESK_ID,
    CURRENT_STEP,
    COMPLETED_STEP_NUMBER,
    TOTAL_STEPS,
    TITLE,
    COMPLETED_STEP_NAME,
    CURRENT_STEP_NAME,
    NEXT_STEP_NAME,
    STATUS,
    RELATED_CASES,
    LAST_UPDATED_DATETIME,

with relationship_aggregate as
(
  SELECT DISTINCT
      MAIN_MNG_NM,
      LISTAGG(SUB_MNG_NM,',') OVER (PARTITION BY MAIN_MNG_NM) AS RELATED_CASES
  FROM  {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_RELATIONSHIP_INFO') }}
  WHERE TRIM(MAIN_MNG_NM)!=''
),
helpdesk_Cases as
(
  SELECT
    CASE_NUMBER,
    TGISNUMBER
  FROM {{ ref('GOLD__TEH_SUPPORT_SERVICES__ITHD_HELPDESK_CASES') }}
),
change_work_in_charge as
(
    SELECT
        CHG_MNG_NM,
        STEP_NUMBER,
        LISTAGG(WORK_INCHARGE_TELNAME,';') WITHIN GROUP (ORDER BY CHG_MNG_NM,STEP_NUMBER) AS WORKINCHARGE
    FROM {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_WORKINCHARGE') }}
    GROUP BY ALL
),
change_timeline as
(
    SELECT
        CHG_MNG_NM,
        COMMENT_EN,
        STEP_NUMBER,
        WORK_NUMBER,
        WORK_INCHARGE_TELNAME
   FROM {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_DETAILS') }}
   WHERE (CHG_MNG_NM,STEP_NUMBER,WORK_NUMBER) IN (SELECT CHG_MNG_NM,STEP_NUMBER,MAX(TRY_TO_NUMBER(WORK_NUMBER))
                                                          FROM {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_DETAILS') }} GROUP BY CHG_MNG_NM,STEP_NUMBER)
),
change_logs as
(
  SELECT DISTINCT
    CHANGE_SUMMARY.CHG_MNG_NM AS ID,
    CURRENT_STEP.STEP_NUMBER AS CURRENT_STEP,
    COMPLETED_STEP.STEP_NUMBER AS COMPLETED_STEP_NUMBER,
    CHANGE_SUMMARY.LAST_STEP_NUMBER AS TOTAL_STEPS,
    CHANGE_SUMMARY.SUBJECT_EN AS TITLE,
    COMPLETED_STEP.STEP_NAME_EN AS COMPLETED_STEP_NAME,
    CURRENT_STEP.STEP_NAME_EN AS CURRENT_STEP_NAME,
    NEXT_STEP.STEP_NAME_EN AS NEXT_STEP_NAME,
    CHANGE_SUMMARY.COMPLETE_RESULT_CATEGORY_EN AS STATUS,
    CHANGE_SUMMARY.UPDATED_DATE AS LAST_UPDATED_DATETIME,
    RELATED_CASES,
    WORKINCHARGE,
    COALESCE(change_timeline.COMMENT_EN,'N/A') AS LATEST_COMMENT,
    CASE
      WHEN change_timeline.COMMENT_EN IS NOT NULL
      THEN change_timeline.WORK_INCHARGE_TELNAME
      ELSE 'N/A'
    END AS LATEST_COMMENT_UPDATE_BY,
    COMPLETED_STEP.WORK_EXEC_DATE AS LATEST_COMMENT_UPDATE_DATETIME,
    REGISTERED_DATE AS ISSUE_DATE
  FROM
    {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_SUMMARY') }} CHANGE_SUMMARY
    LEFT JOIN {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_DETAILS') }} AS CURRENT_STEP
      ON CHANGE_SUMMARY.PROGRESS_STEP_NUMBER=CURRENT_STEP.STEP_NUMBER
        AND CHANGE_SUMMARY.CHG_MNG_NM=CURRENT_STEP.CHG_MNG_NM
    LEFT JOIN {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_DETAILS') }} AS LAST_STEP
      ON CHANGE_SUMMARY.LAST_STEP_NUMBER=LAST_STEP.STEP_NUMBER
        AND CHANGE_SUMMARY.CHG_MNG_NM=LAST_STEP.CHG_MNG_NM
    LEFT JOIN {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_DETAILS') }} AS COMPLETED_STEP
      ON CHANGE_SUMMARY.PROGRESS_STEP_NUMBER-1=COMPLETED_STEP.STEP_NUMBER
        AND CHANGE_SUMMARY.CHG_MNG_NM=COMPLETED_STEP.CHG_MNG_NM
    LEFT JOIN change_timeline
      ON CHANGE_SUMMARY.PROGRESS_STEP_NUMBER-1=change_timeline.STEP_NUMBER
        AND CHANGE_SUMMARY.CHG_MNG_NM=change_timeline.CHG_MNG_NM
    LEFT JOIN {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_CHANGE_DETAILS') }} NEXT_STEP
      ON CHANGE_SUMMARY.PROGRESS_STEP_NUMBER+1=NEXT_STEP.STEP_NUMBER
        AND CHANGE_SUMMARY.CHG_MNG_NM=NEXT_STEP.CHG_MNG_NM
    LEFT JOIN relationship_aggregate
      ON CHANGE_SUMMARY.CHG_MNG_NM=relationship_aggregate.MAIN_MNG_NM
    LEFT JOIN change_work_in_charge work_in_charge
       ON CHANGE_SUMMARY.CHG_MNG_NM=work_in_charge.CHG_MNG_NM AND CURRENT_STEP.STEP_NUMBER=work_in_charge.STEP_NUMBER
),
problem_work_in_charge as

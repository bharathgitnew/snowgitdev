    LEFT JOIN {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_PROBLEM_DETAILS') }} NEXT_STEP
      ON PROBLEM_SUMMARY.PROGRESS_STEP_NUMBER+1=NEXT_STEP.STEP_NUMBER
        AND PROBLEM_SUMMARY.PRB_MNG_NM=NEXT_STEP.PRB_MNG_NM
    LEFT JOIN relationship_aggregate
      ON PROBLEM_SUMMARY.PRB_MNG_NM=relationship_aggregate.MAIN_MNG_NM
    LEFT JOIN problem_work_in_charge work_in_charge
       ON PROBLEM_SUMMARY.PRB_MNG_NM=work_in_charge.PRB_MNG_NM AND CURRENT_STEP.STEP_NUMBER=work_in_charge.STEP_NUMBER
),

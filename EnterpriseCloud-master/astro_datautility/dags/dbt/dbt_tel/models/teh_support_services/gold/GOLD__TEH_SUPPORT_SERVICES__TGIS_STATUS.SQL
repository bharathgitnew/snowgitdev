    LEFT JOIN {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_PROBLEM_DETAILS') }} AS LAST_STEP
      ON PROBLEM_SUMMARY.LAST_STEP_NUMBER=LAST_STEP.STEP_NUMBER
        AND PROBLEM_SUMMARY.PRB_MNG_NM=LAST_STEP.PRB_MNG_NM
    LEFT JOIN {{ ref('BRONZE__TEH_SUPPORT_SERVICES__TGIS_PROBLEM_DETAILS') }} AS COMPLETED_STEP
      ON PROBLEM_SUMMARY.PROGRESS_STEP_NUMBER-1=COMPLETED_STEP.STEP_NUMBER
        AND PROBLEM_SUMMARY.PRB_MNG_NM=COMPLETED_STEP.PRB_MNG_NM

    LATEST_COMMENT_UPDATE_BY,
    LATEST_COMMENT_UPDATE_DATETIME,
    ISSUE_DATE
  FROM union_data
    LEFT JOIN helpdesk_Cases
      ON helpdesk_Cases.TGISNUMBER=union_data.ID
),
transform_data as
(
    SELECT
    ID,
    IT_HELPDESK_ID,
    CURRENT_STEP,
    COMPLETED_STEP_NUMBER,
    TOTAL_STEPS,
    TITLE,
    COMPLETED_STEP_NAME,
    CURRENT_STEP_NAME,
    NEXT_STEP_NAME,
    STATUS,
    RELATED_CASES,
    LAST_UPDATED_DATETIME,
    CASE
        WHEN STATUS='Completed' THEN CONCAT(TOTAL_STEPS,'/',TOTAL_STEPS)
        WHEN STATUS='Terminated' THEN CONCAT('0/',TOTAL_STEPS)
        WHEN LEFT(ID,3)='ICD' THEN 'N/A'
        WHEN LEFT(ID,3)!='ICD' AND COMPLETED_STEP_NUMBER IS NULL THEN CONCAT('0/',TOTAL_STEPS)
        ELSE CONCAT(COMPLETED_STEP_NUMBER,'/',TOTAL_STEPS)
    END AS PROGRESS,
    WORKINCHARGE,
    LATEST_COMMENT,
    LATEST_COMMENT_UPDATE_BY,
    LATEST_COMMENT_UPDATE_DATETIME,
    ISSUE_DATE,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH
  FROM source_data
  WHERE ID not in ('SVC-0000005616','SVC-0000028770','SVC-0000028618') AND TRIM(ID)!='' --Added on 2/1 to skip these service requests as they have duplicates in source TGIS database. Email sent to source team to fix this, will remove this condition once the source records are fixed.
),

type_data as
(
  SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    ID,
    IT_HELPDESK_ID,
    CURRENT_STEP,
    COMPLETED_STEP_NUMBER,
    TOTAL_STEPS,
    TITLE,
    COMPLETED_STEP_NAME,
    CURRENT_STEP_NAME,
    NEXT_STEP_NAME,
    STATUS,
    RELATED_CASES,
    CAST(LAST_UPDATED_DATETIME AS TIMESTAMP_NTZ(9)) AS LAST_UPDATED_DATETIME,
    PROGRESS,
    WORKINCHARGE,
    LATEST_COMMENT,
    LATEST_COMMENT_UPDATE_BY,
    CAST(LATEST_COMMENT_UPDATE_DATETIME AS TIMESTAMP_NTZ(9)) AS LATEST_COMMENT_UPDATE_DATETIME,
    CAST(ISSUE_DATE AS TIMESTAMP_NTZ(9)) AS ISSUE_DATE
  FROM transform_data
)

select * from type_data order by ISSUE_DATE DESC
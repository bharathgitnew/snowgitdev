with ref_latest_data as
(
SELECT
    CASE_NUMBER as CN,
    MAX(INCIDENT_DETAILS_HISTORY_NM) MAX_HIST_NM 
FROM {{ ref('GOLD__TEH_SUPPORT_SERVICES__HELPDESK_TGIS_MASTER') }}  
    GROUP BY CASE_NUMBER
)
,source_data as 
(
SELECT
    CASE_NUMBER,
    TGISNUMBER,
    CASE_TITLE,
    PRIMARY_CONTACT,
    CREATED_ON,
    URGENCY,
    STATUS,
    SYSTEM,
    DESCRIPTION,
    WORKED_BY,
    IMPACT_ON,
    CASE_TYPE,
    CASE_SUB_TYPE,
    PRIMARY_CONTACT_LOCATION,
    SYSTEM_CATEGORY,
    QUEUE,
    AGE_DAYS,
    INCIDENT_SUMMARY_INCIDENT_MNG_NM AS TGIS_ID,
    CASE_NUMBER AS RELATED_CASE_ID,
    INCIDENT_SUMMARY_MATTER_CATEGORY_EN AS MATTER_CATEGORY_NAME,
    INCIDENT_SUMMARY_SUBJECT_EN AS SUBJECT,
    INCIDENT_SUMMARY_LAST_URGENCY_EN AS URGENCY_TYPE_NAME,
    INCIDENT_SUMMARY_LAST_URGENCY_REASON_EN AS URGENCY_REASON,
    INCIDENT_SUMMARY_SYSTEM_EN AS SYSTEM_NAME,
    INCIDENT_SUMMARY_INCHARGE_GROUP_EN AS L2_GROUP_NAME,
    INCIDENT_SUMMARY_REGISTERED_TELNAME AS REGISTERED_TELNAME,
    PRIMARY_CONTACT AS CASE_PRIMARY_CONTACT,
    INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN AS CONDITION_NAME,
    INCIDENT_SUMMARY_REGISTERED_DATE AS REGISTERED_DATE,
    INCIDENT_SUMMARY_CAUSE_CATEGORY_EN AS CAUSE_CATEGORY_NAME,
    INCIDENT_SUMMARY_LAST_STATUS_EN AS STATUS_NAME,
    INCIDENT_DETAILS_CONTENT_EN,
    DATEDIFF(day,CURRENT_TIMESTAMP(),INCIDENT_SUMMARY_REGISTERED_DATE) AS DAYS,
    INCIDENT_SUMMARY_NOTES_EN,
    INCIDENT_DETAILS_HISTORY_NM,
    INCIDENT_SUMMARY_UPDATED_DATE,
     (CASE 
        WHEN STATUS IS NULL OR TRIM(STATUS)='' OR INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IS NULL  OR TRIM(INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN)='' THEN ''
        WHEN STATUS='In Progress' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IN('Accepted(Service Desk)','Accepted(Company/Genpo IS)','L1 dispatching(Service Desk)','L1 In Progress(Service Desk)','L2 dispatching','L2 In Progress','Problem Escalation','Change Escalation','Service Request Escalation','L1 In Progress(Company/Genpo IS)','L1 dispatching(Company/Genpo IS)','L1 Answered(Service Desk)','L2 Answered','L1 Answered(Company/Genpo IS)','L1 Compatible','L1 Answered','IS Compatible','L2 Compatible')THEN 'Yes'
        WHEN STATUS='Resolved - Pending Confirmation' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN='Resolved – Pending Confirmation' THEN 'Yes'
        WHEN STATUS='Resolved - Closed' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN='Resolved' THEN 'Yes'
        WHEN STATUS='Canceled' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN IN('Resolved – Pending Confirmation','Resolved','Canceled') THEN 'Yes'
        WHEN STATUS='On hold' and INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN NOT IN('Resolved') THEN 'Yes' 
        ELSE 'NO'
    END) as STATUS_MATCH,
    CASE 
        WHEN STATUS=INCIDENT_SUMMARY_LAST_STATUS_CONDITION_EN
            THEN 'MATCH'
        ELSE 'NOT MATCH'
    END AS STATUS_INDICATOR,
    ITHD_ETA AS ITHD_ETA,
    TGIS_ETA AS TGIS_ETA,
    RELATED_CASE AS RELATED_CASE,
    COUNT_OF_RELATED_ICD_CASES AS COUNT_OF_RELATED_ICD_CASES
FROM {{ ref('GOLD__TEH_SUPPORT_SERVICES__HELPDESK_TGIS_MASTER') }} 
        INNER JOIN ref_latest_data
    ON CASE_NUMBER=CN AND (INCIDENT_DETAILS_HISTORY_NM=MAX_HIST_NM OR MAX_HIST_NM IS NULL)
)

,transform_data as 
(
  SELECT 
        CASE_NUMBER,
        TGISNUMBER,
        CASE_TITLE,
        PRIMARY_CONTACT,
        CREATED_ON,
        URGENCY,
        STATUS,
        SYSTEM,
        DESCRIPTION,
        WORKED_BY,
        IMPACT_ON,
        CASE_TYPE,
        CASE_SUB_TYPE,
        PRIMARY_CONTACT_LOCATION,
        SYSTEM_CATEGORY,
        QUEUE,
        AGE_DAYS,
        TGIS_ID,
        RELATED_CASE_ID,
        MATTER_CATEGORY_NAME,
        SUBJECT,
        URGENCY_TYPE_NAME,
        URGENCY_REASON,
        SYSTEM_NAME,
        L2_GROUP_NAME,
        REGISTERED_TELNAME,
        CASE_PRIMARY_CONTACT,
        CONDITION_NAME,
        REGISTERED_DATE,
        CAUSE_CATEGORY_NAME,
        STATUS_NAME,
        INCIDENT_DETAILS_CONTENT_EN,
        DAYS,
        INCIDENT_SUMMARY_NOTES_EN,
        INCIDENT_DETAILS_HISTORY_NM,
        INCIDENT_SUMMARY_UPDATED_DATE,
        STATUS_MATCH,
        ITHD_ETA,
        TGIS_ETA,
        RELATED_CASE,
        COUNT_OF_RELATED_ICD_CASES
  FROM source_data
),


        CAST(DESCRIPTION AS VARCHAR(16777216)) AS DESCRIPTION,
        CAST(WORKED_BY AS VARCHAR(16777216)) AS WORKED_BY,
        CAST(IMPACT_ON AS VARCHAR(16777216)) AS IMPACT_ON,
        CAST(CASE_TYPE AS VARCHAR(16777216)) AS CASE_TYPE,
        CAST(CASE_SUB_TYPE AS VARCHAR(16777216)) AS CASE_SUB_TYPE,
        CAST(PRIMARY_CONTACT_LOCATION AS VARCHAR(16777216)) AS PRIMARY_CONTACT_LOCATION,
        CAST(SYSTEM_CATEGORY AS VARCHAR(16777216)) AS SYSTEM_CATEGORY,
        CAST(QUEUE AS VARCHAR(16777216)) AS QUEUE,
        CAST(AGE_DAYS AS VARCHAR(16777216)) AS AGE_DAYS,
        CAST(TGIS_ID AS VARCHAR(16777216)) AS TGIS_ID,
        CAST(RELATED_CASE_ID AS VARCHAR(16777216)) AS RELATED_CASE_ID,
        CAST(MATTER_CATEGORY_NAME AS VARCHAR(16777216)) AS MATTER_CATEGORY_NAME,
        CAST(SUBJECT AS VARCHAR(16777216)) AS SUBJECT,
        CAST(URGENCY_TYPE_NAME AS VARCHAR(16777216)) AS URGENCY_TYPE_NAME,
        CAST(URGENCY_REASON AS VARCHAR(16777216)) AS URGENCY_REASON,
        CAST(SYSTEM_NAME AS VARCHAR(16777216)) AS SYSTEM_NAME,
        CAST(L2_GROUP_NAME AS VARCHAR(16777216)) AS L2_GROUP_NAME,
        CAST(REGISTERED_TELNAME AS VARCHAR(16777216)) AS REGISTERED_TELNAME,

        CAST(INCIDENT_DETAILS_CONTENT_EN AS VARCHAR(16777216)) AS INCIDENT_DETAILS_CONTENT_EN,
        CAST(DAYS AS VARCHAR(16777216)) AS DAYS,
        CAST(INCIDENT_SUMMARY_NOTES_EN AS VARCHAR(16777216)) AS INCIDENT_SUMMARY_NOTES_EN,
        CAST(INCIDENT_DETAILS_HISTORY_NM AS VARCHAR(16777216)) AS INCIDENT_DETAILS_HISTORY_NM,
        CAST(INCIDENT_SUMMARY_UPDATED_DATE AS DATE) AS INCIDENT_SUMMARY_UPDATED_DATE,
        CAST(STATUS_MATCH AS VARCHAR(16777216)) AS STATUS_MATCH,
        CAST(ITHD_ETA AS VARCHAR(16777216)) AS ITHD_ETA,
        CAST(TGIS_ETA AS VARCHAR(16777216)) AS TGIS_ETA,
        CAST(RELATED_CASE AS VARCHAR(16777216)) AS RELATED_CASE,
        CAST(COUNT_OF_RELATED_ICD_CASES AS VARCHAR(16777216)) AS COUNT_OF_RELATED_ICD_CASES
    FROM transform_data
)


/************
    Combined current model for UPS TEA SEC 232 (daily + latest weekly snapshot)
*************/

{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='UPS_TEA_SEC_232_CURRENT',
    transient=false
) }}


with daily_data as (
    select
        to_date(_FILEDATE) as SNAPSHOT_DATE,
        * exclude REPORT_DATE
    from {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__UPS_TEA_SEC_232') }}
    where _FILENAME ilike 'TEA SEC 232 Daily Report%'
),
latest_weekly_snapshot_date as (
    select
        max(to_date(_FILEDATE)) as MAX_SNAPSHOT_FILEDATE
    from {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__UPS_TEA_SEC_232_SNAPSHOT') }}
    where _FILENAME ilike 'TEA SEC 232 Weekly 2025 Report%'
),
weekly_snapshot_data as (
    select
        *
    from {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__UPS_TEA_SEC_232_SNAPSHOT') }}
    where _FILENAME ilike 'TEA SEC 232 Weekly 2025 Report%'
      and to_date(_FILEDATE) = (select MAX_SNAPSHOT_FILEDATE from latest_weekly_snapshot_date)
),
combined_data as (
    select * from daily_data
    union all
    select * from weekly_snapshot_data
),
transform_data as (
    select
        SNAPSHOT_DATE,
        _FILEDATE,
        _FILENAME,
        _AUDIT_LOG_ID,
        _ROW_HASH,
        _ROW_SURROGATE_KEY,
        ENTRY_NUMBER,
        BROKER_REFERENCE_NUMBER,
        BROKER_OFFICE_NUMBER,
        LATEST_COMMENT,
        MASTER_BILLS,
        HOUSE_BILL_NUMBERS_CONCATENATED,
        ENTRY_PORT,
        POE_ACTUAL_ARRIVAL_DATE,
        CUSTOMS_RELEASED_DATE,
        ENTRY_LINE_NUMBER,
        HARMONIZED_NUMBER,
        COMMERCIAL_INVOICE_NUMBER,
        COMMERCIAL_INVOICE_DETAIL_LINE_NUMBER,
        ITEM_NUMBER,
        INVOICE_LINE_QUANTITY,
        INVOICE_LINE_QUANTITY_UOM,
        ENTERED_VALUE,
        AD_VALOREM_DUTY_RATE,
        DUTY_AMOUNT,
        COMMERCIAL_INVOICE_SEQUENCE_NUMBER,
        IOR_TAX_ID,
        GOODS_ORIGIN_COUNTRY_OR_TERRITORY_ISO_CODE,
        SUMMARY_DATE,
        MERCHANDISE_PROCESSING_FEE,
        ENTRY_DATE,
        HARMONIZED_ITEM_DESCRIPTION,
        SHIPPER_NAME,
        LATEST_STATUS,
        LATEST_STATUS_DATE,
        ESTIMATED_LIQUIDATION_DATE,
        LIQUIDATED_DATE
    from combined_data
),
type_data as (
    select
        cast(SNAPSHOT_DATE AS DATE) AS SNAPSHOT_DATE,
        cast(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
        cast(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
        cast(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        cast(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        cast(_ROW_SURROGATE_KEY AS VARCHAR(128)) AS _ROW_SURROGATE_KEY,
        cast(ENTRY_NUMBER AS VARCHAR(16777216)) AS ENTRY_NUMBER,
        cast(BROKER_REFERENCE_NUMBER AS VARCHAR(16777216)) AS BROKER_REFERENCE_NUMBER,
        cast(BROKER_OFFICE_NUMBER AS VARCHAR(16777216)) AS BROKER_OFFICE_NUMBER,
        cast(LATEST_COMMENT AS VARCHAR(16777216)) AS LATEST_COMMENT,
        cast(MASTER_BILLS AS VARCHAR(16777216)) AS MASTER_BILLS,
        cast(HOUSE_BILL_NUMBERS_CONCATENATED AS VARCHAR(16777216)) AS HOUSE_BILL_NUMBERS_CONCATENATED,
        cast(ENTRY_PORT AS VARCHAR(16777216)) AS ENTRY_PORT,
        cast(POE_ACTUAL_ARRIVAL_DATE AS TIMESTAMP_NTZ(9)) AS POE_ACTUAL_ARRIVAL_DATE,
        cast(CUSTOMS_RELEASED_DATE AS TIMESTAMP_NTZ(9)) AS CUSTOMS_RELEASED_DATE,
        cast(ENTRY_LINE_NUMBER AS VARCHAR(16777216)) AS ENTRY_LINE_NUMBER,
        cast(HARMONIZED_NUMBER AS VARCHAR(16777216)) AS HARMONIZED_NUMBER,
        cast(COMMERCIAL_INVOICE_NUMBER AS VARCHAR(16777216)) AS COMMERCIAL_INVOICE_NUMBER,
        cast(COMMERCIAL_INVOICE_DETAIL_LINE_NUMBER AS VARCHAR(16777216)) AS COMMERCIAL_INVOICE_DETAIL_LINE_NUMBER,
        cast(ITEM_NUMBER AS VARCHAR(16777216)) AS ITEM_NUMBER,
        cast(INVOICE_LINE_QUANTITY AS NUMBER(38,2)) AS INVOICE_LINE_QUANTITY,
        cast(INVOICE_LINE_QUANTITY_UOM AS VARCHAR(16777216)) AS INVOICE_LINE_QUANTITY_UOM,
        cast(ENTERED_VALUE AS NUMBER(38,2)) AS ENTERED_VALUE,
        cast(AD_VALOREM_DUTY_RATE AS NUMBER(38,2)) AS AD_VALOREM_DUTY_RATE,
        cast(DUTY_AMOUNT AS NUMBER(38,2)) AS DUTY_AMOUNT,
        cast(COMMERCIAL_INVOICE_SEQUENCE_NUMBER AS VARCHAR(16777216)) AS COMMERCIAL_INVOICE_SEQUENCE_NUMBER,
        cast(IOR_TAX_ID AS VARCHAR(16777216)) AS IOR_TAX_ID,
        cast(GOODS_ORIGIN_COUNTRY_OR_TERRITORY_ISO_CODE AS VARCHAR(16777216)) AS GOODS_ORIGIN_COUNTRY_OR_TERRITORY_ISO_CODE,
        cast(SUMMARY_DATE AS TIMESTAMP_NTZ(9)) AS SUMMARY_DATE,
        cast(MERCHANDISE_PROCESSING_FEE AS NUMBER(38,2)) AS MERCHANDISE_PROCESSING_FEE,
        cast(ENTRY_DATE AS TIMESTAMP_NTZ(9)) AS ENTRY_DATE,
        cast(HARMONIZED_ITEM_DESCRIPTION AS VARCHAR(16777216)) AS HARMONIZED_ITEM_DESCRIPTION,
        cast(SHIPPER_NAME AS VARCHAR(16777216)) AS SHIPPER_NAME,
        cast(LATEST_STATUS AS VARCHAR(16777216)) AS LATEST_STATUS,
        cast(LATEST_STATUS_DATE AS TIMESTAMP_NTZ(9)) AS LATEST_STATUS_DATE,
        cast(ESTIMATED_LIQUIDATION_DATE AS TIMESTAMP_NTZ(9)) AS ESTIMATED_LIQUIDATION_DATE,
        cast(LIQUIDATED_DATE AS TIMESTAMP_NTZ(9)) AS LIQUIDATED_DATE
    from transform_data
)

select * from type_data

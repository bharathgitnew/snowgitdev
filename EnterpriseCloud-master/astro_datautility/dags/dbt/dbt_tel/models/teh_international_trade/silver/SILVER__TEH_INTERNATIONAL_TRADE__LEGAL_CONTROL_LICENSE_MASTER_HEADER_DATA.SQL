WITH T606X as (
    select 
        GENNR as INTERNAL_LICENSE_NUMBER,
        listagg(distinct GENLA, ', ') within group (order by GENLA) as COUNTRIES_OF_DESTINATION
    from {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__SAPO_LEGAL_CONTROL_DESTINATION_COUNTRIES_FOR_LICENSE') }} T606X 
    group by INTERNAL_LICENSE_NUMBER
),

T606Y as (
    select
        GENNR as INTERNAL_LICENSE_NUMBER,
        listagg(distinct ALNUM, ', ') within group (order by ALNUM) as ECCNS,
    from {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__SAPO_LEGAL_CONTROL_EXPORT_CONTROL_CLASSES_FOR_LICENSE') }}
    group by INTERNAL_LICENSE_NUMBER
),

T606Z as (
    select
        GENNR as INTERNAL_LICENSE_NUMBER,
        listagg(distinct KUNNR, ', ') within group (order by KUNNR) as CUSTOMER_NUMBERS,
    from {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__SAPO_LEGAL_CONTROL_PARTNERS_CUSTOMERS_FOR_LICENSE') }}
    group by INTERNAL_LICENSE_NUMBER
),

SOURCE_DATA AS(
    SELECT 
        EMBK._CAPTUREDATETIME,
        EMBK.MANDT AS CLIENT,
        EMBK.GENNR AS INTERNAL_LICENSE_NUMBER,
        EMBK.INDEI AS INDICATOR_LEGAL_CONTROL_IMPORT_EXPORT,
        EMBK.GEGRU AS LEGAL_REGULATION_FOR_LEGAL_CONTROL,
        EMBK.GEART AS LICENSE_TYPE,
        EMBK.EXGEN AS EXTERNAL_LICENSE_NUMBER,
        EMBK.GENST AS STATUS_FOR_LEGAL_CONTROL,
        TRY_TO_DATE(EMBK.ANFDA,'YYYYMMDD') AS APPLICATION_DATE,
        EMBK.ANFUZ AS APPLICATION_TIME,
        TRY_TO_DATE(EMBK.ABGDA,'YYYYMMDD') AS REJECTION_DATE,
        EMBK.ABGUZ AS TIME_OF_REJECTION,
        TRY_TO_DATE(EMBK.EIGDA,'YYYYMMDD') AS DATE_OF_RECEIPT,
        EMBK.EIGUZ AS TIME_RECEIVED,
        TRY_TO_DATE(EMBK.VELDA,'YYYYMMDD') AS RENEWAL_DATE,
        EMBK.VELUZ AS RENEWAL_TIME,
        TRY_TO_DATE(EMBK.REODA,'YYYYMMDD') AS REORGANIZATION_DATE,
        EMBK.REOUZ AS REORGANIZATION_TIME,
        EMBK.GST_0 AS COMMENT_FOR_STATUS,
        EMBK.GST_A AS COMMENT_FOR_STATUS_A,
        EMBK.GST_B AS COMMENT_FOR_STATUS_B,
        EMBK.GST_C AS COMMENT_FOR_STATUS_C,
        EMBK.GST_D AS COMMENT_FOR_STATUS_D,
        EMBK.GST_Z AS COMMENT_FOR_STATUS_Z,
        TRY_TO_DATE(EMBK.GANDA,'YYYYMMDD') AS VALIDITY_START_DATE,
        TRY_TO_DATE(EMBK.GENDA,'YYYYMMDD') AS VALIDITY_END_DATE,
        EMBK.GMAXW AS MAXIMUM_LICENSE_VALUE,
        EMBK.WAERS AS CURRENCY_KEY,
        EMBK.GMAXQ AS MAXIMUM_LICENSE_QUANTITY,
        EMBK.MEINS AS BASE_UNIT_OF_MEASURE,
        EMBK.ERNAM AS NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
        TRY_TO_DATE(EMBK.ERDAT,'YYYYMMDD') AS DATE_ON_WHICH_RECORD_WAS_CREATED,
        EMBK.ERZET AS ENTRY_TIME,
        EMBK.GENLA AS COUNTRY_OF_DESTINATION,
        EMBK.EXART AS BUSINESS_TRANSACTION_TYPE_FOR_FOREIGN_TRADE,
        EMBK.GAUFW AS VALUE_CONSUMED_BY_ORDERS,
        EMBK.GLIEW AS VALUE_CONSUMED_BY_DELIVERIES,
        EMBK.BUKRS AS COMPANY_CODE,
        EMBK.ZTERM AS TERMS_OF_PAYMENT_KEY,
        EMBK.GMAXA AS MAXIMUM_NUMBER_OF_ORDERS,
        EMBK.GAUFA AS CURRENT_NUMBER_OF_ORDERS,
        EMBK.GPRZW AS MAX_VALUE_EXCESS_IN_PERCENT,
        EMBK.GAUFQ AS UPDATED_ORDER_QUANTITY,
        EMBK.GLIEQ AS UPDATED_DELIVERY_QUANTITY,
        EMBK.VBELN AS NUMBER_OF_SD_DOCUMENT_ASSIGNED_TO_LICENSE,
        EMBK.VBDFG AS VALIDITY_OF_EXPORT_LICENSE_FOR_AFFILIATED_COMPANIES,
        EMBK.VBDNR AS AFFILIATED_COMPANY_NUMBER,
        EMBK.BEHO2 AS AUTHORITY_OF_EXPORTING_COUNTRY,
        EMBK.BEHOE1 AS ISSUING_AUTHORITY_FROM_IMPORTING_COUNTRY,
        EMBK.BEHOE2 AS ISSUING_AUTHORITY_FROM_COUNTRY_OF_DISPATCH,
        T606X.COUNTRIES_OF_DESTINATION,
        T606Y.ECCNS,
        T606Z.CUSTOMER_NUMBERS,
    FROM {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__SAPO_LEGAL_CONTROL_LICENSE_MASTER_HEADER_DATA') }} as EMBK
    left join T606X on EMBK.GENNR = T606X.INTERNAL_LICENSE_NUMBER
    left join T606Y on EMBK.GENNR = T606Y.INTERNAL_LICENSE_NUMBER
    left join T606Z on EMBK.GENNR = T606Z.INTERNAL_LICENSE_NUMBER
),


    SELECT
        GMX.SEQ_NUM AS SEQUENCE_NUMBER,
        GMX.INVOICE_NUMBER AS INVOICE_NUMBER,
        GMX.LINE_ITEM_PER_SHIPMENT AS UPS_ENTRY_LINE_NUMBER,
        NULL AS UPS_ENTRY_NUMBER,

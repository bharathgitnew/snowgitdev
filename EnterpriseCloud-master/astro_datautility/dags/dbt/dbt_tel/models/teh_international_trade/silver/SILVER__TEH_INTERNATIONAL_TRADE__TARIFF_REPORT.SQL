        WHERE HARMONIZED_NUMBER NOT LIKE '99%'
),
TAGGED_GMX_DATA AS (
    SELECT
        *,
        CONCAT(LPAD(GROUP_ID, 5, '0') , '-', IDX0_IN_GROUP) AS LINE_ITEM_PER_SHIPMENT,
        CASE
            WHEN MAX(IDX0_IN_GROUP) OVER (PARTITION BY INVOICE_NUMBER) = 0
            THEN INVOICE_ITEM_NUMBER::VARCHAR
            ELSE (
            CASE
                WHEN INVOICE_ROW_COUNT = 1 THEN 1
                WHEN IDX0_IN_GROUP = 0 THEN 999999999
                ELSE
                SUM(CASE WHEN IDX0_IN_GROUP > 0 THEN 1 ELSE 0 END) OVER (
                    PARTITION BY INVOICE_NUMBER
                    ORDER BY SEQ_NUM
                    ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
                )
            END
            )::VARCHAR
        END AS UPS_ITEM_JOIN
    FROM UPS_ITEM_JOIN_SEQUENCE
), 

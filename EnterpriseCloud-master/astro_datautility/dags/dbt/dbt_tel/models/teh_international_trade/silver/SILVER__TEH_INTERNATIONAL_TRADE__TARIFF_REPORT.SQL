        NO_CHARGE_FLAG,
        ORDER_REASON
    FROM {{ ref('BRONZE__TEH_INTERNATIONAL_TRADE__GMX_INVOICE_EXPORT_HISTORY') }} 
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY INVOICE_NUMBER, SEQ_ITEM_ID
            ORDER BY PSL_UPDDATE DESC
        ) = 1
),
INVOICE_NUMBER_CHANGE_FLAG AS (
    SELECT
        B.*,
        CASE
        WHEN LAG(INVOICE_ITEM_NUMBER) OVER (PARTITION BY INVOICE_NUMBER ORDER BY SEQ_NUM) IS NULL
            OR LAG(INVOICE_ITEM_NUMBER) OVER (PARTITION BY INVOICE_NUMBER ORDER BY SEQ_NUM) <> INVOICE_ITEM_NUMBER
        THEN 1 ELSE 0
        END AS NEW_GROUP_FLAG
    FROM GMX_INVOICE_HISTORY B
),
GROUP_DIVISION_INVOICE AS (
    SELECT
        F.*,
        SUM(NEW_GROUP_FLAG) OVER (
        PARTITION BY INVOICE_NUMBER
        ORDER BY SEQ_NUM
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) AS GROUP_ID
    FROM INVOICE_NUMBER_CHANGE_FLAG F
),
UPS_ITEM_JOIN_SEQUENCE AS (
    SELECT
        G.*,
        ROW_NUMBER() OVER (PARTITION BY INVOICE_NUMBER, GROUP_ID ORDER BY SEQ_NUM) - 1 AS IDX0_IN_GROUP,
        COUNT(*) OVER (PARTITION BY INVOICE_NUMBER) AS INVOICE_ROW_COUNT
    FROM GROUP_DIVISION_INVOICE G
),
UPS AS (
    SELECT 
        LTRIM(COMMERCIAL_INVOICE_NUMBER, '''*') AS COMMERCIAL_INVOICE_NUMBER,
        COMMERCIAL_INVOICE_DETAIL_LINE_NUMBER,

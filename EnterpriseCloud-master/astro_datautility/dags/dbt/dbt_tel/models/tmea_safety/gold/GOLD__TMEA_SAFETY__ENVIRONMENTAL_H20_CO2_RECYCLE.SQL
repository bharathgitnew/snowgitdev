{{ config(
      materialized='tel_incremental',
      incremental_strategy='insert_overwrite',
      alias='ENVIRONMENTAL_H20_CO2_RECYCLE',
      transient=false
) }}

WITH CTE_RECYCLING AS(
select 
FISCALYEAR,
KPI,
MONTH,
VALUE,
GOALS.TARGET,
TO_NUMBER(((DIV0(VALUE,GOALS.TARGET))-1),10,2)*100 AS RATIO,
'Recycle Rate' AS INDICATOR
FROM {{ ref('SILVER__TMEA_SAFETY__ENVIRONMENTAL_KPI') }} 
LEFT JOIN {{ ref('SILVER__TMEA_SAFETY__MANAGEMENT_KPI_GOALS') }} GOALS
ON INDICATOR = GOALS.INDICATORS_KPIS
WHERE TITLE = 'Recycling'
),

CTE_H2O AS(
SELECT 
FISCALYEAR,
KPI,
MONTH,
VALUE,
GOALS.TARGET,
TO_NUMBER((1-(DIV0(VALUE,GOALS.TARGET)))*100,10,2) AS RATIO,
'Water Usage' AS INDICATOR
FROM {{ ref('SILVER__TMEA_SAFETY__ENVIRONMENTAL_KPI') }} 
LEFT JOIN {{ ref('SILVER__TMEA_SAFETY__MANAGEMENT_KPI_GOALS') }}  GOALS
ON INDICATOR = GOALS.INDICATORS_KPIS
WHERE TITLE = 'H2O'
),

CTE_CO2 AS(
SELECT 
FISCALYEAR,
KPI,
MONTH,
VALUE,
GOALS.TARGET,
TO_NUMBER((1-(DIV0(VALUE,GOALS.TARGET)))*100,10,2) AS RATIO,
'CO2 Generation' AS INDICATOR
FROM {{ ref('SILVER__TMEA_SAFETY__ENVIRONMENTAL_KPI') }} 
LEFT JOIN {{ ref('SILVER__TMEA_SAFETY__MANAGEMENT_KPI_GOALS') }}   GOALS
ON INDICATOR = GOALS.INDICATORS_KPIS
WHERE TITLE = 'CO2'
),

CTE_UNION AS (
SELECT * FROM CTE_RECYCLING
UNION ALL 
SELECT * FROM CTE_H2O
UNION ALL
SELECT * FROM CTE_CO2
),

MAIN AS(
SELECT DISTINCT
INDICATOR,
FISCALYEAR,
MONTH, 
MONTH_OF_FISCAL_YEAR_NUMBER,
VALUE,
TARGET,
RATIO
FROM CTE_UNION
LEFT JOIN {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
    ON FISCALYEAR = FISCAL_YEAR_SHORT_TEXT
    AND MONTH = MONTH_TEXT
),

source_data AS(    
    SELECT 
        INDICATOR,
	    FISCALYEAR,
	    MONTH,
	    MONTH_OF_FISCAL_YEAR_NUMBER,
	    VALUE,
	    TARGET,
	    RATIO
    FROM MAIN
ORDER BY INDICATOR,FISCALYEAR,MONTH_OF_FISCAL_YEAR_NUMBER
),

transform_data as(
SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH, 
    INDICATOR,
	FISCALYEAR,
	MONTH,
	MONTH_OF_FISCAL_YEAR_NUMBER,
	VALUE,
	TARGET,
	RATIO
 FROM source_data
),
type_data as(
SELECT 
    _AUDIT_LOG_ID,
    _ROW_HASH,
    INDICATOR,
    FISCALYEAR,
    MONTH,
    MONTH_OF_FISCAL_YEAR_NUMBER,
    CAST(VALUE AS NUMBER(38,2)) AS VALUE,
    CAST(TARGET AS NUMBER(38,2)) AS TARGET,
    RATIO
 FROM transform_data
)

select * from type_data
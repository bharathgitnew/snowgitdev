WITH CTE_TIRS AS (
select 
TIRS_NO,
COMPANY,
INCIDENT_STATUS,
INI_REPORTER_WORKFLOW,
INI_REPORTER_BU,
INI_REPORTER_REPORT_DATE AS REPORT_DATE,
DET_INJURY_ILLNESS_INCIDENT_CLASSIFICATION
from {{ ref('SILVER__TMEA_SAFETY__TIRSACCIDENT') }} 
WHERE COMPANY = 'TMEA'
AND DET_INJURY_ILLNESS_INCIDENT_CLASSIFICATION = 'TCIR (Recordable)'
),
CTE_CALENDARDATE AS(
select 
calendar_date,
-- YEAR_NUMBER,
-- FISCAL_YEAR_NUMBER,
FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
-- QUARTER_TEXT,
-- QUARTER_SHORT_TEXT,
-- MONTH_TEXT,
MONTH_ABBREVIATION_TEXT AS MONTH,
MONTH_OF_FISCAL_YEAR_NUMBER
MONTH_OF_YEAR_NUMBER
-- FISCAL_QUARTER_TEXT,
-- FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
-- FISCAL_YEAR_QUARTER_SHORT_TEXT,
-- FISCAL_YEAR_MONTH_SHORT_TEXT
from  {{ source('STATIC_OBJECTS', 'CALENDAR_DATE') }}
),

MAIN AS (
SELECT 
TIRS_NO,
COMPANY,
INCIDENT_STATUS,
INI_REPORTER_WORKFLOW,
INI_REPORTER_BU,
DET_INJURY_ILLNESS_INCIDENT_CLASSIFICATION,
FISCAL_YEAR,
MONTH,
MONTH_OF_YEAR_NUMBER
FROM CTE_TIRS
LEFT JOIN CTE_CALENDARDATE
    ON CALENDAR_DATE = REPORT_DATE
),

source_data as(
	SELECT 
	FISCAL_YEAR,
	MONTH,
	MONTH_OF_YEAR_NUMBER,
	INI_REPORTER_BU,
	DET_INJURY_ILLNESS_INCIDENT_CLASSIFICATION,
	COUNT(TIRS_NO) AS TIRS_NO
	FROM MAIN
	GROUP BY FISCAL_YEAR,MONTH,INI_REPORTER_BU,MONTH_OF_YEAR_NUMBER,DET_INJURY_ILLNESS_INCIDENT_CLASSIFICATION
),
transform_data as(
	SELECT 
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') AS _ROW_HASH,
	FISCAL_YEAR,
	MONTH,
	MONTH_OF_YEAR_NUMBER,
	INI_REPORTER_BU,
	DET_INJURY_ILLNESS_INCIDENT_CLASSIFICATION,
	TIRS_NO
FROM source_data
),
type_data as(
	SELECT 
	CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
	,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
	,FISCAL_YEAR
	,MONTH
	,MONTH_OF_YEAR_NUMBER
	,INI_REPORTER_BU
	,DET_INJURY_ILLNESS_INCIDENT_CLASSIFICATION
	,TIRS_NO
FROM transform_data
)
select * from type_data
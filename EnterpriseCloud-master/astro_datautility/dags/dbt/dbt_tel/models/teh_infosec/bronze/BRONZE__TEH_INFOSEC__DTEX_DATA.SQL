{{ config(
    materialized='tel_incremental',
    incremental_strategy='insert_overwrite',
    alias='DTEX_DATA'
) }}

with source_data as
(
    SELECT
        jsonfield:event:ReportingProduct::string as Reporting_Product,
        jsonfield:event:ReportingVendor::string as ReportingVendor,
        jsonfield:event:ReportingVersion::string as ReportingVersion,
        jsonfield:event:activities_count::string as activities_count,
        jsonfield:event:activities_url::string as activities_url,
        jsonfield:event:agent_timezone::string as agent_timezone,
        jsonfield:event:alert_type::string as alert_type,
        jsonfield:event:assignee::string as assignee,
        jsonfield:event:category::string as category,
        jsonfield:event:category_id::string as category_id,
        jsonfield:event:category_weight::string as category_weight,
        jsonfield:event:created_at::string as created_at,
        device_details.value:device_name::string as device_name,
        device_details.value:operating_system::string as operating_system,
        device_details.value:os_type::string as os_type,
        jsonfield:event:iden_hash::string as iden_hash,
        jsonfield:event:last_changed_by::string as last_changed_by,
        anomalyd.value:activities_count::string as anomalyd_activities_count,
        anomalyd.value:rule::string as anomalyd_rule,
        jsonfield:event:max_activity_day_of_week::string as max_activity_day_of_week,
        jsonfield:event:max_activity_hour::string as max_activity_hour,
        jsonfield:event:max_activity_occurred::string as max_activity_occurred,
        jsonfield:event:max_activity_recv::string as max_activity_recv,
        jsonfield:event:min_activity_day_of_week::string as min_activity_day_of_week,
        jsonfield:event:min_activity_hour::string as min_activity_hour,
        jsonfield:event:min_activity_occurred::string as min_activity_occurred,
        jsonfield:event:min_activity_recv::string as min_activity_recv,
        jsonfield:event:occurred_at::string as occurred_at,
        jsonfield:event:occurred_at::date as occurred_at_date,
        jsonfield:event:occurred_at::TIMESTAMP_NTZ as occurred_at_datetime,
        jsonfield:event:risk_area::string as risk_area,
        jsonfield:event:risk_score::string as risk_score,
        jsonfield:event:rules::string as rules,
        jsonfield:event:severity::string as severity,
        jsonfield:event:state::string as state,
        jsonfield:event:updated_at::string as updated_at,
        jsonfield:event:user_name::string as user_name,
        SUBSTRING(jsonfield:event:user_name::string,POSITION ( '\\' IN jsonfield:event:user_name::string)+1,length(jsonfield:event:user_name::string)) as user_name_eid,
        jsonfield:event:user_peer_info::string as user_peer_info,
        jsonfield:event:user_risk_score::string as user_risk_score,
        jsonfield:sourcetype::string as sourcetype,
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE
    from {{ source("DTEX", "DTEX_DAILY_DATA") }}
        ,LATERAL FLATTEN (input => parse_json(JSonField:event:device_details)) device_details
        ,LATERAL FLATTEN (input => parse_json(JSonField:event:matched_rules:anomalyd)) anomalyd
    where _UPLOADDATE >  (select COALESCE(max(_UPLOADDATE),'1900-01-01') from {{ this }})

)

,transform_data as
(
    SELECT
        _FILENAME,
        _FILEDATE,
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        _UPLOADDATE,
        Reporting_Product,
        ReportingVendor,
        ReportingVersion,
        activities_count,
        activities_url,
        agent_timezone,
        alert_type,
        assignee,
        category,
        category_id,
        category_weight,
        created_at,
        device_name,
        operating_system,
        os_type,
        iden_hash,
        last_changed_by,
        anomalyd_activities_count,
        anomalyd_rule,
        max_activity_day_of_week,
        max_activity_hour,
        max_activity_occurred,
        max_activity_recv,
        min_activity_day_of_week,
        min_activity_hour,
        min_activity_occurred,
        min_activity_recv,
        occurred_at,
        occurred_at_date,
        occurred_at_datetime,
        risk_area,
        risk_score,
        rules,
        severity,
        state,
        updated_at,
        user_name,
        user_name_eid,
        user_peer_info,
        user_risk_score
    FROM source_data
)

 ,type_data as
 (
     select
        _FILENAME,
        _FILEDATE,
        _AUDIT_LOG_ID,
        _ROW_HASH,
        _UPLOADDATE,
        Reporting_Product,
        ReportingVendor,
        ReportingVersion,
        activities_count,
        activities_url,
        agent_timezone,
        alert_type,
        assignee,
        category,
        category_id,
        category_weight,
        created_at,
        device_name,
        operating_system,
        os_type,
        iden_hash,
        last_changed_by,
        anomalyd_activities_count,
        anomalyd_rule,
        max_activity_day_of_week,
        max_activity_hour,
        max_activity_occurred,
        max_activity_recv,
        min_activity_day_of_week,
        min_activity_hour,
        min_activity_occurred,
        min_activity_recv,
        occurred_at,
        occurred_at_date,
        occurred_at_datetime,
        risk_area,
        risk_score,
        rules,
        severity,
        state,
        updated_at,
        user_name,
        user_name_eid,
        user_peer_info,
        user_risk_score
     from transform_data
)
select * from type_data
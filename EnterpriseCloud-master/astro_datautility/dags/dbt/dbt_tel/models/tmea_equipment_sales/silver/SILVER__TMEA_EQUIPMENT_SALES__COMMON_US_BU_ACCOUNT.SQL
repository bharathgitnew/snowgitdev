with Account as
(
select distinct
    _SALES_ACCOUNT          as SALES_ACCOUNT,
    _SALES_ACCOUNT_REGION   as SALES_ACCOUNT_REGION
from {{ ref('BRONZE__TMEA_EQUIPMENT_SALES__SHAREPOINT_COMMON_SALES_ACCOUNT') }}
-- from COPPER.TEH_EQUIPMENT_SALES.COMMON_SALES_ACCOUNT_TEMP --replace with BRONZE.TEH_EQUIPMENT_SALES.COMMON_SALES_ACCOUNT
where COUNTRY ilike any ('USA', 'Canada', 'Mexico')
),
BU as
(
select
    BU,
    BU_TYPE,
    case when SUB_BU ilike any ('%Other', 'FS_3DI', 'FS_TS', '%GCIB', '%CCS', '%NEXX', 'FPD%', 'TEL%') then 'Others' 
        else BU_TYPE 
        end             as BU_TYPE_Others,
    BU_GROUP,
    case when SUB_BU ilike any ('%Other', 'FS_3DI', 'FS_TS', '%GCIB', '%CCS', '%NEXX', 'FPD%', 'TEL%') then 'Others' 
        else BU_GROUP 
        end             as BU_GROUP_Others,
    SUB_BU,
    _BU,
    _BU_TYPE,
    case when _SUB_BU ilike any ('%Other', 'FS_3DI', 'FS_TS', '%GCIB', '%CCS', '%NEXX', 'FPD%', 'TEL%') then 'Others' 
        else BU_TYPE 
        end             as _BU_TYPE_Others,
    _BU_GROUP,
    case when _SUB_BU ilike any ('%Other', 'FS_3DI', 'FS_TS', '%GCIB', '%CCS', '%NEXX', 'FPD%', 'TEL%') then 'Others' 
        else _BU_GROUP 
        end             as _BU_GROUP_Others,
    _SUB_BU
from {{ ref('BRONZE__TMEA_EQUIPMENT_SALES__SHAREPOINT_COMMON_BUSINESS_UNIT') }}
)
,source_data as 

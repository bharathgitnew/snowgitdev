    concat(acc.SALES_ACCOUNT, ' ', bu._BU_TYPE_OTHERS)   as _SALES_ACCOUNT_BU_TYPE_OTHERS_SALES_ACCOUNT,
    concat(acc.SALES_ACCOUNT, ' ', bu._BU_GROUP)         as _SALES_ACCOUNT_BU_GROUP_SALES_ACCOUNT,
    concat(acc.SALES_ACCOUNT, ' ', bu._BU_GROUP_OTHERS)  as _SALES_ACCOUNT_BU_GROUP_OTHERS_SALES_ACCOUNT,
    concat(acc.SALES_ACCOUNT, ' ', bu._SUB_BU)           as _SALES_ACCOUNT_SUB_BU_SALES_ACCOUNT,
    concat(acc.SALES_ACCOUNT_REGION, ' ', bu._BU)               as _SALES_ACCOUNT_REGION_BU,
    concat(acc.SALES_ACCOUNT_REGION, ' ', bu._BU_TYPE)          as _SALES_ACCOUNT_REGION_BU_TYPE,
    concat(acc.SALES_ACCOUNT_REGION, ' ', bu._BU_TYPE_OTHERS)   as _SALES_ACCOUNT_REGION_BU_TYPE_OTHERS,
    concat(acc.SALES_ACCOUNT_REGION, ' ', bu._BU_GROUP)         as _SALES_ACCOUNT_REGION_BU_GROUP,
    concat(acc.SALES_ACCOUNT_REGION, ' ', bu._BU_GROUP_OTHERS)  as _SALES_ACCOUNT_REGION_BU_GROUP_OTHERS,
    concat(acc.SALES_ACCOUNT_REGION, ' ', bu._SUB_BU)           as _SALES_ACCOUNT_REGION_SUB_BU,
    concat(bu._BU, ' ', acc.SALES_ACCOUNT)               as _BU_SALES_ACCOUNT,
    concat(bu._BU_TYPE, ' ', acc.SALES_ACCOUNT)          as _BU_TYPE_SALES_ACCOUNT,
    concat(bu._BU_TYPE_OTHERS, ' ', acc.SALES_ACCOUNT)   as _BU_TYPE_OTHERS_SALES_ACCOUNT,
    concat(bu._BU_GROUP, ' ', acc.SALES_ACCOUNT)         as _BU_GROUP_SALES_ACCOUNT,
    concat(bu._BU_GROUP_OTHERS, ' ', acc.SALES_ACCOUNT)  as _BU_GROUP_OTHERS_SALES_ACCOUNT,
    concat(bu._SUB_BU, ' ', acc.SALES_ACCOUNT)           as _SUB_BU_SALES_ACCOUNT,
    concat(bu._BU, ' ', acc.SALES_ACCOUNT_REGION)               as _BU_SALES_ACCOUNT_REGION,
    concat(bu._BU_TYPE, ' ', acc.SALES_ACCOUNT_REGION)          as _BU_TYPE_SALES_ACCOUNT_REGION,
    concat(bu._BU_TYPE_OTHERS, ' ', acc.SALES_ACCOUNT_REGION)   as _BU_TYPE_OTHERS_SALES_ACCOUNT_REGION,
    concat(bu._BU_GROUP, ' ', acc.SALES_ACCOUNT_REGION)         as _BU_GROUP_SALES_ACCOUNT_REGION,
    concat(bu._BU_GROUP_OTHERS, ' ', acc.SALES_ACCOUNT_REGION)  as _BU_GROUP_OTHERS_SALES_ACCOUNT_REGION,
    concat(bu._SUB_BU, ' ', acc.SALES_ACCOUNT_REGION)           as _SUB_BU_SALES_ACCOUNT_REGION,
    bu._BU,
    bu._BU_TYPE,
    bu._BU_TYPE_OTHERS,
    _BU_GROUP,
    _BU_GROUP_OTHERS,
    _SUB_BU,
    acc.SALES_ACCOUNT,
    acc.SALES_ACCOUNT_REGION
from ACCOUNT acc
cross join BU bu
order by bu.SUB_BU asc, acc.SALES_ACCOUNT_REGION asc

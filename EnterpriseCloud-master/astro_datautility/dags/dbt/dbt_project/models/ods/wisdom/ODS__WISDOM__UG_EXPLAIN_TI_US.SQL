{{ config(
        alias = 'UG_EXPLAIN_TI_US',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with source_data as (
    select
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE,
        JSONFIELD:BU_NAME::STRING as BU_NAME,
        JSONFIELD:CUSTOMER_CODE::STRING as CUSTOMER_CODE,
        JSONFIELD:CUSTOMER_NAME::STRING as CUSTOMER_NAME,
        JSONFIELD:CUSTOMER_LOCATION::STRING as CUSTOMER_LOCATION,
        JSONFIELD:FCN_NO::STRING as FCN_NO,
        JSONFIELD:FCN_NAME::STRING as FCN_NAME,
        JSONFIELD:CATEGORY::STRING as CATEGORY,
        JSONFIELD:EXPLANATION_CUSTOMER_NAME::STRING as EXPLANATION_CUSTOMER_NAME,
        JSONFIELD:EXPLANATION_CUSTOMER_DEPT::STRING as EXPLANATION_CUSTOMER_DEPT,
        JSONFIELD:EXPLANATION_DATE::STRING as EXPLANATION_DATE,
        JSONFIELD:EXPLANATION_FILE::STRING as EXPLANATION_FILE,
        JSONFIELD:SIGNATURE_CUSTOMER_NAME::STRING as SIGNATURE_CUSTOMER_NAME,
        JSONFIELD:SIGNATURE_CUSTOMER_DEPT::STRING as SIGNATURE_CUSTOMER_DEPT,
        JSONFIELD:SIGNATURE_DATE::STRING as SIGNATURE_DATE,
        JSONFIELD:SIGNATURE_FILE::STRING as SIGNATURE_FILE,
        JSONFIELD:EXPLANATION_SIGNATURE_COMMENT::STRING as EXPLANATION_SIGNATURE_COMMENT,
    from {{ source('WISDOM', 'UG_EXPLAIN_TI_US') }} 
    WHERE _FILEDATE = (
    SELECT MAX(RUN_TIME)
    FROM {{ source('WISDOM', 'CONTROLTABLE') }}
    WHERE TABLE_NAME = 'V_UG_EXPLAIN_TI_US'
)
),

transform_data as (
    select 
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE,
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        BU_NAME,
        CUSTOMER_CODE,
        CUSTOMER_NAME,
        CUSTOMER_LOCATION,
        FCN_NO,
        FCN_NAME,
        CATEGORY,
        EXPLANATION_CUSTOMER_NAME,
        EXPLANATION_CUSTOMER_DEPT,
        EXPLANATION_DATE,
        EXPLANATION_FILE,
        SIGNATURE_CUSTOMER_NAME,
        SIGNATURE_CUSTOMER_DEPT,
        SIGNATURE_DATE,
        SIGNATURE_FILE,
        EXPLANATION_SIGNATURE_COMMENT,
    from source_data
),

type_data as (
    select 
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE,
        _AUDIT_LOG_ID,
        _ROW_HASH,
        BU_NAME,
        CUSTOMER_CODE,
        CUSTOMER_NAME,
        CUSTOMER_LOCATION,
        FCN_NO,
        FCN_NAME,
        CATEGORY,
        EXPLANATION_CUSTOMER_NAME,
        EXPLANATION_CUSTOMER_DEPT,
        EXPLANATION_DATE,
        EXPLANATION_FILE,
        SIGNATURE_CUSTOMER_NAME,
        SIGNATURE_CUSTOMER_DEPT,
        SIGNATURE_DATE,
        SIGNATURE_FILE,
        EXPLANATION_SIGNATURE_COMMENT,
    from transform_data
)

select * from type_data
{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='WISDOM_ES_MAC_US'
) }}

with source_data as
(
    SELECT 
    JSONFIELD:LOCAL_FE_STATION::VARCHAR as LOCAL_FE_STATION,
    JSONFIELD:CUSTOMER_CODE::VARCHAR as CUSTOMER_CODE,
    JSONFIELD:COMPANY_NAME::VARCHAR as COMPANY_NAME,
    JSONFIELD:LOCATION_NAME::VARCHAR as LOCATION_NAME,
    JSONFIELD:CUSTOMER_CODE_9::VARCHAR as CUSTOMER_CODE_9,
    JSONFIELD:SALES_STATION::VARCHAR as SALES_STATION,
    JSONFIELD:BU_NAME::VARCHAR as BU_NAME,
    JSONFIELD:MACHINE_ID::VARCHAR as MACHINE_ID,
    JSONFIELD:MACHINE_SN::VARCHAR as MACHINE_SN,
    JSONFIELD:PARENT_SN::VARCHAR as PARENT_SN,
    JSONFIELD:CUSTOMER_TOOL_ID::VARCHAR as CUSTOMER_TOOL_ID,
    JSONFIELD:MODEL_NAME::VARCHAR as MODEL_NAME,
    JSONFIELD:MACHINE_WARRANTY_STATUS::VARCHAR as MACHINE_WARRANTY_STATUS,
    JSONFIELD:SYSTEM_NAME::VARCHAR as SYSTEM_NAME,
    JSONFIELD:PROCESS_NAME::VARCHAR as PROCESS_NAME,
    JSONFIELD:WAFER_SIZE::VARCHAR as WAFER_SIZE,
    JSONFIELD:SWLH_MODEL::VARCHAR as SWLH_MODEL,
    JSONFIELD:POSITION::VARCHAR as POSITION,
    JSONFIELD:REGION_NAME::VARCHAR as REGION_NAME,
    JSONFIELD:SUBSIDIARY_NAME::VARCHAR as SUBSIDIARY_NAME,
    _FILEDATE
    FROM {{ source('WISDOM','WISDOM_ES_MAC_US') }}
    WHERE _FILEDATE = (
    SELECT MAX(RUN_TIME)
    FROM {{ source('WISDOM', 'CONTROLTABLE') }}
    WHERE TABLE_NAME = 'V_ES_MAC_US'
)
    
    ),

transform_data as 
(
    SELECT
        _FILEDATE as _FILEDATE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
            LOCAL_FE_STATION as LOCAL_FE_STATION,
        CUSTOMER_CODE as CUSTOMER_CODE,
        COMPANY_NAME as COMPANY_NAME,
        LOCATION_NAME as LOCATION_NAME,
        CUSTOMER_CODE_9 as CUSTOMER_CODE_9,
        SALES_STATION as SALES_STATION,
        BU_NAME as BU_NAME,
        MACHINE_ID as MACHINE_ID,
        MACHINE_SN as MACHINE_SN,
        PARENT_SN as PARENT_SN,
        CUSTOMER_TOOL_ID as CUSTOMER_TOOL_ID,
        MODEL_NAME as MODEL_NAME,
        MACHINE_WARRANTY_STATUS as MACHINE_WARRANTY_STATUS,
        SYSTEM_NAME as SYSTEM_NAME,
        PROCESS_NAME as PROCESS_NAME,
        WAFER_SIZE as WAFER_SIZE,
        SWLH_MODEL as SWLH_MODEL,
        POSITION as POSITION,
        REGION_NAME as REGION_NAME,
        SUBSIDIARY_NAME as SUBSIDIARY_NAME
    FROM source_data 
),
type_data as 
(
    SELECT
        _FILEDATE,
        AUDIT_LOG_ID,
        _ROW_HASH,
        LOCAL_FE_STATION,
        CUSTOMER_CODE,
        COMPANY_NAME,
        LOCATION_NAME,
        CUSTOMER_CODE_9,
        SALES_STATION,
        BU_NAME,
        CAST(MACHINE_ID AS NUMBER(38,0)) AS MACHINE_ID,
        MACHINE_SN,
        PARENT_SN,
        CUSTOMER_TOOL_ID,
        MODEL_NAME,
        MACHINE_WARRANTY_STATUS,
        SYSTEM_NAME,
        PROCESS_NAME,
        WAFER_SIZE,
        SWLH_MODEL,
        POSITION,
        REGION_NAME,
        SUBSIDIARY_NAME
    FROM transform_data 
)
select * from type_data
{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='SAP_USER_LIST',
    unique_key= ['EMAIL',
    'COST_CENTER_CODE']
) }}

with source_data as 
(
    SELECT 
    NAME,
    EMP_NUMBER,
    FIRST_NAME,
    LAST_NAME,
    EMAIL,
    SUPERVISOR,
    COMPANY,
    DEPARTMENT AS BAAN_DEPARTMENT_CODE,
    COMPANY_CODE as BAAN_COMPANY_CODE,
    SEGMENT AS BAAN_SEGMENT_CODE,
    OFFICE AS BAAN_OFFICE_CODE,
    COST_CENTER_CODE,
    COST_CENTER_OWNER,
    _FILEDATE
    FROM {{ source("FILE", "SAP_USER_LIST") }}
        {% if is_incremental() %}WHERE  _FileDate > IFNULL((SELECT MAX(_FileDate) FROM {{ this }}),'1970-01-01'){% endif %}
		QUALIFY (ROW_NUMBER() OVER (PARTITION BY EMAIL,COST_CENTER_CODE ORDER BY _Filedate DESC )) = 1
)


,transform_data as 
(
    SELECT 
        NAME,
        EMP_NUMBER,
        FIRST_NAME,
        LAST_NAME,
        EMAIL,
        SUPERVISOR,
        COMPANY,
        BAAN_DEPARTMENT_CODE,
        BAAN_COMPANY_CODE,
        BAAN_SEGMENT_CODE,
        BAAN_OFFICE_CODE,
        COST_CENTER_CODE,
        COST_CENTER_OWNER,
        _FILEDATE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM source_data 
)
,type_data as (
    SELECT
        CAST(NAME AS VARCHAR(16777216)) AS NAME,
        CAST(EMP_NUMBER AS VARCHAR(16777216)) AS EMP_NUMBER,
        CAST(FIRST_NAME AS VARCHAR(16777216)) AS FIRST_NAME,
        CAST(LAST_NAME AS VARCHAR(16777216)) AS LAST_NAME,
        CAST(EMAIL AS VARCHAR(16777216)) AS EMAIL,
        CAST(SUPERVISOR AS VARCHAR(16777216)) AS SUPERVISOR,
        CAST(COMPANY AS VARCHAR(16777216)) AS COMPANY,
        CAST(BAAN_DEPARTMENT_CODE AS VARCHAR(16777216)) AS BAAN_DEPARTMENT_CODE,
        CAST(BAAN_COMPANY_CODE AS VARCHAR(16777216)) AS BAAN_COMPANY_CODE,
        CAST(BAAN_SEGMENT_CODE AS VARCHAR(16777216)) AS BAAN_SEGMENT_CODE,
        CAST(BAAN_OFFICE_CODE AS VARCHAR(16777216)) AS BAAN_OFFICE_CODE,
        CAST(COST_CENTER_CODE AS VARCHAR(16777216)) AS COST_CENTER_CODE,
        CAST(COST_CENTER_OWNER AS VARCHAR(16777216)) AS COST_CENTER_OWNER,
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)

SELECT * from type_data
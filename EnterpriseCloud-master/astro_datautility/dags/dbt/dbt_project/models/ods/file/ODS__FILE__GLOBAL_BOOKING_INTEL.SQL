{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='GLOBAL_BOOKING_INTEL',
    unique_key=[]
) }}

with incremental_FileIngestionLogId as
(
    SELECT
        COALESCE(MAX(FileIngestionLogId),0)+1 AS NEXT_FILE_INGESTION_LOG_ID
    FROM {{ this }}
    WHERE _FILEDATE NOT IN (SELECT _FILEDATE FROM {{this}})
),
source_data as
(
    SELECT
        FiscalYear AS FiscalYear,
        Quarter AS Quarter,
        BookingMonth AS BookingMonth,
        BusinessUnitCode AS BusinessUnitCode,
        KA AS KA,
        BusinessUnitName AS BusinessUnitName,
        SubBusinessUnitName AS SubBusinessUnitName,
        SalesOrderNumber AS SalesOrderNumber,
        AccountCode AS AccountCode,
        AccountName AS AccountName,
        CustomerCode AS CustomerCode,
        CustomerName AS CustomerName,
        EndUserCode AS EndUserCode,
        EndUserName AS EndUserName,
        Opportunity AS Opportunity,
        ProductName AS ProductName,
        Level AS Level,
        Level2 AS Level2,
        BookingAmount AS BookingAmount,
        BookingAmount100M AS BookingAmount100M,
        Quantity AS Quantity,
        EuropeRequestDate AS EuropeRequestDate,
        DeliveryDate AS DeliveryDate,
        CustomClearenceDate AS CustomClearenceDate,
        OnDockDate AS OnDockDate,
        SalesDate AS SalesDate,
        MachineSerialNumber AS MachineSerialNumber,
        SalesCategoryCode AS SalesCategoryCode,
        SalesCategoryName AS SalesCategoryName,
        Area AS Area,
        AreaName AS AreaName,
        DistributionFlag AS DistributionFlag,
        LoanFlag AS LoanFlag,
        CSTFlag AS CSTFlag,
        InvestmentCode AS InvestmentCode,
        ProcessOfRecord AS ProcessOfRecord,
        BackUp AS BackUp,
        DegreeOfSalesUncertainty AS DegreeOfSalesUncertainty,
        InvestmentSubCode AS InvestmentSubCode,
        Device1Code AS Device1Code,
        Device1Name AS Device1Name,
        Device2Code AS Device2Code,
        Device2Name AS Device2Name,
        NULL AS SourceType,
        (SELECT NEXT_FILE_INGESTION_LOG_ID FROM incremental_FileIngestionLogId) AS FileIngestionLogId,
        NULL AS FileDate,
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE
    FROM {{ source("FILE", "GLOBAL_BOOKING_INTEL") }}
    where _UPLOADDATE > (select COALESCE(max(_UPLOADDATE),'1900-01-01') from {{ this }})
)

,transform_data as
(
    SELECT
        _FILENAME,
        _FILEDATE,
        _UPLOADDATE,
        FiscalYear,
        Quarter,
        BookingMonth,
        BusinessUnitCode,
        KA,
        BusinessUnitName,
        SubBusinessUnitName,
        SalesOrderNumber,
        AccountCode,
        AccountName,
        CustomerCode,
        CustomerName,
        EndUserCode,
        EndUserName,
        Opportunity,
        ProductName,
        Level,
        Level2,
        BookingAmount,
        BookingAmount100M,
        Quantity,
        EuropeRequestDate,
        DeliveryDate,
        CustomClearenceDate,
        OnDockDate,
        SalesDate,
        MachineSerialNumber,
        SalesCategoryCode,
        SalesCategoryName,
        Area,
        AreaName,
        DistributionFlag,
        LoanFlag,
        CSTFlag,
        InvestmentCode,
        ProcessOfRecord,
        BackUp,
        DegreeOfSalesUncertainty,
        InvestmentSubCode,
        Device1Code,
        Device1Name,
        Device2Code,
        Device2Name,
        SourceType,
        COALESCE(FileIngestionLogId,(SELECT NEXT_FILE_INGESTION_LOG_ID FROM incremental_FileIngestionLogId)) AS FileIngestionLogId,
        FileDate,
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
        FROM source_data
)

 ,type_data as
 (
     select
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
        CAST(_UPLOADDATE AS TIMESTAMP_NTZ(9)) AS _UPLOADDATE,
        FiscalYear,
        Quarter,
        BookingMonth,
        BusinessUnitCode,
        KA,
        BusinessUnitName,
        SubBusinessUnitName,
        SalesOrderNumber,
        AccountCode,
        AccountName,
        CustomerCode,
        CustomerName,
        EndUserCode,
        EndUserName,
        Opportunity,
        ProductName,
        Level,
        Level2,
        BookingAmount,
        BookingAmount100M,
        Quantity,
        EuropeRequestDate,
        DeliveryDate,
        CustomClearenceDate,
        OnDockDate,
        SalesDate,
        MachineSerialNumber,
        SalesCategoryCode,
        SalesCategoryName,
        Area,
        AreaName,
        DistributionFlag,
        LoanFlag,
        CSTFlag,
        InvestmentCode,
        ProcessOfRecord,
        BackUp,
        DegreeOfSalesUncertainty,
        InvestmentSubCode,
        Device1Code,
        Device1Name,
        Device2Code,
        Device2Name,
        SourceType,
        CAST(FileIngestionLogId AS NUMBER(38,0)) AS FileIngestionLogId,
        FileDate
     from transform_data
     )
select * from type_data
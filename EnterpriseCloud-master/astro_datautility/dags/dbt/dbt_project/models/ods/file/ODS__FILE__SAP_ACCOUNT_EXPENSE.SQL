{{ config(
        materialized='incremental'    ,
    incremental_strategy='insert_overwrite'    ,
    alias='SAP_ACCOUNT_EXPENSE'    ,
    unique_key= ['SAP_GL',
     'ORACLE_GL',
     'BAAN_GL']    
) }}

with source_data as
(
    SELECT
		_FILENAME,
		_FILEDATE,
		_UPLOADDATE,
        BASE_GL_TYPE,
        FINANCIAL_ACCOUNT_TYPE,
        SENSITIVE_INDICATOR,
        FINANCIAL_STATUTORY_CATEGORY,
        SAP_GL,
        SAP_ACCT_DESCRIPTION,
        ORACLE_GL,
        ORACLE_GL_ALIAS,
        ORACLE_GL_PARENT,
        BAAN_GL,
        BAAN_ACCT_DESCRIPTION
    FROM {{ source("FILE", "SAP_ACCOUNT_EXPENSE") }}

    where _UPLOADDATE = (select max(_UPLOADDATE) from {{ source("FILE", "SAP_ACCOUNT_EXPENSE") }})

)

,transform_data as
(
    SELECT
		_FILENAME,
		_FILEDATE,
		_UPLOADDATE,
        BASE_GL_TYPE,
        FINANCIAL_ACCOUNT_TYPE,
        SENSITIVE_INDICATOR,
        FINANCIAL_STATUTORY_CATEGORY,
        SAP_GL,
        SAP_ACCT_DESCRIPTION,
        ORACLE_GL,
        ORACLE_GL_ALIAS,
        ORACLE_GL_PARENT,
        BAAN_GL,
        BAAN_ACCT_DESCRIPTION,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
        FROM source_data
)

,type_data as
(
    select
        CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
        CAST(_UPLOADDATE AS TIMESTAMP_NTZ(9)) AS _UPLOADDATE,
        CAST(BASE_GL_TYPE AS VARCHAR(16777216) ) AS BASE_GL_TYPE,
        CAST(FINANCIAL_ACCOUNT_TYPE AS VARCHAR(16777216) ) AS FINANCIAL_ACCOUNT_TYPE,
        CAST(SENSITIVE_INDICATOR AS VARCHAR(16777216) ) AS SENSITIVE_INDICATOR,
        CAST(FINANCIAL_STATUTORY_CATEGORY AS VARCHAR(16777216) ) AS FINANCIAL_STATUTORY_CATEGORY,
        CAST(SAP_GL AS VARCHAR(16777216) ) AS SAP_GL,
        CAST(SAP_ACCT_DESCRIPTION AS VARCHAR(16777216) ) AS SAP_ACCT_DESCRIPTION,
        CAST(ORACLE_GL AS VARCHAR(16777216) ) AS ORACLE_GL,
        CAST(ORACLE_GL_ALIAS AS VARCHAR(16777216) ) AS ORACLE_GL_ALIAS,
        CAST(ORACLE_GL_PARENT AS VARCHAR(16777216) ) AS ORACLE_GL_PARENT,
        CAST(BAAN_GL AS VARCHAR(16777216) ) AS BAAN_GL,
        CAST(BAAN_ACCT_DESCRIPTION AS VARCHAR(16777216) ) AS BAAN_ACCT_DESCRIPTION,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    from transform_data
    )
select * from type_data
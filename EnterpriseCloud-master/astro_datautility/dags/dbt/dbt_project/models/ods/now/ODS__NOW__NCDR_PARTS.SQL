    materialized='incremental',
    incremental_strategy='merge',
    alias='NCDR_PARTS',
    unique_key = ['NCDR_PART_ID']
) }}


with source_data as 
(
    SELECT
        JSONFIELD:NCDR_PART_ID::STRING AS NCDR_PART_ID,
        JSONFIELD:NCDR_NUMBER::STRING AS NCDR_NUMBER,
        JSONFIELD:PART_NUMBER::STRING AS PART_NUMBER,
        JSONFIELD:DESCRIPTION::STRING AS DESCRIPTION,
        JSONFIELD:CONSUME_FLAG::STRING AS CONSUME_FLAG,
        JSONFIELD:INTEL_FLAG::STRING AS INTEL_FLAG,
        JSONFIELD:SIGNAL_CODE::STRING AS SIGNAL_CODE,
        JSONFIELD:PRICE_CURRENCY::STRING AS PRICE_CURRENCY,
        JSONFIELD:SALE_PRICE::STRING AS SALE_PRICE,
        JSONFIELD:STANDARD_COST::STRING AS STANDARD_COST,
        JSONFIELD:TRANSFER_PRICE::STRING AS TRANSFER_PRICE,
        JSONFIELD:UNIT_OF_MEASURE::STRING AS UNIT_OF_MEASURE,
        JSONFIELD:REMARKS::STRING AS REMARKS,
        JSONFIELD:QUANTITY::STRING AS QUANTITY,
        JSONFIELD:DOCUMENT::STRING AS DOCUMENT,
        JSONFIELD:SHIP_FROM::STRING AS SHIP_FROM,
        JSONFIELD:RETURNED_DATE::STRING AS RETURNED_DATE,
        JSONFIELD:DELIVERY_DATE::STRING AS DELIVERY_DATE,
        JSONFIELD:UPDATED_DELIVERY_DATE::STRING AS UPDATED_DELIVERY_DATE,
        JSONFIELD:DELIVERY_REMARKS::STRING AS DELIVERY_REMARKS,
        JSONFIELD:APPROVED::STRING AS APPROVED,
        JSONFIELD:AICS_WARNING::STRING AS AICS_WARNING,
        JSONFIELD:RETURN_TO_STOCK::STRING AS RETURN_TO_STOCK,
        JSONFIELD:RETURN_REASON::STRING AS RETURN_REASON,
        JSONFIELD:LINE_NUMBER::STRING AS LINE_NUMBER,
        JSONFIELD:LAST_UPDATED_DATE::STRING AS LAST_UPDATED_DATE,
        JSONFIELD:READY_BY_FACTORY::STRING AS READY_BY_FACTORY,
        JSONFIELD:EOL_FLG::STRING AS EOL_FLG,
        JSONFIELD:LEAD_TIME::STRING AS LEAD_TIME,
        JSONFIELD:NCDR_LINE_ID::STRING AS NCDR_LINE_ID,
        JSONFIELD:URL_REFERENCE::STRING AS URL_REFERENCE,
        JSONFIELD:SHIP_COMPLETE::STRING AS SHIP_COMPLETE,
        JSONFIELD:SO_NUMBER::STRING AS SO_NUMBER,
        JSONFIELD:SO_LINE_ITEM::STRING AS SO_LINE_ITEM,
        _FILEDATE,
        _FILENAME
    FROM {{ source("NOW", "NCDR_PARTS") }} 
    {% if is_incremental() %}WHERE  _FILEDATE > IFNULL((SELECT MAX(_FILEDATE) FROM {{ this }}),'1970-01-01'){% endif %}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY JSONFIELD:NCDR_PART_ID::STRING  ORDER BY _FILENAME DESC,_FILEDATE DESC )) = 1
)

,transform_data as (
    SELECT
        NCDR_PART_ID,
        NCDR_NUMBER,
        PART_NUMBER,
        DESCRIPTION,
        CONSUME_FLAG,
        INTEL_FLAG,
        SIGNAL_CODE,
        PRICE_CURRENCY,
        SALE_PRICE,
        STANDARD_COST,
        TRANSFER_PRICE,
        UNIT_OF_MEASURE,
        REMARKS,
        QUANTITY,
        DOCUMENT,
        SHIP_FROM,
        RETURNED_DATE,
        DELIVERY_DATE,
        UPDATED_DELIVERY_DATE,
        DELIVERY_REMARKS,
        APPROVED,
        AICS_WARNING,
        RETURN_TO_STOCK,
        RETURN_REASON,
        LINE_NUMBER,
        LAST_UPDATED_DATE,
        READY_BY_FACTORY,
        EOL_FLG,
        LEAD_TIME,
        NCDR_LINE_ID,
        URL_REFERENCE,
        SHIP_COMPLETE,
        SO_NUMBER,
        SO_LINE_ITEM,
        _FILEDATE,
        _FILENAME,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    from source_data
)

,type_data as (
    SELECT 
        CAST (NCDR_PART_ID AS VARCHAR(16777216)) AS NCDR_PART_ID,
        CAST (NCDR_NUMBER AS VARCHAR(16777216)) AS NCDR_NUMBER,
        CAST (PART_NUMBER AS VARCHAR(16777216)) AS PART_NUMBER,
        CAST (DESCRIPTION AS VARCHAR(16777216)) AS DESCRIPTION,
        CAST (CONSUME_FLAG AS VARCHAR(16777216)) AS CONSUME_FLAG,
        CAST (INTEL_FLAG AS VARCHAR(16777216)) AS INTEL_FLAG,
        CAST (SIGNAL_CODE AS VARCHAR(16777216)) AS SIGNAL_CODE,
        CAST (PRICE_CURRENCY AS VARCHAR(16777216)) AS PRICE_CURRENCY,
        CAST (SALE_PRICE AS VARCHAR(16777216)) AS SALE_PRICE,
        CAST (STANDARD_COST AS VARCHAR(16777216)) AS STANDARD_COST,
        CAST (TRANSFER_PRICE AS VARCHAR(16777216)) AS TRANSFER_PRICE,
        CAST (UNIT_OF_MEASURE AS VARCHAR(16777216)) AS UNIT_OF_MEASURE,
        CAST (REMARKS AS VARCHAR(16777216)) AS REMARKS,
        CAST (QUANTITY AS VARCHAR(16777216)) AS QUANTITY,
        CAST (DOCUMENT AS VARCHAR(16777216)) AS DOCUMENT,
        CAST (SHIP_FROM AS VARCHAR(16777216)) AS SHIP_FROM,
        CAST (RETURNED_DATE AS VARCHAR(16777216)) AS RETURNED_DATE,
        CAST (DELIVERY_DATE AS VARCHAR(16777216)) AS DELIVERY_DATE,
        CAST (UPDATED_DELIVERY_DATE AS VARCHAR(16777216)) AS UPDATED_DELIVERY_DATE,
        CAST (DELIVERY_REMARKS AS VARCHAR(16777216)) AS DELIVERY_REMARKS,
        CAST (APPROVED AS VARCHAR(16777216)) AS APPROVED,
        CAST (AICS_WARNING AS VARCHAR(16777216)) AS AICS_WARNING,
        CAST (RETURN_TO_STOCK AS VARCHAR(16777216)) AS RETURN_TO_STOCK,
        CAST (RETURN_REASON AS VARCHAR(16777216)) AS RETURN_REASON,
        CAST (LINE_NUMBER AS VARCHAR(16777216)) AS LINE_NUMBER,
        CAST (LAST_UPDATED_DATE AS VARCHAR(16777216)) AS LAST_UPDATED_DATE,
        CAST (READY_BY_FACTORY AS VARCHAR(16777216)) AS READY_BY_FACTORY,
        CAST (EOL_FLG AS VARCHAR(16777216)) AS EOL_FLG,
        CAST (LEAD_TIME AS VARCHAR(16777216)) AS LEAD_TIME,
        CAST (NCDR_LINE_ID AS VARCHAR(16777216)) AS NCDR_LINE_ID,
        CAST (URL_REFERENCE AS VARCHAR(16777216)) AS URL_REFERENCE,
        CAST (SHIP_COMPLETE AS VARCHAR(16777216)) AS SHIP_COMPLETE,
        CAST (SO_NUMBER AS VARCHAR(16777216)) AS SO_NUMBER,
        CAST (SO_LINE_ITEM AS VARCHAR(16777216)) AS SO_LINE_ITEM,
        CAST(_FILEDATE as TIMESTAMP_NTZ(9)) as _FILEDATE,
		CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
		CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
	FROM transform_data
)

SELECT * FROM type_data
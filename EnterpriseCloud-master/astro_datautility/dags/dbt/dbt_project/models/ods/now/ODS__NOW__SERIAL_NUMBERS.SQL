{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='SERIAL_NUMBERS',
    unique_key = ['SERIAL_NUMBER_ID']
) }}


with source_data as
(
    SELECT 
        JSONFIELD:SERIAL_NUMBER_ID::STRING AS SERIAL_NUMBER_ID,
        JSONFIELD:NCDR_NUMBER::STRING AS NCDR_NUMBER,
        JSONFIELD:MACHINE_SERIAL_NUMBER::STRING AS MACHINE_SERIAL_NUMBER,
        JSONFIELD:MACHINE_STATUS::STRING AS MACHINE_STATUS,
        JSONFIELD:MACHINE_SYSTEM_TYPE::STRING AS MACHINE_SYSTEM_TYPE,
        JSONFIELD:MACHINE_EXIT_FACTORY_DATE::STRING AS MACHINE_EXIT_FACTORY_DATE,
        JSONFIELD:MACHINE_SYSTEM_ACCEPTANCE_DATE::STRING AS MACHINE_SYSTEM_ACCEPTANCE_DATE,
        JSONFIELD:MACHINE_STARTUP_START_DATE::STRING AS MACHINE_STARTUP_START_DATE,
        JSONFIELD:MACHINE_WARRANTY_START_DATE::STRING AS MACHINE_WARRANTY_START_DATE,
        JSONFIELD:MACHINE_WARRANTY_EXPIRE_DATE::STRING AS MACHINE_WARRANTY_EXPIRE_DATE,
        JSONFIELD:WARRANTY_STATUS_ID::STRING AS WARRANTY_STATUS_ID,
        JSONFIELD:OBJECT_NUMBER::STRING AS OBJECT_NUMBER,
        JSONFIELD:SUPPLIER_CD::STRING AS SUPPLIER_CD,
        JSONFIELD:DEFECTIVE_PORTION_ID::STRING AS DEFECTIVE_PORTION_ID,
        JSONFIELD:FRF_FLAG::STRING AS FRF_FLAG,
        JSONFIELD:MAC_HIST_REASON_ID::STRING AS MAC_HIST_REASON_ID,
        JSONFIELD:MAC_HIST_REASON_NAME_J::STRING AS MAC_HIST_REASON_NAME_J,
        JSONFIELD:MAC_HIST_REASON_NAME::STRING AS MAC_HIST_REASON_NAME,
        JSONFIELD:PROJECT_NO::STRING AS PROJECT_NO,
        _FILEDATE,
        _FILENAME
    FROM {{ source("NOW", "SERIAL_NUMBERS") }} 
    {% if is_incremental() %}WHERE  _FILEDATE > IFNULL((SELECT MAX(_FILEDATE) FROM {{ this }}),'1970-01-01'){% endif %}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY JSONFIELD:SERIAL_NUMBER_ID::STRING  ORDER BY _FILENAME DESC,_FILEDATE DESC )) = 1
)

,transform_data as (
    SELECT 
        SERIAL_NUMBER_ID,
        NCDR_NUMBER,
        MACHINE_SERIAL_NUMBER,
        MACHINE_STATUS,
        MACHINE_SYSTEM_TYPE,
        MACHINE_EXIT_FACTORY_DATE,
        MACHINE_SYSTEM_ACCEPTANCE_DATE,
        MACHINE_STARTUP_START_DATE,
        MACHINE_WARRANTY_START_DATE,
        MACHINE_WARRANTY_EXPIRE_DATE,
        WARRANTY_STATUS_ID,
        OBJECT_NUMBER,
        SUPPLIER_CD,
        DEFECTIVE_PORTION_ID,
        FRF_FLAG,
        MAC_HIST_REASON_ID,
        MAC_HIST_REASON_NAME_J,
        MAC_HIST_REASON_NAME,
        PROJECT_NO,
        _FILEDATE,
        _FILENAME,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    from source_data
)

,type_data as (
    SELECT 
        CAST (SERIAL_NUMBER_ID AS VARCHAR(16777216)) AS SERIAL_NUMBER_ID,
        CAST (NCDR_NUMBER AS VARCHAR(16777216)) AS NCDR_NUMBER,
        CAST (MACHINE_SERIAL_NUMBER AS VARCHAR(16777216)) AS MACHINE_SERIAL_NUMBER,
        CAST (MACHINE_STATUS AS VARCHAR(16777216)) AS MACHINE_STATUS,
        CAST (MACHINE_SYSTEM_TYPE AS VARCHAR(16777216)) AS MACHINE_SYSTEM_TYPE,
        CAST (MACHINE_EXIT_FACTORY_DATE AS VARCHAR(16777216)) AS MACHINE_EXIT_FACTORY_DATE,
        CAST (MACHINE_SYSTEM_ACCEPTANCE_DATE AS VARCHAR(16777216)) AS MACHINE_SYSTEM_ACCEPTANCE_DATE,
        CAST (MACHINE_STARTUP_START_DATE AS VARCHAR(16777216)) AS MACHINE_STARTUP_START_DATE,
        CAST (MACHINE_WARRANTY_START_DATE AS VARCHAR(16777216)) AS MACHINE_WARRANTY_START_DATE,
        CAST (MACHINE_WARRANTY_EXPIRE_DATE AS VARCHAR(16777216)) AS MACHINE_WARRANTY_EXPIRE_DATE,
        CAST (WARRANTY_STATUS_ID AS VARCHAR(16777216)) AS WARRANTY_STATUS_ID,
        CAST (OBJECT_NUMBER AS VARCHAR(16777216)) AS OBJECT_NUMBER,
        CAST (SUPPLIER_CD AS VARCHAR(16777216)) AS SUPPLIER_CD,
        CAST (DEFECTIVE_PORTION_ID AS VARCHAR(16777216)) AS DEFECTIVE_PORTION_ID,
        CAST (FRF_FLAG AS VARCHAR(16777216)) AS FRF_FLAG,
        CAST (MAC_HIST_REASON_ID AS VARCHAR(16777216)) AS MAC_HIST_REASON_ID,
        CAST (MAC_HIST_REASON_NAME_J AS VARCHAR(16777216)) AS MAC_HIST_REASON_NAME_J,
        CAST (MAC_HIST_REASON_NAME AS VARCHAR(16777216)) AS MAC_HIST_REASON_NAME,
        CAST (PROJECT_NO AS VARCHAR(16777216)) AS PROJECT_NO,
        CAST(_FILEDATE as TIMESTAMP_NTZ(9)) as _FILEDATE,
		CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
		CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
	FROM transform_data
)

SELECT * FROM type_data
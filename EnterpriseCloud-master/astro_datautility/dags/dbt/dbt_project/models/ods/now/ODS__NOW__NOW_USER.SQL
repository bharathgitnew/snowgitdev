{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='NOW_USER'
) }}


with source_data as
(
    SELECT
        _FILENAME,
        _FILEDATE,
        JSONFIELD:USER_ID::STRING AS USER_ID,
        JSONFIELD:EMPLOYEE_NUMBER::STRING AS EMPLOYEE_NUMBER,
        JSONFIELD:FIRST_NAME::STRING AS FIRST_NAME,
        JSONFIELD:LAST_NAME::STRING AS LAST_NAME,
        JSONFIELD:PHONE::STRING AS PHONE,
        JSONFIELD:PHONE_EXT::STRING AS PHONE_EXT,
        JSONFIELD:PAGER::STRING AS PAGER,
        JSONFIELD:PAGER_PIN::STRING AS PAGER_PIN,
        JSONFIELD:EMAIL::STRING AS EMAIL,
        JSONFIELD:CUSTOMER_PHONE::STRING AS CUSTOMER_PHONE,
        JSONFIELD:CUSTOMER_PHONE_EXT::STRING AS CUSTOMER_PHONE_EXT,
        JSONFIELD:CUSTOMER_PAGER::STRING AS CUSTOMER_PAGER,
        JSONFIELD:CUSTOMER_PAGER_PIN::STRING AS CUSTOMER_PAGER_PIN,
        JSONFIELD:PASSWORD::STRING AS PASSWORD,
        JSONFIELD:ACCOUNT_STATUS_ID::STRING AS ACCOUNT_STATUS_ID,
        JSONFIELD:ACCOUNT_TYPE_ID::STRING AS ACCOUNT_TYPE_ID,
        JSONFIELD:CHANGE_PASSWORD::STRING AS CHANGE_PASSWORD,
        JSONFIELD:LANGUAGE_ID::STRING AS LANGUAGE_ID,
        JSONFIELD:TZ_ID::STRING AS TZ_ID,
        JSONFIELD:DATE_FORMAT_ID::STRING AS DATE_FORMAT_ID,
        JSONFIELD:MILITARY_TIME_ID::STRING AS MILITARY_TIME_ID,
        JSONFIELD:DUMMY_USER::STRING AS DUMMY_USER,
        JSONFIELD:LOCK_FLG::STRING AS LOCK_FLG,
        JSONFIELD:LOGIN_ERROR_DT::STRING AS LOGIN_ERROR_DT,
        JSONFIELD:LOGIN_ERROR_CNT::STRING AS LOGIN_ERROR_CNT,
        JSONFIELD:LAST_UPDATE_USER::STRING AS LAST_UPDATE_USER,
        JSONFIELD:LAST_UPDATE_DATE::STRING AS LAST_UPDATE_DATE
    FROM {{ source("NOW", "NOW_USER") }}
    WHERE _FILEDATE = (
        SELECT MAX(RUN_TIME)
        FROM {{ source('NOW', 'CONTROLTABLE') }}
        WHERE TABLE_NAME = 'T_NOW_USER'
            ) 
)
,transform_data as
(
    SELECT
        _FILENAME,
        _FILEDATE,
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        USER_ID,
        EMPLOYEE_NUMBER,
        FIRST_NAME,
        LAST_NAME,
        PHONE,
        PHONE_EXT,
        PAGER,
        PAGER_PIN,
        EMAIL,
        CUSTOMER_PHONE,
        CUSTOMER_PHONE_EXT,
        CUSTOMER_PAGER,
        CUSTOMER_PAGER_PIN,
        PASSWORD,
        ACCOUNT_STATUS_ID,
        ACCOUNT_TYPE_ID,
        CHANGE_PASSWORD,
        LANGUAGE_ID,
        TZ_ID,
        DATE_FORMAT_ID,
        MILITARY_TIME_ID,
        DUMMY_USER,
        LOCK_FLG,
        LOGIN_ERROR_DT,
        LOGIN_ERROR_CNT,
        LAST_UPDATE_USER,
        LAST_UPDATE_DATE
    FROM source_data
),

type_data as (
select
    CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
    CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    USER_ID,
    EMPLOYEE_NUMBER,
    FIRST_NAME,
    LAST_NAME,
    PHONE,
    PHONE_EXT,
    PAGER,
    PAGER_PIN,
    EMAIL,
    CUSTOMER_PHONE,
    CUSTOMER_PHONE_EXT,
    CUSTOMER_PAGER,
    CUSTOMER_PAGER_PIN,
    PASSWORD,
    ACCOUNT_STATUS_ID,
    ACCOUNT_TYPE_ID,
    CHANGE_PASSWORD,
    LANGUAGE_ID,
    TZ_ID,
    DATE_FORMAT_ID,
    MILITARY_TIME_ID,
    DUMMY_USER,
    LOCK_FLG,
    LOGIN_ERROR_DT,
    LOGIN_ERROR_CNT,
    LAST_UPDATE_USER,
    LAST_UPDATE_DATE
from transform_data
)

select * from type_data
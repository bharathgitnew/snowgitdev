{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='PAID_SERVICE_QUOTE_MASTER',
    unique_key = ['ID']
) }}

with source_data as
(
    SELECT
    JSONFIELD:ID::NUMBER(38,0) AS ID
    ,JSONFIELD:QUOTESTATUSID::NUMBER(38,0) AS QUOTESTATUSID
    ,JSONFIELD:REQUESTOREMPNO::STRING AS	REQUESTOREMPNO
    ,JSONFIELD:REQUESTORNAME::STRING AS	REQUESTORNAME
    ,JSONFIELD:SUPERVISOREMPNO::STRING AS	SUPERVISOREMPNO
    ,JSONFIELD:SUPERVISORNAME::STRING AS	SUPERVISORNAME
    ,JSONFIELD:CUSTOMER_CODE::STRING AS	CUSTOMER_CODE
    ,JSONFIELD:CUSTOMER_NAME::STRING AS	CUSTOMER_NAME
    ,JSONFIELD:SITESUPERVISORNAME::STRING AS	SITESUPERVISORNAME
    ,JSONFIELD:SITESUPERVISOREMPNO::STRING AS	SITESUPERVISOREMPNO
    ,REGEXP_REPLACE(JSONFIELD:REQUESTDATE, '\/Date\\(|\\)\/', '')::TIMESTAMP AS	REQUESTDATE
    ,JSONFIELD:QUOTENUMBER::STRING	AS	QUOTENUMBER
    ,JSONFIELD:TOOIDNUMBER::STRING	AS	TOOIDNUMBER
    ,JSONFIELD:SERIALNUMBER::STRING	AS	SERIALNUMBER
    ,REGEXP_REPLACE(JSONFIELD:SERVICESTARTDATE	, '\/Date\\(|\\)\/', '')::TIMESTAMP	AS SERVICESTARTDATE
    ,REGEXP_REPLACE(JSONFIELD:SERVCEENDDATE	, '\/Date\\(|\\)\/', '')::TIMESTAMP	AS SERVCEENDDATE
    ,JSONFIELD:PRODUCT::STRING AS PRODUCT
    ,JSONFIELD:BRIEFDESCRIPTIONOFWORK::STRING AS BRIEFDESCRIPTIONOFWORK
    ,JSONFIELD:FABLOCATIONS::STRING	AS FABLOCATIONS
    ,JSONFIELD:SERVICETYPESID::NUMBER(38,0) AS SERVICETYPESID
    ,JSONFIELD:WORKTYPESID::NUMBER(38,0) AS WORKTYPESID
    ,JSONFIELD:IS_ACTIVE::NUMBER(38,0) AS IS_ACTIVE
    ,JSONFIELD:CREADTEDBY::NUMBER(38,0) AS CREADTEDBY
    ,JSONFIELD:UPDATEDBY::NUMBER(38,0) AS UPDATEDBY
    ,REGEXP_REPLACE(JSONFIELD:CREATEDON	, '\/Date\\(|\\)\/', '')::TIMESTAMP	AS	CREATEDON
    ,REGEXP_REPLACE(JSONFIELD:UPDATEDON	, '\/Date\\(|\\)\/', '')::TIMESTAMP	AS	UPDATEDON
    ,JSONFIELD:IS_SECTIONONEVALID::NUMBER(38,0) AS IS_SECTIONONEVALID
    ,JSONFIELD:IS_SECTIONTWOVALID::NUMBER(38,0) AS IS_SECTIONTWOVALID
    ,JSONFIELD:IS_SECTIONTHREEVALID::NUMBER(38,0) AS IS_SECTIONTHREEVALID
    ,JSONFIELD:WORKORDER::STRING	AS	WORKORDER
    ,JSONFIELD:POAMOUNT::NUMBER(38,2)	AS	POAMOUNT
    ,JSONFIELD:PQSSHAREPOINTPATH::STRING	AS	PQSSHAREPOINTPATH
    ,JSONFIELD:BOOKINGCONFIDENCEID::NUMBER(38,0) AS BOOKINGCONFIDENCEID
    ,JSONFIELD:LOCALFABNAMEFORDISPLAY::STRING	AS	LOCALFABNAMEFORDISPLAY
    ,JSONFIELD:TOTALPRICING::NUMBER(38,2)	AS	TOTALPRICING 
    FROM {{ source("LZ_TELQS", "PAID_SERVICE_QUOTE_MASTER") }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source("LZ_TELQS", "PAID_SERVICE_QUOTE_MASTER") }})
)

,transform_data as
(
    SELECT
        ID
        ,QUOTESTATUSID
        ,REQUESTOREMPNO
        ,REQUESTORNAME
        ,SUPERVISOREMPNO
        ,SUPERVISORNAME
        ,CUSTOMER_CODE
        ,CUSTOMER_NAME
        ,SITESUPERVISORNAME
        ,SITESUPERVISOREMPNO
        ,REQUESTDATE
        ,QUOTENUMBER
        ,TOOIDNUMBER
        ,SERIALNUMBER
        ,SERVICESTARTDATE
        ,SERVCEENDDATE
        ,PRODUCT
        ,BRIEFDESCRIPTIONOFWORK
        ,FABLOCATIONS
        ,SERVICETYPESID
        ,WORKTYPESID
        ,IS_ACTIVE
        ,CREADTEDBY
        ,UPDATEDBY
        ,CREATEDON
        ,UPDATEDON
        ,IS_SECTIONONEVALID
        ,IS_SECTIONTWOVALID
        ,IS_SECTIONTHREEVALID
        ,WORKORDER
        ,POAMOUNT
        ,PQSSHAREPOINTPATH
        ,BOOKINGCONFIDENCEID
        ,LOCALFABNAMEFORDISPLAY
        ,TOTALPRICING
        ,'{{ invocation_id }}' AS AUDIT_LOG_ID
        ,SHA2('hash_me') AS _ROW_HASH
    FROM source_data
)

,type_data as 
(
    select
        CAST(ID AS NUMBER(38,0)) AS ID
        ,CAST(QUOTESTATUSID AS NUMBER(38,0)) AS QUOTESTATUSID
        ,CAST(REQUESTOREMPNO AS VARCHAR(16777216)) AS REQUESTOREMPNO
        ,CAST(REQUESTORNAME AS VARCHAR(16777216)) AS REQUESTORNAME
        ,CAST(SUPERVISOREMPNO AS VARCHAR(16777216)) AS SUPERVISOREMPNO
        ,CAST(SUPERVISORNAME AS VARCHAR(16777216)) AS SUPERVISORNAME
        ,CAST(CUSTOMER_CODE AS VARCHAR(16777216)) AS CUSTOMER_CODE
        ,CAST(CUSTOMER_NAME AS VARCHAR(16777216)) AS CUSTOMER_NAME
        ,CAST(SITESUPERVISORNAME AS VARCHAR(16777216)) AS SITESUPERVISORNAME
        ,CAST(SITESUPERVISOREMPNO AS VARCHAR(16777216)) AS SITESUPERVISOREMPNO
        ,CAST(REQUESTDATE AS TIMESTAMP_NTZ(9)) AS REQUESTDATE
        ,CAST(QUOTENUMBER AS VARCHAR(16777216)) AS QUOTENUMBER
        ,CAST(TOOIDNUMBER AS VARCHAR(16777216)) AS TOOIDNUMBER
        ,CAST(SERIALNUMBER AS VARCHAR(16777216)) AS SERIALNUMBER
        ,CAST(SERVICESTARTDATE AS TIMESTAMP_NTZ(9)) AS SERVICESTARTDATE
        ,CAST(SERVCEENDDATE AS TIMESTAMP_NTZ(9)) AS SERVCEENDDATE
        ,CAST(PRODUCT AS VARCHAR(16777216)) AS PRODUCT
        ,CAST(BRIEFDESCRIPTIONOFWORK AS VARCHAR(16777216)) AS BRIEFDESCRIPTIONOFWORK
        ,CAST(FABLOCATIONS AS VARCHAR(16777216)) AS FABLOCATIONS
        ,CAST(SERVICETYPESID AS NUMBER(38,0)) AS SERVICETYPESID
        ,CAST(WORKTYPESID AS NUMBER(38,0)) AS WORKTYPESID
        ,CAST(IS_ACTIVE AS NUMBER(38,0)) AS IS_ACTIVE
        ,CAST(CREADTEDBY AS NUMBER(38,0)) AS CREADTEDBY
        ,CAST(UPDATEDBY AS NUMBER(38,0)) AS UPDATEDBY
        ,CAST(CREATEDON	AS TIMESTAMP_NTZ(9)) AS CREATEDON
        ,CAST(UPDATEDON	AS TIMESTAMP_NTZ(9)) AS UPDATEDON
        ,CAST(IS_SECTIONONEVALID AS NUMBER(38,0)) AS IS_SECTIONONEVALID
        ,CAST(IS_SECTIONTWOVALID AS NUMBER(38,0)) AS IS_SECTIONTWOVALID
        ,CAST(IS_SECTIONTHREEVALID AS NUMBER(38,0)) AS IS_SECTIONTHREEVALID
        ,CAST(WORKORDER AS VARCHAR(16777216)) AS WORKORDER
        ,CAST(POAMOUNT AS NUMBER(38,2)) AS POAMOUNT
        ,CAST(PQSSHAREPOINTPATH	AS VARCHAR(16777216)) AS PQSSHAREPOINTPATH
        ,CAST(BOOKINGCONFIDENCEID AS NUMBER(38,0)) AS BOOKINGCONFIDENCEID
        ,CAST(LOCALFABNAMEFORDISPLAY AS VARCHAR(16777216)) AS LOCALFABNAMEFORDISPLAY
        ,CAST(TOTALPRICING AS NUMBER(38,2)) AS TOTALPRICING
        ,CAST(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID
        ,CAST(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
    )
select * from type_data
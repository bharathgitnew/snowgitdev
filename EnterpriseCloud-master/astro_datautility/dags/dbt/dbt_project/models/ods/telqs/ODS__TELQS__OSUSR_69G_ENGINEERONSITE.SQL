{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='OSUSR_69G_ENGINEERONSITE'
) }}

with source_data as
(
SELECT
JSONFIELD:ID::STRING AS ID,
JSONFIELD:SERVICEQUOTEWITHCONTRACTID::STRING AS SERVICEQUOTEWITHCONTRACTID,
JSONFIELD:MACHINESID::STRING AS MACHINESID,
JSONFIELD:REQUESTTOFSC::STRING AS REQUESTTOFSC,
JSONFIELD:ISNEWCONTRACT::NUMBER(38,0) AS ISNEWCONTRACT,
JSONFIELD:ISWARRANTY::STRING AS ISWARRANTY,
JSONFIELD:ISNEEDS_A_BILLING::STRING AS ISNEEDS_A_BILLING,
JSONFIELD:IS_ACTIVE::NUMBER(38,0) AS IS_ACTIVE,
JSONFIELD:CREADTEDBY::STRING AS CREADTEDBY,
JSONFIELD:UPDATEDBY::STRING AS UPDATEDBY,
JSONFIELD:CREATEDON::STRING AS CREATEDON,
TO_TIMESTAMP_NTZ(TRIM(jsonfield:UPDATEDON,'/Date()/')) AS UPDATEDON, 
JSONFIELD:ENGINEEROTHERDETAILID::STRING AS ENGINEEROTHERDETAILID,
JSONFIELD:IS_BILLINGMATRIXWITHOUTQUOTE::STRING AS IS_BILLINGMATRIXWITHOUTQUOTE

FROM {{ source('LZ_TELQS', 'OSUSR_69G_ENGINEERONSITE') }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_69G_ENGINEERONSITE') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
ID,
SERVICEQUOTEWITHCONTRACTID,
MACHINESID,
REQUESTTOFSC,
ISNEWCONTRACT,
ISWARRANTY,
ISNEEDS_A_BILLING,
IS_ACTIVE,
CREADTEDBY,
UPDATEDBY,
CREATEDON,
UPDATEDON,
ENGINEEROTHERDETAILID,
IS_BILLINGMATRIXWITHOUTQUOTE
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
ID,
SERVICEQUOTEWITHCONTRACTID,
MACHINESID,
REQUESTTOFSC,
ISNEWCONTRACT,
ISWARRANTY,
ISNEEDS_A_BILLING,
IS_ACTIVE,
CREADTEDBY,
UPDATEDBY,
CREATEDON,
UPDATEDON,
ENGINEEROTHERDETAILID,
IS_BILLINGMATRIXWITHOUTQUOTE
from transform_data 
)
SELECT * from type_data
{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='OSUSR_BN7_ADDTIONALDETAILS'
) }}

with source_data as
(
SELECT
JSONFIELD:ID::STRING AS ID,
JSONFIELD:SERVICECONTRACTQUOTEMASTERID::STRING AS SERVICECONTRACTQUOTEMASTERID,
JSONFIELD:DESCRIPTIONOFWORK::STRING AS DESCRIPTIONOFWORK,
JSONFIELD:IS_ACTIVE::STRING AS IS_ACTIVE,
JSONFIELD:CREADTEDBY::STRING AS CREADTEDBY,
JSONFIELD:UPDATEDBY::STRING AS UPDATEDBY,
JSONFIELD:CREATEDON::STRING AS CREATEDON,
JSONFIELD:UPDATEDON::STRING AS UPDATEDON,
JSONFIELD:AGGREMENTNOTES::STRING AS AGGREMENTNOTES

FROM {{ source('LZ_TELQS', 'OSUSR_BN7_ADDTIONALDETAILS') }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_BN7_ADDTIONALDETAILS') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
ID,
SERVICECONTRACTQUOTEMASTERID,
DESCRIPTIONOFWORK,
IS_ACTIVE,
CREADTEDBY,
UPDATEDBY,
CREATEDON,
UPDATEDON,
AGGREMENTNOTES
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
ID,
SERVICECONTRACTQUOTEMASTERID,
DESCRIPTIONOFWORK,
IS_ACTIVE,
CREADTEDBY,
UPDATEDBY,
CREATEDON,
UPDATEDON,
AGGREMENTNOTES
from transform_data 
)
SELECT * from type_data
{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='OSUSR_BN7_VERSIONHISTORY'
) }}

with source_data as
(
SELECT
JSONFIELD:ID::STRING AS ID,
JSONFIELD:VERSION::STRING AS VERSION,
JSONFIELD:SERVICECONTRACTQUOTEMASTERID::STRING AS SERVICECONTRACTQUOTEMASTERID,
JSONFIELD:PREVIOUSVALUE::STRING AS PREVIOUSVALUE,
JSONFIELD:NEWVALUE::STRING AS NEWVALUE,
JSONFIELD:PREVIOUSSTATUS::STRING AS PREVIOUSSTATUS,
JSONFIELD:NEWSTATUS::STRING AS NEWSTATUS,
TO_TIMESTAMP_NTZ(TRIM(jsonfield:UPDATEDSTATUSDATE,'/Date()/')) AS UPDATEDSTATUSDATE,
JSONFIELD:DAYSINPROCESSING::STRING AS DAYSINPROCESSING,
JSONFIELD:DAYSSPENTONPREVIOUSSTATUS::STRING AS DAYSSPENTONPREVIOUSSTATUS,
JSONFIELD:COMMENTS::STRING AS COMMENTS,
JSONFIELD:CREATEDBY::STRING AS CREATEDBY,
JSONFIELD:CREATEDON::STRING AS CREATEDON,
JSONFIELD:HEADCOUNT::STRING AS HEADCOUNT,
JSONFIELD:TOTALAMOUNT::STRING AS TOTALAMOUNT,
JSONFIELD:CONTRACTTYPENAME::STRING AS CONTRACTTYPENAME,
JSONFIELD:CONTRACTTYPEID::STRING AS CONTRACTTYPEID,
TO_TIMESTAMP_NTZ(TRIM(jsonfield:STARTDATE,'/Date()/')) AS STARTDATE,
TO_TIMESTAMP_NTZ(TRIM(jsonfield:ENDDATE,'/Date()/')) AS  ENDDATE,
JSONFIELD:PRODUCTS::STRING AS PRODUCTS,
JSONFIELD:COUNTPENDINGDAYS::STRING AS COUNTPENDINGDAYS,
JSONFIELD:COUNTWAITFST::STRING AS COUNTWAITFST,
JSONFIELD:COUNTQUOTEREVISION::STRING AS COUNTQUOTEREVISION,
JSONFIELD:COUNTQUOTESEND::STRING AS COUNTQUOTESEND

FROM {{ source('LZ_TELQS', 'OSUSR_BN7_VERSIONHISTORY') }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_BN7_VERSIONHISTORY') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
ID,
VERSION,
SERVICECONTRACTQUOTEMASTERID,
PREVIOUSVALUE,
NEWVALUE,
PREVIOUSSTATUS,
NEWSTATUS,
UPDATEDSTATUSDATE,
DAYSINPROCESSING,
DAYSSPENTONPREVIOUSSTATUS,
COMMENTS,
CREATEDBY,
CREATEDON,
HEADCOUNT,
TOTALAMOUNT,
CONTRACTTYPENAME,
CONTRACTTYPEID,
STARTDATE,
ENDDATE,
PRODUCTS,
COUNTPENDINGDAYS,
COUNTWAITFST,
COUNTQUOTEREVISION,
COUNTQUOTESEND
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
ID,
VERSION,
SERVICECONTRACTQUOTEMASTERID,
PREVIOUSVALUE,
NEWVALUE,
PREVIOUSSTATUS,
NEWSTATUS,
UPDATEDSTATUSDATE,
DAYSINPROCESSING,
DAYSSPENTONPREVIOUSSTATUS,
COMMENTS,
CREATEDBY,
CREATEDON,
HEADCOUNT,
TOTALAMOUNT,
CONTRACTTYPENAME,
CONTRACTTYPEID,
STARTDATE,
ENDDATE,
PRODUCTS,
COUNTPENDINGDAYS,
COUNTWAITFST,
COUNTQUOTEREVISION,
COUNTQUOTESEND
from transform_data 
)
SELECT * from type_data
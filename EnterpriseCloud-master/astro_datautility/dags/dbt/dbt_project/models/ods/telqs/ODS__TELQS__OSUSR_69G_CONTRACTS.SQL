{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='OSUSR_69G_CONTRACTS'
) }}

with source_data as
(
SELECT
JSONFIELD:ID::STRING AS ID,
JSONFIELD:SERVICECONTRACTQUOTE::STRING AS SERVICECONTRACTQUOTE,
JSONFIELD:ISCOMPREHENSIVE::STRING AS ISCOMPREHENSIVE,
JSONFIELD:IS_NONITMIZEDPRICING::STRING AS IS_NONITMIZEDPRICING,
JSONFIELD:CONTRACTLENGTHID::STRING AS CONTRACTLENGTHID,
TO_TIMESTAMP_NTZ(TRIM(jsonfield:CONTRACTSTARTDATE,'/Date()/')) AS CONTRACTSTARTDATE,
TO_TIMESTAMP_NTZ(TRIM(jsonfield:CONTRACTENDDATE,'/Date()/')) AS CONTRACTENDDATE,
JSONFIELD:ISRENEWAL::STRING AS ISRENEWAL,
JSONFIELD:PROVIDECONTREACTNO::STRING AS PROVIDECONTREACTNO,
JSONFIELD:FORECASTMONTH::STRING AS FORECASTMONTH,
JSONFIELD:PROBABILITY::STRING AS PROBABILITY,
JSONFIELD:IS_ACTIVE::NUMBER(38,0) AS IS_ACTIVE,
JSONFIELD:CREADTEDBY::STRING AS CREADTEDBY,
JSONFIELD:UPDATEDBY::STRING AS UPDATEDBY,
JSONFIELD:CREATEDON::STRING AS CREATEDON,
TO_TIMESTAMP_NTZ(TRIM(jsonfield:UPDATEDON,'/Date()/')) AS UPDATEDON

FROM {{ source('LZ_TELQS', 'OSUSR_69G_CONTRACTS') }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_69G_CONTRACTS') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
ID,
SERVICECONTRACTQUOTE,
ISCOMPREHENSIVE,
IS_NONITMIZEDPRICING,
CONTRACTLENGTHID,
CONTRACTSTARTDATE,
CONTRACTENDDATE,
ISRENEWAL,
PROVIDECONTREACTNO,
FORECASTMONTH,
PROBABILITY,
IS_ACTIVE,
CREADTEDBY,
UPDATEDBY,
CREATEDON,
UPDATEDON
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
ID,
SERVICECONTRACTQUOTE,
ISCOMPREHENSIVE,
IS_NONITMIZEDPRICING,
CONTRACTLENGTHID,
CONTRACTSTARTDATE,
CONTRACTENDDATE,
ISRENEWAL,
PROVIDECONTREACTNO,
FORECASTMONTH,
PROBABILITY,
IS_ACTIVE,
CREADTEDBY,
UPDATEDBY,
CREATEDON,
UPDATEDON
from transform_data 
)
SELECT * from type_data
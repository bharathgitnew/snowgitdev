{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='OSUSR_BN7_SQCPROCESSORDERPRICING'
) }}

with source_data as
(
SELECT
JSONFIELD:ID::STRING AS ID,
JSONFIELD:SERVICEPROCESSORDERID::STRING AS SERVICEPROCESSORDERID,
JSONFIELD:CONTRACTTYPEID::STRING AS CONTRACTTYPEID,
JSONFIELD:POAMOUNT::STRING AS POAMOUNT,
JSONFIELD:DESCRIPTION::STRING AS DESCRIPTION,
JSONFIELD:QUANTITY::STRING AS QUANTITY,
JSONFIELD:UNITPRICE::STRING AS UNITPRICE,
JSONFIELD:TOTAL::STRING AS TOTAL,
JSONFIELD:NETCHANGE::STRING AS NETCHANGE,
JSONFIELD:CONTRACTTYPE::STRING AS CONTRACTTYPE

FROM {{ source('LZ_TELQS', 'OSUSR_BN7_SQCPROCESSORDERPRICING') }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_BN7_SQCPROCESSORDERPRICING') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
ID,
SERVICEPROCESSORDERID,
CONTRACTTYPEID,
POAMOUNT,
DESCRIPTION,
QUANTITY,
UNITPRICE,
TOTAL,
NETCHANGE,
CONTRACTTYPE
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
ID,
SERVICEPROCESSORDERID,
CONTRACTTYPEID,
POAMOUNT,
DESCRIPTION,
QUANTITY,
UNITPRICE,
TOTAL,
NETCHANGE,
CONTRACTTYPE
from transform_data 
)
SELECT * from type_data
{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='OSUSR_CZN_CONTRACTTYPEDETAILS'
) }}

with source_data as
(
SELECT
JSONFIELD:CONTRACTTYPEID::STRING AS CONTRACTTYPEID,
JSONFIELD:CONTRACTTYPENAME::STRING AS CONTRACTTYPENAME,
JSONFIELD:CRMCONTRACTSCOPE::STRING AS CRMCONTRACTSCOPE,
JSONFIELD:IS_ACTIVE::NUMBER(38,0) AS IS_ACTIVE
FROM {{ source('LZ_TELQS', 'OSUSR_CZN_CONTRACTTYPEDETAILS') }}
WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source('LZ_TELQS', 'OSUSR_CZN_CONTRACTTYPEDETAILS') }})
)

,transform_data as
(
SELECT
'{{ invocation_id }}' AS _AUDIT_LOG_ID,
 SHA2('hash_me') AS _ROW_HASH,
CONTRACTTYPEID,
CONTRACTTYPENAME,
CRMCONTRACTSCOPE,
IS_ACTIVE
FROM source_data
)

,type_data as 
(
SELECT
_AUDIT_LOG_ID,
_ROW_HASH,
CONTRACTTYPEID,
CONTRACTTYPENAME,
CRMCONTRACTSCOPE,
IS_ACTIVE
from transform_data 
)
SELECT * from type_data
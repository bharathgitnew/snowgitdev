{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='BAANCOMMONITEMBASEDATA_ALTERNATIVEITEMS',
    unique_key = ['ITEM',
    'ALTERNATIVEITEMS',
    'PRIORITY',
    'REVERSEID']
) }}

with source_data as 
(
    SELECT SOURCETABLE._CAPTUREDATETIME            AS _CAPTUREDATETIME 
    ,201                                           AS _COMPANYID 
    ,NULLIF(RTRIM(LTRIM(SOURCETABLE.T$ITEM)),'')   AS ITEM 
    ,NULLIF(RTRIM(LTRIM(SOURCETABLE.T$AITM)),'')   AS ALTERNATIVEITEMS 
    ,CAST("T$PRIO" AS INT)                         AS PRIORITY 
    ,T$REVE.CONSTANTDESCRIPTION     AS REVERSEDESCRIPTION 
    ,CAST(T$REVE AS INT)            AS REVERSEID 
    ,T$NATU.CONSTANTDESCRIPTION     AS INTERCHANGEABLEDESCRIPTION 
    ,CAST(T$NATU AS INT)            AS INTERCHANGEABLEID 
    ,CAST(CASE WHEN T$SDTE<= '1/1/1970' THEN NULL ELSE T$SDTE  END AS DATETIME) AS INTRODUCTIONDATE
    ,CAST(CASE WHEN T$EDTE<= '1/1/1970' THEN NULL ELSE T$EDTE  END AS DATETIME) AS EXPIRYDATE
    ,T$REPL.CONSTANTDESCRIPTION     AS REPLACEMENTDESCRIPTION 
    ,CAST(T$REPL AS INT)            AS REPLACEMENTID 
    FROM {{ source("BAAN_ORACLE_LIVE", "TTCIBD005201") }} SOURCETABLE
    /*INTERCHANGEABLE*/ 
    LEFT OUTER JOIN {{ source("BAAN", "ENUMERATIONS") }} AS T$NATU 
     ON   T$NATU.TABLENAME  = 'TCIBD005' 
      AND T$NATU.COLUMNNAME = 'T$NATU' 
      AND T$NATU.CONSTANT   = SOURCETABLE.T$NATU
    /*REPLACEMENT*/ 
    LEFT OUTER JOIN {{ source("BAAN", "ENUMERATIONS") }} AS T$REPL 
     ON   T$REPL.TABLENAME  = 'TCIBD005' 
      AND T$REPL.COLUMNNAME = 'T$REPL' 
      AND T$REPL.CONSTANT   = SOURCETABLE.T$REPL
    /*REVERSE*/ 
    LEFT OUTER JOIN {{ source("BAAN", "ENUMERATIONS") }} AS T$REVE 
     ON   T$REVE.TABLENAME  = 'TCIBD005' 
      AND T$REVE.COLUMNNAME = 'T$REVE' 
      AND T$REVE.CONSTANT   = SOURCETABLE.T$REVE 
    WHERE FALSE
)        
,transform_data as
(
    SELECT
    _CAPTUREDATETIME,
    _COMPANYID,
    ITEM,
    ALTERNATIVEITEMS,
    PRIORITY,
    REVERSEDESCRIPTION,
    REVERSEID,
    INTERCHANGEABLEDESCRIPTION,
    INTERCHANGEABLEID,
    INTRODUCTIONDATE,
    EXPIRYDATE,
    REPLACEMENTDESCRIPTION,
    REPLACEMENTID,
    '{{ invocation_id }}' AS AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH
    FROM source_data
)
,type_data as 
(
    SELECT
    cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
    cast(_COMPANYID as NUMBER(3,0)) as _COMPANYID,
    cast(ITEM as VARCHAR(16777216)) as ITEM,
    cast(ALTERNATIVEITEMS as VARCHAR(16777216)) as ALTERNATIVEITEMS,
    cast(PRIORITY as NUMBER(38,0)) as PRIORITY,
    cast(REVERSEDESCRIPTION as VARCHAR(16777216)) as REVERSEDESCRIPTION,
    cast(REVERSEID as NUMBER(38,0)) as REVERSEID,
    cast(INTERCHANGEABLEDESCRIPTION as VARCHAR(16777216)) as INTERCHANGEABLEDESCRIPTION,
    cast(INTERCHANGEABLEID as NUMBER(38,0)) as INTERCHANGEABLEID,
    cast(INTRODUCTIONDATE as TIMESTAMP_LTZ(9)) as INTRODUCTIONDATE,
    cast(EXPIRYDATE as TIMESTAMP_LTZ(9)) as EXPIRYDATE,
    cast(REPLACEMENTDESCRIPTION as VARCHAR(16777216)) as REPLACEMENTDESCRIPTION,
    cast(REPLACEMENTID as NUMBER(38,0)) as REPLACEMENTID,
    cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
    cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)

select * from type_data
        TO_TIMESTAMP_NTZ(TRIM(DataItems.Value:ApprovedBy,'/Date()/')) AS ApprovedDate
        from {{source('SHAREPOINT','REQUEST_FOR_QUOTE')}}, lateral flatten(jsonfield:Data) DataItems
        where _filename like concat('%', (select distinct substr(_filename,1,length(_filename)-6) from {{source('SHAREPOINT','REQUEST_FOR_QUOTE')}}
                                      where _filedate = (select max(_filedate)
                                      from {{source('SHAREPOINT','REQUEST_FOR_QUOTE')}})), '%')
        AND _filedate > (select COALESCE(MAX(_filedate),'1970-01-01') from {{this}})
),


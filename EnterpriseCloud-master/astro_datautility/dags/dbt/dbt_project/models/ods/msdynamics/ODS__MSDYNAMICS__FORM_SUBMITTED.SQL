{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='FORM_SUBMITTED',
    unique_key = []
) }}

with source_data as
(
    SELECT
        MESSAGEID,
        PAGEID,
        FORMID,
        FORMNAME,
        FORMSUBMISSIONID,
        CUSTOMERJOURNEYID,
        CUSTOMERJOURNEYITERATIONID,
        RESULT,
        VISITORID,
        SESSIONID,
        CONTACTID,
        ACCOUNTID,
        CONTACTMATCHINGRESULT,
        LEADMATCHINGRESULT,
        COUNTRYISOCODE,
        STATE,
        CITY,
        POSTALCODE,
        BROWSERID,
        BROWSERVERSION,
        OPERATINGSYSTEMID,
        OPERATINGSYSTEMVERSION,
        REFERRERURI,
        SENDINGID,
        SEARCHPHRASE,
        SEARCHENGINENAME,
        VISITDURATION,
        VISITORRETURNINGSTATUS,
        CONTACTFAILUREMESSAGE,
        LEADFAILUREMESSAGE,
        TIMESTAMP,
        VISITORANONYMOUSSTATUS,
        LEADID,
        SUBMITTEDVALUES,
        WEBSITEID,
        PAGEURL,
        INTERNALMARKETINGINTERACTIONID,
        ORGANIZATIONID,
        INTERACTIONTYPE,
        VERSION,
        _FILENAME,
        _FILEDATE
        FROM {{ source("MSDYNAMICS", "FORM_SUBMITTED") }}
        WHERE TO_DATE(_FileDate) = IFNULL((SELECT MAX(TO_DATE(_FileDate)) FROM {{ source("MSDYNAMICS", "FORM_SUBMITTED") }}),'1970-01-01')
        )
,transform_data as
(
    SELECT
        MESSAGEID,
        PAGEID,
        FORMID,
        FORMNAME,
        FORMSUBMISSIONID,
        CUSTOMERJOURNEYID,
        CUSTOMERJOURNEYITERATIONID,
        RESULT,
        VISITORID,
        SESSIONID,
        CONTACTID,
        ACCOUNTID,
        CONTACTMATCHINGRESULT,
        LEADMATCHINGRESULT,
        COUNTRYISOCODE,
        STATE,
        CITY,
        POSTALCODE,
        BROWSERID,
        BROWSERVERSION,
        OPERATINGSYSTEMID,
        OPERATINGSYSTEMVERSION,
        REFERRERURI,
        SENDINGID,
        SEARCHPHRASE,
        SEARCHENGINENAME,
        VISITDURATION,
        VISITORRETURNINGSTATUS,
        CONTACTFAILUREMESSAGE,
        LEADFAILUREMESSAGE,
        TIMESTAMP,
        VISITORANONYMOUSSTATUS,
        LEADID,
        SUBMITTEDVALUES,
        WEBSITEID,
        PAGEURL,
        INTERNALMARKETINGINTERACTIONID,
        ORGANIZATIONID,
        INTERACTIONTYPE,
        VERSION,
        _FILENAME,
        _FILEDATE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH -- Adds column to table on full refresh.
    FROM source_data
)
,type_data as
(
    select
        CAST(MESSAGEID AS VARCHAR(16777216)) AS MESSAGEID,
        CAST(PAGEID AS VARCHAR(16777216)) AS PAGEID,
        CAST(FORMID AS VARCHAR(16777216)) AS FORMID,
        CAST(FORMNAME AS VARCHAR(16777216)) AS FORMNAME,
        CAST(FORMSUBMISSIONID AS VARCHAR(16777216)) AS FORMSUBMISSIONID,
        CAST(CUSTOMERJOURNEYID AS VARCHAR(16777216)) AS CUSTOMERJOURNEYID,
        CAST(CUSTOMERJOURNEYITERATIONID AS VARCHAR(16777216)) AS CUSTOMERJOURNEYITERATIONID,
        CAST(RESULT AS VARCHAR(16777216)) AS RESULT,
        CAST(VISITORID AS VARCHAR(16777216)) AS VISITORID,
        CAST(SESSIONID AS VARCHAR(16777216)) AS SESSIONID,
        CAST(CONTACTID AS VARCHAR(16777216)) AS CONTACTID,
        CAST(ACCOUNTID AS VARCHAR(16777216)) AS ACCOUNTID,
        CAST(CONTACTMATCHINGRESULT AS VARCHAR(16777216)) AS CONTACTMATCHINGRESULT,
        CAST(LEADMATCHINGRESULT AS VARCHAR(16777216)) AS LEADMATCHINGRESULT,
        CAST(COUNTRYISOCODE AS VARCHAR(16777216)) AS COUNTRYISOCODE,
        CAST(STATE AS VARCHAR(16777216)) AS STATE,
        CAST(CITY AS VARCHAR(16777216)) AS CITY,
        CAST(POSTALCODE AS VARCHAR(16777216)) AS POSTALCODE,
        CAST(BROWSERID AS VARCHAR(16777216)) AS BROWSERID,
        CAST(BROWSERVERSION AS VARCHAR(16777216)) AS BROWSERVERSION,
        CAST(OPERATINGSYSTEMID AS VARCHAR(16777216)) AS OPERATINGSYSTEMID,
        CAST(OPERATINGSYSTEMVERSION AS VARCHAR(16777216)) AS OPERATINGSYSTEMVERSION,
        CAST(REFERRERURI AS VARCHAR(16777216)) AS REFERRERURI,
        CAST(SENDINGID AS VARCHAR(16777216)) AS SENDINGID,
        CAST(SEARCHPHRASE AS VARCHAR(16777216)) AS SEARCHPHRASE,
        CAST(SEARCHENGINENAME AS VARCHAR(16777216)) AS SEARCHENGINENAME,
        CAST(VISITDURATION AS VARCHAR(16777216)) AS VISITDURATION,
        CAST(VISITORRETURNINGSTATUS AS VARCHAR(16777216)) AS VISITORRETURNINGSTATUS,
        CAST(CONTACTFAILUREMESSAGE AS VARCHAR(16777216)) AS CONTACTFAILUREMESSAGE,
        CAST(LEADFAILUREMESSAGE AS VARCHAR(16777216)) AS LEADFAILUREMESSAGE,
        CAST(TIMESTAMP AS VARCHAR(16777216)) AS TIMESTAMP,
        CAST(VISITORANONYMOUSSTATUS AS VARCHAR(16777216)) AS VISITORANONYMOUSSTATUS,
        CAST(LEADID AS VARCHAR(16777216)) AS LEADID,
        CAST(SUBMITTEDVALUES AS VARCHAR(16777216)) AS SUBMITTEDVALUES,
        CAST(WEBSITEID AS VARCHAR(16777216)) AS WEBSITEID,
        CAST(PAGEURL AS VARCHAR(16777216)) AS PAGEURL,
        CAST(INTERNALMARKETINGINTERACTIONID AS VARCHAR(16777216)) AS INTERNALMARKETINGINTERACTIONID,
        CAST(ORGANIZATIONID AS VARCHAR(16777216)) AS ORGANIZATIONID,
        CAST(INTERACTIONTYPE AS VARCHAR(16777216)) AS INTERACTIONTYPE,
        CAST(VERSION AS VARCHAR(16777216)) AS VERSION,
        CAST(_FILENAME AS VARCHAR(16777216))  AS _FILENAME,
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9))  AS _FILEDATE,
        CAST(AUDIT_LOG_ID AS VARCHAR(128))  AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128))  AS _ROW_HASH
    from transform_data
    )
select * from type_data
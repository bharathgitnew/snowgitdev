with source_data as (
    SELECT
        _FILEDATE,
        _FILENAME,
		JSONFIELD:"ADDRNUMBER"::STRING      AS "ADDRNUMBER",
        JSONFIELD:"CONSNUMBER"::STRING      AS "CONSNUMBER",
        JSONFIELD:"DATE_FROM"::STRING       AS "DATE_FROM",
        JSONFIELD:"DELFLAG"::STRING         AS "DELFLAG",
        JSONFIELD:"FLGDEFAULT"::STRING      AS "FLGDEFAULT",
        JSONFIELD:"HOME_FLAG"::STRING       AS "HOME_FLAG",
        JSONFIELD:"PSL_INSDATE"::STRING     AS "PSL_INSDATE",
        JSONFIELD:"PSL_UPDDATE"::STRING     AS "PSL_UPDDATE",
        JSONFIELD:"SMTP_ADDR"::STRING       AS "SMTP_ADDR",
        JSONFIELD:"SMTP_SRCH"::STRING       AS "SMTP_SRCH",
        JSONFIELD:"VALID_FROM"::STRING      AS "VALID_FROM",
        JSONFIELD:"VALID_TO"::STRING        AS "VALID_TO",
		JSONFIELD:Mandt::STRING AS MANDT,
		JSONFIELD:Client::STRING AS CLIENT,
		JSONFIELD:Persnumber::STRING AS PERSNUMBER,
		JSONFIELD:FlgNouse::STRING AS FLGNOUSE,
		JSONFIELD:DftReceiv::STRING AS DFTRECEIV,
		JSONFIELD:R3User::STRING AS R3USER,
		JSONFIELD:Encode::STRING AS ENCODE,
		JSONFIELD:Tnef::STRING AS TNEF,
		JSONFIELD:Dataaging::STRING AS DATAAGING,
		JSONFIELD:update_date::STRING AS UPDATE_DATE
    FROM {{ source('SAPH','SAP_MMM_EV_ADR6') }}
	WHERE _FILEDATE::STRING = (
        SELECT MAX(RUN_TIME)::STRING
        FROM {{ source('SAPH', 'CONTROLTABLE') }}
        WHERE TABLE_NAME = 'SAP_MMM_EV_ADR6'
        )
	QUALIFY ROW_NUMBER() OVER ( PARTITION BY ADDRNUMBER, CLIENT, CONSNUMBER, DATE_FROM, PERSNUMBER ORDER BY _FILEDATE DESC, _UPLOADDATE DESC) = 1
),
transform_data as (
    SELECT
        _FILEDATE AS _FILEDATE,
        _FILENAME AS _FILENAME,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
		CLIENT as CLIENT,
		ADDRNUMBER as ADDRNUMBER,
		PERSNUMBER as PERSNUMBER,
		DATE_FROM as DATE_FROM,
		LPAD(coalesce("CONSNUMBER",''),3,'0') as "CONSNUMBER",
		Case when "FLGDEFAULT"='X' then 'true' else 'false' end as "FLGDEFAULT",
		FLGNOUSE as FLG_NOUSE,
		Case when "HOME_FLAG"='X' then 'true' else 'false' end as "HOME_FLAG",
		SMTP_ADDR as SMTP_ADDR,
		SMTP_SRCH as SMTP_SRCH,
		DFTRECEIV as DFT_RECEIV,
		R3USER as R3_USER,
		ENCODE as ENCODE,
		TNEF as TNEF,
		VALID_FROM as VALID_FROM,
		VALID_TO as VALID_TO,
		DATAAGING as _DATAAGING,
		UPDATE_DATE as UPDATE_DATE
    FROM source_data
),
type_data as (
    SELECT
        _FILEDATE,
        _FILENAME,
        AUDIT_LOG_ID,
        _ROW_HASH,
		CLIENT,
		ADDRNUMBER,
		PERSNUMBER,
		DATE_FROM,
		CONSNUMBER,
		FLGDEFAULT,
		FLG_NOUSE,
		HOME_FLAG,
		SMTP_ADDR,
		SMTP_SRCH,
		DFT_RECEIV,
		R3_USER,
		ENCODE,
		TNEF,
		VALID_FROM,
		VALID_TO,
		_DATAAGING,
		UPDATE_DATE
    FROM transform_data
)
select * from type_data
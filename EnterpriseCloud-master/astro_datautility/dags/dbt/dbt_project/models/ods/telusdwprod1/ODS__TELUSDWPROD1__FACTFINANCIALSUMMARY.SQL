{{ config(
    	materialized='incremental',
    	incremental_strategy='insert_overwrite',
    	alias='FACTFINANCIALSUMMARY',
    	transient=false
) }} 

with source_data as (
	SELECT
 	JSONFIELD:"CompanyKey"::NUMBER AS "COMPANYKEY",
    JSONFIELD:"CustomerFinancialTransactionKey"::NUMBER AS "CUSTOMERFINANCIALTRANSACTIONKEY",
    JSONFIELD:"FiscalMonthKey"::NUMBER AS "FISCALMONTHKEY",
    JSONFIELD:"FinancialCostCenterKey"::NUMBER AS "FINANCIALCOSTCENTERKEY",
    JSONFIELD:"FinancialAccountKey"::NUMBER AS "FINANCIALACCOUNTKEY",
    JSONFIELD:"FinancialDepartmentKey"::NUMBER AS "FINANCIALDEPARTMENTKEY",
    JSONFIELD:"FinancialProductTypeKey"::NUMBER AS "FINANCIALPRODUCTTYPEKEY",
    JSONFIELD:"FinancialScenarioKey"::NUMBER AS "FINANCIALSCENARIOKEY",
    JSONFIELD:"FinancialSegmentKey"::NUMBER AS "FINANCIALSEGMENTKEY",
    JSONFIELD:"OfficeKey"::NUMBER AS "OFFICEKEY",
    JSONFIELD:"SegmentBusinessUnitKey"::NUMBER AS "SEGMENTBUSINESSUNITKEY",
    JSONFIELD:"Amount"::NUMBER AS "AMOUNT",
    JSONFIELD:"_HashValue"::STRING AS "_HASHVALUE",
    JSONFIELD:"_RowStatusCode"::STRING AS "_ROWSTATUSCODE",
    REGEXP_REPLACE(JSONFIELD:_CreatedDatetime, '\/Date\\(|\\)\/', '')::TIMESTAMP AS "_CREATEDDATETIME",
    JSONFIELD:"_CreatedBy"::STRING AS "_CREATEDBY",
    JSONFIELD:"_CreatedExecutionPeriodId"::NUMBER AS "_CREATEDEXECUTIONPERIODID",
    JSONFIELD:"_CreatedContainerLogId"::NUMBER AS "_CREATEDCONTAINERLOGID",
    JSONFIELD:"_CreatedLineageId"::NUMBER AS "_CREATEDLINEAGEID",
    REGEXP_REPLACE(JSONFIELD:_ModifiedDatetime, '\/Date\\(|\\)\/', '')::TIMESTAMP AS "_MODIFIEDDATETIME",
    JSONFIELD:"_ModifiedBy"::STRING AS "_MODIFIEDBY",
    JSONFIELD:"_ModifiedExecutionPeriodId"::NUMBER AS "_MODIFIEDEXECUTIONPERIODID",
    JSONFIELD:"_ModifiedContainerLogId"::NUMBER AS "_MODIFIEDCONTAINERLOGID",
    JSONFIELD:"_ModifiedLineageId"::NUMBER AS "_MODIFIEDLINEAGEID",
    JSONFIELD:"_IsDeleted"::NUMBER AS "_ISDELETED",
    _FILEDATE,
	_FILENAME
	FROM {{ source('LEGACYPROD1','FACTFINANCIALSUMMARY') }}
    --WHERE _FILEDATE = (SELECT MAX(_FILEDATE) FROM {{ source('LEGACYPROD1','FACTFINANCIALSUMMARY') }})
),

transform_data as (
	SELECT 
	COMPANYKEY,
    CUSTOMERFINANCIALTRANSACTIONKEY,
    FISCALMONTHKEY,
    FINANCIALCOSTCENTERKEY,
    FINANCIALACCOUNTKEY,
    FINANCIALDEPARTMENTKEY,
    FINANCIALPRODUCTTYPEKEY,
    FINANCIALSCENARIOKEY,
    FINANCIALSEGMENTKEY,
    OFFICEKEY,
    SEGMENTBUSINESSUNITKEY,
    AMOUNT,
    _HASHVALUE,
    _ROWSTATUSCODE,
    _CREATEDDATETIME,
    _CREATEDBY,
    _CREATEDEXECUTIONPERIODID,
    _CREATEDCONTAINERLOGID,
    _CREATEDLINEAGEID,
    _MODIFIEDDATETIME,
    _MODIFIEDBY,
    _MODIFIEDEXECUTIONPERIODID,
    _MODIFIEDCONTAINERLOGID,
    _MODIFIEDLINEAGEID,
    _ISDELETED, 
    _FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH
	FROM source_data
),

type_data as (
	SELECT
    CAST(_FILEDATE as TIMESTAMP_NTZ(9)) as _FILEDATE,
		_FILENAME,
	    "AUDIT_LOG_ID",
    CAST("COMPANYKEY" AS NUMBER(38,0)) AS "COMPANYKEY", 
    CAST("CUSTOMERFINANCIALTRANSACTIONKEY" AS NUMBER(38,0)) AS "CUSTOMERFINANCIALTRANSACTIONKEY", 
    CAST("FISCALMONTHKEY" AS NUMBER(38,0)) AS "FISCALMONTHKEY", 
    CAST("FINANCIALCOSTCENTERKEY" AS NUMBER(38,0)) AS "FINANCIALCOSTCENTERKEY", 
    CAST("FINANCIALACCOUNTKEY" AS NUMBER(38,0)) AS "FINANCIALACCOUNTKEY", 
    CAST("FINANCIALDEPARTMENTKEY" AS NUMBER(38,0)) AS "FINANCIALDEPARTMENTKEY", 
    CAST("FINANCIALPRODUCTTYPEKEY" AS NUMBER(38,0)) AS "FINANCIALPRODUCTTYPEKEY", 
    CAST("FINANCIALSCENARIOKEY" AS NUMBER(38,0)) AS "FINANCIALSCENARIOKEY", 
    CAST("FINANCIALSEGMENTKEY" AS NUMBER(38,0)) AS "FINANCIALSEGMENTKEY", 
    CAST("OFFICEKEY" AS NUMBER(38,0)) AS "OFFICEKEY", 
    CAST("SEGMENTBUSINESSUNITKEY" AS NUMBER(38,0)) AS "SEGMENTBUSINESSUNITKEY", 
    CAST("AMOUNT" AS NUMBER(38,2)) AS "AMOUNT", 
		"_HASHVALUE", 
		"_ROWSTATUSCODE", 
    CAST("_CREATEDDATETIME" AS TIMESTAMP_NTZ(9)) AS "_CREATEDDATETIME", 
		"_CREATEDBY", 
    CAST("_CREATEDEXECUTIONPERIODID" AS NUMBER(38,0)) AS "_CREATEDEXECUTIONPERIODID", 
    CAST("_CREATEDCONTAINERLOGID" AS NUMBER(38,0)) AS "_CREATEDCONTAINERLOGID", 
    CAST("_CREATEDLINEAGEID" AS NUMBER(38,0)) AS "_CREATEDLINEAGEID", 
    CAST("_MODIFIEDDATETIME" AS TIMESTAMP_NTZ(9)) AS "_MODIFIEDDATETIME", 
		"_MODIFIEDBY", 
    CAST("_MODIFIEDEXECUTIONPERIODID" AS NUMBER(38,0)) AS "_MODIFIEDEXECUTIONPERIODID", 
    CAST("_MODIFIEDCONTAINERLOGID" AS NUMBER(38,0)) AS "_MODIFIEDCONTAINERLOGID", 
    CAST("_MODIFIEDLINEAGEID" AS NUMBER(38,0)) AS "_MODIFIEDLINEAGEID", 
    CAST("_ISDELETED" AS NUMBER(38,0)) AS "_ISDELETED"
	FROM transform_data
)

SELECT * FROM type_data
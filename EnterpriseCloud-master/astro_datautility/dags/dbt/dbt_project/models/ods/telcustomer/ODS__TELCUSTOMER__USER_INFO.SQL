{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='USER_INFO',
    unique_key = ['USERID']
) }}

with source_data as
(
    SELECT
        _FILENAME
        ,_FILEDATE
        ,JSONFIELD:"USERID"::NUMBER AS USERID
        ,JSONFIELD:"USERNAME"::STRING AS USERNAME
        ,JSONFIELD:"TEL_REGION"::STRING AS TEL_REGION
        ,JSONFIELD:"BUSINESS_PARTNER_ID"::NUMBER AS BUSINESS_PARTNER_ID
        ,JSONFIELD:"EMPLOYER_ID"::NUMBER AS EMPLOYER_ID
        ,JSONFIELD:"ACCEPT_NDA"::NUMBER AS ACCEPT_NDA
        ,REGEXP_REPLACE(JSONFIELD:JSONFIELD:"LAST_ACTIVITY_DATE", '\/Date\\(|\\)\/', '')::TIMESTAMP AS LAST_ACTIVITY_DATE
        ,JSONFIELD:"ACTIVE"::NUMBER AS ACTIVE
        ,JSONFIELD:"SALUTATION"::STRING AS SALUTATION
        ,JSONFIELD:"TITLE"::STRING AS TITLE
        ,JSONFIELD:"DEPT"::STRING AS DEPT
        ,JSONFIELD:"PHONE"::STRING AS PHONE
        ,JSONFIELD:"COUNTRY"::STRING AS COUNTRY
        ,JSONFIELD:"FULL_KANJI_NAME"::STRING AS FULL_KANJI_NAME
        ,REGEXP_REPLACE(JSONFIELD:JSONFIELD:"ACTIVATED", '\/Date\\(|\\)\/', '')::TIMESTAMP AS ACTIVATED
        ,JSONFIELD:"FIRST_NAME"::STRING AS FIRST_NAME
        ,JSONFIELD:"LAST_NAME"::STRING AS LAST_NAME
        ,JSONFIELD:"EMAIL"::STRING AS EMAIL
        ,JSONFIELD:"CREATED_BY"::STRING AS CREATED_BY
        ,REGEXP_REPLACE(JSONFIELD:JSONFIELD:"CREATE_DATE", '\/Date\\(|\\)\/', '')::TIMESTAMP AS CREATE_DATE
        ,JSONFIELD:"UPDATED_BY"::STRING AS UPDATED_BY
        ,REGEXP_REPLACE(JSONFIELD:JSONFIELD:"UPDATE_DATE", '\/Date\\(|\\)\/', '')::TIMESTAMP AS UPDATE_DATE
        ,REGEXP_REPLACE(JSONFIELD:JSONFIELD:"LAST_CONFIRM_DATE", '\/Date\\(|\\)\/', '')::TIMESTAMP AS LAST_CONFIRM_DATE
        ,JSONFIELD:"JOB_CATEGORY"::STRING AS JOB_CATEGORY
        ,JSONFIELD:"FAB"::STRING AS FAB
        ,JSONFIELD:"PRODUCT_LINE"::STRING AS PRODUCT_LINE
    FROM {{ source("TELCUSTOMER", "USER_INFO") }}
    WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ source("TELCUSTOMER", "USER_INFO") }})
)

,transform_data as
(
    SELECT
        USERID,
        USERNAME,
        TEL_REGION,
        BUSINESS_PARTNER_ID,
        EMPLOYER_ID,
        ACCEPT_NDA,
        LAST_ACTIVITY_DATE,
        ACTIVE,
        SALUTATION,
        TITLE,
        DEPT,
        PHONE,
        COUNTRY,
        FULL_KANJI_NAME,
        ACTIVATED,
        FIRST_NAME,
        LAST_NAME,
        EMAIL,
        CREATED_BY,
        CREATE_DATE,
        UPDATED_BY,
        UPDATE_DATE,
        LAST_CONFIRM_DATE,
        JOB_CATEGORY,
        FAB,
        PRODUCT_LINE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _Row_Hash
    FROM source_data
)

,type_data as 
(
    select
        cast(USERID as NUMBER(38,0)) as USERID,
        cast(USERNAME as VARCHAR(16777216)) as USERNAME,
        cast(TEL_REGION as VARCHAR(16777216)) as TEL_REGION,
        cast(BUSINESS_PARTNER_ID as NUMBER(38,0)) as BUSINESS_PARTNER_ID,
        cast(EMPLOYER_ID as NUMBER(38,0)) as EMPLOYER_ID,
        cast(ACCEPT_NDA as NUMBER(38,0)) as ACCEPT_NDA,
        cast(LAST_ACTIVITY_DATE as TIMESTAMP_NTZ(9)) as LAST_ACTIVITY_DATE,
        cast(ACTIVE as NUMBER(38,0)) as ACTIVE,
        cast(SALUTATION as VARCHAR(16777216)) as SALUTATION,
        cast(TITLE as VARCHAR(16777216)) as TITLE,
        cast(DEPT as VARCHAR(16777216)) as DEPT,
        cast(PHONE as VARCHAR(16777216)) as PHONE,
        cast(COUNTRY as VARCHAR(16777216)) as COUNTRY,
        cast(FULL_KANJI_NAME as VARCHAR(16777216)) as FULL_KANJI_NAME,
        cast(ACTIVATED as TIMESTAMP_NTZ(9)) as ACTIVATED,
        cast(FIRST_NAME as VARCHAR(16777216)) as FIRST_NAME,
        cast(LAST_NAME as VARCHAR(16777216)) as LAST_NAME,
        cast(EMAIL as VARCHAR(16777216)) as EMAIL,
        cast(CREATED_BY as VARCHAR(16777216)) as CREATED_BY,
        cast(CREATE_DATE as TIMESTAMP_NTZ(9)) as CREATE_DATE,
        cast(UPDATED_BY as VARCHAR(16777216)) as UPDATED_BY,
        cast(UPDATE_DATE as TIMESTAMP_NTZ(9)) as UPDATE_DATE,
        cast(LAST_CONFIRM_DATE as TIMESTAMP_NTZ(9)) as LAST_CONFIRM_DATE,
        cast(JOB_CATEGORY as VARCHAR(16777216)) as JOB_CATEGORY,
        cast(FAB as VARCHAR(16777216)) as FAB,
        cast(PRODUCT_LINE as VARCHAR(16777216)) as PRODUCT_LINE,
        cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
    )
select * from type_data
{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='MATERIAL_MASTER_STORAGE_LOCATION_SEGMENT_HISTORY',
        unique_key = ['MANDT',
    'MATNR',
    'WERKS',
    'LGORT',
    'LFGJA',
    'LFMON'],
        transient=false
) }} 

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	MATNR,
	WERKS,
	LGORT,
	LFGJA,
	LFMON,
	LABST,
	UMLME,
	INSME,
	EINME,
	SPEME,
	RETME,
	VKLAB,
	VKUML
	FROM {{ source("SAP_ORACLE_LIVE", "MARDH") }}
),


transform_data as 
(
    SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	MATNR as MATNR,
	WERKS as WERKS,
	LGORT as LGORT,
	LFGJA as LFGJA,
	LFMON as LFMON,
	LABST as LABST,
	UMLME as UMLME,
	INSME as INSME,
	EINME as EINME,
	SPEME as SPEME,
	RETME as RETME,
	VKLAB as VKLAB,
	VKUML as VKUML
	FROM SOURCE_DATA
), 

type_data as 
(
    SELECT 
    CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	MATNR,
	WERKS,
	LGORT,
	LFGJA,
	LFMON,
	CAST(LABST AS NUMBER(38,10)) AS LABST,
	CAST(UMLME AS NUMBER(38,10)) AS UMLME,
	CAST(INSME AS NUMBER(38,10)) AS INSME,
	CAST(EINME AS NUMBER(38,10)) AS EINME,
	CAST(SPEME AS NUMBER(38,10)) AS SPEME,
	CAST(RETME AS NUMBER(38,10)) AS RETME,
	CAST(VKLAB AS NUMBER(38,10)) AS VKLAB,
	CAST(VKUML AS NUMBER(38,10)) AS VKUML
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='MATERIAL_DATA_FOR_EACH_WAREHOUSE_NUMBER',
        unique_key = ['MANDT',
    'MATNR',
    'LGNUM'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	MATNR,
	LGNUM,
	LVORM,
	LGBKZ,
	LTKZE,
	LTKZA,
	LHMG1,
	LHMG2,
	LHMG3,
	LHME1,
	LHME2,
	LHME3,
	LETY1,
	LETY2,
	LETY3,
	LVSME,
	KZZUL,
	BLOCK,
	KZMBF,
	BSSKZ,
	MKAPV,
	BEZME,
	PLKPT,
	VOMEM,
	L2SKR
	FROM {{source('SAP_ORACLE_LIVE', 'MLGN')}}
),


transform_data as 
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	MATNR as MATNR,
	LGNUM as LGNUM,
	LVORM as LVORM,
	LGBKZ as LGBKZ,
	LTKZE as LTKZE,
	LTKZA as LTKZA,
	LHMG1 as LHMG1,
	LHMG2 as LHMG2,
	LHMG3 as LHMG3,
	LHME1 as LHME1,
	LHME2 as LHME2,
	LHME3 as LHME3,
	LETY1 as LETY1,
	LETY2 as LETY2,
	LETY3 as LETY3,
	LVSME as LVSME,
	KZZUL as KZZUL,
	BLOCK as BLOCK,
	KZMBF as KZMBF,
	BSSKZ as BSSKZ,
	MKAPV as MKAPV,
	BEZME as BEZME,
	PLKPT as PLKPT,
	VOMEM as VOMEM,
	L2SKR as L2SKR
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	MATNR,
	LGNUM,
	LVORM,
	LGBKZ,
	LTKZE,
	LTKZA,
	CAST(LHMG1 AS NUMBER(38,10)) AS LHMG1,
	CAST(LHMG2 AS NUMBER(38,10)) AS LHMG2,
	CAST(LHMG3 AS NUMBER(38,10)) AS LHMG3,
	LHME1,
	LHME2,
	LHME3,
	LETY1,
	LETY2,
	LETY3,
	LVSME,
	KZZUL,
	BLOCK,
	KZMBF,
	BSSKZ,
	CAST(MKAPV AS NUMBER(38,10)) AS MKAPV,
	BEZME,
	PLKPT,
	VOMEM,
	L2SKR
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
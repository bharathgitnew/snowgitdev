{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='LANGUAGE_DEPENDENT_TEXTS_FOR_TABLE_TQ15',
        unique_key = ['MANDT',
    'SPRACHE',
    'KATALOGART'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	SPRACHE,
	KATALOGART,
	KATALOGTXT,
	SCHLAGWORT
	FROM {{source('SAP_ORACLE_LIVE', 'TQ15T')}}
),


transform_data as 
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	SPRACHE as SPRACHE,
	KATALOGART as KATALOGART,
	KATALOGTXT as KATALOGTXT,
	SCHLAGWORT as SCHLAGWORT
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	SPRACHE,
	KATALOGART,
	KATALOGTXT,
	SCHLAGWORT
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
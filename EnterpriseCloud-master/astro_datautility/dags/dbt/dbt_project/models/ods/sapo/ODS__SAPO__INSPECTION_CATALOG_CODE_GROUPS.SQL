{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='INSPECTION_CATALOG_CODE_GROUPS',
        unique_key = ['MANDT',
    'KATALOGART',
    'CODEGRUPPE'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	KATALOGART,
	CODEGRUPPE,
	ERSTELLER,
	E_DATUM,
	AENDERER,
	A_DATUM,
	VERWENDUNG,
	INAKTIV,
	STATUS
	FROM {{source('SAP_ORACLE_LIVE', 'QPGR')}}
),


transform_data as 
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	KATALOGART as KATALOGART,
	CODEGRUPPE as CODEGRUPPE,
	ERSTELLER as ERSTELLER,
	E_DATUM as E_DATUM,
	AENDERER as AENDERER,
	A_DATUM as A_DATUM,
	VERWENDUNG as VERWENDUNG,
	INAKTIV as INAKTIV,
	STATUS as STATUS
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	KATALOGART,
	CODEGRUPPE,
	ERSTELLER,
	E_DATUM,
	AENDERER,
	A_DATUM,
	VERWENDUNG,
	INAKTIV,
	STATUS
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	PROFID as PROFID,
	AENAM as AENAM,
	PROTECT as PROTECT,
	HIER_LEVEL as HIER_LEVEL,
	KZKAU as KZKAU,
	ADOBJ as ADOBJ,
	EXCMRPLOGIC as EXCMRPLOGIC,
	AVAILDATELOGIC as AVAILDATELOGIC,
	AVAILATPLOGIC as AVAILATPLOGIC,
	AVAILSSTOCK as AVAILSSTOCK,
	EXCQUANTITY as EXCQUANTITY,
	PR_MENDIF as PR_MENDIF,
	EXCDATE as EXCDATE,
	TATVZ as TATVZ,
	MEIVT as MEIVT,
	ERWVZ as ERWVZ,
	MEIVE as MEIVE,
	ADDMATERIAL as ADDMATERIAL,
	REORDER as REORDER,
	BULKMAT as BULKMAT,
	COBYPRODUCT as COBYPRODUCT,
	ADDELEMENT as ADDELEMENT,
	PIPELINE as PIPELINE,
	USEBUFFER as USEBUFFER,
	MLDELAY as MLDELAY,
	MLAPPROACH as MLAPPROACH,
	MLOPER as MLOPER,
	SLDELAY as SLDELAY,
	MLGREEN as MLGREEN,
	MLYELLOW as MLYELLOW,
	MLRED as MLRED
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	PROFID,
	AENAM,
	PROTECT,
	HIER_LEVEL,
	KZKAU,
	ADOBJ,
	EXCMRPLOGIC,
	AVAILDATELOGIC,
	AVAILATPLOGIC,
	AVAILSSTOCK,
	EXCQUANTITY,
	CAST(PR_MENDIF AS NUMBER(38,10)) AS PR_MENDIF,
	EXCDATE,
	TATVZ,
	MEIVT,
	ERWVZ,
	MEIVE,
	ADDMATERIAL,
	REORDER,
	BULKMAT,
	COBYPRODUCT,
	ADDELEMENT,
	PIPELINE,
	USEBUFFER,
	MLDELAY,
	MLAPPROACH,
	MLOPER,
	SLDELAY,
	CAST(MLGREEN AS NUMBER(38,10)) AS MLGREEN,

{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='BOM_HEADER',
        unique_key = ['MANDT',
    'STLTY',
    'STLNR',
    'STLAL',
    'STKOZ'],
        transient=false
) }}

with source_data as (
    select
		_CAPTUREDATETIME,
        MANDT as MANDT,
		STLTY as STLTY,
		STLNR as STLNR,
		STLAL as STLAL,
		STKOZ as STKOZ,
		DATUV as DATUV,
		TECHV as TECHV,
		AENNR as AENNR,
		LKENZ as LKENZ,
		LOEKZ as LOEKZ,
		VGKZL as VGKZL,
		ANDAT as ANDAT,
		ANNAM as ANNAM,
		AEDAT as AEDAT,
		AENAM as AENAM,
		BMEIN as BMEIN,
		BMENG as BMENG,
		CADKZ as CADKZ,
		LABOR as LABOR,
		LTXSP as LTXSP,
		STKTX as STKTX,
		STLST as STLST,
		WRKAN as WRKAN,
		DVDAT as DVDAT,
		DVNAM as DVNAM,
		AEHLP as AEHLP,
		ALEKZ as ALEKZ,
		GUIDX as GUIDX,
		VALID_TO as VALID_TO,
		VALID_TO_RKEY as VALID_TO_RKEY,
		ECN_TO as ECN_TO,
		ECN_TO_RKEY as ECN_TO_RKEY
    from {{source('SAP_ORACLE_LIVE', 'STKO')}}
),

transform_is_deleted as (
    select
		tgt._CAPTUREDATETIME,
		tgt._AUDIT_LOG_ID,
		tgt._ROW_HASH,
        tgt.MANDT,
		tgt.STLTY,
		tgt.STLNR,
		tgt.STLAL,
		tgt.STKOZ,
		tgt.DATUV,
		tgt.TECHV,
		tgt.AENNR,
		tgt.LKENZ,
		tgt.LOEKZ,
		tgt.VGKZL,
		tgt.ANDAT,
		tgt.ANNAM,
		tgt.AEDAT,
		tgt.AENAM,
		tgt.BMEIN,
		tgt.BMENG,
		tgt.CADKZ,
		tgt.LABOR,
		tgt.LTXSP,
		tgt.STKTX,
		tgt.STLST,
		tgt.WRKAN,
		tgt.DVDAT,
		tgt.DVNAM,
		tgt.AEHLP,
		tgt.ALEKZ,
		tgt.GUIDX,
		tgt.VALID_TO,
		tgt.VALID_TO_RKEY,
		tgt.ECN_TO,
		tgt.ECN_TO_RKEY
    from {{this}} tgt
    left join source_data src
    on tgt.MANDT=src.MANDT
	and tgt.STLTY=src.STLTY
	and tgt.STLNR=src.STLNR
	and tgt.STLAL=src.STLAL
	and tgt.STKOZ=src.STKOZ
	where src.MANDT is null
	and src.STLTY is null
	and src.STLNR is null
	and src.STLAL is null
	and src.STKOZ is null
),

transform_data as (
    select
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        MANDT,
		STLTY,
		STLNR,
		STLAL,
		STKOZ,
		DATUV,
		TECHV,
		AENNR,
		LKENZ,
		LOEKZ,
		VGKZL,
		ANDAT,
		ANNAM,
		AEDAT,
		AENAM,
		BMEIN,
		BMENG,
		CADKZ,
		LABOR,
		LTXSP,
		STKTX,
		STLST,
		WRKAN,
		DVDAT,
		DVNAM,
		AEHLP,
		ALEKZ,
		CAST(GUIDX AS VARCHAR) AS GUIDX,
		VALID_TO,
		VALID_TO_RKEY,
		ECN_TO,
		ECN_TO_RKEY,
		'No' as IS_DELETED
    from source_data
    union
    select
		_CAPTUREDATETIME,
		_AUDIT_LOG_ID,
		_ROW_HASH,
        MANDT,
		STLTY,
		STLNR,
		STLAL,
		STKOZ,
		DATUV,
		TECHV,
		AENNR,
		LKENZ,
		LOEKZ,
		VGKZL,
		ANDAT,
		ANNAM,
		AEDAT,
		AENAM,
		BMEIN,
		BMENG,
		CADKZ,
		LABOR,
		LTXSP,
		STKTX,
		STLST,
		WRKAN,
		DVDAT,
		DVNAM,
		AEHLP,
		ALEKZ,
		CAST(GUIDX AS VARCHAR) AS GUIDX,
		VALID_TO,
		VALID_TO_RKEY,
		ECN_TO,
		ECN_TO_RKEY,
		'Yes' as IS_DELETED
    from transform_is_deleted
),

type_data as (
    select
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        MANDT,
		STLTY,
		STLNR,
		STLAL,
		STKOZ,
		DATUV,
		TECHV,
		AENNR,
		LKENZ,
		LOEKZ,
		VGKZL,
		ANDAT,
		ANNAM,
		AEDAT,
		AENAM,
		BMEIN,
		cast(BMENG as NUMBER(38,10)) as BMENG,
		CADKZ,
		LABOR,
		LTXSP,
		STKTX,
		STLST,
		WRKAN,
		DVDAT,
		DVNAM,
		AEHLP,
		ALEKZ,
		CAST(GUIDX AS VARCHAR) AS GUIDX,
		VALID_TO,
		VALID_TO_RKEY,
		ECN_TO,
		ECN_TO_RKEY,
		IS_DELETED
    from transform_data
)
select * from type_data
{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='PLANNING_AND_ORGANIZATION_FILE',
        unique_key = ['MANDT',
    'PLVAR',
    'OTYPE',
    'OBJID',
    'INFTY',
    'SUBTY',
    'ISTAT',
    'PRIOX',
    'BEGDA',
    'ENDDA',
    'VARYF',
    'SEQNR'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	PLVAR,
	OTYPE,
	OBJID,
	INFTY,
	SUBTY,
	ISTAT,
	PRIOX,
	BEGDA,
	ENDDA,
	VARYF,
	SEQNR,
	AEDTM,
	UNAME,
	REASN,
	HISTO,
	ITXNR,
	VDATA
	FROM {{source('SAP_ORACLE_LIVE', 'PLOG')}}
),


transform_data as 
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	PLVAR as PLVAR,
	OTYPE as OTYPE,
	OBJID as OBJID,
	INFTY as INFTY,
	SUBTY as SUBTY,
	ISTAT as ISTAT,
	PRIOX as PRIOX,
	BEGDA as BEGDA,
	ENDDA as ENDDA,
	VARYF as VARYF,
	SEQNR as SEQNR,
	AEDTM as AEDTM,
	UNAME as UNAME,
	REASN as REASN,
	HISTO as HISTO,
	ITXNR as ITXNR,
	VDATA as VDATA
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	PLVAR,
	OTYPE,
	OBJID,
	INFTY,
	SUBTY,
	ISTAT,
	PRIOX,
	BEGDA,
	ENDDA,
	VARYF,
	SEQNR,
	AEDTM,
	UNAME,
	REASN,
	HISTO,
	ITXNR,
	CAST(VDATA as VARCHAR) as VDATA
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
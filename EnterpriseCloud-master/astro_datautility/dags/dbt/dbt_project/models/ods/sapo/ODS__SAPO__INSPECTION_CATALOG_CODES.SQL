{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='INSPECTION_CATALOG_CODES',
        unique_key = ['MANDT',
    'KATALOGART',
    'CODEGRUPPE',
    'CODE',
    'VERSION'],
        transient=false
) }}

with source_data as (
	SELECT 
	_CAPTUREDATETIME,
	MANDT,
	KATALOGART,
	CODEGRUPPE,
	CODE,
	VERSION,
	GUELTIGAB,
	FEHLKLASSE,
	ERSTELLER,
	E_DATUM,
	AENDERER,
	A_DATUM,
	INAKTIV,
	VERWENDUNG,
	GELOESCHT,
	FOLGEAKTI
	FROM {{source('SAP_ORACLE_LIVE', 'QPCD')}}
),


transform_data as 
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	KATALOGART as KATALOGART,
	CODEGRUPPE as CODEGRUPPE,
	CODE as CODE,
	VERSION as VERSION,
	GUELTIGAB as GUELTIGAB,
	FEHLKLASSE as FEHLKLASSE,
	ERSTELLER as ERSTELLER,
	E_DATUM as E_DATUM,
	AENDERER as AENDERER,
	A_DATUM as A_DATUM,
	INAKTIV as INAKTIV,
	VERWENDUNG as VERWENDUNG,
	GELOESCHT as GELOESCHT,
	FOLGEAKTI as FOLGEAKTI
	FROM SOURCE_DATA
), 

type_data as 
(
SELECT 
	CAST(_CAPTUREDATETIME AS TIMESTAMP_LTZ(9)) AS _CAPTUREDATETIME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MANDT,
	KATALOGART,
	CODEGRUPPE,
	CODE,
	VERSION,
	GUELTIGAB,
	FEHLKLASSE,
	ERSTELLER,
	E_DATUM,
	AENDERER,
	A_DATUM,
	INAKTIV,
	VERWENDUNG,
	GELOESCHT,
	FOLGEAKTI
FROM TRANSFORM_DATA
)
 
SELECT * FROM TYPE_DATA
(
SELECT
    _CAPTUREDATETIME,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
	MANDT as MANDT,
	TDOBJECT as TDOBJECT,
	TDNAME as TDNAME,
	TDID as TDID,
	TDSPRAS as TDSPRAS,
	TDTITLE as TDTITLE,
	TDFRELES as TDFRELES,
	TDFUSER as TDFUSER,
	TDFDATE as TDFDATE,
	TDFTIME as TDFTIME,

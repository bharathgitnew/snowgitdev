	TDMACODE2 as TDMACODE2,
	TDTXTLINES as TDTXTLINES,
	TDREF as TDREF,
	TDREFOBJ as TDREFOBJ,
	TDREFNAME as TDREFNAME,
	TDREFID as TDREFID,
	TDTEXTTYPE as TDTEXTTYPE,
	TDCOMPRESS as TDCOMPRESS,
	TDOCLASS as TDOCLASS,
	LOGSYS as LOGSYS
	FROM SOURCE_DATA
), 

type_data as 

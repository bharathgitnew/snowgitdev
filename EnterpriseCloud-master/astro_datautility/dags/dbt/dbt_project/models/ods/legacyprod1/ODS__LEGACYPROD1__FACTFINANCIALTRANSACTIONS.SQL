	SELECT 
		FINANCIALDOCUMENTLINEID,
		COMPANYKEY,
		CUSTOMERFINANCIALTRANSACTIONKEY,
		DEBITCREDITKEY,
		FINANCIALTRANSACTIONTYPEKEY,
		FINANCIALTRANSACTIONDATEKEY,

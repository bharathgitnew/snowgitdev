		FINANCIALSEGMENTKEY,
		FINANCIALPRODUCTTYPEKEY,
		OFFICEKEY,
		SEGMENTBUSINESSUNITKEY,
		AMOUNT,
		_HASHVALUE,
		_ROWSTATUSCODE,
		_CREATEDDATETIME,
		_CREATEDBY,
		_CREATEDEXECUTIONPERIODID,
		_CREATEDCONTAINERLOGID,
		_CREATEDLINEAGEID,
		_MODIFIEDDATETIME,
		_MODIFIEDBY,
		_MODIFIEDEXECUTIONPERIODID,
		_MODIFIEDCONTAINERLOGID,
		_MODIFIEDLINEAGEID,
		_ISDELETED, 

with source_data as
(
    SELECT
        _FILENAME,
        _FILEDATE,
        JSONFIELD:"Disposition" :: STRING AS DISPOSITION,
        JSONFIELD:"Message_ID" :: STRING AS MESSAGE_ID,
        JSONFIELD:"Message_Line_Nbr" :: STRING AS ROSETTANET_LINE_NUMBER,
        JSONFIELD:"Item_Code" :: STRING AS TEL_PART_NUMBER,
        JSONFIELD:"Customer_Item_Code" :: STRING AS CUSTOMER_PART_NUMBER,
        JSONFIELD:"Customer_Item_Desc" :: STRING AS CUSTOMER_PART_DESCRIPTION,
        JSONFIELD:"Qty" :: STRING AS QUANTITY,
        JSONFIELD:"Consumable" :: STRING AS CONSUMABLE_FLAG,
        JSONFIELD:"Processed" :: STRING AS TRANSFERRED_FLAG,
        JSONFIELD:"Reconciled" :: STRING AS RECONCILED_FLAG,
        JSONFIELD:"Customer_Stockroom" :: STRING AS STOCK_ROOM,
        JSONFIELD:"Warehouse" :: STRING AS WAREHOUSE,
        JSONFIELD:"Customer_Trans_Type" :: STRING AS TRANSACTION_TYPE,
        JSONFIELD:"Customer_Trans_Reason" :: STRING AS TRANSACTION_REASON,
        JSONFIELD:"Baan_Order_Origin" :: STRING AS ORDER_ORIGIN,
        JSONFIELD:"Baan_Order_Nbr" :: STRING AS SERVICE_ORDER_NUMBER,
        JSONFIELD:"Baan_Order_Line_Nbr" :: STRING AS POSITION_NUMBER,
        JSONFIELD:"Local_Consumption_Dt" :: STRING AS DATE_CONSUMED,
        JSONFIELD:"Message_Dt" :: STRING AS DATE_RECEIVED,
        JSONFIELD:"Contact" :: STRING AS CONTACT_NAME,
        JSONFIELD:"Contact_Phone" :: STRING AS CONTACT_PHONE,
        JSONFIELD:"Additional_Info" :: STRING AS CONTACT_EMAIL,
        JSONFIELD:"Error_Message" :: STRING AS ERROR_MESSAGE,
        JSONFIELD:"Customer_Factory" :: STRING AS FACTORY_NAME,
        JSONFIELD:"Error" :: STRING AS ERROR_FLAG,
        JSONFIELD:"Serial_Nbr" :: STRING AS SERIAL_NUMBER,
        JSONFIELD:"Process_Dt" :: STRING AS TRANSFERRED_DATE,
        JSONFIELD:"Customer_Trans_ID" :: STRING AS CUSTOMER_TRANSACTION_ID,
        JSONFIELD:"Customer_Trans_Line_Nbr" :: STRING AS CUSTOMER_TRANSACTION_LINE_ID,
        JSONFIELD:"NCDR_Nbr" :: STRING AS NCDR_NUMBER,
        JSONFIELD:"PIP" :: STRING AS ROSETTANET_PIP,
        JSONFIELD:"Customer_Ref_1" :: STRING AS WIINGS_ISSUE_ID
    FROM {{ source("ROSETTA", "RN_CONSIGNMENT_TRANSACTION") }}
    WHERE _FILEDATE = (SELECT MAX(_FILEDATE) FROM {{ source("ROSETTA", "RN_CONSIGNMENT_TRANSACTION") }}  )
)
,transform_data as
(
    SELECT
        _FILENAME,
        _FILEDATE,
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        DISPOSITION,
        MESSAGE_ID,
        ROSETTANET_LINE_NUMBER,
        TEL_PART_NUMBER,
        CUSTOMER_PART_NUMBER,
        CUSTOMER_PART_DESCRIPTION,
        QUANTITY,
        CONSUMABLE_FLAG,
        TRANSFERRED_FLAG,
        RECONCILED_FLAG,
        STOCK_ROOM,
        WAREHOUSE,
        TRANSACTION_TYPE,
        TRANSACTION_REASON,
        ORDER_ORIGIN,
        SERVICE_ORDER_NUMBER,
        POSITION_NUMBER,
        DATE_CONSUMED,
        DATE_RECEIVED,
        CONTACT_NAME,
        CONTACT_PHONE,
        CONTACT_EMAIL,
        ERROR_MESSAGE,
        FACTORY_NAME,
        ERROR_FLAG,
        SERIAL_NUMBER,
        TRANSFERRED_DATE,
        CUSTOMER_TRANSACTION_ID,
        CUSTOMER_TRANSACTION_LINE_ID,
        NCDR_NUMBER,
        ROSETTANET_PIP,
        WIINGS_ISSUE_ID
    FROM source_data
),

type_data as (
    SELECT
        CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(DISPOSITION AS VARCHAR(16777216)) AS DISPOSITION,
        CAST(MESSAGE_ID AS VARCHAR(16777216)) AS MESSAGE_ID,
        CAST(ROSETTANET_LINE_NUMBER AS VARCHAR(16777216)) AS ROSETTANET_LINE_NUMBER,
        CAST(TEL_PART_NUMBER AS VARCHAR(16777216)) AS TEL_PART_NUMBER,
        CAST(CUSTOMER_PART_NUMBER AS VARCHAR(16777216)) AS CUSTOMER_PART_NUMBER,
        CAST(CUSTOMER_PART_DESCRIPTION AS VARCHAR(16777216)) AS CUSTOMER_PART_DESCRIPTION,
        CAST(QUANTITY AS VARCHAR(16777216)) AS QUANTITY,
        CAST(CONSUMABLE_FLAG AS VARCHAR(16777216)) AS CONSUMABLE_FLAG,
        CAST(TRANSFERRED_FLAG AS VARCHAR(16777216)) AS TRANSFERRED_FLAG,
        CAST(RECONCILED_FLAG AS VARCHAR(16777216)) AS RECONCILED_FLAG,
        CAST(STOCK_ROOM AS VARCHAR(16777216)) AS STOCK_ROOM,
        CAST(WAREHOUSE AS VARCHAR(16777216)) AS WAREHOUSE,
        CAST(TRANSACTION_TYPE AS VARCHAR(16777216)) AS TRANSACTION_TYPE,
        CAST(TRANSACTION_REASON AS VARCHAR(16777216)) AS TRANSACTION_REASON,
        CAST(ORDER_ORIGIN AS VARCHAR(16777216)) AS ORDER_ORIGIN,
        CAST(SERVICE_ORDER_NUMBER AS VARCHAR(16777216)) AS SERVICE_ORDER_NUMBER,
        CAST(POSITION_NUMBER AS VARCHAR(16777216)) AS POSITION_NUMBER,
        CAST(DATE_CONSUMED AS VARCHAR(16777216)) AS DATE_CONSUMED,
        CAST(DATE_RECEIVED AS VARCHAR(16777216)) AS DATE_RECEIVED,
        CAST(CONTACT_NAME AS VARCHAR(16777216)) AS CONTACT_NAME,
        CAST(CONTACT_PHONE AS VARCHAR(16777216)) AS CONTACT_PHONE,
        CAST(CONTACT_EMAIL AS VARCHAR(16777216)) AS CONTACT_EMAIL,
        CAST(ERROR_MESSAGE AS VARCHAR(16777216)) AS ERROR_MESSAGE,
        CAST(FACTORY_NAME AS VARCHAR(16777216)) AS FACTORY_NAME,
        CAST(ERROR_FLAG AS VARCHAR(16777216)) AS ERROR_FLAG,
        CAST(SERIAL_NUMBER AS VARCHAR(16777216)) AS SERIAL_NUMBER,
        CAST(TRANSFERRED_DATE AS VARCHAR(16777216)) AS TRANSFERRED_DATE,
        CAST(CUSTOMER_TRANSACTION_ID AS VARCHAR(16777216)) AS CUSTOMER_TRANSACTION_ID,
        CAST(CUSTOMER_TRANSACTION_LINE_ID AS VARCHAR(16777216)) AS CUSTOMER_TRANSACTION_LINE_ID,
        CAST(NCDR_NUMBER AS VARCHAR(16777216)) AS NCDR_NUMBER,
        CAST(ROSETTANET_PIP AS VARCHAR(16777216)) AS ROSETTANET_PIP,
        CAST(WIINGS_ISSUE_ID AS VARCHAR(16777216)) AS WIINGS_ISSUE_ID
    FROM transform_data
)


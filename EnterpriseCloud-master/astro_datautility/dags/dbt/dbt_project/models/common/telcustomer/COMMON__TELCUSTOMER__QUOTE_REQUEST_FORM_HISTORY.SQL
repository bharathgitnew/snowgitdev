with source_data as
(
    SELECT 
        TEL_QUOTE_ID, 
        REQUEST_NUMBER, 
        REV, 
        REQUEST_DATE, 
        PUBLISH_DATE_REGION, 
        APPROVAL_DATE_REGION, 
        CANCEL_DATE, 
        STATUS_DATE, 
        REQUEST_REVISION_DATE, 
        REQUEST_REVISION_NAME, 
        REQUESTOR, 
        ACTIVE, 
        STATUS, 
        QUOTE_TYPE, 
        QUOTE_CURRENCY, 
        QUOTE_AMT, 
        PRODUCT_LINE, 
        FAB, 
        CATEGORY, 
        MODEL, 
        NODES, 
        REFERENCE_1, 
        DESCRIPTION, 
        TEL_QUOTE_NODE_PROCESS, 
        SPECIFIC_REQUEST_TYPE, 
        COMPANY, 
        BIS_CUSTOMER_CODE, 
        TIERED, 
        LEAD_TIME_UNIT, 
        LEAD_TIME,
        ESA,
        TEL_QUOTE_STATUS
FROM 
  {{ ref('ODS__TELCUSTOMER__TELCUST_ARF_QRF_DATA') }}
WHERE 
  REQTYPE = 'QRF'

)
/**************  TRANSFORMS **************/
, transform_data AS
(
    SELECT 
        DISTINCT TEL_QUOTE_ID AS TEL_QUOTE_ID , 
        REQUEST_NUMBER AS REQUEST_NUMBER , 
        TEL_QUOTE_ID || '-' || REQUEST_NUMBER AS QRF_KEY, 
        LPAD(REV, 2, '00') AS QUOTE_REQUEST_REVISION_NUMBER, 
        TEL_QUOTE_ID || '-' || REQUEST_NUMBER || '-' || LPAD(REV, 2, '00') AS QRF_QUOTE_STATUS_KEY, 
        CASE WHEN REV = '0' THEN TO_DATE(REQUEST_DATE) ELSE TO_DATE(PUBLISH_DATE_REGION) END AS QRF_INTEL_REQUEST_DATE, 
        TO_DATE(PUBLISH_DATE_REGION) as QRF_TEL_PUBLISH_DATE, 
        TO_DATE(APPROVAL_DATE_REGION) as QRF_INTEL_APPROVAL_DATE, 
        TO_DATE(CANCEL_DATE) AS QRF_CANCEL_DATE, 
        TO_DATE(STATUS_DATE) AS QRF_STATUS_DATE, 
        TO_DATE(REQUEST_REVISION_DATE) AS QRF_REVISION_DATE, 
        UPPER(REQUEST_REVISION_NAME) AS QRF_REVISION_NAME, 
        DATEDIFF(
            DAY, REQUEST_DATE, PUBLISH_DATE_REGION
        ) as QRF_TEL_PUBLISH_DAYS, 
        DATEDIFF(
            DAY, PUBLISH_DATE_REGION, APPROVAL_DATE_REGION
        ) as QRF_INTEL_APPROVAL_DAYS, 
        UPPER(REQUESTOR) AS QRF_REQUESTOR, 
        UPPER(STATUS) as QRF_REQUEST_STATUS, 
        CASE WHEN UPPER(ACTIVE) = 'YES' THEN 'ACTIVE' 
        WHEN UPPER(ACTIVE) = 'NO' THEN 'DNO'
        WHEN UPPER(ACTIVE) = 'YES/NO' THEN 'ACTIVE/DNO'
        ELSE NULL
        END AS QUOTE_STATUS, 
        UPPER(STATUS) AS QUOTE_STATUS_VALIDATION, 
        UPPER(QUOTE_TYPE) AS QRF_QUOTE_TYPE, 
        QUOTE_CURRENCY AS QUOTE_CURRENCY, 
        QUOTE_AMT  AS QUOTE_AMT, 
        PRODUCT_LINE as BUSINESS_UNIT, 
        UPPER(FAB) AS SITE, 
        UPPER(CATEGORY) AS CATEGORY, 
        UPPER(MODEL) AS MODEL, 
        UPPER(NODES) AS PROCESS, 
        UPPER(REFERENCE_1) AS TEL_DESCRIPTION, 
        UPPER(DESCRIPTION)  AS INTEL_DESCRIPTION, 
        TEL_QUOTE_NODE_PROCESS AS TEL_QUOTE_NODE_PROCESS , 
        UPPER(SPECIFIC_REQUEST_TYPE) AS SPECIFIC_REQUEST_TYPE, 
        UPPER(COMPANY)  AS CLIENT, 
        BIS_CUSTOMER_CODE AS CLIENT_CODE, 
        TIERED   AS TIERED , 
        LEAD_TIME_UNIT   AS LEAD_TIME_UNIT , 
        LEAD_TIME  AS LEAD_TIME ,
        ESA AS EQUIPMENT_SPECIFIC_ADDENDUM,
        TEL_QUOTE_STATUS,
         '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH -- Adds column to table on full refresh.
FROM 
  source_data 
)
,type_data as 
(
    select
		cast(TEL_QUOTE_ID as VARCHAR(16777216)) as TEL_QUOTE_ID,
		cast(REQUEST_NUMBER as NUMBER(38,0)) as REQUEST_NUMBER,
		cast(QRF_KEY as VARCHAR(16777216)) as QRF_KEY,
		cast(QUOTE_REQUEST_REVISION_NUMBER as VARCHAR(16777216)) as QUOTE_REQUEST_REVISION_NUMBER,
		cast(QRF_QUOTE_STATUS_KEY as VARCHAR(16777216)) as QRF_QUOTE_STATUS_KEY,
		cast(QRF_INTEL_REQUEST_DATE as DATE) as QRF_INTEL_REQUEST_DATE,
		cast(QRF_TEL_PUBLISH_DATE as DATE) as QRF_TEL_PUBLISH_DATE,
		cast(QRF_INTEL_APPROVAL_DATE as DATE) as QRF_INTEL_APPROVAL_DATE,
		cast(QRF_CANCEL_DATE as DATE) as QRF_CANCEL_DATE,
		cast(QRF_STATUS_DATE as DATE) as QRF_STATUS_DATE,
		cast(QRF_REVISION_DATE as DATE) as QRF_REVISION_DATE,
		cast(QRF_REVISION_NAME as VARCHAR(16777216)) as QRF_REVISION_NAME,
		cast(QRF_TEL_PUBLISH_DAYS as NUMBER(9,0)) as QRF_TEL_PUBLISH_DAYS,
		cast(QRF_INTEL_APPROVAL_DAYS as NUMBER(9,0)) as QRF_INTEL_APPROVAL_DAYS,
		cast(QRF_REQUESTOR as VARCHAR(16777216)) as QRF_REQUESTOR,
		cast(QRF_REQUEST_STATUS as VARCHAR(16777216)) as QRF_REQUEST_STATUS,
		cast(QUOTE_STATUS as VARCHAR(16777216)) as QUOTE_STATUS,
		cast(QUOTE_STATUS_VALIDATION as VARCHAR(16777216)) as QUOTE_STATUS_VALIDATION,
		cast(QRF_QUOTE_TYPE as VARCHAR(16777216)) as QRF_QUOTE_TYPE,
		cast(QUOTE_CURRENCY as VARCHAR(16777216)) as QUOTE_CURRENCY,
		cast(QUOTE_AMT as NUMBER(38,0)) as QUOTE_AMT,
		cast(BUSINESS_UNIT as VARCHAR(16777216)) as BUSINESS_UNIT,
		cast(SITE as VARCHAR(16777216)) as SITE,
		cast(CATEGORY as VARCHAR(16777216)) as CATEGORY,
		cast(MODEL as VARCHAR(16777216)) as MODEL,
		cast(PROCESS as VARCHAR(16777216)) as PROCESS,
		cast(TEL_DESCRIPTION as VARCHAR(16777216)) as TEL_DESCRIPTION,
		cast(INTEL_DESCRIPTION as VARCHAR(16777216)) as INTEL_DESCRIPTION,
		cast(TEL_QUOTE_NODE_PROCESS as VARCHAR(16777216)) as TEL_QUOTE_NODE_PROCESS,
		cast(SPECIFIC_REQUEST_TYPE as VARCHAR(16777216)) as SPECIFIC_REQUEST_TYPE,
		cast(CLIENT as VARCHAR(16777216)) as CLIENT,
		cast(CLIENT_CODE as VARCHAR(16777216)) as CLIENT_CODE,
		cast(TIERED as VARCHAR(16777216)) as TIERED,
		cast(LEAD_TIME_UNIT as VARCHAR(16777216)) as LEAD_TIME_UNIT,
		cast(LEAD_TIME as VARCHAR(16777216)) as LEAD_TIME,
    cast(EQUIPMENT_SPECIFIC_ADDENDUM as VARCHAR(16777216)) as EQUIPMENT_SPECIFIC_ADDENDUM,
    cast(TEL_QUOTE_STATUS as VARCHAR(16777216)) as TEL_QUOTE_STATUS,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
    cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
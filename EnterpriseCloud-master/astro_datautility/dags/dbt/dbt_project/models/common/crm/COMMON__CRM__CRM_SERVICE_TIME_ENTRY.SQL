{{ config(
        alias = 'CRM_SERVICE_TIME_ENTRY',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with CRM_WORKORDER_REF as (
	select * from {{ ref('COMMON__CRM__WORKORDER') }}
 	
 ),
MSDYN_WORKORDERSERVICE_REF as (
	select * from {{ ref('ODS__CRM_FILE__MSDYN_WORKORDERSERVICE') }}
 	WHERE ISDELETE is NULL
),
GLOBALOPTIONSETMETADATA_REF as (
	select * from {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }}
 	
),
MSDYN_TIMEENTRY_REF as (
	select * from {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }}
 	WHERE ISDELETE is NULL
),
 source_data as (
    SELECT DISTINCT
            WO.MSDYN_NAME
            ,WO.WO_WOTITLE AS WO_TITLE
            ,WO.CREATEDON as WO_CREATED_ON
            ,WO.CREATEDBYYOMINAME AS WO_CREATOR
            ,TEL_WO_MAINCATEGORY_SOREQUEST
            ,G.LOCALIZEDLABEL AS WO_MAINCATEGORY
            ,TEL_WO_SUBCATEGORY_SOREQUESTNAME AS WO_SUBCATEGORY
            ,TEL_WO_SERVICEORDERNO_3200 AS SAP_SERVICE_ORDER
            ,MSDYN_SUBSTATUSNAME AS STATUS
            ,MAX(WOS_R.MSDYN_UNITAMOUNT) OVER(PARTITION BY WO.WORK_ORDER_ID,WO.TEL_WO_SERVICEORDERNO_3200) AS CRM_REG_RATE
            ,MAX(WOS_OT.MSDYN_UNITAMOUNT) OVER(PARTITION BY WO.WORK_ORDER_ID,WO.TEL_WO_SERVICEORDERNO_3200) AS CRM_OT_RATE
            ,COUNT(T.ID)  OVER(PARTITION BY WORK_ORDER_ID,TEL_WO_SERVICEORDERNO_3200) AS CRM_TIME_ENTRIES -- filter this on 4/28 forward.
            ,SUM(T.WO_DURATION_HR) OVER(PARTITION BY WORK_ORDER_ID,TEL_WO_SERVICEORDERNO_3200) AS CRM_HOURS  -- filter this on 4/28 forward.
            ,MIN(CAST(T.CREATEDON AS DATE)) OVER(PARTITION BY WO.WORK_ORDER_ID,WO.TEL_WO_SERVICEORDERNO_3200) AS FIRST_TIME_ENTRY
            ,MAX(CAST(T.CREATEDON AS DATE)) OVER(PARTITION BY WO.WORK_ORDER_ID,WO.TEL_WO_SERVICEORDERNO_3200) AS LAST_TIME_ENTRY
            ,WO.CREATEDBY AS CREATEDBY
   FROM CRM_WORKORDER_REF WO
   LEFT OUTER JOIN GLOBALOPTIONSETMETADATA_REF G
       ON WO.TEL_WO_MAINCATEGORY_SOREQUEST = G.OPTION
            AND G.LOCALIZEDLABELLANGUAGECODE = '1033' AND G.OPTIONSETNAME = 'wo_maincategory_options'
   LEFT OUTER JOIN MSDYN_TIMEENTRY_REF T
        ON try_to_number(T.WO_WORKORDERNONAME) = try_to_number(WO.MSDYN_NAME) AND T.OWNINGBUSINESSUNITNAME = 'US'
            AND T.WO_DELETE_FLG = 'FALSE' AND T.CREATEDON > '2023-04-28'  -- may need TO be removed later
   LEFT OUTER JOIN MSDYN_WORKORDERSERVICE_REF WOS_R
        ON WOS_R.MSDYN_WORKORDER = T.WO_WORKORDERNO
            AND WOS_R.WO_RESOURCE = T.MSDYN_BOOKABLERESOURCE and WOS_R.MSDYN_SERVICENAME = 'Field Engineer Regular Charge Work'
   LEFT OUTER JOIN MSDYN_WORKORDERSERVICE_REF WOS_OT
        ON WOS_OT.MSDYN_WORKORDER = T.WO_WORKORDERNO
            AND WOS_OT.WO_RESOURCE = T.MSDYN_BOOKABLERESOURCE AND WOS_OT.MSDYN_SERVICENAME = 'Field Engineer Over Time Charge Work'
),

transform_data as (
    SELECT
        MSDYN_NAME,
        WO_TITLE,
        WO_CREATED_ON,
        WO_CREATOR,
        TEL_WO_MAINCATEGORY_SOREQUEST,
        WO_MAINCATEGORY,
        WO_SUBCATEGORY,
        SAP_SERVICE_ORDER,
        STATUS,
        CRM_REG_RATE,
        CRM_OT_RATE,
        CRM_TIME_ENTRIES,
        CRM_HOURS,
        FIRST_TIME_ENTRY,
        LAST_TIME_ENTRY,
        CREATEDBY,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    from source_data
),

type_data as (
    select 
        cast(MSDYN_NAME as VARCHAR(16777216)) as MSDYN_NAME, 
        cast(WO_TITLE as VARCHAR(16777216)) as WO_TITLE, 
        cast(WO_CREATED_ON as VARCHAR(16777216)) as WO_CREATED_ON, 
        cast(WO_CREATOR as VARCHAR(16777216)) as WO_CREATOR, 
        cast(TEL_WO_MAINCATEGORY_SOREQUEST as VARCHAR(16777216)) as TEL_WO_MAINCATEGORY_SOREQUEST, 
        cast(WO_MAINCATEGORY as VARCHAR(16777216)) as WO_MAINCATEGORY, 
        cast(WO_SUBCATEGORY as VARCHAR(16777216)) as WO_SUBCATEGORY, 
        cast(SAP_SERVICE_ORDER as VARCHAR(16777216)) as SAP_SERVICE_ORDER, 
        cast(STATUS as VARCHAR(16777216)) as STATUS, 
        cast(CRM_REG_RATE as VARCHAR(16777216)) as CRM_REG_RATE, 
        cast(CRM_OT_RATE as VARCHAR(16777216)) as CRM_OT_RATE, 
        cast(CRM_TIME_ENTRIES as VARCHAR(16777216)) as CRM_TIME_ENTRIES, 
        cast(CRM_HOURS as VARCHAR(16777216)) as CRM_HOURS, 
        cast(FIRST_TIME_ENTRY as VARCHAR(16777216)) as FIRST_TIME_ENTRY, 
        cast(LAST_TIME_ENTRY as VARCHAR(16777216)) as LAST_TIME_ENTRY,
        CAST(CREATEDBY AS VARCHAR(16777216)) AS CREATEDBY, 
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        
    from transform_data
)

select * from type_data
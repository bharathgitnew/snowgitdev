,BU AS
(
    SELECT
        BU_SOURCE_KEY
        ,BU_GROUP
        ,BU_GROUP_LEADER
    -- FROM ODS.FILE.SERVICE_BUSINESS_UNIT_MAPPING
    FROM {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }}
)
,MACHINE_HISTORY AS
(
    SELECT
        OPTION
        ,LOCALIZEDLABEL AS MACHINE_HISTORY_REASON
    -- FROM ODS.CRM_FILE.GLOBALOPTIONSETMETADATA
    FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }}

    WHERE 1=1
    AND OPTIONSETNAME = 'tel_wo_machinehistory'
    AND LOCALIZEDLABELLANGUAGECODE = '1033'
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY OPTION ORDER BY LOCALIZEDLABEL DESC) = 1)
)
,WARRANTY_STATUS AS
(
    SELECT
        OPTION
        ,LOCALIZEDLABEL AS WARRANTY_STATUS
    -- FROM  ODS.CRM_FILE.GLOBALOPTIONSETMETADATA
    FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }}
    WHERE 1 =1
    AND OPTIONSETNAME = 'com_machinewarrantystatus_en_options'
    AND LOCALIZEDLABELLANGUAGECODE = '1033'
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY OPTION ORDER BY LOCALIZEDLABEL DESC) = 1)
)

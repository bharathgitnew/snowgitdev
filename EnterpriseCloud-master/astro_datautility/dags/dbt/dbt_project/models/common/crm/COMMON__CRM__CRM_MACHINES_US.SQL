    FROM {{ ref('ODS__CRM_FILE__MSDYN_CUSTOMERASSET') }}

    WHERE 1 =1
    AND STATECODE = 0
    QUALIFY(ROW_NUMBER() OVER (PARTITION BY MSDYN_NAME ORDER BY VERSIONNUMBER DESC) = 1)

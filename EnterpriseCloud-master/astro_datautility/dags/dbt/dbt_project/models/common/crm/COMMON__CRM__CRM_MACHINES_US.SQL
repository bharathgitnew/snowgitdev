        ,TEL_COM_STARTUP_HOOKUP_START_DATE AS SU_HOOKUP_START
        ,COM_SL1FINISHDATE AS SL1_FINISH
        ,COM_SL2FINISHDATE AS SL2_FINISH
        ,COM_HWSTARTUPSTARTDATE AS HW_STARTUP_START
        ,COM_HWSTARTUPENDDATE AS HW_STARTUP_END
        ,COM_MACHINEHANDLEDATE AS HANDED_TO_CUSTOMER_DATE
        ,TEL_COM_SIGN_DATE AS SIGN_DATE
        ,TEL_COM_SIGN_LATEST_DATE AS LATEST_SIGN_DATE
        ,COM_NISSALESDATE AS NIS_SALES_DATE
        ,COM_INSPECTDATE AS TECHNICAL_ACCEPTANCE_DATE
        ,COM_ISFREEPERIODSTART AS WARRANTY_START
        ,COM_ISFREEPERIODEND AS WARRANTY_END
        ,COM_INSPECTLATESTDATE AS LATEST_INSPECTED_DATE
        ,TEL_COM_SAP_SALES_DOCUMENT_NO AS SAP_SALES_DOCUMENT
        ,TEL_COM_SAP_ITEM_NO AS SAP_ITEM_NO
        ,TEL_COM_SAP_CONSULTING_NO AS SAP_CONSULTATION_NO
        ,COM_PROJECTNO AS PROJECT_NUMBER
        ,COM_TELPONO AS TEL_PO
        ,CASE
            WHEN UPPER(COM_FLG_CONTRACT) = 'TRUE' THEN 'Contractable'
            ELSE 'Not Contractable' END AS CONTRACTABLE_FLAG
        ,COM_PROCESSNAME_EN AS PROCESS_NAME
        ,COM_CUSTOMERBY9DIGITSNAME AS CUSTOMER9_NAME
        ,COM_TOOLID_JP AS CUSTOMER_TOOL_ID_JP
        ,COM_NISPRODUCTNAME_EN AS NIS_PRODUCT_NAME
        ,COM_SALESSTATIONREGION_EN AS SALES_REGION
        ,MSDYN_CUSTOMERASSETID AS CUSTOMER_ASSET_ID
        ,MSDYN_ACCOUNT
        ,COM_CUSTOMERBY9DIGITS
        ,CREATEDON AS RECORD_CREATED_DATE
        ,COM_HISTORYREASON_EN_OPTIONS
        ,COM_MACHINEWARRANTYSTATUS_EN_OPTIONS
        ,TEL_COM_2DIGITSBUID
        ,STATECODE
        ,STATUSCODE
        ,COM_MACHINEID AS WISDOM_MACHINE_ID
        ,COM_CLUSTERNAME AS CLUSTER_NAME
        ,COM_CSTSALESSTANDARDS AS SALES_BASIS
        ,COALESCE(MSDYN_MASTERASSETNAME,MSDYN_NAME) AS PARENT_SN
        ,COM_LOCATION AS INSTALL_LOCATION
        ,CASE
            WHEN UPPER(COM_SWLHSYSTEMTYPE) LIKE '%INGEN%' THEN 'Software'
            ELSE  'Tool'
            END AS MACHINE_CATEGORY

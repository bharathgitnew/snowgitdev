WITH ACCOUNT AS
(
    SELECT
        ACCOUNT.ACCOUNTID AS ACCOUNT_ID
        ,ACCOUNT.ACCOUNTNUMBER
        ,ACCOUNT.NAME
        ,ACCOUNT.TEL_COM_COUNTRYNAME
        ,ACCOUNT.COM_PLACE_E_NAME
        ,ACCOUNT.COM_REGIONNAME AS REGION
        ,ACCOUNT.PARENTACCOUNTID
        ,PARENT.ACCOUNTNUMBER AS PARENT_ACCOUNT_NUMBER
        ,ACCOUNT.PARENTACCOUNTIDNAME
        ,ACCOUNT.TEL_COM_SEARCH_TERM_2_EN
        ,ACCOUNT.ADDRESS2_STATEORPROVINCE
        ,ACCOUNT.TEL_COM_CUSTOMER_GROUP_1NAME AS CUSTOMER_GROUP_CRM
    -- FROM ODS.CRM_FILE.ACCOUNT ACCOUNT
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }} ACCOUNT
    -- LEFT OUTER JOIN ODS.CRM_FILE.ACCOUNT PARENT
    LEFT OUTER JOIN {{ ref('ODS__CRM_FILE__ACCOUNT') }} PARENT
    ON ACCOUNT.PARENTACCOUNTID = PARENT.ACCOUNTID
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY ACCOUNT.ACCOUNTID ORDER BY PARENT.ACCOUNTNUMBER) = 1)
)
,CUSTOMER_GROUP AS
(
    SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    -- FROM ODS.FILE.CUSTOMER_GROUP_MAPPING
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_GROUP_MAPPING') }}
    WHERE LEN(ACCOUNT_NUMBER) > 1
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY ACCOUNT_NUMBER ORDER BY CUSTOMER_GROUP) = 1)
)
,CUSTOMERASSET AS
(
    SELECT
        MSDYN_ACCOUNTNAME AS ACCOUNT_NAME
        ,MSDYN_NAME AS SERIAL_NUMBER
        ,COM_TOOLID_EN AS CUSTOMER_TOOL_ID
        ,COM_PRODUCTLINENAME AS PRODUCT_LINE_CRM
        ,TEL_COM_SAP_PRODUCT_CODE AS PRODUCT_CODE_CRM
        ,COM_SUPPLIERCODE AS SUPPLIER_CODE
        ,COM_SWLHSYSTEMTYPE AS SWLH_MODEL
        ,COM_PRODUCTMODELNAME AS MODEL_NAME
        ,COM_SYSTEMIDNAME AS SYSTEM_NAME
        ,COM_NISPRODUCTFAMILYCODE AS MODEL_CODE
        ,COM_WAFERPANELSIZE AS WAFER_SIZE
        ,CASE
            WHEN COM_STARTUPSTATUS_EN LIKE 'Start-up対象外' THEN 'Start-up'
            ELSE COM_STARTUPSTATUS_EN
            END AS STARTUP_STATUS
        ,COM_CLUSTERFLG AS CLUSTER_FLAG
        ,CASE
            WHEN COM_CLUSTERFLG = '1' THEN 'Independent Machine'
            WHEN COM_CLUSTERFLG = '2' THEN 'Parent Machine'
            WHEN COM_CLUSTERFLG = '3' THEN 'Child Machine'
            ELSE COM_CLUSTERFLG || '*Not Defined - '
            END AS MACHINE_CLUSTER_TYPE
        ,CASE
            WHEN COM_CLUSTERFLG = '3' THEN 'N'
            ELSE 'Y' END AS MAIN_TOOL_FLAG
        ,COM_FACTORYSHIPDATE AS FACTORY_SHIP_DATE
        ,COM_MAINUNITSHIPPINGDATE AS MAIN_UNIT_SHIP_DATE
        ,COM_TELPLACEMENTSTARTDATE AS TEL_DELIVERY_START
        ,COM_TELPLACEMENTENDDATE AS TEL_DELIVERY_END

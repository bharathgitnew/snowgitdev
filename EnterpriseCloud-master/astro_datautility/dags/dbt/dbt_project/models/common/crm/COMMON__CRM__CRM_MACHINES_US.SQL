        ,SECONDARY_CONTACTID
        ,STATECODE
        ,STATUSCODE
        ,CUSTOMER_ASSET_ID
        ,MSDYN_ACCOUNT AS B_CODE_ID
        ,COM_CUSTOMERBY9DIGITS AS D_CODE_ID
        ,CASE
            WHEN WISDOM.WISDOM_SN IS NULL THEN 'Not in Wisdom'
            ELSE 'In Wisdom'
            END AS WISDOM_FLAG
        ,WISDOM_CUSTOMER_B
        ,CASE
            WHEN WISDOM.WISDOM_SN IS NOT NULL AND WISDOM_CUSTOMER_B =  ACCOUNT.ACCOUNTNUMBER THEN 'Y'
            ELSE 'N'
            END AS WISDOM_LOCATION_MATCH
    FROM CUSTOMERASSET
    LEFT OUTER JOIN ACCOUNT
    ON ACCOUNT.ACCOUNT_ID = CUSTOMERASSET.MSDYN_ACCOUNT
    LEFT OUTER JOIN ACCOUNT DCODE
    ON DCODE.ACCOUNT_ID = CUSTOMERASSET.COM_CUSTOMERBY9DIGITS
    LEFT OUTER JOIN CUSTOMER_GROUP
    ON CUSTOMER_GROUP.ACCOUNT_NUMBER = ACCOUNT.ACCOUNTNUMBER
    LEFT OUTER JOIN BU
    ON BU.BU_SOURCE_KEY = CUSTOMERASSET.SUPPLIER_CODE
    AND BU.BU_GROUP = CUSTOMERASSET.PRODUCT_LINE_CRM
    LEFT OUTER JOIN MACHINE_HISTORY
    ON MACHINE_HISTORY.OPTION = CUSTOMERASSET.COM_HISTORYREASON_EN_OPTIONS
    LEFT OUTER JOIN WARRANTY_STATUS
    ON WARRANTY_STATUS.OPTION = CUSTOMERASSET.COM_MACHINEWARRANTYSTATUS_EN_OPTIONS
    LEFT OUTER JOIN TWODIGITBU
    ON TWODIGITBU.ID = TEL_COM_2DIGITSBUID
    LEFT OUTER JOIN SAPCUSTOMER
    ON SAPCUSTOMER.BUSINESS_PARTNER_NUMBER = ACCOUNT.ACCOUNTNUMBER
    LEFT OUTER JOIN OFFICE
    ON OFFICE.B_CODE = ACCOUNT.ACCOUNTNUMBER
    LEFT OUTER JOIN CUSTOMER_MANAGER
    ON CUSTOMER_MANAGER.CC_BU_KEY = ACCOUNT.ACCOUNTNUMBER||'_'||BU.BU_GROUP
    LEFT OUTER JOIN WISDOM
    ON WISDOM.WISDOM_SN = CUSTOMERASSET.SERIAL_NUMBER
    WHERE SALES_REGION = 'North America' OR ACCOUNT.REGION = 'US'
)

    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU160_TVAUT') }} AS TVAUT ON (
        TVAUT.SPRAS='EN' AND
        TVAUT.AUGRU = SOBL.VBAP_ORDER_REASON
    )
    LEFT JOIN SALES_DOCUMENT_TEXT
        ON SOBL.VBAK_SALES_DOCUMENT_TYPE = SALES_DOCUMENT_TEXT.SALES_DOCUMENT_TYPE
    LEFT JOIN SERVICE
        ON SOBL.VBAK_SALES_DOCUMENT = SERVICE.SALES_ORDER
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA
        ON MARA.MATNR = SOBL.VBAP_MATERIAL_NUMBER
    LEFT JOIN (
        SELECT DISTINCT
            BP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as SALES_DOCUMENT,
            BP.ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM,
            BP.CUSTOMER_NUMBER AS END_USER,
            CUSTOMER.CUSTOMER_NAME AS END_USER_NAME,
            CUSTOMER.CUSTOMER_GROUP AS END_USER_GROUP,
            CUSTOMER.CUSTOMER_GROUP2 AS END_USER_GROUP2,
            CUSTOMER.CITY AS END_USER_CITY,
            CUSTOMER.REGION AS END_USER_REGION,
            CUSTOMER.COUNTRY_KEY AS END_USER_COUNTRY
        FROM {{ ref('COMMON__SAPH_GMX__BUSINESS_PARTNERS') }} AS BP
            LEFT JOIN CUSTOMER
                ON BP.CUSTOMER_NUMBER = CUSTOMER.CUSTOMER_NUMBER
        WHERE BP.PARTNER_FUNCTION = 'Z6'
        ) AS ENDUSER
    ON SOBL.VBAK_SALES_DOCUMENT = ENDUSER.SALES_DOCUMENT
    AND 0 = try_to_number(ENDUSER.SALES_DOCUMENT_ITEM)
    GROUP BY
        ALL
)

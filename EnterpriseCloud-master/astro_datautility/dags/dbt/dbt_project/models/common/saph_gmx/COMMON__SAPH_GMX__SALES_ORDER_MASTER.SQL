    FROM {{ ref('COMMON__SAPH_GMX__SALES_ORDER_BILLING_LINE') }} a
    LEFT JOIN mara
        ON a.VBAP_MATERIAL_NUMBER = mara.MARA_MATERIAL_NUMBER
    LEFT JOIN (SELECT distinct NAME_1,CUSTOMER_NUMBER FROM {{ ref('COMMON__SAPH_GMX__BUSINESS_PARTNERS_GENERAL_DATA') }} WHERE CUSTOMER_FLAG='Y') kna1
        ON a.VBAK_SOLD_TO_PARTY = kna1.CUSTOMER_NUMBER
    LEFT JOIN sosl
        ON (sosl.VBEP_SALES_DOCUMENT) = (a.VBAK_SALES_DOCUMENT)
        AND (sosl.VBEP_SALES_DOCUMENT_ITEM) = (a.SALES_DOCUMENT_ITEM_POSNR)
    LEFT JOIN security_cost_cte
        ON a.VBAP_COST_CENTER = security_cost_cte.cost_center_code
    LEFT JOIN security_profit_cte
        ON a.VBAP_PROFIT_CENTER = security_profit_cte.profit_center_code
    LEFT JOIN MAT_VENDORS mv
        ON a.VBAP_MATERIAL_NUMBER = mv.MATERIAL_NUMBER_VENDOR
    LEFT JOIN DOC_TYPE doc_type
        ON doc_type.DOCTYPE_VBAK_SALES_DOCUMENT_TYPE = a.VBAK_SALES_DOCUMENT_TYPE

        ON podl.EKKO_VENDOR_S_ACCOUNT_NUMBER=BPGD.BUSINESS_PARTNER_NUMBER 
    GROUP BY MATERIAL_NUMBER_MATNR 
 ),
sosl as
(
    SELECT
        VBEP_SALES_DOCUMENT
        ,VBEP_SALES_DOCUMENT_ITEM
        ,VBEP_SALES_DOCUMENT||'|'||VBEP_SALES_DOCUMENT_ITEM as vbep_so_id

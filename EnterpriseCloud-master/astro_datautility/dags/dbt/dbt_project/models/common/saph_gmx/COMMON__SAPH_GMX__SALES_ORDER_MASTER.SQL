        ,sum(CONFIRMED_QUANTITY) confirmed_quantity -- confirmed_quantity
        ,max(SCHEDULE_LINE_DATE_EDATU) schedule_line_date -- schedule_line_date
    FROM {{ ref('COMMON__SAPH_GMX__SALES_ORDER_SCHEDULE_LINE') }} --SalesDocumentSchedule
    GROUP BY 1,2
),
mara as
(
    SELECT DISTINCT
        MARA_MATERIAL_NUMBER
        ,MATERIAL_GROUP
        ,MATERIAL_DESCRIPTION
    FROM {{ ref('COMMON__SAPH__MATERIAL_PLANT_MASTER') }}
)


with MAT_VENDORS as 
( 
    SELECT
        podl.MATERIAL_NUMBER_MATNR as MATERIAL_NUMBER_VENDOR,
        LISTAGG(distinct INITCAP(BPGD.NAME_1),',') as RECOMMENDED_VENDOR_NAME
    FROM {{ ref('COMMON__SAPH_GMX__PURCHASE_ORDER_DELIVERY_LINE') }} podl

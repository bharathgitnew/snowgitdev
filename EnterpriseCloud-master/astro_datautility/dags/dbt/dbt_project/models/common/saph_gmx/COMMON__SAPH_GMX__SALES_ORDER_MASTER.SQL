        LIKP_DELIVERY_PRIORITY AS DELIVERY_ORDER_PRIORITY_CODE,
        ORDER_PRIORITY_ZZOPZZ AS SALES_ORDER_PRIORITY_CODE,
        CASE
            WHEN ORDER_PRIORITY_ZZOPZZ = '1' THEN 'Normal'
            WHEN ORDER_PRIORITY_ZZOPZZ = '2' THEN 'Rush'
            WHEN ORDER_PRIORITY_ZZOPZZ = '3' THEN 'Urgent'
            WHEN ORDER_PRIORITY_ZZOPZZ = '4' THEN 'Emergency'
        ELSE 'N/A' END AS SALES_ORDER_PRIORITY,
        CASE
            WHEN ORDER_PRIORITY_ZZOPZZ = '4' THEN 'Emergency'
        ELSE 'N/A' END AS SALES_ORDER_EMERGENCY_FLAG,
        SHIP_TO_PARTY AS SHIP_TO_PARTY,
        LIKP_VENDOR_S_ACCOUNT_NUMBER AS LIKP_VENDOR_S_ACCOUNT_NUMBER,

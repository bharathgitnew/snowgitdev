WITH
-- Negative Doc Types
-- 
-- Support CTE used to transform lines with "return" sales document types into
-- negative amounts and quantities.
NEGATIVE_DOC_TYPES AS (
    SELECT SALES_DOC_TYPE, -1 AS COEF
    FROM (VALUES ('ZPR0'), ('ZPR2'), ('ZRR0'), ('ZSR0'), ('ZSR1'), ('ZER0')) AS X(SALES_DOC_TYPE)
)
,SERVICE AS (
    SELECT DISTINCT
        AUFNR AS SERVICE_ORDER,
        KDAUF AS SALES_ORDER,
        AUART AS SERVICE_ORDER_TYPE
    FROM {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU090_AUFK') }}
)
,SALES_DOCUMENT_TEXT as (
    SELECT 
        SPRAS,
        AUART AS SALES_DOCUMENT_TYPE,
        BEZEI AS SALES_DOCUMENT_TYPE_DESCRIPTION
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU023_TVAKT') }}  SALES_DOCUMENT_TEXT
    Where SALES_DOCUMENT_TEXT.SPRAS='EN'
)
,CUSTOMER as (
    SELECT DISTINCT
        CUSTOMER.BUSINESS_PARTNER_NUMBER AS CUSTOMER_NUMBER
        , CUSTOMER.SEARCH_TERM_1 as CUSTOMER_NAME
        , CUSTOMER.SEARCH_TERM_2 as CUSTOMER_NAME_B
        , CUSTOMER.BUSINESS_PARTNER_NUMBER
        , CUSTOMER.CORPORATION
        , CUSTOMER.CORPORATION_NAME
        , CUSTOMER.CUSTOMER_GROUP
        , CUSTOMER.CITY
        , CUSTOMER.REGION
    FROM {{ ref('COMMON__SAPH_GMX__SAP_CUSTOMER') }} AS CUSTOMER
)
,CUSTOMER_GROUP1 AS (
    SELECT 
        KVGR1 AS CUSTOMER_GROUP1,
        UPPER(BEZEI) AS CUSTOMER_GROUP1_NAME
    FROM  {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU177_TVV1T') }}
)
,CUSTOMER_GROUP2 AS (
    SELECT 
        KVGR2 AS CUSTOMER_GROUP2,
        UPPER(BEZEI) AS CUSTOMER_GROUP2_NAME
    FROM {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU178_TVV2T') }}
) 
,COST_CENTER as (
    select
        COST_CENTER_CODE,
        COST_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('ODS__FILE__COST_CENTER') }}
)

,PROFIT_CENTER as (
    select 
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('ODS__FILE__PROFIT_CENTER') }}
)
,TIMESHEET AS (
SELECT DISTINCT
    SERVICEORDER,
    FAB,
    FABCODE,
    FABOFFICECODE,
    FABOFFICENAME
FROM {{ ref('COMMON__REPORTS_GMX__TIMESHEET') }}
)
,SOURCE_DATA AS (
    SELECT DISTINCT
        SOL.VBAK_SALES_DOCUMENT || SOL.SALES_DOCUMENT_ITEM_POSNR AS SO_ID,
        SOL.VBAK_SALES_DOCUMENT AS SALES_ORDER_HEADER_NUMBER,
        SOL.SALES_DOCUMENT_ITEM_POSNR AS SALES_ORDER_LINE_NUMBER,
        --DLVR.DO_ID AS DELIVERY_ORDER_HEADER_NUMBER,
        SOL.NCDR_NUMBER,
        CASE 
            WHEN SOL.ORDER_PRIORITY_ZZOPZZ = '4' THEN 'Emergency'
            WHEN SOL.ORDER_PRIORITY_ZZOPZZ = '3' THEN 'Urgent'
            WHEN SOL.ORDER_PRIORITY_ZZOPZZ = '2' THEN 'Rush'
            WHEN SOL.ORDER_PRIORITY_ZZOPZZ = '1' THEN 'Normal'
            ELSE 'N/A'
        END AS ORDER_PRIORITY,
        SOL.VBAK_DELIVERY_CREATE_DATE AS SALES_ORDER_DATE,
        SOL.DOCUMENT_DATE AS SALES_ORDER_DOCUMENT_DATE,
        SOL.VBAK_DELIVERY_STATUS AS DELIVERY_STATUS,
        SOL.REQUESTED_DELIVERY_DATE,
        SOL.SCHEDULED_WAREHOUSE_DELIVERY_DATE,
        SOL.SCHEDULED_CUSTOMS_CLEARANCE_DATE,
        SOL.SHIP_DATE AS SHIP_DATE,
        SOL.SALES_DOCUMENT_TYPE AS SALES_DOC_TYPE,
        SALES_DOCUMENT_TEXT.SALES_DOCUMENT_TYPE_DESCRIPTION AS SALES_DOC_TYPE_DESCRIPTION,
        SOL.VBAP_MATERIAL_NUMBER AS MATERIAL_NUMBER,
        SOL.VBAP_MATERIAL_GROUP AS MATERIAL_GROUP,
        MARA.MAKTX AS MATERIAL_DESCRIPTION,
        SOL.TOOL_SERIAL_NO,
        SOL.VBAK_SALES_CATEGORY AS SALES_CATEGORY_HEAD,
        SOL.STORAGE_LOCATION,
        SOL.NCDR_REQUESTOR,
        SOL.NCDR_FLAG,
        SOL.NCDR_STATUS,
        COALESCE(SOL.NET_PRICE, 0) * COALESCE(NDT.COEF, 1) AS UNIT_AMOUNT,
        COALESCE(SOL.NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY, 0) * COALESCE(NDT.COEF, 1) AS SALES_ORDER_LINE_AMOUNT,
        COALESCE(SOL.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS, 0) * COALESCE(NDT.COEF, 1) AS SALES_ORDER_QUANTITY,
        SOL.VBAK_ORDER_REASON AS ORDER_REASON_CODE,
        CASE
            WHEN VBAP_ORDER_REASON = 'CPR' THEN 'Customer Paid Repair'
            WHEN VBAP_ORDER_REASON = 'WKT' THEN 'Tools / Doc. / Software'
            WHEN VBAP_ORDER_REASON = 'SLS' THEN 'Normal Parts Sales'
            WHEN VBAP_ORDER_REASON = 'REX' THEN 'Repair Exchange'
            WHEN VBAP_ORDER_REASON = 'TBS' THEN 'TSM Billable Sales'
            WHEN VBAP_ORDER_REASON = 'R01' THEN 'Received Damaged'
            WHEN VBAP_ORDER_REASON = 'FCN' THEN 'FCN / SI'
            WHEN VBAP_ORDER_REASON = 'SUP' THEN 'Start up Trouble/ Mod. Instl. Trouble'
            WHEN VBAP_ORDER_REASON = 'GNS' THEN 'Strategic Sales Concession / Genpo'
            WHEN VBAP_ORDER_REASON = 'WTY' THEN 'Equip. Warranty/ Mod. Warranty'
            WHEN VBAP_ORDER_REASON = 'LNR' THEN 'Loan Parts'
            WHEN VBAP_ORDER_REASON = 'CMR' THEN 'Credit Memo'
            WHEN VBAP_ORDER_REASON = 'R11' THEN 'NCDR Return'
            WHEN VBAP_ORDER_REASON = 'PSO' THEN 'Paid Service'
            WHEN VBAP_ORDER_REASON = 'RTC' THEN 'Consignment Stock Return'
            WHEN VBAP_ORDER_REASON = 'XPT' THEN 'Export Parts Sales'
            WHEN VBAP_ORDER_REASON = 'R05' THEN 'Fail on Install'
            WHEN VBAP_ORDER_REASON = 'TWS' THEN 'TSM Warranty Sales'
            WHEN VBAP_ORDER_REASON = 'EVL' THEN 'Evaluation'
            WHEN VBAP_ORDER_REASON = 'IPR' THEN 'Sales Concession/FS: Sales'
            WHEN VBAP_ORDER_REASON = 'STO' THEN 'Stock Transfer'
            WHEN VBAP_ORDER_REASON = 'GNP' THEN 'Sales concession/Genpo'
            WHEN VBAP_ORDER_REASON = 'FAC' THEN 'Factory  Concession'
            WHEN VBAP_ORDER_REASON = 'TEL' THEN 'Sales Concession/ Product Sales'
            WHEN VBAP_ORDER_REASON = 'SSC' THEN 'Strategic Sales Concession'
            WHEN VBAP_ORDER_REASON = 'R04' THEN 'Defective'
            WHEN VBAP_ORDER_REASON = 'PWO' THEN 'Paperwork only Sales'
            WHEN VBAP_ORDER_REASON = 'R02' THEN 'Wrong Parts'
            WHEN VBAP_ORDER_REASON = 'PRW' THEN 'Pre Warranty'
            WHEN VBAP_ORDER_REASON = 'DMR' THEN 'Debit Memo'
            WHEN VBAP_ORDER_REASON = 'R07' THEN 'Not Needed'
        ELSE 'N/A' END AS  ORDER_REASON,
        SOL.CUSTOMER_GROUP_1 AS CUSTOMER_GROUP1,
        CUSTOMER_GROUP1.CUSTOMER_GROUP1_NAME,
        SOL.CUSTOMER_GROUP_2 AS CUSTOMER_GROUP2,
        CUSTOMER_GROUP2.CUSTOMER_GROUP2_NAME,
        SOL.SOLD_TO_PARTY AS SOLD_TO_PARTY_CODE,
        KNA1.NAME1 AS SOLD_TO_PARTY,
        SOL.CONTRACT_NUMBER as CONTRACT_NUMBER,
        SOL.VBAP_COST_CENTER AS COST_CENTER,
        SOL.VBAP_PROFIT_CENTER AS PROFIT_CENTER,
        --New field addition 12/6/2023
        PROFIT_CENTER.SEGMENT_CODE,
        IFNULL(PROFIT_CENTER.SEGMENT,'NOVALUE') AS SEGMENT,
        PROFIT_CENTER.DEPARTMENT_CODE,
        IFNULL(PROFIT_CENTER.DEPARTMENT,'NOVALUE') AS DEPARTMENT,
        PROFIT_CENTER.OFFICE_CODE,
        IFNULL(PROFIT_CENTER.OFFICE,'NOVALUE') AS OFFICE,
        SOL.CUSTOMER_REFERENCE,
        SOL.SERVICE_CRM_WO_NO,
        LISTAGG(SERVICE.SERVICE_ORDER,', ') OVER (partition by SO_ID) AS SERVICE_ORDER,
        SERVICE.SERVICE_ORDER_TYPE,
        CASE WHEN SOL.MATERIAL_GROUP_2='1' THEN 'Consumable'
            WHEN SOL.MATERIAL_GROUP_2='0' THEN 'Non Consumable'
        END AS CONSUMABLE_FLAG,
        ENDUSER.END_USER,
        ENDUSER.END_USER_NAME,
        ENDUSER.END_USER_GROUP,
        ENDUSER.END_USER_CITY,
        ENDUSER.END_USER_REGION,
        --FAB TIMSHEET DETAIL
        LISTAGG(TIMESHEET.FAB ,'') OVER (partition by SO_ID) AS FAB,
        LISTAGG(TIMESHEET.FABCODE ,'') OVER (partition by SO_ID) AS FABCODE,
        LISTAGG(TIMESHEET.FABOFFICECODE,'') OVER (partition by SO_ID) AS FABOFFICECODE,
        LISTAGG(TIMESHEET.FABOFFICENAME,'') OVER (partition by SO_ID) AS FABOFFICENAME,
        IFNULL(SOL.VBAP_DELIVERY_SERVICE_CODE,'NA') AS DELIVERY_SERVICE_CODE,
        Case When SOL.VBAP_DELIVERY_SERVICE_CODE='A01' Then 'Local Drive'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A02' Then 'Door to Door - Next flight Out'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A03' Then 'Counter to Counter - Next Flight out'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A04' Then 'Will Call'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A05' Then 'Next Business Day AM Delivery'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A06' Then 'Next Business Day Early AM Delivery'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A07' Then 'Next Business Day PM Delivery'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A08' Then '2-Day'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A09' Then '3-day'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A10' Then 'Economy Ground'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A11' Then 'Air Ride Van/Truck'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A12' Then 'LTL Ground'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A13' Then 'Saturday Delivery'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A14' Then 'Internal Whse Transfer'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A16' Then 'International Next Day air'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A17' Then 'INTERNATIONAL EXPRESS EMERGENCY NEXT Flight out'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A18' Then 'International Consolidated Freight'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='A19' Then 'Ocean'
            When SOL.VBAP_DELIVERY_SERVICE_CODE='PWO' Then 'Paperwork Only'
        Else 'NA' End As DELIVERY_SERVICE_CODE_DESCRIPTION,
        CASE WHEN REJECTION_STATUS_FOR_SALES_DOCUMENT_ITEM = 'C' THEN TRUE ELSE FALSE END AS REJECTED,
        SOL.CREATED_BY_EMPLOYEE_NO,
        coalesce(created_by_emp.FULL_NAME, SOL.CREATED_BY_EMPLOYEE_NO) as CREATED_BY_EMPLOYEE_NAME,
        SOL.SALES_REP_EMPLOYEE_NO,
        coalesce(sales_rep_emp.FULL_NAME, SOL.SALES_REP_EMPLOYEE_NO) as SALES_REP_EMPLOYEE_NAME,
        SOL.BILLING_BLOCK_FOR_ITEM,
        SOL.CUSTOMER_REQUEST_NO,
        SOL.EDI_NO,
    FROM {{ ref('COMMON__SAPH_GMX__SALES_ORDER') }} AS SOL
    LEFT JOIN NEGATIVE_DOC_TYPES AS NDT ON (NDT.SALES_DOC_TYPE = SOL.SALES_DOCUMENT_TYPE)
    -- Customer Lookup
    LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (SOL.SOLD_TO_PARTY = KNA1.KUNNR)
    -- Material Lookup
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA ON (SOL.VBAP_MATERIAL_NUMBER = MARA.MATNR)
    LEFT JOIN SERVICE ON SOL.VBAK_SALES_DOCUMENT = SERVICE.SALES_ORDER
    LEFT JOIN (
        SELECT DISTINCT
            BP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as SALES_DOCUMENT,
            BP.ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM,
            BP.CUSTOMER_NUMBER AS END_USER,
            CUSTOMER.CUSTOMER_NAME AS END_USER_NAME,
            CUSTOMER.CUSTOMER_GROUP AS END_USER_GROUP,
            CUSTOMER.CITY AS END_USER_CITY,
            CUSTOMER.REGION AS END_USER_REGION
        FROM {{ ref('COMMON__SAPH_GMX__BUSINESS_PARTNERS') }} AS BP
            LEFT JOIN CUSTOMER 
                ON BP.CUSTOMER_NUMBER = CUSTOMER.CUSTOMER_NUMBER
        WHERE BP.PARTNER_FUNCTION = 'Z6'
        ) AS ENDUSER
    ON SOL.VBAK_SALES_DOCUMENT = ENDUSER.SALES_DOCUMENT
    AND 0 = try_to_number(ENDUSER.SALES_DOCUMENT_ITEM)
    LEFT JOIN SALES_DOCUMENT_TEXT
        ON SOL.SALES_DOCUMENT_TYPE = SALES_DOCUMENT_TEXT.SALES_DOCUMENT_TYPE
    LEFT OUTER JOIN COST_CENTER
        ON (SOL.VBAP_COST_CENTER=cost_center.COST_CENTER_CODE)
    LEFT OUTER JOIN PROFIT_CENTER
        ON (SOL.VBAP_PROFIT_CENTER=profit_center.PROFIT_CENTER_CODE)
    LEFT JOIN TIMESHEET 
        ON SERVICE_ORDER=TIMESHEET.SERVICEORDER
    LEFT JOIN CUSTOMER_GROUP1
        ON SOL.CUSTOMER_GROUP_1=CUSTOMER_GROUP1.CUSTOMER_GROUP1
    LEFT JOIN CUSTOMER_GROUP2
        ON SOL.CUSTOMER_GROUP_2=CUSTOMER_GROUP2.CUSTOMER_GROUP2
    left join {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }} as created_by_emp
        on SOL.CREATED_BY_EMPLOYEE_NO = created_by_emp.EMPLOYEE_ID
    left join {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }} as sales_rep_emp
        on SOL.SALES_REP_EMPLOYEE_NO = sales_rep_emp.EMPLOYEE_ID
),
TRANSFORM_DATA AS (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        SO_ID,
        SALES_ORDER_HEADER_NUMBER,
        SALES_ORDER_LINE_NUMBER,
        NCDR_NUMBER,
        LEFT(NCDR_NUMBER, 2) AS NCDR_PRODUCT_CODE,
        LEFT(RIGHT(NCDR_NUMBER, 9), 3) AS NCDR_REGION_CODE,
        ORDER_PRIORITY,
        SALES_DOC_TYPE, 
        SALES_DOC_TYPE_DESCRIPTION,
        MATERIAL_NUMBER, 
        MATERIAL_GROUP,
        MATERIAL_DESCRIPTION,
        TOOL_SERIAL_NO,

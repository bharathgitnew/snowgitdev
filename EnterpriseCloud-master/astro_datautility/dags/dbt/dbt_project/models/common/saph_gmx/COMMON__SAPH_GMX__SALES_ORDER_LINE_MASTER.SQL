        STORAGE_LOCATION,
        NCDR_REQUESTOR,
        NCDR_FLAG, 
        NCDR_STATUS,
        SALES_ORDER_QUANTITY, 
        UNIT_AMOUNT,
        SALES_ORDER_LINE_AMOUNT,  
        ORDER_REASON_CODE,
        ORDER_REASON, 
        TRY_TO_DATE(SALES_ORDER_DATE, 'YYYYMMDD') AS SALES_ORDER_DATE,
        TRY_TO_DATE(SALES_ORDER_DOCUMENT_DATE, 'YYYYMMDD') AS SALES_ORDER_DOCUMENT_DATE,
        TRY_TO_DATE(REQUESTED_DELIVERY_DATE, 'YYYYMMDD') AS REQUESTED_DELIVERY_DATE,
        TRY_TO_DATE(SCHEDULED_WAREHOUSE_DELIVERY_DATE, 'YYYYMMDD') AS SCHEDULED_WAREHOUSE_DELIVERY_DATE,
        TRY_TO_DATE(SCHEDULED_CUSTOMS_CLEARANCE_DATE, 'YYYYMMDD') AS SCHEDULED_CUSTOMS_CLEARANCE_DATE,
        DELIVERY_STATUS,
        TRY_TO_DATE(SHIP_DATE, 'YYYYMMDD') AS SHIP_DATE, 
        SOLD_TO_PARTY_CODE, 
        SOLD_TO_PARTY, 
        CONTRACT_NUMBER,
        COST_CENTER,
        CUSTOMER_GROUP1,
        CUSTOMER_GROUP1_NAME,
        CUSTOMER_GROUP2,
        CUSTOMER_GROUP2_NAME,
        PROFIT_CENTER,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE,
        CUSTOMER_REFERENCE,
        SERVICE_CRM_WO_NO,
        SERVICE_ORDER,
        SERVICE_ORDER_TYPE,
        CONSUMABLE_FLAG,
        END_USER,
        END_USER_NAME,
        END_USER_GROUP,
        END_USER_CITY,
        END_USER_REGION,
        FAB,
        FABCODE,
        FABOFFICECODE,
        FABOFFICENAME,
        DELIVERY_SERVICE_CODE,
        DELIVERY_SERVICE_CODE_DESCRIPTION,
        REJECTED,
        CREATED_BY_EMPLOYEE_NO,
        CREATED_BY_EMPLOYEE_NAME,
        SALES_REP_EMPLOYEE_NO,
        SALES_REP_EMPLOYEE_NAME,
        BILLING_BLOCK_FOR_ITEM,
        CUSTOMER_REQUEST_NO,
        EDI_NO,
    FROM SOURCE_DATA
),

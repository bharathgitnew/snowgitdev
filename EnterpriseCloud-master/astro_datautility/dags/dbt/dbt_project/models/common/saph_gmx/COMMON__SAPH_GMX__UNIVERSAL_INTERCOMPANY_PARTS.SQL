WHEN KNA1.VBUND IS NOT NULL THEN 'Internal'
ELSE 'No Value' END AS INTERCOMPANY_FLAG
FROM DASL
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU038_BSEG') }}  BSEG
        ON try_to_number(COMPANY_CODE) = try_to_number(BSEG.bukrs)
        AND try_to_number(ACCOUNTING_DOCUMENT_NUMBER) = try_to_number(BSEG.belnr)
        AND try_to_number(FISCAL_YEAR) = try_to_number(BSEG.gjahr)
        AND try_to_number(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER) = try_to_number(BSEG.buzei)
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU047_VBPA') }}  VBPA
    ON BSEG.VBELN = VBPA.VBELN
    AND 'PY'=VBPA.PARVW
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU020_KNA1') }}  KNA1
    ON VBPA.KUNNR=KNA1.KUNNR
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU010_VBAP') }} VBAP

WITH DASL AS (
SELECT * 
FROM {{ ref('COMMON__SAPH_GMX__DAILY_ACTUALS_SALES_LINE') }}
)
,AA AS (
SELECT 
COMPANY_CODE,
FISCAL_YEAR,
DOCUMENT_TYPE,
ACCOUNTING_DOCUMENT_LINE,
SALES_ORDER_LINE,
xref1 as Payer,
'Internal' AS INTERCOMPANY_FLAG
FROM DASL
WHERE ACCOUNT_NUMBER = '5110100000'
    AND DOCUMENT_TYPE='AA'
)
,CO AS (
SELECT 
COMPANY_CODE,
FISCAL_YEAR,
DOCUMENT_TYPE,
ACCOUNTING_DOCUMENT_LINE,
SALES_ORDER_LINE,
SAP_SERVICE_ORDER,
SALES_DOCUMENT,
VBPA.KUNNR as Payer,
KNA1.VBUND,
CASE 
WHEN VBPA.KUNNR IS NOT NULL AND VBPA.KUNNR<>'' AND KNA1.VBUND IS NULL THEN 'External'
WHEN VBPA.KUNNR IS NOT NULL AND VBPA.KUNNR<>'' AND KNA1.VBUND ='' THEN 'External'
WHEN KNA1.VBUND IS NOT NULL THEN 'Internal'
ELSE 'No Value'
END AS INTERCOMPANY_FLAG
FROM DASL
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU047_VBPA') }}  VBPA
    ON DASL.SALES_DOCUMENT = VBPA.VBELN
    AND 'PY'=VBPA.PARVW
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU020_KNA1') }}  KNA1
    ON VBPA.KUNNR=KNA1.KUNNR
WHERE ACCOUNT_NUMBER = '5110100000'
    AND DOCUMENT_TYPE='CO'
)
,ML AS (
SELECT DISTINCT
COMPANY_CODE,
FISCAL_YEAR,
DOCUMENT_TYPE,
ACCOUNTING_DOCUMENT_LINE,
SALES_ORDER_LINE,
SALES_DOCUMENT_TYPE,
COST_CENTER,
WBS_CATEGORY,
VBPA.KUNNR as Payer,
KNA1.VBUND,
CASE 
WHEN COST_CENTER IS NOT NULL AND COST_CENTER<>'' THEN 'Internal'
WHEN WBS_CATEGORY IN ('Z-P','P-S','P-Q') THEN 'External'
WHEN WBS_CATEGORY NOT IN ('Z-P','P-S','P-Q') THEN 'Internal'
WHEN SALES_DOCUMENT_TYPE='ZE10' THEN 'Internal'
WHEN VBPA.KUNNR IS NOT NULL AND VBPA.KUNNR<>'' AND KNA1.VBUND IS NULL THEN 'External'
WHEN VBPA.KUNNR IS NOT NULL AND VBPA.KUNNR<>'' AND KNA1.VBUND ='' THEN 'External'
WHEN KNA1.VBUND IS NOT NULL THEN 'Internal'
ELSE 'No Value'
END AS INTERCOMPANY_FLAG
FROM DASL
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU047_VBPA') }}  VBPA
    ON DASL.SALES_DOCUMENT = VBPA.VBELN
    AND 'PY'=VBPA.PARVW
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU020_KNA1') }}  KNA1
    ON VBPA.KUNNR=KNA1.KUNNR
WHERE ACCOUNT_NUMBER = '5110100000'
    AND DOCUMENT_TYPE='ML'
)
,RV_P1 AS (
SELECT 
COMPANY_CODE,
FISCAL_YEAR,
DOCUMENT_TYPE,
ACCOUNTING_DOCUMENT_NUMBER,
SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
ACCOUNTING_DOCUMENT_LINE,
-- REFERENCE_DOCUMENT_NUMBER,
SALES_ORDER_LINE,
BSEG_DATA.XREF1 as Payer,
-- KNA1.VBUND,
CASE 
WHEN BSEG_DATA.XREF1 IS NOT NULL AND BSEG_DATA.XREF1<>'' AND KNA1.VBUND IS NULL THEN 'External'
WHEN BSEG_DATA.XREF1 IS NOT NULL AND BSEG_DATA.XREF1<>'' AND KNA1.VBUND ='' THEN 'External'
WHEN BSEG_DATA.XREF1 IS NOT NULL AND KNA1.VBUND IS NOT NULL THEN 'Internal'
ELSE 'No Value'
END AS INTERCOMPANY_FLAG
FROM DASL 
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU038_BSEG') }}  BSEG_DATA
        ON try_to_number(COMPANY_CODE) = try_to_number(bseg_data.bukrs)
        AND try_to_number(ACCOUNTING_DOCUMENT_NUMBER) = try_to_number(bseg_data.belnr)
        AND try_to_number(FISCAL_YEAR) = try_to_number(bseg_data.gjahr)
        AND try_to_number(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER) = try_to_number(bseg_data.buzei)
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU020_KNA1') }}  as KNA1
    ON BSEG_DATA.XREF1=KNA1.KUNNR
WHERE ACCOUNT_NUMBER = '5110100000'
    AND DOCUMENT_TYPE='RV'
)
,RV_P2 AS (
SELECT 
COMPANY_CODE,
FISCAL_YEAR,
DOCUMENT_TYPE,
ACCOUNTING_DOCUMENT_NUMBER,
SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
ACCOUNTING_DOCUMENT_LINE,
-- REFERENCE_DOCUMENT_NUMBER,
-- VBRK.VBELN,
SALES_ORDER_LINE,
VBRK.KUNRG as Payer,
-- KNA1.VBUND,
CASE 
WHEN VBRK.KUNRG IS NOT NULL AND VBRK.KUNRG<>'' AND KNA1.VBUND IS NULL THEN 'External'
WHEN VBRK.KUNRG IS NOT NULL AND VBRK.KUNRG<>'' AND KNA1.VBUND ='' THEN 'External'
WHEN KNA1.VBUND IS NOT NULL THEN 'Internal'
ELSE 'No Value'
END AS INTERCOMPANY_FLAG
FROM DASL 
--Priority 3 with Billing Document 
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU014_VBRK') }}  VBRK
    ON DASL.REFERENCE_DOCUMENT_NUMBER = VBRK.VBELN
LEFT JOIN  {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU020_KNA1') }}  as KNA1
    ON VBRK.KUNRG = KNA1.KUNNR
LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU038_BSEG') }}  BSEG_DATA
        ON try_to_number(COMPANY_CODE) = try_to_number(bseg_data.bukrs)
        AND try_to_number(ACCOUNTING_DOCUMENT_NUMBER) = try_to_number(bseg_data.belnr)
        AND try_to_number(FISCAL_YEAR) = try_to_number(bseg_data.gjahr)
        AND try_to_number(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER) = try_to_number(bseg_data.buzei)
WHERE ACCOUNT_NUMBER = '5110100000'
    AND DOCUMENT_TYPE='RV'
    AND (BSEG_DATA.VBEL2='' OR BSEG_DATA.VBEL2 IS NULL)
)
,RV AS (
SELECT 
RV_P1.COMPANY_CODE,
RV_P1.FISCAL_YEAR,
RV_P1.DOCUMENT_TYPE,
RV_P1.ACCOUNTING_DOCUMENT_LINE,
RV_P1.SALES_ORDER_LINE,
CASE
WHEN RV_P1.INTERCOMPANY_FLAG NOT LIKE ('No Value') THEN RV_P1.Payer
ELSE RV_P2.Payer END AS Payer,
CASE 
WHEN RV_P1.INTERCOMPANY_FLAG NOT LIKE ('No Value') THEN RV_P1.INTERCOMPANY_FLAG
ELSE RV_P2.INTERCOMPANY_FLAG END AS INTERCOMPANY_FLAG
FROM RV_P1 JOIN RV_P2
ON RV_P1.ACCOUNTING_DOCUMENT_NUMBER=RV_P2.ACCOUNTING_DOCUMENT_NUMBER AND
RV_P1.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER=RV_P2.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER
)

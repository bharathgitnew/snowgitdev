WITH DASL AS (
SELECT * 
FROM {{ ref('COMMON__SAPH_GMX__DAILY_ACTUALS_SALES_LINE') }}
)
--bring in kna1 vbund(company code of sold to party) from first SO item where sales cat is 5* 
,KOAE_TP AS(
    SELECT 
        EX.COMPANY_CODE,
        EX.FISCAL_YEAR,
        EX.ACCOUNTING_DOCUMENT_NUMBER,
        EX.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        EX.SALES_CATEGORY,
        EX.SALES_DOCUMENT,
        EX.SALES_DOCUMENT_ITEM,
        EX.SALES_DOCUMENT || '_' || EX.SALES_DOCUMENT_ITEM AS SALES_DOCUMENT_LINE,
        SO.SOLD_TO_PARTY,
        KNA1.VBUND,
        EX.KUNNR
    FROM {{ ref('COMMON__SAPH_GMX__UNIVERSAL_ACTUAL_SETTLEMENT_EXTERNAL') }} EX
    left join {{ ref('COMMON__SAPH_GMX__SALES_ORDER') }} SO
    on SALES_DOCUMENT = SO.VBAP_SALES_DOCUMENT
    LEFT JOIN {{ ref('ODS__SAPAPI_GMX__ZCDV_T_CMTU020_KNA1') }} KNA1
    ON SO.SOLD_TO_PARTY = KNA1.KUNNR
    WHERE SALES_CATEGORY ILIKE '5%'
    AND SALES_DOCUMENT_ITEM = '000100' --take off these filters to get kunnr(ie customer for the payer) gaby will confirm on the PARVW = z6 or py
)
--these wbs cats are fixed internal
,INTERNAL_WBS AS (
SELECT 
DASL.COMPANY_CODE,
DASL.FISCAL_YEAR,
POSTING_DATE,
DOCUMENT_TYPE,
ACCOUNTING_DOCUMENT_LINE,
SALES_ORDER_LINE,
WBS_CATEGORY,
DASL.COMPANY_ID_OF_TRADING_PARTNER as Payer,
KOAE_TP.KUNNR as CUSTOMER,
KOAE_TP.SOLD_TO_PARTY,
KOAE_TP.VBUND,
CASE 
WHEN WBS_CATEGORY IN ('A-4', 'A-5', 'A-6', 'A-7', 'A-A', 'A-B', 'A-C', 'A-D', 'I-4', 'I-5', 'I-6', 'I-7', 'I-C', 'X-U', 'X-V', 'Z-4', 'Z-5', 'Z-8', 'Z-9', 'Z-Z') THEN 'Internal'
WHEN WBS_CATEGORY NOT IN ('A-4', 'A-5', 'A-6', 'A-7', 'A-A', 'A-B', 'A-C', 'A-D', 'I-4', 'I-5', 'I-6', 'I-7', 'I-C', 'X-U', 'X-V', 'Z-4', 'Z-5', 'Z-8', 'Z-9', 'Z-Z') THEN 'External'
WHEN WBS_CATEGORY = 'P-Q' THEN 'External'
ELSE 'External'
END AS INTERCOMPANY_FLAG
FROM DASL
left join KOAE_TP
ON DASL.COMPANY_CODE = KOAE_TP.COMPANY_CODE
AND DASL.FISCAL_YEAR = KOAE_TP.FISCAL_YEAR
AND ACCOUNTING_DOCUMENT_LINE = KOAE_TP.ACCOUNTING_DOCUMENT_NUMBER || '_' || KOAE_TP.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER
WHERE ACCOUNT_NUMBER = '5110100004'
)
--join this to external settlement cte to get condition for internal/external
,PS AS (
SELECT 
DASL.COMPANY_CODE,
DASL.FISCAL_YEAR,
POSTING_DATE,
DOCUMENT_TYPE,
ACCOUNTING_DOCUMENT_LINE,
SALES_ORDER_LINE,
WBS_CATEGORY,
DASL.COMPANY_ID_OF_TRADING_PARTNER as Payer,
KOAE_TP.vbund as CC_Internal,
KOAE_TP.KUNNR as CUSTOMER,
KOAE_TP.SOLD_TO_PARTY,
KOAE_TP.VBUND,
CASE 
WHEN CC_Internal IN ('1100', '3500','7100') THEN 'Internal'
WHEN CC_Internal NOT IN ('1100', '3500','7100') THEN 'External'
WHEN CC_Internal IS NULL THEN 'External'
ELSE 'External'
END AS INTERCOMPANY_FLAG 
FROM DASL
left join KOAE_TP
ON DASL.COMPANY_CODE = KOAE_TP.COMPANY_CODE
AND DASL.FISCAL_YEAR = KOAE_TP.FISCAL_YEAR
AND ACCOUNTING_DOCUMENT_LINE = KOAE_TP.ACCOUNTING_DOCUMENT_NUMBER || '_' || KOAE_TP.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER
WHERE ACCOUNT_NUMBER = '5110100004'
    AND WBS_CATEGORY='P-S'
)
,COMBINED AS (
    SELECT 
        INTERNAL_WBS.COMPANY_CODE,
        INTERNAL_WBS.FISCAL_YEAR,
        POSTING_DATE,
        DOCUMENT_TYPE,
        ACCOUNTING_DOCUMENT_LINE,
        SALES_ORDER_LINE,
        WBS_CATEGORY,
        Payer,
        INTERCOMPANY_FLAG,
        CUSTOMER,
        SOLD_TO_PARTY,
        VBUND
    FROM INTERNAL_WBS
    UNION ALL
    SELECT 
        PS.COMPANY_CODE,
        PS.FISCAL_YEAR,
        POSTING_DATE,
        DOCUMENT_TYPE,
        ACCOUNTING_DOCUMENT_LINE,
        SALES_ORDER_LINE,
        WBS_CATEGORY,
        Payer,
        INTERCOMPANY_FLAG,
        CUSTOMER,
        SOLD_TO_PARTY,
        VBUND
    FROM PS
)
,FINAL AS (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    COMPANY_CODE,
    FISCAL_YEAR,
    POSTING_DATE,
    DOCUMENT_TYPE,
    ACCOUNTING_DOCUMENT_LINE,
    SALES_ORDER_LINE,
    WBS_CATEGORY,
    Payer,
    INTERCOMPANY_FLAG,
    CUSTOMER,
    SOLD_TO_PARTY,
    VBUND
FROM COMBINED
)
SELECT * FROM FINAL

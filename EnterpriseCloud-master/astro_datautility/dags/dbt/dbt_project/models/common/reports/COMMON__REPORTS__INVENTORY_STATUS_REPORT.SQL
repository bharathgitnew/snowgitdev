{{ config(
        materialized='incremental',
        incremental_strategy='insert_overwrite',
        alias='INVENTORY_STATUS_REPORT',
        transient=false
) }}

with source_data as (
    SELECT
        inv.MATERIAL_NUMBER,
        inv.PLANT,
        inv.STORAGE_LOCATION,
        inv.BATCH_NUMBER,
        inv.BASE_UNIT_OF_MEASURE_MATERIAL_BASE_UNIT,
        inv.WMS_BATCH_NUMBER,
        inv.SERIAL_NUMBER,
        inv.STOCK_DATE,
        inv.STOCK_TIME,
        inv.UNRESTRICTED_QUANTITY,
        inv.STOCK_IN_TRANSFER,
        marc.TRAME AS STOCK_IN_TRANSIT,
        inv.STOCK_IN_QUALITY,
        inv.STOCK_RESTRICTED_BATCHES,
        inv.BLOCKED_STOCK,
        inv.BLOCKED_STOCK_RETURNS,
        inv.MATERIAL_BASE_UNIT_ISO,
        inv.COMPANY_CODE,
        inv.SALES_ORGANIZATION,
        inv.DISTRIBUTION_CHANNEL_CODE,
        inv.DIVISION_CODE,
        inv.MATERIAL_DESCRIPTION,
        inv.STORAGE_LOCATION_NAME,
        inv.DEVICE_CODE,
        inv.PRODUCT_CODE,
        inv.CUSTOMER_CONSIGNMENT_CODE,
        inv.CUSTOMER_CONSIGNMENT_NAME,
        inv.CUSTOMER_LOAN_CODE,
        inv.CUSTOMER_LOAN_NAME,
        inv.BASE_UNIT_OF_MEASURE_BASE_UNIT,
        inv.ISO_CODE_FOR_UNIT_OF_MEASUREMENT,
        mvke.MVGR1 AS MATERIAL_GROUP_1,
        mvke.MVGR2 AS MATERIAL_GROUP_2,
        marc.ZZLABC AS LOCAL_ABC,
        marc.ZZSABC AS SPECIFIC_CUSTOMER_ABC,
        marc.EISBE AS SAFETY_STOCK,
        marc.MINBE AS REORDER_POINT
    FROM {{ ref('COMMON__SAPH__INVENTORY_STATUS') }} inv
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU019_MVKE') }} mvke 
    ON inv.MATERIAL_NUMBER=mvke.MATNR 
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU026_MARC') }} marc 
    ON inv.MATERIAL_NUMBER=marc.MATNR AND inv.PLANT=marc.WERKS 
),

transform_data as (
    SELECT
        MATERIAL_NUMBER,
        PLANT,
        STORAGE_LOCATION,
        CASE
            WHEN right(STORAGE_LOCATION, 1) = '0' THEN 'Good'
            WHEN right(STORAGE_LOCATION, 1) = '1' THEN 'SCRP'
            WHEN right(STORAGE_LOCATION, 1) = '2' THEN 'BBK'
            WHEN right(STORAGE_LOCATION, 1) = '3' THEN 'NCDR - Not Used'
            WHEN right(STORAGE_LOCATION, 1) = '4' THEN 'FCN'
            WHEN right(STORAGE_LOCATION, 1) = '5' THEN 'RPRCORE'
            WHEN right(STORAGE_LOCATION, 1) = '7' THEN 'INSPECTION'
            WHEN right(STORAGE_LOCATION, 1) = '8' THEN 'INSURANCE'
            WHEN right(STORAGE_LOCATION, 1) = '9' THEN 'RSRV'
            WHEN STORAGE_LOCATION = '' AND CUSTOMER_CONSIGNMENT_CODE is not NULL  THEN 'CONSIGNMENT' 
            ELSE NULL
        END as SLOC_PURPOSE,
        BATCH_NUMBER,
        BASE_UNIT_OF_MEASURE_MATERIAL_BASE_UNIT,
        WMS_BATCH_NUMBER,
        SERIAL_NUMBER,
        STOCK_DATE,
        STOCK_TIME,
        DATEDIFF('days', TRY_TO_DATE(STOCK_DATE), CURRENT_DATE())/30 AS MONTHS_AGING, 
        UNRESTRICTED_QUANTITY,
        STOCK_IN_TRANSFER,
        STOCK_IN_TRANSIT,
        STOCK_IN_QUALITY,
        STOCK_RESTRICTED_BATCHES,
        BLOCKED_STOCK,
        BLOCKED_STOCK_RETURNS,
        MATERIAL_BASE_UNIT_ISO,
        COMPANY_CODE,
        SALES_ORGANIZATION,
        DISTRIBUTION_CHANNEL_CODE,
        DIVISION_CODE,
        MATERIAL_DESCRIPTION,
        STORAGE_LOCATION_NAME,
        DEVICE_CODE,
        PRODUCT_CODE,
        CUSTOMER_CONSIGNMENT_CODE,
        CUSTOMER_CONSIGNMENT_NAME,
        CUSTOMER_LOAN_CODE,
        CUSTOMER_LOAN_NAME,
        BASE_UNIT_OF_MEASURE_BASE_UNIT,
        ISO_CODE_FOR_UNIT_OF_MEASUREMENT,
        MATERIAL_GROUP_1, 
        MATERIAL_GROUP_2, 
        LOCAL_ABC, 
        SPECIFIC_CUSTOMER_ABC,
        SAFETY_STOCK,
        REORDER_POINT,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    FROM source_data
),

type_data as (
    SELECT
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(STORAGE_LOCATION AS VARCHAR(16777216)) AS STORAGE_LOCATION,
        CAST(STORAGE_LOCATION_NAME AS VARCHAR(16777216)) AS STORAGE_LOCATION_NAME,
        CAST(SLOC_PURPOSE AS VARCHAR(16777216)) AS SLOC_PURPOSE,
        CAST(BATCH_NUMBER AS VARCHAR(16777216)) AS BATCH_NUMBER,
        CAST(BASE_UNIT_OF_MEASURE_MATERIAL_BASE_UNIT AS VARCHAR(16777216)) AS BASE_UNIT_OF_MEASURE_MATERIAL_BASE_UNIT,
        CAST(WMS_BATCH_NUMBER AS VARCHAR(16777216)) AS WMS_BATCH_NUMBER,
        CAST(SERIAL_NUMBER AS VARCHAR(16777216)) AS SERIAL_NUMBER,
        CAST(STOCK_DATE AS VARCHAR(16777216)) AS STOCK_DATE,
        CAST(STOCK_TIME AS VARCHAR(16777216)) AS STOCK_TIME,
        CAST(MONTHS_AGING AS NUMBER(38, 0)) AS MONTHS_AGING,
        CAST(UNRESTRICTED_QUANTITY AS VARCHAR(16777216)) AS UNRESTRICTED_QUANTITY,
        CAST(STOCK_IN_TRANSFER AS NUMBER(38,0)) AS STOCK_IN_TRANSFER,
        CAST(STOCK_IN_TRANSIT AS NUMBER(38,10)) AS STOCK_IN_TRANSIT,
        CAST(STOCK_IN_QUALITY AS NUMBER(38,0)) AS STOCK_IN_QUALITY,
        CAST(STOCK_RESTRICTED_BATCHES AS NUMBER(38,0)) AS STOCK_RESTRICTED_BATCHES,
        CAST(BLOCKED_STOCK AS NUMBER(38,0)) AS BLOCKED_STOCK,
        CAST(BLOCKED_STOCK_RETURNS AS NUMBER(38,0)) AS BLOCKED_STOCK_RETURNS,
        CAST(MATERIAL_BASE_UNIT_ISO AS VARCHAR(16777216)) AS MATERIAL_BASE_UNIT_ISO,
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(SALES_ORGANIZATION AS VARCHAR(16777216)) AS SALES_ORGANIZATION,
        CAST(DISTRIBUTION_CHANNEL_CODE AS VARCHAR(16777216)) AS DISTRIBUTION_CHANNEL_CODE,
        CAST(DIVISION_CODE AS VARCHAR(16777216)) AS DIVISION_CODE,
        CAST(DEVICE_CODE AS VARCHAR(16777216)) AS DEVICE_CODE,
        CAST(PRODUCT_CODE AS VARCHAR(16777216)) AS PRODUCT_CODE,
        CAST(CUSTOMER_CONSIGNMENT_CODE AS VARCHAR(16777216)) AS CUSTOMER_CONSIGNMENT_CODE,
        CAST(CUSTOMER_CONSIGNMENT_NAME AS VARCHAR(16777216)) AS CUSTOMER_CONSIGNMENT_NAME,
        CAST(CUSTOMER_LOAN_CODE AS VARCHAR(16777216)) AS CUSTOMER_LOAN_CODE,
        CAST(CUSTOMER_LOAN_NAME AS VARCHAR(16777216)) AS CUSTOMER_LOAN_NAME,
        CAST(BASE_UNIT_OF_MEASURE_BASE_UNIT AS VARCHAR(16777216)) AS BASE_UNIT_OF_MEASURE_BASE_UNIT,
        CAST(ISO_CODE_FOR_UNIT_OF_MEASUREMENT AS VARCHAR(16777216)) AS ISO_CODE_FOR_UNIT_OF_MEASUREMENT,
        CAST(MATERIAL_GROUP_1 AS VARCHAR(16777216)) AS MATERIAL_GROUP_1, 
        CAST(MATERIAL_GROUP_2 AS VARCHAR(16777216)) AS MATERIAL_GROUP_2, 
        CAST(LOCAL_ABC AS VARCHAR(16777216)) AS LOCAL_ABC, 
        CAST(SPECIFIC_CUSTOMER_ABC AS VARCHAR(16777216)) AS SPECIFIC_CUSTOMER_ABC, 
        CAST(SAFETY_STOCK AS VARCHAR(16777216)) AS SAFETY_STOCK, 
        CAST(REORDER_POINT AS VARCHAR(16777216)) AS REORDER_POINT, 
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)

SELECT * FROM type_data
        materialized='incremental'    ,
     incremental_strategy='insert_overwrite'    ,
     alias='INVENTORY_REVALUATION'    ,
     transient=false
) }}

WITH 
PB AS (
    SELECT 
        PB.PART_NUMBER,
        MAX(TRY_CAST(REPLACE(PB.SALES_PRICE, ',', '') AS FLOAT)) AS SALE_PRICE,
        MAX(TRY_CAST(REPLACE(PB.PURCHASE_PRICE, ',', '') AS FLOAT)) AS PURCHASE_PRICE
    FROM {{ ref('ODS__FILE__TEL_PRICING_ACTUAL') }} AS PB
    WHERE
        TRY_CAST(REPLACE(PB.SALES_PRICE, ',', '') AS FLOAT) IS NOT NULL AND
        TRY_CAST(REPLACE(PB.PURCHASE_PRICE, ',', '') AS FLOAT) IS NOT NULL
    GROUP BY 
        PB.PART_NUMBER  
),
STOCK_RECORDS AS (
    SELECT DISTINCT
        MATNR, 
        LBKUM, 
        VERPR, 
        STPRS, 
        TO_NUMBER(LFGJA),
        TO_NUMBER(LFMON),
        BWKEY,
        VPRSV,
        NULL AS VBELN,
        NULL AS POSNR,
        'MBEWH' AS SRC
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU243_MBEWH') }} AS MBEWH
    WHERE 
        BWKEY = '3200' 
        AND VPRSV = 'V'
        AND LFGJA='2023'
        QUALIFY (ROW_NUMBER() OVER (PARTITION BY MATNR ORDER BY TO_NUMBER(LFGJA) DESC,TO_NUMBER(LFMON) DESC )) = 1
    UNION ALL
    SELECT DISTINCT
        MATNR, 
        LBKUM, 
        VERPR, 
        STPRS, 
        TO_NUMBER(LFGJA),
        TO_NUMBER(LFMON),
        BWKEY,
        VPRSV, 
        VBELN,
        POSNR,
        'EBEWH' AS SRC
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU246_EBEWH') }} AS EBEWH
    WHERE 
        BWKEY = '3200' 
        AND VPRSV = 'V'
        AND LFGJA='2023'
        QUALIFY (ROW_NUMBER() OVER (PARTITION BY MATNR ORDER BY TO_NUMBER(LFGJA) DESC,TO_NUMBER(LFMON) DESC )) = 1  
),
BASE AS (
    SELECT 
        MATNR, 
        MAX(CASE WHEN SRC = 'MBEWH' THEN VERPR ELSE NULL END) AS MOVING_AVG_PRICE_MBEWH,
        MAX(CASE WHEN SRC = 'EBEWH' THEN VERPR ELSE NULL END) AS MOVING_AVG_PRICE_EBEWH,
        MAX(VERPR) AS MAX_MAP_PRICE,
        MIN(VERPR) AS MIN_MAP_PRICE,
        MAX(CASE WHEN SRC = 'MBEWH' THEN STPRS ELSE NULL END) AS STD_PRICE_FROM_MBEWH,
        MAX(CASE WHEN SRC = 'EBEWH' THEN STPRS ELSE NULL END) AS STD_PRICE_FROM_EBEWH,
        SUM(CASE WHEN SRC = 'MBEWH' THEN LBKUM ELSE 0 END) AS STOCK_FROM_MBEWH,
        SUM(CASE WHEN SRC = 'EBEWH' THEN LBKUM ELSE 0 END) AS STOCK_FROM_EBEWH,
        VBELN,
        POSNR
    FROM STOCK_RECORDS 
    GROUP BY MATNR,VBELN,POSNR
    HAVING SUM(CASE WHEN SRC = 'MBEWH' THEN 1 ELSE 0 END) <= 1
)
,FINAL_CALC AS (
SELECT
    BASE.MATNR AS MATERIAL_NUMBER,
    BASE.MOVING_AVG_PRICE_MBEWH,
    BASE.MOVING_AVG_PRICE_EBEWH,
    BASE.STD_PRICE_FROM_MBEWH,
    BASE.STD_PRICE_FROM_EBEWH,
    BASE.STOCK_FROM_MBEWH,
    BASE.STOCK_FROM_EBEWH,
    (BASE.STOCK_FROM_MBEWH + BASE.STOCK_FROM_EBEWH) AS TTL_STOCK,
    PB.SALE_PRICE AS PRICEBOOK_SALE_PRICE,
    BASE.VBELN,
    BASE.POSNR
FROM BASE
LEFT JOIN PB ON (PB.PART_NUMBER = BASE.MATNR)
)
,MAT_FLAG AS (
SELECT DISTINCT
    MATERIAL_NUMBER,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT,
    INTEL_FLAG,
    INTEL_FLAG_TEXT,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS,
    CASE 
    WHEN DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS='Z1' THEN 'Sellable'
    WHEN DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS='Z2' THEN 'Sellable Stock Only'
    WHEN DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS='Z3' THEN 'Internal Sale Only'
    WHEN DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS='Z4' THEN 'NonSellable'
    WHEN DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS='Z5' THEN 'Need Rework to Sell'
    WHEN DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS='Z6' THEN 'Confirm with Vendor'
    WHEN DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS='Z7' THEN 'NonSellable (Temp)'
    ELSE NULL 
    END AS DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS_TEXT
FROM {{ ref('COMMON__REPORTS__MASTER_MATERIAL_REPORT') }}
)
,MSPR_FP12 AS (
SELECT 
MATNR,WERKS,PSPNR,LFGJA,LFMON 
FROM {{ ref('ODS__SAPH__SAP_US_MMT_EV_MSPR') }}
WHERE LFMON='12'
)
,WRITE_DOWN AS (
SELECT DISTINCT
    FINAL_CALC.MATERIAL_NUMBER,
    IFNULL(MOVING_AVG_PRICE_MBEWH,'0') AS MOVING_AVG_PRICE_MBEWH,
    IFNULL(MOVING_AVG_PRICE_EBEWH,'0') AS MOVING_AVG_PRICE_EBEWH,
    IFNULL(STD_PRICE_FROM_MBEWH,'0') AS STD_PRICE_FROM_MBEWH,
    IFNULL(STD_PRICE_FROM_EBEWH,'0') AS STD_PRICE_FROM_EBEWH,
    CASE WHEN STOCK_FROM_EBEWH<>0 AND FINAL_CALC.VBELN IS NULL AND MSPR_FP12.PSPNR IS NULL THEN TTL_STOCK ELSE STOCK_FROM_MBEWH END AS STOCK_FROM_MBEWH,
    CASE WHEN STOCK_FROM_EBEWH<>0 AND FINAL_CALC.VBELN IS NULL AND MSPR_FP12.PSPNR IS NULL THEN 0 ELSE STOCK_FROM_EBEWH END AS STOCK_FROM_EBEWH,
    CASE WHEN STOCK_FROM_EBEWH<>0 AND FINAL_CALC.VBELN IS NULL AND MSPR_FP12.PSPNR IS NULL THEN 'Y' ELSE 'N' END AS SS_FLAG,
    TTL_STOCK,
    PRICEBOOK_SALE_PRICE,
    (1-.079) * PRICEBOOK_SALE_PRICE AS UNIT_NRV,
    (MOVING_AVG_PRICE_MBEWH *STOCK_FROM_MBEWH) AS INVENTORY_VALUE_MBEWH,
    (MOVING_AVG_PRICE_EBEWH *STOCK_FROM_EBEWH) AS INVENTORY_VALUE_EBEWH,
    ((1-.079) * PRICEBOOK_SALE_PRICE) * STOCK_FROM_MBEWH AS EXTENDED_NRV_MBEWH,
    ((1-.079) * PRICEBOOK_SALE_PRICE) * STOCK_FROM_EBEWH AS EXTENDED_NRV_EBEWH,
    CASE WHEN INVENTORY_VALUE_MBEWH > EXTENDED_NRV_MBEWH THEN INVENTORY_VALUE_MBEWH - EXTENDED_NRV_MBEWH ELSE 0 END AS WRITE_DOWN_MBEWH,
    CASE WHEN INVENTORY_VALUE_EBEWH > EXTENDED_NRV_EBEWH THEN INVENTORY_VALUE_EBEWH - EXTENDED_NRV_EBEWH ELSE 0 END AS WRITE_DOWN_EBEWH,
    FINAL_CALC.VBELN||'_'||FINAL_CALC.POSNR AS SALES_ORDER_LINE, 
    MSPR_FP12.PSPNR AS WBS_ELEMENT,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT,
    INTEL_FLAG,
    INTEL_FLAG_TEXT,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS_TEXT
FROM FINAL_CALC
LEFT JOIN MAT_FLAG ON FINAL_CALC.MATERIAL_NUMBER=MAT_FLAG.MATERIAL_NUMBER
LEFT JOIN MSPR_FP12 ON FINAL_CALC.MATERIAL_NUMBER = MSPR_FP12.MATNR
)
,TYPE_DATA AS (
SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    MATERIAL_NUMBER,
    CAST(MOVING_AVG_PRICE_MBEWH AS NUMBER(38,2)) AS MOVING_AVG_PRICE_MBEWH,
    CAST(MOVING_AVG_PRICE_EBEWH AS NUMBER(38,2)) AS MOVING_AVG_PRICE_EBEWH,
    CAST(STD_PRICE_FROM_MBEWH AS NUMBER(38,2)) AS STD_PRICE_FROM_MBEWH,
    CAST(STD_PRICE_FROM_EBEWH AS NUMBER(38,2)) AS STD_PRICE_FROM_EBEWH,
    CAST(STOCK_FROM_MBEWH AS NUMBER(38,0)) AS STOCK_FROM_MBEWH,
    CAST(STOCK_FROM_EBEWH AS NUMBER(38,0)) AS STOCK_FROM_EBEWH,
    SS_FLAG,
    CAST(TTL_STOCK AS NUMBER(38,0)) AS TTL_STOCK,
    CAST(PRICEBOOK_SALE_PRICE AS NUMBER(38,2)) AS PRICEBOOK_SALE_PRICE,
    CAST(UNIT_NRV AS NUMBER(38,2)) AS UNIT_NRV,
    CAST(INVENTORY_VALUE_MBEWH AS NUMBER(38,2)) AS INVENTORY_VALUE_MBEWH,
    CAST(INVENTORY_VALUE_EBEWH AS NUMBER(38,2)) AS INVENTORY_VALUE_EBEWH,
    CAST(EXTENDED_NRV_MBEWH AS NUMBER(38,2)) AS EXTENDED_NRV_MBEWH,
    CAST(EXTENDED_NRV_EBEWH AS NUMBER(38,2)) AS EXTENDED_NRV_EBEWH,
    CAST(WRITE_DOWN_MBEWH AS NUMBER(38,2)) AS WRITE_DOWN_MBEWH,
    CAST(WRITE_DOWN_EBEWH AS NUMBER(38,2)) AS WRITE_DOWN_EBEWH,
    SALES_ORDER_LINE,
    WBS_ELEMENT,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR,
    SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT,
    INTEL_FLAG,
    INTEL_FLAG_TEXT,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS_TEXT
FROM WRITE_DOWN
)
SELECT * FROM TYPE_DATA
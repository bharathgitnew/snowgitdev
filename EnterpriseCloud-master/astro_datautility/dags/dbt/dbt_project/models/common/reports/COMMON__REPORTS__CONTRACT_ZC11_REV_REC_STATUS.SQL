WITH SOITEM_SAP AS
(
  SELECT
    VBAP.POSNR AS "SO_ITEM",
    VBAP.VBELN AS "SO",
    CASE
      WHEN VBAP.ZZBAST IN (NULL, '') THEN 'Awaiting for WF requirement Judge/WF not required'
      WHEN VBAP.ZZBAST = 'A' THEN 'Auto Approval'
      WHEN VBAP.ZZBAST = 'C' THEN 'Approved'
      WHEN VBAP.ZZBAST = 'Q' THEN 'Awaiting WF'
      WHEN VBAP.ZZBAST = 'R' THEN 'Rejected'
      WHEN VBAP.ZZBAST = 'P' THEN 'Partially Approved'
      WHEN VBAP.ZZBAST = 'Z' THEN 'Approved for sales and DP cancellation'
      WHEN VBAP.ZZBAST = 'W' THEN 'Rejected for sales and DP cancellation'
      ELSE 'ERROR'
    END AS "SALES_APPROVAL_STATUS",
    CASE
      WHEN VBAP.ZZAPAST IN (NULL, '') THEN 'Awaiting for WF requirement Judge/WF not required'
      WHEN VBAP.ZZAPAST = 'A' THEN 'Auto Approval'
      WHEN VBAP.ZZAPAST = 'C' THEN 'Approved'
      WHEN VBAP.ZZAPAST = 'Q' THEN 'Awaiting WF'
      WHEN VBAP.ZZAPAST = 'R' THEN 'Rejected'
      WHEN VBAP.ZZAPAST = 'P' THEN 'Partially Approved'
      WHEN VBAP.ZZAPAST = 'Z' THEN 'Approved for sales and DP cancellation'
      WHEN VBAP.ZZAPAST = 'W' THEN 'Rejected for sales and DP cancellation'
      ELSE 'ERROR'
    END AS "DP_APPROVAL_STATUS",
    VBAP.GBSTA AS "OVERALL_STATUS",
    VBAP.NETWR AS "NET_VALUE", --move cast logic to transform query
    VBAP.PSTYV AS "ITEM_CATEGORY",
    VBAP.ABGRU AS "REJECTION_REASON",
    VBAP.IS_DELETED,
    VBAP.MATNR AS "MATERIAL_NUMBER"
  FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} as VBAP
),

SOITEM_CRM AS
(
  SELECT
    SOITEM.TEL_COM_CONTRACT_NUMBER AS "CONTRACT_NO",
    SOITEM.TEL_COM_SOW AS "SOW",
    LEFT(SOITEM.TEL_COM_SOW,8) AS "SCOPE",
    SOITEM.TEL_COM_SOITEMNO AS "SO_ITEM"
  FROM {{ ref('ODS__CRM_FILE__TEL_COM_SALESORDERITEM') }} AS SOITEM
),

SOHEADER_SAP AS
(
  SELECT
    VBAK.AUART AS "SO_TYPE",
    VBAK.VBELN AS "SO"
  FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} AS VBAK
),

CON AS
(
  SELECT
      CONTRACT_TITLE,
      MANAGED_BY,
      CONTRACT_NUMBER,
      CONTRACT_TYPE
  FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
),

SOBUSINESS_SAP AS
(
  SELECT
    VBKD.FKDAT AS "BILLING_DATE",
    LEFT(VBKD.FKDAT,7) AS "BILLING_MONTH",
    VBKD.POSNR AS "SO_ITEM",
    VBKD.VBELN AS "SO"
  FROM {{ ref('ODS__SAPH__SAP_US_SDT_EV_VBKD') }} AS VBKD
),

RR_REQUEST AS
(
  SELECT
    SOHEADER_SAP.SO_TYPE,
    SOHEADER_SAP.SO,
    SOITEM_SAP.SO_ITEM,
    SOHEADER_SAP.SO||SOITEM_SAP.SO_ITEM AS SO_SOITEM,
    SOITEM_SAP.SALES_APPROVAL_STATUS,
    SOITEM_SAP.DP_APPROVAL_STATUS,
    SOITEM_SAP.OVERALL_STATUS,
    SOITEM_SAP.NET_VALUE,
    SOITEM_SAP.ITEM_CATEGORY,
    SOITEM_SAP.REJECTION_REASON,
    SOITEM_CRM.CONTRACT_NO,
    SOITEM_CRM.SOW,
    SOITEM_CRM.SCOPE,
    CON.CONTRACT_TITLE ,
    CON.MANAGED_BY,
    CON.CONTRACT_TYPE,
    SOBUSINESS_SAP.BILLING_DATE,
    SOBUSINESS_SAP.BILLING_MONTH
  FROM SOITEM_SAP
  LEFT JOIN SOITEM_CRM
  ON SOITEM_CRM.SO_ITEM = SOITEM_SAP.SO||SOITEM_SAP.SO_ITEM
  LEFT JOIN SOHEADER_SAP
  ON SOHEADER_SAP.SO = SOITEM_SAP.SO
  LEFT JOIN CON
  ON CON.CONTRACT_NUMBER = SOITEM_CRM.CONTRACT_NO
  LEFT JOIN SOBUSINESS_SAP
  ON SOBUSINESS_SAP.SO = SOITEM_SAP.SO
  AND RIGHT('000000'||SOBUSINESS_SAP.SO_ITEM,6) = RIGHT('000000'||SOITEM_SAP.SO_ITEM,6)
  WHERE
  SOHEADER_SAP.SO_TYPE = 'ZC11' AND
  SOITEM_CRM.SO_ITEM IS NOT NULL AND
  SOITEM_SAP.IS_DELETED = 'No' AND
  SOITEM_SAP.MATERIAL_NUMBER <> 'CONTRACT_SALES_RECOGNITION' AND
  IFNULL(SOITEM_SAP.REJECTION_REASON,'') = '' AND
  SOITEM_SAP.ITEM_CATEGORY = 'ZSC3'
),

SOURCE_DATA AS (
SELECT DISTINCT
    CAST(SO_TYPE AS VARCHAR(16777216)) AS SO_TYPE,
    CAST(SO AS VARCHAR(16777216)) AS SO,
    CAST(SO_ITEM AS VARCHAR(16777216)) AS SO_ITEM,
    CAST(SO_SOITEM AS VARCHAR(16777216)) AS SO_SOITEM,
    CAST(CONTRACT_NO AS VARCHAR(16777216)) AS CONTRACT_NO,
    CAST(CONTRACT_TITLE AS VARCHAR(16777216)) AS CONTRACT_TITLE,
    CAST(MANAGED_BY AS VARCHAR(16777216)) AS CONTRACT_MANAGED_BY,
    CAST(CONTRACT_TYPE AS VARCHAR(16777216)) AS CONTRACT_TYPE,
    CAST(SOW AS VARCHAR(16777216)) AS SOW,
    CAST(SCOPE AS VARCHAR(16777216)) AS SCOPE,
    CAST(SALES_APPROVAL_STATUS AS VARCHAR(16777216)) AS SALES_APPROVAL_STATUS,
    CAST(DP_APPROVAL_STATUS AS VARCHAR(16777216)) AS DP_APPROVAL_STATUS,
    CAST(OVERALL_STATUS AS VARCHAR(16777216)) AS OVERALL_STATUS,
    CAST(NET_VALUE AS DECIMAL(15,2)) AS NET_VALUE,
    CAST(BILLING_DATE AS DATE) AS BILLING_DATE,
    CAST(BILLING_MONTH AS VARCHAR(16777216)) AS BILLING_MONTH,
    CAST(ITEM_CATEGORY AS VARCHAR(16777216)) AS ITEM_CATEGORY,
    CAST(REJECTION_REASON AS VARCHAR(16777216)) AS REJECTION_REASON
FROM RR_REQUEST
),

TRANSFORM_DATA AS (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    SO_TYPE,
    SO,
    SO_ITEM,
    SO_SOITEM,
    CONTRACT_NO,
    CONTRACT_TITLE,
    CONTRACT_MANAGED_BY,
    CONTRACT_TYPE,
    SOW,
    SCOPE,
    SALES_APPROVAL_STATUS,
    DP_APPROVAL_STATUS,
    OVERALL_STATUS,
    NET_VALUE,
    BILLING_DATE,
    BILLING_MONTH,
    ITEM_CATEGORY,
    REJECTION_REASON
FROM SOURCE_DATA
),

TYPE_DATA AS (
SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    SO_TYPE,
    SO,
    SO_ITEM,
    SO_SOITEM,
    CONTRACT_NO,
    CONTRACT_TITLE,
    CONTRACT_MANAGED_BY,
    CONTRACT_TYPE,
    SOW,
    SCOPE,
    SALES_APPROVAL_STATUS,
    DP_APPROVAL_STATUS,
    OVERALL_STATUS,
    CAST(NET_VALUE AS NUMBER(15,2)) AS NET_VALUE,
    CAST(BILLING_DATE AS DATE) AS BILLING_DATE,
    BILLING_MONTH,
    ITEM_CATEGORY,
    REJECTION_REASON
FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
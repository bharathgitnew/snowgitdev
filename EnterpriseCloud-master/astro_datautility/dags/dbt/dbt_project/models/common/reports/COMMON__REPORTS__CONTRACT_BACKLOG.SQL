WITH CUSTOMER AS (
	SELECT DISTINCT
    	CUSTOMER_NUMBER
        , NAME_1 AS CUSTOMER_NAME
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE CUSTOMER_FLAG = 'Y'
)

, SALES_DOC_PARTNER_DATA as (
	SELECT DISTINCT
    	SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as SALES_DOCUMENT
        , ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM
        , CUSTOMER_NUMBER
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }}
    WHERE PARTNER_FUNCTION = 'Z6'
)

, MASTER_DATA_SEGMENT AS (
    SELECT DISTINCT
        SAP_CODE
        , SAP_DESCRIPTION AS SEGMENT
    FROM {{ ref('COMMON__SAPH__SAP_SEGMENT') }}
)

, CRM_OPTIONSET_INVOICE_FREQUENCY AS (
    SELECT 
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM  {{ ref('COMMON__CRM__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'cnt_invoicefrequency'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'GLOBAL'
)
, CRM_OPTIONSET_APPROVAL_STATUS AS (
    SELECT 
        OPTIONSETNAME,
        OPTION,
        LOCALIZEDLABEL
    FROM {{ ref('COMMON__CRM__OPTIONSET_METADATA') }}
    WHERE 1=1
        AND OPTIONSETNAME = 'cnt_approvalstatus'
        AND LOCALIZEDLABELLANGUAGECODE = 1033
        AND SOURCE_FLAG = 'LOCAL'
)

, CRM_FAB AS (
	SELECT DISTINCT
    	CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
        , LISTAGG(DISTINCT ACCOUNTNUMBER, ', ') OVER (PARTITION BY CNT_CONTRUCTNUMBER) AS FAB_CODE
        , LISTAGG(DISTINCT NAME, ', ') OVER (PARTITION BY CNT_CONTRUCTNUMBER) AS FAB_NAME
    FROM {{ ref('COMMON__CRM__CONTRACT_SUMMARY_ACCOUNT') }}
)
, CRM_CONTRACTS AS (
	SELECT DISTINCT
    	CONTRACT_SUMMARY_DETAILS.ID_CONTRACT_SUMMARY
        , CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
        , CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTSTARTDATE AS CONTRACT_START_DATE
		, CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTENDDATE AS CONTRACT_END_DATE
        , CRM_OPTIONSET_INVOICE_FREQUENCY.LOCALIZEDLABEL AS INSTALLMENT_TIMING
        , CRM_OPTIONSET_APPROVAL_STATUS.LOCALIZEDLABEL AS APPROVAL_STATUS
        , CONTRACT_SUMMARY_DETAILS.MSDYN_NAME AS CONTRACT_SCOPE_NUMBER
        , CONTRACT_SUMMARY_DETAILS.CNT_PRODUCT_CONTRACT_SUMMARY AS CONTRACT_PRODUCTS
        , CONTRACT_SUMMARY_DETAILS.CNT_PRODUCT_AGREEMENT AS BU_CRM_SCOPE
        , LISTAGG(DISTINCT CNT_NAME,', ') OVER (PARTITION BY CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER) AS SCOPE_CONSUMPTION_TYPE
        , CRM_FAB.FAB_CODE
        , CRM_FAB.FAB_NAME
    FROM {{ ref('COMMON__CRM__CONTRACT_SUMMARY_DETAILS') }} AS CONTRACT_SUMMARY_DETAILS
        LEFT JOIN CRM_FAB
            ON CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER = CRM_FAB.CONTRACT_NUMBER
        LEFT JOIN CRM_OPTIONSET_INVOICE_FREQUENCY
            ON TRY_TO_NUMBER(CONTRACT_SUMMARY_DETAILS.CNT_INVOICEFREQUENCY)=TRY_TO_NUMBER(CRM_OPTIONSET_INVOICE_FREQUENCY.OPTION)
        LEFT JOIN CRM_OPTIONSET_APPROVAL_STATUS
            ON TRY_TO_NUMBER(CONTRACT_SUMMARY_DETAILS.CNT_APPROVALSTATUS) = TRY_TO_NUMBER(CRM_OPTIONSET_APPROVAL_STATUS.OPTION)
)

, VBAK_HIST AS (
    SELECT DISTINCT
        VBELN AS SALES_DOCUMENT
        , ERDAT AS CREATE_DATE
        , AUART AS SALES_DOCUMENT_TYPE
        , BSTNK AS CUSTOMER_REFERENCE
        , BSTDK as CUSTOMER_REFERENCE_DATE
        , ZZCNZZ AS CONTRACT_NUMBER
        , KUNNR AS SOLD_TO_PARTY
        , AUDAT AS SALES_DOCUMENT_DATE
        , NETWR AS NET_VALUE
        , SNAPSHOT_DATE
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK_HIST') }}
    WHERE 1=1
        and VKORG = '3200'
        and SNAPSHOT_DATE-1 <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN ORDER BY SNAPSHOT_DATE DESC )) = 1 
)
, VBAP_HIST AS (
    SELECT * FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP_HIST') }}
)
, VBAP_HIST_RECENT AS ( -- TO CAPTURE ALL SALES ORDER LINES EVEN IF CREATED AT A LATER DATE
    SELECT
        VBELN AS SALES_DOCUMENT
        , POSNR AS SALES_DOCUMENT_ITEM
        , ZZORTY AS SALES_CATEGORY
        , PRCTR as PROFIT_CENTER
        , KOSTL AS COST_CENTER
        , NETWR AS SALES_ITEM_AMT
        , SNAPSHOT_DATE
    FROM VBAP_HIST
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1 
)
, VBAP_HIST_EOM AS ( -- CAPTURE STATUS AS-OF THE LAST DAY OF THE MONTH
    SELECT
        VBELN AS SALES_DOCUMENT
        , POSNR AS SALES_DOCUMENT_ITEM 
        , ABGRU AS REJECTION_REASON_SALES_ITEM
        , SNAPSHOT_DATE
    from VBAP_HIST
    WHERE 1=1
        AND SNAPSHOT_DATE-1 <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
        AND ABGRU <> ''
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1 
)
, VBAP_HIST_AS_OF AS ( -- FOR ALL SO LINES NOT REJECTED AS OF THE LAST OF THE MONTH
    SELECT * 
    FROM VBAP_HIST_RECENT
    WHERE VBAP_HIST_RECENT.SALES_DOCUMENT || VBAP_HIST_RECENT.SALES_DOCUMENT_ITEM NOT IN (
        SELECT SALES_DOCUMENT || SALES_DOCUMENT_ITEM FROM VBAP_HIST_EOM
        )
)

, VBRK_HIST AS (
    SELECT * FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU014_VBRK_HIST') }}
)
, VBRK_HIST_RECENT AS ( --TO CAPTURE DOCUMENTS WITH BILLING DATE <= LAST DAY OF MONTH EVEN IF THEY WERE CREATED AFTER THE END OF THE MONTH
    SELECT
        VBELN as BILLING_DOCUMENT
        , FKDAT AS BILLING_DATE
        , FKART AS BILLING_TYPE
        , FKSTO AS BILLING_DOC_IS_CANCELED
        , SFAKN AS CANCELLED_BILLING_DOCUMENT
        , SNAPSHOT_DATE
    FROM VBRK_HIST
    WHERE 1=1
        AND VKORG = '3200'
        AND TRY_TO_DATE(FKDAT, 'YYYYMMDD') <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN ORDER BY SNAPSHOT_DATE DESC )) = 1
)
, VBRK_HIST_EOM AS ( -- TO CAPTURE BILLING DOCUMENT CANCELLED AS OF THE END OF THE MONTH
    SELECT
        VBELN as BILLING_DOCUMENT
        , FKDAT AS BILLING_DATE
        , FKART AS BILLING_TYPE
        , FKSTO AS BILLING_DOC_IS_CANCELED
        , SFAKN AS CANCELLED_BILLING_DOCUMENT
    FROM VBRK_HIST
    WHERE SNAPSHOT_DATE-1 <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN ORDER BY SNAPSHOT_DATE DESC)) = 1 
)
, VBRK_HIST_AS_OF AS (
    SELECT
        VBRK_HIST_RECENT.BILLING_DOCUMENT
        , VBRK_HIST_RECENT.BILLING_DATE
        , VBRK_HIST_RECENT.BILLING_TYPE
        , VBRK_HIST_EOM.BILLING_DOC_IS_CANCELED AS BILLING_DOC_IS_CANCELED
        , VBRK_HIST_EOM.CANCELLED_BILLING_DOCUMENT AS CANCELLED_BILLING_DOCUMENT
    FROM VBRK_HIST_RECENT
        LEFT JOIN VBRK_HIST_EOM
            ON VBRK_HIST_RECENT.BILLING_DOCUMENT = VBRK_HIST_EOM.BILLING_DOCUMENT
)

, VBRP_HIST AS (
    SELECT
        PRCTR AS PROFIT_CENTER
        , VBELN as BILLING_DOCUMENT
        , POSNR AS BILLING_DOCUMENT_ITEM
        , AUBEL AS SALES_DOCUMENT
        , AUPOS AS SALES_DOCUMENT_ITEM
        , NETWR AS BILLING_ITEM_AMT
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU015_VBRP_HIST') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1
)

, CANCELLED_BILL AS (
    SELECT
        VBRK_HIST_AS_OF.BILLING_DOCUMENT AS BILLING_DOCUMENT
        , VBRK_HIST_AS_OF.BILLING_DOC_IS_CANCELED
        , VBRK_HIST_AS_OF.CANCELLED_BILLING_DOCUMENT AS CANCELLED_BILLING_DOCUMENT
        , VBRP_HIST.BILLING_DOCUMENT_ITEM AS CANCELLED_BILLING_DOCUMENT_ITEM
    FROM VBRK_HIST_AS_OF
        LEFT JOIN VBRP_HIST
            ON VBRK_HIST_AS_OF.BILLING_DOCUMENT = VBRP_HIST.BILLING_DOCUMENT
    WHERE BILLING_DOC_IS_CANCELED = true
        OR CANCELLED_BILLING_DOCUMENT <> ''
)
, BILLING AS (
    SELECT
        VBRK_HIST_AS_OF.BILLING_DOCUMENT AS BILLING_DOCUMENT
        , VBRP_HIST.BILLING_DOCUMENT_ITEM
        , VBRK_HIST_AS_OF.BILLING_DATE AS BILLING_DATE
        , VBRK_HIST_AS_OF.BILLING_TYPE AS BILLING_TYPE
        , VBRK_HIST_AS_OF.BILLING_DOC_IS_CANCELED AS BILLING_DOC_IS_CANCELED
        , VBRK_HIST_AS_OF.CANCELLED_BILLING_DOCUMENT AS CANCELLED_BILLING_DOCUMENT
        , VBRP_HIST.PROFIT_CENTER AS VBRP_PROFIT_CENTER
        , VBRP_HIST.SALES_DOCUMENT
        , VBRP_HIST.SALES_DOCUMENT_ITEM
        , VBRP_HIST.BILLING_ITEM_AMT
    FROM VBRK_HIST_AS_OF
        LEFT JOIN VBRP_HIST
            ON VBRK_HIST_AS_OF.BILLING_DOCUMENT = VBRP_HIST.BILLING_DOCUMENT
    WHERE VBRK_HIST_AS_OF.BILLING_DOCUMENT || VBRP_HIST.BILLING_DOCUMENT_ITEM NOT IN (
        SELECT CANCELLED_BILLING_DOCUMENT || CANCELLED_BILLING_DOCUMENT_ITEM FROM CANCELLED_BILL
        )
)
, SOBL_HIST AS (
    SELECT
        VBAK_HIST.CONTRACT_NUMBER
        , VBAK_HIST.SALES_DOCUMENT_DATE
        , VBAK_HIST.SALES_DOCUMENT_TYPE
        , VBAK_HIST.SOLD_TO_PARTY
        , VBAK_HIST.CUSTOMER_REFERENCE
        , VBAK_HIST.CUSTOMER_REFERENCE_DATE
        , VBAK_HIST.SALES_DOCUMENT
        , VBAK_HIST.CREATE_DATE
        , VBAK_HIST.NET_VALUE AS VBAK_NET_VALUE
        , VBAP_HIST_AS_OF.PROFIT_CENTER
        , VBAP_HIST_AS_OF.SALES_DOCUMENT_ITEM
        , VBAP_HIST_AS_OF.SALES_CATEGORY
        , VBAP_HIST_AS_OF.SALES_ITEM_AMT
        , BILLING.BILLING_TYPE
        , BILLING.VBRP_PROFIT_CENTER
        , BILLING.BILLING_DOCUMENT
        , BILLING.SALES_DOCUMENT_ITEM
        , BILLING.BILLING_ITEM_AMT
        , CASE
            WHEN SUBSTRING(MASTER_DATA_SEGMENT.SEGMENT,CHARINDEX('-',MASTER_DATA_SEGMENT.SEGMENT)+1,LEN(MASTER_DATA_SEGMENT.SEGMENT)) <> '3DI Bonder'
                THEN SUBSTRING(MASTER_DATA_SEGMENT.SEGMENT,CHARINDEX('-',MASTER_DATA_SEGMENT.SEGMENT)+1,LEN(MASTER_DATA_SEGMENT.SEGMENT))
        ELSE '3DI'
        END AS BU_BILLING
    FROM VBAK_HIST
        LEFT JOIN VBAP_HIST_AS_OF
            ON VBAK_HIST.SALES_DOCUMENT = VBAP_HIST_AS_OF.SALES_DOCUMENT
        LEFT JOIN BILLING
            ON VBAP_HIST_AS_OF.SALES_DOCUMENT = BILLING.SALES_DOCUMENT
            AND VBAP_HIST_AS_OF.SALES_DOCUMENT_ITEM = BILLING.SALES_DOCUMENT_ITEM
        LEFT JOIN MASTER_DATA_SEGMENT
            ON SUBSTRING(BILLING.VBRP_PROFIT_CENTER, 4, 2) = MASTER_DATA_SEGMENT.SAP_CODE
    WHERE VBAK_HIST.SALES_DOCUMENT_TYPE IN ('ZC11', 'ZSC1')
)

, ZC11_SO AS (
    SELECT *  FROM SOBL_HIST WHERE SALES_DOCUMENT_TYPE = 'ZC11'
)

, MIN_CONTRACT_DATE AS (
    SELECT contract_number, MIN(CREATE_DATE) AS CREATE_DATE
    FROM ZC11_SO
    GROUP BY contract_number
)

, CONTRACT_CREATE as (
    SELECT DISTINCT MIN_CONTRACT_DATE.CONTRACT_NUMBER, MIN(ZC11_SO.customer_reference_date) AS customer_reference_date
    from MIN_CONTRACT_DATE
        INNER JOIN ZC11_SO
            ON MIN_CONTRACT_DATE.CONTRACT_NUMBER = ZC11_SO.CONTRACT_NUMBER
            AND MIN_CONTRACT_DATE.CREATE_DATE = ZC11_SO.CREATE_DATE
    GROUP BY MIN_CONTRACT_DATE.CONTRACT_NUMBER
)

, REVENUE_RECOGNITION AS (
    SELECT DISTINCT
        SALES_DOCUMENT
        , CONTRACT_NUMBER
        , LISTAGG(DISTINCT SALES_CATEGORY, ', ') OVER (PARTITION BY CONTRACT_NUMBER) AS SALES_CATEGORY_BILLING
        , LISTAGG(DISTINCT VBRP_PROFIT_CENTER, ', ') OVER (PARTITION BY CONTRACT_NUMBER) AS PROFIT_CENTER_BILLING
        , BU_BILLING
        , SUM(BILLING_ITEM_AMT) OVER(PARTITION BY CONTRACT_NUMBER, BU_BILLING) AS REVENUE_RECOGNIZED
    FROM ZC11_SO
    WHERE BILLING_TYPE = 'ZC11'
)

, CONTRACT_SCOPE AS (
    SELECT DISTINCT
        SOBL_HIST.CONTRACT_NUMBER
        , SOBL_HIST.CUSTOMER_REFERENCE AS CRM_SCOPE
        , CRM_CONTRACTS.CONTRACT_PRODUCTS
        , CASE
            WHEN CRM_CONTRACTS.BU_CRM_SCOPE IS NOT NULL THEN CRM_CONTRACTS.BU_CRM_SCOPE
            WHEN CRM_CONTRACTS.BU_CRM_SCOPE IS NULL AND CRM_CONTRACTS.CONTRACT_PRODUCTS IS NULL THEN 'N/A'
            WHEN CRM_CONTRACTS.BU_CRM_SCOPE IS NULL THEN CRM_CONTRACTS.CONTRACT_PRODUCTS
            ELSE 'NO BU'
        END AS BU_CRM_SCOPE
        , SOBL_HIST.VBAK_NET_VALUE
    FROM SOBL_HIST
        LEFT JOIN CRM_CONTRACTS
            ON SOBL_HIST.CUSTOMER_REFERENCE = CRM_CONTRACTS.CONTRACT_SCOPE_NUMBER
    WHERE 1=1
        AND SOBL_HIST.SALES_DOCUMENT_TYPE = 'ZSC1'
        AND SOBL_HIST.CUSTOMER_REFERENCE <> ''
)
, ZC11_AND_SCOPE AS (
    SELECT DISTINCT
        ZC11_SO.SOLD_TO_PARTY AS ZC11_SOLD_TO_PARTY
        , ZC11_SO.CUSTOMER_REFERENCE AS ZC11_CUSTOMER_REFERENCE
        , ZC11_SO.CUSTOMER_REFERENCE_DATE AS ZC11_SO_CUSTOMER_REFERENCE_DATE
        , ZC11_SO.CONTRACT_NUMBER
        , CRM_SCOPE
        , ZC11_SO.SALES_DOCUMENT AS ZC11_SALES_DOCUMENT
        , CASE
            WHEN BU_CRM_SCOPE IS NOT NULL THEN BU_CRM_SCOPE
            ELSE 'NO SCOPE'
        END AS BU_CRM_SCOPE
        , CONTRACT_SCOPE.VBAK_NET_VALUE
    FROM ZC11_SO
        LEFT JOIN CONTRACT_SCOPE
            ON ZC11_SO.CONTRACT_NUMBER = CONTRACT_SCOPE.CONTRACT_NUMBER
)

, BU_AMT AS (
    SELECT 
        ZC11_SOLD_TO_PARTY
        , ZC11_CUSTOMER_REFERENCE
        , ZC11_SO_CUSTOMER_REFERENCE_DATE
        , ZC11_SALES_DOCUMENT
        , CONTRACT_NUMBER
        , CRM_SCOPE
        , BU_CRM_SCOPE
        , SUM(VBAK_NET_VALUE) OVER (PARTITION BY ZC11_SALES_DOCUMENT, BU_CRM_SCOPE) as NET_VALUE
    FROM ZC11_AND_SCOPE
)
 
, CONTRACT_TOTAL AS (
    SELECT DISTINCT
        CONTRACT_NUMBER
        , SUM(VBAK_NET_VALUE) AS TOTAL_CONTRACT_AMT
    FROM CONTRACT_SCOPE
    GROUP BY CONTRACT_NUMBER
)

, SOURCE_DATA AS (
    SELECT DISTINCT
        COALESCE(ZC11_SO.SOLD_TO_PARTY, BU_AMT.ZC11_SOLD_TO_PARTY) AS SOLD_TO
        , CUSTOMER.CUSTOMER_NAME AS SOLD_TO_NAME
        , listagg(distinct SALES_DOC_PARTNER_DATA.CUSTOMER_NUMBER,', ') OVER (PARTITION BY COALESCE(ZC11_SO.CONTRACT_NUMBER, BU_AMT.CONTRACT_NUMBER)) as END_USER
        , listagg(distinct END_USER.CUSTOMER_NAME,', ') OVER (PARTITION BY COALESCE(ZC11_SO.CONTRACT_NUMBER, BU_AMT.CONTRACT_NUMBER)) as END_USER_NAME
        , listagg(distinct COALESCE(ZC11_SO.CUSTOMER_REFERENCE, BU_AMT.ZC11_CUSTOMER_REFERENCE), ', ') OVER (PARTITION BY COALESCE(ZC11_SO.CONTRACT_NUMBER, BU_AMT.CONTRACT_NUMBER)) AS CUSTOMER_PO
        , COALESCE(ZC11_SO.CONTRACT_NUMBER, BU_AMT.CONTRACT_NUMBER) AS CONTRACT_NUMBER
        , CRM_CONTRACTS.APPROVAL_STATUS
        , BU_AMT.ZC11_SO_CUSTOMER_REFERENCE_DATE
        , CONTRACT_CREATE.CUSTOMER_REFERENCE_DATE
        , CRM_CONTRACTS.CONTRACT_START_DATE
        , CRM_CONTRACTS.CONTRACT_END_DATE
        , CRM_CONTRACTS.INSTALLMENT_TIMING
        , listagg(distinct COALESCE(ZC11_SO.SALES_DOCUMENT, BU_AMT.ZC11_SALES_DOCUMENT),', ') OVER (PARTITION BY COALESCE(ZC11_SO.CONTRACT_NUMBER, BU_AMT.CONTRACT_NUMBER)) AS SALES_DOCUMENT
        , REVENUE_RECOGNITION.PROFIT_CENTER_BILLING
        , REVENUE_RECOGNITION.SALES_CATEGORY_BILLING
        , BU_AMT.BU_CRM_SCOPE
        , REVENUE_RECOGNITION.BU_BILLING
        , CRM_CONTRACTS.SCOPE_CONSUMPTION_TYPE
        , CONTRACT_TOTAL.TOTAL_CONTRACT_AMT
        , BU_AMT.NET_VALUE AS VALUE_BY_BU
        , REVENUE_RECOGNITION.REVENUE_RECOGNIZED
        , CRM_CONTRACTS.FAB_CODE
        , CRM_CONTRACTS.FAB_NAME
        , LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH') AS AS_OF_DATE
    FROM ZC11_SO
        LEFT JOIN REVENUE_RECOGNITION
            ON ZC11_SO.contract_number = REVENUE_RECOGNITION.contract_number
            and ZC11_SO.BU_BILLING = REVENUE_RECOGNITION.BU_BILLING
        FULL OUTER JOIN BU_AMT
            ON REVENUE_RECOGNITION.CONTRACT_NUMBER = BU_AMT.CONTRACT_NUMBER
            AND REVENUE_RECOGNITION.BU_BILLING = BU_AMT.BU_CRM_SCOPE
        LEFT JOIN CONTRACT_TOTAL
            ON COALESCE(ZC11_SO.CONTRACT_NUMBER, BU_AMT.CONTRACT_NUMBER) = CONTRACT_TOTAL.CONTRACT_NUMBER
        LEFT JOIN CRM_CONTRACTS
            ON COALESCE(ZC11_SO.CONTRACT_NUMBER, BU_AMT.CONTRACT_NUMBER) = CRM_CONTRACTS.CONTRACT_NUMBER
        LEFT JOIN CONTRACT_CREATE
            ON ZC11_SO.CONTRACT_NUMBER = CONTRACT_CREATE.CONTRACT_NUMBER
        LEFT JOIN SALES_DOC_PARTNER_DATA
            ON COALESCE(ZC11_SO.SALES_DOCUMENT, BU_AMT.ZC11_SALES_DOCUMENT) = SALES_DOC_PARTNER_DATA.SALES_DOCUMENT
            AND 0 = TRY_TO_NUMBER(SALES_DOC_PARTNER_DATA.SALES_DOCUMENT_ITEM)   
        LEFT JOIN CUSTOMER
            ON COALESCE(ZC11_SO.SOLD_TO_PARTY, BU_AMT.ZC11_SOLD_TO_PARTY) = CUSTOMER.CUSTOMER_NUMBER
        LEFT JOIN CUSTOMER AS END_USER
            ON SALES_DOC_PARTNER_DATA.CUSTOMER_NUMBER = END_USER.CUSTOMER_NUMBER
            AND 0 = TRY_TO_NUMBER(SALES_DOC_PARTNER_DATA.SALES_DOCUMENT_ITEM)   
    WHERE (REVENUE_RECOGNITION.BU_BILLING IS NOT NULL OR BU_AMT.BU_CRM_SCOPE IS NOT NULL)
),

TRANSFORM_DATA AS (
	SELECT DISTINCT
    	'{{ invocation_id }}' AS AUDIT_LOG_ID
        , SHA2('hash_me') AS _ROW_HASH
        , SOLD_TO
        , SOLD_TO_NAME
        , END_USER
        , END_USER_NAME
        , CUSTOMER_PO
        , TRY_TO_DATE((COALESCE(CUSTOMER_REFERENCE_DATE,ZC11_SO_CUSTOMER_REFERENCE_DATE)),'YYYYMMDD') AS CONTRACT_CREATE_DATE
        , SALES_DOCUMENT
        , CONTRACT_NUMBER
        , APPROVAL_STATUS        
        , TO_VARCHAR(TO_TIMESTAMP_TZ(CONTRACT_START_DATE), 'MM/DD/YYYY') AS CONTRACT_START_DATE
        , TO_VARCHAR(TO_TIMESTAMP_TZ(CONTRACT_END_DATE), 'MM/DD/YYYY') AS CONTRACT_END_DATE
        , INSTALLMENT_TIMING
        , PROFIT_CENTER_BILLING
        , SALES_CATEGORY_BILLING
        , BU_CRM_SCOPE
        , TRIM(BU_BILLING) AS BU_BILLING
        , SCOPE_CONSUMPTION_TYPE
        , TOTAL_CONTRACT_AMT
        , ROUND(VALUE_BY_BU,2) AS VALUE_BY_BU
        , ROUND(REVENUE_RECOGNIZED,2) AS REVENUE_RECOGNIZED
        , (ZEROIFNULL(VALUE_BY_BU) - ZEROIFNULL(REVENUE_RECOGNIZED)) AS BACKLOG_AMT
        , FAB_CODE
        , FAB_NAME
        , AS_OF_DATE
    from SOURCE_DATA
),

TYPE_DATA AS (
	SELECT
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        , CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
        , SOLD_TO
        , SOLD_TO_NAME
        , END_USER
        , END_USER_NAME
        , CUSTOMER_PO
        , CONTRACT_CREATE_DATE
        , SALES_DOCUMENT
        , CONTRACT_NUMBER
        , APPROVAL_STATUS
        , CAST(CONTRACT_START_DATE AS DATE) AS CONTRACT_START_DATE
        , CAST(CONTRACT_END_DATE AS DATE) AS CONTRACT_END_DATE
        , INSTALLMENT_TIMING
        , PROFIT_CENTER_BILLING
        , SALES_CATEGORY_BILLING
        , BU_CRM_SCOPE
        , BU_BILLING
        , SCOPE_CONSUMPTION_TYPE
        , CAST(TOTAL_CONTRACT_AMT AS NUMBER(38,2)) AS TOTAL_CONTRACT_AMT
        , CAST(VALUE_BY_BU AS NUMBER(38,2)) AS VALUE_BY_BU
        , CAST(REVENUE_RECOGNIZED AS NUMBER(38,2)) AS REVENUE_RECOGNIZED
        , CAST(BACKLOG_AMT AS NUMBER(38,2)) AS BACKLOG_AMT
        , FAB_CODE
        , FAB_NAME
        , CAST(AS_OF_DATE AS DATE) AS AS_OF_DATE
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
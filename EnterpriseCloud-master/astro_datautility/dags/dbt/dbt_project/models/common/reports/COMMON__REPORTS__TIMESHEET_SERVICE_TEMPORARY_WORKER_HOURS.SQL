{{ config(
    alias='TIMESHEET_SERVICE_TEMPORARY_WORKER_HOURS',
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    tags=['kronos'],
) }}

with CALENDAR_DATE as (
    SELECT 
      CALENDAR_DATE, 
      SUBCONTRACTOR_WORK_WEEK_ENDING_DATE
    FROM {{ source('COMMON__DE_SAP_MASTER_DATA', 'CALENDAR_DATE') }} 
),

TEACOMMON_EMPLOYEE as (
    SELECT DISTINCT 
      EMPLOYEEID, 
      EMPLOYEETYPE, 
      VENDORNAME, 
      COSTCENTER 
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
),

source_data as 
(
  SELECT 
    TS.EMPLOYEEFULLNAME,
    TS.EMPLOYEEID,
    TS.APPROVINGSUPERVISOR, 
    D.SUBCONTRACTOR_WORK_WEEK_ENDING_DATE,
    TS.EVENTDATE,
    '' AS BU, //intentionally blank
    '' AS OFFICE, //intentionally blank
    EMP.VENDORNAME,
    'Hours Worked' AS PAYCODE, //return 'Hours Worked' for PAYCODE
    TS.HOURSCHARGED,
    TYPEOFWORKSOURCE,
    TS.TASK,
    TS.PAYCODENAME,
    TS.SHIFTNUMBER,
    TS.STARTDATETIMESTAMP,
    TS.ENDDATETIMESTAMP, 
    '' AS ENTERED_DATE, //intentionally blank
    SUBSTR(EMP.COSTCENTER,2,2) AS EMP_COMPANY, 
    TS.EMPLOYEEDEPARTMENTID,
    TS.EMPLOYEEBUCODE,
    '' AS EMP_OFFICE_CODE, //intentionally blank
    '' AS NOTES //intentionally blank
FROM {{ ref('COMMON__REPORTS__TIMESHEET') }} TS //COMMON.REPORTS.TIMESHEET
JOIN CALENDAR_DATE D ON TS.EVENTDATE = D.CALENDAR_DATE //PUB.DE_OPERATIONS.CALENDAR_DATE
LEFT OUTER JOIN TEACOMMON_EMPLOYEE EMP ON TS.EMPLOYEEID = EMP.EMPLOYEEID //COMMON.TEACOMMON.EMPLOYEE
WHERE D.SUBCONTRACTOR_WORK_WEEK_ENDING_DATE BETWEEN DATEADD(DAYS, -14, CURRENT_DATE) and CURRENT_DATE //filter on previous two subcon work weeks
 AND EMP.EMPLOYEETYPE = 3 //filter on Temp Worker Employee Type 
), 

transform_data as (
  select 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    EMPLOYEEFULLNAME AS EMPLOYEE,
    EMPLOYEEID AS EMP_ID,
    APPROVINGSUPERVISOR AS SUPERVISOR, 
    SUBCONTRACTOR_WORK_WEEK_ENDING_DATE AS WEEK_ENDING,
    EVENTDATE,
    BU, 
    OFFICE, 
    VENDORNAME AS VENDOR,
    PAYCODE, 
    HOURSCHARGED AS TASK_HOURS,
    TYPEOFWORKSOURCE AS TYPE_OF_WORK,
    TASK,
    PAYCODENAME AS WORK_RULE_NAME,
    SHIFTNUMBER AS SHIFT,
    STARTDATETIMESTAMP AS START_TIME,
    ENDDATETIMESTAMP  AS END_TIME, 
    ENTERED_DATE, 
    EMP_COMPANY, 
    EMPLOYEEDEPARTMENTID AS EMP_DEPT_CODE,
    EMPLOYEEBUCODE AS EMP_SEGMENT_CODE,
    EMP_OFFICE_CODE, 
    NOTES 
  from source_data
),

type_data as (
  select 
    _AUDIT_LOG_ID, 
    _ROW_HASH, 
    EMPLOYEE,
    EMP_ID,
    SUPERVISOR, 
    WEEK_ENDING, 
    EVENTDATE,
    BU, 
    OFFICE, 
    VENDOR,
    PAYCODE, 
    TASK_HOURS,
    TYPE_OF_WORK,
    TASK,
    WORK_RULE_NAME,
    SHIFT,
    START_TIME,
    END_TIME, 
    ENTERED_DATE, 
    EMP_COMPANY, 
    EMP_DEPT_CODE,
    EMP_SEGMENT_CODE,
    EMP_OFFICE_CODE, 
    NOTES 
  from transform_data
) 

select * from type_data
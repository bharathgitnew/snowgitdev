WITH ZS10 AS (
    SELECT
        SOLD_TO_PARTY_CODE AS CUSTOMER_SOLD_TO_CODE
        ,SOLD_TO_PARTY AS CUSTOMER_SOLD_TO
        ,SALES_ORDER_HEADER_NUMBER AS ZS10_SALES_ORDER
        ,SALES_ORDER_LINE_NUMBER
        ,SO_ID
        ,MATERIAL_NUMBER
        ,MATERIAL_GROUP
        ,MATERIAL_DESCRIPTION
        ,TOOL_SERIAL_NO AS SERIAL_NUMBER
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_LINE_MASTER') }}
    WHERE 1=1
      AND SALES_DOC_TYPE = 'ZS10'
    --AND SALES_ORDER_HEADER_NUMBER = '100607350'
    ORDER BY SO_ID )

,BILLING AS (
    SELECT
        VBAK_SALES_DOCUMENT||SALES_DOCUMENT_ITEM_POSNR AS SO_ID
        ,DOCUMENT_DATE
    ,CASE
        WHEN LEN(CUSTOMER_REFERENCE) < 1 THEN NULL
    ELSE CUSTOMER_REFERENCE
    END AS CUSTOMER_PO
    ,CASE
        WHEN LEN(ITEM_NUMBER_OF_THE_UNDERLYING_PURCHASE_ORDER) < 1 THEN NULL
    ELSE ITEM_NUMBER_OF_THE_UNDERLYING_PURCHASE_ORDER
    END AS CUSTOMER_PO_LINE
        ,TRY_TO_DATE(CUSTOMER_REFERENCE_DATE,'YYYYMMDD') AS CUSTOMER_PO_DATE
        ,TRY_TO_DATE(DOCUMENT_DATE,'YYYYMMDD') AS SALES_DOCUMENT_DATE
        ,VBAK_DATE_OF_LAST_CHANGE
        ,TRY_TO_DATE(SALES_BILLING_DATE,'YYYYMMDD')  AS BILLING_DATE
        ,VBAK_BILLING_STATUS AS BILLING_STATUS
    ,CASE
        WHEN VBAK_BILLING_STATUS = 'A' THEN 'OPEN'
        WHEN VBAK_BILLING_STATUS = 'B' THEN 'PARTIALLY PROCESSED'
        WHEN VBAK_BILLING_STATUS = 'C' THEN 'INVOICED'
        WHEN VBAK_BILLING_STATUS = 'D' THEN 'REJECTED'
        WHEN VBAK_BILLING_STATUS = 'E' THEN 'BILLING REJECTED'
    ELSE NULL
    END AS BILLING_STATUS_DESC
        ,VBAK_OVERALL_PROCESSING_STATUS_OF_DOCUMENT
        ,VBAK_OVERALL_BLOCKED_STATUS
        ,PAYMENT_CATEGORY_NAME
    ,CASE
        WHEN LEN(SERVICE_CRM_WO_NO) < 1 THEN NULL
    ELSE SERVICE_CRM_WO_NO
    END AS CRM_WO_NO
        ,VBAP_SALES_DOCUMENT_ITEM_CATEGORY AS ITEM_CATEGORY
        ,NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY AS NET_VALUE
        ,CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS AS QTY
        ,VBAP_SALES_UNIT AS SALES_UNIT
        ,VBAP_PROFIT_CENTER AS PROFIT_CENTER
        ,VBAP_ITEM_CREDIT_PRICE_CMPRE AS UNIT_PRICE
        ,REJECTION_STATUS_FOR_SALES_DOCUMENT_ITEM
        ,VBAP_BILLING_STATUS_FOR_ORDER_RELATED_BILLING_DOCUMENTS
        ,VBAP_OVERALL_PROCESSING_STATUS_OF_THE_SD_DOCUMENT_ITEM
    ,CASE
        WHEN LEN(SALES_APPROVAL_STATUS) < 1 THEN NULL
    ELSE SALES_APPROVAL_STATUS
    END AS SALES_APPROVAL_STATUS
    ,CASE
        WHEN SALES_APPROVAL_STATUS = 'C' THEN  'APPROVED'
        WHEN SALES_APPROVAL_STATUS = 'R' THEN 'REJECTED'
        WHEN SALES_APPROVAL_STATUS = 'Z' THEN 'APPROVED FOR SALES AND DP CANCELLATION'
    ELSE NULL
    END AS SALES_APPROVAL_STATUS_DESC
        ,VBAP_ORDER_ITEM_NAME
    ,CASE
        WHEN LEN(VBAP_PRODUCT_CODE) < 1 THEN NULL
    ELSE VBAP_PRODUCT_CODE
    END AS PRODUCT_CODE
        ,VBAP_SALES_CATEGORY AS SALES_CATEGORY
    ,CASE
        WHEN LEN(QUOTE_NO)> 1 THEN QUOTE_NO
    ELSE NULL
    END AS QUOTE
    ,CASE
        WHEN LEN(CUSTOMER_REQUEST_NO)>1 THEN CUSTOMER_REQUEST_NO
    ELSE NULL
    END AS BAAN_SO
        ,SALES_BILLING_DOCUMENT AS BILLING_DOCUMENT
        ,SALES_BILLING_TYPE AS BILLING_TYPE
        ,SALES_BILLING_CATEGORY
        ,SALES_ACCOUNTING_DOCUMENT_NUMBER
        ,SALES_PAYER
        ,SALES_SOLD_TO_PARTY
        ,SALES_REFERENCE_DOCUMENT_NUMBER
        ,SALES_BILLING_DOCUMENT_IS_CANCELED AS BILLING_DOCUMENT_IS_CANCELED
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE = 'ZS10')
,
CGM AS (
SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_GROUP_MAPPING') }}
)
,CUSTOMER AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER,
        NAME_1_OF_ORGANIZATION AS CUSTOMER_NAME,
        SEARCH_TERM_2_FOR_BUSINESS_PARTNER AS SEARCH_TERM_2,
        CGM.CUSTOMER_GROUP,
        CGM.CUSTOMER_GROUP2
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    LEFT JOIN CGM
        ON CGM.ACCOUNT_NUMBER = CORPORATION
    WHERE LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B'

)

,OFFICE AS (
    SELECT
        B_CODE
        ,LEGACY_OFFICE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
    )

,CRM_WO AS (
    SELECT
        LPAD(MSDYN_NAME,8,'0') AS WO
        ,WO_WOTITLE AS WO_TITLE
        ,WO_TEMP_MSNAME AS WO_MACHINESN
        ,TEL_WO_PRIMARY_SONAME AS WO_RELATED_SO
        ,WO_TEMP_PRODUCTLINE_TEXT AS WO_PRODUCT_LINE
        ,MSDYN_SUBSTATUSNAME AS WO_SUBSTATUS
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
    WHERE 1=1
      AND WO_REGIONNAME = 'US')

,BAANSO AS (
    SELECT DISTINCT
        SERVICE_ORDER_NO
        ,DESCRIPTION
    FROM {{ ref('COMMON__DE_TEL_REPORTING__BAANV_TEA_SERVICE_ORDERS') }}
    WHERE LEFT(SERVICE_ORDER_NO,3)= 'PDS'
      AND ACTIVITY_LINE = '10')

,QUOTE AS (
    SELECT DISTINCT
        QUOTENUMBER
        ,LEFT(WORKDESCRIPTION,50) AS WORKDESCRIPTION
    FROM {{ ref('ODS__SHAREPOINT__PAIDSERVICEQUOTE') }}
    )

,SALES_CATEGORY AS (
    SELECT
        SAP_SALES_CATEGORY
        ,SAP_SALES_CATEGORY_NAME AS SALES_CATEGORY_NAME
        ,BAAN_PRODUCT_TYPE
    FROM {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }}
    WHERE SAP_SALES_CATEGORY <> 'LG')

,SOURCE AS (
    SELECT
        CUSTOMER.CUSTOMER_GROUP
        ,CUSTOMER.CUSTOMER_GROUP2
        ,ZS10.CUSTOMER_SOLD_TO
        ,ZS10.CUSTOMER_SOLD_TO_CODE
        ,OFFICE.LEGACY_OFFICE
        ,ZS10.ZS10_SALES_ORDER
        ,ZS10.SALES_ORDER_LINE_NUMBER
        ,BILLING.PRODUCT_CODE
        ,ZS10.MATERIAL_NUMBER
        ,ZS10.MATERIAL_GROUP
        ,ZS10.MATERIAL_DESCRIPTION
        ,BILLING.ITEM_CATEGORY
        ,BILLING.QTY
        ,BILLING.SALES_UNIT
        ,BILLING.UNIT_PRICE
        ,BILLING.NET_VALUE
        ,BILLING.BILLING_STATUS
        ,BILLING.BILLING_STATUS_DESC
        ,BILLING.BILLING_DOCUMENT_IS_CANCELED
        ,BILLING.SALES_APPROVAL_STATUS
        ,BILLING.SALES_APPROVAL_STATUS_DESC
        ,ZS10.SERIAL_NUMBER
    ,CASE
        WHEN LEFT(BILLING.CRM_WO_NO,1) <> 'X' THEN BILLING.CRM_WO_NO
        WHEN LEFT(BILLING.CRM_WO_NO,1) = 'X' AND BILLING.BAAN_SO IS NOT NULL THEN BILLING.BAAN_SO
        WHEN LEFT(BILLING.CRM_WO_NO,1) = 'X' AND BILLING.QUOTE IS NOT NULL THEN BILLING.QUOTE
    ELSE '*No Order'
    END AS RELATED_ORDER_NUMBER
    ,CASE
        WHEN LEFT(BILLING.CRM_WO_NO,1) <> 'X'THEN CRM_WO.WO_TITLE
        WHEN BAANSO.DESCRIPTION IS NOT NULL THEN BAANSO.DESCRIPTION
        WHEN CUSTOMER_SOLD_TO = 'TOKYO ELECTRON EUROPE LTD.' AND (LEN(BILLING.CRM_WO_NO) < 1 OR LEFT(BILLING.CRM_WO_NO,1) = 'X') THEN 'TEE WORK'
        WHEN QUOTE.WORKDESCRIPTION IS NOT NULL THEN QUOTE.WORKDESCRIPTION
    END AS LABOR_DESCRIPTION
        ,BILLING.SALES_CATEGORY
        ,SALES_CATEGORY.SALES_CATEGORY_NAME
        ,BILLING.CRM_WO_NO
        ,BILLING.QUOTE
        ,BILLING.BAAN_SO
        ,BILLING.CUSTOMER_PO
        ,BILLING.CUSTOMER_PO_LINE
        ,BILLING.CUSTOMER_PO_DATE
        ,BILLING.BILLING_TYPE
        ,BILLING.BILLING_DOCUMENT
        ,BILLING.BILLING_DATE
        ,LEFT(BILLING.BILLING_DATE,7) AS BILLING_MONTH
        ,CRM_WO.WO_PRODUCT_LINE
        ,CRM_WO.WO_SUBSTATUS
        ,SALES_CATEGORY.BAAN_PRODUCT_TYPE
        ,BILLING.PROFIT_CENTER
        ,SALES_DOCUMENT_DATE
        ,ZS10.SO_ID
    FROM ZS10
    LEFT OUTER JOIN BILLING
    ON ZS10.SO_ID = BILLING.SO_ID
    LEFT OUTER JOIN CUSTOMER
    ON ZS10.CUSTOMER_SOLD_TO_CODE = CUSTOMER.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN OFFICE
    ON ZS10.CUSTOMER_SOLD_TO_CODE = OFFICE.B_CODE
    LEFT OUTER JOIN CRM_WO
    ON BILLING.CRM_WO_NO = CRM_WO.WO
    LEFT OUTER JOIN SALES_CATEGORY
    ON BILLING.SALES_CATEGORY = SALES_CATEGORY.SAP_SALES_CATEGORY
    LEFT OUTER JOIN BAANSO
    ON BILLING.BAAN_SO = BAANSO.SERVICE_ORDER_NO
    LEFT OUTER JOIN QUOTE
    ON BILLING.QUOTE = QUOTE.QUOTENUMBER
    WHERE BAAN_PRODUCT_TYPE = 'PDSRV' )

,transform_data as (
    select
        '{{ invocation_id }}' AS AUDIT_LOG_ID
        ,SHA2('hash_me') AS _ROW_HASH
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
        ,CUSTOMER_SOLD_TO
        ,CUSTOMER_SOLD_TO_CODE
        ,LEGACY_OFFICE
        ,ZS10_SALES_ORDER
        ,SALES_ORDER_LINE_NUMBER
        ,PRODUCT_CODE
        ,MATERIAL_NUMBER
        ,MATERIAL_GROUP
        ,MATERIAL_DESCRIPTION
        ,ITEM_CATEGORY
        ,QTY
        ,SALES_UNIT
        ,UNIT_PRICE
        ,NET_VALUE
        ,BILLING_STATUS
        ,BILLING_STATUS_DESC
        ,BILLING_DOCUMENT_IS_CANCELED
        ,SALES_APPROVAL_STATUS
        ,SALES_APPROVAL_STATUS_DESC
        ,SERIAL_NUMBER
        ,RELATED_ORDER_NUMBER
        ,LABOR_DESCRIPTION
        ,SALES_CATEGORY
        ,SALES_CATEGORY_NAME
        ,CRM_WO_NO
        ,QUOTE
        ,BAAN_SO
        ,CUSTOMER_PO
        ,CUSTOMER_PO_LINE
        ,CUSTOMER_PO_DATE
        ,BILLING_TYPE
        ,BILLING_DOCUMENT
        ,BILLING_DATE
        ,BILLING_MONTH
        ,WO_PRODUCT_LINE
        ,WO_SUBSTATUS
        ,BAAN_PRODUCT_TYPE
        ,PROFIT_CENTER
        ,SALES_DOCUMENT_DATE
        ,SO_ID
    from source
)

,TYPE_DATA AS (
    SELECT
        CAST(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID
        ,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
        ,CUSTOMER_SOLD_TO
        ,CUSTOMER_SOLD_TO_CODE
        ,LEGACY_OFFICE
        ,ZS10_SALES_ORDER
        ,SALES_ORDER_LINE_NUMBER
        ,PRODUCT_CODE
        ,MATERIAL_NUMBER
        ,MATERIAL_GROUP
        ,MATERIAL_DESCRIPTION
        ,ITEM_CATEGORY
        ,CAST(QTY as NUMBER(38,2)) AS QTY
        ,SALES_UNIT
        ,CAST(UNIT_PRICE as NUMBER(38,2)) AS UNIT_PRICE
        ,CAST(NET_VALUE as NUMBER(38,2)) AS NET_VALUE
        ,BILLING_STATUS
        ,BILLING_STATUS_DESC
        ,BILLING_DOCUMENT_IS_CANCELED
        ,SALES_APPROVAL_STATUS
        ,SALES_APPROVAL_STATUS_DESC
        ,SERIAL_NUMBER
        ,RELATED_ORDER_NUMBER
        ,LABOR_DESCRIPTION
        ,SALES_CATEGORY
        ,SALES_CATEGORY_NAME
        ,CRM_WO_NO
        ,QUOTE
        ,BAAN_SO
        , CUSTOMER_PO
        , CUSTOMER_PO_LINE
        ,CAST(CUSTOMER_PO_DATE as DATE) AS CUSTOMER_PO_DATE
        ,BILLING_TYPE
        , BILLING_DOCUMENT
        ,CAST(BILLING_DATE as DATE) AS BILLING_DATE
        , BILLING_MONTH
        , WO_PRODUCT_LINE
        , WO_SUBSTATUS
        , BAAN_PRODUCT_TYPE
        , PROFIT_CENTER
        ,CAST(SALES_DOCUMENT_DATE as DATE) AS SALES_DOCUMENT_DATE
        , SO_ID
    FROM transform_data)
SELECT * FROM TYPE_DATA
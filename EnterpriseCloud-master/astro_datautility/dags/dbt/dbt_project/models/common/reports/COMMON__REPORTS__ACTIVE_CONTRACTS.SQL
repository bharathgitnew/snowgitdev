WITH SOURCE_DATA as (
SELECT
    CUSTOMER_GROUP,
    CUSTOMER_NAME,
    PRODUCT,
    CONTRACT_OWNER,
    CONTRACT_OWNER_ID,
    CONTRACT_NUMBER,
    CONTRACT_TITLE,
    CONTRACT_START_DATE,
    CONTRACT_END_DATE,
    CONTRACT_TYPE,
    CONTRACT_STATUS,
    CUSTOMER_CODE,
    MAIN_FAB,
    TOTAL_CONTRACT_CRM_AMOUNT,
    TOTAL_CONTRACT_SAP_AMOUNT,
    PO_NUMBER,
    CONTRACT_SCOPE_BY_PRODUCT,
    INSTALLMENT_TIMING,
    QUOTE_RENEWAL_NO,
    BAAN_CONTRACT_NUMBER,
    SITE_SUPERVISOR,
    CONTRACT_START_YYYY_MM,
    CONTRACT_START_FISCAL_HALF,
    NOTES,
    COVERED_FAB,
    ZSC1_SALES_ORDER,
    ZC10_SALES_ORDER,
    ZC11_SALES_ORDER,
    ZC12_SALES_ORDER,
    ZSC0_SALES_ORDER,
    ZS10_SALES_ORDER,
    SITE_SUPERVISOR_ID,
    MANAGED_BY
FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
WHERE CONTRACT_STATUS IN ('Providing Service')
)
,TRANSFORM_DATA AS (
    SELECT 
        CUSTOMER_GROUP,
        CUSTOMER_NAME,
        PRODUCT,
        CONTRACT_OWNER,
        CONTRACT_OWNER_ID,
        CONTRACT_NUMBER,
        CONTRACT_TITLE,
        CONTRACT_START_DATE,
        CONTRACT_END_DATE,
        CONTRACT_TYPE,
        CONTRACT_STATUS,
        CUSTOMER_CODE,
        MAIN_FAB,
        TOTAL_CONTRACT_CRM_AMOUNT,
        TOTAL_CONTRACT_SAP_AMOUNT,
        PO_NUMBER,
        CONTRACT_SCOPE_BY_PRODUCT,
        INSTALLMENT_TIMING,
        QUOTE_RENEWAL_NO,
        BAAN_CONTRACT_NUMBER,
        SITE_SUPERVISOR,
        CONTRACT_START_YYYY_MM,
        CONTRACT_START_FISCAL_HALF,
        NOTES,
        COVERED_FAB,
        ZSC1_SALES_ORDER,
        ZC10_SALES_ORDER,
        ZC11_SALES_ORDER,
        ZC12_SALES_ORDER,
        ZSC0_SALES_ORDER,
        ZS10_SALES_ORDER,
        SITE_SUPERVISOR_ID,
        MANAGED_BY,
        '{{ invocation_id }}' AS AUDIT_LOG_ID
    FROM SOURCE_DATA
)
,type_data as (
    SELECT
        CAST(CUSTOMER_GROUP AS VARCHAR(16777216)) AS CUSTOMER_GROUP,
        CAST(CUSTOMER_NAME AS VARCHAR(16777216)) AS CUSTOMER_NAME,
        CAST(PRODUCT AS VARCHAR(16777216)) AS PRODUCT,
        CAST(CONTRACT_OWNER AS VARCHAR(16777216)) AS CONTRACT_OWNER,
        CAST(CONTRACT_OWNER_ID AS VARCHAR(16777216)) AS CONTRACT_OWNER_ID,
        CAST(CONTRACT_NUMBER AS VARCHAR(16777216)) AS CONTRACT_NUMBER,
        CAST(CONTRACT_TITLE AS VARCHAR(16777216)) AS CONTRACT_TITLE,
        CAST(CONTRACT_START_DATE AS DATE) AS CONTRACT_START_DATE,
        CAST(CONTRACT_END_DATE AS DATE) AS CONTRACT_END_DATE,
        CAST(CONTRACT_TYPE AS VARCHAR(16777216)) AS CONTRACT_TYPE,
        CAST(CONTRACT_STATUS AS VARCHAR(16777216)) AS CONTRACT_STATUS,
        CAST(CUSTOMER_CODE AS VARCHAR(16777216)) AS CUSTOMER_CODE,
        CAST(MAIN_FAB AS VARCHAR(16777216)) AS MAIN_FAB,
        CAST(TOTAL_CONTRACT_CRM_AMOUNT AS NUMBER(38,2)) AS TOTAL_CONTRACT_CRM_AMOUNT,
        CAST(TOTAL_CONTRACT_SAP_AMOUNT AS NUMBER(38,2)) AS TOTAL_CONTRACT_SAP_AMOUNT,
        CAST(PO_NUMBER AS VARCHAR(16777216)) AS PO_NUMBER,
        CAST(CONTRACT_SCOPE_BY_PRODUCT AS VARCHAR(16777216)) AS CONTRACT_SCOPE_BY_PRODUCT,
        CAST(INSTALLMENT_TIMING AS VARCHAR(16777216)) AS INSTALLMENT_TIMING,
        CAST(QUOTE_RENEWAL_NO AS VARCHAR(16777216)) AS QUOTE_RENEWAL_NO,
        CAST(BAAN_CONTRACT_NUMBER AS VARCHAR(16777216)) AS BAAN_CONTRACT_NUMBER,
        CAST(SITE_SUPERVISOR AS VARCHAR(16777216)) AS SITE_SUPERVISOR,
        CAST(CONTRACT_START_YYYY_MM AS VARCHAR(16777216)) AS CONTRACT_START_YYYY_MM,
        CAST(CONTRACT_START_FISCAL_HALF AS VARCHAR(16777216)) AS CONTRACT_START_FISCAL_HALF,
        CAST(NOTES AS VARCHAR(16777216)) AS NOTES,
        CAST(COVERED_FAB AS VARCHAR(16777216)) AS COVERED_FAB,
        CAST(ZSC1_SALES_ORDER AS VARCHAR(16777216)) AS ZSC1_SALES_ORDER,
        CAST(ZC10_SALES_ORDER AS VARCHAR(16777216)) AS ZC10_SALES_ORDER,
        CAST(ZC11_SALES_ORDER AS VARCHAR(16777216)) AS ZC11_SALES_ORDER,
        CAST(ZC12_SALES_ORDER AS VARCHAR(16777216)) AS ZC12_SALES_ORDER,
        CAST(ZSC0_SALES_ORDER AS VARCHAR(16777216)) AS ZSC0_SALES_ORDER,
        CAST(ZS10_SALES_ORDER AS VARCHAR(16777216)) AS ZS10_SALES_ORDER,
        CAST(SITE_SUPERVISOR_ID AS VARCHAR(16777216)) AS SITE_SUPERVISOR_ID,
        CAST(MANAGED_BY AS VARCHAR(16777216)) AS MANAGED_BY,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    FROM transform_data
)

SELECT * from type_data
{{ config(
        alias = 'MATERIAL_MASTER_3PL_REPORT',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with source_data as
(
    SELECT    
        MATERIAL_NUMBER,
        MARA_MATERIAL_DESCRIPTION,
        MARA_UOM,
        STANDARD_PRICE,
        UNNUM1,
        FINAL_UPDATE_DATE AS UPDATE_DATE,
        SERIAL_NUMBER_PROFILE,
        SERIALIZED,
        BIN_BULK_INDICATOR,
        MARC_PLANT AS PLANT
    FROM {{ ref('COMMON__SAPH__MATERIAL_MASTER_3PL') }} 
    WHERE MARC_PLANT='3200' 
            AND (TRY_TO_NUMBER(SUBSTR(MATERIAL_NUMBER,1,1)) IS NULL OR SUBSTR(MATERIAL_NUMBER,1,1)='E')
            AND ((TRY_TO_NUMBER(SUBSTR(MATERIAL_NUMBER,2,1)) IS NULL OR SUBSTR(MATERIAL_NUMBER,2,1)='E')
                    OR LEFT(MATERIAL_NUMBER,2) IN ('L1','J8','P5'))
            AND LEFT(MATERIAL_NUMBER,2) NOT IN ('CC','CL','FC','HP','NX','UL')
),

transform_data as (
    SELECT
        MATERIAL_NUMBER,
        MARA_MATERIAL_DESCRIPTION,
        MARA_UOM,
        STANDARD_PRICE,
        UNNUM1,
        UPDATE_DATE,
        SERIAL_NUMBER_PROFILE,
        SERIALIZED,
        BIN_BULK_INDICATOR,
        PLANT,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM source_data
),
type_data as (
select
    CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
    CAST(MARA_MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MARA_MATERIAL_DESCRIPTION,
    CAST(MARA_UOM AS VARCHAR(16777216)) AS MARA_UOM,
    CAST(STANDARD_PRICE AS VARCHAR(16777216)) AS STANDARD_PRICE,
    CAST(UNNUM1 AS VARCHAR(16777216)) AS UNNUM1,
    CAST(SERIAL_NUMBER_PROFILE AS VARCHAR(16777216)) AS SERIAL_NUMBER_PROFILE,
    CAST(SERIALIZED AS VARCHAR(1)) AS SERIALIZED,
    CAST(BIN_BULK_INDICATOR AS VARCHAR(1)) AS BIN_BULK_INDICATOR,
    CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
    CAST(UPDATE_DATE AS VARCHAR(16777216)) AS UPDATE_DATE,
    CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
from transform_data
)

select * from type_data
WITH MAT AS
(
    SELECT DISTINCT
        MATERIAL_DESCRIPTION,
        MARA_MATERIAL_NUMBER
    FROM {{ ref('COMMON__SAPH__MATERIAL_PLANT_MASTER') }}
),

LOC AS
(
    SELECT DISTINCT
        PLANT,
        STORAGE_LOCATION,
        DESCRIPTION_OF_STORAGE_LOCATION
    FROM  {{ ref('COMMON__SAPH__MATERIAL_STORAGE_LOCATION_MASTER') }}
),

CUST AS
(
	SELECT DISTINCT 
		NAME_1, 
		CUSTOMER_NUMBER
	FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
),

VBEP AS 
(
	SELECT DISTINCT
		PURCHASE_REQUISITION_NUMBER,            
		ITEM_NUMBER_OF_PURCHASE_REQUISITION,
		LIPS_DELIVERY,
		DELIVERY_ITEM_POSNR
	FROM {{ ref('COMMON__SAPH__PURCHASE_ORDER_DELIVERY_LINE') }}
),

TVLKT AS 
(
	SELECT DISTINCT
	DESCRIPTION,
	DELIVERY_TYPE
	FROM {{ ref('COMMON__SAPH__DELIVERY_ORDER_LINE_MASTER') }} 
),

SLINE AS 
(
	SELECT
	--Sales Header
	'Sale'                                                    AS HEADER_TYPE,
	SLINE.VBAK_SALES_ORGANIZATION                                   AS SALES_ORG,
	SLINE.VBAK_SALES_DOCUMENT                                 AS DOC_HEADER,
	SLINE.VBAK_SALES_DOCUMENT_TYPE                                  AS DOC_TYPE,
	SLINE.SALES_DOCUMENT_ITEM_POSNR                           AS HEADER_DOC_LINE,
	SLINE.VBAK_ORDER_REASON                                   AS ORDER_REASON,
	SLINE.LIPS_DELIVERY                                             AS DELIVERY_HEADER,
	SLINE.DELIVERY_ITEM_POSNR                                       AS DELIVERY_LINE,
	CONCAT(SLINE.LIPS_DELIVERY ,'|' , SLINE.DELIVERY_ITEM_POSNR)          AS DELIVERY_ID,
	SLINE.DELIVERY_TYPE_LFART                                       AS DELIVERY_TYPE,
	TVLKT.DESCRIPTION                                               AS DELIVERY_TYPE_DESC,
	SLINE.LIPS_MOVEMENT_TYPE                                        AS MOVEMENT_TYPE,
	SLINE.SHIP_TO_PARTY 									  AS SHIP_TO,
	CUST.NAME_1                                               AS SHIP_TO_NAME,
	SLINE.LIPS_SPECIAL_STOCK_INDICATOR AS SPECIAL_STOCK_IND,
	
	--Dates
	TRY_TO_DATE(SLINE.PICKING_DATE,'YYYYMMDD')                      AS PICKING_DATE,
	TRY_TO_DATE(SLINE.PLANNED_GOODS_MOVEMENT_DATE,'YYYYMMDD')       AS PLANNED_GOODS_MOVE_DATE, --comes from SO schedule line
	TRY_TO_DATE(SLINE.ACTUAL_GOODS_MOVEMENT_DATE,'YYYYMMDD')        AS ACTUAL_GOODS_MOVE_DATE, --date of goods issue, left warehouse
	DATEDIFF(DAY,
	 TRY_TO_DATE(SLINE.PLANNED_GOODS_MOVEMENT_DATE,'YYYYMMDD'),
	 TRY_TO_DATE(SLINE.ACTUAL_GOODS_MOVEMENT_DATE,'YYYYMMDD'))      AS DAYS_BETWEEN_PLAN_VS_ACTUAL_GOODS_MOVE,
	TO_DATE(SLINE.LIKP_SHIP_DATE)                                   AS SHIP_DATE,
	TRY_TO_DATE(SLINE.DELIVERY_DATE_LFDAT,'YYYYMMDD')               AS DELIVERY_DATE,
	DATEDIFF(DAY,
		TRY_TO_DATE(SLINE.PLANNED_GOODS_MOVEMENT_DATE,'YYYYMMDD'),
		TRY_TO_DATE(SLINE.DELIVERY_DATE_LFDAT,'YYYYMMDD'))             AS DAYS_BETWEEN_REQ_VS_ACTUAL_DELIVERY,
	TRY_TO_DATE(SLINE.CONFIRMED_WAREHOUSE_DELIVERY_DATE,'YYYYMMDD') AS CONF_WH_DELIVERY_DATE,
	TRY_TO_DATE(SLINE.SCHEDULED_WAREHOUSE_DELIVERY_DATE,'YYYYMMDD') AS SCHED_WH_DELIVERY_DATE,
	TRY_TO_DATE(SLINE.PLANNED_DELIVERY_DATE_TO_RECEIVER,'YYYYMMDD') AS PLANNED_DELIVERY_DATE,
	try_to_date(SLINE.CONFIRMED_CUSTOMS_CLEARANCE_DATE,'YYYYMMDD')  AS EXPORT_DATE,
	
	--Material 
	SLINE.MATERIAL_NUMBER                                     AS MATERIAL_NUMBER,
	MAT.MATERIAL_DESCRIPTION,
	CASE
	    WHEN LIKE(MATERIAL_DESCRIPTION, 'repair') 
	    THEN 'Repair' 
	    ELSE 'NA' 
	END                                                       AS REPAIR_FLAG,
	
    -- REF doc ids
	VBEP.PURCHASE_REQUISITION_NUMBER                          AS PURCHASE_REQUISITION,            
	VBEP.ITEM_NUMBER_OF_PURCHASE_REQUISITION                  AS PURCHASE_REQ_LINE,
	
	--Storage
	SLINE.STORAGE_LOCATION_LIPS                               AS STORAGE_LOC,
	LOC.DESCRIPTION_OF_STORAGE_LOCATION                       AS STORAGE_LOC_NAME,
	SLINE.PLANT_LIPS                                          AS PLANT,
	
	--Qty
	SLINE.PURCHASE_ORDER_QUANTITY                             AS PURCHASE_ORDER_QTY,
	SLINE.ACTUAL_QUANTITY_DELIVERED                           AS ACTUAL_DEL_QTY,
	VBFA.VBFA_REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE     AS PICKED_QUANTITY,
	
	--Status
	SLINE.VBAK_DELIVERY_BLOCK                                 AS DELIVERY_BLOCK,
	CASE  
	    WHEN VBFA.VBFA_REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE < SLINE.ACTUAL_QUANTITY_DELIVERED 
	    OR VBFA.VBFA_REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE > SLINE.ACTUAL_QUANTITY_DELIVERED
	    THEN 'Y'  
	    ELSE 'N' 
	END                                                       AS PICKING_HOLD,
	CASE  
	    WHEN SLINE.PICKING_STATUS_PUTAWAY_STATUS = 'A'
	    THEN 'Not Yet Processed'   
	    WHEN SLINE.PICKING_STATUS_PUTAWAY_STATUS = 'B' 
	    THEN 'Partially Processed'   
	    WHEN SLINE.PICKING_STATUS_PUTAWAY_STATUS = 'C' 
	    THEN 'Completely Processed'   
	    ELSE 'NA' 
	END                                                       AS PICKING_STATUS,
	SLINE.VBAK_DELAY_STATUS                                   AS DELAY_STATUS,
	CASE 
	    WHEN SLINE.LIPS_OVERALL_PROCESSING_STATUS_OF_THE_SD_DOCUMENT_ITEM = 'A' 
	    THEN 'Not Yet Processed'   
	    WHEN SLINE.LIPS_OVERALL_PROCESSING_STATUS_OF_THE_SD_DOCUMENT_ITEM = 'B' 
	    THEN 'Partially Processed'   
	    WHEN SLINE.LIPS_OVERALL_PROCESSING_STATUS_OF_THE_SD_DOCUMENT_ITEM = 'C' 
	    THEN 'Completely Processed'   
	    ELSE 'NA' 
	END                                                       AS DELIVERY_STATUS,
	CASE 
	    WHEN SLINE.LIKP_OVERALL_GOODS_MOVEMENT_STATUS = 'A' 
	    THEN 'Not Yet Processed'   
	    WHEN SLINE.LIKP_OVERALL_GOODS_MOVEMENT_STATUS = 'B' 
	    THEN 'Partially Processed'   
	    WHEN SLINE.LIKP_OVERALL_GOODS_MOVEMENT_STATUS = 'C' 
	    THEN 'Completely Processed'   
	    ELSE 'NA' 
	END                                                       AS MOVEMENT_STATUS,
	SLINE.LIKP_DELIVERY_CERATOR                               AS CREADTED_BY
	
	FROM {{ ref('COMMON__SAPH__SALES_ORDER_DELIVERY_LINE') }} AS SLINE
	LEFT JOIN  MAT ON SLINE.MATERIAL_NUMBER = MAT.MARA_MATERIAL_NUMBER
	LEFT JOIN  LOC ON SLINE.STORAGE_LOCATION_LIPS = LOC.STORAGE_LOCATION AND SLINE.PLANT_LIPS = LOC.PLANT
	LEFT JOIN {{ ref('COMMON__SAPH__SALES_ORDER_DOCUMENT_FLOW') }} AS VBFA
		ON SLINE.LIPS_DELIVERY = VBFA.VBFA_PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT
		AND SLINE.DELIVERY_ITEM_POSNR = VBFA.VBFA_PRECEDING_ITEM_OF_AN_SD_DOCUMENT
		AND VBFA.VBFA_DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = 'Q'
	LEFT JOIN CUST ON SLINE.SHIP_TO_PARTY = CUST.CUSTOMER_NUMBER
	
	LEFT JOIN VBEP ON SLINE.VBAP_SALES_DOCUMENT = VBEP.LIPS_DELIVERY AND SLINE.SALES_DOCUMENT_ITEM_POSNR = VBEP.DELIVERY_ITEM_POSNR
	
	LEFT JOIN TVLKT ON SLINE.DELIVERY_TYPE_LFART = TVLKT.DELIVERY_TYPE
	--------------
	WHERE SLINE.LIPS_DELIVERY IS NOT NULL
),

PLINE AS 
(
	SELECT
	--Purchase Header
	'Purchase'                                                AS HEADER_TYPE,
	PLINE.SALES_ORGANIZATION                                  AS SALES_ORG,
	PLINE.EKPO_PURCHASING_DOCUMENT_NUMBER                           AS DOC_HEADER,
	PLINE.PURCHASING_DOCUMENT_TYPE                                  AS DOC_TYPE,
    PLINE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP                  AS HEADER_DOC_LINE,

	PLINE.ORDER_REASON                                              AS ORDER_REASON, --ToDO
	PLINE.LIPS_DELIVERY                                             AS DELIVERY_HEADER,
	PLINE.DELIVERY_ITEM_POSNR                                       AS DELIVERY_LINE,
	CONCAT(PLINE.LIPS_DELIVERY ,'|' , PLINE.DELIVERY_ITEM_POSNR)          AS DELIVERY_ID,
	PLINE.DELIVERY_TYPE_LFART                                       AS DELIVERY_TYPE,
	TVLKT.DESCRIPTION                                               AS DELIVERY_TYPE_DESC,
	PLINE.MOVEMENT_TYPE                                             AS MOVEMENT_TYPE,
	PLINE.SHIP_TO_PARTY                                             AS SHIP_TO,
	CUST.NAME_1                                                AS SHIP_TO_NAME,
	PLINE.LIPS_SPECIAL_STOCK_INDICATOR                              AS SPECIAL_STOCK_IND,
	
	--Dates
	TRY_TO_DATE(PLINE.PICKING_DATE,'YYYYMMDD')                      AS PICKING_DATE,
	TRY_TO_DATE(PLINE.PLANNED_GOODS_MOVEMENT_DATE,'YYYYMMDD')       AS PLANNED_GOODS_MOVE_DATE,
	TRY_TO_DATE(PLINE.ACTUAL_GOODS_MOVEMENT_DATE,'YYYYMMDD')        AS ACTUAL_GOODS_MOVE_DATE,
	DATEDIFF(DAY,
	 TRY_TO_DATE(PLINE.PLANNED_GOODS_MOVEMENT_DATE,'YYYYMMDD'),
	 TRY_TO_DATE(PLINE.ACTUAL_GOODS_MOVEMENT_DATE,'YYYYMMDD'))      AS DAYS_BETWEEN_PLAN_VS_ACTUAL_GOODS_MOVE,
	TO_DATE(PLINE.SHIP_DATE)                                  AS SHIP_DATE,
	try_to_date(PLINE.DELIVERY_DATE_LFDAT,'YYYYMMDD')               AS DELIVERY_DATE,
	DATEDIFF(DAY,
	 TRY_TO_DATE(PLINE.PLANNED_GOODS_MOVEMENT_DATE,'YYYYMMDD'),
	 TRY_TO_DATE(PLINE.DELIVERY_DATE_LFDAT,'YYYYMMDD'))             AS DAYS_BETWEEN_REQ_VS_ACTUAL_DELIVERY,
	try_to_date(PLINE.CONFIRMED_WAREHOUSE_DELIVERY_DATE,'YYYYMMDD') AS CONF_WH_DELIVERY_DATE,
	'0'                                                       AS SCHED_WH_DELIVERY_DATE,
	try_to_date(PLINE.PLANNED_DELIVERY_DATE_TO_RECEIVER,'YYYYMMDD') AS PLANNED_DELIVERY_DATE,
	try_to_date(PLINE.CONFIRMED_CUSTOMS_CLEARANCE_DATE,'YYYYMMDD')  AS EXPORT_DATE,
	
	--Material 
	PLINE.MATERIAL_NUMBER_MATNR                                     AS MATERIAL_NUMBER,
	MAT.MATERIAL_DESCRIPTION,
	CASE
	    WHEN LIKE(MAT.MATERIAL_DESCRIPTION, 'repair') 
	    THEN 'Repair' 
	    ELSE 'NA' 
	END                                                       AS REPAIR_FLAG,
	
	--Reference docs
	PLINE.PURCHASE_REQUISITION_NUMBER                               AS PURCHASE_REQ,            
	PLINE.ITEM_NUMBER_OF_PURCHASE_REQUISITION                       AS PURCHASE_REQ_LINE,
	
	--Storage
	PLINE.LIPS_STORAGE_LOCATION                               AS STORAGE_LOC,
	DESCRIPTION_OF_STORAGE_LOCATION                           AS STORAGE_LOC_NAME,
	PLINE.LIPS_PLANT                                          AS PLANT,
	
	--Qty
	PLINE.PURCHASE_ORDER_QUANTITY                             AS PURCHASE_ORDER_QTY,
	PLINE.ACTUAL_QUANTITY_DELIVERED                                 AS ACTUAL_DEL_QTY,
	VBFA.VBFA_REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE          AS PICKED_QUANTITY,
    PLINE.DELIVERY_BLOCK                                      AS DELIVERY_BLOCK,
	
	--Status
	CASE  
	    WHEN VBFA.VBFA_REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE < ACTUAL_QUANTITY_DELIVERED 
	    OR VBFA.VBFA_REFERENCED_QUANTITY_IN_BASE_UNIT_OF_MEASURE > ACTUAL_QUANTITY_DELIVERED
	    THEN 'Y'  
	    ELSE 'N' 
	END                                                       AS PICKING_HOLD, 
	
	CASE  
	    WHEN PLINE.PICKING_STATUS_PUTAWAY_STATUS = 'A'
	    THEN 'Not Yet Processed'   
	    WHEN PLINE.PICKING_STATUS_PUTAWAY_STATUS = 'B' 
	    THEN 'Partially Processed'   
	    WHEN PLINE.PICKING_STATUS_PUTAWAY_STATUS = 'C' 
	    THEN 'Completely Processed'   
	    ELSE 'NA' 
	END                                                       AS PICKING_STATUS,
	'N/A'                                                     AS DELAY_STATUS,
	CASE 
	    WHEN PLINE.OVERALL_PROCESSING_STATUS_OF_THE_SD_DOCUMENT_ITEM = 'A' 
	    THEN 'Not Yet Processed'   
	    WHEN PLINE.OVERALL_PROCESSING_STATUS_OF_THE_SD_DOCUMENT_ITEM = 'B' 
	    THEN 'Partially Processed'   
	    WHEN PLINE.OVERALL_PROCESSING_STATUS_OF_THE_SD_DOCUMENT_ITEM = 'C' 
	    THEN 'Completely Processed'   
	    ELSE 'NA' 
	END                                                       AS DELIVERY_STATUS,
	CASE 
	    WHEN PLINE.OVERALL_GOODS_MOVEMENT_STATUS = 'A' 
	    THEN 'Not Yet Processed'   
	    WHEN PLINE.OVERALL_GOODS_MOVEMENT_STATUS = 'B' 
	    THEN 'Partially Processed'   
	    WHEN PLINE.OVERALL_GOODS_MOVEMENT_STATUS = 'C' 
	    THEN 'Completely Processed'   
	    ELSE 'NA' 
	END                                                       AS MOVEMENT_STATUS,
	PLINE.LIKP_DELIVERY_CERATOR                                     AS CREADTED_BY
	
	FROM PUB.COMMON_SAPH.PURCHASE_ORDER_DELIVERY_LINE PLINE
	LEFT JOIN  MAT ON PLINE.MATERIAL_NUMBER = MAT.MARA_MATERIAL_NUMBER
	LEFT JOIN LOC ON PLINE.LIPS_STORAGE_LOCATION = LOC.STORAGE_LOCATION AND PLINE.LIPS_PLANT = LOC.PLANT
	LEFT JOIN PUB.COMMON_SAPH.SALES_ORDER_DOCUMENT_FLOW VBFA
		ON PLINE.LIPS_DELIVERY = VBFA.VBFA_PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT
		AND PLINE.DELIVERY_ITEM_POSNR = VBFA.VBFA_PRECEDING_ITEM_OF_AN_SD_DOCUMENT
		AND VBFA.VBFA_DOCUMENT_CATEGORY_OF_SUBSEQUENT_DOCUMENT = 'Q'
	LEFT JOIN CUST ON PLINE.SHIP_TO_PARTY = CUST.CUSTOMER_NUMBER
	LEFT JOIN TVLKT ON PLINE.DELIVERY_TYPE_LFART = TVLKT.DELIVERY_TYPE

	WHERE PLINE.LIPS_DELIVERY IS NOT NULL
), 

SOURCE_DATA AS 
(
	SELECT * FROM SLINE
	UNION ALL
	SELECT * FROM PLINE
),

TRANSFORM_DATA AS
(
	SELECT
	HEADER_TYPE,
	SALES_ORG,
	DOC_HEADER,
	DOC_TYPE,
	HEADER_DOC_LINE,
	ORDER_REASON,
	DELIVERY_HEADER,
	DELIVERY_LINE,
	DELIVERY_ID,
	DELIVERY_TYPE,
	DELIVERY_TYPE_DESC,
	MOVEMENT_TYPE,
	SHIP_TO,
	SHIP_TO_NAME,
	SPECIAL_STOCK_IND,
	PICKING_DATE,
	PLANNED_GOODS_MOVE_DATE, 
	ACTUAL_GOODS_MOVE_DATE,
	DAYS_BETWEEN_PLAN_VS_ACTUAL_GOODS_MOVE,
	SHIP_DATE,
	DELIVERY_DATE,
	DAYS_BETWEEN_REQ_VS_ACTUAL_DELIVERY,
	CONF_WH_DELIVERY_DATE,
	SCHED_WH_DELIVERY_DATE,
	PLANNED_DELIVERY_DATE,
	EXPORT_DATE,
	MATERIAL_NUMBER,
	MATERIAL_DESCRIPTION,
	REPAIR_FLAG,
	PURCHASE_REQUISITION,            
	PURCHASE_REQ_LINE,
	STORAGE_LOC,
	STORAGE_LOC_NAME,
	PLANT,
	PURCHASE_ORDER_QTY,
	ACTUAL_DEL_QTY,
	PICKED_QUANTITY,
	DELIVERY_BLOCK,
	PICKING_HOLD,
	PICKING_STATUS,
	DELAY_STATUS,
	DELIVERY_STATUS,
	MOVEMENT_STATUS,
	CREADTED_BY,
    '{{ invocation_id }}' AS AUDIT_LOG_ID
	FROM SOURCE_DATA
),

TYPE_DATA as (
    SELECT
        CAST(HEADER_TYPE AS VARCHAR(16777216)) AS HEADER_TYPE,
        CAST(SALES_ORG AS VARCHAR(16777216)) AS SALES_ORG,
        CAST(DOC_HEADER AS VARCHAR(16777216)) AS DOC_HEADER,
        CAST(DOC_TYPE AS VARCHAR(16777216)) AS DOC_TYPE,
        CAST(HEADER_DOC_LINE AS VARCHAR(16777216)) AS HEADER_DOC_LINE,
        CAST(ORDER_REASON AS VARCHAR(16777216)) AS ORDER_REASON,
        CAST(DELIVERY_HEADER AS VARCHAR(16777216)) AS DELIVERY_HEADER,
        CAST(DELIVERY_LINE AS VARCHAR(16777216)) AS DELIVERY_LINE,
        CAST(DELIVERY_ID AS VARCHAR(16777216)) AS DELIVERY_ID,
        CAST(DELIVERY_TYPE AS VARCHAR(16777216)) AS DELIVERY_TYPE,
        CAST(DELIVERY_TYPE_DESC AS VARCHAR(16777216)) AS DELIVERY_TYPE_DESC,
        CAST(MOVEMENT_TYPE AS VARCHAR(16777216)) AS MOVEMENT_TYPE,
        CAST(SHIP_TO AS VARCHAR(16777216)) AS SHIP_TO,
        CAST(SHIP_TO_NAME AS VARCHAR(16777216)) AS SHIP_TO_NAME,
        CAST(SPECIAL_STOCK_IND AS VARCHAR(16777216)) AS SPECIAL_STOCK_IND,
        CAST(PICKING_DATE AS DATE) AS PICKING_DATE,
        CAST(PLANNED_GOODS_MOVE_DATE AS DATE) AS PLANNED_GOODS_MOVE_DATE,
        CAST(ACTUAL_GOODS_MOVE_DATE AS DATE) AS ACTUAL_GOODS_MOVE_DATE,
        CAST(DAYS_BETWEEN_PLAN_VS_ACTUAL_GOODS_MOVE AS NUMBER) AS DAYS_BETWEEN_PLAN_VS_ACTUAL_GOODS_MOVE,
        CAST(SHIP_DATE AS DATE) AS SHIP_DATE,
        CAST(DELIVERY_DATE AS DATE) AS DELIVERY_DATE,
        CAST(DAYS_BETWEEN_REQ_VS_ACTUAL_DELIVERY AS NUMBER) AS DAYS_BETWEEN_REQ_VS_ACTUAL_DELIVERY,
        CAST(CONF_WH_DELIVERY_DATE AS DATE) AS CONF_WH_DELIVERY_DATE,
        CAST(SCHED_WH_DELIVERY_DATE AS DATE) AS SCHED_WH_DELIVERY_DATE,
        CAST(PLANNED_DELIVERY_DATE AS DATE) AS PLANNED_DELIVERY_DATE,
        CAST(EXPORT_DATE AS DATE) AS EXPORT_DATE,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(REPAIR_FLAG AS VARCHAR(16777216)) AS REPAIR_FLAG,
        CAST(PURCHASE_REQUISITION AS VARCHAR(16777216)) AS PURCHASE_REQUISITION,            
	    CAST(PURCHASE_REQ_LINE AS VARCHAR(16777216)) AS PURCHASE_REQ_LINE,
        CAST(STORAGE_LOC AS VARCHAR(16777216)) AS STORAGE_LOC,
        CAST(STORAGE_LOC_NAME AS VARCHAR(16777216)) AS STORAGE_LOC_NAME,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(PURCHASE_ORDER_QTY AS VARCHAR(16777216)) AS PURCHASE_ORDER_QTY,
        CAST(ACTUAL_DEL_QTY AS VARCHAR(16777216)) AS ACTUAL_DEL_QTY,
        CAST(PICKED_QUANTITY AS VARCHAR(16777216)) AS PICKED_QUANTITY,
        CAST(DELIVERY_BLOCK AS VARCHAR(16777216)) AS DELIVERY_BLOCK,
        CAST(PICKING_HOLD AS VARCHAR(16777216)) AS PICKING_HOLD,
        CAST(PICKING_STATUS AS VARCHAR(16777216)) AS PICKING_STATUS,
        CAST(DELAY_STATUS AS VARCHAR(16777216)) AS DELAY_STATUS,
        CAST(DELIVERY_STATUS AS VARCHAR(16777216)) AS DELIVERY_STATUS,
        CAST(MOVEMENT_STATUS AS VARCHAR(16777216)) AS MOVEMENT_STATUS,
        CAST(CREADTED_BY AS VARCHAR(16777216)) AS CREADTED_BY,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
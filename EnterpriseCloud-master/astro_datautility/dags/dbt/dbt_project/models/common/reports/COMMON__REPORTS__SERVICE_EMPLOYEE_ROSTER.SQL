WITH TEACOMMON AS (
    SELECT
        COMPANYID,
        CASE
            WHEN BU_GROUP IS NOT NULL THEN 'GCE'
            WHEN DEPTCODE || '_' || PRODLINECODE IN ('049-33', '155-28') OR SUPERVISORID IN ('512873', '045079') OR EMPLOYEEID = '129233' THEN 'SOG'
	    WHEN COSTCENTER IN ('1321909101','1322815501','1323304901','1323700601','1323705001')  AND EMPLOYEEID <> '947069' THEN 'SOG'  --Added 5/31/24
            ELSE NULL
        END AS SERVICE_GROUP,
        BU_GROUP,
        SUPERVISOR_NAME,
		FULLNAME ,
        EMPLOYEEID,
        JOBTITLE,
        CASE
            WHEN STATUS_CODE IN ('A', 'L') THEN 'Active'
            WHEN STATUS_CODE IN ('T', 'F') AND ACTIVE = 'false' THEN 'Not Active'
            WHEN STATUS_CODE IS NULL THEN 'Not Active'
            ELSE 'Not Active'
        END AS ACTIVE_FLAG,
        CASE
            WHEN STATUS_CODE = 'A' THEN 'Active'
            WHEN STATUS_CODE = 'L' THEN 'On Leave'
            WHEN STATUS_CODE = 'T' THEN 'Terminated'
            WHEN STATUS_CODE = 'F' THEN 'Future Hire'
            WHEN STATUS_CODE IS NULL AND ACTIVE = 'false' THEN 'Not Active'
            ELSE STATUS_CODE
        END AS EMP_STATUS,
        CASE
            WHEN PRODLINECODE = '33' THEN 'FST'
            WHEN DEPTCODE IN ('053', '054') THEN 'Tech Support'
            ELSE 'N/A'
        END AS SERVICE_GROUP_FLAG,
        DEPARTMENT_NAME,
        DEPTCODE,
        BUSINESS_UNIT_NAME,
        PRODLINECODE,
        OFFICE_NAME,
        LOCATIONCODE,
        COSTCENTER,
        BU_GROUP_LEADER,
        ISMANAGER,
        EMPLOYEETYPE,
        CASE
            WHEN EMPLOYEETYPE = 1 THEN 'FTE'
            WHEN EMPLOYEETYPE = 2 THEN 'Subcon'
            WHEN EMPLOYEETYPE = 3 THEN 'Subcon'
            ELSE 'Other'
        END AS EMPLOYEETYPENAME,
        CASE
            WHEN EMPLOYEETYPE = 1 THEN 'FTE'
            WHEN EMPLOYEETYPE = 2 THEN 'Consultant'
            WHEN EMPLOYEETYPE = 3 THEN 'Temporary Worker'
            ELSE 'Other'
        END AS EMPLOYEETYPEDESC,
        FTE,
        STATUS_CODE,
        ACTIVE,
        VENDORNAME,
        DATEHIRE,
        DATETERM,
        REHIREDATE,
        EXPAT_FLAG,
        LASTUPDATED,
        EMAIL,
        SUPERVISORID,
        CASE
            WHEN LEFT(COMPANYID, 3) = 'TEA' THEN 1
            WHEN LEFT(COMPANYID, 3) = 'TEH' THEN 2
            WHEN LEFT(COMPANYID, 4) = 'TTCA' THEN 3
            WHEN LEFT(COMPANYID, 4) = 'TMEA' THEN 4
            ELSE 5
        END AS COMPANY_ORDER,
        FUNCTION1,
        JOB_FAMILY
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
),

GLOBAL_EMP AS (
    SELECT
        EMPLOYEE_ID,
        ACTIVEDIRECTORYDISPLAYNAME AS ACTIVE_DIRECTORY_NAME
    FROM {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY EMPLOYEE_ID ORDER BY EMPLOYEE_STATUS DESC)) = 1
),

GCESOGRAW AS (
    SELECT
        CASE
            WHEN BU_GROUP IS NOT NULL THEN 'GCE'
            WHEN DEPTCODE || '-' || PRODLINECODE IN ('049-33', '155-28') OR SUPERVISORID IN ('512873', '045079', '957136', '997049') OR EMPLOYEEID IN ('129233', '967151') THEN 'SOG'
            WHEN COSTCENTER IN ('1321909101','1322815501','1323304901','1323700601','1323705001')  AND EMPLOYEEID <> '947069' THEN 'SOG'  --Added 5/31/24
	    ELSE NULL
        END AS GCE_GROUP,
        BU_GROUP,
        FULLNAME,
        EMPLOYEEID,
        COSTCENTER,
        CASE
            WHEN SUPERVISORID = '071240' THEN 'Rathsack, Ben'
            WHEN SUPERVISORID = '007280' THEN 'Gandhi, Sundar'
            WHEN SUPERVISORID = '850236' THEN 'Shirai, Bobby'
            ELSE SUPERVISOR_NAME
        END AS SUPERVISOR_NAME,
        SUPERVISORID,
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
    WHERE
        STATUS_CODE IN ('A', 'L') AND
        (
            BU_GROUP IS NOT NULL
            OR DEPTCODE || '-' || PRODLINECODE IN ('049-33', '155-28')
            OR SUPERVISORID IN ('512873', '045079', '957136', '997049', '860153')
            OR EMPLOYEEID IN ('129233', '967151')
	        OR (COSTCENTER IN ('1321909101','1322815501','1323304901','1323700601','1323705001')  AND EMPLOYEEID <> '947069')  --Added 5/31/24
        )
),

SUPERVISOR AS (
    SELECT
        FULLNAME,
        EMPLOYEEID,
        CASE
            WHEN SUPERVISORID = '071240' THEN 'Rathsack, Ben'
            WHEN SUPERVISORID = '007280' THEN 'Gandhi, Sundar'
            WHEN SUPERVISORID = '850236' THEN 'Shirai, Bobby'
            ELSE SUPERVISOR_NAME
        END AS SUPERVISOR_NAME,
        CASE
            WHEN SUPERVISORID = '860153' THEN NULL --Want to stop at Bobby
            ELSE SUPERVISORID
        END AS SUPERVISORID
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
),

COMBINEDGCE AS (
    SELECT
        GCESOGRAW.EMPLOYEEID,
        GCESOGRAW.GCE_GROUP,
        GCESOGRAW.BU_GROUP,
        GCESOGRAW.FULLNAME,
        GCESOGRAW.COSTCENTER,
        GCESOGRAW.SUPERVISOR_NAME AS SUPERVISOR_1,
        GCESOGRAW.SUPERVISORID AS SUPERVISORID_1,
        SUPERVISOR.SUPERVISOR_NAME AS SUPERVISOR_2,
        SUPERVISOR.SUPERVISORID AS SUPERVISORID_2,
        SUP2.SUPERVISOR_NAME AS SUPERVISOR_3,
        SUP2.SUPERVISORID AS SUPERVISORID_3,
        SUP3.SUPERVISOR_NAME AS SUPERVISOR_4,
        SUP3.SUPERVISORID AS SUPERVISORID_4,
        SUP4.SUPERVISOR_NAME AS SUPERVISOR_5,
        SUP4.SUPERVISORID AS SUPERVISORID_5,
        SUP5.SUPERVISOR_NAME AS SUPERVISOR_6,
        SUP5.SUPERVISORID AS SUPERVISORID_6,
        SUP6.SUPERVISOR_NAME AS SUPERVISOR_7,
        SUP6.SUPERVISORID AS SUPERVISORID_7,
        SUP7.SUPERVISOR_NAME AS SUPERVISOR_8,
        SUP7.SUPERVISORID AS SUPERVISORID_8,
        CASE
            WHEN COALESCE(GCESOGRAW.SUPERVISORID, '-') || COALESCE(SUPERVISOR.SUPERVISORID, '-') || COALESCE(SUP2.SUPERVISORID, '-') || COALESCE(SUP3.SUPERVISORID, '-') || COALESCE(SUP4.SUPERVISORID, '-') || COALESCE(SUP5.SUPERVISORID, '-') ILIKE '%071240%' THEN 'BU1'
            WHEN COALESCE(GCESOGRAW.SUPERVISORID, '-') || COALESCE(SUPERVISOR.SUPERVISORID, '-') || COALESCE(SUP2.SUPERVISORID, '-') || COALESCE(SUP3.SUPERVISORID, '-') || COALESCE(SUP4.SUPERVISORID, '-') || COALESCE(SUP5.SUPERVISORID, '-') ILIKE '%007280%' THEN 'BU2'
            ELSE GCE_GROUP
        END AS GCE_GROUP2
    FROM GCESOGRAW
    LEFT JOIN SUPERVISOR ON GCESOGRAW.SUPERVISORID = SUPERVISOR.EMPLOYEEID
    LEFT JOIN SUPERVISOR SUP2 ON SUPERVISOR.SUPERVISORID = SUP2.EMPLOYEEID
    LEFT JOIN SUPERVISOR SUP3 ON SUP2.SUPERVISORID = SUP3.EMPLOYEEID
    LEFT JOIN SUPERVISOR SUP4 ON SUP3.SUPERVISORID = SUP4.EMPLOYEEID
    LEFT JOIN SUPERVISOR SUP5 ON SUP4.SUPERVISORID = SUP5.EMPLOYEEID
    LEFT JOIN SUPERVISOR SUP6 ON SUP5.SUPERVISORID = SUP6.EMPLOYEEID
    LEFT JOIN SUPERVISOR SUP7 ON SUP6.SUPERVISORID = SUP7.EMPLOYEEID
),


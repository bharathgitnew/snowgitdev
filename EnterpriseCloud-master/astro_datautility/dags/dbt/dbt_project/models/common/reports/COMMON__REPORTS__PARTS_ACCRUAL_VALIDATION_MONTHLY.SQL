WITH VBAK_HIST AS (
    SELECT DISTINCT
        VBELN AS SALES_DOCUMENT
        , AUART AS SALES_DOCUMENT_TYPE
        , ZZPSDZ as PO_START_DATE
        , ZZPEDZ AS PO_END_DATE
        , BSTNK AS CUSTOMER_REFERENCE
        , SNAPSHOT_DATE
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK_HIST') }}
    WHERE 1=1
        and VKORG = '3200'
        and SNAPSHOT_DATE-1 <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN ORDER BY SNAPSHOT_DATE DESC )) = 1
)

, VBAP_HIST AS (
    SELECT * FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP_HIST') }}
)
, VBAP_HIST_RECENT AS ( -- TO CAPTURE ALL SALES ORDER LINES EVEN IF CREATED AT A LATER DATE
    SELECT
        VBELN AS SALES_DOCUMENT
        , POSNR AS SALES_DOCUMENT_ITEM
        , PRCTR as PROFIT_CENTER
        , MATNR AS MATERIAL_NUMBER
        , NETWR AS SALES_ITEM_AMT
        , ZZTIZZ AS TRANSACTION_ID
        , ZZDISP AS DISPOSITION
        , SNAPSHOT_DATE
    FROM VBAP_HIST
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1 
)
, VBAP_HIST_EOM AS ( -- CAPTURE STATUS AS-OF THE LAST DAY OF THE MONTH
    SELECT
        VBELN AS SALES_DOCUMENT
        , POSNR AS SALES_DOCUMENT_ITEM 
        , ABGRU AS REJECTION_REASON_SALES_ITEM
        , SNAPSHOT_DATE
    from VBAP_HIST
    WHERE 1=1
        AND SNAPSHOT_DATE-1 <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
        AND ABGRU <> ''
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1 
)
, VBAP_HIST_AS_OF AS ( -- FOR ALL SO LINES NOT REJECTED AS OF THE LAST OF THE MONTH
    SELECT * 
    FROM VBAP_HIST_RECENT
    WHERE VBAP_HIST_RECENT.SALES_DOCUMENT || VBAP_HIST_RECENT.SALES_DOCUMENT_ITEM NOT IN (
        SELECT SALES_DOCUMENT || SALES_DOCUMENT_ITEM FROM VBAP_HIST_EOM
        )
)

, VBRK_HIST AS (
    SELECT * FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU014_VBRK_HIST') }}
)
, VBRK_HIST_RECENT AS ( --TO CAPTURE DOCUMENTS WITH BILLING DATE <= LAST DAY OF MONTH EVEN IF THEY WERE CREATED AFTER THE END OF THE MONTH
    SELECT
        VBELN as BILLING_DOCUMENT
        , FKDAT AS BILLING_DATE
        , FKART AS BILLING_TYPE
        , FKSTO AS BILLING_DOC_IS_CANCELED
        , SFAKN AS CANCELLED_BILLING_DOCUMENT
        , SNAPSHOT_DATE
    FROM VBRK_HIST
    WHERE 1=1
        AND VKORG = '3200'
        AND TRY_TO_DATE(FKDAT, 'YYYYMMDD') <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN ORDER BY SNAPSHOT_DATE DESC )) = 1
)
, VBRK_HIST_EOM AS ( -- TO CAPTURE BILLING DOCUMENT CANCELLED AS OF THE END OF THE MONTH
    SELECT
        VBELN as BILLING_DOCUMENT
        , FKDAT AS BILLING_DATE
        , FKART AS BILLING_TYPE
        , FKSTO AS BILLING_DOC_IS_CANCELED
        , SFAKN AS CANCELLED_BILLING_DOCUMENT
        , VBTYP AS DOCUMENT_CATEGORY
    FROM VBRK_HIST
    WHERE SNAPSHOT_DATE-1 <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN ORDER BY SNAPSHOT_DATE DESC)) = 1 
)
, VBRK_HIST_AS_OF AS (
    SELECT
        VBRK_HIST_RECENT.BILLING_DOCUMENT
        , VBRK_HIST_RECENT.BILLING_DATE
        , VBRK_HIST_RECENT.BILLING_TYPE
        , VBRK_HIST_EOM.BILLING_DOC_IS_CANCELED AS BILLING_DOC_IS_CANCELED
        , VBRK_HIST_EOM.CANCELLED_BILLING_DOCUMENT AS CANCELLED_BILLING_DOCUMENT
        , VBRK_HIST_EOM.DOCUMENT_CATEGORY
    FROM VBRK_HIST_RECENT
        LEFT JOIN VBRK_HIST_EOM
            ON VBRK_HIST_RECENT.BILLING_DOCUMENT = VBRK_HIST_EOM.BILLING_DOCUMENT
)
, VBRP_HIST AS (
    SELECT
        PRCTR AS PROFIT_CENTER
        , VBELN as BILLING_DOCUMENT
        , POSNR AS BILLING_DOCUMENT_ITEM
        , AUBEL AS SALES_DOCUMENT
        , AUPOS AS SALES_DOCUMENT_ITEM
        , NETWR AS BILLING_ITEM_AMT
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU015_VBRP_HIST') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY VBELN, POSNR ORDER BY SNAPSHOT_DATE DESC )) = 1
)

, CANCELLED_BILL AS (
    SELECT
        VBRK_HIST_AS_OF.BILLING_DOCUMENT AS BILLING_DOCUMENT
        , VBRK_HIST_AS_OF.BILLING_DOC_IS_CANCELED
        , VBRK_HIST_AS_OF.CANCELLED_BILLING_DOCUMENT AS CANCELLED_BILLING_DOCUMENT
        , VBRP_HIST.BILLING_DOCUMENT_ITEM AS CANCELLED_BILLING_DOCUMENT_ITEM
    FROM VBRK_HIST_AS_OF
        LEFT JOIN VBRP_HIST
            ON VBRK_HIST_AS_OF.BILLING_DOCUMENT = VBRP_HIST.BILLING_DOCUMENT
    WHERE 1=1
        AND BILLING_DOC_IS_CANCELED = true
        OR VBRK_HIST_AS_OF.CANCELLED_BILLING_DOCUMENT <> ''
        OR VBRK_HIST_AS_OF.DOCUMENT_CATEGORY = 'N'
)
, BILLING AS (
    SELECT
        VBRK_HIST_AS_OF.BILLING_DOCUMENT AS BILLING_DOCUMENT
        , VBRP_HIST.BILLING_DOCUMENT_ITEM
        , VBRK_HIST_AS_OF.BILLING_DATE AS BILLING_DATE
        , VBRK_HIST_AS_OF.BILLING_TYPE AS BILLING_TYPE
        , VBRK_HIST_AS_OF.BILLING_DOC_IS_CANCELED AS BILLING_DOC_IS_CANCELED
        , VBRK_HIST_AS_OF.CANCELLED_BILLING_DOCUMENT AS CANCELLED_BILLING_DOCUMENT
        , VBRP_HIST.PROFIT_CENTER AS VBRP_PROFIT_CENTER
        , VBRP_HIST.SALES_DOCUMENT
        , VBRP_HIST.SALES_DOCUMENT_ITEM
        , VBRP_HIST.BILLING_ITEM_AMT
    FROM VBRK_HIST_AS_OF
        LEFT JOIN VBRP_HIST
            ON VBRK_HIST_AS_OF.BILLING_DOCUMENT = VBRP_HIST.BILLING_DOCUMENT
    WHERE VBRK_HIST_AS_OF.BILLING_DOCUMENT || VBRP_HIST.BILLING_DOCUMENT_ITEM NOT IN (
        SELECT CANCELLED_BILLING_DOCUMENT || CANCELLED_BILLING_DOCUMENT_ITEM FROM CANCELLED_BILL)
)

, LIPS AS (
    SELECT
        VBELN AS DELIVERY_DOCUMENT
        , POSNR AS DELIVERY_DOCUMENT_ITEM
        , LFIMG as DELIVERY_QTY
        , VGBEL AS REFERENCE_DOCUMENT
        , VGPOS AS REFERENCE_DOCUMENT_ITEM
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU013_LIPS') }}
)
, LIKP AS (
    SELECT
        VBELN as Delivery_document
        , wbstk as LIKP_OVERALL_GOODS_MOVEMENT_STATUS
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU012_LIKP') }}
    where VKORG = '3200'
)

,SALES_DOC_PARTNER_DATA as (
	SELECT DISTINCT
    	SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as SALES_DOCUMENT
        , ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM
        , CUSTOMER_NUMBER
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }}
    WHERE PARTNER_FUNCTION = 'Z6'
)
, CUSTOMER AS (
	SELECT DISTINCT
    	CUSTOMER_NUMBER
        , NAME_1 AS CUSTOMER_NAME
        , REGION
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE CUSTOMER_FLAG = 'Y'
)

, SOURCE_DATA AS (
    SELECT DISTINCT
        VBAP_HIST_AS_OF.TRANSACTION_ID
        , SALES_DOC_PARTNER_DATA.CUSTOMER_NUMBER AS END_USER
        , CUSTOMER.CUSTOMER_NAME as END_USER_NAME
        , CUSTOMER.REGION AS END_USER_REGION
        , VBAP_HIST_AS_OF.SALES_DOCUMENT
        , VBAP_HIST_AS_OF.SALES_DOCUMENT_ITEM
        , VBAK_HIST.SALES_DOCUMENT_TYPE
        , VBAP_HIST_AS_OF.DISPOSITION
        , VBAP_HIST_AS_OF.PROFIT_CENTER
        , VBAP_HIST_AS_OF.MATERIAL_NUMBER
        , VBAP_HIST_AS_OF.SALES_ITEM_AMT AS SALES_DOCUMENT_ITEM_AMT
        , LIKP.LIKP_OVERALL_GOODS_MOVEMENT_STATUS
        , BILLING.BILLING_DOCUMENT
        , VBAK_HIST.PO_START_DATE
        , VBAK_HIST.PO_END_DATE
        , VBAK_HIST.CUSTOMER_REFERENCE
    FROM VBAK_HIST
        LEFT JOIN VBAP_HIST_AS_OF
            ON VBAK_HIST.SALES_DOCUMENT = VBAP_HIST_AS_OF.SALES_DOCUMENT
        LEFT JOIN LIPS
            ON LIPS.REFERENCE_DOCUMENT = VBAP_HIST_AS_OF.SALES_DOCUMENT
            AND LIPS.REFERENCE_DOCUMENT_ITEM = VBAP_HIST_AS_OF.SALES_DOCUMENT_ITEM
        LEFT JOIN LIKP
            ON LIPS.DELIVERY_DOCUMENT = LIKP.DELIVERY_DOCUMENT
        LEFT JOIN BILLING
            ON VBAP_HIST_AS_OF.SALES_DOCUMENT = BILLING.SALES_DOCUMENT
            AND VBAP_HIST_AS_OF.SALES_DOCUMENT_ITEM = BILLING.SALES_DOCUMENT_ITEM
        LEFT JOIN SALES_DOC_PARTNER_DATA
        	ON TRY_TO_NUMBER(VBAK_HIST.SALES_DOCUMENT) = TRY_TO_NUMBER(SALES_DOC_PARTNER_DATA.SALES_DOCUMENT)
            AND 0 = TRY_TO_NUMBER(SALES_DOC_PARTNER_DATA.SALES_DOCUMENT_ITEM)
        LEFT JOIN CUSTOMER
            ON SALES_DOC_PARTNER_DATA.CUSTOMER_NUMBER = CUSTOMER.CUSTOMER_NUMBER
    WHERE 1=1
        AND VBAK_HIST.SALES_DOCUMENT_TYPE IN ('ZP12', 'ZPR2')
        AND LIKP.LIKP_OVERALL_GOODS_MOVEMENT_STATUS = 'C'
        and LIPS.DELIVERY_QTY <> '0'
        AND (BILLING.BILLING_DOCUMENT = '' OR BILLING.BILLING_DOCUMENT IS NULL)
)

, TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') AS _ROW_HASH
        , TRANSACTION_ID
        , END_USER
        , END_USER_NAME
        , END_USER_REGION
        , SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM
        , SALES_DOCUMENT_TYPE
        , DISPOSITION
        , PROFIT_CENTER
        , MATERIAL_NUMBER
        , SALES_DOCUMENT_ITEM_AMT
        , CASE
            WHEN LIKP_OVERALL_GOODS_MOVEMENT_STATUS = 'C' THEN 'COMPLETELY PROCESSED'
            ELSE LIKP_OVERALL_GOODS_MOVEMENT_STATUS
        end as GOODS_ISSUE
        , BILLING_DOCUMENT
        , TRY_TO_DATE(PO_START_DATE, 'YYYYMMDD') AS PO_START_DATE
        , TRY_TO_DATE(PO_END_DATE, 'YYYYMMDD') AS PO_END_DATE
        , CUSTOMER_REFERENCE
        , CASE 
            WHEN SALES_DOCUMENT_TYPE = 'ZPR2' THEN SALES_DOCUMENT_ITEM_AMT * -1
            ELSE SALES_DOCUMENT_ITEM_AMT
        END AS ACCRUAL_AMOUNT  
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        TRANSACTION_ID,
        END_USER,
        END_USER_NAME,
        END_USER_REGION,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        SALES_DOCUMENT_TYPE,
        DISPOSITION,
        PROFIT_CENTER,
        MATERIAL_NUMBER,
        SALES_DOCUMENT_ITEM_AMT,
        GOODS_ISSUE,
        BILLING_DOCUMENT,
        CAST(PO_START_DATE AS DATE) AS PO_START_DATE,
        CAST(PO_END_DATE AS DATE) AS PO_END_DATE,
        CUSTOMER_REFERENCE,
        CAST(ACCRUAL_AMOUNT AS NUMBER(38,2)) AS ACCRUAL_AMOUNT
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
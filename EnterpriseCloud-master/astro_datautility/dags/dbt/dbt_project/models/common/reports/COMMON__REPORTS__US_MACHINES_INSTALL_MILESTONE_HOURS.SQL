WITH SN AS (
	SELECT
		DISTINCT MACHINESERIALNUMBER AS SERIAL_NUMBER
	FROM
		{{ ref('COMMON__KRONOS__TIMESHEET') }}
	WHERE
		TYPEOFWORK IN (
			'Startup',
			'Pre-Warranty',
			'Pre-warranty'
		)
		AND MACHINESERIALNUMBER IS NOT NULL
	UNION
	SELECT
		DISTINCT SERIAL_NUMBER
	FROM
		{{ ref('COMMON__DE_WISDOM__GLOBAL_MACHINES') }}
	WHERE
		CHAMBER_FLAG = 'N'
		AND TEL_REGION = 'North America'
		AND (
			INSTALL_BASE_STATUS IN (
				'Eval Tool',
				'Forecast Tool',
				'Startup Tool'
			)
			OR (
				INSTALL_BASE_STATUS = 'Production Tool'
				AND WARRANTY_STATUS = 'Pre Warranty'
			)
		)
),
DETAILS AS (
	SELECT
		CUSTOMER_GROUP,
		CASE
			WHEN CUSTOMER_GROUP = 'INTEL' THEN 'Y'
			ELSE 'N'
		END AS INTEL_FLAG,
		PARENT_CUSTOMER_NAME AS CURRENT_PARENT_CUSTOMER,
		CUSTOMER_NAME AS CURRENT_CUSTOMER_NAME,
		LOCATION_NAME AS CURRENT_LOCATION_NAME,
		LEGACY_BU,
		SERIAL_NUMBER,
		CUSTOMER_TOOL_ID,
		SWLH_MODEL,
		TEL_MODEL,
		START_UP_STATUS AS CURRENT_START_UP_STATUS,
		WARRANTY_STATUS AS CURRENT_WARRANTY_STATUS,
		MACHINE_HISTORY_REASON AS CURRENT_MACHINE_HISTORY_REASON,
		SAP_PRODUCT_CODE,
		LOAN_FLAG AS CURRENT_LOAN_FLAG,
		INSTALL_BASE_STATUS AS CURRENT_INSTALL_BASE_STATUS,
		ACT_DOCK_DATE,
		ACT_MOVE_IN,
		ACT_STARTUP_HOOKUP_START,
		COALESCE(ACT_STARTUP_HOOKUP_START, ACT_MOVE_IN) AS CALC_INSTALL_START,
		ACT_SL1,
		ACT_SL2,
		ACT_HW_STARTUP_END,
		ACT_EQ_HANDOFF_TO_CUST,
		CASE
			WHEN ACT_EQ_HANDOFF_TO_CUST IS NULL
			AND ACT_HW_STARTUP_END IS NULL
			AND ACT_ACCEPTANCE IS NOT NULL THEN ACT_ACCEPTANCE
			WHEN ACT_EQ_HANDOFF_TO_CUST IS NULL
			AND ACT_HW_STARTUP_END IS NOT NULL THEN ACT_HW_STARTUP_END
			WHEN ACT_EQ_HANDOFF_TO_CUST IS NOT NULL
			AND ACT_HW_STARTUP_END IS NULL THEN ACT_EQ_HANDOFF_TO_CUST
			WHEN ACT_EQ_HANDOFF_TO_CUST <= ACT_HW_STARTUP_END THEN ACT_EQ_HANDOFF_TO_CUST
			WHEN ACT_HW_STARTUP_END < ACT_EQ_HANDOFF_TO_CUST THEN ACT_HW_STARTUP_END
		END AS CALC_INSTALL_END,
		CTA_SIGNOFF_DATE,
		ACT_ACCEPTANCE,
		WARRANTY_START,
		WARRANTY_END
	FROM
		{{ ref('COMMON__DE_WISDOM__GLOBAL_MACHINES') }}
	WHERE
		CHAMBER_FLAG = 'N'
		AND (
			WARRANTY_START IS NULL
			OR WARRANTY_START >= '2018-04-01'
		)
),
KRONOS AS (
	SELECT
		MACHINESERIALNUMBER AS SERIAL_NUMBER,
		EMPLOYEEFULLNAME,
		EMPLOYEEID,
		EMPLOYEETYPE,
		EVENTDATE,
		HOURSCHARGED AS KRONOS_HOURS,
		TYPEOFWORK,
		TASK,
		TIMESHEETITEMID
	FROM
		{{ ref('COMMON__KRONOS__TIMESHEET') }}
	WHERE
		TYPEOFWORK IN (
			'Startup',
			'Pre-Warranty',
			'Pre-warranty'
		)
		AND MACHINESERIALNUMBER IS NOT NULL
),
DATE AS (
	SELECT
		CALENDAR_DATE,
		YEAR_MONTH_TEXT,
		FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR,
		FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF,
		FISCAL_YEAR_QUARTER_SHORT_TEXT AS FISCAL_QTR,
		PAY_PERIOD_BEGIN_DATE,
		PAY_PERIOD_END_DATE
	FROM
		COMMON.DE_SAP_MASTER_DATA.CALENDAR_DATE
),
MACHINE AS (
	SELECT
		DETAILS.CUSTOMER_GROUP,
		DETAILS.INTEL_FLAG,
		DETAILS.CURRENT_PARENT_CUSTOMER,
		DETAILS.CURRENT_CUSTOMER_NAME,
		DETAILS.CURRENT_LOCATION_NAME,
		DETAILS.LEGACY_BU,
		SN.SERIAL_NUMBER,
		KRONOS.EMPLOYEEFULLNAME,
		KRONOS.EMPLOYEEID,
		KRONOS.EMPLOYEETYPE,
		KRONOS.EVENTDATE,
		KRONOS.KRONOS_HOURS,
		KRONOS.TYPEOFWORK,
		KRONOS.TASK,
		CASE
			WHEN KRONOS.EVENTDATE IS NULL THEN 'No Hours'
			WHEN DETAILS.CURRENT_INSTALL_BASE_STATUS IN (
				'Forecast Tool',
				'Startup Tool',
				'Eval Tool',
				'Inactive Tool'
			)
			AND COALESCE(DETAILS.ACT_DOCK_DATE, DETAILS.ACT_MOVE_IN) IS NULL THEN 'Prefac Work'
			WHEN DETAILS.CURRENT_INSTALL_BASE_STATUS IN (
				'Forecast Tool',
				'Startup Tool',
				'Eval Tool',
				'Inactive Tool'
			)
			AND KRONOS.EVENTDATE <= DETAILS.ACT_DOCK_DATE THEN 'Prefac Work'
			WHEN DETAILS.CURRENT_INSTALL_BASE_STATUS IN (
				'Forecast Tool',
				'Startup Tool',
				'Eval Tool',
				'Inactive Tool'
			)
			AND KRONOS.EVENTDATE >= DETAILS.ACT_DOCK_DATE
			AND DETAILS.CALC_INSTALL_START IS NULL THEN 'Prefac Work'
			WHEN KRONOS.EVENTDATE < DETAILS.CALC_INSTALL_START THEN 'Prefac Work'
			WHEN KRONOS.EVENTDATE >= DETAILS.CALC_INSTALL_START
			AND COALESCE(DETAILS.ACT_SL1, DETAILS.ACT_SL2) IS NULL THEN 'Install Start to SL1'
			WHEN KRONOS.EVENTDATE >= DETAILS.CALC_INSTALL_START
			AND KRONOS.EVENTDATE < COALESCE(DETAILS.ACT_SL1, DETAILS.ACT_SL2) THEN 'Install Start to SL1'
			WHEN KRONOS.EVENTDATE >= DETAILS.ACT_SL1
			AND KRONOS.EVENTDATE < COALESCE(DETAILS.ACT_SL2, DETAILS.CALC_INSTALL_END) THEN 'SL1 to SL2'
			WHEN KRONOS.EVENTDATE >= DETAILS.ACT_SL1
			AND COALESCE(DETAILS.ACT_SL2, DETAILS.CALC_INSTALL_END) IS NULL THEN 'SL2 to Install End'
			WHEN KRONOS.EVENTDATE >= DETAILS.ACT_SL2
			AND DETAILS.CALC_INSTALL_END IS NULL THEN 'SL2 to Install End'
			WHEN KRONOS.EVENTDATE >= DETAILS.ACT_SL2
			AND KRONOS.EVENTDATE < DETAILS.CALC_INSTALL_END THEN 'SL2 to Install End'
			WHEN KRONOS.EVENTDATE >= DETAILS.ACT_SL2
			AND KRONOS.EVENTDATE < DETAILS.CTA_SIGNOFF_DATE THEN 'SL2 to Install End'
			WHEN KRONOS.EVENTDATE >= COALESCE(
				DETAILS.CALC_INSTALL_END,
				DETAILS.CTA_SIGNOFF_DATE
			) THEN 'Install End to Acceptance'
			ELSE 'Mapping Error'
		END AS STARTUP_HOURS_TYPE,
		DETAILS.CUSTOMER_TOOL_ID,
		DETAILS.SWLH_MODEL,
		DETAILS.TEL_MODEL,
		DETAILS.CURRENT_START_UP_STATUS,
		DETAILS.CURRENT_WARRANTY_STATUS,
		DETAILS.CURRENT_MACHINE_HISTORY_REASON,
		DETAILS.SAP_PRODUCT_CODE,
		DETAILS.CURRENT_LOAN_FLAG,
		CASE
			WHEN DETAILS.CALC_INSTALL_END IS NULL THEN 'Under Install'
			ELSE 'Install Completed'
		END INSTALL_STATUS,
		DETAILS.CURRENT_INSTALL_BASE_STATUS,
		DETAILS.ACT_DOCK_DATE,
		DETAILS.ACT_MOVE_IN,
		DETAILS.ACT_STARTUP_HOOKUP_START,
		DETAILS.CALC_INSTALL_START,
		DETAILS.ACT_SL1,
		DETAILS.ACT_SL2,
		DETAILS.ACT_HW_STARTUP_END,
		DETAILS.ACT_EQ_HANDOFF_TO_CUST,
		DETAILS.CALC_INSTALL_END,
		DETAILS.CTA_SIGNOFF_DATE,
		DETAILS.ACT_ACCEPTANCE,
		DETAILS.WARRANTY_START,
		DETAILS.WARRANTY_END,
		DATEDIFF(day, CALC_INSTALL_START, ACT_SL1) AS INSTALL_START_TO_SL1_DAYS,
		DATEDIFF(day, ACT_SL1, ACT_SL2) AS SL1_TO_SL2_DAYS,
		DATEDIFF(day, ACT_SL2, CALC_INSTALL_END) AS SL2_TO_INSTALL_END_DAYS,
		DATEDIFF(day, CALC_INSTALL_END, ACT_ACCEPTANCE) AS INSTALL_END_TO_ACCEPTANCE_DAYS,
		DATEDIFF(day, CALC_INSTALL_START, CALC_INSTALL_END) AS INSTALL_START_TO_INSTALL_END_DAYS,
		DATEDIFF(day, CALC_INSTALL_START, ACT_ACCEPTANCE) AS TOTAL_SOLT,
		DATE.YEAR_MONTH_TEXT AS INSTALL_START_MONTH,
		DATE.FISCAL_YEAR AS INSTALL_START_FISCAL_YEAR,
		DATE.FISCAL_HALF AS INSTALL_START_FISCAL_HALF,
		DATE.FISCAL_QTR AS INSTALL_START_FISCAL_QTR,
		INSTALLEND.YEAR_MONTH_TEXT AS INSTALL_END_MONTH,
		INSTALLEND.FISCAL_YEAR AS INSTALL_END_FISCAL_YEAR,
		INSTALLEND.FISCAL_HALF AS INSTALL_END_FISCAL_HALF,
		INSTALLEND.FISCAL_QTR AS INSTALL_END_FISCAL_QTR,
		EVENTDATE.YEAR_MONTH_TEXT AS KRONOS_MONTH,
		EVENTDATE.FISCAL_YEAR AS KRONOS_FISCAL_YEAR,
		EVENTDATE.FISCAL_HALF AS KRONOS_FISCAL_HALF
	FROM
		SN
		INNER JOIN DETAILS ON SN.SERIAL_NUMBER = DETAILS.SERIAL_NUMBER
		LEFT JOIN DATE ON DETAILS.CALC_INSTALL_START = DATE.CALENDAR_DATE
		LEFT JOIN DATE INSTALLEND ON DETAILS.CALC_INSTALL_END = INSTALLEND.CALENDAR_DATE
		LEFT JOIN KRONOS ON KRONOS.SERIAL_NUMBER = DETAILS.SERIAL_NUMBER
		LEFT JOIN DATE EVENTDATE ON KRONOS.EVENTDATE = EVENTDATE.CALENDAR_DATE
),
SOURCE AS (
	SELECT
		MACHINE.CUSTOMER_GROUP,
		MACHINE.INTEL_FLAG,
		MACHINE.CURRENT_PARENT_CUSTOMER,
		MACHINE.CURRENT_CUSTOMER_NAME,
		MACHINE.CURRENT_LOCATION_NAME,
		MACHINE.LEGACY_BU,
		MACHINE.SERIAL_NUMBER,
		MACHINE.EMPLOYEEFULLNAME,
		MACHINE.EMPLOYEEID,
		MACHINE.EMPLOYEETYPE,
		MACHINE.EVENTDATE,
		MACHINE.KRONOS_HOURS,
		MACHINE.TYPEOFWORK,
		MACHINE.TASK,
		MACHINE.STARTUP_HOURS_TYPE,
		CASE
			WHEN MACHINE.STARTUP_HOURS_TYPE = 'No Hours' THEN 0
			WHEN MACHINE.STARTUP_HOURS_TYPE = 'Prefac Work' THEN 1
			WHEN MACHINE.STARTUP_HOURS_TYPE = 'Install Start to SL1' THEN 2
			WHEN MACHINE.STARTUP_HOURS_TYPE = 'SL1 to SL2' THEN 3
			WHEN MACHINE.STARTUP_HOURS_TYPE = 'SL2 to Install End' THEN 4
			WHEN MACHINE.STARTUP_HOURS_TYPE = 'Install End to Acceptance' THEN 5
			ELSE 6
		END AS STARTUP_HOURS_RANK,
		MACHINE.CUSTOMER_TOOL_ID,
		MACHINE.SWLH_MODEL,
		MACHINE.TEL_MODEL,
		MACHINE.CURRENT_START_UP_STATUS,
		MACHINE.CURRENT_WARRANTY_STATUS,
		MACHINE.CURRENT_MACHINE_HISTORY_REASON,
		MACHINE.SAP_PRODUCT_CODE,
		MACHINE.CURRENT_LOAN_FLAG,
		MACHINE.INSTALL_STATUS,
		MACHINE.CURRENT_INSTALL_BASE_STATUS,
		MACHINE.ACT_DOCK_DATE,
		MACHINE.ACT_MOVE_IN,
		MACHINE.ACT_STARTUP_HOOKUP_START,
		MACHINE.CALC_INSTALL_START,
		MACHINE.ACT_SL1,
		MACHINE.ACT_SL2,
		MACHINE.ACT_HW_STARTUP_END,
		MACHINE.ACT_EQ_HANDOFF_TO_CUST,
		MACHINE.CALC_INSTALL_END,
		MACHINE.CTA_SIGNOFF_DATE,
		MACHINE.ACT_ACCEPTANCE,
		MACHINE.WARRANTY_START,
		MACHINE.WARRANTY_END,
		MACHINE.INSTALL_START_TO_SL1_DAYS,
		MACHINE.SL1_TO_SL2_DAYS,
		MACHINE.SL2_TO_INSTALL_END_DAYS,
		MACHINE.INSTALL_END_TO_ACCEPTANCE_DAYS,
		MACHINE.INSTALL_START_TO_INSTALL_END_DAYS,
		MACHINE.TOTAL_SOLT,
		MACHINE.INSTALL_START_MONTH,
		MACHINE.INSTALL_START_FISCAL_YEAR,
		MACHINE.INSTALL_START_FISCAL_HALF,
		MACHINE.INSTALL_START_FISCAL_QTR,
		MACHINE.INSTALL_END_MONTH,
		MACHINE.INSTALL_END_FISCAL_YEAR,
		MACHINE.INSTALL_END_FISCAL_HALF,
		MACHINE.INSTALL_END_FISCAL_QTR,
		MACHINE.KRONOS_MONTH,
		MACHINE.KRONOS_FISCAL_YEAR,
		MACHINE.KRONOS_FISCAL_HALF
	FROM
		MACHINE
	ORDER BY
		SERIAL_NUMBER
),
TRANSFORM AS (
	SELECT
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH,
		CUSTOMER_GROUP,
		INTEL_FLAG,
		CURRENT_PARENT_CUSTOMER,
		CURRENT_CUSTOMER_NAME,
		CURRENT_LOCATION_NAME,
		LEGACY_BU,
		SERIAL_NUMBER,
		EMPLOYEEFULLNAME,
		EMPLOYEEID,
		EMPLOYEETYPE,
		EVENTDATE,
		KRONOS_HOURS,
		TYPEOFWORK,
		TASK,
		STARTUP_HOURS_TYPE,
		STARTUP_HOURS_RANK,
		CUSTOMER_TOOL_ID,
		SWLH_MODEL,
		TEL_MODEL,
		CURRENT_START_UP_STATUS,
		CURRENT_WARRANTY_STATUS,
		CURRENT_MACHINE_HISTORY_REASON,
		SAP_PRODUCT_CODE,
		CURRENT_LOAN_FLAG,
		INSTALL_STATUS,
		CURRENT_INSTALL_BASE_STATUS,
		ACT_DOCK_DATE,
		ACT_MOVE_IN,
		ACT_STARTUP_HOOKUP_START,
		CALC_INSTALL_START,
		ACT_SL1,
		ACT_SL2,
		ACT_HW_STARTUP_END,
		ACT_EQ_HANDOFF_TO_CUST,
		CALC_INSTALL_END,
		CTA_SIGNOFF_DATE,
		ACT_ACCEPTANCE,
		WARRANTY_START,
		WARRANTY_END,
		INSTALL_START_TO_SL1_DAYS,
		SL1_TO_SL2_DAYS,
		SL2_TO_INSTALL_END_DAYS,
		INSTALL_END_TO_ACCEPTANCE_DAYS,
		INSTALL_START_TO_INSTALL_END_DAYS,
		TOTAL_SOLT,
		INSTALL_START_MONTH,
		INSTALL_START_FISCAL_YEAR,
		INSTALL_START_FISCAL_HALF,
		INSTALL_START_FISCAL_QTR,
		INSTALL_END_MONTH,
		INSTALL_END_FISCAL_YEAR,
		INSTALL_END_FISCAL_HALF,
		INSTALL_END_FISCAL_QTR,
		KRONOS_MONTH,
		KRONOS_FISCAL_YEAR,
		KRONOS_FISCAL_HALF
	FROM
		SOURCE
),
TYPE_DATA AS (
	SELECT
		CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
		CUSTOMER_GROUP,
		INTEL_FLAG,
		CURRENT_PARENT_CUSTOMER,
		CURRENT_CUSTOMER_NAME,
		CURRENT_LOCATION_NAME,
		LEGACY_BU,
		SERIAL_NUMBER,
		EMPLOYEEFULLNAME,
		EMPLOYEEID,
		EMPLOYEETYPE,
		CAST(EVENTDATE AS DATE) AS EVENTDATE,
		CAST(KRONOS_HOURS AS NUMBER(38, 2)) AS KRONOS_HOURS,
		TYPEOFWORK,
		TASK,
		STARTUP_HOURS_TYPE,
		CAST(STARTUP_HOURS_RANK AS NUMBER(38, 2)) AS STARTUP_HOURS_RANK,
		CUSTOMER_TOOL_ID,
		SWLH_MODEL,
		TEL_MODEL,
		CURRENT_START_UP_STATUS,
		CURRENT_WARRANTY_STATUS,
		CURRENT_MACHINE_HISTORY_REASON,
		SAP_PRODUCT_CODE,
		CURRENT_LOAN_FLAG,
		INSTALL_STATUS,
		CURRENT_INSTALL_BASE_STATUS,
		CAST(ACT_DOCK_DATE AS DATE) AS ACT_DOCK_DATE,
		CAST(ACT_MOVE_IN AS DATE) AS ACT_MOVE_IN,
		CAST(ACT_STARTUP_HOOKUP_START AS DATE) AS ACT_STARTUP_HOOKUP_START,
		CAST(CALC_INSTALL_START AS DATE) AS CALC_INSTALL_START,
		CAST(ACT_SL1 AS DATE) AS ACT_SL1,
		CAST(ACT_SL2 AS DATE) AS ACT_SL2,
		CAST(ACT_HW_STARTUP_END AS DATE) AS ACT_HW_STARTUP_END,
		CAST(ACT_EQ_HANDOFF_TO_CUST AS DATE) AS ACT_EQ_HANDOFF_TO_CUST,
		CAST(CALC_INSTALL_END AS DATE) AS CALC_INSTALL_END,
		CAST(CTA_SIGNOFF_DATE AS DATE) AS CTA_SIGNOFF_DATE,
		CAST(ACT_ACCEPTANCE AS DATE) AS ACT_ACCEPTANCE,
		CAST(WARRANTY_START AS DATE) AS WARRANTY_START,
		CAST(WARRANTY_END AS DATE) AS WARRANTY_END,
		CAST(INSTALL_START_TO_SL1_DAYS AS NUMBER(38, 2)) AS INSTALL_START_TO_SL1_DAYS,
		CAST(SL1_TO_SL2_DAYS AS NUMBER(38, 2)) AS SL1_TO_SL2_DAYS,
		CAST(SL2_TO_INSTALL_END_DAYS AS NUMBER(38, 2)) AS SL2_TO_INSTALL_END_DAYS,
		CAST(INSTALL_END_TO_ACCEPTANCE_DAYS AS NUMBER(38, 2)) AS INSTALL_END_TO_ACCEPTANCE_DAYS,
		CAST(
			INSTALL_START_TO_INSTALL_END_DAYS AS NUMBER(38, 2)
		) AS INSTALL_START_TO_INSTALL_END_DAYS,
		CAST(TOTAL_SOLT AS NUMBER(38, 2)) AS TOTAL_SOLT,
		INSTALL_START_MONTH,
		INSTALL_START_FISCAL_YEAR,
		INSTALL_START_FISCAL_HALF,
		INSTALL_START_FISCAL_QTR,
		INSTALL_END_MONTH,
		INSTALL_END_FISCAL_YEAR,
		INSTALL_END_FISCAL_HALF,
		INSTALL_END_FISCAL_QTR,
		KRONOS_MONTH,
		KRONOS_FISCAL_YEAR,
		KRONOS_FISCAL_HALF
	FROM
		TRANSFORM
)
SELECT
	*
FROM
	TYPE_DATA
with lips_cte as (
    select * from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU013_LIPS') }}
    where IS_DELETED = 'No'
),


likp_cte as (
    select * from  {{ ref('ODS__SAPAPI__ZCDV_T_CMTU012_LIKP') }}
    where IS_DELETED = 'No'
),

Vendor_name as (
select distinct LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR, LFA1_NAME_1_NAME1
from {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
),

ADDRESS as (
select ADDRNUMBER, Name1
from  {{ ref('ODS__SAPAPI__ZCDV_T_CMTU087_ADRC') }} where LANGU= 'EN'  and nation = 'I'
),

PLANT_ADRC AS (
SELECT WERKS,NAME1
FROM  {{ ref('ODS__SAPAPI__ZCDV_T_CMTU063_T001W') }}
),
PO_HISTROY as (
select 
		EBELN AS PURCHASE_ORDER,
		EBELP AS PO_LINE,
        BEWTP as GR_INV,
        BUDAT as POSTING_DATE,
		SUM(CASE WHEN SHKZG = 'S' THEN MENGE ELSE MENGE * -1 END) AS QTY,
		SUM(CASE WHEN SHKZG = 'S' THEN WRBTR ELSE WRBTR * -1 END) AS AMOUNT
from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU217_EKBE') }} where BEWTP in ('Q','E')
group by EBELN,EBELP,BUDAT,SHKZG,BEWTP
),

GR as (
select
    PURCHASE_ORDER as PURCHASING_DOCUMENT_NUMBER,
    PO_LINE as ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    POSTING_DATE as RECEIPT_DATE,
    sum(QTY) as Gr_Quantity,
    sum(Gr_Quantity) Over (Partition By PURCHASE_ORDER,PO_LINE order By PURCHASE_ORDER,PO_LINE ) as DeliveredQuantity,
    sum(Gr_Quantity) Over (Partition By PURCHASE_ORDER,PO_LINE order By  PURCHASE_ORDER,PO_LINE,POSTING_DATE Rows Between Unbounded Preceding And Current Row ) as runningsum
from PO_HISTROY where GR_INV = 'E'
group by PURCHASE_ORDER,PO_LINE,POSTING_DATE
),

invoice as (
select
    PURCHASE_ORDER as PURCHASING_DOCUMENT_NUMBER,
    PO_LINE as ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    sum(AMOUNT) as InvoicedAmount
from  PO_HISTROY where GR_INV = 'Q'
group by PURCHASE_ORDER,PO_LINE),


EKET as (
select
    ebeln as PURCHASING_DOCUMENT_NUMBER,
    ebelp as ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    EINDT as Scheduled_Date,
    SUM(MENGE)  as Scheduled_Quantity
from   {{ ref('ODS__SAPAPI__ZCDV_T_CMTU048_EKET') }}
group by ebeln,ebelp,EINDT
),

ekes as (
select
    EKKO_COMPANY_CODE,
    CONCATENATION_OF_EBELN_AND_EBELP,
    EKKO_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    SEQUENTIAL_NUMBER_OF_SUPPLIER_CONFIRMATION_ETENS,
    PURCHASING_DOCUMENT_TYPE,
    T161T.BATXT as POTYPE_DESCRIPTION,
    MATERIAL_NUMBER_MATNR,
    SHORT_TEXT,
    plant,
    NET_ORDER_VALUE_IN_PO_CURRENCY,
    CURRENCY_KEY,
    PURCHASE_ORDER_QUANTITY,
    PURCHASE_ORDER_UNIT_OF_MEASURE,
    NET_PRICE_IN_PURCHASING_DOCUMENT,
    TERMS_OF_PAYMENT_KEY,
    PURCHASING_DOCUMENT_DATE ,
    PURCHASE_APPROVE_DATE,
    PURCHASING_ORGANIZATION_EKORG,--EKPO.INFNR
    NUMBER_OF_PURCHASING_INFO_RECORD,--EKPO.ZZOPZZ
    CASE ORDER_PRIORITY_ZZOPZZ
    WHEN '1' THEN 'NORMAL'
    WHEN '2' THEN 'RUSH'
    WHEN '3' THEN 'URGENT'
    WHEN '4' THEN 'EMERGENCY'
    ELSE 'NORMAL' END AS OrderPriority,
    YOUR_REFERENCE,
    OUR_REFERENCE,
    EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT,
    CREATED_BY_EMPLOYEE_NO,
    CONFIRMATION_CATEGORY,
    EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    CREATION_DATE_OF_CONFIRMATION,
    QUANTITY_AS_PER_SUPPLIER_CONFIRMATION,
    QUANTITY_REDUCED,
    DELIVERY_VBELN,
    COLLECTIVE_NUMBER,
    STORAGE_LOCATION,
    PRODUCT_CODE,
    VENDOR_S_ACCOUNT_NUMBER,
    case when NUMBER_OF_DELIVERY_ADDRESS = '' then MANUAL_ADDRESS_NUMBER_IN_PURCHASING_DOCUMENT_ITEM else NUMBER_OF_DELIVERY_ADDRESS
    end as NUMBER_OF_DELIVERY_ADDRESS
from {{ ref('COMMON__SAPH__PURCHASE_ORDER_SUPPLIER_CONFIRMATION') }} as EKES
left join  {{ ref('ODS__SAPAPI__ZCDV_T_CMTU129_T161T') }}  as T161T
on EKES.PURCHASING_DOCUMENT_TYPE = T161T.BSART
where T161T.SPRAS = 'EN' and T161T.BSTYP = 'F'
),

ekes_ab as (
select
    EKKO_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    CREATION_DATE_OF_CONFIRMATION,
    sum(QUANTITY_AS_PER_SUPPLIER_CONFIRMATION) as QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    SUM(QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1) OVER (PARTITION BY EKKO_PURCHASING_DOCUMENT_NUMBER,ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP                                               ORDER BY EKKO_PURCHASING_DOCUMENT_NUMBER,ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION
                                                    asc ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) as TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION
from ekes
where CONFIRMATION_CATEGORY = 'AB'
group by EKKO_PURCHASING_DOCUMENT_NUMBER,ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,CREATION_DATE_OF_CONFIRMATION
),

ekes_ab_n as (
select
    EKKO_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    CREATION_DATE_OF_CONFIRMATION,
    QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION,
    gr.runningsum
from ekes_ab as ekes
left join GR as gr
  on ekes.EKKO_PURCHASING_DOCUMENT_NUMBER = GR.PURCHASING_DOCUMENT_NUMBER
and ekes.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP = GR.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
where (case when ekes.EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION is null then 1 else 0 end or ekes.TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION >= GR.runningsum )
  qualify(row_number() over(partition by GR.PURCHASING_DOCUMENT_NUMBER,GR.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,GR.runningsum
                          order by  EKES.TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION))= 1

),

ekes_la as (
select
    EKKO_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    CREATION_DATE_OF_CONFIRMATION,
    max(DELIVERY_VBELN) as DELIVERY,
    sum(QUANTITY_AS_PER_SUPPLIER_CONFIRMATION) as QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    SUM(QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1) OVER (PARTITION BY EKKO_PURCHASING_DOCUMENT_NUMBER,ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP                                               ORDER BY EKKO_PURCHASING_DOCUMENT_NUMBER,ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION
                                                    asc ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) as TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION
from ekes
where CONFIRMATION_CATEGORY = 'LA' and  QUANTITY_REDUCED > 0
group by EKKO_PURCHASING_DOCUMENT_NUMBER,ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,CREATION_DATE_OF_CONFIRMATION
),

ekes_la_n as (
select
    EKKO_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    DELIVERY,
    QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION,
    gr.runningsum
from ekes_la as ekes
left join GR as gr
  on ekes.EKKO_PURCHASING_DOCUMENT_NUMBER = GR.PURCHASING_DOCUMENT_NUMBER
and ekes.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP = GR.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
where (case when ekes.EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION is null then 1 else 0 end or ekes.TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION >= GR.runningsum )
qualify(row_number() over(partition by GR.PURCHASING_DOCUMENT_NUMBER,GR.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,GR.runningsum
                          order by  EKES.TOTAL_QTY_AS_PER_VENDOR_CONFIRMATION))= 1
),

ekes_final as (
select
    ekes_ab_n.EKKO_PURCHASING_DOCUMENT_NUMBER,
    ekes_ab_n.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    ekes_ab_n.CREATION_DATE_OF_CONFIRMATION as ab_CREATION_DATE_OF_CONFIRMATION,
    ekes_ab_n.EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION as ab_EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    ekes_ab_n.QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1 as ab_QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    ekes_la_n.DELIVERY,
    ekes_la_n.EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION as la_EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    ekes_la_n.QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1 as la_QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    ekes_la_n.runningsum
from ekes_ab_n
left join ekes_la_n
on ekes_ab_n.EKKO_PURCHASING_DOCUMENT_NUMBER = ekes_la_n.EKKO_PURCHASING_DOCUMENT_NUMBER
  and ekes_ab_n.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP = ekes_la_n.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP
  and ekes_ab_n.runningsum = ekes_la_n.runningsum
),

ekes_final_n as ( 
select
    EKKO_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    ab_CREATION_DATE_OF_CONFIRMATION,
    ab_EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    ab_QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    DELIVERY,
    la_EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,
    la_QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1,
    gr.runningsum
from gr as gr
left join ekes_final as ekes_final
ON gr.PURCHASING_DOCUMENT_NUMBER = EKES_final.EKKO_PURCHASING_DOCUMENT_NUMBER AND
gr.ITEM_NUMBER_OF_PURCHASING_DOCUMENT = EKES_final.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP
-- and  gr.runningsum = ekes_final.runningsum
qualify(row_number() over(partition by GR.PURCHASING_DOCUMENT_NUMBER,GR.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,GR.runningsum
                          order by  ekes_final.runningsum))= 1
 ),

delivery as (
select distinct
    likp.VBELN as delivery,
    lips.VGBEL as PURCHASING_DOCUMENT_NUMBER,
    lips.VGPOS as ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
    max(likp.LFDAT) as delivery_date,
    max(likp.WadatIst) as GOODS_MOVEMENT_DATE
from lips_cte as lips
inner join likp_cte as likp
on lips.VBELN = likp.VBELN
where lips.VGBEL IS NOT NULL
group by lips.VGBEL,lips.VGPOS,likp.vbeln
),

ekes_distinct as (
select distinct
    EKKO_COMPANY_CODE,
    CONCATENATION_OF_EBELN_AND_EBELP,
    EKKO_PURCHASING_DOCUMENT_NUMBER,
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,
    PURCHASING_DOCUMENT_TYPE,
    POTYPE_DESCRIPTION,
    PRODUCT_CODE,
    MATERIAL_NUMBER_MATNR,
    SHORT_TEXT,
    plant,
    VENDOR_S_ACCOUNT_NUMBER,
    STORAGE_LOCATION,
    NET_ORDER_VALUE_IN_PO_CURRENCY,
    CURRENCY_KEY,
    PURCHASE_ORDER_QUANTITY,
    PURCHASE_ORDER_UNIT_OF_MEASURE,
    NET_PRICE_IN_PURCHASING_DOCUMENT,
    TERMS_OF_PAYMENT_KEY,
    PURCHASING_DOCUMENT_DATE ,
    PURCHASE_APPROVE_DATE,
    PURCHASING_ORGANIZATION_EKORG,
    NUMBER_OF_PURCHASING_INFO_RECORD,
    OrderPriority,
    YOUR_REFERENCE,
    OUR_REFERENCE,
    EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT,
    CREATED_BY_EMPLOYEE_NO,
    COLLECTIVE_NUMBER,
    NUMBER_OF_DELIVERY_ADDRESS
from ekes
),
PIR as (
select 
EINE_PURCHASING_ORGANIZATION,
EINA_NUMBER_OF_PURCHASING_INFO_RECORD,
EINE_PLANNED_DELIVERY_TIME_IN_DAYS
from {{ ref('COMMON__SAPH__PURCHASE_INFORMATION_PURCHASE_ORDER') }} 
where EINE_PURCHASING_ORGANIZATION = '3200'
  qualify(row_number() over(partition by EINE_PURCHASING_ORGANIZATION,EINA_NUMBER_OF_PURCHASING_INFO_RECORD
                          order by  EINE_PLANNED_DELIVERY_TIME_IN_DAYS desc ))= 1
),

final as (
select
    EKES.CONCATENATION_OF_EBELN_AND_EBELP as POLineID,
    ekes.PURCHASING_DOCUMENT_TYPE as POType,
    ekes.POTYPE_DESCRIPTION as POTYPE_DESCRIPTION,
    EKES.EKKO_PURCHASING_DOCUMENT_NUMBER as PONumber,
    EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP as POItemNumber,
    EKES.PRODUCT_CODE as PRODUCT_CODE,
    EKES.MATERIAL_NUMBER_MATNR as ItemNumber,
    EKES.SHORT_TEXT as ItemDescription,
    EKES.STORAGE_LOCATION,
    ekes.OUR_REFERENCE,
    ekes.YOUR_REFERENCE,
    EKES.COLLECTIVE_NUMBER,
    case when adrc.name1 is NULL then PLANT_ADRC.name1 else adrc.name1  end as address,
    case when  EKES.STORAGE_LOCATION = 'Z100' and ( address iLike '%INTEL%'  or address ilike '%Consignment%') then 'Intel'
        when substr(EKES.STORAGE_LOCATION,3,1) = '3' then 'Intel'
        else 'Non-Intel'
        end as Intel,
    ZEROIFNULL(EKES.NET_ORDER_VALUE_IN_PO_CURRENCY) AS OrderedAmount,
    ZEROIFNULL(EKES.PURCHASE_ORDER_QUANTITY) AS OrderedQuantity,
    ZEROIFNULL(GR.DeliveredQuantity) AS Delivered_qty,
    OrderedQuantity - Delivered_qty as BackOrderQuantity,
    EKES.PURCHASE_ORDER_UNIT_OF_MEASURE AS UnitOfMeasure,
    (Delivered_qty * EKES.NET_PRICE_IN_PURCHASING_DOCUMENT) AS CostPrice,
    ZEROIFNULL(EKES.NET_PRICE_IN_PURCHASING_DOCUMENT) AS Unit_Price,
    invoice.InvoicedAmount as InvoicedAmount,
    concat(date_part(month,try_to_date(EKES.PURCHASING_DOCUMENT_DATE,'yyyymmdd')), '-', date_part(year,try_to_date(EKES.PURCHASING_DOCUMENT_DATE,'yyyymmdd'))) as PURCHASEORDERMONTHYEAR,
    try_to_date(EKES.PURCHASING_DOCUMENT_DATE,'yyyymmdd') AS PurchaseOrderDate,
    try_to_date(EKET.Scheduled_Date,'yyyymmdd') as PlannedDeliveryDate,
    try_to_date(EKes_final.ab_CREATION_DATE_OF_CONFIRMATION,'yyyymmdd') as Confirm_delivery_date,
    try_to_date(EKES_final.ab_EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,'yyyymmdd') as Response_DeliveryDate,
    try_to_date(EKES_final.la_EKES_DELIVERY_DATE_OF_SUPPLIER_CONFIRMATION,'yyyymmdd') as Ship_ack_DeliveryDate,
    EKES_final.DELIVERY,
    try_to_date(delivery.GOODS_MOVEMENT_DATE,'yyyymmdd') as ActFOBNaritaDate,
    to_date(gr.receipt_date,'yyyymmdd' ) as ActualReceiptDate,
    EKET.Scheduled_Quantity as PlannedSchedule_quantity,
    ekes_final.ab_QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1 as Vendor_ack_qty,
    ekes_final.la_QUANTITY_AS_PER_SUPPLIER_CONFIRMATION1 as Vendor_ship_qty,
    gr.Gr_Quantity as receipt_qty,
    YEAR(TO_DATE(gr.RECEIPT_DATE,'yyyymmdd')) AS ActualReceiptYear,
    MONTH(TO_DATE(gr.RECEIPT_DATE,'yyyymmdd')) AS ActualReceiptMonth,
    --try_to_date(EKES.PURCHASE_APPROVE_DATE,'yyyymmdd') AS PurchaseOrderConfirmationDate,
    --DATEDIFF(day,EKES.PURCHASE_APPROVE_DATE::DATE,Confirm_delivery_date::DATE) AS ontime_delivery_status,
    --DATEDIFF(day,EKES.PURCHASE_APPROVE_DATE::DATE,EKES.PURCHASING_DOCUMENT_DATE::DATE) AS POResponseDays,
    DATEDIFF(day,PurchaseOrderDate::DATE,PlannedDeliveryDate::DATE) as RequestedLeadTimeDays,
    DATEDIFF(day,PurchaseOrderDate::DATE,ActualReceiptDate::DATE) as LeadTimeVarianceDays,
    case when OrderPriority = 'EMERGENCY' then
    ( case when LeadTimeVarianceDays <= 1 THEN 'Ontime'
    WHEN LeadTimeVarianceDays <= 6 THEN '2-5 Days Late'
    WHEN LeadTimeVarianceDays <= 9 THEN '5-8 Days Late'
    WHEN LeadTimeVarianceDays <= 16 THEN '8-15 Days Late'
    WHEN LeadTimeVarianceDays <= 31 THEN '15-30 Days Late' ELSE '>30 Days Late' end )
    WHEN OrderPriority = 'URGENT' THEN
    ( CASE WHEN LeadTimeVarianceDays <= 2 THEN 'Ontime'
    WHEN LeadTimeVarianceDays <= 7 THEN '2-5 Days Late'
    WHEN LeadTimeVarianceDays <= 10 THEN '5-8 Days Late'
    WHEN LeadTimeVarianceDays <= 17 THEN '8-15 Days Late'
    WHEN LeadTimeVarianceDays <= 32 THEN '15-30 Days Late'
    ELSE '>30 Days Late' end )
    else
    (CASE WHEN LeadTimeVarianceDays <=3 THEN 'Ontime'
    when LeadTimeVarianceDays <= 7 THEN '2-5 Days Late'
    when LeadTimeVarianceDays <= 10 THEN '5-8 Days Late'
    WHEN LeadTimeVarianceDays <= 17 THEN '8-15 Days Late'
    WHEN LeadTimeVarianceDays <= 32 THEN '15-30 Days Late'
    ELSE '>30 Days Late' end)
    end AS LeadTimeVarianceGroup,
    CASE WHEN OrderPriority = 'EMERGENCY' THEN CASE WHEN LeadTimeVarianceDays <= 1 THEN 'Ontime' ELSE 'Late' END
        WHEN OrderPriority = 'URGENT' THEN CASE WHEN LeadTimeVarianceDays <= 2 THEN 'Ontime' ELSE 'Late' END
        ELSE CASE WHEN LeadTimeVarianceDays <=3 THEN 'Ontime' ELSE 'Late'END
    END AS LeadTimeKPIFlag,
    case when REQUESTEDLEADTIMEDAYS < PIR.EINE_PLANNED_DELIVERY_TIME_IN_DAYS  then ( case when ORDERPRIORITY ='NORMAL' then 0 end )
    else  ( case when ORDERPRIORITY ='NORMAL' then 1 end )  end as Fakenormal,
    case ekes.EKPO_DELETION_INDICATOR_IN_PURCHASING_DOCUMENT when 'L' then 'YES' else 'NO' end as Cancelled,
    ekes.OrderPriority,
    PIR.EINE_PLANNED_DELIVERY_TIME_IN_DAYS as LeadTimeDays,
    EKES.CURRENCY_KEY as Currency,
    case marc.REPAIRABLE
    when '0' then 'Unknown'
    when '1' then 'Repairable'
    when '2' then 'Non-Repairable'
    when '3' then 'Repairable on Condition'
    end as RepairFlag,
    MARC.NARITA_ABC,
    MARC.SPECIFIC_CUSTOMER_ABC,
    MARC.LOCAL_ABC,
    EKES.PLANT,
    EKES.CREATED_BY_EMPLOYEE_NO as BuyerEmpID,
    EKES.TERMS_OF_PAYMENT_KEY,
    EKES.PURCHASING_ORGANIZATION_EKORG as PURCHASING_ORGANIZATION,
    EKES.VENDOR_S_ACCOUNT_NUMBER as Vendor,
    LFA1_NAME_1_NAME1 as Vendor_name
from EKES_distinct as EKES
left join {{ ref('COMMON__SAPH__PURCHASE_INFORMATION_PURCHASE_ORDER') }} as PIR
ON EKES.NUMBER_OF_PURCHASING_INFO_RECORD = PIR.EINA_NUMBER_OF_PURCHASING_INFO_RECORD
and EKES.PURCHASING_ORGANIZATION_EKORG = PIR.EINE_PURCHASING_ORGANIZATION
left join {{ ref('COMMON__SAPH__MATERIAL_PLANT_MASTER') }} as MARC
on EKES.MATERIAL_NUMBER_MATNR = MARC.MARC_MATERIAL_NUMBER
and EKES.PLANT = MARC.MARC_PLANT
left join Vendor_name LFA1
on EKES.VENDOR_S_ACCOUNT_NUMBER = LFA1.LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
left join  ADDRESS as adrc
on ekes.NUMBER_OF_DELIVERY_ADDRESS = adrc.addrnumber
left join PLANT_ADRC as PLANT_ADRC
on ekes.PLANT = PLANT_ADRC.werks
left join eket
ON EKES.EKKO_PURCHASING_DOCUMENT_NUMBER = eket.PURCHASING_DOCUMENT_NUMBER AND
EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP = eket.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
LEFT JOIN GR as GR
on EKES.EKKO_PURCHASING_DOCUMENT_NUMBER = GR.PURCHASING_DOCUMENT_NUMBER and
EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP = GR.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
LEFT JOIN INVOICE as INVOICE
ON LTRIM(EKES.EKKO_PURCHASING_DOCUMENT_NUMBER,0) = LTRIM(INVOICE.PURCHASING_DOCUMENT_NUMBER,0) AND
LTRIM(EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP,0) = LTRIM(INVOICE.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,0)
left join EKES_final
ON EKES.EKKO_PURCHASING_DOCUMENT_NUMBER = EKES_final.EKKO_PURCHASING_DOCUMENT_NUMBER AND
EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP = EKES_final.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP
and  gr.runningsum = ekes_final.runningsum
left join delivery
 on delivery.DELIVERY = EKES_final.DELIVERY
and  EKES.EKKO_PURCHASING_DOCUMENT_NUMBER = delivery.PURCHASING_DOCUMENT_NUMBER AND
EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP = delivery.ITEM_NUMBER_OF_PURCHASING_DOCUMENT
),


final_n as (
select
    EKES.CONCATENATION_OF_EBELN_AND_EBELP as POLineID,
    ekes.PURCHASING_DOCUMENT_TYPE as POType,
    ekes.POTYPE_DESCRIPTION as POTYPE_DESCRIPTION,
    EKES.EKKO_PURCHASING_DOCUMENT_NUMBER as PONumber,
    EKES.ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP as POItemNumber,
    EKES.PRODUCT_CODE as PRODUCT_CODE,
    EKES.MATERIAL_NUMBER_MATNR as ItemNumber,
    EKES.SHORT_TEXT as ItemDescription,
    EKES.STORAGE_LOCATION,
    ekes.OUR_REFERENCE,

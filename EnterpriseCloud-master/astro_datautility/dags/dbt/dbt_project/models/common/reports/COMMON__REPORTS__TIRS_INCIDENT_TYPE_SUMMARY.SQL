{{ config(
      materialized='table',
      alias='TIRS_INCIDENT_TYPE_SUMMARY',
      transient=false,
      enabled=true
) }}


with CALENDARDATE as  
(
    SELECT
        CALENDAR_DATE_KEY 
        ,FISCAL_YEAR_NUMBER 
        ,MONTH_ABBREVIATION_TEXT 
        ,MONTH_OF_FISCAL_YEAR_NUMBER 
    FROM {{ source('COMMON__DE_SAP_MASTER_DATA', 'CALENDAR_DATE') }}
)

,source_data as  
(
    SELECT
        TIRS_NO 
        ,COMMON_INCIDENT_TYPE_EN AS INCIDENT_TYPE
        ,REPLACE(INITIAL_REPORTER_DATE_OF_OCCURRENCE,'/','') AS OCCURRENCE_DATE_KEY
        ,COMMON_COUNTRY_OF_ACCIDENT_EN AS COUNTRY_OF_ACCIDENT --Region RLS 
    FROM {{ ref('COMMON__TIRS__ACCIDENTREPORTSFORUS_NOLOCK') }} 
)

,transform_data as (
    SELECT
        source_data.INCIDENT_TYPE
        ,CALENDARDATE.FISCAL_YEAR_NUMBER 
        ,CALENDARDATE.MONTH_ABBREVIATION_TEXT 
        ,CALENDARDATE.MONTH_OF_FISCAL_YEAR_NUMBER 
        ,COUNT(source_data.TIRS_NO) AS TIRS_COUNT 
        ,'{{ invocation_id }}' AS AUDIT_LOG_ID
        ,SHA2('hash_me') as _ROW_HASH
    FROM source_data 
    JOIN PUB.DE_SAP_MASTER_DATA.CALENDAR_DATE CALENDARDATE ON source_data.OCCURRENCE_DATE_KEY = CALENDARDATE.CALENDAR_DATE_KEY
    WHERE source_data.COUNTRY_OF_ACCIDENT = 'USA' --Future: replace with Region RLS 
    GROUP BY source_data.INCIDENT_TYPE,CALENDARDATE.FISCAL_YEAR_NUMBER,CALENDARDATE.MONTH_OF_FISCAL_YEAR_NUMBER,CALENDARDATE.MONTH_ABBREVIATION_TEXT,source_data.COUNTRY_OF_ACCIDENT
)

,type_data as (
    SELECT 
        CAST(INCIDENT_TYPE AS VARCHAR(16777216)) AS INCIDENT_TYPE
        ,CAST(FISCAL_YEAR_NUMBER AS VARCHAR(128)) AS FISCAL_YEAR_NUMBER
        ,CAST(MONTH_ABBREVIATION_TEXT AS VARCHAR(128)) AS MONTH_ABBREVIATION_TEXT
        ,CAST(MONTH_OF_FISCAL_YEAR_NUMBER AS VARCHAR(128)) AS MONTH_OF_FISCAL_YEAR_NUMBER
        ,CAST(TIRS_COUNT AS NUMBER(38,0)) AS TIRS_COUNT
        ,CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
        ,CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH      
    FROM transform_data
)

SELECT * FROM type_data
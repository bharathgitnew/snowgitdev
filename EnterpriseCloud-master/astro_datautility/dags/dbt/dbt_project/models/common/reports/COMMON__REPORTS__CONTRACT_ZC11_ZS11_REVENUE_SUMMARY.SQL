WITH ACTUALS AS (
    SELECT
        CALENDAR_YEAR_MONTH AS REPORT_PERIOD
        ,END_USER
        ,END_USER_NAME AS CUSTOMER
    ,CASE
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME = 'TEXAS INSTRUMENTS INC.' THEN 'TI'
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME LIKE '%NXP%' THEN 'Regional'
        ELSE END_USER_GROUP
    END AS CUSTOMER_GROUP
        ,SALES_DOCUMENT_TYPE
        ,SALES_DOCUMENT
    ,CASE
        WHEN CONTRACT_NUMBER IS NOT NULL AND LEN(CONTRACT_NUMBER) > 1 THEN CONTRACT_NUMBER
    ELSE '*No Contract Assigned'
    END AS CONTRACT_NUMBER
        ,SALES_CATEGORY
    ,CASE
        WHEN SALES_CATEGORY = '98' THEN 'Other'
        WHEN SALES_CATEGORY = '99' THEN 'Free of Charge sales'
        WHEN SALES_CATEGORY = '45' THEN 'SW license Subscrip.'
    ELSE SALES_CATEGORY_NAME
    END AS SALES_CATEGORY_NAME
        ,SOLD_TO_PARTY_NAME
    ,CASE
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '98' THEN 'SAP_98'
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '99' THEN 'SAP_99'
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '45' THEN 'TSCSTD'
        ELSE SALES_CATEGORY_ORACLE
    END AS SALES_CATEGORY_ORACLE
        ,SEGMENT_CODE
        ,SEGMENT
        ,SOLD_TO_PARTY
        ,WBS_ELEMENT
    ,CASE
        WHEN (PRODUCT_TYPE_NAME IS NULL OR LEN(PRODUCT_TYPE_NAME)<1) AND SALES_CATEGORY = '98' THEN 'SAP_98'
        WHEN (PRODUCT_TYPE_NAME IS NULL OR LEN(PRODUCT_TYPE_NAME)<1) AND SALES_CATEGORY = '99' THEN 'SAP_99'
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '45' THEN 'TSC-Remote Support Contracts'
    ELSE PRODUCT_TYPE_NAME
    END AS PRODUCT_TYPE_NAME
    ,(SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) * -1)  AS REVENUE
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE') }}
    WHERE 1=1
      AND CALENDAR_YEAR_MONTH >= '2023-05'
      AND LEFT(ACCOUNT_NUMBER,1) IN ('4')
      AND COMPANY_CODE = '3200'
      AND (SALES_DOCUMENT_TYPE IN ('ZS11', 'ZC11')
      OR (SALES_DOCUMENT_TYPE IS NULL AND SALES_CATEGORY_ORACLE IN ( 'CONTRA', 'SMSRV', 'TSCREM', 'TSCSTD')))
--AND SALES_CATEGORY_ORACLE IN  ('PDSRV', 'CONTRA', 'SMSRV', 'TSCREM', 'TSCSTD')

    GROUP BY 
        CALENDAR_YEAR_MONTH
        ,END_USER
        ,END_USER_NAME
    ,CASE
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME = 'TEXAS INSTRUMENTS INC.' THEN 'TI'
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME LIKE '%NXP%' THEN 'Regional'
        ELSE END_USER_GROUP
    END
        ,SALES_DOCUMENT_TYPE
        ,SALES_DOCUMENT
    ,CASE
        WHEN CONTRACT_NUMBER IS NOT NULL AND LEN(CONTRACT_NUMBER) > 1 THEN CONTRACT_NUMBER
    ELSE '*No Contract Assigned'
    END
        ,SALES_CATEGORY
    ,CASE
        WHEN SALES_CATEGORY = '98' THEN 'Other'
        WHEN SALES_CATEGORY = '99' THEN 'Free of Charge sales'
        WHEN SALES_CATEGORY = '45' THEN 'SW license Subscrip.'
    ELSE SALES_CATEGORY_NAME
    END
        ,SOLD_TO_PARTY_NAME
    ,CASE
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '98' THEN 'SAP_98'
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '99' THEN 'SAP_99'
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '45' THEN 'TSCSTD'
    ELSE SALES_CATEGORY_ORACLE
    END
        ,SEGMENT_CODE
        ,SEGMENT
        ,SOLD_TO_PARTY
        ,WBS_ELEMENT
    ,CASE
        WHEN (PRODUCT_TYPE_NAME IS NULL OR LEN(PRODUCT_TYPE_NAME)<1) AND SALES_CATEGORY = '98' THEN 'SAP_98'
        WHEN (PRODUCT_TYPE_NAME IS NULL OR LEN(PRODUCT_TYPE_NAME)<1) AND SALES_CATEGORY = '99' THEN 'SAP_99'
        WHEN (SALES_CATEGORY_ORACLE IS NULL OR LEN(SALES_CATEGORY_ORACLE)<1) AND SALES_CATEGORY = '45' THEN 'TSC-Remote Support Contracts'
    ELSE PRODUCT_TYPE_NAME
    END
    HAVING SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) <> 0)

,CONTRACT AS (
    SELECT
        CONTRACT_NUMBER
        ,CONTRACT_TITLE
        ,CONTRACT_TYPE
        ,BAAN_CONTRACT_NUMBER
        ,CONTRACT_END_DATE
        ,CONTRACT_SCOPE_BY_PRODUCT
    FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
    )

,OFFICE AS (
    SELECT
        B_CODE
        ,LEGACY_OFFICE
        ,LEGACY_OFFICE_CODE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
    )

,SALES_CATEGORY AS (
    SELECT 
        SAP_SALES_CATEGORY
        ,SAP_SALES_CATEGORY_NAME AS SALES_CATEGORY_NAME
        ,BAAN_PRODUCT_TYPE
    FROM {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }}
    WHERE SAP_SALES_CATEGORY <> 'LG')

,ENDUSER AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
    ,CASE
        WHEN LEN(SEARCH_TERM_2_FOR_BUSINESS_PARTNER) < 1 THEN NULL
    ELSE SEARCH_TERM_2_FOR_BUSINESS_PARTNER
    END AS END_USER_SEARCH2_NAME
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B')

,SOLD_TO AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
    ,CASE
        WHEN LEN(SEARCH_TERM_2_FOR_BUSINESS_PARTNER) < 1 THEN NULL
    ELSE SEARCH_TERM_2_FOR_BUSINESS_PARTNER
    END AS SOLD_TO_SEARCH2_NAME
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B')

,SEGMENT AS (
    SELECT DISTINCT
        SAP_CODE AS SEGMENT_SAP_CODE
    ,CASE
        WHEN SAP_CODE = '29' THEN '5900'
    ELSE BAAN_CODE 
    END AS LEGACY_SEGMENT_CODE
    FROM {{ ref('COMMON__SAPH__SAP_SEGMENT') }}
    )

,SOURCE AS (
    SELECT 
        ACTUALS.REPORT_PERIOD
        ,ACTUALS.CUSTOMER_GROUP
        ,ACTUALS.CUSTOMER
        ,OFFICE.LEGACY_OFFICE
    ,CASE
        WHEN ACTUALS.SEGMENT LIKE 'FS-%' THEN REPLACE(ACTUALS.SEGMENT, 'FS-','')
    ELSE ACTUALS.SEGMENT
    END AS BU
        ,ACTUALS.SALES_CATEGORY_ORACLE
        ,ACTUALS.CONTRACT_NUMBER
        ,ACTUALS.REVENUE
        ,CONTRACT.CONTRACT_TITLE
        ,CONTRACT.CONTRACT_TYPE
        ,CONTRACT.CONTRACT_SCOPE_BY_PRODUCT
        ,CONTRACT.CONTRACT_END_DATE
        ,CONTRACT.BAAN_CONTRACT_NUMBER
        ,ACTUALS.SALES_DOCUMENT
        ,ACTUALS.SALES_DOCUMENT_TYPE
        ,ACTUALS.SALES_CATEGORY_NAME
        ,ACTUALS.SALES_CATEGORY
        ,ACTUALS.SEGMENT
        ,ACTUALS.SEGMENT_CODE
        ,SEGMENT.LEGACY_SEGMENT_CODE
        ,OFFICE.LEGACY_OFFICE_CODE
        ,ACTUALS.END_USER
        ,ENDUSER.END_USER_SEARCH2_NAME
        ,ACTUALS.SOLD_TO_PARTY
        ,SOLD_TO.SOLD_TO_SEARCH2_NAME
        ,PRODUCT_TYPE_NAME
    ,CASE
        WHEN ACTUALS.SALES_CATEGORY_ORACLE = 'PDSRV' THEN 'Recognized as Paid Service'
        WHEN ACTUALS.SALES_CATEGORY_ORACLE NOT IN ('PDSRV', 'CONTRA', 'SMSRV', 'TSCREM', 'TSCSTD') THEN 'Recognized as Non-Service Product Type'
    ELSE 'OK'
    END AS EXCEPTION_COMMENT
        ,ACTUALS.WBS_ELEMENT
        ,ACTUALS.REPORT_PERIOD || '.'|| ACTUALS.CONTRACT_NUMBER || '.' ||ACTUALS.WBS_ELEMENT AS MONTH_CONTRACT_WBS_ID
    FROM ACTUALS
    LEFT OUTER JOIN CONTRACT
    ON ACTUALS.CONTRACT_NUMBER = CONTRACT.CONTRACT_NUMBER
    LEFT OUTER JOIN OFFICE
    ON ACTUALS.END_USER = OFFICE.B_CODE
    LEFT OUTER JOIN SALES_CATEGORY
    ON ACTUALS.SALES_CATEGORY = SALES_CATEGORY.SAP_SALES_CATEGORY
    LEFT OUTER JOIN ENDUSER
    ON ACTUALS.END_USER= ENDUSER.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN SOLD_TO
    ON ACTUALS.END_USER= SOLD_TO.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN SEGMENT
    ON ACTUALS.SEGMENT_CODE = SEGMENT.SEGMENT_SAP_CODE)

,transform_data as (
    select 
        REPORT_PERIOD 
        ,CUSTOMER_GROUP 
        ,CUSTOMER 
        ,LEGACY_OFFICE 
        ,BU 
        ,SALES_CATEGORY_ORACLE 
        ,CONTRACT_NUMBER 
        ,REVENUE 
        ,CONTRACT_TITLE 
        ,CONTRACT_TYPE 
        ,CONTRACT_SCOPE_BY_PRODUCT 
        ,CONTRACT_END_DATE 
        ,BAAN_CONTRACT_NUMBER 
        ,SALES_DOCUMENT 
        ,SALES_DOCUMENT_TYPE 
        ,SALES_CATEGORY_NAME 
        ,SALES_CATEGORY 
        ,SEGMENT 
        ,SEGMENT_CODE 
        ,LEGACY_SEGMENT_CODE 
        ,LEGACY_OFFICE_CODE 
        ,END_USER 
        ,END_USER_SEARCH2_NAME 
        ,SOLD_TO_PARTY 
        ,SOLD_TO_SEARCH2_NAME 
        ,PRODUCT_TYPE_NAME 
        ,EXCEPTION_COMMENT 
        ,WBS_ELEMENT 
        ,MONTH_CONTRACT_WBS_ID 
        ,'{{ invocation_id }}' AS AUDIT_LOG_ID
        ,SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    from source        
)
  
,TYPE_DATA AS (
    SELECT
        CAST(REPORT_PERIOD as VARCHAR(16777216)) AS REPORT_PERIOD
        ,CAST(CUSTOMER_GROUP as VARCHAR(16777216)) AS CUSTOMER_GROUP
        ,CAST(CUSTOMER as VARCHAR(16777216)) AS CUSTOMER
        ,CAST(LEGACY_OFFICE as VARCHAR(16777216)) AS LEGACY_OFFICE
        ,CAST(BU as VARCHAR(16777216)) AS BU
        ,CAST(SALES_CATEGORY_ORACLE as VARCHAR(16777216)) AS SALES_CATEGORY_ORACLE
        ,CAST(CONTRACT_NUMBER as VARCHAR(16777216)) AS CONTRACT_NUMBER
        ,CAST(REVENUE as VARCHAR(16777216)) AS REVENUE
        ,CAST(CONTRACT_TITLE as VARCHAR(16777216)) AS CONTRACT_TITLE
        ,CAST(CONTRACT_TYPE as VARCHAR(16777216)) AS CONTRACT_TYPE
        ,CAST(CONTRACT_SCOPE_BY_PRODUCT as VARCHAR(16777216)) AS CONTRACT_SCOPE_BY_PRODUCT
        ,CAST(CONTRACT_END_DATE as DATE) AS CONTRACT_END_DATE
        ,CAST(BAAN_CONTRACT_NUMBER as VARCHAR(16777216)) AS BAAN_CONTRACT_NUMBER
        ,CAST(SALES_DOCUMENT as VARCHAR(16777216)) AS SALES_DOCUMENT
        ,CAST(SALES_DOCUMENT_TYPE as VARCHAR(16777216)) AS SALES_DOCUMENT_TYPE
        ,CAST(SALES_CATEGORY_NAME as VARCHAR(16777216)) AS SALES_CATEGORY_NAME
        ,CAST(SALES_CATEGORY as VARCHAR(16777216)) AS SALES_CATEGORY
        ,CAST(SEGMENT as VARCHAR(16777216)) AS SEGMENT
        ,CAST(SEGMENT_CODE as VARCHAR(16777216)) AS SEGMENT_CODE
        ,CAST(LEGACY_SEGMENT_CODE as VARCHAR(16777216)) AS LEGACY_SEGMENT_CODE
        ,CAST(LEGACY_OFFICE_CODE as VARCHAR(16777216)) AS LEGACY_OFFICE_CODE
        ,CAST(END_USER as VARCHAR(16777216)) AS END_USER
        ,CAST(END_USER_SEARCH2_NAME as VARCHAR(16777216)) AS END_USER_SEARCH2_NAME
        ,CAST(SOLD_TO_PARTY as VARCHAR(16777216)) AS SOLD_TO_PARTY
        ,CAST(SOLD_TO_SEARCH2_NAME as VARCHAR(16777216)) AS SOLD_TO_SEARCH2_NAME
        ,CAST(PRODUCT_TYPE_NAME as VARCHAR(16777216)) AS PRODUCT_TYPE_NAME
        ,CAST(EXCEPTION_COMMENT as VARCHAR(16777216)) AS EXCEPTION_COMMENT
        ,CAST(WBS_ELEMENT as VARCHAR(16777216)) AS WBS_ELEMENT
        ,CAST(MONTH_CONTRACT_WBS_ID as VARCHAR(16777216)) AS MONTH_CONTRACT_WBS_ID
        ,cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID
        ,cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    FROM transform_data)
SELECT * FROM TYPE_DATA
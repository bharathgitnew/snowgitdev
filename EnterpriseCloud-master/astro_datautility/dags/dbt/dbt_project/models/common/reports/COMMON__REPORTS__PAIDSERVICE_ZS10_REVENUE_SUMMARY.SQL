WITH ACTUALS AS (
    SELECT
        CALENDAR_YEAR_MONTH AS REPORT_PERIOD
        ,END_USER
        ,END_USER_NAME AS CUSTOMER
    ,CASE
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME = 'TEXAS INSTRUMENTS INC.' THEN 'TI'
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME LIKE '%NXP%' THEN 'Regional'
        ELSE END_USER_GROUP
    END AS CUSTOMER_GROUP
        ,SALES_DOCUMENT_TYPE
        ,SALES_DOCUMENT
        ,SALES_CATEGORY
        ,SALES_CATEGORY_NAME
        ,SOLD_TO_PARTY_NAME
        ,SALES_CATEGORY_ORACLE
        ,SEGMENT_CODE
        ,SEGMENT
        ,SOLD_TO_PARTY
        ,WBS_ELEMENT
        ,(SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) * -1)  AS REVENUE
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE') }}
    WHERE 1=1
      AND CALENDAR_YEAR_MONTH >= '2023-05'
      AND LEFT(ACCOUNT_NUMBER,1) IN ('4')
      AND COMPANY_CODE = '3200'
      AND (SALES_DOCUMENT_TYPE = 'ZS10' OR SALES_DOCUMENT_TYPE  IS NULL)
      AND SALES_CATEGORY_ORACLE = 'PDSRV'

    GROUP BY 
        CALENDAR_YEAR_MONTH
        ,END_USER
        ,END_USER_NAME
    ,CASE
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME = 'TEXAS INSTRUMENTS INC.' THEN 'TI'
        WHEN END_USER_GROUP = 'NXP/TI' AND END_USER_NAME LIKE '%NXP%' THEN 'Regional'
        ELSE END_USER_GROUP
    END
        ,SALES_DOCUMENT_TYPE
        ,SALES_DOCUMENT
        ,SALES_CATEGORY
        ,SALES_CATEGORY_NAME
        ,SOLD_TO_PARTY_NAME
        ,SALES_CATEGORY_ORACLE
        ,SEGMENT_CODE
        ,SEGMENT
        ,SOLD_TO_PARTY
        ,WBS_ELEMENT
    HAVING SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) <> 0)

,ZS10 AS (
    SELECT DISTINCT
        VBAK_SALES_DOCUMENT
        ,SERVICE_CRM_WO_NO AS CRM_WO_NO
        ,VBAK_SALES_DOCUMENT_TYPE
    ,CASE
        WHEN LEN(QUOTE_NO)> 1 THEN QUOTE_NO
    ELSE NULL
    END AS QUOTE
    ,CASE
        WHEN LEN(CUSTOMER_REQUEST_NO)>1 THEN CUSTOMER_REQUEST_NO
    ELSE NULL
    END AS BAAN_SO
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
    WHERE 1=1
      AND VBAK_SALES_DOCUMENT_TYPE = 'ZS10')

,SN AS (
    SELECT
        VBAK_SALES_DOCUMENT
        ,LISTAGG(DISTINCT TOOL_SERIAL_NO, ', ')AS MACHINE_SN
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
    WHERE 1=1
      AND TOOL_SERIAL_NO IS NOT NULL
      AND LEN(TOOL_SERIAL_NO)>1
      AND VBAK_SALES_DOCUMENT_TYPE = 'ZS10'
    GROUP BY VBAK_SALES_DOCUMENT)

,OFFICE AS (
    SELECT
        B_CODE
        ,LEGACY_OFFICE
        ,LEGACY_OFFICE_CODE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
    )

,CRM_WO AS (
    SELECT
        LPAD(MSDYN_NAME,8,'0') AS WO
        ,WO_WOTITLE AS WO_TITLE
        ,WO_TEMP_MSNAME AS WO_MACHINESN
        ,TEL_WO_PRIMARY_SONAME AS WO_RELATED_SO
        ,WO_TEMP_PRODUCTLINE_TEXT AS WO_PRODUCT_LINE
        ,MSDYN_SUBSTATUSNAME AS WO_SUBSTATUS
        ,TEL_WO_SERVICEORDERNO_3200 AS SAP_SERVICE_ORDER
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
    WHERE 1=1
      AND WO_REGIONNAME = 'US')

,BAANSO AS (
    SELECT DISTINCT
        SERVICE_ORDER_NO
        ,DESCRIPTION
    FROM {{ ref('COMMON__DE_TEL_REPORTING__BAANV_TEA_SERVICE_ORDERS') }}
    WHERE LEFT(SERVICE_ORDER_NO,3)= 'PDS'
      AND ACTIVITY_LINE = '10')

,SALES_CATEGORY AS (
    SELECT 
        SAP_SALES_CATEGORY
        ,SAP_SALES_CATEGORY_NAME AS SALES_CATEGORY_NAME
        ,BAAN_PRODUCT_TYPE
    FROM {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }}
    WHERE SAP_SALES_CATEGORY <> 'LG')

,QUOTE AS (
    SELECT DISTINCT
        QUOTENUMBER
        ,LEFT(WORKDESCRIPTION,50) AS WORKDESCRIPTION
    FROM {{ ref('ODS__SHAREPOINT__PAIDSERVICEQUOTE') }}
    )

,ENDUSER AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
    ,CASE
        WHEN LEN(SEARCH_TERM_2_FOR_BUSINESS_PARTNER) < 1 THEN NULL
    ELSE SEARCH_TERM_2_FOR_BUSINESS_PARTNER
    END AS END_USER_SEARCH2_NAME
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B')

,SOLD_TO AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
    ,CASE
        WHEN LEN(SEARCH_TERM_2_FOR_BUSINESS_PARTNER) < 1 THEN NULL
    ELSE SEARCH_TERM_2_FOR_BUSINESS_PARTNER
    END AS SOLD_TO_SEARCH2_NAME
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B')

,SEGMENT AS (
    SELECT DISTINCT
        SAP_CODE AS SEGMENT_SAP_CODE
    ,CASE
        WHEN SAP_CODE = '29' THEN '5900'
    ELSE BAAN_CODE 
    END AS LEGACY_SEGMENT_CODE
    FROM {{ ref('COMMON__SAPH__SAP_SEGMENT') }}
    )

,SOURCE AS (
    SELECT 
        ACTUALS.REPORT_PERIOD
        ,ACTUALS.CUSTOMER_GROUP
        ,ACTUALS.CUSTOMER
        ,OFFICE.LEGACY_OFFICE
    ,CASE
        WHEN ACTUALS.SEGMENT LIKE 'FS-%' THEN REPLACE(ACTUALS.SEGMENT, 'FS-','')
    ELSE ACTUALS.SEGMENT
    END AS BU
        ,ACTUALS.SALES_DOCUMENT
        ,ACTUALS.REVENUE
    ,CASE
        WHEN LEFT(ZS10.CRM_WO_NO,1) <> 'X' THEN ZS10.CRM_WO_NO
        WHEN LEFT(ZS10.CRM_WO_NO,1) = 'X' AND ZS10.BAAN_SO IS NOT NULL THEN ZS10.BAAN_SO
        WHEN LEFT(ZS10.CRM_WO_NO,1) = 'X' AND ZS10.QUOTE IS NOT NULL THEN ZS10.QUOTE
    ELSE '*No Order'
    END AS RELATED_ORDER_NUMBER
    ,CASE
        WHEN LEFT(ZS10.CRM_WO_NO,1) <> 'X'THEN CRM_WO.WO_TITLE
        WHEN BAANSO.DESCRIPTION IS NOT NULL THEN BAANSO.DESCRIPTION
        WHEN ACTUALS.SOLD_TO_PARTY_NAME = 'TOKYO ELECTRON EUROPE LTD.' AND (LEN(ZS10.CRM_WO_NO) < 1 OR LEFT(ZS10.CRM_WO_NO,1) = 'X') THEN 'TEE WORK'
        WHEN QUOTE.WORKDESCRIPTION IS NOT NULL THEN QUOTE.WORKDESCRIPTION
    END AS LABOR_DESCRIPTION
        ,ZS10.CRM_WO_NO
        ,ZS10.QUOTE
        ,ZS10.BAAN_SO
        ,SN.MACHINE_SN
        ,CRM_WO.SAP_SERVICE_ORDER
        ,ACTUALS.SALES_DOCUMENT_TYPE
        ,ACTUALS.SALES_CATEGORY_NAME
        ,ACTUALS.SALES_CATEGORY
        ,ACTUALS.SALES_CATEGORY_ORACLE
        ,ACTUALS.SEGMENT
        ,ACTUALS.SEGMENT_CODE
        ,SEGMENT.LEGACY_SEGMENT_CODE
        ,OFFICE.LEGACY_OFFICE_CODE
        ,ACTUALS.END_USER
        ,ENDUSER.END_USER_SEARCH2_NAME
        ,ACTUALS.SOLD_TO_PARTY
        ,SOLD_TO.SOLD_TO_SEARCH2_NAME
        ,ACTUALS.WBS_ELEMENT
        ,(REPLACE(ACTUALS.REPORT_PERIOD,'-','')||'.'||ACTUALS.SALES_DOCUMENT) AS MONTH_SO_ID
    FROM ACTUALS
    LEFT OUTER JOIN ZS10
    ON ACTUALS.SALES_DOCUMENT = ZS10.VBAK_SALES_DOCUMENT
    LEFT OUTER JOIN SN
    ON ACTUALS.SALES_DOCUMENT = SN.VBAK_SALES_DOCUMENT
    LEFT OUTER JOIN OFFICE
    ON ACTUALS.END_USER = OFFICE.B_CODE
    LEFT OUTER JOIN CRM_WO
    ON ZS10.CRM_WO_NO = CRM_WO.WO
    LEFT OUTER JOIN SALES_CATEGORY
    ON ACTUALS.SALES_CATEGORY = SALES_CATEGORY.SAP_SALES_CATEGORY
    LEFT OUTER JOIN BAANSO
    ON ZS10.BAAN_SO = BAANSO.SERVICE_ORDER_NO
    LEFT OUTER JOIN QUOTE
    ON ZS10.QUOTE = QUOTE.QUOTENUMBER
    LEFT OUTER JOIN ENDUSER
    ON ACTUALS.END_USER= ENDUSER.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN SOLD_TO
    ON ACTUALS.END_USER= SOLD_TO.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN SEGMENT
    ON ACTUALS.SEGMENT_CODE = SEGMENT.SEGMENT_SAP_CODE)

,transform_data as (
    select 
        REPORT_PERIOD 
        ,CUSTOMER_GROUP 
        ,CUSTOMER 
        ,LEGACY_OFFICE 
        ,BU 
        ,SALES_DOCUMENT 
        ,REVENUE 
        ,RELATED_ORDER_NUMBER 
        ,LABOR_DESCRIPTION 
        ,CRM_WO_NO 
        ,QUOTE 
        ,BAAN_SO 
        ,MACHINE_SN 
        ,SAP_SERVICE_ORDER 
        ,SALES_DOCUMENT_TYPE 
        ,SALES_CATEGORY_NAME 
        ,SALES_CATEGORY 
        ,SALES_CATEGORY_ORACLE 
        ,SEGMENT 
        ,SEGMENT_CODE 
        ,LEGACY_SEGMENT_CODE 
        ,LEGACY_OFFICE_CODE 
        ,END_USER 
        ,END_USER_SEARCH2_NAME 
        ,SOLD_TO_PARTY 
        ,SOLD_TO_SEARCH2_NAME 
        ,WBS_ELEMENT 
        ,MONTH_SO_ID 
        ,'{{ invocation_id }}' AS AUDIT_LOG_ID
        ,SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    from source        
)

,TYPE_DATA AS (
    SELECT
        CAST(REPORT_PERIOD as VARCHAR(16777216)) AS REPORT_PERIOD
        ,CAST(CUSTOMER_GROUP as VARCHAR(16777216)) AS CUSTOMER_GROUP
        ,CAST(CUSTOMER as VARCHAR(16777216)) AS CUSTOMER
        ,CAST(LEGACY_OFFICE as VARCHAR(16777216)) AS LEGACY_OFFICE
        ,CAST(BU as VARCHAR(16777216)) AS BU
        ,CAST(SALES_DOCUMENT as VARCHAR(16777216)) AS SALES_DOCUMENT
        ,CAST(REVENUE as NUMBER(38,2)) AS REVENUE
        ,CAST(RELATED_ORDER_NUMBER as VARCHAR(16777216)) AS RELATED_ORDER_NUMBER
        ,CAST(LABOR_DESCRIPTION as VARCHAR(16777216)) AS LABOR_DESCRIPTION
        ,CAST(CRM_WO_NO as VARCHAR(16777216)) AS CRM_WO_NO
        ,CAST(QUOTE as VARCHAR(16777216)) AS QUOTE
        ,CAST(BAAN_SO as VARCHAR(16777216)) AS BAAN_SO
        ,CAST(MACHINE_SN as VARCHAR(16777216)) AS MACHINE_SN
        ,CAST(SAP_SERVICE_ORDER as VARCHAR(16777216)) AS SAP_SERVICE_ORDER
        ,CAST(SALES_DOCUMENT_TYPE as VARCHAR(16777216)) AS SALES_DOCUMENT_TYPE
        ,CAST(SALES_CATEGORY_NAME as VARCHAR(16777216)) AS SALES_CATEGORY_NAME
        ,CAST(SALES_CATEGORY as VARCHAR(16777216)) AS SALES_CATEGORY
        ,CAST(SALES_CATEGORY_ORACLE as VARCHAR(16777216)) AS SALES_CATEGORY_ORACLE
        ,CAST(SEGMENT as VARCHAR(16777216)) AS SEGMENT
        ,CAST(SEGMENT_CODE as VARCHAR(16777216)) AS SEGMENT_CODE 
        ,CAST(LEGACY_SEGMENT_CODE as VARCHAR(16777216)) AS LEGACY_SEGMENT_CODE
        ,CAST(LEGACY_OFFICE_CODE as VARCHAR(16777216)) AS LEGACY_OFFICE_CODE
        ,CAST(END_USER as VARCHAR(16777216)) AS END_USER
        ,CAST(END_USER_SEARCH2_NAME as VARCHAR(16777216)) AS END_USER_SEARCH2_NAME
        ,CAST(SOLD_TO_PARTY as VARCHAR(16777216)) AS SOLD_TO_PARTY
        ,CAST(SOLD_TO_SEARCH2_NAME as VARCHAR(16777216)) AS SOLD_TO_SEARCH2_NAME
        ,CAST(WBS_ELEMENT as VARCHAR(16777216)) AS WBS_ELEMENT
        ,CAST(MONTH_SO_ID as VARCHAR(16777216)) AS MONTH_SO_ID
        ,cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID
        ,cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
FROM transform_data)
SELECT * FROM TYPE_DATA
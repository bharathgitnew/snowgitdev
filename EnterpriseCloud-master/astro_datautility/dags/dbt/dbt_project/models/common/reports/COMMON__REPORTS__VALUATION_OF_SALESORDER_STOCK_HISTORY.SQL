WITH EBEWH_CTE AS (
    SELECT 
        EBEWH.*,
        VBAK.KUNNR ,
        MARA.MAKTX 
    from
        {{ ref('ODS__SAPAPI__ZCDV_T_CMTU246_EBEWH') }}  EBEWH  
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }}  VBAK ON EBEWH.VBELN = VBAK.VBELN
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA ON EBEWH.MATNR = MARA.MATNR
),
FINAL_CTE AS (
    SELECT 
        EBEWH_CTE.*,
        KNA1.NAME1 
        FROM EBEWH_CTE 
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} KNA1 ON KNA1.KUNNR = EBEWH_CTE.KUNNR
),
SOURCE_DATA AS (
SELECT 
    FINAL.MATNR AS MATERIAL_NUMBER,
    FINAL.MAKTX AS MATERIAL_DESCRIPTION,
    FINAL.BWKEY AS VALUATION_AREA,
    FINAL.BWTAR AS VALUATION_TYPE,
    FINAL.SOBKZ AS SPECIAL_STOCK,
    FINAL.VBELN AS SALES_DOCUMENT,
    FINAL.POSNR AS ITEM_NUMBER_OF_THE_SD_DOCUMENT,
    FINAL.LFGJA AS YEAR_CURRENT_PERIOD,
    FINAL.LFMON AS CURRENT_PERIOD,
    FINAL.LBKUM AS TOTAL_STOCK,
    FINAL.SALK3 AS TOTAL_VALUE,
    FINAL.VPRSV AS PRICE_CONTROL,
    FINAL.VERPR AS MOVING_PRICE,
    FINAL.STPRS AS STANDARD_PRICE,
    FINAL.PEINH AS PRICE_UNIT,
    FINAL.BKLAS AS VALUATION_CLASS,
    FINAL.SALKV AS VALUE_BASED_ON_MOVING_AVERAGE_PRICE,
    FINAL.VKSAL AS VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE,
    FINAL.KUNNR AS SOLD_TO_PARTY,
    FINAL.NAME1 AS SOLD_TO_PARTY_NAME
FROM FINAL_CTE AS FINAL
),
TRANSFORM_DATA AS (
    SELECT 
    MATERIAL_NUMBER,
    VALUATION_AREA,
    VALUATION_TYPE,
    SPECIAL_STOCK,
    SALES_DOCUMENT,
    ITEM_NUMBER_OF_THE_SD_DOCUMENT,
    YEAR_CURRENT_PERIOD,
    CURRENT_PERIOD,
    TOTAL_STOCK,
    TOTAL_VALUE,
    PRICE_CONTROL,
    MOVING_PRICE,
    STANDARD_PRICE,
    PRICE_UNIT,
    VALUATION_CLASS,
    VALUE_BASED_ON_MOVING_AVERAGE_PRICE,
    VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE,
    SOLD_TO_PARTY,
    MATERIAL_DESCRIPTION,
    SOLD_TO_PARTY_NAME,
    '{{ invocation_id }}' AS AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH 
from SOURCE_DATA
),
TYPE_DATA AS (
    SELECT 
       CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(VALUATION_AREA AS VARCHAR(16777216)) AS VALUATION_AREA,
        CAST(VALUATION_TYPE AS VARCHAR(16777216)) AS VALUATION_TYPE,
        CAST(SPECIAL_STOCK AS VARCHAR(16777216)) AS SPECIAL_STOCK,
        CAST(SALES_DOCUMENT AS VARCHAR(16777216)) AS SALES_DOCUMENT,
        CAST(ITEM_NUMBER_OF_THE_SD_DOCUMENT AS VARCHAR(16777216)) AS ITEM_NUMBER_OF_THE_SD_DOCUMENT,
        CAST(YEAR_CURRENT_PERIOD AS VARCHAR(16777216)) AS YEAR_CURRENT_PERIOD,
        CAST(CURRENT_PERIOD AS VARCHAR(16777216)) AS CURRENT_PERIOD,
        CAST(TOTAL_STOCK AS NUMBER(38,2)) AS TOTAL_STOCK,
        CAST(TOTAL_VALUE AS NUMBER(38,2)) AS TOTAL_VALUE,
        CAST(PRICE_CONTROL AS VARCHAR(16777216)) AS PRICE_CONTROL,
        CAST(MOVING_PRICE AS NUMBER(38,2)) AS MOVING_PRICE,
        CAST(STANDARD_PRICE AS NUMBER(38,2)) AS STANDARD_PRICE,
        CAST(PRICE_UNIT AS NUMBER(38,2)) AS PRICE_UNIT,
        CAST(VALUATION_CLASS AS VARCHAR(16777216)) AS VALUATION_CLASS,
        CAST(VALUE_BASED_ON_MOVING_AVERAGE_PRICE AS NUMBER(38,2)) AS VALUE_BASED_ON_MOVING_AVERAGE_PRICE,
        CAST(VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE AS NUMBER(38,2)) AS VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE,
        CAST(SOLD_TO_PARTY AS VARCHAR(16777216)) AS SOLD_TO_PARTY,
        CAST(SOLD_TO_PARTY_NAME AS VARCHAR(16777216)) AS SOLD_TO_PARTY_NAME, 
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
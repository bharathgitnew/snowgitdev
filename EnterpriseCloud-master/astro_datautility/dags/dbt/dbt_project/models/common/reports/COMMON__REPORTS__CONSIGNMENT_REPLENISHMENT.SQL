with REORDER_POINT_MRP as
(
SELECT MARA_MATERIAL_NUMBER as MATERIAL_NUMBER,MATERIAL_DESCRIPTION,
       RIGHT(MDMA_MRP_AREA,4) as STORAGE_LOCATION,
       MDMA_REORDER_POINT as REORDER_POINT
FROM {{ ref('COMMON__SAPH__MATERIAL_MRP_AREA_MASTER') }} 
WHERE MDMA_MRP_AREA IN ('3200-F120','3200-F220','3200-F320','3200-H220')
AND MARA_MATERIAL_NUMBER IS NOT NULL 
),

SUM_STOCK as ( 
SELECT 
    MATERIAL_NUMBER,
    MATERIAL_NUMBER_DESCRIPTION,
    case when  STORAGE_LOCATION = 'F120' or SPEC_STOCK_PARTNER= 'DD3435602' then 'F120'
    when  STORAGE_LOCATION = 'F220' or SPEC_STOCK_PARTNER= 'DB3435604' then 'F220'
    when  STORAGE_LOCATION = 'F320' or SPEC_STOCK_PARTNER= 'D00000377' then 'F320'
    when  STORAGE_LOCATION = 'H220' or SPEC_STOCK_PARTNER= 'D00000141' then 'H220'
    end as F_STORAGE_LOCATION,
    case when  STORAGE_LOCATION = 'F120' or SPEC_STOCK_PARTNER= 'DD3435602' then 'DD3435602'
    when  STORAGE_LOCATION = 'F220' or SPEC_STOCK_PARTNER= 'DB3435604' then 'DB3435604'
    when  STORAGE_LOCATION = 'F320' or SPEC_STOCK_PARTNER= 'D00000377' then 'D00000377'
    when  STORAGE_LOCATION = 'H220' or SPEC_STOCK_PARTNER= 'D00000141' then 'D00000141'
    end as F_SPEC_STOCK_PARTNER,
    -- Special Stock Partner On Hand
    case when SPEC_STOCK_PARTNER <> '' then sum(CUSTOMER_CONSIGNMENT_QTY) else 0  end as SUM_SSPOH,
    -- Special Stock Partner On Order
    case when SPEC_STOCK_PARTNER <> '' then sum(ON_ORDER_STOCK) else 0 end as SUM_SSPOO,
    --Special Stock Partner Allocated
    case when SPEC_STOCK_PARTNER <> '' then sum(ALLOCATED_STOCK) else 0 end as SUM_SSPA,
    --Consignment SLOC Allocated
    case when STORAGE_LOCATION <> '' then sum(ALLOCATED_STOCK) else 0 end as SUM_CSA,
    --Consignment SLOC On Order
    case when STORAGE_LOCATION <> '' then sum(ON_ORDER_STOCK) else 0 end as SUM_CSOO,
    -- Consignment SLOC On Hand
    case when STORAGE_LOCATION <> '' then sum(STOCK_TOTAL) else 0 end as SUM_CSOH 
FROM {{ ref('COMMON__REPORTS__PART_STOCK_OVERVIEW_REPORT')}}
WHERE STORAGE_LOCATION IN ('F120','F220','F320','H220') 
      OR SPEC_STOCK_PARTNER IN ('DD3435602','DB3435604','D00000377','D00000141')
GROUP BY MATERIAL_NUMBER,MATERIAL_NUMBER_DESCRIPTION,SPEC_STOCK_PARTNER,STORAGE_LOCATION
),
STOCK_SUMMARY as 
( 
SELECT 
    MATERIAL_NUMBER,
    F_STORAGE_LOCATION as STORAGE_LOCATION,
    sum(SUM_SSPOH) as SSPOH,
    sum(SUM_SSPOO) as SSPOO,
    sum(SUM_SSPA) as SSPA,
    sum(SUM_CSA) as CSA,
    sum(SUM_CSOO) as CSOO,
    sum(SUM_CSOH) as CSOH,
    -- Consignment effective on hand
    (CSOH + CSOO + SSPOH +SSPOO - CSA - SSPA) as COH
FROM SUM_STOCK 
GROUP BY MATERIAL_NUMBER, F_STORAGE_LOCATION
),
 
SOURCE_DATA as (
SELECT 
    MATERIAL.STORAGE_LOCATION,
    MATERIAL.MATERIAL_NUMBER,
    MATERIAL.MATERIAL_DESCRIPTION,
    MATERIAL.REORDER_POINT AS SLOC_SAFETY_STOCK,
    ZEROIFNULL(COH) AS CONSIGNMENT_EFFECTIVE_ON_HAND,
    SLOC_SAFETY_STOCK-CONSIGNMENT_EFFECTIVE_ON_HAND AS REPLENISHMENT_QTY
FROM REORDER_POINT_MRP as MATERIAL
LEFT JOIN STOCK_SUMMARY as STOCK_SUMMARY
ON STOCK_SUMMARY.MATERIAL_NUMBER = MATERIAL.MATERIAL_NUMBER
AND STOCK_SUMMARY.STORAGE_LOCATION = MATERIAL.STORAGE_LOCATION
where  REPLENISHMENT_QTY > 0
),

TRANSFORM_DATA AS (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    STORAGE_LOCATION,
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    REPLENISHMENT_QTY,
    CONSIGNMENT_EFFECTIVE_ON_HAND,
    SLOC_SAFETY_STOCK
FROM SOURCE_DATA
),

TYPE_DATA AS (
SELECT
    _AUDIT_LOG_ID,
    _ROW_HASH,
    STORAGE_LOCATION,
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    REPLENISHMENT_QTY,
    CONSIGNMENT_EFFECTIVE_ON_HAND,
    SLOC_SAFETY_STOCK
FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
            materialized='incremental',
            incremental_strategy='insert_overwrite',
            alias='PURCHASE_ORDER_LINE_REPORT',
            transient=false    
) }}


WITH 
SOURCE_DATA AS (
    SELECT 
        PO_HDR, 
        PO_LINE,
        PO_LINE_ID,
        PO_DATE,
        NET_ORDER_VALUE,
        NET_PRICE,
        GROSS_ORDER_VALUE,
        MATERIAL_ID,
        PRODUCT_LINE,
        MARA.MAKTX AS MATERIAL_DESC,
        MATERIAL_GROUP,
        VENDOR_ACCOUNT_NUMBER,
        LFA1.NAME1 AS VENDOR_NAME,
        SLOC,
        PO_DOC_TYPE,
        PO_DOC_CATEGORY,
        PO_STATUS,
        RFQ_STATUS,
        CREATOR,
        COMPANY_CODE,
        PURCHASING_ORG,
        PURCHASING_GROUP,
        PO_QTY,
        TGT_QTY,
        DELETION_INDICATOR,
        PLANT,
        CURRENCY_KEY
    FROM {{ ref('COMMON__SAPH__PURCHASE_ORDER_LINE') }} AS POL
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA ON (MARA.MATNR = POL.MATERIAL_ID)
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU061_LFA1') }} AS LFA1 ON (LFA1.LIFNR = POL.VENDOR_ACCOUNT_NUMBER)
),
TRANSFORM_DATA AS (
    SELECT
        PO_HDR, 
        PO_LINE,
        PO_LINE_ID,
        PO_DATE,
        NET_ORDER_VALUE,
        NET_PRICE,
        GROSS_ORDER_VALUE,
        MATERIAL_ID,
        PRODUCT_LINE,
        MATERIAL_DESC,
        MATERIAL_GROUP,
        VENDOR_ACCOUNT_NUMBER,
        VENDOR_NAME,
        SLOC,
        PO_DOC_TYPE,
        PO_DOC_CATEGORY,
        PO_STATUS,
        RFQ_STATUS,
        CREATOR,
        COMPANY_CODE,
        PURCHASING_ORG,
        PURCHASING_GROUP,
        PO_QTY,
        TGT_QTY,
        DELETION_INDICATOR,
        PLANT,
        CURRENCY_KEY,
        '{{ invocation_id }}' as AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        CAST(PO_HDR AS VARCHAR(16777216)) AS PO_HDR,
        CAST(PO_LINE AS VARCHAR(16777216)) AS PO_LINE,
        CAST(PO_LINE_ID AS VARCHAR(16777216)) AS PO_LINE_ID,
        CAST(PO_DATE AS DATE) AS PO_DATE,
        CAST(NET_ORDER_VALUE AS FLOAT) AS NET_ORDER_VALUE,
        CAST(NET_PRICE AS FLOAT) AS NET_PRICE,
        CAST(GROSS_ORDER_VALUE AS FLOAT) AS GROSS_ORDER_VALUE,
        CAST(MATERIAL_ID AS VARCHAR(16777216)) AS MATERIAL_ID,
        CAST(MATERIAL_DESC AS VARCHAR(16777216)) AS MATERIAL_DESC,
        CAST(PRODUCT_LINE AS VARCHAR(16777216)) AS PRODUCT_LINE,
        CAST(MATERIAL_GROUP AS VARCHAR(16777216)) AS MATERIAL_GROUP,
        CAST(VENDOR_ACCOUNT_NUMBER AS VARCHAR(16777216)) AS VENDOR_ACCOUNT_NUMBER,
        CAST(VENDOR_NAME AS VARCHAR(16777216)) AS VENDOR_NAME,
        CAST(SLOC AS VARCHAR(16777216)) AS SLOC,
        CAST(PO_DOC_TYPE AS VARCHAR(16777216)) AS PO_DOC_TYPE,
        CAST(PO_DOC_CATEGORY AS VARCHAR(16777216)) AS PO_DOC_CATEGORY,
        CAST(PO_STATUS AS VARCHAR(16777216)) AS PO_STATUS,
        CAST(RFQ_STATUS AS VARCHAR(16777216)) AS RFQ_STATUS,
        CAST(CREATOR AS VARCHAR(16777216)) AS CREATOR,
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(PURCHASING_ORG AS VARCHAR(16777216)) AS PURCHASING_ORG,
        CAST(PURCHASING_GROUP AS VARCHAR(16777216)) AS PURCHASING_GROUP,
        CAST(PO_QTY AS VARCHAR(16777216)) AS PO_QTY,
        CAST(TGT_QTY AS VARCHAR(16777216)) AS TGT_QTY,
        CAST(DELETION_INDICATOR AS VARCHAR(16777216)) AS DELETION_INDICATOR,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(CURRENCY_KEY AS VARCHAR(16777216)) AS CURRENCY_KEY,
        CAST(AUDIT_LOG_ID AS VARCHAR(16777216)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
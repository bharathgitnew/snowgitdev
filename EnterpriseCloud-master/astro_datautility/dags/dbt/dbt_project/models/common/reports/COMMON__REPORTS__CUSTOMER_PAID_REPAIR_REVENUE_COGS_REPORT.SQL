WITH DETAILS AS (
    SELECT
        CALENDAR_YEAR_MONTH,
        END_USER_GROUP,
        END_USER_NAME,
        END_USER,
        BAAN_OFFICE,
        SEGMENT,
        SALES_DOCUMENT_TYPE_DESCRIPTION,
        SALES_DOCUMENT || '_' || SALES_DOCUMENT_ITEM AS SALES_DOCUMENT_LINE,
        SALES_CATEGORY,
        SALES_CATEGORY_NAME,
        PNL_CATEGORY,
        CASE
            WHEN PNL_CATEGORY = 'Revenue' THEN -1 * AMOUNT_IN_COMPANY_CODE_CURRENCY
            ELSE 0
        END AS REVENUE,
        CASE
            WHEN PNL_CATEGORY = 'COGS' THEN AMOUNT_IN_COMPANY_CODE_CURRENCY
            ELSE 0
        END AS COGS,
        ORDER_REASON,
        SALES_CATEGORY_ORACLE,
        PRODUCT_TYPE_NAME,
        SALES_DOCUMENT_TYPE,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        ACDOCA_MATERIAL_GROUP,
        ACDOCA_MATERIAL_GROUP_NAME,
        ACDOCA_MATERIAL_NUMBER,
        SOLD_TO_PARTY,
        SOLD_TO_PARTY_NAME,
        BAAN_OFFICE_CODE,
        BAAN_SEGMENT_CODE,
        SEGMENT_CODE,
        BILLING_DESCRIPTION,
        CUSTOMER_REFERENCE,
        WBS_CATEGORY,
        WBS_CATEGORY_NAME,
        WBS_ELEMENT,
        WBS_SHORT_DESCRIPTION,
        ACCOUNT_NAME,
        ACCOUNT_NUMBER
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE') }}
    WHERE CALENDAR_YEAR_MONTH >= '2023-05'
        AND COMPANY_CODE = '3200'
        AND SALES_CATEGORY = '70'
),
SOBL AS (
    SELECT
        DISTINCT VBAK_SALES_DOCUMENT,
        RMA_NUMBER
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
    WHERE LEN(RMA_NUMBER) > 1
),
LINE AS (
    SELECT
        DISTINCT VBAK_SALES_DOCUMENT || '_' || SALES_DOCUMENT_ITEM_POSNR AS SALES_ORDER_LINE,
        VBAP_MATERIAL_NUMBER AS MATERIAL_NUMBER,
        VBAP_MATERIAL_GROUP AS MATERIAL_GROUP,
        VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM AS SALES_ORDER_ITEM,
        VBAP_ORDER_ITEM_NAME AS ORDER_ITEM_NAME
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
),
RMAPART AS (
    SELECT
        DISTINCT BATCH AS RMA,
        MATERIAL,
        REPAIR_MATERIAL_TYPE,
        MATERIAL_DESCRIPTION,
        SO,
        SVO AS SERVICE_ORDER,
        RMA_SAPH.VENDOR AS RMA_VENDOR
    FROM {{ ref('COMMON__SAPH__RMA_SAPH') }}
    LEFT OUTER JOIN {{ ref('COMMON__REPORTS__MASTER_MATERIAL_REPORT') }} ON MATERIAL_NUMBER = REPAIR_MATERIAL_TYPE
    WHERE REPAIR_MATERIAL_TYPE IS NOT NULL
        AND LEN(BATCH) > 1 
    QUALIFY row_number() over (partition by SO order by BATCH desc) = 1
),
VENDOR AS (
    SELECT
        BUSINESS_PARTNER_NUMBER,
        CORPORATION,
        NAME_1_OF_ORGANIZATION AS VENDOR_NAME,
        COUNT(*) AS COUNT
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }} B
    WHERE LEFT(B.BUSINESS_PARTNER_NUMBER, 1) = 'B'
        AND LEN(CORPORATION) > 1
    GROUP BY
        BUSINESS_PARTNER_NUMBER,
        CORPORATION,
        NAME_1_OF_ORGANIZATION 
    QUALIFY row_number() over (partition by BUSINESS_PARTNER_NUMBER order by COUNT(*) desc) = 1
),
ORDERITEM AS (
    SELECT
        MVKE_MATERIAL_NUMBER,
        ORDER_ITEM_NAME
    FROM {{ ref('COMMON__SAPH__MATERIAL_SALES_ORG_MASTER') }}
    WHERE LEN(ORDER_ITEM_NAME) > 1 
    QUALIFY row_number() over (partition by MVKE_MATERIAL_NUMBER order by ORDER_ITEM_NAME desc) = 1
),
SOURCE AS (
    SELECT
        CALENDAR_YEAR_MONTH,
        END_USER_GROUP,
        END_USER_NAME,
        END_USER,
        BAAN_OFFICE,
        SEGMENT,
        SALES_CATEGORY_NAME,
        SALES_DOCUMENT_LINE,
        MATERIAL_NUMBER,
        MATERIAL_GROUP,
        RMA_NUMBER,
        MATERIAL,
        REPAIR_MATERIAL_TYPE,
        MATERIAL_DESCRIPTION,
        ORDERITEM.ORDER_ITEM_NAME,
        SUM(REVENUE) AS REVENUE,
        SUM(COGS) AS COGS,
        ORDER_REASON,
        SALES_CATEGORY,
        DETAILS.SALES_CATEGORY_ORACLE,
        PRODUCT_TYPE_NAME,
        DETAILS.SALES_DOCUMENT_TYPE,
        SALES_DOCUMENT_TYPE_DESCRIPTION,
        DETAILS.SALES_DOCUMENT,
        DETAILS.SALES_DOCUMENT_ITEM,
        SERVICE_ORDER,
        RMA_VENDOR,
        VENDOR_NAME AS RMA_VENDOR_NAME,
        SOLD_TO_PARTY,
        SOLD_TO_PARTY_NAME,
        BAAN_OFFICE_CODE,
        BAAN_SEGMENT_CODE,
        SEGMENT_CODE,
        WBS_CATEGORY,
        WBS_CATEGORY_NAME,
        WBS_ELEMENT
    FROM DETAILS
    LEFT OUTER JOIN SOBL ON DETAILS.SALES_DOCUMENT = SOBL.VBAK_SALES_DOCUMENT
    LEFT OUTER JOIN RMAPART ON SOBL.VBAK_SALES_DOCUMENT = RMAPART.SO
    LEFT OUTER JOIN LINE ON DETAILS.SALES_DOCUMENT_LINE = LINE.SALES_ORDER_LINE
    LEFT OUTER JOIN VENDOR ON RMAPART.RMA_VENDOR = VENDOR.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN ORDERITEM ON RMAPART.REPAIR_MATERIAL_TYPE = ORDERITEM.MVKE_MATERIAL_NUMBER
    GROUP BY ALL
),


WITH MACHINES AS (
    SELECT 
        CUSTOMER_GROUP,
        PARENT_CUSTOMER_NAME,
        CUSTOMER_NAME,
        LOCATION_NAME,
        LEGACY_BU,
        SERIAL_NUMBER,
        SWLH_MODEL,
        CUSTOMER_TOOL_ID,
        PROJECT_NUMBER,
        TEL_SALES_ORDER,
        MACHINE_HISTORY_REASON,
        LOAN_FLAG,
        START_UP_STATUS,
        WARRANTY_STATUS,
        TEL_SHIP_DATE,
        SCH_DOCK_DATE,
        ACT_DOCK_DATE,
        SCH_MOVE_IN,
        ACT_MOVE_IN,
        SCH_STARTUP_HOOKUP_START,
        ACT_STARTUP_HOOKUP_START,
        SCH_SL1,
        ACT_SL1,
        SCH_SL2,
        ACT_SL2,
        SCH_HW_STARTUP_START,
        ACT_HW_STARTUP_START,
        SCH_HW_STARTUP_END,
        ACT_HW_STARTUP_END,
        SCH_PROCESS_QUAL_START,
        ACT_PROCESS_QUAL_START,
        SCH_PROCESS_QUAL_END,
        ACT_PROCESS_QUAL_END,
        SCH_EQ_HANDOFF_TO_CUST,
        ACT_EQ_HANDOFF_TO_CUST,
        SCH_CST AS SCH_CTA,
        CTA_SIGNOFF_DATE,
        SCH_ACCEPTANCE,
        ACT_ACCEPTANCE,
        WARRANTY_MONTHS,
        SOLD_BASIS,
        CUSTOMER_PO_NO,
        WISDOM_MAC_ID,
        CUSTOMER_CODE_B,
        CUSTOMER_CODE_D,
        SUPPLIER_CODE,
        SAP_PRODUCT_CODE,
        MODEL_NAME,
        TEL_MODEL,
        INSTALL_BASE_STATUS,
        PROJECT_NUMBER || '-' || SERIAL_NUMBER AS PROJECT_SN,
        CASE
            WHEN SOLD_BASIS = 'SHIP' THEN 'NA - SHIP'
            WHEN SOLD_BASIS = 'CTA'
            AND CTA_SIGNOFF_DATE IS NULL THEN 'CTA Not Complete'
            WHEN SOLD_BASIS = 'CTA'
            AND CTA_SIGNOFF_DATE IS NOT NULL THEN 'CTA Complete'
            ELSE NULL
        END AS CTA_ACTION_FLAG,
        BU_GROUP AS BU,
        BU_GROUP_LEADER,
        FACTORY_SHIP_DATE,
        SCH_FOB_FCA,
        ACT_FOB_FCA,
        CITY,
        STATE_PROVINCE,
        POSTALCODE as POSTAL_CODE,
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE MAIN_TOOL_FLAG = 'Y'
        AND ACTIVE_FLAG = 'Active'
        AND INSTALL_BASE_STATUS NOT IN ('Software', 'Inactive Tool')
        AND WARRANTY_STATUS NOT IN ('Warranty Out', 'Under Warranty')
        AND (
            MACHINE_HISTORY_REASON IN ('New', 'TEL Group')
            OR (
                MACHINE_HISTORY_REASON = 'Rental'
                AND WARRANTY_STATUS <> 'Pre Warranty'
            )
        )
        AND ACT_ACCEPTANCE IS NULL
),

LEGACY_OFFICE AS (
    SELECT DISTINCT 
        B_CODE,
        LEGACY_OFFICE,
        LEGACY_OFFICE_CODE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
),

DELAY AS (
    SELECT MAC_ID,
        ITEM_NO,
        CASE
            WHEN DELAY_CD = '11' THEN 'Under Start-Up'
            WHEN DELAY_CD = '21' THEN 'Hardware problem'
            WHEN DELAY_CD = '22' THEN 'Software problem'
            WHEN DELAY_CD = '23' THEN 'Process problem'
            WHEN DELAY_CD = '24' THEN 'Network problem'
            WHEN DELAY_CD = '25' THEN 'Unstable system problem'
            WHEN DELAY_CD = '26' THEN 'Spec/RFQ has not been satisfied'
            WHEN DELAY_CD = '32' THEN 'Other sales issue'
            WHEN DELAY_CD = '33' THEN 'No probess spec. agreement'
            WHEN DELAY_CD = '41' THEN 'Holding Start-Up due to customer issue'
            WHEN DELAY_CD = '42' THEN 'Customer new request'
            WHEN DELAY_CD = '43' THEN 'Customer-requested remaining work'
            WHEN DELAY_CD = '44' THEN 'Monitoring/Evaluation of the system'
            WHEN DELAY_CD = '45' THEN 'Internal paperwork'
            WHEN DELAY_CD = '46' THEN 'Waiting for customer sign-off'
            WHEN DELAY_CD = '51' THEN 'Done'
            WHEN DELAY_CD = '61' THEN 'Other than the aboves'
            WHEN DELAY_CD = '62' THEN 'Pre-Start-Up Issue'
            WHEN DELAY_CD = '320' THEN 'No Category'
            ELSE NULL
        END AS DELAY_CATEGORY,
        NOTE AS DELAY_REASON,
        _FILEDATE,
        ROW_NUMBER() OVER (PARTITION BY (MAC_ID || '.' || ITEM_NO) ORDER BY _FILEDATE) AS MAC_ID_ITEM_RN
    FROM {{ ref('COMMON__WISDOM__WISDOM_SURB_DELAY') }} 
    QUALIFY row_number() over (partition by MAC_ID order by ITEM_NO desc, _FILEDATE desc) = 1
),

DATE AS (
    SELECT 
        CALENDAR_DATE,
        YEAR_MONTH_TEXT,
        FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF
    FROM {{ source('COMMON__DE_SAP_MASTER_DATA', 'CALENDAR_DATE') }}
),

STARTUPHOURS AS (
    SELECT 
        MACHINESERIALNUMBER,
        SUM(HOURSCHARGED) AS STARTUP_HOURS
    FROM {{ ref('COMMON__KRONOS__TIMESHEET') }}
    WHERE TYPEOFWORK = 'Startup'
    GROUP BY MACHINESERIALNUMBER
),

PREWARHOURS AS (
    SELECT 
        MACHINESERIALNUMBER,
        SUM(HOURSCHARGED) AS PREWARRANTY_HOURS
    FROM {{ ref('COMMON__KRONOS__TIMESHEET') }}
    WHERE TYPEOFWORK IN ('Pre-Warranty', 'Pre-warranty')
    GROUP BY MACHINESERIALNUMBER
),

FIRST_KRONOS AS (
    SELECT 
        MACHINESERIALNUMBER,
        MIN(EVENTDATE) AS FIRST_KRONOS_ENTRY
    FROM {{ ref('COMMON__KRONOS__TIMESHEET') }}
    WHERE TYPEOFWORK IN ('Startup', 'Pre-Warranty', 'Pre-warranty')
    GROUP BY MACHINESERIALNUMBER
),

LAST_KRONOS AS (
    SELECT 
        MACHINESERIALNUMBER,
        MAX(EVENTDATE) AS LATEST_KRONOS_ENTRY
    FROM {{ ref('COMMON__KRONOS__TIMESHEET') }}
    WHERE TYPEOFWORK IN ('Startup', 'Pre-Warranty', 'Pre-warranty')
    GROUP BY MACHINESERIALNUMBER
),

WORKORDER AS (
    SELECT 
        TEL_COM_SAP_CONSULTING_NO || '-' || WO_PRODUCTSNNAME AS PROJECT_SN,
        LISTAGG(DISTINCT WO_MSDYN_NAME, ', ') PROJECT_RELATED_WORK_ORDERS
    FROM {{ ref('COMMON__CRM__WO_SUMMARY_DETAILS') }}
    GROUP BY TEL_COM_SAP_CONSULTING_NO || '-' || WO_PRODUCTSNNAME
),

source_data AS (
    SELECT 
        DATE.FISCAL_HALF AS SCH_ACCEPTANCE_FISCAL_HALF,

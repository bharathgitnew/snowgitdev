        MACHINES.LOCATION_NAME,
        MACHINES.SERIAL_NUMBER,
        MACHINES.SWLH_MODEL,
        MACHINES.CUSTOMER_TOOL_ID,
        COALESCE(STARTUPHOURS.STARTUP_HOURS, 0) + COALESCE(PREWARHOURS.PREWARRANTY_HOURS, 0) AS TOTAL_HOURS,
        MACHINES.SCH_ACCEPTANCE,
        DELAY.DELAY_CATEGORY,
        DELAY.DELAY_REASON,
        MACHINES.MACHINE_HISTORY_REASON,
        MACHINES.LOAN_FLAG,
        MACHINES.START_UP_STATUS,
        MACHINES.WARRANTY_STATUS,
        MACHINES.TEL_SHIP_DATE,
        MACHINES.SCH_DOCK_DATE,
        MACHINES.ACT_DOCK_DATE,
        MACHINES.SCH_MOVE_IN,
        MACHINES.ACT_MOVE_IN,
        MACHINES.SCH_STARTUP_HOOKUP_START,
        MACHINES.ACT_STARTUP_HOOKUP_START,
        MACHINES.SCH_SL1,
        MACHINES.ACT_SL1,
        MACHINES.SCH_SL2,
        MACHINES.ACT_SL2,
        MACHINES.SCH_HW_STARTUP_START,
        MACHINES.ACT_HW_STARTUP_START,
        MACHINES.SCH_HW_STARTUP_END,
        MACHINES.ACT_HW_STARTUP_END,
        MACHINES.SCH_PROCESS_QUAL_START,
        MACHINES.ACT_PROCESS_QUAL_START,
        MACHINES.SCH_PROCESS_QUAL_END,
        MACHINES.ACT_PROCESS_QUAL_END,
        MACHINES.SCH_EQ_HANDOFF_TO_CUST,
        MACHINES.ACT_EQ_HANDOFF_TO_CUST,
        MACHINES.SCH_CTA,
        MACHINES.CTA_SIGNOFF_DATE,
        MACHINES.CTA_ACTION_FLAG,
        ODD.YEAR_MONTH_TEXT AS SCH_ODD_MONTH,
        DATE.YEAR_MONTH_TEXT AS SCH_ACCEPTANCE_MONTH,
        CTA.YEAR_MONTH_TEXT AS SCH_CTA_MONTH,
        ODD.FISCAL_HALF AS SCH_ODD_FISCAL_HALF,
        CTA.FISCAL_HALF AS SCH_CTA_FISCAL_HALF,
        COALESCE(STARTUPHOURS.STARTUP_HOURS, 0) AS STARTUP_HOURS,
        COALESCE(PREWARHOURS.PREWARRANTY_HOURS, 0) AS PREWARRANTY_HOURS,
        FIRST_KRONOS.FIRST_KRONOS_ENTRY,
        LAST_KRONOS.LATEST_KRONOS_ENTRY,
        MACHINES.WARRANTY_MONTHS,
        MACHINES.SOLD_BASIS,
        MACHINES.PARENT_CUSTOMER_NAME,
        MACHINES.CUSTOMER_CODE_B,
        MACHINES.CUSTOMER_CODE_D,
        MACHINES.SUPPLIER_CODE,
        MACHINES.SAP_PRODUCT_CODE,
        MACHINES.TEL_SALES_ORDER,
        MACHINES.TEL_MODEL,
        MACHINES.INSTALL_BASE_STATUS,
        MACHINES.WISDOM_MAC_ID,
        MACHINES.PROJECT_NUMBER,
        WORKORDER.PROJECT_RELATED_WORK_ORDERS,
        MACHINES.BU,
        MACHINES.BU_GROUP_LEADER,
        MACHINES.FACTORY_SHIP_DATE,
        MACHINES.SCH_FOB_FCA,
        MACHINES.ACT_FOB_FCA,
        MACHINES.CITY,
        MACHINES.STATE_PROVINCE,
        MACHINES.POSTAL_CODE,
    FROM MACHINES
        LEFT OUTER JOIN LEGACY_OFFICE ON MACHINES.CUSTOMER_CODE_B = LEGACY_OFFICE.B_CODE
        LEFT OUTER JOIN DELAY ON MACHINES.WISDOM_MAC_ID = DELAY.MAC_ID
        LEFT OUTER JOIN DATE ON MACHINES.SCH_ACCEPTANCE = DATE.CALENDAR_DATE
        LEFT OUTER JOIN DATE CTA ON MACHINES.SCH_CTA = CTA.CALENDAR_DATE
        LEFT OUTER JOIN DATE ODD ON MACHINES.SCH_DOCK_DATE = ODD.CALENDAR_DATE
        LEFT OUTER JOIN STARTUPHOURS ON MACHINES.SERIAL_NUMBER = STARTUPHOURS.MACHINESERIALNUMBER
        LEFT OUTER JOIN PREWARHOURS ON MACHINES.SERIAL_NUMBER = PREWARHOURS.MACHINESERIALNUMBER
        LEFT OUTER JOIN FIRST_KRONOS ON MACHINES.SERIAL_NUMBER = FIRST_KRONOS.MACHINESERIALNUMBER
        LEFT OUTER JOIN LAST_KRONOS ON MACHINES.SERIAL_NUMBER = LAST_KRONOS.MACHINESERIALNUMBER
        LEFT OUTER JOIN WORKORDER ON MACHINES.PROJECT_SN = WORKORDER.PROJECT_SN
),


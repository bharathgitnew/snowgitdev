        materialized='incremental',
        incremental_strategy='insert_overwrite',
        alias='INVENTORY_HISTORY_FULL',
        transient=false,
    
) }}

with MVKE as
(
    select 
        MVKE_MATERIAL_NUMBER
        , MATERIAL_GROUP_1
        , MATERIAL_GROUP_2
    from {{ ref('COMMON__SAPH__INVENTORY_SALES_MATERIAL') }}
     QUALIFY ROW_NUMBER() OVER (PARTITION BY MVKE_MATERIAL_NUMBER ORDER BY MVKE_MATERIAL_NUMBER ) = 1
),

security_cte as (
select
    COST_CENTER_CODE,
    SEGMENT_CODE as SECURITY_SEGMENT,
    DEPARTMENT_CODE as SECURITY_DEPARTMENT,
    OFFICE_CODE as SECURITY_OFFICE
from {{ ref('ODS__FILE__COST_CENTER') }}
),

profit_center as (
    select
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('ODS__FILE__PROFIT_CENTER') }}
),


MPS as (
    select 
    distinct MARA_MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION 
    from {{ ref('COMMON__SAPH__MATERIAL_PLANT_MASTER') }}

),

t156 as (
    select 
        BWART as MOVEMENT_TYPE, 
        SOBKZ as SPECIAL_STOCK_INDICATOR_SOBKZ, 
        KZBEW as MOVEMENT_INDICATOR, 
        KZZUG as RECEIPT_INDICATOR, 
        KZVBR as CONSUMPTION_POSTING, 
        BTEXT as MOVEMENT_TYPE_DESC 
    from {{ ref('ODS__SAPH__SAP_MMM_EV_T156T') }}
    where SPRAS = 'EN'
),


source_data as (
    select
        MATDOC.NUMBER_OF_MATERIAL_DOCUMENT_MBLNR as DOCUMENT_NUMBER
        , MATDOC.MOVEMENT_TYPE
        , MATDOC.ITEM_IN_MATERIAL_DOCUMENT_ZEILE as DOCUMENT_ITEM
        , MATDOC.MATERIAL_IN_RESPECT_OF_WHICH_STOCK_IS_MANAGED as MATERIAL
        , MPS.MATERIAL_DESCRIPTION
        , MATDOC.PLANT_WERKS as PLANT
        , MATDOC.STORAGE_LOCATION_LGORT_SID as STORAGE_LOCATION
        , MATDOC.CUSTOMER_FOR_SPECIAL_STOCK_KUNNR_SID as CONSIGNMENT_CUSTOMER
        , KNA1.NAME_1 as CUSTOMER_NAME
        , case when STORAGE_LOCATION_LGORT_SID = '' then KNA1.NAME_1 else STORAGE_LOCATION_LGORT_SID end as SLOC_CUSTOMER_COMBINED
        , MATDOC.DAY_ON_WHICH_ACCOUNTING_DOCUMENT_WAS_ENTERED as ENTRY_DATE
        , MATDOC.TIME_OF_ENTRY as ENTRY_TIME
        , convert_timezone('Etc/UCT', 'US/Central', to_timestamp(MATDOC.DAY_ON_WHICH_ACCOUNTING_DOCUMENT_WAS_ENTERED||MATDOC.TIME_OF_ENTRY,'YYYYMMDDHH24MISS')) as CST_TIME_STAMP
        , to_date(convert_timezone('Etc/UCT', 'US/Central', to_timestamp(MATDOC.DAY_ON_WHICH_ACCOUNTING_DOCUMENT_WAS_ENTERED||MATDOC.TIME_OF_ENTRY,'YYYYMMDDHH24MISS'))) as CST_ENTRY_DATE
        , to_time(convert_timezone('Etc/UCT', 'US/Central', to_timestamp(MATDOC.DAY_ON_WHICH_ACCOUNTING_DOCUMENT_WAS_ENTERED||MATDOC.TIME_OF_ENTRY,'YYYYMMDDHH24MISS'))) as CST_ENTRY_TIME
        , to_date(MATDOC.DAY_ON_WHICH_ACCOUNTING_DOCUMENT_WAS_ENTERED,'YYYYMMDD') as UTC_ENTRY_DATE
        , to_time(MATDOC.TIME_OF_ENTRY,'HH24MISS') as UTC_ENTRY_TIME
        , to_timestamp(MATDOC.DAY_ON_WHICH_ACCOUNTING_DOCUMENT_WAS_ENTERED||MATDOC.TIME_OF_ENTRY,'YYYYMMDDHH24MISS') as UTC_TIMESTAMP
        , case when MATDOC.DEBIT_CREDIT_INDICATOR = 'H' then MATDOC.QUANTITY_IN_UNIT_OF_ENTRY * - 1 else MATDOC.QUANTITY_IN_UNIT_OF_ENTRY end as TRANSACTION_QTY
        , case when MATDOC.DEBIT_CREDIT_INDICATOR = 'H' then MATDOC.AMOUNT_IN_LOCAL_CURRENCY * - 1 else MATDOC.AMOUNT_IN_LOCAL_CURRENCY end as TRANSACTION_VALUE
        , MVKE.MATERIAL_GROUP_1 as PRODUCT_CODE
        , MATDOC.LOCAL_ABC as LOCAL_ABC
        , MATDOC.SPECIFIC_CUSTOMER_ABC as INTEL_ABC
        , case when MVKE.MATERIAL_GROUP_2 = '0' then 'Non-Consumable' else 'Consumable' end  as CONSUMABLE
        , case when substr(MATDOC.STORAGE_LOCATION_LGORT_SID,3,1) = '3' or KNVV.kdgrp = 'Z1' then 'Intel' else 'Non-Intel' end as Intel
        , MATDOC.MATDOC_PROFIT_CENTER as PROFIT_CENTER
        , MATDOC.COST_CENTER as COST_CENTER
        , MATDOC.SPECIAL_STOCK_INDICATOR_SOBKZ
        , MATDOC.MOVEMENT_INDICATOR
        , MATDOC.RECEIPT_INDICATOR
        , MATDOC.CONSUMPTION_POSTING
        , t156.MOVEMENT_TYPE_DESC
        , MATDOC.REFERENCE_DOCUMENT_NUMBER AS REFERENCE
        , MATDOC.PURCHASE_ORDER_NUMBER AS PURCHASEORDER
        , TO_NUMBER(MATDOC.ITEM_NUMBER_OF_PURCHASING_DOCUMENT) AS PURCHASEORDER_ITEM
        , MATDOC.VENDOR_S_ACCOUNT_NUMBER AS SUPPLIER
        , MATDOC.BATCH_NUMBER_CHARG AS BATCH
        , MATDOC.DOCUMENT_DATE_IN_DOCUMENT AS DOCUMENT_DATE
        , MATDOC.MATDOC_BASE_UNIT_OF_MEASURE AS UNITOFENTRY
        , MATDOC.SALES_ORDER_NUMBER AS SALESORDER
        , MATDOC.ITEM_NUMBER_IN_SALES_ORDER AS SALESORDERITEM
        , to_date(MATDOC.POSTING_DATE_IN_THE_DOCUMENT,'YYYYMMDD') as POSTING_DATE
        , MATDOC.UNIT_OF_ENTRY AS UNIT_OF_ENTRY
        , MATDOC.RECORD_TYPE_RECORD_TYPE as RECORD_TYPE_RECORD_TYPE
        , '<ALL>' as SECURITY_SEGMENT
        , '<ALL>' as SECURITY_DEPARTMENT
        , '<ALL>' as SECURITY_OFFICE
        , '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') as _ROW_HASH
    from {{ ref('COMMON__SAPH__INVENTORY_PLANT_MATERIAL') }} MATDOC
    left join MVKE on MVKE.MVKE_MATERIAL_NUMBER = MATDOC.MATERIAL_IN_RESPECT_OF_WHICH_STOCK_IS_MANAGED
    left join {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}  KNA1 on KNA1.business_partner_number = MATDOC.CUSTOMER_FOR_SPECIAL_STOCK_KUNNR_SID
    left join {{ ref('ODS__SAPAPI__ZCDV_T_CMTU021_KNVV') }} KNVV on kna1.business_partner_number = knvv.kunnr
    left join MPS on MPS.MARA_MATERIAL_NUMBER = MATDOC.MATERIAL_IN_RESPECT_OF_WHICH_STOCK_IS_MANAGED
    left join t156 
        on t156.MOVEMENT_TYPE = MATDOC.MOVEMENT_TYPE
       and coalesce(t156.SPECIAL_STOCK_INDICATOR_SOBKZ, '') = coalesce(MATDOC.SPECIAL_STOCK_INDICATOR_SOBKZ, '')
       and coalesce(t156.MOVEMENT_INDICATOR, '') = coalesce(MATDOC.MOVEMENT_INDICATOR, '')
       and coalesce(t156.RECEIPT_INDICATOR, '') = coalesce(MATDOC.RECEIPT_INDICATOR, '')
       and coalesce(t156.CONSUMPTION_POSTING, '') = coalesce(MATDOC.CONSUMPTION_POSTING, '')
    left outer join security_cte
        on MATDOC.COST_CENTER=security_cte.COST_CENTER_CODE
    left outer join profit_center
        on MATDOC.MATDOC_PROFIT_CENTER=profit_center.PROFIT_CENTER_CODE
    where MATDOC.PLANT_WERKS in ('3200','3300','3400') and  MATDOC.RECORD_TYPE_RECORD_TYPE = 'MDOC'
),

transform_data AS
(
     select
         _AUDIT_LOG_ID
        , _ROW_HASH
        , DOCUMENT_NUMBER
        , MOVEMENT_TYPE
        , MOVEMENT_TYPE_DESC
        , REFERENCE
        , DOCUMENT_ITEM
        , MATERIAL
        , MATERIAL_DESCRIPTION
        , PLANT
        , STORAGE_LOCATION
        , CONSIGNMENT_CUSTOMER
        , CUSTOMER_NAME
        , SLOC_CUSTOMER_COMBINED
        , ENTRY_DATE
        , ENTRY_TIME
        , CST_TIME_STAMP
        , CST_ENTRY_DATE
        , CST_ENTRY_TIME
        , UTC_ENTRY_DATE
        , UTC_ENTRY_TIME
        , UTC_TIMESTAMP
        , CAST(TRANSACTION_QTY AS NUMBER(38,5)) AS TRANSACTION_QTY
        , CAST(TRANSACTION_VALUE AS NUMBER(38,5)) AS TRANSACTION_VALUE
        , PRODUCT_CODE
        , LOCAL_ABC
        , INTEL_ABC
        , CONSUMABLE
        , INTEL
		, PROFIT_CENTER
		, COST_CENTER
        , PURCHASEORDER
        , PURCHASEORDER_ITEM
        , SUPPLIER
        , BATCH
        , DOCUMENT_DATE
        , UNITOFENTRY
        , SALESORDER
        , SALESORDERITEM
        , POSTING_DATE
        , SECURITY_SEGMENT
        , SECURITY_DEPARTMENT
        , SECURITY_OFFICE
    from source_data
)

    select * from transform_data
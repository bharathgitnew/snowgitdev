with SOURCE_DATA AS (
    SELECT 
        BSEG.BUKRS AS COMPANY_CODE,
        BSEG.HKONT AS GL_ACCOUNT,
        BKPF.BELNR AS DOCUMENT_NO,
        BSEG.BUZEI AS LINE,
        BKPF.BLDAT AS DOCUMENT_DATE,
        BSEG.BSCHL AS POSTING_KEY,
        BKPF.BUDAT AS POSTING_DATE,
        BSEG.WRBTR AS AMOUNT_IN_DOCUMENT_CURRENCY,
        BKPF.WAERS AS CURRENCY,
        BKPF.WAERS AS LOCAL_CURRENCY,
        BSEG.DMBTR AS AMOUNT_IN_LOCAL_CURRENCY,
        BSEG.SGTXT AS ITEM_TEXT,
        BSEG.KIDNO AS PAYMENT_REFERENCE,
        BSEG.FMXDOCLN AS REFERENCE_LINE_ITEM,
        BSEG.KOART AS ACCOUNT_TYPE,
        BKPF.KURSF AS EXCHANGE_RATE,
        BSEG.PRCTR AS PROFIT_CENTER,
        BSEG.KOSTL AS COST_CENTER,
        BSEG.SHKZG AS DC_DESC
    FROM {{ ref('ODS__SAPO__SAPO_ACCOUNTING_DOCUMENT_HEADER') }} BKPF
    LEFT JOIN {{ ref('ODS__SAPO__SAPO_ACCOUNTING_DOCUMENT_SEGMENT') }} BSEG
        ON BKPF.MANDT = BSEG.MANDT 
        AND BKPF.BUKRS =  BSEG.BUKRS
        AND BKPF.BELNR = BSEG.BELNR
        AND BKPF.GJAHR = BSEG.GJAHR
    WHERE BSEG.GJAHR = '2023'
),

TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH,
        current_timestamp()::timestamp_ntz as _REFRESHDATE,
        COMPANY_CODE,
        GL_ACCOUNT,
        DOCUMENT_NO,
        LINE,
        DOCUMENT_DATE,
        POSTING_KEY,
        POSTING_DATE,
        AMOUNT_IN_DOCUMENT_CURRENCY,
        CURRENCY,
        LOCAL_CURRENCY,
        AMOUNT_IN_LOCAL_CURRENCY,
        ITEM_TEXT,
        PAYMENT_REFERENCE,
        REFERENCE_LINE_ITEM,
        ACCOUNT_TYPE,
        EXCHANGE_RATE,
        PROFIT_CENTER,
        COST_CENTER,
        DC_DESC
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT 
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
 	    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CAST(_REFRESHDATE AS timestamp_ntz) AS _REFRESHDATE,
        COMPANY_CODE,
        GL_ACCOUNT,
        DOCUMENT_NO,
        LINE,
        DOCUMENT_DATE,
        POSTING_KEY,
        POSTING_DATE,
        AMOUNT_IN_DOCUMENT_CURRENCY,
        CURRENCY,
        LOCAL_CURRENCY,
        AMOUNT_IN_LOCAL_CURRENCY,
        ITEM_TEXT,
        PAYMENT_REFERENCE,
        REFERENCE_LINE_ITEM,
        ACCOUNT_TYPE,
        EXCHANGE_RATE,
        PROFIT_CENTER,
        COST_CENTER,
        DC_DESC
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
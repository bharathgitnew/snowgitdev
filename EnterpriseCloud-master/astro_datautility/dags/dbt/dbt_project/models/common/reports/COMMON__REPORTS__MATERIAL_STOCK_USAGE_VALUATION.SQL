WITH FilteredMaterial AS (
    SELECT DISTINCT 
        MATERIAL_NUMBER,
        ABC_LOCAL,
        ABC_INTEL,
        ABC_GLOBAL,
        INTEL_FLAG_TEXT,
        REPAIR_FLAG_TEXT,
        MATERIAL_GROUP_2_TEXT,
        AVAILABLE_FOR_SALE_TEXT,
        SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT
    FROM {{ ref('COMMON__REPORTS__MASTER_MATERIAL_REPORT') }}
    WHERE VALUATION_AREA = '3200'
),

MaterialValuation AS (
      select MBEW_MATERIAL_NUMBER as MATERIAL_NUMBER ,
        case when PRICE_CONTROL_INDICATOR = 'S' then STANDARD_PRICE
        else  MOVING_AVERAGE_PRICE_PERIODIC_UNIT_PRICE END AS MOVING_AVERAGE_PRICE
      from {{ ref('COMMON__SAPH__MATERIAL_VALUATION_MASTER_CODED') }}
),


PartStockOverview AS (
    SELECT
        MATERIAL_NUMBER,
        MATERIAL_NUMBER_DESCRIPTION,
        STORAGE_LOCATION,
        STORAGE_LOCATION_NAME,
        SPEC_STOCK_PARTNER,
        SPEC_STOCK_PARTNER_NAME,
        PRODUCT_CODE,
        AVAILABLE_FOR_SALE,
        SPECIFIC_CUSTOMER_SELLABLE_INDICATOR,
        FORECAST_CLASSIFICATION,
        VENDOR,
        VENDOR_NAME,
        DELIVERY_TIME_DAYS,
        SALES_LEAD_TIME_REGION,
        SALES_LEAD_TIME_OVERSEAS,
        ALLOC_AUTHORITY_FLAG,
        UNIT_OF_MEASURE,
        SAFETY_STOCK,
        REORDER_POINT,
        MAXIMUM_STOCK_LEVEL,
        LIST_PRICE,
        LIST_PRICE_UOM,
        STANDARD_COST,
        STOCK,
        UNRESTRICTED_STOCK,
        QUALITY_INPECTION_STOCK,
        SALES_ORDER_STOCK,
        TOTAL_STOCK_ON_HAND,
        ON_ORDER_STOCK,
        STOCK_IN_TRANSIT,
        STOCK_IN_TRANSFER,
        STOCK_TOTAL,
        CUSTOMER_CONSIGNMENT_QTY,
        ALLOCATED_STOCK,
        TOTAL_LIST_PRICE_IN_CONSIGNMENT,
        TOTAL_STANDARD_COST_IN_CONSIGNMENT,
        LENDING_STOCK_QUANITY,
        EFFECTIVE_STOCK,
        TOTAL_LIST_PRICE_IN_LENDING_STOCK,
        TOTAL_STANDARD_COST_IN_LENDING_STOCK,
        FLAG,
        --SLOCTYPE_STORAGE_TYPE,
        --Intel_INTEL_STATUS,
        --TTLQTY_TOTAL_QUANTITY,
        --STDTTL AMT,
        CONCAT(SPEC_STOCK_PARTNER, '_', MATERIAL_NUMBER) AS SLOCPN,
        --MAValue,
        --MATTL AMT,
        --SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT,
        --AVAILABLE_FOR_SALE_TEXT,
        --CONSUMABLES,
        --REPAIR_FLAG_TEXT,
        --INTEL_FLAG_TEXT,
        --ABC_GLOBAL,
        --ABC_LOCAL,
        --ABC_INTEL,
        --QA,
        --BU,
        CASE 
            WHEN STORAGE_LOCATION IN ('A120', 'A530') THEN 'RDC'
            WHEN ENDSWITH(STORAGE_LOCATION, '4') THEN 'FCN'
            WHEN STOCK = 'L' THEN 'Loan'
            WHEN STOCK = 'C' THEN 'Consignment'
            ELSE 'Depot'
        END AS STORAGE_TYPE,
        CASE
            WHEN ENDSWITH(SUBSTR(STORAGE_LOCATION, 1, 3), '3') THEN 'INTEL'
            when STORAGE_LOCATION_NAME ilike '%INT%' then 'INTEL'
            WHEN MATERIAL_NUMBER LIKE '%-V%' THEN 'INTEL'
            WHEN SPEC_STOCK_PARTNER_NAME LIKE '%INTEL%' or SPEC_STOCK_PARTNER_NAME LIKE '%TEA Consignm%' 
            or SPEC_STOCK_PARTNER_NAME LIKE '%Fab 32%'  or SPEC_STOCK_PARTNER_NAME LIKE '%D1B%'  or SPEC_STOCK_PARTNER_NAME LIKE '%11X%'
            or SPEC_STOCK_PARTNER_NAME LIKE '%Aloha%'  or SPEC_STOCK_PARTNER_NAME LIKE '%INTOR%'  or SPEC_STOCK_PARTNER_NAME LIKE '%TokyoElectronAmerica%' THEN 'INTEL'
            WHEN SPEC_STOCK_PARTNER ilike '%10106%' or SPEC_STOCK_PARTNER ilike '%10137%' or SPEC_STOCK_PARTNER ilike '%10162%' then 'INTEL'
            when PRODUCT_CODE = 'A2' then 'INTEL'
            ELSE 'NIC'
        END AS INTEL_STATUS,
        TOTAL_STOCK_ON_HAND + STOCK_IN_TRANSFER + CUSTOMER_CONSIGNMENT_QTY + LENDING_STOCK_QUANITY AS TOTAL_QUANTITY,
        TOTAL_QUANTITY * STANDARD_COST AS TOTAL_COST,
        -- CASE 
        --     WHEN ABC_INTEL IN ('A', 'Q') THEN 'QA'
        --     ELSE ''
        -- END AS QA_STATUS,
        CASE
            WHEN PRODUCT_CODE IN ('CS', 'SR', 'D4', 'D3') THEN 'SPS'
            WHEN PRODUCT_CODE IN ('G2') THEN 'TS'
            WHEN PRODUCT_CODE IN ('PK', 'PM', 'PT', 'PY') THEN 'IPO'
            WHEN PRODUCT_CODE IN ('B3', 'B4') THEN 'ES'
            WHEN PRODUCT_CODE IN ('A2') THEN 'DS'
            WHEN PRODUCT_CODE IN ('B2') THEN 'CT'
            WHEN PRODUCT_CODE IN ('C4') THEN 'MB'
            ELSE PRODUCT_CODE
        END AS BUSINESS_UNIT
    FROM {{ ref('COMMON__REPORTS__PART_STOCK_OVERVIEW_REPORT') }}
),

JoinedData AS (
    SELECT
        PSO.*,
        MV.MOVING_AVERAGE_PRICE AS VALUATION_PRICE,
        COALESCE(MV.MOVING_AVERAGE_PRICE, PSO.STANDARD_COST) AS FINAL_VALUATION_PRICE,
        FINAL_VALUATION_PRICE * TOTAL_QUANTITY AS FINAL_TOTAL_COST
    FROM PartStockOverview PSO
    LEFT JOIN MaterialValuation MV ON PSO.MATERIAL_NUMBER = MV.MATERIAL_NUMBER
),

averages as (
SELECT
    ITEM,
    MATERIAL_DESC,
    CASE WHEN STARTsWITH(upper(SOLD_TO_BP),'INTEL') THEN 'INTEL'
    when SEARCH_TERM_1 = 'INTEL' or SEARCH_TERM_1 = 'INTEL CORPORATION' then 'INTEL'
    else 'NIC'
    END AS INTEL_STATUS,
    -- 3-Months Calculations
    COUNT(CASE WHEN PERIOD >= DATEADD(MONTH, -3, CURRENT_DATE) THEN 1 END) AS MOU_3,
    NULLIF(SUM(CASE WHEN PERIOD >= DATEADD(MONTH, -3, CURRENT_DATE) THEN SO_QTY ELSE 0 END) / 91.5, 0) AS AVG_Daily_Usage_3,

    -- 12-Months Calculations
    COUNT(CASE WHEN PERIOD >= DATEADD(MONTH, -12, CURRENT_DATE) THEN 1 END) AS MOU_12,
    NULLIF(SUM(CASE WHEN PERIOD >= DATEADD(MONTH, -12, CURRENT_DATE) THEN SO_QTY ELSE 0 END) / 365, 0) AS AVG_Daily_Usage_12,
    SUM(SO_QTY) AS CURRENT_USAGE

FROM
    {{ ref('COMMON__REPORTS__DEMAND_BY_SITE_V2') }}
WHERE
    PERIOD >= DATEADD(MONTH, -12, CURRENT_DATE)
GROUP BY
    ITEM,
    MATERIAL_DESC,
    INTEL_STATUS
HAVING
    SUM(CASE WHEN PERIOD >= DATEADD(MONTH, -12, CURRENT_DATE) THEN SO_QTY ELSE 0 END) > 0


),
FinalData AS (
    SELECT
        JD.*,
        MR.SPECIFIC_CUSTOMER_SELLABLE_INDICATOR_TEXT AS CUSTOMER_SELLABLE_INDICATOR,
        MR.AVAILABLE_FOR_SALE_TEXT AS SALE_STATUS,
        MR.MATERIAL_GROUP_2_TEXT AS CONSUMABLES_GROUP,
        MR.REPAIR_FLAG_TEXT AS REPAIR_FLAG,
        MR.INTEL_FLAG_TEXT AS INTEL_FLAG,
        MR.ABC_GLOBAL AS GLOBAL_ABC,
        MR.ABC_LOCAL AS LOCAL_ABC,
        MR.ABC_INTEL AS INTEL_ABC,
        AV.MOU_3,
        AV.AVG_Daily_Usage_3,
        AV.MOU_12,
        AV.AVG_Daily_Usage_12,
        AV.CURRENT_USAGE,
        JD.TOTAL_STOCK_ON_HAND/AV.AVG_Daily_Usage_12 AS TOTAL_ON_HAND
    FROM JoinedData JD
    LEFT JOIN FilteredMaterial MR ON JD.MATERIAL_NUMBER = MR.MATERIAL_NUMBER
    LEFT JOIN averages AV ON JD.MATERIAL_NUMBER = AV.ITEM and av.INTEL_STATUS = JD.INTEL_STATUS

),


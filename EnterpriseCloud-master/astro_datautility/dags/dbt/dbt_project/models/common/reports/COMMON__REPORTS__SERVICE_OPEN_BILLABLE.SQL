with SALES_ORDER as (
SELECT DISTINCT
        VBAK_SALES_DOCUMENT AS ZS10_SALES_ORDER,
        row_number() over ( partition by VBAK_SALES_DOCUMENT order by VBAK_SALES_DOCUMENT,SALES_DOCUMENT_ITEM_POSNR desc ) as RECORD,
        CUSTOMER_REFERENCE AS CUSTOMER_PO,
        VBAK_NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY AS CUSTOMER_PO_AMOUNT,
        VBAK_SOLD_TO_PARTY AS SOLD_TO_CUSTOMER_CODE,
        VBAP_PRODUCT_CODE AS PRODUCT_CODE,
        TOOL_SERIAL_NO AS SERIAL_NUMBER,
        SERVICE_CRM_WO_NO AS CRM_WORK_ORDER,
        VBAK_NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY AS SAP_AMT,
        CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS as SAP_HOURS,
        DOCUMENT_DATE AS SALES_ORDER_DATE,
        CASE VBAP_BILLING_STATUS_FOR_ORDER_RELATED_BILLING_DOCUMENTS
            WHEN NULL THEN 'NOT RELEVANT'
            WHEN 'A' THEN 'NOT YET PROCESSED'
            WHEN 'B' THEN 'PARTIALLY PROCESSED'
            WHEN 'C' THEN 'COMPLETELY PROCESSED'
        END as SAP_BILLING_STATUS
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}  as SO
    WHERE 1=1
        AND SO.VBAK_SALES_ORGANIZATION = '3200'
        AND SO.VBAK_ORDER_REASON = 'PSO'
        AND SO.VBAK_SALES_DOCUMENT_TYPE = 'ZS10'
and VBAP_SALES_DOCUMENT_ITEM_CATEGORY = 'ZSD2'
),
 VBAK_SO as (
    select * from SALES_ORDER where RECORD = 1
),
CGM AS (
    SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_GROUP_MAPPING') }}
),
BP AS(
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER,
        NAME_1_OF_ORGANIZATION AS CUSTOMER_NAME,
        SEARCH_TERM_2_FOR_BUSINESS_PARTNER AS SOLD_TO_CUSTOMER
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    ),
TEACOMMONEMP AS (
    SELECT
        EMPLOYEEID,
        SUPERVISORID,
        SUPERVISOR_NAME
        FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
    ),
USER AS (
    SELECT
        UPPER(ID) AS ID
        ,(LASTNAME||', '||FIRSTNAME) AS WO_CREATOR
        ,LPAD(EMPLOYEEID,6,'0') AS WO_CREATOR_ID
        ,COM_EMPLOYEE_ATTRIBUTES
FROM {{ ref('ODS__CRM_FILE__SYSTEMUSER') }}
),

-- temporary solution while waiting on common crm file repoint
cte_CRM_FILE_WORKORDER as (
    SELECT DISTINCT
            WO.MSDYN_NAME
            ,WO.WO_WOTITLE AS WO_TITLE
            ,WO.CREATEDON as WO_CREATED_ON
            ,WO.CREATEDBYYOMINAME AS WO_CREATOR
            ,TEL_WO_MAINCATEGORY_SOREQUEST
            ,G.LOCALIZEDLABEL AS WO_MAINCATEGORY
            ,TEL_WO_SUBCATEGORY_SOREQUESTNAME AS WO_SUBCATEGORY
            ,TEL_WO_SERVICEORDERNO_3200 AS SAP_SERVICE_ORDER
            ,MSDYN_SUBSTATUSNAME AS STATUS
            ,MAX(WOS_R.MSDYN_UNITAMOUNT) OVER(PARTITION BY WO.ID,WO.TEL_WO_SERVICEORDERNO_3200) AS CRM_REG_RATE
            ,MAX(WOS_OT.MSDYN_UNITAMOUNT) OVER(PARTITION BY WO.ID,WO.TEL_WO_SERVICEORDERNO_3200) AS CRM_OT_RATE
            ,COUNT(T.ID)  OVER(PARTITION BY WO.ID,TEL_WO_SERVICEORDERNO_3200) AS CRM_TIME_ENTRIES -- filter this on 4/28 forward.
            ,SUM(T.WO_DURATION_HR) OVER(PARTITION BY WO.ID,TEL_WO_SERVICEORDERNO_3200) AS CRM_HOURS  -- filter this on 4/28 forward.
            ,MIN(CAST(T.CREATEDON AS DATE)) OVER(PARTITION BY WO.ID,WO.TEL_WO_SERVICEORDERNO_3200) AS FIRST_TIME_ENTRY
            ,MAX(CAST(T.CREATEDON AS DATE)) OVER(PARTITION BY WO.ID,WO.TEL_WO_SERVICEORDERNO_3200) AS LAST_TIME_ENTRY
            ,WO.CREATEDBY
            ,WO.TEL_WO_ORDER_NO_TEXT
            ,WO.WO_REMARKSINTERNAL AS WO_INTERNAL_NOTES
            ,WO.TEL_WO_MESSAGETOOP AS MESSAGE_FOR_SAP
            ,WO.ID as WO_ID
   FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }} WO
   LEFT OUTER JOIN {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }} G
       ON WO.WO_MAINCATEGORY_OPTIONS = G.OPTION
            AND G.LOCALIZEDLABELLANGUAGECODE = '1033' AND G.OPTIONSETNAME = 'wo_maincategory_options' AND G.ENTITYNAME = 'msdyn_workorder'
   LEFT OUTER JOIN {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }} T
        ON try_to_number(T.WO_WORKORDERNONAME) = try_to_number(WO.MSDYN_NAME) AND T.OWNINGBUSINESSUNITNAME = 'US'
            AND T.WO_DELETE_FLG = 'FALSE' AND T.CREATEDON > '2023-04-28'  -- may need TO be removed later
   LEFT OUTER JOIN {{ ref('ODS__CRM_FILE__MSDYN_WORKORDERSERVICE') }} WOS_R
        ON WOS_R.MSDYN_WORKORDER = T.WO_WORKORDERNO
            AND WOS_R.WO_RESOURCE = T.MSDYN_BOOKABLERESOURCE and WOS_R.MSDYN_SERVICENAME = 'Field Engineer Regular Charge Work'
   LEFT OUTER JOIN {{ ref('ODS__CRM_FILE__MSDYN_WORKORDERSERVICE') }} WOS_OT
        ON WOS_OT.MSDYN_WORKORDER = T.WO_WORKORDERNO
            AND WOS_OT.WO_RESOURCE = T.MSDYN_BOOKABLERESOURCE AND WOS_OT.MSDYN_SERVICENAME = 'Field Engineer Over Time Charge Work'
),

CRM_FINAL AS (
    SELECT
        MSDYN_NAME,
        WO_TITLE,
        WO_CREATED_ON,
        TEL_WO_MAINCATEGORY_SOREQUEST,
        WO_MAINCATEGORY,
        WO_SUBCATEGORY,
        SAP_SERVICE_ORDER,
        STATUS,
        CRM_REG_RATE,
        CRM_HOURS,
        FIRST_TIME_ENTRY,
        LAST_TIME_ENTRY,
        C.WO_CREATOR AS WO_CREATOR,
        U.WO_CREATOR_ID AS WO_CREATOR_ID,
        T.SUPERVISOR_NAME AS WO_CREATOR_SUPERVISOR_NAME,
        C.CREATEDBY AS CREATEDBY,
        C.TEL_WO_ORDER_NO_TEXT,
        C.WO_INTERNAL_NOTES,
        C.MESSAGE_FOR_SAP,
        C.WO_ID,
FROM  cte_CRM_FILE_WORKORDER C
LEFT JOIN USER U ON UPPER(C.CREATEDBY) = UPPER(u.ID)
LEFT JOIN TEACOMMONEMP T ON UPPER(U.WO_CREATOR_ID) = UPPER(T.EMPLOYEEID)
),
KR AS (
    SELECT
        SERVICEORDER, SUM(HOURSCHARGED) AS KRONOS_HOURS
    FROM {{ ref('COMMON__KRONOS__TIMESHEET') }}
    WHERE SOURCESYSTEM = 'C'
        AND EVENTDATE >= '2023-04-28'  -- may need TO be removed later
        AND LEFT(SERVICEORDER,1) = '3'
    GROUP BY SERVICEORDER
),
WO_CRM_HOURS AS (
    SELECT
        LPAD(MSDYN_NAME,8,'0') AS WORK_ORDER
        ,UPPER(MSDYN_WORKORDERID) AS WO_ID
        ,DATE(MSDYN_TIMECLOSED) AS WO_CLOSE_DATE
		,DATE(WO_CUSTOMERSIGNRECEIVEDON) AS CUSTOMER_SIGN_OFF_RECEIVED_ON
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
),
TIMEENTRY AS (
    SELECT
    UPPER(WO_WORKORDERNO) AS WO_WORKORDERNO
    ,SUM(WO_DURATION_HR) AS TOTALHOURS
    FROM {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }}
    WHERE 1=1
    AND WO_DELETE_FLG = 'FALSE'
    AND WO_DUPLICATIONFLAG = 'FALSE'
    GROUP BY UPPER(WO_WORKORDERNO)
),
CRM_HOURS_SOURCE AS (
    SELECT
        WORK_ORDER
        ,WO_ID
        ,TOTALHOURS
        ,WO_CLOSE_DATE
        ,CUSTOMER_SIGN_OFF_RECEIVED_ON
        FROM WO_CRM_HOURS
    LEFT OUTER JOIN TIMEENTRY
    ON WO_CRM_HOURS.WO_ID = WO_WORKORDERNO
),

MACHINE AS (
    SELECT
        SERIAL_NUMBER
        ,LEGACY_BU
        ,SWLH_MODEL
    FROM {{ ref('COMMON__DE_WISDOM__GLOBAL_MACHINES') }}
),

SEGMENT AS (
    SELECT
        SAP_CODE AS SAP_SEGMENT_CODE
        ,CASE
            WHEN SAP_DESCRIPTION = 'FS-3DI Bonder' THEN '3DIBON'
            WHEN SAP_DESCRIPTION LIKE '%Certas%' THEN 'CERTAS'
            ELSE UPPER(REPLACE(SAP_DESCRIPTION, 'FS-') )
        END AS SAP_DESCRIPTION
        ,ORACLE_CODE AS ORACLE_SEGMENT_CODE
    FROM {{ ref('COMMON__SAPH__SAP_SEGMENT') }}
    WHERE LEFT(SAP_DESCRIPTION,3) IN ( 'FS-', 'FS ')
),

PO AS (
    SELECT
        PONUMBER AS PO_NUMBER
        ,POAMOUNT AS PO_AMOUNT
        ,CASE
            WHEN STATUS = 1 THEN 'Active'
            WHEN STATUS = 2 THEN 'Invoiced'
            WHEN STATUS = 3 THEN 'Need Revised PO'
            WHEN STATUS = 4 THEN 'Inactive'
            WHEN STATUS = 5 THEN 'Cancelled'
            ELSE NULL
        END AS PO_STATUS
    FROM {{ ref('COMMON__TELQS__PROCESS_ORDER_DETAILS') }}
    WHERE PONUMBER NOT LIKE '%If I am%'
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY PO_NUMBER ORDER BY PO_STATUS DESC)) = 1
),

SAP_SO_HOURS AS (
    SELECT
        SERVICE_ORDER,
        SUM(HOURS_ADJUSTED) AS SAP_HOURS,
    FROM {{ ref('COMMON__REPORTS__SERVICE_ORDER_OPERATION_SUMMARY') }}
    GROUP BY SERVICE_ORDER
),

source_data AS (
    SELECT
        CGM.CUSTOMER_GROUP AS CUSTOMER_GROUP,
        CGM.CUSTOMER_GROUP2 AS CUSTOMER_GROUP2,
        BP.CUSTOMER_NAME AS CUSTOMER_NAME,
        BP.SOLD_TO_CUSTOMER AS SOLD_TO_CUSTOMER,
        VBAK_SO.SOLD_TO_CUSTOMER_CODE AS SOLD_TO_CUSTOMER_CODE,
        VBAK_SO.ZS10_SALES_ORDER AS ZS10_SALES_ORDER,
        VBAK_SO.CUSTOMER_PO AS CUSTOMER_PO,
        zeroifnull(PO.PO_AMOUNT) AS CUSTOMER_PO_AMOUNT,
        VBAK_SO.PRODUCT_CODE AS PRODUCT_CODE,
        VBAK_SO.SERIAL_NUMBER AS SERIAL_NUMBER,
        VBAK_SO.CRM_WORK_ORDER AS CRM_WORK_ORDER,
        zeroifnull(SAP_SO_HOURS.SAP_HOURS) AS SAP_HOURS,
        VBAK_SO.SALES_ORDER_DATE AS SALES_ORDER_DATE,
        VBAK_SO.SAP_BILLING_STATUS AS SAP_BILLING_STATUS,
        CRM_FINAL.SAP_SERVICE_ORDER AS SAP_SERVICE_ORDER,
        CRM_FINAL.WO_TITLE AS WO_TITLE,
        CRM_FINAL.WO_CREATED_ON AS WO_CREATED_ON,
        CRM_FINAL.WO_MAINCATEGORY AS WO_MAINCATEGORY,
        CRM_FINAL.WO_SUBCATEGORY AS WO_SUBCATEGORY,
        CRM_FINAL.WO_CREATOR AS WO_CREATOR,
        CRM_FINAL.STATUS AS WO_STATUS,
        crm_hours.TOTALHOURS as CRM_HOURS,
        case
            when CRM_FINAL.CRM_REG_RATE is not null then CRM_FINAL.CRM_REG_RATE
            when CGM.CUSTOMER_GROUP = 'Intel' then 235
            when CGM.CUSTOMER_GROUP = 'Micron' then 220
            when BP.SOLD_TO_CUSTOMER IN ('TTCA', 'TMEA') THEN 70
            when CGM.CUSTOMER_GROUP = 'TEL Group' then 100
            else 275
        end AS CRM_REG_RATE,
        CRM_FINAL.FIRST_TIME_ENTRY AS FIRST_CRM_TIME_ENTRY,
        CRM_FINAL.LAST_TIME_ENTRY AS LAST_CRM_TIME_ENTRY,
        KR.KRONOS_HOURS AS KRONOS_HOURS,
        LO.LEGACY_OFFICE as LEGACY_OFFICE,
        MACHINE.LEGACY_BU,
        MACHINE.SWLH_MODEL,
        SEGMENT.SAP_SEGMENT_CODE,
        SEGMENT.ORACLE_SEGMENT_CODE,
        crm_hours.WO_CLOSE_DATE AS WO_CLOSE_DATE,
        crm_hours.CUSTOMER_SIGN_OFF_RECEIVED_ON AS CUSTOMER_SIGN_OFF_RECEIVED_ON,
        CRM_FINAL.WO_CREATOR_SUPERVISOR_NAME AS WO_CREATOR_SUPERVISOR_NAME,
        CRM_FINAL.TEL_WO_ORDER_NO_TEXT AS WO_PURCHASE_ORDER_NO,
        CRM_FINAL.WO_INTERNAL_NOTES,
        CRM_FINAL.MESSAGE_FOR_SAP,
        CASE
            WHEN LEN(VBAK_SO.CUSTOMER_PO) > 1
                AND LEFT(VBAK_SO.CUSTOMER_PO,1) <> '*'
                AND UPPER(VBAK_SO.CUSTOMER_PO) NOT IN ('TBD', 'WARRANTY')
            THEN VBAK_SO.CUSTOMER_PO
            WHEN LEN(CRM_FINAL.TEL_WO_ORDER_NO_TEXT) > 1
                AND UPPER(CRM_FINAL.TEL_WO_ORDER_NO_TEXT) NOT IN ('TBD', 'WARRANTY')
            THEN CRM_FINAL.TEL_WO_ORDER_NO_TEXT
            ELSE '*No PO'
        END AS CUSTOMER_PO_FINAL,
        BUMAP.BU_GROUP,
        BUMAP.BU_GROUP_LEADER,
        BUMAP.BU_GROUP_LEADER_ID,
        CSCMAP.PRIMARY_CONTACT AS PRIMARY_SERVICE_CONTACT,
        CSCMAP.PRIMARY_CONTACTID AS PRIMARY_SERVICE_CONTACT_ID,
        CSCMAP.SECONDARY_CONTACT AS SECONDARY_SERVICE_CONTACT,
        CSCMAP.SECONDARY_CONTACT AS SECONDARY_SERVICE_CONTACT_ID,
        PO.PO_STATUS,
        DATEDIFF(day, CURRENT_DATE(), WO_CREATED_ON) AS DAYS_SINCE_WO_CREATED,
        DATEDIFF(day, LAST_CRM_TIME_ENTRY, CURRENT_DATE())  AS DAYS_SINCE_LAST_TIME_ENTRY,
        CASE
            WHEN LAST_CRM_TIME_ENTRY IS NULL THEN '*No Entries'
            WHEN DAYS_SINCE_LAST_TIME_ENTRY > 180 THEN 'Over 6 Months'
            WHEN DAYS_SINCE_LAST_TIME_ENTRY > 30 THEN '1-6 Months'
            ELSE '*Within 30 Days'
        END AS LAST_TIME_ENTRY_FLAG,
        CRM_FINAL.WO_ID,
    FROM VBAK_SO
        LEFT OUTER JOIN CRM_FINAL ON VBAK_SO.CRM_WORK_ORDER = CRM_FINAL.MSDYN_NAME
        LEFT OUTER JOIN BP ON VBAK_SO.SOLD_TO_CUSTOMER_CODE = BP.BUSINESS_PARTNER_NUMBER
        LEFT OUTER JOIN KR ON CRM_FINAL.SAP_SERVICE_ORDER = KR.SERVICEORDER
        left join CRM_HOURS_SOURCE crm_hours on crm_hours.WORK_ORDER=VBAK_SO.CRM_WORK_ORDER
        left join {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }} LO on LO.B_CODE = VBAK_SO.SOLD_TO_CUSTOMER_CODE
        LEFT OUTER JOIN MACHINE ON MACHINE.SERIAL_NUMBER = VBAK_SO.SERIAL_NUMBER
        LEFT OUTER JOIN SEGMENT ON MACHINE.LEGACY_BU = SEGMENT.SAP_DESCRIPTION
        LEFT OUTER JOIN CGM ON VBAK_SO.SOLD_TO_CUSTOMER_CODE = CGM.ACCOUNT_NUMBER
        LEFT OUTER JOIN {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }} BUMAP
        ON BUMAP.BU_SOURCE_KEY = VBAK_SO.PRODUCT_CODE
        LEFT OUTER JOIN {{ ref('ODS__SHAREPOINT__CUSTOMER_SITE_SERVICE_MANAGER_MAPPING') }} CSCMAP
        ON CSCMAP.CC_BU_KEY = VBAK_SO.SOLD_TO_CUSTOMER_CODE||'_'||BUMAP.BU_GROUP
        left join PO on CUSTOMER_PO_FINAL = PO.PO_NUMBER
        left join SAP_SO_HOURS on CRM_FINAL.SAP_SERVICE_ORDER = SAP_SO_HOURS.SERVICE_ORDER
    WHERE WO_MAINCATEGORY = 'Paid Service' and SAP_BILLING_STATUS <> 'COMPLETELY PROCESSED'
),

transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        CUSTOMER_GROUP,
        CUSTOMER_GROUP2,
        CUSTOMER_NAME,
        SOLD_TO_CUSTOMER,
        SOLD_TO_CUSTOMER_CODE,
        ZS10_SALES_ORDER,
        CUSTOMER_PO,
        CUSTOMER_PO_AMOUNT,
        PRODUCT_CODE,
        SERIAL_NUMBER,
        CRM_WORK_ORDER,
        SAP_HOURS,
        SAP_HOURS * CRM_REG_RATE AS SAP_AMT,
        try_to_date(SALES_ORDER_DATE, 'YYYYMMDD') as SALES_ORDER_DATE,
        SAP_BILLING_STATUS,
        SAP_SERVICE_ORDER,
        WO_TITLE,
        WO_CREATED_ON,
        WO_MAINCATEGORY,
        WO_SUBCATEGORY,
        WO_CREATOR,
        WO_STATUS,
        ifnull(CRM_HOURS, 0) as CRM_HOURS,
        zeroifnull(CRM_HOURS * CRM_REG_RATE) as CRM_EXPECTED_AMT,
        FIRST_CRM_TIME_ENTRY,
        LAST_CRM_TIME_ENTRY,
        CRM_REG_RATE,
        ifnull(KRONOS_HOURS, 0) as KRONOS_HOURS,
        LEGACY_OFFICE,
        LEGACY_BU,
        SWLH_MODEL,
        SAP_SEGMENT_CODE,
        ORACLE_SEGMENT_CODE,
        WO_CLOSE_DATE,
        CUSTOMER_SIGN_OFF_RECEIVED_ON,
        WO_CREATOR_SUPERVISOR_NAME,
        WO_PURCHASE_ORDER_NO,
        WO_INTERNAL_NOTES,
        MESSAGE_FOR_SAP,
        CUSTOMER_PO_FINAL,
        BU_GROUP,
        BU_GROUP_LEADER,
        BU_GROUP_LEADER_ID,
        PRIMARY_SERVICE_CONTACT,
        PRIMARY_SERVICE_CONTACT_ID,
        SECONDARY_SERVICE_CONTACT,
        SECONDARY_SERVICE_CONTACT_ID,
        PO_STATUS,
        DAYS_SINCE_WO_CREATED,
        DAYS_SINCE_LAST_TIME_ENTRY,
        LAST_TIME_ENTRY_FLAG,
        WO_ID,
    FROM source_data
),

type_data as (
    select
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        CUSTOMER_GROUP,
        CUSTOMER_GROUP2,
        CUSTOMER_NAME,
        SOLD_TO_CUSTOMER,
        SOLD_TO_CUSTOMER_CODE,
        ZS10_SALES_ORDER,
        CUSTOMER_PO,
        cast(CUSTOMER_PO_AMOUNT as NUMBER(38,2)) as CUSTOMER_PO_AMOUNT,
        PRODUCT_CODE,
        SERIAL_NUMBER,
        CRM_WORK_ORDER,
        cast(SAP_HOURS as NUMBER(38,2)) as SAP_HOURS,
        cast(SAP_AMT as NUMBER(38,2)) as SAP_AMT,
        cast(SALES_ORDER_DATE as DATE) as SALES_ORDER_DATE,
        SAP_BILLING_STATUS,
        SAP_SERVICE_ORDER,
        WO_TITLE,
        cast(WO_CREATED_ON as DATE) as WO_CREATED_ON,
        WO_MAINCATEGORY,
        WO_SUBCATEGORY,
        WO_CREATOR,
        WO_STATUS,
        cast(CRM_HOURS as NUMBER(38,2)) as CRM_HOURS,
        cast(CRM_EXPECTED_AMT as NUMBER(38,2)) as CRM_EXPECTED_AMT,
        cast(FIRST_CRM_TIME_ENTRY as DATE) as FIRST_CRM_TIME_ENTRY,
        cast(LAST_CRM_TIME_ENTRY as DATE) as LAST_CRM_TIME_ENTRY,
        cast(CRM_REG_RATE as NUMBER(38,2)) as CRM_REG_RATE,
        cast(KRONOS_HOURS as NUMBER(38,2)) as KRONOS_HOURS,
        LEGACY_OFFICE,
        LEGACY_BU,
        SWLH_MODEL,
        SAP_SEGMENT_CODE,
        ORACLE_SEGMENT_CODE,
        cast(WO_CLOSE_DATE as DATE) as WO_CLOSE_DATE,
        cast(CUSTOMER_SIGN_OFF_RECEIVED_ON as DATE) as CUSTOMER_SIGN_OFF_RECEIVED_ON,
        WO_CREATOR_SUPERVISOR_NAME,
        WO_PURCHASE_ORDER_NO,
        WO_INTERNAL_NOTES,
        MESSAGE_FOR_SAP,
        CUSTOMER_PO_FINAL,
        BU_GROUP,
        BU_GROUP_LEADER,
        BU_GROUP_LEADER_ID,
        PRIMARY_SERVICE_CONTACT,
        PRIMARY_SERVICE_CONTACT_ID,
        SECONDARY_SERVICE_CONTACT,
        SECONDARY_SERVICE_CONTACT_ID,
        PO_STATUS,
        cast(DAYS_SINCE_WO_CREATED as NUMBER(38,0)) as DAYS_SINCE_WO_CREATED,
        cast(DAYS_SINCE_LAST_TIME_ENTRY as NUMBER(38,0)) as DAYS_SINCE_LAST_TIME_ENTRY,
        LAST_TIME_ENTRY_FLAG,
        WO_ID,
    from transform_data
)

select * from type_data
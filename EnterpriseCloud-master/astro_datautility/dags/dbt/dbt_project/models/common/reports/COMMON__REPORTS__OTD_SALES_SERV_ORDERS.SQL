WITH source_data as (
SELECT 
	'SLS BAAN' AS SOURCE, 
	CONCAT(SALES_ORDER_NO, '_', POSITION_NO) AS SO_LINE,  
	ITEM AS MATERIAL, 
	ORDER_DATE, 
	DELIVERY_DATE, 
	CASE WHEN LEFT(SOLDTO_BPID, 5) = '20301' THEN 'INTEL' ELSE 'NON-INTEL' END AS INTEL, LEFT(DELIVERY_DATE, 7) AS MONTH_ODT 
FROM {{ ref('COMMON__DE_TEL_REPORTING__BAANV_TEA_SALES_ORDERS') }}  
UNION
SELECT 
	'SRV_BAAN', 
	CONCAT(SRV.SERVICE_ORDER_NO, '_', SRV.ACTIVITY_LINE) AS SO_LINE, 
	SRV.ITEM, 
	SRV.MATERIAL_ORDER_DATE, 
	CASE WHEN SRV.DELIVERY_TYPE = 'From Warehouse' THEN SRV.DELIVERY_DATE ELSE IB.ACT_RECEIPT_DATE END AS DDT, 
	CASE WHEN LEFT(SRV.SOLD_TO_BPID, 5) = '20301' THEN 'INTEL' ELSE 'NON-INTEL' END AS INTEL, LEFT(SRV.DELIVERY_DATE, 7) AS MONTH_ODT
FROM {{ ref('COMMON__DE_TEL_REPORTING__BAANV_TEA_SERVICE_ORDERS') }}  SRV 
JOIN {{ ref('COMMON__DE_TEL_REPORTING__BAANV_TEA_WAREHOUSE_ORDERS_INBOUND') }}  IB 
ON SERVICE_ORDER_NO = WHS_ORDER_NO AND ACTIVITY_LINE = IB_POS_NO 
UNION
( WITH MAX_DELIVERY_DATE AS
(
 SELECT DISTINCT
   LIPS_DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,
    LIPS_ITEM_NUMBER_OF_THE_REFERENCE_ITEM, 
    SUM(LIPS_ACTUAL_QUANTITY_DELIVERED) AS DELIVERED_QTY
    ,MAX(LIKP_DOCUMENT_DATE_IN_DOCUMENT) AS LIKP_DOCUMENT_DATE
    ,MAX(LIKP_ACTUAL_GOODS_MOVEMENT_DATE) AS LIKP_ACTUAL_GOODS_MOVEMENT_DATE
FROM {{ ref('COMMON__SAPH__DELIVERY_ORDER_LINE_MASTER') }} 
GROUP BY LIPS_DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,LIPS_ITEM_NUMBER_OF_THE_REFERENCE_ITEM 
), 
VBPA_INFO AS (
    SELECT DISTINCT
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_THE_SD_DOCUMENT,
        CUSTOMER_NUMBER,
        PARTNER_FUNCTION
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }}
  WHERE PARTNER_FUNCTION='SP' ),
FINAL_DATA AS (SELECT 'SLS_SAP',
CONCAT(VBAP.VBELN, '-', VBAP.POSNR) AS SO_LINE, VBAP.MATNR, try_to_Date(VBAP.ERDAT,'yyyymmdd') as ORDER_DATE, 
try_to_Date(LIKP_ACTUAL_GOODS_MOVEMENT_DATE,'yyyymmdd') AS DELIVERY_DATE, CASE WHEN LEFT(KNA1.NAME1, 3) = 'INT' THEN 'INTEL' ELSE 'NON-INTEL' END AS INTEL, LEFT(LIKP_ACTUAL_GOODS_MOVEMENT_DATE, 7) AS MONTH_ODT
FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} VBAP 
 LEFT JOIN MAX_DELIVERY_DATE
  ON VBAP.VBELN = MAX_DELIVERY_DATE.LIPS_DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT 
  AND  VBAP.POSNR = MAX_DELIVERY_DATE.LIPS_ITEM_NUMBER_OF_THE_REFERENCE_ITEM
    LEFT JOIN VBPA_INFO ON SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER=VBAP.VBELN 
  LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} KNA1 ON VBPA_INFO.CUSTOMER_NUMBER = KNA1.KUNNR )
  SELECT * FROM FINAL_DATA) 
  ),
 transform_data as (
  SELECT 
	SOURCE,
	SO_LINE,
	MATERIAL,
	ORDER_DATE,
	DELIVERY_DATE,
	INTEL,
	MONTH_ODT,
	'{{ invocation_id }}' AS AUDIT_LOG_ID
FROM source_data 
),
type_data as (
 SELECT
    CAST(SOURCE AS VARCHAR(16777216)) AS  SOURCE,
    CAST(SO_LINE AS VARCHAR(16777216)) AS  SO_LINE,
    CAST(MATERIAL AS VARCHAR(16777216)) AS  MATERIAL,
    CAST(ORDER_DATE AS TIMESTAMP_NTZ(9)) AS  ORDER_DATE,
    CAST(DELIVERY_DATE AS TIMESTAMP_NTZ(9)) AS  DELIVERY_DATE,
    CAST(INTEL AS VARCHAR(16777216)) AS  INTEL,
    CAST(MONTH_ODT AS VARCHAR(16777216)) AS  MONTH_ODT,
    CAST(AUDIT_LOG_ID AS VARCHAR(36)) AS  AUDIT_LOG_ID
FROM transform_data)

SELECT * from type_data
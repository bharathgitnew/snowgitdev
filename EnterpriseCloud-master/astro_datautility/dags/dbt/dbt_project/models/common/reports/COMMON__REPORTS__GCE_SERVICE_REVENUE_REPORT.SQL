{{ config(
      materialized='table',
      alias='GCE_SERVICE_REVENUE_REPORT',
      transient=false
) }}

WITH SOURCE_DATA AS (
SELECT
    FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF
    ,CALENDAR_YEAR_MONTH
    ,END_USER_GROUP
    ,END_USER_NAME
    ,END_USER
    ,END_USER_CITY
    ,END_USER_REGION
    ,BAAN_OFFICE
    ,BAAN_OFFICE_CODE
    ,SEGMENT
    ,SEGMENT_CODE
    ,BAAN_SEGMENT_CODE
    ,BU_GROUP AS BU
    ,PRODUCT_TYPE_NAME AS PRODUCT_TYPE
    ,SALES_CATEGORY_ORACLE AS PRODUCT_TYPE_CODE
    ,CASE
    WHEN SALES_CATEGORY_ORACLE  IN ('CONTRA', 'PDSRV', 'SMSRV', 'TRNPD', 'TSCREM', 'TSCSTD') THEN 'External'
    WHEN SALES_CATEGORY_ORACLE IN ('FACSCN','FCN','INSTAL','PDSRVT','TECSUP','TELCNS','TELSCN','TRNFIX','TRNVAR','UPGMOD','WARRAN') THEN 'Internal'
    ELSE 'Unknown'
    END AS REVENUE_SOURCE
    ,CASE
    WHEN SALES_CATEGORY_ORACLE  IN ('FACSCN', 'TECSUP', 'TELCNS', 'TELSCN') THEN 'Concession'
    WHEN SALES_CATEGORY_ORACLE  IN ('CONTRA', 'PDSRV','SMSRV', 'TSCREM', 'TSCSTD') THEN 'Contract & Paid Service'
    WHEN SALES_CATEGORY_ORACLE IN ('TRNFIX', 'TRNPD', 'TRNVAR') THEN 'Training'
    WHEN SALES_CATEGORY_ORACLE IN ('INSTAL') THEN 'Startup'
    WHEN SALES_CATEGORY_ORACLE IN ('WARRAN') THEN 'Warranty'
    WHEN SALES_CATEGORY_ORACLE IN ('PDSRVT') THEN 'TEL Group'
    WHEN SALES_CATEGORY_ORACLE IN ('UPGMOD') THEN 'Modification'
    ELSE SALES_CATEGORY_ORACLE
    END AS PRODUCT_TYPE_GROUP
    ,SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY * '-1') AS REVENUE
FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE_ENHANCED') }}
WHERE 1=1
AND CALENDAR_YEAR_MONTH < LEFT(CURRENT_DATE,7)
AND PNL_CATEGORY = 'Revenue'
AND SALES_CATEGORY_ORACLE  IN ('CONTRA', 'PDSRV', 'SMSRV', 'TRNPD', 'TSCREM', 'TSCSTD',
                              'FACSCN','FCN','INSTAL','PDSRVT','TECSUP','TELCNS','TELSCN','TRNFIX','TRNVAR','UPGMOD','WARRAN')
GROUP BY
FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
,CALENDAR_YEAR_MONTH
,END_USER_GROUP
,END_USER_NAME
,END_USER
,END_USER_CITY
,END_USER_REGION
,BAAN_OFFICE
,BAAN_OFFICE_CODE
,SEGMENT
,SEGMENT_CODE
,BAAN_SEGMENT_CODE
,BU_GROUP
,PRODUCT_TYPE_NAME
,SALES_CATEGORY_ORACLE
),

TRANSFORM_DATA as (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID
    ,SHA2('hash_me') as _ROW_HASH
    ,FISCAL_HALF
    ,CALENDAR_YEAR_MONTH
    ,END_USER_GROUP
    ,END_USER_NAME
    ,BAAN_OFFICE
    ,BU
    ,REVENUE_SOURCE
    ,PRODUCT_TYPE_GROUP
    ,PRODUCT_TYPE_CODE
    ,PRODUCT_TYPE
    ,REVENUE
    ,END_USER
    ,END_USER_CITY
    ,END_USER_REGION
    ,BAAN_OFFICE_CODE
    ,SEGMENT
    ,SEGMENT_CODE
    ,BAAN_SEGMENT_CODE
FROM SOURCE_DATA
),

TYPE_DATA AS (
SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
    ,CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    ,FISCAL_HALF
    ,CALENDAR_YEAR_MONTH
    ,END_USER_GROUP
    ,END_USER_NAME
    ,BAAN_OFFICE
    ,BU
    ,CAST(REVENUE_SOURCE AS VARCHAR(16777216)) AS REVENUE_SOURCE
    ,PRODUCT_TYPE_GROUP
    ,PRODUCT_TYPE_CODE
    ,PRODUCT_TYPE
    ,CAST(REVENUE AS NUMBER(38,2)) AS REVENUE
    ,END_USER
    ,END_USER_CITY
    ,END_USER_REGION
    ,BAAN_OFFICE_CODE
    ,SEGMENT
    ,SEGMENT_CODE
    ,BAAN_SEGMENT_CODE
FROM TRANSFORM_DATA
)

select * from TYPE_DATA


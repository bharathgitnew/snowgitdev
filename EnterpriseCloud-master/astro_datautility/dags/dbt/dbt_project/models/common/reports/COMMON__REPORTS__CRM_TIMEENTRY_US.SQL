WITH TIMEENTRY AS (
    SELECT
        WO_WORKORDERNONAME AS WORK_ORDER,
        WO_EMPLOYEE_ATTRIBUTES,
        WO_DURATION_HR AS DURATION_HR,
        MSDYN_DURATION AS DURATION_MIN,
        MSDYN_DATE,
        CAST(WO_STARTTIME AS DATE) START_DATE,
        LEFT(WO_STARTTIME, 7) START_MONTH,
        WO_STARTTIME,
        WO_ENDTIME,
        WO_FABNAME,
        WO_PRODUCTSNNAME AS SERIAL_NUMBER,
        WO_TASK2NAME,
        WO_TASK2RESOURCEREGIONNAME,
        TEL_WO_CATEGORYNAME,
        WO_TIMEZONES AS TIMEZONE_CODE,
        TEL_WO_LOCAL_START,
        TEL_WO_LOCAL_END,
        CREATEDON,
        MODIFIEDON AS MODIFIED_ON,
        WO_FAB,
        WO_MAINCATEGORY,
        WO_DELETE_FLG,
        WO_DUPLICATIONFLAG,
        WO_IFERROR,
        WO_BOOKABLERESOURCEBOOKINGNAME,
        WO_CUSTOMER,
        UPPER(CREATEDBY) AS CREATEDBY,
        WO_TYPEOFWORKNAME,
        WO_TYPEOFWORKRESOURCEREGIONNAME,
        TEL_WO_BUNAME,
        TEL_WO_BU2NAME,
        MODIFIEDBY,
        WO_DUPLICATIONFLAG AS WO_DUPLICATION_FLAG,
        STATECODE AS TE_STATECODE,
        MSDYN_TIMEENTRYID AS TIME_ENTRY_ID,
        OWNINGBUSINESSUNITNAME,
        CASE
            WHEN STATECODE = '0' THEN 'Active'
            Else 'Inactive'
        END as TE_STATUS
    FROM {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }}
    WHERE
        1 = 1
        AND WO_STARTTIME >= '2023-01-01'
        AND WO_DUPLICATIONFLAG = 'FALSE'
        AND WO_TASK2NAME NOT IN (
            'Lunch Time',
            'PPL',
            'Holiday',
            'Other Unpaid Break'
        )
        AND OWNINGBUSINESSUNITNAME IN ('US')
),

WO AS (
    SELECT
        LPAD(MSDYN_NAME, 8, '0') AS WORK_ORDER,
        WO_WOTITLE AS WO_TITLE,
        TEL_WO_SUBCATEGORY_SOREQUESTNAME AS WO_SUBCATEGORY,
        MSDYN_WORKORDERTYPENAME AS WO_TYPE,
        WO_TYPEOFWORK_CUSTOMIZEDNAME AS WO_TYPEOFWORKCUSTOMIZEDNAME,
        WO_TEMP_FAB_TEXT AS WO_FAB,
        WO_CUSTOMERNAME AS WO_CUSTOMER,
        WO_TEMP_MSNAME AS WO_SERIAL_NUMBER,
        WO_TEMP_TOOLID_JP AS CUSTOMER_TOOL_ID,
        TEL_WO_SERVICEORDERNO_3200 AS SAP_SERVICE_ORDER,
        WO_TEMP_PRODUCTLINE_TEXT AS WO_PRODUCT_LINE,
        MSDYN_SUBSTATUSNAME AS WO_SUBSTATUS,
        CASE
            WHEN MSDYN_SUBSTATUSNAME = 'Closed' THEN 'Y'
            ELSE 'N'
        END AS WO_IS_CLOSED_FLAG,
        WO_PROCESSSTAGENAME AS WO_PROCESS_STAGE,
        TEL_WO_TYPEOFPAYMENT AS WO_TEL_WO_TYPEOFPAYMENT,
        WO_WOISSUEDATE AS WO_ISSUE_DATE,
        MSDYN_COMPLETEDON AS WO_COMPLETED_DATE,
        TEL_WO_PRIMARY_SONAME AS WO_PRIMARY_SALES_ORDER,
        MSDYN_WORKORDERID AS WO_ID,
        WO_MAINCATEGORY_OPTIONS,
        UPPER(TEL_WO_CONTRACTGROUP) AS TEL_WO_CONTRACTGROUP,
        TEL_WO_CUSTOMERBY9DIGITSNAME AS CUSTOMER_D_CODE_NAME,
        TEL_WO_CUSTOMERBY9DIGITS,
        TEL_WO_SAPFIELDMODIFIEDON,
        WO_TIMEZONES,
        TEL_WO_SOWNAME AS WO_SOWNAME,
        WO_MASTERPROJECTNAME AS WO_PROJECT_NAME,
        MODIFIEDON AS WO_MODIFIEDON,
        CREATEDBYNAME
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
    WHERE
        1 = 1
        AND WO_REGIONNAME = 'US'
        AND LEFT(MSDYN_NAME, 8) <> 'Template'
),

CRM_CUSTOMER AS (
    SELECT
        ACCOUNTNUMBER,
        NAME,
        COM_COMPANY_E_NAME AS CUSTOMER_NAME,
        ID
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }}
    WHERE COM_COUNTRY_NAMENAME = 'USA'
),

MAINCAT AS (
    SELECT
        OPTION,
        LOCALIZEDLABEL AS WO_MAINCATEGORY
    FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }} --ODS.CRM.WO_GLOBALOPTIONSETMETADATA
    WHERE
        LOCALIZEDLABELLANGUAGECODE = '1033'
        AND OPTIONSETNAME = 'wo_maincategory_options'
),

PAYMENT AS (
    SELECT
        OPTION,
        LOCALIZEDLABEL AS WO_PAYMENT_TYPE
    FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }} --ODS.CRM.WO_GLOBALOPTIONSETMETADATA
    WHERE
        LOCALIZEDLABELLANGUAGECODE = '1033'
        AND OPTIONSETNAME = 'tel_wo_typeofpayment'
        AND ENTITYNAME = 'msdyn_workorder'
),

TIMEZONE AS (
    SELECT
        TIMEZONECODE,
        STANDARDNAME AS TIMEZONE,
        USERINTERFACENAME
    FROM {{ ref('ODS__CRM_FILE__TIMEZONEDEFINITION') }}
),

USER AS (
    SELECT
        UPPER(ID) AS ID,
        FIRSTNAME,
        LASTNAME,(LASTNAME || ', ' || FIRSTNAME) AS WO_CREATOR,
        LPAD(EMPLOYEEID, 6, '0') AS USER_EMP_ID,
        COM_EMPLOYEE_ATTRIBUTES
    FROM {{ ref('ODS__CRM_FILE__SYSTEMUSER') }}
),

TEACOMMONEMP AS (
    SELECT
        EMPLOYEEID AS EMPLOYEE_ID,
        SUPERVISORID AS SUPERVISOR_ID,
        FULLNAME AS EMPLOYEE_NAME,
        SUPERVISOR_NAME
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
),

CONTRACT AS (
    SELECT
        UPPER(ID) AS ID,
        CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
    FROM {{ ref('ODS__CRM_FILE__CNT_CONTRACTSUMMARY') }}
),

CONTRACT_MASTER AS (
    SELECT
        CONTRACT_NUMBER,
        CONTRACT_TITLE,
        CONTRACT_TYPE,
        BAAN_CONTRACT_NUMBER,
        PO_NUMBER
    FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY CONTRACT_NUMBER ORDER BY PO_NUMBER DESC)) = 1
),

SAP_CUSTOMER AS (
    SELECT
        BUSINESS_PARTNER_NUMBER,
        CUSTOMER_GROUP
    FROM {{ ref('COMMON__SAPH__SAP_CUSTOMER') }}
    WHERE
        BUSINESS_PARTNER_SERIES = 'A'
),

GLOBAL_MACHINE AS (
SELECT DISTINCT SERIAL_NUMBER, BU_GROUP FROM {{ ref('COMMON__DE_WISDOM__GLOBAL_MACHINES') }}
),

COMBINED AS (
    SELECT
        TIMEENTRY.START_MONTH,
        CREATEDBYEMP.SUPERVISOR_NAME,
        CREATEDBYEMP.EMPLOYEE_NAME,
        CREATEDBYEMP.EMPLOYEE_ID,
        TIMEENTRY.START_DATE,
        TIMEENTRY.DURATION_HR,
        TIMEENTRY.TEL_WO_CATEGORYNAME,
        MAINCAT.WO_MAINCATEGORY,
        TIMEENTRY.WORK_ORDER,
        WO.WO_TITLE,
        WO.WO_SUBCATEGORY,
        PAYMENT.WO_PAYMENT_TYPE,
        CASE
            WHEN COALESCE(TIMEENTRY.WO_CUSTOMER, TIMEENTRY.WO_FABNAME) IS NULL THEN 'N/A'
            WHEN SAP_CUSTOMER.CUSTOMER_GROUP IS NOT NULL THEN SAP_CUSTOMER.CUSTOMER_GROUP
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'TOKYO ELECTRON%'
            OR CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'TEL %'
            OR TIMEENTRY.WO_FABNAME iLIKE 'TEA/%' THEN 'TEL Group'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'SAMSUNG%' THEN 'Samsung'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'INTEL%'
            OR TIMEENTRY.WO_FABNAME iLIKE 'INTEL%' THEN 'Intel'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'MICRON%'
            OR TIMEENTRY.WO_FABNAME iLIKE 'MICRON%' THEN 'Micron'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'TEXAS INSTRUMENTS%'
            OR TIMEENTRY.WO_FABNAME iLIKE 'TI/%' THEN 'TI'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE '%TSMC%'
            OR TIMEENTRY.WO_FABNAME iLIKE 'TSMC%' THEN 'TSMC'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'GLOBALFOUND%'
            OR CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'GLOBAL FOUND%' THEN 'GF/IBM/Albany'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE 'IBM%'
            OR CRM_CUSTOMER.CUSTOMER_NAME iLIKE '%ALBANY (SUNY)%' THEN 'GF/IBM/Albany'
            WHEN CRM_CUSTOMER.CUSTOMER_NAME iLIKE '%RESERCH FOUNDATION FOR STATE UNIVERSITY%'
            OR TIMEENTRY.WO_FABNAME iLIKE 'SUNY ALBANY UNIV%' THEN 'GF/IBM/Albany'
            ELSE 'Regional'
        END AS CUSTOMER_GROUP,
        CRM_CUSTOMER.CUSTOMER_NAME,
        TIMEENTRY.WO_FABNAME,
        WO.CUSTOMER_D_CODE_NAME,
        CASE WHEN GM.SERIAL_NUMBER IS NOT NULL THEN GM.BU_GROUP
        WHEN GM.SERIAL_NUMBER IS NULL AND COALESCE(WO_PRODUCT_LINE, TEL_WO_BUNAME) = 'FSI' THEN 'CCS'
        WHEN GM.SERIAL_NUMBER IS NULL AND COALESCE(WO_PRODUCT_LINE, TEL_WO_BUNAME) = 'EPION' THEN 'GCIB'
        ELSE COALESCE(WO_PRODUCT_LINE, TEL_WO_BUNAME) END AS BU,
        WO.WO_PRODUCT_LINE,
        TIMEENTRY.SERIAL_NUMBER,
        WO.CUSTOMER_TOOL_ID,
        TIMEENTRY.WO_TASK2NAME,
        TIMEENTRY.WO_TASK2RESOURCEREGIONNAME,
        CONTRACT.CONTRACT_NUMBER,
        CONTRACT_MASTER.CONTRACT_TYPE,
        CONTRACT_MASTER.CONTRACT_TITLE,
        WO.WO_PRIMARY_SALES_ORDER,
        WO.SAP_SERVICE_ORDER,
        WO.WO_SOWNAME,
        WO.WO_PROJECT_NAME,
        WO.WO_PROCESS_STAGE,
        WO.WO_SUBSTATUS,
        WO.WO_IS_CLOSED_FLAG,
        CRM_CUSTOMER.ACCOUNTNUMBER AS CUSTOMER_A_CODE,
        CASE
            WHEN LEFT(FAB.ACCOUNTNUMBER, 1) = 'B' THEN FAB.ACCOUNTNUMBER
            WHEN LEFT(DCODE.ACCOUNTNUMBER, 1) = 'B' THEN DCODE.ACCOUNTNUMBER
            ELSE NULL
        END AS CUSTOMER_B_CODE,
        CASE
            WHEN LEFT(FAB.ACCOUNTNUMBER, 1) = 'D' THEN FAB.ACCOUNTNUMBER
            WHEN LEFT(DCODE.ACCOUNTNUMBER, 1) = 'D' THEN DCODE.ACCOUNTNUMBER
            ELSE NULL
        END AS CUSTOMER_D_CODE,
        TIMEENTRY.TEL_WO_BUNAME,
        TIMEENTRY.TEL_WO_BU2NAME,
        TIMEENTRY.WO_EMPLOYEE_ATTRIBUTES,
        TIMEENTRY.DURATION_MIN,
        TIMEENTRY.MSDYN_DATE,
        TIMEENTRY.WO_STARTTIME,
        TIMEENTRY.WO_ENDTIME,
        TIMEENTRY.TIMEZONE_CODE,
        TIMEZONE.TIMEZONE,
        TIMEENTRY.TEL_WO_LOCAL_START,
        TIMEENTRY.TEL_WO_LOCAL_END,
        TIMEENTRY.MODIFIED_ON,
        TIMEENTRY.WO_DUPLICATION_FLAG,
        TIMEENTRY.WO_DELETE_FLG,
        TIMEENTRY.TE_STATUS,
        TIMEENTRY.TE_STATECODE,
        CREATEDBYEMP.SUPERVISOR_ID,
        WO.WO_ID,
        TIMEENTRY.TIME_ENTRY_ID
    FROM TIMEENTRY
    LEFT JOIN WO ON TIMEENTRY.WORK_ORDER = WO.WORK_ORDER
    LEFT JOIN MAINCAT ON WO.WO_MAINCATEGORY_OPTIONS = MAINCAT.OPTION
    LEFT JOIN PAYMENT ON WO.WO_TEL_WO_TYPEOFPAYMENT = PAYMENT.OPTION
    LEFT JOIN TIMEZONE ON TIMEENTRY.TIMEZONE_CODE = TIMEZONE.TIMEZONECODE
    LEFT JOIN CRM_CUSTOMER ON TIMEENTRY.WO_CUSTOMER = CRM_CUSTOMER.ID
    LEFT JOIN CRM_CUSTOMER FAB ON TIMEENTRY.WO_FAB = FAB.ID
    LEFT JOIN CRM_CUSTOMER DCODE ON WO.TEL_WO_CUSTOMERBY9DIGITS = DCODE.ID
    LEFT JOIN SAP_CUSTOMER ON CRM_CUSTOMER.ACCOUNTNUMBER = SAP_CUSTOMER.BUSINESS_PARTNER_NUMBER
    LEFT JOIN USER CREATEDBYUSER ON TIMEENTRY.CREATEDBY = CREATEDBYUSER.ID
    LEFT JOIN TEACOMMONEMP CREATEDBYEMP ON CREATEDBYUSER.USER_EMP_ID = CREATEDBYEMP.EMPLOYEE_ID
    LEFT JOIN CONTRACT ON WO.TEL_WO_CONTRACTGROUP = CONTRACT.ID
    LEFT JOIN CONTRACT_MASTER ON CONTRACT.CONTRACT_NUMBER = CONTRACT_MASTER.CONTRACT_NUMBER
    LEFT JOIN GLOBAL_MACHINE GM ON TIMEENTRY.SERIAL_NUMBER = GM.SERIAL_NUMBER
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        START_MONTH,
        SUPERVISOR_NAME,
        EMPLOYEE_NAME,
        EMPLOYEE_ID,
        START_DATE,
        DURATION_HR,
        TEL_WO_CATEGORYNAME,
        WO_MAINCATEGORY,
        WORK_ORDER,
        WO_TITLE,
        WO_SUBCATEGORY,
        WO_PAYMENT_TYPE,
        CUSTOMER_GROUP,
        CUSTOMER_NAME,
        WO_FABNAME,
        CUSTOMER_D_CODE_NAME,
        BU,
        WO_PRODUCT_LINE,
        SERIAL_NUMBER,
        CUSTOMER_TOOL_ID,
        WO_TASK2NAME,
        WO_TASK2RESOURCEREGIONNAME,
        CONTRACT_NUMBER,
        CONTRACT_TYPE,
        CONTRACT_TITLE,
        WO_PRIMARY_SALES_ORDER,
        SAP_SERVICE_ORDER,
        WO_SOWNAME,
        WO_PROJECT_NAME,
        WO_PROCESS_STAGE,
        WO_SUBSTATUS,
        WO_IS_CLOSED_FLAG,
        CUSTOMER_A_CODE,
        CUSTOMER_B_CODE,
        CUSTOMER_D_CODE,
        TEL_WO_BUNAME,
        TEL_WO_BU2NAME,
        WO_EMPLOYEE_ATTRIBUTES,
        DURATION_MIN,
        MSDYN_DATE,
        WO_STARTTIME,
        WO_ENDTIME,
        TIMEZONE_CODE,
        TIMEZONE,
        TEL_WO_LOCAL_START,
        TEL_WO_LOCAL_END,
        MODIFIED_ON,
        WO_DELETE_FLG,
        TE_STATUS,
        TE_STATECODE,
        SUPERVISOR_ID,
        WO_ID,
        TIME_ENTRY_ID
    from COMBINED
),

type_data as (
    select
        _AUDIT_LOG_ID,
        _ROW_HASH,
        START_MONTH,
        SUPERVISOR_NAME,
        EMPLOYEE_NAME,
        EMPLOYEE_ID,
        START_DATE,
        cast(DURATION_HR as NUMBER(38, 4)) as DURATION_HR,
        TEL_WO_CATEGORYNAME,
        WO_MAINCATEGORY,
        WORK_ORDER,
        WO_TITLE,
        WO_SUBCATEGORY,
        WO_PAYMENT_TYPE,
        CUSTOMER_GROUP,
        CUSTOMER_NAME,
        WO_FABNAME,
        CUSTOMER_D_CODE_NAME,
        BU,
        WO_PRODUCT_LINE,
        SERIAL_NUMBER,
        CUSTOMER_TOOL_ID,
        WO_TASK2NAME,
        WO_TASK2RESOURCEREGIONNAME,
        CONTRACT_NUMBER,
        CONTRACT_TYPE,
        CONTRACT_TITLE,
        WO_PRIMARY_SALES_ORDER,
        SAP_SERVICE_ORDER,
        WO_SOWNAME,
        WO_PROJECT_NAME,
        WO_PROCESS_STAGE,
        WO_SUBSTATUS,
        WO_IS_CLOSED_FLAG,
        CUSTOMER_A_CODE,
        CUSTOMER_B_CODE,
        CUSTOMER_D_CODE,
        TEL_WO_BUNAME,
        TEL_WO_BU2NAME,
        WO_EMPLOYEE_ATTRIBUTES,
        cast(DURATION_MIN as NUMBER(38, 2)) as DURATION_MIN,
        cast(MSDYN_DATE as DATE) as MSDYN_DATE,
        cast(WO_STARTTIME as TIMESTAMP_NTZ(9)) as WO_STARTTIME,
        cast(WO_ENDTIME as TIMESTAMP_NTZ(9)) as WO_ENDTIME,
        cast(TIMEZONE_CODE as VARCHAR(16777216)) as TIMEZONE_CODE,
        TIMEZONE,
        cast(TEL_WO_LOCAL_START as VARCHAR(16777216)) as TEL_WO_LOCAL_START,
        cast(TEL_WO_LOCAL_END as VARCHAR(16777216)) as TEL_WO_LOCAL_END,
        cast(MODIFIED_ON as TIMESTAMP_NTZ(9)) as MODIFIED_ON,
        cast(WO_DELETE_FLG as VARCHAR(16777216)) as WO_DELETE_FLG,
        TE_STATUS,
        cast(TE_STATECODE as VARCHAR(16777216)) as TE_STATECODE,
        SUPERVISOR_ID,
        WO_ID,
        TIME_ENTRY_ID
    from transform_data
)


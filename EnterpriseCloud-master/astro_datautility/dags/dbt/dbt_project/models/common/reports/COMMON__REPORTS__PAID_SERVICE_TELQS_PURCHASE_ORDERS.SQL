WITH TELQS_PO AS (
    SELECT
        PONUMBER AS PO_NUMBER
        ,CASE
            WHEN LEN(QUOTENUMBER)>1 THEN QUOTENUMBER
            ELSE NULL
        END AS QUOTE_NUMBER
        ,CUSTOMER AS TELQS_CUSTOMER
        ,CASE
            WHEN LEN(CUSTOMERCODE)>1 THEN CUSTOMERCODE
            ELSE NULL
        END AS TELQS_CUSTOMERCODE
        ,PRODUCT
        ,CASE
            WHEN PRODUCT = 'SD' THEN 'MT'
            WHEN PRODUCT = 'TP' THEN 'DS'
            ELSE PRODUCT
        END AS PRODUCT2
        ,POAMOUNT AS PO_AMOUNT
        ,PODATE AS PO_DATE
        ,CASE
            WHEN STATUS = 1 THEN 'Active'
            WHEN STATUS = 2 THEN 'Invoiced'
            WHEN STATUS = 3 THEN 'Need Revised PO'
            WHEN STATUS = 4 THEN 'Inactive'
            WHEN STATUS = 5 THEN  'Cancelled'
            ELSE NULL
        END AS PO_STATUS
        ,CASE
            WHEN LEN(FAB)>1 THEN FAB
            ELSE NULL
        END AS FAB
        ,CUSTOMERGROUP AS TELQS_CUSTOMERGROUP
        ,BUSINESSISSUINGPO
        ,LEFT(SPLIT_PART(BUSINESSISSUINGPO, '(', 2),9) AS BUSINESSISSUINGPOCODE
        ,RECIEVEDATE AS RECEIVED_DATE
        ,PODESCRIPTION AS PO_DESCRIPTION
        ,CASE
            WHEN LEN(FSBCOMMENTS)< 1 THEN NULL
            ELSE FSBCOMMENTS
        END AS FSB_COMMENTS
        ,CASE
            WHEN WORKSTARTDATE = '1900-01-01' THEN NULL
            ELSE WORKSTARTDATE
        END AS WORK_START_DATE
        ,CASE
            WHEN PLANNEDENDDATE = '1900-01-01' THEN NULL
            ELSE PLANNEDENDDATE
        END AS PLANNED_END_DATE
        ,CASE
            WHEN LEN(WORKORDER)< 1 THEN NULL
            ELSE WORKORDER
        END AS WORK_ORDER
        ,QUOTEREQUESTOR
        ,QUOTESUPERVISOR
        ,SITESUPERVISOR
        ,CASE
            WHEN LEN(QUOTEREQUESTOREMPNO) > 1 THEN QUOTEREQUESTOREMPNO
            ELSE NULL
        END AS QUOTE_REQUESTOR_ID
        ,CASE
            WHEN LEN(QUOTESUPERVISOREMPNO) > 1 THEN QUOTESUPERVISOREMPNO
            ELSE NULL
        END AS QUOTE_SUPERVISOR_ID
        ,CASE
            WHEN LEN(SITESUPERVISOREMPNO) > 1 THEN SITESUPERVISOREMPNO
            ELSE NULL
        END AS SITE_SUPERVISOR_ID
        ,STATUS AS PO_STATUS_CODE
        ,ID
    FROM {{ ref('COMMON__TELQS__PROCESS_ORDER_DETAILS') }}
    WHERE PONUMBER NOT LIKE '%If I am%'
    ORDER BY ID
)

,QUOTE AS (
    SELECT
        QUOTENUMBER
        ,SITESUPERVISOREMPNO AS SITE_SUPERVISOR_ID
        ,REQUESTOREMPNO AS REQUESTOR_ID
        ,SUPERVISOREMPNO AS SUPERVISOR_ID
    FROM {{ ref('COMMON__TELQS__PAID_SERVICE_QUOTE_MASTER') }}
)

,EMPLOYEE AS (
    SELECT
        EMPLOYEEID
        ,FULLNAME
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
)

,EMPNAME AS (
    SELECT
        UPPER(FIRSTNAME)||' '||UPPER(LASTNAME) AS MAPPEDNAME
        ,FULLNAME
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
    QUALIFY row_number() over ( partition by MAPPEDNAME order by ACTIVE desc, LASTUPDATED desc ) = 1
)

,BU AS (
    SELECT DISTINCT
        SAP_PRODUCT_CODE
        ,CASE
            WHEN SAP_PRODUCT_CODE = 'L1' THEN 'FS-Certas'
            WHEN SAP_PRODUCT_CODE = 'SS' THEN 'FS-3DI Bonder'
            WHEN SAP_PRODUCT_CODE = 'HD' THEN 'FS-PVD'
            ELSE 'FS-'||LEGACY_BU
        END AS SEGMENT_NAME
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE SAP_PRODUCT_CODE IS NOT NULL
    QUALIFY row_number() over ( partition by SAP_PRODUCT_CODE order by LEGACY_BU desc ) = 1
)

,FS_SEGMENT AS (
    SELECT DISTINCT
        ORACLE_CODE AS SEGMENT_CODE_ORACLE
        ,ORACLE_DESCRIPTION
        ,SAP_CODE AS SEGMENT_CODE_SAP
    FROM {{ ref('COMMON__SAPH__SAP_SEGMENT') }}
    WHERE LEFT(ORACLE_DESCRIPTION,3) = 'FS-'
)

,CUSTOMER AS (
    SELECT
        CUSTOMER_GROUP
        ,BUSINESS_PARTNER_NUMBER
        ,CORPORATION_NAME AS CUSTOMER
        ,CORPORATION AS CUSTOMER_A_CODE
        ,IDENTIFICATION_NUMBER
        ,SEARCH_TERM_2
    FROM {{ ref('COMMON__SAPH__SAP_CUSTOMER') }}
    WHERE BUSINESS_PARTNER_SERIES IN ('A','B','D')
)

,FAB_B_CODE AS (
    SELECT DISTINCT
        CUSTOMER_CODE_B
        ,CUSTOMER_CODE_D
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE LEN(CUSTOMER_CODE_B)>1 AND LEN(CUSTOMER_CODE_D)>1
    QUALIFY row_number() over ( partition by CUSTOMER_CODE_D order by CUSTOMER_CODE_B desc ) = 1
)

,SAP_INVOICE AS (
    SELECT
        CUSTOMER_REFERENCE AS PO
        ,CALENDAR_YEAR_MONTH
        ,SALES_DOCUMENT
        ,REFERENCE_DOCUMENT_NUMBER
        ,SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY)*-1 AS REVENUE
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE') }}
    WHERE PNL_CATEGORY = 'Revenue'
        AND SALES_DOCUMENT_TYPE = 'ZS10'
    GROUP BY
        CUSTOMER_REFERENCE
        ,CALENDAR_YEAR_MONTH
        ,SALES_DOCUMENT
        ,REFERENCE_DOCUMENT_NUMBER
)

,PO_INVOICED_SAP AS (
    SELECT
        PO
        ,LISTAGG(DISTINCT SALES_DOCUMENT, ' ,') AS ZS10_INVOICED
    FROM SAP_INVOICE
    GROUP BY PO
)

,OPEN_BILLABLE AS (
    SELECT
        CUSTOMER_PO
        ,LISTAGG(DISTINCT ZS10_SALES_ORDER, ' ,') AS OPEN_BILLABLE_ZS10
    FROM {{ ref('COMMON__REPORTS__SERVICE_OPEN_BILLABLE') }}
    WHERE LEN(CUSTOMER_PO)> 1
    GROUP BY CUSTOMER_PO
)
, CSSMAP as (
    SELECT
     PRIMARY_CONTACT AS PRIMARY_SERVICE_CONTACT
    ,PRIMARY_CONTACTID AS PRIMARY_SERVICE_CONTACT_ID
    ,SECONDARY_CONTACT AS SECONDARY_SERVICE_CONTACT
    ,SECONDARY_CONTACTID AS SECONDARY_SERVICE_CONTACT_ID
    ,CC_BU_KEY
FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_SITE_SERVICE_MANAGER_MAPPING') }}
)

,PO_DETAILS AS (
    SELECT
        CASE
            WHEN BUSINESS.CUSTOMER_GROUP IS NOT NULL THEN BUSINESS.CUSTOMER_GROUP
            WHEN TELQS_PO.BUSINESSISSUINGPO LIKE 'SAMSUNG AUSTIN%' OR  TELQS_PO.BUSINESSISSUINGPO = 'SAS' THEN 'Samsung'
            WHEN LEFT(TELQS_PO.BUSINESSISSUINGPO,3) = 'IBM'THEN 'GF/IBM/Albany'
            WHEN LEFT(TELQS_PO.BUSINESSISSUINGPO,5) IN ('INTEL', 'Intel') THEN 'Intel'
            WHEN LEFT(TELQS_PO.BUSINESSISSUINGPO,6) IN ('MICRON', 'Micron') THEN 'Micron'
            WHEN TELQS_PO.BUSINESSISSUINGPO LIKE 'TEXAS INSTRUMENT%' OR LEFT(TELQS_PO.BUSINESSISSUINGPO ,3) = 'TI/' THEN 'TI'
            WHEN TELQS_PO.BUSINESSISSUINGPO LIKE 'TOKYO ELECTRON EUROPE%'THEN 'TEL GROUP'
            WHEN TELQS_PO.BUSINESSISSUINGPO = 'TEL Groups' THEN 'TEL GROUP'
            ELSE 'Regional'
        END AS CUSTOMER_GROUP
        ,CASE
            WHEN BUSINESS.CUSTOMER IS NOT NULL THEN BUSINESS.CUSTOMER
            ELSE TRIM(SPLIT_PART(TELQS_PO.BUSINESSISSUINGPO, '(', 1))
        END AS CUSTOMER
        ,TELQS_PO.PO_STATUS
        ,TELQS_PO.PO_NUMBER
        ,TELQS_PO.QUOTE_NUMBER
        ,TELQS_PO.PRODUCT
        ,BUMAP.BU_GROUP AS LEGACY_BU
        ,TELQS_PO.PO_AMOUNT
        ,TELQS_PO.PO_DATE
        ,TELQS_PO.RECEIVED_DATE
        ,TELQS_PO.PO_DESCRIPTION
        ,TELQS_PO.FSB_COMMENTS
        ,TELQS_PO.WORK_START_DATE
        ,TELQS_PO.PLANNED_END_DATE
        ,TELQS_PO.WORK_ORDER
        ,BUSINESS.CUSTOMER_A_CODE
        ,CASE
            WHEN LEFT(TELQS_PO.BUSINESSISSUINGPOCODE,1) = 'B' THEN TELQS_PO.BUSINESSISSUINGPOCODE
            WHEN TELQS_PO.BUSINESSISSUINGPO LIKE 'SAMSUNG AUSTIN%'THEN 'BA2120300'
            WHEN TELQS_PO.BUSINESSISSUINGPO LIKE 'TOKYO ELECTRON EUROPE%'THEN 'BA0010300'
            WHEN FAB_B_CODE.CUSTOMER_CODE_B IS NOT NULL THEN FAB_B_CODE.CUSTOMER_CODE_B
            ELSE NULL
        END AS CUSTOMER_B_CODE
        ,CASE
            WHEN LEFT(TELQS_PO.FAB,1) = 'D' THEN TELQS_PO.FAB
            WHEN LEFT(NINEDIGIT.BUSINESS_PARTNER_NUMBER,1) = 'D' THEN NINEDIGIT.BUSINESS_PARTNER_NUMBER
            ELSE NULL
        END AS CUSTOMER_D_CODE
        ,TELQS_PO.BUSINESSISSUINGPO
        ,TELQS_PO.FAB
        ,CASE
            WHEN TELQS_PO.QUOTE_REQUESTOR_ID IS NOT NULL AND TELQSQUOTEREQ.FULLNAME IS NOT NULL THEN TELQSQUOTEREQ.FULLNAME
            WHEN QUOTEREQUESTOR.FULLNAME IS NOT NULL THEN QUOTEREQUESTOR.FULLNAME
            WHEN QUOTEREQEMPNAME.FULLNAME IS NOT NULL THEN QUOTEREQEMPNAME.FULLNAME
            WHEN LEN(TELQS_PO.QUOTEREQUESTOR)>1 THEN  '*'||TELQS_PO.QUOTEREQUESTOR
            ELSE NULL
        END AS QUOTE_REQUESTOR
        ,CASE
            WHEN TELQS_PO.QUOTE_SUPERVISOR_ID IS NOT NULL AND TELQSQUOTESUP.FULLNAME IS NOT NULL THEN TELQSQUOTESUP.FULLNAME
            WHEN QUOTEREQUESTORSUPERVISOR.FULLNAME IS NOT NULL THEN QUOTEREQUESTORSUPERVISOR.FULLNAME
            WHEN QUOTESUPEMPNAME.FULLNAME IS NOT NULL THEN QUOTESUPEMPNAME.FULLNAME
            WHEN LEN(TELQS_PO.QUOTESUPERVISOR) > 1 THEN  '*'||TELQS_PO.QUOTESUPERVISOR
            ELSE NULL
        END AS QUOTE_SUPERVISOR
        ,CASE
            WHEN TELQS_PO.SITE_SUPERVISOR_ID IS NOT NULL AND TELQSQUOTESITESUP.FULLNAME IS NOT NULL THEN TELQSQUOTESITESUP.FULLNAME
            WHEN QUOTESITESUPERVISOR.FULLNAME IS NOT NULL THEN QUOTESITESUPERVISOR.FULLNAME
            WHEN QUOTESITESUPEMPNAME.FULLNAME IS NOT NULL THEN QUOTESITESUPEMPNAME.FULLNAME
            WHEN LEN(TELQS_PO.SITESUPERVISOR) > 1 THEN  '*'||TELQS_PO.SITESUPERVISOR
            ELSE NULL
        END AS SITE_SUPERVISOR
        ,CASE
            WHEN PO_INVOICED_SAP.ZS10_INVOICED IS NOT NULL THEN 'Y'
            ELSE 'N'
        END PO_INVOICED_FLAG
        ,PO_INVOICED_SAP.ZS10_INVOICED
        ,CASE
            WHEN OPEN_BILLABLE.OPEN_BILLABLE_ZS10 IS NOT NULL THEN 'Y'
            ELSE 'N'
        END AS OPEN_BILLABLE_FLAG
        ,OPEN_BILLABLE.OPEN_BILLABLE_ZS10
        ,CASE
            WHEN PO_INVOICED_SAP.ZS10_INVOICED IS NOT NULL THEN 'N'
            WHEN OPEN_BILLABLE.OPEN_BILLABLE_ZS10 IS NOT NULL THEN 'N'
            WHEN TELQS_PO.RECEIVED_DATE > ADD_MONTHS(LAST_DAY(CURRENT_DATE),-1) THEN 'N'
            WHEN TELQS_PO.PO_STATUS <> 'Active' THEN 'N'
            WHEN TELQS_PO.TELQS_CUSTOMER LIKE 'TOKYO ELECTRON EUROPE%'THEN 'N'
            WHEN TELQS_PO.TELQS_CUSTOMERGROUP = 'TEL Groups' THEN 'N'
            ELSE 'Y'
        END AS CURRENT_BACKLOG_FLAG
        ,BU.SEGMENT_NAME
        ,FS_SEGMENT.SEGMENT_CODE_ORACLE
        ,FS_SEGMENT.SEGMENT_CODE_SAP
        ,TELQS_PO.TELQS_CUSTOMERGROUP
        ,TELQS_PO.TELQS_CUSTOMER
        ,TELQS_PO.TELQS_CUSTOMERCODE
        ,TELQS_PO.PO_STATUS_CODE
        ,TELQS_PO.ID
        ,TELQS_PO.PRODUCT2
        ,TELQS_PO.QUOTE_REQUESTOR_ID
        ,TELQS_PO.QUOTE_SUPERVISOR_ID
        ,TELQS_PO.SITE_SUPERVISOR_ID
        ,BUMAP.BU_GROUP
        ,BUMAP.BU_GROUP_LEADER
        ,BUMAP.BU_GROUP_LEADER_ID
        ,CSSMAP.PRIMARY_SERVICE_CONTACT
        ,CSSMAP.PRIMARY_SERVICE_CONTACT_ID
        ,CSSMAP.SECONDARY_SERVICE_CONTACT
        ,CSSMAP.SECONDARY_SERVICE_CONTACT_ID
    FROM TELQS_PO
    LEFT OUTER JOIN QUOTE
        ON TELQS_PO.QUOTE_NUMBER = QUOTE.QUOTENUMBER
    LEFT OUTER JOIN EMPLOYEE QUOTEREQUESTOR  --QUOTE  (Requestor)
        ON QUOTE.REQUESTOR_ID = QUOTEREQUESTOR.EMPLOYEEID
    LEFT OUTER JOIN EMPLOYEE TELQSQUOTEREQ  --TELQS ID  (Requestor)
        ON TELQS_PO.QUOTE_REQUESTOR_ID = TELQSQUOTEREQ.EMPLOYEEID
    LEFT OUTER JOIN EMPNAME QUOTEREQEMPNAME  --TELQS Name (Requestor)
        ON QUOTEREQEMPNAME.MAPPEDNAME = UPPER(TELQS_PO.QUOTEREQUESTOR)
    LEFT OUTER JOIN EMPLOYEE QUOTEREQUESTORSUPERVISOR   --QUOTE  (Requestor Supervisor)
        ON QUOTE.SUPERVISOR_ID = QUOTEREQUESTORSUPERVISOR.EMPLOYEEID
    LEFT OUTER JOIN EMPLOYEE TELQSQUOTESUP  --TELQS ID  (Requestor Supervisor)
        ON TELQS_PO.QUOTE_SUPERVISOR_ID = TELQSQUOTESUP.EMPLOYEEID
    LEFT OUTER JOIN EMPNAME QUOTESUPEMPNAME  --TELQS Name (Requestor Supervisor)
        ON QUOTESUPEMPNAME.MAPPEDNAME = UPPER(TELQS_PO.QUOTESUPERVISOR)
    LEFT OUTER JOIN EMPLOYEE QUOTESITESUPERVISOR    --QUOTE  (Site Supervisor)
        ON QUOTE.SITE_SUPERVISOR_ID = QUOTESITESUPERVISOR.EMPLOYEEID
    LEFT OUTER JOIN EMPLOYEE TELQSQUOTESITESUP  --TELQS ID  (Site Supervisor)
        ON TELQS_PO.SITE_SUPERVISOR_ID = TELQSQUOTESITESUP.EMPLOYEEID
    LEFT OUTER JOIN EMPNAME QUOTESITESUPEMPNAME    --TELQS Name (Site Supervisor)
        ON QUOTESITESUPEMPNAME.MAPPEDNAME = UPPER(TELQS_PO.SITESUPERVISOR)
    LEFT OUTER JOIN CUSTOMER BUSINESS
        ON TELQS_PO.BUSINESSISSUINGPOCODE = BUSINESS.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN CUSTOMER NINEDIGIT
        ON TELQS_PO.FAB = NINEDIGIT.IDENTIFICATION_NUMBER
    LEFT OUTER JOIN FAB_B_CODE
        ON TELQS_PO.FAB = FAB_B_CODE.CUSTOMER_CODE_D
    LEFT OUTER JOIN PO_INVOICED_SAP
        ON TELQS_PO.PO_NUMBER = PO_INVOICED_SAP.PO
    LEFT OUTER JOIN OPEN_BILLABLE
        ON TELQS_PO.PO_NUMBER = OPEN_BILLABLE.CUSTOMER_PO
    LEFT OUTER JOIN BU
        ON TELQS_PO.PRODUCT2 = BU.SAP_PRODUCT_CODE
    LEFT OUTER JOIN FS_SEGMENT
        ON FS_SEGMENT.ORACLE_DESCRIPTION = BU.SEGMENT_NAME
    LEFT JOIN  {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }} BUMAP
    ON TELQS_PO.PRODUCT = BUMAP.BU_SOURCE_KEY
    LEFT OUTER JOIN CSSMAP
    ON CSSMAP.CC_BU_KEY = (CUSTOMER_B_CODE||'_'||BUMAP.BU_GROUP)
),


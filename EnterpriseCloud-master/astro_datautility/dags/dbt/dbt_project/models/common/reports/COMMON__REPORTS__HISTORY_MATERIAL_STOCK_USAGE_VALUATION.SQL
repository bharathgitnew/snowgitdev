{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='HISTORY_MATERIAL_STOCK_USAGE_VALUATION',
    unique_key = ['SNAPSHOT_DATE'],
    post_hook = "
        UPDATE {{ this }} AS tgt
        SET 
            FINAL_VALUATION_PRICE = CAST(
                CASE
                    WHEN corrected.NEW_PRICE IS NULL THEN tgt.STANDARD_COST
                    ELSE corrected.NEW_PRICE
                END AS NUMBER(38,2)
            ),
            FINAL_TOTAL_COST = CAST(
                COALESCE(tgt.TOTAL_QUANTITY, 0) * CASE
                    WHEN corrected.NEW_PRICE IS NULL THEN tgt.STANDARD_COST
                    ELSE corrected.NEW_PRICE
                END AS NUMBER(38,2)
            )
        FROM (
            SELECT
                MATERIAL_NUMBER AS MATNR,
                CASE
                    WHEN MOVING_AVERAGE_PRICE = 0 THEN STANDARD_PRICE
                    ELSE MOVING_AVERAGE_PRICE
                END AS NEW_PRICE
            FROM {{ ref('COMMON__REPORTS__MATERIAL_VALUATION_HISTORY_TABLE') }}
            QUALIFY ROW_NUMBER() OVER (
                PARTITION BY MATERIAL_NUMBER
                ORDER BY CONCAT(FISCAL_YEAR_OF_CURRENT_PERIOD, ' ', CURRENT_PERIOD) DESC
            ) = 1
        ) AS corrected
        WHERE tgt.MATERIAL_NUMBER = corrected.MATNR
          AND tgt.SNAPSHOT_DATE = DATE_TRUNC('MONTH', CURRENT_DATE)::DATE
          AND CURRENT_DATE = (
              SELECT d
              FROM (
                  SELECT DATEADD(DAY, SEQ4(), DATE_TRUNC('MONTH', CURRENT_DATE))::DATE AS d
                  FROM TABLE(GENERATOR(ROWCOUNT => 14))
              )
              WHERE DAYOFWEEK(d) NOT IN (0, 6)
              QUALIFY ROW_NUMBER() OVER (ORDER BY d) = 3
          )
    "
) }}



WITH MBEWH_MARA_HISTORY AS (

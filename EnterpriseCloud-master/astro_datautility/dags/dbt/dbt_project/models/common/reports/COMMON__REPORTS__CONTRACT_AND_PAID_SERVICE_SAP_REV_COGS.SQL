WITH FINANCIALDETAIL AS (
    SELECT
        CALENDAR_YEAR_MONTH AS REPORT_PERIOD
        ,END_USER_GROUP
        ,END_USER_NAME
        ,COALESCE(END_USER,'-1') AS END_USER
        ,COALESCE(BAAN_OFFICE,'*Not Assigned') AS BAAN_OFFICE 
        ,SEGMENT
        ,SALES_DOCUMENT_TYPE_DESCRIPTION
        ,SALES_DOCUMENT||'_'||SALES_DOCUMENT_ITEM AS SALES_DOCUMENT_LINE
        ,SALES_CATEGORY
        ,SALES_CATEGORY_NAME
        ,PNL_CATEGORY
        ,CASE
            WHEN PNL_CATEGORY = 'Revenue' THEN (-1 * AMOUNT_IN_COMPANY_CODE_CURRENCY)
            ELSE 0
        END AS REVENUE
        ,CASE
            WHEN PNL_CATEGORY = 'COGS' THEN AMOUNT_IN_COMPANY_CODE_CURRENCY
            ELSE 0
        END AS COGS
        ,CONTRACT_NUMBER
        ,SERVICE_CRM_WO_NO
        ,PRODUCT_TYPE_NAME
        ,COALESCE(BAAN_SEGMENT_CODE,'-1') AS BAAN_SEGMENT_CODE
        ,COALESCE(BAAN_OFFICE_CODE,'-1') AS BAAN_OFFICE_CODE
        ,SEGMENT_CODE
        ,CASE
            WHEN SALES_CATEGORY_ORACLE IS NOT NULL AND LEN(SALES_CATEGORY_ORACLE)>1 THEN SALES_CATEGORY_ORACLE
            ELSE 'SAP_'||SALES_CATEGORY
        END AS SALES_CATEGORY_ORACLE
        ,SALES_DOCUMENT_TYPE
        ,SALES_DOCUMENT
        ,SALES_DOCUMENT_ITEM
        ,WBS_CATEGORY
        ,WBS_CATEGORY_NAME
        ,WBS_ELEMENT
        ,SAP_SERVICE_ORDER
        ,REFERENCE_DOCUMENT_NUMBER
        ,REFERENCE_DOCUMENT_LINE_ITEM
        ,CUSTOMER_REFERENCE
        ,MATERIAL_NUMBER
        ,MATERIAL_DESCRIPTION
        ,PRODUCT_TYPE_CATEGORY
        ,ITEM_TEXT
        ,BU_GROUP
        ,BU_GROUP_LEADER
        ,END_USER_GROUP2
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE') }}
    WHERE 1=1
        AND CALENDAR_YEAR_MONTH >= '2023-05'
        AND COMPANY_CODE = '3200'
        AND (SALES_CATEGORY_ORACLE IN ('CONTRA', 'PDSRV', 'SMSRV') OR LEN(CONTRACT_NUMBER)>1 )
)

,CONTRACT AS (
    SELECT DISTINCT
        CONTRACT_NUMBER
        ,CONTRACT_TITLE
        ,CONTRACT_END_DATE
        ,CONTRACT_TYPE
        ,CONTRACT_SCOPE_BY_PRODUCT
        ,BAAN_CONTRACT_NUMBER
    FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
)

,ZS10 AS (
    SELECT DISTINCT
        VBAK_SALES_DOCUMENT
        ,SERVICE_CRM_WO_NO AS CRM_WO_NO
        ,VBAK_SALES_DOCUMENT_TYPE
        ,CASE
            WHEN LEN(QUOTE_NO)> 1 THEN QUOTE_NO
            ELSE NULL
        END AS QUOTE
        ,CASE
            WHEN LEN(CUSTOMER_REQUEST_NO)>1 THEN CUSTOMER_REQUEST_NO
            ELSE NULL
        END AS BAAN_SO
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
    WHERE 1=1
        AND VBAK_SALES_DOCUMENT_TYPE = 'ZS10'
    QUALIFY row_number() over ( partition by VBAK_SALES_DOCUMENT order by SERVICE_CRM_WO_NO desc ) = 1
)

,CRMWO AS (
    SELECT DISTINCT
        MSDYN_NAME
        ,WO_WOTITLE
        ,LISTAGG(DISTINCT WO_PRODUCTSNNAME, ', ') AS MACHINE_SN
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
    GROUP BY ALL
    QUALIFY row_number() over ( partition by MSDYN_NAME order by WO_WOTITLE desc ) = 1
)

,BAANSO AS (
    SELECT
        SERVICE_ORDER_NO
        ,DESCRIPTION
        ,MIN(ACTIVITY_LINE) AS MIN_AL
    FROM {{ ref('COMMON__DE_TEL_REPORTING__BAANV_TEA_SERVICE_ORDERS') }}
    WHERE LEFT(SERVICE_ORDER_NO,3) = 'PDS'
    GROUP BY ALL
    QUALIFY row_number() over ( partition by SERVICE_ORDER_NO order by DESCRIPTION desc ) = 1
)

,COMBINED AS (
    SELECT
        FINANCIALDETAIL.REPORT_PERIOD
        ,CASE
            WHEN LEN(FINANCIALDETAIL.CONTRACT_NUMBER) > 1  THEN 'Contract'
            WHEN LEN(FINANCIALDETAIL.SERVICE_CRM_WO_NO) > 1  THEN 'Paid Service'
            WHEN SALES_CATEGORY_ORACLE = 'PDSRV' THEN 'Paid Service (Manually Assigned)'
            WHEN SALES_CATEGORY_ORACLE = 'CONTRA' THEN 'Contract (Manually Assigned)'
            WHEN SALES_CATEGORY_ORACLE = 'SMSRV' THEN 'Supplier Managed Service'
            ELSE NULL
        END AS SERVICE_TYPE
        ,CASE
            WHEN SERVICE_TYPE IN ('Contract', 'Contract (Manually Assigned)', 'Supplier Managed Service') THEN 'Contract'
            WHEN SERVICE_TYPE IN ('Paid Service', 'Paid Service (Manually Assigned)') THEN 'Paid Service'
            ELSE SERVICE_TYPE
        END AS SERVICE_TYPE_GROUP
        ,CASE
            WHEN FINANCIALDETAIL.END_USER = '-1' THEN '*No Customer Assigned'
            ELSE FINANCIALDETAIL.END_USER_GROUP
        END AS END_USER_GROUP
        ,CASE
            WHEN FINANCIALDETAIL.END_USER = '-1' THEN '*No Customer Assigned'
            ELSE FINANCIALDETAIL.END_USER_NAME
        END AS END_USER_NAME
        ,FINANCIALDETAIL.END_USER
        ,FINANCIALDETAIL.SEGMENT
        ,FINANCIALDETAIL.SALES_DOCUMENT_LINE
        ,FINANCIALDETAIL.SALES_CATEGORY
        ,FINANCIALDETAIL.SALES_CATEGORY_NAME
        ,FINANCIALDETAIL.REVENUE
        ,FINANCIALDETAIL.COGS
        ,CASE
            WHEN LEN(FINANCIALDETAIL.CONTRACT_NUMBER) > 1  THEN FINANCIALDETAIL.CONTRACT_NUMBER
            WHEN SALES_CATEGORY_ORACLE = 'CONTRA' THEN '*No Contract Assigned'
            WHEN SALES_CATEGORY_ORACLE = 'SMSRV' THEN 'Supplier Managed Service'
            WHEN FINANCIALDETAIL.SERVICE_CRM_WO_NO <>  'XXXXXXXX' AND FINANCIALDETAIL.SERVICE_CRM_WO_NO IS NOT NULL THEN FINANCIALDETAIL.SERVICE_CRM_WO_NO
            WHEN FINANCIALDETAIL.SERVICE_CRM_WO_NO = 'XXXXXXXX' AND LEFT(BAAN_SO,3) = 'PDS' THEN BAAN_SO
            WHEN FINANCIALDETAIL.SERVICE_CRM_WO_NO = 'XXXXXXXX' THEN '*No WO Assigned'
            WHEN SALES_CATEGORY_ORACLE = 'PDSRV' THEN '*No WO Assigned'
            ELSE NULL
        END AS PRIMARY_ORDER
        ,CASE
            WHEN LEN(FINANCIALDETAIL.CONTRACT_NUMBER) > 1  THEN CONTRACT.CONTRACT_TITLE
            WHEN SALES_CATEGORY_ORACLE = 'CONTRA' THEN '*No Contract Assigned'
            WHEN FINANCIALDETAIL.SERVICE_CRM_WO_NO <>  'XXXXXXXX' AND FINANCIALDETAIL.SERVICE_CRM_WO_NO IS NOT NULL THEN CRMWO.WO_WOTITLE
            WHEN FINANCIALDETAIL.SERVICE_CRM_WO_NO = 'XXXXXXXX' AND LEFT(ZS10.BAAN_SO,3) = 'PDS' THEN BAANSO.DESCRIPTION
            WHEN FINANCIALDETAIL.END_USER = 'BA0010300' AND FINANCIALDETAIL.SERVICE_CRM_WO_NO = 'XXXXXXXX' THEN 'TEE Work (No WO)'
            WHEN SALES_CATEGORY_ORACLE = 'PDSRV' THEN '*No WO Assigned'
            ELSE '*No Primary Order Ref'
        END AS PRIMARY_ORDER_DESCRIPTION
        ,CASE
            WHEN LEFT(BAAN_CONTRACT_NUMBER,2) IN ('CN', 'BN','RC') THEN BAAN_CONTRACT_NUMBER
            WHEN LEFT(ZS10.BAAN_SO,3) = 'PDS' THEN BAAN_SO
            ELSE'*No Primary Order Ref'
        END AS BAAN_RELATED_ORDER
        ,FINANCIALDETAIL.CONTRACT_NUMBER
        ,CONTRACT.CONTRACT_TITLE
        ,CASE
            WHEN LEN(FINANCIALDETAIL.SERVICE_CRM_WO_NO) > 1 THEN FINANCIALDETAIL.SERVICE_CRM_WO_NO
            ELSE NULL
        END AS SERVICE_CRM_WO_NO
        ,CASE
            WHEN LEN(FINANCIALDETAIL.PRODUCT_TYPE_NAME) >1 THEN FINANCIALDETAIL.PRODUCT_TYPE_NAME
            ELSE FINANCIALDETAIL.SALES_CATEGORY_ORACLE
        END AS PRODUCT_TYPE_NAME
        ,FINANCIALDETAIL.BAAN_OFFICE_CODE
        ,FINANCIALDETAIL.BAAN_SEGMENT_CODE
        ,FINANCIALDETAIL.SEGMENT_CODE
        ,FINANCIALDETAIL.SALES_CATEGORY_ORACLE
        ,FINANCIALDETAIL.SALES_DOCUMENT_TYPE
        ,FINANCIALDETAIL.SALES_DOCUMENT
        ,FINANCIALDETAIL.SALES_DOCUMENT_ITEM
        ,FINANCIALDETAIL.BAAN_OFFICE
        ,CONTRACT.CONTRACT_END_DATE
        ,CONTRACT.CONTRACT_TYPE
        ,FINANCIALDETAIL.WBS_CATEGORY
        ,FINANCIALDETAIL.WBS_CATEGORY_NAME
        ,FINANCIALDETAIL.WBS_ELEMENT
        ,FINANCIALDETAIL.SAP_SERVICE_ORDER
        ,FINANCIALDETAIL.REFERENCE_DOCUMENT_NUMBER
        ,FINANCIALDETAIL.REFERENCE_DOCUMENT_LINE_ITEM
        ,FINANCIALDETAIL.CUSTOMER_REFERENCE
        ,FINANCIALDETAIL.MATERIAL_NUMBER
        ,FINANCIALDETAIL.MATERIAL_DESCRIPTION
        ,CASE
            WHEN LEN(FINANCIALDETAIL.PRODUCT_TYPE_CATEGORY) >1 THEN  FINANCIALDETAIL.PRODUCT_TYPE_CATEGORY
            ELSE 'Other -'||FINANCIALDETAIL.SALES_CATEGORY_ORACLE
        END AS CATEGORY
        ,CRMWO.WO_WOTITLE AS WO_TITLE
        ,CRMWO.MACHINE_SN
        ,FINANCIALDETAIL.ITEM_TEXT
        ,CASE
            WHEN FINANCIALDETAIL.SALES_CATEGORY_ORACLE IN ('CONTRA', 'PDSRV', 'TSCREM','TSCSTD', 'SMSRV') THEN 'External Service'
            WHEN FINANCIALDETAIL.SALES_CATEGORY_ORACLE IN ('SPAREC') THEN 'External Parts'
            WHEN FINANCIALDETAIL.SALES_CATEGORY IN ('98','99') OR FINANCIALDETAIL.SALES_CATEGORY IS NULL THEN '*Not Included'
            ELSE '*Value Needs Mapping'
        END AS FBR_REPORT_FLAG
        ,FINANCIALDETAIL.BU_GROUP
        ,FINANCIALDETAIL.BU_GROUP_LEADER
        ,FINANCIALDETAIL.END_USER_GROUP2
    FROM FINANCIALDETAIL
    LEFT OUTER JOIN CONTRACT
    ON FINANCIALDETAIL.CONTRACT_NUMBER = CONTRACT.CONTRACT_NUMBER
    LEFT OUTER JOIN ZS10
    ON FINANCIALDETAIL.SALES_DOCUMENT  = ZS10.VBAK_SALES_DOCUMENT
    LEFT OUTER JOIN CRMWO
    ON FINANCIALDETAIL.SERVICE_CRM_WO_NO = CRMWO.MSDYN_NAME
    LEFT OUTER JOIN BAANSO
    ON BAANSO.SERVICE_ORDER_NO = ZS10.BAAN_SO
)

,SOURCE AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        ,SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
        ,REPORT_PERIOD
        ,CATEGORY
        ,SERVICE_TYPE
        ,SERVICE_TYPE_GROUP
        ,END_USER_GROUP
        ,END_USER_NAME
        ,BAAN_OFFICE
        ,SEGMENT
        ,PRODUCT_TYPE_NAME
        ,SALES_CATEGORY_ORACLE
        ,PRIMARY_ORDER
        ,PRIMARY_ORDER_DESCRIPTION
        ,SUM(REVENUE) AS REVENUE
        ,SUM(COGS) AS COGS
        ,SALES_DOCUMENT_LINE
        ,SALES_CATEGORY
        ,SALES_CATEGORY_NAME
        ,SALES_DOCUMENT_TYPE
        ,SAP_SERVICE_ORDER
        ,END_USER
        ,WBS_CATEGORY
        ,WBS_CATEGORY_NAME
        ,WBS_ELEMENT
        ,MATERIAL_NUMBER
        ,MATERIAL_DESCRIPTION
        ,MACHINE_SN
        ,CONTRACT_NUMBER
        ,CONTRACT_TITLE
        ,SERVICE_CRM_WO_NO
        ,WO_TITLE
        ,BAAN_RELATED_ORDER
        ,CONTRACT_END_DATE
        ,CONTRACT_TYPE
        ,BAAN_OFFICE_CODE
        ,BAAN_SEGMENT_CODE
        ,SEGMENT_CODE
        ,SALES_DOCUMENT
        ,SALES_DOCUMENT_ITEM
        ,REFERENCE_DOCUMENT_NUMBER
        ,CUSTOMER_REFERENCE
        ,ITEM_TEXT
        ,FBR_REPORT_FLAG
        ,BU_GROUP
        ,BU_GROUP_LEADER
        ,END_USER_GROUP2
    FROM COMBINED
    GROUP BY ALL
)

,TRANSFORM AS (
    SELECT
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
        ,cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
        ,REPORT_PERIOD
        ,CATEGORY
        ,SERVICE_TYPE
        ,SERVICE_TYPE_GROUP
        ,END_USER_GROUP
        ,END_USER_NAME
        ,BAAN_OFFICE
        ,SEGMENT
        ,PRODUCT_TYPE_NAME
        ,SALES_CATEGORY_ORACLE
        ,PRIMARY_ORDER
        ,PRIMARY_ORDER_DESCRIPTION
        ,CAST(REVENUE as NUMBER(38,2)) AS REVENUE
        ,CAST(COGS as NUMBER(38,2)) AS COGS
        ,SALES_DOCUMENT_LINE
        ,SALES_CATEGORY
        ,SALES_CATEGORY_NAME
        ,SALES_DOCUMENT_TYPE
        ,SAP_SERVICE_ORDER
        ,END_USER
        ,WBS_CATEGORY
        ,WBS_CATEGORY_NAME
        ,WBS_ELEMENT
        ,MATERIAL_NUMBER
        ,MATERIAL_DESCRIPTION
        ,MACHINE_SN
        ,CONTRACT_NUMBER
        ,CONTRACT_TITLE
        ,SERVICE_CRM_WO_NO
        ,WO_TITLE
        ,BAAN_RELATED_ORDER
        ,CAST(CONTRACT_END_DATE as DATE) AS CONTRACT_END_DATE
        ,CONTRACT_TYPE
        ,BAAN_OFFICE_CODE
        ,BAAN_SEGMENT_CODE
        ,SEGMENT_CODE
        ,SALES_DOCUMENT
        ,SALES_DOCUMENT_ITEM
        ,REFERENCE_DOCUMENT_NUMBER
        ,CUSTOMER_REFERENCE
        ,ITEM_TEXT
        ,FBR_REPORT_FLAG
        ,BU_GROUP
        ,BU_GROUP_LEADER
        ,END_USER_GROUP2
    FROM SOURCE 
)

SELECT * FROM TRANSFORM
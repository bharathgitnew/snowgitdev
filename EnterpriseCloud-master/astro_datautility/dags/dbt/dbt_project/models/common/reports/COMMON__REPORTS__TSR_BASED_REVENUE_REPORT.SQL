{{ config(
        alias = 'TSR_BASED_REVENUE_REPORT',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        tags=["finance"],
        transient = false
) }}

WITH REVENUE AS (
    SELECT
        CALENDAR_YEAR_MONTH AS REPORT_PERIOD,
        END_USER_GROUP,
        END_USER_NAME,
        END_USER,
        BAAN_OFFICE,
        SEGMENT,
        SALES_DOCUMENT_TYPE_DESCRIPTION,
        SALES_DOCUMENT || '_' || SALES_DOCUMENT_ITEM AS SALES_DOCUMENT_LINE,
        SALES_CATEGORY,
        SALES_CATEGORY_NAME,
        PNL_CATEGORY,(-1 * SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY)) AS AMOUNT,
        CONTRACT_NUMBER,
        SERVICE_CRM_WO_NO AS PAID_SERVICE_WO,
        PRODUCT_TYPE_NAME,
        BAAN_OFFICE_CODE,
        BAAN_SEGMENT_CODE,
        SEGMENT_CODE,
        SALES_CATEGORY_ORACLE,
        SALES_DOCUMENT_TYPE,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        CUSTOMER_REFERENCE,
        BU_GROUP,
        BU_GROUP_LEADER,
        END_USER_GROUP2
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE') }}
    WHERE
        CALENDAR_YEAR_MONTH >= '2023-05'
        AND COMPANY_CODE = '3200'
        AND SALES_CATEGORY_ORACLE IN ('CONTRA', 'PDSRV')
        AND PNL_CATEGORY = 'Revenue'
    GROUP BY
        CALENDAR_YEAR_MONTH,
        END_USER_GROUP,
        END_USER_NAME,
        END_USER,
        BAAN_OFFICE,
        SEGMENT,
        SALES_DOCUMENT_TYPE_DESCRIPTION,
        SALES_DOCUMENT || '_' || SALES_DOCUMENT_ITEM,
        SALES_CATEGORY,
        SALES_CATEGORY_NAME,
        PNL_CATEGORY,
        CONTRACT_NUMBER,
        SERVICE_CRM_WO_NO,
        PRODUCT_TYPE_NAME,
        BAAN_OFFICE_CODE,
        BAAN_SEGMENT_CODE,
        SEGMENT_CODE,
        SALES_CATEGORY_ORACLE,
        SALES_DOCUMENT_TYPE,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        CUSTOMER_REFERENCE,
        BU_GROUP,
        BU_GROUP_LEADER,
        END_USER_GROUP2
    HAVING (-1 * SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY)) <> 0
),
CONTRACT AS (
    SELECT
        DISTINCT CONTRACT_NUMBER,
        CONTRACT_TITLE,
        CONTRACT_END_DATE,
        CONTRACT_TYPE,
        CONTRACT_SCOPE_BY_PRODUCT,
        BAAN_CONTRACT_NUMBER
    FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
),
ZS10 AS (
    SELECT
        DISTINCT VBAK_SALES_DOCUMENT,
        SERVICE_CRM_WO_NO AS CRM_WO_NO,
        VBAK_SALES_DOCUMENT_TYPE,
        CASE
            WHEN LEN(QUOTE_NO) > 1 THEN QUOTE_NO
            ELSE NULL
        END AS QUOTE,
        CASE
            WHEN LEN(CUSTOMER_REQUEST_NO) > 1 THEN CUSTOMER_REQUEST_NO
            ELSE NULL
        END AS BAAN_SO
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE = 'ZS10'
),
SOURCE AS (
    SELECT
        REVENUE.REPORT_PERIOD,
        CASE
            WHEN LEN(REVENUE.CONTRACT_NUMBER) > 1 THEN 'BOH Contract'
            WHEN LEN(REVENUE.PAID_SERVICE_WO) > 1 THEN 'Paid Service'
            ELSE NULL
        END AS SERVICE_TYPE,
        REVENUE.END_USER_GROUP,
        REVENUE.END_USER_NAME,
        REVENUE.END_USER,
        REVENUE.SEGMENT,
        REVENUE.SALES_DOCUMENT_LINE,
        REVENUE.SALES_CATEGORY,
        REVENUE.SALES_CATEGORY_NAME,
        REVENUE.AMOUNT AS REVENUE_AMOUNT,
        CASE
            WHEN LEN(REVENUE.CONTRACT_NUMBER) > 1 THEN REVENUE.CONTRACT_NUMBER
            ELSE REVENUE.PAID_SERVICE_WO
        END AS RELATED_ORDER,
        CASE
            WHEN LEFT(BAAN_CONTRACT_NUMBER, 2) IN ('CN', 'BN', 'RC') THEN BAAN_CONTRACT_NUMBER
            WHEN LEFT(BAAN_SO, 3) = 'PDS' THEN BAAN_SO
            ELSE NULL
        END AS BAAN_RELATED_ORDER,
        REVENUE.CONTRACT_NUMBER,
        CONTRACT.CONTRACT_TITLE,
        CASE
            WHEN LEN(REVENUE.PAID_SERVICE_WO) > 1 THEN REVENUE.PAID_SERVICE_WO
            ELSE NULL
        END AS PAID_SERVICE_WO,
        REVENUE.PRODUCT_TYPE_NAME,
        REVENUE.BAAN_SEGMENT_CODE,
        REVENUE.SEGMENT_CODE,
        REVENUE.SALES_CATEGORY_ORACLE,
        REVENUE.SALES_DOCUMENT_TYPE,
        REVENUE.SALES_DOCUMENT,
        REVENUE.SALES_DOCUMENT_ITEM,
        REVENUE.BAAN_OFFICE,
        CONTRACT.CONTRACT_END_DATE,
        CONTRACT.CONTRACT_TYPE,
        REVENUE.CUSTOMER_REFERENCE AS CUSTOMER_REFERENCE,
        REVENUE.BU_GROUP,
        REVENUE.BU_GROUP_LEADER,
        REVENUE.END_USER_GROUP2,
    FROM REVENUE
    LEFT OUTER JOIN CONTRACT ON REVENUE.CONTRACT_NUMBER = CONTRACT.CONTRACT_NUMBER
    LEFT OUTER JOIN ZS10 ON REVENUE.SALES_DOCUMENT = ZS10.VBAK_SALES_DOCUMENT
    WHERE LEN(REVENUE.PAID_SERVICE_WO) > 1
        OR CONTRACT_TYPE = 'BOH'
),

transform_data as (
    select 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH ,-- Adds column to table on full refresh.
        REPORT_PERIOD,
        SERVICE_TYPE,
        END_USER_GROUP,
        END_USER_NAME,
        END_USER,
        SEGMENT,
        SALES_DOCUMENT_LINE,
        SALES_CATEGORY,
        SALES_CATEGORY_NAME,
        REVENUE_AMOUNT,
        RELATED_ORDER,
        BAAN_RELATED_ORDER,
        CONTRACT_NUMBER,
        CONTRACT_TITLE,
        PAID_SERVICE_WO,
        PRODUCT_TYPE_NAME,
        BAAN_SEGMENT_CODE,
        SEGMENT_CODE,
        SALES_CATEGORY_ORACLE,
        SALES_DOCUMENT_TYPE,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        BAAN_OFFICE,
        CONTRACT_END_DATE,
        CONTRACT_TYPE,
        CUSTOMER_REFERENCE,
        BU_GROUP,
        BU_GROUP_LEADER,
        END_USER_GROUP2
    from SOURCE
),

type_data AS (
    SELECT
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        REPORT_PERIOD,
        SERVICE_TYPE,
        END_USER_GROUP,
        END_USER_NAME,
        END_USER,
        SEGMENT,
        SALES_DOCUMENT_LINE,
        SALES_CATEGORY,
        SALES_CATEGORY_NAME,
        CAST(REVENUE_AMOUNT as NUMBER(38, 2)) AS REVENUE_AMOUNT,
        RELATED_ORDER,
        BAAN_RELATED_ORDER,
        CONTRACT_NUMBER,
        CONTRACT_TITLE,
        PAID_SERVICE_WO,
        PRODUCT_TYPE_NAME,
        BAAN_SEGMENT_CODE,
        SEGMENT_CODE,
        SALES_CATEGORY_ORACLE,
        SALES_DOCUMENT_TYPE,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        BAAN_OFFICE,
        CAST(CONTRACT_END_DATE as DATE) AS CONTRACT_END_DATE,
        CONTRACT_TYPE,
        CUSTOMER_REFERENCE,
        BU_GROUP,
        BU_GROUP_LEADER,
        END_USER_GROUP2
    FROM transform_data
)

select * from type_data
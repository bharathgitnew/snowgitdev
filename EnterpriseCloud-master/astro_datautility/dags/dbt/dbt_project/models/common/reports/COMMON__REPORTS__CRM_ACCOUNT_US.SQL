WITH CRMACCOUNT AS (
    SELECT
        ACCOUNTNUMBER AS ACCOUNT_NUMBER,
        LEFT(ACCOUNTNUMBER, 1) AS ACCOUNT_NUMBER_SERIES,
        NAME,
        COM_COMPANY_E_NAME AS CUSTOMER_NAME,
        COM_COMPANY_NAME,
        COM_COMPANY_SHORT_NAME,
        TEL_COM_OLD_CUSTOMER_CODE AS OLD_CUSTOMER_CODE,
        ADDRESS2_LINE1 AS ADDRESS_LINE1,
        ADDRESS2_LINE2 AS ADDRESS_LINE2,
        ADDRESS2_CITY AS CITY,
        ADDRESS2_STATEORPROVINCE AS STATEORPROVINCE,
        ADDRESS2_POSTALCODE AS POSTALCODE,
        COM_ADDRESS2 AS COMPLETE_ADDRESS,
        COM_COUNTRY_NAMENAME AS COUNTRY,
        COM_GROUP_REGION_CD,
        COM_REGION,
        STATUSCODE,
        BUSINESSTYPECODE,
        TEL_COM_SOLD_TO_PARTY_FLAG,
        TEL_COM_SUPPLIER_FLAG,
        ID AS ACCOUNT_ID,
        PARENTACCOUNTIDNAME AS PARENT_ACCOUNT_NAME,
        PARENTACCOUNTID AS PARENT_ACCOUNT_ID
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }}
    WHERE LEFT(ACCOUNTNUMBER, 1) IN ('A', 'B', 'C', 'D')
),

ACCOUNTNUMBER AS (
    SELECT
        ACCOUNTNUMBER,
        ID,
        TEL_COM_OLD_CUSTOMER_CODE
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }}
),

B_PARENT AS (
    SELECT
        CRMACCOUNT.ACCOUNT_NUMBER AS ACCOUNT_NUMBER_B,
        ACCOUNTNUMBER.ACCOUNTNUMBER AS ACCOUNT_NUMBER_A,
        CRMACCOUNT.PARENT_ACCOUNT_ID AS ACCOUNT_ID_A,
        CASE
            WHEN CRMACCOUNT.COM_REGION = '9b639312-78a5-e711-8100-480fcff2c651' THEN 'Y'
            WHEN CRMACCOUNT.COUNTRY = 'USA' THEN 'Y'
            ELSE 'N'
        END AS NORTH_AMERICAN_CUSTOMER
    FROM CRMACCOUNT
    LEFT OUTER JOIN ACCOUNTNUMBER ON CRMACCOUNT.PARENT_ACCOUNT_ID = ACCOUNTNUMBER.ID
    WHERE CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'B'
),

NA_ACODE AS (
    SELECT
        DISTINCT ACCOUNT_NUMBER_A,
        NORTH_AMERICAN_CUSTOMER
    FROM B_PARENT
    WHERE NORTH_AMERICAN_CUSTOMER = 'Y'
),

COMBINED AS (
    SELECT
        CRMACCOUNT.ACCOUNT_NUMBER,
        CRMACCOUNT.ACCOUNT_ID,
        CASE
            WHEN CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'A' THEN CRMACCOUNT.ACCOUNT_NUMBER
            ELSE ACCOUNTNUMBER.ACCOUNTNUMBER
        END AS PARENT_ACCOUNT_NUMBER,
        CASE
            WHEN CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'A' THEN CRMACCOUNT.ACCOUNT_NUMBER
            ELSE B_PARENT.ACCOUNT_NUMBER_A
        END AS ACCOUNT_NUMBER_A,
        CASE
            WHEN NA_ACODE.NORTH_AMERICAN_CUSTOMER IS NOT NULL THEN NA_ACODE.NORTH_AMERICAN_CUSTOMER
            WHEN B_PARENT.NORTH_AMERICAN_CUSTOMER IS NOT NULL THEN B_PARENT.NORTH_AMERICAN_CUSTOMER
            WHEN CRMACCOUNT.COM_REGION = '9b639312-78a5-e711-8100-480fcff2c651' THEN 'Y'
            WHEN CRMACCOUNT.COUNTRY = 'USA' THEN 'Y'
            ELSE 'N'
        END AS NORTH_AMERICAN_CUSTOMER
    FROM CRMACCOUNT
    LEFT OUTER JOIN ACCOUNTNUMBER ON CRMACCOUNT.PARENT_ACCOUNT_ID = ACCOUNTNUMBER.ID
    LEFT OUTER JOIN B_PARENT ON ACCOUNTNUMBER.ACCOUNTNUMBER = B_PARENT.ACCOUNT_NUMBER_B
    LEFT OUTER JOIN NA_ACODE ON NA_ACODE.ACCOUNT_NUMBER_A = CRMACCOUNT.ACCOUNT_NUMBER
),

SAPCUSTOMER AS (
    SELECT
        BUSINESS_PARTNER_NUMBER,
        CORPORATION_NAME AS SAP_CORPORATION_NAME,
        CORPORATION AS SAP_CORPORATION,
        EXTENDED_TO_COMPANY_3200_ADJ
    FROM {{ ref('COMMON__SAPH__SAP_CUSTOMER') }}
),

SALES_REGION AS (
    SELECT
        ACCOUNT_NUMBER,
        SALES_REGION
    FROM {{ ref('COMMON__DE_SALES_OPERATIONS__SALES_CRM_SALES_REGION') }}
),

WISDOM_B AS (
    SELECT
        DISTINCT CUSTOMER_CODE_B
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE INSTALL_BASE_STATUS <> 'Inactive Tool'
),

WISDOM_D AS (
    SELECT
        DISTINCT CUSTOMER_CODE_D
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE INSTALL_BASE_STATUS <> 'Inactive Tool'
),

USCRMACCOUNT AS (
    SELECT
        cgm.CUSTOMER_GROUP,
        cgm.CUSTOMER_GROUP2,
        CRMACCOUNT.ACCOUNT_NUMBER_SERIES,
        CRMACCOUNT.ACCOUNT_NUMBER,
        CRMACCOUNT.NAME AS CUSTOMER_DISPLAY_NAME,
        CRMACCOUNT.CUSTOMER_NAME,
        COALESCE(SAPCUSTOMER.EXTENDED_TO_COMPANY_3200_ADJ, 'N') AS EXTENDED_TO_SAP_3200,
        CASE
            WHEN WISDOM_B.CUSTOMER_CODE_B IS NOT NULL THEN 'Y'
            WHEN WISDOM_D.CUSTOMER_CODE_D IS NOT NULL THEN 'Y'
            ELSE 'N'
        END AS MACHINES_IN_WISDOM_FLAG,
        CRMACCOUNT.COM_COMPANY_NAME AS COMPANY_NAME,
        CRMACCOUNT.COM_COMPANY_SHORT_NAME AS COMPANY_SHORT_NAME,
        CRMACCOUNT.OLD_CUSTOMER_CODE,
        SAPCUSTOMER.SAP_CORPORATION_NAME,
        SAPCUSTOMER.SAP_CORPORATION,
        CRMACCOUNT.ADDRESS_LINE1,
        CRMACCOUNT.ADDRESS_LINE2,
        CRMACCOUNT.CITY,
        CRMACCOUNT.STATEORPROVINCE,
        CRMACCOUNT.POSTALCODE,
        CRMACCOUNT.COUNTRY,
        CASE
            WHEN LEFT(CRMACCOUNT.ACCOUNT_NUMBER, 1) = 'A' THEN CRMACCOUNT.ACCOUNT_NUMBER
            ELSE COMBINED.PARENT_ACCOUNT_NUMBER
        END AS new_PARENT_ACCOUNT_NUMBER,
        CASE
            WHEN CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'A' THEN CRMACCOUNT.CUSTOMER_NAME
            ELSE CRMACCOUNT.PARENT_ACCOUNT_NAME
        END AS PARENT_ACCOUNT_NAME,
        CASE
            WHEN CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'A' THEN CRMACCOUNT.ACCOUNT_NUMBER
            WHEN CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'B' THEN COMBINED.PARENT_ACCOUNT_NUMBER
            ELSE COMBINED.ACCOUNT_NUMBER_A
        END AS CORPORATION_CODE,
        COMBINED.NORTH_AMERICAN_CUSTOMER,
        SALES_REGION.SALES_REGION,
        CRMACCOUNT.TEL_COM_SOLD_TO_PARTY_FLAG,
        CRMACCOUNT.TEL_COM_SUPPLIER_FLAG,
        CRMACCOUNT.COMPLETE_ADDRESS,
        CRMACCOUNT.COM_GROUP_REGION_CD,
        CRMACCOUNT.STATUSCODE,
        CRMACCOUNT.BUSINESSTYPECODE,
        CRMACCOUNT.COM_REGION,
        CRMACCOUNT.ACCOUNT_ID,
        CRMACCOUNT.PARENT_ACCOUNT_ID
    FROM CRMACCOUNT
    LEFT OUTER JOIN COMBINED ON CRMACCOUNT.ACCOUNT_NUMBER = COMBINED.ACCOUNT_NUMBER
    LEFT OUTER JOIN SAPCUSTOMER ON CRMACCOUNT.ACCOUNT_NUMBER = SAPCUSTOMER.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN SALES_REGION ON CRMACCOUNT.ACCOUNT_NUMBER = SALES_REGION.ACCOUNT_NUMBER
    LEFT OUTER JOIN WISDOM_B ON CRMACCOUNT.ACCOUNT_NUMBER = WISDOM_B.CUSTOMER_CODE_B
    LEFT OUTER JOIN WISDOM_D ON CRMACCOUNT.ACCOUNT_NUMBER = WISDOM_D.CUSTOMER_CODE_D
    LEFT JOIN {{ ref('ODS__SHAREPOINT__CUSTOMER_GROUP_MAPPING') }} AS cgm ON cgm.ACCOUNT_NUMBER = coalesce(new_PARENT_ACCOUNT_NUMBER, CRMACCOUNT.ACCOUNT_NUMBER)
    WHERE COMBINED.NORTH_AMERICAN_CUSTOMER = 'Y'
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        CUSTOMER_GROUP,
        CUSTOMER_GROUP2,
        ACCOUNT_NUMBER_SERIES,
        ACCOUNT_NUMBER,
        CUSTOMER_DISPLAY_NAME,
        CUSTOMER_NAME,
        EXTENDED_TO_SAP_3200,
        MACHINES_IN_WISDOM_FLAG,
        COMPANY_NAME,
        COMPANY_SHORT_NAME,
        OLD_CUSTOMER_CODE,
        SAP_CORPORATION_NAME,
        SAP_CORPORATION,
        ADDRESS_LINE1,
        ADDRESS_LINE2,
        CITY,
        STATEORPROVINCE,
        POSTALCODE,
        COUNTRY,
        new_PARENT_ACCOUNT_NUMBER as PARENT_ACCOUNT_NUMBER,
        PARENT_ACCOUNT_NAME,
        CORPORATION_CODE,
        NORTH_AMERICAN_CUSTOMER,
        SALES_REGION,
        TEL_COM_SOLD_TO_PARTY_FLAG,
        TEL_COM_SUPPLIER_FLAG,
        COMPLETE_ADDRESS,
        COM_GROUP_REGION_CD,
        STATUSCODE,
        BUSINESSTYPECODE,
        COM_REGION,
        ACCOUNT_ID,
        PARENT_ACCOUNT_ID
    from USCRMACCOUNT
),

type_data as (
    select
        _AUDIT_LOG_ID,
        _ROW_HASH,
        CUSTOMER_GROUP,
        CUSTOMER_GROUP2,
        ACCOUNT_NUMBER_SERIES,
        ACCOUNT_NUMBER,
        CUSTOMER_DISPLAY_NAME,
        CUSTOMER_NAME,
        EXTENDED_TO_SAP_3200,
        MACHINES_IN_WISDOM_FLAG,
        COMPANY_NAME,
        COMPANY_SHORT_NAME,
        OLD_CUSTOMER_CODE,
        SAP_CORPORATION_NAME,
        SAP_CORPORATION,
        ADDRESS_LINE1,
        ADDRESS_LINE2,
        CITY,
        STATEORPROVINCE,
        POSTALCODE,
        COUNTRY,
        PARENT_ACCOUNT_NUMBER,
        PARENT_ACCOUNT_NAME,
        CORPORATION_CODE,
        NORTH_AMERICAN_CUSTOMER,
        SALES_REGION,
        cast(TEL_COM_SOLD_TO_PARTY_FLAG as VARCHAR(16777216)) as TEL_COM_SOLD_TO_PARTY_FLAG,
        cast(TEL_COM_SUPPLIER_FLAG as VARCHAR(16777216)) as TEL_COM_SUPPLIER_FLAG,
        COMPLETE_ADDRESS,
        COM_GROUP_REGION_CD,
        cast(STATUSCODE as VARCHAR(16777216)) as STATUSCODE,
        cast(BUSINESSTYPECODE as VARCHAR(16777216)) as BUSINESSTYPECODE,
        COM_REGION,
        ACCOUNT_ID,
        PARENT_ACCOUNT_ID
    from transform_data
)

select * from type_data
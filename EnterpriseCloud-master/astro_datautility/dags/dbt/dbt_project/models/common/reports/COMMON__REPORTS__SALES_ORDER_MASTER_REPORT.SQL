WITH
-- Negative Doc Types
-- 
-- Support CTE used to transform lines with "return" sales document types into
-- negative amounts and quantities.
NEGATIVE_DOC_TYPES AS (
    SELECT SALES_DOC_TYPE, -1 AS COEF
    FROM (VALUES ('ZPR0'), ('ZPR2'), ('ZRR0'), ('ZSR0'), ('ZSR1'), ('ZER0')) AS X(SALES_DOC_TYPE)
),
-- Sales Order Bill
--
-- Aggregation of billing information based on the Sales Order Line
SOLB AS (
    SELECT 
        VBRP.AUBEL || VBRP.AUPOS AS SO_ID,
        SUM(VBRP.FKIMG) AS BILLED_QTY,
        SUM(VBRP.NETWR) AS BILLING_AMOUNT
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU015_VBRP') }} AS VBRP
    GROUP BY VBRP.AUBEL || VBRP.AUPOS 
),
-- Delivery Aggregation
--
-- Aggregation of delivery information based on the Sales Order Line
DLVR AS (
    SELECT
        LIPS.VGBEL || LIPS.VGPOS AS SO_ID,
        -- Count LIPS rows where RMA number is populated.
        SUM(CASE WHEN NULLIF(LIPS.ZZRNZZ, '') IS NOT NULL THEN 1 ELSE 0 END) AS RMA_COUNT,
        MAX(LIKP.WADATIST) AS SHIP_DATE,
        SUM(LIPS.LFIMG) AS DO_LINE_QTY_SUM,
        CASE WHEN MIN(LIPS.VBELN) = MAX(LIPS.VBELN) THEN MAX(LIPS.VBELN) ELSE 'Multiple DO IDs' END AS DO_ID
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU013_LIPS') }} AS LIPS
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU012_LIKP') }} AS LIKP ON (
        LIKP.VBELN = LIPS.VBELN
    )
    GROUP BY LIPS.VGBEL || LIPS.VGPOS
),
-- SOSL: Sales Order Schedule Line Aggregate 
SOSL AS (
    SELECT
        VBEP_SALES_DOCUMENT||VBEP_SALES_DOCUMENT_ITEM as SO_ID,
        SUM(DELIVERED_QUANTITY_DLVQTY_SU) AS delivered_quantity,
        SUM(CONFIRMED_QUANTITY) AS confirmed_quantity,
        MIN(SCHEDULE_LINE_DATE_EDATU) AS MIN_SCHEDULE_LINE_DATE,
        MAX(SCHEDULE_LINE_DATE_EDATU) AS MAX_SCHEDULE_LINE_DATE
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_SCHEDULE_LINE') }}
    GROUP BY VBEP_SALES_DOCUMENT||VBEP_SALES_DOCUMENT_ITEM
),
SOURCE_DATA AS (
    SELECT 
        VBAP.VBELN || VBAP.POSNR AS SO_ID,
        VBAP.VBELN AS SALES_ORDER_HEADER_NUMBER,
        VBAP.POSNR AS SALES_ORDER_LINE_NUMBER,
        DLVR.DO_ID AS DELIVERY_ORDER_HEADER_NUMBER,
        VBAP.ZZNNZZ AS NCDR_NUMBER,
        CASE 
            WHEN VBAP.ZZOPZZ = '4' THEN 'Emergency'
            WHEN VBAP.ZZOPZZ = '3' THEN 'Urgent'
            WHEN VBAP.ZZOPZZ = '2' THEN 'Rush'
            WHEN VBAP.ZZOPZZ = '1' THEN 'Normal'
            ELSE 'N/A'
        END AS ORDER_PRIORITY,
        VBAP.ERDAT AS SALES_ORDER_DATE,
        SOL.SALES_DOCUMENT_TYPE AS SALES_DOC_TYPE,
        COALESCE(VBAP.NETWR, 0) * COALESCE(NDT.COEF, 1) AS SALES_ORDER_AMOUNT,
        COALESCE(SOLB.BILLING_AMOUNT, 0) * COALESCE(NDT.COEF, 1) AS BILLING_AMOUNT,
        COALESCE(SOL.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS, 0) * COALESCE(NDT.COEF, 1) AS SALES_ORDER_QUANTITY,
        COALESCE(DLVR.DO_LINE_QTY_SUM, 0) * COALESCE(NDT.COEF, 1) AS DO_LINE_QTY_SUM,
        DLVR.RMA_COUNT,
        VBAP.MATNR AS MATERIAL_NUMBER,
        VBAP.MATKL AS MATERIAL_GROUP,
        MARA.MAKTX AS MATERIAL_DESCRIPTION,
        VBAP.ZZTSNZ AS TOOL_SERIAL_NO,
        SOL.VBAK_SALES_CATEGORY AS SALES_CATEGORY_HEAD,
        SOL.NCDR_FLAG,
        SOL.NCDR_STATUS,
        SOSL.DELIVERED_QUANTITY,
        SOSL.CONFIRMED_QUANTITY,
        SOSL.MIN_SCHEDULE_LINE_DATE,
        SOSL.MAX_SCHEDULE_LINE_DATE,
        SOL.VBAK_ORDER_REASON AS ORDER_REASON_CODE,
        CASE
            WHEN VBAP.ZZORZZ = 'CPR' THEN 'Customer Paid Repair'
            WHEN VBAP.ZZORZZ = 'WKT' THEN 'Tools / Doc. / Software'
            WHEN VBAP.ZZORZZ = 'SLS' THEN 'Normal Parts Sales'
            WHEN VBAP.ZZORZZ = 'REX' THEN 'Repair Exchange'
            WHEN VBAP.ZZORZZ = 'TBS' THEN 'TSM Billable Sales'
            WHEN VBAP.ZZORZZ = 'R01' THEN 'Received Damaged'
            WHEN VBAP.ZZORZZ = 'FCN' THEN 'FCN / SI'
            WHEN VBAP.ZZORZZ = 'SUP' THEN 'Start up Trouble/ Mod. Instl. Trouble'
            WHEN VBAP.ZZORZZ = 'GNS' THEN 'Strategic Sales Concession / Genpo'
            WHEN VBAP.ZZORZZ = 'WTY' THEN 'Equip. Warranty/ Mod. Warranty'
            WHEN VBAP.ZZORZZ = 'LNR' THEN 'Loan Parts'
            WHEN VBAP.ZZORZZ = 'CMR' THEN 'Credit Memo'
            WHEN VBAP.ZZORZZ = 'R11' THEN 'NCDR Return'
            WHEN VBAP.ZZORZZ = 'PSO' THEN 'Paid Service'
            WHEN VBAP.ZZORZZ = 'RTC' THEN 'Consignment Stock Return'
            WHEN VBAP.ZZORZZ = 'XPT' THEN 'Export Parts Sales'
            WHEN VBAP.ZZORZZ = 'R05' THEN 'Fail on Install'
            WHEN VBAP.ZZORZZ = 'TWS' THEN 'TSM Warranty Sales'
            WHEN VBAP.ZZORZZ = 'EVL' THEN 'Evaluation'
            WHEN VBAP.ZZORZZ = 'IPR' THEN 'Sales Concession/FS: Sales'
            WHEN VBAP.ZZORZZ = 'STO' THEN 'Stock Transfer'
            WHEN VBAP.ZZORZZ = 'GNP' THEN 'Sales concession/Genpo'
            WHEN VBAP.ZZORZZ = 'FAC' THEN 'Factory  Concession'
            WHEN VBAP.ZZORZZ = 'TEL' THEN 'Sales Concession/ Product Sales'
            WHEN VBAP.ZZORZZ = 'SSC' THEN 'Strategic Sales Concession'
            WHEN VBAP.ZZORZZ = 'R04' THEN 'Defective'
            WHEN VBAP.ZZORZZ = 'PWO' THEN 'Paperwork only Sales'
            WHEN VBAP.ZZORZZ = 'R02' THEN 'Wrong Parts'
            WHEN VBAP.ZZORZZ = 'PRW' THEN 'Pre Warranty'
            WHEN VBAP.ZZORZZ = 'DMR' THEN 'Debit Memo'
            WHEN VBAP.ZZORZZ = 'R07' THEN 'Not Needed'
        ELSE 'N/A' END AS  ORDER_REASON,
        DLVR.SHIP_DATE,
        SOL.SOLD_TO_PARTY AS SOLD_TO_PARTY_CODE,
        KNA1.NAME1 AS SOLD_TO_PARTY,
        VBAP.KOSTL AS COST_CENTER,
        VBAP.PRCTR AS PROFIT_CENTER
    FROM {{ ref('COMMON__SAPH__SALES_ORDER') }} AS SOL
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP ON (
        VBAP.VBELN = SOL.VBAK_SALES_DOCUMENT AND
        VBAP.POSNR = SOL.SALES_DOCUMENT_ITEM_POSNR
    )
    LEFT JOIN NEGATIVE_DOC_TYPES AS NDT ON (NDT.SALES_DOC_TYPE = SOL.SALES_DOCUMENT_TYPE)
    -- SOLB = Billing Data Lookup
    LEFT JOIN SOLB ON (VBAP.VBELN || VBAP.POSNR = SOLB.SO_ID)
    LEFT JOIN DLVR ON (VBAP.VBELN || VBAP.POSNR = DLVR.SO_ID)
    -- Customer Lookup
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (
        SOL.SOLD_TO_PARTY = KNA1.KUNNR
    )
    -- Material Lookup
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA ON (
        VBAP.MATNR = MARA.MATNR
    )
    LEFT JOIN SOSL ON (VBAP.VBELN || VBAP.POSNR = SOSL.SO_ID)
),
TRANSFORM_DATA AS (
    SELECT 
        SO_ID,
        SALES_ORDER_HEADER_NUMBER,
        SALES_ORDER_LINE_NUMBER,
        DELIVERY_ORDER_HEADER_NUMBER,
        NCDR_NUMBER,
        LEFT(NCDR_NUMBER, 2) AS NCDR_PRODUCT_CODE,
        LEFT(RIGHT(NCDR_NUMBER, 9), 3) AS NCDR_REGION_CODE,
        ORDER_PRIORITY,
        TO_DATE(SALES_ORDER_DATE, 'YYYYMMDD') AS SALES_ORDER_DATE, 
        SALES_DOC_TYPE, 
        SALES_ORDER_QUANTITY, 
        SALES_ORDER_AMOUNT, 
        BILLING_AMOUNT, 
        DO_LINE_QTY_SUM,
        CASE WHEN DO_LINE_QTY_SUM IS NULL OR DO_LINE_QTY_SUM = 0 THEN FALSE ELSE TRUE END AS HAS_DO_FLAG,
        RMA_COUNT, 
        TRY_TO_DATE(SHIP_DATE, 'YYYYMMDD') AS SHIP_DATE, 
        MATERIAL_NUMBER, 
        MATERIAL_GROUP,
        MATERIAL_DESCRIPTION,
        TOOL_SERIAL_NO,
        SALES_CATEGORY_HEAD,
        NCDR_FLAG, 
        NCDR_STATUS, 
        ORDER_REASON_CODE,
        ORDER_REASON, 
        DELIVERED_QUANTITY,
        CONFIRMED_QUANTITY,
        TRY_TO_DATE(MAX_SCHEDULE_LINE_DATE, 'YYYYMMDD') AS MAX_SCHEDULE_LINE_DATE,
        TRY_TO_DATE(MIN_SCHEDULE_LINE_DATE, 'YYYYMMDD') AS MIN_SCHEDULE_LINE_DATE,
        SOLD_TO_PARTY_CODE, 
        SOLD_TO_PARTY, 
        COST_CENTER,
        PROFIT_CENTER,
        CASE WHEN SALES_ORDER_QUANTITY = DO_LINE_QTY_SUM AND SHIP_DATE IS NOT NULL THEN TRUE ELSE FALSE END AS CLOSED,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT
        CAST(SO_ID AS VARCHAR(16777216)) AS SO_ID,
        CAST(SALES_ORDER_HEADER_NUMBER AS VARCHAR(16777216)) AS SALES_ORDER_HEADER_NUMBER,
        CAST(SALES_ORDER_LINE_NUMBER AS VARCHAR(16777216)) AS SALES_ORDER_LINE_NUMBER,
        CAST(DELIVERY_ORDER_HEADER_NUMBER AS VARCHAR(16777216)) AS DELIVERY_ORDER_HEADER_NUMBER,
        CAST(NCDR_NUMBER AS VARCHAR(16777216)) AS NCDR_NUMBER,
        CAST(NCDR_PRODUCT_CODE AS VARCHAR(16777216)) AS NCDR_PRODUCT_CODE,
        CAST(NCDR_REGION_CODE AS VARCHAR(16777216)) AS NCDR_REGION_CODE,
        CAST(ORDER_PRIORITY AS VARCHAR(16777216)) AS ORDER_PRIORITY,
        CAST(SALES_ORDER_DATE AS DATE) AS SALES_ORDER_DATE,
        CAST(SALES_DOC_TYPE AS VARCHAR(16777216)) AS SALES_DOC_TYPE,
        CAST(SALES_ORDER_QUANTITY AS FLOAT) AS SALES_ORDER_QUANTITY,
        CAST(SALES_ORDER_AMOUNT AS FLOAT) AS SALES_ORDER_AMOUNT,
        CAST(DO_LINE_QTY_SUM AS FLOAT) AS DO_LINE_QTY_SUM,
        CAST(HAS_DO_FLAG AS BOOLEAN) AS HAS_DO_FLAG,
        CAST(RMA_COUNT AS INT) AS RMA_COUNT,
        CAST(SHIP_DATE AS DATE) AS SHIP_DATE,
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_GROUP AS VARCHAR(16777216)) AS MATERIAL_GROUP,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(TOOL_SERIAL_NO AS VARCHAR(16777216)) AS TOOL_SERIAL_NO,
        CAST(SALES_CATEGORY_HEAD AS VARCHAR(16777216)) AS SALES_CATEGORY_HEAD,
        CAST(SOLD_TO_PARTY_CODE AS VARCHAR(16777216)) AS SOLD_TO_PARTY_CODE,
        CAST(SOLD_TO_PARTY AS VARCHAR(16777216)) AS SOLD_TO_PARTY,
        CAST(NCDR_FLAG AS VARCHAR(16777216)) AS NCDR_FLAG,
        CAST(NCDR_STATUS AS VARCHAR(16777216)) AS NCDR_STATUS,
        CAST(ORDER_REASON_CODE AS VARCHAR(16777216)) AS ORDER_REASON_CODE,
        CAST(ORDER_REASON AS VARCHAR(16777216)) AS ORDER_REASON,
        CAST(MAX_SCHEDULE_LINE_DATE AS DATE) AS MAX_SCHEDULE_LINE_DATE,
        CAST(MIN_SCHEDULE_LINE_DATE AS DATE) AS MIN_SCHEDULE_LINE_DATE,
        CAST(CLOSED AS BOOLEAN) AS CLOSED,
        CAST(COST_CENTER AS VARCHAR(16777216)) AS COST_CENTER,
        CAST(PROFIT_CENTER AS VARCHAR(16777216)) AS PROFIT_CENTER,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(BILLING_AMOUNT AS FLOAT) AS BILLING_AMOUNT,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
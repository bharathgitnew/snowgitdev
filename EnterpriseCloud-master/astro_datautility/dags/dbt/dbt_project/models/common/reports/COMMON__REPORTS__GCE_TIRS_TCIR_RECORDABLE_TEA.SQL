WITH TIRS AS(
    SELECT
        TIRS_NO
        ,LEFT(TRY_TO_DATE(INITIAL_REPORTER_DATE_OF_OCCURRENCE, 'YYYY/MM/DD') ,7) AS INCIDENT_MONTH
        ,TRY_TO_DATE(INITIAL_REPORTER_DATE_OF_OCCURRENCE, 'YYYY/MM/DD') AS INCIDENT_DATE
        ,COMMON_INCIDENT_TITLE_EN AS INCIDENT_TITLE
        ,CASE
        --WHEN STATUS_EN = '7. Closed' THEN 'Closed'
        --WHEN STATUS_EN = '5. Complete Report' THEN 'Complete Report'
        WHEN STATUS_EN LIKE '%. %' THEN SPLIT_PART(STATUS_EN, '. ', 2)
        ELSE STATUS_EN
        END AS STATUS
        ,COMMON_COMPANY_EN AS COMPANY
        ,COMMON_LOCATION_TYPE_EN AS LOCATION_TYPE
        ,COMMON_INCIDENT_TYPE_EN AS INCIDENT_TYPE
        ,COMMON_CATEGORY_EN AS CATEGORY
        ,COMMON_SUB_CATEGORY_EN AS SUB_CATEGORY
        ,COMMON_SUB_CATEGORY_OTHER AS SUB_CATEGORY_OTHER
        ,COMMON_BU_EN AS BU
        ,COMMON_EQUIPMENT_SN AS MACHINE_SN
        ,COMMON_OCCURRENCE_PLACE_CUSTOMER_NAME_OR_AREA_EN AS CUSTOMER_NAME_OR_AREA
        ,COMMON_LOCATION_DESCRIPTION_BUILDING_OR_LINE_NAME_EN AS LOCATION_OR_BUILDING
        ,COMMON_COUNTRY_OF_ACCIDENT_EN AS COUNTRY_OF_ACCIDENT
        ,INITIAL_REPORTER_COMPANY AS REPORTER_COMPANY
        ,INITIAL_REPORTER_BU_EN AS REPORTER_BU
        ,INITIAL_REPORTER_WORKFLOW_EN AS REPORTER_WORKFLOW
        ,INITIAL_EQUIPMENT_INFORMATION_EQUIPMENT_NAME AS EQUIPMENT_NAME
        ,INITIAL_EQUIPMENT_INFORMATION_BU_EN AS EQUIPMENT_BU
        ,INITIAL_EQUIPMENT_INFORMATION_MODULE_OR_CHAMBER_POSITION AS MODULE_OR_CHAMBER_POSITION
        ,INITIAL_EQUIPMENT_INFORMATION_DAMAGED_PORTION AS DAMAGED_PORTION
        ,INITIAL_EQUIPMENT_INFORMATION_EXPECTED_MAIN_ROOT_CAUSE_EN AS EXPECTED_MAIN_ROOT_CAUSE
        ,INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED
        ,INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY
        ,INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT
        ,INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN
        ,INITIAL_OCCURRENCE_SITUATION_DESCRIPTION_EN AS SITUATION_DESCRIPTION
        ,INITIAL_OCCURRENCE_SITUATION_TYPE_OF_WORKER_EN AS SITUATION_TYPE_OF_WORKER
        ,INITIAL_OCCURRENCE_SITUATION_TASK_EN AS SITUATION_TASK
        ,INITIAL_OCCURRENCE_SITUATION_SITUATION_OF_EQUIPMENT_EN AS SITUATION_OF_EQUIPMENT
        ,INITIAL_OCCURRENCE_SITUATION_SITUATION_OF_WORKER_EN AS SITUATION_OF_WORKER
        ,INITIAL_OCCURRENCE_SITUATION_DAMAGE_TYPE_EN AS DAMAGE_TYPE
        ,DETAILED_INJURY_OR_ILLNESS_INCIDENT_INCIDENT_CLASSIFICATION_EN AS INCIDENT_CLASSIFICATION
    FROM {{ ref('COMMON__TIRS__ACCIDENTREPORTSFORUS_NOLOCK') }}
    WHERE 1=1
    AND DETAILED_INJURY_OR_ILLNESS_INCIDENT_INCIDENT_CLASSIFICATION_EN  = 'TCIR (Recordable)'
    AND COMMON_COMPANY_EN = 'TEA'
    AND TRY_TO_DATE(INITIAL_REPORTER_DATE_OF_OCCURRENCE, 'YYYY/MM/DD') >= '2019-04-01'
)
,DATE AS (
    SELECT
        CALENDAR_DATE
        ,FISCAL_YEAR_SHORT_TEXT AS FISCAL_YEAR
        ,FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF
        ,FISCAL_YEAR_QUARTER_SHORT_TEXT AS FISCAL_QTR
    FROM {{ source('PUB__COMMON_SYSTEM', 'CALENDARDATE') }}
WHERE CALENDAR_DATE >= '2019-04-01')
,BUGROUP AS (
    SELECT
        BU_SOURCE_KEY
        ,BU_GROUP
        ,BU_GROUP_LEADER
    FROM {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }} )
,SOURCE_DATA AS (
SELECT
    DATE.FISCAL_YEAR
    ,DATE.FISCAL_HALF
    ,DATE.FISCAL_QTR
    ,TIRS.INCIDENT_MONTH
    ,TIRS.INCIDENT_DATE
    ,COALESCE(BU_GROUP,TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN) AS BU_GROUP
    ,TIRS.TIRS_NO
    ,TIRS.INCIDENT_TITLE
    ,TIRS.INCIDENT_CLASSIFICATION
    ,TIRS.STATUS
    ,TIRS.COMPANY
    ,TIRS.LOCATION_TYPE
    ,TIRS.INCIDENT_TYPE
    ,TIRS.CATEGORY
    ,TIRS.SUB_CATEGORY
    ,TIRS.SUB_CATEGORY_OTHER
    ,TIRS.BU
    ,TIRS.MACHINE_SN
    ,TIRS.CUSTOMER_NAME_OR_AREA
    ,TIRS.LOCATION_OR_BUILDING
    ,TIRS.COUNTRY_OF_ACCIDENT
    ,TIRS.REPORTER_COMPANY
    ,TIRS.REPORTER_BU
    ,TIRS.REPORTER_WORKFLOW
    ,TIRS.EQUIPMENT_NAME
    ,TIRS.EQUIPMENT_BU
    ,TIRS.MODULE_OR_CHAMBER_POSITION
    ,TIRS.DAMAGED_PORTION
    ,TIRS.EXPECTED_MAIN_ROOT_CAUSE
    ,TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED
    ,TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY
    ,TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT
    ,TIRS.INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN
    ,TIRS.SITUATION_DESCRIPTION
    ,TIRS.SITUATION_TYPE_OF_WORKER
    ,TIRS.SITUATION_TASK
    ,TIRS.SITUATION_OF_EQUIPMENT
    ,TIRS.SITUATION_OF_WORKER
    ,TIRS.DAMAGE_TYPE
    ,BUGROUP.BU_GROUP_LEADER
    FROM TIRS
    LEFT OUTER JOIN BUGROUP
    ON UPPER(INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN) = BU_SOURCE_KEY
    LEFT OUTER JOIN DATE
    ON DATE.CALENDAR_DATE  = TIRS.INCIDENT_DATE)
,TRANSFORM_DATA AS (
SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH,
    FISCAL_YEAR,
    FISCAL_HALF,
    FISCAL_QTR,
    INCIDENT_MONTH,
    INCIDENT_DATE,
    BU_GROUP,
    TIRS_NO,
    INCIDENT_TITLE,
    INCIDENT_CLASSIFICATION,
    STATUS,
    COMPANY,
    LOCATION_TYPE,
    INCIDENT_TYPE,
    CATEGORY,
    SUB_CATEGORY,
    SUB_CATEGORY_OTHER,
    BU,
    MACHINE_SN,
    CUSTOMER_NAME_OR_AREA,
    LOCATION_OR_BUILDING,
    COUNTRY_OF_ACCIDENT,
    REPORTER_COMPANY,
    REPORTER_BU,
    REPORTER_WORKFLOW,
    EQUIPMENT_NAME,
    EQUIPMENT_BU,
    MODULE_OR_CHAMBER_POSITION,
    DAMAGED_PORTION,
    EXPECTED_MAIN_ROOT_CAUSE,
    INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED,
    INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY,
    INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT,
    INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN,
    SITUATION_DESCRIPTION,
    SITUATION_TYPE_OF_WORKER,
    SITUATION_TASK,
    SITUATION_OF_EQUIPMENT,
    SITUATION_OF_WORKER,
    DAMAGE_TYPE,
    BU_GROUP_LEADER
FROM SOURCE_DATA),
TYPE_DATA AS (
    SELECT
        _AUDIT_LOG_ID,
        _ROW_HASH,
        FISCAL_YEAR,
        FISCAL_HALF,
        FISCAL_QTR,
        INCIDENT_MONTH,
        INCIDENT_DATE,
        BU_GROUP,
        TIRS_NO,
        INCIDENT_TITLE,
        INCIDENT_CLASSIFICATION,
        STATUS,
        COMPANY,
        LOCATION_TYPE,
        INCIDENT_TYPE,
        CATEGORY,
        SUB_CATEGORY,
        SUB_CATEGORY_OTHER,
        BU,
        MACHINE_SN,
        CUSTOMER_NAME_OR_AREA,
        LOCATION_OR_BUILDING,
        COUNTRY_OF_ACCIDENT,
        REPORTER_COMPANY,
        REPORTER_BU,
        REPORTER_WORKFLOW,
        EQUIPMENT_NAME,
        EQUIPMENT_BU,
        MODULE_OR_CHAMBER_POSITION,
        DAMAGED_PORTION,
        EXPECTED_MAIN_ROOT_CAUSE,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_NUMBER_OF_PEOPLE_INVOLVED,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_COMPANY,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_DEPARTMENT,
        INITIAL_INFORMATION_PERSON_PEOPLE_INVOLVED_BU_EN,
        SITUATION_DESCRIPTION,
        SITUATION_TYPE_OF_WORKER,
        SITUATION_TASK,
        SITUATION_OF_EQUIPMENT,
        SITUATION_OF_WORKER,
        DAMAGE_TYPE,
        BU_GROUP_LEADER
    FROM TRANSFORM_DATA
)
    SELECT * FROM TYPE_DATA
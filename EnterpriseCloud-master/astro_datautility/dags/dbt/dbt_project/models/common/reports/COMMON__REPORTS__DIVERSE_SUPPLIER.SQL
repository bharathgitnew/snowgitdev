WITH SOURCE_DATA AS 
(
	SELECT DISTINCT
		LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR AS VENDOR_NUMBER,
		LFA1_NAME_1_NAME1 AS VENDOR_NAME,
		TERMS_OF_PAYMENT_KEY AS PAYMENT_TERMS,
		PURCHASING_ORGANIZATION AS LFM1_PURCH_ORG,
		MINORITY_INDICATOR AS MINORITY_INDICATOR,
		CASE 
					WHEN MINORITY_INDICATOR='Z01' THEN 'Disabled-Owned'
					WHEN MINORITY_INDICATOR='Z02' THEN 'Minority-Owned'
					WHEN MINORITY_INDICATOR='Z03' THEN 'SmallBusiness-Owned'
					WHEN MINORITY_INDICATOR='Z04' THEN 'Veteran-Owned'
					WHEN MINORITY_INDICATOR='Z05' THEN 'Women-Owned'
					ELSE 'NOVALUE'
		END DIVERSITY_TYPE
	FROM
		{{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
	WHERE VENDOR_FLAG='Y'
	AND LFB1_COMPANY_CODE='3100'
	AND DIVERSITY_TYPE!='NOVALUE'
	AND LEFT(LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,1)='B'
),
TRANSFORM_DATA AS ( 
    SELECT
        VENDOR_NUMBER,
        VENDOR_NAME,
        PAYMENT_TERMS,
        LFM1_PURCH_ORG,
        MINORITY_INDICATOR,
        DIVERSITY_TYPE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('HASH_ME') AS _ROW_HASH -- ADDS COLUMN TO TABLE ON FULL REFRESH.
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT 
        CAST(VENDOR_NUMBER AS VARCHAR(16777216)) AS  VENDOR_NUMBER,
        CAST(VENDOR_NAME AS VARCHAR(16777216)) AS  VENDOR_NAME,
        CAST(PAYMENT_TERMS AS VARCHAR(16777216)) AS  PAYMENT_TERMS,
        CAST(LFM1_PURCH_ORG AS VARCHAR(16777216)) AS  LFM1_PURCH_ORG,
        CAST(MINORITY_INDICATOR AS VARCHAR(16777216)) AS  MINORITY_INDICATOR,
        CAST(DIVERSITY_TYPE AS VARCHAR(16777216)) AS  DIVERSITY_TYPE,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
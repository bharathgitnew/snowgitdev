WITH CONTRACT AS (
SELECT
CUSTOMER_GROUP
,CUSTOMER_GROUP2
,CUSTOMER_NAME
,CUSTOMER_CODE
,CONTRACT_OWNER
,CONTRACT_NUMBER
,CONTRACT_TITLE
,CONTRACT_STATUS
,PRODUCT
,CASE WHEN CONTRACT_TYPE = 'Comprehensive' AND CONTRACT_SCOPE_BY_PRODUCT LIKE '%BOH%'
    THEN COALESCE(CAST(TRY_TO_NUMBER(LEFT(REPLACE(NOTES,',',''),POSITION('hrs',lower(REPLACE(NOTES,',','')))-1)) AS NUMERIC(38,10)),
                CAST(TRY_TO_NUMBER(LEFT(REPLACE(NOTES,',',''),POSITION('hrs.',lower(REPLACE(NOTES,',','')))-1)) AS NUMERIC(38,10)))
ELSE COVERED_HOURS
END AS COVERED_HOURS
,CONTRACT_START_DATE
,CONTRACT_END_DATE
,CONTRACT_TYPE
,COVERED_FAB
,MAIN_FAB
,ZS10_SALES_ORDER
,WORK_ORDER
,BAAN_CONTRACT_NUMBER
,CONTRACT_SCOPE_BY_PRODUCT
,NOTES
FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
WHERE CONTRACT_STATUS IN ('Providing Service')
AND (CONTRACT_TYPE = 'BOH' OR (CONTRACT_TYPE = 'Comprehensive' AND CONTRACT_SCOPE_BY_PRODUCT LIKE '%BOH%')))

,LEGACY_OFFICE AS (
SELECT
B_CODE
,LEGACY_OFFICE
FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }} )

,SAP_TSR_HOURS AS (
    SELECT DISTINCT
    SAP.VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER,
    sum(SAP.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS) OVER (PARTITION BY SAP.VBAK_CONTRACT_NUMBER) AS SAP_TSR_HOURS
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }} AS SAP
    LEFT JOIN {{ ref('COMMON__CRM__WORKORDER') }} AS CRM
    ON SAP.SERVICE_CRM_WO_NO=CRM.MSDYN_NAME
    WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZS10')
        AND REASON_FOR_REJECTION_OF_SALES_DOCUMENTS<>'Z1'
        AND VBAK_SALES_ORGANIZATION IN ('3200')
        AND TARGET_QUANTITY_UOM='H'
        AND SALES_APPROVAL_STATUS=''
        AND VBAK_CONTRACT_NUMBER<>''
    AND CRM.msdyn_substatusname ILIKE 'CLOSED'
)

,SAP_KRONOS_HOURS AS (
    SELECT
        SC.CONTRACT_NUMBER
        ,SUM(HOURSCHARGED) AS SAP_KRONOS_HOURS
    FROM {{ ref('COMMON__KRONOS__TIMESHEET') }} T
    LEFT OUTER JOIN (
        SELECT DISTINCT 
            CRM.TEL_WO_SERVICEORDERNO_3200 AS SERVICE_ORDER
            ,SOBL.VBAK_CONTRACT_NUMBER AS CONTRACT_NUMBER
        FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}    CRM
        INNER JOIN {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}  SOBL
            ON SOBL.VBAK_SALES_DOCUMENT = CRM.TEL_WO_PRIMARY_SONAME
        WHERE CRM.TEL_WO_SERVICEORDERNO_3200 IS NOT NULL
        AND VBAK_SALES_ORGANIZATION = '3200'
        AND VBAK_SALES_DOCUMENT_TYPE = 'ZS10'
        AND LEFT(VBAK_CONTRACT_NUMBER,1) = 'T'
    ) SC
    ON SC.SERVICE_ORDER = T.SERVICEORDER
    WHERE LEFT(SERVICEORDER,1) = '3'
        AND TYPEOFWORKSOURCE LIKE '%BOH%'
        AND SOURCESYSTEM = 'C'
        AND EVENTDATE >= '2023-05-01'
        AND LEFT(SERVICEORDER,1) = '3'
    GROUP BY SC.CONTRACT_NUMBER
)

,BAAN_KRONOS_HOURS AS (
SELECT
CONTRACT_NUMBER
,SUM(HOURSCHARGED) AS BAAN_KRONOS_HOURS
FROM {{ ref('COMMON__KRONOS__TIMESHEET') }} T
LEFT OUTER JOIN
(
SELECT DISTINCT
SERVICEORDER,
CASE
WHEN SERVICEORDER = 'FLX005322' THEN 'BN0000242'
WHEN SERVICEORDER = 'FLX005323' THEN 'BN0000243'
ELSE CONTRACT_NO
END AS CONTRACT_NUMBER
FROM {{ ref('COMMON__KRONOS__TIMESHEET') }} K
LEFT OUTER JOIN (SELECT DISTINCT CONTRACT_NO,SERVICE_ORDER_NO FROM {{ ref('COMMON__BAAN__SERVICEORDER') }} WHERE LEFT(SERVICE_ORDER_NO,3)= 'FLX') S
    ON K.SERVICEORDER = S.SERVICE_ORDER_NO
WHERE LEFT(SERVICEORDER,3) = 'FLX') SO
ON SO.SERVICEORDER = T.SERVICEORDER
WHERE LEFT(T.SERVICEORDER,3) = 'FLX'
GROUP BY CONTRACT_NUMBER)


,SAP_CRM_HOURS AS (
SELECT
C.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
,SUM(WO_DURATION_HR) AS SAP_CRM_HOURS
FROM  {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }} A
LEFT JOIN {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }} AS B
ON A.WO_WORKORDERNO=B.ID
LEFT JOIN {{ ref('ODS__CRM_FILE__CNT_CONTRACTSUMMARY') }} AS C
ON B.TEL_WO_CONTRACTGROUP=C.ID
WHERE 1=1
AND A.WO_DELETE_FLG = 'FALSE'
AND A. WO_STARTTIME > '2023-05-01'
AND (B.TEL_WO_SUBCATEGORY_SOREQUESTNAME = 'Flex Contract(BOH)' or B.WO_TYPEOFWORK_CUSTOMIZEDNAME = 'Flex Contract(BOH)')
GROUP BY C.CNT_CONTRUCTNUMBER )

,BAAN_TSR_HOURS AS (
SELECT
LTRIM(RTRIM(CONTRACT_NUMBER)) AS CONTRACT_NUMBER
,SUM(FINANCE_TSR_HOURS) AS BAAN_TSR_HOURS
FROM {{ ref('COMMON__SHAREPOINT__SERVICECONTRACTSFLEXTSRS') }}
WHERE REV_REC_DATE < '2023-05-01'
GROUP BY LTRIM(RTRIM(CONTRACT_NUMBER)))

,BAAN_CRM_HOURS AS (
SELECT
SO.CONTRACT_NUMBER
,SUM(WO_DURATION_HR) AS BAAN_CRM_HOURS
FROM {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }} T
LEFT OUTER JOIN
(
SELECT DISTINCT
WO_SONAME,
CASE
WHEN WO_SONAME = 'FLX005322' THEN 'BN0000242'
WHEN WO_SONAME = 'FLX005323' THEN 'BN0000243'
ELSE CONTRACT_NO
END AS CONTRACT_NUMBER
FROM {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }} C
LEFT OUTER JOIN (SELECT DISTINCT CONTRACT_NO,SERVICE_ORDER_NO FROM {{ ref('COMMON__BAAN__SERVICEORDER') }} WHERE LEFT(SERVICE_ORDER_NO,3)= 'FLX') S
    ON C.WO_SONAME = S.SERVICE_ORDER_NO
WHERE LEFT(WO_SONAME,3) = 'FLX') SO
ON SO.WO_SONAME = T.WO_SONAME
WHERE WO_STARTTIME < '2023-05-01'
AND T.WO_DELETE_FLG = 'FALSE'
AND CONTRACT_NUMBER IS NOT NULL
GROUP BY CONTRACT_NUMBER)


,CTE1 AS (
SELECT
CONTRACT.CUSTOMER_GROUP
,CONTRACT.CUSTOMER_GROUP2
,LEGACY_OFFICE
,CONTRACT.CUSTOMER_NAME
,CONTRACT.CONTRACT_OWNER
,CONTRACT.CONTRACT_NUMBER
,CONTRACT.CONTRACT_TITLE
,CONTRACT.CONTRACT_STATUS
,CONTRACT.PRODUCT
,COALESCE(CONTRACT.COVERED_HOURS,0) AS COVERED_HOURS
,COALESCE(SAP_TSR_HOURS.SAP_TSR_HOURS,0) + COALESCE(BAAN_TSR_HOURS.BAAN_TSR_HOURS,0) AS TSR_HOURS
,(COALESCE(CONTRACT.COVERED_HOURS,0)-COALESCE(SAP_TSR_HOURS.SAP_TSR_HOURS,0) - COALESCE(BAAN_TSR_HOURS.BAAN_TSR_HOURS,0)) AS TSR_DELTA
,CASE
WHEN COALESCE(CONTRACT.COVERED_HOURS,0) <> 0  THEN  (COALESCE(SAP_TSR_HOURS.SAP_TSR_HOURS,0) + COALESCE(BAAN_TSR_HOURS.BAAN_TSR_HOURS,0) )/CONTRACT.COVERED_HOURS
ELSE 0
END AS TSR_PERCENTAGE
,COALESCE(SAP_KRONOS_HOURS,0) + COALESCE(BAAN_KRONOS_HOURS,0) AS KRONOS_HOURS
,(COALESCE(CONTRACT.COVERED_HOURS,0)-COALESCE(SAP_KRONOS_HOURS,0) - COALESCE(BAAN_KRONOS_HOURS,0)) AS KRONOS_DELTA
,CASE
WHEN COALESCE(CONTRACT.COVERED_HOURS,0) <> 0  THEN  (COALESCE(SAP_KRONOS_HOURS,0) + COALESCE(BAAN_KRONOS_HOURS,0))/CONTRACT.COVERED_HOURS
ELSE 0
END AS KRONOS_PERCENTAGE
,COALESCE(SAP_CRM_HOURS,0) + COALESCE(BAAN_CRM_HOURS,0) AS CRM_HOURS
,(COALESCE(CONTRACT.COVERED_HOURS,0) - COALESCE(SAP_CRM_HOURS,0)- COALESCE(BAAN_CRM_HOURS,0)) AS CRM_DELTA
,CASE
WHEN COALESCE(CONTRACT.COVERED_HOURS,0) <> 0  THEN  (COALESCE(SAP_CRM_HOURS,0) + COALESCE(BAAN_CRM_HOURS,0))/CONTRACT.COVERED_HOURS
ELSE 0
END AS CRM_PERCENTAGE
,CONTRACT.CONTRACT_START_DATE
,CONTRACT.CONTRACT_END_DATE
,CONTRACT.CONTRACT_TYPE
,CONTRACT.COVERED_FAB
,CONTRACT.MAIN_FAB
,CONTRACT.ZS10_SALES_ORDER
,CONTRACT.WORK_ORDER
,CONTRACT.BAAN_CONTRACT_NUMBER
,CONTRACT.CONTRACT_SCOPE_BY_PRODUCT
,COALESCE(SAP_TSR_HOURS.SAP_TSR_HOURS,0) AS SAP_TSR_HOURS
,COALESCE(SAP_KRONOS_HOURS,0) AS SAP_KRONOS_HOURS
,COALESCE(SAP_CRM_HOURS,0) AS SAP_CRM_HOURS
,COALESCE(BAAN_TSR_HOURS.BAAN_TSR_HOURS,0) AS BAAN_TSR_HOURS
,COALESCE(BAAN_KRONOS_HOURS,0) AS BAAN_KRONOS_HOURS
,COALESCE(BAAN_CRM_HOURS,0) AS BAAN_CRM_HOURS
FROM CONTRACT
LEFT OUTER JOIN SAP_KRONOS_HOURS
ON CONTRACT.CONTRACT_NUMBER = SAP_KRONOS_HOURS.CONTRACT_NUMBER
LEFT OUTER JOIN BAAN_KRONOS_HOURS
ON CONTRACT.BAAN_CONTRACT_NUMBER = BAAN_KRONOS_HOURS.CONTRACT_NUMBER
LEFT OUTER JOIN LEGACY_OFFICE
ON CONTRACT.CUSTOMER_CODE = LEGACY_OFFICE.B_CODE
LEFT OUTER JOIN SAP_TSR_HOURS
ON CONTRACT.CONTRACT_NUMBER = SAP_TSR_HOURS.CONTRACT_NUMBER
LEFT OUTER JOIN BAAN_TSR_HOURS
ON CONTRACT.BAAN_CONTRACT_NUMBER  = BAAN_TSR_HOURS.CONTRACT_NUMBER
LEFT OUTER JOIN SAP_CRM_HOURS
ON CONTRACT.CONTRACT_NUMBER = SAP_CRM_HOURS.CONTRACT_NUMBER
LEFT OUTER JOIN BAAN_CRM_HOURS
ON CONTRACT.BAAN_CONTRACT_NUMBER = BAAN_CRM_HOURS.CONTRACT_NUMBER)

,SOURCE_DATA AS (
SELECT
'{{ invocation_id }}' AS AUDIT_LOG_ID
,SHA2('hash_me') AS _ROW_HASH
,CUSTOMER_GROUP
,CUSTOMER_GROUP2
,LEGACY_OFFICE
,CUSTOMER_NAME
,CONTRACT_OWNER
,CONTRACT_NUMBER
,CONTRACT_TITLE
,CONTRACT_STATUS
,PRODUCT
,COVERED_HOURS
,TSR_HOURS
,TSR_DELTA
,TSR_PERCENTAGE
,KRONOS_HOURS
,KRONOS_DELTA
,KRONOS_PERCENTAGE
,CRM_HOURS
,CRM_DELTA
,CRM_PERCENTAGE
,CONTRACT_START_DATE
,CONTRACT_END_DATE
,CONTRACT_TYPE
,COVERED_FAB
,MAIN_FAB
,ZS10_SALES_ORDER
,WORK_ORDER
,BAAN_CONTRACT_NUMBER
,CONTRACT_SCOPE_BY_PRODUCT
,SAP_TSR_HOURS
,SAP_KRONOS_HOURS
,SAP_CRM_HOURS
,BAAN_TSR_HOURS
,BAAN_KRONOS_HOURS
,BAAN_CRM_HOURS

FROM CTE1
WHERE TSR_HOURS<COVERED_HOURS
)

,TYPE_DATA AS (
SELECT
CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
,CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
,CUSTOMER_GROUP
,CUSTOMER_GROUP2
,LEGACY_OFFICE
,CUSTOMER_NAME
,CONTRACT_OWNER
,CONTRACT_NUMBER
,CONTRACT_TITLE
,CONTRACT_STATUS
,PRODUCT
,CAST(COVERED_HOURS AS NUMBER(38,2)) AS COVERED_HOURS
,CAST(TSR_HOURS AS NUMBER(38,2)) AS TSR_HOURS
,CAST(TSR_DELTA AS NUMBER(38,2)) AS TSR_DELTA
,CAST(TSR_PERCENTAGE AS NUMBER(38,2)) AS TSR_PERCENTAGE
,CAST(KRONOS_HOURS AS NUMBER(38,2)) AS KRONOS_HOURS
,CAST(KRONOS_DELTA AS NUMBER(38,2)) AS KRONOS_DELTA
,CAST(KRONOS_PERCENTAGE AS NUMBER(38,2)) AS KRONOS_PERCENTAGE
,CAST(CRM_HOURS AS NUMBER(38,2)) AS CRM_HOURS
,CAST(CRM_DELTA AS NUMBER(38,2)) AS CRM_DELTA
,CAST(CRM_PERCENTAGE AS NUMBER(38,2)) AS CRM_PERCENTAGE
,CAST(CONTRACT_START_DATE AS DATE) AS CONTRACT_START_DATE
,CAST(CONTRACT_END_DATE AS DATE) AS CONTRACT_END_DATE
,CONTRACT_TYPE
,COVERED_FAB
,MAIN_FAB
,ZS10_SALES_ORDER
,WORK_ORDER
,BAAN_CONTRACT_NUMBER
,CONTRACT_SCOPE_BY_PRODUCT
,CAST(SAP_TSR_HOURS AS NUMBER(38,2))  AS SAP_TSR_HOURS
,CAST(SAP_KRONOS_HOURS AS NUMBER(38,2)) AS SAP_KRONOS_HOURS
,CAST(SAP_CRM_HOURS AS NUMBER(38,2)) AS SAP_CRM_HOURS
,CAST(BAAN_TSR_HOURS AS NUMBER(38,2)) AS BAAN_TSR_HOURS
,CAST(BAAN_KRONOS_HOURS AS NUMBER(38,2)) AS BAAN_KRONOS_HOURS
,CAST(BAAN_CRM_HOURS AS NUMBER(38,2)) AS BAAN_CRM_HOURS
FROM SOURCE_DATA)
SELECT * FROM TYPE_DATA
WITH FREE_STOCK as (
    SELECT
        MATNR, 
        LFGJA,
        LFMON,
        VERPR  --moving average price
        --,STPRS --standard price 
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU243_MBEWH') }}
    WHERE BWKEY = '3200'
    AND VPRSV = 'V'
),

SALES_ORDER_STOCK as (
    SELECT 
        MATNR, 
        VBELN,
        POSNR, 
        LFGJA,
        LFMON,
        VERPR  --moving average price
        --,STPRS --standard price
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU246_EBEWH') }}
    WHERE BWKEY = '3200'
    AND VPRSV = 'V'
),

ACDOCA as (
    SELECT
        ACDOCA.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        ACDOCA.COMPANY_CODE,
        ACDOCA.ACCOUNTING_DOCUMENT_NUMBER,
        ACDOCA.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        ACDOCA.FISCAL_YEAR,
        RIGHT(ACDOCA.PERIOD_YEAR,3) AS FISCAL_PERIOD, 
        LEFT(substring(ACDOCA.PERIOD_YEAR,2), 4) || '/' || LPAD(RIGHT(substring(ACDOCA.PERIOD_YEAR,2), 3), 3, '0') AS YEAR_PERIOD,
        ACDOCA.ACCOUNT_NUMBER,
        ACDOCA.AMOUNT_IN_COMPANY_CODE_CURRENCY,
        ACDOCA.COMPANY_CODE_CURRENCY,
        ACDOCA.DOCUMENT_TYPE,
        ACDOCA.MATERIAL_NUMBER,
        ACDOCA.QUANTITY,
        ACDOCA.PURCHASING_DOCUMENT_NUMBER,
        ACDOCA.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        POL.PO_DOC_TYPE AS PURCHASE_ORDER_TYPE,
        POL.PO_DATE AS PURCHASE_ORDER_DATE,
        --ACDOCA.SALES_ORDER_NUMBER,
        --ACDOCA.ITEM_NUMBER_IN_SALES_ORDER,
        ACDOCA.SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        ACDOCA.SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        ACDOCA.WBS_ELEMENT_OF_VALUATED_SPECIAL_INVENTORY_MAT_PS_POSID,
        ACDOCA.QUANTITY*-1 AS QUANTITY_SIGN_FLIP
        --ACDOCA.INVENTORY_QUANTITY*-1 AS INVENTORY_QUANTITY
    FROM {{ ref('COMMON__SAPH__UNIVERSAL_JOURNAL_ENTRY_LINE') }} ACDOCA
    LEFT JOIN {{ ref('COMMON__SAPH__PURCHASE_ORDER_LINE') }} POL
    ON ACDOCA.PURCHASING_DOCUMENT_NUMBER = POL.PO_HDR
    WHERE ACDOCA.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING = '0L'
    AND ACDOCA.COMPANY_CODE = '3200'
    AND ACDOCA.MATERIAL_NUMBER != ''
    AND ACDOCA.DOCUMENT_TYPE != 'RE'
    AND ACDOCA.ACCOUNT_NUMBER = '213XX00001'
),

SOURCE_DATA as (
    SELECT 
        DISTINCT
        ACDOCA.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        ACDOCA.COMPANY_CODE,
        ACDOCA.ACCOUNTING_DOCUMENT_NUMBER,
        ACDOCA.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        ACDOCA.FISCAL_YEAR,
        ACDOCA.FISCAL_PERIOD,
        ACDOCA.YEAR_PERIOD,
        ACDOCA.ACCOUNT_NUMBER,
        ACDOCA.AMOUNT_IN_COMPANY_CODE_CURRENCY,
        ACDOCA.COMPANY_CODE_CURRENCY,
        ACDOCA.DOCUMENT_TYPE,
        ACDOCA.MATERIAL_NUMBER,
        ACDOCA.QUANTITY,
        ACDOCA.PURCHASING_DOCUMENT_NUMBER,
        ACDOCA.ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        ACDOCA.PURCHASE_ORDER_TYPE,
        ACDOCA.PURCHASE_ORDER_DATE,
        --ACDOCA.SALES_ORDER_NUMBER,
        --ACDOCA.ITEM_NUMBER_IN_SALES_ORDER,
        ACDOCA.SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        ACDOCA.SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        ACDOCA.WBS_ELEMENT_OF_VALUATED_SPECIAL_INVENTORY_MAT_PS_POSID,
        ACDOCA.QUANTITY_SIGN_FLIP,
        --SALES_ORDER_STOCK.VERPR,
        --FREE_STOCK.VERPR AS PUP_1,
        CASE WHEN (ACDOCA.SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY IS NULL or ACDOCA.SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY = '') 
             THEN FREE_STOCK.VERPR
        ELSE SALES_ORDER_STOCK.VERPR
        END AS PUP,
        QUANTITY_SIGN_FLIP*PUP AS INV_PUP
        FROM ACDOCA
        LEFT JOIN FREE_STOCK
        ON ACDOCA.MATERIAL_NUMBER = FREE_STOCK.MATNR
        AND ACDOCA.FISCAL_YEAR = FREE_STOCK.LFGJA
        AND TO_NUMBER(ACDOCA.FISCAL_PERIOD) = TO_NUMBER(FREE_STOCK.LFMON)
        LEFT JOIN SALES_ORDER_STOCK
        ON ACDOCA.MATERIAL_NUMBER = SALES_ORDER_STOCK.MATNR
        AND ACDOCA.SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY = SALES_ORDER_STOCK.VBELN
        AND ACDOCA.SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY = SALES_ORDER_STOCK.POSNR
        AND ACDOCA.FISCAL_YEAR = SALES_ORDER_STOCK.LFGJA
        AND TO_NUMBER(ACDOCA.FISCAL_PERIOD) = TO_NUMBER(SALES_ORDER_STOCK.LFMON)
),

TRANSFORM_DATA AS (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        COMPANY_CODE,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        YEAR_PERIOD,
        ACCOUNT_NUMBER,
        AMOUNT_IN_COMPANY_CODE_CURRENCY,
        COMPANY_CODE_CURRENCY,
        DOCUMENT_TYPE,
        MATERIAL_NUMBER,
        QUANTITY,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        PURCHASE_ORDER_TYPE,
        PURCHASE_ORDER_DATE,
        SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        WBS_ELEMENT_OF_VALUATED_SPECIAL_INVENTORY_MAT_PS_POSID,
        QUANTITY_SIGN_FLIP,
        PUP,
        INV_PUP
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT 
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        COMPANY_CODE,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        FISCAL_YEAR,
        FISCAL_PERIOD,
        YEAR_PERIOD,
        ACCOUNT_NUMBER,
        AMOUNT_IN_COMPANY_CODE_CURRENCY,
        COMPANY_CODE_CURRENCY,
        DOCUMENT_TYPE,
        MATERIAL_NUMBER,
        CAST(QUANTITY as NUMBER(38,2)) as QUANTITY,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        PURCHASE_ORDER_TYPE,
        PURCHASE_ORDER_DATE,
        SALES_DOCUMENT_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        SALES_DOCUMENT_ITEM_NUMBER_OF_VALUATED_SPECIAL_INVENTORY,
        WBS_ELEMENT_OF_VALUATED_SPECIAL_INVENTORY_MAT_PS_POSID,
        CAST(QUANTITY_SIGN_FLIP as NUMBER(38,2)) as QUANTITY_SIGN_FLIP,
        CAST(PUP as NUMBER(38,2)) as PUP,
        CAST(INV_PUP as NUMBER(38,2)) as INV_PUP, 
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
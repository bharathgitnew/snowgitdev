,RECEIPT_QTYS as (
    select  
        REF_DOC, 
         MATNR,
        SUM(DO_QTY) AS DO_QTY,
        SUM(QTY_RECEIVED) AS QTY_RECEIVED
    from RECEIPT_QTYS_ALL
    group by REF_DOC,MATNR
),
GR_QUANTITY AS (
select
    EBELN AS STO,
    EBELP AS STO_LINE,
    SUM(CASE WHEN SHKZG = 'S' THEN MENGE ELSE MENGE * -1 END) AS GOODS_RECEIVED_QUANTITY
from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU217_EKBE') }}  where BEWTP = 'E'
group by EBELN,EBELP,SHKZG
),
SOURCE_DATA AS (
    SELECT
        EKKO.EBELN AS STO,
        EKPO.EBELP AS STO_LINE,
        TRY_TO_DATE(EKKO.AEDAT, 'YYYYMMDD') AS CREATED_DATE,
        EKKO.ZZCBENO as CREATED_BY_EMPLOYEE_NO,
        CONCAT(PARTNER.NAME1FIRST,' ' ,PARTNER.name1last) AS CREATED_BY_NAME,
        EKPO.LGORT AS RECEIVING_SLOC,
        -- The only reason this alias is semantically correct is because
        -- we are filtering on ZP25
        EKPO.RESLO AS ZP25_ISSUING_SLOC,
        EKPO.EMATN AS MATNR,
        EKPO.MENGE AS PO_QTY,
        COALESCE(DA.DO_QTY, 0) AS DO_QTY,
        COALESCE(RDR.QTY_RECEIVED, 0) AS QTY_CONFIRMED_RECEIVED,
        COALESCE(GR.GOODS_RECEIVED_QUANTITY,0) AS GOODS_RECEIVED_QUANTITY,
        CASE 
            WHEN COALESCE(RDR.QTY_RECEIVED, 0) >= EKPO.MENGE 
            THEN TRUE ELSE FALSE 
        END AS RECEIPT_CONFIRMED,
        DA.LATEST_DO_CREATED_DATE,
        DA.LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
        DA.LATEST_DELIVERY_DATE,
        DA.LATEST_PICKING_DATE,
        DA.HAWBS,
        DA.DO_LINE_IDS,
        DA.BATCHES,
        DA.PICKING_STATUS_CODES,
        DA.PROCESSING_STATUS_CODES,
        DA.COMPLETED,
        DA.REMARKS,
        DA.ARRIVED_AT_DELIVERY_QTY,
        DA.TENDERED_FOR_DELIVERY_QTY,
        DA.SHIPMENT_RECEIVED_QTY,
        DA.AVAILABLE_FOR_DELIVERY_QTY,
        DA.SHIPMENT_CANCELLED_QTY
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU027_EKKO') }} AS EKKO
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU028_EKPO') }} AS EKPO ON (EKPO.EBELN = EKKO.EBELN)
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU251_ZMAT0011') }} AS PARTNER
    ON LTRIM(PARTNER.PARTNER,'0') = LTRIM(EKKO.ZZCBENO,'0')
    LEFT JOIN DELIVERY_AGG AS DA ON (
        DA.REF_DOC_HDR = EKKO.EBELN AND
        LTRIM(DA.REF_DOC_LINE, '0') = LTRIM(EKPO.EBELP, '0')
    )
    LEFT JOIN RECEIPT_QTYS AS RDR ON (RDR.MATNR = EKPO.EMATN AND RDR.REF_DOC = EKKO.EBELN)
    LEFT JOIN GR_QUANTITY GR ON (GR.STO_LINE=EKPO.EBELP AND GR.STO=EKKO.EBELN)
    WHERE 
        EKKO.BSART = 'ZP25' AND 
        UPPER(EKPO.LGORT) NOT LIKE 'A%' AND
        -- LOEKZ is a deletion indicator
        -- "L" indicates that the item is deleted at the purchase order level
        -- "S" indicates that the item is (temporarily) blocked but not deleted.
        EKPO.LOEKZ != 'L'
),
TRANSFORM_DATA AS (
    SELECT 
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH,
        SOURCE_DATA.STO,
        SOURCE_DATA.STO_LINE,
        SOURCE_DATA.CREATED_DATE,
        SOURCE_DATA.CREATED_BY_EMPLOYEE_NO,
        SOURCE_DATA.CREATED_BY_NAME,
        SOURCE_DATA.RECEIVING_SLOC,
        SOURCE_DATA.ZP25_ISSUING_SLOC,
        SOURCE_DATA.MATNR,
        SOURCE_DATA.PO_QTY,
        SOURCE_DATA.DO_QTY,
        SOURCE_DATA.QTY_CONFIRMED_RECEIVED,
        SOURCE_DATA.GOODS_RECEIVED_QUANTITY,
        SOURCE_DATA.RECEIPT_CONFIRMED,
        SOURCE_DATA.LATEST_DO_CREATED_DATE,
        SOURCE_DATA.LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
        SOURCE_DATA.LATEST_DELIVERY_DATE,
        SOURCE_DATA.LATEST_PICKING_DATE,
        SOURCE_DATA.HAWBS,
        SOURCE_DATA.DO_LINE_IDS,
        SOURCE_DATA.BATCHES,
        SOURCE_DATA.PICKING_STATUS_CODES,
        SOURCE_DATA.PROCESSING_STATUS_CODES,
        SOURCE_DATA.COMPLETED,
        SOURCE_DATA.REMARKS,
        SOURCE_DATA.ARRIVED_AT_DELIVERY_QTY AS TPL_ARRIVED_AT_DELIVERY_QTY,
        SOURCE_DATA.TENDERED_FOR_DELIVERY_QTY AS TPL_TENDERED_FOR_DELIVERY_QTY,
        SOURCE_DATA.SHIPMENT_RECEIVED_QTY AS TPL_SHIPMENT_RECEIVED_QTY,
        SOURCE_DATA.AVAILABLE_FOR_DELIVERY_QTY AS TPL_AVAILABLE_FOR_DELIVERY_QTY,
        SOURCE_DATA.SHIPMENT_CANCELLED_QTY AS TPL_SHIPMENT_CANCELLED_QTY
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT 
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    STO,
    STO_LINE,
    CAST(TRANSFORM_DATA.CREATED_DATE AS DATE) AS CREATED_DATE,
    CREATED_BY_EMPLOYEE_NO,
    CREATED_BY_NAME,
    RECEIVING_SLOC,
    ZP25_ISSUING_SLOC,
    MATNR,
    CAST(TRANSFORM_DATA.PO_QTY AS INT) AS PO_QTY,
    CAST(TRANSFORM_DATA.DO_QTY AS INT) AS DO_QTY,
    CAST(TRANSFORM_DATA.QTY_CONFIRMED_RECEIVED AS INT) AS QTY_CONFIRMED_RECEIVED,
    CAST(TRANSFORM_DATA.GOODS_RECEIVED_QUANTITY AS INT) AS GOODS_RECEIVED_QUANTITY,
    CAST(TRANSFORM_DATA.RECEIPT_CONFIRMED AS BOOLEAN) AS RECEIPT_CONFIRMED,
    CAST(TRANSFORM_DATA.LATEST_DO_CREATED_DATE AS DATE) AS LATEST_DO_CREATED_DATE,
    CAST(TRANSFORM_DATA.LATEST_ACTUAL_GOODS_MOVEMENT_DATE AS DATE) AS LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
    CAST(TRANSFORM_DATA.LATEST_DELIVERY_DATE AS DATE) AS LATEST_DELIVERY_DATE,
    CAST(TRANSFORM_DATA.LATEST_PICKING_DATE AS DATE) AS LATEST_PICKING_DATE,
    HAWBS,
    DO_LINE_IDS,
    BATCHES,
    PICKING_STATUS_CODES,
    PROCESSING_STATUS_CODES,
    CAST(TRANSFORM_DATA.COMPLETED AS BOOLEAN) AS COMPLETED,
    REMARKS,
    CAST(TPL_ARRIVED_AT_DELIVERY_QTY AS INT) AS TPL_ARRIVED_AT_DELIVERY_QTY,
    CAST(TPL_TENDERED_FOR_DELIVERY_QTY AS INT) AS TPL_TENDERED_FOR_DELIVERY_QTY,
    CAST(TPL_SHIPMENT_RECEIVED_QTY AS INT) AS TPL_SHIPMENT_RECEIVED_QTY,
    CAST(TPL_AVAILABLE_FOR_DELIVERY_QTY AS INT) AS TPL_AVAILABLE_FOR_DELIVERY_QTY,
    CAST(TPL_SHIPMENT_CANCELLED_QTY AS INT) AS TPL_SHIPMENT_CANCELLED_QTY
FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
WITH
-- Goal  : Get delivery qtys for PO lines
-- Method: Deliveries aggregated by reference document (PO) line.
DELIVERY_AGG AS (
    SELECT
        DOL.REF_DOC_HDR, 
        DOL.REF_DOC_LINE,
        MAX(DOL.CREATED_ON) AS LATEST_DO_CREATED_DATE,
        MAX(DOL.ACTUAL_GOODS_MOVEMENT_DATE) AS LATEST_ACTUAL_GOODS_MOVEMENT_DATE,
        MAX(DOL.DELIVERY_DATE_ZZDDZZ) AS LATEST_DELIVERY_DATE,
        MAX(DOL.PICKING_DATE) AS LATEST_PICKING_DATE,
        LISTAGG(CASE WHEN DOL.HAWB != '' THEN DOL.HAWB ELSE NULL END, '|') AS HAWBS,
        COUNT(*) AS NUMBER_OF_DO_LINES,
        SUM(DOL.QTY) AS DO_QTY,
        SUM(CASE WHEN TRIM(LOWER(SS.CURRENT_STATUS)) = 'arrived at delivery' THEN DOL.QTY ELSE 0 END) AS ARRIVED_AT_DELIVERY_QTY,
        SUM(CASE WHEN TRIM(LOWER(SS.CURRENT_STATUS)) = 'tendered for deliver' THEN DOL.QTY ELSE 0 END) AS TENDERED_FOR_DELIVERY_QTY,
        SUM(CASE WHEN LOWER(SS.CURRENT_STATUS) = 'shipment has been re' THEN DOL.QTY ELSE 0 END) AS SHIPMENT_RECEIVED_QTY,
        SUM(CASE WHEN LOWER(SS.CURRENT_STATUS) = 'available for delive' THEN DOL.QTY ELSE 0 END) AS AVAILABLE_FOR_DELIVERY_QTY,
        SUM(CASE WHEN LOWER(SS.CURRENT_STATUS) = 'shipment cancelled' THEN DOL.QTY ELSE 0 END) AS SHIPMENT_CANCELLED_QTY,
        LISTAGG(DOL.HDR || '-' || DOL.LINE_POSNR, ' | ') AS DO_LINE_IDS,
        LISTAGG(DOL.BATCH, '|') AS BATCHES,
        CASE 
            WHEN SUM(CASE WHEN DOL.PROCESSING_STATUS = 'C' THEN 1 ELSE 0 END) = COUNT(*) 
            THEN TRUE ELSE FALSE 
        END AS COMPLETED,
        LISTAGG(DOL.PICKING_STATUS, '|') AS PICKING_STATUS_CODES,
        LISTAGG(DOL.PROCESSING_STATUS, '|') AS PROCESSING_STATUS_CODES,
        LISTAGG(DOL.REMARKS, ' | ') AS REMARKS
    FROM {{ ref('COMMON__SAPH__DELIVERY_ORDER_LINE_MASTER_PUB') }} AS DOL
    LEFT JOIN {{ ref('ODS__THREEPL__TPL_SHIPMENT_STATUS') }} AS SS ON (
        DOL.HDR = SS.DOCUMENT_NUMBER AND
        DOL.LINE_POSNR = LPAD(SS.LINE_NUMBER, 6, '0')
    )
    -- Filter out DO lines where qty = 0
    WHERE DOL.QTY > 0
    GROUP BY DOL.REF_DOC_HDR, DOL.REF_DOC_LINE
),
-- Goal: 
--  Get the sum of delivered materials for all DOs and pull in the PO
--  that produced the DO
-- 
-- Method
--  Get qty sums for delivery order header and material number pairs.
--  We would use DO lines, but sometimes the material numbers are spread
--  across multiple DO lines. We then filter to instances where the DO
--  header maps to one and only one PO.
--  Note the relationship between PO/SO and DO is almost always one to
--  one or one to many, but I did find a few edge cases in my analysis.
MAT_DELIV AS (
    SELECT DOL.HDR, DOL.MATNR, SUM(DOL.QTY) AS DO_QTY, MAX(DOL.REF_DOC_HDR) AS REF_DOC
    FROM {{ ref('COMMON__SAPH__DELIVERY_ORDER_LINE_MASTER_PUB') }} AS DOL
    GROUP BY DOL.HDR, DOL.MATNR
    HAVING MIN(DOL.REF_DOC_HDR) = MAX(DOL.REF_DOC_HDR)
),

ROSETTA as (
    SELECT 
        SHIPMENT_TRACKING_ID,
        ITEM_CODE,
        sum(QTY) as QTY
    from  {{ ref('COMMON__ROSETTA__CONSIGNMENT_SHIPMENT_RECEIPT') }}
    group by SHIPMENT_TRACKING_ID,ITEM_CODE
),

RECEIPT_QTYS_all AS (
    SELECT M.REF_DOC, 
        CSR.ITEM_CODE AS MATNR,
        (M.DO_QTY) AS DO_QTY,
        (CSR.QTY) AS QTY_RECEIVED
    FROM ROSETTA AS CSR
    JOIN MAT_DELIV AS M ON 
         M.HDR = CSR.SHIPMENT_TRACKING_ID 
         AND
        M.MATNR = CSR.ITEM_CODE
 union all
    SELECT  M.REF_DOC, 
        CSR.ITEM_CODE AS MATNR,
        (M.DO_QTY) AS DO_QTY,
        (CSR.QTY) AS QTY_RECEIVED
    FROM ROSETTA AS CSR
    JOIN (select * from MAT_DELIV where HDR not in (select SHIPMENT_TRACKING_ID from rosetta))
    AS M ON 
          M.REF_DOC = CSR.SHIPMENT_TRACKING_ID  
         AND 
        M.MATNR = CSR.ITEM_CODE
    )

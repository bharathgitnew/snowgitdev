WITH PROD_ORDER AS
(
SELECT 
    AUFK.AUFNR AS ORDER_NUMBER,
    AFRU.WERKS AS PLANT,
    AUFK.AUART AS ORDER_TYPE,
    AUFK.KTEXT AS DESCRIPTION,
    PRPS.POSKI AS WBS,
    --STATUS_VALUE.STATUS,
    TO_DATE(AFRU.BUDAT, 'yyyymmdd') AS POSTING_DATE,
	TO_DATE(AFRU.ISDD, 'yyyymmdd') AS START_OF_EXECUTION,
    TO_DATE(AFRU.IEDD, 'yyyymmdd') AS END_OF_FINISH,
    AUFK.PRCTR AS PROFIT_CENTER,
    AFKO.PLNNR AS GROUP1,
    AFRU.LTXA1 AS EMPLOYEE,
    --COEP.KSTAR AS COST_ELEMENT,
    COBK.BELNR AS DOCUMENT_NO,
    AFRU.ISM01 AS TOTAL_HRS

FROM 
{{ ref('ODS__SAPAPI__ZCDV_T_CMTU090_AUFK') }} AS AUFK
LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU119_AFKO') }} AS AFKO
ON AFKO.AUFNR = AUFK.AUFNR
LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU088_AFPO') }} AS AFPO
ON AFPO.AUFNR = AUFK.AUFNR
LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU219_AFRU') }} AS AFRU
ON AUFK.AUFNR = AFRU.AUFNR
LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU040_PRPS') }} AS PRPS
ON AFPO.PROJN = PRPS.POSKI 
LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU046_COBK') }}  AS COBK
ON TRY_TO_NUMBER(AFRU.RUECK) = TRY_TO_NUMBER(REFBN)
AND  TRY_TO_NUMBER(AFRU.RMZHL) =  TRY_TO_NUMBER(AWORG)
--LEFT JOIN  "LZ_DEV"."SAPAPI"."COEP" AS COEP
--ON TRY_TO_NUMBER(COBK.BELNR) = TRY_TO_NUMBER(COEP.BELNR)  AND COBK.KOKRS = COEP.KOKRS 
--LEFT JOIN STATUS_VALUE AS STATUS_VALUE
--ON TRY_TO_NUMBER(STATUS_VALUE.OBJECT_NUMBER) = AUFK.AUFNR
WHERE  
AUFK.AUART = 'ZD01' AND
PRPS.PRART = 'V' AND 
COBK.BELNR IS NOT NULL 
),
SOURCE_DATA as
(  SELECT
    ORDER_NUMBER,
    PLANT,
    ORDER_TYPE,
    DESCRIPTION,
    WBS,
    POSTING_DATE,
    START_OF_EXECUTION,
    END_OF_FINISH,
    PROFIT_CENTER,
    GROUP1,
    EMPLOYEE,
    DOCUMENT_NO,
    TOTAL_HRS
    from prod_order
),
TRANSFORM_DATA AS (
    SELECT 
        ORDER_NUMBER,
        PLANT,
        ORDER_TYPE,
        DESCRIPTION,
        WBS,
        POSTING_DATE,
        START_OF_EXECUTION,
        END_OF_FINISH,
        PROFIT_CENTER,
        GROUP1,
        EMPLOYEE,
        DOCUMENT_NO,
        TOTAL_HRS,
        '{{ invocation_id }}' AS AUDIT_LOG_ID
    FROM SOURCE_DATA
),
TYPE_DATA as (
    SELECT
        CAST(ORDER_NUMBER AS VARCHAR(16777216)) AS ORDER_NUMBER,
        CAST(PLANT AS VARCHAR(16777216)) AS PLANT,
        CAST(ORDER_TYPE AS VARCHAR(16777216)) AS ORDER_TYPE,
        CAST(DESCRIPTION AS VARCHAR(16777216)) AS DESCRIPTION,
        CAST(WBS AS VARCHAR(16777216)) AS WBS,
        CAST(POSTING_DATE AS DATE) AS POSTING_DATE,
        CAST(START_OF_EXECUTION AS DATE) AS START_OF_EXECUTION,
        CAST(END_OF_FINISH AS DATE) AS END_OF_FINISH,
        CAST(PROFIT_CENTER AS VARCHAR(16777216)) AS PROFIT_CENTER,
        CAST(GROUP1 AS VARCHAR(16777216)) AS GROUP1,
        CAST(EMPLOYEE AS VARCHAR(16777216)) AS EMPLOYEE,
        CAST(DOCUMENT_NO AS VARCHAR(16777216)) AS DOCUMENT_NO,
        CAST(TOTAL_HRS AS NUMBER(38,2)) AS TOTAL_HRS,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    FROM TRANSFORM_DATA
)

SELECT * from TYPE_DATA
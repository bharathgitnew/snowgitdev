        alias = 'PAID_SERVICE_TELQS_QUOTES',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

WITH TEQQUOTE AS (
    SELECT
        QUOTENUMBER AS QUOTE_NUMBER
        ,PRODUCT
        ,CUSTOMER_NAME AS CUSTOMER_NAME_SOURCE
        ,TRIM(SPLIT_PART(CUSTOMER_NAME, '(', 1)) AS CUSTOMER_NAME
        ,SERVICESTARTDATE AS START_DATE
        ,SERVCEENDDATE AS END_DATE
        ,CUSTOMER_CODE
        ,CASE
            WHEN LEFT(CUSTOMER_CODE,1) = 'B' THEN CUSTOMER_CODE
            ELSE NULL
        END AS CUSTOMER_CODE_B
        ,REQUESTDATE AS REQUEST_DATE
        ,CASE
            WHEN LEN(TOOIDNUMBER) > 1 THEN  TOOIDNUMBER
            ELSE NULL
        END AS CUSTOMER_TOOL_ID
        ,SERIALNUMBER AS SERIAL_NUMBER
        ,CASE
            WHEN WORKTYPESID = '1' THEN 'Troubleshooting/Repair'
            WHEN WORKTYPESID = '2' THEN 'Accelerated Startup'
            WHEN WORKTYPESID = '3' THEN 'Preventative Maintenance'
            WHEN WORKTYPESID = '4' THEN 'Overhaul'
            WHEN WORKTYPESID = '5' THEN 'Customer Training at Customer Site'
            WHEN WORKTYPESID = '6' THEN 'Process/Application'
            WHEN WORKTYPESID = '7' THEN 'Consulting/Analysis'
            WHEN WORKTYPESID = '8' THEN 'Relocation'
            WHEN WORKTYPESID = '9' THEN 'Decommission'
            WHEN WORKTYPESID = '10' THEN 'Re-Installation'
            WHEN WORKTYPESID = '11' THEN 'Modification'
            WHEN WORKTYPESID = '12' THEN 'Standby Service'
            WHEN WORKTYPESID IS NULL THEN '*No Work Type Assigned'
            ELSE '*ID Not Mapped -' || WORKTYPESID
        END AS WORK_TYPE
        ,BRIEFDESCRIPTIONOFWORK AS LABOR_DESCRIPTION
        ,TOTALPRICING AS TOTAL_QUOTE_AMT
        ,FABLOCATIONS AS FAB_LOCATION_CODE
        ,IS_ACTIVE
        ,CREATEDON AS CREATED_ON
        ,CASE
            WHEN UPDATEDON > '2000-01-01' THEN UPDATEDON
            ELSE NULL
        END AS UPDATED_ON
        ,CASE
            WHEN LEN(WORKORDER) >1 THEN WORKORDER
            ELSE NULL
        END AS WORK_ORDER
        ,POAMOUNT AS PO_AMOUNT
        ,TRIM(SPLIT_PART(LOCALFABNAMEFORDISPLAY, '(', 1)) AS FAB_LOCATION
        ,SITESUPERVISOREMPNO AS SITE_SUPERVISOR_ID
        ,REQUESTOREMPNO AS REQUESTOR_ID
        ,SUPERVISOREMPNO AS SUPERVISOR_ID
    FROM {{ ref('COMMON__TELQS__PAID_SERVICE_QUOTE_MASTER') }}
    WHERE
        LEFT(QUOTENUMBER,1) = 'P'  -- Only Want Paid Service
        AND REQUESTORNAME NOT IN ('MELISSA FLORES','Nuno Rodrigues', 'Richard Lazarus') -- These are test/dummy records
        AND BRIEFDESCRIPTIONOFWORK NOT IN ('TEST', 'test') -- These are test/dummy records
)

,EMPLOYEE AS (
    SELECT
        EMPLOYEEID
        ,FULLNAME
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
)
,CSSMAP as (
    SELECT
     PRIMARY_CONTACT AS PRIMARY_SERVICE_CONTACT
    ,PRIMARY_CONTACTID AS PRIMARY_SERVICE_CONTACT_ID
    ,SECONDARY_CONTACT AS SECONDARY_SERVICE_CONTACT
    ,SECONDARY_CONTACTID AS SECONDARY_SERVICE_CONTACT_ID
    ,CC_BU_KEY
FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_SITE_SERVICE_MANAGER_MAPPING') }}
)

,CUSTOMER AS (
    SELECT
        CUSTOMER_GROUP
        ,BUSINESS_PARTNER_NUMBER
        ,CORPORATION_NAME AS CUSTOMER
        ,CORPORATION AS CUSTOMER_A_CODE
    FROM {{ ref('COMMON__SAPH__SAP_CUSTOMER') }}
)

,FAB_B_CODE AS (
    SELECT DISTINCT
        CUSTOMER_CODE_B
        ,CUSTOMER_CODE_D
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE LEN(CUSTOMER_CODE_B)>1 AND LEN(CUSTOMER_CODE_D)>1
    QUALIFY row_number() over ( partition by CUSTOMER_CODE_D order by CUSTOMER_CODE_B desc ) = 1
)

,CUSTOMERPO AS (
    SELECT
        PONUMBER AS PO_NUMBER
        ,CASE
            WHEN LEN(QUOTENUMBER)>1 THEN QUOTENUMBER
            ELSE NULL
        END AS QUOTE_NUMBER
        ,POAMOUNT AS PO_AMOUNT
        ,CASE
            WHEN LEN(WORKORDER)< 1 THEN NULL
            ELSE WORKORDER
        END AS WORK_ORDER
    FROM {{ ref('COMMON__TELQS__PROCESS_ORDER_DETAILS') }}
    WHERE PONUMBER NOT LIKE '%If I am%'
)

,PO_LIST AS (
    SELECT
        QUOTE_NUMBER
        ,LISTAGG(DISTINCT PO_NUMBER, ' ,') AS PO_NUMBER
        ,LISTAGG(DISTINCT WORK_ORDER, ' ,') AS WORK_ORDER
        ,SUM(PO_AMOUNT) AS TOTAL_PO_AMOUNT
    FROM CUSTOMERPO
    WHERE QUOTE_NUMBER IS NOT NULL
    GROUP BY QUOTE_NUMBER
)

,QUOTE AS (
    SELECT
        CASE
            WHEN CUSTOMER.CUSTOMER_GROUP IS NOT NULL THEN CUSTOMER.CUSTOMER_GROUP
            WHEN TEQQUOTE.CUSTOMER_NAME iLIKE 'Micron%' THEN 'Micron'
            WHEN TEQQUOTE.CUSTOMER_NAME iLIKE 'Samsung%' THEN 'Samsung'
            WHEN TEQQUOTE.CUSTOMER_NAME iLIKE 'Intel %' THEN 'Intel'
            WHEN TEQQUOTE.CUSTOMER_NAME iLIKE 'TOKYO ELECTRON %' THEN 'TEL GROUP'
            ELSE 'Regional'
        END AS CUSTOMER_GROUP
        ,BUMAP.BU_GROUP AS LEGACY_BU
        ,TEQQUOTE.PRODUCT
        ,COALESCE(CUSTOMER.CUSTOMER,TEQQUOTE.CUSTOMER_NAME) AS CUSTOMER
        ,TEQQUOTE.QUOTE_NUMBER
        ,LEFT(TEQQUOTE.REQUEST_DATE,7) AS QUOTE_REQUEST_MONTH
        ,TEQQUOTE.REQUEST_DATE
        ,EMPSUPERVISOR.FULLNAME AS SUPERVISOR
        ,EMPREQUESTOR.FULLNAME AS REQUESTOR
        ,TEQQUOTE.WORK_TYPE
        ,TEQQUOTE.TOTAL_QUOTE_AMT
        ,TEQQUOTE.START_DATE
        ,TEQQUOTE.END_DATE
        ,TEQQUOTE.SERIAL_NUMBER
        ,TEQQUOTE.CUSTOMER_TOOL_ID
        ,TEQQUOTE.LABOR_DESCRIPTION
        ,TEQQUOTE.CUSTOMER_NAME
        ,TEQQUOTE.FAB_LOCATION
        ,TEQQUOTE.CUSTOMER_CODE
        ,TEQQUOTE.FAB_LOCATION_CODE
        ,CASE
            WHEN LEN(TEQQUOTE.WORK_ORDER)>1 THEN TEQQUOTE.WORK_ORDER
            WHEN LEN(PO_LIST.WORK_ORDER)> 1 THEN PO_LIST.WORK_ORDER
            ELSE NULL
        END AS WORK_ORDER
        ,PO_LIST.PO_NUMBER
        ,PO_LIST.TOTAL_PO_AMOUNT
        ,TEQQUOTE.PO_AMOUNT
        ,CUSTOMER.CUSTOMER_A_CODE
        ,CASE
            WHEN TEQQUOTE.CUSTOMER_CODE_B IS NOT NULL THEN TEQQUOTE.CUSTOMER_CODE_B
            WHEN CUSTOMER.CUSTOMER LIKE 'SAMSUNG AUSTIN%'THEN 'BA2120300'
            WHEN CUSTOMER.CUSTOMER LIKE 'TOKYO ELECTRON EUROPE%'THEN 'BA0010300'
            WHEN FAB_B_CODE.CUSTOMER_CODE_B IS NOT NULL THEN FAB_B_CODE.CUSTOMER_CODE_B
            ELSE NULL
        END AS CUSTOMER_B_CODE
        ,TEQQUOTE.CREATED_ON
        ,TEQQUOTE.UPDATED_ON
        ,TEQQUOTE.IS_ACTIVE
        ,EMPSUPERVISOR.FULLNAME AS SITE_SUPERVISOR
        ,TEQQUOTE.SITE_SUPERVISOR_ID
        ,TEQQUOTE.REQUESTOR_ID
        ,TEQQUOTE.SUPERVISOR_ID
        ,BUMAP.BU_GROUP
        ,BUMAP.BU_GROUP_LEADER
        ,BUMAP.BU_GROUP_LEADER_ID
        ,CSSMAP.PRIMARY_SERVICE_CONTACT
        ,CSSMAP.PRIMARY_SERVICE_CONTACT_ID
        ,CSSMAP.SECONDARY_SERVICE_CONTACT
        ,CSSMAP.SECONDARY_SERVICE_CONTACT_ID
    FROM TEQQUOTE
    LEFT OUTER JOIN EMPLOYEE EMPREQUESTOR
        ON TEQQUOTE.REQUESTOR_ID = EMPREQUESTOR.EMPLOYEEID
    LEFT OUTER JOIN EMPLOYEE EMPSUPERVISOR
        ON TEQQUOTE.SUPERVISOR_ID = EMPSUPERVISOR.EMPLOYEEID
    LEFT OUTER JOIN EMPLOYEE EMPSITESUPERVISOR
        ON TEQQUOTE.SITE_SUPERVISOR_ID = EMPSITESUPERVISOR.EMPLOYEEID
    LEFT OUTER JOIN CUSTOMER
        ON TEQQUOTE.CUSTOMER_CODE = CUSTOMER.BUSINESS_PARTNER_NUMBER
    LEFT OUTER JOIN FAB_B_CODE
        ON TEQQUOTE.FAB_LOCATION_CODE = FAB_B_CODE.CUSTOMER_CODE_D
    LEFT OUTER JOIN PO_LIST
        ON TEQQUOTE.QUOTE_NUMBER = PO_LIST.QUOTE_NUMBER
    LEFT JOIN  {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }} BUMAP
    ON TEQQUOTE.PRODUCT = BUMAP.BU_SOURCE_KEY
    LEFT OUTER JOIN CSSMAP
    ON CSSMAP.CC_BU_KEY = (CUSTOMER_B_CODE||'_'||BUMAP.BU_GROUP)
)

,transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        CUSTOMER_GROUP,
        LEGACY_BU,
        PRODUCT,
        CUSTOMER,
        QUOTE_NUMBER,
        QUOTE_REQUEST_MONTH,
        REQUEST_DATE,
        SUPERVISOR,
        REQUESTOR,
        WORK_TYPE,
        TOTAL_QUOTE_AMT,
        START_DATE,
        END_DATE,
        SERIAL_NUMBER,
        CUSTOMER_TOOL_ID,
        LABOR_DESCRIPTION,
        CUSTOMER_NAME,
        FAB_LOCATION,
        CUSTOMER_CODE,
        FAB_LOCATION_CODE,
        WORK_ORDER,
        PO_NUMBER,
        TOTAL_PO_AMOUNT,
        PO_AMOUNT,
        CUSTOMER_A_CODE,
        CUSTOMER_B_CODE,
        CREATED_ON,
        UPDATED_ON,
        IS_ACTIVE,
        SITE_SUPERVISOR,
        SITE_SUPERVISOR_ID,
        REQUESTOR_ID,
        SUPERVISOR_ID
        ,BU_GROUP
        ,BU_GROUP_LEADER
        ,BU_GROUP_LEADER_ID
        ,PRIMARY_SERVICE_CONTACT
        ,PRIMARY_SERVICE_CONTACT_ID
        ,SECONDARY_SERVICE_CONTACT
        ,SECONDARY_SERVICE_CONTACT_ID
    from QUOTE
)

,type_data AS (
    SELECT
        _AUDIT_LOG_ID,
        _ROW_HASH,
        CUSTOMER_GROUP,
        LEGACY_BU,
        PRODUCT,
        CUSTOMER,
        QUOTE_NUMBER,
        QUOTE_REQUEST_MONTH,
        CAST(REQUEST_DATE as DATE) AS REQUEST_DATE,
        SUPERVISOR,
        REQUESTOR,
        WORK_TYPE,
        TOTAL_QUOTE_AMT,
        CAST(START_DATE as DATE) AS START_DATE,
        CAST(END_DATE as DATE) AS END_DATE,
        SERIAL_NUMBER,
        CUSTOMER_TOOL_ID,
        LABOR_DESCRIPTION,
        CUSTOMER_NAME,
        FAB_LOCATION,
        CUSTOMER_CODE,
        FAB_LOCATION_CODE,
        WORK_ORDER,
        PO_NUMBER,
        TOTAL_PO_AMOUNT,
        CUSTOMER_A_CODE,
        CUSTOMER_B_CODE,
        CAST(CREATED_ON as DATE) AS CREATED_ON,
        CAST(UPDATED_ON as DATE) AS UPDATED_ON,
        CAST(IS_ACTIVE as VARCHAR(16777216)) AS IS_ACTIVE,
        SITE_SUPERVISOR,
        SITE_SUPERVISOR_ID,
        REQUESTOR_ID ,
        SUPERVISOR_ID
        ,BU_GROUP
        ,BU_GROUP_LEADER
        ,BU_GROUP_LEADER_ID
        ,PRIMARY_SERVICE_CONTACT
        ,PRIMARY_SERVICE_CONTACT_ID
        ,SECONDARY_SERVICE_CONTACT
        ,SECONDARY_SERVICE_CONTACT_ID
    FROM transform_data
)

select * from type_data
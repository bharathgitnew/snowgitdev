with cost_center as (
select
    COST_CENTER_CODE,
    SEGMENT_CODE as SECURITY_SEGMENT,
    DEPARTMENT_CODE as SECURITY_DEPARTMENT,
    OFFICE_CODE as SECURITY_OFFICE
from {{ ref('ODS__FILE__COST_CENTER') }}),

profit_center as (
select
    PROFIT_CENTER_CODE,
    PROFIT_CENTER_NAME,
    SEGMENT_CODE,
    SEGMENT,
    DEPARTMENT_CODE,
    DEPARTMENT,
    OFFICE_CODE,
    OFFICE
from {{ ref('ODS__FILE__PROFIT_CENTER') }}),

source_data as (
    select
        'PURCHASES' as RECORD_TYPE
        , EKPO_PURCHASING_DOCUMENT_NUMBER as ORDER_NO
        , ITEM_NUMBER_OF_PURCHASING_DOCUMENT_EBELP as ORDER_LINE_NO
        , LIKP_Delivery AS DO_NO
        , DELIVERY_ITEM_POSNR as DO_LINE_NO
        , DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT as DO_REF_ORDER
        , ITEM_NUMBER_OF_THE_REFERENCE_ITEM as DO_REF_LINE
        , ORDER_PRIORITY_ZZOPZZ as ORDER_PRIORITY
        , PURCHASING_DOCUMENT_TYPE as ORDER_TYPE
        , GOODS_MOVEMENT_STATUS as ORDER_STATUS
        , PURCHASE_ORDER_QUANTITY as ORDER_QTY
        , ACTUAL_QUANTITY_DELIVERED as DELIVERED_QTY
        , EKPO_PROFIT_CENTER as PROFIT_CENTER
        , LIPS_COST_CENTER as COST_CENTER
        , '<ALL>' as SECURITY_SEGMENT
        , '<ALL>' as SECURITY_DEPARTMENT
        , '<ALL>' as SECURITY_OFFICE
    from {{ ref('COMMON__SAPH__PURCHASE_ORDER_DELIVERY_LINE') }}
    left outer join cost_center
        on COST_CENTER=cost_center.COST_CENTER_CODE
    left outer join profit_center
        on PROFIT_CENTER=profit_center.PROFIT_CENTER_CODE
    where LIKP_DELIVERY is not null
    union all
    select 'SALES' as RECORD_TYPE
        , VBAP_SALES_DOCUMENT as ORDER_NO
        , SALES_DOCUMENT_ITEM_POSNR as ORDER_LINE_NO
        , LIPS_DELIVERY as DO_NO
        , DELIVERY_ITEM_POSNR as DO_LINE_NO
        , LIPS_DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT as DO_REF_ORDER
        , LIPS_ITEM_NUMBER_OF_THE_REFERENCE_ITEM as DO_REF_LINE
        , ORDER_PRIORITY_ZZOPZZ as ORDER_PRIORITY
        , SALES_DOCUMENT_ITEM_CATEGORY as ORDER_TYPE
        , LIPS_GOODS_MOVEMENT_STATUS as ORDER_STATUS
        , CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS as ORDER_QTY
        , ACTUAL_QUANTITY_DELIVERED as DELIVERED_QTY
        , VBAP_PROFIT_CENTER as PROFIT_CENTER
        , VBAP_COST_CENTER as COST_CENTER
        , '<ALL>' as SECURITY_SEGMENT
        , '<ALL>' as SECURITY_DEPARTMENT
        , '<ALL>' as SECURITY_OFFICE
    from {{ ref('COMMON__SAPH__SALES_ORDER_DELIVERY_LINE') }}  SO
    left outer join cost_center
        on COST_CENTER=cost_center.COST_CENTER_CODE
    left outer join profit_center
        on PROFIT_CENTER=profit_center.PROFIT_CENTER_CODE
    where LIPS_DELIVERY is not null
),

transform_data AS
(
    select
        RECORD_TYPE,
        ORDER_NO,
        ORDER_LINE_NO,
        DO_NO,
        DO_LINE_NO,
        DO_REF_ORDER,
        DO_REF_LINE,
        ORDER_PRIORITY,
        ORDER_TYPE,
        ORDER_STATUS,
        ORDER_QTY,
        DELIVERED_QTY,
        PROFIT_CENTER,
        COST_CENTER,
        SECURITY_SEGMENT,
        SECURITY_DEPARTMENT,
        SECURITY_OFFICE,
		'{{ invocation_id }}' AS AUDIT_LOG_ID
    from source_data
),

type_data as (
select
    CAST(RECORD_TYPE as VARCHAR(16777216)) as RECORD_TYPE,
    CAST(ORDER_NO as VARCHAR(16777216)) as ORDER_NO,
    CAST(ORDER_LINE_NO as VARCHAR(16777216)) as ORDER_LINE_NO,
    CAST(DO_NO as VARCHAR(16777216)) as DO_NO,
    CAST(DO_LINE_NO as VARCHAR(16777216)) as DO_LINE_NO,
    CAST(DO_REF_ORDER as VARCHAR(16777216)) as DO_REF_ORDER,
    CAST(DO_REF_LINE as VARCHAR(16777216)) as DO_REF_LINE,
    CAST(ORDER_PRIORITY as VARCHAR(16777216)) as ORDER_PRIORITY,
    CAST(ORDER_TYPE as VARCHAR(16777216)) as ORDER_TYPE,
    CAST(ORDER_STATUS as VARCHAR(16777216)) as ORDER_STATUS,
    CAST(ORDER_QTY as VARCHAR(16777216)) as ORDER_QTY,
    CAST(DELIVERED_QTY as VARCHAR(16777216)) as DELIVERED_QTY,
    CAST(PROFIT_CENTER as VARCHAR(16777216)) as PROFIT_CENTER,
    CAST(COST_CENTER as VARCHAR(16777216)) as COST_CENTER,
    CAST(SECURITY_SEGMENT as VARCHAR(16777216)) as SECURITY_SEGMENT,
    CAST(SECURITY_DEPARTMENT as VARCHAR(16777216)) as SECURITY_DEPARTMENT,
    CAST(SECURITY_OFFICE as VARCHAR(16777216)) as SECURITY_OFFICE,
    CAST(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID
from transform_data
)

select * from type_data
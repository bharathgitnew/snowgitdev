    a.pending_regional_approval_date AS Pending_RA ,
    a.pending_global_approval_date AS Pending_GA ,
    a.transfer_price AS transfer_price ,
    a.standard_cost AS standard_cost ,
    a.sale_price AS sale_price ,
    a.shipment_type AS shipment_type ,
    CASE a.machine_down WHEN 'Yes' THEN '1' WHEN 'No' THEN '0' END AS machine_down,
    a.cancelled_flag AS Cancelled ,
    CASE a.on_hold_status WHEN 'Yes' THEN '1' WHEN 'No' THEN '0' END AS on_hold_status,
    CASE a.paperwork_only WHEN 'Yes' THEN '1' WHEN 'No' THEN '0' END AS paperwork_only ,
    CASE a.return_to_stock WHEN 'Yes' THEN '1' WHEN 'No' THEN '0' END AS return_to_stock ,
    a.part_description AS Parts_Reason ,
    CASE a.STATUS_ID WHEN 1 THEN 'Pending Submission' WHEN 2 THEN 'Pending Regional Approval' WHEN 3 THEN 'Pending Global Approval' WHEN 4 THEN 'Denied' WHEN 5 THEN 'Regionally Approved' WHEN 6 THEN 'Globally Approved' WHEN 7 THEN 'Sales Order Evaluated' WHEN 8 THEN 'Pending Sales Order Evaluation' WHEN 11 THEN 'Workflow Started' WHEN 12 THEN 'Workflow Finished' WHEN 13 THEN 'Workflow Aborted' WHEN 14 THEN 'Sales Order Created' WHEN 15 THEN 'Regionally Timed-out' WHEN 16 THEN 'Globally Timed-out' WHEN 17 THEN 'Regional Hold' WHEN 18 THEN 'Global Hold' WHEN 19 THEN 'Pending Regional Post-Approval' WHEN 20 THEN 'Pending Global Post-Approval' WHEN 21 THEN 'Regionally Post- Approved' WHEN 22 THEN 'Globally Post-Approved' WHEN 23 THEN 'NCDR Cancelled' END AS Current_Workflow_Status	 ,
    a.originator_emp_no AS originator_id ,
    CASE b.approved WHEN 3 THEN '0' WHEN 2 THEN '1' ELSE '2' END AS PART_APPROVAL ,
    d.description AS DEFECTIVE_PORTION,
    a.BU_ID
from nowdata a
inner join ncdr_parts b
    on (a.ncdr_number = b.ncdr_number and a.line_number = b.line_number
    and ( a.region_code = 'TEA'))
inner join serial_numbers s
    on s.ncdr_number = a.ncdr_number
left outer join defective_portion_types d
    on d.defective_portion_id = s.defective_portion_id
),


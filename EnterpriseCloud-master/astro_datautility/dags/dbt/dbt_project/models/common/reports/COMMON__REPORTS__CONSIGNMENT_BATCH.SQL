--     JOIN MSKU_DISTINCT AS MS ON (MS.MATNR = QTYS.MATNR AND MS.CHARG = QTYS.CHARG)
--     LEFT JOIN SO ON (
--         QTYS.CHARG = SO.CHARG AND QTYS.MATNR = SO.MATNR
--     )
-- ),
SOURCE_DATA_NEW AS (
    SELECT 
        QTYS.MATNR AS MATERIAL,
        QTYS.CHARG AS BATCH, 
        QTYS.UNRESTRICTED_QTY,
        QTYS.SLOC,
        QTYS.SLOC_NAME,
        case when QTYS.SLOC = '' then CUSTOMER_CONSIGNMENT_CODE
        else T001L.KUNNR end AS LOCATION_CUSTOMER_CODE,
        case when QTYS.SLOC = '' then    CUSTOMER_CONSIGNMENT_NAME
        else KNA1.NAME1 end AS LOCATION_CUSTOMER_NAME,
        COALESCE(SO.CONSUMED_QTY, 0) AS CONSUMED_QTY,
        COALESCE(SO.RETURNED_QTY, 0) AS RETURNED_QTY,
        COALESCE(SO.FILLUP_QTY, 0) AS FILLUP_QTY,
        COALESCE(SO.PICKUP_QTY, 0) AS PICKUP_QTY,
        COALESCE(SO.PAID_REPAIR_QTY, 0) AS PAID_REPAIR_QTY,
        COALESCE(SO.TOTAL_SO_QTY, 0) AS TOTAL_SO_QTY,
        QTYS.RECORDS_IN_INV_STS_TBL,
        COALESCE(SO.SO_LINE_CNT, 0) AS SO_LINE_CNT,
        TRY_TO_DATE(SO.LATEST_SO_DATE, 'YYYYMMDD') AS LATEST_SO_DATE,
        case when COALESCE(SO.CONSUMED_QTY, 0) +  QTYS.UNRESTRICTED_QTY +COALESCE(SO.RETURNED_QTY, 0)
        + COALESCE(SO.FILLUP_QTY, 0) + COALESCE(SO.PICKUP_QTY, 0) + COALESCE(SO.PAID_REPAIR_QTY, 0)
        +COALESCE(SO.SO_LINE_CNT, 0) = 0 then 'X' else '' end as flag
    FROM QTYS_NEW as QTYS
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU080_T001L') }} AS T001L ON (
        T001L.LGORT = QTYS.SLOC AND T001L.WERKS = '3200'
    )
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (
        KNA1.KUNNR = T001L.KUNNR
    )
    JOIN MSKU_DISTINCT AS MS ON (MS.MATNR = QTYS.MATNR AND MS.CHARG = QTYS.CHARG)
    LEFT JOIN SO ON (
        QTYS.CHARG = SO.CHARG AND QTYS.MATNR = SO.MATNR
    )
    where flag = ''
),
transform_data as (
SELECT
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	MATERIAL,
	BATCH,
	UNRESTRICTED_QTY,
	SLOC,
	SLOC_NAME,
	LOCATION_CUSTOMER_CODE,
	LOCATION_CUSTOMER_NAME,
	CONSUMED_QTY,
	RETURNED_QTY,
	FILLUP_QTY,
	PICKUP_QTY,
	PAID_REPAIR_QTY,
	TOTAL_SO_QTY,
	RECORDS_IN_INV_STS_TBL,
	SO_LINE_CNT
 from SOURCE_DATA_NEW
),

type_data as (
SELECT
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	MATERIAL,
	BATCH,
	CAST(UNRESTRICTED_QTY AS FLOAT) AS UNRESTRICTED_QTY,
    CAST(SLOC AS VARCHAR(16777216)) AS SLOC,
    CAST(SLOC_NAME AS VARCHAR(16777216)) AS SLOC_NAME,
    CAST(LOCATION_CUSTOMER_CODE AS VARCHAR(16777216)) AS LOCATION_CUSTOMER_CODE,
    CAST(LOCATION_CUSTOMER_NAME AS VARCHAR(16777216)) AS LOCATION_CUSTOMER_NAME,
	CAST(CONSUMED_QTY AS FLOAT) AS CONSUMED_QTY,
	CAST(RETURNED_QTY AS FLOAT) AS RETURNED_QTY,
	CAST(FILLUP_QTY AS FLOAT) AS FILLUP_QTY,
	CAST(PICKUP_QTY AS FLOAT) AS PICKUP_QTY,
	CAST(PAID_REPAIR_QTY AS FLOAT) AS PAID_REPAIR_QTY,
	CAST(TOTAL_SO_QTY AS FLOAT) AS TOTAL_SO_QTY,
	CAST(RECORDS_IN_INV_STS_TBL AS INT) AS RECORDS_IN_INV_STS_TBL,
	CAST(SO_LINE_CNT AS INT) AS SO_LINE_CNT
 from transform_data
)

Select * from type_data
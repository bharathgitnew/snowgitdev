QTYS_new AS (
    SELECT 
        INVS.MATERIAL_NUMBER AS MATNR, 
        INVS.BATCH_NUMBER AS CHARG,
        INVS.STORAGE_LOCATION AS SLOC,
        CUSTOMER_CONSIGNMENT_CODE,
        CUSTOMER_CONSIGNMENT_NAME,
        MAX(INVS.STORAGE_LOCATION_NAME) AS SLOC_NAME,
        MAX(INVS.STORAGE_LOCATION) AS MAX_SLOC,
        MIN(INVS.STORAGE_LOCATION) AS MIN_SLOC,
--        MAX(INVS._FILEDATE),
        SUM(INVS.UNRESTRICTED_QUANTITY) AS UNRESTRICTED_QTY,
        COUNT(*) AS RECORDS_IN_INV_STS_TBL
    from {{ ref('COMMON__SAPH__INVENTORY_STATUS') }}  AS INVS
    WHERE INVS.BATCH_NUMBER != 'DUMMY' AND INVS.COMPANY_CODE = '3200'
--    and  INVS.STORAGE_LOCATION <> '' 
    GROUP BY INVS.MATERIAL_NUMBER, INVS.BATCH_NUMBER, INVS.STORAGE_LOCATION,CUSTOMER_CONSIGNMENT_CODE,
        CUSTOMER_CONSIGNMENT_NAME
),
-- The MSKU table in SAP tracks special stocks related to specific
-- customers. If a batch is not in the MSKU table, it is out of scope
-- for this report per Charles Mays
MSKU_DISTINCT AS (
    SELECT DISTINCT MSKU.MATNR, MSKU.CHARG
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU110_MSKU') }} AS MSKU
),
-- SOURCE_DATA AS (

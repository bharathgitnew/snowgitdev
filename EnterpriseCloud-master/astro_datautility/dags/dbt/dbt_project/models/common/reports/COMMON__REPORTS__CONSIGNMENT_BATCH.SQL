--         QTYS.MATNR AS MATERIAL,
--         QTYS.CHARG AS BATCH, 
--         QTYS.UNRESTRICTED_QTY,
--         QTYS.SLOC,
--         QTYS.SLOC_NAME,
--         T001L.KUNNR AS LOCATION_CUSTOMER_CODE,
--         KNA1.NAME1 AS LOCATION_CUSTOMER_NAME,
--         COALESCE(SO.CONSUMED_QTY, 0) AS CONSUMED_QTY,
--         COALESCE(SO.RETURNED_QTY, 0) AS RETURNED_QTY,
--         COALESCE(SO.FILLUP_QTY, 0) AS FILLUP_QTY,
--         COALESCE(SO.PICKUP_QTY, 0) AS PICKUP_QTY,
--         COALESCE(SO.PAID_REPAIR_QTY, 0) AS PAID_REPAIR_QTY,
--         COALESCE(SO.TOTAL_SO_QTY, 0) AS TOTAL_SO_QTY,
--         QTYS.RECORDS_IN_INV_STS_TBL,
--         COALESCE(SO.SO_LINE_CNT, 0) AS SO_LINE_CNT,
--         TRY_TO_DATE(SO.LATEST_SO_DATE, 'YYYYMMDD') AS LATEST_SO_DATE

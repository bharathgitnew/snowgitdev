WITH
SO AS (
    SELECT 
        VBAP.CHARG, 
        VBAP.MATNR, 
        SUM(CASE WHEN VBAK.AUART = 'ZS14' THEN VBAP.KWMENG ELSE 0 END) AS INITIATED_QTY,
        SUM(CASE WHEN VBAK.AUART = 'ZS12' THEN VBAP.KWMENG ELSE 0 END) AS CONSUMED_QTY,
        SUM(CASE WHEN VBAK.AUART IN ('ZPR2', 'ZPR0') THEN VBAP.KWMENG ELSE 0 END) AS RETURNED_QTY,
        SUM(CASE WHEN VBAK.AUART = 'ZP11' THEN VBAP.KWMENG ELSE 0 END) AS FILLUP_QTY,
        SUM(CASE WHEN VBAK.AUART = 'ZPR1' THEN VBAP.KWMENG ELSE 0 END) AS PICKUP_QTY,
        SUM(CASE WHEN VBAK.AUART = 'ZR10' THEN VBAP.KWMENG ELSE 0 END) AS PAID_REPAIR_QTY,
        SUM(VBAP.KWMENG) AS TOTAL_SO_QTY,
        COUNT(*) AS SO_LINE_CNT,
        MAX(VBAP.ERDAT) AS LATEST_SO_DATE
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} AS VBAK ON (VBAK.VBELN = VBAP.VBELN)
    WHERE 
        NULLIF(VBAP.CHARG, '') IS NOT NULL AND 
        VBAP.WERKS = '3200'
    GROUP BY VBAP.CHARG, VBAP.MATNR
),

WITH SO AS (
    SELECT DISTINCT
        SALES_DOCUMENT_TYPE  AS SALES_DOCUMENT_TYPE
        , VBAK_SALES_DOCUMENT AS SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM_POSNR AS SALES_DOCUMENT_ITEM
        , SOLD_TO_PARTY AS SOLD_TO_CUSTOMER_CODE
        , SHORT_TEXT_FOR_SALES_ORDER_ITEM AS ITEM_SHORT_TEXT
        , ORDER_ITEM_NAME AS ORDER_ITEM
        , VBAK_PRODUCT_CODE AS PRODUCT_CODE
        , VBAP_MATERIAL_NUMBER AS MATERIAL_NUMBER
        , MATERIAL_GROUP_1 AS MATERIAL_GROUP1
        , VBAP_MATERIAL_GROUP AS MATERIAL_GROUP
        , TRY_TO_DATE(DOCUMENT_DATE,'YYYYMMDD') AS DOCUMENT_DATE
        , TRY_TO_DATE(VBAK_DELIVERY_CREATE_DATE,'YYYYMMDD') AS DELIVERY_CREATE_DATE
        , TRY_TO_DATE(REQUESTED_DELIVERY_DATE,'YYYYMMDD')  AS DELIVERY_DATE
        , TRY_TO_DATE(LOCAL_SUBSIDIARY_PO_RECEIVED_DATE,'YYYYMMDD')  AS LOCAL_PO_RECEIVE_DATE
        , TRY_TO_DATE(BOOKING_DATE,'YYYYMMDD') AS BOOKING_DATE
        , TRY_TO_DATE(END_USER_BOOKING_DATE,'YYYYMMDD') AS END_USER_BOOKING_DATE
        , SALES_DOCUMENT_ITEM_CATEGORY AS SALES_DOCUMENT_ITEM_CATEGORY
        , PRPS.WBS_ELEMENT_SHORT_IDENTIFICATION AS WORK_BREAKDOWN_STRUCTURE
        , VBAP_PROFIT_CENTER AS PROFIT_CENTER
        , RIGHT(VBAP_PROFIT_CENTER, 2) AS OFFICE_CODE
        , SALES_REP_EMPLOYEE_NO
        , VBAK_SALES_CATEGORY AS SALES_CATEGORY
        , CRM_OPPORTUNITY_ID
        --//,NET_VALUE_OF_THE_SALES_ORDER_IN_DOCUMENT_CURRENCY AS SALES_ORDER_ITEM_NET_VALUE
        , VBAK_SD_DOCUMENT_CURRENCY
        , SALES_DOCUMENT_ITEM_POSNR
        , SHIP.CUSTOMER_NUMBER AS SHIP_TO_CUSTOMER
    FROM {{ ref('COMMON__SAPH__SALES_ORDER') }} AS SO
    LEFT JOIN {{ ref('COMMON__SAPH__WBS_MASTER') }} AS PRPS
        ON try_to_number(SO.VBAP_WORK_BREAKDOWN_STRUCTURE_ELEMENT)=try_to_number(PRPS.WBS_ELEMENT)
    LEFT OUTER JOIN {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }} SHIP
        ON SO.VBAK_SALES_DOCUMENT = SHIP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
        AND SHIP.PARTNER_FUNCTION  = 'SH'
    WHERE 1=1
        AND VBAK_SALES_CATEGORY IN ('11', '12')
        AND SALES_DOCUMENT_ITEM_CATEGORY <> 'ZE12' -- ZE12 is External Order
)

, SO_NEGOTIATION AS (
    SELECT
        VBAK_SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM_POSNR
        , CRM_OPPORTUNITY_ID
        , BOOKING_CONFIDENCE
        , SALES_REP_EMPLOYEE_NO
        , VBAK_SALES_CATEGORY
        , SHORT_TEXT_FOR_SALES_ORDER_ITEM
        , ZSDT0015_PROJECT_DEF AS PROJECT_NUMBER
        , ZSDT0015_MODEL_TYPE AS CRM_MODEL_CODE
        , ZSDT0015_PRODUCT_CODE AS CRM_PRODUCT_CODE
        , ZSDT0013_TECHNICAL_ACCEPTANCE_TSR_SIGNATURE_UNAVAILABLE
        , CASE
            WHEN ZSDT0013_TECHNICAL_ACCEPTANCE_DATE = 0 THEN NULL
            ELSE TRY_TO_DATE(ZSDT0013_TECHNICAL_ACCEPTANCE_DATE,'YYYYMMDD')
        END AS TECH_ACCEPTANCE_DT
        , ZSDT0013_TECHNICAL_ACCEPTANCE_DATE_ACTUAL AS TECH_ACCEPTANCE_DT_ACTUAL
        , ZSDT0013_TECHNICAL_ACCEPTANCE_TSR_CUSTOMER_SIGNATURE_DATE_ACTUAL AS TECH_ACCEPTANCE_TSR_CUST_SIGN_DT_ACTUAL
        , TRY_TO_DATE(ZSDT0013_TECHNICAL_ACCEPTANCE_TSR_CUSTOMER_SIGNATURE_DATE,'YYYYMMDD') AS TECH_ACCEPTANCE_TSR_CUST_SIGN_DT
        , ZSDT0013_SERIAL_NO AS SERIAL_NUMBER
        , ZSDT0015_WORK_BREAKDOWN_STRUCTURE_ELEMENT_WBS_ELEMENT AS WORK_BREAKDOWN_STRUCTURE
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_NEGOTIATION_LINES') }}
)

, SOBL AS (
    SELECT
        VBAK_SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM_POSNR
        , VBAP_NET_PRICE AS SALES_ORDER_ITEM_NET_PRICE
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
)

, EMPLOYEE AS (
    SELECT
        EMPLOYEE_ID
        , FULL_NAME
    FROM {{ ref('PUB__COMMON_SYSTEM__EMPLOYEE') }}
),
CGM AS (
SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_GROUP_MAPPING') }}
)
, CUSTOMER AS(
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
        , SEARCH_TERM_2_FOR_BUSINESS_PARTNER AS CUSTOMER_NAME
        , NAME_1_OF_ORGANIZATION AS CUSTOMER
        , CORPORATION
        , CGM.CUSTOMER_GROUP
        , CGM.CUSTOMER_GROUP2
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    LEFT JOIN CGM
        ON CGM.ACCOUNT_NUMBER = CORPORATION
    WHERE LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B'
)
, SHIPTO AS (
    SELECT DISTINCT
        BUSINESS_PARTNER_NUMBER
        , CONCAT(CITY, ', ',REGION) AS SHIP_TO_LOCATION
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
    WHERE 1=1
        AND LEFT(BUSINESS_PARTNER_NUMBER,1) = 'C'
        AND COUNTRY_KEY IN ('US', 'CA', 'MX')
)

, SALES_CATEGORY AS (
    SELECT DISTINCT
        SAP_SALES_CATEGORY
        , SAP_SALES_CATEGORY_NAME AS SALES_CATEGORY_NAME
    FROM {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }}
)

, BU_GROUP AS (
    SELECT
        MATERIAL_NUMBER
        , MATERIAL_GROUP_1_TEXT AS BU_GROUP
    FROM {{ ref('COMMON__REPORTS__MASTER_MATERIAL_REPORT') }}
    WHERE MATERIAL_GROUP IN ( 'Z101', 'Z104')
)

, LEGACYOFFICE AS (
    SELECT
        B_CODE
        , LEGACY_OFFICE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
)
, SOURCE_DATA AS (
    SELECT
        CUSTOMER.CUSTOMER_GROUP
        , CUSTOMER.CUSTOMER_GROUP2
        , CUSTOMER.CUSTOMER
        , CUSTOMER.CUSTOMER_NAME
        , SO.SOLD_TO_CUSTOMER_CODE
        , SO.PRODUCT_CODE
        , SO.SALES_DOCUMENT
        , SO.SALES_DOCUMENT_ITEM
        , SALES_CATEGORY.SALES_CATEGORY_NAME
        , SO.ITEM_SHORT_TEXT
        , SOBL.SALES_ORDER_ITEM_NET_PRICE
        , SO.CRM_OPPORTUNITY_ID
        , SO_NEGOTIATION.PROJECT_NUMBER
        , CASE
            WHEN LEN(SO_NEGOTIATION.SERIAL_NUMBER)> 1 THEN SO_NEGOTIATION.SERIAL_NUMBER
            ELSE NULL
        END AS SERIAL_NUMBER
        , SO.DOCUMENT_DATE
        , SO.DELIVERY_CREATE_DATE
        , SO.DELIVERY_DATE
        , SO.LOCAL_PO_RECEIVE_DATE
        , SO.BOOKING_DATE
        , SO.END_USER_BOOKING_DATE
        , SO_NEGOTIATION.TECH_ACCEPTANCE_DT
        , SO_NEGOTIATION.TECH_ACCEPTANCE_DT_ACTUAL
        , SO_NEGOTIATION.TECH_ACCEPTANCE_TSR_CUST_SIGN_DT
        , SO_NEGOTIATION.TECH_ACCEPTANCE_TSR_CUST_SIGN_DT_ACTUAL
        , SO_NEGOTIATION.BOOKING_CONFIDENCE
        , SO.SALES_CATEGORY
        , SO_NEGOTIATION.CRM_PRODUCT_CODE
        , SO_NEGOTIATION.CRM_MODEL_CODE
        , E1.FULL_NAME AS SALES_REP_NAME
        , SO_NEGOTIATION.SALES_REP_EMPLOYEE_NO
        , SO.SALES_DOCUMENT_TYPE
        , SO.WORK_BREAKDOWN_STRUCTURE
        , SO.PROFIT_CENTER
        , LEGACYOFFICE.LEGACY_OFFICE
        , SO.MATERIAL_GROUP
        , SO.MATERIAL_GROUP1
        , SO.MATERIAL_NUMBER
        , SO.SALES_DOCUMENT_ITEM_CATEGORY
        , BU_GROUP.BU_GROUP
        , SO.SHIP_TO_CUSTOMER
        , SHIPTO.SHIP_TO_LOCATION
    FROM SO
        LEFT OUTER JOIN CUSTOMER
            ON SO.SOLD_TO_CUSTOMER_CODE = CUSTOMER.BUSINESS_PARTNER_NUMBER
        LEFT OUTER JOIN SALES_CATEGORY
            ON SO.SALES_CATEGORY = SALES_CATEGORY.SAP_SALES_CATEGORY
        LEFT OUTER JOIN SO_NEGOTIATION
            ON SO.SALES_DOCUMENT = SO_NEGOTIATION.VBAK_SALES_DOCUMENT
            AND SO.SALES_DOCUMENT_ITEM = SO_NEGOTIATION.SALES_DOCUMENT_ITEM_POSNR
        LEFT OUTER JOIN EMPLOYEE E1
            ON SO_NEGOTIATION.SALES_REP_EMPLOYEE_NO  = E1.EMPLOYEE_ID
        LEFT OUTER JOIN BU_GROUP
            ON SO.MATERIAL_NUMBER = BU_GROUP.MATERIAL_NUMBER
        LEFT OUTER JOIN LEGACYOFFICE
            ON SO.SOLD_TO_CUSTOMER_CODE  =  LEGACYOFFICE.B_CODE
        LEFT OUTER JOIN SHIPTO
            ON SO.SHIP_TO_CUSTOMER = SHIPTO.BUSINESS_PARTNER_NUMBER
        LEFT OUTER JOIN SOBL
            ON SO.SALES_DOCUMENT = SOBL.VBAK_SALES_DOCUMENT
            AND SO.SALES_DOCUMENT_ITEM = SOBL.SALES_DOCUMENT_ITEM_POSNR
)
,
TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        CUSTOMER_GROUP,
        CUSTOMER_GROUP2,
        CUSTOMER,
        CUSTOMER_NAME,
        SOLD_TO_CUSTOMER_CODE,
        PRODUCT_CODE,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
        SALES_CATEGORY_NAME,
        ITEM_SHORT_TEXT,
        SALES_ORDER_ITEM_NET_PRICE,
        CRM_OPPORTUNITY_ID,
        PROJECT_NUMBER,
        SERIAL_NUMBER,
        DOCUMENT_DATE,
        DELIVERY_CREATE_DATE,
        DELIVERY_DATE,
        LOCAL_PO_RECEIVE_DATE,
        BOOKING_DATE,
        END_USER_BOOKING_DATE,
        TECH_ACCEPTANCE_DT,
        TECH_ACCEPTANCE_DT_ACTUAL,
        TECH_ACCEPTANCE_TSR_CUST_SIGN_DT,
        TECH_ACCEPTANCE_TSR_CUST_SIGN_DT_ACTUAL,
        BOOKING_CONFIDENCE,
        SALES_CATEGORY,
        CRM_PRODUCT_CODE,
        CRM_MODEL_CODE,
        SALES_REP_NAME ,
        SALES_REP_EMPLOYEE_NO ,
        SALES_DOCUMENT_TYPE,
        WORK_BREAKDOWN_STRUCTURE ,
        PROFIT_CENTER,
        LEGACY_OFFICE,
        MATERIAL_NUMBER,
        MATERIAL_GROUP1,
        MATERIAL_GROUP,
        SALES_DOCUMENT_ITEM_CATEGORY,
        BU_GROUP,
        SHIP_TO_CUSTOMER,
        SHIP_TO_LOCATION
    FROM SOURCE_DATA
)
, TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
        CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
        , CUSTOMER
        , CUSTOMER_NAME
        , SOLD_TO_CUSTOMER_CODE
        , PRODUCT_CODE
        , SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM
        , SALES_CATEGORY_NAME
        , ITEM_SHORT_TEXT
        , CAST(SALES_ORDER_ITEM_NET_PRICE as NUMBER(38,0)) AS SALES_ORDER_ITEM_NET_PRICE
        , CRM_OPPORTUNITY_ID
        , PROJECT_NUMBER
        , SERIAL_NUMBER
        , CAST(DOCUMENT_DATE as DATE) AS DOCUMENT_DATE
        , CAST(DELIVERY_CREATE_DATE AS DATE) AS DELIVERY_CREATE_DATE
        , CAST(DELIVERY_DATE as DATE) AS DELIVERY_DATE
        , CAST(LOCAL_PO_RECEIVE_DATE as DATE) AS LOCAL_PO_RECEIVE_DATE
        , CAST(BOOKING_DATE as DATE) AS BOOKING_DATE
        , CAST(END_USER_BOOKING_DATE as DATE) AS END_USER_BOOKING_DATE
        , CAST(TECH_ACCEPTANCE_DT as DATE) AS TECH_ACCEPTANCE_DT
        , TECH_ACCEPTANCE_DT_ACTUAL
        , CAST(TECH_ACCEPTANCE_TSR_CUST_SIGN_DT as DATE) AS TECH_ACCEPTANCE_TSR_CUST_SIGN_DT
        , TECH_ACCEPTANCE_TSR_CUST_SIGN_DT_ACTUAL
        , BOOKING_CONFIDENCE
        , SALES_CATEGORY
        , CRM_PRODUCT_CODE
        , CRM_MODEL_CODE
        , SALES_REP_NAME
        , SALES_REP_EMPLOYEE_NO
        , SALES_DOCUMENT_TYPE
        , WORK_BREAKDOWN_STRUCTURE
        , PROFIT_CENTER
        , LEGACY_OFFICE
        , MATERIAL_NUMBER
        , MATERIAL_GROUP1
        , MATERIAL_GROUP
        , SALES_DOCUMENT_ITEM_CATEGORY
        , BU_GROUP
        , SHIP_TO_CUSTOMER
        , SHIP_TO_LOCATION
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
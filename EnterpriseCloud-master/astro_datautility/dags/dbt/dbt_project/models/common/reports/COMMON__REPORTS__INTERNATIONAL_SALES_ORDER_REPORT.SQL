with cost_center as (
select
    COST_CENTER_CODE,
    SEGMENT_CODE as SECURITY_SEGMENT,
    DEPARTMENT_CODE as SECURITY_DEPARTMENT,
    OFFICE_CODE as SECURITY_OFFICE
from {{ ref('ODS__FILE__COST_CENTER') }}),

profit_center as (
select
    PROFIT_CENTER_CODE,
    PROFIT_CENTER_NAME,
    SEGMENT_CODE,
    SEGMENT,
    DEPARTMENT_CODE,
    DEPARTMENT,
    OFFICE_CODE,
    OFFICE
from {{ ref('ODS__FILE__PROFIT_CENTER') }}),

vbpa as (
    select * from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU047_VBPA') }}
    where UPPER(IS_DELETED) = 'NO' 
),

source_data as (
    select
        VBAK_SALES_DOCUMENT as SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM_POSNR as ITEM,
        VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM as SHORT_TEXT_FOR_SALES_ORDER_ITEM,
        VBAK_SALES_ORGANIZATION as SALES_ORGANIZATION,
        LIKP_DELIVERY as DELIVERY,
        VBAK_SOLD_TO_PARTY as SOLD_TO_PARTY,
        -- sold to party addr
        adrc_sp.NAME1 as SOLD_TO_NAME,
        adrc_sp.HOUSENUM1 as SOLD_TO_HOUSENUM,
        adrc_sp.STREET as SOLD_TO_STREET,
        adrc_sp.POSTCODE1 as SOLD_TO_POSTCODE,
        adrc_sp.CITY1 as SOLD_TO_CITY,
        adrc_sp.COUNTRY as SOLD_TO_COUNTRY,
        SHIP_TO_PARTY,
        --ship to addr
        adrc1.NAME1 as SHIP_TO_NAME,
        adrc1.HOUSENUM1 as SHIP_TO_HOUSENUM,
        adrc1.STREET as SHIP_TO_STREET,
        adrc1.POSTCODE1 as SHIP_TO_POSTCODE,
        adrc1.CITY1 as SHIP_TO_CITY,
        adrc1.COUNTRY as SHIP_TO_COUNTRY,
        PLANNED_GOODS_MOVEMENT_DATE as PLANNED_GOODS_MOVEMENT_DATE,
        DELIVERY_TYPE_LFART as DELIVERY_TYPE,
        VBAP_SHIPPING_POINT_RECEIVING_POINT as SHIPPING_POINT_RECEIVING_POINT,
        PICKING_DATE as PICKING_DATE,
        LIKP_TRANSPORTATION_PLANNING_DATE as TRANSPORTATION_PLANNING_DATE,
        DELIVERY_DATE_LFDAT as DELIVERY_DATE,
        MATERIAL_NUMBER as MATERIAL_NUMBER,
        CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS as CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
        VBAP_NET_PRICE as NET_PRICE,
        CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS*VBAP_NET_PRICE as CUMULATIVE_ORDER_NET_PRICE,
        VBAP_SALES_UNIT as SALES_UNIT,
        VBAK_MATERIAL_STAGING_AVAILABILITY_DATE as MATERIAL_STAGING_AVAILABILITY_DATE,
        GROSS_WEIGHT_OF_THE_ITEM as GROSS_WEIGHT,
        VBAP_WEIGHT_UNIT as WEIGHT_UNIT,
        -- storage location details
        STORAGE_LOCATION_VBAP as STORAGE_LOCATION,
        adrc_sl.NAME1 as SLOC_NAME,
        adrc_sl.HOUSENUM1 as SLOC_HOUSENUM,
        adrc_sl.STREET as SLOC_STREET,
        adrc_sl.POSTCODE1 as SLOC_POSTCODE,
        adrc_sl.CITY1 as SLOC_CITY,
        adrc_sl.COUNTRY as SLOC_COUNTRY,
        PLANT_VBAP as PLANT,
        -- pick up party addr
        adrc_pu.NAME1 as PICK_UP_NAME,
        adrc_pu.HOUSENUM1 as PICK_UP_HOUSENUM,
        adrc_pu.STREET as PICK_UP_STREET,
        adrc_pu.POSTCODE1 as PICK_UP_POSTCODE,
        adrc_pu.CITY1 as PICK_UP_CITY,
        adrc_pu.COUNTRY as PICK_UP_COUNTRY,
        -- end user addr
        vbpa_eu.KUNNR as END_USER_KUNNR,
        adrc_eu.NAME1 as END_USER_NAME, --end user
        adrc_eu.HOUSENUM1 as END_USER_HOUSENUM,
        adrc_eu.STREET as END_USER_STREET,
        adrc_eu.POSTCODE1 as END_USER_POSTCODE,
        adrc_eu.CITY1 as END_USER_CITY,
        adrc_eu.COUNTRY as END_USER_COUNTRY,
        CONFIRMED_CUSTOMS_CLEARANCE_DATE as CONFIRMED_CUSTOMS_CLEARANCE_DATE,
        VBAP_GTM_SENDING_FLAG as GTM_SENDING_FLAG,
        VBAP_PROFIT_CENTER as PROFIT_CENTER,
        VBAP_COST_CENTER as COST_CENTER,
        '<ALL>' as SECURITY_SEGMENT,
        '<ALL>' as SECURITY_DEPARTMENT,
        '<ALL>' as SECURITY_OFFICE
    from {{ ref('COMMON__SAPH__SALES_ORDER_DELIVERY_LINE') }}
    left join (SELECT NAME_1,CUSTOMER_NUMBER,ADDRESS_NUMBER FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }} WHERE CUSTOMER_FLAG='Y') kna1
        on SHIP_TO_PARTY = kna1.CUSTOMER_NUMBER  -- ship to party
    left join {{ ref('ODS__SAPAPI__ZCDV_T_CMTU087_ADRC') }} adrc1 on kna1.ADDRESS_NUMBER = adrc1.ADDRNUMBER and adrc1.NATION = 'I'
    left join vbpa vbpa_sp on --sold to party
        VBAK_SALES_DOCUMENT = vbpa_sp.VBELN and
        VBAK_SOLD_TO_PARTY = vbpa_sp.KUNNR and
        vbpa_sp.PARVW = 'SP'
    left join {{ ref('ODS__SAPAPI__ZCDV_T_CMTU087_ADRC') }} adrc_sp on vbpa_sp.ADRNR = adrc_sp.ADDRNUMBER and adrc_sp.NATION = 'I'
    left join vbpa vbpa_pu on --pick up location
        VBAK_SALES_DOCUMENT = vbpa_pu.VBELN and
        SALES_DOCUMENT_ITEM_POSNR = vbpa_pu.POSNR and
        vbpa_pu.PARVW = 'Z7'
    left join {{ ref('ODS__SAPAPI__ZCDV_T_CMTU087_ADRC') }} adrc_pu on vbpa_pu.ADRNR = adrc_pu.ADDRNUMBER and adrc_pu.NATION = 'I'
    left join vbpa vbpa_eu on -- end user
        VBAK_SALES_DOCUMENT = vbpa_eu.VBELN and
        SALES_DOCUMENT_ITEM_POSNR = vbpa_eu.POSNR and
        vbpa_eu.PARVW = 'Z6'
    left join {{ ref('ODS__SAPAPI__ZCDV_T_CMTU087_ADRC') }} adrc_eu on vbpa_eu.ADRNR = adrc_eu.ADDRNUMBER and adrc_eu.NATION = 'I'
    left outer join cost_center
        on COST_CENTER=cost_center.COST_CENTER_CODE
    left join {{ ref('ODS__SAPAPI__ZCDV_T_CMTU203_TWLAD') }} twlad on
        VBAK_SALES_ORGANIZATION = twlad.WERKS and 
        STORAGE_LOCATION_VBAP = twlad.LGORT
    left join {{ ref('ODS__SAPAPI__ZCDV_T_CMTU087_ADRC') }} adrc_sl
        on twlad.ADRNR = adrc_sl.ADDRNUMBER
    left outer join profit_center
        on PROFIT_CENTER=profit_center.PROFIT_CENTER_CODE
    where
        VBAK_SALES_ORGANIZATION is not null and
        SHIP_TO_COUNTRY <> 'US'
),

transform_data as (
    select
        SALES_DOCUMENT,
        ITEM,
        SHORT_TEXT_FOR_SALES_ORDER_ITEM,
        SALES_ORGANIZATION,
        DELIVERY,
        SOLD_TO_PARTY,
        SOLD_TO_NAME,
        SOLD_TO_HOUSENUM,
        SOLD_TO_STREET,
        SOLD_TO_POSTCODE,
        SOLD_TO_CITY,
        SOLD_TO_COUNTRY,
        SHIP_TO_PARTY,
        SHIP_TO_NAME,
        SHIP_TO_HOUSENUM,
        SHIP_TO_STREET,
        SHIP_TO_POSTCODE,
        SHIP_TO_CITY,
        SHIP_TO_COUNTRY,
        PLANNED_GOODS_MOVEMENT_DATE,
        DELIVERY_TYPE,
        SHIPPING_POINT_RECEIVING_POINT,
        PICKING_DATE,
        TRANSPORTATION_PLANNING_DATE,
        DELIVERY_DATE,
        MATERIAL_NUMBER,
        CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
        NET_PRICE,
        CUMULATIVE_ORDER_NET_PRICE,
        SALES_UNIT,
        MATERIAL_STAGING_AVAILABILITY_DATE,
        GROSS_WEIGHT,
        WEIGHT_UNIT,
        STORAGE_LOCATION,
        SLOC_NAME,
        SLOC_HOUSENUM,
        SLOC_STREET,
        SLOC_POSTCODE,
        SLOC_CITY,
        SLOC_COUNTRY,
        PLANT,
        PICK_UP_NAME,
        PICK_UP_HOUSENUM,
        PICK_UP_STREET,
        PICK_UP_POSTCODE,
        PICK_UP_CITY,
        PICK_UP_COUNTRY,
        END_USER_KUNNR,
        END_USER_NAME,
        END_USER_HOUSENUM,
        END_USER_STREET,
        END_USER_POSTCODE,
        END_USER_CITY,
        END_USER_COUNTRY,
        CONFIRMED_CUSTOMS_CLEARANCE_DATE,
        GTM_SENDING_FLAG,
        PROFIT_CENTER,
        COST_CENTER,
        SECURITY_SEGMENT,
        SECURITY_DEPARTMENT,
        SECURITY_OFFICE,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    from source_data
),


{{ config(
        alias = 'SAPH_MATERIAL_VALUATION_HISTORY',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with source_data as (
    SELECT
        MBEWH.matnr as MATERIAL_NUMBER,
        mara.MAKTX AS MATERIAL_DESCRIPTION,
        MBEWH.BWKEY AS COMPANY_CODE,
        MBEWH.LFGJA AS FISCAL_YEAR,
        MBEWH.LFMON AS FISCAL_PERIOD,
        MBEWH.STPRS AS STANDARD_COST,
        CASE WHEN PM.CONDITION_AMOUNT_OR_PERCENTAGE_WHERE_NO_SCALE_EXISTS IS NOT NULL THEN PM.CONDITION_AMOUNT_OR_PERCENTAGE_WHERE_NO_SCALE_EXISTS
             ELSE LAG(PM.CONDITION_AMOUNT_OR_PERCENTAGE_WHERE_NO_SCALE_EXISTS) IGNORE NULLS OVER(ORDER BY MBEWH.matnr,MBEWH.BWKEY,MBEWH.LFGJA,MBEWH.LFMON) 
        END AS SALES_PRICE
FROM
    {{ ref('ODS__SAPAPI__ZCDV_T_CMTU243_MBEWH') }} MBEWH
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} MARA
        ON MBEWH.matnr=MARA.matnr
    LEFT JOIN 
    (
        SELECT
            MATERIAL_NUMBER,
            CONDITION_AMOUNT_OR_PERCENTAGE_WHERE_NO_SCALE_EXISTS,
            VALIDITY_END_DATE_OF_THE_CONDITION_RECORD,
            VALIDITY_START_DATE_OF_THE_CONDITION_RECORD
        FROM {{ ref('COMMON__SAPH__PRICE_MATRIX') }}
        WHERE PRICING_COUNTRY='US' 
        ORDER BY material_number) PM
    ON MBEWH.matnr=PM.material_number
    AND concat(LFGJA,'-',lfmon)<=substr(to_date(VALIDITY_END_DATE_OF_THE_CONDITION_RECORD,'YYYYMMDD'),1,7)
    AND concat(LFGJA,'-',lfmon)>=substr(to_date(VALIDITY_START_DATE_OF_THE_CONDITION_RECORD,'YYYYMMDD'),1,7)
    WHERE
        MBEWH.BWKEY='3200'AND MBEWH.LFGJA>='2023'
),

transform_data as (
SELECT
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    COMPANY_CODE,
    FISCAL_YEAR,
    FISCAL_PERIOD,
    STANDARD_COST,
    SALES_PRICE,
    '{{ invocation_id }}' AS AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
FROM source_data
),

type_data as (
select
    CAST(MATERIAL_NUMBER as VARCHAR(16777216)) AS MATERIAL_NUMBER,
    CAST(MATERIAL_DESCRIPTION as VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
    CAST(COMPANY_CODE as VARCHAR(16777216)) AS COMPANY_CODE,
    CAST(FISCAL_YEAR as VARCHAR(16777216)) AS FISCAL_YEAR,
    CAST(FISCAL_PERIOD AS VARCHAR(16777216)) AS FISCAL_PERIOD,
    CAST(STANDARD_COST AS NUMBER(38,2)) AS STANDARD_COST,
    CAST(SALES_PRICE AS NUMBER(38,2)) AS SALES_PRICE,
    CAST(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
from transform_data
)

select * from type_data
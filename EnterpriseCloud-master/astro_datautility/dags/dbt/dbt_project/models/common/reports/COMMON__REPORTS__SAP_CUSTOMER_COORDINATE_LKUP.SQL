WITH 
ZIP AS (
    SELECT 
        POSTAL_CODE,
        P.COUNTRY_CODE,
        AVG(P.LATITUDE) AS LAT,
        AVG(P.LONGITUDE) AS LNG,
        COUNT(*) AS RECORD_CNT
    FROM {{ ref('ODS__FILE__OPENDATASOFT_POSTALCODE_GEODATA') }} AS P
    GROUP BY P.POSTAL_CODE, P.COUNTRY_CODE
),
ZIP_MATCH AS (
    SELECT 
        KNA1.KUNNR, ZIP.LAT, ZIP.LNG, KNA1.ORT01
    FROM ODS.SAPAPI.ZCDV_T_CMTU020_KNA1 AS KNA1
    JOIN ZIP ON (
        (
            SPLIT_PART(KNA1.PSTLZ, '-', 1) = ZIP.POSTAL_CODE OR
            KNA1.PSTLZ = ZIP.POSTAL_CODE
        )
        AND 
        ZIP.COUNTRY_CODE = KNA1.LAND1
    )
),
DISTINCT_CUSTOMER_CITIES AS (
    SELECT DISTINCT KNA1.ORT01, KNA1.REGIO, KNA1.LAND1
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} AS KNA1
    WHERE KNA1.KUNNR NOT IN (SELECT KUNNR FROM ZIP_MATCH)
),
-- We don't want to consider common suffixes like "County", "City", and "Province" (in any language)
-- Machi = City (JP)
-- Gun = District / County (JP)
STR_DISTS AS (
    SELECT 
        EDITDISTANCE(
            REPLACE(REGEXP_REPLACE(UPPER(W.CITY_ASCII), 'CITY|COUNTY|PROVINCE|-SHI|-SI|-KU|-MACHI|-GUN', ''), '-', ''), 
            REPLACE(REGEXP_REPLACE(UPPER(C.ORT01), 'CITY|COUNTY|PROVINCE|-SHI|-SI|-KU|-MACHI|-GUN', ''), '-', '')
        ) / GREATEST(LEN(C.ORT01), LEN(W.CITY)) AS DIST, 
        C.ORT01 AS SAP_CITY,
        C.LAND1 AS SAP_NATION,
        W.CITY_ASCII AS DATASET_CITY,
        W.LAT,
        W.LNG
    FROM {{ ref('ODS__FILE__WORLDCITIES_DB') }} AS W
    JOIN DISTINCT_CUSTOMER_CITIES AS C ON (
        C.LAND1 = W.ISO2 AND 
        LEFT(UPPER(W.CITY_ASCII), 1) = LEFT(UPPER(C.ORT01), 1)
    )
),
RNKS AS (
    SELECT 
        D.*,
        ROW_NUMBER() OVER(PARTITION BY D.SAP_CITY ORDER BY D.DIST) AS RN_SAP,
        ROW_NUMBER() OVER(PARTITION BY D.DATASET_CITY ORDER BY D.DIST) AS RN_DTA
    FROM STR_DISTS AS D
),
CITY_FINAL AS (
    SELECT * FROM RNKS WHERE RN_SAP = 1 AND DIST < .15
),
REPORT_CITY_ZIP AS (
    SELECT 
        KNA1.KUNNR, 
        COALESCE(ZIP_MATCH.LAT, CF.LAT) AS LAT, 
        COALESCE(ZIP_MATCH.LNG, CF.LNG) AS LNG, 
        KNA1.LAND1 AS NATION, 
        KNA1.REGIO AS PROV, 
        KNA1.PSTLZ AS POSTAL_CODE, 
        KNA1.ORT01 AS CITY,
        CASE 
            WHEN ZIP_MATCH.LAT IS NOT NULL THEN 'POSTAL_CODE'
            WHEN CF.LAT IS NOT NULL THEN 'CITY'
            ELSE NULL
        END AS LEVEL,
        CF.DIST AS CITY_STR_DIST,
        CF.DATASET_CITY AS MATCHED_CITY_NAME
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} AS KNA1
    LEFT JOIN ZIP_MATCH ON (KNA1.KUNNR = ZIP_MATCH.KUNNR)
    LEFT JOIN CITY_FINAL AS CF ON (CF.SAP_CITY = KNA1.ORT01 AND CF.SAP_NATION = KNA1.LAND1)
),
-- For any remaining records we can't match by zip code, match by province instead.
PROVINCE_AVG AS (
    SELECT NATION, PROV, AVG(LAT) AS LAT, AVG(LNG) AS LNG
    FROM REPORT_CITY_ZIP 
    WHERE LEVEL IS NOT NULL
    GROUP BY NATION, PROV
),
SOURCE_DATA AS (
    SELECT
        R.KUNNR AS SAP_CUSTOMER_ID,
        COALESCE(R.LAT, P.LAT) AS LAT,
        COALESCE(R.LNG, P.LNG) AS LNG,
        R.NATION,
        R.PROV,
        R.POSTAL_CODE,
        R.CITY,
        CASE WHEN R.LEVEL IS NULL AND P.PROV IS NOT NULL THEN 'PROV' ELSE R.LEVEL END AS LEVEL
    FROM REPORT_CITY_ZIP AS R
    LEFT JOIN PROVINCE_AVG AS P ON (R.NATION = P.NATION AND R.PROV = P.PROV)
),
TYPE_DATA AS (
    SELECT
        CAST(SAP_CUSTOMER_ID AS VARCHAR(16777216)) AS SAP_CUSTOMER_ID,
        CAST(LAT AS FLOAT) AS LAT,
        CAST(LNG AS FLOAT) AS LNG,
        CAST(NATION AS VARCHAR(16777216)) AS NATION,
        CAST(PROV AS VARCHAR(16777216)) AS PROV,
        CAST(POSTAL_CODE AS VARCHAR(16777216)) AS POTAL_CODE,
        CAST(CITY AS VARCHAR(16777216)) AS CITY,
        CAST(LEVEL AS VARCHAR(16777216)) AS LEVEL
    FROM SOURCE_DATA
)
SELECT * FROM TYPE_DATA
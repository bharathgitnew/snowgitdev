        BILLING_TYPE,
        al.REF_INVOICE,
        al.REF_FISCAL_YEAR,
        al.REF_LINE_ITEM,
        from ALL_DOC_TYPES1 as al
        left join  Additional_data as ad 
        on al.ACCOUNTING_DOCUMENT = ad.ACCOUNTING_DOCUMENT
        and to_number(al.ACCOUNTING_DOCUMENT_LINE) = to_number(ad.ACCOUNTING_DOCUMENT_LINE)
        and al.GL_FISCAL_YEAR = ad.GL_FISCAL_YEAR
        --and  al.GL = AD.account_number
),

UJSL_NEW AS (
    SELECT vbkd.BSTKD AS VBKD_CUSTOMER_REFERENCE,
    vbkd.VBELN AS VBKD_SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU069_VBKD') }} vbkd 
    WHERE POSNR = '000000'
),

SOBL AS (
        SELECT
        NULL AS DELIVERY_DOCUMENT,
        vbrk_bill.FKART AS SALES_BILLING_TYPE,
        vbrp_bill.VBELN AS BILLING_DOCUMENT,
        vbak.BSTNK AS CUSTOMER_REFERENCE,
        vbak.AUART AS VBAK_SALES_DOCUMENT_TYPE,
        vbap.VBELN AS VBAK_SALES_DOCUMENT
    FROM (select * from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }}  where IS_DELETED = 'No') vbak --Sales Head
        LEFT JOIN ( select * from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }}  where IS_DELETED = 'No') vbap --Sales Line
            ON try_to_number(vbap.VBELN) = try_to_number(vbak.VBELN)
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU064_VBFA') }}   vbfa -- Delivery Line
            ON try_to_number(vbfa.vbelv) = try_to_number(vbap.VBELN) AND try_to_number(vbfa.posnv) = try_to_number(vbap.POSNR)
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU015_VBRP') }}  vbrp_bill -- Billing Document Item
            ON try_to_number(vbrp_bill.VGBEL)= try_to_number(vbfa.vbelv) AND try_to_number(vbrp_bill.VBELN) = try_to_number(vbfa.VBELN) and try_to_number(vbrp_bill.posnr) = try_to_number(vbfa.posnn) 
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU014_VBRK') }}  vbrk_bill -- Billing Document Head
            ON try_to_number(vbrk_bill.VBELN) = try_to_number(vbrp_bill.VBELN)
    WHERE vbak.AUART IN ('ZSC1', 'ZC11')
            AND ((VBFA.VBTYP_N in ('M','N')) OR (VBFA.VBTYP_N is NULL))
UNION 
    SELECT DISTINCT
        LISTAGG(DISTINCT SOBL.LIPS_DELIVERY, ', ') OVER (PARTITION BY SOBL.SALES_BILLING_DOCUMENT) as DELIVERY_DOCUMENT
        , SOBL.SALES_BILLING_TYPE 
        , SOBL.SALES_BILLING_DOCUMENT AS BILLING_DOCUMENT
        , SOBL.CUSTOMER_REFERENCE --do not use, VBAK.BSTNK truncates data
        , SOBL.VBAK_SALES_DOCUMENT_TYPE
        , SOBL.VBAK_SALES_DOCUMENT
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}  SOBL
    INNER JOIN ALL_DOC_TYPES
    ON TRY_TO_NUMBER(ALL_DOC_TYPES.BILLING_DOCUMENT) = TRY_TO_NUMBER(SOBL.SALES_BILLING_DOCUMENT)
    WHERE VBAK_SALES_ORGANIZATION = '3200'
    AND SOBL.VBAK_SALES_DOCUMENT_TYPE NOT IN ('ZSC1', 'ZC11')
    AND SOBL.VBAK_SALES_DOCUMENT_TYPE IS NOT NULL
),

BUS_PARTNER AS (
    SELECT DISTINCT
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER AS SALES_DOCUMENT
        , ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM
        , CUSTOMER_NUMBER
        , PARTNER_FUNCTION
    FROM  {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }} 
    WHERE PARTNER_FUNCTION IN ('SP', 'BP') 
),

CUSTOMER_DETAIL AS (
    SELECT DISTINCT
        CUSTOMER_NUMBER
        , NAME_1 AS CUSTOMER_NAME
        , CITY
        , REGION
    FROM   {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }} 
    WHERE CUSTOMER_FLAG ='Y'
),

CTE_LEGACY_AROPENENTRIES AS (
    SELECT DISTINCT DOCUMENT AS DOCUMENT_AROPENENTRIES,
    CUST_PO,
    SHIPMENT_IDENTIFICATION_NO 
    FROM COMMON.BAAN.FILE_AROPENENTRIES
),

VBRK_VBAK AS (
    SELECT 
    DISTINCT 
    TRY_TO_NUMBER(VBAK.VBELN) AS VBELN,
    VBRK.VBELN AS VBRK_BILLING_DOCUMENT,
    VBRK.ZUONR,
    VBRK.FKART AS VBRK_BILLING_TYPE,
    VBAK.AUART AS VBAK_SALES_DOCUMENT_TYPE
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU014_VBRK') }}  VBRK 
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} VBAK
    ON TRY_TO_NUMBER(VBAK.VBELN) = TRY_TO_NUMBER(VBRK.ZUONR)
),

SOURCE_DATA AS (
    SELECT
        ALL_DOC_TYPES.CUSTOMER_NUMBER AS CUSTOMER_NUMBER
        , CUSTOMER_INFO.CUSTOMER_NAME AS CUSTOMER_NAME
        , BILL_TO.CUSTOMER_NUMBER AS BILL_TO_PARTY
        , BILL_TO_NAME.CUSTOMER_NAME AS BILL_TO_NAME
        , SOLD_TO.CUSTOMER_NUMBER AS SOLD_TO_PARTY
        , SOLD_TO_INFO.CUSTOMER_NAME AS SOLD_TO_NAME
        , ALL_DOC_TYPES.ACCOUNT_NUMBER as ACCOUNT_NUMBER
        , VBKD_CUSTOMER_REFERENCE as CUSTOMER_REFERENCE
        , ALL_DOC_TYPES.SALES_DOCUMENT AS SALES_DOCUMENT
        , ALL_DOC_TYPES.GL_FISCAL_YEAR AS GL_FISCAL_YEAR
        , ALL_DOC_TYPES.ACCOUNTING_DOCUMENT AS ACCOUNTING_DOCUMENT
        , ALL_DOC_TYPES.ACCOUNTING_DOCUMENT_LINE AS ACCOUNTING_DOCUMENT_LINE
        , case when SOBL.SALES_BILLING_TYPE is null then BILLING_TYPE else SOBL.SALES_BILLING_TYPE end AS BILLING_TYPE
        , ALL_DOC_TYPES.DOCUMENT_TYPE AS DOCUMENT_TYPE
        , ALL_DOC_TYPES.DOCUMENT_DATE AS DOCUMENT_DATE
        , ALL_DOC_TYPES.BASELINE_DATE_FOR_DUE_DATE_CALCULATION AS BASELINE_DATE_FOR_DUE_DATE_CALCULATION
        , ALL_DOC_TYPES.REFERENCE_DOCUMENT AS REFERENCE_DOCUMENT
        , ALL_DOC_TYPES.DOCUMENT_HEADER_TEXT AS DOCUMENT_HEADER_TEXT
        , ALL_DOC_TYPES.ITEM_TEXT AS ITEM_TEXT
        , ALL_DOC_TYPES.AMOUNT AS AMOUNT
        , CUSTOMER_INFO.CITY AS CUSTOMER_CITY
        , CUSTOMER_INFO.REGION AS CUSTOMER_REGION
        , SOLD_TO_INFO.CITY AS SOLD_TO_CITY
        , SOLD_TO_INFO.REGION AS SOLD_TO_REGION
        , ALL_DOC_TYPES.BILLING_DOCUMENT AS BILLING_DOCUMENT
        , SOBL.DELIVERY_DOCUMENT AS DELIVERY_DOCUMENT
        , ALL_DOC_TYPES.DUE_DATE AS DUE_DATE
        , ALL_DOC_TYPES.PROFIT_CENTER AS PROFIT_CENTER
        , ALL_DOC_TYPES.COMPANY_CODE
        , CASE WHEN BKPF.REF_TRANS = 'VBRK' THEN BKPF.REF_KEY
          ELSE ALL_DOC_TYPES.REF_INVOICE
          END AS ORIGINAL_BILLING_DOCUMENT
        , CASE WHEN SOBL_NEW.SALES_BILLING_TYPE IS NULL THEN VBRK_VBAK.VBRK_BILLING_TYPE
          ELSE SOBL_NEW.SALES_BILLING_TYPE
          END AS ORIGINAL_BILLING_TYPE
        , CASE WHEN SOBL.VBAK_SALES_DOCUMENT_TYPE IS NULL THEN VBRK_VBAK_NEW.VBAK_SALES_DOCUMENT_TYPE
          ELSE SOBL.VBAK_SALES_DOCUMENT_TYPE
          END AS SALES_DOCUMENT_TYPE
        --, SOBL_NEW.SALES_BILLING_TYPE AS ORIGINAL_BILLING_TYPE
        --, SOBL.VBAK_SALES_DOCUMENT_TYPE AS SALES_DOCUMENT_TYPE 
    FROM ALL_DOC_TYPES as ALL_DOC_TYPES
    LEFT JOIN SOBL
        ON TRY_TO_NUMBER(ALL_DOC_TYPES.BILLING_DOCUMENT) = TRY_TO_NUMBER(SOBL.BILLING_DOCUMENT)
    LEFT JOIN UJSL_NEW 
        ON TRY_TO_NUMBER(VBKD_SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER) = TRY_TO_NUMBER(ALL_DOC_TYPES.SALES_DOCUMENT)
    LEFT JOIN CUSTOMER_DETAIL AS CUSTOMER
        ON ALL_DOC_TYPES.CUSTOMER_NUMBER = CUSTOMER.CUSTOMER_NUMBER
    LEFT JOIN BUS_PARTNER AS BILL_TO
        ON TRY_TO_NUMBER(ALL_DOC_TYPES.SALES_DOCUMENT) = TRY_TO_NUMBER(BILL_TO.SALES_DOCUMENT)
        AND BILL_TO.PARTNER_FUNCTION = 'BP'
        AND TRY_TO_NUMBER(BILL_TO.SALES_DOCUMENT_ITEM) = 0
    LEFT JOIN BUS_PARTNER AS SOLD_TO
        ON TRY_TO_NUMBER(ALL_DOC_TYPES.SALES_DOCUMENT) = TRY_TO_NUMBER(SOLD_TO.SALES_DOCUMENT)
        AND SOLD_TO.PARTNER_FUNCTION = 'SP'
    LEFT JOIN CUSTOMER_DETAIL AS CUSTOMER_INFO
        ON CUSTOMER_INFO.CUSTOMER_NUMBER = ALL_DOC_TYPES.CUSTOMER_NUMBER
    LEFT JOIN CUSTOMER_DETAIL AS SOLD_TO_INFO
        ON SOLD_TO.CUSTOMER_NUMBER = SOLD_TO_INFO.CUSTOMER_NUMBER
    LEFT JOIN CUSTOMER_DETAIL AS BILL_TO_NAME
        ON BILL_TO.CUSTOMER_NUMBER = BILL_TO_NAME.CUSTOMER_NUMBER   
    LEFT JOIN BKPF AS BKPF 
        ON BKPF.ACCOUNTING_DOCUMENT = ALL_DOC_TYPES.REF_INVOICE
        AND BKPF.GL_FISCAL_YEAR = ALL_DOC_TYPES.REF_FISCAL_YEAR 
    LEFT JOIN SOBL AS SOBL_NEW
        ON TRY_TO_NUMBER(SOBL_NEW.BILLING_DOCUMENT) = TRY_TO_NUMBER(ORIGINAL_BILLING_DOCUMENT)
    LEFT JOIN VBRK_VBAK
        ON TRY_TO_NUMBER(ORIGINAL_BILLING_DOCUMENT) = VBRK_VBAK.VBRK_BILLING_DOCUMENT 
    LEFT JOIN (SELECT DISTINCT VBELN,VBAK_SALES_DOCUMENT_TYPE FROM VBRK_VBAK) AS VBRK_VBAK_NEW
        ON TRY_TO_NUMBER(ALL_DOC_TYPES.SALES_DOCUMENT) = VBRK_VBAK_NEW.VBELN  
),

TRANSFORM_DATA AS (
     SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH,
        ACCOUNT_NUMBER
        ,CUSTOMER_NUMBER
        , CUSTOMER_NAME
        , CASE 
            WHEN DOCUMENT_TYPE <> 'ZX' AND BILL_TO_PARTY IS NOT NULL THEN BILL_TO_PARTY --NON-MIGRATION ITEMS
            ELSE CUSTOMER_NUMBER --MIGRATION ITEMS AND NON-MIGRATION ITEMS WITHOUT A SAP SALES ORDER
        END AS BILL_TO_PARTY
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' AND BILL_TO_PARTY IS NOT NULL THEN BILL_TO_NAME --NON-MIGRATION ITEMS
            ELSE CUSTOMER_NAME --MIGRATION ITEMS AND NON-MIGRATION ITEMS WITHOUT A SAP SALES ORDER
        END AS BILL_TO_NAME
        , SOLD_TO_PARTY
        , SOLD_TO_NAME
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' THEN CUSTOMER_REFERENCE --NON-MIGRATION ITEMS
            ELSE '' --MIGRATION ITEMS
        END AS CUSTOMER_PO
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' THEN SALES_DOCUMENT --NON-MIGRATION ITEMS
            ELSE DOCUMENT_HEADER_TEXT --MIGRATION ITEMS
        END AS SALES_DOCUMENT
        , GL_FISCAL_YEAR
        , ACCOUNTING_DOCUMENT
        , ACCOUNTING_DOCUMENT_LINE
        , BILLING_TYPE
        , DOCUMENT_TYPE
        , CASE
            WHEN DOCUMENT_TYPE <> 'RV' THEN ACCOUNTING_DOCUMENT
            ELSE BILLING_DOCUMENT
        END AS BILLING_DOCUMENT
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' THEN ITEM_TEXT --NON-MIGRATION ITEMS
            ELSE REFERENCE_DOCUMENT --MIGRATION ITEMS
        END AS REFERENCE_DOCUMENT
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' THEN TRY_TO_DATE(DOCUMENT_DATE, 'YYYYMMDD')--NON-MIGRATION ITEMS 
            ELSE TRY_TO_DATE(BASELINE_DATE_FOR_DUE_DATE_CALCULATION, 'YYYYMMDD') --MIGRATION ITEMS
        END AS BILLING_DATE
        ,TRY_TO_DATE(DUE_DATE,'YYYYMMDD') AS DUE_DATE
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' THEN 
            DATEDIFF(DAY,TRY_TO_DATE(DOCUMENT_DATE,'YYYYMMDD'),LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE), 'MONTH')) --NON-MIGRATION ITEMS
            ELSE
           DATEDIFF(DAY, TRY_TO_DATE(BASELINE_DATE_FOR_DUE_DATE_CALCULATION, 'YYYYMMDD'), LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE), 'MONTH')) --MIGRATION ITEMS
        END AS DAYS_SINCE_INVOICING
        , AMOUNT AS BILLING_AMOUNT
        , PROFIT_CENTER
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' AND SOLD_TO_PARTY IS NOT NULL THEN SOLD_TO_CITY --NON-MIGRATION ITEMS
            ELSE CUSTOMER_CITY --MIGRATION ITEMS AND NON-MIGRATION ITEMS WITHOUT A SAP SALES ORDER
        END AS CUSTOMER_CITY
        , CASE
            WHEN DOCUMENT_TYPE <> 'ZX' AND SOLD_TO_PARTY IS NOT NULL THEN SOLD_TO_REGION --NON-MIGRATION ITEMS
            ELSE CUSTOMER_REGION --MIGRATION ITEMS AND NON-MIGRATION ITEMS WITHOUT A SAP SALES ORDER
        END AS CUSTOMER_REGION
        , DELIVERY_DOCUMENT
        , DATEDIFF(DAY, TRY_TO_DATE(DUE_DATE, 'YYYYMMDD'), LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE), 'MONTH')) AS DAYS_SINCE_DUE
        , CASE
        	WHEN DAYS_SINCE_DUE <= 30 THEN 'CURR'
        	WHEN DAYS_SINCE_DUE BETWEEN 31 AND 60 THEN 'OVER 30'
        	WHEN DAYS_SINCE_DUE BETWEEN 61 AND 90 THEN 'OVER 60'
        	WHEN DAYS_SINCE_DUE >= 91 THEN 'OVER 90'
        END AS AGING
        , COMPANY_CODE
        , ORIGINAL_BILLING_DOCUMENT
        , ORIGINAL_BILLING_TYPE
        , SALES_DOCUMENT_TYPE
    FROM SOURCE_DATA
),

MERGE_AROPENENTRIES_OPEN_INVOICES AS (
    SELECT   
        op_inv._AUDIT_LOG_ID,
        op_inv._ROW_HASH,
        op_inv.ACCOUNT_NUMBER,
        op_inv.CUSTOMER_NUMBER,
        op_inv.CUSTOMER_NAME,
        op_inv.BILL_TO_PARTY,
        op_inv.BILL_TO_NAME,
        op_inv.SOLD_TO_PARTY,
        op_inv.SOLD_TO_NAME,
        CASE WHEN DOCUMENT_TYPE = 'ZX' THEN CTE_LEGACY_AROPENENTRIES.CUST_PO  -- MIGRATION ITEMS
        ELSE op_inv.CUSTOMER_PO -- NON-MIGRATION ITEMS
        END AS CUSTOMER_PO,
        op_inv.SALES_DOCUMENT,
        op_inv.GL_FISCAL_YEAR,
        op_inv.ACCOUNTING_DOCUMENT,
        op_inv.ACCOUNTING_DOCUMENT_LINE,
        op_inv.BILLING_TYPE,
        op_inv.DOCUMENT_TYPE,
        op_inv.BILLING_DOCUMENT,
        op_inv.REFERENCE_DOCUMENT,
        op_inv.BILLING_DATE,
        op_inv.DUE_DATE,
        op_inv.DAYS_SINCE_INVOICING,
        op_inv.BILLING_AMOUNT,
        op_inv.PROFIT_CENTER,
        op_inv.CUSTOMER_CITY,
        op_inv.CUSTOMER_REGION,   
        CASE WHEN DOCUMENT_TYPE = 'ZX' THEN CTE_LEGACY_AROPENENTRIES.SHIPMENT_IDENTIFICATION_NO
        ELSE op_inv.DELIVERY_DOCUMENT
        END AS DELIVERY_DOCUMENT,
        op_inv.DAYS_SINCE_DUE,
        op_inv.AGING,
        COMPANY_CODE,
        CTE_LEGACY_AROPENENTRIES.DOCUMENT_AROPENENTRIES AS DOCUMENT_AROPENENTRIES
        , op_inv.ORIGINAL_BILLING_DOCUMENT
        , op_inv.ORIGINAL_BILLING_TYPE
        , op_inv.SALES_DOCUMENT_TYPE
        FROM TRANSFORM_DATA op_inv 
        LEFT JOIN CTE_LEGACY_AROPENENTRIES 
        ON op_inv.REFERENCE_DOCUMENT = CTE_LEGACY_AROPENENTRIES.DOCUMENT_AROPENENTRIES
),


where BKPF.BUKRS = '3200'
),

Additional_data as (
    SELECT DISTINCT
        ACCOUNTING_DOCUMENT_NUMBER AS ACCOUNTING_DOCUMENT
        ,SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER as ACCOUNTING_DOCUMENT_LINE
        ,COMPANY_CODE
        ,FISCAL_YEAR as GL_FISCAL_YEAR

WITH ALL_DOC_TYPES1  as ( 
    SELECT
        bseg.bukrs as COMPANY_CODE,
        bseg.belnr as ACCOUNTING_DOCUMENT,
        bseg.buzei as ACCOUNTING_DOCUMENT_LINE,
        bseg.SAKNR as ACCOUNT_NUMBER,
        bseg.gjahr as GL_FISCAL_YEAR,
        bseg.hkont as GL,
        bkpf.BLART as DOCUMENT_TYPE,
        bseg.ZFBDT as BASELINE_DATE_FOR_DUE_DATE_CALCULATION,
        bseg.netdt as DUE_DATE,
        case when bseg.SHKZG = 'S' then bseg.DMBTR
        else bseg.DMBTR * -1 end as AMOUNT,
        bkpf.bktxt as DOCUMENT_HEADER_TEXT,
        bkpf.xblnr as REFERENCE_DOCUMENT_NUMBER,
        bseg.PRCTR as PROFIT_CENTER,
        bseg.KUNNR as CUSTOMER_NUMBER,
        BSEG.SGTXT as ITEM_TEXT,
        bkpf.BLDAT AS DOCUMENT_DATE,
        VORGN as  BUSINESS_TRANSACTION_TYPE ,
        bseg.VBELN as BILLING_DOCUMENT,
        bseg.REBZG as REFERENCE_DOCUMENT,
        bseg.XREF3 as CUSTOMER_REFERENCE,
        bseg.ZUONR as SALES_DOCUMENT,
        bseg.UMSKZ as SPECIAL_INDICATOR,
        bseg.REBZG AS REF_INVOICE,
        bseg.REBZJ AS REF_FISCAL_YEAR,
        bseg.REBZZ AS REF_LINE_ITEM,
        bkpf.BUDAT AS Posting_Date
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU038_BSEG') }} as bseg
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU037_BKPF') }} as bkpf
    ON try_to_number(bkpf.bukrs) = try_to_number(BSEG.bukrs)
    AND try_to_number(bkpf.GJAHR) = try_to_number(BSEG.gjahr)
    AND try_to_number(bkpf.BELNR) = try_to_number(BSEG.belnr)
    WHERE koart = 'D' 
    AND ( bseg.AUGDT = '00000000' or bseg.AUGDT is null ) 
    AND bseg.BUKRS = '3200'
    AND bseg.UMSKZ = ''
    AND bseg.hkont = '1120300001'
    AND to_date(bkpf.BUDAT,'YYYYMMDD') <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE), 'MONTH')
    UNION
    SELECT
        bseg.bukrs as COMPANY_CODE,
        bseg.belnr as ACCOUNTING_DOCUMENT,
        bseg.buzei as ACCOUNTING_DOCUMENT_LINE,
        bseg.SAKNR as ACCOUNT_NUMBER,
        bseg.gjahr as GL_FISCAL_YEAR,
        bseg.hkont as GL,
        bkpf.BLART as DOCUMENT_TYPE,
        bseg.ZFBDT as BASELINE_DATE_FOR_DUE_DATE_CALCULATION,
        bseg.netdt as DUE_DATE,
        case when bseg.SHKZG = 'S' then bseg.DMBTR
        else bseg.DMBTR * -1 end as AMOUNT,
        bkpf.bktxt as DOCUMENT_HEADER_TEXT,
        bkpf.xblnr as REFERENCE_DOCUMENT_NUMBER,
        bseg.PRCTR as PROFIT_CENTER,
        bseg.KUNNR as CUSTOMER_NUMBER,
        BSEG.SGTXT as ITEM_TEXT,
        bkpf.BLDAT AS DOCUMENT_DATE,
        VORGN as  BUSINESS_TRANSACTION_TYPE ,
        bseg.VBELN as BILLING_DOCUMENT,
        bseg.REBZG as REFERENCE_DOCUMENT,
        bseg.XREF3 as CUSTOMER_REFERENCE,
        bseg.ZUONR as SALES_DOCUMENT,
        bseg.UMSKZ as SPECIAL_INDICATOR,
        bseg.REBZG AS REF_INVOICE,
        bseg.REBZJ AS REF_FISCAL_YEAR,
        bseg.REBZZ AS REF_LINE_ITEM,
        bkpf.BUDAT AS Posting_Date
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU038_BSEG') }} as bseg
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU037_BKPF') }} as bkpf
    ON try_to_number(bkpf.bukrs) = try_to_number(BSEG.bukrs)
    AND try_to_number(bkpf.GJAHR) = try_to_number(BSEG.gjahr)
    AND try_to_number(bkpf.BELNR) = try_to_number(BSEG.belnr)
    WHERE koart = 'D' 
    AND bseg.AUGDT != '00000000' 
    AND bseg.BUKRS = '3200'
    AND bseg.UMSKZ = ''
    AND bseg.hkont = '1120300001'
    AND to_date(bseg.AUGDT,'YYYYMMDD') > LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE), 'MONTH')
    AND to_date(bkpf.BUDAT,'YYYYMMDD') <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE), 'MONTH')
),

BKPF as (
select BKPF.AWKEY AS REF_KEY,
        BKPF.AWTYP AS REF_TRANS,
        BKPF.BELNR as ACCOUNTING_DOCUMENT,
        BKPF.GJAHR as GL_FISCAL_YEAR,
        BKPF.BLART as DOCUMENT_TYPE

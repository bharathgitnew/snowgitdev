        else ACDOCA_PROFIT_CENTER end as PROFIT_CENTER
        ,BILLING_TYPE
        ,ACCOUNT_NUMBER
        ,REFERENCE_DOCUMENT_NUMBER as REFERENCE_DOCUMENT
	    ,DOCUMENT_DATE_IN_DOCUMENT as DOCUMENT_DATE
    FROM {{ ref('COMMON__SAPH_NEW_ACDOCA__UNIVERSAL_BS_ACCOUNT_TYPE') }} 
    WHERE 1=1
    AND COMPANY_CODE = 3200
    AND LEDGER_IN_GENERAL_LEDGER_ACCOUNTING = '0L'
    --AND ACCOUNT_TYPE = 'D'
),

ALL_DOC_TYPES as (
    select  
        al.COMPANY_CODE,
        al.ACCOUNTING_DOCUMENT,
        al.ACCOUNTING_DOCUMENT_LINE,
        al.ACCOUNT_NUMBER,
        al.GL_FISCAL_YEAR,
        DOCUMENT_TYPE,
        BASELINE_DATE_FOR_DUE_DATE_CALCULATION,
        DUE_DATE,
        AMOUNT,
        DOCUMENT_HEADER_TEXT,
        REFERENCE_DOCUMENT_NUMBER,
        case when ad.PROFIT_CENTER is not null then ad.PROFIT_CENTER else al.PROFIT_CENTER end as PROFIT_CENTER,
        CUSTOMER_NUMBER,
        ITEM_TEXT,
        ad.DOCUMENT_DATE,
        BUSINESS_TRANSACTION_TYPE ,
        BILLING_DOCUMENT,
--        case when al.REFERENCE_DOCUMENT is null then ad.REFERENCE_DOCUMENT else al.REFERENCE_DOCUMENT end as REFERENCE_DOCUMENT,
        ad.REFERENCE_DOCUMENT as REFERENCE_DOCUMENT,
        CUSTOMER_REFERENCE,

      alias = 'MATERIAL_VALUATION_HISTORY_TABLE',
       materialized='incremental',
      incremental_strategy = 'insert_overwrite',
       transient = false
) }} 


WITH MBEWH_CTE AS (
    SELECT 
        MBEWH.*,
        MARA.MAKTX
    FROM 
        {{ ref('ODS__SAPAPI__ZCDV_T_CMTU243_MBEWH') }} AS MBEWH 
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA
            ON MBEWH.MATNR = MARA.MATNR
),
SOURCE_DATA AS (
    SELECT 
        FINAL.MATNR AS MATERIAL_NUMBER,
        FINAL.MAKTX AS MATERIAL_DESCRIPTION,
        FINAL.BWKEY AS VALUATION_AREA,
        FINAL.BWTAR AS VALUATION_TYPE,
        FINAL.LFGJA AS FISCAL_YEAR_OF_CURRENT_PERIOD,
        FINAL.LFMON AS CURRENT_PERIOD,
        FINAL.LBKUM AS TOTAL_VALUATED_STOCK,
        FINAL.SALK3 AS VALUE_OF_TOTAL_VALUATED_STOCK,
        FINAL.VPRSV AS PRICE_CONTROL_INDICATOR,
        FINAL.VERPR AS MOVING_AVERAGE_PRICE,
        FINAL.STPRS AS STANDARD_PRICE,
        FINAL.PEINH AS PRICE_UNIT,
        FINAL.BKLAS AS VALUATION_CLASS,
        FINAL.SALKV AS VALUE_BASED_ON_MOVING_AVERAGE_PRICE,
        FINAL.VKSAL AS VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE

    FROM MBEWH_CTE AS FINAL
        
),
TRANSFORM_DATA AS (
    SELECT 
        MATERIAL_NUMBER,
        MATERIAL_DESCRIPTION,
        VALUATION_AREA,
        VALUATION_TYPE,
        FISCAL_YEAR_OF_CURRENT_PERIOD,
        CURRENT_PERIOD,
        TOTAL_VALUATED_STOCK,
        VALUE_OF_TOTAL_VALUATED_STOCK,
        PRICE_CONTROL_INDICATOR,
        MOVING_AVERAGE_PRICE,
        STANDARD_PRICE,
        PRICE_UNIT,
        VALUATION_CLASS,
        VALUE_BASED_ON_MOVING_AVERAGE_PRICE,
        VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH 
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT 
        CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
        CAST(MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MATERIAL_DESCRIPTION,
        CAST(VALUATION_AREA AS VARCHAR(16777216)) AS VALUATION_AREA,
        CAST(VALUATION_TYPE AS VARCHAR(16777216)) AS VALUATION_TYPE,
        CAST(FISCAL_YEAR_OF_CURRENT_PERIOD AS VARCHAR(16777216)) AS FISCAL_YEAR_OF_CURRENT_PERIOD,
        CAST(CURRENT_PERIOD AS VARCHAR(16777216)) AS CURRENT_PERIOD,
        CAST(TOTAL_VALUATED_STOCK AS NUMBER(38,2)) AS TOTAL_VALUATED_STOCK,
        CAST(VALUE_OF_TOTAL_VALUATED_STOCK AS NUMBER(38,2)) AS VALUE_OF_TOTAL_VALUATED_STOCK,
        CAST(PRICE_CONTROL_INDICATOR AS VARCHAR(16777216)) AS PRICE_CONTROL_INDICATOR,
        CAST(MOVING_AVERAGE_PRICE AS NUMBER(38,2)) AS MOVING_AVERAGE_PRICE,
        CAST(STANDARD_PRICE AS NUMBER(38,2)) AS STANDARD_PRICE,
        CAST(PRICE_UNIT AS NUMBER(38,2)) AS PRICE_UNIT,
        CAST(VALUATION_CLASS AS VARCHAR(16777216)) AS VALUATION_CLASS,
        CAST(VALUE_BASED_ON_MOVING_AVERAGE_PRICE AS NUMBER(38,2)) AS VALUE_BASED_ON_MOVING_AVERAGE_PRICE,
        CAST(VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE AS NUMBER(38,2)) AS VALUE_OF_TOTAL_VALUATED_STOCK_AT_SALES_PRICE,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM 
        TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
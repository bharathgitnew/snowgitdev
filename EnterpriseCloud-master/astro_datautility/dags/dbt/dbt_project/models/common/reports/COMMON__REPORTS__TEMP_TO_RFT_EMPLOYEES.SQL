    p.FIRST_NAME as permanent_FIRST_NAME,
    p.LAST_NAME as permanent_LAST_NAME,
    p.EMAILADDRESS as permanent_EMAILADDRESS,
    p.SUPERVISOR_EMPLOYEE_ID as permanent_SUPERVISOR_EMPLOYEE_ID,
    p.SUPERVISOR_NAME as permanent_SUPERVISOR_NAME,
    p.SENIORITY_DATE as permanent_SENIORITY_DATE,

    t.ACTIVEDIRECTORYDISPLAYNAME as temp_ACTIVEDIRECTORYDISPLAYNAME,
    t.COMPANY_HR_REGION as temp_COMPANY_HR_REGION,
    p.EMPLOYEE_ID as permanent_EMPLOYEE_ID,

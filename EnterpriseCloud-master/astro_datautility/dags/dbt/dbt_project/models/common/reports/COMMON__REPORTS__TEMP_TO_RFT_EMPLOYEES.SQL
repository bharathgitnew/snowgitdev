with temp as (
select * from {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }}
where employee_status!='Active'
and employee_type in ('Subcontractor','Temp Worker')
and employee_id is not null and trim(employee_id)!=''
and emailaddress is not null and trim(emailaddress)!=''
),

permanent as (
select * from {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }}
where employee_status!='InActive'
and employee_type='Regular Full-Time'
and employee_id is not null and trim(employee_id)!=''
and emailaddress is not null and trim(emailaddress)!=''

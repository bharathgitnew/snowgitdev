WITH WO AS (
    SELECT
        LPAD(MSDYN_NAME,8,'0') AS WORK_ORDER
        ,WO_WOTITLE AS WO_TITLE
        ,TEL_WO_SUBCATEGORY_SOREQUESTNAME AS WO_SUBCATEGORY
        ,MSDYN_WORKORDERTYPENAME AS WO_TYPE
        ,WO_TYPEOFWORK_CUSTOMIZEDNAME AS WO_TYPEOFWORKCUSTOMIZEDNAME
        ,WO_TEMP_FAB_TEXT AS WO_FAB
        ,WO_CUSTOMERNAME AS WO_CUSTOMER
        ,WO_TEMP_MSNAME AS WO_SERIAL_NUMBER
        ,WO_TEMP_TOOLID_JP AS CUSTOMER_TOOL_ID
        ,TEL_WO_SERVICEORDERNO_3200 AS SAP_SERVICE_ORDER
        ,WO_TEMP_PRODUCTLINE_TEXT AS WO_PRODUCT_LINE
        ,MSDYN_SUBSTATUSNAME AS WO_SUBSTATUS
        ,
        CASE
            WHEN MSDYN_SUBSTATUSNAME = 'Closed' THEN 'Y'
        ELSE 'N'
        END AS WO_IS_CLOSED_FLAG
        ,WO_PROCESSSTAGENAME AS WO_PROCESS_STAGE
        ,WO_WOISSUEDATE AS WO_ISSUE_DATE
        ,MSDYN_COMPLETEDON AS WO_COMPLETED_DATE
        ,TEL_WO_PRIMARY_SONAME AS PRIMARY_SALES_ORDER
        ,TEL_WO_PRIMARY_SO
        ,TEL_WO_SECONDARY_SO
        ,WO_TEAMINCHARGENAME AS WO_TEAM
        ,UPPER(MSDYN_WORKORDERID) AS WO_ID
        ,WO_MAINCATEGORY_OPTIONS
        ,UPPER(TEL_WO_CONTRACTGROUP) AS TEL_WO_CONTRACTGROUP
        ,MSDYN_SERVICEACCOUNT
        ,TEL_WO_CUSTOMERBY9DIGITSNAME AS CUSTOMER_D_CODE_NAME
        ,TEL_WO_CUSTOMERBY9DIGITS
        ,TEL_WO_TYPEOFPAYMENT AS WO_TEL_WO_TYPEOFPAYMENT
        ,TEL_WO_SAPFIELDMODIFIEDON
        ,WO_TIMEZONES
        ,TEL_WO_SOWNAME
        ,WO_MASTERPROJECTNAME
        ,UPPER(CREATEDBY) AS WO_CREATEDBY
        ,WO_DAYSOPEN
        ,WO_PLANNEDSTART
        ,WO_PLANNEDEND
        ,WO_NOOFASSIGNEDFE_STATE
        ,WO_NOOFASSIGNEDFE_DATE AS ASSIGNEDFE_DATE
        ,MODIFIEDON AS WO_MODIFIEDON
        ,WO_CUSTOMER AS WO_CUSTOMER_ID
        ,UPPER(MSDYN_CUSTOMERASSET)  AS MSDYN_CUSTOMERASSET
        ,WO_FILEATTACHED
        ,WO_PROCESSISSUE
        ,WO_TROUBLEREOCCURRENCE
        ,WO_TROUBLESHOOTING
        ,MSDYN_PRICELISTNAME AS WO_PRICELIST
        ,TEL_WO_IFFIELD_MODIFIEDON_WISDOM AS WO_WISDOM_MODIFIEDON
        ,ISDELETE AS WO_ISDELETE
        ,CREATEDBYNAME
        ,CREATEDON
        ,MSDYN_TIMECLOSED
        ,STATECODE
        ,TEL_WO_ORDER_NO_TEXT
        ,WO_LATESTPASSDOWNCREATEDDATE
        ,WO_FCNSIID
        ,WO_TSRTOTALHOURS
        ,WO_CUSTOMERSIGNRECEIVEDON
        ,WO_REGIONNAME
        ,TEL_WO_MESSAGETOOP
        ,TEL_WO_FILEINTEGRATIONINFO
        ,WO_TSRLABORSTATUS
        ,TEL_WO_DOCUMENT_TYPE
        ,WO_CUSTOMERSIGNRECEIVEDPICKLIST
        ,WO_RECORDTYPE
        ,WO_MOBILESYNCRESULT
        ,WO_MASTERPROJECT
        ,TEL_WO_TRIGGER_SIGNEDTSR_INTEGRATION
        ,WO_REMARKSINTERNAL AS WO_INTERNAL_NOTES
        ,TEL_WO_SERVICEFROM_WHICHCREATED
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
    WHERE 1=1
      AND WO_REGIONNAME = 'US'
      AND LEFT(MSDYN_NAME,8) <> 'Template'
      AND CREATEDON >= '2023-05-01')

,MAINCAT AS (
    SELECT
        OPTION
        ,LOCALIZEDLABEL AS WO_MAINCATEGORY
        FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }} --ODS.CRM.WO_GLOBALOPTIONSETMETADATA
    WHERE LOCALIZEDLABELLANGUAGECODE = '1033'
      AND OPTIONSETNAME = 'wo_maincategory_options')

,CONTRACT AS (
    SELECT
        UPPER(ID) AS ID
        ,CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER
        ,CNT_BALANCETOTAL
        ,CNT_ORDERAMOUNTTOTAL
    FROM {{ ref('ODS__CRM_FILE__CNT_CONTRACTSUMMARY') }}
    )

,CONTRACT_MASTER AS (
    SELECT
        CONTRACT_NUMBER
        ,CONTRACT_TITLE
        ,CONTRACT_TYPE
        ,BAAN_CONTRACT_NUMBER
        ,PO_NUMBER
        ,CONTRACT_END_DATE
        ,CONTRACT_STATUS
    FROM {{ ref('COMMON__SAPH__CONTRACTS_MASTER') }}
    )


,PAYMENT AS (
    SELECT
        OPTION
        ,LOCALIZEDLABEL AS WO_PAYMENT_TYPE
    FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }} --ODS.CRM.WO_GLOBALOPTIONSETMETADATA
    WHERE LOCALIZEDLABELLANGUAGECODE = '1033'
      AND OPTIONSETNAME = 'tel_wo_typeofpayment'
      AND ENTITYNAME = 'msdyn_workorder')
,
CGM AS (
SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
        ,CUSTOMER_GROUP2
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_GROUP_MAPPING') }}
)
,ACODE AS (
    SELECT
        ID
        ,NAME AS CUSTOMERNAME
        ,ACCOUNTNUMBER AS WO_CUSTOMER_CODE
        , CGM.CUSTOMER_GROUP
        , CGM.CUSTOMER_GROUP2
        ,TEL_COM_OLD_CUSTOMER_CODE AS CUSTOMER_CODE_5DIGIT
    FROM {{ ref('COMMON__CRM__ACCOUNT') }}
        LEFT JOIN CGM
            ON CGM.ACCOUNT_NUMBER = WO_CUSTOMER_CODE
    )

,BCODE AS (
    SELECT
        ID
        ,NAME AS CUSTOMERNAME
        ,ACCOUNTNUMBER AS WO_FABCODE
        ,TEL_COM_OLD_CUSTOMER_CODE AS CUSTOMER_CODE_7DIGIT
        ,COM_COMPANY_NAME AS CUSTOMER
        , CGM.CUSTOMER_GROUP
        , CGM.CUSTOMER_GROUP2
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }}
          LEFT JOIN CGM
            ON CGM.ACCOUNT_NUMBER = WO_FABCODE
)
,DCODE AS (
    SELECT
        ID
        --,NAME AS CUSTOMER_D_CODE_NAME
        ,ACCOUNTNUMBER AS CUSTOMER_D_CODE
        ,TEL_COM_OLD_CUSTOMER_CODE AS CUSTOMER_CODE_9DIGIT
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }}
    )

,USER AS (
    SELECT
        UPPER(ID) AS ID
        ,FIRSTNAME
        ,LASTNAME
        ,(LASTNAME||', '||FIRSTNAME) AS WO_CREATOR
        ,LPAD(EMPLOYEEID,6,'0') AS WO_CREATOR_ID
        ,COM_EMPLOYEE_ATTRIBUTES
    FROM {{ ref('ODS__CRM_FILE__SYSTEMUSER') }}
    ) ,

CRM_MACHINE AS (
SELECT
    MSDYN_NAME AS CRM_SN
    ,TEL_COM_SAP_PRODUCT_CODE AS SAP_PRODUCT_CODE
    ,BUMAP.BU_GROUP
    ,BUMAP.BU_GROUP_LEADER
    ,BUMAP.BU_GROUP_LEADER_ID
    ,BUMAP.BU_SOURCE_KEY
    FROM {{ ref('ODS__CRM_FILE__MSDYN_CUSTOMERASSET') }}
    LEFT JOIN  {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }} BUMAP
    ON BUMAP.BU_SOURCE_KEY = SAP_PRODUCT_CODE
    QUALIFY row_number() over ( partition by (MSDYN_NAME) ORDER BY CREATEDON DESC) = 1

),
CSSMAP AS (
    SELECT
         PRIMARY_CONTACT AS PRIMARY_SERVICE_CONTACT
        ,PRIMARY_CONTACTID AS PRIMARY_SERVICE_CONTACT_ID
        ,SECONDARY_CONTACT AS SECONDARY_SERVICE_CONTACT
        ,SECONDARY_CONTACTID AS SECONDARY_SERVICE_CONTACT_ID
        ,CC_BU_KEY
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_SITE_SERVICE_MANAGER_MAPPING') }}
)

,TEACOMMONEMP AS (
    SELECT
        EMPLOYEEID
        ,SUPERVISORID
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
    )
,SUPERVISOR AS (
    SELECT
        EMPLOYEEID AS SUPERVISOR_ID
        ,FULLNAME AS SUPERVISOR_NAME
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
    )

,OFFICE AS (
    SELECT
        B_CODE
        ,LEGACY_OFFICE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
    )

,CUSTOMER_PO AS (
    SELECT DISTINCT
        VBAK_SALES_DOCUMENT
        ,SALES_CUSTOMER_REFERENCE AS PRIMARY_SO_CUSTOMER_PO
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }}
    WHERE VBAK_SALES_DOCUMENT_TYPE = 'ZS10'
      AND SALES_CUSTOMER_REFERENCE IS NOT NULL)

,HOURS AS (
    SELECT
        UPPER(WO_WORKORDERNO) AS WO_WORKORDERNO
        ,SUM(WO_DURATION_HR) AS TOTALHOURS
    FROM {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }}
    WHERE 1=1
      AND WO_DELETE_FLG = 'FALSE'
      AND WO_DUPLICATIONFLAG = 'FALSE'
    GROUP BY UPPER(WO_WORKORDERNO))

,MINTIMEENTRY AS (
    SELECT
        UPPER(WO_WORKORDERNO) AS WO_WORKORDERNO
        ,MIN(WO_STARTTIME) AS FIRST_TIME_ENTRY
    FROM {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }}
    WHERE 1=1
      AND WO_DELETE_FLG = 'FALSE'
      AND WO_DUPLICATIONFLAG = 'FALSE'
    GROUP BY UPPER(WO_WORKORDERNO) )

,MAXTIMEENTRY AS (
    SELECT
        UPPER(WO_WORKORDERNO) AS WO_WORKORDERNO
        ,MAX(WO_STARTTIME) AS LAST_TIME_ENTRY
    FROM {{ ref('ODS__CRM_FILE__MSDYN_TIMEENTRY') }}
    WHERE 1=1
      AND WO_DELETE_FLG = 'FALSE'
      AND WO_DUPLICATIONFLAG = 'FALSE'
    GROUP BY UPPER(WO_WORKORDERNO) )

,PRIMARY_SO AS (
    SELECT
        ID
        ,TEL_COM_SALES_DOC_TYPE_CODE AS PRIMARY_SALES_ORDER_TYPE
        ,TEL_COM_SALES_DOCUMENT_NO AS PRIMARY_SALES_ORDER
        ,TEL_COM_SALES_ORGANIZATIONNAME AS PRIMARY_SO_OWNER
    FROM {{ ref('ODS__CRM_FILE__TEL_COM_SALESORDERHEADER') }}
    )

,SECONDARY_SO AS (
    SELECT
        ID
        ,TEL_COM_SALES_DOC_TYPE_CODE AS SECONDARY_SALES_ORDER_TYPE
        ,TEL_COM_SALES_DOCUMENT_NO AS SECONDARY_SALES_ORDER
        ,TEL_COM_SALES_ORGANIZATIONNAME AS SECONDARY_SO_OWNER
    FROM {{ ref('ODS__CRM_FILE__TEL_COM_SALESORDERHEADER') }}
    )

,WISDOMMACHINE AS (
    SELECT
        SERIAL_NUMBER
        ,SWLH_MODEL
        ,TEL_MODEL
        ,WAFER_SIZE
        ,SAP_PRODUCT_CODE AS SN_SAP_PRODUCT_CODE
    FROM {{ ref('COMMON__DE_WISDOM__GLOBAL_MACHINES') }}
    )

,TELCOM_SO AS (
    SELECT
        TEL_COM_SALESORDERHEADERID
        ,TEL_COM_CUST_REFERENCE_VBKD
        ,TEL_COM_SALES_DOC_TYPENAME
    FROM {{ ref('ODS__CRM_FILE__TEL_COM_SALESORDERHEADER') }}
)

,METADATA AS (
    SELECT
        OPTION
        ,LOCALIZEDLABEL
        ,OPTIONSETNAME
    FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }}
    WHERE LOCALIZEDLABELLANGUAGECODE = 1033
        AND EntityName = 'msdyn_workorder'
    ORDER BY OPTIONSETNAME
)

,PROJECT AS (
    SELECT DISTINCT
        ID AS PROJECT_ID
        ,COM_NAME
    FROM {{ ref('ODS__CRM_FILE__MSDYN_PROJECT') }}
)

,source AS (
    SELECT
        COALESCE(BCODE.CUSTOMER_GROUP,ACODE.CUSTOMER_GROUP) AS CUSTOMER_GROUP
        ,COALESCE(BCODE.CUSTOMER_GROUP2, ACODE.CUSTOMER_GROUP2) AS CUSTOMER_GROUP2
        ,LEGACY_OFFICE
        ,WO.WO_PRODUCT_LINE
        ,WO.WORK_ORDER
        ,WO.WO_TITLE
        ,WO.WO_IS_CLOSED_FLAG
        ,COALESCE(HOURS.TOTALHOURS,0) AS TOTALHOURS
        ,WO_ISSUE_DATE
        ,WO_PROCESS_STAGE
        ,WO.WO_SUBSTATUS
        ,MAINCAT.WO_MAINCATEGORY
        ,COALESCE(WO.WO_SUBCATEGORY,WO_TYPEOFWORKCUSTOMIZEDNAME) AS WO_SUBCATEGORY
        ,WO_TYPEOFWORKCUSTOMIZEDNAME
        ,WO.WO_TYPE
        ,PAYMENT.WO_PAYMENT_TYPE
        ,COALESCE(WO.WO_CUSTOMER,BCODE.CUSTOMER) AS WO_CUSTOMER
        ,WO.WO_FAB
        ,WO.CUSTOMER_D_CODE_NAME
        ,WO.WO_SERIAL_NUMBER
        ,WO.CUSTOMER_TOOL_ID
        ,WISDOMMACHINE.SWLH_MODEL
        ,WISDOMMACHINE.TEL_MODEL
        ,WISDOMMACHINE.SN_SAP_PRODUCT_CODE
        ,WISDOMMACHINE.WAFER_SIZE
        ,WO.SAP_SERVICE_ORDER
        ,WO.PRIMARY_SALES_ORDER
        ,PRIMARY_SO.PRIMARY_SALES_ORDER_TYPE
        ,PRIMARY_SO.PRIMARY_SO_OWNER
        ,SECONDARY_SO.SECONDARY_SALES_ORDER
        ,SECONDARY_SO.SECONDARY_SALES_ORDER_TYPE
        ,SECONDARY_SO.SECONDARY_SO_OWNER
        ,CONTRACT.CONTRACT_NUMBER
        ,CONTRACT_MASTER.CONTRACT_TITLE
        ,CONTRACT_MASTER.CONTRACT_TYPE
        ,CONTRACT_MASTER.BAAN_CONTRACT_NUMBER
        ,WO_TEAM
        ,COALESCE(USER.WO_CREATOR,CREATEDBYNAME) AS WO_CREATOR
        ,USER.WO_CREATOR_ID
        ,SUPERVISOR.SUPERVISOR_NAME
        ,BCODE.WO_FABCODE
        ,DCODE.CUSTOMER_D_CODE
        ,BCODE.CUSTOMER_CODE_7DIGIT
        ,DCODE.CUSTOMER_CODE_9DIGIT
        ,WO.WO_NOOFASSIGNEDFE_STATE
        ,WO.ASSIGNEDFE_DATE
        ,WO.WO_COMPLETED_DATE
        ,WO.TEL_WO_SAPFIELDMODIFIEDON
        ,WO.WO_MODIFIEDON
        ,WO.WO_WISDOM_MODIFIEDON
        ,MINTIMEENTRY.FIRST_TIME_ENTRY
        ,MAXTIMEENTRY.LAST_TIME_ENTRY
        ,WO.WO_PRICELIST
        ,COALESCE(CUSTOMER_PO.PRIMARY_SO_CUSTOMER_PO,CONTRACT_MASTER.PO_NUMBER) AS RELATED_PO
        ,WO.WO_FILEATTACHED
        ,WO.WO_TROUBLEREOCCURRENCE
        ,WO.WO_TROUBLESHOOTING
        ,WO_PROCESSISSUE
        ,WO.WO_ID
        ,WO.WO_ISDELETE
        ,WO.CREATEDON AS CREATED_ON
        ,WO.MSDYN_TIMECLOSED AS CLOSED_DATE
        ,CASE
            WHEN WO.STATECODE = 0 THEN 'Active'
            WHEN WO.STATECODE = 1 THEN 'Inactive'
            ELSE 'ERROR'
        END AS WO_STATUS
        ,WO.WO_DAYSOPEN AS WO_DAYS_OPEN
        ,WO.WO_PLANNEDSTART AS WO_PLANNED_START
        ,WO.WO_PLANNEDEND AS WO_PLANNED_END
        ,WO.TEL_WO_ORDER_NO_TEXT AS WO_PURCHASE_ORDER_NO
        ,WO.WO_LATESTPASSDOWNCREATEDDATE AS LAST_PASSDOWN
        ,WO_MASTERPROJECTNAME AS SO_GROUP_PROJECT
        ,WO.WO_FCNSIID AS FCN_SI_ID
        ,TELCOM_SO.TEL_COM_CUST_REFERENCE_VBKD AS SALES_ORDER_PURCHASE_ORDER_NO
        ,TSRLABORSTATUS.LOCALIZEDLABEL AS TSR_CALCULATION_STATUS
        ,WO.WO_TSRTOTALHOURS AS TSR_TOTAL_HOURS
        ,CUSTOMERSIGNOFF.LOCALIZEDLABEL AS CUSTOMER_SIGN_OFF
        ,WO.WO_CUSTOMERSIGNRECEIVEDON AS CUSTOMER_SIGN_RECEIVED_ON
        ,TEL_WO_TRIGGER_SIGNEDTSR_INTEGRATION AS TSR_INTEGRATED_FLAG
        ,DOCTYPE.LOCALIZEDLABEL AS DOC_TYPE
        ,WO.WO_MASTERPROJECTNAME AS SO_GROUP_PROJECTID
        ,WO.TEL_WO_SOWNAME AS CONTRACT_SCOPE
        ,CONTRACT_MASTER.CONTRACT_END_DATE
        ,CONTRACT_MASTER.CONTRACT_STATUS
        ,CONTRACT.CNT_BALANCETOTAL AS CONTRACT_BALANCE_TOTAL
        ,CONTRACT.CNT_ORDERAMOUNTTOTAL AS CONTRACT_PO_AMOUNT_TOTAL
        ,PROJECT.COM_NAME AS PROJECT_TITLE
        ,WO.WO_REGIONNAME AS REGION_NAME
        ,RECORDTYPE.LOCALIZEDLABEL AS RECORD_TYPE
        ,MOBILESYNC.LOCALIZEDLABEL AS MOBILE_SYNC_RESULT
        ,WO.TEL_WO_MESSAGETOOP AS MESSAGE_FOR_SAP
        ,WO.TEL_WO_FILEINTEGRATIONINFO AS WO_ATTACHMENT
        ,WO.WO_INTERNAL_NOTES AS WO_INTERNAL_NOTES
        ,CRM_MACHINE.SAP_PRODUCT_CODE
        ,CRM_MACHINE.BU_GROUP
        ,CRM_MACHINE.BU_GROUP_LEADER
        ,CRM_MACHINE.BU_GROUP_LEADER_ID
        ,CSSMAP.PRIMARY_SERVICE_CONTACT
        ,CSSMAP.PRIMARY_SERVICE_CONTACT_ID
        ,CSSMAP.SECONDARY_SERVICE_CONTACT
        ,CSSMAP.SECONDARY_SERVICE_CONTACT_ID
        ,SERVICE_CREATED.LOCALIZEDLABEL as SERVICE_FROM_WHICH_CREATED
    FROM WO
    LEFT OUTER JOIN MAINCAT
        ON WO.WO_MAINCATEGORY_OPTIONS = MAINCAT.OPTION
    LEFT OUTER JOIN PAYMENT
        ON WO.WO_TEL_WO_TYPEOFPAYMENT = PAYMENT.OPTION
    LEFT OUTER JOIN CONTRACT
        ON WO.TEL_WO_CONTRACTGROUP = CONTRACT.ID
    LEFT OUTER JOIN ACODE
        ON UPPER(WO.WO_CUSTOMER_ID) = UPPER(ACODE.ID)
    LEFT OUTER JOIN BCODE
        ON WO.MSDYN_SERVICEACCOUNT = BCODE.ID
    LEFT OUTER JOIN DCODE
        ON WO.TEL_WO_CUSTOMERBY9DIGITS = DCODE.ID
    LEFT OUTER JOIN HOURS
        ON WO.WO_ID = HOURS.WO_WORKORDERNO
    LEFT OUTER JOIN MINTIMEENTRY
        ON WO.WO_ID = MINTIMEENTRY.WO_WORKORDERNO
    LEFT OUTER JOIN MAXTIMEENTRY
        ON WO.WO_ID = MAXTIMEENTRY.WO_WORKORDERNO
    LEFT OUTER JOIN PRIMARY_SO
        ON WO.PRIMARY_SALES_ORDER = PRIMARY_SO.PRIMARY_SALES_ORDER
    LEFT OUTER JOIN SECONDARY_SO
        ON WO.TEL_WO_SECONDARY_SO = SECONDARY_SO.ID
    LEFT OUTER JOIN OFFICE
        ON BCODE.WO_FABCODE = OFFICE.B_CODE
    LEFT OUTER JOIN USER
        ON WO.WO_CREATEDBY = USER.ID
    LEFT OUTER JOIN CUSTOMER_PO
        ON PRIMARY_SO.PRIMARY_SALES_ORDER = CUSTOMER_PO.VBAK_SALES_DOCUMENT
    LEFT OUTER JOIN CONTRACT_MASTER
        ON CONTRACT.CONTRACT_NUMBER = CONTRACT_MASTER.CONTRACT_NUMBER
    LEFT OUTER JOIN TEACOMMONEMP
        ON USER.WO_CREATOR_ID = TEACOMMONEMP.EMPLOYEEID
    LEFT OUTER JOIN SUPERVISOR
        ON TEACOMMONEMP.SUPERVISORID = SUPERVISOR.SUPERVISOR_ID
    LEFT OUTER JOIN WISDOMMACHINE
        ON WO.WO_SERIAL_NUMBER = WISDOMMACHINE.SERIAL_NUMBER
    LEFT OUTER JOIN TELCOM_SO
        ON WO.TEL_WO_PRIMARY_SO = TELCOM_SO.TEL_COM_SALESORDERHEADERID
    LEFT OUTER JOIN METADATA TSRLABORSTATUS
        ON WO.WO_TSRLABORSTATUS = TSRLABORSTATUS.OPTION
        AND TSRLABORSTATUS.OPTIONSETNAME = 'wo_tsrlaborstatus'
    LEFT OUTER JOIN METADATA CUSTOMERSIGNOFF
        ON WO.WO_CUSTOMERSIGNRECEIVEDPICKLIST = CUSTOMERSIGNOFF.OPTION
        AND CUSTOMERSIGNOFF.OPTIONSETNAME = 'wo_customersignreceivedpicklist'
    LEFT OUTER JOIN METADATA RECORDTYPE
        ON WO.WO_RECORDTYPE = RECORDTYPE.OPTION
        AND RECORDTYPE.OPTIONSETNAME = 'wo_recordtype'
    LEFT OUTER JOIN METADATA DOCTYPE
        ON WO.TEL_WO_DOCUMENT_TYPE = DOCTYPE.OPTION
        AND DOCTYPE.OPTIONSETNAME = 'tel_wo_document_type'
    LEFT OUTER JOIN METADATA MOBILESYNC
        ON WO.WO_MOBILESYNCRESULT = MOBILESYNC.OPTION
        AND MOBILESYNC.OPTIONSETNAME = 'wo_mobilesyncresult'
    LEFT OUTER JOIN METADATA SERVICE_CREATED
        ON WO.TEL_WO_SERVICEFROM_WHICHCREATED = SERVICE_CREATED.OPTION
        AND SERVICE_CREATED.OPTIONSETNAME = 'tel_wo_servicefrom_whichcreated'
    LEFT OUTER JOIN PROJECT
        ON WO.WO_MASTERPROJECT = PROJECT.PROJECT_ID
    LEFT JOIN CRM_MACHINE ON
    CRM_MACHINE.CRM_SN = WO.WO_SERIAL_NUMBER
    LEFT OUTER JOIN CSSMAP
    ON CSSMAP.CC_BU_KEY = (BCODE.WO_FABCODE||'_'||BU_GROUP)

)


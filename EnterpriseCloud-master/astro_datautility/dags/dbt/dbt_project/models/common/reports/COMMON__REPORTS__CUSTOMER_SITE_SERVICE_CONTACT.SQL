{{ config(
        alias = 'CUSTOMER_SITE_SERVICE_CONTACT',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

WITH FILE AS (
    SELECT
        BU
        ,CUSTOMER_CODE
        ,PRIMARY_CONTACT
        ,SECONDARY_CONTACT
        ,PRIMARY_CONTACTID
        ,SECONDARY_CONTACTID
        ,CC_BU_KEY
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_SITE_SERVICE_MANAGER_MAPPING') }}
),

SAPCUSTOMER AS (
    SELECT
        BUSINESS_PARTNER_NUMBER
        ,CUSTOMER_GROUP
        ,CORPORATION_NAME
        ,SEARCH_TERM_2
        ,CORPORATION
        ,STREET_AND_HOUSE_NUMBER
        ,CITY
        ,US_STATE
        ,POSTAL_CODE
        ,COUNTRY
    FROM {{ ref('COMMON__SAPH__SAP_CUSTOMER') }}
    WHERE BUSINESS_PARTNER_SERIES = 'B'
),

CRMACCOUNT AS (
    SELECT
        ACCOUNTNUMBER AS ACCOUNT_NUMBER
        ,LEFT(ACCOUNTNUMBER,1) AS ACCOUNT_NUMBER_SERIES
        ,NAME AS SEARCH_TERM_2
        ,COM_COMPANY_E_NAME
        ,COM_COMPANY_NAME AS CORPORATION_NAME
        ,COM_COMPANY_SHORT_NAME
        ,TEL_COM_OLD_CUSTOMER_CODE AS OLD_CUSTOMER_CODE
        ,ADDRESS2_LINE1 AS ADDRESS_LINE1
        ,ADDRESS2_LINE2 AS ADDRESS_LINE2
        ,ADDRESS2_CITY AS CITY
        ,ADDRESS2_STATEORPROVINCE AS US_STATE
        ,ADDRESS2_POSTALCODE AS POSTAL_CODE
        ,COM_ADDRESS2 AS COMPLETE_ADDRESS
        ,COM_COUNTRY_NAMENAME AS COUNTRY
        ,ID AS ACCOUNT_ID
        ,PARENTACCOUNTIDNAME AS PARENT_ACCOUNT_NAME
        ,PARENTACCOUNTID AS PARENT_ACCOUNT_ID
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }}
    WHERE LEFT(ACCOUNTNUMBER,1) ='B'
),

ACCOUNTNUMBER AS (
    SELECT
        ACCOUNTNUMBER
        ,ID
        ,TEL_COM_OLD_CUSTOMER_CODE
    FROM {{ ref('ODS__CRM_FILE__ACCOUNT') }}
),

B_PARENT AS (
    SELECT
        CRMACCOUNT.ACCOUNT_NUMBER AS ACCOUNT_NUMBER_B
        ,ACCOUNTNUMBER.ACCOUNTNUMBER AS ACCOUNT_NUMBER_A
        ,CRMACCOUNT.PARENT_ACCOUNT_ID AS ACCOUNT_ID_A
    FROM CRMACCOUNT
    LEFT OUTER JOIN ACCOUNTNUMBER
    ON CRMACCOUNT.PARENT_ACCOUNT_ID = ACCOUNTNUMBER.ID
    WHERE CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'B'
),

CRMCOMBINED AS (
    SELECT
        CRMACCOUNT.ACCOUNT_NUMBER
        ,CRMACCOUNT.CORPORATION_NAME
        ,CRMACCOUNT.SEARCH_TERM_2
        ,CRMACCOUNT.ACCOUNT_ID
        ,COALESCE(CRMACCOUNT.ADDRESS_LINE2,'')|| ' '||CRMACCOUNT.ADDRESS_LINE1 AS STREET_AND_HOUSE_NUMBER
        ,CRMACCOUNT.CITY
        ,CRMACCOUNT.US_STATE
        ,CRMACCOUNT.POSTAL_CODE
        ,CRMACCOUNT.COMPLETE_ADDRESS
        ,CRMACCOUNT.COUNTRY
        ,CASE
            WHEN CRMACCOUNT.ACCOUNT_NUMBER_SERIES = 'A' THEN CRMACCOUNT.ACCOUNT_NUMBER
            ELSE ACCOUNTNUMBER.ACCOUNTNUMBER
        END AS CORPORATION
    FROM CRMACCOUNT
    LEFT OUTER JOIN ACCOUNTNUMBER
    ON CRMACCOUNT.PARENT_ACCOUNT_ID = ACCOUNTNUMBER.ID
    LEFT OUTER JOIN B_PARENT
    ON ACCOUNTNUMBER.ACCOUNTNUMBER = B_PARENT.ACCOUNT_NUMBER_B
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY CRMACCOUNT.ACCOUNT_NUMBER ORDER BY CRMACCOUNT.ACCOUNT_ID)) = 1
),

CGM AS (
    SELECT
        ACCOUNT_NUMBER
        ,CUSTOMER_GROUP
    FROM {{ ref('ODS__SHAREPOINT__CUSTOMER_GROUP_MAPPING') }}
),

LEGACYOFFICE AS (
    SELECT
        B_CODE
        ,LEGACY_OFFICE AS OFFICE
        ,LEGACY_OFFICE_CODE AS OFFICE_CODE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
),

BUGROUP AS (
    SELECT
        BU_SOURCE_KEY
        ,BU_GROUP_LEADER
        ,BU_GROUP_LEADER_ID
    FROM {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }}
),

ACTIVETOOLCOUNT AS (
    SELECT
        CUSTOMER_CODE_B||'_'||BU_GROUP AS CC_BU_KEY
        ,COUNT(SERIAL_NUMBER) AS MAIN_TOOL_COUNT_ACTIVE
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE 1=1
        AND MAIN_TOOL_FLAG = 'Y'
        AND INSTALL_BASE_STATUS IN ('Production Tool', 'Startup Tool', 'Eval Tool')
        AND CUSTOMER_CODE_B IS NOT NULL
        AND BU_GROUP IS NOT NULL
    GROUP BY CUSTOMER_CODE_B||'_'||BU_GROUP
),

ALLTOOLCOUNT AS (
    SELECT
        CUSTOMER_CODE_B||'_'||BU_GROUP  AS CC_BU_KEY
        ,COUNT(SERIAL_NUMBER) AS MAIN_TOOL_COUNT_ALL
    FROM {{ ref('COMMON__DE_WISDOM__US_MACHINES') }}
    WHERE 1=1
        AND MAIN_TOOL_FLAG = 'Y'
        AND CUSTOMER_CODE_B IS NOT NULL
        AND BU_GROUP IS NOT NULL
    GROUP BY CUSTOMER_CODE_B||'_'||BU_GROUP
),

EMPSTATUS AS (
    SELECT
        EMPLOYEEID
        ,STATUS_CODE
        ,CASE
        WHEN STATUS_CODE IN ('A', 'L') THEN 'Active'
        ELSE 'Not Active'
        END AS EMP_ACTIVE_FLAG
    FROM {{ ref('COMMON__TEACOMMON__EMPLOYEE') }}
),

CUSTOMERCONTACT AS (
    SELECT
        FILE.BU
        ,COALESCE(SAPCUSTOMER.CUSTOMER_GROUP, CGM.CUSTOMER_GROUP) AS CUSTOMER_GROUP
        ,COALESCE(SAPCUSTOMER.CORPORATION_NAME,CRMCOMBINED.CORPORATION_NAME) AS CORPORATION_NAME
        ,COALESCE(SAPCUSTOMER.SEARCH_TERM_2, CRMCOMBINED.SEARCH_TERM_2) AS SEARCH_TERM_2
        ,LEGACYOFFICE.OFFICE
        ,FILE.PRIMARY_CONTACT
        ,FILE.SECONDARY_CONTACT
        ,BUGROUP.BU_GROUP_LEADER
        ,COALESCE(ACTIVETOOLCOUNT.MAIN_TOOL_COUNT_ACTIVE,0) AS MAIN_TOOL_COUNT_ACTIVE
        ,FILE.PRIMARY_CONTACTID
        ,PRIMARYCONTACT.EMP_ACTIVE_FLAG AS PRIMARY_CONTACT_STATUS
        ,FILE.SECONDARY_CONTACTID
        ,SECONDARYCONTACT.EMP_ACTIVE_FLAG  AS SECONDARY_CONTACT_STATUS
        ,BUGROUP.BU_GROUP_LEADER_ID
        ,FILE.CC_BU_KEY
        ,FILE.CUSTOMER_CODE
        ,COALESCE(SAPCUSTOMER.CORPORATION,CRMCOMBINED.CORPORATION) AS CORPORATION
        ,LEGACYOFFICE.OFFICE_CODE
        ,COALESCE(SAPCUSTOMER.STREET_AND_HOUSE_NUMBER,CRMCOMBINED.STREET_AND_HOUSE_NUMBER) AS STREET_AND_HOUSE_NUMBER
        ,COALESCE(SAPCUSTOMER.CITY, CRMCOMBINED.CITY) AS CITY
        ,COALESCE(SAPCUSTOMER.US_STATE, CRMCOMBINED.US_STATE) AS US_STATE
        ,COALESCE(SAPCUSTOMER.POSTAL_CODE, CRMCOMBINED.POSTAL_CODE) AS POSTAL_CODE
        ,COALESCE(SAPCUSTOMER.COUNTRY, CRMCOMBINED.COUNTRY) AS COUNTRY
        ,COALESCE(ALLTOOLCOUNT.MAIN_TOOL_COUNT_ALL,0) AS MAIN_TOOL_COUNT_ALL
        ,CASE
            WHEN SAPCUSTOMER.BUSINESS_PARTNER_NUMBER IS NOT NULL THEN 'Y'
            ELSE 'N'
        END AS SAP_CUSTOMER_FLAG
    FROM FILE
    LEFT OUTER JOIN SAPCUSTOMER
    ON SAPCUSTOMER.BUSINESS_PARTNER_NUMBER = FILE.CUSTOMER_CODE
    LEFT OUTER JOIN LEGACYOFFICE
    ON LEGACYOFFICE.B_CODE = FILE.CUSTOMER_CODE
    LEFT OUTER JOIN CRMCOMBINED
    ON CRMCOMBINED.ACCOUNT_NUMBER = FILE.CUSTOMER_CODE
    LEFT OUTER JOIN CGM
    ON CGM.ACCOUNT_NUMBER = CRMCOMBINED.CORPORATION
    LEFT OUTER JOIN BUGROUP
    ON BUGROUP.BU_SOURCE_KEY = FILE.BU
    LEFT OUTER JOIN ALLTOOLCOUNT
    ON ALLTOOLCOUNT.CC_BU_KEY = FILE.CC_BU_KEY
    LEFT OUTER JOIN ACTIVETOOLCOUNT
    ON ACTIVETOOLCOUNT.CC_BU_KEY = FILE.CC_BU_KEY
    LEFT OUTER JOIN EMPSTATUS PRIMARYCONTACT
    ON FILE.PRIMARY_CONTACTID = PRIMARYCONTACT.EMPLOYEEID
    LEFT OUTER JOIN EMPSTATUS SECONDARYCONTACT
    ON FILE.PRIMARY_CONTACTID = SECONDARYCONTACT.EMPLOYEEID
),

transform_data as (
    select
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH, -- Adds column to table on full refresh.
        BU,
        CUSTOMER_CODE,
        CUSTOMER_GROUP,
        CORPORATION_NAME,
        SEARCH_TERM_2,
        OFFICE,
        PRIMARY_CONTACT,
        SECONDARY_CONTACT,
        BU_GROUP_LEADER,
        SAP_CUSTOMER_FLAG,
        PRIMARY_CONTACTID,
        PRIMARY_CONTACT_STATUS,
        SECONDARY_CONTACTID,
        SECONDARY_CONTACT_STATUS,
        BU_GROUP_LEADER_ID,
        CC_BU_KEY,
        CORPORATION,
        OFFICE_CODE,
        MAIN_TOOL_COUNT_ACTIVE,
        MAIN_TOOL_COUNT_ALL,
        STREET_AND_HOUSE_NUMBER,
        CITY,
        US_STATE,
        POSTAL_CODE,
        COUNTRY,
    from CUSTOMERCONTACT
),

type_data as (
    select
        _AUDIT_LOG_ID,
        _ROW_HASH,
        BU,
        CUSTOMER_CODE,
        CUSTOMER_GROUP,
        CORPORATION_NAME,
        SEARCH_TERM_2,
        OFFICE,
        PRIMARY_CONTACT,
        SECONDARY_CONTACT,
        BU_GROUP_LEADER,
        SAP_CUSTOMER_FLAG,
        PRIMARY_CONTACTID,
        PRIMARY_CONTACT_STATUS,
        SECONDARY_CONTACTID,
        SECONDARY_CONTACT_STATUS,
        BU_GROUP_LEADER_ID,
        CC_BU_KEY,
        CORPORATION,
        OFFICE_CODE,
        MAIN_TOOL_COUNT_ACTIVE::NUMBER(38,0) as MAIN_TOOL_COUNT_ACTIVE,
        MAIN_TOOL_COUNT_ALL::NUMBER(38,0) as MAIN_TOOL_COUNT_ALL,
        STREET_AND_HOUSE_NUMBER,
        CITY,
        US_STATE,
        POSTAL_CODE,
        COUNTRY,
    from transform_data
)

select * from type_data
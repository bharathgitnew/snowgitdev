    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='Activities_TEE'
) }}


with SourceData as (
SELECT
QRY_Activities_TEE.ACTIVITYLEVEL1NAMEMAINCATEGORY,
QRY_Activities_TEE.ACTIVITYLEVEL1NAMESUBCATEGORY,
QRY_Activities_TEE.ACTIVITYLEVEL2NAMEBU,
QRY_Activities_TEE.ACTIVITYLEVEL2NAMESERIALNO,
QRY_Activities_TEE.ACTIVITYLEVEL3NAMEINSTALLATIONID,
QRY_Activities_TEE.ACTIVITYLEVEL3NAMESERVICEORDER,
QRY_Activities_TEE.ACTIVITYLEVEL4NAMETASK,
QRY_Activities_TEE.ALLOCATED_HOURS,
QRY_Activities_TEE.APPLYDATE,
QRY_Activities_TEE.APPROVEDBYMANAGER,
QRY_Activities_TEE.EMPLOYEENUMBER,
QRY_Activities_TEE.END_DATE,
QRY_Activities_TEE.HOMELABORCATEGORY1COSTSTRUCTURE,
QRY_Activities_TEE.HOME_REGION,
QRY_Activities_TEE.PAYCODE,
QRY_Activities_TEE.PAYCODE_TYPE,
QRY_Activities_TEE.START_DATE,
QRY_Activities_TEE.THIRD_PARTY_EMPLOYEE,
QRY_Activities_TEE.TIMEPUNCHID,
QRY_Activities_TEE.UPDATEDATETIME,
QRY_Activities_TEE.WORKEDLABORCATEGORY1COSTSTRUCTURE,
QRY_Activities_TEE.WORKRULE,
QRY_Activities_TEE.WORK_REGION
FROM
(
SELECT EMPLOYEENUMBER
, ACTIVITYLEVEL1NAMEMAINCATEGORY
, ACTIVITYLEVEL1NAMESUBCATEGORY
, ACTIVITYLEVEL2NAMEBU
, ACTIVITYLEVEL2NAMESERIALNO
, ACTIVITYLEVEL3NAMESERVICEORDER
, ACTIVITYLEVEL3NAMEINSTALLATIONID
, ACTIVITYLEVEL4NAMETASK
, APPLYDATE
, UPDATEDATETIME
, ADJUSTEDSTARTDATETIME AS START_DATE
, ADJUSTEDENDDATETIME AS END_DATE
, ALLOCATEDHOURSTIMEINSECONDS AS ALLOCATED_HOURS
, WORKRULE
, TIMEPUNCHID
, HOMEBS5TELOFFICE AS HOME_REGION
, WORKEDBS5TELOFFICE AS WORK_REGION
, HOMELABORCATEGORY1COSTSTRUCTURE
, WORKEDLABORCATEGORY1COSTSTRUCTURE
, CASE WHEN RIGHT(HOMELABORCATEGORY1COSTSTRUCTURE,2) = '3P' THEN 'Yes' ELSE 'No' END as THIRD_PARTY_EMPLOYEE
, APPROVEDBYMANAGER
, PAYCODE
, CASE WHEN PAYCODE LIKE '%OT%' OR PAYCODE LIKE '%PREMIUM%' OR PAYCODE LIKE '%WE OnCall%'
OR PAYCODE LIKE '%Overtime%' OR PAYCODE LIKE '%Overtime%' OR PAYCODE LIKE '%More than 10 Hrs%' THEN 'OT'
WHEN PAYCODE LIKE '%SHIFT%' OR PAYCODE LIKE '%Sunday 30%' THEN 'Shift'
WHEN PAYCODE LIKE '%TOIL%' THEN 'Toil'
WHEN PAYCODE LIKE '%ACCURAL' THEN 'Accural'
ELSE 'Regular' END AS PAYCODE_TYPE
FROM {{ ref('ODS__KRONOS__ACTIVITIESTOTAL_TEE') }}
where HOMEBS2REGION = 'Europe'
) QRY_Activities_TEE
)

,transform_data as (
   select 
        ACTIVITYLEVEL1NAMEMAINCATEGORY,
        ACTIVITYLEVEL1NAMESUBCATEGORY,
        ACTIVITYLEVEL2NAMEBU,
        ACTIVITYLEVEL2NAMESERIALNO,
        ACTIVITYLEVEL3NAMEINSTALLATIONID,
        ACTIVITYLEVEL3NAMESERVICEORDER,
        ACTIVITYLEVEL4NAMETASK,
        ALLOCATED_HOURS,
        APPLYDATE,
        APPROVEDBYMANAGER,
        EMPLOYEENUMBER,
        END_DATE,
        HOMELABORCATEGORY1COSTSTRUCTURE,
        HOME_REGION,
        PAYCODE,
        PAYCODE_TYPE,
        START_DATE,
        THIRD_PARTY_EMPLOYEE,
        TIMEPUNCHID,
        UPDATEDATETIME,
        WORKEDLABORCATEGORY1COSTSTRUCTURE,
        WORKRULE,
        WORK_REGION,
      '{{ invocation_id }}' AS AUDIT_LOG_ID
  from SourceData
)

,type_data as (
    SELECT
        CAST(ACTIVITYLEVEL1NAMEMAINCATEGORY AS VARCHAR(16777216)) AS ACTIVITYLEVEL1NAMEMAINCATEGORY,
        CAST(ACTIVITYLEVEL1NAMESUBCATEGORY AS VARCHAR(16777216)) AS ACTIVITYLEVEL1NAMESUBCATEGORY,
        CAST(ACTIVITYLEVEL2NAMEBU AS VARCHAR(16777216)) AS ACTIVITYLEVEL2NAMEBU,
        CAST(ACTIVITYLEVEL2NAMESERIALNO AS VARCHAR(16777216)) AS ACTIVITYLEVEL2NAMESERIALNO,
        CAST(ACTIVITYLEVEL3NAMEINSTALLATIONID AS VARCHAR(16777216)) AS ACTIVITYLEVEL3NAMEINSTALLATIONID,
        CAST(ACTIVITYLEVEL3NAMESERVICEORDER AS VARCHAR(16777216)) AS ACTIVITYLEVEL3NAMESERVICEORDER,
        CAST(ACTIVITYLEVEL4NAMETASK AS VARCHAR(16777216)) AS ACTIVITYLEVEL4NAMETASK,
        CAST(ALLOCATED_HOURS AS NUMBER(38,10)) AS ALLOCATED_HOURS,
        CAST(APPLYDATE AS TIMESTAMP_LTZ(9)) AS APPLYDATE,
        CAST(APPROVEDBYMANAGER AS BOOLEAN) AS APPROVEDBYMANAGER,
        CAST(EMPLOYEENUMBER AS VARCHAR(16777216)) AS EMPLOYEENUMBER,
        CAST(END_DATE AS TIMESTAMP_NTZ(9)) AS END_DATE,
        CAST(HOMELABORCATEGORY1COSTSTRUCTURE AS VARCHAR(16777216)) AS HOMELABORCATEGORY1COSTSTRUCTURE,
        CAST(HOME_REGION AS VARCHAR(16777216)) AS HOME_REGION,
        CAST(PAYCODE AS VARCHAR(16777216)) AS PAYCODE,
        CAST(PAYCODE_TYPE AS VARCHAR(7)) AS PAYCODE_TYPE,
        CAST(START_DATE AS TIMESTAMP_NTZ(9)) AS START_DATE,
        CAST(THIRD_PARTY_EMPLOYEE AS VARCHAR(3)) AS THIRD_PARTY_EMPLOYEE,
        CAST(TIMEPUNCHID AS VARCHAR(16777216)) AS TIMEPUNCHID,
        CAST(UPDATEDATETIME AS TIMESTAMP_NTZ(9)) AS UPDATEDATETIME,
        CAST(WORKEDLABORCATEGORY1COSTSTRUCTURE AS VARCHAR(16777216)) AS WORKEDLABORCATEGORY1COSTSTRUCTURE,
        CAST(WORKRULE AS VARCHAR(16777216)) AS WORKRULE,
        CAST(WORK_REGION AS VARCHAR(16777216)) AS WORK_REGION,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    FROM transform_data
)

SELECT * from type_data
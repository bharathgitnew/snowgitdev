{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='SERVICE_CONTRACT_QUOTE_DATA',
    unique_key = ['QUOTENUMBER']
) }}

WITH MASTER AS(
    SELECT * FROM {{ ref('ODS__TELQS__OSUSR_BN7_SERVICECONTRACTQUOTEMASTER') }}
),
SERVICE_QUOTE_WITH_CONTRACT AS(
    SELECT * FROM {{ ref('ODS__TELQS__OSUSR_BN7_SERVICEQUOTEWITHCONTRACT') }}
),
PRODUCT AS (
SELECT
    MASTER.QUOTENUMBER,
    (
        SELECT LISTAGG(distinct C.PRODUCT ,', ') WITHIN GROUP (ORDER BY C.PRODUCT)
        FROM SERVICE_QUOTE_WITH_CONTRACT AS SQWC
        LEFT JOIN {{ ref('ODS__TELQS__OSUSR_BN7_CONTRACTSERIALNUMBER') }} AS C ON SQWC.ID = C.SERVICEQUOTEWITHCONTRACTID
        WHERE SQWC.ServiceContractQuoteMasterID = MASTER.ID
    ) AS Products,
    (
        SELECT LISTAGG(distinct C.FAB_CODE ,', ') WITHIN GROUP (ORDER BY C.FAB_CODE)
        FROM SERVICE_QUOTE_WITH_CONTRACT AS SQWC
        LEFT JOIN {{ ref('ODS__TELQS__OSUSR_BN7_CONTRACTSERIALNUMBER') }} AS C ON SQWC.ID = C.SERVICEQUOTEWITHCONTRACTID
        WHERE SQWC.ServiceContractQuoteMasterID = MASTER.ID
    ) AS FAB_CODE

FROM MASTER 
),
CONTRACTTYPEDETAILS AS
(
SELECT QUOTENUMBER,
    LISTAGG(D.CONTRACTTYPENAME, ',\n') WITHIN GROUP (ORDER BY D.CONTRACTTYPENAME) as CONTRACT_TYPE,
    FROM MASTER
    LEFT JOIN SERVICE_QUOTE_WITH_CONTRACT as SQWC on MASTER.ID=SQWC.SERVICECONTRACTQUOTEMASTERID
    LEFT JOIN {{ ref('ODS__TELQS__OSUSR_CZN_CONTRACTTYPEDETAILS') }} D ON D.CONTRACTTYPEID=SQWC.CONTRACTTYPEID
    GROUP BY QUOTENUMBER
),
CONTRACTS AS(
SELECT MASTER.QUOTENUMBER,
    TO_CHAR(CONTRACT.CONTRACTSTARTDATE,'MM/DD/YYYY') AS CONTRACTSTARTDATE,
    TO_CHAR(CONTRACT.CONTRACTENDDATE,'MM/DD/YYYY') AS CONTRACTENDDATE ,
    CONTRACT.PROVIDECONTREACTNO AS PREVIOUS_CONTRACT_NUMBER
    FROM master
    LEFT JOIN {{ ref('ODS__TELQS__OSUSR_69G_CONTRACTS') }}  CONTRACT ON CONTRACT.SERVICECONTRACTQUOTE=MASTER.ID 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY CONTRACT.SERVICECONTRACTQUOTE ORDER BY CONTRACT.UPDATEDON DESC) =1
),
QUOTESTATUS AS (
SELECT MASTER.QUOTENUMBER,
    QUOTES.LABEL AS QUOTESTATUS
    FROM MASTER
    LEFT JOIN {{ ref('ODS__TELQS__OSUSR_BN7_QUOTESTATUS') }} QUOTES ON QUOTES.ID=MASTER.QUOTESTATUSID
),
CONTRACTLENGTH AS (
    SELECT QUOTENUMBER, 
    CON_LEN.LABEL AS CONTRACT_LENGTH
FROM  MASTER
LEFT JOIN {{ ref('ODS__TELQS__OSUSR_69G_CONTRACTS') }} CONTRACTS ON CONTRACTS.SERVICECONTRACTQUOTE=MASTER.ID
LEFT JOIN {{ ref('ODS__TELQS__OSUSR_69G_CONTRACTLENGTH') }} CON_LEN ON CON_LEN.ID=CONTRACTS.ContractLengthId
WHERE CONTRACTS.UPDATEDBY IS NOT NULL
),
BOH AS (
    SELECT MASTER.QUOTENUMBER,
    SUM(FLEX.TotalFlexHours) AS TOTAL_BOH_HOURS,
    LISTAGG(distinct PR4TYPEOFWORK.TypeOfWork ,', ') WITHIN GROUP (ORDER BY PR4TYPEOFWORK.TypeOfWork) AS TYPE_OF_WORK
FROM MASTER
LEFT JOIN SERVICE_QUOTE_WITH_CONTRACT SQWC ON master.id=SQWC.servicecontractquotemasterid
LEFT JOIN {{ ref('ODS__TELQS__OSUSR_69G_FLEX') }} FLEX ON FLEX.ServiceQuoteWithContractId=SQWC.ID
LEFT JOIN {{ ref('ODS__TELQS__OSUSR_69G_FLEX_TYPEOFWORK') }} TYPEOFWORK ON FLEX.ID=TYPEOFWORK.FLEXID
LEFT JOIN {{ ref('ODS__TELQS__OSUSR_PR4_TYPEOFWORK') }} PR4TYPEOFWORK ON PR4TYPEOFWORK.ID=TYPEOFWORK.typeofworkid GROUP BY MASTER.QUOTENUMBER
),
DOW AS (SELECT MASTER.QUOTENUMBER,
LISTAGG(distinct AD.DESCRIPTIONOFWORK ,', ') WITHIN GROUP (ORDER BY AD.DESCRIPTIONOFWORK) AS  DESCRIPTION_OF_WORK
FROM MASTER
LEFT JOIN {{ ref('ODS__TELQS__OSUSR_BN7_ADDTIONALDETAILS') }} AD ON AD.ServiceContractQuoteMasterID=MASTER.ID GROUP BY MASTER.QUOTENUMBER
),
FSCTEAM AS(
SELECT MASTER.QUOTENUMBER,
OS_USER.DISPLAYNAME AS FSC_TEAM
FROM MASTER
LEFT JOIN {{ ref('ODS__TELQS__OS_USER_PROFILE') }} OS_USER ON MASTER.UPDATEDBY=OS_USER.USERID
),
source_data as (
SELECT 
    MASTER.QUOTENUMBER AS QUOTENUMBER,
    TO_CHAR(MASTER.REQUESTDATE,'MM/DD/YYYY') AS REQUEST_DATE,
    MASTER.REQUESTOR_NAME AS REQUESTER,
    MASTER.Supervisor_NAME AS REQUESTER_SUPERVISOR,
    case when POSITION(MASTER.CUSTOMER_CODE ,MASTER.CUSTOMER_NAME) =0 then concat(MASTER.CUSTOMER_NAME,' (',MASTER.CUSTOMER_CODE,')') ELSE  MASTER.CUSTOMER_NAME END as CUSTOMER_NAME ,
    case when  MASTER.Is_Comprehensive ='1' then 'Yes' else 'No' END AS Comprehensive,
    PRODUCT.Products AS PRODUCTS,
    CONTRACTTYPEDETAILS.CONTRACT_TYPE AS CONTRACT_TYPE,
    CONTRACTS.CONTRACTSTARTDATE AS CONTRACTSTARTDATE,
    CONTRACTS.CONTRACTENDDATE AS CONTRACTENDDATE,
    MASTER.ContractOverValue AS CONTRACT_TOTAL,
    QUOTESTATUS.QUOTESTATUS AS QUOTE_STATUS,
    FSCTEAM.FSC_TEAM AS FSC_TEAM,
    CONTRACTLENGTH.CONTRACT_LENGTH AS CONTRACT_LENGTH,
    CASE WHEN CONTRACTS.PREVIOUS_CONTRACT_NUMBER='' THEN 'Yes' else 'No' END AS NEW_CONTRACT,
    CONTRACTS.PREVIOUS_CONTRACT_NUMBER AS PREVIOUS_CONTRACT_NUMBER,
    PRODUCT.FAB_CODE AS COVERED_FAB,
    COALESCE(BOH.TOTAL_BOH_HOURS,0) AS TOTAL_BOH_HOURS,
    BOH.TYPE_OF_WORK AS TYPE_OF_WORK,
    DOW.DESCRIPTION_OF_WORK AS DESCRIPTION_OF_WORK
FROM MASTER
LEFT JOIN PRODUCT ON MASTER.QUOTENUMBER=PRODUCT.QUOTENUMBER
LEFT JOIN CONTRACTTYPEDETAILS ON MASTER.QUOTENUMBER=CONTRACTTYPEDETAILS.QUOTENUMBER
LEFT JOIN CONTRACTS ON MASTER.QUOTENUMBER=CONTRACTS.QUOTENUMBER
LEFT JOIN QUOTESTATUS ON MASTER.QUOTENUMBER=QUOTESTATUS.QUOTENUMBER
LEFT JOIN CONTRACTLENGTH ON MASTER.QUOTENUMBER=CONTRACTLENGTH.QUOTENUMBER
LEFT JOIN BOH ON MASTER.QUOTENUMBER=BOH.QUOTENUMBER
LEFT JOIN DOW ON MASTER.QUOTENUMBER=DOW.QUOTENUMBER
LEFT JOIN FSCTEAM ON MASTER.QUOTENUMBER=FSCTEAM.QUOTENUMBER
WHERE LEN(MASTER.QUOTENUMBER)>1
),
transform_data as (
SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
	QUOTENUMBER,
	REQUEST_DATE,
	REQUESTER,
	REQUESTER_SUPERVISOR,
	CUSTOMER_NAME,
	COMPREHENSIVE,
	PRODUCTS,
	CONTRACT_TYPE,
	CONTRACTSTARTDATE,
	CONTRACTENDDATE,
	CONTRACT_TOTAL,
	QUOTE_STATUS,
	FSC_TEAM,
	CONTRACT_LENGTH,
	NEW_CONTRACT ,
	PREVIOUS_CONTRACT_NUMBER,
	COVERED_FAB,
	TOTAL_BOH_HOURS,
	TYPE_OF_WORK,
	DESCRIPTION_OF_WORK
FROM source_data
),
type_data as (
SELECT
    _AUDIT_LOG_ID,
    _ROW_HASH,
	QUOTENUMBER,
	REQUEST_DATE,
	REQUESTER,
	REQUESTER_SUPERVISOR,
	CUSTOMER_NAME,
	COMPREHENSIVE,
	PRODUCTS,
	CONTRACT_TYPE,
	CONTRACTSTARTDATE,
	CONTRACTENDDATE,
	CONTRACT_TOTAL,
	QUOTE_STATUS,
	FSC_TEAM,
	CONTRACT_LENGTH,
	NEW_CONTRACT ,
	PREVIOUS_CONTRACT_NUMBER,
	COVERED_FAB,
	CAST(TOTAL_BOH_HOURS AS NUMERIC(38,0)) AS TOTAL_BOH_HOURS,
	TYPE_OF_WORK,
	DESCRIPTION_OF_WORK
FROM transform_data
)
select * from type_data
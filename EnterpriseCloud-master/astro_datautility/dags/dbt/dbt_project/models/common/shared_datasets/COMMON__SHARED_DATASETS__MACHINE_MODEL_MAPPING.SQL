{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='MACHINE_MODEL_MAPPING',
    unique_key = ['MACHINE_MODEL']
) }}

WITH models AS
(
    SELECT DISTINCT
        LEFT(MAC_LIST_TEL_MODEL_CODE,2) AS MACHINE_PRODUCT_CODE
        ,UPPER(MAC_LIST_TEL_MODEL) AS MACHINE_MODEL
    FROM {{ ref('COMMON__WISDOM__WISDOM_MACHINE_DETAILS') }}
    WHERE MAC_LIST_TEL_MODEL IS NOT NULL AND MAC_LIST_TEL_MODEL_CODE IS NOT NULL
    UNION
    SELECT DISTINCT
        LEFT(MAC_LIST_TEL_MODEL_CODE,2)
        ,UPPER(MAC_LIST_SWLH_MODEL)
    FROM {{ ref('COMMON__WISDOM__WISDOM_MACHINE_DETAILS') }}
    WHERE MAC_LIST_SWLH_MODEL IS NOT NULL AND MAC_LIST_TEL_MODEL_CODE IS NOT NULL
    UNION
    SELECT DISTINCT
        PRODUCT_CD
        ,UPPER(MODEL_NM)
    FROM {{ ref('COMMON__WISDOM__SAP_SURB') }}
    WHERE SALES_CTG IN ('10', '11','12','13') AND PRODUCT_CD IS NOT NULL
    UNION
    SELECT DISTINCT
        PRODUCT_CODE
        ,UPPER(MODEL)
    FROM {{ ref('COMMON__DE_SALES_OPERATIONS__SALES_CRM_MODEL') }}
    WHERE PRODUCT_CODE IS NOT NULL
),
mapping AS
(
    SELECT
        MACHINE_MODEL_KEY
        ,MODEL_GROUP1
        ,MODEL_GROUP2
        ,MODEL_GROUP3
        ,PLANNING_INSTALL_DURATION_MONTH
        ,PLANNING_INSTALL_DURATION_HOUR
        ,PLANNING_WARRANTY_FACTOR AS PLANNING_WARRANTY_TERM_FACTOR
        ,PLANNING_WARRANTY_HOUR
        ,USED_FLAG
    FROM {{ ref('ODS__SHAREPOINT__MACHINE_MODEL_MAPPING') }}
    WHERE MACHINE_MODEL_KEY IS NOT NULL
),
business_unit AS
(
    SELECT
        BU_SOURCE_KEY
        ,BU_GROUP
    FROM {{ ref('ODS__SHAREPOINT__SERVICE_BUSINESS_UNIT_MAPPING') }}
),
combined AS
(
    SELECT
        models.MACHINE_MODEL
        ,models.MACHINE_PRODUCT_CODE
        ,business_unit.BU_GROUP
        ,mapping.MODEL_GROUP1
        ,mapping.MODEL_GROUP2
        ,mapping.MODEL_GROUP3
        ,mapping.PLANNING_INSTALL_DURATION_MONTH
        ,mapping.PLANNING_INSTALL_DURATION_HOUR
        ,mapping.PLANNING_WARRANTY_TERM_FACTOR
        ,mapping.PLANNING_WARRANTY_HOUR
        ,mapping.USED_FLAG
    FROM models
    LEFT OUTER JOIN mapping
    ON UPPER(models.MACHINE_MODEL) = mapping.MACHINE_MODEL_KEY
    LEFT OUTER JOIN business_unit
    ON models.MACHINE_PRODUCT_CODE = business_unit.BU_SOURCE_KEY
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY MACHINE_MODEL ORDER BY BU_GROUP) = 1)
),
transform_data AS
(
    SELECT
        MACHINE_MODEL
        ,MACHINE_PRODUCT_CODE
        ,BU_GROUP
        ,MODEL_GROUP1
        ,MODEL_GROUP2
        ,MODEL_GROUP3
        ,PLANNING_INSTALL_DURATION_MONTH
        ,PLANNING_INSTALL_DURATION_HOUR
        ,PLANNING_WARRANTY_TERM_FACTOR
        ,PLANNING_WARRANTY_HOUR
        ,USED_FLAG
        ,'{{ invocation_id }}' AS _AUDIT_LOG_ID
        ,SHA2('hash_me') as _ROW_HASH
    FROM combined
),
type_data as
(
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
        ,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
        ,CAST(MACHINE_MODEL as VARCHAR(16777216)) AS MACHINE_MODEL
        ,CAST(MACHINE_PRODUCT_CODE as VARCHAR(16777216)) AS MACHINE_PRODUCT_CODE
        ,CAST(BU_GROUP as VARCHAR(16777216)) AS BU_GROUP
        ,CAST(MODEL_GROUP1 as VARCHAR(16777216)) AS MODEL_GROUP1
        ,CAST(MODEL_GROUP2 as VARCHAR(16777216)) AS MODEL_GROUP2
        ,CAST(MODEL_GROUP3 as VARCHAR(16777216)) AS MODEL_GROUP3
        ,CAST(PLANNING_INSTALL_DURATION_MONTH as NUMBER(38,0)) AS PLANNING_INSTALL_DURATION_MONTH
        ,CAST(PLANNING_INSTALL_DURATION_HOUR as NUMBER(38,2)) AS PLANNING_INSTALL_DURATION_HOUR
        ,CAST(PLANNING_WARRANTY_TERM_FACTOR as NUMBER(38,2)) AS PLANNING_WARRANTY_TERM_FACTOR
        ,CAST(PLANNING_WARRANTY_HOUR as NUMBER(38,2)) AS PLANNING_WARRANTY_HOUR
        ,CAST(USED_FLAG as VARCHAR(16777216)) AS USED_FLAG
    FROM transform_data
    ORDER BY BU_GROUP, MACHINE_MODEL
)
SELECT * FROM type_data
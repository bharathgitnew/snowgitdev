    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='PRODUCT_TYPE_MAPPING',
    unique_key = ['PRODUCT_TYPE_KEY']
) }}

WITH PT_ALL AS
(
    SELECT
        DISTINCT PRODUCT_TYPE_CODE
    FROM {{ source('ODS__BAAN', 'LEGACY_FSTR_FST_BUDGET_ACTUAL_FORECAST_LEGACY') }}
    UNION
    SELECT
        DISTINCT REPLACE(DIMENSION_4,' ','')
    FROM {{ source('ODS__BAAN', 'LEGACY_TELR_BAANV_TEA_FINALIZED_TRANSACTIONS') }}
    WHERE LEN(DIMENSION_4) > 1
    AND LEFT (LEDGER_ACC,1) IN ('4','5')
    UNION
    SELECT
        DISTINCT PT_KEY
    FROM {{ ref('ODS__SHAREPOINT__SERVICE_PRODUCT_TYPE_MAPPING') }}
    UNION
    SELECT
        DISTINCT SAP_SALES_CATEGORY
    FROM {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }}
    UNION
    SELECT
        DISTINCT SALES_CATEGORY
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE_ENHANCED') }}
    WHERE LEN(SALES_CATEGORY) > 1
    UNION
    SELECT
        DISTINCT FINANCIALPRODUCTCODE
    FROM {{ ref('COMMON__SAPH__ACTUAL_BUDGET_FORECAST_PNL') }}
    WHERE LEN(FINANCIALPRODUCTCODE) > 1
),
BAAN_PT AS
(
    SELECT
        REPLACE(DIMENSION_CODE,' ','') AS BAAN_DIM
        ,REPLACE(DIMENSION_DESCRIPTION, ' ', '') AS BAAN_NAME
    FROM {{ source('ODS__BAAN', 'LEGACY_TELR_BAANV_TEA_DIMENSIONS') }}
    WHERE DIMENSION_TYPE_CODE = 4
),
PT_MAP AS
(
    SELECT
        PT_KEY
        ,PRODUCT_TYPE
        ,PRODUCT_TYPE_MAPPED
        ,PRODUCT_TYPE_CATEGORY
        ,PRODUCT_TYPE_GROUP
        ,PRODUCT_TYPE_GROUP2
        ,REVENUE_SOURCE
        ,STATUTORY_GROUP
        ,PRODUCT_TYPE_CODE_MAPPED
    FROM {{ ref('ODS__SHAREPOINT__SERVICE_PRODUCT_TYPE_MAPPING') }}
),
SAP_SC AS
(
    SELECT
        SAP_SALES_CATEGORY
        ,SAP_SALES_CATEGORY_NAME
        ,BAAN_PRODUCT_TYPE
        ,CASE
            WHEN
                BAAN_PRODUCT_TYPE = 'CORPADMIN' THEN 'ADMIN'
            ELSE BAAN_PRODUCT_TYPE
            END AS BAAN_PRODUCT_TYPE_ADJ
        ,PRODUCT_TYPE AS SAP_PRODUCT_TYPE
        ,PRODUCT_TYPE_CATEGORY AS SAP_PRODUCT_TYPE_CATEGORY
        ,PRODUCT_TYPE_GROUP AS SAP_PRODUCT_TYPE_GROUP
        ,PRODUCT_TYPE_GROUP2 AS SAP_PRODUCT_TYPE_GROUP2
        ,REVENUE_SOURCE AS SAP_REVENUE_SOURCE
        ,STATUTORY_GROUP AS SAP_STATUTORY_GROUP
        ,PRODUCT_TYPE_CODE_MAPPED AS SAP_PRODUCT_TYPE_CODE_MAPPED
        ,PRODUCT_TYPE_MAPPED AS SAP_PRODUCT_TYPE_MAPPED
    FROM {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }}
    LEFT OUTER JOIN PT_MAP
    ON PT_MAP.PT_KEY = SAP_SALES_CATEGORY.BAAN_PRODUCT_TYPE
),
COMBINED AS (
    SELECT
        PT_ALL.PRODUCT_TYPE_CODE AS PRODUCT_TYPE_KEY
        ,COALESCE(SAP_SC.BAAN_PRODUCT_TYPE, PT_ALL.PRODUCT_TYPE_CODE) AS PRODUCT_TYPE_CODE
        ,COALESCE(SAP_SC.SAP_PRODUCT_TYPE, PT_MAP.PRODUCT_TYPE,BAAN_PT.BAAN_NAME) AS PRODUCT_TYPE_NAME
        ,COALESCE(SAP_SC.SAP_PRODUCT_TYPE_CATEGORY, PT_MAP.PRODUCT_TYPE_CATEGORY) AS PRODUCT_TYPE_CATEGORY
        ,COALESCE(SAP_SC.SAP_PRODUCT_TYPE_GROUP, PT_MAP.PRODUCT_TYPE_GROUP) AS PRODUCT_TYPE_GROUP
        ,COALESCE(SAP_SC.SAP_PRODUCT_TYPE_GROUP2, PT_MAP.PRODUCT_TYPE_GROUP2) AS PRODUCT_TYPE_GROUP2
        ,COALESCE(SAP_SC.SAP_REVENUE_SOURCE, PT_MAP.REVENUE_SOURCE) AS REVENUE_SOURCE
        ,COALESCE(SAP_SC.SAP_STATUTORY_GROUP, PT_MAP.STATUTORY_GROUP) AS STATUTORY_GROUP
        ,COALESCE(SAP_SC.SAP_PRODUCT_TYPE_CODE_MAPPED, PT_MAP.PRODUCT_TYPE_CODE_MAPPED) AS PRODUCT_TYPE_CODE_MAPPED
        ,COALESCE(SAP_SC.SAP_PRODUCT_TYPE_MAPPED, PT_MAP.PRODUCT_TYPE_MAPPED) AS PRODUCT_TYPE_MAPPED
        ,SAP_SALES_CATEGORY_NAME
        ,CASE
            WHEN
                LEN(PT_ALL.PRODUCT_TYPE_CODE) = '2' AND PT_ALL.PRODUCT_TYPE_CODE NOT IN ('NA', '-1') THEN 'SAP Sales Category'
            WHEN
                PT_ALL.PRODUCT_TYPE_CODE IN ('SAP_98', 'SAP_99') THEN 'SAP Sales Category'
            ELSE 'Legacy'
            END AS SOURCE_SYSTEM
    FROM PT_ALL
    LEFT OUTER JOIN PT_MAP
    ON PT_ALL.PRODUCT_TYPE_CODE = PT_MAP.PT_KEY
    LEFT OUTER JOIN BAAN_PT
    ON PT_ALL.PRODUCT_TYPE_CODE = BAAN_PT.BAAN_DIM
    LEFT OUTER JOIN SAP_SC
    ON PT_ALL.PRODUCT_TYPE_CODE = SAP_SC.SAP_SALES_CATEGORY AND LEN(PT_ALL.PRODUCT_TYPE_CODE) = 2
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY PT_ALL.PRODUCT_TYPE_CODE ORDER BY SOURCE_SYSTEM) = 1)
),
transform_data AS
(
    SELECT
        PRODUCT_TYPE_KEY
        ,PRODUCT_TYPE_CODE
        ,PRODUCT_TYPE_NAME
        ,PRODUCT_TYPE_CATEGORY
        ,PRODUCT_TYPE_GROUP
        ,PRODUCT_TYPE_GROUP2
        ,REVENUE_SOURCE
        ,STATUTORY_GROUP
        ,PRODUCT_TYPE_CODE_MAPPED
        ,PRODUCT_TYPE_MAPPED
        ,SAP_SALES_CATEGORY_NAME
        ,SOURCE_SYSTEM
        ,'{{ invocation_id }}' AS _AUDIT_LOG_ID
        ,SHA2('hash_me') as _ROW_HASH
    FROM COMBINED
    WHERE NULLIF(PRODUCT_TYPE_KEY,'') IS NOT NULL
    ORDER BY SOURCE_SYSTEM,PRODUCT_TYPE_KEY
),
type_data AS
(
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
        ,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
        ,CAST(PRODUCT_TYPE_KEY as VARCHAR(16777216)) AS PRODUCT_TYPE_KEY
        ,CAST(PRODUCT_TYPE_CODE as VARCHAR(16777216)) AS PRODUCT_TYPE_CODE
        ,CAST(PRODUCT_TYPE_NAME as VARCHAR(16777216)) AS PRODUCT_TYPE_NAME
        ,CAST(PRODUCT_TYPE_CATEGORY as VARCHAR(16777216)) AS PRODUCT_TYPE_CATEGORY
        ,CAST(PRODUCT_TYPE_GROUP as VARCHAR(16777216)) AS PRODUCT_TYPE_GROUP
        ,CAST(PRODUCT_TYPE_GROUP2 as VARCHAR(16777216)) AS PRODUCT_TYPE_GROUP2
        ,CAST(REVENUE_SOURCE as VARCHAR(16777216)) AS REVENUE_SOURCE
        ,CAST(STATUTORY_GROUP as VARCHAR(16777216)) AS STATUTORY_GROUP
        ,CAST(PRODUCT_TYPE_CODE_MAPPED as VARCHAR(16777216)) AS PRODUCT_TYPE_CODE_MAPPED
        ,CAST(PRODUCT_TYPE_MAPPED as VARCHAR(16777216)) AS PRODUCT_TYPE_MAPPED
        ,CAST(SAP_SALES_CATEGORY_NAME as VARCHAR(16777216)) AS SAP_SALES_CATEGORY_NAME
        ,CAST(SOURCE_SYSTEM as VARCHAR(16777216)) AS SOURCE_SYSTEM
    FROM transform_data)
SELECT * FROM type_data

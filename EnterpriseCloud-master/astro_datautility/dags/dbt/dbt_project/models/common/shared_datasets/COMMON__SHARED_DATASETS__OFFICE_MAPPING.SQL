{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='OFFICE_MAPPING',
    unique_key = ['OFFICE_CODE']
) }}

WITH OFFICE_ALL AS
(
	SELECT
		DISTINCT SAP_CODE AS OFFICE_CODE
		FROM {{ ref('COMMON__SAPH__SAP_REGION') }}
	UNION
	SELECT DISTINCT
	LEFT(DIMENSION_3,4)
	FROM {{ source('ODS__BAAN', 'LEGACY_TELR_BAANV_TEA_FINALIZED_TRANSACTIONS') }}
	WHERE LEN(DIMENSION_3) > 1
	UNION
	SELECT DISTINCT OFFICE_CODE
	FROM {{ ref('ODS__SHAREPOINT__SERVICE_OFFICE_MAPPING') }}
),
MAPPING AS
(
	SELECT
		OFFICE_CODE
		,OFFICE
		,REGION
		,REGION_GROUP
		,REGION_GROUP2
	FROM {{ ref('ODS__SHAREPOINT__SERVICE_OFFICE_MAPPING') }}
),
SAPREGION AS (
	SELECT
		SAP_CODE
		,ORACLE_CODE
		,ORACLE_DESCRIPTION
		,SAP_DESCRIPTION
		,MAPPING.OFFICE
		,MAPPING.REGION
		,MAPPING.REGION_GROUP
		,MAPPING.REGION_GROUP2
	FROM {{ ref('COMMON__SAPH__SAP_REGION') }}
	LEFT OUTER JOIN MAPPING
	ON SAP_REGION.ORACLE_CODE = 'R'||OFFICE_CODE
	WHERE SAP_CODE IS NOT NULL ORDER BY SAP_CODE
),
transform_data AS
(
    SELECT
		OFFICE_ALL.OFFICE_CODE
		,COALESCE(MAPPING.OFFICE,SAPREGION.OFFICE) AS OFFICE
		,COALESCE(MAPPING.REGION,SAPREGION.REGION) AS REGION
		,COALESCE(MAPPING.REGION_GROUP,SAPREGION.REGION_GROUP) AS REGION_GROUP
		,COALESCE(MAPPING.REGION_GROUP2,SAPREGION.REGION_GROUP2) AS REGION_GROUP2
		,CASE
			WHEN
				MAPPING.OFFICE_CODE = '-1' THEN 'No Region'
			WHEN
				LEN(MAPPING.OFFICE_CODE) = 4 THEN 'R'||OFFICE_ALL.OFFICE_CODE
			ELSE SAPREGION.ORACLE_CODE
			END AS ORACLE_CODE
		,SAPREGION.ORACLE_DESCRIPTION
		,SAPREGION.SAP_DESCRIPTION
		,CASE
			WHEN
				SAPREGION.SAP_CODE IS NOT NULL THEN 'SAP'
			ELSE 'BAAN'
			END AS SOURCE_APPLICATION
		,'{{ invocation_id }}' AS _AUDIT_LOG_ID
        ,SHA2('hash_me') as _ROW_HASH
	FROM OFFICE_ALL
	LEFT OUTER JOIN SAPREGION
	ON OFFICE_ALL.OFFICE_CODE = SAPREGION.SAP_CODE
	LEFT OUTER JOIN MAPPING
	ON OFFICE_ALL.OFFICE_CODE = MAPPING.OFFICE_CODE
	QUALIFY (ROW_NUMBER() OVER (PARTITION BY OFFICE_ALL.OFFICE_CODE ORDER BY MAPPING.OFFICE) = 1)
),
type_data AS
(
    SELECT
        CAST(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID
        ,CAST(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
        ,CAST(OFFICE_CODE as VARCHAR(16777216)) AS OFFICE_CODE
        ,CAST(OFFICE as VARCHAR(16777216)) AS OFFICE
        ,CAST(REGION as VARCHAR(16777216)) AS REGION
        ,CAST(REGION_GROUP as VARCHAR(16777216)) AS REGION_GROUP
        ,CAST(REGION_GROUP2 as VARCHAR(16777216)) AS REGION_GROUP2
        ,CAST(ORACLE_CODE as VARCHAR(16777216)) AS ORACLE_CODE
        ,CAST(ORACLE_DESCRIPTION as VARCHAR(16777216)) AS ORACLE_DESCRIPTION
        ,CAST(SAP_DESCRIPTION as VARCHAR(16777216)) AS SAP_DESCRIPTION
        ,CAST(SOURCE_APPLICATION as VARCHAR(16777216)) AS SOURCE_APPLICATION
    FROM transform_data
)

SELECT * FROM type_data
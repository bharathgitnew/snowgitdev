transform_data as
(
        SELECT
            EMPLOYEE_ID,
            FULL_NAME,
            FIRST_NAME,
            LAST_NAME,
            EMAILADDRESS,
            SUPERVISOR_EMPLOYEE_ID,
            SUPERVISOR_NAME,
            SENIORITY_DATE,
            HIRE_DATE,
            REHIRE_DATE,
            TERMINATION_DATE,
            SALARY_TYPE,
            EMPLOYEE_STATUS,
            IS_EXPAT,
            IS_MANAGER,
            BUSINESS_UNIT,
            COMPANY_ID,
            DEPARTMENT_ID,
            OFFICE_ID,
            JOB_TITLE,
            JOB_FAMILY_GROUPNAME,
            EMPLOYEE_TYPE_CODE,
            EMPLOYEE_TYPE,
            EMPLOYEE_TYPE_FST,
            GROUP_NAME_FST,
            ACTIVEDIRECTORYID,
            ACTIVEDIRECTORYDISPLAYNAME,
            IS_IN_WORKDAY,
            IS_IN_TEACOMMON,
            IS_IN_ACTIVEDIRECTORY,

        FIRST_NAME,
        LAST_NAME,
        EMAILADDRESS,
        SUPERVISOR_EMPLOYEE_ID,
        SUPERVISOR_NAME,
        SENIORITY_DATE,
        HIRE_DATE,
        REHIRE_DATE,
        TERMINATION_DATE,
        SALARY_TYPE,
        EMPLOYEE_STATUS,

        cast(EMPLOYEE_TYPE as VARCHAR(16777216)) as EMPLOYEE_TYPE,
        cast(EMPLOYEE_TYPE_FST as VARCHAR(16777216)) as EMPLOYEE_TYPE_FST,
        cast(GROUP_NAME_FST as VARCHAR(16777216)) as GROUP_NAME_FST,
        cast(ACTIVEDIRECTORYID as VARCHAR(16777216)) as ACTIVEDIRECTORYID,
        cast(ACTIVEDIRECTORYDISPLAYNAME as VARCHAR(16777216)) as ACTIVEDIRECTORYDISPLAYNAME,
        cast(IS_IN_WORKDAY as VARCHAR(16777216)) as IS_IN_WORKDAY,
        cast(IS_IN_TEACOMMON as VARCHAR(16777216)) as IS_IN_TEACOMMON,
        cast(IS_IN_ACTIVEDIRECTORY as VARCHAR(16777216)) as IS_IN_ACTIVEDIRECTORY,
        cast(COMPANY_HR_REGION as VARCHAR(16777216)) as COMPANY_HR_REGION,
        cast(SECURITY_USERID as VARCHAR(16777216)) as SECURITY_USERID,
        cast(US_REGION_STATUS as VARCHAR(16777216)) as US_REGION_STATUS,
        cast(IS_MANAGER_FLAG as VARCHAR(16777216)) as IS_MANAGER_FLAG,
        cast(Current_Home_Company_Id as VARCHAR(16777216)) as Current_Home_Company_Id,
        cast(Current_Home_Department_Id as VARCHAR(16777216)) as Current_Home_Department_Id,
        cast(Current_Host_Company_Id as VARCHAR(16777216)) as Current_Host_Company_Id,
        cast(Current_Host_Department_Id as VARCHAR(16777216)) as Current_Host_Department_Id,
        CAST(SNAPSHOT_DATE AS DATE) AS SNAPSHOT_DATE,
        cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
        cast(_Row_Hash as varchar(128)) as _ROW_HASH
    from transform_data
    )

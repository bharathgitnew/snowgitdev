,type_data as
(
    select
        cast(EMPLOYEE_ID as VARCHAR(16777216)) as EMPLOYEE_ID,
        cast(FULL_NAME as VARCHAR(16777216)) as FULL_NAME,
        cast(FIRST_NAME as VARCHAR(16777216)) as FIRST_NAME,
        cast(LAST_NAME as VARCHAR(16777216)) as LAST_NAME,
        cast(EMAILADDRESS as VARCHAR(16777216)) as EMAILADDRESS,
        cast(SUPERVISOR_EMPLOYEE_ID as VARCHAR(16777216)) as SUPERVISOR_EMPLOYEE_ID,
        CAST(SUPERVISOR_NAME AS VARCHAR(16777216)) AS SUPERVISOR_NAME,
        cast(SENIORITY_DATE as DATE) as SENIORITY_DATE,
        cast(HIRE_DATE AS DATE) AS HIRE_DATE,
        cast(REHIRE_DATE as DATE) as REHIRE_DATE,
        cast(TERMINATION_DATE AS DATE) AS TERMINATION_DATE,
        cast(SALARY_TYPE as VARCHAR(16777216)) as SALARY_TYPE,
        cast(EMPLOYEE_STATUS as VARCHAR(16777216)) as EMPLOYEE_STATUS,

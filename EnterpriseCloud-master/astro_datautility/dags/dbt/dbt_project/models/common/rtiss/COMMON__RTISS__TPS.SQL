{{ config(
	materialized='incremental',
	incremental_strategy='insert_overwrite',
	alias='TPS',
	transient=false
) }}

with source_data as (
SELECT
	_FILEDATE,
	_FILENAME,
	RTISS_NO,
    BU,
    SUBJECT,
    AUTHOR,
    CUSTOMERNAME,
    MODELNAME,
    MODULENAME,
    DETAILS,
    MAC_SN,
    NCDRNO,
    STATUS,
    OCCURRENCEDATE,
    DEPTINCHARGE,
    PERSONINCHARGE,
    COMPLETIONDATE,
    DUEDATE,
    MACHINEWARRANTYSTATUS,
    LASTUPDATEDAT,
    URL
FROM {{ ref('ODS__RTISS__TPS') }} AS CT

),
transform_data as (
SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	SHA2('hash_me') as _ROW_HASH,
	RTISS_NO,
    BU,
    SUBJECT,
    AUTHOR,
    CUSTOMERNAME,
    MODELNAME,
    MODULENAME,
    DETAILS,
    MAC_SN,
    NCDRNO,
    STATUS,
    OCCURRENCEDATE,
    DEPTINCHARGE,
    PERSONINCHARGE,
    COMPLETIONDATE,
    DUEDATE,
    MACHINEWARRANTYSTATUS,
    LASTUPDATEDAT,
    URL
FROM source_data
),
type_data as (
SELECT
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	CAST(RTISS_NO AS NUMBER(38,0)) AS RTISS_NO,
    BU,
    SUBJECT,
    AUTHOR,
    CUSTOMERNAME,
    MODELNAME,
    MODULENAME,
    DETAILS,
    MAC_SN,
    NCDRNO,
    STATUS,
    CAST(OCCURRENCEDATE AS TIMESTAMP_NTZ(9)) AS OCCURRENCEDATE,
    DEPTINCHARGE,
    PERSONINCHARGE,
    CAST(COMPLETIONDATE AS TIMESTAMP_NTZ(9)) AS COMPLETIONDATE,
    CAST(DUEDATE AS TIMESTAMP_NTZ(9)) AS DUEDATE,
    MACHINEWARRANTYSTATUS,
    CAST(LASTUPDATEDAT AS TIMESTAMP_NTZ(9)) AS LASTUPDATEDAT,
    URL
FROM transform_data
)
SELECT * FROM type_data
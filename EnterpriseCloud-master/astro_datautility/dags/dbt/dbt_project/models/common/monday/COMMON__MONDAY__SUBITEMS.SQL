{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='SUBITEMS',
    unique_key = ['BOARDS_ID',
     'ITEMS_ID',
     'SUBITEMS_ID']
) }}

WITH subitems AS
(
    SELECT
        ACCOUNT_ID
        ,BOARDS_ID
        ,BOARDS_NAME
        ,ITEMS_ID
        ,ITEMS_NAME
        ,SUBITEMS_ID
        ,SUBITEMS_NAME
        ,MAX("'Owner Sub-item (R)'") AS SUBITEMS_OWNER_R
        ,MAX("'Timeline Sub-item (R)'") AS SUBITEMS_TIMELINE_R
        ,MAX("'Duration Sub-item (R)'") AS SUBITEMS_DURATION_R
        ,MAX("'Status Sub-item (R)'") AS SUBITEMS_STATUS_R
        ,MAX("'Completion % Sub-item (R)'") AS SUBITEMS_COMPLETION_R
        ,SUBSTR(SUBITEMS_TIMELINE_R, 0, 10) as SUBITEMS_STARTDATE
        ,SUBSTR(SUBITEMS_TIMELINE_R, -10, 10) as SUBITEMS_ENDDATE
        ,SUBITEMS_UPDATED_AT
        ,_FILEDATE
    FROM {{ ref('ODS__MONDAY__SUBITEMS') }}
        PIVOT (MAX(TEXT) for TITLE in (
        'Owner Sub-item (R)',
        'Timeline Sub-item (R)',
        'Duration Sub-item (R)',
        'Status Sub-item (R)',
        'Completion % Sub-item (R)'
        ))
    -- WHERE BOARDS_ID IN (
    --     '4811102084'
    --     ,'3946712305'
    --     ,'3946712609'
    --     ,'3679695583'
    --     )
    GROUP BY
        ACCOUNT_ID
        ,BOARDS_ID
        ,BOARDS_NAME
        ,ITEMS_ID
        ,ITEMS_NAME
        ,SUBITEMS_ID
        ,SUBITEMS_NAME
        ,SUBITEMS_UPDATED_AT
        ,_FILEDATE
)

,workspace AS
(
    SELECT
        WORKSPACE_ID
        ,WORKSPACE_NAME
        ,BOARD_ID
    FROM {{ ref('ODS__MONDAY__WORKSPACE') }}
)

,source_data AS
(
    SELECT
        WORKSPACE_ID
        ,WORKSPACE_NAME
        ,ACCOUNT_ID
        ,BOARDS_ID
        ,BOARDS_NAME
        ,ITEMS_ID
        ,ITEMS_NAME
        ,SUBITEMS_ID
        ,SUBITEMS_NAME
        ,SUBITEMS_OWNER_R
        ,SUBITEMS_TIMELINE_R
        ,SUBITEMS_DURATION_R
        ,SUBITEMS_STATUS_R
        ,SUBITEMS_COMPLETION_R
        ,SUBITEMS_STARTDATE
        ,SUBITEMS_ENDDATE
        ,SUBITEMS_UPDATED_AT
        ,_FILEDATE
    FROM subitems
    LEFT OUTER JOIN workspace on subitems.BOARDS_ID = workspace.BOARD_ID
)

,transform_data AS
(
    SELECT
        WORKSPACE_ID AS WORKSPACE_ID
        ,WORKSPACE_NAME AS WORKSPACE_NAME
        ,ACCOUNT_ID AS ACCOUNT_ID
        ,BOARDS_ID AS BOARDS_ID
        ,BOARDS_NAME AS BOARDS_NAME
        ,ITEMS_ID AS ITEMS_ID
        ,ITEMS_NAME AS ITEMS_NAME
        ,SUBITEMS_ID AS SUBITEMS_ID
        ,SUBITEMS_NAME AS SUBITEMS_NAME
        ,SUBITEMS_OWNER_R AS SUBITEMS_OWNER_R
        ,SUBITEMS_TIMELINE_R AS SUBITEMS_TIMELINE_R
        ,SUBITEMS_DURATION_R AS SUBITEMS_DURATION_R
        ,SUBITEMS_STATUS_R AS SUBITEMS_STATUS_R
        ,SUBITEMS_COMPLETION_R AS SUBITEMS_COMPLETION_R
        ,SUBITEMS_STARTDATE AS SUBITEMS_STARTDATE
        ,SUBITEMS_ENDDATE AS SUBITEMS_ENDDATE
        ,SUBITEMS_UPDATED_AT AS SUBITEMS_UPDATED_AT
        ,_FILEDATE AS _FILEDATE
        ,'{{ invocation_id }}' AS _AUDIT_LOG_ID
        ,SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    FROM source_data
)

,type_data AS
(
    SELECT
        CAST(WORKSPACE_ID AS VARCHAR(16777216)) AS WORKSPACE_ID
        ,CAST(WORKSPACE_NAME AS VARCHAR(16777216)) AS WORKSPACE_NAME
        ,CAST(ACCOUNT_ID AS VARCHAR(16777216)) AS ACCOUNT_ID
        ,CAST(BOARDS_ID AS VARCHAR(16777216)) AS BOARDS_ID
        ,CAST(BOARDS_NAME AS VARCHAR(16777216)) AS BOARDS_NAME
        ,CAST(ITEMS_ID AS VARCHAR(16777216)) AS ITEMS_ID
        ,CAST(ITEMS_NAME AS VARCHAR(16777216)) AS ITEMS_NAME
        ,CAST(SUBITEMS_ID AS VARCHAR(16777216)) AS SUBITEMS_ID
        ,CAST(SUBITEMS_NAME AS VARCHAR(16777216)) AS SUBITEMS_NAME
        ,CAST(SUBITEMS_OWNER_R AS VARCHAR(16777216)) AS SUBITEMS_OWNER_R
        ,CAST(SUBITEMS_TIMELINE_R AS VARCHAR(16777216)) AS SUBITEMS_TIMELINE_R
        ,CAST(SUBITEMS_DURATION_R AS NUMBER(38,10)) AS SUBITEMS_DURATION_R
        ,CAST(SUBITEMS_STATUS_R AS VARCHAR(16777216)) AS SUBITEMS_STATUS_R
        ,CAST(SUBITEMS_COMPLETION_R AS NUMBER(38,10)) AS SUBITEMS_COMPLETION_R
        ,CAST(SUBITEMS_STARTDATE AS TIMESTAMP_LTZ(9)) AS SUBITEMS_STARTDATE
        ,CAST(SUBITEMS_ENDDATE AS TIMESTAMP_LTZ(9)) AS SUBITEMS_ENDDATE
        ,CAST(SUBITEMS_UPDATED_AT AS TIMESTAMP_LTZ(9)) AS SUBITEMS_UPDATED_AT
        ,CAST(_FILEDATE AS TIMESTAMP_LTZ(9)) AS _FILEDATE
        ,CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID
        ,CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)

SELECT * FROM type_data
with items AS
(
    SELECT
        ACCOUNT_ID
        ,BOARDS_ID
        ,BOARDS_NAME
        ,ITEMS_ID
        ,ITEMS_NAME
        ,ITEMS_GROUP_TITLE
        ,max("'Project Status (R)'") AS PROJECT_STATUS_R
        ,max("'Class (R)'") AS CLASS_R
        ,max("'Business Group (R)'") AS BUSINESS_GROUP_R
        ,max("'Tasks Status (R)'") AS TASKS_STATUS_R
        ,max("'Strategic Initiative (R)'") AS STRATEGIC_INITIATIVE_R
        ,max("'Project Manager (R)'") AS PROJECT_MANAGER_R
        ,max("'Sponsor (R)'") AS SPONSOR_R
        ,max("'Goal Statement (R)'") AS GOAL_STATEMENT_R
        ,max("'Problem Statement (R)'") AS PROBLEM_STATEMENT_R
        ,max("'Scope (R)'") AS SCOPE_R
        ,max("'Business Case (R)'") AS BUSINESS_CASE_R
        ,max("'Level of Confidentiality (R)'") AS LEVEL_OF_CONFIDENTIALITY_R
        ,max("'Start Date – End Date (R)'") AS STARTDATE_ENDDATE_R
        ,max("'Project Completion (R)'") AS PROJECT_COMPLETION_R
        ,max("'Group (R)'") AS GROUP_R
        ,max("'Priority (R)'") AS PRIORITY_R
        ,max("'Project or Task (R)'") AS PROJECT_FLAG_R
        ,SUBSTR(max("'Creation Log (R)'"), 0, 19) AS CREATION_LOG_R
        ,max("'Sponsor Business Group (O)'") AS SPONSOR_BUSINESS_GROUP_O
        ,max("'Resource Hours (O)'") AS RESOURCE_HOURS_O
        ,max("'Cost to Implement (O)'") AS COST_TO_IMPLEMENT_O
        ,max("'Financial Impact (O)'") AS FINANCIAL_IMPACT_O
        ,max("'Intangible Impact (O)'") AS INTANGIBLE_IMPACT_O
        ,max("'Four Corners (O)'") AS FOUR_CORNERS_O
        ,max("'Phase (O)'") AS PHASE_O
        ,max("'Related Docs (O)'") AS RELATED_DOCS_O
        -- ,max("'Owner (R)'") AS GT_TASK_OWNER_R
        -- ,max("'Timeline (R)'") AS GT_TIMELINE_R
        -- ,max("'Task Duration (R)'") AS GT_TASK_DURATION_R
        -- ,max("'Priority (R)'") AS GT_PRIORITY_R
        -- ,max("'Task Completion % (R)'") AS GT_TASK_COMPLETION_R
        -- ,max("'Task Description (R)'") AS GT_TASK_DESCRIPTION_R
        -- ,SUBSTR(GT_TIMELINE_R, 0, 10) as GT_TASK_STARTDATE
        -- ,SUBSTR(GT_TIMELINE_R, -10, 10) as GT_TASK_ENDDATE
        ,ITEMS_UPDATED_AT
        ,_FILEDATE
    FROM {{ ref('ODS__MONDAY__ITEMS') }}
    PIVOT (MAX(TEXT) for TITLE in (
        'Project Status (R)'
        ,'Class (R)'
        ,'Business Group (R)'
        ,'Sponsor Business Group (O)'
        ,'Tasks Status (R)'
        ,'Strategic Initiative (R)'
        ,'Project Manager (R)'
        ,'Sponsor (R)'
        ,'Team Members (R)'
        ,'Goal Statement (R)'
        ,'Problem Statement (R)'
        ,'Scope (R)'
        ,'Business Case (R)'
        ,'Level of Confidentiality (R)'
        ,'Start Date – End Date (R)'
        ,'Project Completion (R)'
        ,'Priority (R)'
        ,'Group (R)'
        ,'Project or Task (R)'
        ,'Creation Log (R)'
        ,'Resource Hours (O)'
        ,'Cost to Implement (O)'
        ,'Financial Impact (O)'
        ,'Intangible Impact (O)'
        ,'Four Corners (O)'
        ,'Phase (O)'
        ,'Related Docs (O)'
        -- ,'Owner (R)'
        -- ,'Timeline (R)'
        -- ,'Task Duration (R)'
        -- ,'Task Completion % (R)'
        -- ,'Task Description (R)'
        ))
    -- WHERE BOARDS_ID IN (
    --     '4811102084'
    --     ,'3946712305'
    --     ,'3946712609'
    --     ,'3679695583'
    --     )
    GROUP BY
        ACCOUNT_ID
        ,BOARDS_ID
        ,BOARDS_NAME
        ,ITEMS_ID
        ,ITEMS_NAME
        ,ITEMS_UPDATED_AT
        ,ITEMS_GROUP_TITLE
        ,_FILEDATE
)

,subitems_items AS
(
    SELECT
        -- WORKSPACE_ID
        -- ,WORKSPACE_NAME
        ITEMS_ID AS SUBITEMS_ITEMS_ID
        ,LISTAGG(DISTINCT(SUBITEMS_OWNER_R), ', ') AS TEAM_MEMBERS_R
        ,MIN(SUBITEMS_STARTDATE) AS SUBITEMS_STARTDATE_MIN
        ,MAX(SUBITEMS_ENDDATE) AS SUBITEMS_ENDDATE_MAX
        ,SUM(SUBITEMS_DURATION_R) AS SUBITEMS_ITEMS_DURATION
    FROM  {{ ref('COMMON__MONDAY__SUBITEMS') }}
    GROUP BY
        -- WORKSPACE_ID
        -- ,WORKSPACE_NAME
        SUBITEMS_ITEMS_ID
)

,workspace AS 
(
    SELECT 
        WORKSPACE_ID
        ,WORKSPACE_NAME
        ,BOARD_ID
    FROM {{ ref('ODS__MONDAY__WORKSPACE') }}
)

,source_data AS
(
    SELECT
        WORKSPACE_ID
        ,WORKSPACE_NAME
        ,ACCOUNT_ID
        ,BOARDS_ID
        ,BOARDS_NAME
        ,ITEMS_ID
        ,ITEMS_NAME
        ,ITEMS_GROUP_TITLE
        ,PROJECT_STATUS_R
        ,CLASS_R
        ,BUSINESS_GROUP_R
        ,TASKS_STATUS_R
        ,STRATEGIC_INITIATIVE_R
        ,PROJECT_MANAGER_R
        ,SPONSOR_R
        ,TEAM_MEMBERS_R
        ,GOAL_STATEMENT_R
        ,PROBLEM_STATEMENT_R
        ,SCOPE_R
        ,BUSINESS_CASE_R
        ,LEVEL_OF_CONFIDENTIALITY_R
        ,STARTDATE_ENDDATE_R
        ,PROJECT_COMPLETION_R
        ,GROUP_R
        ,PRIORITY_R
        ,PROJECT_FLAG_R
        ,CREATION_LOG_R
        ,SPONSOR_BUSINESS_GROUP_O
        ,RESOURCE_HOURS_O
        ,COST_TO_IMPLEMENT_O
        ,FINANCIAL_IMPACT_O
        ,INTANGIBLE_IMPACT_O
        ,FOUR_CORNERS_O
        ,PHASE_O
        ,RELATED_DOCS_O
        ,CASE WHEN STARTDATE_ENDDATE_R is NULL THEN SUBITEMS_STARTDATE_MIN ELSE SUBSTR(STARTDATE_ENDDATE_R, 0, 10) END AS ITEMS_STARTDATE
        ,CASE WHEN STARTDATE_ENDDATE_R is NULL THEN SUBITEMS_ENDDATE_MAX ELSE SUBSTR(STARTDATE_ENDDATE_R, -10, 10) END AS ITEMS_ENDDATE
        ,CASE 
            WHEN 
                NULLIF(TO_VARCHAR(ITEMS_STARTDATE),'') IS NOT NULL
                AND ITEMS_STARTDATE = ITEMS_ENDDATE
                AND NULLIF(TO_VARCHAR(SUBITEMS_ITEMS_DURATION),'') IS NULL 
            THEN  1

            WHEN 
                NULLIF(TO_VARCHAR(ITEMS_STARTDATE),'') IS NOT NULL
                AND ITEMS_STARTDATE != ITEMS_ENDDATE
                AND NULLIF(TO_VARCHAR(SUBITEMS_ITEMS_DURATION),'') IS NULL 
            THEN  DATEDIFF(day, ITEMS_STARTDATE, ITEMS_ENDDATE)
            ELSE SUBITEMS_ITEMS_DURATION END AS ITEMS_DURATION
        -- ,CASE
        --     WHEN PROJECT_MANAGER_R is NOT NULL THEN 'Project'
        --     WHEN GT_TASK_OWNER_R is NOT NULL THEN 'General Task'
        --     ELSE NULL
        --     END AS PROJECT_FLAG
        -- ,SUBITEMS_STARTDATE_MIN
        -- ,SUBITEMS_ENDDATE_MAX
        -- ,GT_TASK_OWNER_R
        -- ,GT_TIMELINE_R
        -- ,GT_TASK_DURATION_R
        -- ,GT_PRIORITY_R
        -- ,GT_TASK_COMPLETION_R
        -- ,GT_TASK_DESCRIPTION_R
        -- ,GT_TASK_STARTDATE
        -- ,GT_TASK_ENDDATE
        ,ITEMS_UPDATED_AT
        ,_FILEDATE
    FROM items
    LEFT OUTER JOIN subitems_items on items.ITEMS_ID = subitems_items.SUBITEMS_ITEMS_ID
    LEFT OUTER JOIN workspace on items.BOARDS_ID = workspace.BOARD_ID
)


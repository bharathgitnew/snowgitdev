WITH SOURCE_DATA as (
SELECT
    CALENDAR_YEAR_MONTH,
    ACCOUNT_NUMBER,
    BUSINESS_TRANSACTION_TYPE,
    DOCUMENT_TYPE,
    PNL_CATEGORY,
    SALES_DOCUMENT,
    LEAD_SO,
    LEAD_SO_TYPE,
    SALES_DOCUMENT_TYPE,
    SALES_DOCUMENT_TYPE_DESCRIPTION,
    CASE WHEN PNL_CATEGORY='Revenue' AND SALES_DOCUMENT_TYPE='ZXE0' THEN SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) ELSE 0 END AS ZXE0_REVENUE,
    CASE WHEN PNL_CATEGORY='Revenue' AND SALES_DOCUMENT_TYPE='ZXE1' THEN SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) ELSE 0 END AS ZXE1_REVENUE,
    CASE WHEN PNL_CATEGORY='COGS' AND SALES_DOCUMENT_TYPE='ZP12' THEN SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) ELSE 0 END AS ZP12_COGS
FROM {{ ref('COMMON__SAPH_GMX__DAILY_ACTUALS_SALES_LINE') }}
WHERE SALES_DOCUMENT_TYPE IN ('ZP12','ZXE0','ZXE1')
GROUP BY ALL 
)
,DISTINCT_SO_LIST AS (
SELECT 
    CALENDAR_YEAR_MONTH,
    LISTAGG(DISTINCT SALES_DOCUMENT, ', ') OVER (PARTITION BY CALENDAR_YEAR_MONTH,LEAD_SO) AS SO_LIST,
    LEAD_SO,
    LEAD_SO_TYPE,
    ZXE0_REVENUE,
    ZXE1_REVENUE,
    ZP12_COGS
FROM SOURCE_DATA
GROUP BY 
    CALENDAR_YEAR_MONTH,
    SALES_DOCUMENT,
    LEAD_SO,
    LEAD_SO_TYPE,
    ZXE0_REVENUE,
    ZXE1_REVENUE,
    ZP12_COGS
)
,FINAL AS (
SELECT 
    CALENDAR_YEAR_MONTH,
    SO_LIST,
    LEAD_SO,
    LEAD_SO_TYPE,
    SUM(ZXE0_REVENUE) AS ZXE0_REVENUE,
    SUM(ZXE1_REVENUE) AS ZXE1_REVENUE,
    SUM(ZP12_COGS) AS ZP12_COGS,
    SUM(ZXE0_REVENUE+ZXE1_REVENUE+ZP12_COGS) AS GM,
    CASE WHEN GM=0 THEN 'Pass' 
        WHEN GM<>0 AND SUM(ZP12_COGS)>0 THEN 'Pass'
    ELSE 'Fail' END AS ACCRUAL_TEST
FROM DISTINCT_SO_LIST  
GROUP BY 
    CALENDAR_YEAR_MONTH,
    SO_LIST,
    LEAD_SO ,
    LEAD_SO_TYPE
)
,TRANSFORM_DATA AS (
    SELECT 
    CALENDAR_YEAR_MONTH,
    SO_LIST,
    LEAD_SO,
    LEAD_SO_TYPE,
    ZXE0_REVENUE,
    ZXE1_REVENUE,
    ZP12_COGS,
    GM,
    ACCRUAL_TEST,
    '{{ invocation_id }}' AS AUDIT_LOG_ID
    FROM FINAL
)
,TYPE_DATA AS (
    SELECT
        CAST(CALENDAR_YEAR_MONTH AS VARCHAR(16777216)) AS CALENDAR_YEAR_MONTH,
        CAST(SO_LIST AS VARCHAR(16777216)) AS SO_LIST,
        CAST(LEAD_SO AS VARCHAR(16777216)) AS LEAD_SO,
        CAST(LEAD_SO_TYPE AS VARCHAR(16777216)) AS LEAD_SO_TYPE,
        CAST(ZXE0_REVENUE AS VARCHAR(16777216)) AS ZXE0_REVENUE,
        CAST(ZXE1_REVENUE AS VARCHAR(16777216)) AS ZXE1_REVENUE,
        CAST(ZP12_COGS AS VARCHAR(16777216)) AS ZP12_COGS,
        CAST(GM AS VARCHAR(16777216)) AS GM,
        CAST(ACCRUAL_TEST AS VARCHAR(16777216)) AS ACCRUAL_TEST,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
        ,CAST(OPERATION_SHORT_TEXT  as VARCHAR(16777216)) AS OPERATION_SHORT_TEXT
        ,CAST(HOURS as NUMBER(38,2)) AS HOURS
        ,CAST(HOURS_ADJUSTED as NUMBER(38,2)) AS HOURS_ADJUSTED
        ,CAST(SALES_ORDER_NUMBER  as VARCHAR(16777216)) AS SALES_ORDER_NUMBER
        ,CAST(ITEM_NUMBER_IN_SALES_ORDER  as VARCHAR(16777216)) AS ITEM_NUMBER_IN_SALES_ORDER
        ,CAST(WO_TYPE  as VARCHAR(16777216)) AS WO_TYPE
        ,CAST(WO_MAINCATEGORY  as VARCHAR(16777216)) AS WO_MAINCATEGORY
        ,CAST(WO_SUBCATEGORY as VARCHAR(16777216)) AS WO_SUBCATEGORY
        ,CAST(WO_PRODUCT_LINE  as VARCHAR(16777216)) AS WO_PRODUCT_LINE
        ,CAST(WO_IS_CLOSED_FLAG  as VARCHAR(16777216)) AS WO_IS_CLOSED_FLAG
        ,CAST(SERIAL_NUMBER  as VARCHAR(16777216)) AS SERIAL_NUMBER
        ,CAST(CONTRACT_NUMBER  as VARCHAR(16777216)) AS CONTRACT_NUMBER
        ,CAST(CONTRACT_TITLE  as VARCHAR(16777216)) AS CONTRACT_TITLE
        ,CAST(CONTRACT_TYPE  as VARCHAR(16777216)) AS CONTRACT_TYPE
        ,CAST(SALESORDER_LINE  as VARCHAR(16777216)) AS SALESORDER_LINE
        ,CAST(SALES_DOC_TYPE  as VARCHAR(16777216)) AS SALES_DOC_TYPE
        ,CAST(SALES_DOC_TYPE_DESCRIPTION  as VARCHAR(16777216)) AS SALES_DOC_TYPE_DESCRIPTION
        ,CAST(END_USER_GROUP  as VARCHAR(16777216)) AS END_USER_GROUP
        ,CAST(FAB  as VARCHAR(16777216)) AS FAB

        HOURS_ADJUSTED,
        SALES_ORDER_NUMBER,
        ITEM_NUMBER_IN_SALES_ORDER,
        WO_TYPE,
        WO_MAINCATEGORY,
        WO_SUBCATEGORY,
        WO_PRODUCT_LINE,
        WO_IS_CLOSED_FLAG,
        SERIAL_NUMBER,
        CONTRACT_NUMBER,
        CONTRACT_TITLE,
        CONTRACT_TYPE,
        SALESORDER_LINE,
        SALES_DOC_TYPE,
        SALES_DOC_TYPE_DESCRIPTION,
        END_USER_GROUP,
        FAB,
        SO_DESCRIPTION,
        RESPONSIBLE_COST_CENTER,
        PROFIT_CENTER,
        COMPANY,
        MAIN_WORK_CENTER_FOR_MAINTENANCE_TASKS,
        ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER_AUFPL,
        ENTERED_BY,
        LAST_CHANGED_BY,
        APPLICATION,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
    from SO_LINE
)


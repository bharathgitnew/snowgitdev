WITH SO_SOURCE AS (
    SELECT
        AUFK_ORDER_NUMBER AS SERVICE_ORDER
        ,ORDER_TYPE AS SERVICE_ORDER_TYPE
        ,CASE
            WHEN ORDER_TYPE = 'Z999' THEN 'Simulation for unacquired assets'
            WHEN ORDER_TYPE = 'ZD01' THEN 'R&D-Labor'
            WHEN ORDER_TYPE = 'ZD02' THEN 'R&D-Material'
            WHEN ORDER_TYPE = 'ZD03' THEN 'R&D-General Purpose'
            WHEN ORDER_TYPE = 'ZS01' THEN 'Service'
            WHEN ORDER_TYPE = 'ZS02' THEN 'Repair'
            WHEN ORDER_TYPE = 'ZS03' THEN 'Service Paid'
            ELSE NULL
        END AS SERVICE_ORDER_TYPE_DESC
        ,DESCRIPTION AS SO_DESCRIPTION
        ,CASE
            WHEN LEFT(DESCRIPTION,2) IN ('WO', '00') THEN RIGHT(DESCRIPTION,8)
            ELSE NULL
        END AS WORK_ORDER
        ,OPERATION_ACTIVITY_NUMBER AS OPERATION_LINE
        ,OPERATION_SHORT_TEXT
        ,SALES_ORDER_NUMBER	
        ,ITEM_NUMBER_IN_SALES_ORDER
        ,SALES_ORDER_NUMBER||ITEM_NUMBER_IN_SALES_ORDER AS SALESORDER_LINE
        ,RESPONSIBLE_COST_CENTER
        ,AUFK_PROFIT_CENTER AS PROFIT_CENTER
        ,AUFK_COMPANY_CODE AS COMPANY
        ,MAIN_WORK_CENTER_FOR_MAINTENANCE_TASKS
        ,ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER_AUFPL
        ,ENTERED_BY
        ,LAST_CHANGED_BY
        ,APPLICATION
        ,AFVC_COMPLETION_CONFIRMATION_NUMBER_FOR_THE_OPERATION
    FROM {{ ref('COMMON__SAPH_GMX__SERVICE_ORDER_LINE') }}
    WHERE ORDER_TYPE = 'ZS03'
)

,BULK AS (
    SELECT
        AUFK_ORDER_NUMBER
        ,OPERATION_SHORT_TEXT AS BULK_SO_TEXT
    FROM {{ ref('COMMON__SAPH_GMX__SERVICE_ORDER_LINE') }}
    WHERE OPERATION_ACTIVITY_NUMBER = '0010'
        AND OPERATION_SHORT_TEXT LIKE 'Bulk%'
)

,MANUAL_SO AS (
    SELECT
        AUFK_ORDER_NUMBER
        ,OPERATION_SHORT_TEXT AS MANUAL_SO_TEXT
    FROM {{ ref('COMMON__SAPH_GMX__SERVICE_ORDER_LINE') }}
    WHERE OPERATION_ACTIVITY_NUMBER = '0020'
        AND (OPERATION_SHORT_TEXT iLIKE 'Onsite Work%' OR OPERATION_SHORT_TEXT iLIKE 'Work in%')
)

,CRMWO AS (
    SELECT
        LPAD(MSDYN_NAME,8,'0') AS WO
        ,WO_WOTITLE AS WO_TITLE
        ,WO_MAINCATEGORY_OPTIONS
        ,WO_TEMP_MSNAME AS WO_SERIAL_NUMBER
        ,WO_TEMP_PRODUCTLINE_TEXT AS WO_PRODUCT_LINE
        ,WO_TEMP_FAB_TEXT AS WO_FAB
        ,TEL_WO_SUBCATEGORY_SOREQUESTNAME AS WO_SUBCATEGORY
        ,MSDYN_WORKORDERTYPENAME AS WO_TYPE
        ,CASE
            WHEN MSDYN_SUBSTATUSNAME = 'Closed' THEN 'Y'
            ELSE 'N'
        END AS WO_IS_CLOSED_FLAG
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
)

,STARTUPPROJ AS (
    SELECT
        WO_MASTERPROJECTNAME
        ,WO_TEMP_MSNAME
        ,WO_TEMP_FAB_TEXT
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }}
    WHERE WO_WOTITLE  LIKE 'PRJ-Startup%'
    QUALIFY row_number() over ( partition by WO_MASTERPROJECTNAME order by WO_TEMP_MSNAME) = 1
)

,SALES_ORDER AS (
    SELECT DISTINCT
        SO_ID
        ,SALES_DOC_TYPE
        ,SALES_DOC_TYPE_DESCRIPTION
        ,CASE
            WHEN LEN(CONTRACT_NUMBER)>1 THEN CONTRACT_NUMBER
            ELSE NULL
        END AS CONTRACT_NUMBER
        ,END_USER_GROUP
        ,FAB
    FROM {{ ref('COMMON__SAPH_GMX__SALES_ORDER_LINE_MASTER') }}
)

,MAINCAT AS (
    SELECT
        OPTION
        ,LOCALIZEDLABEL AS WO_MAINCATEGORY
    FROM {{ ref('ODS__CRM_FILE__GLOBALOPTIONSETMETADATA') }}
    WHERE 
        LOCALIZEDLABELLANGUAGECODE = '1033' 
        AND OPTIONSETNAME = 'wo_maincategory_options'
        AND ISUSERLOCALIZEDLABEL = 'False'
        AND ENTITYNAME = 'msdyn_workorder'
)

,CONTRACT_MASTER AS (
    SELECT
        CONTRACT_NUMBER
        ,CONTRACT_TITLE
        ,CONTRACT_TYPE
        ,PO_NUMBER
    FROM {{ ref('COMMON__SAPH_GMX__CONTRACTS_MASTER') }}
)

,reversed_work_hours as (
    select 
        RUECK as CONFIRMATION,
        STOKZ as REVERSED_FLAG,
        sum(
            case 
                when ISMNE = 'MIN' then ISMNW/60
                else ISMNW
            end
        ) as ACTUAL_WORK_SUM  
    from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU219_AFRU') }}
    group by CONFIRMATION, REVERSED_FLAG
)

,actual_work_hours as (
    select
        a.CONFIRMATION,
        a.ACTUAL_WORK_SUM - zeroifnull(b.ACTUAL_WORK_SUM) as ACTUAL_WORK
    from (select * from reversed_work_hours where REVERSED_FLAG='false') a
    left join (select * from reversed_work_hours where REVERSED_FLAG='true') b on a.CONFIRMATION=b.CONFIRMATION
)

,SO_LINE AS(
    SELECT
        SO_SOURCE.SERVICE_ORDER_TYPE
        ,SO_SOURCE.SERVICE_ORDER_TYPE_DESC
        ,SO_SOURCE.SERVICE_ORDER
        ,CASE
            WHEN LEFT(SO_SOURCE.SO_DESCRIPTION,2) IN ('WO','00') THEN 'Work Order'
            WHEN BULK.BULK_SO_TEXT IS NOT NULL THEN 'Bulk Order'
            WHEN MANUAL_SO.AUFK_ORDER_NUMBER IS NOT NULL THEN 'Manual SO'
            WHEN LEFT(SO_SOURCE.SO_DESCRIPTION,3) = 'PRJ' AND STARTUPPROJ.WO_MASTERPROJECTNAME IS NOT NULL THEN 'Startup Project'
            ELSE NULL
        END AS SO_SOURCE
        ,SO_SOURCE.WORK_ORDER
        ,CASE
            WHEN LEFT(SO_SOURCE.SO_DESCRIPTION,2) IN ('WO','00')  THEN WO_TITLE
            WHEN BULK.BULK_SO_TEXT IS NOT NULL THEN BULK.BULK_SO_TEXT
            WHEN MANUAL_SO.MANUAL_SO_TEXT IS NOT NULL THEN MANUAL_SO.MANUAL_SO_TEXT 
            WHEN LEFT(SO_SOURCE.SO_DESCRIPTION,3) = 'PRJ' THEN SO_SOURCE.SO_DESCRIPTION
            ELSE SALES_ORDER.SALES_DOC_TYPE_DESCRIPTION
        END AS LABOR_DESCRIPTION
        ,SO_SOURCE.OPERATION_LINE
        ,SO_SOURCE.OPERATION_SHORT_TEXT
        ,zeroifnull(actual_work_hours.ACTUAL_WORK) AS HOURS
        ,zeroifnull(actual_work_hours.ACTUAL_WORK/2) AS HOURS_ADJUSTED
        ,SO_SOURCE.SALES_ORDER_NUMBER	
        ,SO_SOURCE.ITEM_NUMBER_IN_SALES_ORDER
        ,CRMWO.WO_TYPE
        ,MAINCAT.WO_MAINCATEGORY
        ,CRMWO.WO_SUBCATEGORY
        ,CRMWO.WO_PRODUCT_LINE
        ,CASE
            WHEN CRMWO.WO_SERIAL_NUMBER IS NOT NULL THEN CRMWO.WO_SERIAL_NUMBER
            WHEN STARTUPPROJ.WO_TEMP_MSNAME IS NOT NULL THEN STARTUPPROJ.WO_TEMP_MSNAME
            ELSE NULL
        END AS SERIAL_NUMBER
        ,CRMWO.WO_IS_CLOSED_FLAG
        ,SALES_ORDER.CONTRACT_NUMBER
        ,CONTRACT_MASTER.CONTRACT_TITLE
        ,CONTRACT_MASTER.CONTRACT_TYPE
        ,SO_SOURCE.SALESORDER_LINE
        ,SALES_ORDER.SALES_DOC_TYPE
        ,SALES_ORDER.SALES_DOC_TYPE_DESCRIPTION
        ,SALES_ORDER.END_USER_GROUP
        ,CASE
            WHEN LEN(SALES_ORDER.FAB) > 1 THEN SALES_ORDER.FAB
            WHEN LEN(STARTUPPROJ.WO_TEMP_FAB_TEXT) > 1 THEN STARTUPPROJ.WO_TEMP_FAB_TEXT
            ELSE NULL
        END AS FAB
        ,SO_SOURCE.SO_DESCRIPTION
        ,SO_SOURCE.RESPONSIBLE_COST_CENTER
        ,SO_SOURCE.PROFIT_CENTER
        ,SO_SOURCE.COMPANY
        ,SO_SOURCE.MAIN_WORK_CENTER_FOR_MAINTENANCE_TASKS
        ,SO_SOURCE.ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER_AUFPL
        ,SO_SOURCE.ENTERED_BY
        ,SO_SOURCE.LAST_CHANGED_BY
        ,SO_SOURCE.APPLICATION
    FROM SO_SOURCE
    LEFT OUTER JOIN BULK
        ON SO_SOURCE.SERVICE_ORDER = BULK.AUFK_ORDER_NUMBER
    LEFT OUTER JOIN MANUAL_SO
        ON SO_SOURCE.SERVICE_ORDER = MANUAL_SO.AUFK_ORDER_NUMBER
    LEFT OUTER JOIN CRMWO
        ON SO_SOURCE.WORK_ORDER = CRMWO.WO
    LEFT OUTER JOIN MAINCAT
        ON CRMWO.WO_MAINCATEGORY_OPTIONS = MAINCAT.OPTION
    LEFT OUTER JOIN SALES_ORDER
        ON SO_SOURCE.SALESORDER_LINE = SALES_ORDER.SO_ID
    LEFT OUTER JOIN CONTRACT_MASTER
        ON CONTRACT_MASTER.CONTRACT_NUMBER = SALES_ORDER.CONTRACT_NUMBER
    LEFT OUTER JOIN STARTUPPROJ
        ON SO_SOURCE.SO_DESCRIPTION=STARTUPPROJ.WO_MASTERPROJECTNAME
    LEFT JOIN actual_work_hours 
        ON SO_SOURCE.AFVC_COMPLETION_CONFIRMATION_NUMBER_FOR_THE_OPERATION = actual_work_hours.CONFIRMATION
)

,transform_data as (
    select 
        SERVICE_ORDER_TYPE,

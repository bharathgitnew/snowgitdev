        ,CAST(RESPONSIBLE_COST_CENTER  as VARCHAR(16777216)) AS RESPONSIBLE_COST_CENTER
        ,CAST(PROFIT_CENTER  as VARCHAR(16777216)) AS PROFIT_CENTER
        ,CAST(COMPANY  as VARCHAR(16777216)) AS COMPANY
        ,CAST(MAIN_WORK_CENTER_FOR_MAINTENANCE_TASKS  as VARCHAR(16777216)) AS MAIN_WORK_CENTER_FOR_MAINTENANCE_TASKS
        ,CAST(ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER_AUFPL  as VARCHAR(16777216)) AS ROUTING_NUMBER_OF_OPERATIONS_IN_THE_ORDER_AUFPL
        ,CAST(ENTERED_BY  as VARCHAR(16777216)) AS ENTERED_BY
        ,CAST(LAST_CHANGED_BY  as VARCHAR(16777216)) AS LAST_CHANGED_BY
        ,CAST(APPLICATION  as VARCHAR(16777216)) AS APPLICATION
        ,cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID
        ,cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    from transform_data
)


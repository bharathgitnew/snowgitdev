{{ config(
        materialized='incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='CurrentStatuses'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	QVICSID AS QVICSID,
	CATEGORYID AS CATEGORYID,
	COMMENT AS COMMENT,
	COMMENT_NOTAG AS COMMENT_NOTAG,
	CREATEDBY AS CREATEDBY,
	CREATEDBYNAME AS CREATEDBYNAME,
	CREATEDAT AS CREATEDAT,
	UPDATEDBY AS UPDATEDBY,
	UPDATEDBYNAME AS UPDATEDBYNAME,
	UPDATEDAT AS UPDATEDAT,
	DELETEDAT AS DELETEDAT,
	_FILEDATE,
	_FILENAME
FROM {{ ref('ODS__QVICS_C_TMEA__CURRENTSTATUSES') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('ODS__QVICS_C_TMEA__CURRENTSTATUSES') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	QVICSID,
	CATEGORYID,
	COMMENT,
	COMMENT_NOTAG,
	CREATEDBY,
	CREATEDBYNAME,
	CREATEDAT,
	UPDATEDBY,
	UPDATEDBYNAME,
	UPDATEDAT,
	DELETEDAT
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	QVICSID,
	CATEGORYID,
	COMMENT,
	COMMENT_NOTAG,
	CREATEDBY,
	CREATEDBYNAME,
	CREATEDAT,
	UPDATEDBY,
	UPDATEDBYNAME,
	UPDATEDAT,
	DELETEDAT
 from transform_data 
)
SELECT * from type_data
{{ config(
        materialized='incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='TroubleForTotalization_ListColumns'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	LABELNAME_J AS LABELNAME_J,
	LABELNAME_E AS LABELNAME_E,
	COLUMNNAME_J AS COLUMNNAME_J,
	COLUMNNAME_E AS COLUMNNAME_E,
	ISSELECTABLE AS ISSELECTABLE,
	ISHIDDEN AS ISHIDDEN,
	WIDTH AS WIDTH,
	FIRSTSORTINDESC AS FIRSTSORTINDESC,
	PRECEDENCE AS PRECEDENCE,
	_FILEDATE,
	_FILENAME
FROM {{ ref('ODS__QVICS_C_TMEA__TROUBLEFORTOTALIZATION_LISTCOLUMNS') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('ODS__QVICS_C_TMEA__TROUBLEFORTOTALIZATION_LISTCOLUMNS') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	LABELNAME_J,
	LABELNAME_E,
	COLUMNNAME_J,
	COLUMNNAME_E,
	ISSELECTABLE,
	ISHIDDEN,
	WIDTH,
	FIRSTSORTINDESC,
	PRECEDENCE
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	LABELNAME_J,
	LABELNAME_E,
	COLUMNNAME_J,
	COLUMNNAME_E,
	ISSELECTABLE,
	ISHIDDEN,
	WIDTH,
	FIRSTSORTINDESC,
	PRECEDENCE
 from transform_data 
)
SELECT * from type_data
{{ config(
        materialized='incremental'
        ,incremental_strategy='insert_overwrite'
        ,alias='AssignedPeople'
        ,unique_key = ['']
		,tags=["qvics"]
        ,transient=false
    ) }}

    with source_data as
    (
    SELECT
	ID AS ID,
	QVICSID AS QVICSID,
	DEPARTMENTID AS DEPARTMENTID,
	GROUPID AS GROUPID,
	ASSIGNEDPERSON AS ASSIGNEDPERSON,
	ASSIGNEDPERSONNAME AS ASSIGNEDPERSONNAME,
	ASSIGNCATEGORY AS ASSIGNCATEGORY,
	DELETEDAT AS DELETEDAT,
	_FILEDATE,
	_FILENAME
FROM {{ ref('ODS__QVICS_C_TMEA__ASSIGNEDPEOPLE') }}
        WHERE _Filedate = (SELECT MAX(_FileDate) FROM {{ ref('ODS__QVICS_C_TMEA__ASSIGNEDPEOPLE') }})
    )
    ,transform_data as
    (
    SELECT
	_FILEDATE,
	_FILENAME,
	'{{ invocation_id }}' AS _AUDIT_LOG_ID,
	 SHA2('hash_me') AS _ROW_HASH,
	ID,
	QVICSID,
	DEPARTMENTID,
	GROUPID,
	ASSIGNEDPERSON,
	ASSIGNEDPERSONNAME,
	ASSIGNCATEGORY,
	DELETEDAT
FROM source_data
)
,type_data as (
    SELECT 
	CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
	CAST(_FILENAME AS VARCHAR(128)) AS _FILENAME,
	CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
	CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
	ID,
	QVICSID,
	DEPARTMENTID,
	GROUPID,
	ASSIGNEDPERSON,
	ASSIGNEDPERSONNAME,
	ASSIGNCATEGORY,
	DELETEDAT
 from transform_data 
)
SELECT * from type_data
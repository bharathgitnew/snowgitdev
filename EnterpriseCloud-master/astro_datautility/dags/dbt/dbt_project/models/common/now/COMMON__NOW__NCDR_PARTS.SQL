{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='NCDR_Parts',
    unique_key = ['NCDR_PART_ID']
) }}


with source_data as 
(
    SELECT
        NCDR_PART_ID AS NCDR_PART_ID,
        NCDR_NUMBER AS NCDR_NUMBER,
        PART_NUMBER AS PART_NUMBER,
        DESCRIPTION AS DESCRIPTION,
        CONSUME_FLAG AS CONSUME_FLAG,
        INTEL_FLAG AS INTEL_FLAG,
        SIGNAL_CODE AS SIGNAL_CODE,
        PRICE_CURRENCY AS PRICE_CURRENCY,
        SALE_PRICE AS SALE_PRICE,
        STANDARD_COST AS STANDARD_COST,
        TRANSFER_PRICE AS TRANSFER_PRICE,
        UNIT_OF_MEASURE AS UNIT_OF_MEASURE,
        REMARKS AS REMARKS,
        QUANTITY AS QUANTITY,
        DOCUMENT AS DOCUMENT,
        SHIP_FROM AS SHIP_FROM,
        RETURNED_DATE AS RETURNED_DATE,
        DELIVERY_DATE AS DELIVERY_DATE,
        UPDATED_DELIVERY_DATE AS UPDATED_DELIVERY_DATE,
        DELIVERY_REMARKS AS DELIVERY_REMARKS,
        APPROVED AS APPROVED,
        AICS_WARNING AS AICS_WARNING,
        RETURN_TO_STOCK AS RETURN_TO_STOCK,
        RETURN_REASON AS RETURN_REASON,
        LINE_NUMBER AS LINE_NUMBER,
        LAST_UPDATED_DATE AS LAST_UPDATED_DATE,
        READY_BY_FACTORY AS READY_BY_FACTORY,
        EOL_FLG AS EOL_FLG,
        LEAD_TIME AS LEAD_TIME,
        NCDR_LINE_ID AS NCDR_LINE_ID,
        URL_REFERENCE AS URL_REFERENCE,
        SHIP_COMPLETE AS SHIP_COMPLETE,
        SO_NUMBER AS SO_NUMBER,
        SO_LINE_ITEM AS SO_LINE_ITEM,
        _FILEDATE,
        _FILENAME
    FROM {{ ref('ODS__NOW__NCDR_PARTS') }} 
    {% if is_incremental() %}WHERE  _FILEDATE > IFNULL((SELECT MAX(_FILEDATE) FROM {{ this }}),'1970-01-01'){% endif %}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY NCDR_PART_ID  ORDER BY _FILENAME DESC,_FILEDATE DESC )) = 1
)

,transform_data as (
    SELECT
        NCDR_PART_ID,
        NCDR_NUMBER,
        PART_NUMBER,
        DESCRIPTION,
        CONSUME_FLAG,
        INTEL_FLAG,
        SIGNAL_CODE,
        PRICE_CURRENCY,
        SALE_PRICE,
        STANDARD_COST,
        TRANSFER_PRICE,
        UNIT_OF_MEASURE,
        REMARKS,
        QUANTITY,
        DOCUMENT,
        SHIP_FROM,
        RETURNED_DATE,
        DELIVERY_DATE,
        UPDATED_DELIVERY_DATE,
        DELIVERY_REMARKS,
        APPROVED,
        AICS_WARNING,
        RETURN_TO_STOCK,
        RETURN_REASON,
        LINE_NUMBER,
        LAST_UPDATED_DATE,
        READY_BY_FACTORY,
        EOL_FLG,
        LEAD_TIME,
        NCDR_LINE_ID,
        URL_REFERENCE,
        SHIP_COMPLETE,
        SO_NUMBER,
        SO_LINE_ITEM,
        _FILEDATE,
        _FILENAME,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    from source_data
)

,type_data as (
    SELECT 
        CAST (NCDR_PART_ID AS VARCHAR(16777216)) AS NCDR_PART_ID,
        CAST (NCDR_NUMBER AS VARCHAR(16777216)) AS NCDR_NUMBER,
        CAST (PART_NUMBER AS VARCHAR(16777216)) AS PART_NUMBER,
        CAST (DESCRIPTION AS VARCHAR(16777216)) AS DESCRIPTION,
        CAST (CONSUME_FLAG AS VARCHAR(16777216)) AS CONSUME_FLAG,
        CAST (INTEL_FLAG AS VARCHAR(16777216)) AS INTEL_FLAG,
        CAST (SIGNAL_CODE AS VARCHAR(16777216)) AS SIGNAL_CODE,
        CAST (PRICE_CURRENCY AS VARCHAR(16777216)) AS PRICE_CURRENCY,
        CAST (SALE_PRICE AS VARCHAR(16777216)) AS SALE_PRICE,
        CAST (STANDARD_COST AS VARCHAR(16777216)) AS STANDARD_COST,
        CAST (TRANSFER_PRICE AS VARCHAR(16777216)) AS TRANSFER_PRICE,
        CAST (UNIT_OF_MEASURE AS VARCHAR(16777216)) AS UNIT_OF_MEASURE,
        CAST (REMARKS AS VARCHAR(16777216)) AS REMARKS,
        CAST (QUANTITY AS VARCHAR(16777216)) AS QUANTITY,
        CAST (DOCUMENT AS VARCHAR(16777216)) AS DOCUMENT,
        CAST (SHIP_FROM AS VARCHAR(16777216)) AS SHIP_FROM,
        CAST (RETURNED_DATE AS VARCHAR(16777216)) AS RETURNED_DATE,
        CAST (DELIVERY_DATE AS VARCHAR(16777216)) AS DELIVERY_DATE,
        CAST (UPDATED_DELIVERY_DATE AS VARCHAR(16777216)) AS UPDATED_DELIVERY_DATE,
        CAST (DELIVERY_REMARKS AS VARCHAR(16777216)) AS DELIVERY_REMARKS,
        CAST (APPROVED AS VARCHAR(16777216)) AS APPROVED,
        CAST (AICS_WARNING AS VARCHAR(16777216)) AS AICS_WARNING,
        CAST (RETURN_TO_STOCK AS VARCHAR(16777216)) AS RETURN_TO_STOCK,
        CAST (RETURN_REASON AS VARCHAR(16777216)) AS RETURN_REASON,
        CAST (LINE_NUMBER AS VARCHAR(16777216)) AS LINE_NUMBER,
        CAST (LAST_UPDATED_DATE AS VARCHAR(16777216)) AS LAST_UPDATED_DATE,
        CAST (READY_BY_FACTORY AS VARCHAR(16777216)) AS READY_BY_FACTORY,
        CAST (EOL_FLG AS VARCHAR(16777216)) AS EOL_FLG,
        CAST (LEAD_TIME AS VARCHAR(16777216)) AS LEAD_TIME,
        CAST (NCDR_LINE_ID AS VARCHAR(16777216)) AS NCDR_LINE_ID,
        CAST (URL_REFERENCE AS VARCHAR(16777216)) AS URL_REFERENCE,
        CAST (SHIP_COMPLETE AS VARCHAR(16777216)) AS SHIP_COMPLETE,
        CAST (SO_NUMBER AS VARCHAR(16777216)) AS SO_NUMBER,
        CAST (SO_LINE_ITEM AS VARCHAR(16777216)) AS SO_LINE_ITEM,
        CAST(_FILEDATE as TIMESTAMP_NTZ(9)) as _FILEDATE,
		CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
		CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
	FROM transform_data
)

SELECT * FROM type_data
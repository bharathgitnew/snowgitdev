-- This model is only used in a PUB view. More accurate reporting can be done out of NCDR_SAPH or NOWDATA.

-- Intended Grain: NCDR # (NCDR15) and Part # (PART_NUMBER)
-- Usage
-- Base table for NCDRs. Any approved TEA NCDR in NOW
-- should show up in this table.

with NOW_DEDUP as (
    select
        *,
        count(*) OVER (partition by NCDR15, PART_NUMBER) as TTL_NCDR_QTY,
    from {{ ref('ODS__NOW__NOWDATA') }}
    where NCDR15 is not null and PART_NUMBER is not null
    qualify row_number() over (partition by NCDR15, PART_NUMBER order by LINE_NUMBER desc) = 1
),

-- Pull in SAP Sales Order data rolled up to the NCDR # / Part # level 
SAP_NCDR_PART_SO_AGG AS (
    SELECT 
        VBAP.ZZNNZZ, 
        VBAP.MATNR,
        MIN(TRY_TO_DATE(VBAK.ERDAT, 'YYYYMMDD')) AS FIRST_SAP_SO_CREATE_DATE,
        MAX(TRY_TO_DATE(VBAK.ERDAT, 'YYYYMMDD')) AS LATEST_SAP_SO_CREATE_DATE,
        COUNT(*) AS SO_LINE_CNT,
        LISTAGG(VBAP.VBELN || '-' || VBAP.POSNR, '|') AS SAP_SO_LINE_IDS,
        LISTAGG(VBAK.AUART, '|') AS SAP_SALES_DOC_TYPES,
        SUM(CASE WHEN VBAK.AUART IN ('ZS14', 'ZF11', 'ZP12') THEN CAST(VBAP.KWMENG AS INT) ELSE 0 END) AS SAP_ORDR_QTY,
        SUM(CASE WHEN VBAK.AUART IN ('ZSR0', 'ZPR2', 'ZPR1') THEN CAST(VBAP.KWMENG AS INT) ELSE 0 END) AS SAP_RTRN_QTY,
        SUM(CASE WHEN VBAK.AUART IN ('ZS14') THEN CAST(VBAP.KWMENG AS INT) ELSE 0 END) AS SAP_LOAN_INIT_QTY,
        SUM(CASE WHEN VBAK.AUART IN ('ZS12') THEN CAST(VBAP.KWMENG AS INT) ELSE 0 END) AS SAP_LOAN_CONSUMED_QTY,
        -- Pick up one CRM WO # available if SAP (if any)
        MAX(CASE WHEN NULLIF(VBAK.ZZSCWN, '') IS NOT NULL THEN VBAK.ZZSCWN ELSE NULL END) AS SERVICE_CRM_WO_NUMBER
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP
    INNER JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} AS VBAK ON (
        VBAK.VBELN = VBAP.VBELN
    )
    WHERE NULLIF(VBAP.ZZNNZZ, '') IS NOT NULL
    GROUP BY VBAP.ZZNNZZ, VBAP.MATNR
),
-- #################
-- # Carma Support #
-- #################
-- Carma data only contains the NCDR # and Material ID to key from
-- This means SOs where the material ID is duplicated along multiple
-- lines will not map to a single record.
--
-- To deal with this situation, if an NCDR # / Material ID pair has
-- consummption in CARMA, we distribute the consumption evenly across
-- all matched SO lines.
CARMA_AGG AS (
    SELECT 
        C.NCDR, 
        C.PART_NUMBER, 
        SUM(C.QTY_ORDERED) AS CARMA_ORDERED_QTY,
        SUM(C.QTY_CONSUMED) AS CARMA_CONSUMED_QTY,
        MIN(C.CREATED_DT) AS FIRST_CARMA_ACTIVITY_DT,
        MAX(C.LAST_UPDATED_DT) AS LATEST_CARMA_ACTIVITY_DT
    FROM {{ ref('COMMON__CARMA__CONSUMPTION') }} AS C
    GROUP BY C.NCDR, C.PART_NUMBER
),
-- Pull in CRM data
CRM_WO AS (
    SELECT
        LPAD(WO.MSDYN_NAME, 8, '0') AS SERVICE_CRM_WO_NUMBER,
        WOP.MSDYN_PRODUCTNAME,
        CASE 
            WHEN MIN(WO.WO_PRODUCTSNNAME) = MAX(WO.WO_PRODUCTSNNAME) THEN MAX(WO.WO_PRODUCTSNNAME) 
        END AS CRM_TOOL_SERIAL,
        MAX(WO.CREATEDON) AS CREATED_ON,
        COALESCE(CAST(MAX(WOP.MSDYN_ESTIMATEQUANTITY) AS INT), 0) AS PLANNED_QTY,
        COALESCE(CAST(MAX(WOP.MSDYN_QUANTITY) AS INT), 0) AS INSTALLED_QTY,
        COALESCE(CAST(MAX(WOP.TEL_WO_ORDEREDQTY) AS INT), 0) AS ORDERED_QTY,
        COALESCE(CAST(MAX(WOP.TEL_WO_RETURNEDQTY) AS INT), 0) AS RETURNED_QTY,
        COALESCE(CAST(MAX(WOP.TEL_WO_SHIPPEDQTY) AS INT), 0) AS SHIPPED_QTY,
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }} AS WO
    INNER JOIN {{ ref('ODS__CRM_FILE__MSDYN_WORKORDERPRODUCT') }} AS WOP ON (
        WOP.MSDYN_WORKORDER = WO.MSDYN_WORKORDERID and WOP.STATECODE = '0' and WOP.STATUSCODE = '1'
    )
    WHERE NULLIF(WO.MSDYN_NAME, '') IS NOT NULL 
    GROUP BY LPAD(WO.MSDYN_NAME, 8, '0'), WOP.MSDYN_PRODUCTNAME
),
SOURCE_DATA AS (
    SELECT 
        ND.NCDR15 as NCDR_NUMBER,
        ND.PART_NUMBER,
        CASE WHEN CARMA.NCDR IS NOT NULL THEN 1 ELSE 0 END AS IN_CARMA,
        CASE WHEN ND.NCDR15 IS NOT NULL THEN 1 ELSE 0 END AS IN_NOW,
        CASE WHEN SO_AGG.ZZNNZZ IS NOT NULL THEN 1 ELSE 0 END AS IN_SAP,
        CASE 
            WHEN CRM_WO.SERVICE_CRM_WO_NUMBER IS NOT NULL 
            THEN 1 ELSE 0 
        END AS IN_CRM,
        ND.TTL_NCDR_QTY AS QTY_NOW,
        ND.WORK_FLOW_STARTED_DATE,
        ND.CUSTOMER_COMMIT_DATE,
        ND.GLOBAL_APPROVER,
        ND.GLOBALLY_APPROVED_DATE,
        ND.REGION,
        ND.REGIONAL_APPROVER,
        ND.REGIONALLY_APPROVED_DATE,
        ND.DENY_DATE,
        ND.REASON,
        -- NCDR People
        ND.ORIGINATOR,
        ND.REQUESTOR,
        ND.REQUESTOR_EMP_NO,
        EMP.EMAILADDRESS,
        EMP.SUPERVISOR_NAME,
        EMP.SUPERVISOR_EMPLOYEE_ID,
        -- Machine Data
        ND.MACHINE_WARR_STATUS,
        ND.MACHINE_STATUS_CODE,
        -- CARMA Data
        CARMA.CARMA_CONSUMED_QTY,
        CARMA.CARMA_ORDERED_QTY,
        CARMA.FIRST_CARMA_ACTIVITY_DT,
        CARMA.LATEST_CARMA_ACTIVITY_DT,
        -- CRM Data
        ND.CRM_WORK_ORDER_NO as NOW_WORK_ORDER_NO,
        CRM_WO.SERVICE_CRM_WO_NUMBER as CRM_WORK_ORDER_NO,
        CRM_WO.MSDYN_PRODUCTNAME as MSDYN_PRODUCTNAME,
        CRM_WO.PLANNED_QTY AS CRM_PLANNED_QTY,
        CRM_WO.INSTALLED_QTY AS CRM_INSTALLED_QTY,
        CRM_WO.ORDERED_QTY AS CRM_ORDERED_QTY,
        CRM_WO.RETURNED_QTY AS CRM_RETURNED_QTY,
        CRM_WO.SHIPPED_QTY AS CRM_SHIPPED_QTY,
        CRM_WO.CREATED_ON AS CRM_WO_CREATEDON,
        CRM_WO.CRM_TOOL_SERIAL AS CRM_TOOL_SERIAL,
        -- SAP Data
        SO_AGG.SAP_ORDR_QTY,
        SO_AGG.SAP_RTRN_QTY,
        SO_AGG.SAP_LOAN_CONSUMED_QTY,
        SO_AGG.SO_LINE_CNT, 
        SO_AGG.SAP_SO_LINE_IDS,
        SO_AGG.SAP_SALES_DOC_TYPES,
        SO_AGG.FIRST_SAP_SO_CREATE_DATE,
        SO_AGG.LATEST_SAP_SO_CREATE_DATE,
        -- Synthetic
        LEAST(
            COALESCE(FIRST_SAP_SO_CREATE_DATE, CAST('2100-01-01' AS DATE)), 
            COALESCE(WORK_FLOW_STARTED_DATE, CAST('2100-01-01' AS DATE)),
            COALESCE(FIRST_CARMA_ACTIVITY_DT, CAST('2100-01-01' AS DATE))
        ) AS STARTED_DT,
        GREATEST(
            COALESCE(LATEST_CARMA_ACTIVITY_DT, CAST('1900-01-01' AS DATE)), 
            COALESCE(LATEST_SAP_SO_CREATE_DATE, CAST('1900-01-01' AS DATE)),
            COALESCE(WORK_FLOW_STARTED_DATE, CAST('1900-01-01' AS DATE)),
            COALESCE(GLOBALLY_APPROVED_DATE, CAST('1900-01-01' AS DATE)),
            COALESCE(REGIONALLY_APPROVED_DATE, CAST('1900-01-01' AS DATE))
        ) AS LATEST_ACTIVITY_DT,
        ND.MACHINE_SYSTEM_TYPE as MACHINE_SYSTEM_TYPE,
        ND.APPROVED as APPROVED,
    FROM NOW_DEDUP AS ND
    LEFT JOIN SAP_NCDR_PART_SO_AGG AS SO_AGG ON (
        SO_AGG.ZZNNZZ = ND.NCDR15 AND
        SO_AGG.MATNR = ND.PART_NUMBER
    )
    LEFT JOIN CARMA_AGG AS CARMA ON (
        CARMA.NCDR = ND.NCDR15 AND
        CARMA.PART_NUMBER = ND.PART_NUMBER
    )
    -- CRM data must JOIN to NOW
    LEFT JOIN CRM_WO ON (
        ND.PART_NUMBER = CRM_WO.MSDYN_PRODUCTNAME AND
        coalesce(SO_AGG.SERVICE_CRM_WO_NUMBER, ND.CRM_WORK_ORDER_NO) = CRM_WO.SERVICE_CRM_WO_NUMBER
    )
    LEFT JOIN {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }} AS EMP ON (
        EMP.EMPLOYEE_ID = ND.REQUESTOR_EMP_NO
    )
),

TRANSFORM_DATA AS (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH,
        NCDR_NUMBER,
        PART_NUMBER,
        NCDR_NUMBER || '_' || PART_NUMBER AS NCDR_PART_PAIR_KEY,
        IN_CARMA,
        IN_NOW,
        IN_SAP,
        IN_CRM,
        QTY_NOW,
        WORK_FLOW_STARTED_DATE,
        CUSTOMER_COMMIT_DATE,
        GLOBAL_APPROVER,
        GLOBALLY_APPROVED_DATE,
        REGION,
        REGIONAL_APPROVER,
        REGIONALLY_APPROVED_DATE,
        DENY_DATE,
        REASON AS NOW_REASON,
        -- NCDR People
        ORIGINATOR,
        REQUESTOR,
        REQUESTOR_EMP_NO,
        EMAILADDRESS AS REQUESTOR_EMAIL,
        SUPERVISOR_NAME,
        SUPERVISOR_EMPLOYEE_ID,
        -- Machine Data
        MACHINE_WARR_STATUS,
        MACHINE_STATUS_CODE,
        -- Carma Data
        FIRST_CARMA_ACTIVITY_DT,
        LATEST_CARMA_ACTIVITY_DT,
        CARMA_CONSUMED_QTY,
        CARMA_ORDERED_QTY,
        -- CRM Data
        NOW_WORK_ORDER_NO,
        CRM_WORK_ORDER_NO,
        MSDYN_PRODUCTNAME,
        CRM_PLANNED_QTY,
        CRM_INSTALLED_QTY,
        CRM_ORDERED_QTY,
        CRM_RETURNED_QTY,
        CRM_SHIPPED_QTY,
        CRM_WO_CREATEDON,
        CRM_TOOL_SERIAL,
        -- SAP Data
        SAP_ORDR_QTY,
        SAP_RTRN_QTY,
        SAP_LOAN_CONSUMED_QTY,
        SO_LINE_CNT,
        SAP_SO_LINE_IDS,
        SAP_SALES_DOC_TYPES,
        FIRST_SAP_SO_CREATE_DATE,
        LATEST_SAP_SO_CREATE_DATE,
        CASE 
            WHEN STARTED_DT = CAST('2100-01-01' AS DATE)
            THEN NULL ELSE STARTED_DT 
        END AS STARTED_DT,
        CASE
            WHEN LATEST_ACTIVITY_DT = CAST('1900-01-01' AS DATE) 
            THEN NULL ELSE LATEST_ACTIVITY_DT
        END AS LATEST_ACTIVITY_DT,
        MACHINE_SYSTEM_TYPE,
        APPROVED,
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(16777216)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH,
        CAST(NCDR_NUMBER AS VARCHAR(16777216)) AS NCDR_NUMBER,
        CAST(PART_NUMBER AS VARCHAR(16777216)) AS PART_NUMBER,
        CAST(NCDR_PART_PAIR_KEY AS VARCHAR(16777216)) AS NCDR_PART_PAIR_KEY,
        CAST(IN_CARMA AS INT) AS IN_CARMA,
        CAST(IN_NOW AS INT) AS IN_NOW,
        CAST(IN_SAP AS INT) AS IN_SAP,
        CAST(IN_CRM AS INT) AS IN_CRM,
        CAST(QTY_NOW AS INT) AS QTY_NOW,
        CAST(WORK_FLOW_STARTED_DATE AS DATE) AS WORK_FLOW_STARTED_DATE,
        CAST(CUSTOMER_COMMIT_DATE AS DATE) AS CUSTOMER_COMMIT_DATE,
        CAST(GLOBAL_APPROVER AS VARCHAR(16777216)) AS GLOBAL_APPROVER,
        CAST(GLOBALLY_APPROVED_DATE AS DATE) AS GLOBALLY_APPROVED_DATE,
        CAST(REGION AS VARCHAR(16777216)) AS REGION,
        CAST(REGIONAL_APPROVER AS VARCHAR(16777216)) AS REGIONAL_APPROVER,
        CAST(REGIONALLY_APPROVED_DATE AS DATE) AS REGIONALLY_APPROVED_DATE,
        CAST(DENY_DATE AS DATE) AS DENY_DATE,
        CAST(NOW_REASON AS VARCHAR(16777216)) AS NOW_REASON,
        -- NCDR People
        CAST(ORIGINATOR AS VARCHAR(16777216)) AS ORIGINATOR,
        CAST(REQUESTOR AS VARCHAR(16777216)) AS REQUESTOR,
        CAST(REQUESTOR_EMP_NO AS VARCHAR(16777216)) AS REQUESTOR_EMP_NO,
        CAST(REQUESTOR_EMAIL AS VARCHAR(16777216)) AS REQUESTOR_EMAIL,
        CAST(SUPERVISOR_NAME AS VARCHAR(16777216)) AS SUPERVISOR_NAME,
        CAST(SUPERVISOR_EMPLOYEE_ID AS VARCHAR(16777216)) AS SUPERVISOR_EMPLOYEE_ID,
        -- Machine data
        CAST(MACHINE_WARR_STATUS AS VARCHAR(16777216)) AS MACHINE_WARR_STATUS,
        CAST(MACHINE_STATUS_CODE AS VARCHAR(16777216)) AS MACHINE_STATUS_CODE,
        -- CARMA Data
        CAST(FIRST_CARMA_ACTIVITY_DT AS DATE) AS FIRST_CARMA_ACTIVITY_DT,
        CAST(LATEST_CARMA_ACTIVITY_DT AS DATE) AS LATEST_CARMA_ACTIVITY_DT,
        CAST(CARMA_CONSUMED_QTY AS INT) AS CARMA_CONSUMED_QTY,
        CAST(CARMA_ORDERED_QTY AS INT) AS CARMA_ORDERED_QTY,
        -- CRM Information
        CAST(NOW_WORK_ORDER_NO AS VARCHAR(16777216)) AS NOW_WORK_ORDER_NO,
        CAST(CRM_WORK_ORDER_NO AS VARCHAR(16777216)) AS CRM_WORK_ORDER_NO,
        CAST(MSDYN_PRODUCTNAME AS VARCHAR(16777216)) AS MSDYN_PRODUCTNAME,
        CAST(CRM_PLANNED_QTY AS INT) AS CRM_PLANNED_QTY,
        CAST(CRM_INSTALLED_QTY AS INT) AS CRM_INSTALLED_QTY,
        CAST(CRM_ORDERED_QTY AS INT) AS CRM_ORDERED_QTY,
        CAST(CRM_RETURNED_QTY as NUMBER(38,0)) as CRM_RETURNED_QTY,
        CAST(CRM_SHIPPED_QTY as NUMBER(38,0)) as CRM_SHIPPED_QTY,
        CAST(CRM_WO_CREATEDON AS DATE) AS CRM_WO_CREATEDON,
        CAST(CRM_TOOL_SERIAL AS VARCHAR(16777216)) AS CRM_TOOL_SERIAL,
        -- SAP Data
        CAST(SAP_ORDR_QTY AS INT) AS SAP_ORDR_QTY,
        CAST(SAP_RTRN_QTY AS INT) AS SAP_RTRN_QTY,
        CAST(SAP_LOAN_CONSUMED_QTY AS INT) AS SAP_LOAN_CONSUMED_QTY,
        CAST(SO_LINE_CNT AS INT) AS SO_LINE_CNT,
        CAST(SAP_SO_LINE_IDS AS VARCHAR(16777216)) AS SAP_SO_LINE_IDS,
        CAST(SAP_SALES_DOC_TYPES AS VARCHAR(16777216)) AS SAP_SALES_DOC_TYPES,
        CAST(FIRST_SAP_SO_CREATE_DATE AS DATE) AS FIRST_SAP_SO_CREATE_DATE,
        CAST(LATEST_SAP_SO_CREATE_DATE AS DATE) AS LATEST_SAP_SO_CREATE_DATE,
        -- Synthatic
        CAST(STARTED_DT AS DATE) AS STARTED_DT,
        CAST(LATEST_ACTIVITY_DT AS DATE) AS LATEST_ACTIVITY_DT,
        MACHINE_SYSTEM_TYPE,
        APPROVED,
    FROM TRANSFORM_DATA
)

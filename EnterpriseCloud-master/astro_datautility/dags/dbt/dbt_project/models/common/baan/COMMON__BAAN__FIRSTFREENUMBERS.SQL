{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='FIRSTFREENUMBERS',
    unique_key = ['NUMBERGROUP',
    'SERIES']
) }}

with source_data as
(

    SELECT
        BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS.FIRSTFREENUMBER AS FIRSTFREENUMBER,
        BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS.FIRSTFREENUMBERCACHESIZE AS FIRSTFREENUMBERCACHESIZE,
        BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS.NUMBERGROUP AS NUMBERGROUP,
        BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS.SERIES AS SERIES,
        BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS.SERIESBLOCKEDFORINPUTDESCRIPTION AS SERIESBLOCKEDFORINPUTDESCRIPTION,
        BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS.SERIESBLOCKEDFORINPUTID AS SERIESBLOCKEDFORINPUTID,
        BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS.SERIESDESCRIPTION AS SERIESDESCRIPTION
    FROM {{ ref('ODS__BAAN__BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS') }} BAANCOMMONSYSTEMTABLES_FIRSTFREENUMBERS

),

transform_data as
(
    select
        FIRSTFREENUMBER,
        FIRSTFREENUMBERCACHESIZE,
        NUMBERGROUP,
        SERIES,
        SERIESBLOCKEDFORINPUTDESCRIPTION,
        SERIESBLOCKEDFORINPUTID,
        SERIESDESCRIPTION,
        '{{ invocation_id }}' AS AUDIT_LOG_ID
        ,SHA2('hash_me') as _ROW_HASH -- Adds column to table on full refresh.
    FROM source_data
)

,type_data as
(
    select
        cast(FIRSTFREENUMBER as NUMBER(38,0)) as FIRSTFREENUMBER,
        cast(FIRSTFREENUMBERCACHESIZE as NUMBER(38,0)) as FIRSTFREENUMBERCACHESIZE,
        cast(NUMBERGROUP as VARCHAR(16777216)) as NUMBERGROUP,
        cast(SERIES as VARCHAR(16777216)) as SERIES,
        cast(SERIESBLOCKEDFORINPUTDESCRIPTION as VARCHAR(16777216)) as SERIESBLOCKEDFORINPUTDESCRIPTION,
        cast(SERIESBLOCKEDFORINPUTID as NUMBER(38,0)) as SERIESBLOCKEDFORINPUTID,
        cast(SERIESDESCRIPTION as VARCHAR(16777216)) as SERIESDESCRIPTION,
        cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
        cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
    )
select * from type_data
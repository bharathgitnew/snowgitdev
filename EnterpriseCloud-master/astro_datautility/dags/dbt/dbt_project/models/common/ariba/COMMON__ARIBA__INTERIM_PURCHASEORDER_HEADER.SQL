        PurchaseOrderHeader.OriginatingSystemReferenceId AS ORIGINATINGSYSTEMREFERENCEID,
        PurchaseOrderHeader.PaymentTermsCode AS PAYMENTTERMSCODE,
        CASE PurchaseOrderHeader.PreOrdered WHEN 1 THEN 'Yes' ELSE 'No' END AS PREORDERED,
        PurchaseOrderHeader.PreparerCode AS PREPARERCODE,
        PurchaseOrderHeader.PreviousApprovalRequestsVersion AS PREVIOUSAPPROVALREQUESTSVERSION,

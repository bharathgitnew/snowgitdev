        PurchaseOrderHeader.UniqueName AS UNIQUENAME,
        CASE PurchaseOrderHeader.UsePOLineNumberForIntegration WHEN 1 THEN 'Yes' ELSE 'No' END AS USEPOLINENUMBERFORINTEGRATION,
        PurchaseOrderHeader.Version AS VERSION,
        CASE PurchaseOrderHeader.CustomField_BPO WHEN 1 THEN 'Yes' ELSE 'No' END AS CUSTOMFIELD_BPO,
        PurchaseOrderHeader.CustomField_BuyerDetails AS CUSTOMFIELD_BUYERDETAILS,
        PurchaseOrderHeader.CustomField_BuyerName AS CUSTOMFIELD_BUYERNAME,
        PurchaseOrderHeader.CustomField_CompanyName AS CUSTOMFIELD_COMPANYNAME,

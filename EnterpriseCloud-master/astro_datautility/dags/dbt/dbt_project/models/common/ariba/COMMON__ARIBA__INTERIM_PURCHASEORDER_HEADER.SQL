        CASE PurchaseOrderHeader.CustomField_IsBaanSpecific WHEN 1 THEN 'Yes' ELSE 'No' END AS CUSTOMFIELD_ISBAANSPECIFIC,
        PurchaseOrderHeader.CustomField_StartDate AS CUSTOMFIELD_STARTDATE,

{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='BOM_HEADER',
        unique_key = ['CLIENT',
    'BOM_CATEGORY',
    'BILL_OF_MATERIAL',
    'ALTERNATIVE_BOM',
    'INTERNAL_COUNTER'],
        transient=false
) }}

with source_data as (
    select
		_CAPTUREDATETIME,
        MANDT as CLIENT,
		STLTY as BOM_CATEGORY,
		STLNR as BILL_OF_MATERIAL,
		STLAL as ALTERNATIVE_BOM,
		STKOZ as INTERNAL_COUNTER,
		DATUV as VALID_FROM_DATE,
		TECHV as TECHNICAL_STATUS_FROM,
		AENNR as CHANGE_NUMBER,
		LKENZ as DELETION_INDICATOR,
		LOEKZ as DELETION_FLAG_FOR_BOMS,
		VGKZL as PREVIOUS_HEADER_COUNTER,
		ANDAT as DATE_RECORD_CREATED_ON,
		ANNAM as USER_WHO_CREATED_RECORD,
		AEDAT as DATE_OF_LAST_CHANGE,
		AENAM as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		BMEIN as BASE_UNIT_OF_MEASURE_FOR_BOM,
		BMENG as BASE_QUANTITY,
		CADKZ as CAD_INDICATOR,
		LABOR as LABORATORY_DESIGN_OFFICE,
		LTXSP as LONG_TEXT_LANGUAGE_FOR_CREATION_OF_A_CHANGE_DOCUMENT,
		STKTX as ALTERNATIVE_BOM_TEXT,
		STLST as BOM_STATUS,
		WRKAN as PLANT_WHERE_BOM_OR_ALTERNATIVE_VARIANT_CREATED,
		DVDAT as DATE_OF_LAST_DATE_SHIFT,
		DVNAM as NAME_OF_THE_USER_WHO_CARRIED_OUT_THE_DATE_SHIFT,
		AEHLP as DATE_SHIFT_HIERARCHY_INDICATOR,
		ALEKZ as ALE_INDICATOR,
		GUIDX as GLOBAL_IDENTIFICATION_OF_A_BOM_HEADER_CHANGE_STATUS,
		VALID_TO as VALID_TO_DATE,
		VALID_TO_RKEY as VALID_TO_RKEY_VALID_TO_DATE,
		ECN_TO as CHANGE_NUMBER_TO,
		ECN_TO_RKEY as ECN_TO_RKEY_CHANGE_NUMBER_TO,
		IS_DELETED
    from {{ ref('ODS__SAPO__BOM_HEADER') }}
),

transform_data as (
    select
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
        CLIENT,
		BOM_CATEGORY,
		BILL_OF_MATERIAL,
		ALTERNATIVE_BOM,
		INTERNAL_COUNTER,
		TRY_TO_DATE(VALID_FROM_DATE, 'YYYYMMDD') as VALID_FROM_DATE,
		TECHNICAL_STATUS_FROM,
		CHANGE_NUMBER,
		DELETION_INDICATOR,
		DELETION_FLAG_FOR_BOMS,
		PREVIOUS_HEADER_COUNTER,
		TRY_TO_DATE(DATE_RECORD_CREATED_ON, 'YYYYMMDD') as DATE_RECORD_CREATED_ON,
		USER_WHO_CREATED_RECORD,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE, 'YYYYMMDD') as DATE_OF_LAST_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		BASE_UNIT_OF_MEASURE_FOR_BOM,
		BASE_QUANTITY,
		CAD_INDICATOR,
		LABORATORY_DESIGN_OFFICE,
		LONG_TEXT_LANGUAGE_FOR_CREATION_OF_A_CHANGE_DOCUMENT,
		ALTERNATIVE_BOM_TEXT,
		BOM_STATUS,
		PLANT_WHERE_BOM_OR_ALTERNATIVE_VARIANT_CREATED,
		TRY_TO_DATE(DATE_OF_LAST_DATE_SHIFT, 'YYYYMMDD') as DATE_OF_LAST_DATE_SHIFT,
		NAME_OF_THE_USER_WHO_CARRIED_OUT_THE_DATE_SHIFT,
		DATE_SHIFT_HIERARCHY_INDICATOR,
		ALE_INDICATOR,
		GLOBAL_IDENTIFICATION_OF_A_BOM_HEADER_CHANGE_STATUS,
		TRY_TO_DATE(VALID_TO_DATE, 'YYYYMMDD') as VALID_TO_DATE,
		TRY_TO_DATE(VALID_TO_RKEY_VALID_TO_DATE, 'YYYYMMDD') as VALID_TO_RKEY_VALID_TO_DATE,
		CHANGE_NUMBER_TO,
		ECN_TO_RKEY_CHANGE_NUMBER_TO,
		IS_DELETED
    from source_data
),

type_data as (
    select
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
        CLIENT,
		BOM_CATEGORY,
		BILL_OF_MATERIAL,
		ALTERNATIVE_BOM,
		INTERNAL_COUNTER,
		cast(VALID_FROM_DATE as DATE) as VALID_FROM_DATE,
		TECHNICAL_STATUS_FROM,
		CHANGE_NUMBER,
		DELETION_INDICATOR,
		DELETION_FLAG_FOR_BOMS,
		PREVIOUS_HEADER_COUNTER,
		cast(DATE_RECORD_CREATED_ON as DATE) as DATE_RECORD_CREATED_ON,
		USER_WHO_CREATED_RECORD,
		cast(DATE_OF_LAST_CHANGE as DATE) as DATE_OF_LAST_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		BASE_UNIT_OF_MEASURE_FOR_BOM,
		cast(BASE_QUANTITY as NUMBER(38,10)) as BASE_QUANTITY,
		CAD_INDICATOR,
		LABORATORY_DESIGN_OFFICE,
		LONG_TEXT_LANGUAGE_FOR_CREATION_OF_A_CHANGE_DOCUMENT,
		ALTERNATIVE_BOM_TEXT,
		BOM_STATUS,
		PLANT_WHERE_BOM_OR_ALTERNATIVE_VARIANT_CREATED,
		cast(DATE_OF_LAST_DATE_SHIFT as DATE) as DATE_OF_LAST_DATE_SHIFT,
		NAME_OF_THE_USER_WHO_CARRIED_OUT_THE_DATE_SHIFT,
		DATE_SHIFT_HIERARCHY_INDICATOR,
		ALE_INDICATOR,
		GLOBAL_IDENTIFICATION_OF_A_BOM_HEADER_CHANGE_STATUS,
		cast(VALID_TO_DATE as DATE) as VALID_TO_DATE,
		cast(VALID_TO_RKEY_VALID_TO_DATE as DATE) as VALID_TO_RKEY_VALID_TO_DATE,
		CHANGE_NUMBER_TO,
		ECN_TO_RKEY_CHANGE_NUMBER_TO,
		IS_DELETED
    from transform_data
)
select * from type_data
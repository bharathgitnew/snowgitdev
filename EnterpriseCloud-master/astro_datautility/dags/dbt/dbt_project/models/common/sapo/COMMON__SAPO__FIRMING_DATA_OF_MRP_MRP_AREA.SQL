{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='FIRMING_DATA_OF_MRP_MRP_AREA',
        unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'MRP_AREA',
    'PLANNING_SCENARIO_OF_LONG_TERM_PLANNING'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		MATNR as MATERIAL_NUMBER,
		BERID as MRP_AREA,
		PLSCN as PLANNING_SCENARIO_OF_LONG_TERM_PLANNING,
		OPFDT as DATE_OF_FIRM_PLANNED_ORDER_LAST_COPIED_FROM_MRP,
		MFXDT as MANUAL_FIRMING_DATE,
		MFNAM as SET_MANUAL_FIRMING_DATE_USER,
		MFDAT as SET_MANUAL_FIRMING_DATE_DATE_TO_SET,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__FIRMING_DATA_OF_MRP_MRP_AREA') }}
),

transform_data as (
    select
        CLIENT,
		MATERIAL_NUMBER,
		MRP_AREA,
		PLANNING_SCENARIO_OF_LONG_TERM_PLANNING,
		TRY_TO_DATE(DATE_OF_FIRM_PLANNED_ORDER_LAST_COPIED_FROM_MRP,'YYYYMMDD')  AS DATE_OF_FIRM_PLANNED_ORDER_LAST_COPIED_FROM_MRP,
		TRY_TO_DATE(MANUAL_FIRMING_DATE,'YYYYMMDD')  AS MANUAL_FIRMING_DATE,
		SET_MANUAL_FIRMING_DATE_USER,
		TRY_TO_DATE(SET_MANUAL_FIRMING_DATE_DATE_TO_SET,'YYYYMMDD')  AS SET_MANUAL_FIRMING_DATE_DATE_TO_SET,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(MATERIAL_NUMBER as VARCHAR) as MATERIAL_NUMBER,
		cast(MRP_AREA as VARCHAR) as MRP_AREA,
		cast(PLANNING_SCENARIO_OF_LONG_TERM_PLANNING as VARCHAR) as PLANNING_SCENARIO_OF_LONG_TERM_PLANNING,
		cast(DATE_OF_FIRM_PLANNED_ORDER_LAST_COPIED_FROM_MRP as DATE) as DATE_OF_FIRM_PLANNED_ORDER_LAST_COPIED_FROM_MRP,
		cast(MANUAL_FIRMING_DATE as DATE) as MANUAL_FIRMING_DATE,
		cast(SET_MANUAL_FIRMING_DATE_USER as VARCHAR) as SET_MANUAL_FIRMING_DATE_USER,
		cast(SET_MANUAL_FIRMING_DATE_DATE_TO_SET as DATE) as SET_MANUAL_FIRMING_DATE_DATE_TO_SET,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
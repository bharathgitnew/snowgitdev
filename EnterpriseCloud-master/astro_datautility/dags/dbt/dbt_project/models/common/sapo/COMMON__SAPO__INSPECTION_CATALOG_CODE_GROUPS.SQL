{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='INSPECTION_CATALOG_CODE_GROUPS',
        unique_key = ['CLIENT',
    'CATALOG',
    'CODE_GROUP'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		KATALOGART as CATALOG,
		CODEGRUPPE as CODE_GROUP,
		ERSTELLER as NAME_OF_USER_WHO_CREATED_THE_DATA_RECORD,
		E_DATUM as DATE_ON_WHICH_THE_DATA_RECORD_WAS_CREATED,
		AENDERER as NAME_OF_USER_WHO_MOST_RECENTLY_CHANGED_THE_DATA_RECORD,
		A_DATUM as DATE_ON_WHICH_DATA_RECORD_WAS_CHANGED,
		VERWENDUNG as DATA_RECORD_IS_USED,
		INAKTIV as STATUS_OF_CODE_GROUP_OR_CODE_RECORD,
		STATUS as STATUS_OF_MASTER_RECORD,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__INSPECTION_CATALOG_CODE_GROUPS') }}
),

transform_data as (
    select
        CLIENT,
		CATALOG,
		CODE_GROUP,
		NAME_OF_USER_WHO_CREATED_THE_DATA_RECORD,
		TRY_TO_DATE(DATE_ON_WHICH_THE_DATA_RECORD_WAS_CREATED, 'YYYYMMDD') as DATE_ON_WHICH_THE_DATA_RECORD_WAS_CREATED,
		NAME_OF_USER_WHO_MOST_RECENTLY_CHANGED_THE_DATA_RECORD,
		TRY_TO_DATE(DATE_ON_WHICH_DATA_RECORD_WAS_CHANGED, 'YYYYMMDD') as DATE_ON_WHICH_DATA_RECORD_WAS_CHANGED,
		DATA_RECORD_IS_USED,
		STATUS_OF_CODE_GROUP_OR_CODE_RECORD,
		STATUS_OF_MASTER_RECORD,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR(16777216)) as CLIENT,
		cast(CATALOG as VARCHAR(16777216)) as CATALOG,
		cast(CODE_GROUP as VARCHAR(16777216)) as CODE_GROUP,
		cast(NAME_OF_USER_WHO_CREATED_THE_DATA_RECORD as VARCHAR(16777216)) as NAME_OF_USER_WHO_CREATED_THE_DATA_RECORD,
		cast(DATE_ON_WHICH_THE_DATA_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_THE_DATA_RECORD_WAS_CREATED,
		cast(NAME_OF_USER_WHO_MOST_RECENTLY_CHANGED_THE_DATA_RECORD as VARCHAR(16777216)) as NAME_OF_USER_WHO_MOST_RECENTLY_CHANGED_THE_DATA_RECORD,
		cast(DATE_ON_WHICH_DATA_RECORD_WAS_CHANGED as DATE) as DATE_ON_WHICH_DATA_RECORD_WAS_CHANGED,
		cast(DATA_RECORD_IS_USED as VARCHAR(16777216)) as DATA_RECORD_IS_USED,
		cast(STATUS_OF_CODE_GROUP_OR_CODE_RECORD as VARCHAR(16777216)) as STATUS_OF_CODE_GROUP_OR_CODE_RECORD,
		cast(STATUS_OF_MASTER_RECORD as VARCHAR(16777216)) as STATUS_OF_MASTER_RECORD,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='EXTERNAL_OBJECT_TYPES',
        unique_key = ['CLIENT',
    'OBJECT_TYPE'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		OTYPE as OBJECT_TYPE,
		PKSUB as KEY_STRUCTURE_OF_EXTERNAL_OBJECT_TYPES,
		DYNNR as SCREEN_NUMBER_OF_EXTERNAL_OBJECT_TYPES,
		PROG as INTERFACE_NAME,
		INREL as INVERSE_RELATIONSHIP,
		SOTYP as INDICATOR_FOR_STANDARD_OBJECT_TYPE,
		BIRTH as EXTERNAL_OBJECT_INCLUDED_IN_ENHANCED_REL_MAINTENANCE,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__EXTERNAL_OBJECT_TYPES') }}
),

transform_data as (
    select
        CLIENT,
		OBJECT_TYPE,
		KEY_STRUCTURE_OF_EXTERNAL_OBJECT_TYPES,
		SCREEN_NUMBER_OF_EXTERNAL_OBJECT_TYPES,
		INTERFACE_NAME,
		INVERSE_RELATIONSHIP,
		INDICATOR_FOR_STANDARD_OBJECT_TYPE,
		EXTERNAL_OBJECT_INCLUDED_IN_ENHANCED_REL_MAINTENANCE,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(OBJECT_TYPE as VARCHAR) as OBJECT_TYPE,
		cast(KEY_STRUCTURE_OF_EXTERNAL_OBJECT_TYPES as VARCHAR) as KEY_STRUCTURE_OF_EXTERNAL_OBJECT_TYPES,
		cast(SCREEN_NUMBER_OF_EXTERNAL_OBJECT_TYPES as VARCHAR) as SCREEN_NUMBER_OF_EXTERNAL_OBJECT_TYPES,
		cast(INTERFACE_NAME as VARCHAR) as INTERFACE_NAME,
		cast(INVERSE_RELATIONSHIP as VARCHAR) as INVERSE_RELATIONSHIP,
		cast(INDICATOR_FOR_STANDARD_OBJECT_TYPE as VARCHAR) as INDICATOR_FOR_STANDARD_OBJECT_TYPE,
		cast(EXTERNAL_OBJECT_INCLUDED_IN_ENHANCED_REL_MAINTENANCE as VARCHAR) as EXTERNAL_OBJECT_INCLUDED_IN_ENHANCED_REL_MAINTENANCE,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
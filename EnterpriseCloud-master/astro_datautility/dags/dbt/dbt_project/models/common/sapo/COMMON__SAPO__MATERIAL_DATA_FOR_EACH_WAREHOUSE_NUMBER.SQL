		KZMBF as INDICATOR_MESSAGE_TO_INVENTORY_MANAGEMENT,
		BSSKZ as SPECIAL_MOVEMENT_INDICATOR_FOR_WAREHOUSE_MANAGEMENT,
		MKAPV as CAPACITY_USAGE,
		BEZME as UNIT_OF_MEASURE_FOR_CAPACITY_CONSUMPTION,
		PLKPT as PICKING_STORAGE_TYPE_FOR_ROUGH_CUT_AND_DETAILED_PLANNING,
		VOMEM as DEFAULT_FOR_UNIT_OF_MEASURE_FROM_MATERIAL_MASTER_RECORD,
		L2SKR as MATERIAL_RELEVANCE_FOR_2_STEP_PICKING,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__MATERIAL_DATA_FOR_EACH_WAREHOUSE_NUMBER') }}
),

transform_data as (
    select
        CLIENT,
		MATERIAL_NUMBER,
		WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		DELETION_FLAG_FOR_ALL_MATERIAL_DATA_OF_A_WAREHOUSE_NUMBER,
		STORAGE_SECTION_INDICATORS,
		STORAGE_TYPE_INDICATOR_FOR_STOCK_PLACEMENT,
		STORAGE_TYPE_INDICATOR_FOR_STOCK_REMOVAL,
		LOADING_EQUIPMENT_QUANTITY_1,
		LOADING_EQUIPMENT_QUANTITY_2,
		LOADING_EQUIPMENT_QUANTITY_3,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_1,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_2,
		UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_3,
		FIRST_STORAGE_UNIT_TYPE,
		SECOND_STORAGE_UNIT_TYPE,
		THIRD_STORAGE_UNIT_TYPE,
		WAREHOUSE_MANAGEMENT_UNIT_OF_MEASURE,
		INDICATOR_ALLOW_ADDITION_TO_EXISTING_STOCK,
		BULK_STORAGE_INDICATOR,
		INDICATOR_MESSAGE_TO_INVENTORY_MANAGEMENT,
		SPECIAL_MOVEMENT_INDICATOR_FOR_WAREHOUSE_MANAGEMENT,
		CAPACITY_USAGE,
		UNIT_OF_MEASURE_FOR_CAPACITY_CONSUMPTION,
		PICKING_STORAGE_TYPE_FOR_ROUGH_CUT_AND_DETAILED_PLANNING,
		DEFAULT_FOR_UNIT_OF_MEASURE_FROM_MATERIAL_MASTER_RECORD,
		MATERIAL_RELEVANCE_FOR_2_STEP_PICKING,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR(16777216)) as CLIENT,
		cast(MATERIAL_NUMBER as VARCHAR(16777216)) as MATERIAL_NUMBER,
		cast(WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX as VARCHAR(16777216)) as WAREHOUSE_NUMBER_WAREHOUSE_COMPLEX,
		cast(DELETION_FLAG_FOR_ALL_MATERIAL_DATA_OF_A_WAREHOUSE_NUMBER as VARCHAR(16777216)) as DELETION_FLAG_FOR_ALL_MATERIAL_DATA_OF_A_WAREHOUSE_NUMBER,
		cast(STORAGE_SECTION_INDICATORS as VARCHAR(16777216)) as STORAGE_SECTION_INDICATORS,
		cast(STORAGE_TYPE_INDICATOR_FOR_STOCK_PLACEMENT as VARCHAR(16777216)) as STORAGE_TYPE_INDICATOR_FOR_STOCK_PLACEMENT,
		cast(STORAGE_TYPE_INDICATOR_FOR_STOCK_REMOVAL as VARCHAR(16777216)) as STORAGE_TYPE_INDICATOR_FOR_STOCK_REMOVAL,
		cast(LOADING_EQUIPMENT_QUANTITY_1 as NUMBER(38,10)) as LOADING_EQUIPMENT_QUANTITY_1,
		cast(LOADING_EQUIPMENT_QUANTITY_2 as NUMBER(38,10)) as LOADING_EQUIPMENT_QUANTITY_2,
		cast(LOADING_EQUIPMENT_QUANTITY_3 as NUMBER(38,10)) as LOADING_EQUIPMENT_QUANTITY_3,
		cast(UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_1 as VARCHAR(16777216)) as UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_1,
		cast(UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_2 as VARCHAR(16777216)) as UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_2,
		cast(UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_3 as VARCHAR(16777216)) as UNIT_OF_MEASURE_FOR_LOADING_EQUIPMENT_QUANTITY_3,
		cast(FIRST_STORAGE_UNIT_TYPE as VARCHAR(16777216)) as FIRST_STORAGE_UNIT_TYPE,
		cast(SECOND_STORAGE_UNIT_TYPE as VARCHAR(16777216)) as SECOND_STORAGE_UNIT_TYPE,
		cast(THIRD_STORAGE_UNIT_TYPE as VARCHAR(16777216)) as THIRD_STORAGE_UNIT_TYPE,
		cast(WAREHOUSE_MANAGEMENT_UNIT_OF_MEASURE as VARCHAR(16777216)) as WAREHOUSE_MANAGEMENT_UNIT_OF_MEASURE,
		cast(INDICATOR_ALLOW_ADDITION_TO_EXISTING_STOCK as VARCHAR(16777216)) as INDICATOR_ALLOW_ADDITION_TO_EXISTING_STOCK,
		cast(BULK_STORAGE_INDICATOR as VARCHAR(16777216)) as BULK_STORAGE_INDICATOR,
		cast(INDICATOR_MESSAGE_TO_INVENTORY_MANAGEMENT as VARCHAR(16777216)) as INDICATOR_MESSAGE_TO_INVENTORY_MANAGEMENT,
		cast(SPECIAL_MOVEMENT_INDICATOR_FOR_WAREHOUSE_MANAGEMENT as VARCHAR(16777216)) as SPECIAL_MOVEMENT_INDICATOR_FOR_WAREHOUSE_MANAGEMENT,
		cast(CAPACITY_USAGE as NUMBER(38,10)) as CAPACITY_USAGE,
		cast(UNIT_OF_MEASURE_FOR_CAPACITY_CONSUMPTION as VARCHAR(16777216)) as UNIT_OF_MEASURE_FOR_CAPACITY_CONSUMPTION,
		cast(PICKING_STORAGE_TYPE_FOR_ROUGH_CUT_AND_DETAILED_PLANNING as VARCHAR(16777216)) as PICKING_STORAGE_TYPE_FOR_ROUGH_CUT_AND_DETAILED_PLANNING,
		cast(DEFAULT_FOR_UNIT_OF_MEASURE_FROM_MATERIAL_MASTER_RECORD as VARCHAR(16777216)) as DEFAULT_FOR_UNIT_OF_MEASURE_FROM_MATERIAL_MASTER_RECORD,
		cast(MATERIAL_RELEVANCE_FOR_2_STEP_PICKING as VARCHAR(16777216)) as MATERIAL_RELEVANCE_FOR_2_STEP_PICKING,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    from transform_data
)

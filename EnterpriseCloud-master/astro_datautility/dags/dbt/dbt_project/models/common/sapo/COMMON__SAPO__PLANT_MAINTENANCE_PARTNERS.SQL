{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='PLANT_MAINTENANCE_PARTNERS',
        unique_key = ['CLIENT',
    'OBJECT_NUMBER',
    'PARTNER_FUNCTION',
    'COUNTER_FOR_DIFFERENTIATION_DIGIT'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		OBJNR as OBJECT_NUMBER,
		PARVW as PARTNER_FUNCTION,
		COUNTER as COUNTER_FOR_DIFFERENTIATION_DIGIT,
		OBTYP as OBJECT_CATEGORY,
		PARNR as PARTNER,
		INHER as DATA_ORIGIN_INDICATOR,
		ERDAT as DATE_ON_WHICH_RECORD_WAS_CREATED,
		ERZEIT as TIME_AT_WHICH_RECORD_WAS_ADDED,
		ERNAM as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		AEDAT as DATE_OF_LAST_CHANGE,
		AEZEIT as TIME_OF_CHANGE,
		AENAM as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		KZLOESCH as DELETE_DATA_RECORD,
		ADRNR as ADDRESS_NUMBER,
		TZONSP as TIME_ZONE_FOR_PARTNER,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__PLANT_MAINTENANCE_PARTNERS') }}
),

transform_data as (
    select
        CLIENT,
		OBJECT_NUMBER,
		PARTNER_FUNCTION,
		COUNTER_FOR_DIFFERENTIATION_DIGIT,
		OBJECT_CATEGORY,
		PARTNER,
		DATA_ORIGIN_INDICATOR,
		TRY_TO_DATE(DATE_ON_WHICH_RECORD_WAS_CREATED, 'YYYYMMDD') as DATE_ON_WHICH_RECORD_WAS_CREATED,
		TIME_AT_WHICH_RECORD_WAS_ADDED,
		NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		TRY_TO_DATE(DATE_OF_LAST_CHANGE, 'YYYYMMDD') as DATE_OF_LAST_CHANGE,
		TIME_OF_CHANGE,
		NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		DELETE_DATA_RECORD,
		ADDRESS_NUMBER,
		TIME_ZONE_FOR_PARTNER,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR(16777216)) as CLIENT,
		cast(OBJECT_NUMBER as VARCHAR(16777216)) as OBJECT_NUMBER,
		cast(PARTNER_FUNCTION as VARCHAR(16777216)) as PARTNER_FUNCTION,
		cast(COUNTER_FOR_DIFFERENTIATION_DIGIT as VARCHAR(16777216)) as COUNTER_FOR_DIFFERENTIATION_DIGIT,
		cast(OBJECT_CATEGORY as VARCHAR(16777216)) as OBJECT_CATEGORY,
		cast(PARTNER as VARCHAR(16777216)) as PARTNER,
		cast(DATA_ORIGIN_INDICATOR as VARCHAR(16777216)) as DATA_ORIGIN_INDICATOR,
		cast(DATE_ON_WHICH_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_RECORD_WAS_CREATED,
		cast(TIME_AT_WHICH_RECORD_WAS_ADDED as VARCHAR(16777216)) as TIME_AT_WHICH_RECORD_WAS_ADDED,
		cast(NAME_OF_PERSON_WHO_CREATED_THE_OBJECT as VARCHAR(16777216)) as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		cast(DATE_OF_LAST_CHANGE as DATE) as DATE_OF_LAST_CHANGE,
		cast(TIME_OF_CHANGE as VARCHAR(16777216)) as TIME_OF_CHANGE,
		cast(NAME_OF_PERSON_WHO_CHANGED_OBJECT as VARCHAR(16777216)) as NAME_OF_PERSON_WHO_CHANGED_OBJECT,
		cast(DELETE_DATA_RECORD as VARCHAR(16777216)) as DELETE_DATA_RECORD,
		cast(ADDRESS_NUMBER as VARCHAR(16777216)) as ADDRESS_NUMBER,
		cast(TIME_ZONE_FOR_PARTNER as VARCHAR(16777216)) as TIME_ZONE_FOR_PARTNER,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
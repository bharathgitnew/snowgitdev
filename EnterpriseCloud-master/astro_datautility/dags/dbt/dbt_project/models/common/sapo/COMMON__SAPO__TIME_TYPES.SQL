{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='TIME_TYPES',
        unique_key = ['CLIENT',
    'GROUPING_OF_PERSONNEL_SUBAREAS_FOR_TIME_RECORDING',
    'TIME_TYPE',
    'END_DATE'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		MOBDE as GROUPING_OF_PERSONNEL_SUBAREAS_FOR_TIME_RECORDING,
		ZTART as TIME_TYPE,
		ENDDA as END_DATE,
		BEGDA as START_DATE,
		MOSUM as CUMULATE_IN_PERIOD_BALANCE,
		VORMO as TRANSFER_FROM_PREVIOUS_PERIOD,
		EISUM as SAVE_AS_DAY_BALANCE,
		JAUEB as TRANSFER_FROM_PREVIOUS_YEAR,
		SAKOR as ELIGIBILITY_INDICATOR_FOR_TIME_TRANSFERS,
		ZTNXP as TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_PERIOD,
		ZTNXY as TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_YEAR,
		B1SUM as STORE_FOR_TIME_ACCOUNTS_AND_DOWNLOAD_TO_SUBSYSTEM,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__TIME_TYPES') }}
),

transform_data as (
    select
        CLIENT,
		GROUPING_OF_PERSONNEL_SUBAREAS_FOR_TIME_RECORDING,
		TIME_TYPE,
		TRY_TO_DATE(END_DATE,'YYYYMMDD')  AS END_DATE, 
		TRY_TO_DATE(START_DATE,'YYYYMMDD')  AS START_DATE, 
		CUMULATE_IN_PERIOD_BALANCE,
		TRANSFER_FROM_PREVIOUS_PERIOD,
		SAVE_AS_DAY_BALANCE,
		TRANSFER_FROM_PREVIOUS_YEAR,
		ELIGIBILITY_INDICATOR_FOR_TIME_TRANSFERS,
		TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_PERIOD,
		TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_YEAR,
		STORE_FOR_TIME_ACCOUNTS_AND_DOWNLOAD_TO_SUBSYSTEM,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(GROUPING_OF_PERSONNEL_SUBAREAS_FOR_TIME_RECORDING as VARCHAR) as GROUPING_OF_PERSONNEL_SUBAREAS_FOR_TIME_RECORDING,
		cast(TIME_TYPE as VARCHAR) as TIME_TYPE,
		cast(END_DATE as DATE) as END_DATE,
		cast(START_DATE as DATE) as START_DATE,
		cast(CUMULATE_IN_PERIOD_BALANCE as VARCHAR) as CUMULATE_IN_PERIOD_BALANCE,
		cast(TRANSFER_FROM_PREVIOUS_PERIOD as VARCHAR) as TRANSFER_FROM_PREVIOUS_PERIOD,
		cast(SAVE_AS_DAY_BALANCE as VARCHAR) as SAVE_AS_DAY_BALANCE,
		cast(TRANSFER_FROM_PREVIOUS_YEAR as VARCHAR) as TRANSFER_FROM_PREVIOUS_YEAR,
		cast(ELIGIBILITY_INDICATOR_FOR_TIME_TRANSFERS as VARCHAR) as ELIGIBILITY_INDICATOR_FOR_TIME_TRANSFERS,
		cast(TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_PERIOD as VARCHAR) as TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_PERIOD,
		cast(TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_YEAR as VARCHAR) as TRANSFER_TO_NEW_PERIOD_BALANCE_AT_START_OF_NEW_YEAR,
		cast(STORE_FOR_TIME_ACCOUNTS_AND_DOWNLOAD_TO_SUBSYSTEM as VARCHAR) as STORE_FOR_TIME_ACCOUNTS_AND_DOWNLOAD_TO_SUBSYSTEM,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
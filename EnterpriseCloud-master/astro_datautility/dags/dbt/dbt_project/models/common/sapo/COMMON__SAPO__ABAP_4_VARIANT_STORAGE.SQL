{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='ABAP_4_VARIANT_STORAGE',
        unique_key = ['CLIENT',
    'RELATION_ID',
    'ABAP_PROGRAM_NAME_IN_VARIANT_KEY',
    'ABAP_NAME_OF_VARIANT_WITHOUT_PROGRAM_NAME',
    'NEXT_RECORD_COUNTER_IN_EXPORTIMPORT_DATA_TABLES'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		RELID as RELATION_ID,
		REPORT as ABAP_PROGRAM_NAME_IN_VARIANT_KEY,
		VARIANT as ABAP_NAME_OF_VARIANT_WITHOUT_PROGRAM_NAME,
		SRTF2 as NEXT_RECORD_COUNTER_IN_EXPORTIMPORT_DATA_TABLES,
		VDATE as ABAP_DATE_OF_A_VARIANT,
		VTIME as ABAP_TIME_OF_A_VARIANT,
		VERNR as ABAP_PROGRAM_VERSION_NUMBER,
		CLUSTR as BIN2_DATA_ELEMENT_FOR_SYST,
		CLUSTD as CONTENTS_OF_VARIANT,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__ABAP_4_VARIANT_STORAGE') }}
),

transform_data as (
    select
        CLIENT,
		RELATION_ID,
		ABAP_PROGRAM_NAME_IN_VARIANT_KEY,
		ABAP_NAME_OF_VARIANT_WITHOUT_PROGRAM_NAME,
		NEXT_RECORD_COUNTER_IN_EXPORTIMPORT_DATA_TABLES,
		TRY_TO_DATE(ABAP_DATE_OF_A_VARIANT,'YYYYMMDD')  AS ABAP_DATE_OF_A_VARIANT,
		ABAP_TIME_OF_A_VARIANT,
		ABAP_PROGRAM_VERSION_NUMBER,
		BIN2_DATA_ELEMENT_FOR_SYST,
		CONTENTS_OF_VARIANT,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(RELATION_ID as VARCHAR) as RELATION_ID,
		cast(ABAP_PROGRAM_NAME_IN_VARIANT_KEY as VARCHAR) as ABAP_PROGRAM_NAME_IN_VARIANT_KEY,
		cast(ABAP_NAME_OF_VARIANT_WITHOUT_PROGRAM_NAME as VARCHAR) as ABAP_NAME_OF_VARIANT_WITHOUT_PROGRAM_NAME,
		cast(NEXT_RECORD_COUNTER_IN_EXPORTIMPORT_DATA_TABLES as NUMBER(38,10)) as NEXT_RECORD_COUNTER_IN_EXPORTIMPORT_DATA_TABLES,
		cast(ABAP_DATE_OF_A_VARIANT as DATE) as ABAP_DATE_OF_A_VARIANT,
		cast(ABAP_TIME_OF_A_VARIANT as VARCHAR) as ABAP_TIME_OF_A_VARIANT,
		cast(ABAP_PROGRAM_VERSION_NUMBER as VARCHAR) as ABAP_PROGRAM_VERSION_NUMBER,
		cast(BIN2_DATA_ELEMENT_FOR_SYST as NUMBER(38,10)) as BIN2_DATA_ELEMENT_FOR_SYST,
		cast(CONTENTS_OF_VARIANT as VARCHAR) as CONTENTS_OF_VARIANT,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
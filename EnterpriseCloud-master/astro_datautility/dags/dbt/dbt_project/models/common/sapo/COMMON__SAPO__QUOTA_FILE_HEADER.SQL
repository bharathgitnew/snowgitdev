{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='QUOTA_FILE_HEADER',
        unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'PLANT',
    'QUOTA_ARRANGEMENT_PERIOD_VALID_UNTIL'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		MATNR as MATERIAL_NUMBER,
		WERKS as PLANT,
		BDATU as QUOTA_ARRANGEMENT_PERIOD_VALID_UNTIL,
		VDATU as QUOTA_ARRANGEMENT_PERIOD_VALID_FROM,
		QUNUM as NUMBER_OF_QUOTA_ARRANGEMENT,
		ERDAT as DATE_ON_WHICH_RECORD_WAS_CREATED,
		ERNAM as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		SCMNG as MINIMUM_QUANTITY_FOR_SPLITTING_QUOTA,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__QUOTA_FILE_HEADER') }}
),

transform_data as (
    select
        CLIENT,
		MATERIAL_NUMBER,
		PLANT,
		TRY_TO_DATE(QUOTA_ARRANGEMENT_PERIOD_VALID_UNTIL,'YYYYMMDD')  AS QUOTA_ARRANGEMENT_PERIOD_VALID_UNTIL, 
		TRY_TO_DATE(QUOTA_ARRANGEMENT_PERIOD_VALID_FROM,'YYYYMMDD')  AS QUOTA_ARRANGEMENT_PERIOD_VALID_FROM, 
		NUMBER_OF_QUOTA_ARRANGEMENT,
		TRY_TO_DATE(DATE_ON_WHICH_RECORD_WAS_CREATED,'YYYYMMDD')  AS DATE_ON_WHICH_RECORD_WAS_CREATED, 
		NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		MINIMUM_QUANTITY_FOR_SPLITTING_QUOTA,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(MATERIAL_NUMBER as VARCHAR) as MATERIAL_NUMBER,
		cast(PLANT as VARCHAR) as PLANT,
		cast(QUOTA_ARRANGEMENT_PERIOD_VALID_UNTIL as DATE) as QUOTA_ARRANGEMENT_PERIOD_VALID_UNTIL,
		cast(QUOTA_ARRANGEMENT_PERIOD_VALID_FROM as DATE) as QUOTA_ARRANGEMENT_PERIOD_VALID_FROM,
		cast(NUMBER_OF_QUOTA_ARRANGEMENT as VARCHAR) as NUMBER_OF_QUOTA_ARRANGEMENT,
		cast(DATE_ON_WHICH_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_RECORD_WAS_CREATED,
		cast(NAME_OF_PERSON_WHO_CREATED_THE_OBJECT as VARCHAR) as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		cast(MINIMUM_QUANTITY_FOR_SPLITTING_QUOTA as NUMBER(38,10)) as MINIMUM_QUANTITY_FOR_SPLITTING_QUOTA,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
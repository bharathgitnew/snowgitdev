{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='GL_ACCOUNT_MASTER',
        unique_key = ['CLIENT',
    'CHART_OF_ACCOUNTS',
    'GL_ACCOUNT_NUMBER'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		KTOPL as CHART_OF_ACCOUNTS,
		SAKNR as GL_ACCOUNT_NUMBER,
		XBILK as INDICATOR_ACCOUNT_IS_A_BALANCE_SHEET_ACCOUNT,
		SAKAN as GL_ACCOUNT_NUMBER_SIGNIFICANT_LENGTH,
		BILKT as GROUP_ACCOUNT_NUMBER,
		ERDAT as DATE_ON_WHICH_THE_RECORD_WAS_CREATED,
		ERNAM as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		GVTYP as P_L_STATEMENT_ACCOUNT_TYPE,
		KTOKS as GL_ACCOUNT_GROUP,
		MUSTR as NUMBER_OF_THE_SAMPLE_ACCOUNT,
		VBUND as COMPANY_ID_OF_TRADING_PARTNER,
		XLOEV as INDICATOR_ACCOUNT_MARKED_FOR_DELETION,
		XSPEA as INDICATOR_ACCOUNT_IS_BLOCKED_FOR_CREATION,
		XSPEB as INDICATOR_IS_ACCOUNT_BLOCKED_FOR_POSTING,
		XSPEP as INDICATOR_ACCOUNT_BLOCKED_FOR_PLANNING,
		MCOD1 as SEARCH_TERM_FOR_USING_MATCHCODE,
		FUNC_AREA as FUNCTIONAL_AREA,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__GL_ACCOUNT_MASTER') }}
),

transform_data as (
    select
        CLIENT,
		CHART_OF_ACCOUNTS,
		GL_ACCOUNT_NUMBER,
		INDICATOR_ACCOUNT_IS_A_BALANCE_SHEET_ACCOUNT,
		GL_ACCOUNT_NUMBER_SIGNIFICANT_LENGTH,
		GROUP_ACCOUNT_NUMBER,
		TRY_TO_DATE(DATE_ON_WHICH_THE_RECORD_WAS_CREATED,'YYYYMMDD')  AS DATE_ON_WHICH_THE_RECORD_WAS_CREATED,
		NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		P_L_STATEMENT_ACCOUNT_TYPE,
		GL_ACCOUNT_GROUP,
		NUMBER_OF_THE_SAMPLE_ACCOUNT,
		COMPANY_ID_OF_TRADING_PARTNER,
		INDICATOR_ACCOUNT_MARKED_FOR_DELETION,
		INDICATOR_ACCOUNT_IS_BLOCKED_FOR_CREATION,
		INDICATOR_IS_ACCOUNT_BLOCKED_FOR_POSTING,
		INDICATOR_ACCOUNT_BLOCKED_FOR_PLANNING,
		SEARCH_TERM_FOR_USING_MATCHCODE,
		FUNCTIONAL_AREA,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(CHART_OF_ACCOUNTS as VARCHAR) as CHART_OF_ACCOUNTS,
		cast(GL_ACCOUNT_NUMBER as VARCHAR) as GL_ACCOUNT_NUMBER,
		cast(INDICATOR_ACCOUNT_IS_A_BALANCE_SHEET_ACCOUNT as VARCHAR) as INDICATOR_ACCOUNT_IS_A_BALANCE_SHEET_ACCOUNT,
		cast(GL_ACCOUNT_NUMBER_SIGNIFICANT_LENGTH as VARCHAR) as GL_ACCOUNT_NUMBER_SIGNIFICANT_LENGTH,
		cast(GROUP_ACCOUNT_NUMBER as VARCHAR) as GROUP_ACCOUNT_NUMBER,
		cast(DATE_ON_WHICH_THE_RECORD_WAS_CREATED as DATE) as DATE_ON_WHICH_THE_RECORD_WAS_CREATED,
		cast(NAME_OF_PERSON_WHO_CREATED_THE_OBJECT as VARCHAR) as NAME_OF_PERSON_WHO_CREATED_THE_OBJECT,
		cast(P_L_STATEMENT_ACCOUNT_TYPE as VARCHAR) as P_L_STATEMENT_ACCOUNT_TYPE,
		cast(GL_ACCOUNT_GROUP as VARCHAR) as GL_ACCOUNT_GROUP,
		cast(NUMBER_OF_THE_SAMPLE_ACCOUNT as VARCHAR) as NUMBER_OF_THE_SAMPLE_ACCOUNT,
		cast(COMPANY_ID_OF_TRADING_PARTNER as VARCHAR) as COMPANY_ID_OF_TRADING_PARTNER,
		cast(INDICATOR_ACCOUNT_MARKED_FOR_DELETION as VARCHAR) as INDICATOR_ACCOUNT_MARKED_FOR_DELETION,
		cast(INDICATOR_ACCOUNT_IS_BLOCKED_FOR_CREATION as VARCHAR) as INDICATOR_ACCOUNT_IS_BLOCKED_FOR_CREATION,
		cast(INDICATOR_IS_ACCOUNT_BLOCKED_FOR_POSTING as VARCHAR) as INDICATOR_IS_ACCOUNT_BLOCKED_FOR_POSTING,
		cast(INDICATOR_ACCOUNT_BLOCKED_FOR_PLANNING as VARCHAR) as INDICATOR_ACCOUNT_BLOCKED_FOR_PLANNING,
		cast(SEARCH_TERM_FOR_USING_MATCHCODE as VARCHAR) as SEARCH_TERM_FOR_USING_MATCHCODE,
		cast(FUNCTIONAL_AREA as VARCHAR) as FUNCTIONAL_AREA,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data


{{ config(
    materialized='incremental',
    incremental_strategy='merge',
    alias='ACTIVITY_MASTER',
    unique_key = ['CLIENT','CONTROLLING_AREA','ACTIVITY_TYPE','VALID_TO_DATE'],
    transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		KOKRS as CONTROLLING_AREA,
		LSTAR as ACTIVITY_TYPE,
		DATBI as VALID_TO_DATE,
		DATAB as VALID_FROM_DATE,
		LEINH as ACTIVITY_UNIT,
		LATYP as ACTIVITY_TYPE_CATEGORY,
		LATYPI as VARIANT_ACTIVITY_TYPE_CATEGORY_FOR_ACTUAL_POSTINGS,
		ERSDA as CREATED_ON,
		USNAM as ENTERED_BY,
		KSTTY as VALID_COST_CENTER_CATEGORIES,
		AUSEH as OUTPUT_UNIT,
		AUSFK as OUTPUT_FACTOR,
		VKSTA as ALLOCATION_COST_ELEMENT,
		LARK1 as INDICATOR_FOR_COMPONENT_RELEVANCY_CO,
		LARK2 as INDICATOR_COMPONENT_RELEVANCE_HR,
		SPRKZ as LOCK_INDICATOR,
		HRKFT as ORIGIN_GROUP_AS_SUBDIVISION_OF_COST_ELEMENT,
		FIXVO as PREDISTRIBUTION_OF_FIXED_COSTS_FOR_ACTY_TYPE_BUS_PROCESS,
		TARKZ as PRICE_INDICATOR_CALCULATE_ALLOCATION_PRICE,
		YRATE as PRICE_CALCULATION_WITH_PERIOD_BASED_AVERAGE_PRICES,
		TARKZ_I as INDICATOR_ACTUAL_ALLOCATION_PRICE,
		MANIST as INDICATOR_CONFIRM_QUANTITY_MANUALLY_IN_ACTUAL,
		MANPLAN as INDICATOR_PLAN_QUANTITY_MANUALLY_SET,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__ACTIVITY_MASTER') }} 
),

transform_data as (
    select
		'{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH,
		_CAPTUREDATETIME,
        CLIENT,
		CONTROLLING_AREA,
		ACTIVITY_TYPE,
		TRY_TO_DATE(VALID_TO_DATE, 'YYYYMMDD') as VALID_TO_DATE,
		TRY_TO_DATE(VALID_FROM_DATE, 'YYYYMMDD') as VALID_FROM_DATE,
		ACTIVITY_UNIT,
		ACTIVITY_TYPE_CATEGORY,
		VARIANT_ACTIVITY_TYPE_CATEGORY_FOR_ACTUAL_POSTINGS,
		TRY_TO_DATE(CREATED_ON, 'YYYYMMDD') as CREATED_ON,
		ENTERED_BY,
		VALID_COST_CENTER_CATEGORIES,
		OUTPUT_UNIT,
		OUTPUT_FACTOR,
		ALLOCATION_COST_ELEMENT,
		INDICATOR_FOR_COMPONENT_RELEVANCY_CO,
		INDICATOR_COMPONENT_RELEVANCE_HR,
		LOCK_INDICATOR,
		ORIGIN_GROUP_AS_SUBDIVISION_OF_COST_ELEMENT,
		PREDISTRIBUTION_OF_FIXED_COSTS_FOR_ACTY_TYPE_BUS_PROCESS,
		PRICE_INDICATOR_CALCULATE_ALLOCATION_PRICE,
		PRICE_CALCULATION_WITH_PERIOD_BASED_AVERAGE_PRICES,
		INDICATOR_ACTUAL_ALLOCATION_PRICE,
		INDICATOR_CONFIRM_QUANTITY_MANUALLY_IN_ACTUAL,
		INDICATOR_PLAN_QUANTITY_MANUALLY_SET
    from source_data
),

type_data as (
    select
        cast(_AUDIT_LOG_ID as VARCHAR(128)) as _AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		CLIENT,
		CONTROLLING_AREA,
		ACTIVITY_TYPE,
		cast(VALID_TO_DATE as DATE) as VALID_TO_DATE,
		cast(VALID_FROM_DATE as DATE) as VALID_FROM_DATE,
		ACTIVITY_UNIT,
		ACTIVITY_TYPE_CATEGORY,
		VARIANT_ACTIVITY_TYPE_CATEGORY_FOR_ACTUAL_POSTINGS,
		cast(CREATED_ON as DATE) as CREATED_ON,
		ENTERED_BY,
		VALID_COST_CENTER_CATEGORIES,
		OUTPUT_UNIT,
		cast(OUTPUT_FACTOR as NUMBER(38,10)) as OUTPUT_FACTOR,
		ALLOCATION_COST_ELEMENT,
		INDICATOR_FOR_COMPONENT_RELEVANCY_CO,
		INDICATOR_COMPONENT_RELEVANCE_HR,
		LOCK_INDICATOR,
		ORIGIN_GROUP_AS_SUBDIVISION_OF_COST_ELEMENT,
		PREDISTRIBUTION_OF_FIXED_COSTS_FOR_ACTY_TYPE_BUS_PROCESS,
		PRICE_INDICATOR_CALCULATE_ALLOCATION_PRICE,
		PRICE_CALCULATION_WITH_PERIOD_BASED_AVERAGE_PRICES,
		INDICATOR_ACTUAL_ALLOCATION_PRICE,
		INDICATOR_CONFIRM_QUANTITY_MANUALLY_IN_ACTUAL,
		INDICATOR_PLAN_QUANTITY_MANUALLY_SET
    from transform_data
)
select * from type_data
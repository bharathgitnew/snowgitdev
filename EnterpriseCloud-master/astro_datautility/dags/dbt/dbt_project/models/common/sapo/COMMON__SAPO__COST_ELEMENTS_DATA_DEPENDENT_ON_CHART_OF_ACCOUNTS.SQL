{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='COST_ELEMENTS_DATA_DEPENDENT_ON_CHART_OF_ACCOUNTS',
        unique_key = ['CLIENT',
    'CHART_OF_ACCOUNTS',
    'COST_ELEMENT',
    'CREATED_ON',
    'ENTERED_BY',
    'COST_ELEMENT_IS_TAX_RELEVANT',
    'COST_ELEMENT_AFFECTING_PAYMENT',
    'KSTSN_COST_ELEMENT',
    'FUNCTIONAL_AREA'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		KTOPL as CHART_OF_ACCOUNTS,
		KSTAR as COST_ELEMENT,
		ERSDA as CREATED_ON,
		USNAM as ENTERED_BY,
		STEKZ as COST_ELEMENT_IS_TAX_RELEVANT,
		ZAHKZ as COST_ELEMENT_AFFECTING_PAYMENT,
		KSTSN as KSTSN_COST_ELEMENT,
		FUNC_AREA as FUNCTIONAL_AREA,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__COST_ELEMENTS_DATA_DEPENDENT_ON_CHART_OF_ACCOUNTS') }}
),

transform_data as (
    select
        CLIENT,
		CHART_OF_ACCOUNTS,
		COST_ELEMENT,
		TRY_TO_DATE(CREATED_ON, 'YYYYMMDD') as CREATED_ON,
		ENTERED_BY,
		COST_ELEMENT_IS_TAX_RELEVANT,
		COST_ELEMENT_AFFECTING_PAYMENT,
		KSTSN_COST_ELEMENT,
		FUNCTIONAL_AREA,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR(16777216)) as CLIENT,
		cast(CHART_OF_ACCOUNTS as VARCHAR(16777216)) as CHART_OF_ACCOUNTS,
		cast(COST_ELEMENT as VARCHAR(16777216)) as COST_ELEMENT,
		cast(CREATED_ON as DATE) as CREATED_ON,
		cast(ENTERED_BY as VARCHAR(16777216)) as ENTERED_BY,
		cast(COST_ELEMENT_IS_TAX_RELEVANT as VARCHAR(16777216)) as COST_ELEMENT_IS_TAX_RELEVANT,
		cast(COST_ELEMENT_AFFECTING_PAYMENT as VARCHAR(16777216)) as COST_ELEMENT_AFFECTING_PAYMENT,
		cast(KSTSN_COST_ELEMENT as VARCHAR(16777216)) as KSTSN_COST_ELEMENT,
		cast(FUNCTIONAL_AREA as VARCHAR(16777216)) as FUNCTIONAL_AREA,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as VARCHAR(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as VARCHAR(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
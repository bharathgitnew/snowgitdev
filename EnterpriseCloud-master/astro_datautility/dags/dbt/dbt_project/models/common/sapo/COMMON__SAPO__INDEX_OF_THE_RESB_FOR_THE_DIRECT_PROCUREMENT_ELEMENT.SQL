{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='INDEX_OF_THE_RESB_FOR_THE_DIRECT_PROCUREMENT_ELEMENT',
        unique_key = ['CLIENT',
    'NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS',
    'ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS',
    'RECORD_TYPE',
    'INDEX_COUNTER_FOR_DIRECT_PROCUREMENT_ELEMENTS'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		RSNUM as NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS,
		RSPOS as ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS,
		RSART as RECORD_TYPE,
		RSINZ as INDEX_COUNTER_FOR_DIRECT_PROCUREMENT_ELEMENTS,
		PLNUM as PLANNED_ORDER_NUMBER,
		BANFN as PURCHASE_REQUISITION_NUMBER,
		BNFPO as ITEM_NUMBER_OF_PURCHASE_REQUISITION,
		EBELN as PURCHASING_DOCUMENT_NUMBER,
		EBELP as ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
		AUFNR as ORDER_NUMBER,
		AUFPO as ORDER_ITEM_NUMBER,
		AOBAR as TYPE_OF_RELATIONSHIP,
		ZEINH as UNIT_FOR_THE_TIME_INTERVAL_BETWEEN_RELATIONSHIPS,
		DAUER as TIME_INTERVAL_BETWEEN_RELATIONSHIPS,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__INDEX_OF_THE_RESB_FOR_THE_DIRECT_PROCUREMENT_ELEMENT') }}
),

transform_data as (
    select
        CLIENT,
		NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS,
		ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS,
		RECORD_TYPE,
		INDEX_COUNTER_FOR_DIRECT_PROCUREMENT_ELEMENTS,
		PLANNED_ORDER_NUMBER,
		PURCHASE_REQUISITION_NUMBER,
		ITEM_NUMBER_OF_PURCHASE_REQUISITION,
		PURCHASING_DOCUMENT_NUMBER,
		ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
		ORDER_NUMBER,
		ORDER_ITEM_NUMBER,
		TYPE_OF_RELATIONSHIP,
		UNIT_FOR_THE_TIME_INTERVAL_BETWEEN_RELATIONSHIPS,
		TIME_INTERVAL_BETWEEN_RELATIONSHIPS,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS as VARCHAR) as NUMBER_OF_RESERVATIONDEPENDENT_REQUIREMENTS,
		cast(ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS as VARCHAR) as ITEM_NUMBER_OF_RESERVATION_DEPENDENT_REQUIREMENTS,
		cast(RECORD_TYPE as VARCHAR) as RECORD_TYPE,
		cast(INDEX_COUNTER_FOR_DIRECT_PROCUREMENT_ELEMENTS as VARCHAR) as INDEX_COUNTER_FOR_DIRECT_PROCUREMENT_ELEMENTS,
		cast(PLANNED_ORDER_NUMBER as VARCHAR) as PLANNED_ORDER_NUMBER,
		cast(PURCHASE_REQUISITION_NUMBER as VARCHAR) as PURCHASE_REQUISITION_NUMBER,
		cast(ITEM_NUMBER_OF_PURCHASE_REQUISITION as VARCHAR) as ITEM_NUMBER_OF_PURCHASE_REQUISITION,
		cast(PURCHASING_DOCUMENT_NUMBER as VARCHAR) as PURCHASING_DOCUMENT_NUMBER,
		cast(ITEM_NUMBER_OF_PURCHASING_DOCUMENT as VARCHAR) as ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
		cast(ORDER_NUMBER as VARCHAR) as ORDER_NUMBER,
		cast(ORDER_ITEM_NUMBER as VARCHAR) as ORDER_ITEM_NUMBER,
		cast(TYPE_OF_RELATIONSHIP as VARCHAR) as TYPE_OF_RELATIONSHIP,
		cast(UNIT_FOR_THE_TIME_INTERVAL_BETWEEN_RELATIONSHIPS as VARCHAR) as UNIT_FOR_THE_TIME_INTERVAL_BETWEEN_RELATIONSHIPS,
		cast(TIME_INTERVAL_BETWEEN_RELATIONSHIPS as NUMBER(38,10)) as TIME_INTERVAL_BETWEEN_RELATIONSHIPS,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
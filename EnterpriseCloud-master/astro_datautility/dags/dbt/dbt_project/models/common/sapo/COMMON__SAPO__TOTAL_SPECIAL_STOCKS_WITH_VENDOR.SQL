{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='TOTAL_SPECIAL_STOCKS_WITH_VENDOR',
        unique_key = ['CLIENT',
    'MATERIAL_NUMBER',
    'PLANT',
    'SPECIAL_STOCK_INDICATOR',
    'ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		MATNR as MATERIAL_NUMBER,
		WERKS as PLANT,
		SOBKZ as SPECIAL_STOCK_INDICATOR,
		LIFNR as ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		LFGJA as FISCAL_YEAR_OF_CURRENT_PERIOD,
		LFMON as CURRENT_PERIOD_POSTING_PERIOD,
		SLLAB as VALUATED_UNRESTRICTED_USE_STOCK,
		SLINS as STOCK_IN_QUALITY_INSPECTION,
		SLEIN as TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES,
		ERSDA as CREATED_ON,
		XOBEW as VENDOR_STOCK_VALUATION_INDICATOR,
		SLUML as STOCK_IN_TRANSFER_FOR_SUBCONTRACTING_PLANT_TO_PLANT,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__TOTAL_SPECIAL_STOCKS_WITH_VENDOR') }}
),

transform_data as (
    select
        CLIENT,
		MATERIAL_NUMBER,
		PLANT,
		SPECIAL_STOCK_INDICATOR,
		ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		FISCAL_YEAR_OF_CURRENT_PERIOD,
		CURRENT_PERIOD_POSTING_PERIOD,
		VALUATED_UNRESTRICTED_USE_STOCK,
		STOCK_IN_QUALITY_INSPECTION,
		TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES,
		TRY_TO_DATE(CREATED_ON,'YYYYMMDD')  AS CREATED_ON, 
		VENDOR_STOCK_VALUATION_INDICATOR,
		STOCK_IN_TRANSFER_FOR_SUBCONTRACTING_PLANT_TO_PLANT,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(MATERIAL_NUMBER as VARCHAR) as MATERIAL_NUMBER,
		cast(PLANT as VARCHAR) as PLANT,
		cast(SPECIAL_STOCK_INDICATOR as VARCHAR) as SPECIAL_STOCK_INDICATOR,
		cast(ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR as VARCHAR) as ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR,
		cast(FISCAL_YEAR_OF_CURRENT_PERIOD as VARCHAR) as FISCAL_YEAR_OF_CURRENT_PERIOD,
		cast(CURRENT_PERIOD_POSTING_PERIOD as VARCHAR) as CURRENT_PERIOD_POSTING_PERIOD,
		cast(VALUATED_UNRESTRICTED_USE_STOCK as NUMBER(38,10)) as VALUATED_UNRESTRICTED_USE_STOCK,
		cast(STOCK_IN_QUALITY_INSPECTION as NUMBER(38,10)) as STOCK_IN_QUALITY_INSPECTION,
		cast(TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES as NUMBER(38,10)) as TOTAL_STOCK_OF_ALL_RESTRICTED_BATCHES,
		cast(CREATED_ON as DATE) as CREATED_ON,
		cast(VENDOR_STOCK_VALUATION_INDICATOR as VARCHAR) as VENDOR_STOCK_VALUATION_INDICATOR,
		cast(STOCK_IN_TRANSFER_FOR_SUBCONTRACTING_PLANT_TO_PLANT as NUMBER(38,10)) as STOCK_IN_TRANSFER_FOR_SUBCONTRACTING_PLANT_TO_PLANT,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='STXD_SAPSCRIPT_TEXT_FILE_HEADER',
        unique_key = ['CLIENT',
    'TEXTS_APPLICATION_OBJECT',
    'NAME',
    'TEXT_ID',
    'LANGUAGE_KEY'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		TDOBJECT as TEXTS_APPLICATION_OBJECT,
		TDNAME as NAME,
		TDID as TEXT_ID,
		TDSPRAS as LANGUAGE_KEY,
		TDTITLE as TITLE_IN_DIALOG_BOX,
		TDFRELES as RELEASE,
		TDFUSER as CREATED_BY,
		TDFDATE as DATE_CREATED,
		TDFTIME as TIME_CREATED,
		TDLRELES as LAST_CHANGED_IN_RELEASE,
		TDLUSER as LAST_CHANGED_BY,
		TDLDATE as CHANGED_ON,
		TDLTIME as LAST_CHANGED_AT,
		TDVERSION as VERSION,
		TDSTYLE as STYLE_NAME,
		TDFORM as FORM_NAME,
		TDHYPHENAT as HYPHENATION_ACTIVE,
		TDTRANSTAT as TRANSLATION_STATUS,
		TDOSPRAS as ORIGINAL_LANGUAGE,
		TDMACODE1 as SHORT_TITLE_1,
		TDMACODE2 as SHORT_TITLE_2,
		TDTXTLINES as NUMBER_OF_TEXT_LINES_IN_LINE_TABLE,
		TDREF as REFERENCE_TEXT,
		TDREFOBJ as OBJECT_OF_REFERENCED_TEXT,
		TDREFNAME as NAME_OF_REFERENCED_TEXT,
		TDREFID as ID_OF_REFERENCED_TEXT,
		TDTEXTTYPE as SAPSCRIPT_FORMAT_OF_TEXT,
		TDCOMPRESS as SAPSCRIPT_TEXT_IS_COMPRESSED,
		TDOCLASS as SAPSCRIPT_OBJECT_CLASS,
		LOGSYS as LOGICAL_SYSTEM,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__STXD_SAPSCRIPT_TEXT_FILE_HEADER') }}
),

transform_data as (
    select
        CLIENT,
		TEXTS_APPLICATION_OBJECT,
		NAME,
		TEXT_ID,
		LANGUAGE_KEY,
		TITLE_IN_DIALOG_BOX,
		RELEASE,
		CREATED_BY,
		TRY_TO_DATE(DATE_CREATED,'YYYYMMDD')  AS DATE_CREATED, 
		TIME_CREATED,
		LAST_CHANGED_IN_RELEASE,
		LAST_CHANGED_BY,
		TRY_TO_DATE(CHANGED_ON,'YYYYMMDD')  AS CHANGED_ON, 
		LAST_CHANGED_AT,
		VERSION,
		STYLE_NAME,
		FORM_NAME,
		HYPHENATION_ACTIVE,
		TRANSLATION_STATUS,
		ORIGINAL_LANGUAGE,
		SHORT_TITLE_1,
		SHORT_TITLE_2,
		NUMBER_OF_TEXT_LINES_IN_LINE_TABLE,
		REFERENCE_TEXT,
		OBJECT_OF_REFERENCED_TEXT,
		NAME_OF_REFERENCED_TEXT,
		ID_OF_REFERENCED_TEXT,
		SAPSCRIPT_FORMAT_OF_TEXT,
		SAPSCRIPT_TEXT_IS_COMPRESSED,
		SAPSCRIPT_OBJECT_CLASS,
		LOGICAL_SYSTEM,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(TEXTS_APPLICATION_OBJECT as VARCHAR) as TEXTS_APPLICATION_OBJECT,
		cast(NAME as VARCHAR) as NAME,
		cast(TEXT_ID as VARCHAR) as TEXT_ID,
		cast(LANGUAGE_KEY as VARCHAR) as LANGUAGE_KEY,
		cast(TITLE_IN_DIALOG_BOX as VARCHAR) as TITLE_IN_DIALOG_BOX,
		cast(RELEASE as VARCHAR) as RELEASE,
		cast(CREATED_BY as VARCHAR) as CREATED_BY,
		cast(DATE_CREATED as DATE) as DATE_CREATED,
		cast(TIME_CREATED as VARCHAR) as TIME_CREATED,
		cast(LAST_CHANGED_IN_RELEASE as VARCHAR) as LAST_CHANGED_IN_RELEASE,
		cast(LAST_CHANGED_BY as VARCHAR) as LAST_CHANGED_BY,
		cast(CHANGED_ON as DATE) as CHANGED_ON,
		cast(LAST_CHANGED_AT as VARCHAR) as LAST_CHANGED_AT,
		cast(VERSION as VARCHAR) as VERSION,
		cast(STYLE_NAME as VARCHAR) as STYLE_NAME,
		cast(FORM_NAME as VARCHAR) as FORM_NAME,
		cast(HYPHENATION_ACTIVE as VARCHAR) as HYPHENATION_ACTIVE,
		cast(TRANSLATION_STATUS as VARCHAR) as TRANSLATION_STATUS,
		cast(ORIGINAL_LANGUAGE as VARCHAR) as ORIGINAL_LANGUAGE,
		cast(SHORT_TITLE_1 as VARCHAR) as SHORT_TITLE_1,
		cast(SHORT_TITLE_2 as VARCHAR) as SHORT_TITLE_2,
		cast(NUMBER_OF_TEXT_LINES_IN_LINE_TABLE as VARCHAR) as NUMBER_OF_TEXT_LINES_IN_LINE_TABLE,
		cast(REFERENCE_TEXT as VARCHAR) as REFERENCE_TEXT,
		cast(OBJECT_OF_REFERENCED_TEXT as VARCHAR) as OBJECT_OF_REFERENCED_TEXT,
		cast(NAME_OF_REFERENCED_TEXT as VARCHAR) as NAME_OF_REFERENCED_TEXT,
		cast(ID_OF_REFERENCED_TEXT as VARCHAR) as ID_OF_REFERENCED_TEXT,
		cast(SAPSCRIPT_FORMAT_OF_TEXT as VARCHAR) as SAPSCRIPT_FORMAT_OF_TEXT,
		cast(SAPSCRIPT_TEXT_IS_COMPRESSED as VARCHAR) as SAPSCRIPT_TEXT_IS_COMPRESSED,
		cast(SAPSCRIPT_OBJECT_CLASS as VARCHAR) as SAPSCRIPT_OBJECT_CLASS,
		cast(LOGICAL_SYSTEM as VARCHAR) as LOGICAL_SYSTEM,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='INFOTYPE_1001_DB_TABLE',
        unique_key = ['CLIENT',
    'OBJECT_TYPE',
    'OBJECT_ID',
    'PLAN_VERSION',
    'RELATIONSHIP_SPECIFICATION',
    'RELATIONSHIP_BETWEEN_OBJECTS',
    'PLANNING_STATUS',
    'PRIORITY',
    'START_DATE',
    'END_DATE',
    'VARIATION_FIELD_FOR_FILE_PLOG',
    'NUMBER_OF_INFOTYPE_RECORD_WITH_SAME_KEY'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		OTYPE as OBJECT_TYPE,
		OBJID as OBJECT_ID,
		PLVAR as PLAN_VERSION,
		RSIGN as RELATIONSHIP_SPECIFICATION,
		RELAT as RELATIONSHIP_BETWEEN_OBJECTS,
		ISTAT as PLANNING_STATUS,
		PRIOX as PRIORITY,
		BEGDA as START_DATE,
		ENDDA as END_DATE,
		VARYF as VARIATION_FIELD_FOR_FILE_PLOG,
		SEQNR as NUMBER_OF_INFOTYPE_RECORD_WITH_SAME_KEY,
		INFTY as INFOTYPE,
		OTJID as CONCATENATION_OF_OBJECT_TYPE_AND_OBJECT_ID,
		SUBTY as SUBTYPE,
		AEDTM as CHANGED_ON,
		UNAME as USER_NAME,
		REASN as REASON,
		HISTO as HISTORICAL_RECORD_FLAG,
		ITXNR as TEXT_MODULE_FOR_INFOTYPE,
		SCLAS as TYPE_OF_RELATED_OBJECT,
		SOBID as ID_OF_RELATED_OBJECT,
		PROZT as WEIGHTING_PERCENTAGE,
		ADATANR as ADATA_NUMBER,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__INFOTYPE_1001_DB_TABLE') }}
),

transform_data as (
    select
        CLIENT,
		OBJECT_TYPE,
		OBJECT_ID,
		PLAN_VERSION,
		RELATIONSHIP_SPECIFICATION,
		RELATIONSHIP_BETWEEN_OBJECTS,
		PLANNING_STATUS,
		PRIORITY,
		TRY_TO_DATE(START_DATE,'YYYYMMDD')  AS START_DATE,
		TRY_TO_DATE(END_DATE,'YYYYMMDD')  AS END_DATE,
		VARIATION_FIELD_FOR_FILE_PLOG,
		NUMBER_OF_INFOTYPE_RECORD_WITH_SAME_KEY,
		INFOTYPE,
		CONCATENATION_OF_OBJECT_TYPE_AND_OBJECT_ID,
		SUBTYPE,
		TRY_TO_DATE(CHANGED_ON,'YYYYMMDD')  AS CHANGED_ON,
		USER_NAME,
		REASON,
		HISTORICAL_RECORD_FLAG,
		TEXT_MODULE_FOR_INFOTYPE,
		TYPE_OF_RELATED_OBJECT,
		ID_OF_RELATED_OBJECT,
		WEIGHTING_PERCENTAGE,
		ADATA_NUMBER,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(OBJECT_TYPE as VARCHAR) as OBJECT_TYPE,
		cast(OBJECT_ID as VARCHAR) as OBJECT_ID,
		cast(PLAN_VERSION as VARCHAR) as PLAN_VERSION,
		cast(RELATIONSHIP_SPECIFICATION as VARCHAR) as RELATIONSHIP_SPECIFICATION,
		cast(RELATIONSHIP_BETWEEN_OBJECTS as VARCHAR) as RELATIONSHIP_BETWEEN_OBJECTS,
		cast(PLANNING_STATUS as VARCHAR) as PLANNING_STATUS,
		cast(PRIORITY as VARCHAR) as PRIORITY,
		cast(START_DATE as DATE) as START_DATE,
		cast(END_DATE as DATE) as END_DATE,
		cast(VARIATION_FIELD_FOR_FILE_PLOG as VARCHAR) as VARIATION_FIELD_FOR_FILE_PLOG,
		cast(NUMBER_OF_INFOTYPE_RECORD_WITH_SAME_KEY as VARCHAR) as NUMBER_OF_INFOTYPE_RECORD_WITH_SAME_KEY,
		cast(INFOTYPE as VARCHAR) as INFOTYPE,
		cast(CONCATENATION_OF_OBJECT_TYPE_AND_OBJECT_ID as VARCHAR) as CONCATENATION_OF_OBJECT_TYPE_AND_OBJECT_ID,
		cast(SUBTYPE as VARCHAR) as SUBTYPE,
		cast(CHANGED_ON as DATE) as CHANGED_ON,
		cast(USER_NAME as VARCHAR) as USER_NAME,
		cast(REASON as VARCHAR) as REASON,
		cast(HISTORICAL_RECORD_FLAG as VARCHAR) as HISTORICAL_RECORD_FLAG,
		cast(TEXT_MODULE_FOR_INFOTYPE as VARCHAR) as TEXT_MODULE_FOR_INFOTYPE,
		cast(TYPE_OF_RELATED_OBJECT as VARCHAR) as TYPE_OF_RELATED_OBJECT,
		cast(ID_OF_RELATED_OBJECT as VARCHAR) as ID_OF_RELATED_OBJECT,
		cast(WEIGHTING_PERCENTAGE as NUMBER(38,10)) as WEIGHTING_PERCENTAGE,
		cast(ADATA_NUMBER as VARCHAR) as ADATA_NUMBER,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
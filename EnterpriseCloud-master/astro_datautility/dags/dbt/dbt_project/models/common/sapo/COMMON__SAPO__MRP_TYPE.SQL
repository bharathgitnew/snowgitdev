{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='MRP_TYPE',
        unique_key = ['CLIENT',
    'MRP_TYPE'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		DISMM as MRP_TYPE,
		DISVF as MRP_PROCEDURE,
		PROKZ as FORECAST_INDICATOR,
		PROVB as CONSUMPTION_INDICATOR_OF_FORECAST,
		PROOS as MRP_INDICATOR_OF_FORECAST,
		KZSIB as INDICATOR_CALCULATE_SAFETY_STOCK,
		KZMEB as INDICATOR_CALCULATE_REORDER_LEVEL,
		PRRED as REDUCE_FORECAST_REQUIREMENTS,
		FXART as FIRMING_TYPE_OF_THE_PLANNING_RESULT,
		RESPL as INDICATOR_DELETE_FIRM_PLANNED_ORDERS,
		KZREG as INDICATOR_PLAN_MATERIAL_REGULARLY,
		ICBED as REORDER_POINT_PLANNING_WITH_EXTERNAL_REQUIREMENTS,
		RYBED as TIME_PHASED_PLANNING_WITH_REQUIREMENTS_MRP,
		DYFOL as SCREEN_SEQUENCE_FOR_THE_HEADER_DETAILS,
		CBPPT as METHOD_BY_WHICH_A_MATERIAL_IS_PLANNED,
		BBBED as MATERIAL_STAGING_REQMTS_SUBCONTR_REQMTS_MRP_ELEMENT_BB,
		U1BED as RELEASE_FOR_STOCK_TRANSFER_ORDER,
		U2BED as DELIVERY_SCHEDULE_FOR_A_STOCK_TRANSFER_REQUISITION,
		U4BED as DELIVERY_SCHEDULE_FOR_STOCK_TRANSPORT_SCHEDULING_AGREEMENT,
		A1BED as DEPENDENT_RESERVATION_STANDARD_ORDERS,
		A2BED as DEPENDENT_RESERVATION_PLANT_MAINTENANCE_ORDERS_AND_NETWORK,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__MRP_TYPE') }}
),

transform_data as (
    select
        CLIENT,
		MRP_TYPE,
		MRP_PROCEDURE,
		FORECAST_INDICATOR,
		CONSUMPTION_INDICATOR_OF_FORECAST,
		MRP_INDICATOR_OF_FORECAST,
		INDICATOR_CALCULATE_SAFETY_STOCK,
		INDICATOR_CALCULATE_REORDER_LEVEL,
		REDUCE_FORECAST_REQUIREMENTS,
		FIRMING_TYPE_OF_THE_PLANNING_RESULT,
		INDICATOR_DELETE_FIRM_PLANNED_ORDERS,
		INDICATOR_PLAN_MATERIAL_REGULARLY,
		REORDER_POINT_PLANNING_WITH_EXTERNAL_REQUIREMENTS,
		TIME_PHASED_PLANNING_WITH_REQUIREMENTS_MRP,
		SCREEN_SEQUENCE_FOR_THE_HEADER_DETAILS,
		METHOD_BY_WHICH_A_MATERIAL_IS_PLANNED,
		MATERIAL_STAGING_REQMTS_SUBCONTR_REQMTS_MRP_ELEMENT_BB,
		RELEASE_FOR_STOCK_TRANSFER_ORDER,
		DELIVERY_SCHEDULE_FOR_A_STOCK_TRANSFER_REQUISITION,
		DELIVERY_SCHEDULE_FOR_STOCK_TRANSPORT_SCHEDULING_AGREEMENT,
		DEPENDENT_RESERVATION_STANDARD_ORDERS,
		DEPENDENT_RESERVATION_PLANT_MAINTENANCE_ORDERS_AND_NETWORK,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(MRP_TYPE as VARCHAR) as MRP_TYPE,
		cast(MRP_PROCEDURE as VARCHAR) as MRP_PROCEDURE,
		cast(FORECAST_INDICATOR as VARCHAR) as FORECAST_INDICATOR,
		cast(CONSUMPTION_INDICATOR_OF_FORECAST as VARCHAR) as CONSUMPTION_INDICATOR_OF_FORECAST,
		cast(MRP_INDICATOR_OF_FORECAST as VARCHAR) as MRP_INDICATOR_OF_FORECAST,
		cast(INDICATOR_CALCULATE_SAFETY_STOCK as VARCHAR) as INDICATOR_CALCULATE_SAFETY_STOCK,
		cast(INDICATOR_CALCULATE_REORDER_LEVEL as VARCHAR) as INDICATOR_CALCULATE_REORDER_LEVEL,
		cast(REDUCE_FORECAST_REQUIREMENTS as VARCHAR) as REDUCE_FORECAST_REQUIREMENTS,
		cast(FIRMING_TYPE_OF_THE_PLANNING_RESULT as VARCHAR) as FIRMING_TYPE_OF_THE_PLANNING_RESULT,
		cast(INDICATOR_DELETE_FIRM_PLANNED_ORDERS as VARCHAR) as INDICATOR_DELETE_FIRM_PLANNED_ORDERS,
		cast(INDICATOR_PLAN_MATERIAL_REGULARLY as VARCHAR) as INDICATOR_PLAN_MATERIAL_REGULARLY,
		cast(REORDER_POINT_PLANNING_WITH_EXTERNAL_REQUIREMENTS as VARCHAR) as REORDER_POINT_PLANNING_WITH_EXTERNAL_REQUIREMENTS,
		cast(TIME_PHASED_PLANNING_WITH_REQUIREMENTS_MRP as VARCHAR) as TIME_PHASED_PLANNING_WITH_REQUIREMENTS_MRP,
		cast(SCREEN_SEQUENCE_FOR_THE_HEADER_DETAILS as VARCHAR) as SCREEN_SEQUENCE_FOR_THE_HEADER_DETAILS,
		cast(METHOD_BY_WHICH_A_MATERIAL_IS_PLANNED as VARCHAR) as METHOD_BY_WHICH_A_MATERIAL_IS_PLANNED,
		cast(MATERIAL_STAGING_REQMTS_SUBCONTR_REQMTS_MRP_ELEMENT_BB as VARCHAR) as MATERIAL_STAGING_REQMTS_SUBCONTR_REQMTS_MRP_ELEMENT_BB,
		cast(RELEASE_FOR_STOCK_TRANSFER_ORDER as VARCHAR) as RELEASE_FOR_STOCK_TRANSFER_ORDER,
		cast(DELIVERY_SCHEDULE_FOR_A_STOCK_TRANSFER_REQUISITION as VARCHAR) as DELIVERY_SCHEDULE_FOR_A_STOCK_TRANSFER_REQUISITION,
		cast(DELIVERY_SCHEDULE_FOR_STOCK_TRANSPORT_SCHEDULING_AGREEMENT as VARCHAR) as DELIVERY_SCHEDULE_FOR_STOCK_TRANSPORT_SCHEDULING_AGREEMENT,
		cast(DEPENDENT_RESERVATION_STANDARD_ORDERS as VARCHAR) as DEPENDENT_RESERVATION_STANDARD_ORDERS,
		cast(DEPENDENT_RESERVATION_PLANT_MAINTENANCE_ORDERS_AND_NETWORK as VARCHAR) as DEPENDENT_RESERVATION_PLANT_MAINTENANCE_ORDERS_AND_NETWORK,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)
select * from type_data
{{ config(
        materialized='incremental',
        incremental_strategy='merge',
        alias='VALUATION_AREA',
        unique_key = ['CLIENT',
    'VALUATION_AREA'],
        transient=false
) }}

with source_data as (
    select
        MANDT as CLIENT,
		BWKEY as VALUATION_AREA,
		BUKRS as COMPANY_CODE,
		BWMOD as VALUATION_GROUPING_CODE,
		XBKNG as NEGATIVE_STOCKS_IN_VALUATION_AREA_ALLOWED,
		MLBWA as MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA,
		MLBWV as MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA_COMPULSORY,
		XVKBW as SALES_PRICE_VALUATION_ACTIVE,
		ERKLAERKOM as EXPLANATION_FACILITY_FOR_MATERIAL_LEDGER_ACTIVEINACTIVE,
		UPROF as RETAIL_REVALUTION_PROFILE,
		WBPRO as PROFILE_FOR_VALUE_BASED_INVENTORY_MANAGEMENT,
		MLAST as MATERIAL_PRICE_DETERMINATION_CONTROL,
		MLASV as PRICE_DETERMINATION_IS_BINDING_IN_VALUATION_AREA,
		BDIFP as STOCK_CORRECTION_TOLERANCE,
		XLBPD as PRICE_DIFFERENCE_POSTING_IN_GR_FOR_SUBCONTRACT_ODER,
		XEWRX as POST_PURCHASE_ACCOUNT_WITH_RECEIPT_VALUE,
		X2FDO as TWO_FI_DOCUMENTS_WITH_PURCHASE_ACCOUNT,
		PRSFR as PRICE_RELEASE,
		MLCCS as ACTIVE_ACTUAL_COST_COMPONENT_SPLIT,
		XEFRE as DEL_COSTS_TO_PRICE_DIFF_ACCT_WHEN_PURCH_ACCT_ACTIVE,
		EFREJ as START_OF_VALIDITY_PERIOD_F_DEL_COSTS_IN_PRICE_DIFF_ACCT,
		FMP_PRSFR as PRICE_RELEASE_FLEXIBLE_MATERIAL_PRICES,
		FMP_PRFRGR as PRICE_RELEASE_GROUP,
		_CAPTUREDATETIME
    from {{ ref('ODS__SAPO__VALUATION_AREA') }}
),

transform_data as (
    select
        CLIENT,
		VALUATION_AREA,
		COMPANY_CODE,
		VALUATION_GROUPING_CODE,
		NEGATIVE_STOCKS_IN_VALUATION_AREA_ALLOWED,
		MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA,
		MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA_COMPULSORY,
		SALES_PRICE_VALUATION_ACTIVE,
		EXPLANATION_FACILITY_FOR_MATERIAL_LEDGER_ACTIVEINACTIVE,
		RETAIL_REVALUTION_PROFILE,
		PROFILE_FOR_VALUE_BASED_INVENTORY_MANAGEMENT,
		MATERIAL_PRICE_DETERMINATION_CONTROL,
		PRICE_DETERMINATION_IS_BINDING_IN_VALUATION_AREA,
		STOCK_CORRECTION_TOLERANCE,
		PRICE_DIFFERENCE_POSTING_IN_GR_FOR_SUBCONTRACT_ODER,
		POST_PURCHASE_ACCOUNT_WITH_RECEIPT_VALUE,
		TWO_FI_DOCUMENTS_WITH_PURCHASE_ACCOUNT,
		PRICE_RELEASE,
		ACTIVE_ACTUAL_COST_COMPONENT_SPLIT,
		DEL_COSTS_TO_PRICE_DIFF_ACCT_WHEN_PURCH_ACCT_ACTIVE,
		START_OF_VALIDITY_PERIOD_F_DEL_COSTS_IN_PRICE_DIFF_ACCT,
		PRICE_RELEASE_FLEXIBLE_MATERIAL_PRICES,
		PRICE_RELEASE_GROUP,
		_CAPTUREDATETIME,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') as _ROW_HASH
    from source_data
),

type_data as (
    select
        cast(CLIENT as VARCHAR) as CLIENT,
		cast(VALUATION_AREA as VARCHAR) as VALUATION_AREA,
		cast(COMPANY_CODE as VARCHAR) as COMPANY_CODE,
		cast(VALUATION_GROUPING_CODE as VARCHAR) as VALUATION_GROUPING_CODE,
		cast(NEGATIVE_STOCKS_IN_VALUATION_AREA_ALLOWED as VARCHAR) as NEGATIVE_STOCKS_IN_VALUATION_AREA_ALLOWED,
		cast(MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA as VARCHAR) as MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA,
		cast(MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA_COMPULSORY as VARCHAR) as MATERIAL_LEDGER_ACTIVATED_IN_VALUATION_AREA_COMPULSORY,
		cast(SALES_PRICE_VALUATION_ACTIVE as VARCHAR) as SALES_PRICE_VALUATION_ACTIVE,
		cast(EXPLANATION_FACILITY_FOR_MATERIAL_LEDGER_ACTIVEINACTIVE as VARCHAR) as EXPLANATION_FACILITY_FOR_MATERIAL_LEDGER_ACTIVEINACTIVE,
		cast(RETAIL_REVALUTION_PROFILE as VARCHAR) as RETAIL_REVALUTION_PROFILE,
		cast(PROFILE_FOR_VALUE_BASED_INVENTORY_MANAGEMENT as VARCHAR) as PROFILE_FOR_VALUE_BASED_INVENTORY_MANAGEMENT,
		cast(MATERIAL_PRICE_DETERMINATION_CONTROL as VARCHAR) as MATERIAL_PRICE_DETERMINATION_CONTROL,
		cast(PRICE_DETERMINATION_IS_BINDING_IN_VALUATION_AREA as VARCHAR) as PRICE_DETERMINATION_IS_BINDING_IN_VALUATION_AREA,
		cast(STOCK_CORRECTION_TOLERANCE as NUMBER(38,10)) as STOCK_CORRECTION_TOLERANCE,
		cast(PRICE_DIFFERENCE_POSTING_IN_GR_FOR_SUBCONTRACT_ODER as VARCHAR) as PRICE_DIFFERENCE_POSTING_IN_GR_FOR_SUBCONTRACT_ODER,
		cast(POST_PURCHASE_ACCOUNT_WITH_RECEIPT_VALUE as VARCHAR) as POST_PURCHASE_ACCOUNT_WITH_RECEIPT_VALUE,
		cast(TWO_FI_DOCUMENTS_WITH_PURCHASE_ACCOUNT as VARCHAR) as TWO_FI_DOCUMENTS_WITH_PURCHASE_ACCOUNT,
		cast(PRICE_RELEASE as VARCHAR) as PRICE_RELEASE,
		cast(ACTIVE_ACTUAL_COST_COMPONENT_SPLIT as VARCHAR) as ACTIVE_ACTUAL_COST_COMPONENT_SPLIT,
		cast(DEL_COSTS_TO_PRICE_DIFF_ACCT_WHEN_PURCH_ACCT_ACTIVE as VARCHAR) as DEL_COSTS_TO_PRICE_DIFF_ACCT_WHEN_PURCH_ACCT_ACTIVE,
		cast(START_OF_VALIDITY_PERIOD_F_DEL_COSTS_IN_PRICE_DIFF_ACCT as VARCHAR) as START_OF_VALIDITY_PERIOD_F_DEL_COSTS_IN_PRICE_DIFF_ACCT,
		cast(PRICE_RELEASE_FLEXIBLE_MATERIAL_PRICES as VARCHAR) as PRICE_RELEASE_FLEXIBLE_MATERIAL_PRICES,
		cast(PRICE_RELEASE_GROUP as VARCHAR) as PRICE_RELEASE_GROUP,
		cast(_CAPTUREDATETIME as TIMESTAMP_LTZ(9)) as _CAPTUREDATETIME,
		cast(AUDIT_LOG_ID as varchar(128)) as AUDIT_LOG_ID,
		cast(_ROW_HASH as varchar(128)) as _ROW_HASH
    from transform_data
)

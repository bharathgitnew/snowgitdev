    	materialized='incremental',
    	incremental_strategy='insert_overwrite',
    	alias='DW_SMBWA',
    	transient=false
) }}

with source_data as (
    SELECT
        ANSWER,
        BU_CODE,
        COMMENT,
        CUSTOMER,
        CUSTOMER_ID,
        FAB,
        FAB_ID,
        GOOD_CATCH,
        INCIDENT_ADDRESS,
        INCIDENT_CLASSIFICATION,
        INCIDENT_REPORT_DATETIME,
        INCIDENT_STATUS,
        LOCATION_DESCRIPTION,
        LOCATION_TYPE,
        OTHER_LOCATION_TYPE,
        PERSON_CLASSIFICATION,
        PERSON_FUNCTION,
        PERSON_SUBSIDIARY,
        QMBWW_AUDITED,
        QMBWW_TITLE,
        QUESTION,
        QUESTION_NUMBER,
        REGIONAL_OFFICE,
        REPORT_NUMBER,
        SUBMITTER,
        SUBMITTER_EMAIL,
        SUBMITTER_EMPLOYEEID,
        SUPERVISOR_EMAILADDRESS,
        SUPERVISOR_NAME,
        TEL_SUBSIDIARY
	FROM {{ ref('ODS__CSDPRO__DW_SMBWA') }}
),

transform_data as (
    SELECT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH,
        ANSWER,
        BU_CODE,
        COMMENT,
        CUSTOMER,
        CUSTOMER_ID,
        FAB,
        FAB_ID,
        GOOD_CATCH,
        INCIDENT_ADDRESS,
        INCIDENT_CLASSIFICATION,
        INCIDENT_REPORT_DATETIME,
        INCIDENT_STATUS,
        LOCATION_DESCRIPTION,
        LOCATION_TYPE,
        OTHER_LOCATION_TYPE,
        PERSON_CLASSIFICATION,
        PERSON_FUNCTION,
        PERSON_SUBSIDIARY,
        QMBWW_AUDITED,
        QMBWW_TITLE,
        QUESTION,
        QUESTION_NUMBER,
        REGIONAL_OFFICE,
        REPORT_NUMBER,
        SUBMITTER,
        SUBMITTER_EMAIL,
        SUBMITTER_EMPLOYEEID,
        SUPERVISOR_EMAILADDRESS,
        SUPERVISOR_NAME,
        TEL_SUBSIDIARY
	FROM source_data
),

type_data as (
    SELECT
        CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
        ANSWER,
        BU_CODE,
        COMMENT,
        CUSTOMER,
        CUSTOMER_ID,
        FAB,
        FAB_ID,
        GOOD_CATCH,
        INCIDENT_ADDRESS,
        INCIDENT_CLASSIFICATION,
        CAST(INCIDENT_REPORT_DATETIME AS DATE) AS INCIDENT_REPORT_DATETIME,
        INCIDENT_STATUS,
        LOCATION_DESCRIPTION,
        LOCATION_TYPE,
        OTHER_LOCATION_TYPE,
        PERSON_CLASSIFICATION,
        PERSON_FUNCTION,
        PERSON_SUBSIDIARY,
        QMBWW_AUDITED,
        QMBWW_TITLE,
        QUESTION,
        QUESTION_NUMBER,
        REGIONAL_OFFICE,
        REPORT_NUMBER,
        SUBMITTER,
        SUBMITTER_EMAIL,
        SUBMITTER_EMPLOYEEID,
        SUPERVISOR_EMAILADDRESS,
        SUPERVISOR_NAME,
        TEL_SUBSIDIARY
	FROM transform_data
)

select * from type_data
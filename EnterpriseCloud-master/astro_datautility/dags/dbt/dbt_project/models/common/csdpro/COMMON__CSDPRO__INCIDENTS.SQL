transform_data as (
	SELECT 
		i.INCIDENT_ID, 
		i.INCIDENT_ID + 10000 AS REPORT_NUMBER, 
		TO_NUMBER(TO_VARCHAR(TO_DATE(i.INCIDENT_REPORT_DATETIME),'YYYYMMDD')) AS INCIDENT_REPORT_DATE_KEY,  
		p.EMPLOYEE_NUMBER AS SUBMITTER_EMPLOYEE_ID,  
		pc.DESCRIPTION AS PERSON_CLASSIFICATION, 
		pf.DESCRIPTION AS PERSON_FUNCTION, 
		CASE i.GOOD_CATCH WHEN '1' THEN 'Yes' WHEN '2' THEN 'No' ELSE 'Not Answered' END AS GOOD_CATCH, 
		b.BUCODE AS BU_CODE, 
		lt.DESCRIPTION AS LOCATION_TYPE, 
		NULLIF(i.OTHER_LOCATION_TYPE,'') AS OTHER_LOCATION_TYPE,
		ld.DESCRIPTION AS LOCATION_DESCRIPTION, 
		NULLIF(i.OTHER_LOCATION_DESCRIPTION,'') AS OTHER_LOCATION_DESCRIPTION,
		ts.ABBREVIATION AS TEL_SUBSIDIARY,
		ps.ABBREVIATION AS PERSON_SUBSIDIARY, 
		o.DESCRIPTION AS REGIONAL_OFFICE, 
		c.NAME AS CUSTOMER, 
		f.NAME AS FAB,
		ic.DESCRIPTION AS INCIDENT_CLASSIFICATION,
		ist.DESCRIPTION AS INCIDENT_STATUS, 
		CASE i.QMBWW_BEING_AUDITED WHEN '1' THEN 'Yes' ELSE 'No' END AS QMBWW_AUDITED, 
		NULLIF(i.QMBWW_AUDIT_TASK_TITLE,'') AS QMBWW_TITLE, 
		CONCAT(RTRIM(i.INCIDENT_ADDRESS),', ',RTRIM(i.INCIDENT_CITY),', ',RTRIM(i.INCIDENT_STATE_PROVINCE),', ',RTRIM(i.INCIDENT_POSTAL_CODE)) AS INCIDENT_ADDRESS,  
		CONCAT(NULLIF(i.SUPERVISOR_LAST_NAME,'')||', '||NULLIF(i.SUPERVISOR_FIRST_NAME,'')) AS RESPONSIBLE_SUPERVISOR_NAME,
		i.SUPERVISOR_EMAIL_ADDRESS AS RESPONSIBLE_SUPERVISOR_EMAIL, 
		i.INCIDENT_REPORT_DATETIME, 
		CONCAT('http://tehaus0124:8070/safetyapp/faces/jsp/safetyIncident/goto_incident_summary.jsp?incidentID=', i.INCIDENT_ID) AS REPORT_URL, 
		i.INCIDENT_CLASSIFICATION_ID,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
		SHA2('hash_me') AS _ROW_HASH -- Adds column to table on full refresh.
	FROM source_data_incidents i  
		JOIN source_data_status_history sh ON i.INCIDENT_ID = sh.INCIDENT_ID AND sh.IS_CURRENT_STATUS=1 
		JOIN source_data_incident_status ist ON sh.INCIDENT_STATUS_ID = ist.INCIDENT_STATUS_ID 
		JOIN source_data_person p ON i.PERSON_ID = p.PERSON_ID 
		JOIN source_data_incident_classification ic ON i.INCIDENT_CLASSIFICATION_ID = ic.INCIDENT_CLASSIFICATION_ID
		LEFT OUTER JOIN source_data_tel_subsidiary ts ON i.INCIDENT_TEL_SUBSIDIARY_ID = ts.TEL_SUBSIDIARY_ID 
		LEFT OUTER JOIN source_data_tel_subsidiary ps ON i.VICTIM_TEL_SUBSIDIARY_ID = ps.TEL_SUBSIDIARY_ID
		LEFT OUTER JOIN source_data_baan_bp c ON i.BAAN_BP_ID = c.BAAN_BP_ID 
		LEFT OUTER JOIN source_data_baan_fab f ON i.BAAN_FAB_ID = f.BAAN_FAB_ID
		LEFT OUTER JOIN source_data_bu b ON i.BU_ID = b.BU_ID
		LEFT OUTER JOIN source_data_person_classification pc ON i.PERSON_CLASSIFICATION_ID = pc.PERSON_CLASSIFICATION_ID
		LEFT OUTER JOIN source_data_person_function pf ON i.PERSON_FUNCTION_ID = pf.PERSON_FUNCTION_ID
		LEFT OUTER JOIN source_data_location_type lt ON i.LOCATION_TYPE_ID = lt.LOCATION_TYPE_ID
		LEFT OUTER JOIN source_data_location_description ld ON i.LOCATION_DESCRIPTION_ID = ld.LOCATION_DESCRIPTION_ID
		LEFT OUTER JOIN source_data_location_tel_office o ON i.TEL_OFFICE_ID = o.TEL_OFFICE_ID 
), 

type_data as (
	SELECT
		CAST(INCIDENT_ID AS NUMBER(38,0)) AS INCIDENT_ID,
		CAST(REPORT_NUMBER AS NUMBER(38,0)) AS REPORT_NUMBER,
		CAST(INCIDENT_REPORT_DATE_KEY AS NUMBER(38,0)) AS INCIDENT_REPORT_DATE_KEY,
		CAST(SUBMITTER_EMPLOYEE_ID AS VARCHAR(16777216)) AS SUBMITTER_EMPLOYEE_ID,  
		CAST(PERSON_CLASSIFICATION AS VARCHAR(16777216)) AS PERSON_CLASSIFICATION, 
		CAST(PERSON_FUNCTION AS VARCHAR(16777216)) AS PERSON_FUNCTION, 
		CAST(GOOD_CATCH AS VARCHAR(16777216)) AS GOOD_CATCH, 
		CAST(BU_CODE AS VARCHAR(16777216)) AS BU_CODE, 
		CAST(LOCATION_TYPE AS VARCHAR(16777216)) AS LOCATION_TYPE, 
		CAST(OTHER_LOCATION_TYPE AS VARCHAR(16777216)) AS OTHER_LOCATION_TYPE, 
		CAST(LOCATION_DESCRIPTION AS VARCHAR(16777216)) AS LOCATION_DESCRIPTION, 
		CAST(OTHER_LOCATION_DESCRIPTION AS VARCHAR(16777216)) AS OTHER_LOCATION_DESCRIPTION, 
		CAST(TEL_SUBSIDIARY AS VARCHAR(16777216)) AS TEL_SUBSIDIARY,
		CAST(PERSON_SUBSIDIARY AS VARCHAR(16777216)) AS PERSON_SUBSIDIARY, 
		CAST(REGIONAL_OFFICE AS VARCHAR(16777216)) AS REGIONAL_OFFICE, 
		CAST(CUSTOMER AS VARCHAR(16777216)) AS CUSTOMER, 
		CAST(FAB AS VARCHAR(16777216)) AS FAB,
		CAST(INCIDENT_CLASSIFICATION AS VARCHAR(16777216)) AS INCIDENT_CLASSIFICATION,
		CAST(INCIDENT_STATUS AS VARCHAR(16777216)) AS INCIDENT_STATUS,
		CAST(QMBWW_AUDITED AS VARCHAR(16777216)) AS QMBWW_AUDITED, 
		CAST(QMBWW_TITLE AS VARCHAR(16777216)) AS QMBWW_TITLE,
		CAST(INCIDENT_ADDRESS AS VARCHAR(16777216)) AS INCIDENT_ADDRESS, 
		CAST(RESPONSIBLE_SUPERVISOR_NAME AS VARCHAR(16777216)) AS RESPONSIBLE_SUPERVISOR_NAME,
		CAST(RESPONSIBLE_SUPERVISOR_EMAIL AS VARCHAR(16777216)) AS RESPONSIBLE_SUPERVISOR_EMAIL,
		CAST(INCIDENT_REPORT_DATETIME AS TIMESTAMP_LTZ(9)) AS INCIDENT_REPORT_DATETIME, 
		CAST(REPORT_URL AS VARCHAR(16777216)) AS REPORT_URL, 
		CAST(INCIDENT_CLASSIFICATION_ID AS NUMBER(38,0)) AS INCIDENT_CLASSIFICATION_ID,
		CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
		CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
	FROM transform_data

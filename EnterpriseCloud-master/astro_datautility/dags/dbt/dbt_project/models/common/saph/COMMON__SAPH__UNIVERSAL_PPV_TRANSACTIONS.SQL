WITH ACDOCA AS (
SELECT  
    COMPANY_CODE,
    FISCAL_YEAR,
    POSTING_PERIOD,
    LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    ACCOUNTING_DOCUMENT_NUMBER,
    SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    TO_DATE(POSTING_DATE_IN_THE_DOCUMENT,'YYYYMMDD') AS POSTING_DATE,
    TO_DATE(DATE.YEAR_MONTH_TEXT,'YYYY-MM') AS YEAR_MONTH_TEXT,
    DOCUMENT_TYPE,
    BUSINESS_TRANSACTION_TYPE,
    ACCOUNT_NUMBER,
    MATERIAL_NUMBER,
    WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_POSID,
    COST_CENTER,
    AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT
FROM {{ ref('COMMON__SAPH_NEW_ACDOCA__UNIVERSAL_JOURNAL_ENTRY_LINE') }}
LEFT JOIN {{ source('EDW__DE', 'D_DATE') }} DATE
ON TO_DATE(POSTING_DATE_IN_THE_DOCUMENT,'YYYYMMDD')=DATE.CALENDAR_DATE
WHERE 
    DOCUMENT_TYPE='ML'
    AND COMPANY_CODE='3200'
    AND LEFT(ACCOUNT_NUMBER,1)='5'
    AND LEDGER_IN_GENERAL_LEDGER_ACCOUNTING='0L'
    AND WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR<>'00000000'
)
,BSEG AS (
SELECT  
    BUKRS AS COMPANY_CODE,
    GJAHR AS FISCAL_YEAR,
    GJAHR AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    BELNR AS ACCOUNTING_DOCUMENT_NUMBER,
    BUZEI AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    TO_DATE(H_BUDAT,'YYYYMMDD') AS POSTING_DATE,
    TO_DATE(DATE.YEAR_MONTH_TEXT,'YYYY-MM') AS YEAR_MONTH_TEXT,
    VBEL2 AS SALES_DOCUMENT,
    POSN2 AS SALES_DOCUMENT_ITEM,
    H_BLART AS DOCUMENT_TYPE,
    MATNR AS MATERIAL_NUMBER,
    UJEL.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    MENGE AS QUANTITY
FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU038_BSEG') }} BSEG
LEFT JOIN {{ ref('COMMON__SAPH_NEW_ACDOCA__UNIVERSAL_JOURNAL_ENTRY_LINE') }} UJEL
        ON try_to_number(UJEL.COMPANY_CODE) = try_to_number(BSEG.BUKRS)
        AND try_to_number(UJEL.ACCOUNTING_DOCUMENT_NUMBER) = try_to_number(BSEG.BELNR)
        AND try_to_number(UJEL.FISCAL_YEAR) = try_to_number(BSEG.GJAHR)
        AND try_to_number(UJEL.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER) = try_to_number(BSEG.BUZEI)
LEFT JOIN {{ source('EDW__DE', 'D_DATE') }} DATE
ON TO_DATE(H_BUDAT,'YYYYMMDD') =DATE.CALENDAR_DATE
WHERE 
    H_BLART<>'ML'
    AND KTOSL='GBB'
    AND BUKRS='3200'
    AND UJEL.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR<>'00000000'
)
,SOURCE AS (
SELECT 
    ACDOCA.COMPANY_CODE,
    ACDOCA.FISCAL_YEAR,
    ACDOCA.POSTING_PERIOD,
    ACDOCA.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    ACDOCA.ACCOUNTING_DOCUMENT_NUMBER||'_'||ACDOCA.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS ACCOUNTING_DOCUMENT_LINE,
    ACDOCA.ACCOUNTING_DOCUMENT_NUMBER,
    ACDOCA.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    ACDOCA.POSTING_DATE,
    ACDOCA.YEAR_MONTH_TEXT,
    ACDOCA.DOCUMENT_TYPE,
    ACDOCA.BUSINESS_TRANSACTION_TYPE,
    ACDOCA.ACCOUNT_NUMBER,
    ACDOCA.MATERIAL_NUMBER,
    ACDOCA.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    ACDOCA.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_POSID,
    ACDOCA.COST_CENTER,
    TO_NUMBER(BSEG.SALES_DOCUMENT) AS SALES_DOCUMENT,
    TO_NUMBER(BSEG.SALES_DOCUMENT_ITEM) AS SALES_DOCUMENT_ITEM ,
    CASE WHEN COST_CENTER<>'' THEN '98' ELSE SO.VBAP_SALES_CATEGORY END AS SALES_CATEGORY,
    TO_NUMBER(BSEG.QUANTITY) AS QUANTITY,
    ACDOCA.AMOUNT
FROM ACDOCA
LEFT JOIN BSEG 
    ON ACDOCA.MATERIAL_NUMBER=BSEG.MATERIAL_NUMBER
    AND ACDOCA.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR=BSEG.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR
    AND ACDOCA.YEAR_MONTH_TEXT=BSEG.YEAR_MONTH_TEXT
LEFT JOIN COMMON.SAPH.SALES_ORDER AS SO
    ON BSEG.SALES_DOCUMENT=SO.VBAP_SALES_DOCUMENT
    AND BSEG.SALES_DOCUMENT_ITEM=SO.SALES_DOCUMENT_ITEM_POSNR
)
,CASE_TEST AS (
SELECT 
    ACCOUNTING_DOCUMENT_NUMBER||'_'||SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS ACCOUNTING_DOCUMENT_LINE,
    MATERIAL_NUMBER,
    WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    YEAR_MONTH_TEXT,
    QUANTITY,
    COUNT(ACCOUNTING_DOCUMENT_LINE) AS KEY_COUNT,
    CASE WHEN KEY_COUNT>1 THEN '2' ELSE '1' END AS TEST
FROM SOURCE 
GROUP BY 
    ACCOUNTING_DOCUMENT_NUMBER,
    SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    MATERIAL_NUMBER,
    WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    YEAR_MONTH_TEXT,
    QUANTITY
QUALIFY (ROW_NUMBER() OVER (PARTITION BY SOURCE.ACCOUNTING_DOCUMENT_NUMBER,SOURCE.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,SOURCE.YEAR_MONTH_TEXT ORDER BY TEST ASC))=1
)
,CASE_1 AS (
SELECT 
    SOURCE.COMPANY_CODE,
    SOURCE.FISCAL_YEAR,
    SOURCE.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    SOURCE.ACCOUNTING_DOCUMENT_NUMBER,
    SOURCE.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    SOURCE.ACCOUNTING_DOCUMENT_LINE,
    SOURCE.MATERIAL_NUMBER,
    SOURCE.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    SOURCE.BUSINESS_TRANSACTION_TYPE AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
    SOURCE.ACCOUNT_NUMBER,
    SOURCE.YEAR_MONTH_TEXT,
    SOURCE.SALES_DOCUMENT,
    SOURCE.SALES_DOCUMENT_ITEM,
    SOURCE.SALES_CATEGORY,
    SOURCE.AMOUNT,
    CASE_TEST.TEST
FROM SOURCE
LEFT JOIN CASE_TEST 
    ON SOURCE.ACCOUNTING_DOCUMENT_LINE=CASE_TEST.ACCOUNTING_DOCUMENT_LINE
WHERE CASE_TEST.TEST='1'
QUALIFY (ROW_NUMBER() OVER (PARTITION BY SOURCE.ACCOUNTING_DOCUMENT_LINE,SOURCE.YEAR_MONTH_TEXT ORDER BY SOURCE.QUANTITY DESC))=1
)
,CASE_2 AS (
SELECT
    SOURCE.COMPANY_CODE,
    SOURCE.FISCAL_YEAR,
    SOURCE.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING, 
    SOURCE.ACCOUNTING_DOCUMENT_NUMBER,
    SOURCE.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    SOURCE.ACCOUNTING_DOCUMENT_LINE,
    SOURCE.MATERIAL_NUMBER,
    SOURCE.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    SOURCE.BUSINESS_TRANSACTION_TYPE AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
    SOURCE.ACCOUNT_NUMBER,
    SOURCE.YEAR_MONTH_TEXT,
    SOURCE.SALES_DOCUMENT,
    SOURCE.SALES_DOCUMENT_ITEM,
    SOURCE.SALES_CATEGORY,
    SOURCE.AMOUNT,
    CASE_TEST.TEST
FROM SOURCE
LEFT JOIN CASE_TEST 
    ON SOURCE.ACCOUNTING_DOCUMENT_LINE=CASE_TEST.ACCOUNTING_DOCUMENT_LINE
WHERE CASE_TEST.TEST='2'
QUALIFY (ROW_NUMBER() OVER (PARTITION BY SOURCE.ACCOUNTING_DOCUMENT_LINE,SOURCE.YEAR_MONTH_TEXT ORDER BY SOURCE.SALES_DOCUMENT,SOURCE.SALES_DOCUMENT_ITEM ASC))=1
)
,FINAL AS (
SELECT 
    COMPANY_CODE,
    FISCAL_YEAR,
    LEDGER_IN_GENERAL_LEDGER_ACCOUNTING, 
    ACCOUNTING_DOCUMENT_NUMBER,
    SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    ACCOUNTING_DOCUMENT_LINE,
    MATERIAL_NUMBER,
    WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    ACDOCA_BUSINESS_TRANSACTION_TYPE,
    ACCOUNT_NUMBER,
    YEAR_MONTH_TEXT,
    SALES_DOCUMENT,
    SALES_DOCUMENT_ITEM,
    SALES_CATEGORY,
    AMOUNT,
    TEST
FROM CASE_1
UNION ALL
SELECT 
    COMPANY_CODE,
    FISCAL_YEAR,
    LEDGER_IN_GENERAL_LEDGER_ACCOUNTING, 
    ACCOUNTING_DOCUMENT_NUMBER,
    SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    ACCOUNTING_DOCUMENT_LINE,
    MATERIAL_NUMBER,
    WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    ACDOCA_BUSINESS_TRANSACTION_TYPE,
    ACCOUNT_NUMBER,
    YEAR_MONTH_TEXT,
    SALES_DOCUMENT,
    SALES_DOCUMENT_ITEM,
    SALES_CATEGORY,
    AMOUNT,
    TEST
FROM CASE_2
)
,CASE_ORDER AS (
SELECT 
    COMPANY_CODE,
    FISCAL_YEAR,
    LEDGER_IN_GENERAL_LEDGER_ACCOUNTING, 
    ACCOUNTING_DOCUMENT_NUMBER,
    SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    ACCOUNTING_DOCUMENT_LINE,
    MATERIAL_NUMBER,
    WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
    ACDOCA_BUSINESS_TRANSACTION_TYPE,
    ACCOUNT_NUMBER,
    YEAR_MONTH_TEXT,
    SALES_DOCUMENT,
    SALES_DOCUMENT_ITEM,
    SALES_CATEGORY,
    AMOUNT,
    TEST
FROM FINAL
QUALIFY (ROW_NUMBER() OVER (PARTITION BY ACCOUNTING_DOCUMENT_LINE,YEAR_MONTH_TEXT ORDER BY TEST ASC))=1
)
,transform_data as
(
SELECT
    COMPANY_CODE,
    FISCAL_YEAR,
    ACCOUNTING_DOCUMENT_NUMBER,
    SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    NULL AS PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
    NULL AS WBS_ELEMENT_SHORT_IDENTIFICATION,
    ACDOCA_BUSINESS_TRANSACTION_TYPE,
    LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    NULL AS NAME_1,
    ACCOUNT_NUMBER,
    SALES_CATEGORY,
    SALES_DOCUMENT,
    SALES_DOCUMENT_ITEM,
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') as _ROW_HASH
FROM CASE_ORDER
),
type_data as
(
SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
    CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
    CAST(ACCOUNTING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS ACCOUNTING_DOCUMENT_NUMBER,
    CAST(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS VARCHAR(16777216)) AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
    CAST(PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR AS VARCHAR(16777216)) AS PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
    CAST(WBS_ELEMENT_SHORT_IDENTIFICATION AS VARCHAR(16777216)) AS WBS_ELEMENT_SHORT_IDENTIFICATION,
    CAST(ACDOCA_BUSINESS_TRANSACTION_TYPE AS VARCHAR(16777216)) AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
    CAST(LEDGER_IN_GENERAL_LEDGER_ACCOUNTING AS VARCHAR(16777216)) AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
    CAST(NAME_1 AS VARCHAR(16777216)) AS NAME_1,
    CAST(ACCOUNT_NUMBER AS VARCHAR(16777216)) AS ACCOUNT_NUMBER,
    CAST(SALES_CATEGORY AS VARCHAR(16777216)) AS SALES_CATEGORY,
    CAST(SALES_DOCUMENT AS VARCHAR(16777216)) AS SALES_DOCUMENT,
    CAST(SALES_DOCUMENT_ITEM AS VARCHAR(16777216)) AS SALES_DOCUMENT_ITEM
FROM transform_data
)

SELECT * from type_data
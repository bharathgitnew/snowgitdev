        alias = 'UNIVERSAL_INVENTORY_DIFFERENCE',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        tags=["finance"],
        transient = false
) }}


with vbap_cte as (
    select * from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }}
    where IS_DELETED = 'No'
),

universal_pl_data as
(
        SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        OBJECT_NUMBER,
        PURCHASING_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_PURCHASING_DOCUMENT,
        WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR,
        ITEM_NUMBER_IN_SALES_ORDER,
        SALES_ORDER_NUMBER,
        ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        REFERENCE_DOCUMENT_LINE_ITEM
    FROM {{ ref('COMMON__SAPH_NEW_ACDOCA__UNIVERSAL_PL_ACCOUNT_TYPE') }} -- General Ledger
    WHERE ACDOCA_BUSINESS_TRANSACTION_TYPE = 'RMWL'
),

Kdauf_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        vbap.zzorty AS SALES_CATEGORY,
        vbap.VBELN AS SALES_DOCUMENT,
        vbap.POSNR AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN vbap_cte  VBAP
            ON universal_pl_data.SALES_ORDER_NUMBER = VBAP.VBELN
            and universal_pl_data.ITEM_NUMBER_IN_SALES_ORDER = VBAP.POSNR
    WHERE SALES_ORDER_NUMBER is not null
),

No_Kdauf_data as (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        vbap.zzorty AS SALES_CATEGORY,
        vbap.VBELN AS SALES_DOCUMENT,
        vbap.POSNR AS SALES_DOCUMENT_ITEM
    FROM universal_pl_data
        JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU038_BSEG') }} BSEG
            ON try_to_number(universal_pl_data.COMPANY_CODE) = try_to_number(bseg.bukrs)
        AND try_to_number(universal_pl_data.ACCOUNTING_DOCUMENT_NUMBER) = try_to_number(bseg.belnr)
        AND try_to_number(universal_pl_data.FISCAL_YEAR) = try_to_number(bseg.gjahr)
        AND try_to_number(universal_pl_data.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER) = try_to_number(bseg.buzei)
        JOIN vbap_cte  VBAP
            ON BSEG.VBEL2 = VBAP.VBELN
            and BSEG.POSN2 = VBAP.POSNR
),
source_data as
(
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        SALES_CATEGORY,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM
    FROM Kdauf_data
    UNION
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        SALES_CATEGORY,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM
    FROM No_Kdauf_data
),
transform_data as
(
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        WBS_ELEMENT_SHORT_IDENTIFICATION,
        ACDOCA_BUSINESS_TRANSACTION_TYPE,
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        NAME_1,
        ACCOUNT_NUMBER,
        SALES_CATEGORY,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM source_data
),
type_data as
(
    SELECT
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(ACCOUNTING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS ACCOUNTING_DOCUMENT_NUMBER,
        CAST(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS VARCHAR(16777216)) AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        CAST(PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR AS VARCHAR(16777216)) AS PARTNER_WORK_BREAKDOWN_STRUCTURE_ELEMENT_PPS_PSP_PNR,
        CAST(WBS_ELEMENT_SHORT_IDENTIFICATION AS VARCHAR(16777216)) AS WBS_ELEMENT_SHORT_IDENTIFICATION,
        CAST(ACDOCA_BUSINESS_TRANSACTION_TYPE AS VARCHAR(16777216)) AS ACDOCA_BUSINESS_TRANSACTION_TYPE,
        CAST(LEDGER_IN_GENERAL_LEDGER_ACCOUNTING AS VARCHAR(16777216)) AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        CAST(NAME_1 AS VARCHAR(16777216)) AS NAME_1,
        CAST(ACCOUNT_NUMBER AS VARCHAR(16777216)) AS ACCOUNT_NUMBER,
        CAST(SALES_CATEGORY AS VARCHAR(16777216)) AS SALES_CATEGORY,
        CAST(SALES_DOCUMENT AS VARCHAR(16777216)) AS SALES_DOCUMENT,
        CAST(SALES_DOCUMENT_ITEM AS VARCHAR(16777216)) AS SALES_DOCUMENT_ITEM,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)

SELECT * from type_data
            alias = 'SERVICE_CONTRACT',
            materialized='incremental',
            incremental_strategy = 'insert_overwrite',
            transient = false    
) }}

WITH
DIM_CONTRACT AS (
    SELECT  
        CS.CNT_CONTRUCTNUMBER AS CONTRACT_NUMBER,
        MAX(AG.CNT_SOWNAME) AS CONTRACT_SOW_ID,
        MAX(AG.CNT_SOWNAMENAME) AS CONTRACT_SOW,
        MAX(CS.CNT_SUBJECT) AS CONTRACT_SUBJECT,
        MAX(CAST(CS.CNT_CONTRACTSTARTDATE AS DATE)) AS CONTRACT_START_DATE
    FROM {{ ref('ODS__CRM_FILE__CNT_CONTRACTSUMMARY') }} AS CS
    LEFT JOIN {{ ref('ODS__CRM_FILE__MSDYN_AGREEMENT') }} AS AG ON (
        CS.ID = AG.CNT_CONTRACTGROUP
    )
    WHERE CS.CNT_CONTRUCTNUMBER IS NOT NULL AND CS.CNT_REGIONNAME LIKE '%US%'
    GROUP BY CS.CNT_CONTRUCTNUMBER
)
SELECT 
    VBAK.VBELN AS SAP_SO_HDR,
    VBAP.POSNR AS SAP_SO_LINE,
    VBAK.KUNNR AS SOLD_TO_PARTY_CODE,
    KNA1.NAME1 AS SOLD_TO_PARTY_NAME,
    VBAK.ZZCNZZ AS CONTRACT_NUMBER,
    TO_DATE(VBAK.AUDAT, 'YYYYMMDD') AS SO_DOCUMENT_DATE,
    VBAK.BSTNK AS CUSTOMER_PO_NUMBER,
    VBAK.BSTDK AS CUSTOMER_PO_DATE,
    DC.CONTRACT_SUBJECT, 
    DC.CONTRACT_START_DATE,
    DC.CONTRACT_SOW_ID,
    DC.CONTRACT_SOW,
    VBAP.MATNR AS MATERIAL_CODE,
    MARA.MAKTX AS MATERIAL_DESC,
    VBAP.NETWR AS SO_NET_VALUE,
    VBAP.KWMENG AS SO_UNIT_QTY,
    VBAP.ZZPRCODE AS SO_PRODUCT_CODE,
    VBAK.WAERK AS SO_CURRENCY,
    CASE WHEN DC.CONTRACT_START_DATE > CURRENT_DATE() THEN TRUE ELSE FALSE END AS PENDING
FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} AS VBAK
JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP ON (VBAP.VBELN = VBAK.VBELN)
JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA ON (MARA.MATNR = VBAP.MATNR)
LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (KNA1.KUNNR = VBAK.KUNNR)
LEFT JOIN DIM_CONTRACT AS DC ON (DC.CONTRACT_NUMBER = VBAK.ZZCNZZ)
WHERE 
    NULLIF(VBAK.BSTNK, '') IS NOT NULL AND 
    VBAK.AUART = 'ZC11'
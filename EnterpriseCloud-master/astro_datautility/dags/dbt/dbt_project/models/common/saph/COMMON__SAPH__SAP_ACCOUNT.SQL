{{ config(
        materialized='incremental'    ,
    incremental_strategy='insert_overwrite'    ,
    alias='SAP_ACCOUNT'    
) }}

WITH SKA1 AS (
    SELECT
        KTOPL
        , SAKNR
        , ERDAT
        , ERNAM
        , XLOEV
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU114_SKA1') }}
)

, SKAT AS (
    SELECT
        SPRAS
        , SAKNR
        , TXT20
        , TXT50
        , MCOD1
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU121_SKAT') }}
)

, AGG_EXPENSE_SUB_ACCOUNTS AS (
    SELECT
        SUBSTRING(SAKNR,2,LEN(SAKNR)) AS SUBTOTAL_ACCOUNT_NUMBER
        , COUNT(*)
    FROM SKA1
    WHERE LEFT(SAKNR, 1) IN ('6', '7')
    GROUP BY SUBTOTAL_ACCOUNT_NUMBER
    HAVING COUNT(*) > 1
)

, LIST_EXPENSE_SUB_ACCOUNTS AS (
    SELECT
        SAKNR
        , LISTAGG(DISTINCT SAKNR, ', ') WITHIN GROUP (ORDER BY SAKNR) OVER (PARTITION BY SUBSTRING(SAKNR,2,LEN(SAKNR))) as EXPENSE_SUBTOTAL_ACCOUNTS
    FROM SKA1
    WHERE LEFT(SAKNR, 1) IN ('6', '7')
)

, SOURCE_DATA AS (
    SELECT
        SKA1.KTOPL AS CHART_OF_ACCOUNTS
        , SKA1.SAKNR AS ACCOUNT_NUMBER
        , SKAT.TXT20 AS ACCOUNT_SHORT_DESCRIPTION
        , SKAT.TXT50 AS ACCOUNT_LONG_DESCRIPTION
        , SKAT.MCOD1 AS ACCOUNT_LONG_DESCRIPTION_ALTERNATE
        , AGG_EXPENSE_SUB_ACCOUNTS.SUBTOTAL_ACCOUNT_NUMBER
        , LIST_EXPENSE_SUB_ACCOUNTS.EXPENSE_SUBTOTAL_ACCOUNTS
        , SKA1.ERDAT AS CREATED_ON
        , SKA1.ERNAM AS CREATED_BY
        , SKA1.XLOEV AS DELETE_FLAG
    FROM SKA1
        LEFT JOIN SKAT
            ON SKA1.SAKNR = SKAT.SAKNR
        LEFT JOIN AGG_EXPENSE_SUB_ACCOUNTS
            ON SUBSTRING(SKA1.SAKNR,2,LEN(SKA1.SAKNR)) = AGG_EXPENSE_SUB_ACCOUNTS.SUBTOTAL_ACCOUNT_NUMBER
            AND LEFT(SKA1.SAKNR, 1) IN ('6', '7')
        LEFT JOIN LIST_EXPENSE_SUB_ACCOUNTS
            ON SKA1.SAKNR = LIST_EXPENSE_SUB_ACCOUNTS.SAKNR
    WHERE 1=1
        AND SKA1.KTOPL = 'Z001'
        AND SKAT.SPRAS = 'EN'
)

, TRANSFORM_DATA AS (
    SELECT
		CHART_OF_ACCOUNTS
        , ACCOUNT_NUMBER
        , ACCOUNT_SHORT_DESCRIPTION
        , ACCOUNT_LONG_DESCRIPTION
        , ACCOUNT_LONG_DESCRIPTION_ALTERNATE
        , CASE
            WHEN SUBTOTAL_ACCOUNT_NUMBER IS NOT NULL THEN 'Y'
            ELSE 'N'
        END AS IS_EXPENSE_SUB_ACCOUNT
        , EXPENSE_SUBTOTAL_ACCOUNTS
        , TRY_TO_DATE(CREATED_ON, 'YYYYMMDD') AS CREATED_ON
        , CREATED_BY
        , DELETE_FLAG
        , '{{ invocation_id }}' AS AUDIT_LOG_ID
        , SHA2('hash_me') as _ROW_HASH
    FROM SOURCE_DATA
)

, TYPE_DATA AS (
    SELECT
        CAST(CHART_OF_ACCOUNTS AS VARCHAR(16777216)) AS CHART_OF_ACCOUNTS,
        CAST(ACCOUNT_NUMBER AS VARCHAR(16777216)) AS ACCOUNT_NUMBER,
        CAST(ACCOUNT_SHORT_DESCRIPTION AS VARCHAR(16777216)) AS ACCOUNT_SHORT_DESCRIPTION,
        CAST(ACCOUNT_LONG_DESCRIPTION AS VARCHAR(16777216)) AS ACCOUNT_LONG_DESCRIPTION,
        CAST(ACCOUNT_LONG_DESCRIPTION_ALTERNATE AS VARCHAR(16777216)) AS ACCOUNT_LONG_DESCRIPTION_ALTERNATE,
        CAST(IS_EXPENSE_SUB_ACCOUNT AS VARCHAR(16777216)) AS IS_EXPENSE_SUB_ACCOUNT,
        CAST(EXPENSE_SUBTOTAL_ACCOUNTS AS VARCHAR(16777216)) AS EXPENSE_SUBTOTAL_ACCOUNTS,
        CAST(CREATED_ON AS DATE) AS CREATED_ON,
        CAST(CREATED_BY AS VARCHAR(16777216)) AS CREATED_BY,
        CAST(DELETE_FLAG AS VARCHAR(16777216)) AS DELETE_FLAG,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
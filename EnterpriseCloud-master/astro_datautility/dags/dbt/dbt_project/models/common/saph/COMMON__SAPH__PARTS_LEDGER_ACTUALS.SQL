{{ config(
        alias = 'PARTS_LEDGER_ACTUALS',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with vbap_cte as (
    select * from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }}
    where IS_DELETED = 'No'
),

acdoca_data as (
    SELECT
        --START ACDOCA
        acdoca.RLDNR AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        acdoca.RBUKRS AS COMPANY_CODE,
        acdoca.GJAHR AS FISCAL_YEAR,
        acdoca.BELNR AS ACCOUNTING_DOCUMENT_NUMBER,
        acdoca.DOCLN AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        acdoca.AWREF AS ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        acdoca.AWITEM AS REFERENCE_DOCUMENT_LINE_ITEM,
        acdoca.HSL AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        acdoca.ZUONR AS ACDOCA_ASSIGNMENT_NUMBER,
        acdoca.FKART AS BILLING_TYPE
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU024_ACDOCA') }} acdoca -- General Ledger
    WHERE LEDGER_IN_GENERAL_LEDGER_ACCOUNTING='0L'
),
vbap_data as
(
    SELECT
        vbap.VBELN as SALES_DOCUMENT,
        vbap.POSNR as SALES_DOCUMENT_ITEM_POSNR,
        vbap.ZZORTY as SALES_CATEGORY
    FROM vbap_cte vbap
),
vbfa_data_order as
(
    SELECT
        vbfa.VBELN AS SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT,
        vbfa.POSNN AS SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT,
        vbfa.VBTYP_V AS DOCUMENT_CATEGORY_OF_PRECEDING_SD_DOCUMENT,
        vbfa.VBELV AS PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
        vbfa.POSNV AS PRECEDING_ITEM_OF_AN_SD_DOCUMENT
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU064_VBFA') }}  vbfa
    WHERE DOCUMENT_CATEGORY_OF_PRECEDING_SD_DOCUMENT='C'
),
vbfa_data_delivery as
(
    SELECT
        vbfa.VBELN AS SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT,
        vbfa.POSNN AS SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT,
        vbfa.VBTYP_V AS DOCUMENT_CATEGORY_OF_PRECEDING_SD_DOCUMENT,
        vbfa.VBELV AS PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
        vbfa.POSNV AS PRECEDING_ITEM_OF_AN_SD_DOCUMENT
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU064_VBFA') }}  vbfa
    WHERE DOCUMENT_CATEGORY_OF_PRECEDING_SD_DOCUMENT='J'
),
vbfa_data_goods_movement as
(
    SELECT
        vbfa.VBELN AS SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT,
        vbfa.POSNN AS SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT,
        vbfa.VBTYP_V AS DOCUMENT_CATEGORY_OF_PRECEDING_SD_DOCUMENT,
        vbfa.VBELV AS PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT,
        vbfa.POSNV AS PRECEDING_ITEM_OF_AN_SD_DOCUMENT
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU064_VBFA') }}  vbfa
    WHERE DOCUMENT_CATEGORY_OF_PRECEDING_SD_DOCUMENT='R'
),
source_data as (
    SELECT
        acdoca_data.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        acdoca_data.COMPANY_CODE AS COMPANY_CODE,
        acdoca_data.FISCAL_YEAR AS FISCAL_YEAR,
        acdoca_data.ACCOUNTING_DOCUMENT_NUMBER AS ACCOUNTING_DOCUMENT_NUMBER,
        acdoca_data.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        acdoca_data.ACDOCA_REFERENCE_DOCUMENT_NUMBER AS ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        acdoca_data.REFERENCE_DOCUMENT_LINE_ITEM AS REFERENCE_DOCUMENT_LINE_ITEM,
        acdoca_data.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        acdoca_data.ACDOCA_ASSIGNMENT_NUMBER AS ACDOCA_ASSIGNMENT_NUMBER,
        acdoca_data.BILLING_TYPE AS BILLING_TYPE,
        vbap_data.SALES_DOCUMENT as SALES_DOCUMENT,
        vbap_data.SALES_DOCUMENT_ITEM_POSNR as SALES_DOCUMENT_ITEM_POSNR,
        vbap_data.SALES_CATEGORY as SALES_CATEGORY
    FROM acdoca_data
    JOIN vbfa_data_order
        ON try_to_number(acdoca_data.ACDOCA_REFERENCE_DOCUMENT_NUMBER) = try_to_number(vbfa_data_order.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT)
            AND try_to_number(acdoca_data.REFERENCE_DOCUMENT_LINE_ITEM) = try_to_number(vbfa_data_order.SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT)
    LEFT JOIN vbap_data
        ON try_to_number(vbfa_data_order.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT) = try_to_number(vbap_data.SALES_DOCUMENT)
            AND try_to_number(vbfa_data_order.PRECEDING_ITEM_OF_AN_SD_DOCUMENT) = try_to_number(vbap_data.SALES_DOCUMENT_ITEM_POSNR)
    LEFT JOIN vbfa_data_delivery
        ON try_to_number(acdoca_data.ACDOCA_REFERENCE_DOCUMENT_NUMBER) = try_to_number(vbfa_data_delivery.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT)
            AND try_to_number(acdoca_data.REFERENCE_DOCUMENT_LINE_ITEM) = try_to_number(vbfa_data_delivery.SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT)
    LEFT JOIN vbfa_data_goods_movement
        ON try_to_number(vbfa_data_goods_movement.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT)=try_to_number(vbfa_data_delivery.PRECEDING_SALES_AND_DISTRIBUTION_DOCUMENT)
            AND try_to_number(vbfa_data_goods_movement.PRECEDING_ITEM_OF_AN_SD_DOCUMENT)=try_to_number(vbfa_data_delivery.PRECEDING_ITEM_OF_AN_SD_DOCUMENT)
            AND try_to_number(acdoca_data.ACDOCA_REFERENCE_DOCUMENT_NUMBER) = try_to_number(vbfa_data_goods_movement.SUBSEQUENT_SALES_AND_DISTRIBUTION_DOCUMENT)
            AND try_to_number(acdoca_data.REFERENCE_DOCUMENT_LINE_ITEM) = try_to_number(vbfa_data_goods_movement.SUBSEQUENT_ITEM_OF_AN_SD_DOCUMENT)
),

transform_data as (
    SELECT
        LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        COMPANY_CODE,
        FISCAL_YEAR,
        ACCOUNTING_DOCUMENT_NUMBER,
        SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        REFERENCE_DOCUMENT_LINE_ITEM,
        AMOUNT_IN_COMPANY_CODE_CURRENCY,
        ACDOCA_ASSIGNMENT_NUMBER,
        BILLING_TYPE,
        SALES_DOCUMENT,
        SALES_DOCUMENT_ITEM_POSNR,
        SALES_CATEGORY,
		'{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH -- Adds column to table on full refresh.
    FROM source_data
),

type_data as (
    SELECT
        CAST(LEDGER_IN_GENERAL_LEDGER_ACCOUNTING AS VARCHAR(16777216)) AS LEDGER_IN_GENERAL_LEDGER_ACCOUNTING,
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(ACCOUNTING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS ACCOUNTING_DOCUMENT_NUMBER,
        CAST(SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS VARCHAR(16777216)) AS SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER,
        CAST(ACDOCA_REFERENCE_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS ACDOCA_REFERENCE_DOCUMENT_NUMBER,
        CAST(REFERENCE_DOCUMENT_LINE_ITEM AS VARCHAR(16777216)) AS REFERENCE_DOCUMENT_LINE_ITEM,
        CAST(AMOUNT_IN_COMPANY_CODE_CURRENCY AS VARCHAR(16777216)) AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        CAST(ACDOCA_ASSIGNMENT_NUMBER AS VARCHAR(16777216)) AS ACDOCA_ASSIGNMENT_NUMBER,
        CAST(BILLING_TYPE AS VARCHAR(16777216)) AS BILLING_TYPE,
        CAST(SALES_DOCUMENT AS VARCHAR(16777216)) AS SALES_DOCUMENT,
        CAST(SALES_DOCUMENT_ITEM_POSNR AS VARCHAR(16777216)) AS SALES_DOCUMENT_ITEM_POSNR,
        CAST(SALES_CATEGORY AS VARCHAR(16777216)) AS SALES_CATEGORY,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM transform_data
)
SELECT * from type_data
WITH
CRM_WO_PRODUCT_AGG AS (
    SELECT 
        LPAD(WO.MSDYN_NAME, 8, '0') AS SERVICE_CRM_WO_NUMBER,
        WOP.MSDYN_PRODUCTNAME,
        MAX(WOP.MSDYN_QUANTITY) AS MSDYN_QUANTITY
    FROM {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }} AS WO
    JOIN {{ ref('ODS__CRM_FILE__MSDYN_WORKORDERPRODUCT') }} AS WOP ON (
        WOP.MSDYN_WORKORDER = WO.MSDYN_WORKORDERID
    )
    GROUP BY LPAD(WO.MSDYN_NAME, 8, '0'), WOP.MSDYN_PRODUCTNAME
),
BILL AS (
    SELECT 
        VBRP.AUBEL, 
        VBRP.AUPOS,
        CASE WHEN MAX(VBRP.VBELN) = MIN(VBRP.VBELN) THEN MAX(VBRP.VBELN) END AS BILL_HDR,
        SUM(VBRP.FKIMG) AS QTY,
        SUM(VBRP.WAVWR) AS COST_IN_DOC_CURRENCY, 
        SUM(VBRP.KZWI1) AS SUBTOTAL_1, 
        SUM(VBRP.KZWI2) AS SUBTOTAL_2
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU014_VBRK') }} AS VBRK
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU015_VBRP') }} AS VBRP ON (VBRP.VBELN = VBRK.VBELN)
    GROUP BY VBRP.AUBEL, VBRP.AUPOS
),
DELIV AS (
    SELECT 
        LIPS.VGBEL AS REF_DOC, 
        LIPS.VGPOS AS REF_DOC_POSNR,
        MAX(LIKP.WADAT) AS GOODS_ISSUE_DATE,
        CASE 
            WHEN MIN(LIKP.VBELN) = MAX(LIKP.VBELN) 
            THEN MAX(LIKP.VBELN) 
            ELSE 'Multiple DOs for SO line' 
        END AS DO_HDR,
        CASE 
            WHEN 
                MAX(LIPS.POSNR) = MIN(LIPS.POSNR) AND
                MIN(LIKP.VBELN) = MAX(LIKP.VBELN)
            THEN MAX(LIPS.POSNR) 
            ELSE 'Multiple DO Lines for SO line' 
        END AS DO_LINE,
        MIN(NULLIF(LIKP.WADATIST, '00000000')) AS FIRST_GOODS_MOVEMENT_DATE,
        MAX(NULLIF(LIKP.WADATIST, '00000000')) AS LAST_GOODS_MOVEMENT_DATE,
        SUM(LIPS.LFIMG) AS DELIVERED_QTY,
        COUNT(*) AS DELIVERY_LINE_COUNT,
        COUNT(DISTINCT(LIPS.VGBEL)) AS DELIVERY_HDR_COUNT,
        MAX(LIKP.UVWAK) AS PGI_STATUS
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU013_LIPS') }} AS LIPS
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU012_LIKP') }} AS LIKP ON (LIPS.VBELN = LIKP.VBELN)
    GROUP BY LIPS.VGBEL, LIPS.VGPOS
),
NCDR_BASE AS (
    SELECT 
        VBAK.VBELN,
        VBAP.POSNR,
        TRY_TO_DATE(VBAP.ERDAT, 'YYYYMMDD') AS SO_CREATED_DATE,
        VBAK.AUART AS SALES_DOC_TYPE,
        VBAK.KNKLI AS CUSTOMER_ACCOUNT_NO,
        TO_DATE(VBAK.ERDAT, 'YYYYMMDD') AS DOCUMENT_DATE,
        VBAP.ZZNNZZ AS NCDR_NUMBER,
        VBAP.MATNR AS MATERIAL_NUMBER,
        MARA.MAKTX AS MATERIAL_DESC,
        MARA.MATKL AS MATERIAL_GROUP,
        MARA.MEINS AS MATERIAL_BASE_UNIT_OF_MEASURE,
        MARA.NTGEW AS MATERIAL_NET_WEIGHT,
        MARA.BRGEW AS MATERIAL_GROSS_WEIGHT,
        MARA.GEWEI AS MATERIAL_WEIGHT_UNIT,
        VBAP.KWMENG AS QTY,
        CONCAT(VBAP.ZZNNZZ, '__', VBAP.MATNR) AS NCDR_LINE_ID,
        TRY_TO_DATE(DELIV.GOODS_ISSUE_DATE,'YYYYMMDD') AS GOODS_ISSUE_DATE,
        DELIV.FIRST_GOODS_MOVEMENT_DATE,
        DELIV.LAST_GOODS_MOVEMENT_DATE,
        DELIV.DO_HDR,
        DELIV.DO_LINE,
        DELIV.DELIVERED_QTY,
        DELIV.PGI_STATUS,
        VBAP.KWMENG - DELIV.DELIVERED_QTY AS UNPROCESSED_QTY,
        COALESCE(DELIV.DELIVERY_LINE_COUNT, 0) AS DELIVERY_LINE_COUNT,
        COALESCE(DELIV.DELIVERY_HDR_COUNT, 0) AS DELIVERY_HDR_COUNT,
        COALESCE(BILL.QTY, 0) AS BILLED_QTY,
        BILL.BILL_HDR,
        CASE WHEN BILL.AUBEL IS NULL THEN FALSE ELSE TRUE END AS HAS_BILL,
        VBAP.ERNAM AS LINE_CREATED_BY,
        VBAK.IHREZ AS BAAN_SO_REFERENCE,
        VBAK.ZZSCWN AS SERVICE_CRM_WO_NUMBER,
        VBAP.ZZTSNZ AS SAP_TOOL_SERIAL,
        VBAK.AUGRU AS ORDER_REASON,
        VBAP.NETWR AS NET_VALUE_OF_LINE_ITEM,
        VBAP.WAVWR AS COST_IN_DOCUMENT_CURRENCY,
        VBAP.KZWI1 AS SUBTOTAL1,
        VBAK.KUNNR AS SOLD_TO_PARTY_CODE,
        KNA1.NAME1 AS SOLD_TO_PARTY,
        CG.CUSTOMER_GROUP,
        VBAP.PRCTR AS PROFIT_CENTER,
        VBAK.VKBUR AS SALES_OFFICE,
        VBAK.BSTNK AS CUSTOMER_REFERENCE,
        PRPS.POSKI AS WBS_ELEMENT,
        VBAP.ZZORTY AS SALES_CATEGORY,
        SCAT.SAP_SALES_CATEGORY_NAME AS SALES_CATEGORY_NAME,
        VBAP.FAKSP AS BILLING_BLOCK_FOR_ITEM
    -- VBAP / VBAK: Sales Order header / line
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} AS VBAK ON (VBAK.VBELN = VBAP.VBELN)
    -- KNA1: Customer Master
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU020_KNA1') }} AS KNA1 ON (
        VBAK.KUNNR = KNA1.KUNNR
    )
    LEFT JOIN {{ ref('COMMON__SAPH__SAP_CUSTOMER_GROUP') }} AS CG ON (CG.CUSTOMER_CODE = KNA1.KUNNR)
    -- MARA: Material Master
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} AS MARA ON (MARA.MATNR = VBAP.MATNR)
    -- PRPS: Work Breakdown Structure
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU040_PRPS') }} AS PRPS ON (
        VBAP.PS_PSP_PNR_NEW = PRPS.PSPNR_NEW
    )
    LEFT JOIN DELIV ON (
        VBAK.VBELN = DELIV.REF_DOC AND VBAP.POSNR = DELIV.REF_DOC_POSNR
    )
    LEFT JOIN BILL ON (
        BILL.AUBEL = VBAK.VBELN AND BILL.AUPOS = VBAP.POSNR
    )
    LEFT JOIN {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }} AS SCAT ON (SCAT.SAP_SALES_CATEGORY = VBAP.ZZORTY)
    WHERE 
        VBAK.AUART IN ('ZS14', 'ZS12') AND 
        NULLIF(TRIM(VBAP.ZZNNZZ), '') IS NOT NULL AND
        VBAK.VKORG = '3200'
),
NCDR_ZS12_AGG AS (
    SELECT
        NCDR_LINE_ID,
        MAX(BILL_HDR) AS ZS12_BILLING_DOC,
        MIN(VBELN) AS MIN_SALES_DOC_HDR,
        MAX(VBELN) AS MAX_SALES_DOC_HDR,
        CASE WHEN COUNT(*) = 1 THEN MAX(POSNR) ELSE 'MULTIPLE' END AS ZS12_SALES_DOC_LINE,
        SUM(QTY) AS ZS12_QTY_SUM,
        MAX(FIRST_GOODS_MOVEMENT_DATE) AS ZS12_FIRST_GOODS_MOVMEMENT_DATE,
        MAX(LAST_GOODS_MOVEMENT_DATE) AS ZS12_LAST_GOODS_MOVEMENT_DATE,
        MAX(WBS_ELEMENT) AS ZS12_WBS_ELEMENT,
        COUNT(*) AS LINE_COUNT,
        SUM(CASE WHEN HAS_BILL = TRUE THEN 1 ELSE 0 END) AS ZS12_BILL_LINE_COUNT,
        SUM(BILLED_QTY) AS ZS12_BILLED_QTY,
        SUM(COST_IN_DOCUMENT_CURRENCY) AS ZS12_COST,
        SUM(NET_VALUE_OF_LINE_ITEM) AS ZS12_NET_VALUE,
        SUM(
            CASE WHEN BILLING_BLOCK_FOR_ITEM = 'Z1' THEN QTY ELSE 0 END
        ) AS ZS12_Z1_BILLING_BLOCK_QTY,
        SUM(
            CASE WHEN BILLING_BLOCK_FOR_ITEM = 'Z4' THEN QTY ELSE 0 END
        ) AS ZS12_Z4_BILLING_BLOCK_QTY,
        SUM(
            CASE WHEN BILLING_BLOCK_FOR_ITEM = 'Z1' THEN COST_IN_DOCUMENT_CURRENCY ELSE 0 END
        ) AS ZS12_Z1_BILLING_BLOCK_COST,
        SUM(
            CASE WHEN BILLING_BLOCK_FOR_ITEM = 'Z4' THEN COST_IN_DOCUMENT_CURRENCY ELSE 0 END
        ) AS ZS12_Z4_BILLING_BLOCK_COST,
        CASE WHEN MIN(VBELN) = MAX(VBELN) THEN FALSE ELSE TRUE END AS MULTIPLE_HEADERS_FLAG,
        CASE WHEN MAX(SALES_CATEGORY) = MIN(SALES_CATEGORY) THEN MAX(SALES_CATEGORY) ELSE 'MULTIPLE' END AS ZS12_SALES_CATEGORY,
        CASE WHEN MAX(SALES_CATEGORY) = MIN(SALES_CATEGORY) THEN MAX(SALES_CATEGORY_NAME) ELSE 'MULTIPLE' END AS ZS12_SALES_CATEGORY_NAME
    FROM NCDR_BASE
    WHERE SALES_DOC_TYPE = 'ZS12'
    GROUP BY NCDR_LINE_ID
),
-- CTE: RTRN
-- This CTE collects all loan returns (Sales Doc Type = ZSR0)
-- These records are linked to loan NCDR records (ZS14) via
-- material ID and CRM work order number.
RTRN AS (
    SELECT 
        VBAK.VBELN, 
        VBAP.POSNR, 
        VBAK.ZZSCWN AS CRM_WO_NUMBER, 
        VBAP.MATNR, 
        VBAK.ERDAT, 
        VBAP.KWMENG AS ZSR0_QTY
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} AS VBAK
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP ON (
        VBAP.VBELN = VBAK.VBELN
    )
    WHERE VBAK.AUART = 'ZSR0'
),
-- CTE: RTRN_MRG
-- Link ZSR0 (loan return) records from the RTRN CTE to their 
-- corresponding ZS14 record in the NCDR_BASE CTE
RTRN_MRG AS (
    SELECT 
        --REP.SERVICE_CRM_WO_NUMBER, 
        NCDR_BASE.VBELN, 
        NCDR_BASE.POSNR,
        NCDR_BASE.SO_CREATED_DATE AS ZS14_SO_CREATED_DATE,
        TRY_TO_DATE(RTRN.ERDAT, 'YYYYMMDD') AS RETURN_SO_DATE,
        RTRN.ZSR0_QTY,
        RTRN.VBELN || '-' || RTRN.POSNR AS RETURN_SO_LINE_ID
    FROM NCDR_BASE
    JOIN RTRN ON (
        -- CRM # and Material # must match
        RTRN.CRM_WO_NUMBER = NCDR_BASE.SERVICE_CRM_WO_NUMBER AND 
        NCDR_BASE.MATERIAL_NUMBER = RTRN.MATNR AND
        -- The SO (ZS14) must have been created before the return record (ZSR0)
        NCDR_BASE.SO_CREATED_DATE <= TRY_TO_DATE(RTRN.ERDAT, 'YYYYMMDD')
    )
    WHERE RTRN.ZSR0_QTY > 0 AND NCDR_BASE.SALES_DOC_TYPE = 'ZS14'
),
RTRN_AGG AS (
    SELECT 
        VBELN, 
        POSNR,
        -- There is only one created date and qty
        -- for each ZS14 Header / Line pair.
        -- MAX is only being used to prevent us from putting
        -- more columns in the GROUP BY clause.
        MAX(ZS14_SO_CREATED_DATE) AS ZS14_SO_CREATED_DATE,
        MIN(RETURN_SO_DATE) AS FIRST_RETURN_DATE, 
        MAX(RETURN_SO_DATE) AS LATEST_RETURN_DATE,
        LISTAGG(ZSR0_QTY, '|') AS RETURN_QTYS,
        SUM(ZSR0_QTY) AS LINKED_RETURN_QTY,
        LISTAGG(RETURN_SO_LINE_ID, '|') AS RETURN_SO_LINE_IDS
    FROM RTRN_MRG
    GROUP BY VBELN, POSNR 
),
NOW_RN AS (
    SELECT 
        *,
        ROW_NUMBER() OVER(
            PARTITION BY NCDR, PART_NUMBER
            ORDER BY COALESCE(REGIONALLY_APPROVED_DATE, GLOBALLY_APPROVED_DATE) DESC
        ) AS RN
    FROM ODS.NOW.NOWDATA AS _NOW
),
NOW_DEDUP AS (SELECT * FROM NOW_RN WHERE RN = 1),
ENDUSER AS (
    SELECT
        BUSINESS_PARTNER_NUMBER
        ,CUSTOMER_GROUP AS ENDUSER_CUSTOMER_GROUP
        ,CORPORATION_NAME AS ENDUSER_NAME
        ,SEARCH_TERM_2 AS ENDUSER_SEARCH2_NAME
    FROM {{ ref('COMMON__REPORTS__BUSINESS_PARTNERS_3200_ADDRESS') }}
WHERE LEFT(BUSINESS_PARTNER_NUMBER,1) = 'B'
),
LEGACY_OFFICE AS (
    SELECT DISTINCT B_CODE, LEGACY_OFFICE, LEGACY_OFFICE_CODE
    FROM {{ ref('COMMON__SAPH__SERVICE_B_CODE_MAPPING') }}
),
SO_LINE_SAP_BATCH AS (
    SELECT
        LIPS.VGBEL,
        LIPS.VGPOS,
        MAX(LIKP.UVWAK) AS PGI_STATUS,
        MAX(LIPS.CHARG) AS BATCH
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU013_LIPS') }} AS LIPS
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU012_LIKP') }} AS LIKP ON (LIKP.VBELN = LIPS.VBELN)
    WHERE NULLIF(LIPS.CHARG, '') IS NOT NULL AND LIKP.UVWAK = 'C'
    GROUP BY LIPS.VGBEL, LIPS.VGPOS
    HAVING MAX(LIPS.CHARG) = MIN(LIPS.CHARG)
),
-- #################
-- # Carma Support #
-- #################
-- Carma data only contains the NCDR # and Material ID to key from
-- This means SOs where the material ID is duplicated along multiple
-- lines will not map to a single record.
--
-- To deal with this situation, if an NCDR # / Material ID pair has
-- consummption in CARMA, we distribute the consumption evenly across
-- all matched SO lines.
SO_MATERIAL_QTYS AS (
    SELECT VBAP.VBELN, VBAP.MATNR, SUM(VBAP.KWMENG) AS LINE_MATERIAL_QTY
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP
    GROUP BY VBAP.VBELN, VBAP.MATNR
    HAVING SUM(VBAP.KWMENG) > 0
),
SO_LINE_MATERIAL_RATIO AS (
    SELECT 
        VBAP.VBELN, VBAP.POSNR, VBAP.KWMENG / MQ.LINE_MATERIAL_QTY AS MATERIAL_PERCENT 
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP
    LEFT JOIN SO_MATERIAL_QTYS AS MQ ON (VBAP.VBELN = MQ.VBELN AND VBAP.MATNR = MQ.MATNR)
),
CARMA_CONSUMPTION AS (
    SELECT 
        C.NCDR, 
        C.PART_NUMBER, 
        SUM(C.QTY_CONSUMED) AS NCDR_PART_CARMA_CONSUMED_QTY
    -- ref('CONSUMPTION') refers to COMMON.CARMA.CONSUMPTION
    FROM {{ ref('COMMON__CARMA__CONSUMPTION') }} AS C
    GROUP BY C.NCDR, C.PART_NUMBER
),
SOURCE_DATA AS (
    SELECT 
        NCDR_BASE.VBELN AS ZS14_SO_HDR,
        NCDR_BASE.POSNR AS ZS14_SO_LINE,
        NCDR_BASE.BAAN_SO_REFERENCE,
        CONCAT(NCDR_BASE.VBELN, '-', NCDR_BASE.POSNR) AS ZS14_SALES_DOC_ITEM,
        NCDR_BASE.SO_CREATED_DATE AS ZS14_SO_CREATED_DATE,
        NCDR_BASE.PGI_STATUS,
        NCDR_BASE.DOCUMENT_DATE AS ZS14_DOCUMENT_DATE,
        NCDR_BASE.DO_HDR AS ZS14_DO_HDR,
        NCDR_BASE.DO_LINE AS ZS14_DO_LINE,
        NCDR_BASE.GOODS_ISSUE_DATE,
        TRY_TO_DATE(NCDR_BASE.FIRST_GOODS_MOVEMENT_DATE, 'YYYYMMDD') AS ZS14_FIRST_GOODS_MOVEMENT_DATE,
        TRY_TO_DATE(NCDR_BASE.LAST_GOODS_MOVEMENT_DATE, 'YYYYMMDD') AS ZS14_LAST_GOODS_MOVEMENT_DATE,
        NCDR_BASE.DELIVERY_LINE_COUNT AS ZS14_DELIVERY_LINE_COUNT,
        NCDR_BASE.DELIVERY_HDR_COUNT AS ZS14_DELIVERY_HDR_COUNT,
        NCDR_BASE.QTY AS ZS14_QTY,
        COALESCE(NCDR_BASE.DELIVERED_QTY, 0) AS ZS14_CUMULATED_SHIPPED_QTY,
        NCDR_BASE.NCDR_NUMBER,
        NCDR_BASE.MATERIAL_NUMBER,
        NCDR_BASE.MATERIAL_DESC,
        NCDR_BASE.MATERIAL_BASE_UNIT_OF_MEASURE,
        NCDR_BASE.MATERIAL_GROSS_WEIGHT,
        NCDR_BASE.MATERIAL_NET_WEIGHT,
        NCDR_BASE.MATERIAL_WEIGHT_UNIT,
        NCDR_BASE.MATERIAL_GROUP,
        SPLIT_PART(NCDR_BASE.NCDR_NUMBER, '-', 1) AS MATERIAL_GROUP1,
        CASE 
            WHEN NCDR_ZS12_AGG.ZS12_BILLED_QTY >= NCDR_BASE.QTY 
            THEN 'Consumed' ELSE 'Unconsumed' 
        END AS NCDR_ACTION_FLAG,
        COALESCE(NCDR_ZS12_AGG.MULTIPLE_HEADERS_FLAG, FALSE) AS MUTLIPLE_ZS12_SO_HDR_FLAG,
        NCDR_BASE.LINE_CREATED_BY AS CREATED_BY,
        NCDR_BASE.SERVICE_CRM_WO_NUMBER,
        WOP.MSDYN_QUANTITY,
        NCDR_BASE.SAP_TOOL_SERIAL,
        NCDR_BASE.ORDER_REASON AS ZS14_ORDER_REASON_HDR,
        NCDR_BASE.NET_VALUE_OF_LINE_ITEM,
        NCDR_BASE.COST_IN_DOCUMENT_CURRENCY AS COST,
        NCDR_BASE.SUBTOTAL1,
        NCDR_BASE.SOLD_TO_PARTY_CODE AS END_USER_CODE,
        NCDR_BASE.SOLD_TO_PARTY,
        NCDR_BASE.CUSTOMER_ACCOUNT_NO,
        NCDR_BASE.CUSTOMER_GROUP,
        NCDR_BASE.PROFIT_CENTER,
        LEFT(RIGHT(NCDR_BASE.NCDR_NUMBER, 9), 3) AS NCDR_REGION_CODE,
        NOWDATA.REQUESTOR AS REQUESTOR_NAME,
        NOWDATA.REQUESTOR_EMP_NO,
        EMP.EMAILADDRESS AS REQUESTOR_EMAIL,
        NOWDATA.ORIGINATOR,
        EMP.SUPERVISOR_NAME,
        EMP.SUPERVISOR_EMPLOYEE_ID AS SUPERVISOR_EMPLOYEE_NO,
        --EMP.GROUPNAMEFST AS REQUESTOR_EMP_GROUP,
        NOWDATA.GLOBALLY_APPROVED_DATE,
        NOWDATA.REGIONALLY_APPROVED_DATE,
        NCDR_BASE.CUSTOMER_REFERENCE,
        NCDR_BASE.WBS_ELEMENT,
        NCDR_BASE.SALES_CATEGORY AS ZS14_SALES_CATEGORY,
        NCDR_BASE.SALES_CATEGORY_NAME AS ZS14_SALES_CATEGORY_NAME,
        NCDR_ZS12_AGG.MIN_SALES_DOC_HDR AS ZS12_SALES_DOC_HDR,
        NCDR_ZS12_AGG.ZS12_SALES_DOC_LINE,
        NCDR_ZS12_AGG.ZS12_SALES_CATEGORY,
        NCDR_ZS12_AGG.ZS12_SALES_CATEGORY_NAME,
        COALESCE(NCDR_ZS12_AGG.ZS12_QTY_SUM, 0) AS ZS12_QTY_SUM,
        COALESCE(NCDR_ZS12_AGG.ZS12_BILL_LINE_COUNT, 0) AS ZS12_BILL_LINE_COUNT,
        COALESCE(NCDR_ZS12_AGG.ZS12_BILLED_QTY, 0) AS ZS12_BILLED_QTY,
        NCDR_ZS12_AGG.ZS12_FIRST_GOODS_MOVMEMENT_DATE,
        NCDR_ZS12_AGG.ZS12_LAST_GOODS_MOVEMENT_DATE,
        NCDR_ZS12_AGG.ZS12_WBS_ELEMENT,
        NCDR_BASE.UNPROCESSED_QTY,
        LEGACY_OFFICE.LEGACY_OFFICE AS LEGACY_OFFICE,
        LEGACY_OFFICE.LEGACY_OFFICE_CODE AS LEGACY_OFFICE_CODE,
        ENDUSER.ENDUSER_CUSTOMER_GROUP AS ENDUSER_CUSTOMER_GROUP,
        ENDUSER.ENDUSER_NAME AS ENDUSER_NAME,
        ENDUSER.ENDUSER_SEARCH2_NAME AS ENDUSER_SEARCH2_NAME,
        CURRENT_DATE() - NCDR_BASE.GOODS_ISSUE_DATE::DATE AS DAYS_SINCE_ZS14_GOODS_ISSUE,
        NOWDATA.CUSTOMER AS CUSTOMER_NAME,
        SO_LINE_SAP_BATCH.BATCH AS ZS14_SAP_BATCH,
        COALESCE(RTRN_AGG.LINKED_RETURN_QTY, 0) AS LINKED_RETURN_QTY,
        RTRN_AGG.RETURN_SO_LINE_IDS,
        -- This is the consumption for the NCDR / Part # pair adjusted
        -- for fraction of the pair that the SO-Line represents.
        -- This is different from NCDR_PART_CARMA_CONSUMED_QTY only an SO
        -- has multiple lines for the same material #.
        CC.NCDR_PART_CARMA_CONSUMED_QTY * MR.MATERIAL_PERCENT AS SO_LINE_ADJ_CARMA_CONSUMED_QTY,
        -- This is the total consumption for the NCDR / Part # pair
        CC.NCDR_PART_CARMA_CONSUMED_QTY,
        CASE 
            WHEN 
                CC.NCDR_PART_CARMA_CONSUMED_QTY * MR.MATERIAL_PERCENT >= 
                NCDR_BASE.QTY - COALESCE(RTRN_AGG.LINKED_RETURN_QTY, 0) 
            THEN TRUE ELSE FALSE 
        END AS CARMA_CONSUMED,
        NCDR_ZS12_AGG.ZS12_COST,
        NCDR_ZS12_AGG.ZS12_Z1_BILLING_BLOCK_QTY,
        NCDR_ZS12_AGG.ZS12_Z4_BILLING_BLOCK_QTY,
        NCDR_ZS12_AGG.ZS12_Z1_BILLING_BLOCK_COST,
        NCDR_ZS12_AGG.ZS12_Z4_BILLING_BLOCK_COST
    FROM NCDR_BASE
    LEFT JOIN NCDR_ZS12_AGG ON (
        NCDR_BASE.NCDR_LINE_ID = NCDR_ZS12_AGG.NCDR_LINE_ID
    )
    LEFT JOIN SO_LINE_SAP_BATCH ON (
        SO_LINE_SAP_BATCH.VGBEL = NCDR_BASE.VBELN AND
        SO_LINE_SAP_BATCH.VGPOS = NCDR_BASE.POSNR
    )
    LEFT JOIN NOW_DEDUP AS NOWDATA ON (
        (
            NOWDATA.NCDR15 = NCDR_BASE.NCDR_NUMBER OR
            NOWDATA.NCDR = NCDR_BASE.NCDR_NUMBER
        ) AND
        NOWDATA.PART_NUMBER = NCDR_BASE.MATERIAL_NUMBER
    )
    LEFT JOIN {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }} AS EMP ON (
        EMP.EMPLOYEE_ID = NOWDATA.REQUESTOR_EMP_NO
    )
    LEFT JOIN CRM_WO_PRODUCT_AGG AS WOP ON (
        WOP.SERVICE_CRM_WO_NUMBER = NCDR_BASE.SERVICE_CRM_WO_NUMBER AND
        WOP.MSDYN_PRODUCTNAME = NCDR_BASE.MATERIAL_NUMBER
    )
    LEFT JOIN LEGACY_OFFICE ON (
        NCDR_BASE.SOLD_TO_PARTY_CODE = LEGACY_OFFICE.B_CODE
    )
    LEFT JOIN ENDUSER ON (
        NCDR_BASE.SOLD_TO_PARTY_CODE = ENDUSER.BUSINESS_PARTNER_NUMBER
    )
    LEFT JOIN RTRN_AGG ON (
        RTRN_AGG.VBELN = NCDR_BASE.VBELN AND
        RTRN_AGG.POSNR = NCDR_BASE.POSNR
    )
    LEFT JOIN SO_LINE_MATERIAL_RATIO AS MR ON (
        MR.VBELN = NCDR_BASE.VBELN AND MR.POSNR = NCDR_BASE.POSNR
    )
    LEFT JOIN CARMA_CONSUMPTION AS CC ON (
        CC.NCDR = NCDR_BASE.NCDR_NUMBER AND 
        CC.PART_NUMBER = NCDR_BASE.MATERIAL_NUMBER
    )
    WHERE 
        -- filter down to loan NCDR initiations
        NCDR_BASE.SALES_DOC_TYPE = 'ZS14'
),
TRANSFORM_DATA AS (
    SELECT
        ZS14_SO_HDR,
        ZS14_SO_LINE,
        BAAN_SO_REFERENCE,
        ZS14_SALES_DOC_ITEM,
        ZS14_SO_CREATED_DATE,
        PGI_STATUS,
        ZS14_DOCUMENT_DATE,
        ZS14_DO_HDR,

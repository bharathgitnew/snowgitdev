{{ config(
        alias = 'MATERIAL_MASTER_3PL_LATEST',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with MARA AS
(
    SELECT
        MATNR AS MARA_MATERIAL_NUMBER,
        MAKTX AS MARA_MATERIAL_DESCRIPTION,
        MEINS AS MARA_UOM,
        UPDATE_DATE AS MARA_UPDATE_DATE,
        _FILEDATE AS MARA_FILEDATE
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU017_MARA') }} 
),
MBEW AS
(
    SELECT 
        MATNR AS MBEW_MATERIAL_NUMBER,
        STPRS AS STANDARD_PRICE
    FROM {{ ref('ODS__SAPH__SAP_US_MMT_EV_MBEW') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY MATNR ORDER BY _FILEDATE  DESC )) = 1
),
MARC AS
(
    SELECT 
        MATNR AS MARC_MATERIAL_NUMBER,
        SERNP AS SERIAL_NUMBER_PROFILE,
        WERKS AS MARC_PLANT
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU026_MARC') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY MATNR ORDER BY UPDATE_DATE  DESC )) = 1
),
GTM AS
(
    SELECT 
        PRODUCTNUM AS GTM_MATERIAL_NUMBER,
        UNNUM1 AS UNNUM1
    FROM {{ ref('ODS__SAPH__PARTS_EXPORTIMPORT_CONTROL') }}
    QUALIFY (ROW_NUMBER() OVER (PARTITION BY PRODUCTNUM ORDER BY _FILEDATE,_FILENAME DESC )) = 1
),
source_data as
(
    SELECT DISTINCT   
        MARA_MATERIAL_NUMBER AS MATERIAL_NUMBER,
        MARA_MATERIAL_DESCRIPTION,
        MARA_UOM,
        MARA_UPDATE_DATE,
        MARA_FILEDATE,
        STANDARD_PRICE,
        SERIAL_NUMBER_PROFILE,
        MARC_PLANT,
        UNNUM1
    FROM MARA
        LEFT JOIN MBEW
            ON MARA_MATERIAL_NUMBER = MBEW_MATERIAL_NUMBER
        LEFT JOIN GTM
            ON MARA_MATERIAL_NUMBER = GTM_MATERIAL_NUMBER
        LEFT JOIN MARC
            ON MARA_MATERIAL_NUMBER = MARC_MATERIAL_NUMBER
),
transform_data as (
    SELECT
        MATERIAL_NUMBER,
        MARA_MATERIAL_DESCRIPTION,
        MARA_UOM,
        STANDARD_PRICE,
        UNNUM1,
        MARA_FILEDATE,
        SERIAL_NUMBER_PROFILE,
        CASE WHEN SERIAL_NUMBER_PROFILE='Z002' THEN 'Y' ELSE 'N' end AS SERIALIZED,
        CASE WHEN (STANDARD_PRICE IS NOT NULL AND TRIM(STANDARD_PRICE)!='' and STANDARD_PRICE>30) THEN 0 ELSE 1 END AS BIN_BULK_INDICATOR,
        MARC_PLANT,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM source_data
),
type_data as (
select
    CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
    CAST(MARA_MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MARA_MATERIAL_DESCRIPTION,
    CAST(MARA_UOM AS VARCHAR(16777216)) AS MARA_UOM,
    CAST(STANDARD_PRICE AS VARCHAR(16777216)) AS STANDARD_PRICE,
    CAST(UNNUM1 AS VARCHAR(16777216)) AS UNNUM1,
    CAST(SERIAL_NUMBER_PROFILE AS VARCHAR(16777216)) AS SERIAL_NUMBER_PROFILE,
    CAST(SERIALIZED AS VARCHAR(1)) AS SERIALIZED,
    CAST(BIN_BULK_INDICATOR AS VARCHAR(1)) AS BIN_BULK_INDICATOR,
    CAST(MARC_PLANT AS VARCHAR(16777216)) AS MARC_PLANT,
    CAST(MARA_FILEDATE AS VARCHAR(16777216)) AS UPDATE_DATE,
    CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
from transform_data
)

select * from type_data
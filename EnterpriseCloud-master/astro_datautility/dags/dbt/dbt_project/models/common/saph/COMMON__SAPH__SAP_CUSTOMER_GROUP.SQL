{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='SAP_CUSTOMER_GROUP'
) }}

with source_data as
(
    SELECT
		_FILENAME,
		_FILEDATE,
		_UPLOADDATE,
		CUSTOMER_CODE,
		CUSTOMER_GROUP,
		CUSTOMER_NAME,
		CORPORATION_CODE,
		SEARCH_TERM1,
		SEARCH_TERM2,
		NAME_1,
		NAME_2,
		STREET_AND_HOUSE_NUMBER,
		REGION,
		CITY,
		POSTAL_CODE,
		COUNTRY,
		CUSTOMER_FLAG,
		VENDOR_FLAG,
		SORT_FIELD,
		CUSTOMER_CODE_TYPE_NAME,
		CUSTOMER_CODE_TYPE,
		BUSINESS_PARTNER_CATEGORY,
		PORT
    FROM {{ ref('ODS__FILE__SAP_CUSTOMER_GROUP') }}
  
 
   
)

,transform_data as
(
    SELECT
		_FILENAME,
		_FILEDATE,
		_UPLOADDATE,
		CUSTOMER_CODE,
		CUSTOMER_GROUP,
		CUSTOMER_NAME,
		CORPORATION_CODE,
		SEARCH_TERM1,
		SEARCH_TERM2,
		NAME_1,
		NAME_2,
		STREET_AND_HOUSE_NUMBER,
		REGION,
		CITY,
		POSTAL_CODE,
		COUNTRY,
		CUSTOMER_FLAG,
		VENDOR_FLAG,
		SORT_FIELD,
		CUSTOMER_CODE_TYPE_NAME,
		CUSTOMER_CODE_TYPE,
		BUSINESS_PARTNER_CATEGORY,
		PORT,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
        FROM source_data
)

,type_data as
(
    select
        CAST(_FILENAME AS VARCHAR(16777216)) AS _FILENAME,
        CAST(_FILEDATE AS TIMESTAMP_NTZ(9)) AS _FILEDATE,
        CAST(_UPLOADDATE AS TIMESTAMP_NTZ(9)) AS _UPLOADDATE,
        CAST(CUSTOMER_CODE AS VARCHAR(16777216)) AS CUSTOMER_CODE,
        CAST(CUSTOMER_GROUP AS VARCHAR(16777216)) AS CUSTOMER_GROUP,
        CAST(CUSTOMER_NAME AS VARCHAR(16777216)) AS CUSTOMER_NAME,
        CAST(CORPORATION_CODE AS VARCHAR(16777216)) AS CORPORATION_CODE,
        CAST(SEARCH_TERM1 AS VARCHAR(16777216)) AS SEARCH_TERM1,
        CAST(SEARCH_TERM2 AS VARCHAR(16777216)) AS SEARCH_TERM2,
        CAST(NAME_1 AS VARCHAR(16777216)) AS NAME_1,
        CAST(NAME_2 AS VARCHAR(16777216)) AS NAME_2,
        CAST(STREET_AND_HOUSE_NUMBER AS VARCHAR(16777216)) AS STREET_AND_HOUSE_NUMBER,
        CAST(REGION AS VARCHAR(16777216)) AS REGION,
        CAST(CITY AS VARCHAR(16777216)) AS CITY,
        CAST(POSTAL_CODE AS VARCHAR(16777216)) AS POSTAL_CODE,
        CAST(COUNTRY AS VARCHAR(16777216)) AS COUNTRY,
        CAST(CUSTOMER_FLAG AS VARCHAR(16777216)) AS CUSTOMER_FLAG,
        CAST(VENDOR_FLAG AS VARCHAR(16777216)) AS VENDOR_FLAG,
        CAST(SORT_FIELD AS VARCHAR(16777216)) AS SORT_FIELD,
        CAST(CUSTOMER_CODE_TYPE_NAME AS VARCHAR(16777216)) AS CUSTOMER_CODE_TYPE_NAME,
        CAST(CUSTOMER_CODE_TYPE AS VARCHAR(16777216)) AS CUSTOMER_CODE_TYPE,
        CAST(BUSINESS_PARTNER_CATEGORY AS VARCHAR(16777216)) AS BUSINESS_PARTNER_CATEGORY,
        CAST(PORT AS VARCHAR(16777216)) AS PORT,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    from transform_data
    )
select * from type_data
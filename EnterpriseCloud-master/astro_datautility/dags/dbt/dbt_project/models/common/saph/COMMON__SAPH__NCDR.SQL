WITH vbap_cte as (
    select * from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }}
    where IS_DELETED = 'No'
),

MAX_DELIVERY_DATE AS
(
 SELECT
    LIPS_DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,
    LIPS_ITEM_NUMBER_OF_THE_REFERENCE_ITEM,
    MAX(LIKP_ACTUAL_GOODS_MOVEMENT_DATE) AS LIKP_ACTUAL_GOODS_MOVEMENT_DATE
FROM {{ ref('COMMON__SAPH__DELIVERY_ORDER_LINE_MASTER') }}
GROUP BY LIPS_DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT,
            LIPS_ITEM_NUMBER_OF_THE_REFERENCE_ITEM
),
end_user_details As
(
    SELECT
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER,
        ITEM_NUMBER_OF_THE_SD_DOCUMENT,
        CUSTOMER_NUMBER,
  PARTNER_FUNCTION
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }}
  where PARTNER_FUNCTION='Z6'
),
MATDOC_DETAILS As
(
  SELECT
        AUFK.KDAUF AS AUFK_SALES_ORDER_HEADER,
        AUFK.AUFNR AS AUFK_SERVICE_ORDER,
        MATDOC.AUFNR AS ORDER_NUMBER,
        MATDOC.CHARG_SID AS BATCH_NUMBER_CHARG,
        MATDOC.BUDAT AS POSTING_DATE_IN_THE_DOCUMENT,
        MATDOC.MATNR AS MATDOC_MATERIAL_NO,
        MATDOC.MENGE AS MATDOC_QTY,
        MATDOC.cpudt AS CREATEDDATE,
          row_number() over(partition by ORDER_NUMBER,MATDOC_MATERIAL_NO,BATCH_NUMBER_CHARG,cpudt order by cpudt,CPUTM) As MATDOC_ORDER_SEQUENCE
   FROM
        {{ ref('ODS__SAPAPI__ZCDV_T_CMTU090_AUFK') }} AUFK,
        {{ ref('ODS__SAPAPI__ZCDV_T_CMTU025_MATDOC') }} MATDOC
  WHERE
        MATDOC.AUFNR=AUFK.AUFNR
        AND matdoc.bwart='261'
        AND matdoc.sobkz='W'
        AND cancelled!='true'
   ORDER BY POSTING_DATE_IN_THE_DOCUMENT
),
sales_document As
(
    SELECT
        VBAP_SALES_DOCUMENT,
        SALES_DOC_TYPE_DESC,
        SALES_DOCUMENT_ITEM_POSNR,
        SD2.SALES_QTY AS SALES_DOC_QTY,
        VBAK_SOLD_TO_PARTY,
        SHIP_TO_PARTY,
        DISPOSITION,
        TOOL_SERIAL_NO,
        MATERIAL_NUMBER,
        VBAP_MATERIAL_GROUP_2,
        CUSTOMER_REFERENCE,
        VBAP_NCDR_NUMBER,
        NCDR_FLAG,
        NCDR_ITEM,
        NCDR_REQUESTOR,
        NCDR_STATUS,
        NCDR_PARTS_READY_BY_FACTORY,
        VBAP_ORDER_REASON,
        CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
        VBAP_DELIVERY_CREATE_DATE,
        VBAP_BATCH_NUMBER,
        VBAK_SALES_DOCUMENT_TYPE,
        PROFIT_CENTER_FOR_BILLING,
        VBAP_COST_CENTER,
        SERVICE_CRM_WO_NO,
        VBAK_SALES_DOCUMENT,
        VBAP_WORK_BREAKDOWN_STRUCTURE_ELEMENT,
        VBAK_SALES_CATEGORY,
        VBAP_SALES_CATEGORY,
        VBAK_DELIVERY_CERATOR,
        base_table.ps_psp_pnr_new,
        row_number() over(
            partition by 
                VBAP_SALES_DOCUMENT,
                MATERIAL_NUMBER,
                CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS,
                VBAP_DELIVERY_CREATE_DATE 
            order by VBAP_DELIVERY_CREATE_DATE, vbap_entry_time
        ) AS SALES_ORDER_SEQUENCE,
        BILLING_BLOCK_FOR_ITEM
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_DELIVERY_LINE') }} SD1,
            vbap_cte base_table,
            (SELECT
                VBAP_SALES_DOCUMENT As sd2_doc,
                MATERIAL_NUMBER As sd2_mat,
                VBAP_BATCH_NUMBER As sd2_bat,
                VBAP_DELIVERY_CREATE_DATE As sd2_date,
                sum(CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS) As SALES_QTY
            FROM {{ ref('COMMON__SAPH__SALES_ORDER_DELIVERY_LINE') }} SD2
            WHERE VBAK_SALES_ORGANIZATION='3200'
                AND VBAP_MATERIAL_GROUP<>'Z140'
                AND trim(REASON_FOR_REJECTION_OF_SALES_DOCUMENTS)=''
            GROUP BY
               VBAP_SALES_DOCUMENT,
                MATERIAL_NUMBER,
                VBAP_BATCH_NUMBER,
                VBAP_DELIVERY_CREATE_DATE
            ) AS SD2
        WHERE
            base_table.vbeln=SD1.VBAP_SALES_DOCUMENT
            AND base_table.POSNR=SD1.SALES_DOCUMENT_ITEM_POSNR
            AND  SD1.VBAP_SALES_DOCUMENT=SD2.sd2_doc
            AND SD1.MATERIAL_NUMBER=SD2.sd2_mat
            AND SD1.VBAP_BATCH_NUMBER=SD2.sd2_bat
            AND SD1.VBAP_DELIVERY_CREATE_DATE=SD2.sd2_date
            AND VBAK_SALES_ORGANIZATION='3200'
            AND VBAP_MATERIAL_GROUP<>'Z140'
            AND trim(REASON_FOR_REJECTION_OF_SALES_DOCUMENTS)=''
),
source_data As

        SD.TOOL_SERIAL_NO AS SAP_TOOL_SERIAL_NO,
        NOW.MACHINE_SYSTEM_TYPE AS MACHINE_SYSTEM_TYPE,
        SD.VBAP_ORDER_REASON AS SAP_ORDER_REASON,
        NOW.REASON AS NOW_ORDER_REASON,
        WP.TEL_WO_ORDEREDQTY AS CRM_ORDERED_QTY,
        WP.MSDYN_QUANTITY AS CRM_INSTALLED_QTY,
        SD.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS AS SAP_CONSUMED_QTY,
        NOW.REGION AS REGION,
        NOW.REGIONAL_APPROVER AS REGIONAL_APPROVER_NAME,
        CAST(NOW.REGIONALLY_APPROVED_DATE AS DATE) AS REGIONALLY_APPROVED_DATE,
        CASE WHEN (trim(NOW.GLOBAL_APPROVER) ='' OR NOW.GLOBAL_APPROVER IS NULL) THEN 'No' ELSE 'Yes' END AS GLOBAL_APPROVAL,
        NOW.GLOBAL_APPROVER AS GLOBAL_APPROVER,
        NOW.GLOBALLY_APPROVED_DATE AS GLOBAL_APPROVAL_DATE,
        NOW.APPROVED AS APPROVED,
        SD.DISPOSITION AS DISPOSITION,
        CASE WHEN (DD.DDTEXT='Value' OR DD.DDTEXT IS NULL) THEN 'N/A' ELSE DD.DDTEXT END AS DISPOSITION_TEXT,
        SD.TOOL_SERIAL_NO = WO.WO_PRODUCTSNNAME AS SAP_CRM_TOOL_SERIAL_NO_MATCH_FLAG,
        SD.VBAP_NCDR_NUMBER = NOW.NCDR AS SAP_NOW_NCDR_MATCH_FLAG,
        SD.NCDR_FLAG AS NCDR_FLAG,
        now.line_number AS NOW_NCDR_ITEM,
        now.requestor AS NOW_REQUESTOR,
        EMPLOYEE.SUPERVISOR_NAME AS SUPERVISOR_NAME,
        SD.NCDR_STATUS AS SAP_STATUS,
        now.MACHINE_WARR_STATUS AS NOW_MACHINE_WARR_STATUS,
        now.MACHINE_STATUS_CODE AS NOW_MACHINE_STATUS_CODE,
        PRPS.PRCTR AS PROFIT_CENTER,
        PRPS.FKSTL AS COST_CENTER,
        PRPS.POSKI AS WBS_ELEMENT,
        MAX_DELIVERY_DATE.LIKP_ACTUAL_GOODS_MOVEMENT_DATE AS ACTUAL_GOODS_MOVEMENT_DATE,
        MATDOC_DETAILS.POSTING_DATE_IN_THE_DOCUMENT AS POSTING_DATE_IN_DOCUMENT,
        MD.STANDARD_PRICE AS STANDARD_PRICE,
        MD.BASE_UNIT_OF_MEASURE AS BASE_UNIT,
        (SD.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS*MD.STANDARD_PRICE) AS TOTAL_AMOUNT,
        (TOTAL_AMOUNT*1.09) AS MARKUP_AMOUNT,
        MATDOC_DETAILS.BATCH_NUMBER_CHARG AS BATCH_NUMBER_CHARG,
        NOW.QUANTITY AS QTY_NOW,
        CASE
            WHEN NOW.REASON='FCN/SI' THEN '69'
            WHEN NOW.REASON='Start Up Trouble' THEN '65'
            WHEN NOW.REASON='Pre Warranty' THEN '65'
            WHEN NOW.REASON='Under Warranty' THEN '66'
            WHEN NOW.REASON='Sales Concession' THEN '6A'
            WHEN NOW.REASON='Factory Concession' THEN '68'
            WHEN NOW.REASON='Strategic Sales Concession/Equipment BU and FS Sales' THEN '6A'
            WHEN NOW.REASON='Evaluation Machine' THEN '67'
            WHEN NOW.REASON='Under Warranty after Modification' THEN '66'
            WHEN NOW.REASON='R&D Parts' THEN 'TBD'
            WHEN NOW.REASON='Short Ship' THEN 'N/A'
            WHEN NOW.REASON='FS : Short Ship' THEN 'N/A'
            WHEN NOW.REASON='FS : Sales' THEN 'TBD'
            WHEN NOW.REASON='FS : Factory' THEN 'TBD'
            WHEN NOW.REASON='FS: FRF/CUE/Mods Genpo Concession' THEN 'TBD'
            WHEN NOW.REASON='Prorated Part Warranty' THEN 'N/A'
            WHEN NOW.REASON='Modification Trouble' THEN 'TBD'
            WHEN NOW.REASON='Spare Part Warranty' THEN 'TBD'
            WHEN NOW.REASON='Rental Machine Pre Warranty' THEN 'TBD'
            WHEN NOW.REASON='FCN/SI Inventory Arrangement' THEN 'TBD'
            WHEN NOW.REASON='Non-Strategic Sales Concession / Genpo' THEN 'TBD'
            WHEN NOW.REASON='Strategic Sales Concession/Equipment BU and FS Sales' THEN 'TBD'
            ELSE 'N/A' END AS NOW_SALES_CATEGORY,
        CASE
            WHEN NOW.REASON='FCN/SI' THEN 'FCN'
            WHEN NOW.REASON='Start Up Trouble' THEN 'SUP'
            WHEN NOW.REASON='Pre Warranty' THEN 'PRW'
            WHEN NOW.REASON='Under Warranty' THEN 'WTY'
            WHEN NOW.REASON='Sales Concession' THEN 'TEL'
            WHEN NOW.REASON='Factory Concession' THEN 'FAC'
            WHEN NOW.REASON='Strategic Sales Concession/Equipment BU and FS Sales' THEN 'SSP'
            WHEN NOW.REASON='Evaluation Machine' THEN 'EVL'
            WHEN NOW.REASON='Under Warranty after Modification' THEN 'WTY'
            WHEN NOW.REASON='R&D Parts' THEN 'EVL?'
            WHEN NOW.REASON='Short Ship' THEN 'N/A'
            WHEN NOW.REASON='FS : Short Ship' THEN 'N/A'
            WHEN NOW.REASON='FS : Sales' THEN 'Not Defined'
            WHEN NOW.REASON='FS : Factory' THEN 'Not Defined'
            WHEN NOW.REASON='FS: FRF/CUE/Mods Genpo Concession' THEN 'Not Defined'
            WHEN NOW.REASON='Prorated Part Warranty' THEN 'PPW'
            WHEN NOW.REASON='Modification Trouble' THEN 'Not Defined'
            WHEN NOW.REASON='Spare Part Warranty' THEN 'Not Defined'
            WHEN NOW.REASON='Rental Machine Pre Warranty' THEN 'Not Defined'
            WHEN NOW.REASON='FCN/SI Inventory Arrangement' THEN 'Not Defined'
            WHEN NOW.REASON='Non-Strategic Sales Concession / Genpo' THEN 'GNP'
            WHEN NOW.REASON='Strategic Sales Concession/Equipment BU and FS Sales' THEN 'GNS'
            ELSE 'N/A' END AS NOW_SALES_CATEGORY_NAME,
        VBAP_SALES_CATEGORY AS SAP_SALES_CATEGORY,
        SC.SAP_SALES_CATEGORY_NAME AS SAP_SALES_CATEGORY_NAME,
        end_user_details.CUSTOMER_NUMBER AS END_USER,
        KNA2.NAME_1 AS END_USER_NAME,
        SD.NCDR_ITEM AS SAP_NCDR_ITEM,
        SD.VBAK_DELIVERY_CERATOR AS DELIVERY_CREATOR,
        --this field is populated only for order types ZSR0 and ZSR1 as these order types dont have NCDR number in SAP and NOW, if we populate this field for other order types then it increases the grain
        CASE 
            WHEN SD.VBAK_SALES_DOCUMENT_TYPE in ('ZSR0','ZSR1') 
                THEN WP.WO_NCDRNO 
            ELSE NULL 
        END as CRM_NCDR_NO,
        NULLIF(SD.BILLING_BLOCK_FOR_ITEM, '') AS BILLING_BLOCK_FOR_ITEM,
        -- simple fix for issue CAS-189847-B1V7D3, long term this model will be replaced by NCDR_SAPH
        NOW.CUSTOMER_ID as NOW_CUSTOMER_ID,
        NOW.CUSTOMER as NOW_CUSTOMER_NAME,
        NOW.MACHINE_SERIAL_NUMBER as NOW_TOOL_SERIAL_NO,
    FROM {{ ref('ODS__NOW__NOWDATA') }} NOW
    -- In the vast majority of cases, a LEFT join will work.
    -- Returns are the exception.
    -- ZPR2 records where DISPO = 20 (returns) only exist in SAP
    -- and cannot link using the ncdr number. We want to include those.
    -- See the WHERE clause for record filter critiera.
    FULL OUTER JOIN sales_document SD ON (
        NOW.PART_NUMBER=SD.MATERIAL_NUMBER AND 
      (
        TRIM(REGEXP_REPLACE(NCDR15, '[^[:digit:]]', ' '))=TRIM(REGEXP_REPLACE(sd.VBAP_NCDR_NUMBER, '[^[:digit:]]', ' '))
        OR
        try_to_number(
            TRIM(REGEXP_REPLACE(NCDR15, '[^[:digit:]]', ' '))
        )=try_to_number(TRIM(REGEXP_REPLACE(sd.VBAP_NCDR_NUMBER, '[^[:digit:]]', ' '))))
    )
    LEFT JOIN end_user_details ON (
        end_user_details.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER=SD.VBAP_SALES_DOCUMENT
    )
    LEFT JOIN {{ ref('COMMON__SAPH__MATERIAL_PRICING_GROUP2') }} AS MPG ON (
        SD.VBAP_MATERIAL_GROUP_2 = MPG.material_group_2
    )
    LEFT JOIN (
        SELECT DOMVALUEL,DDTEXT 
        FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU120_DD07T_POSAR') }}
        WHERE DOMNAME = 'ZD_ZZDISP2'
    ) AS DD ON SD.DISPOSITION = DD.DOMVALUEL
    LEFT JOIN MATDOC_DETAILS MATDOC_DETAILS
        ON sd.MATERIAL_NUMBER=MATDOC_DETAILS.MATDOC_MATERIAL_NO
            AND (SD.CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS=MATDOC_DETAILS.MATDOC_QTY OR sd.SALES_DOC_QTY=MATDOC_DETAILS.MATDOC_QTY)
            AND sd.VBAP_SALES_DOCUMENT=MATDOC_DETAILS.AUFK_SALES_ORDER_HEADER
            AND sd.VBAP_BATCH_NUMBER=MATDOC_DETAILS.BATCH_NUMBER_CHARG
            AND sd.SALES_ORDER_SEQUENCE=MATDOC_DETAILS.MATDOC_ORDER_SEQUENCE
            AND sd.VBAP_DELIVERY_CREATE_DATE=matdoc_details.CREATEDDATE
    LEFT JOIN MAX_DELIVERY_DATE
        ON SD.VBAK_SALES_DOCUMENT = MAX_DELIVERY_DATE.LIPS_DOCUMENT_NUMBER_OF_THE_REFERENCE_DOCUMENT
            AND  SD.SALES_DOCUMENT_ITEM_POSNR = MAX_DELIVERY_DATE.LIPS_ITEM_NUMBER_OF_THE_REFERENCE_ITEM
    LEFT JOIN {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }} KNA1
        ON SD.VBAK_SOLD_TO_PARTY = KNA1.CUSTOMER_NUMBER
    LEFT JOIN {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }} KNA2
        ON end_user_details.CUSTOMER_NUMBER=KNA2.CUSTOMER_NUMBER
    LEFT JOIN {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }} SC
        ON SC.SAP_SALES_CATEGORY=SD.VBAP_SALES_CATEGORY
    LEFT JOIN (SELECT MARA_MATERIAL_NUMBER,MATERIAL_DESCRIPTION,STANDARD_PRICE, BASE_UNIT_OF_MEASURE FROM {{ ref('COMMON__SAPH__MATERIAL_VALUATION_MASTER_CODED') }}
                WHERE VALUATION_AREA='3200') MD
        ON SD.MATERIAL_NUMBER=MD.MARA_MATERIAL_NUMBER
    LEFT JOIN {{ ref('ODS__CRM_FILE__MSDYN_WORKORDER') }} WO
        ON SD.SERVICE_CRM_WO_NO = WO.MSDYN_NAME
    LEFT JOIN {{ ref('ODS__CRM_FILE__MSDYN_WORKORDERPRODUCT') }} AS WP
        ON  WO.MSDYN_WORKORDERID=WP.MSDYN_WORKORDER
            AND SD.MATERIAL_NUMBER = WP.MSDYN_PRODUCTNAME
    LEFT JOIN {{ ref('ODS__CRM_FILE__MSDYN_PURCHASEORDER') }} As po
        ON TRIM(REGEXP_REPLACE(sd.VBAP_NCDR_NUMBER, '[^[:digit:]]', ' '))=po.tel_wo_ncdrno
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU040_PRPS') }} PRPS
        ON TRY_TO_NUMBER(SD.ps_psp_pnr_new) = TRY_TO_NUMBER(PRPS.PSPNR_NEW)
    LEFT JOIN
    (
        SELECT
            EMPLOYEE_ID AS EMPLOYEE_ID,
            SUPERVISOR_NAME AS SUPERVISOR_NAME
        FROM
            {{ ref('COMMON__SHARED_DATASETS__GLOBAL_EMPLOYEE') }}
    ) AS EMPLOYEE
        ON EMPLOYEE.EMPLOYEE_ID=NOW.REQUESTOR_EMP_NO
    WHERE 
    -- If a record exists in NOW, it must satsify the following critiera 
    (NOW.AREA='TEA' AND  NOW.CANCELLED='No' AND NOW.APPROVED!='No') OR
    -- If the NCDR number is blank in SAP, we can't match to NOW data.
    -- We still want to include NCDR returns (ZPR2 + Dispoition = 20)
    (SD.VBAK_SALES_DOCUMENT_TYPE = 'ZPR2' AND SD.DISPOSITION = '20') OR
    (SD.VBAK_SALES_DOCUMENT_TYPE in ('ZSR0','ZSR1'))
    ORDER BY SALES_DOCUMENT,SALES_DOCUMENT_LINE,MATERIAL_NUMBER
),

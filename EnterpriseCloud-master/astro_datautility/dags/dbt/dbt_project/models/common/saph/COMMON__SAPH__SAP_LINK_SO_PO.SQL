{{ config(
            materialized='incremental',
            incremental_strategy='insert_overwrite',
            alias='SAP_LINK_SO_PO',
            transient=false    
) }}

WITH 
SOURCE_DATA AS (
    SELECT 
        VBFA.VBELV AS SO_HDR, 
        VBFA.POSNV AS SO_LINE,
        TRY_TO_DATE(VBAP.ERDAT, 'YYYYMMDD') AS SO_RECORD_DATE,
        VBFA.VBELN AS PO_HDR, 
        VBFA.POSNN AS PO_LINE,
        TRY_TO_DATE(EKKO.AEDAT, 'YYYYMMDD') AS PO_RECORD_DATE,
        VBAP.MATNR AS SO_MATNR,
        EKPO.MATNR AS PO_MATNR,
        VBAP.KWMENG AS SO_QTY,
        EKPO.MENGE AS PO_QTY,
        VBAK.AUART AS SO_DOC_TYPE,
        EKKO.BSART AS PO_DOC_TYPE,
        EKPO.LGORT AS PO_SLOC,
        T001L.SLOC_DESC,
        VBFA.ERDAT AS LINK_RECORD_DATE
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU064_VBFA') }} AS VBFA
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU028_EKPO') }} AS EKPO ON (
        EKPO.EBELN = VBFA.VBELN AND LTRIM(EKPO.EBELP, '0') = LTRIM(VBFA.POSNN, '0')
    )
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU027_EKKO') }} AS EKKO ON (
        EKKO.EBELN = VBFA.VBELN
    )
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} AS VBAP ON (
        VBAP.VBELN = VBFA.VBELV AND 
        LTRIM(VBAP.POSNR, '0') = LTRIM(VBFA.POSNV, '0')
    )
    JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} AS VBAK ON (
        VBAK.VBELN = VBFA.VBELV
    )
    LEFT JOIN (
        SELECT LGORT, MAX(LGOBE) AS SLOC_DESC
        FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU080_T001L') }} AS T001L
        GROUP BY LGORT
    ) AS T001L ON (T001L.LGORT = EKPO.LGORT)
    -- Subsequent document (indicated by VBTYP_N) is a purchase order
    -- Preceding document (indicated by VBTYP_V) is a sales order
    WHERE VBFA.VBTYP_N = 'V' AND VBFA.VBTYP_V = 'C'
),
TRANSFORM_DATA AS (
    SELECT 
        SO_HDR,
        SO_LINE,
        SO_RECORD_DATE,
        PO_HDR,
        PO_LINE,
        PO_RECORD_DATE,
        SO_MATNR,
        PO_MATNR,
        SO_QTY,
        PO_QTY,
        SO_DOC_TYPE,
        PO_DOC_TYPE,
        PO_SLOC,
        SLOC_DESC,
        LINK_RECORD_DATE,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH 
    FROM SOURCE_DATA
),
TYPE_DATA AS (
    SELECT 
        CAST(SO_HDR AS VARCHAR(16777216)) AS SO_HDR,
        CAST(SO_LINE AS VARCHAR(16777216)) AS SO_LINE,
        CAST(SO_RECORD_DATE AS DATE) AS SO_RECORD_DATE,
        CAST(PO_HDR AS VARCHAR(16777216)) AS PO_HDR,
        CAST(PO_LINE AS VARCHAR(16777216)) AS PO_LINE,
        CAST(PO_RECORD_DATE AS DATE) AS PO_RECORD_DATE,
        CAST(SO_MATNR AS VARCHAR(16777216)) AS SO_MATNR,
        CAST(PO_MATNR AS VARCHAR(16777216)) AS PO_MATNR,
        CAST(SO_QTY AS INT) AS SO_QTY,
        CAST(PO_QTY AS INT) AS PO_QTY,
        CAST(SO_DOC_TYPE AS VARCHAR(16777216)) AS SO_DOC_TYPE,
        CAST(PO_DOC_TYPE AS VARCHAR(16777216)) AS PO_DOC_TYPE,
        CAST(PO_SLOC AS VARCHAR(16777216)) AS PO_SLOC,
        CAST(SLOC_DESC AS VARCHAR(16777216)) AS SLOC_DESC,
        CAST(LINK_RECORD_DATE AS DATE) AS LINK_RECORD_DATE,
        CAST(AUDIT_LOG_ID AS VARCHAR(16777216)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(16777216)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)
SELECT * FROM TYPE_DATA
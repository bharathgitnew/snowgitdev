{{ config(
        alias = 'MATERIAL_MASTER_3PL',
        materialized='incremental',
        incremental_strategy = 'insert_overwrite',
        transient = false
) }}

with source_data as
(
    SELECT    
        mat_3pl.MATERIAL_NUMBER,
        mat_3pl.MARA_MATERIAL_DESCRIPTION,
        mat_3pl.MARA_UOM,
        mat_3pl.STANDARD_PRICE,
        mat_3pl.UNNUM1,
        mat_3pl.MARA_FILEDATE,
        mat_3pl.COST_FILEDATE,
        mat_3pl.GTM_FILEDATE,
        mat_3pl.FINAL_UPDATE_DATE,
        mat_3pl.SNAPSHOT_DATE,
        marc.SERNP AS SERIAL_NUMBER_PROFILE,
        marc.WERKS AS MARC_PLANT
    FROM {{ ref('ODS__SAPAPI__MATERIAL_MASTER_3PL') }} mat_3pl
        LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU026_MARC') }} marc
        ON mat_3pl.MATERIAL_NUMBER = marc.MATNR
),
transform_data as (
    SELECT
        MATERIAL_NUMBER,
        MARA_MATERIAL_DESCRIPTION,
        MARA_UOM,
        STANDARD_PRICE,
        UNNUM1,
        MARA_FILEDATE,
        COST_FILEDATE,
        GTM_FILEDATE,
        FINAL_UPDATE_DATE,
        SNAPSHOT_DATE,
        SERIAL_NUMBER_PROFILE,
        CASE WHEN SERIAL_NUMBER_PROFILE='Z002' THEN 'Y' ELSE 'N' end AS SERIALIZED,
        CASE
            WHEN SERIAL_NUMBER_PROFILE='Z002' THEN 0
            WHEN (STANDARD_PRICE IS NOT NULL AND TRIM(STANDARD_PRICE)!='' and STANDARD_PRICE>30) THEN 0 
            ELSE 1 
        END AS BIN_BULK_INDICATOR,
        MARC_PLANT,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') as _ROW_HASH
    FROM source_data
),
type_data as (
select
    CAST(MATERIAL_NUMBER AS VARCHAR(16777216)) AS MATERIAL_NUMBER,
    CAST(MARA_MATERIAL_DESCRIPTION AS VARCHAR(16777216)) AS MARA_MATERIAL_DESCRIPTION,
    CAST(MARA_UOM AS VARCHAR(16777216)) AS MARA_UOM,
    CAST(STANDARD_PRICE AS VARCHAR(16777216)) AS STANDARD_PRICE,
    CAST(UNNUM1 AS VARCHAR(16777216)) AS UNNUM1,
    CAST(SERIAL_NUMBER_PROFILE AS VARCHAR(16777216)) AS SERIAL_NUMBER_PROFILE,
    CAST(SERIALIZED AS VARCHAR(1)) AS SERIALIZED,
    CAST(BIN_BULK_INDICATOR AS VARCHAR(1)) AS BIN_BULK_INDICATOR,
    CAST(MARC_PLANT AS VARCHAR(16777216)) AS MARC_PLANT,
    CAST(MARA_FILEDATE AS VARCHAR(16777216)) AS MARA_FILEDATE,
    CAST(COST_FILEDATE AS VARCHAR(16777216)) AS COST_FILEDATE,
    CAST(GTM_FILEDATE AS VARCHAR(16777216)) AS GTM_FILEDATE,
    CAST(FINAL_UPDATE_DATE AS DATE) AS FINAL_UPDATE_DATE,
    CAST(SNAPSHOT_DATE AS DATE) AS SNAPSHOT_DATE,
    CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
from transform_data
)

select * from type_data
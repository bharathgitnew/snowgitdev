    CLASSIFICATION_TEXT,
    SALES_UNIT,
    RETURN_FLAG,
    ABC_GLOBAL,
    ABC_LOCAL,
    ABC_INTEL,
    LEAP_FLAG,
    LEAP_FLAG_TEXT,
    MANUFACTURER_NAME,
    EXPORT_REGULATION_FLAG,
    PROFIT_CENTER,
    PLANT,
    PERIOD_FOR_SLED,
    TOTAL_SHELF_LIFE,
    MIN_REMAINING_SHELF_LIFE,
    SN_PROFILE,
    EBIZ_DISCLOSURE_CLASSIFICATION_BY_SUPPLIER,
    EBIZ_DISCLOSURE_CLASSIFICATION,
    PLANT_SPECIFIC_MATERIAL_STATUS,
    DISTRIBUTION_CHAIN_SPECIFIC_MATERIAL_STATUS,
    ORDER_ITEM_NAME,
    VALUATION_AREA
FROM {{ ref('COMMON__REPORTS__MASTER_MATERIAL_REPORT') }} 
)

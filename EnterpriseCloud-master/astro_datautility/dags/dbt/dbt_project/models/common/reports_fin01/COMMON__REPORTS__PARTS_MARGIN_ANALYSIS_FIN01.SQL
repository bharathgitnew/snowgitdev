WITH BP as (
SELECT DISTINCT
    CUSTOMER_NUMBER,
    CUSTOMER_FLAG,
    POSTAL_CODE
FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
WHERE CUSTOMER_FLAG = 'Y'
)
,COORDINATES AS (
SELECT 
    POSTAL_CODE,
    PLACE_NAME AS CITY,
    ADMIN_CODE1 AS STATE,
    LATITUDE,
    LONGITUDE
FROM {{ ref('ODS__FILE__OPENDATASOFT_POSTALCODE_GEODATA') }}
WHERE COUNTRY_CODE='US'
)
,SOURCE_DATA_DASL as (
SELECT 
    COMPANY_CODE,
    ACCOUNTING_DOCUMENT_LINE,
    SALES_ORDER_LINE,
    ACCOUNT_TYPE,
    ACCOUNT_DESCRIPTION,
    ACCOUNT_NUMBER,
    ACCOUNT_NAME,
    WBS_CATEGORY,
    PROFIT_CENTER,
    COST_CENTER,
    FISCAL_YEAR,
    FINANCIAL_PERIOD,
    CALENDAR_YEAR_MONTH,
    POSTING_DATE,
    DOCUMENT_DATE,
    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    PRODUCT_TYPE_CATEGORY,
    END_USER,
    END_USER_NAME,
    END_USER_GROUP,
    END_USER_CITY,
    END_USER_REGION,
    LEFT(BP.POSTAL_CODE,5) AS POSTAL_CODE,
    COORDINATES.LATITUDE,
    COORDINATES.LONGITUDE,
    IFNULL(MATERIAL_NUMBER,'-1') AS MATERIAL_NUMBER,
    PNL_CATEGORY,
    FINAL_QUANTITY,
    AMOUNT_IN_COMPANY_CODE_CURRENCY
FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE_FIN01') }} 
LEFT JOIN BP ON END_USER=BP.CUSTOMER_NUMBER
LEFT JOIN COORDINATES ON LEFT(BP.POSTAL_CODE,5)=COORDINATES.POSTAL_CODE
)
,SOURCE_DATA_MM AS (
SELECT DISTINCT
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    MATERIAL_TYPE,
    MATERIAL_TYPE_TEXT,

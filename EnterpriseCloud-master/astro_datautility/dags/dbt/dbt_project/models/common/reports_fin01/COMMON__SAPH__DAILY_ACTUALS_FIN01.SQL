        AND ACDOCA.FISCAL_YEAR = BKPF.FISCAL_YEAR
        AND ACDOCA.ACCOUNTING_DOCUMENT_NUMBER = BKPF.ACCOUNTING_DOCUMENT
    LEFT JOIN BSET
        ON ACDOCA.COMPANY_CODE = BSET.COMPANY_CODE
        AND ACDOCA.FISCAL_YEAR = BSET.FISCAL_YEAR
        AND ACDOCA.ACCOUNTING_DOCUMENT_NUMBER = BSET.ACCOUNTING_DOCUMENT
        AND TRY_TO_NUMBER(ACDOCA.SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER) = TRY_TO_NUMBER(BSET.ACCOUNTING_DOCUMENT_LINE)
    LEFT OUTER JOIN date_dimension as D_Date 
        ON (try_to_date(ACDOCA.POSTING_DATE_IN_THE_DOCUMENT,'YYYYMMDD') = D_Date.CALENDAR_DATE)
    LEFT OUTER JOIN account_type 
        ON (ACDOCA.ACCOUNT_NUMBER = account_type.SAKNR)
    LEFT OUTER JOIN billing_type_text    
        ON (ACDOCA.BILLING_TYPE=billing_type_text.FKART)
    LEFT OUTER JOIN customer_detail
        ON (ACDOCA.CUSTOMER_NUMBER= CUSTOMER_DETAIL.CUSTOMER_NUMBER)
    LEFT OUTER JOIN mdm_customer
        ON right(left(ACDOCA.CUSTOMER_NUMBER,7),5) = mdm_customer.CUSTOMERCODE
    LEFT JOIN vendor
        ON ACDOCA.ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR = VENDOR.LFA1_ACCOUNT_NUMBER_OF_VENDOR_OR_CREDITOR
    LEFT OUTER JOIN material_plant_master as MATERIAL_PLANT_MASTER
        ON (ACDOCA.MATERIAL_NUMBER=MATERIAL_PLANT_MASTER.MARA_MATERIAL_NUMBER)
    LEFT OUTER JOIN cost_center
        ON (ACDOCA.COST_CENTER=cost_center.COST_CENTER_CODE)
    LEFT OUTER JOIN profit_center
        ON (ACDOCA.PROFIT_CENTER=profit_center.PROFIT_CENTER_CODE)
    LEFT OUTER JOIN wbs_code_description
        ON (WBS_CATEGORY=wbs_code_description.WBS_CODE)
    LEFT OUTER JOIN WBS_MASTER  
        ON (ACDOCA.WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_POSID = WBS_MASTER.WORK_BREAKDOWN_STRUCTURE_ELEMENT)
    WHERE ACDOCA.LEDGER_IN_GENERAL_LEDGER_ACCOUNTING='0L'

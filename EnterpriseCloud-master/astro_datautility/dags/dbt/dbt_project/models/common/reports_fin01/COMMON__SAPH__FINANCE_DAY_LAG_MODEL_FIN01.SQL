WITH SCHEDULE_DATE AS (
SELECT 
VBELN AS SALES_DOCUMENT,
POSNR AS SALES_DOCUMENT_ITEM,
TRY_TO_DATE(EDATU,'YYYYMMDD') AS SCHEDULE_LINE_DATE
FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU011_VBEP') }}
)
, SO AS (
SELECT 
    TRANSACTION_ID,
    TRANSACTION_ID_ITEM,
    VBAK_SALES_DOCUMENT,
    SALES_DOCUMENT_ITEM_POSNR,
    LIPS_DELIVERY AS DELIVERY_DOCUMENT,
    DELIVERY_ITEM_POSNR AS DELIVERY_DOCUMENT_ITEM,
    VBAK_SALES_DOCUMENT_TYPE AS SALES_DOCUMENT_TYPE,
    NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY AS SALES_ORDER_ITEM_AMOUNT,
    NET_VALUE_OF_THE_ORDER_ITEM_IN_DOCUMENT_CURRENCY AS DELIVERY_ORDER_ITEM_AMOUNT,
    ACTUAL_QUANTITY_DELIVERED,
    CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS AS SAP_SO_QUANTITY,
    VBAP_NET_PRICE AS NET_PRICE,
    MATERIAL_NUMBER,
    VBAP_SALES_CATEGORY,
    ACTUAL_GOODS_MOVEMENT_DATE,
    SCHEDULE_DATE.SCHEDULE_LINE_DATE
FROM {{ ref('COMMON__SAPH__SALES_ORDER_DELIVERY_LINE') }} SODL
LEFT JOIN SCHEDULE_DATE 
ON SODL.VBAK_SALES_DOCUMENT=SCHEDULE_DATE.SALES_DOCUMENT
AND SODL.SALES_DOCUMENT_ITEM_POSNR=SCHEDULE_DATE.SALES_DOCUMENT_ITEM
WHERE VBAK_SALES_DOCUMENT_TYPE IN ('ZP12','ZPR2')
)
,ROSETTA AS (
SELECT 
    TEL_PART_NUMBER,
    QUANTITY AS ROSETTA_QUANTITY,
    CONSUMABLE_FLAG,
    DATE_CONSUMED,
    CONTACT_NAME,
    CUSTOMER_TRANSACTION_ID,
    CUSTOMER_TRANSACTION_LINE_ID
FROM {{ ref('COMMON__ROSETTA__CONSIGNMENT_TRANSACTION') }}
)
,MATERIAL AS (
    SELECT DISTINCT 
    MMR.MATERIAL_NUMBER,
    MMR.STANDARD_COST
    FROM {{ ref('COMMON__REPORTS__MASTER_MATERIAL_REPORT') }} MMR
)

,SO_JOIN AS (
SELECT
    TRANSACTION_ID,
    TRANSACTION_ID_ITEM,
    VBAK_SALES_DOCUMENT AS SALES_DOCUMENT,
    SALES_DOCUMENT_ITEM_POSNR AS SALES_DOCUMENT_ITEM,
    DELIVERY_DOCUMENT,
    DELIVERY_DOCUMENT_ITEM,
    SALES_DOCUMENT_TYPE,
    SO.MATERIAL_NUMBER,
    ACTUAL_QUANTITY_DELIVERED,
    SAP_SO_QUANTITY,
    ROSETTA_QUANTITY,
    STANDARD_COST,
    (STANDARD_COST*ACTUAL_QUANTITY_DELIVERED) AS TOTAL_STANDARD_COST,
    (SALES_ORDER_ITEM_AMOUNT/SAP_SO_QUANTITY) as SALES_ORDER_ITEM_AMOUNT,
    SALES_ORDER_ITEM_AMOUNT AS TOTAL_SALES_PRICE,
    (SALES_ORDER_ITEM_AMOUNT/SAP_SO_QUANTITY)*ACTUAL_QUANTITY_DELIVERED as DELIVERY_ORDER_ITEM_AMOUNT,
    sum(DELIVERY_ORDER_ITEM_AMOUNT) OVER (PARTITION BY DELIVERY_DOCUMENT,DELIVERY_DOCUMENT_ITEM ) AS TOTAL_DELIVERY_PRICE,
    ACTUAL_GOODS_MOVEMENT_DATE,
    SCHEDULE_LINE_DATE,
    DATE_CONSUMED
FROM SO
LEFT OUTER JOIN ROSETTA
ON TRY_TO_NUMBER(SO.TRANSACTION_ID) = TRY_TO_NUMBER(ROSETTA.CUSTOMER_TRANSACTION_ID)
AND TRY_TO_NUMBER(SO.TRANSACTION_ID_ITEM) = TRY_TO_NUMBER(ROSETTA.CUSTOMER_TRANSACTION_LINE_ID)
AND SO.MATERIAL_NUMBER = ROSETTA.TEL_PART_NUMBER
LEFT JOIN MATERIAL
ON MATERIAL.MATERIAL_NUMBER = SO.MATERIAL_NUMBER
WHERE 
ACTUAL_QUANTITY_DELIVERED<>0
)
,CUSTOMER AS (
SELECT DISTINCT
    BP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER as SALES_DOCUMENT,
    BP.ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_ITEM,
    BP.CUSTOMER_NUMBER AS CUSTOMER_NUMBER,
    CUSTOMER.NAME_1 as CUSTOMER_NAME
FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }} AS BP
    LEFT JOIN {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }} AS CUSTOMER
        ON BP.CUSTOMER_NUMBER = CUSTOMER.CUSTOMER_NUMBER
WHERE BP.PARTNER_FUNCTION = 'Z6'
)
,FINANCIALS AS(
SELECT DISTINCT
    TRANSACTION_ID,
    TRANSACTION_ID_ITEM,
    SO_JOIN.SALES_DOCUMENT,
    SO_JOIN.SALES_DOCUMENT_ITEM,
    SO_JOIN.DELIVERY_DOCUMENT,
    SO_JOIN.DELIVERY_DOCUMENT_ITEM,
    SO_JOIN.SALES_DOCUMENT_TYPE,
    SO_JOIN.MATERIAL_NUMBER,
    DASL.PROFIT_CENTER,
    DASL.WBS_ELEMENT,
    CUSTOMER.CUSTOMER_NUMBER,
    CUSTOMER.CUSTOMER_NAME,
    SO_JOIN.ACTUAL_QUANTITY_DELIVERED,
    SAP_SO_QUANTITY,
    ROSETTA_QUANTITY,
    CASE WHEN PNL_CATEGORY='Revenue' THEN SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) ELSE 0 END AS REVENUE,
    CASE WHEN PNL_CATEGORY='COGS' THEN SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) ELSE 0 END AS COGS,
    STANDARD_COST,
    TOTAL_STANDARD_COST,
    SALES_ORDER_ITEM_AMOUNT,
    TOTAL_SALES_PRICE,
    DELIVERY_ORDER_ITEM_AMOUNT,
    TOTAL_DELIVERY_PRICE,
    (DELIVERY_ORDER_ITEM_AMOUNT-TOTAL_STANDARD_COST) AS MARGIN,
    TRY_TO_DATE(ACTUAL_GOODS_MOVEMENT_DATE,'YYYYMMDD') AS ACTUAL_GOODS_MOVEMENT_DATE,
    TO_DATE(DATE_CONSUMED) AS DATE_CONSUMED,
    SCHEDULE_LINE_DATE
FROM SO_JOIN 
LEFT JOIN {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE_FIN01') }} DASL
ON SO_JOIN.SALES_DOCUMENT = DASL.SALES_DOCUMENT
AND SO_JOIN.SALES_DOCUMENT_ITEM = DASL.SALES_DOCUMENT_ITEM
LEFT JOIN CUSTOMER 
ON SO_JOIN.SALES_DOCUMENT = CUSTOMER.SALES_DOCUMENT
GROUP BY
    TRANSACTION_ID,
    TRANSACTION_ID_ITEM,
    SO_JOIN.SALES_DOCUMENT,
    SO_JOIN.SALES_DOCUMENT_ITEM,
    SO_JOIN.DELIVERY_DOCUMENT,
    SO_JOIN.DELIVERY_DOCUMENT_ITEM,
    SO_JOIN.SALES_DOCUMENT_TYPE,
    SO_JOIN.MATERIAL_NUMBER,
    DASL.PROFIT_CENTER,
    DASL.WBS_ELEMENT,
    STANDARD_COST,
    TOTAL_STANDARD_COST,
    SALES_ORDER_ITEM_AMOUNT,
    TOTAL_SALES_PRICE,
    DELIVERY_ORDER_ITEM_AMOUNT,
    TOTAL_DELIVERY_PRICE,
    CUSTOMER.CUSTOMER_NUMBER,
    CUSTOMER.CUSTOMER_NAME,
    PNL_CATEGORY,
    ACTUAL_QUANTITY_DELIVERED,
    SAP_SO_QUANTITY,
    ROSETTA_QUANTITY,
    ACTUAL_GOODS_MOVEMENT_DATE,
    DATE_CONSUMED,
    SCHEDULE_LINE_DATE
)
,SOURCE AS (
SELECT 
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    TRANSACTION_ID,
    TRANSACTION_ID_ITEM,
    SALES_DOCUMENT,
    SALES_DOCUMENT_ITEM,
    DELIVERY_DOCUMENT,
    DELIVERY_DOCUMENT_ITEM,
    SALES_DOCUMENT_TYPE,
    MATERIAL_NUMBER,
    PROFIT_CENTER,
    WBS_ELEMENT,
    CUSTOMER_NUMBER,
    CUSTOMER_NAME,
    CAST(STANDARD_COST AS NUMBER(38,2)) AS STANDARD_COST,
    CAST(TOTAL_STANDARD_COST AS NUMBER(38,2)) AS TOTAL_STANDARD_COST,
    CAST(SALES_ORDER_ITEM_AMOUNT AS NUMBER(38,2)) AS SALES_ORDER_ITEM_AMOUNT,
    CAST(TOTAL_SALES_PRICE AS NUMBER(38,2)) AS TOTAL_SALES_PRICE,
    CAST(DELIVERY_ORDER_ITEM_AMOUNT AS NUMBER(38,2)) AS DELIVERY_ORDER_ITEM_AMOUNT,
    CAST(TOTAL_DELIVERY_PRICE AS NUMBER(38,2)) AS TOTAL_DELIVERY_PRICE,
    CAST(MARGIN AS NUMBER(38,2)) AS MARGIN,
    SUM(REVENUE) AS REVENUE,
    SUM(COGS) AS COGS,
    CAST(ACTUAL_QUANTITY_DELIVERED AS NUMBER(38,0)) AS ACTUAL_QUANTITY_DELIVERED,
    CAST(SAP_SO_QUANTITY AS NUMBER(38,0)) AS SAP_SO_QUANTITY,
    CAST(ROSETTA_QUANTITY AS NUMBER(38,0)) AS ROSETTA_QUANTITY,
    CASE WHEN ACTUAL_GOODS_MOVEMENT_DATE IS NULL AND CUSTOMER_NAME NOT ILIKE 'INTEL%' THEN SCHEDULE_LINE_DATE
    ELSE ACTUAL_GOODS_MOVEMENT_DATE END AS ACTUAL_GOODS_MOVEMENT_DATE,
    DATE_CONSUMED,
    SCHEDULE_LINE_DATE
FROM FINANCIALS
GROUP BY ALL
)
SELECT * FROM SOURCE
WITH BP AS (
    SELECT
        SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER --VBELN
        , CUSTOMER_NUMBER --KUNNR
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }}
    WHERE PARTNER_FUNCTION = 'SP' --PARVW
)

, vbak as (
    select
        VKORG
        , ERDAT
        , VBELN
        , AUART
        , ZZCNZZ
        , NETWR
    from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU009_VBAK') }} 
    where IS_DELETED = 'No'
)

, vbap as (
    select 
        VBELN
        , POSNR
        , ZZPRCODE
    from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU010_VBAP') }} 
    where IS_DELETED = 'No'
)

, vbrp as (
    select
        VBELN
        , AUBEL
        , AUPOS
    from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU015_VBRP') }}
)

, vbrk as (
    select
        FKDAT
        , FKART
        , VBELN
        , ZUONR
        , VBTYP
        , NETWR
        , RFBSK
        , FKSTO
        , SFAKN
    from {{ ref('ODS__SAPAPI__ZCDV_T_CMTU014_VBRK') }}
)

, SOBL as (
    SELECT DISTINCT
        VBAK.VKORG AS SALES_ORGANIZATION
        , VBAK.ERDAT AS SO_CREATE_DATE
        , VBAK.VBELN AS SALES_DOCUMENT
        , VBAK.AUART AS SALES_DOCUMENT_TYPE
        , VBAK.ZZCNZZ AS CONTRACT_NUMBER
        , VBAK.NETWR AS SO_NET_VALUE
        , VBAP.ZZPRCODE AS PRODUCT_CODE
        , VBRK.FKDAT AS BILLING_DATE
        , VBRK.FKART AS BILLING_TYPE
        , VBRK.VBELN AS BILLING_DOCUMENT
        , VBRK.ZUONR AS VRBK_ASSIGNMENT_NUMBER
        , VBRK.VBTYP AS BILLING_DOCUMENT_CATEGORY
        , VBRK.NETWR AS BILLING_NET_VALUE
        , VBRK.RFBSK as STATUS_FOR_TRANSFER_TO_ACCOUNTING
        , VBRK.FKSTO as BILLING_DOCUMENT_IS_CANCELED
        , VBRK.SFAKN as NUMBER_OF_CANCELED_BILLING_DOCUMENT
    FROM vbak 
        LEFT JOIN vbap
            ON try_to_number(vbak.VBELN) = try_to_number(vbap.VBELN)
        LEFT JOIN vbrp
            ON try_to_number(vbrp.AUBEL)= try_to_number(vbap.vbeln)
            AND try_to_number(vbrp.AUPOS) = try_to_number(vbap.POSNR)
        LEFT JOIN vbrk
            ON try_to_number(vbrk.VBELN) = try_to_number(vbrp.VBELN)
)

, ACDOCA AS (
    SELECT 
        ASSIGNMENT_NUMBER --ZUONR
        --, FISCAL_YEAR --GJAHR
        , SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) AS UPFRONT_PAYMENT --HSL
        , TRANSACTION_CURRENCY --RWCUR
    FROM {{ ref('COMMON__SAPH__UNIVERSAL_JOURNAL_ENTRY_LINE_FIN01') }}
    WHERE 1=1
        AND LEDGER_IN_GENERAL_LEDGER_ACCOUNTING = '0L'
        AND SPECIAL_G_L_INDICATOR = 'A' --UMSKZ
        AND DOCUMENT_TYPE = 'DA' --BLART
        AND TO_CHAR(TO_DATE(POSTING_DATE_IN_THE_DOCUMENT, 'YYYYMMDD'), 'YYYY-MM-DD') <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE())) --BUDAT
    GROUP BY
        ASSIGNMENT_NUMBER --ZUONR
       -- , FISCAL_YEAR --GJAHR
        , TRANSACTION_CURRENCY --RWCUR
),

ACDOCA_NEW AS (
    SELECT 
        ASSIGNMENT_NUMBER --ZUONR
        , SUM(AMOUNT_IN_COMPANY_CODE_CURRENCY) AS UPFRONT_PAYMENT_NEW 
        , TRANSACTION_CURRENCY --RWCUR
    FROM {{ref('COMMON__SAPH__UNIVERSAL_JOURNAL_ENTRY_LINE_FIN01')}}
    WHERE 1=1
        AND LEDGER_IN_GENERAL_LEDGER_ACCOUNTING = '0L'
        AND SPECIAL_G_L_INDICATOR = 'A' --UMSKZ
        AND DOCUMENT_TYPE IN ('DZ','ZR') --BLART
        AND ACCOUNT_NUMBER = '2130200001'
        AND TO_CHAR(TO_DATE(POSTING_DATE_IN_THE_DOCUMENT, 'YYYYMMDD'), 'YYYY-MM-DD') <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE())) --BUDAT
    GROUP BY
        ASSIGNMENT_NUMBER --ZUONR
        , TRANSACTION_CURRENCY --RWCUR
)

,BU_CODE AS (
    SELECT DISTINCT
        CONTRACT_NUMBER
        , LISTAGG(DISTINCT (case
                 when PRODUCT_CODE = '' then null
                 else PRODUCT_CODE
             end
             ), ', ') OVER (PARTITION BY CONTRACT_NUMBER) as BU_CODE
    FROM SOBL
    WHERE SALES_DOCUMENT_TYPE = 'ZSC1'
)

, TOTAL_CONTRACT_AMT AS (
    SELECT
        CONTRACT_NUMBER
        , SUM(SO_NET_VALUE) AS CONTRACT_VALUE
    FROM SOBL
    WHERE 1=1
        AND SALES_DOCUMENT_TYPE = 'ZSC1'
        AND SO_CREATE_DATE <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE())) 
    GROUP BY CONTRACT_NUMBER
)

, BILLING AS (
    SELECT DISTINCT
        SALES_DOCUMENT
        , STATUS_FOR_TRANSFER_TO_ACCOUNTING
        , BILLING_DOCUMENT
        , BILLING_DATE
        , BILLING_DOCUMENT_CATEGORY --VBTYP
        , BILLING_NET_VALUE
        , BILLING_DOCUMENT_IS_CANCELED
    from sobl
    where 1=1
        AND STATUS_FOR_TRANSFER_TO_ACCOUNTING = 'C' --RFBSK
        and BILLING_DOCUMENT_IS_CANCELED = FALSE --FKSTO
        and NUMBER_OF_CANCELED_BILLING_DOCUMENT = '' --SFAKN
        and try_to_date(BILLING_DATE,'YYYYMMDD') <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()))
)

, NET_BILLING_AMT1 AS (
    SELECT
        SALES_DOCUMENT
        , ZEROIFNULL(SUM(BILLING_NET_VALUE)) AS NET_BILLING_AMT
    FROM BILLING
    WHERE billing_DOCUMENT_CATEGORY = 'M'
    GROUP BY SALES_DOCUMENT
)

, NET_BILLING_AMT2 AS (
    SELECT
        SALES_DOCUMENT
        , ZEROIFNULL(SUM(BILLING_NET_VALUE)) AS NET_BILLING_AMT
    FROM BILLING
    WHERE billing_DOCUMENT_CATEGORY <> 'M'
    GROUP BY SALES_DOCUMENT
)

, SOURCE_DATA AS (
    SELECT
        SOBL.CONTRACT_NUMBER AS CONTRACT_NUMBER
        , ACDOCA.ASSIGNMENT_NUMBER AS SALES_DOCUMENT
        , TOTAL_CONTRACT_AMT.CONTRACT_VALUE
        , ACDOCA.TRANSACTION_CURRENCY AS CONTRACT_CURRENCY
        , BP.CUSTOMER_NUMBER AS SOLD_TO_PARTY
        , BU_CODE.BU_CODE AS BU_CODE
        , ACDOCA.UPFRONT_PAYMENT AS UPFRONT_PAYMENT
        , NET_BILLING_AMT1.NET_BILLING_AMT as NET_BILLING_AMT1
        , NET_BILLING_AMT2.NET_BILLING_AMT as NET_BILLING_AMT2
        , CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTSTARTDATE AS CONTRACT_START_DATE
        , CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTENDDATE AS CONTRACT_END_DATE
        , LISTAGG(DISTINCT CONTRACT_SUMMARY_DETAILS.CNT_CONTRACTSCOPESO,',') AS CONTRACT_SCOPE
        , ACDOCA_NEW.UPFRONT_PAYMENT_NEW AS REVENUE_APPLIED
    FROM ACDOCA
        LEFT JOIN ACDOCA_NEW
            ON ACDOCA.ASSIGNMENT_NUMBER = ACDOCA_NEW.ASSIGNMENT_NUMBER
        LEFT JOIN SOBL
            ON TRY_TO_NUMBER(ACDOCA.ASSIGNMENT_NUMBER) = SOBL.SALES_DOCUMENT
        LEFT JOIN TOTAL_CONTRACT_AMT
            ON SOBL.CONTRACT_NUMBER = TOTAL_CONTRACT_AMT.CONTRACT_NUMBER
        LEFT JOIN BU_CODE
            ON SOBL.CONTRACT_NUMBER = BU_CODE.CONTRACT_NUMBER
        LEFT JOIN NET_BILLING_AMT1
            ON TRY_TO_NUMBER(ACDOCA.ASSIGNMENT_NUMBER) = NET_BILLING_AMT1.SALES_DOCUMENT
        LEFT JOIN NET_BILLING_AMT2
            ON TRY_TO_NUMBER(ACDOCA.ASSIGNMENT_NUMBER) = NET_BILLING_AMT2.SALES_DOCUMENT
        LEFT JOIN BP
            ON SOBL.SALES_DOCUMENT = BP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
        LEFT JOIN {{ ref('COMMON__CRM__CONTRACT_SUMMARY_DETAILS') }} CONTRACT_SUMMARY_DETAILS
            ON SOBL.CONTRACT_NUMBER = CONTRACT_SUMMARY_DETAILS.CNT_CONTRUCTNUMBER    
        GROUP BY ALL    
)
 
, TRANSFORM_DATA AS (
     SELECT DISTINCT
        '{{ invocation_id }}' AS _AUDIT_LOG_ID
        , SHA2('hash_me') AS _ROW_HASH 
        , CONTRACT_NUMBER
        , LTRIM(SALES_DOCUMENT, '0') as SALES_DOCUMENT
        , CONTRACT_VALUE
        , CONTRACT_CURRENCY
        , SOLD_TO_PARTY
        , BU_CODE
        , (UPFRONT_PAYMENT * -1) AS UPFRONT_PAYMENT
        , (ZEROIFNULL(NET_BILLING_AMT1) - ZEROIFNULL(NET_BILLING_AMT2)) AS REVENUE_RECOGNIZED
        , round((UPFRONT_PAYMENT * -1) - REVENUE_RECOGNIZED, 2) AS DEFERRED_REVENUE
        , TO_VARCHAR(TO_TIMESTAMP_TZ(CONTRACT_START_DATE), 'MM/DD/YYYY') AS CONTRACT_START_DATE
        , TO_VARCHAR(TO_TIMESTAMP_TZ(CONTRACT_END_DATE), 'MM/DD/YYYY') AS CONTRACT_END_DATE
        , CONTRACT_SCOPE
        , REVENUE_APPLIED
     FROM SOURCE_DATA
)

, TYPE_DATA AS (
    SELECT
        _AUDIT_LOG_ID
        , _ROW_HASH 
        , CONTRACT_NUMBER
        , SALES_DOCUMENT
        , CAST(CONTRACT_VALUE AS NUMBER(38,2)) AS CONTRACT_VALUE
        , CONTRACT_CURRENCY
        , SOLD_TO_PARTY
        , BU_CODE
        , CAST(UPFRONT_PAYMENT AS NUMBER(38,2)) AS UPFRONT_PAYMENT
        , CAST(REVENUE_RECOGNIZED AS NUMBER(38,2)) AS REVENUE_RECOGNIZED
        , CAST(DEFERRED_REVENUE AS NUMBER(38,2)) AS DEFERRED_REVENUE
        , CAST(CONTRACT_START_DATE AS DATE) AS CONTRACT_START_DATE
        , CAST(CONTRACT_END_DATE AS DATE) AS CONTRACT_END_DATE
        , CONTRACT_SCOPE
        , REVENUE_APPLIED
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
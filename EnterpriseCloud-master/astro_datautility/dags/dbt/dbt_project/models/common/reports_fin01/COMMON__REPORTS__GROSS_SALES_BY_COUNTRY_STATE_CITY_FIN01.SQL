{{ config(
    materialized='incremental',
    incremental_strategy='insert_overwrite',
    alias='GROSS_SALES_BY_COUNTRY_STATE_CITY',
    transient=false
) }}

with T005T_COUNTRY_CTE as (
    SELECT *
    FROM {{ ref('ODS__SAPH__SAP_ZZM_EV_T005T') }} 
    WHERE SPRAS = 'EN' 
),

T005U_REGION_CTE as (
    SELECT *
    FROM {{ ref('ODS__SAPH__SAP_ZZM_EV_T005U') }} 
    WHERE SPRAS = 'EN'
),

DASL as (
    SELECT 
    COMPANY_CODE,
    COMPANY_NAME,
    ACCOUNT_NUMBER,
    ACCOUNT_NAME, 
    DOCUMENT_TYPE,
    SALES_DOCUMENT,
    END_USER,
    END_USER_NAME,
    END_USER_CITY,
    END_USER_REGION,
    END_USER_COUNTRY,
    SOLD_TO_PARTY,
    SOLD_TO_PARTY_NAME,
    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    FISCAL_YEAR,
    FISCAL_YEAR_PERIOD,
    CUSTOMER_GROUP,
    AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT,
    ORACLE_PRODUCT_TYPE_GROUP
    FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_SALES_LINE_FIN01') }} 
    WHERE LEFT(ACCOUNT_NUMBER,1) LIKE '4%' 
    AND DOCUMENT_TYPE NOT IN ('DR','DG')
),

VBPA_ADRC_CTE as (
    SELECT 
    DISTINCT VBPA.VBELN,
    VBPA.KUNNR,
    VBPA.ADRNR,
    ADRC.NAME1 AS SOLD_TO_NAME,
    ADRC.CITY1 AS SOLD_TO_CITY,
    ADRC.REGION AS SOLD_TO_REGION,
    ADRC.COUNTRY AS SOLD_TO_COUNTRY
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU047_VBPA') }} VBPA
    LEFT JOIN {{ ref('ODS__SAPAPI__ZCDV_T_CMTU087_ADRC') }} ADRC
    ON VBPA.ADRNR = ADRC.ADDRNUMBER
    WHERE UPPER(VBPA.IS_DELETED) = 'NO' AND VBPA.PARVW = 'SP' AND ADRC.NATION = 'I'
),

PAYER as (
    SELECT DISTINCT
    CUSTOMER.CUSTOMER_NUMBER AS PAYER
    ,CUSTOMER.NAME_1 AS PAYER_NAME
    ,CUSTOMER.COUNTRY_KEY AS PAYER_COUNTRY
    ,BP.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER
    ,BP.ITEM_NUMBER_OF_THE_SD_DOCUMENT
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS') }} BP
    LEFT JOIN {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }} CUSTOMER
    ON BP.CUSTOMER_NUMBER = CUSTOMER.CUSTOMER_NUMBER
    WHERE BP.PARTNER_FUNCTION = 'PY' AND CUSTOMER.CUSTOMER_FLAG = 'Y'
),

SOURCE_DATA AS (
    SELECT 
    DASL.COMPANY_CODE,
    DASL.COMPANY_NAME,
    DASL.ACCOUNT_NUMBER,
    DASL.ACCOUNT_NAME,
    DASL.DOCUMENT_TYPE,
    DASL.SALES_DOCUMENT,
    DASL.END_USER,
    DASL.END_USER_NAME,
    DASL.END_USER_CITY,
    DASL.END_USER_REGION,
    T005U_REGION_CTE.BEZEI AS END_USER_REGION_NAME,
    DASL.END_USER_COUNTRY,
    T005T_COUNTRY_CTE.LANDX50 AS END_USER_COUNTRY_NAME,
    DASL.SOLD_TO_PARTY,
    DASL.SOLD_TO_PARTY_NAME,
    VBPA_ADRC_CTE.SOLD_TO_CITY,
    VBPA_ADRC_CTE.SOLD_TO_REGION,
    T005U_REGION_CTE_2.BEZEI AS SOLD_TO_REGION_NAME,
    VBPA_ADRC_CTE.SOLD_TO_COUNTRY,
    T005T_COUNTRY_CTE_2.LANDX50 AS SOLD_TO_COUNTRY_NAME,
    DASL.SALES_CATEGORY,
    DASL.SALES_CATEGORY_NAME,
    DASL.ORACLE_PRODUCT_TYPE_GROUP,
    DASL.FISCAL_YEAR,
    DASL.FISCAL_YEAR_PERIOD,
    DASL.CUSTOMER_GROUP,
    SUM(DASL.AMOUNT) AS AMOUNT,
    PAYER.PAYER,
    PAYER.PAYER_NAME,
    PAYER.PAYER_COUNTRY 
    FROM DASL 
    LEFT JOIN VBPA_ADRC_CTE 
    ON DASL.SALES_DOCUMENT = VBPA_ADRC_CTE.VBELN 
    AND DASL.SOLD_TO_PARTY = VBPA_ADRC_CTE.KUNNR
    LEFT JOIN PAYER 
    ON PAYER.SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER = DASL.SALES_DOCUMENT
    LEFT JOIN T005T_COUNTRY_CTE
    ON T005T_COUNTRY_CTE.LAND1 = DASL.END_USER_COUNTRY
    LEFT JOIN T005U_REGION_CTE
    ON T005U_REGION_CTE.BLAND = DASL.END_USER_REGION
    AND T005U_REGION_CTE.LAND1 = DASL.END_USER_COUNTRY
    LEFT JOIN T005T_COUNTRY_CTE AS T005T_COUNTRY_CTE_2
    ON T005T_COUNTRY_CTE_2.LAND1 = VBPA_ADRC_CTE.SOLD_TO_COUNTRY
    LEFT JOIN T005U_REGION_CTE AS T005U_REGION_CTE_2
    ON T005U_REGION_CTE_2.BLAND = VBPA_ADRC_CTE.SOLD_TO_REGION
    AND T005U_REGION_CTE_2.LAND1 = VBPA_ADRC_CTE.SOLD_TO_COUNTRY
    GROUP BY ALL
),

TRANSFORM_DATA AS (
    SELECT
    '{{ invocation_id }}' AS _AUDIT_LOG_ID,
    SHA2('hash_me') AS _ROW_HASH,
    COMPANY_CODE,
    COMPANY_NAME,
    ACCOUNT_NUMBER,
    ACCOUNT_NAME,
    DOCUMENT_TYPE,
    SALES_DOCUMENT,
    END_USER,
    END_USER_NAME,
    END_USER_CITY,
    END_USER_REGION,
    END_USER_REGION_NAME,
    END_USER_COUNTRY,
    END_USER_COUNTRY_NAME,
    SOLD_TO_PARTY,
    SOLD_TO_PARTY_NAME,
    SOLD_TO_CITY,
    SOLD_TO_REGION,
    SOLD_TO_REGION_NAME,
    SOLD_TO_COUNTRY,
    SOLD_TO_COUNTRY_NAME,
    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    ORACLE_PRODUCT_TYPE_GROUP,
    FISCAL_YEAR,
    FISCAL_YEAR_PERIOD,
    CUSTOMER_GROUP,
    AMOUNT,
    PAYER,
    PAYER_NAME,
    PAYER_COUNTRY 
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
    CAST(_AUDIT_LOG_ID AS VARCHAR(128)) AS _AUDIT_LOG_ID,
    CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH,
    COMPANY_CODE,
    COMPANY_NAME,
    ACCOUNT_NUMBER,
    ACCOUNT_NAME,
    DOCUMENT_TYPE,
    SALES_DOCUMENT,
    END_USER,
    END_USER_NAME,
    END_USER_CITY,
    END_USER_REGION,
    END_USER_REGION_NAME,
    END_USER_COUNTRY,
    END_USER_COUNTRY_NAME,
    SOLD_TO_PARTY,
    SOLD_TO_PARTY_NAME,
    SOLD_TO_CITY,
    SOLD_TO_REGION,
    SOLD_TO_REGION_NAME,
    SOLD_TO_COUNTRY,
    SOLD_TO_COUNTRY_NAME,
    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    ORACLE_PRODUCT_TYPE_GROUP,
    FISCAL_YEAR,
    FISCAL_YEAR_PERIOD,
    CUSTOMER_GROUP,
    AMOUNT,
    PAYER,
    PAYER_NAME,
    PAYER_COUNTRY  
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA

WITH LEDGER_MD AS (
    SELECT DISTINCT
        BASE_GL_TYPE
        , SAP_CODE
        , SAP_ACCT_DESCRIPTION
        , FINANCIAL_ACCOUNT_TYPE
        , FINANCIAL_STATUTORY_CATEGORY
        , SENSITIVE_INDICATOR
        , SECURITY_IS_EXPENSE
        , FOR_EXPENSE_REPORTING
    FROM {{ ref('COMMON__SAPH__ORACLE_ACCOUNT_MAP') }}
)

, ORACLE_DEPT AS (
    SELECT 
	    ORACLE_CODE,
	    ORACLE_DESCRIPTION,
	    SAP_CODE,
	    SAP_DESCRIPTION
    FROM {{ ref('COMMON__SAPH__SAP_DEPARTMENT') }}
)
, STANDARD_DEPT_HIERARCHY AS (
    SELECT DISTINCT
        ORACLE_DEPARTMENT, ORACLE_DEPARTMENT_ALIAS
    FROM {{ ref('COMMON__SAPH__ORACLE_STANDARD_DEPT_HIERARCHY') }}
)
, FUNCTIONAL_DEPT_HIERARCHY AS (
    SELECT * FROM {{ ref('COMMON__SAPH__ORACLE_FUNCTIONAL_DEPT_HIERARCHY') }}
)
, ORACLE_REGION AS (
    SELECT
	    ORACLE_CODE,
	    ORACLE_DESCRIPTION,
	    SAP_CODE,
	    SAP_DESCRIPTION
    FROM {{ ref('COMMON__SAPH__SAP_REGION') }}
)
, ORACLE_SEGMENT AS (
    SELECT
	    ORACLE_CODE,
	    ORACLE_DESCRIPTION,
	    SAP_CODE,
	    SAP_DESCRIPTION
    FROM {{ ref('COMMON__SAPH__SAP_SEGMENT') }}
)
, ACTUALS AS (
    SELECT * FROM {{ ref('COMMON__SAPH__DAILY_ACTUALS_FIN01') }}
)

, SOURCE_DATA AS (
    SELECT
        ACTUALS.COMPANY_CODE
        , ACTUALS.FISCAL_YEAR_PERIOD
        , ACTUALS.FISCAL_YEAR
        , ACTUALS.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT
        , ACTUALS.FINANCIAL_PERIOD AS FISCAL_PERIOD
        , ACTUALS.POSTING_DATE
        , ACTUALS.DOCUMENT_DATE
        , LEDGER_MD.BASE_GL_TYPE
        , ACTUALS.ACCOUNT_NUMBER
        , LEDGER_MD.SAP_ACCT_DESCRIPTION AS ACCOUNT_DESCRIPTION
        , LEDGER_MD.FINANCIAL_ACCOUNT_TYPE
        , LEDGER_MD.FINANCIAL_STATUTORY_CATEGORY
        , ACTUALS.COST_CENTER
        , ACTUALS.PROFIT_CENTER
        , ACTUALS.SEGMENT_CODE
        , ACTUALS.SEGMENT
        , ORACLE_SEGMENT.ORACLE_CODE AS ORACLE_SEGMENT_CODE
        , ACTUALS.OFFICE_CODE
        , ACTUALS.OFFICE
        , ORACLE_REGION.ORACLE_CODE AS ORACLE_OFFICE_CODE
        , ACTUALS.DEPARTMENT_CODE
        , ACTUALS.DEPARTMENT AS DEPARTMENT_NAME
        , FUNCTIONAL_DEPT_HIERARCHY.FUNCTIONAL_DEPARTMENT AS FUNCTIONAL_DEPARTMENT_CODE
        , FUNCTIONAL_DEPT_HIERARCHY.DEPARTMENT_ALIAS AS FUNCTIONAL_DEPARTMENT_NAME
        , ORACLE_DEPT.ORACLE_CODE AS ORACLE_DEPARTMENT_CODE
        , ORACLE_DEPT.ORACLE_DESCRIPTION AS ORACLE_DEPARTMENT_NAME
        , LEDGER_MD.SENSITIVE_INDICATOR
        , ACTUALS.VENDOR_NUMBER
        , ACTUALS.VENDOR_NAME
        , ACTUALS.PURCHASING_DOCUMENT_NUMBER
        , ACTUALS.AMOUNT_IN_COMPANY_CODE_CURRENCY
        , ACTUALS.ITEM_TEXT
        , ACTUALS.DOCUMENT_HEADER_TEXT_BKPF
        , ACTUALS.REFERENCE_BKPF
    FROM ACTUALS
        LEFT JOIN LEDGER_MD
            ON ACTUALS.ACCOUNT_NUMBER = LEDGER_MD.SAP_CODE
        LEFT JOIN ORACLE_DEPT
            ON SUBSTRING(COALESCE(ACTUALS.COST_CENTER, ACTUALS.PROFIT_CENTER),6,3) = ORACLE_DEPT.SAP_CODE
        LEFT JOIN STANDARD_DEPT_HIERARCHY
            ON ORACLE_DEPT.ORACLE_CODE = STANDARD_DEPT_HIERARCHY.ORACLE_DEPARTMENT
        LEFT JOIN FUNCTIONAL_DEPT_HIERARCHY
            ON ORACLE_DEPT.ORACLE_CODE = FUNCTIONAL_DEPT_HIERARCHY.DEPARTMENT
        LEFT JOIN ORACLE_REGION
            ON RIGHT(COALESCE(ACTUALS.COST_CENTER, ACTUALS.PROFIT_CENTER), 2) = ORACLE_REGION.SAP_CODE
        LEFT JOIN ORACLE_SEGMENT
            ON SUBSTRING(COALESCE(ACTUALS.COST_CENTER, ACTUALS.PROFIT_CENTER), 4, 2) = ORACLE_SEGMENT.SAP_CODE
    WHERE LEDGER_MD.FOR_EXPENSE_REPORTING = 'true'
)

, TRANSFORM_DATA AS (
    SELECT
        COMPANY_CODE,
        FISCAL_YEAR_PERIOD,
        FISCAL_YEAR,
        FISCAL_YEAR_HALF_YEAR_SHORT_TEXT,
        FISCAL_PERIOD,
        POSTING_DATE,
        DOCUMENT_DATE,
        BASE_GL_TYPE,
        ACCOUNT_NUMBER,
        ACCOUNT_DESCRIPTION,
        FINANCIAL_ACCOUNT_TYPE,
        FINANCIAL_STATUTORY_CATEGORY,
        COST_CENTER,
        PROFIT_CENTER,
        COALESCE(COST_CENTER, CASE
            WHEN LEFT(PROFIT_CENTER, 1) = '4' THEN CONCAT('2', SUBSTRING(PROFIT_CENTER, 2, LEN(PROFIT_CENTER)))
            WHEN LEFT(PROFIT_CENTER, 1) = '3' THEN CONCAT('1', SUBSTRING(PROFIT_CENTER, 2, LEN(PROFIT_CENTER)))
            ELSE PROFIT_CENTER
        END) AS COST_CENTER_POPULATED,
        SEGMENT_CODE,
        SEGMENT,
        ORACLE_SEGMENT_CODE,
        OFFICE_CODE,
        OFFICE,
        ORACLE_OFFICE_CODE,
        DEPARTMENT_CODE,
        DEPARTMENT_NAME,
        FUNCTIONAL_DEPARTMENT_CODE,
        FUNCTIONAL_DEPARTMENT_NAME,
        ORACLE_DEPARTMENT_CODE,
        ORACLE_DEPARTMENT_NAME,
        SENSITIVE_INDICATOR,
        VENDOR_NUMBER,
        VENDOR_NAME,
        PURCHASING_DOCUMENT_NUMBER,
        AMOUNT_IN_COMPANY_CODE_CURRENCY,
        ITEM_TEXT,
        DOCUMENT_HEADER_TEXT_BKPF,
        REFERENCE_BKPF,
        '{{ invocation_id }}' AS AUDIT_LOG_ID,
        SHA2('hash_me') AS _ROW_HASH
    FROM SOURCE_DATA
)

, TYPE_DATA AS (
    SELECT
        CAST(COMPANY_CODE AS VARCHAR(16777216)) AS COMPANY_CODE,
        CAST(FISCAL_YEAR_PERIOD AS VARCHAR(16777216)) AS FISCAL_YEAR_PERIOD,
        CAST(FISCAL_YEAR AS VARCHAR(16777216)) AS FISCAL_YEAR,
        CAST(FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS VARCHAR(16777216)) AS FISCAL_YEAR_HALF_YEAR_SHORT_TEXT,
        CAST(FISCAL_PERIOD AS VARCHAR(16777216)) AS FISCAL_PERIOD,
        CAST(POSTING_DATE AS DATE) AS POSTING_DATE,
        CAST(DOCUMENT_DATE AS DATE) AS DOCUMENT_DATE,
        CAST(BASE_GL_TYPE AS VARCHAR(16777216)) AS BASE_GL_TYPE,
        CAST(ACCOUNT_NUMBER AS VARCHAR(16777216)) AS ACCOUNT_NUMBER,
        CAST(ACCOUNT_DESCRIPTION AS VARCHAR(16777216)) AS ACCOUNT_DESCRIPTION,
        CAST(FINANCIAL_ACCOUNT_TYPE AS VARCHAR(16777216)) AS FINANCIAL_ACCOUNT_TYPE,
        CAST(FINANCIAL_STATUTORY_CATEGORY AS VARCHAR(16777216)) AS FINANCIAL_STATUTORY_CATEGORY,
        CAST(COST_CENTER AS VARCHAR(16777216)) AS COST_CENTER,
        CAST(PROFIT_CENTER AS VARCHAR(16777216)) AS PROFIT_CENTER,
        CAST(COST_CENTER_POPULATED AS VARCHAR(16777216)) AS COST_CENTER_POPULATED,
        CAST(SEGMENT_CODE AS VARCHAR(16777216)) AS SEGMENT_CODE,
        CAST(SEGMENT AS VARCHAR(16777216)) AS SEGMENT,
        CAST(ORACLE_SEGMENT_CODE AS VARCHAR(16777216)) AS ORACLE_SEGMENT_CODE,
        CAST(OFFICE_CODE AS VARCHAR(16777216)) AS OFFICE_CODE,
        CAST(OFFICE AS VARCHAR(16777216)) AS OFFICE,
        CAST(ORACLE_OFFICE_CODE AS VARCHAR(16777216)) AS ORACLE_OFFICE_CODE,
        CAST(DEPARTMENT_CODE AS VARCHAR(16777216)) AS DEPARTMENT_CODE,
        CAST(DEPARTMENT_NAME AS VARCHAR(16777216)) AS DEPARTMENT_NAME,
        CAST(FUNCTIONAL_DEPARTMENT_CODE AS VARCHAR(16777216)) AS FUNCTIONAL_DEPARTMENT_CODE,
        CAST(FUNCTIONAL_DEPARTMENT_NAME AS VARCHAR(16777216)) AS FUNCTIONAL_DEPARTMENT_NAME,
        CAST(ORACLE_DEPARTMENT_CODE AS VARCHAR(16777216)) AS ORACLE_DEPARTMENT_CODE,
        CAST(ORACLE_DEPARTMENT_NAME AS VARCHAR(16777216)) AS ORACLE_DEPARTMENT_NAME,
        CAST(SENSITIVE_INDICATOR AS VARCHAR(16777216)) AS SENSITIVE_INDICATOR,
        CAST(VENDOR_NUMBER AS VARCHAR(16777216)) AS VENDOR_NUMBER,
        CAST(VENDOR_NAME AS VARCHAR(16777216)) AS VENDOR_NAME,
        CAST(PURCHASING_DOCUMENT_NUMBER AS VARCHAR(16777216)) AS PURCHASING_DOCUMENT_NUMBER,
        CAST(AMOUNT_IN_COMPANY_CODE_CURRENCY AS NUMBER(38,2)) AS AMOUNT_IN_COMPANY_CODE_CURRENCY,
        CAST(ITEM_TEXT AS VARCHAR(16777216)) AS ITEM_TEXT,
        CAST(DOCUMENT_HEADER_TEXT_BKPF AS VARCHAR(16777216)) AS DOCUMENT_HEADER_TEXT_BKPF,
        CAST(REFERENCE_BKPF AS VARCHAR(16777216)) AS REFERENCE_BKPF,
        CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID,
        CAST(_ROW_HASH AS VARCHAR(128)) AS _ROW_HASH
    FROM TRANSFORM_DATA
)

SELECT * FROM TYPE_DATA
WITH security_CTE as (
    select
        COST_CENTER_CODE,
        SEGMENT_CODE as SECURITY_SEGMENT,
        DEPARTMENT_CODE as SECURITY_DEPARTMENT,
        OFFICE_CODE as SECURITY_OFFICE
    from {{ ref('ODS__FILE__COST_CENTER') }}
),

security_PROFIT_CENTER as (
    select 
        PROFIT_CENTER_CODE,
        PROFIT_CENTER_NAME,
        SEGMENT_CODE,
        SEGMENT,
        DEPARTMENT_CODE,
        DEPARTMENT,
        OFFICE_CODE,
        OFFICE
    from {{ ref('ODS__FILE__PROFIT_CENTER') }}
),

 AUAA AS (
    SELECT
        AUAA_NUMBER_OF_A_SETTLEMENT_DOCUMENT AS AUAA_DOCUMENT_NUMBER,
        AUAA_WBS_ELEMENT AS AUAA_WBS_ELEMENT,
        AUAA_ACCOUNT_ASSIGNMENT_CATEGORY AS AUAA_ACCOUNT_ASSIGNMENT_CATEGORY,
        AUAA_ORDER_NUMBER AS AUAA_ORDER_NUMBER,
        AUAA_SEQUENCE_NUMBER_FOUR_CHARACTERS AS AUAA_SEQUENCE_NUMBER,
        AUAA_ORDER_NUMBER AS ORDER_NUMBER,
        SALES_ORDER_NUMBER AS SALES_DOCUMENT,
        ITEM_NUMBER_IN_SALES_ORDER AS SALES_DOCUMENT_LINE
    FROM {{ ref('COMMON__SAPH__SETTLEMENT_MASTER') }}
),

SOBL AS (
    SELECT DISTINCT
        VBAP_SALES_DOCUMENT AS SALES_DOCUMENT
        , SALES_DOCUMENT_ITEM_POSNR AS SALES_DOCUMENT_LINE
        , VBAP_SHORT_TEXT_FOR_SALES_ORDER_ITEM AS ITEM_DESCRIPTION
        , VBAP_WORK_BREAKDOWN_STRUCTURE_ELEMENT AS WBS_ELEMENT
        , VBAP_SALES_CATEGORY AS SALES_CATEGORY
        , VBAK_SOLD_TO_PARTY AS SOLD_TO_PARTY
        , VBAK_SALES_DOCUMENT_TYPE as SALES_DOCUMENT_TYPE
    FROM {{ ref('COMMON__SAPH__SALES_ORDER_BILLING_LINE') }} 
),

KNA1 AS (
    SELECT DISTINCT
        CUSTOMER_NUMBER
        , NAME_1 AS CUSTOMER_NAME
    FROM {{ ref('COMMON__SAPH__BUSINESS_PARTNERS_GENERAL_DATA') }}
),

VBKD AS (
    SELECT DISTINCT
        VBKD_SALES_AND_DISTRIBUTION_DOCUMENT_NUMBER AS SALES_DOCUMENT,
        VBKD_ITEM_NUMBER_OF_THE_SD_DOCUMENT AS SALES_DOCUMENT_LINE,
        VBKD_CUSTOMER_REFERENCE AS CUSTOMER_REFERENCE,
        VBKD_YOUR_REFERENCE AS YOUR_REFERENCE
    FROM {{ ref('COMMON__SAPH__UNIVERSAL_JOURNAL_SALES_LINE_FIN01') }}
),

PRPS AS (
    SELECT
        PSPNR_NEW
        , POSKI
    FROM {{ ref('ODS__SAPAPI__ZCDV_T_CMTU040_PRPS') }} AS PRPS
),

MASTER_DATA AS (
    SELECT
        SAP_SALES_CATEGORY
        , SAP_SALES_CATEGORY_NAME AS SALES_CATEGORY_NAME
    FROM {{ ref('COMMON__SAPH__SAP_SALES_CATEGORY') }}
),

WIP AS(
    SELECT
        POSTING_DATE_IN_THE_DOCUMENT AS POSTING_DATE
        , PROFIT_CENTER
        , COST_CENTER
        , ACCOUNTING_DOCUMENT_NUMBER AS ACCOUNTING_DOCUMENT
        , SIX_CHARACTER_POSTING_ITEM_FOR_LEDGER AS ACCOUNTING_DOCUMENT_LINE
        , REFERENCE_DOCUMENT_NUMBER AS REFERENCE_DOCUMENT
        , WORK_BREAKDOWN_STRUCTURE_ELEMENT_PS_PSP_PNR AS WBS_ELEMENT
        , AMOUNT_IN_COMPANY_CODE_CURRENCY
    FROM {{ ref('COMMON__SAPH__UNIVERSAL_JOURNAL_ENTRY_LINE_FIN01') }}
    WHERE 1=1
        AND LEDGER_IN_GENERAL_LEDGER_ACCOUNTING = '0L'
        AND COMPANY_CODE IN ('3200', '3300')
        AND ACCOUNT_NUMBER = '1140300001'
        AND POSTING_DATE_IN_THE_DOCUMENT != '00000000'
        AND ACCOUNTING_DOCUMENT NOT ILIKE 'B%'
),


WIP_1 AS (
    SELECT
    WIP.POSTING_DATE AS POSTING_DATE
    , WIP.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY
    , WIP.PROFIT_CENTER AS PROFIT_CENTER
    , WIP.COST_CENTER AS COST_CENTER
    , WIP.ACCOUNTING_DOCUMENT AS ACCOUNTING_DOCUMENT
    , WIP.ACCOUNTING_DOCUMENT_LINE AS ACCOUNTING_DOCUMENT_LINE
    , WIP.REFERENCE_DOCUMENT AS REFERENCE_DOCUMENT
    , WIP.WBS_ELEMENT AS WBS_ELEMENT
    , AUAA.ACCOUNT_ASSIGNMENT_CATEGORY AS ACCOUNT_ASSIGNMENT_CATEGORY
    , AUAA.DOCUMENT_NUMBER AS DOCUMENT_NUMBER
    FROM WIP
    LEFT JOIN (
        SELECT
        AUAA_ACCOUNT_ASSIGNMENT_CATEGORY AS ACCOUNT_ASSIGNMENT_CATEGORY,
        AUAA_DOCUMENT_NUMBER AS DOCUMENT_NUMBER,
        AUAA_WBS_ELEMENT AS WBS_ELEMENT
        FROM AUAA
        WHERE AUAA_ORDER_NUMBER IS NOT NULL) AS AUAA
        ON WIP.WBS_ELEMENT = AUAA.WBS_ELEMENT
        AND WIP.REFERENCE_DOCUMENT = AUAA.DOCUMENT_NUMBER
),

WIP_2 AS (
    SELECT
        WIP_1.POSTING_DATE AS POSTING_DATE
        , WIP_1.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY
        , WIP_1.PROFIT_CENTER AS PROFIT_CENTER
        , WIP_1.COST_CENTER AS COST_CENTER
        , WIP_1.ACCOUNTING_DOCUMENT AS ACCOUNTING_DOCUMENT
        , WIP_1.ACCOUNTING_DOCUMENT_LINE AS ACCOUNTING_DOCUMENT_LINE
        , WIP_1.REFERENCE_DOCUMENT AS REFERENCE_DOCUMENT
        , WIP_1.WBS_ELEMENT AS WBS_ELEMENT
        , WIP_1.DOCUMENT_NUMBER AS WIP_DOC_NUM
        , AUAA.DOCUMENT_NUMBER AS DOC_NUM
        , AUAA.ACCOUNT_ASSIGNMENT_CATEGORY AS ACCOUNT_ASSIGNMENT_CATEGORY
        , AUAA.SEQUENCE_NUMBER AS SEQUENCE_NUMBER
    FROM WIP_1
    LEFT JOIN (
        SELECT
        AUAA_ACCOUNT_ASSIGNMENT_CATEGORY AS ACCOUNT_ASSIGNMENT_CATEGORY,
        AUAA_DOCUMENT_NUMBER AS DOCUMENT_NUMBER,
        AUAA_SEQUENCE_NUMBER AS SEQUENCE_NUMBER,
        AUAA_WBS_ELEMENT AS WBS_ELEMENT
        FROM AUAA
        WHERE AUAA_ORDER_NUMBER IS NOT NULL) AS AUAA
        ON AUAA.WBS_ELEMENT = WIP_1.WBS_ELEMENT
),

WIP_2A AS (
    SELECT
        POSTING_DATE
        , SEQUENCE_NUMBER
        , AMOUNT_IN_COMPANY_CODE_CURRENCY
        , PROFIT_CENTER
        , COST_CENTER
        , ACCOUNTING_DOCUMENT
        , REFERENCE_DOCUMENT
        , WBS_ELEMENT
        , WIP_DOC_NUM
        , DOC_NUM
        , ROW_NUMBER() OVER (PARTITION BY WIP_DOC_NUM ORDER BY REFERENCE_DOCUMENT) AS FIRST_ROW
        , ACCOUNT_ASSIGNMENT_CATEGORY
    FROM WIP_2
    WHERE 1=1
        AND WIP_DOC_NUM <> DOC_NUM
        AND TRY_TO_NUMBER(SEQUENCE_NUMBER) = '2'
),

WIP_3A AS (
    SELECT
        WIP_2A.POSTING_DATE AS POSTING_DATE
        , WIP_2A.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY
        , WIP_2A.PROFIT_CENTER AS PROFIT_CENTER
        , WIP_2A.COST_CENTER AS COST_CENTER
        , WIP_2A.ACCOUNTING_DOCUMENT AS ACCOUNTING_DOCUMENT
        , WIP_2A.WBS_ELEMENT AS WBS_ELEMENT
        , WIP_2A.WIP_DOC_NUM AS WIP_DOC_NUM
        , WIP_2A.ACCOUNT_ASSIGNMENT_CATEGORY AS WIP2_EMTYP
        , AUAA.DOCUMENT_NUMBER AS DOC_NUM
        , AUAA.ACCOUNT_ASSIGNMENT_CATEGORY AS WIP3_EMTYP
        , AUAA.ORDER_NUMBER AS ORDER_NUMBER
    FROM WIP_2A
    LEFT JOIN (
        SELECT
            AUAA_ACCOUNT_ASSIGNMENT_CATEGORY AS ACCOUNT_ASSIGNMENT_CATEGORY,
            AUAA_DOCUMENT_NUMBER AS DOCUMENT_NUMBER,
            AUAA_ORDER_NUMBER AS ORDER_NUMBER
        FROM AUAA
        WHERE AUAA_ORDER_NUMBER IS NOT NULL
        ) AS AUAA
            ON WIP_2A.DOC_NUM = AUAA.DOCUMENT_NUMBER
    WHERE 1=1
        AND AUAA.ACCOUNT_ASSIGNMENT_CATEGORY <> 'WBS'
        AND WIP_2A.FIRST_ROW = 1
),

WIP_4A AS (
    SELECT
        WIP_3A.POSTING_DATE AS POSTING_DATE
        , WIP_3A.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT_IN_COMPANY_CODE_CURRENCY
        , WIP_3A.PROFIT_CENTER AS PROFIT_CENTER
        , WIP_3A.COST_CENTER AS COST_CENTER
        , WIP_3A.ACCOUNTING_DOCUMENT AS ACCOUNTING_DOCUMENT
        , WIP_3A.WBS_ELEMENT AS WBS_ELEMENT
        , WIP_3A.ORDER_NUMBER AS ORDER_NUMBER
        , AUFK.SALES_DOCUMENT AS SALES_DOCUMENT
        , AUFK.SALES_DOCUMENT_LINE AS SALES_DOCUMENT_LINE
    FROM WIP_3A
    INNER JOIN (
        SELECT DISTINCT
            SALES_DOCUMENT AS SALES_DOCUMENT
            , SALES_DOCUMENT_LINE AS SALES_DOCUMENT_LINE
            , ORDER_NUMBER AS ORDER_NUMBER
        FROM AUAA
        WHERE ORDER_NUMBER IS NOT NULL
        ) AS AUFK
            ON WIP_3A.ORDER_NUMBER = AUFK.ORDER_NUMBER
),

--WIP_*B FOR CARRYING ROWS WHERE SUBCON POSTED DIRECTLY TO WBS

WIP_2B AS (
    SELECT distinct
        POSTING_DATE
        , AMOUNT_IN_COMPANY_CODE_CURRENCY
        , PROFIT_CENTER
        , COST_CENTER
        , ACCOUNTING_DOCUMENT
        , ACCOUNTING_DOCUMENT_LINE
        , REFERENCE_DOCUMENT
        , WBS_ELEMENT
    FROM WIP_2
    WHERE ACCOUNTING_DOCUMENT NOT IN (SELECT ACCOUNTING_DOCUMENT FROM WIP_2A)
),

WIP_ALL AS (
    SELECT
    POSTING_DATE
    , AMOUNT_IN_COMPANY_CODE_CURRENCY
    , PROFIT_CENTER
    , COST_CENTER
    , ACCOUNTING_DOCUMENT
    , '' AS ACCOUNTING_DOCUMENT_LINE
    , WBS_ELEMENT
    , ORDER_NUMBER
    , SALES_DOCUMENT
    , SALES_DOCUMENT_LINE
FROM WIP_4A

UNION

SELECT
    POSTING_DATE
    , AMOUNT_IN_COMPANY_CODE_CURRENCY
    , PROFIT_CENTER
    , COST_CENTER
    , ACCOUNTING_DOCUMENT
    , ACCOUNTING_DOCUMENT_LINE
    , WBS_ELEMENT
    , '' AS ORDER_NUMBER
    , '' AS SALES_DOCUMENT
    , '' AS SALES_DOCUMENT_LINE
    FROM WIP_2B
),

SOURCE_DATA AS (
    SELECT
    WIP_ALL.AMOUNT_IN_COMPANY_CODE_CURRENCY AS AMOUNT
    , WIP_ALL.PROFIT_CENTER AS PROFIT_CENTER
    , WIP_ALL.ACCOUNTING_DOCUMENT AS ACCOUNTING_DOCUMENT
    , PRPS.POSKI AS WBS_ELEMENT
    , WIP_ALL.SALES_DOCUMENT AS SALES_DOCUMENT
    , WIP_ALL.SALES_DOCUMENT_LINE AS SALES_DOCUMENT_LINE
    , SOBL.ITEM_DESCRIPTION AS ITEM_DESCRIPTION
    , SOBL.SALES_CATEGORY AS SALES_CATEGORY
    , MASTER_DATA.SALES_CATEGORY_NAME AS SALES_CATEGORY_NAME
    , SOBL.SOLD_TO_PARTY AS SOLD_TO_PARTY
    , KNA1.CUSTOMER_NAME AS CUSTOMER_NAME
    , SOBL.SALES_DOCUMENT_TYPE AS SALES_DOCUMENT_TYPE
    , VBKD.CUSTOMER_REFERENCE AS CUSTOMER_REFERENCE
    , VBKD.YOUR_REFERENCE AS YOUR_REFERENCE
    , '<ALL>' as SECURITY_SEGMENT
    , '<ALL>' as SECURITY_DEPARTMENT
    , '<ALL>' as SECURITY_OFFICE
    FROM WIP_ALL
        LEFT JOIN SOBL
            ON WIP_ALL.SALES_DOCUMENT = SOBL.SALES_DOCUMENT
            AND TRY_TO_NUMBER(WIP_ALL.SALES_DOCUMENT_LINE) = TRY_TO_NUMBER(SOBL.SALES_DOCUMENT_LINE)
        LEFT JOIN KNA1
            ON SOBL.SOLD_TO_PARTY = KNA1.CUSTOMER_NUMBER
        LEFT JOIN VBKD
            ON TRY_TO_NUMBER(WIP_ALL.SALES_DOCUMENT) = TRY_TO_NUMBER(VBKD.SALES_DOCUMENT)
            AND WIP_ALL.SALES_DOCUMENT_LINE = VBKD.SALES_DOCUMENT_LINE
        LEFT JOIN PRPS
            ON WIP_ALL.WBS_ELEMENT = PRPS.PSPNR_NEW
        LEFT JOIN MASTER_DATA
            ON SOBL.SALES_CATEGORY = MASTER_DATA.SAP_SALES_CATEGORY
        left outer join security_cte
            on WIP_ALL.COST_CENTER = security_cte.cost_center_code
        left outer join security_PROFIT_CENTER
            on WIP_ALL.PROFIT_CENTER = security_PROFIT_CENTER.profit_center_code
        WHERE TRY_TO_DATE(WIP_ALL.POSTING_DATE) <= LAST_DAY(DATEADD(MONTH, -1, CURRENT_DATE()),'MONTH')
),

TRANSFORM_DATA AS (
    SELECT
        PROFIT_CENTER
        , SOLD_TO_PARTY
        , CUSTOMER_NAME
        , SALES_CATEGORY
        , SALES_CATEGORY_NAME
        , SALES_DOCUMENT
        , TRY_TO_NUMBER(SALES_DOCUMENT_LINE) AS SALES_DOCUMENT_LINE
        , ITEM_DESCRIPTION
        , WBS_ELEMENT
        , AMOUNT
        , CASE
            WHEN SALES_DOCUMENT_TYPE IN ('ZS10', 'ZR10') THEN CUSTOMER_REFERENCE
            WHEN SALES_DOCUMENT_TYPE = 'ZC11' THEN YOUR_REFERENCE
            ELSE null
        END AS CUSTOMER_PO
        , SECURITY_SEGMENT
        , SECURITY_DEPARTMENT
        , SECURITY_OFFICE
        , '{{ invocation_id }}' AS AUDIT_LOG_ID
    FROM SOURCE_DATA
),

TYPE_DATA AS (
    SELECT
        CAST(PROFIT_CENTER AS VARCHAR(16777216)) AS PROFIT_CENTER
        , CAST(SOLD_TO_PARTY AS VARCHAR(16777216)) AS SOLD_TO_PARTY
        , CAST(CUSTOMER_NAME AS VARCHAR(16777216)) AS CUSTOMER_NAME
        , CAST(SALES_CATEGORY AS VARCHAR(16777216)) AS SALES_CATEGORY
        , CAST(SALES_CATEGORY_NAME AS VARCHAR(16777216)) AS SALES_CATEGORY_NAME
        , CAST(SALES_DOCUMENT AS VARCHAR(16777216)) AS SALES_DOCUMENT
        , CAST(SALES_DOCUMENT_LINE AS VARCHAR(16777216)) AS SALES_DOCUMENT_LINE
        , CAST(CUSTOMER_PO AS VARCHAR(16777216)) AS CUSTOMER_PO
        , CAST(ITEM_DESCRIPTION AS VARCHAR(16777216)) AS ITEM_DESCRIPTION
        , CAST(WBS_ELEMENT AS VARCHAR(16777216)) AS WBS_ELEMENT
        , CAST(AMOUNT AS NUMBER(38,10)) AS AMOUNT
        , CAST(SECURITY_SEGMENT AS VARCHAR(16777216)) AS SECURITY_SEGMENT
        , CAST(SECURITY_DEPARTMENT AS VARCHAR(16777216)) AS SECURITY_DEPARTMENT
        , CAST(SECURITY_OFFICE AS VARCHAR(16777216)) AS SECURITY_OFFICE
        , CAST(AUDIT_LOG_ID AS VARCHAR(128)) AS AUDIT_LOG_ID
    from TRANSFORM_DATA
)


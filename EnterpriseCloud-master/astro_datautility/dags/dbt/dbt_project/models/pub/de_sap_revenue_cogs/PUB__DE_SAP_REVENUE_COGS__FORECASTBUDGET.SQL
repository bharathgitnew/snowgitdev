{{ config(
    materialized='view',
    alias='FORECASTBUDGET',
    transient=false
) }}

with SOURCE_DATA AS (
    SELECT 
        DISTINCT
        FORECASTBUDGET.ACCOUNT,
        FORECASTBUDGET.FILE_ACCOUNT,
        FORECASTBUDGET.ENTITY,
        FORECASTBUDGET.DEPARTMENTCODE,
        FORECASTBUDGET.SEGMENTCODE,
        FORECASTBUDGET.OFFICECODE,
        FORECASTBUDGET.FINANCIALPRODUCTCODE,
        FORECASTBUDGET.CUSTOMERCODE,
        FORECASTBUDGET.UD6,
        FORECASTBUDGET.UD7,
        FORECASTBUDGET.VERSION,
        FORECASTBUDGET.SCENARIO,
        FORECASTBUDGET.YEAR,
        FORECASTBUDGET.PERIOD,
        FORECASTBUDGET.CURRENCY,
        FORECASTBUDGET.AMOUNT,
        FORECASTBUDGET._FILEDATE,
        FORECASTBUDGET.SCENARIOCREATEDDATE,
        FORECASTBUDGET.DISPLAYBUDGETFLAG,
        FORECASTBUDGET.DISPLAYFORECASTFLAG,
        FORECASTBUDGET.ACCOUNT_TYPE,
        CALENDAR_DATE.FISCAL_YEAR_HALF_YEAR_SHORT_TEXT AS FISCAL_HALF,
        CALENDAR_DATE.FISCAL_YEAR_QUARTER_SHORT_TEXT AS FISCAL_QTR,
        CALENDAR_DATE.YEAR_MONTH_TEXT AS CALENDAR_YEAR_MONTH
    FROM {{ ref('COMMON__SAPH__FORECASTBUDGET') }} FORECASTBUDGET
    LEFT OUTER JOIN {{ ref('PUB__DE_SAP_MASTER_DATA__CALENDAR_DATE') }}  CALENDAR_DATE
    ON CALENDAR_DATE.MONTH_ABBREVIATION_TEXT||CALENDAR_DATE.FISCAL_YEAR_SHORT_TEXT = FORECASTBUDGET.PERIOD||YEAR
),

TRANSFORM_DATA AS (
    SELECT 
        ACCOUNT,
        FILE_ACCOUNT,
        ENTITY,
        DEPARTMENTCODE,
        SEGMENTCODE,
        OFFICECODE,
        FINANCIALPRODUCTCODE,
        CUSTOMERCODE,
        UD6,
        UD7,
        VERSION,
        SCENARIO,
        YEAR,
        PERIOD,
        CURRENCY,
        AMOUNT,
        _FILEDATE,
        SCENARIOCREATEDDATE,
        DISPLAYBUDGETFLAG,
        DISPLAYFORECASTFLAG,
        ACCOUNT_TYPE,
        FISCAL_HALF,
        FISCAL_QTR,
        CALENDAR_YEAR_MONTH
    FROM SOURCE_DATA
)

SELECT * FROM TRANSFORM_DATA
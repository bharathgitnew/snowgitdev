/*
DROP ROW ACCESS POLICY Policy_Access.TEH_SALES_TO_INSTALLATION_DISTRICT_ACCOUNT;
*/

-- Create Row Access Policy Shell
CREATE ROW ACCESS POLICY Policy_Access.TEH_SALES_TO_INSTALLATION_DISTRICT_ACCOUNT
    AS (DistrictId VARCHAR(16777216),AccountId VARCHAR(16777216))  RETURNS BOOLEAN ->
CASE
    WHEN 1=1 THEN true
    ELSE false
END
;

-- Alter Row Access Policy to provide body of Business Rules
ALTER ROW ACCESS POLICY Policy_Access.TEH_SALES_TO_INSTALLATION_DISTRICT_ACCOUNT
SET BODY ->
CASE
    WHEN CURRENT_USER() = 'SVC_PREFECT'           THEN true
    WHEN CURRENT_USER() = 'SVC_THOUGHTSPOT'       THEN true
    WHEN CURRENT_ROLE() = 'SYSADMIN_PROD'         THEN true 
    WHEN CURRENT_ROLE() = 'SYSADMIN_DEV'          THEN true 
    WHEN CURRENT_ROLE() = 'SYSADMIN_QA'           THEN true 
    WHEN CURRENT_ROLE() = 'SYSADMIN_SIT'          THEN true 
    WHEN CURRENT_ROLE() = 'PLATFORM_TEAM'         THEN true 
    WHEN CURRENT_ROLE() = 'PLATFORM_TEAM_DEV'     THEN true 
    WHEN CURRENT_ROLE() = 'PLATFORM_TEAM_SIT'     THEN true 
    WHEN CURRENT_ROLE() = 'PLATFORM_TEAM_QA'      THEN true 
    WHEN CURRENT_USER() = 'PBISERVICE@US.TEL.COM' THEN true 
    WHEN CURRENT_ROLE() = 'TEH_SALES_TO_INSTALLATION_TEAM_DEV' THEN true 

    WHEN CURRENT_USER() IN (
                    SELECT UserId
                    FROM Entitlement.MaskingRowData
                    WHERE TableName = 'TEH_SALES_TO_INSTALLATION'
                        AND ColumnName =  'SALES_CRM_DISTRICT_ACCOUNT'
                        AND (VisibleValue = concat(DistrictId,'|',AccountId) OR VisibleValue = 'AllValuesInTable' )
                    )                               THEN true
    ELSE false
END;


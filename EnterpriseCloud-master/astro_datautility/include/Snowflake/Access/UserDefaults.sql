SELECT 'USE ROLE SECURITYADMIN;' AS Set_Default_SQL, 1 AS Ordering
UNION ALL
SELECT 'ALTER USER "' || GRANTEE_NAME || '" SET DEFAULT_ROLE = ''' || 'CONSUMER' || ''';' AS Set_Default_SQL, 2 AS Ordering
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS GTU
JOIN Snowflake.ACCOUNT_USAGE.Users Users
ON Users.login_Name = GTU.Grantee_Name
JOIN ADMIN.CONTROL.ROLE_DEFAULTS RD
ON GTU.ROLE = RD.ROLE_NAME
WHERE GTU.DELETED_ON IS NULL
AND GTU.GRANTED_TO = 'USER'
AND GTU.GRANTED_BY = 'AAD_PROVISIONER'
AND Users.Default_Role IS NULL
UNION ALL
SELECT 'ALTER USER "' || GRANTEE_NAME || '" SET DEFAULT_WAREHOUSE = ''' || 'CONSUMER_WH'|| ''';' AS Set_Default_SQL, 3 AS Ordering
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS GTU
JOIN Snowflake.ACCOUNT_USAGE.Users Users
ON Users.login_Name = GTU.Grantee_Name
JOIN ADMIN.CONTROL.ROLE_DEFAULTS RD
ON GTU.ROLE = RD.ROLE_NAME
WHERE GTU.DELETED_ON IS NULL
AND GTU.GRANTED_TO = 'USER'
AND GTU.GRANTED_BY = 'AAD_PROVISIONER'
AND Users.Default_Warehouse IS NULL
UNION ALL
SELECT 'ALTER USER "' || GRANTEE_NAME || '" SET DEFAULT_NAMESPACE = ''' || 'PUB' || ''';' AS Set_Default_SQL, 4 AS Ordering
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS GTU
JOIN Snowflake.ACCOUNT_USAGE.Users Users
ON Users.login_Name = GTU.Grantee_Name
JOIN ADMIN.CONTROL.ROLE_DEFAULTS RD
ON GTU.ROLE = RD.ROLE_NAME
WHERE GTU.DELETED_ON IS NULL
AND GTU.GRANTED_TO = 'USER'
AND GTU.GRANTED_BY = 'AAD_PROVISIONER'
AND Users.Default_Namespace IS NULL
ORDER BY Ordering;

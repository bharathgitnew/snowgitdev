UPDATE COMMON.REFERENCE_NAIVE_PARSE B
SET SALES_SERVICE_ORDER_NUMBER = REFERENCEA, ORDER_TYPE = 'SERVICE ORDER',SERIAL_NUMBER_REFERENCE = SERIALNUMBER

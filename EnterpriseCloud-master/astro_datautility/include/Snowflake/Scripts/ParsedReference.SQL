--CONVERT SINGLE COLUMN DATA TO MULTIPLE ROWS BASED ON DELIMTERS
--1) CONVERT ALL NON-ALPHANUMERIC CHARACTERS TO "/". 2) SPLIT ROWS BASED ON "/" AS DELIMETER 3) GET INCREMENTAL DATA BASED ON _CAPTUREDATETIME
CREATE OR REPLACE TEMPORARY TABLE COMMON.TEMP_PARSED_COLUMNS AS --SELECT COUNT(*) FROM COMMON.TEMP_PARSED_COLUMNS
SELECT DISTINCT REFERENCE_REFR,
	UPPER(VALUE) AS PARSED_COLUMN_VALUE,
	INDEX AS PARSED_COLUMN_NUMBER,
	MAX(_CAPTUREDATETIME) _CAPTUREDATETIME
FROM BAAN.BAANFINANCEGENERALLEDGER_FINALIZEDTRANSACTIONS , 
LATERAL SPLIT_TO_TABLE(REGEXP_REPLACE(BAANFINANCEGENERALLEDGER_FINALIZEDTRANSACTIONS.REFERENCE_REFR, '[^a-zA-Z0-9]+', '/'), '/')
WHERE _CAPTUREDATETIME > (SELECT COALESCE(MAX(_CAPTUREDATETIME),'01/01/1900') FROM COMMON.REFERENCE_NAIVE_PARSE) --and 
GROUP BY REFERENCE_REFR,VALUE,INDEX
;

CREATE OR REPLACE TEMPORARY TABLE CTE_ORDER_TYPE AS
(SELECT * FROM(
	SELECT ORDER_NUMBER AS CTE_ORDER_NUMBER,ORDER_TYPE CTE_ORDER_TYPE, ITEM CTE_ITEM ,CONFIGURATION AS CTE_CONFIGURATION, WAREHOUSE CTE_WAREHOUSE ,POS,SERVICECONTRACT AS CTE_SERVICECONTRACT,
  SOLDTOBUSINESSPARTNER AS CTE_SOLDTOBUSINESSPARTNER,
	MIN(POS) OVER(PARTITION BY ORDER_NUMBER ORDER BY POS) AS MIN_POS--TO PICK SERVICE ORDER OVER SALES ORDER
	FROM (
		SELECT DISTINCT PURCHASEORDER ORDER_NUMBER, 'PURCHASE ORDER' ORDER_TYPE,NULL AS ITEM,WAREHOUSE,NULL CONFIGURATION,1 AS POS,NULL AS SERVICECONTRACT,NULL AS SOLDTOBUSINESSPARTNER
        FROM BAAN.BAANDISTRIBUTIONPURCHASECONTROL_PURCHASEORDERS 
		UNION
		SELECT DISTINCT SALESORDER ORDER_NUMBER, 'SALES ORDER' ORDER_TYPE,NULL AS ITEM ,WAREHOUSE,NULL CONFIGURATION, CASE WHEN LEFT(SALESORDER,3) IN ('MOD','FRF') THEN 2 ELSE 1 END ,NULL AS SERVICECONTRACT
		,SOLDTOBUSINESSPARTNER FROM BAAN.BAANDISTRIBUTIONSALESCONTROL_SALESORDERS 
		UNION	
		SELECT DISTINCT SERVICEORDER, 'SERVICE ORDER',NULL AS ITEM,NULL,CONFIGURATION, CASE WHEN LEFT(SERVICEORDER,3) IN ('MOD','FRF') THEN 1 ELSE 2 END ,SERVICECONTRACT,SOLDTOBUSINESSPARTNER
		FROM BAAN.BAANSERVICESERVICEORDERCONTROL_SERVICEORDERS--- where SERVICEORDER = 'CNP000038'
		UNION
		SELECT DISTINCT PRODUCTIONORDER, 'PRODUCTION ORDER',ITEM,WAREHOUSE,NULL CONFIGURATION,1,NULL AS SERVICECONTRACT,NULL FROM BAAN.BAANMANUFACTURINGSHOPFLOORCONTROL_PRODUCTIONORDERS ---WHERE PRODUCTIONORDE
	)A 
)WHERE POS = MIN_POS );

--FIGURE OUT RELEVANT VALUE FOR EACH WORD IN THE ENTIRE REFERENCE STRING. THEN GROUP THE DATA AND FORM IT IN SINGLE ROW
INSERT INTO COMMON.REFERENCE_NAIVE_PARSE--SELECT * FROM COMMON.REFERENCE_NAIVE_PARSE WHERE ORDER_NUMBER LIKE 'PO%'
SELECT REFERENCE, PROJECT_REFERENCE,
	COALESCE(CASE WHEN SERIAL_NUMBER_REFERENCE ='' THEN NULL ELSE SERIAL_NUMBER_REFERENCE END ,
             CASE WHEN SERVICEORDERS_SERIALNUMBER =''  THEN NULL ELSE SERVICEORDERS_SERIALNUMBER END ,SERIALNO,SERIALNO2) SERIAL_NUMBER_REFERENCE,
	COALESCE(CTE_SOLDTOBUSINESSPARTNER,CASE WHEN SOLDTO_BP_REFERENCE = '' THEN NULL ELSE SOLDTO_BP_REFERENCE END) SOLDTO_BP_REFERENCE, ORDER_NUMBER,
    COALESCE( CASE WHEN SERVICECONTRACTNUMBER ='' THEN NULL ELSE SERVICECONTRACTNUMBER END , SERVICECONTRACT) SERVICE_CONTRACT_REFERENCE, ORDER_SERIES, LINE,
	CASE WHEN IFNULL(LINE,0) = 0 THEN NULL ELSE '-' || RIGHT('0000' || LINE :: STRING ,4) END LINE_DERIVED, 
	SEQUENCE, BACKGROUND_SEQUENCE,IS_PARSED,
	ORDER_TYPE ORDER_TYPE,
	CASE WHEN ORDER_TYPE = 'PURCHASE ORDER' THEN ORDER_NUMBER ELSE '' END PURCHASE_ORDER_NUMBER,
	PURCHASE_ORDER_NUMBER || CASE WHEN ORDER_TYPE = 'PURCHASE ORDER' THEN IFNULL(LINE_DERIVED,'') ELSE NULL END PURCHASE_ORDER_NUMBERANDLINE,
	CASE WHEN ORDER_TYPE IN ('SALES ORDER','SERVICE ORDER') THEN ORDER_NUMBER ELSE NULL END SALES_SERVICE_ORDER_NUMBER ,
	SALES_SERVICE_ORDER_NUMBER || CASE WHEN ORDER_TYPE IN('SALES ORDER','SERVICE ORDER') THEN IFNULL(LINE_DERIVED,'') ELSE NULL END SALES_SERVICE_ORDER_NUMBERANDLINE,

	CASE WHEN ORDER_TYPE = 'PRODUCTION ORDER' THEN ORDER_NUMBER ELSE '' END PRODUCTION_ORDER_NUMBER,

	COALESCE(SERVICEORDERS.ITEM,PURCHASEORDERS.ITEM, SALESORDERS.ITEM,SALESORDERS2.ITEM2,CTE_ITEM) ITEM,
	COALESCE(PURCHASEORDERS.WAREHOUSE, SALESORDERS.WAREHOUSE,SALESORDERS2.WAREHOUSE2 , SERVICEORDERS.ACTUALWAREHOUSE,CTE_WAREHOUSE) WAREHOUSE,
	COALESCE(SERVICEORDERS.CONFIGURATION, CTE_CONFIGURATION) CONFIGURATION ,
	_CAPTUREDATETIME
	FROM(

		SELECT REFERENCE_REFR REFERENCE, LISTAGG(PRJECT) AS PROJECT_REFERENCE, 
		LISTAGG(SERIALNUMBER) SERIAL_NUMBER_REFERENCE, 
		LISTAGG(SOLDTOBUSINESSPARTNER) SOLDTO_BP_REFERENCE,

		--IGNORE WORDS WITH DATES(IN ANY FORMAT), CONCATENATE MULTIPLE VALUES WITH "," , 
		MIN(CTE_ORDER_NUMBER) ORDER_NUMBER,


		---CONTAINS (UPPER(REFERENCE_REFR),'CONTRACT') AND REGEXP_INSTR(REFERENCE_REFR,'CN') > 0 THEN SUBSTR(REFERENCE_REFR,REGEXP_INSTR(REFERENCE_REFR,'CN'),9) 

		--CHECK IF REFERENCE IS ALPHANUMERIC AND PICK ORDER_SERIES
		TRIM(LTRIM(LISTAGG(DISTINCT CASE WHEN REGEXP_LIKE(REFERENCE_REFR, '.*[0-9].*') = 1 THEN ORDER_SERIES ELSE '' END ,','),','),',') ORDER_SERIES,

		--LINENUMBER,SEQUENCENUMBER,BACKGROUNDSEQUENCENUMBER SHOULD BE NUMERIC, LENGTH SHOULD BE MAX 6, <> 'E' IS ADDED TO AVOID GETTING E ENTRIES , SNOWFLAKE BUG 
		TRY_TO_NUMBER(RTRIM(LTRIM(LISTAGG(DISTINCT CASE WHEN TRY_TO_NUMERIC(LINENUMBER) IS NOT NULL AND LENGTH(LINENUMBER) < 6 AND LINENUMBER <> 'E' THEN LINENUMBER ELSE NULL END ,','),','),',')) LINE,
		TRY_TO_NUMBER(RTRIM(LTRIM(LISTAGG(DISTINCT CASE WHEN TRY_TO_NUMERIC(SEQUENCENUMBER) IS NOT NULL AND LENGTH(SEQUENCENUMBER) < 6 AND SEQUENCENUMBER <> 'E' THEN SEQUENCENUMBER ELSE NULL END ,','),','),',')) SEQUENCE,
		TRY_TO_NUMBER(RTRIM(LTRIM(LISTAGG(DISTINCT CASE WHEN TRY_TO_NUMERIC(BACKGROUNDSEQUENCENUMBER) IS NOT NULL AND LENGTH(BACKGROUNDSEQUENCENUMBER) < 6 AND BACKGROUNDSEQUENCENUMBER <> 'E' 
		THEN BACKGROUNDSEQUENCENUMBER ELSE NULL END ,','),','),',')) BACKGROUND_SEQUENCE,
		MIN(CTE_ORDER_TYPE) AS ORDER_TYPE, MIN(CTE_ITEM) CTE_ITEM ,MIN(CTE_WAREHOUSE)CTE_WAREHOUSE, MIN(CTE_CONFIGURATION) CTE_CONFIGURATION,MIN(CTE_SOLDTOBUSINESSPARTNER) CTE_SOLDTOBUSINESSPARTNER,
		--FLAG TO IDENTIFY PARSED AND NON-PARSED RECORDS, DEFAULTED TO TRUE
		TRUE AS IS_PARSED, 
		MAX(_CAPTUREDATETIME) _CAPTUREDATETIME,
		--GET WORDS WITH CONTAIN "CONTRACT"/"CN"
		COALESCE(CASE WHEN LISTAGG(CTE_SERVICECONTRACT) ='' THEN NULL ELSE LISTAGG(CTE_SERVICECONTRACT) END ,
		CASE WHEN ORDER_TYPE <> '' THEN '' ELSE LISTAGG( DISTINCT CONTRACTNUMBER) END ) SERVICE_CONTRACT_REFERENCE

		FROM( 
			SELECT DISTINCT REFERENCE_REFR, 
				PARSED_COLUMN_VALUE,
				CUSTOMERID AS SOLDTOBUSINESSPARTNER,
				B.PROJECT AS PRJECT, 

				--CHECCK IF WORD CONTAINS ATLEAST 1 DIGIT
				REGEXP_LIKE(PARSED_COLUMN_VALUE, '.*[0-9].*') = 1 AS PARSED_COLUMN_CONTAINS_NUMBER,

				--THIS IS TO CHECK IF THE PARSED WORD IS ALPHANUMERIC, AND NOT PLAIN TEXT(JUNK ENTRY)
				CASE WHEN PARSED_COLUMN_CONTAINS_NUMBER = TRUE THEN C.ORDERSERIESCODE ELSE NULL END ORDER_SERIES , 

				--ORDER_REFERENCE SHLD BE 8,9 LETTERS, SHLD BE ALPHANUMERIC OR ONLY DIGITS - BUT NOT ONLY TEXT, WHEN STRING CONTAINS ORDER_SERIES, PICK BEXT 9 LETTERS AS ORDER_REFERENC	

				CASE WHEN LEN(PARSED_COLUMN_VALUE) in(9,8) AND PARSED_COLUMN_CONTAINS_NUMBER = TRUE THEN PARSED_COLUMN_VALUE 
					WHEN ORDER_SERIES IS NOT NULL AND ORDER_SERIES <> 'PO' AND PARSED_COLUMN_CONTAINS_NUMBER = TRUE AND LEN(PARSED_COLUMN_VALUE) >= 9 THEN LEFT(PARSED_COLUMN_VALUE,9)
					WHEN ORDER_SERIES = 'PO' AND PARSED_COLUMN_CONTAINS_NUMBER = TRUE AND LEN(PARSED_COLUMN_VALUE) >= 9 THEN LEFT(RIGHT(PARSED_COLUMN_VALUE,LEN(PARSED_COLUMN_VALUE)-2),9) 
				ELSE NULL END ORDER_REFERENCE,

				--STRING NEXT TO SOLDTOBPREFERENCE, AND FOUND IN SERIALNUMBER MASTER, SHOULD BE CONSIDERED AS SERIALNUMBER
                CASE WHEN SOLDTOBUSINESSPARTNER IS NOT NULL THEN 
                CASE WHEN LEAD(D.SERIALNUMBER) OVER (ORDER BY REFERENCE_REFR,PARSED_COLUMN_NUMBER) IS NOT NULL 
                     THEN LEAD(D.SERIALNUMBER) OVER (ORDER BY REFERENCE_REFR,PARSED_COLUMN_NUMBER) ELSE S.SERIALNUMBER END 
                ELSE NULL END AS SERIALNUMBER,

				---WHEN STRING STARTS WITH "RC","CN" , IS MORE THAN 8 LETTERS, AND CONTAINS ATLEAST 1 DIGIT 
				CASE WHEN LEN(PARSED_COLUMN_VALUE) >= 9 AND PARSED_COLUMN_CONTAINS_NUMBER = TRUE AND regexp_count(PARSED_COLUMN_VALUE,'[0-9]') > 2  
                AND (MONTHTEXT IS NULL OR ORDER_SERIES IS NOT NULL) 
					THEN CASE WHEN PARSED_COLUMN_VALUE LIKE '%RC%' 
						THEN CASE WHEN REGEXP_LIKE(SUBSTR(PARSED_COLUMN_VALUE,charindex('RC',PARSED_COLUMN_VALUE), 9), '.*[0-9].*') = 1 AND LEN(SUBSTR(PARSED_COLUMN_VALUE,charindex('RC',PARSED_COLUMN_VALUE), 9)) >= 9 
						THEN SUBSTR(PARSED_COLUMN_VALUE,charindex('RC',PARSED_COLUMN_VALUE), 9) END
					WHEN PARSED_COLUMN_VALUE LIKE '%CN%' 
						THEN CASE WHEN REGEXP_LIKE(SUBSTR(PARSED_COLUMN_VALUE,charindex('CN',PARSED_COLUMN_VALUE), 9), '.*[0-9].*') = 1 AND LEN(SUBSTR(PARSED_COLUMN_VALUE,charindex('CN',PARSED_COLUMN_VALUE), 9)) >= 9 
						THEN SUBSTR(PARSED_COLUMN_VALUE,charindex('CN',PARSED_COLUMN_VALUE), 9) END
					
					WHEN PARSED_COLUMN_VALUE LIKE '%BN%' 
						THEN CASE WHEN REGEXP_LIKE(SUBSTR(PARSED_COLUMN_VALUE,charindex('BN',PARSED_COLUMN_VALUE), 9), '.*[0-9].*') = 1 AND LEN(SUBSTR(PARSED_COLUMN_VALUE,charindex('BN',PARSED_COLUMN_VALUE), 9)) >= 9 
						THEN SUBSTR(PARSED_COLUMN_VALUE,charindex('BN',PARSED_COLUMN_VALUE), 9) END
					WHEN PARSED_COLUMN_VALUE LIKE '%CCT%' 
						THEN CASE WHEN REGEXP_LIKE(SUBSTR(PARSED_COLUMN_VALUE,charindex('CCT',PARSED_COLUMN_VALUE), 9), '.*[0-9].*') = 1 AND LEN(SUBSTR(PARSED_COLUMN_VALUE,charindex('CCT',PARSED_COLUMN_VALUE), 9)) >= 9 
						THEN SUBSTR(PARSED_COLUMN_VALUE,charindex('CCT',PARSED_COLUMN_VALUE), 9) END
					END
				ELSE NULL END AS CONTRACTNUMBER,
				--CHECK CURRENT AND NEXT PART OF THE REFERENCE, IF THEy MATCH THEN 1ST PART AFTER CURRENT WORD IN REFERENCE ELSE 2ND PART AFTER CURRENT WORD IN REFERENCE
				CASE WHEN ORDER_REFERENCE IS NOT NULL THEN 
					CASE WHEN PARSED_COLUMN_VALUE <> LEAD(PARSED_COLUMN_VALUE) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) 
					THEN LEAD(PARSED_COLUMN_VALUE,1) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) 
					WHEN PARSED_COLUMN_VALUE = LEAD(PARSED_COLUMN_VALUE) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) 
					THEN LEAD(PARSED_COLUMN_VALUE,2) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) END 
				ELSE NULL END LINENUMBER,

				--CHECK CURRENT AND NEXT PART OF THE REFERENCE, IF THEy MATCH THEN 2ND PART AFTER CURRENT WORD IN REFERENCE ELSE 3RDD PART AFTER CURRENT WORD IN REFERENCE
				CASE WHEN ORDER_REFERENCE IS NOT NULL AND LENGTH(LINENUMBER) <= 5 AND TRY_TO_NUMERIC(LINENUMBER) IS NOT NULL THEN 
					CASE WHEN PARSED_COLUMN_VALUE <> LEAD(PARSED_COLUMN_VALUE) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) 
					THEN LEAD(PARSED_COLUMN_VALUE,2) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER)
					WHEN PARSED_COLUMN_VALUE = LEAD(PARSED_COLUMN_VALUE) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) 
					THEN LEAD(PARSED_COLUMN_VALUE,3) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) END 
				ELSE NULL END SEQUENCENUMBER,

				--CHECK CURRENT AND NEXT PART OF THE REFERENCE, IF THEy MATCH THEN 3RD PART AFTER CURRENT WORD IN REFERENCE ELSE 4TH PART AFTER CURRENT WORD IN REFERENCE
				CASE WHEN ORDER_REFERENCE IS NOT NULL AND LENGTH(LINENUMBER) <= 5 AND TRY_TO_NUMERIC(LINENUMBER) IS NOT NULL THEN 
					CASE WHEN PARSED_COLUMN_VALUE <> LEAD(PARSED_COLUMN_VALUE) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) 
					THEN LEAD(PARSED_COLUMN_VALUE,3) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER)
					WHEN PARSED_COLUMN_VALUE = LEAD(PARSED_COLUMN_VALUE) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) 
					THEN LEAD(PARSED_COLUMN_VALUE,4) OVER (PARTITION BY REFERENCE_REFR ORDER BY PARSED_COLUMN_NUMBER) END 
				ELSE NULL END BACKGROUNDSEQUENCENUMBER,

				_CAPTUREDATETIME
				
			FROM COMMON.TEMP_PARSED_COLUMNS A
			LEFT JOIN (SELECT PROJECT FROM BAAN.BAANCOMMONSYSTEMTABLES_PROJECTS UNION SELECT PROJECT FROM BAAN.BAANMANUFACTURINGPROJECTCONTROLSYSTEM_GENERALPROJECTDATA) B ON PARSED_COLUMN_VALUE = PROJECT
			LEFT JOIN (SELECT DISTINCT SERIALNUMBER FROM BAAN.BAANSERVICECONFIGURATIONCONTROL_OBJECTS  ) D ON PARSED_COLUMN_VALUE = D.SERIALNUMBER 
			LEFT JOIN (SELECT CUSTOMERID FROM COMMON.CUSTOMER WHERE SOLDTOINDICATOR = 'YES')E ON PARSED_COLUMN_VALUE = E.CUSTOMERID 
            LEFT JOIN (SELECT DISTINCT SERIALNUMBER FROM BAAN.BAANSERVICECONFIGURATIONCONTROL_OBJECTS) S ON LTRIM(REPLACE(REFERENCE_REFR,E.CUSTOMERID,''),'-') = S.SERIALNUMBER 

			LEFT JOIN (SELECT ORDERSERIESCODE FROM MDM.BAANORDERSERIES WHERE ORDERSERIESCODE <> '00000') C ON CONTAINS(PARSED_COLUMN_VALUE,ORDERSERIESCODE) --union SELECT 'CCT' 
			LEFT JOIN (SELECT DISTINCT UPPER(MONTHTEXT) MONTHTEXT FROM ODS.COMMON.SOURCE_DATE) ON CONTAINS(PARSED_COLUMN_VALUE , MONTHTEXT)
---WHERE REFERENCE_REFR in('TEA - Operating Equip/Tools')---SELECT * FROM COMMON.REFERENCE_NAIVE_PARSE WHERE REFERENCE ='/CN0000982/0100/020/080';
		)REFERENCE 
		LEFT JOIN CTE_ORDER_TYPE ON ORDER_REFERENCE = CTE_ORDER_TYPE.CTE_ORDER_NUMBER--SELECT * FROM CTE_ORDER_TYPE WHERE CTE_ORDER_TYPE = 'NORM32031'
		--- LEFT JOIN ODS.COMMON.SOURCE_DATE ON CONTAINS(UPPER(PARSED_COLUMN_VALUE) , UPPER(MONTHTEXT))
		GROUP BY REFERENCE_REFR
	)REFERENCE_REFR
	LEFT JOIN (SELECT DISTINCT SALESORDER,POSITIONNUMBER, ITEM,SEQUENCENUMBER AS SALES_SEQ ,WAREHOUSE ,UPPER(SERIALNO)SERIALNO FROM BAAN.BAANDISTRIBUTIONSALESCONTROL_SALESORDERLINES
              ) SALESORDERS
	ON (ORDER_NUMBER = SALESORDERS.SALESORDER AND LINE = SALESORDERS.POSITIONNUMBER) AND (IFNULL( SALESORDERS.SALES_SEQ ,0) = IFNULL(REFERENCE_REFR.SEQUENCE,0))
    LEFT JOIN (SELECT DISTINCT SALESORDER AS SALESORDER2,POSITIONNUMBER POSITIONNUMBER2,ITEM ITEM2,SEQUENCENUMBER AS SALES_SEQ2 ,WAREHOUSE WAREHOUSE2 ,UPPER(SERIALNO) SERIALNO2
               FROM BAAN.BAANDISTRIBUTIONSALESCONTROL_SALESORDERLINES) SALESORDERS2
	ON (ORDER_NUMBER = SALESORDERS2.SALESORDER2 AND LINE = SALESORDERS2.POSITIONNUMBER2) AND (SALESORDERS2.SALES_SEQ2 = 0)
	LEFT JOIN (SELECT DISTINCT PURCHASEORDER,POSITIONNUMBER, ITEM,SEQUENCENUMBER AS PURCHASE_SEQ,WAREHOUSE FROM BAAN.BAANDISTRIBUTIONPURCHASECONTROL_PURCHASEORDERLINES) PURCHASEORDERS
	ON ORDER_NUMBER = PURCHASEORDERS.PURCHASEORDER AND LINE = PURCHASEORDERS.POSITIONNUMBER AND PURCHASEORDERS.PURCHASE_SEQ = REFERENCE_REFR.SEQUENCE
	LEFT JOIN (SELECT SERVICEORDER,ITEM,LINENUMBER AS POSITIONNUMBER ,ACTUALWAREHOUSE,CONFIGURATION,UPPER(SERIALNUMBER) AS SERVICEORDERS_SERIALNUMBER,SERVICECONTRACTNUMBER
	FROM BAAN.BAANSERVICESERVICEORDERCONTROL_SERVICEORDERITEMS) SERVICEORDERS ON ORDER_NUMBER = SERVICEORDERS.SERVICEORDER AND LINE = SERVICEORDERS.POSITIONNUMBER
    LEFT JOIN (SELECT DISTINCT SERVICECONTRACT FROM COMMON.SERVICE_CONTRACTS 
              ---where SERVICECONTRACT IN ('CCTJ48071','CCTY27110','RC0927201','RCBP00059','RCSI50814','RCSI52659','RCSI56520','RCSI57281'              ,'RCSI58751','RCSI62484','RCSI62512','RCVE00259')
              )
    ON SERVICECONTRACT = SERVICE_CONTRACT_REFERENCE
;


SET SALES_SERVICE_ORDER_NUMBER = REFERENCEB, ORDER_TYPE = 'SERVICE ORDER',SERIAL_NUMBER_REFERENCE = SERIALNUMBER
FROM (
SELECT DISTINCT PURCHASEORDER, LEFT(REFERENCEB,9) REFERENCEB,SERIALNUMBER
FROM BAAN.BAANSERVICESERVICEORDERCONTROL_SERVICEORDERITEMS SERVICEORDERS_B
INNER JOIN BAAN.BAANDISTRIBUTIONPURCHASECONTROL_PURCHASEORDERS PURCHASEORDERS ON REFERENCEB = SERVICEORDERS_B.SERVICEORDER  
)
WHERE PURCHASEORDER = PURCHASE_ORDER_NUMBER AND IFNULL(SALES_SERVICE_ORDER_NUMBER,'') = '';


IFNULL(SALES_SERVICE_ORDER_NUMBER,'') <>'' ;

UPDATE COMMON.REFERENCE_NAIVE_PARSE SET ORDER_TYPE = 'SERVICE ORDER' 
FROM BAAN.BAANSERVICESERVICEORDERCONTROL_SERVICEORDERITEMS WHERE ORDER_TYPE = 'SALES ORDER' AND SERVICEORDER = SALES_SERVICE_ORDER_NUMBER AND LINENUMBER = LINE ;

UPDATE COMMON.REFERENCE_NAIVE_PARSE SET SERVICE_CONTRACT_REFERENCE = CTE_SERVICECONTRACT
FROM CTE_ORDER_TYPE WHERE CTE_ORDER_NUMBER = SALES_SERVICE_ORDER_NUMBER AND IFNULL(SERVICE_CONTRACT_REFERENCE, '') = '';

UPDATE COMMON.REFERENCE_NAIVE_PARSE B SET SOLDTO_BP_REFERENCE = SOLDTOBUSINESSPARTNER
FROM BAAN.BAANSERVICECONTRACTMANAGEMENT_SERVICECONTRACTS
WHERE SERVICECONTRACT =  SERVICE_CONTRACT_REFERENCE AND IFNULL(SOLDTO_BP_REFERENCE,'') = '';

UPDATE COMMON.REFERENCE_NAIVE_PARSE SET SERIAL_NUMBER_REFERENCE = ToolSerialNumber 
FROM   BAAN.BAANMANUFACTURINGPROJECTCONTROLSYSTEM_GENERALPROJECTDATA
WHERE IFNULL(PROJECT_REFERENCE,'') <>'' AND Project = PROJECT_REFERENCE 
AND IFNULL(SERIAL_NUMBER_REFERENCE,'') ='' ;


UPDATE COMMON.REFERENCE_NAIVE_PARSE B  SET B.SERIAL_NUMBER_REFERENCE = CASE WHEN IFNULL(B.SERIAL_NUMBER_REFERENCE,'') ='' THEN UPPER(SERIALNO) ELSE B.SERIAL_NUMBER_REFERENCE  END,
SOLDTO_BP_REFERENCE =  CASE WHEN IFNULL(B.SOLDTO_BP_REFERENCE,'') ='' THEN UPPER(SOLDTOBUSINESSPARTNER) ELSE B.SOLDTO_BP_REFERENCE  END
FROM BAAN.BAANDISTRIBUTIONSALESCONTROL_SALESORDERLINES SALESORDERS
WHERE (SALES_SERVICE_ORDER_NUMBER = SALESORDERS.SALESORDER AND LINE = SALESORDERS.POSITIONNUMBER) 
AND (IFNULL(SERIAL_NUMBER_REFERENCE,'') ='' OR IFNULL(SOLDTO_BP_REFERENCE,'') ='')
;

UPDATE COMMON.REFERENCE_NAIVE_PARSE B  SET B.SERIAL_NUMBER_REFERENCE = CASE WHEN IFNULL(B.SERIAL_NUMBER_REFERENCE,'') ='' THEN UPPER(SERIALNO) ELSE B.SERIAL_NUMBER_REFERENCE  END,
SOLDTO_BP_REFERENCE =  CASE WHEN IFNULL(B.SOLDTO_BP_REFERENCE,'') ='' THEN UPPER(SOLDTOBUSINESSPARTNER) ELSE B.SOLDTO_BP_REFERENCE  END
FROM (SELECT SALESORDER,MAX(SERIALNO)SERIALNO,MAX(SOLDTOBUSINESSPARTNER)SOLDTOBUSINESSPARTNER
      FROM BAAN.BAANDISTRIBUTIONSALESCONTROL_SALESORDERLINES GROUP BY SALESORDER  HAVING (MAX(SERIALNO) IS NOT NULL OR MAX(SOLDTOBUSINESSPARTNER IS NOT NULL))) SALESORDERS
WHERE (SALES_SERVICE_ORDER_NUMBER = SALESORDERS.SALESORDER ) 
AND (IFNULL(SERIAL_NUMBER_REFERENCE,'') ='' OR IFNULL(SOLDTO_BP_REFERENCE,'') ='')
;
UPDATE COMMON.REFERENCE_NAIVE_PARSE B SET B.SERIAL_NUMBER_REFERENCE = A.SERIALNUMBER_ID
FROM (SELECT  DISTINCT SERIAL_NUMBER_REFERENCE,SERIALNUMBER_ID FROM COMMON.REFERENCE_NAIVE_PARSE 
      LEFT JOIN EDW_DEV.DE.D_SERIAL_NUMBER ON SERIAL_NUMBER_REFERENCE = UPPER(SERIALNUMBER_ID) )A
WHERE A.SERIAL_NUMBER_REFERENCE = B.SERIAL_NUMBER_REFERENCE;


FROM BAAN.BAANSERVICESERVICEORDERCONTROL_SERVICEORDERITEMS SERVICEORDERS_A 
INNER JOIN BAAN.BAANDISTRIBUTIONPURCHASECONTROL_PURCHASEORDERS PURCHASEORDERS ON REFERENCEA = SERVICEORDERS_A.SERVICEORDER
)
WHERE PURCHASEORDER = PURCHASE_ORDER_NUMBER AND IFNULL(SALES_SERVICE_ORDER_NUMBER,'') = '';


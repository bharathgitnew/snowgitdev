create TABLE IF NOT EXISTS <<LZ_EXT>>.SAPH.FILELIST (_FILENAME VARCHAR(16777216),_FILEDATE TIMESTAMP_NTZ(9),UPLOAD_DATE TIMESTAMP_LTZ(9),VALUE VARIANT); 

INSERT INTO <<LZ_EXT>>.SAPH.FileList
SELECT metadata$filename as _FILENAME, 
 To_timestamp(LEFT(REGEXP_REPLACE(METADATA$FILENAME, '[^0-9]', ''),8),'YYYYMMDD') _FILEDATE, 
 CURRENT_TIMESTAMP UPLOAD_DATE , 
 VALUE
  FROM <<LZ_EXT>>.GMX.FileList 
 WHERE NVL(_FILEDATE,'19000101') > NVL( (SELECT MAX(_FILEDATE) FROM <<LZ_EXT>>.SAPH.FileList), '19000101');	
 
INSERT INTO ADMIN.AUDIT.CONTROLTOTALS 
SELECT ENVIRONMENT,DATABASENAME,SCHEMANAME,TABLEORVIEWNAME,SOURCESYSTEM,SUM(RECORDSLOADED),GETDATE() AS RECORDCREATEDTIMESTAMP FROM(
SELECT 'Dev' AS ENVIRONMENT,'LZ_EXT_DEV' AS DATABASENAME, 'GMX' AS SCHEMANAME, REPLACE(REPLACE(value:c1::string,'_EU_','_'),'_US_','_') AS TABLEORVIEWNAME, 
             'SRC_FILE' AS SOURCESYSTEM , value:c2::string AS RECORDSLOADED
       FROM <<LZ_EXT>>.SAPH.FileList WHERE  _FILEDATE = (SELECT MAX(_FILEDATE) FROM <<LZ_EXT>>.SAPH.FileList)
) GROUP BY ENVIRONMENT,DATABASENAME,SCHEMANAME,TABLEORVIEWNAME,SOURCESYSTEM;

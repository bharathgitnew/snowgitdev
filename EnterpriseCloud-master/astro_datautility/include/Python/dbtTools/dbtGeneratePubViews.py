def buildSchemaString(db,schema,df_tables):

    ymlout = """# .yml file generated by dbtRunConvert.ps1 on 1/14/2022 8:44:43 AM
version: 2
sources:
  - name: """ + db + """_""" + schema + """
    description: Landing Zone - """ + schema + """ Schema
    database: "{{ env_var('SNOWFLAKE_""" + db + """') }}"
    schema: """ + schema + """
    tables:
      """

    for idx, row in df_tables.iterrows():
            tableName = row['TABLE_NAME']
            ymlout += """- name: """ + tableName + """
        identifier: """ + tableName + """
        description:  Landing table for """ + tableName + """
      """
    return ymlout


def main(db,schema,path,user):

    ## local vars
    excludeStrings = []
    excludeStrings.append('CREATE OR REPLACE TABLE')
    excludeStrings.append(')COMMENT=')
    excludeStrings.append(';"')
    excludeStrings.append(";'")
    excludeStrings.append("PRIMARY KEY (")
    excludeStrings.append('ERROR_FLAG')
    excludeStrings.append('ERROR_REASON')
    excludeStrings.append('ERROR_CODE')
    excludeStrings.append('RECORD_INSERT_TIMESTAMP')
    excludeStrings.append('OPERATION_TYPE')
    excludeStrings.append('SRC_ROW_NUMBER')
    excludeStrings.append('AUDIT_LOG_ID')
    excludeStrings.append('_ROW_HASH')

    # path = 'C:\\Source\\Repos\\EnterpriseCloud\\dbt\\lz_to_ods\\models\\ariba'
    path += "\\" + schema.lower()

    try:
        # create snowflake connection string
        conn = snowflake.connector.connect(user=user,
                                            account="telus-global.privatelink",
                                            client_session_keep_alive = False,
                                            warehouse= "developer_wh",
                                            database= db+"_dev",
                                            role= "sysadmin_dev",
                                            schema= schema,
                                            threads= 1,
                                            authenticator="externalbrowser",
                                            autocommit=True)


        sql = """select table_name from information_schema.tables
                                    where table_type = 'BASE TABLE'
                                    and table_schema = '""" + schema + """';"""
        df_tables = df(conn,sql)

        # if df_tables is empty, throw error
        if(df_tables.empty):
            message = "No Rows returned from informationschema.columns for this schema. Check spelling and case."
            raise sqlNoRowsError(schema,message)

        # build and output schema.yml file
        file = path + '\\schema.yml'
        if not os.path.exists(file):
            ymlOut = buildSchemaString(db,schema,df_tables)
            writeFile(file,ymlOut)
            print("Schema.yml file created: " + file )
        else:
            print("Schema.yml already exists, delete to refresh.")

        # for each table, build view model
        df_result = pd.DataFrame()
        for idx, row in df_tables.iterrows():
            tableName = row['TABLE_NAME']

            # get column list for schema.table
            sql = """select get_ddl('table','""" + schema + """.""" + tableName + """');"""
            ddlstr = getDDL(conn,sql)
            ddlstr = str(ddlstr)

            # if ddl is empty, throw error
            if(len(ddlstr)==0):
                message = "No ddl returned for schema.table: " + schema + "." + tableName
                raise sqlNoRowsError(schema,message)

            # build jinja source
            jinjaSource = "{{ source('" + db.replace('_DEV', '') + "_" + schema + "','" + tableName + "') }}"
            print(db, db.replace('_DEV', ''), jinjaSource)

            # build final string and overwrite model file
            sel = buildModelString(ddlstr,excludeStrings,tableName,jinjaSource)
            file = path + '\\v_' + tableName + '.sql'
            if not os.path.exists(file):
                writeFile(file,sel)
                print("v_ model created: " + file )
            else:
                print(file + " already exists, delete to refresh.")

    except Exception as e:
        print(e)



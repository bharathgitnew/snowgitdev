	_AUDIT_LOG_ID VARCHAR(128),
	_ROW_HASH VARCHAR(128),	
	ITEM VARCHAR(16777216),
	MATERIAL_DESC VARCHAR(16777216),
	SOLD_TO_BP_CODE VARCHAR(16777216),
	SOLD_TO_BP VARCHAR(16777216),
	PERIOD DATE,
	SALES_DOC_TYPE VARCHAR(16777216),
	SO_QTY FLOAT,
	DELIVERED_QTY FLOAT,
	POTENTIAL_DATA_CORRUPTION_FLAG VARCHAR(16777216),
	DISPOSITION VARCHAR(16777216),
	CUSTOM_PO VARCHAR(16777216),
	SO_COUNT NUMBER(38,0),
	SOURCE VARCHAR(16777216),
	COUNTRY VARCHAR(16777216),
	REGION VARCHAR(16777216),
	SEARCH_TERM_1 VARCHAR(16777216),
	SEARCH_TERM_2 VARCHAR(16777216),
	ORDER_REASON VARCHAR
)COMMENT='Table for DEMAND_BY_SITE_V2 file.'

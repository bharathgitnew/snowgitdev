	SEARCH_TERM_2,
	ORDER_REASON)
select
	AUDIT_LOG_ID,
	_ROW_HASH,
	ITEM,
	MATERIAL_DESC,
	SOLD_TO_BP_CODE,
	SOLD_TO_BP,
	PERIOD,

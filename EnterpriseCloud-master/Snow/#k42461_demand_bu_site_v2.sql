	SO_QTY,
	DELIVERED_QTY,
	POTENTIAL_DATA_CORRUPTION_FLAG,
	NULL AS DISPOSITION,
	NULL AS CUSTOM_PO,
	NULL AS SO_COUNT,
	SOURCE,
	COUNTRY,
	REGION,
	SEARCH_TERM_1,
	SEARCH_TERM_2,

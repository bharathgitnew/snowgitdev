	ITEM,
	MATERIAL_DESC,
	SOLD_TO_BP_CODE,
	SOLD_TO_BP,
	PERIOD,
	SALES_DOC_TYPE,
	SO_QTY,
	DELIVERED_QTY,
	POTENTIAL_DATA_CORRUPTION_FLAG,
	DISPOSITION,
	CUSTOM_PO,
	SO_COUNT,
	SOURCE,
	COUNTRY,
	REGION,

USE ROLE <<PLATFORM_TEAM>>;
USE DATABASE <<GOLD>>;
USE SCHEMA TEA_SALES_REVENUE;

CREATE OR REPLACE TABLE PARTS_FINANCIAL_RECOGNITION_BACKUP CLONE GOLD.TEA_SALES_REVENUE.PARTS_FINANCIAL_RECOGNITION;

CREATE OR REPLACE TABLE PARTS_FINANCIAL_RECOGNITION (
    _AUDIT_LOG_ID VARCHAR(128) COMMENT 'dbt invocation UUID that produced this row. VARCHAR(128). Changes every pipeline run.',
    _ROW_HASH VARCHAR(128) COMMENT 'Static SHA-256 placeholder hash for change detection scaffolding. VARCHAR(128). Not yet computed from row content.',
    SALES_ORDER_NBR VARCHAR(16777216) COMMENT 'SAP sales order header number (e.g. 101638555). VARCHAR. Part of the composite KEY.',
    SALES_ORDER_LINE_NBR VARCHAR(16777216) COMMENT 'SAP sales order line item number (e.g. 001000). VARCHAR. Zero-padded 6-digit position.',
    OUTBOUND_DELIVERY_ORDER_NBR VARCHAR(16777216) COMMENT 'SAP outbound delivery order number (e.g. 803594088). VARCHAR. Part of the composite KEY.',
    DELIVERY_ORDER_LINE_NBR VARCHAR(16777216) COMMENT 'Delivery order line item number (e.g. 900007). VARCHAR. Part of the composite KEY.',
    KEY VARCHAR(16777216) COMMENT 'Composite unique key: SO_NBR-SO_LINE-OBDO_NBR-DO_LINE (hyphen-separated). VARCHAR. Used for joins and deduplication.',
    CUST_PO_NUMBER VARCHAR(16777216) COMMENT 'Customer purchase order number from the sales order header/line (SAP VBKD-BSTKD). VARCHAR. Null when the customer does not supply a PO.',
    BOOKING_DATE DATE COMMENT 'Sales order creation date representing the revenue booking date. DATE. Converted from SAP SO_CREATE_DT.',
    TOTAL_ORDER_QUANTITY FLOAT COMMENT 'Total quantity on the sales order line. FLOAT. May differ from TOTAL_DELIVERY_QUANTITY if partially delivered.',
    TOTAL_DELIVERY_QUANTITY FLOAT COMMENT 'Sum of delivery quantities across all deliveries for this KEY. FLOAT. Used to compute TOTAL_DELIVER_AMOUNT.',
    ORDER_TYPE VARCHAR(16777216) COMMENT 'SAP sales document type code (e.g. ZP12, ZS14, ZF11). VARCHAR. Determines order processing category.',
    ORDER_TYPE_NAME VARCHAR(16777216) COMMENT 'Human-readable name of the sales document type, uppercased (e.g. CONSIGMT.GI). VARCHAR. Looked up from reference data.',
    MATERIAL_NUMBER VARCHAR(16777216) COMMENT 'SAP material/part number (e.g. ES2L10-529577-11). VARCHAR. Prefix determines BU_GROUP fallback logic.',
    MATERIAL_COST VARCHAR(16777216) COMMENT 'Standard cost of the material from reference data. FLOAT. Used for margin analysis.',
    SALES_PRICE FLOAT COMMENT 'Unit selling price for the material on this order. FLOAT. Multiplied by TOTAL_DELIVERY_QUANTITY for TOTAL_DELIVER_AMOUNT.',
    ORDER_AMOUNT FLOAT COMMENT 'Total monetary value of the sales order line (quantity * price). FLOAT. Reflects the full order, not just delivered portion.',
    SLOC VARCHAR(16777216) COMMENT 'SAP storage location code (e.g. Z100, A120). VARCHAR. Null for some consignment orders.',
    SLOC_DESC VARCHAR(16777216) COMMENT 'Storage location description, uppercased (e.g. DROPSHIP). VARCHAR. Affects which goods movement date is used for ship date.',
    SOLD_TO_CUSTOMER_GROUP VARCHAR(16777216) COMMENT 'Sold-to customer group classification from reference data. VARCHAR. Null values are trimmed to null.',
    END_USER_CUSTOMER VARCHAR(16777216) COMMENT 'End-user customer group for the order (e.g. Intel). VARCHAR. Filters exclude TEL GROUP. Null values are trimmed to null.',
    ACTUAL_SHIP_DATE DATE COMMENT 'Actual shipment date, using FIRST_VALUE across the KEY partition to pick the earliest non-null date. DATE. Null if nothing has shipped.',
    BU_GROUP VARCHAR(16777216) COMMENT 'Business unit group (e.g. ES, CT, 3DI, TMEA). VARCHAR. Falls back to material prefix when source BU is null (BT->3DI, P5/TF->TMEA).',
    TEL_MODEL VARCHAR(16777216) COMMENT 'TEL equipment model name from reference data (e.g. TBX-SCCM). VARCHAR. Null if not available in source.',
    SWLH_MODEL VARCHAR(16777216) COMMENT 'SWLH (Switchlab) model name from reference data. VARCHAR. Often matches TEL_MODEL; null if not available.',
    CUSTOMER_TOOL_ID VARCHAR(16777216) COMMENT 'Customer-assigned tool/equipment identifier (e.g. OXS813). VARCHAR. Null if customer does not assign tool IDs.',
    INVOICE_NUMBER VARCHAR(16777216) COMMENT 'Comma-separated list of SAP billing document numbers for this delivery. VARCHAR. Null if not yet invoiced.',
    PRODUCT_TYPE VARCHAR(16777216) COMMENT 'Product classification (Consumables, Non-consumables, or Repair Service). VARCHAR. Repair Service is the default when consumable_flag is null.',
    SALES_CATEGORY VARCHAR(16777216) COMMENT 'SAP sales category numeric code (e.g. 61). VARCHAR. Sourced from reference data.',
    SALES_CATEGORY_NAME VARCHAR(16777216) COMMENT 'Human-readable sales category name (e.g. Consignment sales). VARCHAR. Looked up from sales category code.',
    TOTAL_DELIVER_AMOUNT FLOAT COMMENT 'Revenue amount recognized on delivery, calculated as SALES_PRICE * TOTAL_DELIVERY_QUANTITY, rounded to 2 decimals. FLOAT. Core financial recognition metric.',
    CURRENT_STATUS VARCHAR(16777216) COMMENT 'Derived shipment status: CANCELLED (reason=CANCEL), SHIPPED (ship date <= today), or NOT SHIPPED (ship date null). VARCHAR. Null if none of those conditions apply.',
    IS_INVOICED VARCHAR(3) COMMENT 'Whether a billing document exists for this delivery (Yes or No). VARCHAR. Based on INVOICE_NUMBER being non-null.'
)COMMENT='PURPOSE: Tracks parts revenue from sales order booking through outbound delivery and invoicing, supporting financial recognition reporting by business unit, product type, and customer.\nGRAIN: One row per unique combination of sales order + line + outbound delivery order + delivery line (KEY column).\nKEY LOGIC: Sources from DE_OPERATIONS.SALES_ORDER_WITH_REF_DATA, filters to non-zero delivery quantities with non-cancelled billing documents, excludes TEL GROUP and internal order types (ZPR1, ZP11). Computes TOTAL_DELIVER_AMOUNT as sales_price * total_delivery_quantity. BU_GROUP is inferred from material number prefix when null.\nCAVEAT: Excludes rows where ENDUSER_CUSTOMER_GROUP is null or ''TEL GROUP''. CURRENT_STATUS is null if reason is not CANCEL and ship date is null/future.\n'
;

INSERT INTO PARTS_FINANCIAL_RECOGNITION(
    _AUDIT_LOG_ID,
    _ROW_HASH,
    SALES_ORDER_NBR,
    SALES_ORDER_LINE_NBR,
    OUTBOUND_DELIVERY_ORDER_NBR,
    DELIVERY_ORDER_LINE_NBR,
    KEY,
    CUST_PO_NUMBER,
    BOOKING_DATE,
    TOTAL_ORDER_QUANTITY,
    TOTAL_DELIVERY_QUANTITY,
    ORDER_TYPE,
    ORDER_TYPE_NAME,
    MATERIAL_NUMBER,
    MATERIAL_COST,
    SALES_PRICE,
    ORDER_AMOUNT,
    SLOC,
    SLOC_DESC,
    SOLD_TO_CUSTOMER_GROUP,
    END_USER_CUSTOMER,
    ACTUAL_SHIP_DATE,
    BU_GROUP,
    TEL_MODEL,
    SWLH_MODEL,
    CUSTOMER_TOOL_ID,
    INVOICE_NUMBER,
    PRODUCT_TYPE,
    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    TOTAL_DELIVER_AMOUNT,
    CURRENT_STATUS,
    IS_INVOICED
)
SELECT
    _AUDIT_LOG_ID,
    _ROW_HASH,
    SALES_ORDER_NBR,
    SALES_ORDER_LINE_NBR,
    OUTBOUND_DELIVERY_ORDER_NBR,
    DELIVERY_ORDER_LINE_NBR,
    KEY,
    NULL AS CUST_PO_NUMBER,
    BOOKING_DATE,
    TOTAL_ORDER_QUANTITY,
    TOTAL_DELIVERY_QUANTITY,
    ORDER_TYPE,
    ORDER_TYPE_NAME,
    MATERIAL_NUMBER,
    MATERIAL_COST,
    SALES_PRICE,
    ORDER_AMOUNT,
    SLOC,
    SLOC_DESC,
    SOLD_TO_CUSTOMER_GROUP,
    END_USER_CUSTOMER,
    ACTUAL_SHIP_DATE,
    BU_GROUP,
    TEL_MODEL,
    SWLH_MODEL,
    CUSTOMER_TOOL_ID,
    INVOICE_NUMBER,
    PRODUCT_TYPE,
    SALES_CATEGORY,
    SALES_CATEGORY_NAME,
    TOTAL_DELIVER_AMOUNT,
    CURRENT_STATUS,
    IS_INVOICED
FROM PARTS_FINANCIAL_RECOGNITION_BACKUP;

DROP TABLE IF EXISTS PARTS_FINANCIAL_RECOGNITION_BACKUP;

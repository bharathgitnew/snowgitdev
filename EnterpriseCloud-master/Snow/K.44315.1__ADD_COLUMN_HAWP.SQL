USE ROLE <<PLATFORM_TEAM>>;
USE DATABASE <<SILVER>>;
USE SCHEMA TEH_INTERNATIONAL_TRADE;

CREATE OR REPLACE TABLE FREIGHT_COST_TRACKING_BACKUP CLONE SILVER.TEH_INTERNATIONAL_TRADE.FREIGHT_COST_TRACKING;

CREATE OR REPLACE TABLE FREIGHT_COST_TRACKING (
    _AUDIT_LOG_ID VARCHAR(16777216),
    _ROW_HASH VARCHAR(16777216),
    ORDER_TYPE VARCHAR(16777216) COMMENT 'Sales document type code controlling order behavior. Four-character SAP code such as ZOR or ZRE. Determines workflow and pricing.',
    SALES_DOCUMENT_NUMBER VARCHAR(16777216) COMMENT 'SAP sales order number associated with the shipment. Ten-digit numeric string. Primary order reference.',
    SALES_DOCUMENT_ITEM VARCHAR(16777216) COMMENT 'Line item number within the sales order. Six-digit zero-padded string. Identifies the specific material ordered.',
    DOCUMENT_DATE VARCHAR(16777216) COMMENT 'Date the sales document was created. Date value. Represents when the order was booked.',
    CREATION_TIME VARCHAR(16777216) COMMENT 'Time of day the sales document was created. Time value. Paired with DOCUMENT_DATE for precise audit.',
    CREATED_BY VARCHAR(16777216) COMMENT 'SAP user who created the sales document. User ID. System accounts may appear for EDI orders.',
    ORDER_PRIORITY VARCHAR(12) COMMENT 'Priority classification for the sales order. Two-character code. Higher priority may expedite fulfillment.',
    SALES_REP_EMPLOYEE_NUMBER VARCHAR(16777216) COMMENT 'Employee number of the sales representative on the order. SAP personnel number. Blank for web or EDI orders.',
    SALES_SOLD_TO_PARTY VARCHAR(16777216) COMMENT 'Sold-to customer number from the sales order. SAP customer code. Identifies the ordering entity.',
    SALES_SOLD_TO_PARTY_NAME VARCHAR(16777216) COMMENT 'Name of the sold-to customer resolved from business partner master. Free-text name. Null when partner record not found.',
    ENDUSER VARCHAR(16777216) COMMENT 'End user customer number when different from sold-to. SAP customer code. Blank for direct sales.',
    ENDUSER_NAME VARCHAR(16777216) COMMENT 'Name of the end user resolved from business partner master. Free-text name. Null when end user is not specified.',
    SHIP_TO_PARTY_NAME VARCHAR(16777216) COMMENT 'Name of the ship-to party for the delivery. Free-text from partner master. Identifies the receiving location.',
    ORDER_REASON VARCHAR(16777216) COMMENT 'Business reason code for the sales order such as warranty or replacement. SAP reason code. Blank for standard commercial orders.',
    CUSTOMER_REQUEST_NO VARCHAR(16777216) COMMENT 'Customer request or ticket number referenced on the order. Free-text reference. Blank when not provided.',
    CUSTOMER_REFERENCE VARCHAR(16777216) COMMENT 'Customer purchase order or reference number from the sales header. Free-text. Primary customer cross-reference.',
    SALES_DOCUMENT_ITEM_POSNR VARCHAR(16777216) COMMENT 'Delivery-level item number mapped from the sales document item. Six-digit string. May differ from SALES_DOCUMENT_ITEM due to splitting.',
    MATERIAL VARCHAR(16777216) COMMENT 'Material number for the ordered part. Alphanumeric SAP material code. Identifies the shipped product.',
    MATERIAL_DESCRIPTION VARCHAR(16777216) COMMENT 'Descriptive text for the material from the sales order item. Free-text product name. May include model and configuration details.',
    DELIVERY_SERVICE_CODE VARCHAR(16777216) COMMENT 'Service level code for the delivery method. Short code. Determines carrier selection and transit time.',
    CUMULATIVE_ORDER_QUANTITY_IN_SALES_UNITS VARCHAR(16777216) COMMENT 'Total quantity ordered on the sales document item. Decimal in sales unit. Represents full order, not just shipped portion.',
    UNIT_PRICE FLOAT COMMENT 'Unit price from the sales document in order currency. Decimal amount. Used for revenue and margin calculations.',
    NET_VALUE VARCHAR(16777216) COMMENT 'Net value of the sales item in order currency. Decimal amount. Unit price times quantity minus discounts.',
    CURRENCY VARCHAR(16777216) COMMENT 'Document currency for monetary values on this record. Three-character ISO code. Applies to UNIT_PRICE, NET_VALUE, and COST.',
    COST VARCHAR(16777216) COMMENT 'Computed cost as standard material price times goods-issued quantity. Decimal amount. Null when no material valuation record exists.',
    STORAGE_LOCATION VARCHAR(16777216) COMMENT 'Warehouse storage location from which the delivery was shipped. Four-character SAP code. Identifies the fulfilling warehouse.',
    DELIVERY_NUMBER VARCHAR(16777216) COMMENT 'SAP delivery document number for the shipment. Ten-digit numeric string. Links to shipping and tracking details.',
    DELIVERY_ITEM VARCHAR(16777216) COMMENT 'Line item within the delivery document. Six-digit string. Identifies the specific material shipped.',
    DELIVERY_QTY FLOAT COMMENT 'Quantity shipped on the delivery item. Decimal in sales units. May be less than ordered quantity for partial shipments.',
    SHIP_DATE_DO VARCHAR(16777216) COMMENT 'Planned or actual ship date from the delivery document header. Date value. Used for transit time calculations.',
    GI_QTY NUMBER(30,5) COMMENT 'Goods issue quantity confirming physical shipment from the warehouse. Decimal value. Null until goods issue is posted.',
    UNDELIVERED FLOAT COMMENT 'Remaining undelivered quantity calculated as order quantity minus delivery quantity. Decimal value. Zero when fully delivered.',
    HOUSE_AIRWAY_BILL VARCHAR(16777216) COMMENT 'House air waybill number from the delivery header. Carrier reference. Blank for non-air or unshipped deliveries.',
    MASTER_AIRWAY_BILL VARCHAR(16777216) COMMENT 'Master air waybill number from the delivery header. Carrier reference. Blank for non-air shipments.',
    PURCHASE_ORDER_NO VARCHAR(16777216) COMMENT 'Related purchase order number for inbound freight or third-party shipments. SAP PO number. Blank when no PO is linked.',
    ITEM_NUMBER_OF_PURCHASING_DOCUMENT VARCHAR(16777216) COMMENT 'Line item within the linked purchase order. Six-digit string. Blank when no PO is linked.'
)COMMENT='Freight Cost Tracking. This is a fact table that tracks freight costs for international shipments. It includes dimensions such as shipment ID, date, origin, destination, carrier, and cost. This data can be used to analyze freight expenses and identify opportunities for cost savings.'
;

